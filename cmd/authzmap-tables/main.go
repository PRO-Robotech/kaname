// Команда authzmap-tables пишет порождённые таблицы типов пакета `authzmap`.
//
// Она — ТОНКАЯ: весь вывод живёт в `internal/authzmapgen`, потому что тот же
// вывод зовёт гейт свежести. Копия вывода внутри команды разошлась бы с гейтом
// молча, и гейт сверял бы файл с другим производителем.
//
// # ДВА КОРНЯ, И ОНИ РАЗНЫЕ (#61)
//
// `-root` — корень ПЛАТФОРМЫ: оттуда обходятся `services/*/manifest.yaml`.
// `-module` — корень ЭТОГО модуля: под ним лежит порождённый файл.
//
// Пока служба жила внутри платформы, второй был префиксом первого, и один довод
// обслуживал оба. После разреза это РАЗНЫЕ деревья, и умолчание `-root .`
// означает уже не «корень платформы», а «только собственный манифест».
//
// # ПОЧЕМУ ОДНОГО МОДУЛЯ НЕДОСТАТОЧНО, И ЭТО ОТКАЗ, А НЕ СУЖЕНИЕ
//
// Таблица — МЕЖМОДУЛЬНЫЙ каталог: она отображает точечные имена ресурсов ВСЕХ
// модулей платформы в имена модели прав. Собранная из одного манифеста, она
// выглядит целой и молча теряет типы, а потерянный тип не резолвится краем —
// вопрос о нём не задаётся вовсе, и проверка выглядит пройденной.
//
// Замер, ради которого guard заведён: прогон в самостоятельном клоне с
// умолчанием читал 1 манифест вместо 6 и отдавал таблицу на 7 ресурсов вместо
// 27 — с кодом 0. То есть `go generate` здесь ТИХО УНИЧТОЖИЛ БЫ таблицу,
// отчитавшись успехом.
//
// Исходов четыре, и они различимы кодом возврата:
//
//	0  файл записан (либо уже совпадает)
//	1  обход дал находки либо порождать нечего — предпосылка исчезла
//	2  не записалось: путь недоступен, либо корень платформы не назван /
//	   не является деревом платформы — «условие не создано», третий исход
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/PRO-Robotech/kaname/internal/authzmapgen"
)

func main() {
	root := flag.String("root", "", "корень ПЛАТФОРМЫ: отсюда обходятся services/*/manifest.yaml")
	module := flag.String("module", ".", "корень МОДУЛЯ: под ним лежит порождённый файл")
	out := flag.String("out", "", "куда писать; пусто — штатная координата под корнем модуля")
	flag.Parse()

	// Предпосылка называется ДО обхода: отказ по ненайденному пути посылает
	// читателя чинить путь, тогда как чинить надо не заданный корень.
	if strings.TrimSpace(*root) == "" {
		fmt.Fprint(os.Stderr, ""+
			"authzmap-tables: УСЛОВИЕ НЕ СОЗДАНО (не находка): корень дерева платформы не назван.\n"+
			"  таблица — межмодульный каталог: её источник это services/*/manifest.yaml ВСЕХ модулей,\n"+
			"  а в самостоятельном клоне службы их нет by construction.\n"+
			"  KANAME_PLATFORM_TREE=/путь/к/дереву/платформы go generate ./internal/authzmap/...\n"+
			"  либо: go run ./cmd/authzmap-tables -root /путь/к/дереву/платформы -module .\n")
		os.Exit(2)
	}

	tables, err := authzmapgen.Collect(*root)
	if err != nil {
		fmt.Fprintf(os.Stderr, "authzmap-tables: %v\n", err)
		os.Exit(1)
	}

	// Сужение входа — ОТКАЗ, а не тихая запись. Один модуль означает, что обход
	// прочитал собственный манифест службы и ничего больше, то есть корнем
	// платформы назвали не то дерево.
	if tables.Census.Modules < 2 {
		fmt.Fprintf(os.Stderr, ""+
			"authzmap-tables: УСЛОВИЕ НЕ СОЗДАНО (не находка): обход %s дал модулей %d (%s).\n"+
			"  таблица межмодульная, и собранная из одного манифеста она выглядит целой,\n"+
			"  молча теряя типы: потерянный тип не резолвится краем, вопрос о нём не задаётся\n"+
			"  вовсе, и проверка выглядит пройденной. Назовите корень ДЕРЕВА ПЛАТФОРМЫ.\n",
			*root, tables.Census.Modules, tables.Census.Summary())
		os.Exit(2)
	}
	body, err := authzmapgen.Render(tables)
	if err != nil {
		fmt.Fprintf(os.Stderr, "authzmap-tables: %v\n", err)
		os.Exit(1)
	}

	target := *out
	if target == "" {
		target = filepath.Join(*module, authzmapgen.GeneratedRelPath)
	}
	if err := os.WriteFile(target, body, 0o600); err != nil {
		fmt.Fprintf(os.Stderr, "authzmap-tables: %s не записан: %v\n", target, err)
		os.Exit(2)
	}
	// Перепись печатается ВСЕГДА: без неё «файл записан» не отличается от
	// «записан файл, собранный из части манифестов».
	fmt.Printf("authzmap-tables: %s — %s\n", target, tables.Census.Summary())
}
