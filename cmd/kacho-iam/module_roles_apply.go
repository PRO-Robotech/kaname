// module_roles_apply.go — роли доставленных манифестов ПРИМЕНЯЮТСЯ на старте
// (задача продукта #2010).
//
// # Зачем это здесь
//
// Применитель ролей был написан, покрыт пробами против живой Postgres и прогнан
// сверкой `moduleroleparity` по всем манифестам дерева — и не позван НИ РАЗУ:
// вызовов `moduleroles.NewApplier` в прод-коде было НОЛЬ, все пять вхождений
// стояли в `_test.go`. Пока так, строки `kacho_iam.roles` наполняет МИГРАЦИЯ,
// то есть объявленная манифестом роль доезжает до базы только пересборкой образа
// (`//go:embed *.sql`), а раздел `roles:` остаётся объявлением без производителя.
//
// Применитель, написанный и не позванный, отличается от отсутствующего ровно
// одним: он покрыт пробами и потому выглядит работающим. Это класс мёртвого
// стража (`00-kacho-core` ban #16): отличать надо не «применитель есть» от
// «применителя нет», а «вызов меняет состояние платформы» от «не меняет».
//
// Приёмка `services/iam/docs/engineering/acceptance/roles-come-as-data-not-migrations.md`
// назвала это своим держателем Г8* и оставила БЕЗ держателя вслух: «применитель
// действительно вызывается в развёрнутом контуре — держателя нет». Она же
// оставила форму поставки открытой: «писателем может быть и старт iam, и
// сайдкар — требование к СВОЙСТВАМ, а не к бинарю» (§«iamctl», #1036). Этот файл
// исполняет первую из двух названных форм и закрывает Г8*.
//
// # Порядок: ПОСЛЕ стража паритета каталога
//
// Довод из двух половин, и каждая самостоятельно достаточна.
//
//  1. **Ключи.** Правило роли ссылается на строки каталога: `role_rule_ref_res_fk`
//     на `(module, resource, live)` и `role_rule_ref_verb_fk`. Роль, применённая
//     до каталога, писала бы проекцию сегментов на референт, которого ещё нет, —
//     и отказ пришёл бы от чужого ограничения, называя не тот предмет.
//
//  2. **Каталожный факт.** Производителю правил роли нужен факт о живом
//     каталоге, и берётся он из ТЕХ ЖЕ строк, которые прочитал страж
//     (`catalogCensus.Live`). Второго чтения каталога на старте не заводится —
//     ровно по той же причине, по какой его не заводит снимок: два места об
//     одном предмете разошлись бы молча. Страж при этом фейл-клоузед: применить
//     роли раньше него значило бы записать строки, ссылающиеся на каталог,
//     который через строку будет отвергнут.
//
// Порядок держит гейт `module_roles_apply_wiring_test.go`, а не этот комментарий.
//
// # Отказ применения — ОТКАЗ ПУСКА
//
// Мягкий проход дал бы производителя, не произведшего ни разу и не сказавшего об
// этом (`security.md` §Hardening, п. 8). Хуже того, предмет здесь — ПРАВО: роль,
// применённая наполовину, ýже объявленной, и отличить её от работающей можно
// только вызовом. Служба, поднявшаяся с частью ролей, снаружи выглядит как
// «права не выдали» — а на деле выдала не те.
//
// Цена названа: временный отказ базы на старте роняет под, и он уходит в
// перезапуск. Она мала и ограничена — применение идемпотентно (доказано против
// живой базы, MOD-RD-13), поэтому перезапуск есть повтор, а не углубление беды;
// а путь старта УЖЕ отказывает на сорванной доставке, на расхождении каталога и
// на его применении, то есть четвёртый отказ не заводит оператору новой
// таксономии, а расширяет её текстом, называющим модуль.

