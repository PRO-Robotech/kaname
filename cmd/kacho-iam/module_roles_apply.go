// moduleRolesCensus — перепись применения ролей по всем доставленным манифестам.
//
// Печатается ЧИСЛАМИ и ВСЕГДА: «применено шесть манифестов, ролей записано ноль»
// и «применено ноль манифестов» — разные утверждения о платформе, а молчание у
// них одно и то же.
type moduleRolesCensus struct {
	// Delivered — доставленных манифестов.
	Delivered int
	// Applied — манифестов, по которым применитель отработал.
	Applied int
	// Modules — их модули, в порядке применения.
	Modules []string
	// Declared — ролей кластерного яруса, объявленных доставленными манифестами.
	Declared int
	// Written — строк заведено либо приведено.
	Written int
	// Unchanged — объявленное состояние уже стояло в строке.
	Unchanged int
	// Skipped — ролей иного яруса: применитель их не пишет. Считается отдельно,
	// иначе «ноль записей» читалось бы как «нечего писать».
	Skipped int
	// Names — имена записанных ролей.
	Names []string

	// Retired — строк помечено снятыми (#1913). Счётчик СВОЙ, а не часть
	// `Written`: «записано 0, снято 3» и «записано 3» — разные утверждения о
	// платформе, а молчание у них одно.
	Retired int
	// RetiredNames — имена снятых ролей ПОИМЁННО.
	//
	// Не счётчик: оператору, читающему журнал старта, нужен не вопрос «сколько»,
	// а вопрос «ЧТО именно перестало выдаваться». Снятие проходит молча by
	// construction — оно и заведено затем, чтобы не ронять пуск.
	RetiredNames []string
	// Resettled — строк проекций переселено в ведомость отобранного.
	Resettled int
	// Removed — строк проекций снято БЕЗ переселения: отбор и состав цели.
	// Число своё: переселённое объяснено арендатору, снятое — нет.
	Removed int
	// SectionsDeclared — манифестов, назвавших раздел `roles` вообще.
	//
	// Печатается отдельно от `Declared`, потому что состояний у раздела ТРИ:
	// «не объявлен» и «объявлен и пуст» дают одинаковый ноль ролей и означают
	// ПРОТИВОПОЛОЖНОЕ. Без этого числа «снято 0» читалось бы как «снимать было
	// нечего» и там, где сверка не звалась ни разу.
	SectionsDeclared int
	// LiveExamined — живых системных строк, осмотренных сверкой суммарно.
	LiveExamined int
}

// Changed — тронул ли применитель хоть одну строку. СНЯТИЕ входит сюда наравне
// с записью: платформа, у которой перестала действовать роль, изменилась ровно
// так же, как та, у которой роль появилась.
func (c moduleRolesCensus) Changed() bool { return c.Written > 0 || c.Retired > 0 }

// buildModuleRoleRights собирает ПРОИЗВОДИТЕЛЯ правил роли над живым каталогом
// и встроенным каталогом прав.
//
// # Почему обе величины берутся у уже прочитанного, а не читаются заново
//
// Каталожный факт строится из строк, которые прочитал страж паритета; записи
// каталога прав — из реестра, который процесс и так загружает для порога acr и
// для подробностей отказа. Своего чтения ни у одной из двух здесь нет: второе
// место об одном предмете разошлось бы с первым молча, и разошлось бы именно
// там, где расхождение не видно — на исправном входе оба ответили бы «годно».
//
// # Записи, не приводящиеся к действию модуля, — НЕ отказ, и это сказано числом
//
// Каталог прав платформы несёт записи, чей полный путь к форме
// `kacho.cloud.<модуль>.v1.<Служба>/<Глагол>` не приводится вовсе. Они законны и
// к правам модуля отношения не имеют. Ронять на них пуск значило бы требовать от
// каталога прав формы, которой он никогда не обещал; молчать о них — потерять
// признак того, что приведение вдруг перестало работать целиком. Поэтому их
// число ВОЗВРАЩАЕТСЯ и печатается рядом с числом приведённых.
func buildModuleRoleRights(live catalog.Rows, reg *seed.PermissionRegistry) (
	rights moduleroles.RightsExport, actions, unattributed int, err error,
) {
	facts, ferr := catalog.NewFacts(live)
	if ferr != nil {
		return nil, 0, 0, fmt.Errorf("каталожный факт для правил роли: %w", ferr)
	}
	if reg == nil {
		return nil, 0, 0, errors.New("каталог прав не подан: полноту поимённого перечня " +
			"права роли считать нечем, и перечень, полный по НУЛЮ классов, полон тривиально")
	}

	rows := reg.All()
	entries := make([]roleexport.CatalogEntry, 0, len(rows))
	for _, r := range rows {
		entries = append(entries, roleexport.CatalogEntry{
			FQN:              r.FQN,
			RequiredRelation: r.RequiredRelation,
			ScopeObjectType:  r.ScopeExtractor.ObjectType,
		})
	}
	attributed, faults := roleexport.Attribute(entries)

	x, xerr := moduleroles.NewRightsExport(facts, attributed)
	if xerr != nil {
		return nil, len(attributed), len(faults), fmt.Errorf("производитель правил роли: %w", xerr)
	}
	return x, len(attributed), len(faults), nil
}

// applyDeliveredModuleRoles приводит строки системных ролей к объявленному
// доставленными манифестами состоянию и печатает перепись — ВСЕГДА, независимо
// от исхода.
//
// Отказ ФАТАЛЕН по каждому манифесту: см. шапку файла. Применение идёт по одному
// манифесту, потому что `ApplyAll` у применителя ролей нет — каждый манифест
// ложится СВОЕЙ транзакцией, и это верно по существу: модуль есть единица
// объявления, и половина одного модуля не должна отменять целый другой.
func applyDeliveredModuleRoles(
	ctx context.Context,
	logger *slog.Logger,
	applier *moduleroles.Applier,
	manifests []*manifest.Manifest,
) error {
	c := moduleRolesCensus{Delivered: len(manifests)}
	if len(manifests) == 0 {
		// Законное состояние ровно одно: доставка посадкой не объявлена.
		// «Объявлена и сорвана» сюда не доходит — её отверг читатель доставки.
		// Молчать нельзя: снаружи «применять нечего» неотличимо от «применили и
		// ничего не изменилось».
		logger.Info("применение ролей модуля: доставленных манифестов нет, применять нечего")
		return nil
	}

	var applyErr error
	for _, m := range manifests {
		// Автор — НАЗВАННЫЙ процессный актор этого пути. Он уезжает в пометку
		// снятия и в ведомость отобранного, поэтому подставленного «system»
		// здесь не бывает: применитель отвергает пустого автора до открытия
		// транзакции.
		rep, err := applier.Apply(ctx, m, moduleroles.BootActorID)
		// Перепись копится ДО проверки отказа: числа отказавшего манифеста —
		// то, чем оператор чинит объявление, и терять их вместе с отказом
		// значило бы отдать ему один текст вместо текста с объёмом.
		c.Modules = append(c.Modules, m.Module)
		c.Declared += rep.Declared
		c.Written += rep.Written
		c.Unchanged += rep.Unchanged
		c.Skipped += rep.Skipped
		c.Names = append(c.Names, rep.Names...)
		c.Retired += rep.Retired
		c.RetiredNames = append(c.RetiredNames, rep.RetiredNames...)
		c.Resettled += rep.Resettled
		c.Removed += rep.Removed
		c.LiveExamined += rep.Census.LiveExamined
		if rep.SectionDeclared {
			c.SectionsDeclared++
		}
		if err != nil {
			applyErr = fmt.Errorf("роли модуля %s: %w", m.Module, err)
			break
		}
		c.Applied++
	}

	logger.Info("перепись применения ролей модуля",
		slog.Int("delivered", c.Delivered),
		slog.Int("applied", c.Applied),
		slog.Any("modules", c.Modules),
		slog.Int("declared", c.Declared),
		slog.Int("written", c.Written),
		slog.Int("unchanged", c.Unchanged),
		slog.Int("skipped_other_tier", c.Skipped),
		slog.Any("names", c.Names),
		slog.Int("sections_declared", c.SectionsDeclared),
		slog.Int("live_examined", c.LiveExamined),
		slog.Int("retired", c.Retired),
		slog.Int("resettled", c.Resettled),
		slog.Int("removed_without_resettle", c.Removed),
		slog.Bool("changed", c.Changed()))

	// Снятое называется ПОИМЁННО и ОТДЕЛЬНОЙ строкой — тем же порядком, каким
	// это делает каталог модуля этажом выше (`serve.go`, «строки каталога сняты
	// решением»). Счётчик отвечает на вопрос «сколько», а оператору, читающему
	// журнал старта, нужен другой: ЧТО именно перестало выдаваться. Снятие
	// проходит молча by construction — оно и заведено затем, чтобы не ронять
	// пуск, — поэтому единственное место, где его видно, это здесь.
	if len(c.RetiredNames) > 0 {
		logger.Info("роли модуля сняты решением манифеста — старт продолжается",
			slog.Any("roles", c.RetiredNames),
			slog.Int("resettled_projection_rows", c.Resettled),
			slog.Int("removed_projection_rows", c.Removed))
	}

	if applyErr != nil {
		return fmt.Errorf("применение ролей доставленных манифестов: %w", applyErr)
	}
	return nil
}
