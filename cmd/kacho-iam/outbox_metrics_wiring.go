// outbox_metrics_wiring.go — сканеры СОСТОЯНИЯ очередей kacho-iam.
//
// # Что производит дренаж и чего он не производит
//
// Дренаж сообщает о СОБЫТИЯХ: строка применилась, строка отравилась, голова
// партиции висит дольше порога. Всё это уходит в лог. «В очереди лежит N строк,
// старейшей M секунд, из них K отравлено» — это СОСТОЯНИЕ, и его не производит
// никто, кроме периодического скана таблицы. Без него застрявшая очередь
// неотличима от пустой: обе молчат одинаково.
//
// # Почему именно эти две очереди и почему это не «на всякий случай»
//
// `kacho_iam.fga_outbox` — та самая очередь, через которую физически уходит
// КАЖДЫЙ отзыв прав: снятие привязки, удаление члена группы, delete-stale
// реконсайлера. Её собственная конфигурация дренажа подробно объясняет, почему
// запись и удаление одного tuple не коммутируют и чем грозит их перестановка —
// то есть утверждение о ПОРЯДКЕ там уже есть. Утверждения о ДОСТАВКЕ не было ни
// одного, и сводные величины его дать не могут: выдачи идут непрерывно, поэтому
// глубина мала и голова молода, что бы ни происходило со снятием. Различает их
// только `delivered_total{direction="withdrawal"}`.
//
// `kacho_iam.subject_change_outbox` доставляет инвалидацию кэша решений о
// доступе на шлюз. Недоставленная строка означает, что край продолжает отвечать
// по устаревшему вердикту — ровно тот эффект, ради предотвращения которого
// очередь и заведена. Разложение по направлению к ней не применяется; ПОЧЕМУ —
// сказано один раз в записи repohygiene.outboxDirectionSplitExempt, где перечень
// видов события машинно сверяется со словарём, закрытым миграцией. Здесь оно не
// пересказывается намеренно: пересказ того же вывода у соседней очереди уже
// пережил свой предмет и стал ложным, когда приехал второй вид события.
//
// # Что скан НЕ делает
//
// Не мутирует таблицу, не участвует в пути запроса и не может уронить под:
// ошибки скана логируются и цикл продолжается. Наблюдаемость — не гейт.
package main

import (
	"context"
	"log/slog"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"

	outboxmetrics "github.com/PRO-Robotech/kacho/pkg/outbox/metrics"

	"github.com/PRO-Robotech/kacho-iam/internal/observability/metrics"
)

// outboxMetricsInterval — период скана. Совпадает с остальными сервисами
// платформы: одна и та же величина у всех очередей, чтобы порог тревоги,
// написанный по одной, читался одинаково на любой.
const outboxMetricsInterval = 15 * time.Second

// ЗДЕСЬ БЫЛ СКАН ОЧЕРЕДИ КОРТЕЖЕЙ — у него больше нет предмета.
//
// Он мерил ДОСТАВКУ: возраст самой старой неотправленной строки и число
// отравленных. Обе величины имеют смысл, только пока у журнала есть потребитель,
// который строки отправляет. Потребителя нет: прямой факт складывается из строки
// журнала триггером, в той же транзакции, что и сама мутация, — то есть «доставка»
// стала тождеством коммита.
//
// Оставленный скан отвечал бы РАСТУЩИМ возрастом на исправной службе: строки
// перестали помечаться отправленными не из-за сбоя, а потому, что отправлять их
// некуда. Тревога, которая звонит всегда, — это тревога, которую отключают первой.

// ЗДЕСЬ БЫЛ СКАН ЖУРНАЛА СМЕНЫ СУБЪЕКТА — у него больше нет предмета
// (задача #1024), и снят он по той же причине, что и скан очереди кортежей выше.
//
// Он мерил ДОСТАВКУ. Доставки не стало вместе с толчком к краю: направление
// развёрнуто, потребитель читает журнал КУРСОРОМ (`id > $1`). Величины «возраст
// самой старой неотправленной» и «число отравленных» после этого описывают не
// сбой, а устройство: они растут на исправной службе и растут всегда.
//
// Колонок, по которым эти величины считались, в схеме больше нет: `sent_at` /
// `attempt_count` / `last_error` / `notified_at` сняты миграцией 20260829181500
// (задача #1396) после того, как писателей не осталось. Вернуть сюда скан молча
// теперь не выйдет — он не соберётся.
//
// Тревога, которая звонит всегда, — это тревога, которую отключают первой, а
// вместе с ней перестают читать и настоящую.

// auditOutboxTable — журнал аудита control-plane.
//
// Константой, а не полем чужой структуры, по той же причине, что и у соседей:
// гейт repohygiene резолвит координату очереди разбором исходника, и адрес,
// вычисляемый в рантайме, для него неотличим от отсутствующего.
const auditOutboxTable = "kacho_iam.audit_outbox"

// auditOutboxMaxAttempts — порог, с которого недоставленная строка считается
// застрявшей.
//
// Это НЕ порог травления: травления у журнала нет — у приёмника нет класса «не
// приму никогда», поэтому непринятая запись ждёт следующей попытки бессрочно.
// Величина отвечает на другой вопрос: сколько подряд отказов приёмника уже
// означают, что чинить надо не повторами. Значение совпадает с умолчанием
// прочих очередей, чтобы порог тревоги читался одинаково на любой из них.
const auditOutboxMaxAttempts = 10

// runAuditOutboxMetrics — скан состояния журнала аудита.
//
// # Что эти величины теперь означают
//
// У журнала есть доставка (вывоз, audit_shipper_wiring.go), поэтому величины
// читаются как у любой очереди: глубина падает, возраст головы ограничен
// сверху, `poisoned` считает строки, которым приёмник отказал больше порога раз
// подряд. Растущая глубина при исправном потоке — сигнал сбоя, а не описание.
//
// # Чем это было до приёмника — и почему абзац оставлен
//
// До #812 доставки не существовало, и тот же сканер делал единственное, что
// можно было сделать честно: делал МОЛЧАНИЕ СЛЫШИМЫМ. Величины не изображали
// доставку — глубина росла монотонно, возраст головы равнялся возрасту стенда,
// отравленных было ноль, потому что попыток не было ни одной (замер на стенде
// kind-kacho 2026-08-20: строк 29 446, все недоставленные, max(attempts)=0).
// Абзац оставлен затем, чтобы порог тревоги, написанный по этим величинам,
// читался с пониманием, откуда взялась их прежняя форма.
//
// # Почему форма объявляется
//
// Эта очередь помечает доставленность СОСТОЯНИЕМ (`status`), а не отметкой
// времени. Пока форма подразумевалась, сканер над ней падал бы на первом же
// скане («колонки sent_at нет») — то есть очередь была ненаблюдаема by
// construction, и её ненаблюдаемость выглядела как ненужность наблюдения.
//
// Решение о приёмнике, границах доставки и предикат его пересмотра:
// services/iam/docs/engineering/architecture/audit-outbox-has-no-receiver.md
// (имя файла историческое, см. оговорку в его шапке).
func runAuditOutboxMetrics(ctx context.Context, pool *pgxpool.Pool, rec *metrics.OutboxRecorder, logger *slog.Logger) {
	collector := outboxmetrics.NewCollector(pool, rec, outboxmetrics.CollectorConfig{
		Table:       auditOutboxTable,
		MaxAttempts: auditOutboxMaxAttempts,
		Interval:    outboxMetricsInterval,
		Shape:       outboxmetrics.ShapeStatus,
	})
	// Исход скана наблюдается ЕДИНСТВЕННЫМ производителем — иначе очередь,
	// чей сайт забыли поправить, молчала бы на отказе неотличимо от исправной
	// работы (#2062).
	collector.Run(ctx, metrics.OutboxScanObserver(rec, auditOutboxTable, logger,
		"audit outbox metrics scan failed"))
}
