// reconcile_outbox_metrics_wiring.go — скан СОСТОЯНИЯ очереди сверки прав
// (задача #2050, предикат 3).
//
// # Почему величины, а не строка журнала
//
// Дренаж очереди сверки сообщает о СОБЫТИЯХ и делает это в лог: строка
// применилась, строка отказала, строка перешагнула порог. «В очереди лежит N
// строк, старейшей M секунд, из них K отравлено» — это СОСТОЯНИЕ, и его не
// производит никто, кроме периодического скана таблицы. Без него застрявшая
// очередь неотличима от пустой: обе молчат одинаково.
//
// Для ЭТОЙ очереди вопрос острее, чем у соседей, и вот почему: отсечка у неё
// появилась вместе с учётом попыток (#2050). Строка, перешагнувшая порог, из
// клейма ВЫПАДАЕТ — то есть перестаёт и жаловаться. Величина `poisoned` — это
// единственное, что о ней говорит после того, как дренаж замолчал.
//
// # Предпосылка величин — у очереди ЕСТЬ доставка
//
// Оба соседних скана были сняты, когда их очереди потеряли потребителя: возраст
// старейшей неотправленной на очереди без доставки растёт на ИСПРАВНОЙ службе,
// и тревога, которая звонит всегда, — это тревога, которую отключают первой.
// Здесь предпосылка держится: строки помечает отправленными живой дренаж
// (`seed.NewReconcileWorker` в `serve.go`), поэтому глубина падает, а возраст
// головы ограничен сверху.
//
// # Почему разложение по направлению ЗАДАНО, а не исключено
//
// Очередь несёт ОБЕ половины, и у каждой есть производитель в прод-коде:
// `mirror.upsert` — материализация выдачи (17 мест), `mirror.delete` — снятие
// зеркала объекта, то есть НЕМЕДЛЕННЫЙ ОТЗЫВ. Сводные серии на такой очереди
// здоровы при полностью мёртвом снятии: выдачи идут непрерывно, поэтому глубина
// мала и голова молода, что бы ни происходило со второй половиной. «Работает» и
// «ни одного отзыва не доехало» дают ОДИНАКОВУЮ картину — различает их только
// разложение.
//
// Словарь направлений повторяет словарь события ДОСЛОВНО, и это не совпадение:
// он закрыт ограничением применённой миграции
// (`resource_reconcile_outbox_event_valid`), а гейт дерева сверяет объявленное
// здесь с ним машинно. Второе написание разошлось бы молча.
package main

import (
	"context"
	"log/slog"

	"github.com/jackc/pgx/v5/pgxpool"

	outboxmetrics "github.com/PRO-Robotech/kacho/pkg/outbox/metrics"

	"github.com/PRO-Robotech/kacho-iam/internal/observability/metrics"
	reconcileoutbox "github.com/PRO-Robotech/kacho-iam/internal/repo/kacho/pg/reconcile_outbox"
)

// reconcileOutboxTable — очередь сверки прав.
//
// Константой композиционного корня, а не полем чужой структуры, по той же
// причине, что и у соседей: гейт резолвит координату очереди РАЗБОРОМ
// исходника, и адрес, вычисляемый в рантайме, для него неотличим от
// отсутствующего.
const reconcileOutboxTable = "kacho_iam.resource_reconcile_outbox"

// runReconcileOutboxMetrics — скан состояния очереди сверки.
//
// Порог отсечки берётся КОНСТАНТОЙ САМОЙ ОЧЕРЕДИ, а не переписывается здесь:
// `poisoned` обязан считать ровно те строки, которые клейм уже не берёт. Две
// величины об одном пороге разошлись бы молча, и разошлись бы именно там, где
// расхождение не видно, — на исправной очереди они дают одинаковый ноль.
func runReconcileOutboxMetrics(ctx context.Context, pool *pgxpool.Pool, rec *metrics.OutboxRecorder, logger *slog.Logger) {
	collector := outboxmetrics.NewCollector(pool, rec, outboxmetrics.CollectorConfig{
		Table:       reconcileOutboxTable,
		MaxAttempts: reconcileoutbox.MaxAttempts,
		Interval:    outboxMetricsInterval,
		Directions: map[string][]string{
			// «доехала ли материализация выдачи»
			"upsert": {reconcileoutbox.EventUpsert},
			// «доехало ли снятие» — половина, ради которой разложение и заведено
			"delete": {reconcileoutbox.EventDelete},
		},
	})
	// Исход скана наблюдается ЕДИНСТВЕННЫМ производителем — иначе очередь, чей
	// сайт забыли поправить, молчала бы на отказе неотличимо от исправной работы
	// (#2062).
	collector.Run(ctx, metrics.OutboxScanObserver(rec, reconcileOutboxTable, logger,
		"reconcile outbox metrics scan failed"))
}
