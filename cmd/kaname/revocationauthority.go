// revocationauthority.go — авторитет отзыва НАШИХ токенов не выставляется на
// слушателе, который клиентского сертификата даже не запрашивает.
//
// # Предмет: обработчику, не имеющему чем отказать, отказывать нечем
//
// Своя чеканка приносит с собой авторитет отзыва: поверхность, которой
// присылают предъявленный токен и которая отвечает, действует ли он ещё.
// Отзыв, читаемый только на выдаче, отзывом не является — предъявленное
// продолжало бы проходить до истечения срока, и это состояние не сходится
// само.
//
// Авторитет обязан знать, КТО спрашивает. На слушателе, поднятом в режиме
// `server-tls-only`, сертификат не запрашивается вовсе, поэтому обработчик,
// требующий проверенного пира, не получает его НИ ПРИ КАКОМ входе: контроль
// присутствует, провязан, исполняется на каждом запросе — и не отказывает ни
// разу. Такая посадка не поднимается.
//
// # Почему обоснование, выданное НАБОРУ КЛЮЧЕЙ, сюда не переносится
//
// С зеркала проверочных ключей аутентификация снята осознанно и
// задокументированно (security.md §AuthN+AuthZ ВЕЗДЕ): на проводе там только
// ПУБЛИЧНЫЙ материал, и спрашивать личность у того, кто пришёл за открытым
// ключом, незачем. Здесь по тому же проводу едет ПРЕДЪЯВЛЕННЫЙ ТОКЕН, и
// вопрос «кто спрашивает» — единственное, чем этот обработчик вообще
// располагает. Обоснование соседней поверхности того же слушателя на эту не
// распространяется, и перенесённое сюда оно ложно своей несущей половиной.
//
// # Почему запрашивающего режима ДОСТАТОЧНО, а взаимного не требуется
//
// `optional-mutual` сертификат ЗАПРАШИВАЕТ и проверяет предъявленный, но
// соединение без него пропускает — и это здесь верно, потому что на ТОМ ЖЕ
// слушателе живёт набор проверочных ключей, который обязан оставаться
// доступным без сертификата: плоскость данных реестра ходит за ним, своего
// листа не имея. Взаимный режим отверг бы её на рукопожатии.
//
// Сужает при запрашивающем режиме не транспорт, а обработчик, требующий
// проверенного пира сам, — и авторитет отзыва именно таков
// (`RequireClientCert: true` в его настройке). То есть пара «запрашивающий
// транспорт + требующий обработчик» и есть здесь полный рубеж, а не половина.
//
// # Почему это НЕ страж боевого режима
//
// Условие не спрашивает посадку и спрашивать её не вправе: предмет приносит
// СВОЯ ЧЕКАНКА, а не выбор посадки. Стенд, включивший чеканку, получает ровно
// тот же отказ — и это верно: авторитет отзыва, не отказавший ни разу, вводит
// в заблуждение одинаково на любой посадке.
//
// # Что этот страж НЕ утверждает
//
// Он говорит о РУКОПОЖАТИИ и только о нём: способен ли слушатель установить,
// кто пришёл. О том, кому именно позволено спрашивать об отзыве, решает
// обработчик, и это отдельный предмет.
package main

import (
	"fmt"
	"strings"

	"github.com/PRO-Robotech/kaname/internal/apps/kaname/config"
)

// revocationAuthorityCallerReader — ровно то, что стражу нужно от посадки:
// способен ли слушатель установить вызывающего и что прочитано на его ручке.
//
// Узкий интерфейс здесь не украшение: он позволяет пробе подать посадку, не
// собирая её из окружения, — и он же не даёт стражу прочитать что-либо ещё.
type revocationAuthorityCallerReader interface {
	JWKSProxyVerifiesCaller() bool
	JWKSProxyClientAuthModeValue() string
}

// requireRevocationAuthorityCallerAuth — включённая своя чеканка обязана
// получить слушатель, СПОСОБНЫЙ установить вызывающего.
//
// Чеканка выключена — no-op: авторитета отзыва нет, судить нечего. Пустой
// адрес — no-op: слушателя нет вовсе, тот же порядок, что у соседних стражей
// рёбер.
//
// Отказ называет ОБЕ величины — ручку и то, что на ней прочитано, — требуемое
// значение и ВТОРОЙ законный выход (выключить чеканку). Отказ, называющий
// только ручку, сообщает оператору, что не так, и не сообщает, что именно на
// ней стоит; отказ, называющий один выход, сообщает, что делать, только тому,
// кто чеканку и правда хотел.
func requireRevocationAuthorityCallerAuth(
	ownMintingEnabled bool, jwksProxyAddr string, creds revocationAuthorityCallerReader,
) error {
	if !ownMintingEnabled {
		return nil
	}
	if strings.TrimSpace(jwksProxyAddr) == "" {
		return nil
	}
	if creds.JWKSProxyVerifiesCaller() {
		return nil
	}
	return fmt.Errorf(
		"авторитет отзыва наших токенов не может быть выставлен на слушателе %s, который "+
			"не запрашивает клиентский сертификат "+
			"(KANAME_JWKSPROXY_SERVER_MTLS_CLIENTAUTHMODE=%q): обработчик, требующий "+
			"проверенного пира, не получит его НИ ПРИ КАКОМ входе — контроль исполнялся бы "+
			"на каждом запросе и не отказал бы ни разу. Задайте "+
			"KANAME_JWKSPROXY_SERVER_MTLS_CLIENTAUTHMODE=%s вместе с "+
			"KANAME_JWKSPROXY_SERVER_MTLS_CLIENTCAFILES (набор проверочных ключей при этом "+
			"остаётся доступен без сертификата) либо выключите свою чеканку "+
			"authn.token-signing.enabled; refusing to start",
		jwksProxyAddr, creds.JWKSProxyClientAuthModeValue(),
		config.JWKSProxyRequestingModeName())
}
