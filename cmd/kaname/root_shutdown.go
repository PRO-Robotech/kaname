// root_shutdown.go — ОДНА РУЧКА ГАШЕНИЯ на обе его причины (kacho#2506).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Причин гашения процесса ДВЕ: сигнал среды и КРАХ — отказ слушателя, дренажа,
// поверхности. Сигнальный контекст знает только первую: отменить его изнутри
// нечем, его отмена стоит `defer`-ом и срабатывает уже ПОСЛЕ `group.Wait()`.
//
// Следствие у второй причины было такое: задача-ожидатель блокировалась на
// сигнальном контексте, гашение по краху до неё не доезжало, а `runServe`
// оканчивается на `Wait()`, который возвращает управление лишь когда вернулись
// ВСЕ задачи. То есть при крахе слушателя процесс НЕ ВЫХОДИЛ ВОВСЕ: погашенные
// серверы, живая задача-ожидатель, код возврата краха не отдан никогда.
// Со стороны это неотличимо от исправного пода — он не станет Ready, но и не
// упадёт, и перезапуск начнётся не с падения, а с истечения внешнего окна.
//
// Остальные фоновые задачи, взявшие сигнальный контекст, при крахе продолжали
// работать на уже погашенных слушателях. Дренажи очередей среди них.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ kacho#2465
//
// Тот предмет — контекст, который не отменяется НИКОГДА (`context.Background()`
// в работе). Здесь контекст отменяется, но ОДНОЙ из двух причин. Зелёное того
// гейта об этом не говорит ничего: производный от сигнального корня контекст
// он считает законным by construction — и он законен, просто недостаточен.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОТДЕЛЬНЫЙ ТИП, А НЕ ПАРА ПЕРЕМЕННЫХ В `runServe`
//
// Предикат снятия требует ПРОБ: «ожидатель возвращается по гашению БЕЗ сигнала»
// и «корень возвращает ошибку краха, а не блокируется». Позвать `runServe` в
// пробе нельзя — он поднимает базу, слушатели и поверхности. Механизм,
// вынесенный сюда, проверяется целиком и на той же форме запуска
// (`errgroup.Group`), которой пользуется корень.
package main

import (
	"context"
	"sync"
)

// rootShutdown — корневой контекст фоновых задач и единственная ручка их гашения.
//
// Контекст ПРОИЗВОДНЫЙ от сигнального, поэтому сигнал по-прежнему гасит всё;
// сверх того его отменяет [rootShutdown.Trigger], то есть КРАХ.
type rootShutdown struct {
	ctx  context.Context
	stop context.CancelFunc

	// once — гашение исполняется РОВНО ОДИН раз. Параллельные причины (сигнал
	// пришёл одновременно с крахом внутреннего слушателя) не сделают двойного
	// останова серверов.
	once     sync.Once
	teardown func()
}

// newRootShutdown заводит корень гашения поверх сигнального контекста.
//
// `teardown` — снятие пода из ротации и остановка слушателей; исполняется ПЕРЕД
// отменой контекста задач, и порядок здесь и есть предмет: сперва перестать
// принимать, потом отпускать фоновые работы.
func newRootShutdown(signalCtx context.Context, teardown func()) *rootShutdown {
	ctx, stop := context.WithCancel(signalCtx)
	return &rootShutdown{ctx: ctx, stop: stop, teardown: teardown}
}

// Context — контекст, который берут ФОНОВЫЕ ЗАДАЧИ корня.
//
// Сигнальный контекст задачам не отдаётся: взявшая его задача не возвращается
// по гашению, начатому крахом, и держит `group.Wait()` до прихода сигнала.
func (r *rootShutdown) Context() context.Context { return r.ctx }

// Trigger начинает гашение по ЛЮБОЙ причине: сигнал, крах слушателя, отказ
// дренажа. Идемпотентен.
func (r *rootShutdown) Trigger() {
	r.once.Do(func() {
		if r.teardown != nil {
			r.teardown()
		}
		r.stop()
	})
}

// Stop отпускает ресурсы контекста, НЕ запуская гашения. Место — `defer` в
// корне: он обязан освободить контекст и на пути, где гашения не было вовсе.
func (r *rootShutdown) Stop() { r.stop() }

// Await — тело задачи-ожидателя: дождаться гашения и довести его до конца.
//
// Ждёт КОРНЕВОЙ контекст, а не сигнальный: сигнал отменяет его транзитивно
// (контекст производный), а крах — через [rootShutdown.Trigger]. Прежняя
// редакция ждала сигнальный и потому не просыпалась по краху НИКОГДА.
func (r *rootShutdown) Await() {
	<-r.ctx.Done()
	r.Trigger()
}
