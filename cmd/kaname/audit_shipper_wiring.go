// audit_shipper_wiring.go — ВЫВОЗ журнала аудита control-plane.
//
// # Что здесь появилось
//
// Приёмник. До него журнал писался четырьмя местами и не читался никем: строки
// копились с первого дня стенда, и «ноль доставленных за всю жизнь очереди»
// было верным описанием. Решение о том, ЧТО считать приёмником и почему им стал
// поток структурных записей службы, живёт в пакете `pkg/audit` — здесь оно не
// пересказывается, чтобы два места об одном предмете не разошлись.
//
// # Почему вывоз, а не общий дренаж
//
// Общая оснастка дренажа доставляет НАМЕРЕНИЕ: пару «вид события + полезная
// нагрузка», отобранную из строки. Запись журнала — это строка ЦЕЛИКОМ: актор,
// второе лицо, предмет, область, арендатор. Доставленная через отбор, она
// приехала бы без того, ради чего журнал существует. Плюс идентификатор записи
// журнала — текстовый (`evt_…`), а клейм общего дренажа читает его целым
// числом, то есть эта очередь ему не адресуема вовсе.
package main

import (
	"context"
	"log/slog"

	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/PRO-Robotech/kacho/pkg/audit"
	outboxmetrics "github.com/PRO-Robotech/kacho/pkg/outbox/metrics"
)

// buildAuditShipper строит вывоз журнала аудита.
//
// Приёмник берёт СОБСТВЕННЫЙ логгер службы, а не свой: запись аудита обязана
// уехать тем же путём, которым уезжает всё остальное, что о службе надо знать
// снаружи, — иначе у неё появился бы отдельный конвейер сбора, который никто не
// настраивал.
func buildAuditShipper(
	pool *pgxpool.Pool, rec outboxmetrics.Recorder, logger *slog.Logger,
) (*audit.Shipper, error) {
	sink, err := auditSink(logger)
	if err != nil {
		return nil, err
	}
	return audit.NewShipper(pool, sink, rec,
		logger.With(slog.String("component", "audit_shipper")),
		audit.ShipperConfig{
			Table: auditOutboxTable,
			// Ключа порядка у этой очереди НЕТ, и решение об этом принято не
			// здесь: запись журнала — независимый факт о состоявшемся действии,
			// ни одна не отменяет другую. Обоснование и его машинная сверка со
			// словарём, закрытым миграцией, живут в записи
			// repohygiene.commutativeDrainExempt; пересказывать их тут нельзя —
			// пересказ того же вывода у соседней очереди уже пережил свой
			// предмет и стал ложью, когда приехал второй вид события.
		})
}

// auditSink строит приёмник и ПРОВЕРЯЕТ его предпосылку.
//
// Отдельной функцией, потому что предпосылка проверяется fail-closed ДО подъёма
// и до базы: уровень потока задаётся настройкой развёртывания и в течение жизни
// процесса не меняется, поэтому «доедет ли журнал вообще» решается одним вызовом
// при старте. Служба, чей журнал аудита не доедет by construction, подняться
// молча не имеет права: травления у журнала нет, и очередь росла бы бессрочно
// при исправном на вид процессе.
//
// Порядок «сперва предпосылка, потом база» тоже намеренный и проверяется пробой:
// отказ обязан называть журнал, а не первую попавшуюся недостающую зависимость.
func auditSink(logger *slog.Logger) (*audit.LogSink, error) {
	sink := audit.NewLogSink(logger.With(slog.String("stream", "audit")))
	if err := sink.Preflight(context.Background()); err != nil {
		return nil, err
	}
	return sink, nil
}
