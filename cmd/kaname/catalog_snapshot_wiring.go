// catalog_snapshot_wiring.go — период, с которым снимок каталога перечитывает
// живые строки (kacho#1945).
//
// # Что этот период ЗНАЧИТ для арендатора
//
// Это не настройка производительности, а ОБЪЯВЛЕННОЕ ОКНО: сколько времени
// снятый модуль продолжает приниматься правилом роли на пути запроса. После
// #1927 членство модуля отвечают строки `catalog_module`, но путь запроса читает
// их не по одной на запрос, а через снимок — иначе каждая проверка правила стала
// бы обращением к базе. Цена снимка — ограниченное отставание, и величина
// отставания есть эта ручка.
//
// # Почему ручка, а не константа
//
// Соседние фоновые замеры держат период константой, и там это верно: их
// отставание не наблюдаемо арендатором. Здесь наблюдаемо — окном, в котором
// снятое право ещё действует, — а величину, которую видит оператор, за него не
// решают.
//
// # ОБЪЯВЛЕНИЕ ОДНО, и второе было снято, а не выровнено (#2647)
//
// Здесь стояла половина предмета: период объявляла ЕЩЁ И секция настроек
// (`jobs.catalog-snapshot.refresh-interval`, умолчание — минута), её проверял
// страж старта, и петлю она не вела НИ РАЗУ. Читателей у поля было два, и оба —
// его собственная валидация.
//
// Хуже обычного «принято-и-проигнорировано» тем, что оператор получал УСПЕХ:
// величина принята, провалидирована, отказа нет — и он был уверен, что сузил
// окно отставания. Окно оставалось прежним. Наблюдаемого отличия нет ни одного:
// снимок обновляется, просто не с тем периодом; заметить можно было только
// замером окна. Вдобавок умолчания РАСХОДИЛИСЬ вчетверо — минута против
// пятнадцати секунд, — то есть и незаданная ручка описывала поведение неверно.
//
// Исходов у принятого-и-непрочитанного поля ровно три — реализовать · отвергать
// явно · снять с объявления, — и по умолчанию берётся третий. Взят он.
// Довод не в дешевизне: ручка окружения — механизм ЗАДУМАННЫЙ (у её умолчания
// названо основание, её меряет интеграционная проба стоимости снимка, её
// объявляет страница архитектуры), а поле секции не работало ни дня и не
// описано нигде, кроме себя самого. Снят, таким образом, не выбор оператора, а
// его видимость.
//
// Ручка окружения при этом НЕ становится единственным путём оператора: загрузчик
// настроек несёт `AutomaticEnv`, поэтому всякая живая величина секции берётся
// окружением по каноническому имени. Пропала бы именно та, которой петля не
// слушала.
//
// Выравнивать значения было НЕЛЬЗЯ: два объявления об одном предмете, сведённые
// к одной величине, расходятся снова — и расходится то, которое реже читают.
// Держит это гейт `TestJobSectionKnobHasAReaderOutsideItsOwnValidation`
// (`internal/check`): у каждой величины секции фоновых заданий обязан быть
// читатель в композиционном корне.
//
// # «Никогда» этой ручкой НЕВЫРАЗИМО, и это построение, а не запрет
//
// `envDurationMS` возвращает умолчание на любом непозитивном и неразбираемом
// значении. Поэтому нуля петля не получает ни при какой посадке, и отдельного
// стража старта у величины нет: его предметом было бы состояние, которого не
// бывает. Незаданная ручка означает умолчание ниже, а НЕ «не обновлять» —
// различие несущее: пустое значение здесь пришлось бы читать как «не сужаем»,
// то есть в опасную сторону.
package main

import "time"

const (
	// catalogSnapshotRefreshKnob — период перечитывания живых строк каталога.
	catalogSnapshotRefreshKnob = "KANAME_CATALOG_SNAPSHOT_REFRESH_INTERVAL_MS"

	// catalogSnapshotRefreshDefault — умолчание окна.
	//
	// Совпадает с периодом фоновых замеров этого же процесса (15 с) намеренно:
	// одна величина у всех периодических циклов означает, что порог тревоги,
	// написанный по одному ряду, читается одинаково на любом другом.
	//
	// Цена названа: каталог закрыт и мал (десятки строк), поэтому круг стоит
	// одного чтения на реплику за период — величина, ограниченная числом реплик
	// и периодом, а НЕ нагрузкой арендатора.
	catalogSnapshotRefreshDefault = 15 * time.Second
)

// catalogSnapshotRefreshPeriod — объявленное окно отставания снимка.
func catalogSnapshotRefreshPeriod() time.Duration {
	return envDurationMS(catalogSnapshotRefreshKnob, catalogSnapshotRefreshDefault)
}
