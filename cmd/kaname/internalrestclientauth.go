// internalrestclientauth.go — внутренний REST-фронт в боевой посадке обязан
// требовать проверенного клиентского сертификата.
//
// # Предмет: рубеж у этой поверхности бывает ТОЛЬКО транспортный
//
// Мультиплексор внутреннего фронта своего рубежа не заводит — это записано в
// его собственном объявлении и верно: сужающий сопоставитель заголовков не
// пропускает внутрь НИ ОДНОГО заголовка запроса, а к собственному
// gRPC-слушателю фронт идёт СВОИМ удостоверением. Значит о том, кто позвонил по
// HTTP, ниже по стеку не знает никто: слушатель судит сертификат ФРОНТА, а не
// вызывающего.
//
// Отсюда следствие, ради которого этот страж и заведён: место, где решается
// «кому вообще позволено дотянуться до этой поверхности», у неё РОВНО ОДНО —
// рукопожатие. Односторонний транспорт оставляет этот вопрос без решателя,
// оставаясь на вид настроенным: шифрование есть, аутентификация сервера есть,
// вызывающий не назван ничем.
//
// # Почему довод публичного фронта сюда НЕ переносится
//
// У публичного фронта односторонний режим верен и обоснован: до него
// дотягивается арендатор обычным HTTP-клиентом, клиентского сертификата он не
// носит, и требование предъявить его отвергло бы КАЖДОГО на рукопожатии.
// Вызывающего там называет предъявленное удостоверение, которое проверяет
// звено собственного слушателя.
//
// У внутреннего фронта вызывающие — МОДУЛИ, называющиеся сертификатом (так
// сказано в объявлении самого фронта, и это его отличие от публичного). Довод
// «клиентского сертификата не носят» о них ложен, а предъявленное удостоверение
// внутренний слушатель не читает вовсе — его цепочка личности состоит из
// сертификата пира и переданной разрешённым отправителем личности. То есть
// перенесённый сюда довод не просто слаб: у него нет ни одной верной половины.
//
// # Почему запрашивающий режим не годится
//
// `optional-mutual` сертификат ЗАПРАШИВАЕТ и проверяет, если предъявлен, но
// соединение без него пропускает. Сужает при таком режиме обработчик, который
// проверенного пира требует сам, — а у этой поверхности такого обработчика нет
// by construction (см. выше). Значит запрашивающий режим оставил бы ровно
// прежнее положение дел, добавив к нему вид настроенности.
//
// # Ручки исключения здесь НЕТ, и это область, а не недоделка
//
// Исключение объявляют там, где у него есть предмет: у слушателя обратных
// вызовов провайдера личности он измерен — вызывающий ходит открытым текстом и
// своего доверия не несёт. Здесь предмета нет: всякий законный вызывающий этой
// поверхности — модуль с листом внутреннего удостоверяющего центра, а тот же
// центр уже подписывает материал, который профиль монтирует поду. Ручка без
// предмета есть заранее выданная слепая зона: следующая настоящая находка
// уехала бы под неё незамеченной.
//
// # Что этот страж НЕ утверждает
//
// Он говорит о РУКОПОЖАТИИ и только о нём: кто вправе дотянуться до
// поверхности. О том, что происходит с запросом дальше — чьей личностью фронт
// представляется собственному слушателю и что решает пер-RPC политика
// вызывающего, — он не утверждает ничего, и это отдельный предмет.
package main

import (
	"fmt"
	"strings"

	"github.com/PRO-Robotech/kaname/internal/apps/kaname/config"
)

// internalRESTClientAuthReader — ровно то, что стражу нужно от посадки: требует
// ли ребро сертификата и что на его ручке прочитано.
//
// Узкий интерфейс здесь не украшение: он позволяет пробе подать посадку, не
// собирая её из окружения, — и он же не даёт стражу прочитать что-либо ещё.
type internalRESTClientAuthReader interface {
	InternalRESTRequiresClientCert() bool
	InternalRESTClientAuthModeValue() string
}

// requireInternalRESTMutualClientAuth — в боевой посадке поднятый внутренний
// REST-фронт обязан требовать проверенного клиентского сертификата.
//
// В не-боевой посадке — no-op: тот же порядок, что у соседних стражей рёбер
// (стенд байт-идентичен). Пустой адрес — no-op: фронта нет, судить нечего.
//
// Отказ называет ОБЕ величины — ручку и то, что на ней прочитано, — и требуемое
// значение. Отказ, называющий только ручку, сообщает оператору, что не так, и
// не сообщает, что именно на ней стоит.
func requireInternalRESTMutualClientAuth(
	productionMode bool, internalRESTAddr string, creds internalRESTClientAuthReader,
) error {
	if !productionMode {
		return nil
	}
	if strings.TrimSpace(internalRESTAddr) == "" {
		return nil
	}
	if creds.InternalRESTRequiresClientCert() {
		return nil
	}
	return fmt.Errorf(
		"внутренний REST-фронт %s поднят без требования клиентского сертификата "+
			"(KANAME_INTERNALREST_SERVER_MTLS_CLIENTAUTHMODE=%q, требуется %q): "+
			"фронт своего рубежа не заводит и личность вызывающего внутрь не переносит — "+
			"к собственному слушателю он идёт СВОИМ удостоверением, поэтому «кому позволено "+
			"дотянуться до служебных поверхностей» решает только рукопожатие, а на этом "+
			"режиме его не решает никто; внутренний периметр доверенным не считается; "+
			"refusing to start",
		internalRESTAddr, creds.InternalRESTClientAuthModeValue(), config.InternalRESTMutualModeName())
}
