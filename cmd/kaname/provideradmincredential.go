// provideradmincredential.go — административный контур к поставщику личности
// обязан нести ПАРУ: адрес и удостоверение, которым мы себя назовём.
//
// # Предмет: половина пары хуже отсутствия обеих
//
// Контроль, обращающийся к соседу под своей личностью, объявлен настроенным
// ровно тогда, когда у него есть и адрес, и удостоверение. Объявить первое без
// второго значит завести контур, который отказывает ВСЕГДА и по одной и той же
// причине, — и отказывает молча: сосед отвечает «требуется предъявитель», наш
// клиент классифицирует это как невозможность получить ответ, и снаружи
// исправная служба выглядит недоступной.
//
// Замер, из которого страж выведен (задача #2471): профилей, называющих АДРЕС
// административного контура, — шесть; профилей, объявляющих УДОСТОВЕРЕНИЕ к
// нему, — НОЛЬ. Ни один страж этой половины не судил вовсе.
//
// # Что этот страж судит, а что НЕТ — область названа, чтобы её не выводили
//
// Он судит ПОЛОВИНУ ПАРЫ: оператор объявил, что контур возит предъявитель, а
// предъявитель не пришёл. Это состояние однозначно и чинится одним действием.
//
// Он НЕ требует объявления как такового. Незаданная ручка означает «оператор
// не высказывался», и прежнее поведение (предъявитель не требуется) остаётся:
// потребовать высказывания здесь значило бы не пустить в старт каждый
// существующий стенд — то есть завести объявленную и неисполнимую посадку
// вместо той, которую чиним. Высказаться требует ЧАРТ, у которого есть, с кого
// спросить, и требование это чарт-местное: у зонтичного чарта своя полоса и
// свой владелец.
//
// # Почему неизвестное значение — отказ, а не «считаем, что не нужен»
//
// Опечатка в значении ручки безопасности обязана останавливать старт: прочитанная
// как «не нужен», она даёт ровно то состояние, ради которого страж заведён, и
// выглядит при этом настроенной.
package main

import (
	"fmt"
	"strings"

	"github.com/PRO-Robotech/kaname/internal/apps/kaname/config"
)

// providerAdminCredentialReader — ровно то, что стражу нужно от посадки: адрес
// контура, объявленный способ аутентификации и пришедшее удостоверение.
//
// Узкий интерфейс здесь не украшение: он позволяет пробе подать посадку, не
// собирая её из окружения, — и он же не даёт стражу прочитать что-либо ещё.
type providerAdminCredentialReader interface {
	DeclaredHydraAdminURL() string
	ProviderAdminAuthValue() string
	HydraAdminTokenEnvName() string
	ResolveHydraAdminToken() string
}

// requireProviderAdminCredentialPair — объявленный `bearer` обязан прийти
// вместе с предъявителем.
//
// Адрес не объявлен — no-op: контура нет, судить нечего. Способ не объявлен —
// no-op: см. область в шапке файла. Объявлен `none` — no-op: оператор сказал,
// что его поставщик административный порт не аутентифицирует, и это его
// утверждение о его установке.
//
// Отказ называет ТРИ величины — ручку способа, имя переменной предъявителя и
// адрес контура, — потому что чинится это в трёх разных местах: профиль, объект
// секрета и координата соседа.
func requireProviderAdminCredentialPair(creds providerAdminCredentialReader) error {
	if strings.TrimSpace(creds.DeclaredHydraAdminURL()) == "" {
		return nil
	}
	switch creds.ProviderAdminAuthValue() {
	case "":
		return nil
	case config.ProviderAdminAuthNone:
		return nil
	case config.ProviderAdminAuthBearer:
		if creds.ResolveHydraAdminToken() != "" {
			return nil
		}
		return fmt.Errorf(
			"административный контур к поставщику личности объявлен возящим предъявитель "+
				"(authn.provider-admin-auth=%s), а предъявитель не пришёл: переменная %s пуста "+
				"либо не задана. Адрес контура объявлен (%s), то есть половина пары НАЗВАНА — "+
				"и такая посадка выглядит настроенной, отказывая на КАЖДОЙ административной "+
				"операции фасада: регистрация клиента, выдача доверия, снятие сессии. "+
				"Заведите объект секрета с предъявителем и подайте его этой переменной, либо "+
				"объявите authn.provider-admin-auth=%s, если административный порт вашего "+
				"поставщика не аутентифицирует никого; refusing to start",
			config.ProviderAdminAuthBearer, creds.HydraAdminTokenEnvName(),
			creds.DeclaredHydraAdminURL(), config.ProviderAdminAuthNone)
	default:
		return fmt.Errorf(
			"authn.provider-admin-auth=%q — значение вне закрытого словаря (%s): опечатка в "+
				"ручке безопасности, прочитанная как «предъявитель не нужен», дала бы ровно то "+
				"состояние, ради которого страж заведён, и выглядела бы настроенной; "+
				"refusing to start",
			creds.ProviderAdminAuthValue(), strings.Join(config.ProviderAdminAuthValues(), " | "))
	}
}
