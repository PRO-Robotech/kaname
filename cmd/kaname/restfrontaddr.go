// restfrontaddr.go — ВСЕ поверхности, которые поднимает корень, слушают разные
// адреса.
//
// # Предмет и его границы, названные по замеру, а не по памяти
//
// Раздельность поверхностей есть свойство СОКЕТА, а не содержимого запроса:
// «внутреннее не опубликовано наружу» проверяемо ровно тогда, когда «не
// опубликовано» значит «недосягаемо». Совпавшие адреса делают это требование
// невыполнимым by construction.
//
// Прежняя редакция этой шапки объясняла отказ ТИШИНОЙ: «порт занимает тот
// слушатель, который успел подняться первым; второй отказывает, процесс
// продолжает работу, и снаружи посадка выглядит исправной». Утверждение
// ОПРОВЕРГНУТО опытом (2026-09-13): подъём поверхности привязывает порт
// СИНХРОННО и возвращает отказ, а петля подъёма в `runServe` его не глотает —
//
//	servicehost: kaname не поднимает поверхность "вторая" на 127.0.0.1:34567:
//	listen tcp 127.0.0.1:34567: bind: address already in use
//
// то есть процесс не продолжает работу, а отказывает. Довод, на котором страж
// стоял, был верен для прежнего устройства подъёма и пережил его.
//
// # Что страж покупает СЕГОДНЯ — три вещи, и ни одна не «тишина»
//
//  1. отказ приходит РАНЬШЕ: до привязки хоть одного сокета поверхностей, а не
//     на середине подъёма, когда часть из них уже слушает;
//  2. отказ называет ОБЕ стороны и ОБЕ РУЧКИ профиля. Привязка называет одну
//     поверхность и адрес — и какую именно, решает порядок среза: оператор
//     узнаёт, что не так, и не узнаёт, где чинить;
//  3. отказ называет ВСЕ совпадения сразу. Привязка останавливается на первом,
//     и оператор платит круг подъёма за каждое.
//
// # Чего страж НЕ закрывает, и это не недосмотр
//
// Он сверяет адреса как СТРОКИ, поэтому `:9098` и `0.0.0.0:9098` для него
// различны, а для ядра — один сокет. Такую пару ловит привязка, и ловит
// authoritative: она судит сокет, а не текст профиля. Два механизма здесь
// дополняют друг друга, и сводить их не надо — страж делает отказ ранним и
// читаемым, привязка остаётся последним словом.
//
// # Перечень берётся из среза подъёма
//
// Сверяются ВСЕ поверхности: два gRPC-слушателя и все не-gRPC, поднимаемые
// петлёй. Их адреса приходят не парой ручек, а профилем поверхности, и берутся
// ИЗ ТОГО ЖЕ среза, которым они поднимаются (`httpSurfaces` в `runServe`, см.
// [surfaceAddrsOfRaised]). Второй перечень отстал бы от первого молча — ровно
// тот класс, из-за которого заголовок этого файла и разошёлся с кодом: он
// объявлял «ни одна поверхность не делит адрес с другой», пока сверялись
// четыре из восьми.
//
// Перепись печатается ВСЕГДА и двумя числами: «объявлено N · с адресом M».
// Одно число скрыло бы ровно тот случай, ради которого страж заведён, — а ноль
// сверенных выглядел бы как чистая посадка.
package main

import (
	"errors"
	"fmt"
)

// surfaceAddr — поверхность и ручка, которой её адрес объявлен.
//
// Ручка требуется ПОЛЕМ, а не выводится из имени: текст отказа без неё не
// отличим от придирки, и оператор знает, что не так, не зная, где это чинить.
type surfaceAddr struct {
	// knob — ручка профиля. Попадает в текст отказа.
	knob string
	// addr — адрес слушателя. Пустой ⇒ поверхность не поднимается, судить нечего.
	addr string
}

// surfaceAddrCensus — объём осмотренного. Печатается и на успешном старте:
// «ноль совпадений» обязано быть отличимо от «ничего не сверяли».
type surfaceAddrCensus struct {
	// Declared — сколько поверхностей корень объявил.
	Declared int
	// Addressed — сколько из них НЕСУТ адрес, то есть поднимаются.
	Addressed int
	// Pairs — сколько пар сверено.
	Pairs int
	// Collisions — сколько совпадений названо.
	Collisions int
}

// Fields — перепись в форме, которую принимает журнал.
func (c surfaceAddrCensus) Fields() []any {
	return []any{
		"объявлено", c.Declared,
		"с адресом", c.Addressed,
		"сверено пар", c.Pairs,
		"совпадений", c.Collisions,
	}
}

// requireDistinctSurfaceAddrs — все объявленные поверхности слушают разные
// адреса.
//
// Пустой адрес из сверки исключён: он означает «поверхность не поднята», а две
// неподнятые поверхности совпасть не могут — совпадают занятые порты, а не
// умолчания.
func requireDistinctSurfaceAddrs(surfaces []surfaceAddr) (surfaceAddrCensus, error) {
	c := surfaceAddrCensus{Declared: len(surfaces)}
	for _, s := range surfaces {
		if s.addr != "" {
			c.Addressed++
		}
	}
	var refusals []error
	for i := 0; i < len(surfaces); i++ {
		for j := i + 1; j < len(surfaces); j++ {
			a, b := surfaces[i], surfaces[j]
			if a.addr == "" || b.addr == "" {
				continue
			}
			c.Pairs++
			if a.addr != b.addr {
				continue
			}
			c.Collisions++
			refusals = append(refusals, fmt.Errorf(
				"%s и %s объявлены одним адресом %s: поверхности службы обязаны быть "+
					"РАЗНЫМИ сокетами — иначе порт занимает та, что успела подняться, "+
					"вторая отказывает на привязке, и какую из двух назовёт отказ, решает "+
					"порядок подъёма, а не профиль; refusing to start",
				a.knob, b.knob, a.addr))
		}
	}
	return c, errors.Join(refusals...)
}

// restUpstreamCredentialReader — ровно то, что стражу нужно от посадки
// транспорта: объявлено ли удостоверение фронта для собственного слушателя.
//
// Узкий интерфейс здесь не украшение: он позволяет пробе подать посадку, не
// собирая её из окружения.
type restUpstreamCredentialReader interface {
	RESTUpstreamEnabled() bool
}

// requireRESTUpstreamCredential — поднятый REST-фронт в боевой посадке обязан
// нести удостоверение для СОБСТВЕННОГО gRPC-слушателя.
//
// # Предмет — пара, а не ручка
//
// Фронт идёт к своему слушателю как обычный клиент, а слушатель в боевой
// посадке требует проверенного клиентского сертификата. Объявить адрес фронта
// и не объявить удостоверение значит завести поверхность, которая отказывает
// ВСЕГДА и по одной и той же причине.
//
// # Почему это не видно без стража
//
// Отказ детерминированный и одинаковый: слушатель отвечает «требуется
// сертификат клиента», фронт классифицирует это как невозможность получить
// ответ, и снаружи исправная служба выглядит недоступной. На стенде без боевой
// посадки слушатель сертификата не требует — там фронт работает, и проверить
// нечего.
//
// Половина пары хуже отсутствия обеих: она выглядит настроенной.
func requireRESTUpstreamCredential(productionMode bool, restAddr, internalRESTAddr string,
	creds restUpstreamCredentialReader) error {
	if !productionMode {
		return nil
	}
	if restAddr == "" && internalRESTAddr == "" {
		return nil
	}
	if creds.RESTUpstreamEnabled() {
		return nil
	}
	raised := "KANAME_API_SERVER__REST_ENDPOINT"
	if restAddr == "" {
		raised = "KANAME_API_SERVER__INTERNAL_REST_ENDPOINT"
	}
	return fmt.Errorf(
		"%s объявлен, а KANAME_REST_UPSTREAM_MTLS_ENABLE не задан: REST-фронт идёт к "+
			"СОБСТВЕННОМУ gRPC-слушателю обычным клиентом, а тот в боевой посадке требует "+
			"проверенного клиентского сертификата — без удостоверения он отвергнет фронт на "+
			"КАЖДОМ запросе, и снаружи исправная служба будет выглядеть недоступной; "+
			"refusing to start", raised)
}
