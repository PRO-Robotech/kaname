// restfrontaddr.go — ни одна поверхность службы не делит адрес с другой.
//
// # Предмет, и он появился вместе с собственным REST-фронтом
//
// Раздельность фронтов есть свойство СОКЕТА, а не содержимого запроса: «внутреннее
// не опубликовано наружу» проверяемо ровно тогда, когда «не опубликовано» значит
// «недосягаемо». Совпавшие адреса делают это требование невыполнимым by
// construction.
//
// Опасно здесь не само совпадение, а его ТИШИНА. Порт занимает тот слушатель,
// который успел подняться первым; второй отказывает, процесс продолжает работу,
// и снаружи посадка выглядит исправной. То есть внутренняя поверхность может
// оказаться на публичном адресе, и узнать об этом будет неоткуда.
//
// Поэтому исход — отказ СТАРТА: неверную посадку чинят один раз в профиле, а не
// ловят потом по симптому.
//
// # Отказ называет ВСЕ совпадения сразу
//
// Оператор чинит профиль один раз, а не по одному совпадению за перезапуск.
// Страж, останавливающийся на первом, продаёт круг подъёма вместо одного — тот
// же довод, по которому так устроен страж транспорта рёбер рядом.

package main

import (
	"errors"
	"fmt"
)

// surfaceAddr — поверхность и ручка, которой её адрес объявлен.
//
// Ручка требуется ПОЛЕМ, а не выводится из имени: текст отказа без неё не
// отличим от придирки, и оператор знает, что не так, не зная, где это чинить.
type surfaceAddr struct {
	// knob — ручка профиля. Попадает в текст отказа.
	knob string
	// addr — адрес слушателя. Пустой ⇒ поверхность не поднимается, судить нечего.
	addr string
}

// requireDistinctSurfaceAddrs — четыре поверхности службы слушают четыре разных
// адреса.
//
// Пустой адрес из сверки исключён: он означает «поверхность не поднята», а две
// неподнятые поверхности совпасть не могут — совпадают занятые порты, а не
// умолчания.
func requireDistinctSurfaceAddrs(publicGRPC, internalGRPC, publicREST, internalREST string) error {
	surfaces := []surfaceAddr{
		{"KANAME_API_SERVER__ENDPOINT", publicGRPC},
		{"KANAME_API_SERVER__INTERNAL_ENDPOINT", internalGRPC},
		{"KANAME_API_SERVER__REST_ENDPOINT", publicREST},
		{"KANAME_API_SERVER__INTERNAL_REST_ENDPOINT", internalREST},
	}
	var refusals []error
	for i := 0; i < len(surfaces); i++ {
		for j := i + 1; j < len(surfaces); j++ {
			a, b := surfaces[i], surfaces[j]
			if a.addr == "" || a.addr != b.addr {
				continue
			}
			refusals = append(refusals, fmt.Errorf(
				"%s и %s объявлены одним адресом %s: поверхности службы обязаны быть "+
					"РАЗНЫМИ сокетами — иначе порт занимает та, что успела подняться, "+
					"вторая молча не поднимается, и посадка снаружи выглядит исправной; "+
					"refusing to start",
				a.knob, b.knob, a.addr))
		}
	}
	return errors.Join(refusals...)
}

// restUpstreamCredentialReader — ровно то, что стражу нужно от посадки
// транспорта: объявлено ли удостоверение фронта для собственного слушателя.
//
// Узкий интерфейс здесь не украшение: он позволяет пробе подать посадку, не
// собирая её из окружения.
type restUpstreamCredentialReader interface {
	RESTUpstreamEnabled() bool
}

// requireRESTUpstreamCredential — поднятый REST-фронт в боевой посадке обязан
// нести удостоверение для СОБСТВЕННОГО gRPC-слушателя.
//
// # Предмет — пара, а не ручка
//
// Фронт идёт к своему слушателю как обычный клиент, а слушатель в боевой
// посадке требует проверенного клиентского сертификата. Объявить адрес фронта
// и не объявить удостоверение значит завести поверхность, которая отказывает
// ВСЕГДА и по одной и той же причине.
//
// # Почему это не видно без стража
//
// Отказ детерминированный и одинаковый: слушатель отвечает «требуется
// сертификат клиента», фронт классифицирует это как невозможность получить
// ответ, и снаружи исправная служба выглядит недоступной. На стенде без боевой
// посадки слушатель сертификата не требует — там фронт работает, и проверить
// нечего.
//
// Половина пары хуже отсутствия обеих: она выглядит настроенной.
func requireRESTUpstreamCredential(productionMode bool, restAddr, internalRESTAddr string,
	creds restUpstreamCredentialReader) error {
	if !productionMode {
		return nil
	}
	if restAddr == "" && internalRESTAddr == "" {
		return nil
	}
	if creds.RESTUpstreamEnabled() {
		return nil
	}
	raised := "KANAME_API_SERVER__REST_ENDPOINT"
	if restAddr == "" {
		raised = "KANAME_API_SERVER__INTERNAL_REST_ENDPOINT"
	}
	return fmt.Errorf(
		"%s объявлен, а KANAME_REST_UPSTREAM_MTLS_ENABLE не задан: REST-фронт идёт к "+
			"СОБСТВЕННОМУ gRPC-слушателю обычным клиентом, а тот в боевой посадке требует "+
			"проверенного клиентского сертификата — без удостоверения он отвергнет фронт на "+
			"КАЖДОМ запросе, и снаружи исправная служба будет выглядеть недоступной; "+
			"refusing to start", raised)
}
