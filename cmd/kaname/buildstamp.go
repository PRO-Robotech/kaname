package main

// buildstamp.go — ЧТО ЭТОТ ДВОИЧНЫЙ ФАЙЛ ГОВОРИТ О СЕБЕ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ОТКУДА ПРИХОДЯТ ВЕЛИЧИНЫ
//
// Из ШТАМПА СБОРКИ, подставляемого компоновщиком:
//
//	go build -ldflags "-X main.buildVersion=… -X main.buildRevision=…"
//
// Обе величины сборка берёт из ТОГО ЖЕ объявления, из которого делает клеймо
// образа и файл ревизии внутри него (`ARG KACHO_IMAGE_VERSION` /
// `ARG KACHO_IMAGE_REVISION` в Dockerfile службы, а сами величины — из
// `provenance.mk`). Источник один, поэтому строка на витрине и строка на образе
// разойтись не могут.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ НЕ РУЧКА ПРОФИЛЯ
//
// Величину, которую объявляет оператор, он вправе объявить любой. Тогда ряд
// отвечает не на «что исполняется», а на «что об этом написали» — и первый же
// откат выкатки, забывший поправить ручку, делает витрину лживой ровно в тот
// момент, ради которого она заведена.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ УМОЛЧАНИЕ ПУСТОЕ, А НЕ `dev`
//
// Пустое приводится витриной к слову «не проставлено»
// ([metrics.BuildInfoUnstamped]). Правдоподобное `dev` этого не даёт: оно
// читается как имя ветки, то есть как ответ, — и «сборка штамп не поставила»
// становится неотличимо от «собрано из ветки dev». Различать эти два состояния
// обязательно: первое означает, что величине верить нельзя вовсе.
//
// Здесь эти переменные — ЕДИНСТВЕННОЕ место их объявления в службе. Второе
// объявление разошлось бы с первым молча: компоновщик подставляет значение по
// полному имени и о существовании второго не знает.
var (
	// buildVersion — человекочитаемая версия сборки (у монорепо — имя ссылки git).
	buildVersion = ""
	// buildRevision — ревизия дерева, из которого собран двоичный файл.
	buildRevision = ""
)
