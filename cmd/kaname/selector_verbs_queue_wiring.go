package main

import "time"

// selectorVerbsQueueRetry — пауза между проходами пересчёта очереди глаголов
// правил (kaname#878) после прохода, оставившего очередь непустой (отказ роли
// либо роль, поставленная во время прохода); после пустого прохода разбор ждёт
// десять таких пауз и проверяет очередь снова. Тридцать секунд — того же порядка,
// что окно отставания снимка каталога (catalogSnapshotRefreshDefault): чаще
// повторять бессмысленно, пока отказ держит транзиентная причина, реже — значит
// держать окно миграции открытым дольше, чем отставание каталога.
const selectorVerbsQueueRetry = 30 * time.Second
