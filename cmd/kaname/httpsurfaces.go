// httpsurfaces.go — ОБЩАЯ ЧАСТЬ объявлений не-gRPC поверхностей iam.
//
// Число поверхностей здесь НЕ выписывается: оно росло молча (в день заведения
// этого файла их было четыре, при снятии числа — шесть), а у числа в
// комментарии нет владельца. Перечень выводится предикатом:
//
//	go test ./cmd/kaname/ -run TestIAM2480_DerivedPopulationCounts -v
//
// он печатает перепись и падает, если построенная поверхность никем не
// обслуживается либо обслуживается непостроенная.
//
// # Что здесь общее, а что нет — и почему граница именно такая
//
// Общее — СРОКИ и имя процесса: они одинаковы у всех и были выписаны по месту
// у каждой, то есть держались тем, что автор написал те же числа.
// Разъехавшиеся числа читались бы как осознанная разница, которой нет.
//
// НЕ общее — имя поверхности, адрес, досягаемость, решение об аутентификации и
// транспорт. Их сводить нельзя: именно ими поверхности и отличаются, и
// пара «досягаемость × аутентификация» — единственное, что профиль судит по
// существу. Помощник, подставляющий сюда умолчание, вернул бы решение о доступе,
// принятое никем.
package main

import (
	"crypto/tls"
	"time"

	"github.com/PRO-Robotech/corelib/servicecontract"
)

// Сроки не-gRPC поверхностей iam. Величины взяты у прежних отдельных серверов
// один-в-один, кроме одной: срок гашения раньше жил не в объявлении, а в общем
// триггере остановки — копией на каждую поверхность.
const (
	// iamSurfaceReadHeaderBudget — потолок чтения заголовка.
	iamSurfaceReadHeaderBudget = 10 * time.Second
	// iamSurfaceRequestBudget — потолок чтения и записи запроса целиком.
	//
	// ОБОСНОВАНИЕ ПОТОЛКА — СВОЙСТВО, А НЕ ПЕРЕЧЕНЬ. Прежняя редакция звучала
	// «все четыре поверхности запрос-ответные, потоковых среди них нет» и была
	// верна относительно ПРЕЖНЕЙ популяции: величина связывает теперь и оба
	// REST-фронта, чья обёртка ответа реализует `Flush` ИМЕННО ради потоковой
	// полосы. Живого дефекта нет — потоковых RPC в контракте ноль, — но
	// предпосылка молча перестала описывать то, к чему применяется.
	//
	// Действующее обоснование: поверхность, которой понадобится поток, обязана
	// объявить СВОЙ срок, а не наследовать этот; пока ни одна не объявила, срок
	// общий. Предикат — та же перепись, что и у числа поверхностей.
	iamSurfaceRequestBudget = 30 * time.Second
	// iamSurfaceIdleBudget — потолок простоя keep-alive соединения.
	iamSurfaceIdleBudget = 90 * time.Second
	// iamSurfaceShutdownBudget — срок гашения.
	iamSurfaceShutdownBudget = 5 * time.Second
)

// РУЧКИ ПРОФИЛЯ, которыми объявлены адреса поверхностей.
//
// Имя ручки нужно в ДВУХ местах: в причине, по которой поверхность выключена
// (её печатает журнал при подъёме), и в отказе стража различимости адресов —
// оператор знает, что не так, только если знает, ГДЕ это чинить. Два литерала
// об одном предмете разошлись бы молча, и разошёлся бы тот, который реже
// читают, поэтому имя объявлено здесь один раз.
const (
	// knobPublicGRPC — публичный gRPC-слушатель.
	knobPublicGRPC = "KANAME_API_SERVER__ENDPOINT"
	// knobInternalGRPC — внутренний gRPC-слушатель.
	knobInternalGRPC = "KANAME_API_SERVER__INTERNAL_ENDPOINT"
	// knobPublicREST — собственный публичный REST-фронт.
	knobPublicREST = "KANAME_API_SERVER__REST_ENDPOINT"
	// knobInternalREST — собственный внутренний REST-фронт.
	knobInternalREST = "KANAME_API_SERVER__INTERNAL_REST_ENDPOINT"
	// knobHooks — вебхуки провайдера личности.
	knobHooks = "KANAME_AUTHN__HOOKS_HTTP_ENDPOINT"
	// knobMetrics — скрейп величин.
	knobMetrics = "KANAME_API_SERVER__METRICS_ENDPOINT"
	// knobRegistryToken — выдача докерного токена.
	//
	// #nosec G101 -- это ИМЯ РУЧКИ, которую правит оператор, а не удостоверение:
	// значение приходит из окружения, здесь стоит только его адрес. Сканер
	// опознаёт подстроку TOKEN в имени постоянной и иначе решить не может.
	knobRegistryToken = "KANAME_API_SERVER__REGISTRY_TOKEN__ENDPOINT"
	// knobJWKSProxy — зеркало набора ключей проверки подписи.
	knobJWKSProxy = "KANAME_API_SERVER__JWKS_PROXY__ENDPOINT"
)

// raisedSurface — поверхность, которую поднимает корень, И РУЧКА, которой её
// адрес объявлен.
//
// # Зачем пара, а не голый дескриптор
//
// Ручку не вывести из дескриптора: [servicecontract.Surface] её не несёт, а имя
// поверхности («скрейп величин») оператору адреса не называет. Пара кладётся в
// ТОТ ЖЕ срез, которым поверхности поднимаются, поэтому страж различимости
// адресов читает ровно то, что корень поднимает, и второго перечня — который
// отстал бы молча — не заводится.
type raisedSurface struct {
	// knob — ручка профиля, объявившая адрес. Попадает в текст отказа.
	knob string
	// desc — принятый профиль поверхности, по которому она поднимается.
	desc servicecontract.SurfaceDescriptor
}

// surfaceAddrsOfRaised — адреса поверхностей ИЗ ТОГО ЖЕ среза, которым они
// поднимаются.
//
// Один элемент на элемент, by construction: сверяется ровно то, что поднято, и
// «сверено меньше, чем поднимается» непредставимо. Выключенная поверхность
// отдаёт пустой адрес — страж исключает его сам («поверхность не поднята»),
// и решение об этом принимается в одном месте, а не в двух.
func surfaceAddrsOfRaised(raised []raisedSurface) []surfaceAddr {
	out := make([]surfaceAddr, 0, len(raised))
	for _, s := range raised {
		addr, _ := s.desc.Spec().Addr.Get()
		out = append(out, surfaceAddr{knob: s.knob, addr: addr})
	}
	return out
}

// iamHTTPSurface достраивает объявление ОБЩЕЙ частью и отдаёт его конструктору.
//
// Аргумент — уже наполовину заполненная [servicecontract.Surface], а не набор
// параметров: так видно, что именно вызывающий обязан сказать сам, и добавление
// новой оси в профиль не проходит здесь молча.
func iamHTTPSurface(s servicecontract.Surface) (servicecontract.SurfaceDescriptor, error) {
	s.Service = "kaname"
	s.ReadHeaderBudget = iamSurfaceReadHeaderBudget
	s.RequestBudget = servicecontract.Value(iamSurfaceRequestBudget)
	s.IdleBudget = iamSurfaceIdleBudget
	s.ShutdownBudget = iamSurfaceShutdownBudget
	return servicecontract.NewSurface(s)
}

// restFrontAuthAxis — ЧЕМ собственный публичный REST-фронт устанавливает
// субъекта, ВЫВЕДЕННОЕ из того, построено ли звено, а не вписанное константой.
//
// # Зачем это функция, а не строка по месту
//
// Здесь стояла константа, передаваемая описанием поверхности: она объявляла
// «проверяет и назначает субъекта звено собственного слушателя» при ЛЮБОЙ
// посадке, включая ту, где звена нет вовсе. В том же журнале того же процесса
// стоял признак, говорящий обратное, — два утверждения об одном предмете, из
// которых верно было второе (#2194).
//
// Самоотчёт заводился ровно затем, чтобы ОПЕРАТОРУ было видно, какая посадка
// исполняется. Константа этого не сообщает: пока механизм не построен, отчёт о
// нём есть утверждение без предмета, а когда построен — верен по совпадению.
//
// # Почему аргумент — «построено», а не «включено настройкой»
//
// Настройка объявляет НАМЕРЕНИЕ, построение — ФАКТ. Между ними стоит отказ
// построения (нет собственного реестра ключей — проверять подпись нечем), и
// самоотчёт обязан следовать за фактом: иначе он повторит намерение там, где
// оно не сбылось, — то есть вернёт ровно тот класс, ради которого написан.
//
// Отдельная задача (#2191) — про то, что механизм не поднимается ни на одной
// посадке. Её починка эту не закрывает и не отменяет: константа осталась бы
// константой, просто верной. Здесь предмет — ЗАВИСИМОСТЬ отчёта от предмета.
func restFrontAuthAxis(presentedReaderBuilt bool) servicecontract.Axis[servicecontract.SurfaceAuthMech] {
	if presentedReaderBuilt {
		return servicecontract.Value[servicecontract.SurfaceAuthMech](
			"предъявленное арендатором удостоверение: фронт переносит его, ничего не " +
				"добавляя, а проверяет и назначает субъекта звено собственного слушателя")
	}
	// Отрицательная сторона называет СОСТОЯНИЕ, а не молчит. Молчание здесь
	// неотличимо от «механизм есть», и оператор прочёл бы отсутствие оси как
	// недосмотр объявления, а не как посадку.
	return servicecontract.Value[servicecontract.SurfaceAuthMech](
		"читатель предъявленного удостоверения на этой посадке НЕ ПОДНЯТ: фронт " +
			"переносит предъявленное арендатором, и субъекта по нему не устанавливает " +
			"никто. Вызывающий опознаётся только сертификатом модуля либо личностью, " +
			"переданной разрешённым отправителем, — арендатору, пришедшему извне, " +
			"назваться нечем")
}

// internalRESTFrontAuthAxis — ЧЕМ собственный внутренний REST-фронт опознаёт
// вызывающего, ВЫВЕДЕННОЕ из фактического режима его ребра.
//
// # Предмет: сертификат называет ХОП, а не звонящего
//
// Здесь стояла константа: «цепочка внутреннего слушателя: проверенный
// сертификат модуля и его политика вызывающего». Проверенный сертификат на том
// хопе действительно есть — только он принадлежит САМОМУ ФРОНТУ: к собственному
// слушателю фронт идёт своим удостоверением, а входящие заголовки сужающий
// сопоставитель внутрь не пропускает. О том, кто позвонил по HTTP, этот
// сертификат не говорит ничего, и показание называло механизм, которого на
// проводе нет.
//
// Расхождение показания с проводом дороже самого расхождения посадки: гейт,
// читающий самоотчёт, становится на этой оси вакуумным — он подтверждает то,
// чего нет, и заметить это нечем.
//
// # Почему ось спрашивает про рукопожатие
//
// Рубеж у этой поверхности бывает ровно один — транспортный (разбор в
// internalrestclientauth.go). Значит и назвать ось честно можно только им:
// «требует проверенного клиентского сертификата» либо «не требует ничего».
// Третьего механизма у фронта нет, и приписать ему чужой — то же, что
// приписывали здесь раньше.
//
// # Обе стороны НАЗЫВАЮТ состояние, и ни одна не молчит
//
// Молчание оси означало бы «не объявлена» — отказ старта (Н5), — а объявление
// «аутентификации нет» на внутренней поверхности законно и обязано быть
// прочитанным как посадка, а не как недосмотр. В боевой посадке отрицательная
// сторона недостижима by construction: страж туда не пускает.
func internalRESTFrontAuthAxis(requiresClientCert bool) servicecontract.Axis[servicecontract.SurfaceAuthMech] {
	if requiresClientCert {
		return servicecontract.Value[servicecontract.SurfaceAuthMech](
			"проверенный клиентский сертификат внутреннего удостоверяющего центра, " +
				"требуемый на рукопожатии: фронт своего рубежа не заводит и к личности " +
				"ничего не добавляет, поэтому кому позволено дотянуться до поверхности " +
				"решает только транспорт")
	}
	return servicecontract.NotApplicable[servicecontract.SurfaceAuthMech](
		"клиентского сертификата фронт на этой посадке НЕ ТРЕБУЕТ, и другого рубежа " +
			"у него нет: к собственному слушателю он идёт своим удостоверением, а " +
			"входящие заголовки внутрь не переносит — значит вызывающий не назван ничем. " +
			"Поверхность досягаема только внутри кластера; в боевой посадке такая " +
			"посадка не поднимается")
}

// addrAxis превращает «адрес из конфигурации» в ОСЬ с тремя состояниями.
//
// Пустая строка перестаёт быть молчаливым выключением: она становится
// объявленным выключением с причиной, и причина попадает в журнал при старте.
// Причина требуется АРГУМЕНТОМ, а не берётся из общего шаблона — у четырёх
// поверхностей iam цена выключения РАЗНАЯ: у скрейпа это отсутствие
// наблюдаемости, у зеркала ключей — закрытая верификация всей плоскости данных
// реестра.
func addrAxis(addr, becauseEmpty string) servicecontract.Axis[string] {
	if addr == "" {
		return servicecontract.NotApplicable[string](becauseEmpty)
	}
	return servicecontract.Value(addr)
}

// ownRESTFront — ОБЪЯВЛЕНИЕ собственного REST-фронта: адрес, по которому он
// поднимается, и транспорт, под которым идёт его провод.
//
// # Зачем отдельное значение, а не две переменные по месту
//
// Об одном предмете здесь говорят ДВА потребителя: самоотчёт о посадке
// (own_rest_public_tls / own_rest_internal_tls) и профиль поверхности, по
// которому фронт реально поднимается. Выведенные из ОДНОГО объявления, они не
// могут разойтись by construction; прочитанные порознь из настройки — разойдутся
// молча, и верным окажется одно. Это ровно то требование, которое производитель
// оси предъявляет её величине (pkg/observability, OwnRESTFrontFrom).
//
// # Почему значение живёт здесь, а не строится из дескриптора поверхности
//
// [servicecontract.SurfaceDescriptor] отвечает на те же два вопроса и заведён в
// том числе для этой оси. Взять величину прямо у него нельзя по РАЗМЕЩЕНИЮ:
// дескрипторы собираются вместе с прочими не-gRPC поверхностями — после того как
// сокеты gRPC-слушателей уже привязаны, — а строка самоотчёта обязана быть
// напечатана ДО подъёма листенеров, и это требование держит проба
// TestBootPosture_EmittedFromTheLiveBootPath. Поэтому единым источником сделано
// объявление, а не дескриптор: оба потребителя читают ЕГО, и дескриптор в том
// числе. Согласие двух прочтений не подразумевается, а проверяется —
// TestOwnRESTFrontMatchesTheSurfaceDescriptor.
type ownRESTFront struct {
	// addr — адрес слушателя фронта. Пустой означает «профиль развёртывания эту
	// поверхность не объявил», то есть фронта на этой посадке нет.
	addr string
	// tls — транспорт слушателя. nil означает открытый текст.
	//
	// Ось СПРАШИВАЕТ ПРО ПРОВОД, а не про то, требует ли фронт клиентского
	// сертификата: величина OwnRESTFrontPlaintext объявлена производителем как
	// «работает ОТКРЫТЫМ ТЕКСТОМ», и отдать её под шифрованным проводом без
	// клиентского сертификата значило бы сказать неправду о проводе. Требование
	// клиентского сертификата — отдельное измерение, и в этой оси его нет.
	tls *tls.Config
}

// Enabled — поднимается ли поверхность. Зеркалит
// [servicecontract.SurfaceDescriptor.Enabled].
func (f ownRESTFront) Enabled() bool { return f.addr != "" }

// UnderTLS — идёт ли провод поверхности под транспортом. Зеркалит
// [servicecontract.SurfaceDescriptor.UnderTLS].
func (f ownRESTFront) UnderTLS() bool { return f.tls != nil }
