package main

// module_seed_apply.go — раздел `seed` СВОЕГО манифеста службы и доставленных
// манифестов модулей ПРИМЕНЯЕТСЯ на старте (задачи #2452, kaname#106).
//
// # Зачем это здесь
//
// До этой задачи применителя у раздела `seed` не было НИ ОДНОГО: служебные
// учётки модулей платформы, их членства и выдачи заводила ПРИМЕНЁННАЯ МИГРАЦИЯ
// службы доступа, а раздел с ними лишь сверялся (`internal/moduleseedparity`).
//
// Цена измерена: миграция применяется ВЕЗДЕ, включая установку, где платформы
// нет вовсе, — и самостоятельная служба доступа заводила ПЯТЬ служебных
// личностей чужого продукта, с выданными правами и без способа узнать, откуда
// они взялись. Строки сняты миграцией
// `20260909202745_module_identities_leave_the_baseline.sql`, и их производителем
// стал этот путь.
//
// # Разрядов манифестов ДВА, и условие у них разное (приёмка MRW-1, Р3)
//
// СВОЙ манифест службы приезжает встроенным в образ (`internal/servicemanifest`)
// и применяется ВСЕГДА и ПЕРВЫМ — доставкой он не связан: группу пишущих
// кортежи `module-relation-writers` и её выдачу заводит сама служба, и на
// самостоятельной установке они нужны так же, как в посадке платформы. Порядок
// «своё раньше доставленного» несущий: вступление модуля обязано встретить
// группу заведённой независимо от имени модуля и от порядка обхода каталога
// доставки (`compute` < `iam` лексически).
//
// ДОСТАВЛЕННЫЕ манифесты заводят ровно то, что объявила доставка, и условием
// служит ОНА: каталог доставки кладёт зонтичный чарт платформы и не кладёт чарт
// самостоятельной службы, поэтому «платформа присутствует» выражено тем, что
// объявила установка. Кода, который догадывался бы о присутствии соседей, здесь
// нет и не должно быть: догадка была бы вторым источником одного факта.
//
// Свой манифест подаётся применителю ОТДЕЛЬНЫМ доводом, а не подмешивается в
// перечень доставки: перечень читают пять потребителей старта (опора паритета,
// композиция модели, применитель каталога, применитель ролей, применитель
// посева), и подмешанный манифест достался бы всем разом — вплоть до второго
// писателя строк каталога модуля `iam`, которые сеет миграция. Получатель у
// своего манифеста ровно один — применитель посева; это держит гейт
// `module_seed_apply_wiring_test.go` (часть C), а не этот комментарий.
//
// # Порядок: ПОСЛЕ применения ролей
//
// Довод из двух половин, и каждая самостоятельно достаточна.
//
//  1. **Ключи.** Выдача формой РОЛИ ссылается на строку роли
//     (`access_bindings_role_fk`) и на её живость (`access_bindings_role_is_live_trg`).
//     Посев, применённый до ролей, отказывал бы отказом ЧУЖОГО ограничения,
//     называя не тот предмет. Сегодня ни один манифест такой выдачи не
//     объявляет — но порядок принадлежит ФОРМЕ, а не сегодняшнему содержимому:
//     первый же такой манифест иначе упал бы на старте.
//
//  2. **Ярусность отказов.** Путь старта уже отказывает на сорванной доставке,
//     на расхождении каталога, на его применении и на применении ролей. Пятый
//     отказ стоит последним, потому что его предмет — самый производный: он
//     ссылается и на каталог, и на роли, и на якорь кластера.
//
// Порядок держит гейт `module_seed_apply_wiring_test.go`, а не этот комментарий.
//
// # Отказ применения — ОТКАЗ ПУСКА
//
// Мягкий проход дал бы производителя, не произведшего ни разу и не сказавшего об
// этом (§Hardening, п. 8). Предмет здесь — ЛИЧНОСТЬ И ПРАВО:
// модуль, чья служебная запись не доехала, снаружи выглядит как «сосед
// недоступен», а модуль, чья выдача доехала наполовину, — как «право не выдали».
// Отличить и то и другое от исправной работы можно только вызовом.
//
// Цена названа: временный отказ базы на старте роняет под, и он уходит в
// перезапуск. Она мала и ограничена — применение идемпотентно (доказано против
// живой базы, `module_seed_writer_integration_test.go`), поэтому перезапуск есть
// повтор, а не углубление беды.

import (
	"context"
	"fmt"
	"log/slog"

	"github.com/PRO-Robotech/kaname/internal/apps/kaname/moduleseed"
	"github.com/PRO-Robotech/kaname/internal/manifest"
	"github.com/PRO-Robotech/kaname/internal/servicemanifest"
)

// loadOwnManifest читает СВОЙ манифест службы из образа и печатает перепись его
// связности — ВСЕГДА, независимо от исхода.
//
// Читается тем же загрузчиком, что и доставка, и БЕЗ оракула модели прав (Р3):
// на пути старта модель ещё собирается из доставленного, и второй судья для
// своего документа дал бы другой вердикт, чем оснастка дерева. Отношение и вид
// получателя судит оснастка (`make module-manifest-check`), а копия в образе
// побайтово равна тому, что она судила (`internal/servicemanifest`).
//
// Отказ ФАТАЛЕН: встроенный манифест, который не разбирается, означает образ,
// собранный из документа, не прошедшего оснастку, — поднимать службу на нём
// значило бы поднимать её без группы пишущих кортежи и без её выдачи.
func loadOwnManifest(logger *slog.Logger) (*manifest.Manifest, error) {
	own, err := servicemanifest.Load()
	if err != nil {
		return nil, fmt.Errorf("свой манифест службы: %w", err)
	}
	seeding := own.Seed != nil
	logger.Info("свой манифест службы прочитан из образа",
		slog.String("module", own.Module),
		slog.Bool("seeding", seeding),
		slog.String("linkage", own.Linkage().String()))
	return own, nil
}

// applyModuleSeed приводит посев к объявленному состоянию — сначала СВОИМ
// манифестом службы, затем ДОСТАВЛЕННЫМИ манифестами модулей — и печатает
// перепись ВСЕГДА, независимо от исхода.
//
// Перепись обязательна и печатается ЧИСЛАМИ, раздельно по разрядам: «свой
// применён, доставлено шесть, строк записано ноль» и «свой применён, доставлено
// ноль» — разные утверждения о платформе, а молчание у них одно и то же. Второе
// означает самостоятельную установку — своя группа и её выдача заведены,
// служебных учёток модулей платформы нет; первое — повторный старт, на котором
// всё уже стоит.
//
// Пустая доставка своего применения НЕ отменяет: своё доставкой не связано (Р3).
// «Объявлена и сорвана» сюда не доходит — её отверг читатель доставки.
func applyModuleSeed(
	ctx context.Context,
	logger *slog.Logger,
	applier *moduleseed.Applier,
	own *manifest.Manifest,
	delivered []*manifest.Manifest,
) error {
	if len(delivered) == 0 {
		logger.Info("посев модулей: доставленных манифестов нет — самостоятельная установка, " +
			"служебных учёток модулей платформы не заводится; свой манифест службы применяется")
	}

	census, err := applier.Apply(ctx, own, delivered)
	declared, written := census.Totals()
	logger.Info("перепись применения посева",
		slog.Bool("own_applied", census.Own != nil),
		slog.Int("delivered", census.Manifests),
		slog.Int("seeding", census.Seeding),
		slog.Int("declared_rows", declared),
		slog.Int("written_rows", written))
	reports := census.Reports
	if census.Own != nil {
		reports = append([]moduleseed.Report{*census.Own}, reports...)
	}
	for i, r := range reports {
		kind := "доставленный"
		if census.Own != nil && i == 0 {
			kind = "свой"
		}
		logger.Info("посев манифеста",
			slog.String("kind", kind),
			slog.String("module", r.Module),
			slog.Int("service_accounts", r.WrittenAccounts),
			slog.Int("groups", r.WrittenGroups),
			slog.Int("joins", r.WrittenJoins),
			slog.Int("grants", r.WrittenGrants),
			slog.Int("declared", r.DeclaredAccounts+r.DeclaredGroups+r.DeclaredJoins+r.DeclaredGrants))
	}
	if err != nil {
		return fmt.Errorf("посев модулей: %w", err)
	}
	return nil
}
