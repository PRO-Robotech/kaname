// own_ceilings_apply.go — ТРИ СОБСТВЕННЫХ ПОТОЛКА ПРОЕЦИРУЮТСЯ В СХЕМУ НА СТАРТЕ
// (приёмка `KAN-QUOTA-1`, `П25`; задача продукта #2117).
//
// # Зачем этот шаг вообще нужен
//
// Величину объявляет посадка, а решение о списании принимает единственный
// атомарный оператор в базе — в той же транзакции, что вставка строки ресурса
// (ban #10). Триггер не читает настройку процесса ни при каком построении, значит
// объявленная величина обязана доехать до схемы. Этот шаг — единственный её
// перевозчик, и другого писателя у проекции нет.
//
// # Порядок: ПОСЛЕ стража схемы, ПЕРЕД слушателями
//
// После схемы — потому что проекция пишет в таблицу, которую заводит миграция:
// её отсутствие есть «условие не создано», и говорить об этом обязан страж схемы,
// а не отказ вставки.
//
// Перед слушателями — потому что первый же принятый запрос может создать ресурс,
// чей потолок эта проекция и объявляет. Поднять слушатель раньше значило бы
// открыть окно, в котором действует величина ПРЕДЫДУЩЕГО пуска, а журнал уже
// сообщил новую.
//
// # Отказ проекции — ОТКАЗ ПУСКА
//
// Мягкий проход дал бы контроль, который не отказал ни разу: служба поднялась бы,
// объявив в журнале одну величину и применяя другую. Это ровно тот класс, где
// «работает» и «потолок не тот» выглядят одинаково.
//
// Цена названа: временный отказ базы на старте роняет под, и он уходит в
// перезапуск. Она мала и ограничена — применение идемпотентно, поэтому перезапуск
// есть повтор, а не углубление беды.

import (
	"context"
	"fmt"
	"log/slog"

	"github.com/PRO-Robotech/kaname/internal/apps/kaname/config"
	"github.com/PRO-Robotech/kaname/internal/domain"
	kanamepg "github.com/PRO-Robotech/kaname/internal/repo/kaname/pg"
)

// ownCeilingProjector — писатель проекции. Интерфейс, а не тип: композиционный
// корень остаётся единственным местом, знающим, чем он реализован.
type ownCeilingProjector interface {
	Apply(ctx context.Context, stated map[domain.LimitKind]int64) (kanamepg.OwnCeilingProjection, error)
}

// projectOwnCeilings переносит объявленные посадкой величины в схему и печатает
// перепись — ВСЕГДА, независимо от исхода.
//
// Перепись обязательна: «объявлено три, записано ноль» означает, что величины уже
// совпадали, а «объявлено ноль» — что посадка их не назвала; молчание у этих двух
// утверждений одно и то же.
func projectOwnCeilings(
	ctx context.Context,
	logger *slog.Logger,
	projector ownCeilingProjector,
	cfg config.OwnCeilingsConfig,
) error {
	stated := cfg.Stated()
	census, err := projector.Apply(ctx, stated)
	logger.Info("перепись проекции собственных потолков",
		slog.Int("stated", census.Stated),
		slog.Int("written", census.Written),
		slog.Int("removed", census.Removed),
		slog.Any("kinds", census.Kinds))
	if err != nil {
		return fmt.Errorf("собственные потолки: проекция посадки в схему: %w", err)
	}
	return nil
}
