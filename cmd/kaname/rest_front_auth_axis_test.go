package main

// rest_front_auth_axis_test.go — САМООТЧЁТ О МЕХАНИЗМЕ ВЫВОДИТСЯ ИЗ ТОГО,
// ПОСТРОЕН ЛИ ОН, А НЕ ВПИСАН КОНСТАНТОЙ.
//
// ПРЕДМЕТ. Служба при старте печатала о собственном публичном фронте, что
// звено слушателя «проверяет и назначает субъекта». Строка была КОНСТАНТОЙ,
// передаваемой описанием поверхности, и со состоянием построения не сверялась
// никак. В том же журнале того же процесса стоял признак, говорящий обратное:
// читателя предъявленного удостоверения нет. Два утверждения об одном предмете
// в одном выводе, и верно было второе.
//
// Самоотчёт существует затем, чтобы ОПЕРАТОРУ было видно, какая посадка
// исполняется, — и как раз этого он не сообщал: пока механизм не построен,
// отчёт о нём есть утверждение без предмета, а когда построен — верен по
// совпадению, а не по построению.
//
// ПОЧЕМУ ПАРА, А НЕ ОДНО УТВЕРЖДЕНИЕ. Односторонняя проба («механизм есть →
// строка про него») зеленела бы на константе: константа даёт эту строку при
// любом состоянии. Различающим является ТОЛЬКО сравнение двух посадок между
// собой — оно спрашивает не «верна ли строка», а «меняется ли она вместе с
// тем, о чём говорит».

import (
	"strings"
	"testing"
)

func TestRestFrontAuthAxisFollowsTheWiring(t *testing.T) {
	built, okBuilt := restFrontAuthAxis(true).Get()
	unbuilt, okUnbuilt := restFrontAuthAxis(false).Get()

	if !okBuilt || !okUnbuilt {
		t.Fatalf("ось обязана нести ЗНАЧЕНИЕ в обоих состояниях: построено=%v, не построено=%v",
			okBuilt, okUnbuilt)
	}

	// НЕСУЩЕЕ УТВЕРЖДЕНИЕ: строка меняется вместе с посадкой. На константе оно
	// падает — и только оно.
	if built == unbuilt {
		t.Fatalf("самоотчёт НЕ ЗАВИСИТ от того, построено ли звено: обе посадки дают %q. "+
			"Это константа, а не факт: оператор прочтёт одно и то же на посадке, где "+
			"механизм поднят, и на той, где его нет", built)
	}

	// Положительная половина: там, где звено построено, отчёт называет ЕГО.
	if !strings.Contains(string(built), "проверяет и назначает субъекта") {
		t.Fatalf("посадка со звеном обязана называть его работу; получено %q", built)
	}

	// Отрицательная половина: там, где звена нет, отчёт обязан сказать это
	// словом, а не умолчать. Умолчание здесь неотличимо от «механизм есть».
	// Регистр не судится: предмет утверждения — что состояние НАЗВАНО, а не
	// каким начертанием. Проба, привязанная к регистру, краснела бы на правке
	// оформления и ничего не сообщала бы о свойстве.
	if !strings.Contains(strings.ToLower(string(unbuilt)), "не поднят") {
		t.Fatalf("посадка БЕЗ звена обязана назвать это прямо; получено %q", unbuilt)
	}

	// И не называть работу, которой на этой посадке не происходит.
	if strings.Contains(string(unbuilt), "проверяет и назначает субъекта") {
		t.Fatalf("посадка без звена не вправе утверждать его работу; получено %q", unbuilt)
	}
}
