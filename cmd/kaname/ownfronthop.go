// ownfronthop.go — ЧЕМ собственный REST-фронт называется своему же слушателю,
// прочитанное из того сертификата, который он фактически предъявляет.
//
// # Предмет: величина обязана быть ТОЙ ЖЕ строкой, что увидит слушатель
//
// Пер-RPC политика вызывающего сравнивает предъявленное имя целиком. Значит у
// величины есть ровно один правильный источник — клиентский лист фронта, — и
// ровно один правильный способ её из него достать: тот же отбор, которым имя
// извлекает слушатель ([grpcsrv.TrustDomain.CertIdentity], первое имя URI в
// объявленном домене доверия).
//
// Записанная второй раз — ручкой профиля, литералом в коде, образцом по
// соседям — она разошлась бы с проводом МОЛЧА: сертификат перевыпускается
// шаблоном чарта, а строка осталась бы прежней, и фронт снова начал бы получать
// отказ на каждом запросе. Именно так этот дефект и выглядел: обе стороны были
// защитимы порознь, неверен был их стык.
//
// # Почему домен доверия — АРГУМЕНТ
//
// Домен объявляет установка, и вопрос «наше ли это имя» без него не задаётся.
// Спрашивается ТОТ ЖЕ домен, который слушатель предъявит разбору, — иначе две
// стороны сравнивали бы строки, признанные своими по разным правилам.
package main

import (
	"crypto/x509"
	"encoding/pem"
	"fmt"
	"os"
	"strings"

	"github.com/PRO-Robotech/kacho/pkg/grpcsrv"

	"github.com/PRO-Robotech/kaname/internal/apps/kaname/config"
)

// ownFrontHopSAN отдаёт имя клиентского листа, которым собственный REST-фронт
// приходит к своему же слушателю.
//
// Пустая строка БЕЗ ошибки означает «удостоверения у фронта на этой посадке
// нет» — ребро идёт открытым текстом, как на стенде. Это законная посадка, и
// молчание здесь не послабление: политика вызывающего в такой посадке
// вырождается целиком по другой причине (боевого режима нет), а страж ниже не
// даёт этой ветви дожить до боевой.
//
// Ошибка — только там, где удостоверение ОБЪЯВЛЕНО и прочитать его не вышло:
// это расхождение профиля с деревом, и молчать о нём нельзя.
func ownFrontHopSAN(m config.MTLSConfig, d grpcsrv.TrustDomain) (string, error) {
	if !m.RESTUpstreamMTLS.Enable {
		return "", nil
	}
	path := strings.TrimSpace(m.RESTUpstreamMTLS.CertFile)
	if path == "" {
		return "", fmt.Errorf(
			"удостоверение REST-фронта объявлено включённым, а файл сертификата не назван " +
				"(KANAME_REST_UPSTREAM_MTLS_CERTFILE): предъявлять своему слушателю нечего")
	}
	// #nosec G304 -- путь приходит из собственной конфигурации процесса
	// (KANAME_REST_UPSTREAM_MTLS_CERTFILE), которую задаёт профиль развёртывания,
	// а не из запроса. Вызывающего у этой строки один — композиционный корень на
	// старте; переменной, подконтрольной арендатору, здесь нет ни одной.
	raw, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("сертификат REST-фронта %s не читается: %w", path, err)
	}
	leaf, err := firstCertificate(raw)
	if err != nil {
		return "", fmt.Errorf("сертификат REST-фронта %s: %w", path, err)
	}
	// ТОТ ЖЕ отбор, которым имя извлекает слушатель: своя копия правила
	// разошлась бы с ним на сертификате с несколькими именами URI — и разошлась
	// бы молча, потому что обе строки остались бы синтаксически годными.
	return d.CertIdentity(leaf), nil
}

// firstCertificate — первый блок CERTIFICATE цепочки, то есть сам лист.
//
// Порядок задан форматом: лист идёт первым, за ним промежуточные. Брать
// последний значило бы прочитать имя удостоверяющего центра вместо своего.
func firstCertificate(pemBytes []byte) (*x509.Certificate, error) {
	rest := pemBytes
	for {
		var block *pem.Block
		block, rest = pem.Decode(rest)
		if block == nil {
			return nil, fmt.Errorf("блока CERTIFICATE в файле нет ни одного")
		}
		if block.Type != "CERTIFICATE" {
			continue
		}
		return x509.ParseCertificate(block.Bytes)
	}
}

// requireOwnFrontHopIdentity — в боевой посадке поднятый собственный REST-фронт
// обязан иметь имя, под которым его узнает пер-RPC политика вызывающего.
//
// # Зачем страж, если величина выводится из сертификата
//
// Затем, что вывод может дать ПУСТО, и пустое означает «фронт снова отвергает
// каждый запрос». Без стража эта поломка вернулась бы ровно в прежнем виде:
// поверхность поднята, маршруты зарегистрированы, страница продукта её
// описывает — и ни один вызов не обслуживается. Пустое имя выходит из
// сертификата, у которого нет имени URI в НАШЕМ домене доверия, — то есть из
// листа, выданного не тем центром или не под тем доменом.
//
// Отказ называет обе величины: домен, относительно которого имя искали, и файл,
// в котором его не нашлось. Отказ, называющий только одну, сообщает оператору,
// что не так, и не сообщает, где смотреть.
func requireOwnFrontHopIdentity(
	productionMode bool, internalRESTAddr, publicRESTAddr string, m config.MTLSConfig,
	d grpcsrv.TrustDomain, san string,
) error {
	if !productionMode {
		return nil
	}
	if strings.TrimSpace(internalRESTAddr) == "" && strings.TrimSpace(publicRESTAddr) == "" {
		return nil
	}
	if san != "" {
		return nil
	}
	return fmt.Errorf(
		"собственный REST-фронт поднят, а имени, под которым его узнает политика вызывающего, "+
			"нет: в сертификате %q не нашлось имени URI в домене доверия %q "+
			"(KANAME_REST_UPSTREAM_MTLS_CERTFILE, KANAME_AUTHN__TRUST_DOMAIN). "+
			"Фронт идёт к собственному слушателю СВОИМ удостоверением, и неузнанный лист "+
			"получает отказ на КАЖДОМ запросе — поверхность поднимется и не обслужит ничего; "+
			"refusing to start",
		m.RESTUpstreamMTLS.CertFile, d.Name())
}
