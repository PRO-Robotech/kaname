package main

// sakey_audience_prefix_unwired_test.go — держатель решения «окна двух написаний
// адресата НЕТ, написание одно» (задача продукта #2575).
//
// # Решение, а не наблюдение
//
// Приставка адресата ключа службы (`sa_keys.IssueSAKeyUseCase.AudiencePrefix`)
// достраивает адресат вида `<приставка>/sa/<идентификатор>` и добавляет его в
// перечень зеркала, когда заказчик адресата не назвал. Задача #2557 сменила её
// написание, и отсюда родилось опасение: смена без окна, принимающего ОБА
// написания, обесценит всякий уже выпущенный токен.
//
// Замер показал, что предмета у окна нет, и решение записано здесь:
//
//	приставка НЕ ПРОВЯЗАНА, и это выбор, а не забывчивость. Умолчание адресата
//	живёт у ПОСАДКИ (`authn.client-token.allowed-audiences` и `declared_audiences`
//	строки ключа), а не в этой приставке.
//
// Отсюда «окна нет»: производителя ни у старого написания, ни у нового никогда не
// было, поэтому population уже выпущенных токенов с таким адресатом ПУСТА —
// принимать второе написание не у кого и незачем.
//
// # Чем это держится и почему судится ПРОИЗВОДИМЫЙ признак
//
// Объявленный признак — «поле существует» — о продукте не говорит ничего: поле
// живёт, читается и покрыто пробами. Производимый признак другой: МОЖЕТ ЛИ
// поднятый стенд выпустить достроенный адресат. Может он ровно тогда, когда
// прод-код приставку ПРИСВАИВАЕТ; присваиваний ноль — ветка достройки на стенде
// недостижима, и второму написанию взяться неоткуда.
//
// Гейт поэтому считает присваивания, а не вхождения имени.
//
// # Предикат пересмотра — внешний, и он же условие закрытия
//
// Провязал приставку — гейт краснеет, и решение выше обязано быть пересмотрено
// ТЕМ ЖЕ изменением: у окна появляется предмет, и его придётся открывать явно.
// Гейт не запрещает провязку — он делает её сознательной.
//
// # Свою слепоту гейт проверяет НА КАЖДОМ ПРОГОНЕ
//
// Распознаватель, не знающий формы записи, даёт не красное и не зелёное, а
// МОЛЧАНИЕ, и «прод-присваиваний ноль» тогда неотличимо от «я ничего не умею
// найти». Поэтому вторая половина утверждения требует, чтобы присваивания
// НАХОДИЛИСЬ там, где они заведомо есть, — в пробах пакета выдачи. Обнулится и
// она — гейт краснеет как ослепший, а не молчит как исправный.
//
// # Границы, названные вслух
//
// Судятся две формы записи, и обе — присваивание полю: пара «ключ: значение» в
// составном литерале и присваивание через выбор поля. Установщик-строитель в
// прод-коде отдельной формой не является — его собственное тело присваивает поле
// второй формой и потому виден. Не видны: запись отражением, запись через
// небезопасный указатель и присваивание одноимённому полю ЧУЖОГО типа (последнее
// расширяет перепись, а не сужает: лишнее попадёт в находки и будет разобрано).

import (
	"go/ast"
	"go/parser"
	"go/token"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"github.com/PRO-Robotech/corelib/treecorpus"
)

// audiencePrefixField — имя поля-приставки. Предмет гейта один, и он назван
// здесь, чтобы переименование поля не оставило проверку молча беспредметной:
// пропав из дерева, имя обнулит ОБЕ половины переписи, и вторая половина
// (присваивания в пробах) немедленно покраснеет.
const audiencePrefixField = "AudiencePrefix"

// audiencePrefixWrites — позиции ПРИСВАИВАНИЙ полю в одном разобранном файле.
//
// Считается запись, а не упоминание: чтение (`u.AudiencePrefix != ""`), объявление
// поля и проза комментария адресат не производят и потому предметом не являются.
func audiencePrefixWrites(fset *token.FileSet, f *ast.File) []string {
	var out []string
	at := func(p token.Pos) string {
		pos := fset.Position(p)
		return filepath.Base(pos.Filename) + ":" + itoa(pos.Line)
	}
	ast.Inspect(f, func(n ast.Node) bool {
		switch v := n.(type) {
		// Форма 1 — составной литерал: `IssueSAKeyUseCase{AudiencePrefix: x}`.
		case *ast.KeyValueExpr:
			if id, ok := v.Key.(*ast.Ident); ok && id.Name == audiencePrefixField {
				out = append(out, at(id.Pos()))
			}
		// Форма 2 — присваивание через выбор поля: `u.AudiencePrefix = x`.
		// Тело установщика-строителя, будь он заведён, попадает сюда же.
		case *ast.AssignStmt:
			for _, lhs := range v.Lhs {
				if sel, ok := lhs.(*ast.SelectorExpr); ok && sel.Sel != nil &&
					sel.Sel.Name == audiencePrefixField {
					out = append(out, at(sel.Sel.Pos()))
				}
			}
		}
		return true
	})
	return out
}

// TestSAKeyAudiencePrefixStaysUnwiredSoThereIsOneSpelling — держатель решения.
func TestSAKeyAudiencePrefixStaysUnwiredSoThereIsOneSpelling(t *testing.T) {
	root := iamServiceRoot(t)

	files, err := treecorpus.UnderWithSuffix(root, ".go")
	if err != nil {
		t.Fatalf("перечень файлов Go службы: %v", err)
	}

	fset := token.NewFileSet()
	var prod, fromProbes []string
	parsed := 0
	for _, path := range files {
		f, perr := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
		if perr != nil {
			t.Fatalf("разбор %s: %v", path, perr)
		}
		parsed++
		hits := audiencePrefixWrites(fset, f)
		if len(hits) == 0 {
			continue
		}
		if strings.HasSuffix(path, "_test.go") {
			fromProbes = append(fromProbes, hits...)
			continue
		}
		prod = append(prod, hits...)
	}
	sort.Strings(prod)

	// Объём осмотренного печатается ВСЕГДА: без него «прод-присваиваний ноль»
	// неотличимо от «прочитано ноль файлов».
	t.Logf("перепись: файлов Go разобрано %d · присваиваний приставки в прод-коде %d · в пробах %d",
		parsed, len(prod), len(fromProbes))

	if parsed == 0 {
		t.Fatal("обход пуст: файлов Go не прочитано ни одного — вердикт беспредметен")
	}

	// Половина 1 — САМОПРОВЕРКА распознавателя. Стоит ПЕРВОЙ: не найдя заведомо
	// существующего, о ненайденном в прод-коде он не вправе утверждать ничего.
	if len(fromProbes) == 0 {
		t.Fatalf("распознаватель ослеп: присваиваний приставки %q не найдено НИ ОДНОГО, "+
			"включая пробы пакета выдачи, где они заведомо есть. "+
			"«В прод-коде ноль» на таком обходе не означает ничего — почини формы записи, "+
			"а не решение", audiencePrefixField)
	}

	// Половина 2 — само решение.
	if len(prod) != 0 {
		t.Fatalf("приставка адресата ПРОВЯЗАНА в прод-коде (%d): %s\n"+
			"Решение #2575 — «окна двух написаний нет, написание одно» — держалось тем, "+
			"что производителя достроенного адресата на стенде НЕТ. Провязка заводит его: "+
			"выпущенные токены начнут нести адресат `<приставка>/sa/<идентификатор>`, и "+
			"смена написания снова станет ломающей. Пересмотри решение ТЕМ ЖЕ изменением: "+
			"либо открой окно двух написаний явно и с держателем, либо сними провязку",
			len(prod), strings.Join(prod, ", "))
	}
}
