package main

// internal_rest_front_auth_axis_test.go — ПОКАЗАНИЕ ВНУТРЕННЕГО ФРОНТА
// ВЫВОДИТСЯ ИЗ ПРОВОДА, А НЕ ВПИСАНО КОНСТАНТОЙ.
//
// # Предмет
//
// Служба при старте объявляла о собственном внутреннем фронте, что вызывающего
// на нём опознаёт «проверенный сертификат модуля и его политика вызывающего».
// Строка была КОНСТАНТОЙ и с режимом ребра не сверялась никак, а на
// одностороннем режиме проверенного сертификата у фронта на руках не бывает
// вовсе: тот сертификат, что действительно проверяется ниже, принадлежит САМОМУ
// ФРОНТУ и о HTTP-вызывающем не говорит ничего.
//
// Расхождение показания с проводом дороже расхождения посадки: гейт, читающий
// самоотчёт, становится на этой оси ВАКУУМНЫМ — он подтверждает механизм,
// которого нет, и заметить это нечем.
//
// # Почему пара, а не одно утверждение
//
// Односторонняя проба («режим взаимный → строка про сертификат») зеленела бы на
// константе: константа даёт эту строку при любом режиме. Различающим является
// ТОЛЬКО сравнение двух посадок между собой — оно спрашивает не «верна ли
// строка», а «меняется ли она вместе с тем, о чём говорит».

import (
	"fmt"
	"strings"
	"testing"

	"github.com/PRO-Robotech/corelib/servicecontract"
)

// authAxisProducer — то, что проверяется: производитель оси по режиму ребра.
//
// Параметром, а не прямым вызовом: тем же предикатом инъекция подаёт КОНСТАНТУ
// и требует, чтобы проверка на ней покраснела. Предикат, доказанный только на
// исправном входе, о способности падать не говорит ничего.
type authAxisProducer func(requiresClientCert bool) servicecontract.Axis[servicecontract.SurfaceAuthMech]

// checkAuthAxisFollowsTheEdgeMode — сам предикат. Возвращает жалобу, а не
// роняет пробу: инъекция обязана уметь ПРОЧИТАТЬ его вердикт.
func checkAuthAxisFollowsTheEdgeMode(produce authAxisProducer) error {
	mutual, okMutual := produce(true).Get()
	oneWay, okOneWay := produce(false).Get()

	// Положительная сторона — ЗНАЧЕНИЕ: механизм есть, и ось называет чем.
	if !okMutual {
		return fmt.Errorf("на взаимном режиме ось обязана нести ЗНАЧЕНИЕ: механизм есть, и он назван")
	}
	// Отрицательная — ОБЪЯВЛЕННОЕ ОТСУТСТВИЕ с причиной, а не молчание:
	// необъявленная ось есть отказ старта, а «механизм есть» на посадке, где
	// его нет, — ровно тот дефект, ради которого проба заведена.
	if okOneWay {
		return fmt.Errorf("на одностороннем режиме ось назвала МЕХАНИЗМ (%q) — на этом проводе "+
			"вызывающий не назван ничем, и ось обязана объявить отсутствие с причиной",
			oneWay)
	}

	reasonOneWay, hasReason := produce(false).NotApplicableBecause()
	if !hasReason || strings.TrimSpace(reasonOneWay) == "" {
		return fmt.Errorf("объявленное отсутствие обязано нести причину: без неё оператор прочтёт "+
			"его как недосмотр объявления, а не как посадку; получено %q", reasonOneWay)
	}

	// НЕСУЩЕЕ УТВЕРЖДЕНИЕ: сказанное меняется вместе с режимом. На константе
	// падает оно, и только оно.
	if string(mutual) == reasonOneWay {
		return fmt.Errorf("самоотчёт НЕ ЗАВИСИТ от режима ребра: обе посадки говорят %q — "+
			"это константа, а не факт", mutual)
	}

	// Положительная половина называет ТО, ЧТО ПРОИСХОДИТ НА ПРОВОДЕ.
	if !strings.Contains(string(mutual), "клиентский сертификат") {
		return fmt.Errorf("посадка со взаимным режимом обязана назвать требование сертификата; получено %q", mutual)
	}
	// Отрицательная — говорит об отсутствии прямо.
	if !strings.Contains(strings.ToLower(reasonOneWay), "не требует") {
		return fmt.Errorf("посадка без требования обязана назвать это прямо; получено %q", reasonOneWay)
	}

	// И НИ ОДНА не вправе приписывать вызывающему проверенный сертификат МОДУЛЯ:
	// именно это приписывала снятая константа, и именно этого на проводе нет —
	// лист, который проверяет собственный слушатель, называет ХОП.
	for name, said := range map[string]string{"взаимная": string(mutual), "односторонняя": reasonOneWay} {
		if strings.Contains(said, "сертификат модуля") {
			return fmt.Errorf("%s посадка приписывает вызывающему сертификат модуля — он называет "+
				"ХОП, а не звонящего; получено %q", name, said)
		}
	}
	return nil
}

// TestInternalRESTFrontAuthAxisFollowsTheEdgeMode — предикат на ДЕЙСТВУЮЩЕМ
// производителе. Способность предиката упасть доказывается инъекцией рядом
// (internalrestclientauth_injection_test.go).
func TestInternalRESTFrontAuthAxisFollowsTheEdgeMode(t *testing.T) {
	if err := checkAuthAxisFollowsTheEdgeMode(internalRESTFrontAuthAxis); err != nil {
		t.Fatalf("%v", err)
	}
}
