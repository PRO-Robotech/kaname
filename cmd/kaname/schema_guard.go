package main

// schema_guard.go — загрузочный страж: служба не поднимается поверх базы
// прежней установки.
//
// ─────────────────────────────────────────────────────────────────────────────
// # Почему это страж старта, а не перенос
//
// Схема службы переименована, а пути перехода у прежней установки нет и не
// заводится: решение владельца — ТОЛЬКО чистая установка. Миграция
// переименования исполнялась бы в чужой базе, и за её исход мы отвечать не
// можем; переносить при этом нечего — продукта в проде нет.
//
// Исход, которого НЕ существует, — тихая работа поверх пустой новой схемы.
// Служба поднялась бы, увидела пустую схему продукта, начала бы с нуля, а
// прежние строки остались бы рядом невидимыми: арендатор узнал бы о потере не
// от продукта, а по последствиям. Молчание здесь дороже отказа на порядок,
// поэтому отказ обязан наступить РАНЬШЕ первой записи.
//
// ─────────────────────────────────────────────────────────────────────────────
// # Ось этого стража названа, чтобы молчание не приняли за покрытие
//
// Страж судит ОДНО: есть ли в базе схема отставленного имени. Об отсутствии
// схемы продукта — о ненакаченной цепи миграций — он не утверждает НИЧЕГО и
// пропускает такую базу: это предмет другого стража, и приписывать его сюда
// значило бы обещать проверку, которой нет.
//
// # Почему проверка своя, а не в общем дескрипторе посадки
//
// `pkg/servicecontract` судит посадку процесса — режим, шифрование, круг
// доверенных отправителей, — и делает это ДО первого соединения с базой.
// Здесь ось другая и общей быть не может: чужая схема в СОБСТВЕННОЙ базе этой
// службы. Своя проверка — дополнение к общему дескриптору, а не замена.
//
// # Fail-closed
//
// Не сумев спросить базу, страж отказывает. «Не прочитано» не есть «нет»:
// пропустив старт на неответившем запросе, он открыл бы ровно тот путь, ради
// закрытия которого заведён, и сделал бы это на первой же сетевой заминке.

import (
	"context"
	"fmt"

	"github.com/jackc/pgx/v5/pgxpool"
)

const (
	// schemaOfThisProduct — схема, с которой работает служба.
	//
	// Литерал ЗДЕСЬ, а не взятый у пробы: проба рядом объявляет то же имя
	// НЕЗАВИСИМО и сравнивает с ним состав отказа. Возьми обе стороны одно
	// выражение — утверждение стало бы тождественно истинным и зеленело бы
	// при любом имени.
	schemaOfThisProduct = "kaname"

	// schemaOfThePreviousInstall — имя, отставленное вместе с прежним именем
	// продукта. Строка остаётся в дереве не как наследие, а как ПРЕДМЕТ этого
	// стража: перестанет встречаться — некому будет отличить прежнюю установку
	// от чистой.
	schemaOfThePreviousInstall = "kacho_iam"

	// postgresURLEnvName — ручка, которой оператор меняет базу. Что она
	// доезжает до поля, доказано опытом в разборе настройки
	// (`config.TestDocumentedEnvName_PostgresURL`), поэтому здесь она не
	// перепроверяется — проверяется лишь то, что отказ называет ЕЁ.
	postgresURLEnvName = "KANAME_REPOSITORY__POSTGRES__URL"

	// migratorUpCommand — чем схема накатывается на чистую базу.
	migratorUpCommand = "kaname-migrator up"

	// installDocPath — порядок установки, от корня модуля. Существование
	// координаты и присутствие в ней названной команды держит проба рядом:
	// ссылка, пережившая переезд документа, отсылает в никуда и хуже
	// отсутствующей.
	installDocPath = "docs/content/install/deploy.mdx"
)

// schemaCensus — что страж увидел в базе. Отдельным типом, потому что отказ
// составляется ИЗ ЭТИХ величин, и пробе состава есть что подать без базы.
type schemaCensus struct {
	database             string
	previousInstallFound bool
	productSchemaFound   bool
}

// readSchemaCensus спрашивает базу о ней самой.
//
// Спрашивается системный каталог, а не текст миграции: миграция говорит, что
// схема была бы создана, каталог — что она есть. Имя базы берётся тем же
// запросом, чтобы отказ назвал ИМЕННО ТУ базу, к которой служба подключилась,
// а не ту, которую оператор думает, что задал.
func readSchemaCensus(ctx context.Context, pool *pgxpool.Pool) (schemaCensus, error) {
	var c schemaCensus
	err := pool.QueryRow(ctx,
		`SELECT current_database(),
		        EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = $1),
		        EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = $2)`,
		schemaOfThePreviousInstall, schemaOfThisProduct,
	).Scan(&c.database, &c.previousInstallFound, &c.productSchemaFound)
	return c, err
}

// retiredSchemaComplaint — то, что страж скажет оператору, или nil.
//
// Вынесено отдельно от чтения состояния ровно затем, чтобы пробе было что
// звать без базы: предмет здесь — СОСТАВ отказа, а способность прочитать
// состояние проверена на живом Postgres рядом. Тот же разрез, что у соседнего
// стража бюджета соединений.
//
// Текст называет обнаруженную схему, базу, ручку, команду и документ — это
// рантайм-диагностика оператору, прямо выведенная из-под запрета на публичные
// подробности: без имени ручки и причины стенд не поднять. Отказ, не
// восстанавливающий следующий шаг, — находка, а не строгость.
//
// Отдельно и намеренно текст говорит, что это СОСТОЯНИЕ ОКРУЖЕНИЯ, а не дефект
// продукта: в три часа ночи это решает, кого будят и что чинят.
func retiredSchemaComplaint(database string, previousInstallFound, productSchemaFound bool) error {
	if !previousInstallFound {
		// Схемы отставленного имени нет — ось этого стража чиста. О том, есть
		// ли схема продукта, он не судит (см. шапку).
		return nil
	}

	if productSchemaFound {
		return fmt.Errorf(
			"база %q несёт ОБЕ схемы: прежней установки %q и текущую %q. "+
				"Это состояние окружения, а не дефект продукта. Старт отвергнут ДО первой "+
				"записи: оба имени резолвятся, и какую схему читает служба, решал бы порядок "+
				"search_path — данные выбирались бы молча. "+
				"Дальше: решив судьбу прежних данных САМИ, снимите схему %q в базе %q — "+
				"служба такой операции за оператора не делает, потому что за её исход в чужой "+
				"установке мы не отвечаем; либо, если прежняя установка нужна нетронутой, "+
				"направьте %s на чистую базу и накатите схему командой `%s`. "+
				"Порядок установки: %s",
			database, schemaOfThePreviousInstall, schemaOfThisProduct,
			schemaOfThePreviousInstall, database,
			postgresURLEnvName, migratorUpCommand, installDocPath)
	}

	return fmt.Errorf(
		"база %q несёт схему прежней установки %q, а схемы %q, с которой работает служба, "+
			"в ней нет. Это состояние окружения, а не дефект продукта: схема переименована, и "+
			"автоматического переноса у службы нет — переносить в чужой базе мы не вправе. "+
			"Старт отвергнут ДО первой записи: иначе рядом завелась бы пустая схема %q, служба "+
			"начала бы работать поверх пустого, а прежние строки остались бы невидимыми — "+
			"о потере арендатор узнал бы по последствиям, а не от продукта. "+
			"Дальше, одно из двух: направьте %s на чистую базу и накатите схему командой `%s`; "+
			"либо, решив судьбу прежних данных САМИ, снимите схему %q в базе %q. "+
			"Порядок установки: %s",
		database, schemaOfThePreviousInstall, schemaOfThisProduct,
		schemaOfThisProduct,
		postgresURLEnvName, migratorUpCommand,
		schemaOfThePreviousInstall, database,
		installDocPath)
}

// assertNoRetiredSchema отказывает в старте, обнаружив базу прежней установки.
func assertNoRetiredSchema(ctx context.Context, pool *pgxpool.Pool) error {
	census, err := readSchemaCensus(ctx, pool)
	if err != nil {
		return fmt.Errorf("состояние схем базы не прочитано: %w — стартовать, не зная, "+
			"несёт ли база схему %q прежней установки, значит принять «не прочитано» за «нет» "+
			"и начать работу поверх пустой схемы %q",
			err, schemaOfThePreviousInstall, schemaOfThisProduct)
	}
	return retiredSchemaComplaint(census.database, census.previousInstallFound, census.productSchemaFound)
}
