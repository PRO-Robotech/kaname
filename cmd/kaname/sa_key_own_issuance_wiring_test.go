// sa_key_own_issuance_wiring_test.go — выбор полосы выдачи ключа служебной
// учётки (задача #1120, подфаза Ф4б эпика #896).
//
// # Что здесь утверждается
//
// Решение, а не его последствия: при каком объявлении посадки контур считается
// переведённым. Обе стороны несущие и обе — про цену ошибки:
//
//   - объявили переведённым посадку без токен-эндпоинта — ключ выдан, зеркала у
//     прежнего издателя нет, своей дороги к токену тоже нет: удостоверение,
//     которое не обменять НИ ОДНИМ путём;
//   - не объявили переведённым посадку с эндпоинтом — зеркало продолжает
//     заводиться, и снятие прежнего издателя упирается в поверхность, которую
//     никто не переписывал.
//
// # Чего эта проба НЕ утверждает — сказано прямо
//
// Она не доказывает, что сборка ключей ЗОВЁТ этот выбор: наблюдать провязку
// снаружи нечем — знание о полосе живёт внутри use-case и наружу не выходит.
// Что провязка есть, держат две вещи: полоса печатается в самоотчёте процесса
// при старте (`sa_keys wired … own_issuance=…`) и пара проб самого use-case,
// где обе стороны выбора утверждены исходом у прежнего издателя.
package main

import (
	"testing"

	"github.com/PRO-Robotech/kaname/internal/apps/kaname/config"
)

func TestSAKeyIssuanceIsOurs_FollowsTheExchangeEndpoint(t *testing.T) {
	for _, tc := range []struct {
		name    string
		enabled bool
		want    bool
	}{
		{
			name:    "эндпоинт обмена объявлен — контур переведён",
			enabled: true,
			want:    true,
		},
		{
			// Положительный контроль отрицания: без него проба зеленела бы на
			// функции, возвращающей «переведён» всегда.
			name:    "эндпоинта обмена нет — прежний издатель остаётся единственной дорогой",
			enabled: false,
			want:    false,
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			var cfg config.Config
			cfg.AuthN.ClientToken.Enabled = tc.enabled
			if got := saKeyIssuanceIsOurs(cfg); got != tc.want {
				t.Errorf("saKeyIssuanceIsOurs = %v, ожидалось %v", got, tc.want)
			}
		})
	}
}
