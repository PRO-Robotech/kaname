// dsn_names_a_host_test.go — точка наката отвергает адрес базы без хоста.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО ПРОБА ИМЕННО ЗДЕСЬ, А НЕ ТОЛЬКО У СТРАЖА СЛУЖБЫ
//
// В поставке точка наката исполняется ПЕРВОЙ: чарт ставит её init-контейнером
// перед службой. Значит первое, обо что разбивается неверная настройка
// оператора, — она, а не страж службы; и до этой правки она не судила адрес
// вовсе.
//
// Наблюдалось в кластере: установка с незаданным адресом базы (единственный
// изменённый факт) оставляла init-контейнер в `running` с НУЛЁМ байт журнала
// больше двух с половиной минут. Страж службы к тому времени уже отвергал такой
// адрес — но его код не исполнялся НИКОГДА, потому что до второго контейнера
// дело не доходило.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ НЕ ПОЛНЫЙ `Config.Validate`
//
// Соблазн был: позвать стража службы целиком. Он бы уронил ШТАТНУЮ установку —
// в боевом режиме страж требует общий сговор с поставщиком личности и ключ
// обёртки ключницы, а init-контейнер этих секретов не несёт и нести не должен:
// накат миграций их не использует. Проба на такой правке краснела бы на
// исправной поставке.
//
// Судится ровно та величина, которую точка наката УПОТРЕБЛЯЕТ, — строка
// подключения, и судится она ТЕМ ЖЕ предикатом, что зовёт страж службы
// (`config.DSNNamesAHost`). Своя редакция разошлась бы молча.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ПРОВЕРЯЕТСЯ РАЗРЕШЁННАЯ СТРОКА, А НЕ ОДИН ИСТОЧНИК
//
// Источников у неё три (`--dsn`, переменная окружения, конфигурация службы), и
// негодный адрес одинаково негоден из любого. Проверка стоит ПОСЛЕ разрешения
// приоритета, поэтому покрывает все три и не заводит четвёртого места, где
// порядок источников пришлось бы повторить.
package main

import (
	"strings"
	"testing"
	"testing/fstest"
)

// TestBuildRunner_RefusesADSNWithoutAHost — отрицание: адрес без хоста отвергнут
// до всякого ожидания, и текст называет причину.
func TestBuildRunner_RefusesADSNWithoutAHost(t *testing.T) {
	opts := &rootOptions{dialect: defaultDialect, dsn: "postgres://iam@:5432/kacho_iam"}

	_, err := buildRunner(opts, fstest.MapFS{})
	if err == nil {
		t.Fatal("buildRunner() = nil error, want refusal: адрес базы не называет хоста, и ожидание её не сойдётся никогда")
	}
	if !strings.Contains(err.Error(), "host") {
		t.Fatalf("отказ обязан называть причину (отсутствующий хост), получено: %q", err.Error())
	}
}

// TestBuildRunner_AcceptsADSNWithAHost — ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ.
//
// Без него отрицание выше зеленело бы на точке наката, отвергающей ЛЮБОЙ адрес,
// — то есть на сломанной поставке. Соединение здесь не устанавливается: сборка
// наката его не открывает, поэтому проба судит разбор, а не доступность базы.
func TestBuildRunner_AcceptsADSNWithAHost(t *testing.T) {
	opts := &rootOptions{dialect: defaultDialect, dsn: "postgres://iam@pg:5432/kacho_iam"}

	if _, err := buildRunner(opts, fstest.MapFS{}); err != nil {
		t.Fatalf("buildRunner() = %q, want nil: адрес базы называет хост, отвергать нечего", err.Error())
	}
}

// TestBuildRunner_RefusalDoesNotEchoTheDBPassword — текст отказа НЕ несёт пароля.
//
// Строка подключения, которую собирает запасная конфигурация, содержит пароль
// базы: он приезжает из объекта Secret и подставляется в DSN. Текст отказа
// уезжает в журнал пода, а журнал читают все, у кого есть доступ к кластеру, —
// поэтому величина, названная в отказе, обязана быть обеззаражена.
//
// Проба заведена ПОСЛЕ наблюдения: первая редакция отказа печатала DSN целиком,
// и в журнале init-контейнера стоял пароль открытым текстом.
func TestBuildRunner_RefusalDoesNotEchoTheDBPassword(t *testing.T) {
	const password = "s3cret-never-in-a-log"
	opts := &rootOptions{dialect: defaultDialect, dsn: "postgres://iam:" + password + "@:5432/kacho_iam"}

	_, err := buildRunner(opts, fstest.MapFS{})
	if err == nil {
		t.Fatal("buildRunner() = nil error, want refusal for a hostless DSN")
	}
	if strings.Contains(err.Error(), password) {
		t.Fatalf("текст отказа несёт пароль базы — он уезжает в журнал пода: %q", err.Error())
	}
	if !strings.Contains(err.Error(), "host") {
		t.Fatalf("обеззараживание не должно съедать причину, получено: %q", err.Error())
	}
}
