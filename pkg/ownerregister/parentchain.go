package ownerregister

// Типы предков, выразимые ОБЛАСТЬЮ доставки.
//
// Написаны здесь один раз, а не в каждом сервисе: форма имени объекта
// (`"<type>:<id>"`) принадлежит принимающей стороне, и второе её написание —
// копия, которая разойдётся молча. Значения совпадают с типами, которыми
// принимающая сторона уже заполнила рёбра существующих объектов из тех же двух
// колонок зеркала (миграция обратного заполнения); разойдись они — один и тот
// же объект получил бы двух РАЗНЫХ предков, отличающихся написанием типа.
const (
	parentTypeProject = "project"
	parentTypeAccount = "account"
)

// ParentChain — цепь предков ОДНОЙ доставки регистрации, от ближайшего предка к
// дальнему, каждый элемент в форме `"<type>:<id>"`.
//
// # Зачем это отдельная функция, а не поле, заполняемое на месте
//
// Принимающая сторона держит цепь предков объекта отдельными рёбрами и заменяет
// их набор ЦЕЛИКОМ на каждой применённой регистрации: цепь — это состояние, а не
// приращение. У замены две стороны, и вторая — предмет этой функции:
// производитель, который цепи не называет, на каждой перерегистрации своего
// объекта СТИРАЕТ уже записанных предков и не ставит новых. Объект без предка
// молча выпадает из области выдачи и из каскада — вопрос о нём задаётся, ответ
// «нет», и отказ неотличим от честного.
//
// # Что функция делает и чего НЕ делает
//
//	explicit непуст ⇒ возвращается как есть. Иерархию глубже двух уровней
//	(репозиторий → реестр → проект) знает только владелец, и вывести её из
//	области нельзя: область знает ровно проект и аккаунт. Подмена укоротила бы
//	цепь до той, которой у объекта нет.
//
//	explicit пуст ⇒ цепь выводится ИЗ ОБЛАСТИ ЭТОЙ ЖЕ ДОСТАВКИ — из тех самых
//	`ParentProjectID`/`ParentAccountID`, что едут в том же сообщении. Ничего
//	нового не выдумывается: доставка уже утверждает эти два предка, функция лишь
//	называет их в форме цепи.
//
// Пустой explicit означает «владелец не назвал», а НЕ «предков нет»: строка,
// поставленная в очередь до появления поля, декодируется именно так, и принять
// её за утверждение значило бы стирать предков на каждом повторе. «Предков нет»
// выражается пустой ОБЛАСТЬЮ — тогда результат тоже пуст, и это законный ответ
// для объекта корневого уровня.
//
// Цепь непрерывна: без проекта ближайшим предком становится аккаунт. Дыра
// остановила бы обход вверх и объявила объект не принадлежащим аккаунту.
func ParentChain(explicit []string, projectID, accountID string) []string {
	if len(explicit) > 0 {
		return explicit
	}
	var chain []string
	if projectID != "" {
		chain = append(chain, parentTypeProject+":"+projectID)
	}
	if accountID != "" {
		chain = append(chain, parentTypeAccount+":"+accountID)
	}
	return chain
}
