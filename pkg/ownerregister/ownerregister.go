// Package ownerregister — ОДНА форма синхронной регистрации ресурса у владельца
// прав, общая для всех сервисов-потребителей.
//
// # Зачем один пакет, а не пять регистраторов
//
// Форм было пять, и различались они пятью осями сразу: происхождением маркера
// версии, поведением при отказе на одном из tuple'ов, пробросом личности
// вызывающего, набором форвардимых полей зеркала и трактовкой несконфигурированного
// клиента. Ни одно из различий не было записано решением — только комментариями,
// и ДВА из этих комментариев заявляли паритет с соседом, которого не было:
//
//   - заголовок регистратора nlb объявлял себя зеркалом vpc, а его же тело
//     двадцатью строками ниже разбирало, почему это ложь (версия у vpc из
//     writer-транзакции, у nlb — с часов доставки);
//   - тот же разбор ссылался на функцию, шагающую версию по tuple'ам, «в
//     NewRegisterApplier» nlb — такой функции у nlb нет вовсе, она живёт у
//     registry (предикат: `git grep -n stepSourceVersion` даёт один файл, и это
//     не nlb).
//
// Ложное заявление о паритете и есть то, из-за чего расхождение прожило
// незамеченным: читатель, сверяющий соседа, видел ссылку и не шёл проверять.
//
// # Правило выбора семантики: САМАЯ УЗКАЯ, а не самая снисходительная
//
// Общий код, принявший то, что строгий сервис отвергал, вернул бы отвергнутый
// дефект во ВСЕ сервисы разом. Поэтому по каждой оси взято самое строгое из
// существовавшего, и рядом названо, чей это был выбор и что он отвергает:
//
//  1. ПОКОЛЕНИЕ ОБЪЕКТА — то, что владелец проставил изменению объекта в своей
//     writer-транзакции (то же целое, что в строке `resource-event` его журнала;
//     приёмка NTF-3, Р30 «Поколение и проекция»). Обязательно: [Registration] с
//     нулевым Generation не отправляется вовсе (см. [ErrUnversioned]) — принимающая
//     сторона такую и не примет (`INVALID_ARGUMENT generation: required`).
//     Отвергает часы момента доставки и полное отсутствие версии.
//  2. НЕСКОНФИГУРИРОВАННЫЙ КЛИЕНТ — отказ (форма registry): [New] возвращает
//     [ErrNoClient]. Отвергает молчаливый no-op (nlb), при котором ускоритель
//     выключен и это ничем не наблюдается.
//  3. ЛИЧНОСТЬ ВЫЗЫВАЮЩЕГО — пробрасывается всегда (форма compute/nlb), чтобы
//     least-priv-гейт принимающей стороны судил реального вызывающего, а не
//     только предъявленный сертификат. Отвергает молчаливую потерю личности
//     (vpc/storage/registry).
//  4. ОТКАЗ НА ОДНОМ событии — не прекращает набор (форма nlb): пробуются ВСЕ,
//     ошибки объединяются. Отвергает короткое замыкание (vpc/storage/registry),
//     при котором событие соседнего объекта не доезжает из-за отказа на первом, а
//     вызывающий видит один отказ вместо всех. Кортежи ОДНОГО события едут одним
//     вызовом и применяются атомарно — делить их нечего.
//  5. ПОЛЯ ЗЕРКАЛА — форвардится всё, что у доставки есть, включая TraceID и
//     ParentAccountID (форма nlb — самая полная). Пустое поле принимающая
//     сторона обрабатывает штатно; недосланное — молча обедняет зеркало.
//
// # Чего здесь НЕТ и почему
//
// Ветки «AlreadyExists — это успех» нет. Контракт RegisterResource идемпотентен
// и этого кода НЕ производит (см. godoc RegisterResourceUseCase и handler'а
// internal_iam: «neither AlreadyExists nor NotFound ever surfaces»). Ветка с
// отсутствующим производителем — это форма без содержания: она молчит на том,
// ради чего написана, и однажды проглотит настоящий отказ.
//
// # Признак первой доставки сюда НЕ добавляется
//
// Он уже landed ПОЛЕМ ДЕСКРИПТОРА сервиса (corelib/servicecontract), а не параметром
// запроса. Слот под него в [Registration] был бы вторым местом об одном
// предмете; приёмка XC-7 §10 п.3 это прямо отвергает. Принимающая сторона
// принимает признак лишь В КОНЪЮНКЦИИ со своим вердиктом по данным — правило
// «это не слово вызывающего» сохраняется дословно и здесь не ослабляется.
package ownerregister

import (
	"context"
	"errors"
	"fmt"
	"time"

	"google.golang.org/grpc"

	"github.com/PRO-Robotech/corelib/auth"
	iamv1 "github.com/PRO-Robotech/kaname/pkg/api/kaname/cloud/iam/v1"
)

// defaultTimeout — предельный срок ОДНОГО вызова RegisterResource.
//
// Значение общее для всех пяти потребителей: у каждого стояло ровно 5 секунд, и
// сходилось обоснование — доставка идёт из воркера на detached-контексте без
// собственного дедлайна, поэтому срок обязан стоять здесь
// (§«Per-call deadline на КАЖДОМ внешнем вызове»).
const defaultTimeout = 5 * time.Second

var (
	// ErrNoClient — регистратор собран без клиента к владельцу прав.
	//
	// Это ОТКАЗ, а не пустая операция. Пустая операция выглядит как исправно
	// работающий ускоритель, который никогда ничего не ускорял: ни одного
	// отказа за всю жизнь, ни одной строки в логе, и отличить её от «всё
	// хорошо» нечем (§Hardening-инвариант 8).
	ErrNoClient = errors.New("owner-register: клиент владельца прав не сконфигурирован")

	// ErrUnversioned — регистрация не несёт поколения объекта.
	//
	// Приёма без поколения у принимающей стороны нет: она отвечает
	// `INVALID_ARGUMENT generation: required`. Отказ здесь, до вызова, называет
	// ту же ошибку программиста раньше и громче — непротащенное поколение обязано
	// быть слышно, а не превращаться в отказ, который дренаж будет повторять.
	ErrUnversioned = errors.New("owner-register: регистрация без поколения объекта")
)

// Tuple — кортеж набора события: отношение субъекта к объекту регистрации.
type Tuple struct {
	SubjectID string
	Relation  string
}

// Registration — ОДНО событие объекта, готовое к синхронной доставке: одна строка
// durable-намерения — один вызов.
//
// Единица — СОБЫТИЕ, а не кортеж (приёмка NTF-3, Р30 «Единица поколения —
// событие»). Принимающая сторона применяет регистрацию, только если её поколение
// СТРОГО новее головы объекта; голова — ПО ОБЪЕКТУ. Поэтому все кортежи события
// едут одним вызовом под одним поколением и применяются атомарно: кортеж, отправленный
// отдельным вызовом с тем же поколением, был бы REJECTED_STALE и не записал бы
// ничего, хотя вызов ответил бы успехом.
type Registration struct {
	// Object — объект события, `"<type>:<id>"` словарём модели прав.
	Object string

	// Tuples — набор кортежей события на Object: непустой, без повторов, без
	// подстановочного субъекта (публикация — свой метод принимающей стороны).
	Tuples []Tuple

	// TraceID — идентификатор ресурса, к которому относится доставка.
	TraceID string

	// Labels / ParentProjectID / ParentAccountID — кормление зеркала владельца
	// прав. Пустое значение законно (не у всякого ресурса есть метки, и не
	// всякий сервис резолвит проект→аккаунт на горячем пути).
	Labels          map[string]string
	ParentProjectID string
	ParentAccountID string

	// ParentChain — цепь предков от БЛИЖАЙШЕГО к дальнему, каждый элемент в
	// форме `"<type>:<id>"`.
	//
	// Двух полей выше хватает не всякому ресурсу: они несут ровно проект и
	// аккаунт, а модель прав требует цепи ПРОИЗВОЛЬНОЙ формы (репозиторий →
	// реестр → проект → аккаунт). Ресурс, чей ближайший предок не проект и не
	// аккаунт, без этой цепи регистрируется БЕЗ предка — и молча выпадает из
	// области выдачи и из каскада: вопрос о нём задаётся, ответ «нет», и это
	// неотличимо от честного отказа.
	//
	// Пусто означает «предков нет»: принимающая сторона заменяет набор рёбер
	// объекта целиком, поэтому доставка без цепи не «ничего не меняет», а
	// стирает уже записанных предков. Заполнять цепь обязан КАЖДЫЙ потребитель;
	// у кого иерархия не глубже проекта — вызовом [ParentChain] по области этой
	// же доставки, у кого глубже — своим перечислением звеньев.
	ParentChain []string

	// Generation — поколение объекта, проставленное ВНУТРИ writer-транзакции,
	// породившей это намерение. Не часы момента доставки: обе доставки одной
	// строки обязаны нести ОДНО значение — вторая тогда не новее головы объекта и
	// гасится принимающей стороной как редоставка. Нулевое значение — отказ
	// ([ErrUnversioned]), а не «сойдёт и так».
	Generation int64
}

// RegisterRPC — узкий порт к владельцу прав. Именно узкий, а не весь
// InternalIAMServiceClient: подставной дублёр обязан выполнять контракт
// настоящего, и чем меньше поверхность, тем меньше ему есть где оказаться
// снисходительнее.
type RegisterRPC interface {
	RegisterResource(ctx context.Context, in *iamv1.RegisterResourceRequest, opts ...grpc.CallOption) (*iamv1.RegisterResourceResponse, error)
}

// Registrar — синхронная доставка регистраций владельцу прав.
//
// УСКОРИТЕЛЬ, А НЕ ИСТОЧНИК ИСТИНЫ. Те же строки лежат durable-намерениями в
// очереди той же writer-транзакции, поэтому дренаж доводит регистрацию сам.
// Отсюда и форма отчётности: ошибка ВОЗВРАЩАЕТСЯ вызывающему, но вызывающий её
// логирует, а не роняет мутацию — провалить уже закоммиченный ресурс значило бы
// отдать клиенту отказ на существующую вещь (фантом, ban #9).
type Registrar struct {
	cli     RegisterRPC
	timeout time.Duration
}

// New собирает регистратор. nil-клиент — ОТКАЗ (см. [ErrNoClient]).
func New(cli RegisterRPC) (*Registrar, error) {
	if cli == nil {
		return nil, ErrNoClient
	}
	return &Registrar{cli: cli, timeout: defaultTimeout}, nil
}

// Register доставляет каждое событие набора владельцу прав — одним вызовом на
// событие.
//
// НЕ КОРОТКОЗАМЫКАЕТСЯ: отказ на одном событии не отменяет попытки по остальным
// (у модуля событие одного вызова — разные объекты: сеть, её маршрутная таблица,
// её группа безопасности), и все отказы возвращаются объединёнными.
func (r *Registrar) Register(ctx context.Context, regs []Registration) error {
	if r == nil || r.cli == nil {
		return ErrNoClient
	}
	// Личность вызывающего — чтобы least-priv-гейт принимающей стороны судил
	// того, кто на самом деле создаёт ресурс, а не только предъявителя
	// сертификата.
	ctx = auth.PropagateOutgoing(ctx)

	var errs []error
	for _, reg := range regs {
		if reg.Generation <= 0 {
			errs = append(errs, fmt.Errorf("%s: %w", reg.Object, ErrUnversioned))
			continue
		}
		tuples := make([]*iamv1.RegisteredTuple, 0, len(reg.Tuples))
		for _, t := range reg.Tuples {
			tuples = append(tuples, &iamv1.RegisteredTuple{SubjectId: t.SubjectID, Relation: t.Relation})
		}
		cctx, cancel := context.WithTimeout(ctx, r.timeout)
		_, err := r.cli.RegisterResource(cctx, &iamv1.RegisterResourceRequest{
			Object:          reg.Object,
			Tuples:          tuples,
			TraceId:         reg.TraceID,
			Labels:          reg.Labels,
			ParentProjectId: reg.ParentProjectID,
			ParentAccountId: reg.ParentAccountID,
			ParentChain:     reg.ParentChain,
			Generation:      reg.Generation,
		})
		cancel()
		if err != nil {
			errs = append(errs, fmt.Errorf("регистрация %s: %w", reg.Object, err))
		}
	}
	return errors.Join(errs...)
}
