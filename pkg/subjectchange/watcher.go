// Package subjectchange — ЧИТАТЕЛЬ журнала смены субъекта, живущий в фундаменте.
//
// # Направление: соединение открывает ПОТРЕБИТЕЛЬ
//
// Владелец прав объявлен ЛИСТОМ графа рёбер: его зовут, он не зовёт никого.
// Прежде он сам дозванивался до потребителя и гасил его кэш толчком — ребро из
// листа обратно, да ещё и с обязательной ручкой адреса потребителя, из-за
// которой владелец не поднимался там, где потребителя нет вовсе. Толчок снят
// (задача #1024); читатель — здесь, и открывает соединение он.
//
// # Почему в фундаменте, а не у потребителя
//
// Свойство «смена прав доезжает до кэша решений» держится ОДНОЙ реализацией. Живи
// читатель у каждого потребителя, свойство держалось бы столькими независимыми
// копиями, сколько потребителей, — и достаточно одной забывчивой, чтобы отзыв
// пережил себя у одного из них, причём незаметно: у остальных проба зелёная.
//
// Побочное и не менее важное: живя здесь, читатель проверяется ОДНОЙ пробой
// вместе с производителем журнала — сквозь обе стороны, а не по половине. Пока
// он лежал в дереве потребителя, такая проба была невыразима: правило видимости
// `internal/` не пускает потребителя к производителю и обратно.
//
// # Что он делает — ДВА дела, а не одно
//
// Читает журнал курсором по возрастанию позиции и на всякой непустой порции:
//
//   - гасит кэш решений СВОЕГО процесса — это полоса ЗАПРОСА;
//   - закрывает открытые потоки НАЗВАННЫХ субъектов — это полоса СОЕДИНЕНИЯ
//     (задача #1022).
//
// Второе не выводится из первого и первым не покрывается. Кэш решений отвечает
// на СЛЕДУЮЩИЙ запрос, а длинное соединение следующего запроса не делает: сброс
// кэша выглядит отзывом и потока не касается вовсе — тот самый «контроль,
// действующий на выдаче, но не на предъявлении».
//
// Реплика, обслужившая мутацию, гасит свой кэш сама и немедленно; эта петля
// сводит СОСЕДНИЕ реплики в пределах одного окна — и только она закрывает их
// потоки, потому что других имён соседняя реплика не получает ниоткуда.
package subjectchange

import (
	"context"
	"fmt"
	"log/slog"
	"time"

	"github.com/PRO-Robotech/corelib/authz"
)

// SubjectChange — одна строка `subject_change_outbox` в том объёме, в каком её
// ЧИТАЕТ потребитель.
//
// Вид события (`op`) сюда намеренно не переносится: потребитель его не читает, а
// поле, принятое и не прочитанное, обещает вызывающему поведение, которого нет.
type SubjectChange struct {
	// ID — номер строки журнала; им двигается курсор.
	ID int64
	// Subject — субъект модели прав («user:usr-x»). Может быть пуст, если
	// владелец журнала его не назвал; такая строка двигает курсор и никого не
	// закрывает.
	Subject string
	// Naming — ПОЧЕМУ [SubjectChange.Subject] пуст.
	//
	// Пустое имя приходит по двум несравнимым причинам, и наблюдение обязано
	// их различать: выдача ГРУППЕ безымянна по устройству продукта (норма,
	// при каждом снятии привязки в предпочтительной форме выдачи), а
	// потерянный производителем тип означает, что отзыв по этой строке не
	// доедет ни до кэша поимённо, ни до открытого потока (дефект). Величина, в
	// которую сложены обе, ненулевая в штатной работе — тревогу на неё не
	// повесить (kacho#1463).
	//
	// Читается ТОЛЬКО при пустом имени. Ноль значения —
	// [authz.SubjectUnnameable]: строка, собранная без разбора, попадает в
	// громкую корзину, а не в тихую.
	Naming authz.SubjectNaming
}

// Poller — узкий порт над чтением журнала. Реализуется [Reader]; в пробах —
// чем угодно, потому что предмет петли не транспорт, а курсор и решение гасить.
//
// Предел порции задаёт ВЫЗЫВАЮЩИЙ, а не адаптер: по нему же вызывающий решает,
// могла ли порция быть усечена. Оставь предел у адаптера — и решение об усечении
// принималось бы здесь по числу, объявленному в другом месте, то есть двумя
// местами об одном предмете.
type Poller interface {
	PollSubjectChanges(ctx context.Context, since int64, limit int32) (changes []SubjectChange, headID int64, err error)
}

// StreamCloser — реестр открытых длинных соединений потребителя.
//
// Реализуется проекцией потока (`gateway/internal/subscriptionstream`.Handler).
// Порт объявлен ЗДЕСЬ, а реализация живёт у потребителя: фундамент не знает, что
// именно потребитель держит открытым, и знать не должен.
type StreamCloser interface {
	// CloseSubject закрывает потоки названного субъекта и возвращает их число.
	CloseSubject(subject string) int
	// CloseAll закрывает ВСЕ открытые потоки и возвращает их число.
	CloseAll() int
}

const (
	// minPollTimeout — пол срока одного вызова `PollSubjectChanges`: частый
	// перепрос не вправе сделать срок неразумно тесным.
	minPollTimeout = 5 * time.Second

	// pollBatchLimit — сколько строк просить за один вызов.
	pollBatchLimit = 1000

	// maxPassesPerTick — сколько порций подряд выбирается за ОДИН перепрос.
	//
	// Накопленный задел обязан выбираться целиком, а не по порции за тик:
	// массовый отзыв (увольнение, разбор инцидента, снос группы) — ровно тот
	// случай, ради которого механизм заведён, и растянуть его на десятки тиков
	// значило бы растянуть окно отзыва на те же десятки интервалов.
	//
	// Предел сверху всё же нужен: перепрос синхронен, и неограниченный проход по
	// огромному заделу занял бы петлю целиком, отложив и fail-closed.
	maxPassesPerTick = 16
)

// Config — что приносит композиционный корень потребителя.
type Config struct {
	// Poller — источник изменений субъекта. Обязателен.
	Poller Poller
	// Flush — сброс кэша решений этой реплики. Обязателен.
	Flush func()
	// Interval — период перепроса. Неположительный резолвится в 2s.
	Interval time.Duration

	// Closer — реестр открытых потоков. ОБЯЗАТЕЛЕН.
	//
	// Необязательным он быть не может, и это выяснилось инъекцией: передай в
	// точке сборки ноль — и весь корпус проб потребителя остаётся зелёным, код
	// собирается, а отзыв перестаёт доезжать до потоков совсем. То есть
	// несделанная провязка была бы НЕОТЛИЧИМА от сделанной, и неотличима именно
	// тем механизмом, ради которого задача заведена.
	//
	// Потребитель проекцию строит безусловно, поэтому законного нуля здесь нет.
	Closer StreamCloser

	// StaleAfter — сколько потребитель вправе ДЕРЖАТЬ потоки, не подтвердив
	// чтения отзыва. Обязателен вместе с [Config.Closer].
	//
	// Это ОКНО FAIL-CLOSED, и оно есть следствие решения, а не срока жизни
	// соединения: величина отсчитывается от последнего удачного перепроса и к
	// длительности соединения отношения не имеет. Обязана превосходить
	// [Config.Interval] — иначе один пропущенный перепрос объявляется аварией.
	StaleAfter time.Duration

	// Now — часы. Ноль резолвится в [time.Now]; проба подставляет свои, потому
	// что срок обязан быть свойством решения, а не занятости машины.
	Now func() time.Time

	// Logger — журнал процесса. Обязателен.
	Logger *slog.Logger
}

// Watcher читает журнал смены субъекта, гасит кэш решений своего процесса и
// закрывает открытые потоки названных субъектов.
type Watcher struct {
	cfg         Config
	pollTimeout time.Duration
	cursor      int64
	primed      bool
	lastRead    time.Time
}

// New собирает читателя и судит объявление.
//
// Отказ на сборке, а не первым отказом в бою: величина, при которой fail-closed
// не наступает никогда, — ошибка посадки, и обнаруживать её тогда, когда она уже
// кому-то стоила доступа, поздно.
func New(cfg Config) (*Watcher, error) {
	if cfg.Poller == nil {
		return nil, fmt.Errorf("subjectchange: источник изменений субъекта не назван — " +
			"читатель без него молчит ровно так же, как читатель, которому нечего сообщить")
	}
	if cfg.Flush == nil {
		return nil, fmt.Errorf("subjectchange: сброс кэша решений не назван")
	}
	if cfg.Logger == nil {
		return nil, fmt.Errorf("subjectchange: журнал процесса не назван — " +
			"застрявший отзыв обязан быть виден, а не только не работать")
	}
	if cfg.Interval <= 0 {
		cfg.Interval = 2 * time.Second
	}
	if cfg.Closer == nil {
		return nil, fmt.Errorf("subjectchange: реестр открытых потоков не назван — отзыв не доезжал бы " +
			"до длинных соединений вовсе, и несделанная провязка была бы неотличима от сделанной")
	}
	if cfg.StaleAfter <= 0 {
		return nil, fmt.Errorf("subjectchange: провязан закрыватель потоков, но срок StaleAfter не объявлен — " +
			"поток пережил бы аварию читателя отзыва целиком, то есть контроль отключался бы тем самым " +
			"событием, ради которого заведён")
	}
	if cfg.StaleAfter <= cfg.Interval {
		return nil, fmt.Errorf("subjectchange: StaleAfter %v не превосходит Interval %v — "+
			"срок, исчерпываемый одним пропущенным перепросом, объявляет аварией всякую заминку",
			cfg.StaleAfter, cfg.Interval)
	}
	// ВЕРХНЯЯ сторона срока: молчание, которое читатель считает рабочим
	// состоянием, обязано укладываться в удержание журнала у владельца.
	//
	// Иначе заводится состояние, невидимое ни одной пробе обеих сторон: читатель
	// молчит дольше, чем владелец хранит строки, и на первом же удачном перепросе
	// получает отказ «позиция утрачена» — то есть гасит кэш решений ЦЕЛИКОМ и
	// закрывает ВСЕ открытые потоки, будучи по собственному объявлению здоровым.
	// Это не потеря отзыва (отзыв применяется шире нужного), но это разрыв
	// клиентских соединений в штатной работе, и решать его никто не решал.
	//
	// Отказ, а не предупреждение: величина, при которой контроль работает не так,
	// как объявлен, есть посадка, которую поднимать нельзя.
	if cfg.StaleAfter > JournalRetention {
		return nil, fmt.Errorf("subjectchange: StaleAfter %v превосходит удержание журнала %v — "+
			"читатель объявляет рабочим молчание длиннее того, что владелец хранит, и на первом же "+
			"удачном перепросе получал бы отказ «позиция утрачена» в штатной работе: сплошное "+
			"гашение кэша решений и закрытие всех открытых потоков",
			cfg.StaleAfter, JournalRetention)
	}
	if cfg.Now == nil {
		cfg.Now = time.Now
	}

	// Срок одного вызова масштабируется периодом, но не опускается ниже пола:
	// зависший обработчик владельца не вправе заклинить петлю навсегда, а петля
	// обязана оправиться на следующем перепросе.
	pollTimeout := cfg.Interval * 4
	if pollTimeout < minPollTimeout {
		pollTimeout = minPollTimeout
	}
	// Срок неподтверждённого чтения отсчитывается от СТАРТА, а не от нуля
	// времени: процесс, чей читатель не заработал ни разу, обязан закрывать
	// потоки — но по истечении того же объявленного срока, а не немедленно.
	return &Watcher{cfg: cfg, pollTimeout: pollTimeout, lastRead: cfg.Now()}, nil
}

// Run блокирует до отмены контекста. Зовётся в своей горутине.
//
// РЕПЛИКИ: на-реплику — петля гасит кэш СВОЕГО процесса, закрывает СВОИ потоки и
// держит курсор в памяти. Каждая реплика обязана читать сама: разведи её выбором
// одной — и кэш невыбранных не погаснет вовсе, а их потоки переживут отзыв.
// Дубль чтения безвреден не по намерению, а по свойству оператора: чтение
// журнала ничего не меняет, гашение кэша идемпотентно, а закрытие уже закрытого
// потока стоит нуля.
func (w *Watcher) Run(ctx context.Context) {
	t := time.NewTicker(w.cfg.Interval)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
			w.Poll(ctx)
		}
	}
}

// Poll исполняет РОВНО ОДИН перепрос: прочитать, затем принять голову за курсор
// ЛИБО двинуть курсор по прочитанному, погасить кэш и закрыть названные потоки.
//
// Цикл синхронный: когда вызов вернулся, всё, что этот перепрос собирался
// сделать, сделано. Отсюда два следствия, и оба намеренные.
//
// ПЕРВОЕ — метод публичный. Он и есть та единица работы, которую [Watcher.Run]
// повторяет по расписанию; потребителю, ведущему собственный такт, незачем
// поднимать вторую петлю рядом. Тест-только-шов здесь стоял бы ровно на этом же
// месте и означал бы то же самое, только не будучи назван.
//
// ВТОРОЕ — им ставится СКВОЗНОЙ вопрос. Проба, спрашивающая «изменение прав
// доехало ли до кэша решений и до открытого потока», обязана читать наблюдаемое
// ПОСЛЕ того, как перепрос закончился, а не пока он идёт. Через [Watcher.Run]
// это означало бы угадывать момент по таймеру — угадывание верное на свободной
// машине и неверное на занятой.
func (w *Watcher) Poll(ctx context.Context) {
	// Срок одного вызова: зависший обработчик владельца не вправе заклинить петлю.
	pollCtx, cancel := context.WithTimeout(ctx, w.pollTimeout)
	defer cancel()
	for pass := 0; pass < maxPassesPerTick; pass++ {
		changes, headID, err := w.cfg.Poller.PollSubjectChanges(pollCtx, w.cursor, pollBatchLimit)
		if err != nil {
			// ПОЗИЦИЯ УТРАЧЕНА — отдельная ветвь, и слить её с общей нельзя.
			//
			// Владелец говорит: строки между твоим курсором и полом СНЯТЫ, и ты
			// их уже не получишь. Общая ветвь ниже советует «повторить с той же
			// позиции» — на утраченной позиции этот повтор не пройдёт НИКОГДА,
			// сколько бы ни ждать, то есть петля отзыва встала бы навсегда. И
			// встала бы молча для клиента: кэш вердиктов продолжает отвечать по
			// правам, которых уже нет.
			if lost, ok := AsPositionLost(err); ok {
				w.positionLost(lost)
				return
			}
			w.cfg.Logger.Warn("subject-change poll failed", "err", err)
			w.failClosed()
			return
		}
		w.lastRead = w.cfg.Now()

		// Первый удачный перепрос свежей реплики: курсор принимается, сброса нет.
		// Кэш при старте пуст, а прыжок сразу на позицию избавляет от
		// проигрывания накопленной истории. Отзывом принятие курсора не
		// является — и это ЕДИНСТВЕННОЕ место, где курсор поднимается до позиции.
		//
		// Прыжок безопасен ПОТОМУ, ЧТО позиция — граница УСТОЯВШЕГОСЯ у владельца
		// журнала, а не наибольший видимый номер (kacho#1374): за границей не
		// может появиться меньший номер, а `MAX(id)` этого не гарантировал и
		// уносил курсор за писателя в полёте. Владелец, у которого позиции ещё
		// нет, отвечает отказом, а не нулём, — иначе принятый ноль посадил бы
		// свежую реплику в НАЧАЛО журнала.
		if !w.primed {
			w.primed = true
			w.cursor = headID
			return
		}
		if len(changes) == 0 {
			return
		}

		// Курсор двигается ТОЛЬКО по ПРОЧИТАННЫМ строкам.
		//
		// Прежде он поднимался до `headID` и поднимался БЕЗУСЛОВНО, а `headID`
		// был тогда общим максимумом таблицы. Для сплошного сброса кэша это было безвредно —
		// какие строки прочли, неважно. Для ПОИМЁННОГО закрытия потоков это
		// потеря отзыва: при заделе больше порции курсор перепрыгивал через
		// непрочитанные строки, и их субъекты не назывались бы НИКОГДА.
		// Срабатывало бы ровно при массовом отзыве.
		for _, c := range changes {
			if c.ID > w.cursor {
				w.cursor = c.ID
			}
		}
		w.cfg.Flush()
		closed, usersets, unnamed := w.closeNamed(changes)
		w.cfg.Logger.Info("authz decision-cache flushed by subject-change poll",
			"cursor", w.cursor, "subjects", len(changes), "streams_closed", closed,
			// Безымянные строки считаются ДВУМЯ величинами, а не одной.
			//
			// Прежде счётчик был один, и он делал «закрывать было нечего»
			// отличимым от «закрыть было нечем» — ради этого и заводился. Но два
			// повода «закрыть было нечем» он смешивал: выдачу ГРУППЕ (норма, при
			// каждом снятии привязки в предпочтительной форме выдачи) и
			// потерянное производителем имя (дефект). Смешанная величина
			// ненулевая в штатной работе, поэтому по ней нельзя принять ни одного
			// решения — форма наблюдения без содержания (kacho#1463).
			"usersets_skipped", usersets,
			"subjects_unnamed", unnamed)

		// Тревога вешается на ДЕФЕКТ, и только на него: норма её не поднимает
		// никогда, иначе жалоба звучала бы в штатной работе — и её перестали бы
		// читать вместе с настоящей находкой.
		if unnamed > 0 {
			w.cfg.Logger.Warn("subject-change row carries no subject name",
				"subjects_unnamed", unnamed, "cursor", w.cursor)
		}

		if len(changes) < pollBatchLimit {
			// Порция короче предела — задел выбран целиком.
			return
		}
	}
	w.cfg.Logger.Warn("subject-change backlog exceeds one poll; remainder follows next tick",
		"cursor", w.cursor, "passes", maxPassesPerTick)
}

// closeNamed закрывает потоки НАЗВАННЫХ порцией субъектов, каждого по одному
// разу: повтор имени в порции обходил бы реестр под замком впустую.
//
// Пустое имя отсекается безусловно: под ним не учтён ни один поток, а обход по
// нему был бы вопросом ни о ком.
func (w *Watcher) closeNamed(changes []SubjectChange) (closed, usersets, unnamed int) {
	seen := make(map[string]struct{}, len(changes))
	for _, c := range changes {
		if c.Subject == "" {
			// Субъекта назвать не удалось: тип вне словаря потоков (группа) либо
			// строка записана до того, как производители стали проставлять тип.
			//
			// Что при этом ВСЁ РАВНО закрывается: поток, отобранный по проекту, —
			// страж проектной оси у владельца переспрашивается перед каждой
			// уходящей порцией и разрешает членство группы наравне с прямой
			// выдачей, поэтому отказ стража рвёт и поток, и соединение над ним.
			//
			// Что остаётся: поток БЕЗ проектной оси. Стража у него нет
			// (сторожить нечего), и его защищает только пообъектное сужение —
			// то есть строки перестают уходить в пределах окна вердиктов
			// сужателя, а СОЕДИНЕНИЕ живёт до своего бюджета. Величина названа,
			// чтобы этот остаток был виден, а не выведен.
			if c.Naming == authz.SubjectUserset {
				// НОРМА: множество участников удостоверения не предъявляет, и
				// потока под ним не учтено ни одного. Смена состава группы
				// приезжает ОТДЕЛЬНОЙ строкой, называющей участника.
				usersets++
				continue
			}
			// ДЕФЕКТ: имя должно было быть и потеряно. Отзыв по этой строке не
			// доедет ни до кэша поимённо, ни до открытого потока.
			unnamed++
			continue
		}
		if _, dup := seen[c.Subject]; dup {
			continue
		}
		seen[c.Subject] = struct{}{}
		closed += w.cfg.Closer.CloseSubject(c.Subject)
	}
	return closed, usersets, unnamed
}

// ClosesStreams — провязан ли реестр открытых потоков.
//
// Существует ради САМООТЧЁТА: он обязан печатать НАБЛЮДЕНИЕ, а не литерал.
// Литерал продолжает утверждать «закрывает» при отключённом закрывателе — то
// есть ровно тот класс, ради которого задача заведена.
func (w *Watcher) ClosesStreams() bool { return w.cfg.Closer != nil }

// StaleAfter — объявленный срок неподтверждённого чтения отзыва. Для самоотчёта.
func (w *Watcher) StaleAfter() time.Duration { return w.cfg.StaleAfter }

// positionLost отвечает на «позиция больше не возобновима»: гасит кэш решений
// ЦЕЛИКОМ, закрывает ВСЕ открытые потоки и садится на названную позицию.
//
// # Почему радиус сплошной, а не поимённый
//
// Имена пропущенных субъектов приезжали как раз тем чтением, которого не
// случилось. Реплика в этом состоянии знать их не может НИ ОТКУДА — значит выбор
// стоит между «закрыть всех» и «не закрыть никого», и второе есть отзыв, не
// доехавший до предъявления.
//
// Ответ дёшев ровно потому, что предмет журнала узок: кэш решений
// восстанавливается перепросом права, а закрытый поток переоткрывает клиент. Это
// то же самое, что реплика уже делает при просроченном чтении и на холодном
// старте, — новой стоимости здесь нет.
//
// # Курсор ПРИНИМАЕТСЯ, а не двигается
//
// Названная позиция — «самая ранняя удержанная минус один», поэтому строго выше
// неё снятого нет by construction (уборка снимает ПРЕФИКС). Сесть выше значило бы
// пропустить удержанное; остаться ниже — получать тот же отказ вечно.
//
// # Срок неподтверждённого чтения ОБНОВЛЯЕТСЯ
//
// Владелец ответил, и ответ разобран: читатель не просрочен, он потерял позицию.
// Не обновить срок значило бы через `StaleAfter` объявить аварией состояние,
// которое уже обработано полностью и правильно.
func (w *Watcher) positionLost(lost *PositionLostError) {
	w.cfg.Flush()
	closed := w.cfg.Closer.CloseAll()
	w.lastRead = w.cfg.Now()
	w.cursor = lost.EarliestResumable
	// Праймится в том числе холодная реплика: позиция названа владельцем и
	// принимать вместо неё голову следующим перепросом нельзя — между полом и
	// головой лежат УДЕРЖАННЫЕ строки, которые эта реплика ещё не читала.
	w.primed = true

	// Громко: это потеря отзывов, а не рабочее состояние. Оператору она говорит,
	// что удержание журнала короче, чем отставание читателя, — то есть выбранный
	// срок хранения мал либо читатель отставал дольше него.
	w.cfg.Logger.Error("subject-change position is no longer resumable: flushed every decision "+
		"and closed every open stream (fail-closed)",
		"resumed_from", w.cursor, "streams_closed", closed)
}

// failClosed закрывает ВСЕ потоки, когда читатель отзыва не подтверждался дольше
// объявленного срока.
//
// Неполученный ответ авторитета не есть «прав ни у кого не отзывали». Кого
// именно закрывать, реплика в этом состоянии знать не может: имена приезжали как
// раз тем чтением, которого нет, — поэтому радиус широкий, и он назван.
//
// Закрывает на КАЖДОМ отказе за сроком, а не однажды: клиент, переоткрывшийся в
// середине аварии, обязан закрыться тоже. На пустом реестре это стоит нуля.
func (w *Watcher) failClosed() {
	stale := w.cfg.Now().Sub(w.lastRead)
	if stale < w.cfg.StaleAfter {
		return
	}
	closed := w.cfg.Closer.CloseAll()
	if closed == 0 {
		// Ноль закрытых — не событие: держать было нечего. Печатать это на
		// каждом перепросе значило бы утопить настоящую находку в шуме.
		return
	}
	w.cfg.Logger.Error("subject-change reader is stale: closing every open stream (fail-closed)",
		"stale_for", stale.String(), "stale_after", w.cfg.StaleAfter.String(), "streams_closed", closed)
}
