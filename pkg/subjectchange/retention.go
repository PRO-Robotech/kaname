package subjectchange

import "time"

// retention.go — ВЕЛИЧИНА УДЕРЖАНИЯ журнала смены субъекта.
//
// # Почему она объявлена ЗДЕСЬ, у читателя, а не у владельца журнала
//
// Порог удержания есть функция ПРЕДИКАТА ЧИТАТЕЛЯ: строку позволено снять не
// раньше момента, после которого ни один читатель не изменил бы из-за неё своего
// исхода. Предикат читателя живёт в этом пакете, поэтому величина стоит рядом с
// ним — тем же доводом, каким здесь стоит словарь отказа «позиция утрачена»
// (`positionlost.go`): величина принадлежит ПОЛОСЕ, а не тому, кто оказался её
// первым автором. Владелец журнала (iam) берёт её отсюда и своей копии не
// заводит: копия разошлась бы молча и разошлась бы в ОПАСНУЮ сторону — уборщик
// снимал бы строки, которые читатель ещё вправе получить.

// JournalRetention — НАИБОЛЬШЕЕ ОТСТАВАНИЕ ЧИТАТЕЛЯ, которое владелец журнала
// обязан обслужить точно, и потому же — срок, в течение которого строка журнала
// остаётся возобновимой.
//
// # Величина ВЫВЕДЕНА из читателя, а не назначена из удобства
//
// Читатель — реплика края, ведущая курсор в памяти процесса. Отсюда первый и
// несущий факт: КУРСОР НЕ ПЕРЕЖИВАЕТ ПРОЦЕССА. Свежая реплика праймится на
// голову журнала ([Watcher.Poll], ветвь `!w.primed`) и удержанного хвоста не
// читает вовсе. Значит курсор отстаёт ТОЛЬКО пока процесс жив и не может
// опросить владельца, — а не «пока потребителя нет».
//
// Отсюда порог: он обязан покрывать самое долгое молчание ЖИВОГО читателя,
// которое платформа ещё считает рабочим состоянием. Читатель называет эту
// границу сам — [Config.StaleAfter]: за ней он объявляет себя просроченным и на
// каждом следующем перепросе закрывает ВСЕ открытые потоки ([Watcher.failClosed]).
//
// # Чем это держится, а не обещается
//
// [New] отвергает читателя, объявившего `StaleAfter` больше этой величины.
// Состояние «порог владельца короче того молчания, которое читатель считает
// здоровым» становится НЕВЫРАЗИМЫМ, а не маловероятным: посадка, объявившая
// такое, не поднимается.
//
// # Почему не короче
//
// Единственное ШТАТНОЕ событие, при котором живой читатель не может опросить
// владельца, — перекат самого владельца прав. Десять минут покрывают его с
// запасом, и запас этот платится строками, а не безопасностью.
//
// Сегодняшняя посадка края объявляет `StaleAfter = max(5 × 2s, 10s) = 10s`
// (`gateway/cmd/api-gateway`, `revocationStaleAfter`) — на два порядка ниже
// порога, то есть отказ «позиция утрачена» в штатной работе не производится
// ничем.
//
// # Почему не длиннее
//
// Журнал НЕ является историей выдачи. История — предмет журнала аудита и
// журнала намерений (`kaname.audit_outbox`, `kaname.fga_outbox`), чьё
// удержание объявлено политикой намеренно. Держать здесь дольше значило бы
// завести третье свидетельство одного события — свидетельство без читателя.
//
// # ЧЕГО величина не обещает
//
// Она не есть окно отзыва доступа: окно задаёт ПЕРИОД ПЕРЕПРОСА читателя и
// объявлено политикой (`corelib/authz`.RevocationPolicy). Отставший дальше порога
// читатель получает не «пропущенный отзыв», а ЯВНЫЙ отказ с возобновимой
// позицией — и отвечает на него сплошным гашением кэша и закрытием всех
// потоков ([Watcher.positionLost]). Это дороже точечного закрытия, но не менее
// безопасно: отзыв применяется ШИРЕ нужного, а не уже.
//
// # У порога НЕТ слагаемого на разницу часов
//
// Отметка времени строки ставится умолчанием колонки (`created_at DEFAULT
// now()`), то есть часами БАЗЫ, и уборка судит теми же часами: момент времени в
// сигнатуру уборщика не входит, предикат целиком в SQL. Слагаемое, покрывающее
// разницу, которой нет, было бы запасом без предмета.
const JournalRetention = 10 * time.Minute
