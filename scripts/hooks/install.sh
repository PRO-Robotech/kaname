# install.sh — провязать хуки этого дерева в клон, заявить их за ЭТУ рабочую копию
# и сказать, провязаны ли они.
# Зовётся целями `make install-hooks` / `make check-hooks`; руками — тоже можно.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПРЕДМЕТ: ПЕРЕХОДНИК, НЕ НАШЕДШИЙ АДРЕСАТА, ВЫХОДИЛ УСПЕХОМ
#
# До этого изменения в клонах этого репозитория лежал переходник `kaname-hook-stub
# v1`, а каталога `scripts/hooks` в дереве не было ВОВСЕ. Переходник искал
# `<корень>/scripts/hooks/pre-push`, не находил, печатал одну строку — «проверок
# НЕ БЫЛО» — и выходил НУЛЁМ, то есть пропускал отправку.
#
# Замер (2026-09-22, ствол `cbbac984`, переходник побайтно тот же — sha256
# `5defde11…`): `git push` прошёл за 1.3 секунды, код 0, исполненных проверок 0.
#
# Значит всё, что уезжало из этого репозитория, уезжало НЕПРОВЕРЕННЫМ. Не
# «зелёным» — непроверенным: «ноль находок» и «ноль осмотренного» дают один и тот
# же ноль, и отличить их по исходу `git push` было нечем.
#
# ОТСЮДА ДВА СВОЙСТВА, КОТОРЫЕ ДЕРЖИТ ЭТОТ СКРИПТ:
#
#   1. АДРЕСАТ ЕСТЬ. `scripts/hooks/pre-push` лежит в дереве и отслеживается —
#      значит едет в каждый клон вместе с кодом.
#   2. ОТСУТСТВИЕ АДРЕСАТА — ОТКАЗ В КОПИИ, ЗАЯВИВШЕЙ ПРОВЯЗКУ. Переходник,
#      который кладёт этот скрипт, на ненайденном адресате выходит НЕНУЛЁМ и
#      называет причину. «Условие не создано» — третья категория, и она не
#      зачитывается в успех.
#
# Второе — не подстраховка первого, а самостоятельное свойство: рабочая копия
# бывает старше хука (checkout ревизии, где его ещё нет), и тогда молчаливый
# пропуск вернулся бы ровно в прежнем виде.
#
# ─────────────────────────────────────────────────────────────────────────────
# ОДИН КАТАЛОГ ХУКОВ НА ВСЕ КОПИИ КЛОНА — ОТКАЗ ПРИНАДЛЕЖИТ КОПИИ
#
# git ищет хуки в `<общий каталог>/hooks`, и он ОДИН на все рабочие копии клона
# (`git worktree`). Переходник `v2` отказывал на ненайденном адресате в КАЖДОЙ из
# них: провязка из одной копии останавливала коммит в соседней, чья ревизия
# старше хука, — провязкой, которой та копия не делала. Замер (2026-09-24,
# сборка 412, общий клон): копий 104, без `scripts/hooks/commit-msg` 102, без
# `scripts/hooks/pre-push` 74; опыт — коммит соседней копии, код 1.
#
# Поэтому провязка — два факта, и живут они в РАЗНЫХ местах:
#
#   · переходник — в общем каталоге, один на клон (так устроен git);
#   · заявление — в СЛУЖЕБНОМ каталоге копии (`git rev-parse --absolute-git-dir`,
#     у соседней копии это `<общий>/worktrees/<имя>`), файл `kaname-hooks-declared`
#     с именами хуков, которые эта копия провязала.
#
# Переходник исполняет адресата, если он в дереве есть, — в любой копии, так что
# ничьи проверки лекарство не выключает. Без адресата он ОТКАЗЫВАЕТ там, где хук
# заявлен, и ПРОПУСКАЕТ действие с названной причиной там, где не заявлен: это
# состояние свежего клона, и `make check-hooks` в такой копии называет его
# третьим исходом, а не «провязано». Заявление уходит вместе с копией
# (`git worktree remove` · `prune` сносят её служебный каталог целиком).
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ НЕ `core.hooksPath`
#
# Одна строка настройки выглядит проще всего и имеет цену, которую видно не
# сразу: git начинает искать хуки ТОЛЬКО по указанному пути, и всё, что уже лежит
# в `.git/hooks`, перестаёт исполняться — молча, без единого сообщения. Лекарство
# от молчаливого пропуска обязано быть проверено на то, что оно само ничего не
# выключает молча.
#
# Поэтому в `.git/hooks` кладётся ПЕРЕХОДНИК: короткий файл, который находит
# рабочую копию и исполняет отслеживаемый скрипт из неё. Следствия названы, чтобы
# их не пришлось выяснять:
#
#   · посторонние хуки продолжают работать — переходник ставится только под
#     своим именем, чужой файл не затирается НИКОГДА (это отказ, а не перезапись);
#   · переходник берёт скрипт из ТОЙ рабочей копии, из которой идёт отправка,
#     поэтому в worktree исполняется его собственная версия хука;
#   · путей машины в переходнике нет — переезд клона его не ломает;
#   · цена: новый отслеживаемый хук требует повторного `make install-hooks`.
#     Цена наблюдаемая, а не молчаливая, — её называет `make check-hooks`.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПЕРЕХОДНИК ПРЕЖНЕЙ РЕДАКЦИИ — НЕ «ЧУЖОЙ ФАЙЛ» И НЕ «ПРОВЯЗАНО»
#
# Третье состояние, и без него починка не доезжает до клонов, которые уже
# существуют. Клон с `v1` выглядит провязанным (файл на месте, исполняемый,
# наш маркер), а ведёт себя как непровязанный — пропускает отправку молча.
# Поэтому версия читается из маркера, устаревший переходник числится
# НЕПРОВЯЗАННЫМ, называется отдельной строкой со своей причиной и
# перезаписывается установкой.
#
# ИМЕНА ХУКОВ ТОЧКИ НЕ СОДЕРЖАТ. Отсюда правило отбора: в `scripts/hooks` хуком
# считается отслеживаемый файл, в имени которого нет точки. Этот скрипт под
# правило не подпадает и хуком не станет.
set -uo pipefail

mode="${1:-install}"

die() { printf '%s\n' "$@" >&2; exit 1; }

root="$(git rev-parse --show-toplevel 2>/dev/null)" ||
    die "install-hooks: это не рабочая копия git — провязывать не во что."
common="$(git rev-parse --git-common-dir 2>/dev/null)" ||
    die "install-hooks: git не назвал общий каталог репозитория."
case "$common" in /*) ;; *) common="$root/$common" ;; esac

dst="$common/hooks"

# Служебный каталог ЭТОЙ копии — место её заявления (шапка: «отказ принадлежит
# копии»). Общий каталог сюда не годится: заявление в нём стало бы заявлением
# всех копий клона, то есть вернуло бы ровно дефект v2.
own_dir="$(git rev-parse --absolute-git-dir 2>/dev/null)" ||
    die "install-hooks: git не назвал служебный каталог этой рабочей копии."
declared_name="kaname-hooks-declared"
declared="$own_dir/$declared_name"

# Семейство маркера и текущая редакция. Маркер СЕМЕЙСТВА опознаёт «наш файл»,
# номер — «наш ли он СЕГОДНЯШНИЙ». Одна строка на оба вопроса не отвечает:
# сменив её целиком, мы объявили бы прежние переходники чужими файлами и
# отказались бы их трогать — то есть оставили бы молчаливый пропуск жить.
marker_family="kaname-hook-stub v"
stub_version=3

# stub_for — ЕДИНСТВЕННЫЙ производитель текста переходника.
#
# Второго написания нет и не заводится: проба провязки (install-inject.sh)
# берёт текст ОТСЮДА же, режимом `stub`, а не копией. Копия разошлась бы с
# производителем молча — и проба доказывала бы свойство файла, которого никто
# не кладёт.
stub_for() {
    cat <<STUB
#!/usr/bin/env bash
# СГЕНЕРИРОВАН \`make install-hooks\` — правится НЕ здесь, а в scripts/hooks/$1.
# $marker_family$stub_version
#
# ОТСУТСТВИЕ АДРЕСАТА — ОТКАЗ, А НЕ УСПЕХ, В КОПИИ, ЗАЯВИВШЕЙ ПРОВЯЗКУ. Редакция
# v1 на ненайденном адресате выходила нулём везде; v2 отказывала везде — и в
# соседних копиях клона, провязки не делавших. Этот файл один на все копии,
# поэтому заявление читается из служебного каталога ТОЙ копии, где идёт действие.
# Разбор — в шапке scripts/hooks/install.sh.
set -uo pipefail
top="\$(git rev-parse --show-toplevel 2>/dev/null)" || top=""
[ -n "\$top" ] || top="\$PWD"
real="\$top/scripts/hooks/$1"
[ ! -x "\$real" ] || exec "\$real" "\$@"
# Служебный каталог не назван — заявления не прочесть, и отказ остаётся отказом.
own="\$(git rev-parse --absolute-git-dir 2>/dev/null)" || own=""
if [ -n "\$own" ] && ! grep -Fqx -- "$1" "\$own/$declared_name" 2>/dev/null; then
    {
        echo "$1: проверок НЕ БЫЛО — адресата нет в этой рабочей копии: \$real"
        echo "  копия провязки $1 не заявляла (make install-hooks в ней), и действие не остановлено."
        echo "  Это не зелёное: локально не осмотрено ничего, первым читателем станет конвейер."
    } >&2
    exit 0
fi
{
    echo "$1: ОТКАЗ — действие git остановлено, потому что проверок НЕ БЫЛО."
    echo "  адресат: \$real"
    echo "  его нет в этой рабочей копии либо он не исполняемый, а копия провязку $1 заявила."
    echo "  Это не «ноль находок», это «ноль осмотренного», и зелёным такой исход не бывает."
    echo "  Законных исходов три, и каждый заявляется явно:"
    echo "    · рабочая копия старше хука — перейдите на ревизию, где scripts/hooks/$1 есть,"
    echo "      либо влейте в ветку ту, что его несёт;"
    echo "    · хук снят намеренно — make install-hooks перепишет заявление копии по её дереву;"
    echo "    · действие нужно сейчас и без проверок — скажите это: git commit|push --no-verify."
} >&2
exit 1
STUB
}

if [ "$mode" = "stub" ]; then
    [ "$#" -ge 2 ] || die "install-hooks: режим stub требует имя хука: $0 stub <имя>"
    stub_for "$2"
    exit 0
fi

src="$root/scripts/hooks"

# Отслеживаемые хуки. `git ls-files` — то же множество, что увидит свежий клон:
# файл, лежащий на диске и не добавленный в индекс, провязывать нечестно.
hooks=()
while IFS= read -r rel; do
    [ -n "$rel" ] || continue
    base="${rel##*/}"
    case "$base" in *.*) continue ;; esac
    hooks+=("$base")
done < <(git -C "$root" ls-files scripts/hooks)

[ "${#hooks[@]}" -gt 0 ] ||
    die "install-hooks: в scripts/hooks нет НИ ОДНОГО отслеживаемого хука." \
        "Это отказ, а не «нечего делать»: пустой обход здесь означал бы зелёный" \
        "вывод при непровязанном клоне — ровно тот исход, ради которого этот" \
        "скрипт написан." \
        "Осмотрено: $src"

# ── 1. Настройка, перебивающая .git/hooks ───────────────────────────────────
#
# С выставленным `core.hooksPath` переходники легли бы туда, куда git уже не
# заглядывает: вывод был бы «провязано», исполнялось бы ничего.
configured="$(git -C "$root" config --get core.hooksPath 2>/dev/null || true)"
if [ -n "$configured" ]; then
    case "$mode" in
    notice)
        echo "ВНИМАНИЕ: выставлен core.hooksPath=$configured — переходники не исполняются." >&2
        exit 0
        ;;
    esac
    die "install-hooks: в этом клоне выставлен core.hooksPath=$configured." \
        "Переходники кладутся в $dst, а git ищет хуки по указанному пути — они не" \
        "исполнились бы НИ РАЗУ, и вывод «провязано» был бы ложью." \
        "Снимите настройку (git config --unset core.hooksPath) и повторите."
fi

# ── 2. Состояние переходников ───────────────────────────────────────────────
mkdir -p "$dst" || die "install-hooks: не создать $dst"

# stub_version_of — редакция переходника, прочитанная из его же маркера.
# Пусто — файл не наш.
stub_version_of() {
    sed -n "s/^# ${marker_family}\([0-9][0-9]*\).*/\1/p" "$1" 2>/dev/null | head -1
}

# is_declared <имя> — заявила ли ЭТА копия провязку хука. Тот же вопрос задаёт
# переходник (`grep -Fqx` по тому же файлу), и ответы обязаны совпадать.
is_declared() {
    grep -Fqx -- "$1" "$declared" 2>/dev/null
}

wired=0
missing=()
undeclared=()
stale=()
foreign=()
for name in "${hooks[@]}"; do
    target="$dst/$name"
    if [ ! -e "$target" ]; then
        missing+=("$name")
        continue
    fi
    ver="$(stub_version_of "$target")"
    if [ -z "$ver" ]; then
        foreign+=("$name")
        continue
    fi
    if [ "$ver" -lt "$stub_version" ] 2>/dev/null; then
        stale+=("$name(v$ver)")
        continue
    fi
    if [ ! -x "$target" ]; then
        missing+=("$name")
    elif ! is_declared "$name"; then
        # Переходник на месте, но положила его ДРУГАЯ копия клона: здесь
        # отсутствие адресата не отказывает, и «провязано» было бы ложью.
        undeclared+=("$name")
    else
        wired=$((wired + 1))
    fi
done

# Посторонние хуки, которых мы не предоставляем, — их провязка не касается, и
# сказать это надо прямо: именно ради их сохранности выбран переходник.
# Наш переходник хука, которого это дерево не несёт, — не посторонний: его
# провязала соседняя копия, и здесь он пропускает действие с пометкой.
kept=()
elsewhere=()
refusing=()
for f in "$dst"/*; do
    [ -e "$f" ] || continue
    b="${f##*/}"
    case "$b" in *.sample) continue ;; esac
    ours=0
    for name in "${hooks[@]}"; do [ "$b" = "$name" ] && ours=1; done
    [ "$ours" = 0 ] || continue
    if [ -z "$(stub_version_of "$f")" ]; then kept+=("$b")
    elif is_declared "$b"; then refusing+=("$b")
    else elsewhere+=("$b"); fi
done

# Перепись печатается ВСЕГДА и первой: без объёма осмотренного «провязано 1»
# неотличимо от вывода скрипта, не открывшего ни одного каталога.
report() {
    echo "хуки: отслеживаемых ${#hooks[@]} · провязано $wired · не провязано ${#missing[@]} · не заявлено копией ${#undeclared[@]} · прежней редакции ${#stale[@]} · занято чужим ${#foreign[@]}"
    echo "  дерево:    $src"
    echo "  клон:      $dst"
    echo "  заявление: $declared"
    [ "${#kept[@]}" -eq 0 ] ||
        printf '  посторонних хуков оставлено нетронутыми: %s\n' "${kept[*]}"
    [ "${#elsewhere[@]}" -eq 0 ] ||
        printf '  переходников хуков, которых это дерево не несёт и копия не заявляла: %s (пропускают действие с пометкой)\n' "${elsewhere[*]}"
    [ "${#refusing[@]}" -eq 0 ] ||
        printf '  заявлены копией, а в дереве их нет: %s (действие будет ОСТАНОВЛЕНО; make install-hooks перепишет заявление по дереву)\n' "${refusing[*]}"
}

case "$mode" in
check)
    report
    rc=0
    if [ "${#foreign[@]}" -gt 0 ]; then
        echo "ОТКАЗ: под именем хука лежит ЧУЖОЙ файл: ${foreign[*]}" >&2
        echo "Он не перезаписывается — уберите его сами либо слейте с scripts/hooks/<имя>." >&2
        rc=1
    fi
    if [ "${#stale[@]}" -gt 0 ]; then
        echo "ОТКАЗ: переходник ПРЕЖНЕЙ редакции: ${stale[*]} (нужна v$stub_version)" >&2
        echo "Он выглядит провязанным и ведёт себя не так, как заявляет дерево: v1 на" >&2
        echo "ненайденном адресате пропускал действие молча, v2 останавливал его в каждой" >&2
        echo "копии клона — и в тех, что провязки не заявляли." >&2
        echo "  make install-hooks" >&2
        rc=1
    fi
    unwired=(${missing[@]+"${missing[@]}"} ${undeclared[@]+"${undeclared[@]}"})
    if [ "${#unwired[@]}" -gt 0 ]; then
        # ТРЕТИЙ ИСХОД НАЗЫВАЕТСЯ МЕТКОЙ, И ТОЛЬКО В ЭТОМ СЛУЧАЕ.
        #
        # Предпосылку «копия провязана» создаёт не дерево, а человек, один раз на
        # копию: в свежем клоне и в новой копии `git worktree add` её нет by
        # construction. Переходник, положенный СОСЕДНЕЙ копией, её не создаёт —
        # заявления этой копии он не несёт (шапка: «отказ принадлежит копии»). Для ЧЕЛОВЕКА это отказ —
        # код остаётся ненулевым и инструкция печатается. Для гейта
        # самостоятельного клона (`tools/standalonetargets`) это третий исход,
        # и он читает ИМЕННО метку, а не код: `make` схлопывает любой отказ
        # рецепта в свою двойку.
        #
        # Метка ставится ТОЛЬКО когда иных причин нет. Чужой файл под именем
        # хука и переходник прежней редакции — состояния, которые свежий клон
        # не производит; они остаются находками, иначе гейт перестал бы уметь
        # найти здесь хоть что-нибудь.
        if [ "${#foreign[@]}" -eq 0 ] && [ "${#stale[@]}" -eq 0 ]; then
            echo "УСЛОВИЕ НЕ СОЗДАНО (не находка): хуки в этой рабочей копии не провязаны — ${unwired[*]}" >&2
            echo "Предпосылку создаёт один запуск установки в ЭТОЙ копии, а не дерево:" >&2
        else
            echo "ОТКАЗ: не провязаны: ${unwired[*]}" >&2
        fi
        [ "${#missing[@]}" -eq 0 ] ||
            echo "Без переходника (${missing[*]}) git хука не зовёт: действие не проверяется локально." >&2
        [ "${#undeclared[@]}" -eq 0 ] ||
            echo "Переходник есть, заявления копии нет (${undeclared[*]}): без адресата действие пройдёт с пометкой, а не остановится." >&2
        echo "  make install-hooks" >&2
        rc=1
    fi
    exit "$rc"
    ;;
notice)
    # Тихий режим для чужих целей: он ничего не роняет и говорит ровно тогда,
    # когда сказать есть о чём. Молчание означает «провязано» — положительное
    # утверждение печатает `make check-hooks`, а не каждый прогон проб.
    if [ "${#missing[@]}" -gt 0 ] || [ "${#undeclared[@]}" -gt 0 ] || [ "${#stale[@]}" -gt 0 ] || [ "${#foreign[@]}" -gt 0 ]; then
        echo "ВНИМАНИЕ: хуки git не провязаны (${#missing[@]} нет · ${#undeclared[@]} не заявлено копией · ${#stale[@]} прежней редакции · ${#foreign[@]} занято чужим)." >&2
        echo "  Отправка ветки НЕ будет проверена локально — «make install-hooks» это чинит." >&2
    fi
    exit 0
    ;;
install) ;;
*) die "install-hooks: неизвестный режим «$mode» (install | check | notice | stub <имя>)" ;;
esac

# ── 3. Провязка ─────────────────────────────────────────────────────────────
if [ "${#foreign[@]}" -gt 0 ]; then
    die "ОТКАЗ: под именем хука уже лежит ЧУЖОЙ файл: ${foreign[*]}" \
        "" \
        "Он НЕ перезаписывается: чужой хук мог быть заведён осознанно, и его тихая" \
        "пропажа — тот самый класс, ради которого здесь не выставляется core.hooksPath." \
