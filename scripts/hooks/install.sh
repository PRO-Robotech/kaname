fi

installed=()
for name in "${hooks[@]}"; do
    target="$dst/$name"
    stub_for "$name" > "$target" || die "install-hooks: не записать $target"
    chmod +x "$target" || die "install-hooks: не сделать исполняемым $target"
    installed+=("$name")
done

# Заявление копии — ПОСЛЕ переходников и целиком: частично записанный файл
# объявил бы провязанными не те хуки. Пишется по дереву этой копии, поэтому
# хук, снятый из дерева, из заявления уходит сам.
tmp_declared="$declared.tmp.$$"
if ! {
    echo "# $marker_family$stub_version — заявление копии: без адресата эти хуки ОТКАЗЫВАЮТ (scripts/hooks/install.sh)"
    printf '%s\n' "${installed[@]}"
} > "$tmp_declared" || ! mv -f "$tmp_declared" "$declared"; then
    rm -f "$tmp_declared"
    die "install-hooks: не записать заявление копии $declared"
fi

