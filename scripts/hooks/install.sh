# install.sh — провязать хуки этого дерева в клон и СКАЗАТЬ, провязаны ли они.
# Носители вызова — цели `install-hooks` и `check-hooks`; прямой вызов законен.
#
# `core.hooksPath` ОТВЕРГНУТ, И ПРИЧИНА ИЗМЕРИМА. Настройка делает указанный
# каталог ЕДИНСТВЕННЫМ местом поиска: всё, что уже провязано в `.git/hooks`,
# перестаёт вызываться — без отказа, без предупреждения, без следа в выводе
# `git push`. Предикат цены: `ls .git/hooks` до правки и после; уцелевшее там
# перестанет исполняться, а выглядеть будет по-прежнему провязанным. На машине
# разработчика в этом каталоге живёт страж, сверяющий личность автора коммита, —
# то есть ценой одной строки настройки снимается проверка, чьё отсутствие
# обнаружится только чужим вопросом в обзоре. Средство, снимающее чужую защиту
# ради своей, негодно независимо от того, насколько оно короче.
#
# Поэтому в `.git/hooks` кладётся ПЕРЕХОДНИК — короткий файл, находящий рабочую
# копию и исполняющий отслеживаемый скрипт из неё. Следствия названы, чтобы их
# не пришлось выяснять: чужой файл под тем же именем НЕ ЗАТИРАЕТСЯ (это отказ, а
# не перезапись); путей машины в переходнике нет, поэтому переезд клона его не
# ломает; в рабочей копии исполняется ЕЁ собственная версия хука; цена — новый
# отслеживаемый хук требует повторной провязки, и цену эту называет `check`.
#
# ЛОВУШКА, РАДИ КОТОРОЙ ЗАВЕДЁН РЕЖИМ `check`, НАЗВАНА ПРЯМО. Переходник может
# стоять и звать скрипт, КОТОРОГО В ДЕРЕВЕ НЕТ. Отправку он тогда не рвёт —
# и правильно делает: ветка, заведённая до появления хука, файла не несёт, а
# запрет отправки с неё был бы поломкой, не защитой. Но провязка при этом
# ВЫГЛЯДИТ исполненной, хотя ни одна ветка ни разу не проверялась. Молча
# различить два состояния нечем — их и различает `check`, отказом.
set -uo pipefail

mode="${1:-install}"

die() { printf '%s\n' "$@" >&2; exit 1; }

root="$(git rev-parse --show-toplevel 2>/dev/null)" ||
    die "hooks: это не рабочая копия git — провязывать не во что."
common="$(git rev-parse --git-common-dir 2>/dev/null)" ||
    die "hooks: git не назвал общий каталог репозитория."
case "$common" in /*) ;; *) common="$root/$common" ;; esac

src="$root/scripts/hooks"
dst="$common/hooks"
marker="kaname-hook-stub v1"

# Отслеживаемые хуки ВЫВОДЯТСЯ ИЗ ИНДЕКСА, а не выписываются: `git ls-files` даёт
# то же множество, что увидит свежий клон, — файл, лежащий на диске и не
# добавленный в индекс, провязывать нечестно. Имена хуков git точек не содержат;
# отсюда правило отбора, под которое сам этот скрипт не подпадает.
hooks=()
while IFS= read -r rel; do
    base="${rel##*/}"
    case "$base" in *.*) continue ;; esac
    hooks+=("$base")
done < <(git -C "$root" ls-files scripts/hooks)

[ "${#hooks[@]}" -gt 0 ] ||
    die "hooks: в scripts/hooks нет НИ ОДНОГО отслеживаемого хука." \
        "Это отказ, а не «нечего делать»: пустой обход означал бы зелёный вывод" \
        "при непровязанном клоне."

stub_body() {
    cat <<STUB
#!/usr/bin/env bash
# ПОРОЖДЁН целью \`install-hooks\`. Предмет правки — scripts/hooks/$1, не этот файл:
# здешняя правка уедет при следующей провязке и не оставит следа.
# $marker
set -uo pipefail
top="\$(git rev-parse --show-toplevel 2>/dev/null)" || top=""
[ -n "\$top" ] || top="\$PWD"
real="\$top/scripts/hooks/$1"
if [ ! -x "\$real" ]; then
    echo "$1: в этой рабочей копии нет \$real — проверок НЕ БЫЛО." >&2
    echo "  Это НЕ «дерево чисто»: вердикта нет. Провязку сверяет: make check-hooks" >&2
    exit 0
fi
exec "\$real" "\$@"
STUB
}

case "$mode" in
install)
    mkdir -p "$dst" || die "hooks: не удалось создать $dst"
    installed=0
    for h in "${hooks[@]}"; do
        target="$dst/$h"
        if [ -e "$target" ] && ! grep -q "$marker" "$target" 2>/dev/null; then
            die "hooks: в $target лежит ПОСТОРОННИЙ файл — он не затирается." \
                "Уберите его сами, если он больше не нужен, и повторите."
        fi
        stub_body "$h" > "$target" || die "hooks: не удалось записать $target"
        chmod +x "$target" || die "hooks: не удалось сделать $target исполнимым"
        chmod +x "$src/$h" 2>/dev/null || true
        installed=$((installed + 1))
        echo "провязан: $h"
    done
    echo "провязано хуков: $installed из ${#hooks[@]} отслеживаемых."
    [ "$installed" -eq "${#hooks[@]}" ] || die "hooks: провязаны НЕ ВСЕ."
    ;;
check)
    bad=0
    for h in "${hooks[@]}"; do
        target="$dst/$h"
        if [ ! -e "$target" ]; then
            echo "НЕ ПРОВЯЗАН: $h — в $dst переходника нет." >&2
            echo "  Отправка из этого клона НЕ ПРОВЕРЯЕТСЯ. Чинится: make install-hooks" >&2
            bad=$((bad + 1)); continue
        fi
        if ! grep -q "$marker" "$target" 2>/dev/null; then
            echo "ПОСТОРОННИЙ: $target — не наш переходник, не трогаем." >&2
            bad=$((bad + 1)); continue
        fi
        if [ ! -x "$target" ]; then
            echo "НЕ ИСПОЛНИМ: $target — git его не запустит." >&2
            bad=$((bad + 1)); continue
        fi
        # ГЛАВНАЯ ОСЬ: переходник есть, а звать ему нечего. Он выходит УСПЕХОМ,
        # поэтому по исходу `git push` это состояние неотличимо от исправного.
        if [ ! -x "$src/$h" ]; then
            echo "ПРОВЯЗАН В ПУСТОТУ: $target зовёт $src/$h, а его нет либо он не исполним." >&2
            echo "  Переходник при этом выходит УСПЕХОМ — провязка ВЫГЛЯДИТ исполненной," >&2
            echo "  а не проверяется ничего. Чинится: chmod +x $src/$h" >&2
            bad=$((bad + 1)); continue
        fi
        echo "провязан: $h → scripts/hooks/$h"
    done
    echo "осмотрено хуков: ${#hooks[@]}, находок: $bad"
    [ "$bad" -eq 0 ] || exit 1
    echo "ЗЕЛЁНЫЙ: все отслеживаемые хуки провязаны и разрешимы."
    ;;
*)
    die "hooks: режим «$mode» не знаком; известны install и check."
    ;;
esac
