# prepush-classify.sh — К КАКОЙ КАТЕГОРИИ отнести исход группы проверок.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ПРОИЗВОДИТЕЛЬ, А НЕ ДВЕ СТРОКИ В ХУКЕ
#
# Потому что решение уже ошиблось молча, и ошиблось в пользу «зелёного».
#
# Прежняя редакция хука определяла категорию ЧТЕНИЕМ ВЫВОДА группы: строка,
# начинавшаяся (после снятия отступа) меткой «УСЛОВИЕ НЕ СОЗДАНО», переводила
# ВСЮ группу в третью категорию. А вывод группы — это вывод чужих программ:
# прогонщик проб печатает ТЕКСТ ОТКАЗА упавшей пробы, с отступом.
#
# Значит упавшая проба, чей текст несёт эту метку первой на своей строке,
# ОБНУЛЯЛА свою же красноту. Воспроизведено на боевом хуке (2026-09-22): проба
# `t.Errorf("…\nУСЛОВИЕ НЕ СОЗДАНО…")` — хук напечатал «зелёное — исполнено 6 из
# 7 групп, отказов 0» и вышел кодом 0, то есть ОТПРАВКУ ПРОПУСТИЛ. Метка
# общесловарная: её несут 99 файлов дерева, из них 23 на Go.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧЕМ ЗАКРЫТ КЛАСС — УСТРОЙСТВОМ, А НЕ БОЛЕЕ ТОЧНЫМ ОБРАЗЦОМ
#
# Этому файлу вывод группы НЕ ПЕРЕДАЁТСЯ ВОВСЕ. Он его не читает, не получает и
# не знает, где он лежит. Значит замаскировать красное текстом здесь нечем ни
# при каком содержимом вывода — не «образец стал строже», а входа такого нет.
#
# Категорию сообщают ДВА независимых сигнала, и оба производит сам хук:
#
#   · код возврата группы;
#   · файл заявки, в который пишет ТОЛЬКО функция хука `declare_unmet`. Путь к
#     нему живёт в НЕЭКСПОРТИРУЕМОЙ переменной оболочки: вложенный процесс
#     (`go test`, `make`, линтер) его не наследует и подделать не может.
#
# СИГНАЛЫ ОБЯЗАНЫ СОГЛАСОВАТЬСЯ. Разногласие — самостоятельный исход (код 2,
# «не выполнилось»), а не повод выбрать один из двух: группа, заявившая
# отсутствие предпосылки и при этом отработавшая, сообщает о дефекте хука, и
# молча предпочесть любую из версий значило бы вернуть маску другим путём.
#
# ─────────────────────────────────────────────────────────────────────────────
# ВЫЗОВ
#
#   prepush-classify.sh --rc <код> --unmet <файл заявки>
#
# Печатает ОДНО слово: green | red | unmet. Исходы: 0 — категория названа;
# 2 — судить не по чему либо сигналы разошлись.
#
# Проверяется инъекцией: scripts/hooks/prepush-classify-inject.sh
set -uo pipefail

# UNMET_RC — код, которым группа заявляет «я не исполнялась». Он ЗАРЕЗЕРВИРОВАН
# за хуком: ни одна группа не отдаёт его как исход чужой программы, потому что
# каждая функция, возвращающая его, делает это своей строкой рядом с заявкой.
# Совпадение кода чужой программы с этим числом не проходит молча — оно даёт
# разногласие сигналов, то есть код 2.
UNMET_RC=3

die() { printf '%s\n' "$@" >&2; exit 2; }

rc=""
unmet=""
while [ "$#" -gt 0 ]; do
    case "$1" in
        --rc)    rc="${2:-}"; shift 2 || die "prepush-classify: --rc без значения" ;;
        --unmet) unmet="${2:-}"; shift 2 || die "prepush-classify: --unmet без значения" ;;
        *) die "prepush-classify: неизвестный довод «$1»" \
               "Вывод группы этому файлу не передаётся намеренно — см. его шапку." ;;
    esac
done

case "$rc" in
    ''|*[!0-9]*) die "prepush-classify: код возврата группы не назван числом: «$rc»" ;;
esac
[ -n "$unmet" ] || die "prepush-classify: файл заявки не назван — судить не по чему"
[ -e "$unmet" ] || die "prepush-classify: файла заявки нет: $unmet" \
    "Его создаёт хук ДО прогона группы. Отсутствие означает, что судить не по чему," \
    "а «не по чему» — это не «зелёное»."

declared=0
[ -s "$unmet" ] && declared=1

if [ "$declared" = 1 ] && [ "$rc" != "$UNMET_RC" ]; then
    die "prepush-classify: сигналы разошлись — заявка об отсутствии предпосылки есть, а группа вернула код $rc (ожидался $UNMET_RC)." \
        "Это дефект хука, а не исход группы: выбрать одну из двух версий молча значило бы вернуть маску."
fi
if [ "$declared" = 0 ] && [ "$rc" = "$UNMET_RC" ]; then
    die "prepush-classify: сигналы разошлись — группа вернула код $UNMET_RC («не исполнялась»), а заявки с причиной не оставила." \
        "Причина обязательна: «не исполнялась» без названной предпосылки неотличимо от проглоченного отказа."
fi

if [ "$declared" = 1 ]; then
    echo unmet
elif [ "$rc" = 0 ]; then
    echo green
else
    echo red
fi
exit 0
