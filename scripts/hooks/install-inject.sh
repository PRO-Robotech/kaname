# install-inject.sh — доказательство ИНЪЕКЦИЕЙ, что провязка хука способна
# отказать, и что отказывает она ровно на своём предмете.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАЧЕМ ЭТОТ ФАЙЛ
#
# Предмет починки — механизм отправки, и он обладает свойством, которое делает
# его особенно опасным: НЕИСПРАВНЫЙ он молчит ровно так же, как исправный.
# Переходник `v1` находил отсутствие адресата, печатал одну строку и выходил
# нулём; отличить это от зелёного прогона по исходу `git push` было нечем, и
# оттого ни одна ветка этого репозитория ни разу не была проверена локально.
#
# Значит утверждение «теперь отказывает» обязано быть ДОКАЗАНО опытом, а не
# прочтением кода. Здесь оно доказывается в обе стороны: дефект — отказ с
# названной причиной, законный близнец той же формы — молчание и проход.
# Отказ с редакции v3 принадлежит КОПИИ, заявившей провязку (шапка install.sh),
# и итоговая строка обязана говорить ровно это — раздел ниже.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ЗДЕСЬ НЕ ДЕЛАЕТСЯ
#
# Ни один опыт не трогает ни этот клон, ни его `.git/hooks`. Всё происходит в
# синтетическом репозитории во временном каталоге, и перед его заведением
# проверяется, что каталог не лежит ВНУТРИ чужого дерева: клон внутри чужого
# репозитория получает при обходе вверх чужой индекс, и опыт судил бы не то, что
# объявляет (тот же класс, что закрывает tools/standalonetargets).
#
# Адресатом в опытах служит ПОДСТАВНОЙ скрипт, а не боевой `scripts/hooks/pre-push`:
# предмет здесь — поведение ПЕРЕХОДНИКА (дошёл · отказал), а не содержание
# проверок. Что боевой адресат существует и отслеживается — отдельная ось ниже,
# и она спрашивает индекс git, а не диск.
#
# ─────────────────────────────────────────────────────────────────────────────
# ИТОГОВАЯ СТРОКА — СОСТАВ УСТАНОВЛЕННОГО, А НЕ ВТОРОЕ ЕГО НАПИСАНИЕ
#
# Здесь стояла литеральная строка «без адресата ОТКАЗЫВАЕТ», и она пережила
# сужение свойства: v3 отказывает только в копии, заявившей провязку, а в
# соседней пропускает действие с пометкой — ось 10 держит обе стороны, итоговая
# строка при этом говорила шире доказанного. Её не судил никто: конвейер читает
# код, человек — последнюю строку.
#
# Поэтому ось, доказавшая свойство, заявляет его строкой `claim`, итоговая
# строка СОСТАВЛЯЕТСЯ из заявленного (`compose_verdict`), а судит её прогон,
# который её видит: файл исполняется в две ступени. Внешняя (без доводов либо
# `--self-test`) зовёт внутреннюю (`--axes-only` — оси без суда), повторяет её
# вывод и сверяет последнюю строку с составом строк «установлено:» переписи
# (`judge_verdict`). Литерал на месте состава — отказ; судья сам доказан осью 11.
#
# Прогон: `bash scripts/hooks/install-inject.sh` (или с `--self-test` — тем же).
set -uo pipefail

stage=judge
case "${1:-}" in
    ""|--self-test) ;;
    --axes-only) stage=axes ;;
    *) echo "install-inject: неизвестный довод «$1» (без доводов, --self-test либо --axes-only)" >&2; exit 2 ;;
esac

# compose_verdict <свойство>... — ЕДИНСТВЕННЫЙ производитель итоговой строки.
compose_verdict() {
    local line="ЗЕЛЁНОЕ:" sep=" " c
    for c in "$@"; do line+="$sep$c"; sep="; "; done
    printf '%s.\n' "$line"
}

# judge_verdict <вывод внутренней ступени> — последняя строка обязана быть
# составом строк «установлено:». Код: 0 — совпала, 1 — расходится (шире либо
# уже доказанного), 2 — установленного нет, и судить строку не по чему.
judge_verdict() {
    local cap="$1" got want l
    local -a est=()
    while IFS= read -r l; do est+=("$l"); done < <(sed -n 's/^установлено: //p' "$cap")
    got="$(tail -n 1 "$cap")"
    if [ "${#est[@]}" -eq 0 ]; then
        echo "БЕСПРЕДМЕТНО: итоговая строка «$got» при нуле установленных свойств — вердикта нет." >&2
        return 2
    fi
    want="$(compose_verdict "${est[@]}")"
    if [ "$got" != "$want" ]; then
        {
            echo "ОТКАЗ: итоговая строка расходится с установленным осями — она говорит не то, что доказано."
            echo "  напечатано : $got"
            echo "  установлено: $want"
            echo "  Итоговая строка — состав строк «установлено:» (compose_verdict), а не второе их написание."
        } >&2
        return 1
    fi
    echo "сверка итоговой строки: установленных свойств ${#est[@]}, строка — их состав"
}

if [ "$stage" = judge ]; then
    cap="$(mktemp)" || { echo "install-inject: НЕ ИСПОЛНЯЛОСЬ — нет временного файла для вывода осей" >&2; exit 2; }
    trap 'rm -f "$cap"' EXIT
    # Вывод повторяется вживую, чтобы строки осей не отрывались от своих отказов
    # в stderr. Код каждого звена берётся из PIPESTATUS, а не у трубы целиком.
    bash "${BASH_SOURCE[0]}" --axes-only | tee "$cap"
    st=("${PIPESTATUS[@]}")
    if [ "${st[1]}" -ne 0 ]; then
        echo "install-inject: НЕ ИСПОЛНЯЛОСЬ — вывод осей не записан (tee, код ${st[1]}): итоговую строку судить не по чему" >&2
        exit 2
    fi
    [ "${st[0]}" -eq 0 ] || exit "${st[0]}"
    judge_verdict "$cap"
    exit $?
fi

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || {
    echo "install-inject: НЕ ИСПОЛНЯЛОСЬ — это не рабочая копия git" >&2
    exit 2
}
INSTALL="$ROOT/scripts/hooks/install.sh"
[ -f "$INSTALL" ] || {
    echo "install-inject: НЕ ИСПОЛНЯЛОСЬ — не найден $INSTALL" >&2
    exit 2
}

checks=0
failed=0
ok()  { checks=$((checks + 1)); note_check; echo "  ok   — $1"; }
bad() {
    checks=$((checks + 1)); note_check; failed=$((failed + 1))
    [ "$current_axis" -eq 0 ] || axis_failed[$current_axis]=$(( ${axis_failed[$current_axis]:-0} + 1 ))
    echo "  БЕДА — $1" >&2
}

# claim <свойство> — текущая ось заявляет доказанное ею свойство для итоговой
# строки. Заявляется ПОСЛЕ утверждений, которые его доказывают, и только если
# ни одно утверждение этой оси не разошлось: не доказанное в строку не идёт.
claims=()
claim() {
    [ "${axis_failed[$current_axis]:-0}" -eq 0 ] || return 0
    claims+=("$1")
}

MARK='УСЛОВИЕ НЕ СОЗДАНО'

# ВЕДОМОСТЬ ОСЕЙ — ЕДИНСТВЕННЫЙ источник перечня и ОБОИХ чисел: сколько осей и
# сколько утверждений обязана исполнить каждая. Без неё прогон, потерявший ось
# или утверждение, печатал меньшее число и выходил НУЛЁМ: снятие оси 9 целиком
# давало 9 осей, 24 утверждения и «ЗЕЛЁНОЕ». Конвейер зовёт этот файл соседней
# строкой с прогоном определителя и читает ТОЛЬКО код, поэтому число, которое
# никто не судит, вердикта не несёт.
#
# Порядок здесь — порядок осей в файле; имя оси отделено от её места, потому
# что ось «5а» вставлена между пятой и шестой.
# СЧЁТ ВЕДЁТСЯ ПО ОСЯМ, А НЕ ОДНОЙ СУММОЙ.
#
# Первая редакция сравнивала сумму с суммой, и этого было мало: покрытие,
# ушедшее из одной оси, возмещалось прибавкой в другой, и ведомость молчала.
# Проверено компенсирующей инъекцией с контролем — снять утверждение у оси 1 и
# прибавить оси 2: контроль (одна прибавка) давал код 2, компенсация — код 0.
# Значит числа `AXIS_CHECKS` были пояснением, а не проверкой.
#
# current_axis объявляет, чьё утверждение сейчас считается. Утверждение, не
# приписанное ни одной оси, — тоже дефект пробы: его некому требовать.
current_axis=0
orphan_checks=0
axis_seen=()
axis_failed=()
axis_short=()

note_check() {
    if [ "$current_axis" -gt 0 ]; then
        axis_seen[$current_axis]=$(( ${axis_seen[$current_axis]:-0} + 1 ))
    else
        orphan_checks=$((orphan_checks + 1))
    fi
}

AXIS_NAME=(1 2 3 4 5 5а 6 7 8 9 10 11)
AXIS_CHECKS=(2 4 5 1 4 3 2 2 1 2 5 4)
AXES_DECLARED=${#AXIS_CHECKS[@]}
axes_executed=0
expected_checks=0
unmet_reasons=()

# axis_done <место по ведомости, с 1> — ось исполнена; её утверждения идут в
# ожидаемое число. Ожидаемое набирается ТОЛЬКО по исполненным осям.
axis_done() {
    local want="${AXIS_CHECKS[$1 - 1]}" seen="${axis_seen[$1]:-0}"
    axes_executed=$((axes_executed + 1))
    expected_checks=$((expected_checks + want))
    [ "$seen" -eq "$want" ] || \
        axis_short+=("ось ${AXIS_NAME[$1 - 1]}: объявлено $want, исполнено $seen")
}

# axis_unmet <место> <предпосылка> — ось НЕ исполнялась.
#
# Здесь это шло через `bad`, то есть в КРАСНОЕ (код 1). Несобравшаяся фикстура
# — не находка о предмете: она означает, что о предмете не сказано ничего. Семь
# площадок этого файла зачитывали третью категорию в красное — зеркало того же
# дефекта, из-за которого она у соседа зеленела.
axis_unmet() {
    unmet_reasons+=("ось ${AXIS_NAME[$1 - 1]}: $2")
    echo "  $MARK (не находка): ось ${AXIS_NAME[$1 - 1]} НЕ ИСПОЛНЯЛАСЬ — $2" >&2
    echo "  вердикта об этой оси НЕТ — ни зелёного, ни красного" >&2
}
# ── Фикстура ────────────────────────────────────────────────────────────────

work="$(mktemp -d)" || { echo "install-inject: НЕ ИСПОЛНЯЛОСЬ — нет временного каталога" >&2; exit 2; }
trap 'rm -rf "$work"' EXIT

# Предпосылка фикстуры, проверяемая, а не подразумеваемая.
# Спрашивается ФИЗИЧЕСКИЙ путь: подъём по `dirname` идёт по тексту, и TMPDIR,
# заданный символьной ссылкой внутрь репозитория, прошёл бы молча. Дыра была
# общей у обеих проб и у хука — форму копировали вместе с нею.
probe_dir="$(cd "$work" 2>/dev/null && pwd -P)"
[ -n "$probe_dir" ] || { echo "install-inject: НЕ ИСПОЛНЯЛОСЬ — физический путь временного каталога не установлен: $work" >&2; exit 2; }
while :; do
    if [ -e "$probe_dir/.git" ]; then
        echo "install-inject: НЕ ИСПОЛНЯЛОСЬ — временный каталог лежит внутри репозитория ($probe_dir/.git)." >&2
        echo "  Фикстура получила бы при обходе вверх ЧУЖОЙ индекс, и опыт судил бы не свой предмет." >&2
        echo "  Назовите TMPDIR вне всякого репозитория." >&2
        exit 2
    fi
    parent="$(dirname "$probe_dir")"
    [ "$parent" != "$probe_dir" ] || break
    probe_dir="$parent"
done

# new_clone <каталог> — синтетическая рабочая копия с отслеживаемым хуком
# `scripts/hooks/pre-push` и своим удалённым назначением.
#
# Адресат ПОДСТАВНОЙ и устроен так, что его исполнение НАБЛЮДАЕМО: он оставляет
# файл-отметку. Без отметки «переходник дошёл» доказывалось бы кодом 0, который
# в точности и означал прежний молчаливый пропуск.
new_clone() {
    local d="$1"
    mkdir -p "$d/scripts/hooks" || return 1
    cat > "$d/scripts/hooks/pre-push" <<'STAND'
#!/usr/bin/env bash
set -uo pipefail
top="$(git rev-parse --show-toplevel)"
cat > "$top/.stand-in-stdin"
printf 'исполнен\n' > "$top/.stand-in-ran"
exit "${STAND_IN_RC:-0}"
STAND
    chmod +x "$d/scripts/hooks/pre-push"
    printf 'модуль опыта\n' > "$d/README"
    git -C "$d" init -q . || return 1
    git -C "$d" -c user.email=probe@example.invalid -c user.name=probe add -A || return 1
    git -C "$d" -c user.email=probe@example.invalid -c user.name=probe commit -q -m "фикстура опыта" || return 1
    git init --bare -q "$d.git" || return 1
    git -C "$d" remote add origin "$d.git" || return 1
}

# push_probe <каталог> — отправка в своё назначение; печатает код возврата.
push_probe() {
    local d="$1" out rc
    out="$(git -C "$d" push origin HEAD:refs/heads/probe-$RANDOM 2>&1)"
    rc=$?
    printf '%s\n' "$out"
    return "$rc"
}

echo "── ось 1: БОЕВОЙ АДРЕСАТ СУЩЕСТВУЕТ И ОТСЛЕЖИВАЕТСЯ (спрашиваем индекс, не диск)"
current_axis=1
tracked="$(git -C "$ROOT" ls-files -s scripts/hooks/pre-push)"
if [ -z "$tracked" ]; then
    bad "scripts/hooks/pre-push не отслеживается: переходник поедет в клоны к адресату, которого нет"
else
    ok "scripts/hooks/pre-push отслеживается: $tracked"
    case "$tracked" in
        100755\ *) ok "он отслеживается ИСПОЛНЯЕМЫМ — иначе переходник не позвал бы его и у свежего клона" ;;
        *) bad "он отслеживается НЕ исполняемым: свежий клон получил бы адресата, которого переходник не позовёт" ;;
    esac
fi
axis_done 1

echo "── ось 2: ПЕРЕХОДНИК ДОХОДИТ ДО АДРЕСАТА И ПРОПУСКАЕТ ЗЕЛЁНУЮ ОТПРАВКУ"
current_axis=2
c="$work/reach"
if ! new_clone "$c"; then
    axis_unmet 2 "фикстура не собрана"
else
    # install.sh берёт корень у git, поэтому зовётся ИЗ фикстуры — и только оттуда:
    # тот же вызов из этого клона писал бы в ЕГО служебный каталог.
    ( cd "$c" && bash "$INSTALL" install ) > "$c/.install.log" 2>&1
    if [ ! -x "$c/.git/hooks/pre-push" ]; then
        bad "переходник не положен либо не исполняемый — git его не позовёт"
    else
        ok "переходник положен и исполняемый"
        if out="$(push_probe "$c")"; then
            ok "отправка при зелёном адресате ПРОШЛА (код 0)"
        else
            bad "отправка при зелёном адресате отказала: $out"
        fi
        if [ -f "$c/.stand-in-ran" ]; then
            ok "адресат ИСПОЛНЕН — отметка на месте (код 0 сам по себе этого не доказывает)"
        else
            bad "адресат НЕ исполнялся, а отправка прошла — это ровно прежний молчаливый пропуск"
        fi
        if [ -s "$c/.stand-in-stdin" ]; then
            ok "переходник передал адресату вход git: $(wc -l < "$c/.stand-in-stdin") строк(и) ссылок"
        else
            bad "адресат получил пустой вход — «что уезжает» ему не досталось"
        fi
        claim "переходник доходит до адресата и передаёт ему вход git"
    fi
    axis_done 2
fi

echo "── ось 3: ИНЪЕКЦИЯ — АДРЕСАТА НЕТ, ОТПРАВКА ОБЯЗАНА ОТКАЗАТЬ"
current_axis=3
c="$work/gone"
if ! new_clone "$c"; then
    axis_unmet 3 "фикстура не собрана"
else
    ( cd "$c" && bash "$INSTALL" install ) > "$c/.install.log" 2>&1
    rm -f "$c/scripts/hooks/pre-push"
    if out="$(push_probe "$c")"; then
        bad "адресата НЕТ, а отправка ПРОШЛА — молчаливый пропуск жив: $out"
    else
        ok "адресата нет — отправка ОТКАЗАНА"
        # Текст отказа — часть свойства: находка обязана называть ПРИЧИНУ.
        if printf '%s' "$out" | grep -q 'проверок НЕ БЫЛО'; then
            ok "отказ называет причину: проверок не было"
        else
            bad "отказ не называет причину — читателю останется гадать: $out"
        fi
        if printf '%s' "$out" | grep -q 'scripts/hooks/pre-push'; then
            ok "отказ называет КООРДИНАТУ ненайденного адресата"
        else
            bad "отказ не называет координату адресата: $out"
        fi
        if printf '%s' "$out" | grep -q -- '--no-verify'; then
            ok "отказ называет законный выход — явный обход"
        else
            bad "отказ не называет законного выхода: человек обойдёт его непредсказуемо"
        fi
    fi
    if [ -f "$c/.stand-in-ran" ]; then
        bad "отметка адресата появилась при снятом адресате — опыт судит не свой предмет"
    else
        ok "отметки адресата нет — отказ пришёл именно от переходника"
    fi
    # Фикстура провязана установкой ИЗ СЕБЯ, то есть провязку заявила: отказ
    # доказан для этой копии, и шире её свойство здесь не заявляется.
    claim "копия, заявившая провязку, без адресата ОТКАЗЫВАЕТ и называет причину, адресата и законный выход"
    axis_done 3
fi

echo "── ось 4: ИНЪЕКЦИЯ — КРАСНЫЙ АДРЕСАТ РОНЯЕТ ОТПРАВКУ (переходник не глотает код)"
current_axis=4
c="$work/red"
if ! new_clone "$c"; then
    axis_unmet 4 "фикстура не собрана"
else
    ( cd "$c" && bash "$INSTALL" install ) > "$c/.install.log" 2>&1
    if out="$(STAND_IN_RC=1 push_probe "$c")"; then
        bad "адресат отказал кодом 1, а отправка ПРОШЛА — переходник теряет код возврата: $out"
    else
        ok "код отказа адресата доехал до git — отправка остановлена"
    fi
    axis_done 4
fi

echo "── ось 5: ПЕРЕХОДНИК ПРЕЖНЕЙ РЕДАКЦИИ ЧИСЛИТСЯ НЕПРОВЯЗАННЫМ"
current_axis=5
c="$work/stale"
if ! new_clone "$c"; then
    axis_unmet 5 "фикстура не собрана"
else
    # Дефект вносится в той самой форме, в какой он живёт в клонах СЕГОДНЯ:
    # наш маркер, прежний номер, выход нулём на ненайденном адресате.
    cat > "$c/.git/hooks/pre-push" <<'V1'
#!/usr/bin/env bash
# СГЕНЕРИРОВАН `make install-hooks` — правится НЕ здесь, а в scripts/hooks/pre-push.
# kaname-hook-stub v1
set -uo pipefail
top="$(git rev-parse --show-toplevel 2>/dev/null)" || top=""
[ -n "$top" ] || top="$PWD"
real="$top/scripts/hooks/pre-push"
if [ ! -x "$real" ]; then
    echo "pre-push: в этой рабочей копии нет $real — проверок НЕ БЫЛО" >&2
    exit 0
fi
exec "$real" "$@"
V1
    chmod +x "$c/.git/hooks/pre-push"
    if out="$( cd "$c" && bash "$INSTALL" check 2>&1 )"; then
        bad "переходник v1 принят за провязанный — починка не доедет до существующих клонов"
    else
        ok "переходник v1 объявлен непровязанным"
        if printf '%s' "$out" | grep -q 'прежней редакции'; then
            ok "причина названа отдельно от «нет файла» и «занято чужим»"
        else
            bad "причина не названа — читатель не отличит устаревший переходник от отсутствующего: $out"
        fi
    fi
    ( cd "$c" && bash "$INSTALL" install ) > "$c/.install2.log" 2>&1
    # Редакция берётся у ПРОИЗВОДИТЕЛЯ, а не выписывается литералом: литерал
    # устаревал бы при каждой смене редакции и судил бы прошлую.
    current_marker="$(bash "$INSTALL" stub pre-push 2>/dev/null | sed -n 's/^# \(kaname-hook-stub v[0-9][0-9]*\)$/\1/p')"
    if [ -n "$current_marker" ] && grep -qx "# $current_marker" "$c/.git/hooks/pre-push"; then
        ok "установка ПЕРЕПИСАЛА устаревший переходник"
    else
        bad "устаревший переходник пережил установку"
    fi
    # Законный близнец: после перезаписи `check` обязан МОЛЧАТЬ.
    if ( cd "$c" && bash "$INSTALL" check ) > /dev/null 2>&1; then
        ok "законный близнец: провязанный клон проходит check молча"
    else
        bad "провязанный клон не проходит check — проверка краснеет на своём же исходе"
    fi
    axis_done 5
fi

echo "── ось 5а: СВЕЖИЙ КЛОН — ТРЕТИЙ ИСХОД МЕТКОЙ, ЧУЖОЙ ФАЙЛ — НАХОДКА БЕЗ МЕТКИ"
current_axis=6
#
# Ось нужна потому, что гейт самостоятельного клона этот путь НЕ ПРОХОДИТ:
# он зовёт цели в порядке объявления, `install-hooks` стоит раньше `check-hooks`
# и создаёт ей предпосылку. Значит у метки третьего исхода там читателя нет, и
# держателем ей служит эта ось, а не соседство целей в чужой фикстуре.
c="$work/mark"
if ! new_clone "$c"; then
    axis_unmet 6 "фикстура не собрана"
else
    out="$( cd "$c" && bash "$INSTALL" check 2>&1 )"
    rc=$?
    if [ "$rc" -ne 0 ]; then ok "свежий клон: check отказывает (для человека это отказ)"
    else bad "свежий клон: check прошёл — непровязанность стала невидимой"; fi
    if printf '%s\n' "$out" | grep -qE '^[[:space:]]*УСЛОВИЕ НЕ СОЗДАНО'; then
        ok "свежий клон: метка третьего исхода стоит ПЕРВОЙ на своей строке — гейт её прочтёт"
    else
        bad "свежий клон: метки третьего исхода нет — цель попадёт в находки гейта: $out"
    fi
    # ЗАКОННЫЙ БЛИЗНЕЦ ТОЙ ЖЕ ФОРМЫ: состояние, которого свежий клон не
    # производит, метки получать НЕ ДОЛЖНО — иначе гейт перестал бы уметь найти
    # здесь хоть что-нибудь.
    printf '#!/bin/sh\nexit 0\n' > "$c/.git/hooks/pre-push"; chmod +x "$c/.git/hooks/pre-push"
    out="$( cd "$c" && bash "$INSTALL" check 2>&1 )"
    if printf '%s\n' "$out" | grep -qE '^[[:space:]]*УСЛОВИЕ НЕ СОЗДАНО'; then
        bad "чужой файл получил метку третьего исхода — находка стала невидимой"
    else
        ok "чужой файл метки НЕ получает — остаётся находкой"
    fi
    axis_done 6
fi

echo "── ось 6: ЧУЖОЙ ФАЙЛ ПОД ИМЕНЕМ ХУКА НЕ ЗАТИРАЕТСЯ"
current_axis=7
c="$work/foreign"
if ! new_clone "$c"; then
    axis_unmet 7 "фикстура не собрана"
else
    printf '#!/bin/sh\n# чужой хук, заведённый осознанно\nexit 0\n' > "$c/.git/hooks/pre-push"
    chmod +x "$c/.git/hooks/pre-push"
    before="$(sha256sum "$c/.git/hooks/pre-push" | cut -d' ' -f1)"
    if ( cd "$c" && bash "$INSTALL" install ) > /dev/null 2>&1; then
        bad "установка прошла поверх чужого файла — осознанно заведённый хук пропал бы молча"
    else
        ok "установка ОТКАЗАЛА, встретив чужой файл"
    fi
    after="$(sha256sum "$c/.git/hooks/pre-push" | cut -d' ' -f1)"
    if [ "$before" = "$after" ]; then
        ok "чужой файл не тронут (sha256 совпал)"
    else
        bad "чужой файл изменён — лекарство от молчаливого пропуска само что-то выключило"
    fi
    axis_done 7
fi

echo "── ось 7: ПУСТОЙ ОБХОД — ОТКАЗ, А НЕ «НЕЧЕГО ДЕЛАТЬ»"
current_axis=8
c="$work/empty"
mkdir -p "$c" && printf 'без хуков\n' > "$c/README"
git -C "$c" init -q . >/dev/null 2>&1
git -C "$c" -c user.email=probe@example.invalid -c user.name=probe add -A >/dev/null 2>&1
git -C "$c" -c user.email=probe@example.invalid -c user.name=probe commit -q -m "дерево без хуков" >/dev/null 2>&1
if out="$( cd "$c" && bash "$INSTALL" install 2>&1 )"; then
    bad "дерево без отслеживаемых хуков дало ЗЕЛЁНУЮ установку — «провязано 0» неотличимо от работы"
else
    ok "дерево без отслеживаемых хуков — отказ"
    if printf '%s' "$out" | grep -q 'НИ ОДНОГО отслеживаемого хука'; then
        ok "отказ называет предмет: обход пуст"
    else
        bad "отказ не называет предмет пустого обхода: $out"
    fi
fi
axis_done 8

echo "── ось 8: НАСТРОЙКА, ПЕРЕБИВАЮЩАЯ .git/hooks, ОСТАНАВЛИВАЕТ УСТАНОВКУ"
current_axis=9
c="$work/hookspath"
if ! new_clone "$c"; then
    axis_unmet 9 "фикстура не собрана"
else
    git -C "$c" config core.hooksPath scripts/hooks
    if out="$( cd "$c" && bash "$INSTALL" install 2>&1 )"; then
        bad "установка объявила «провязано» туда, куда git не заглядывает"
    else
        ok "установка остановлена: переходники легли бы мимо взгляда git"
    fi
    axis_done 9
fi

echo "── ось 9: ТЕКСТ ПЕРЕХОДНИКА ИМЕЕТ ОДНОГО ПРОИЗВОДИТЕЛЯ"
current_axis=10
gen="$(bash "$INSTALL" stub pre-push 2>/dev/null)"
if [ -z "$gen" ]; then
    bad "генератор не отдал текст переходника — опыт выше сверял бы копию, а не производимое"
else
    ok "текст переходника берётся у генератора (режим stub), копии в пробе нет"
    if printf '%s' "$gen" | grep -q 'exit 1'; then
        ok "производимый переходник отказывает ненулём"
    else
        bad "производимый переходник не отказывает — ось 3 доказывала бы что-то другое"
    fi
fi
axis_done 10

echo "── ось 10: ОБЩИЙ КАТАЛОГ ХУКОВ — ПРОВЯЗКА ОДНОЙ КОПИИ НЕ ОСТАНАВЛИВАЕТ СОСЕДНЮЮ"
current_axis=11
#
# git ищет хуки в <общий каталог>/hooks — ОДНОМ на все рабочие копии клона.
# Провязка из одной копии кладёт переходник каждой соседней, и переходник v2
# отказывал во всякой копии, чьё дерево адресата не несёт: коммит полосы,
# открытой до хука, останавливала провязка, которой полоса не делала
# (воспроизведено на сборке 412: копий в клоне 104, без commit-msg 102).
#
# Фикстура повторяет ту форму: копия «shared» несёт pre-push и commit-msg и
# провязана; соседняя «shared-old» стоит на ревизии, где commit-msg ещё нет.
# Законный близнец — ТА ЖЕ ревизия в копии, заявившей провязку: там отсутствие
# адресата остаётся отказом. Разница ровно в одном факте — заявлении копии.
c="$work/shared"
o="$work/shared-old"
G=(-c user.email=probe@example.invalid -c user.name=probe)
if ! new_clone "$c"; then
    axis_unmet 11 "фикстура не собрана"
else
    base="$(git -C "$c" rev-parse HEAD)"
    cat > "$c/scripts/hooks/commit-msg" <<'STAND'
#!/usr/bin/env bash
set -uo pipefail
top="$(git rev-parse --show-toplevel)"
printf 'исполнен\n' > "$top/.stand-in-commit-ran"
exit 0
STAND
    chmod +x "$c/scripts/hooks/commit-msg"
    if ! git -C "$c" "${G[@]}" add scripts/hooks/commit-msg ||
       ! git -C "$c" "${G[@]}" commit -q -m "хук коммита" ||
       ! git -C "$c" worktree add -q --detach "$o" "$base"; then
        axis_unmet 11 "соседняя копия не собрана"
    else
        ( cd "$c" && bash "$INSTALL" install ) > "$c/.install.log" 2>&1
        out="$(git -C "$o" "${G[@]}" commit -q --allow-empty -m "работа полосы" 2>&1)"
        rc=$?
        if [ "$rc" -eq 0 ]; then
            ok "соседняя копия без commit-msg КОММИТИТ: чужая провязка её не останавливает"
        else
            bad "соседняя копия без commit-msg не коммитит (код $rc) — провязка одной копии остановила другую: $out"
        fi
        if printf '%s' "$out" | grep -q 'проверок НЕ БЫЛО'; then
            ok "проход соседней копии НАЗВАН: проверок не было — это не зелёное"
        else
            bad "соседняя копия прошла молча либо без переходника — третий исход не назван: $out"
        fi
        claim "копия, провязки не заявлявшая, без адресата ПРОПУСКАЕТ действие и называет, что проверок НЕ БЫЛО"
        out="$( cd "$o" && bash "$INSTALL" check 2>&1 )"
        rc=$?
        if [ "$rc" -ne 0 ] && printf '%s\n' "$out" | grep -qE '^[[:space:]]*УСЛОВИЕ НЕ СОЗДАНО'; then
            ok "check в соседней копии не объявляет её провязанной — метка третьего исхода на месте"
        else
            bad "check в соседней копии (код $rc) объявил провязку, которой копия не заявляла: $out"
        fi
        if out="$(push_probe "$o")" && [ -f "$o/.stand-in-ran" ]; then
            ok "адресат, который соседняя копия НЕСЁТ, исполнен — её проверки не выключены"
        else
            bad "pre-push соседней копии не исполнен — лекарство выключило чужие проверки: $out"
        fi
        git -C "$c" checkout -q --detach "$base"
        out="$(git -C "$c" "${G[@]}" commit -q --allow-empty -m "копия заявила провязку" 2>&1)"
        rc=$?
        if [ "$rc" -ne 0 ] && printf '%s' "$out" | grep -q 'scripts/hooks/commit-msg'; then
            ok "законный близнец: копия, ЗАЯВИВШАЯ провязку, на той же ревизии отказывает и называет адресата"
        else
            bad "копия, заявившая провязку, без адресата не отказала (код $rc) — отказ на ненайденном адресате потерян: $out"
        fi
    fi
    axis_done 11
fi

echo "── ось 11: ИТОГОВАЯ СТРОКА — СОСТАВ УСТАНОВЛЕННОГО, ЛИТЕРАЛ ШИРЕ НЕГО — ОТКАЗ"
current_axis=12
#
# Судья итоговой строки (`judge_verdict`) исполняется внешней ступенью, и его
# собственная способность отказать доказывается здесь, на выводе той формы,
# какую даёт внутренняя ступень. Вход — свойства, заявленные осями ЭТОГО
# прогона; дефект — дословно та строка, что стояла в конце файла до этой правки.
if [ "${#claims[@]}" -eq 0 ]; then
    axis_unmet 12 "ни одна ось не заявила свойства — судить итоговую строку не по чему"
else
    v="$work/verdict"; mkdir -p "$v"
    for f in wide twin empty; do printf '=== install-inject: перепись ===\n' > "$v/$f"; done
    for x in "${claims[@]}"; do printf 'установлено: %s\n' "$x" >> "$v/wide"; printf 'установлено: %s\n' "$x" >> "$v/twin"; done
    echo "ЗЕЛЁНОЕ: переходник доходит до адресата, а без адресата ОТКАЗЫВАЕТ." >> "$v/wide"
    compose_verdict "${claims[@]}" >> "$v/twin"
    compose_verdict "${claims[@]}" >> "$v/empty"
    out="$(judge_verdict "$v/wide" 2>&1)"; rc=$?
    if [ "$rc" -eq 1 ]; then ok "литерал «без адресата ОТКАЗЫВАЕТ» на месте состава — ОТКАЗ (код 1)"
    else bad "безусловная строка «без адресата ОТКАЗЫВАЕТ» принята судьёй (код $rc): $out"; fi
    if printf '%s' "$out" | grep -qF "установлено: $(compose_verdict "${claims[@]}")"; then
        ok "отказ называет, что установлено на деле, — не только «не совпало»"
    else
        bad "отказ судьи не называет установленного — читателю останется гадать: $out"
    fi
    if out="$(judge_verdict "$v/twin" 2>&1)"; then ok "законный близнец: строка-состав проходит суд"
    else bad "строка-состав не проходит суд — судья краснеет на своём же производителе: $out"; fi
    out="$(judge_verdict "$v/empty" 2>&1)"; rc=$?
    if [ "$rc" -eq 2 ]; then ok "ноль установленного — не вердикт (код 2), даже при строке «ЗЕЛЁНОЕ»"
    else bad "ноль установленного судья счёл вердиктом (код $rc): $out"; fi
    axis_done 12
fi

echo
echo "=== install-inject: перепись ==="
echo "осей объявлено        : $AXES_DECLARED"
echo "осей ИСПОЛНЕНО        : $axes_executed"
echo "условие не создано    : ${#unmet_reasons[@]}  (в зачёт прохода НЕ идёт)"
for r in ${unmet_reasons[@]+"${unmet_reasons[@]}"}; do echo "  предпосылка не создана: $r"; done
echo "утверждений объявлено : $expected_checks  (по ведомости ИСПОЛНЕННЫХ осей)"
echo "утверждений исполнено : $checks"
echo "из них не сошлось     : $failed"
echo "утверждений вне осей  : $orphan_checks  (ведомости не приписаны)"
for m in ${axis_short[@]+"${axis_short[@]}"}; do echo "  объём разошёлся     : $m"; done
echo "свойств заявлено осями: ${#claims[@]}  (итоговая строка — их состав; судит внешняя ступень)"
for x in ${claims[@]+"${claims[@]}"}; do echo "установлено: $x"; done

# ПОРЯДОК ИСХОДОВ. Сперва беспредметность, потом находка, потом неисполнение:
# несошедшееся утверждение — вердикт о предмете, и он старше молчания. Он же
# старше расхождения чисел: упавшая ось законно исполняет меньше утверждений,
# чем объявлено, и красное обязано называться красным, а не расхождением.
if [ "$checks" -eq 0 ]; then
    echo "БЕСПРЕДМЕТНО: не исполнено ни одного утверждения — это не зелёное." >&2
    exit 2
fi
if [ "$failed" -gt 0 ]; then
    echo "ОТКАЗ: провязка хука не обладает заявленными свойствами." >&2
    exit 1
fi
if [ "${#unmet_reasons[@]}" -gt 0 ]; then
    echo "НЕ ИСПОЛНЯЛОСЬ: осей ${#unmet_reasons[@]} из $AXES_DECLARED без созданной предпосылки." >&2
    echo "  Это не зелёное и не красное: о свойстве целиком вердикта НЕТ." >&2
    exit 2
fi
if [ "$axes_executed" -ne "$AXES_DECLARED" ]; then
    echo "НЕ ИСПОЛНЯЛОСЬ: объявлено осей $AXES_DECLARED, исполнено $axes_executed, а причины не названо." >&2
    echo "  Расхождение без предпосылки — дефект самой пробы, а не исход предмета." >&2
    exit 2
fi
if [ "${#axis_short[@]}" -gt 0 ]; then
    echo "НЕ ИСПОЛНЯЛОСЬ: у осей ${#axis_short[@]} объём разошёлся с объявленным:" >&2
    for m in ${axis_short[@]+"${axis_short[@]}"}; do echo "  $m" >&2; done
    echo "  СУММА при этом могла сойтись: покрытие, ушедшее из одной оси, не возмещается" >&2
    echo "  прибавкой в другой. Потому объём спрашивается у КАЖДОЙ оси, а не у прогона." >&2
    exit 2
fi
if [ "$orphan_checks" -gt 0 ]; then
    echo "НЕ ИСПОЛНЯЛОСЬ: утверждений вне осей $orphan_checks — их некому требовать." >&2
    echo "  Утверждение, не приписанное ни одной оси, выпадает из ведомости молча." >&2
    exit 2
fi
if [ "$checks" -ne "$expected_checks" ]; then
    echo "НЕ ИСПОЛНЯЛОСЬ: ведомость ждала утверждений $expected_checks, исполнено $checks." >&2
    echo "  Утверждение, пропавшее или прибавившееся молча, — дефект самой пробы: её объём" >&2
    echo "  перестал совпадать с объявленным, и «отказов 0» больше не о том же предмете." >&2
    exit 2
fi
if [ "${#claims[@]}" -eq 0 ]; then
    echo "НЕ ИСПОЛНЯЛОСЬ: ни одна ось не заявила свойства — итоговой строке нечего сказать." >&2
    exit 2
fi
# Итоговая строка — ТОЛЬКО состав заявленного осями; второго её написания нет.
compose_verdict "${claims[@]}"
