# test-standalone.sh — ПРОБЫ МОДУЛЯ У АРЕНДАТОРА, с переписью обеих величин.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПРЕДМЕТ
#
# Часть проб модуля судит ДЕРЕВО: манифесты соседних модулей платформы, каталог
# контрактов, зонтичный чарт стенда, историю дерева. В поставку модуля это не
# входит BY CONSTRUCTION, поэтому у арендатора такие пробы не «красные» — у них
# НЕ СОЗДАНО УСЛОВИЕ. Предпосылку назначает дерево (`internal/treeposture`), а не
# сама проба, и в монорепо ветвь пропуска недостижима.
#
# «Не выполнилось» — третий исход: он не вычитается из вердикта и не зачитывается
# в успех. Значит его надо ПЕЧАТАТЬ ЧИСЛОМ, иначе зелёный прогон у арендатора
# неотличим от прогона, который ничего не спрашивал.
#
# ─────────────────────────────────────────────────────────────────────────────
# ИСХОДЫ
#
#   0 — пробы исполнены, отказов нет (пропущенные названы числом);
#   1 — есть упавшие пробы;
#   2 — позван неверно либо инструмента нет;
#   3 — обход беспредметен: не исполнено НИ ОДНОГО пакета.
set -uo pipefail

command -v go >/dev/null 2>&1 || {
    echo "НЕ ВЫПОЛНИЛОСЬ: инструмента нет — go не найден" >&2; exit 2; }

ARGS=("$@")
[ ${#ARGS[@]} -eq 0 ] && ARGS=(-short)

log="$(mktemp)"
trap 'rm -f "$log"' EXIT

echo "пробы модуля: go test ./... ${ARGS[*]} -count=1 -json"
go test ./... "${ARGS[@]}" -count=1 -json > "$log" 2>&1
rc=$?

# Перепись читается из машинного вывода, а не из вида текста: `--- SKIP`
# печатается только под `-v`, и без него «пропущено» было бы невидимо — то есть
# ровно та величина, ради которой скрипт написан.
python3 - "$log" <<'PY'
import json,sys,collections

# МЕТКА ТРЕТЬЕГО ИСХОДА. Пропуски бывают двух РАЗНЫХ родов, и складывать их
# нельзя: `-short` пропускает интеграцию по флагу самого прогона (это выбор
# запускающего), а `internal/testsupport/platformtree` — по НЕПОСТРОЕННОЙ
# ПРЕДПОСЫЛКЕ (дерева платформы рядом нет). Одно число на оба означало бы
# «пропущено по непостроенной предпосылке» там, где таких единицы.
#
# Различает МЕТКА, а не догадка. Контракт между пробой и переписью — ТЕКСТ метки,
# и производителей у неё столько, сколько родов условия: `platformtree.third`
# называет предпосылку «дерева платформы рядом нет», остальные — СВОЮ (нет
# каталога процессов над файлом; временный каталог лежит внутри дерева; резолв
# отдал ту же копию). Требовать ОДНОГО производителя значило бы требовать одной
# предпосылки.
#
# ЧИСЛО ПРОИЗВОДИТЕЛЕЙ ЗДЕСЬ НЕ НАЗЫВАЕТСЯ, и это решение, а не пропуск
# (задача #53). Оно уже дважды разошлось с деревом молча: прежняя редакция
# утверждала «её печатает РОВНО ОДНА функция» и была неверна в день записи,
# следующая назвала шесть и к своей задаче давала вдвое больше. Довод абзаца
# стоит и без величины — контракт есть ТЕКСТ метки, — а у величины нет
# производителя: её неверность ничего не роняет, поэтому она и стареет.
#
# Вдобавок у неё нет однозначной ЕДИНИЦЫ СЧЁТА. Метку печатает и пропуск
# (`t.Skip`), и журнал (`t.Logf`), и отказ (`require.Truef`), и функция,
# возвращающая её текст вызывающему, — величины разные, и любое одно число
# читалось бы как утверждение обо всех. Нужен счёт — считай его предикатом,
# назвав единицу рядом, а не сверяйся с числом в прозе.
#
# Отсюда единственное, что обязано держаться: ВТОРОЙ РЕДАКЦИИ ТЕКСТА не бывает.
# Пропуск с другим написанием попадёт в «по флагам прогона» — то есть ровно та
# величина, ради которой скрипт написан, тихо занизится.
MARK = "УСЛОВИЕ НЕ СОЗДАНО"

pkgs=collections.defaultdict(dict)
out=collections.defaultdict(list)
unmet=[]; other=0; failed=[]
for line in open(sys.argv[1],encoding='utf-8',errors='replace'):
    line=line.strip()
    if not line.startswith('{'): continue
    try: e=json.loads(line)
    except Exception: continue
    a=e.get('Action'); p=e.get('Package'); test=e.get('Test')
    if not p: continue
    if test:
        if a=='output': out[(p,test)].append(e.get('Output',''))
        elif a=='skip':
            if MARK in ''.join(out[(p,test)]): unmet.append(p+' '+test)
            else: other+=1
            out.pop((p,test), None)
        elif a=='fail':
            failed.append(p+' '+test); out.pop((p,test), None)
        elif a=='pass':
            out.pop((p,test), None)
    else:
        if a in ('pass','fail','skip'): pkgs[p]['res']=a
ran=sum(1 for v in pkgs.values() if v.get('res')=='pass')
bad=sum(1 for v in pkgs.values() if v.get('res')=='fail')
nofiles=sum(1 for v in pkgs.values() if v.get('res')=='skip')
print()
print("перепись: пакетов исполнено %d · пакетов с отказом %d · без файлов проб %d · "
      "проб ПРОПУЩЕНО по непостроенной предпосылке %d · пропущено по флагам прогона %d · "
      "проб упало %d" % (ran, bad, nofiles, len(unmet), other, len(failed)))
if unmet:
    print("  условие не создано (дерева платформы рядом нет — в поставку оно не входит):")
    for s in unmet[:40]: print("    "+s)
    if len(unmet)>40: print("    … и ещё %d" % (len(unmet)-40))
if failed:
    print("  УПАЛИ:")
    for s in failed[:40]: print("    "+s)
if bad and not failed:
    # ОТКАЗ ПАКЕТА БЕЗ ИМЕНИ УПАВШЕЙ ПРОБЫ — вердикт НЕДЕЙСТВИТЕЛЕН, а не красный.
    #
    # Пакет отказал, а ни одна проба в нём не упала: значит он не собрался или
    # не слинковался, и о его пробах не сказано ничего. Самая частая причина —
    # ДВА ИНСТРУМЕНТА В ОДНОЙ КОМАНДЕ: `make lint` и `go test`, запущенные
    # подряд, делят кэш сборки, и прогон отдаёт МЕНЬШЕ пакетов, чем в дереве,
    # с безымянной упавшей пробой. Измерено на этом дереве: 127 пакетов вместо
    # 128, перепрогон на том же коммите дважды дал 128 и ноль отказов.
    #
    # Читать такой прогон как красный нельзя, и как зелёный тоже: он НЕ
    # ВЫПОЛНИЛСЯ. Гони пробы отдельной командой от линта и повтори.
    print("  ОТКАЗ ПАКЕТА БЕЗ ИМЕНИ ПРОБЫ (%d): вердикт НЕДЕЙСТВИТЕЛЕН, а не красный —" % bad)
    print("    пакет не собрался, и о его пробах не сказано ничего. Частая причина: линт и")
    print("    пробы в ОДНОЙ команде делят кэш сборки. Прогони пробы отдельно и повтори.")
sys.exit(0 if (ran+bad+nofiles)>0 else 3)
PY
census_rc=$?

if [ "$census_rc" = "3" ]; then
    echo "обход пуст: не исполнено ни одного пакета — вердикт беспредметен" >&2
    exit 3
fi
if [ "$rc" != "0" ]; then
    echo "ПРОБЫ УПАЛИ: см. перечень выше; полный вывод — go test ./... ${ARGS[*]} -count=1" >&2
    exit 1
fi
echo "пробы модуля зелены; пропущенное названо числом выше и в успех НЕ зачтено"
