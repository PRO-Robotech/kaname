"""Доказательство, что держатель координат СПОСОБЕН упасть и способен смолчать.

Гоняется НАСТОЯЩАЯ судящая функция (`sweep` держателя) на синтетическом дереве;
оси проверяются по одной, у каждой инъекции — законный близнец, отличающийся
ровно ОДНИМ фактом.

ФОРМЫ ЗАПИСИ ПРЕДМЕТА ПЕРЕЧИСЛЕНЫ, И ПО КАЖДОЙ ЕСТЬ ПАРА. Форма, о которой
распознаватель не знает, даёт молчание, поэтому проверяется каждая — включая ту,
которую перемер нашёл уже ПОСЛЕ первой редакции держателя: утверждение,
ПЕРЕНЕСЁННОЕ по ширине, где оборот остался на одной строке, а координата уехала
на следующую. На стволе такое место было одно из двадцати четырёх, и первая
редакция молчала на нём.

  A1 оборот проводки, координата НЕ резолвится          — находка
  A2 он же, ПЕРЕНЕСЁННЫЙ по ширине                      — находка
  A3 оборот проводки, координата резолвится             — молчание
  A4 оборот проводки, координата с приставкой дома      — молчание
  B1 образец состава, которого производитель не несёт   — находка
  B2 образец состава, который производитель несёт       — молчание
  B3 тот же чужой образец БЕЗ упоминания производителя  — молчание (чужой предмет)
  C1 координата фикстуры, файла нет, дом не назван      — находка
  C2 та же координата с приставкой дома                 — молчание
  C3 координата фикстуры, файл В ДЕРЕВЕ ЕСТЬ            — молчание
  C4 та же координата в ИСПОЛНЯЕМОЙ строке скрипта      — молчание (не утверждение)
  D  проза О КЛАССЕ, называющая координату без оборота  — молчание
  E  пустой обход                                       — отличим от чистоты
  F  собственный файл держателя                         — исключён by construction

КТО ЭТУ ПРОБУ ИСПОЛНЯЕТ: `.github/scripts/run-python-probes.py`, обходом дерева.
Проводку держит он же; одноимённый гейт проводки
`PRO-Robotech/kacho:tools/pythonprobes` — координата ДЕРЕВА ПЛАТФОРМЫ, в этом
репозитории его нет.

ШАПКА ОПИСЫВАЕТ ФОРМЫ, А НЕ ВОСПРОИЗВОДИТ ИХ, и это не стиль: первая редакция
выписала оборот проводки с подставной координатой — и держатель нашёл в ней ТРИ
находки, справедливо. Проба, чья шапка есть экземпляр запрещённого, требует
исключения себя, а исключение — место, куда невидимость вносят незамеченной.
Экземпляры живут в ТЕЛЕ, внутри синтетического дерева, где им и место.
"""

from __future__ import annotations

import pathlib
import subprocess
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import own_tree_coordinate_test as gate  # noqa: E402

FAILURES: list[str] = []
PATTERNS = ("tests/newman/scripts/*_test.py", "tests/authz-fixtures/*_test.py")


def check(name: str, ok: bool, detail: str = "") -> None:
    print(f"  {'ok  ' if ok else 'FAIL'} {name}" + ("" if ok else f": {detail}"))
    if not ok:
        FAILURES.append(f"{name}: {detail}")


def run(files: dict[str, str]):
    """Синтетическое дерево под git: состав обхода — отслеживаемое, как в бою."""
    with tempfile.TemporaryDirectory() as tmp:
        root = pathlib.Path(tmp).resolve()
        for rel, body in files.items():
            p = root / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(body, encoding="utf-8")
        for cmd in (["init", "-q"], ["add", "-A"]):
            subprocess.run(["git", "-C", str(root), *cmd], check=True,
                           capture_output=True)
        tracked = gate.tracked_set(root)
        on_disk = gate.tracked_files(root)
        return gate.sweep(on_disk, root=root, tracked=tracked, patterns=PATTERNS)


def main() -> int:
    print("ось A1 — «Проводку держит `X`», X не резолвится")
    a, a2, b, read, vol = run({"p.py": '"""Проводку держит `tools/pythonprobes`."""\n'})
    check("инъекция: находка", len(a) == 1, str(a))
    check("находка называет файл и координату",
          bool(a) and "p.py" in a[0] and "tools/pythonprobes" in a[0], str(a))

    print("ось A2 — то же утверждение, ПЕРЕНЕСЁННОЕ по ширине")
    a, *_ = run({"p.py": '"""Проводку держит\n`tools/pythonprobes`."""\n'})
    check("инъекция: находка (форма с переносом не слепа)", len(a) == 1, str(a))

    print("ось A3 — координата РЕЗОЛВИТСЯ (законный близнец)")
    a, *_ = run({"p.py": '"""Проводку держит `runner.py`."""\n', "runner.py": "x = 1\n"})
    check("контроль: молчание", not a, str(a))

    print("ось A4 — координата названа МЕЖРЕПОЗИТОРНОЙ (законный близнец)")
    a, *_ = run({"p.py": '"""Проводку держит `PRO-Robotech/kacho:tools/pythonprobes`."""\n'})
    check("контроль: молчание", not a, str(a))

    print("ось B1 — образец состава, которого производитель НЕ несёт")
    _, a2, *_ = run({"p.py": '"""run-python-probes собирает по образцу `services/*/x/*_test.py`."""\n'})
    check("инъекция: находка", len(a2) == 1, str(a2))
    check("находка называет образцы производителя",
          bool(a2) and "tests/newman/scripts/*_test.py" in a2[0], str(a2))

    print("ось B2 — образец, который производитель НЕСЁТ (законный близнец)")
    _, a2, *_ = run({"p.py": '"""run-python-probes собирает по образцу `tests/newman/scripts/*_test.py`."""\n'})
    check("контроль: молчание", not a2, str(a2))

    print("ось B3 — ЧУЖОЙ образец без упоминания производителя (законный близнец)")
    _, a2, *_ = run({"p.py": '"""Миграции находятся по образцу `785001_*.sql`."""\n'})
    check("контроль: молчание — предмет другой", not a2, str(a2))

    print("ось C1 — координата фикстуры, файла нет, дом не назван")
    _, _, b, *_ = run({"p.py": '"""Зависимость: tests/authz-fixtures/setup.sh."""\n'})
    check("инъекция: находка", len(b) == 1, str(b))
    check("хвостовая точка в имя НЕ вошла",
          bool(b) and "setup.sh —" in b[0], str(b))

    print("ось C2 — та же координата С ПРИСТАВКОЙ ДОМА (законный близнец)")
    _, _, b, *_ = run({"p.py": '"""Зависимость: PRO-Robotech/kacho:tests/authz-fixtures/setup.sh."""\n'})
    check("контроль: молчание", not b, str(b))

    print("ось C3 — координата фикстуры, файл В ДЕРЕВЕ ЕСТЬ (законный близнец)")
    _, _, b, *_ = run({"p.py": '"""Зависимость: tests/authz-fixtures/setup.sh."""\n',
                       "tests/authz-fixtures/setup.sh": "echo x\n"})
    check("контроль: молчание", not b, str(b))

    print("ось C4 — та же координата в ИСПОЛНЯЕМОЙ строке скрипта (законный близнец)")
    _, _, b, *_ = run({"r.sh": 'DECL="$ROOT/tests/authz-fixtures/setup.sh"\n'})
    check("контроль: молчание — код спрашивает путь, а не утверждает о дереве",
          not b, str(b))
    _, _, b, *_ = run({"r.sh": '# берётся tests/authz-fixtures/setup.sh\n'})
    check("инъекция: КОММЕНТАРИЙ того же скрипта — находка", len(b) == 1, str(b))

    print("ось D — проза О КЛАССЕ без оборота (законный близнец)")
    a, a2, b, *_ = run({"p.py": '"""Координата tools/pythonprobes принадлежит платформе, '
                                'и здесь её нет — об этом и речь."""\n'})
    check("контроль: молчание по всем трём осям", not (a or a2 or b),
          f"{a} {a2} {b}")

    print("ось E — пустой обход отличим от чистоты")
    a, a2, b, read, vol = run({})
    check("файлов прочитано 0, единиц 0", read == 0 and not vol, f"{read} {vol}")

    print("ось F — исключение ТОЛЬКО собственного файла, и оно не маска")
    # Шапка держателя ЦИТИРУЕТ запрещённые формы, объясняя класс, — иначе объяснить
    # его нечем. Поэтому файл исключён из обхода ПО `__file__`: списка прощённых
    # здесь нет и завести его нечем. Что исключение не глушит близнеца в ЧУЖОМ
    # файле, доказывают оси A1/B1/C1 выше — там та же форма находится.
    #
    # ОСТАТОК НАЗВАН ПРЯМО: прозу самого держателя не держит ничто, и ложь о
    # дереве, внесённая в неё, проедет молча. Снимается это не списком, а вторым
    # ЧИТАТЕЛЕМ — пробой в другом файле, судящей прозу этого; завести её здесь
    # нельзя by construction, она унаследовала бы тот же дефект.
    real_root = gate.ROOT
    tracked_files_count = len(gate.tracked_files(real_root))
    _, _, _, read, _ = gate.sweep(gate.tracked_files(real_root), root=real_root,
                                  tracked=gate.tracked_set(real_root),
                                  patterns=gate.runner_patterns())
    check("в НАСТОЯЩЕМ дереве прочитано ровно на один файл меньше отслеживаемых",
          read == tracked_files_count - 1, f"прочитано {read}, отслеживается "
          f"{tracked_files_count}")
    # Первая редакция этой оси утверждала, что КОПИЯ держателя в чужом дереве тоже
    # молчит. Это неверно и неверно ПО СУЩЕСТВУ: копия лежит по другому пути,
    # значит она не `__file__`, и судить её — правильное поведение. Исключение по
    # имени файла вместо пути и было бы той самой маской.
    own = gate.SELF.read_text(encoding="utf-8")
    a, a2, b, read, _ = run({"копия-держателя.py": own})
    check("КОПИЯ держателя по другому пути судится, а не прощается по имени",
          read == 1 and (a or a2 or b), f"read={read} {a} {a2} {b}")

    print()
    if FAILURES:
        print(f"ОТКАЗ: провалено утверждений {len(FAILURES)} из 19", file=sys.stderr)
        for x in FAILURES:
            print("  " + x, file=sys.stderr)
        return 1
    print("ЧИСТО: 19 утверждений, держатель способен упасть и способен смолчать "
          "по каждой из четырнадцати осей")
    return 0


if __name__ == "__main__":
    sys.exit(main())
