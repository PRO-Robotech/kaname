# run-failclosed.sh — СОЗДАЁТ условие, которое нужно коллекции authz-failclosed,
# гоняет её и возвращает стенд как было.
#
# ЗАЧЕМ ОН ЕСТЬ. Кейс «шлюз отказывает, когда источник вердикта недоступно» ссылался
# на этот файл в собственном комментарии, а файла не существовало нигде в дереве.
# Условие создать было нечем, поэтому кейс держали ИСКЛЮЧЕНИЕМ в гейте — то есть
# инвариант «нет ответа о правах ⇒ отказ, никогда не 200» не проверялся ни разу,
# и выглядело это как зелёная суита. Кейсу, которому нужна недоступная
# зависимость, полагается собственная волна, создающая это условие, а не
# исключение (testing.md).
#
# ЧТО ДЕЛАЕТ:
#   1. находит рабочую нагрузку источника вердикта (по имени НЕ гадает — ищет);
#   2. сворачивает её в ноль и ДОЖИДАЕТСЯ, что подов не осталось;
#   3. выжидает кэш решений шлюза (LRU, TTL 5с) — иначе ответ придёт из кэша и
#      кейс проверит кэш вместо отказа;
#   4. гоняет коллекцию, пишет out/authz-failclosed.json|.cli|.rc;
#   5. ВОЗВРАЩАЕТ прежнее число реплик и ждёт готовности, даже если прогон упал
#      (trap): следующий шаг работает на исправном стенде.
#
# ЧЕГО НЕ ДЕЛАЕТ: не прощает. Не нашли нагрузку, не свернулась, не поднялась —
# скрипт падает и отчёта не остаётся, поэтому гейт докладывает
# `authz-failclosed(no-report)` и роняет прогон. «Не смогли создать условие» —
# это открытый долг, а не зелёная суита.
#
# Запуск: cwd = services/iam/tests/newman
#   [SETUP_NS=kacho] [GW_PORT=18080] ./scripts/run-failclosed.sh

set -euo pipefail
cd "$(dirname "$0")/.."

NS="${SETUP_NS:-kacho}"
DELAY="${DELAY:-100}"
STEM="authz-failclosed"
COL="collections/${STEM}.postman_collection.json"
ENV_FILE="environments/local.postman_environment.json"

# Кэш решений слоя авторизации шлюза — LRU с TTL 5с (internal/middleware/authz.go).
# Ждём с запасом: ответ из кэша означал бы, что кейс проверил кэш, а не отказ.
CACHE_SETTLE="${FAILCLOSED_CACHE_SETTLE:-12}"
SCALE_TIMEOUT="${FAILCLOSED_SCALE_TIMEOUT:-90}"

for tool in kubectl newman jq curl python3; do
  command -v "$tool" >/dev/null 2>&1 || { echo "FATAL: '$tool' not found in PATH" >&2; exit 1; }
done
[ -f "$COL" ] || { echo "FATAL: нет коллекции $COL — запусти scripts/gen.py" >&2; exit 1; }
[ -f "$ENV_FILE" ] || { echo "FATAL: нет env $ENV_FILE — его пишет fixture-seed" >&2; exit 1; }

# ─── 0. ПРОГРЕТЬ СНИМОК ПРОВЕРОЧНЫХ КЛЮЧЕЙ КРАЯ (задача #1198) ────────────────
#
# ЗАЧЕМ. Семь списочных утверждений говорят, что отказ производит САМ СЕРВИС. До
# сервиса запрос доезжает только если край смог проверить подпись, а проверочные
# ключи наш издатель держит в ключнице — в ТОЙ ЖЕ базе, которую эта волна и
# сворачивает. Край держит снимок ключей со сроком (по умолчанию 300 с) и
# обновляет его ЛЕНИВО, поэтому ВОЗРАСТ снимка на старте волны — величина, о
# которой никто не решал: он равномерно размазан по сроку. Истёк внутри волны —
# отвечает КРАЙ, и семь утверждений зеленеют не своей полосой (замер задачи:
# примерно каждый четвёртый прогон).
#
# ЧТО ДЕЛАЕТСЯ. Возраст снимка приводится к нулю ДО сворачивания базы —
# ВЫНУЖДЕННЫМ перезапросом: предъявляется удостоверение, отличающееся от
# настоящего РОВНО ОДНИМ полем (идентификатором ключа в заголовке). Край выбирает
# ту же запись издателя, не находит такой ключ в снимке и идёт за набором, НЕ
# спрашивая срок снимка. Источник ключей сейчас исправен ⇒ набор добыт ⇒ снимок
# перезаписан, возраст 0.
#
# ПОЧЕМУ ДВАЖДЫ, С ПАУЗОЙ. У вынужденного перезапроса есть собственный
# минимальный интервал (3 с): запрос, пришедший сразу за другим таким же, набор
# перезапрашивать не станет. Первый заход мог попасть в чужой такой интервал и
# тогда снимок не тронул бы; второй, отстоящий больше чем на интервал, идёт за
# набором ГАРАНТИРОВАННО. Пауза здесь — не ожидание условия, а обход правила
# самого края, и она названа числом.
#
# ЧТО ЭТО ПРОВЕРЯЕТ ЗАОДНО. Ответ 401 на производное удостоверение означает, что
# источник ключей ОТВЕТИЛ (набор добыт, ключа в нём нет ⇒ токен негоден). Ответ
# 503 означал бы, что источник ключей уже недоступен — то есть условие волны
# создать нечем. Ровно эта развилка закрыта задачей #1194 и здесь используется
# как ПРИЗНАК, а не пересматривается.
#
# ЧЕГО НЕ ДЕЛАЕТСЯ. Срок снимка не укорачивается. Ручка читается процессом при
# СТАРТЕ, то есть менять её значит перекатывать край, а перекат пересоздаёт под —
# и проброс к нему, который держит процесс снаружи, обрывается НАВСЕГДА. Цена
# этого класса уже измерена на СОСЕДНЕЙ нагрузке (перезапуск службы в блоке
# восстановления ниже: девять коллекций остались без отчёта), и повторять её на
# крае, через который идёт вся волна, тем более незачем. Поэтому срок читается
# КАК ЕСТЬ и сверяется с бюджетом.

# Бюджет: сколько живёт снимок с момента прогрева до последнего запроса волны.
# Складывается из ожиданий этого же скрипта, а не выписывается отдельным числом.
FAILCLOSED_RUN_BUDGET="${FAILCLOSED_RUN_BUDGET:-60}"
WARM_FORCED_GAP="${FAILCLOSED_WARM_GAP:-4}"

# Адрес края берётся ТОТ ЖЕ, по которому пойдёт коллекция: прогонщик передаёт его
# через EXTRA_NEWMAN_ARGS и он перебивает значение из файла окружения. Два места
# с двумя адресами разошлись бы молча, и прогрев пришёлся бы не на тот процесс.
BASE_URL="$(
  python3 - "$ENV_FILE" <<'PY'
import json, os, re, sys
extra = os.environ.get("EXTRA_NEWMAN_ARGS", "")
m = re.search(r"--env-var\s+baseUrl=(\S+)", extra)
if m:
    print(m.group(1)); raise SystemExit
vals = {v["key"]: v.get("value", "") for v in json.load(open(sys.argv[1])).get("values", [])}
print(vals.get("baseUrl", ""))
PY
)"
[ -n "$BASE_URL" ] || { echo "FATAL: адрес края не определён (ни EXTRA_NEWMAN_ARGS, ни $ENV_FILE) — прогреть снимок ключей нечему" >&2; exit 1; }

REAL_BEARER="$(jq -r '(.values[] | select(.key=="jwtAccountAdminA") | .value) // ""' "$ENV_FILE")"
[ -n "$REAL_BEARER" ] || { echo "FATAL: в $ENV_FILE нет jwtAccountAdminA — условие волны создать нечем (посев не отработал)" >&2; exit 1; }

# Производное удостоверение: тот же издатель, тот же тип, тот же алгоритм — и
# идентификатор ключа, которого мы не публикуем. Строится ТЕМ ЖЕ способом, что и
# в кейсе полосы края, и по той же причине.
#
# Значение идентификатора здесь и в кейсе совпадает ДЛЯ ЧИТАЕМОСТИ, но совпадение
# НЕ ТРЕБУЕТСЯ: обоим нужен лишь идентификатор, которого нет в опубликованном
# наборе. Расхождение двух этих литералов ничего не ломает; а если такой ключ
# когда-нибудь начнут публиковать, обе стороны скажут об этом ГРОМКО — здесь
# прогрев получит 200 вместо 401 и откажется работать, там кейс покраснеет.
PROBE_BEARER="$(
  python3 - "$REAL_BEARER" <<'PY'
import base64, json, sys
def d(s): return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))
def e(b): return base64.urlsafe_b64encode(b).decode().rstrip("=")
parts = sys.argv[1].split(".")
if len(parts) != 3:
    sys.exit("jwtAccountAdminA не разбирается как JWT")
hdr = json.loads(d(parts[0]))
if not isinstance(hdr.get("alg"), str) or not hdr["alg"]:
    sys.exit("в заголовке jwtAccountAdminA нет alg")
hdr["kid"] = "kacho-lane-probe-no-such-key"
parts[0] = e(json.dumps(hdr, separators=(",", ":")).encode())
print(".".join(parts))
PY
)" || { echo "FATAL: производное удостоверение построить не удалось — прогрев снимка ключей невозможен" >&2; exit 1; }

# Срок снимка читается У РАЗВЁРНУТОГО КРАЯ, а не предполагается. Имя нагрузки
# ИЩЕТСЯ по той же причине, что и имя базы ниже: хардкод молча промахнулся бы
# при переименовании релиза, и скрипт «отработал бы», не создав условия.
mapfile -t GW_CANDIDATES < <(
  kubectl -n "$NS" get deploy -o jsonpath='{range .items[*]}{.metadata.name}{"\n"}{end}' 2>/dev/null \
    | grep -E '(^|-)api-gateway$' || true
)
if [ "${#GW_CANDIDATES[@]}" -ne 1 ]; then
  echo "FATAL: в namespace '$NS' ожидался ровно один Deployment края, найдено ${#GW_CANDIDATES[@]}: ${GW_CANDIDATES[*]:-(нет)}" >&2
  echo "       срок снимка проверочных ключей прочитать не у кого — условие для authz-failclosed не создано" >&2
  exit 1
fi
GW_DEPLOY="${GW_CANDIDATES[0]}"
JWKS_TTL="$(kubectl -n "$NS" get deploy "$GW_DEPLOY" \
  -o jsonpath='{.spec.template.spec.containers[0].env[?(@.name=="KACHO_JWKS_CACHE_TTL_SECONDS")].value}' 2>/dev/null || true)"
# Ручка не задана ⇒ действует умолчание процесса. Число не выдумано: оно стоит в
# объявлении настройки края — поле JWKSCacheTTLSeconds, `envconfig` того же имени,
# `default:"300"`. Разойдётся с деревом — разойдётся ГРОМКО: бюджет ниже станет
# считаться от неверной величины и волна откажется стартовать, а не тихо
# отработает не своей полосой.
[ -n "$JWKS_TTL" ] || JWKS_TTL=300
case "$JWKS_TTL" in ''|*[!0-9]*) echo "FATAL: срок снимка ключей края нечисловой: '$JWKS_TTL'" >&2; exit 1 ;; esac
NEED=$((SCALE_TIMEOUT + CACHE_SETTLE + FAILCLOSED_RUN_BUDGET))
if [ "$JWKS_TTL" -lt "$NEED" ]; then
  echo "FATAL: срок снимка проверочных ключей края ${JWKS_TTL}s меньше бюджета волны ${NEED}s" >&2
  echo "       (сворачивание ≤${SCALE_TIMEOUT}s + выжидание кэша решений ${CACHE_SETTLE}s + прогон ${FAILCLOSED_RUN_BUDGET}s)" >&2
  echo "       — снимок истечёт ВНУТРИ волны и на семь списочных утверждений ответит КРАЙ, а не сервис." >&2
  echo "       Это «условие не создано», а не красный вердикт: отчёта не будет, гейт назовёт authz-failclosed(no-report)." >&2
  exit 1
fi

probe_code() { # $1 = bearer
  curl -s -o /dev/null -w '%{http_code}' --max-time 15 \
    -H "Authorization: Bearer $1" "$BASE_URL/iam/v1/accounts" 2>/dev/null || true
  # `|| true`, а НЕ `|| echo 000`: curl печатает `%{http_code}` и на сорванном
  # соединении тоже (нулями), поэтому запасное `echo` дописало бы вторую тройку
  # нулей и превратило исход в неразбираемое `000000`.
}

echo "[failclosed] прогреваю снимок проверочных ключей края (срок ${JWKS_TTL}s, бюджет волны ${NEED}s)"
WARM1="$(probe_code "$PROBE_BEARER")"
sleep "$WARM_FORCED_GAP"
WARM2="$(probe_code "$PROBE_BEARER")"
if [ "$WARM2" != "401" ]; then
  echo "FATAL: вынужденный перезапрос набора ключей ответил $WARM2 (ожидалось 401; первый заход: $WARM1)" >&2
  echo "       401 = источник ключей ОТВЕТИЛ и снимок перезаписан; 503 = источник уже недоступен;" >&2
  echo "       иное = край не выбрал запись нашего издателя. Снимок не прогрет ⇒ условие не создано." >&2
  exit 1
fi
LIVE_CODE="$(probe_code "$REAL_BEARER")"
if [ "$LIVE_CODE" != "200" ]; then
  echo "FATAL: настоящее удостоверение ответило $LIVE_CODE (ожидалось 200) ДО сворачивания базы" >&2
  echo "       — стенд не в том состоянии, из которого эта волна создаёт своё условие." >&2
  exit 1
fi
echo "[failclosed] снимок прогрет: производное удостоверение → 401, настоящее → 200"

# ─── 0б. ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ РАЗЛИЧИТЕЛЯ ПОЛОС ─────────────────────────────
#
# ЗАЧЕМ. Кейсы коллекции — отрицания: «ответ обязан быть отказом названной
# полосы». Отрицание без положительного контроля зеленеет на всём сломанном, и
# конкретно здесь оно зеленело бы, если бы различитель залип на ответе края:
# полосу СЕРВИСА он тогда не опознал бы ни разу, а сказать об этом было бы
# некому.
#
# Контроль стоял ПЕРВЫМ ШАГОМ самой коллекции и там неисполним: под свёрнутой
# базой полоса отзыва наших токенов короткозамыкает запрос на пути
# аутентификации, и до сервиса он не доходит НИ ПРИ КАКОМ входе (разбор — в
# шапке `cases/authz-failclosed.py`). Шаг, который не может сойтись ни при каком
# входе, — красное без предмета, а не контроль. Здесь он исполним: база ещё
# жива, и это последний момент, когда ответ сервиса можно получить.
#
# ЧТО ИМЕННО ПРЕДЪЯВЛЯЕТСЯ. Тот же запрос, что стоял шагом: величина страницы
# вне допустимого диапазона (`MaxListPageSize = 1000`). Она отвергается ПЕРВЫМ
# СТЕЙТМЕНТОМ обработчика, до единого обращения к базе, поэтому ответ приходит
# ОТ СЕРВИСА и НЕ отказом доступности.
#
# ЧТО ЭТО ДОКАЗЫВАЕТ — три вещи, и все три нужны семи отрицаниям волны:
#   * запрос ДОЕЗЖАЕТ до сервиса, когда стенд исправен (значит отказ, который
#     волна увидит потом, произведён свёрнутой базой, а не вечной поломкой);
#   * ответ сервиса несёт ключ `details` — структурная предпосылка различителя
#     выполняется на ЭТОМ стенде и ЭТИМ маршаллером, а не по чтению чужого кода;
#   * различитель опознаёт полосу сервиса на исходе, отличном от 503.
#
# ЧЕГО НЕ ДЕЛАЕТСЯ: не прощается. Не сошлось — волна не стартует, отчёта нет,
# гейт называет `authz-failclosed(no-report)` и роняет прогон. «Предпосылка
# различителя не проверена» — это не зелёная суита.
ACCOUNT_A_ID="$(jq -r '(.values[] | select(.key=="accountAId") | .value) // ""' "$ENV_FILE")"
[ -n "$ACCOUNT_A_ID" ] || { echo "FATAL: в $ENV_FILE нет accountAId — положительный контроль различителя предъявить не на чем (посев не отработал)" >&2; exit 1; }

# Тело И код одним вызовом: код печатается последней строкой, тело — всё, что до
# неё. Два отдельных запроса разошлись бы по состоянию стенда между ними.
PRECOND_RAW="$(
  curl -s -w '\n%{http_code}' --max-time 15 \
    -H "Authorization: Bearer $REAL_BEARER" \
    "$BASE_URL/iam/v1/projects?accountId=${ACCOUNT_A_ID}&pageSize=99999" 2>/dev/null || true
)"
PRECOND_CODE="$(printf '%s' "$PRECOND_RAW" | tail -n1)"
PRECOND_BODY="$(printf '%s' "$PRECOND_RAW" | sed '$d')"
if [ "$PRECOND_CODE" != "400" ]; then
  echo "FATAL: положительный контроль различителя ответил $PRECOND_CODE (ожидалось 400) ДО сворачивания базы" >&2
  echo "       тело: $PRECOND_BODY" >&2
  echo "       400 = запрос доехал до СЕРВИСА и тот отверг величину страницы; 503 = до сервиса не доезжает" >&2
  echo "       уже сейчас; 200 = предел страницы перестал отвергаться, и контроль надо чинить, а не волну." >&2
  exit 1
fi
if ! printf '%s' "$PRECOND_BODY" | jq -e 'has("details") and (.details | type == "array")' >/dev/null 2>&1; then
  echo 'FATAL: в ответе СЕРВИСА нет ключа `details` — предпосылка различителя полос не выполняется' >&2
  echo "       тело: $PRECOND_BODY" >&2
  echo "       различитель отличает ответ сервиса от ответа края именно по этому ключу (его ставит" >&2
  echo "       публичный маршаллер моста gRPC↔REST, EmitUnpopulated=true). Нет ключа — вердикты о" >&2
  echo "       полосах недостоверны все разом, поэтому волна не стартует." >&2
  exit 1
fi
echo "[failclosed] различитель проверен на исправном стенде: сервис → 400 с ключом details"

# ─── 1. найти рабочую нагрузку, дающую ВЕРДИКТ ────────────────────────────────
# Предмет волны — «источник вердикта недоступен», и он пережил смену формы.
# Прежде вердикт давал внешний движок прав, и сворачивалась ЕГО нагрузка. Теперь
# вердикт вычисляет сам iam в своей базе, поэтому сворачивается iam: для края и
# сервисов это ровно то же условие — спросить некого. Утверждения кейсов не
# менялись (503 / gRPC 14, и НИКОГДА 200 с пустым списком): контракт
# fail-closed — свойство продукта, а не движка.
#
# СВОРАЧИВАЕТСЯ БАЗА СЛУЖБЫ, А НЕ САМА СЛУЖБА — и это не деталь, а разница между
# «вердикт не вычислить» и «спросить некого вообще».
#
# Первая редакция сворачивала iam целиком. Прогон показал цену: гаснет и проверка
# личности (край перестаёт получать ключи), поэтому запросы получают отказ
# личности вместо отказа доступности, а девять последующих коллекций остаются
# без отчёта — им не с кем работать. Утверждения кейсов говорят про 503 и gRPC 14,
# то есть именно про НЕДОСТУПНОСТЬ ВЕРДИКТА; их и надо создать.
#
# Свёрнутая база даёт ровно это: служба жива, личность проверяется, а решение о
# доступе вычислить не из чего.
#
# Имя ИЩЕТСЯ, а не пишется: оно зависит от имени релиза чарта, и хардкод молча
# промахнулся бы при переименовании — скрипт «отработал бы», не создав условия.
mapfile -t CANDIDATES < <(
  kubectl -n "$NS" get statefulset -o jsonpath='{range .items[*]}{.metadata.name}{"\n"}{end}' 2>/dev/null \
    | grep -E 'pg-iam$' || true
)
if [ "${#CANDIDATES[@]}" -ne 1 ]; then
  echo "FATAL: в namespace '$NS' ожидался ровно один StatefulSet базы источника вердикта, найдено ${#CANDIDATES[@]}: ${CANDIDATES[*]:-(нет)}" >&2
  echo "       условие для authz-failclosed не создано — отчёта не будет, и гейт это назовёт" >&2
  exit 1
fi
DEPLOY="${CANDIDATES[0]}"
WAS="$(kubectl -n "$NS" get statefulset "$DEPLOY" -o jsonpath='{.spec.replicas}')"
[ -n "$WAS" ] || WAS=1
echo "[failclosed] база источника вердикта: statefulset/$DEPLOY (реплик сейчас: $WAS)"

restore() {
  local rc=$?
  echo "[failclosed] возвращаю statefulset/$DEPLOY → replicas=$WAS"
  kubectl -n "$NS" scale statefulset "$DEPLOY" --replicas="$WAS" >/dev/null 2>&1 || true
  # Ждём готовности: следующий шаг прогона работает на этом же стенде, и
  # оставить его без источника вердикта значило бы обменять один честный красный на
  # каскад чужих.
  kubectl -n "$NS" rollout status statefulset/"$DEPLOY" --timeout="${SCALE_TIMEOUT}s" || {
    echo "FATAL: источник вердикта не вернулось в строй за ${SCALE_TIMEOUT}s — стенд повреждён, дальнейшие суиты недостоверны" >&2
    exit 1
  }
  # Кэш решений держит отказы ровно так же, как разрешения: без выжидания
  # следующая суита получила бы 503 из кэша уже на исправном стенде.
  sleep "$CACHE_SETTLE"

  # СЛУЖБА ТОЖЕ ОБЯЗАНА ВЕРНУТЬСЯ, а не только её база. Она проверяет посадку при
  # старте и при недоступной базе уходит в перезапуск — это верное поведение, но
  # означает, что к моменту следующей коллекции служба может быть ещё не готова.
  # Прогон, где это не дождались, дал девять коллекций БЕЗ ОТЧЁТА: им не с кем
  # было работать, и вердикта не осталось ни у одной.
  # ПЕРЕЗАПУСКАТЬ СЛУЖБУ НЕЛЬЗЯ, и это проверено прогоном. Перезапуск пересоздаёт
  # под, а проброс к нему держится процессом снаружи и обрывается НАВСЕГДА:
  # следующая волна получила `EOF` на внутреннем листенере и не довела посев —
  # девять коллекций остались без отчёта. Служба переживает недоступность базы
  # сама (пул переподключается), поэтому здесь только ДОЖИДАЕМСЯ готовности, а
  # если под всё же перезапустился сам — ждём, пока он вернётся.
  for svc in $(kubectl -n "$NS" get deploy -o jsonpath='{range .items[*]}{.metadata.name}{"\n"}{end}' 2>/dev/null \
                 | grep -E '(^|-)iam$' | grep -v -- 'ui-' | grep -v -- 'bootstrap'); do
    kubectl -n "$NS" rollout status deploy/"$svc" --timeout="${SCALE_TIMEOUT}s" || {
      echo "FATAL: служба $svc не вернулась в строй за ${SCALE_TIMEOUT}s — стенд повреждён для следующих коллекций" >&2
      exit 1
    }
  done

  # СПОСОБНОСТЬ, А НЕ ПРИСУТСТВИЕ. Проба готовности службы намеренно НЕ ходит в
  # базу — служба обязана переживать её недоступность, — поэтому `rollout status`
  # выше возвращается мгновенно: под и не перезапускался. Между «под Ready» и
  # «пул переподключился» лежит окно повторных попыток, и следующая волна
  # попадает ровно в него.
  # Цена измерена, а не предположена (прогон 32532668160): база встала за 22с до
  # начала волны церемонии, служба была Ready, но вход паролем ушёл в её хук,
  # тот не смог писать, и провайдер ответил 502 — посев не встал, ДЕВЯТЬ
  # коллекций остались без отчёта, то есть без вердикта вовсе.
  # Спрашиваем у самой базы, вернулись ли к ней соединения службы: это
  # наблюдаемое СЛЕДСТВИЕ восстановления пула, а не объявление о нём.
  echo "[failclosed] жду СПОСОБНОСТИ: соединения службы к базе"
  conn_probe() {
    kubectl -n "$NS" exec "statefulset/$DEPLOY" -c postgresql -- bash -c \
      'PGPASSWORD="$POSTGRES_PASSWORD" psql -U "$POSTGRES_USER" -d "$POSTGRES_DATABASE" -tAc \
       "SELECT count(*) FROM pg_stat_activity WHERE datname=current_database() AND pid<>pg_backend_pid()"' \
      2>/dev/null | tr -d '[:space:]'
  }
  deadline=$((SECONDS + SCALE_TIMEOUT))
  probed=0
  while :; do
    live="$(conn_probe)"
    case "$live" in ''|*[!0-9]*) : ;; *) probed=1; [ "$live" -gt 0 ] && break ;; esac
    if [ "$SECONDS" -ge "$deadline" ]; then
      if [ "$probed" -eq 0 ]; then
        echo "FATAL: опрос соединений НЕ ИСПОЛНИЛСЯ ни разу за ${SCALE_TIMEOUT}s — это отказ самой проверки, а не вердикт о стенде: следующие коллекции судить нечем" >&2
      else
        echo "FATAL: служба не вернула ни одного соединения к базе за ${SCALE_TIMEOUT}s — стенд повреждён для следующих коллекций" >&2
      fi
      exit 1
    fi
    sleep 2
  done
  echo "[failclosed] способность подтверждена: соединений службы к базе $live"
  echo "[failclosed] стенд восстановлен"
  exit "$rc"
}
trap restore EXIT

# ─── 2. свернуть в ноль и дождаться, что подов не осталось ───────────────────
echo "[failclosed] сворачиваю statefulset/$DEPLOY → replicas=0"
kubectl -n "$NS" scale statefulset "$DEPLOY" --replicas=0
deadline=$((SECONDS + SCALE_TIMEOUT))
while :; do
  live="$(kubectl -n "$NS" get statefulset "$DEPLOY" -o jsonpath='{.status.replicas}' 2>/dev/null || echo "")"
  [ -z "$live" ] && live=0
  [ "$live" -eq 0 ] && break
  if [ "$SECONDS" -ge "$deadline" ]; then
    echo "FATAL: источник вердикта не свернулось за ${SCALE_TIMEOUT}s (осталось реплик: $live) — условие не создано" >&2
    exit 1
  fi
  sleep 2
done
echo "[failclosed] реплик не осталось; жду ${CACHE_SETTLE}s (кэш решений шлюза)"
sleep "$CACHE_SETTLE"

# ─── 3. прогон ровно одной коллекции ────────────────────────────────────────
mkdir -p out
set +e
newman run "$COL" \
  -e "$ENV_FILE" \
  --delay-request "$DELAY" \
  --reporters cli,json \
  --reporter-json-export "out/${STEM}.json" \
  ${EXTRA_NEWMAN_ARGS:-} 2>&1 | tee "out/${STEM}.cli"
rc=${PIPESTATUS[0]}
set -e
echo "$rc" > "out/${STEM}.rc"

if [ "$rc" -ne 0 ]; then
  echo "[failclosed] newman вернул $rc — разбор в out/${STEM}.cli; гейт вынесет вердикт по отчёту" >&2
fi
exit "$rc"
