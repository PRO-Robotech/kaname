"""Гейт: у метки третьего исхода ОДИН производитель, и вердикт читает её у него.

ПРЕДМЕТ. «Условие не создано» и «продукт неверен» — разные вердикты, и различает
их метка в имени утверждения (`gen.py::PRECONDITION_MARK`). Метка отделяет
целый класс исходов от находок, поэтому у неё ровно два способа сломаться, и оба
тихие:

  1. КТО-ТО ЕЩЁ ЕЁ СТАВИТ. Рукописный кейс, поставивший метку себе, выводит своё
     падение из находок — вручную и без чьего-либо решения. Это ровно то
     вычитание, которое снято из вердикта целиком; вернуть его через имя
     утверждения было бы возвратом того же класса с чёрного хода;
  2. ВЕРДИКТ ВЫПИСЫВАЕТ ЕЁ ВТОРЫМ ЛИТЕРАЛОМ. Тогда это два места об одном
     предмете: они разойдутся МОЛЧА, помеченные утверждения тихо вернутся в
     находки, и дефект, ради которого метка заведена, вернётся вместе с зелёным
     гейтом;
  3. ПРОИЗВОДИТЕЛЬ ФОРМЫ ЕЁ НЕ СТАВИТ. Стражей настройки харнесса в дереве не
     один: адрес поверхности, субъект посева, производное удостоверение. Форма у
     них общая — «отказ с именем, потом пропуск», — и скопирована она была
     буквально, вместе с объяснением «identical to gen.py::require_env_url». А
     метка скопирована не была. Тогда ОДИН класс исхода приходит вердикту двумя
     категориями, и та, что крупнее, читается находкой о продукте.

     Замер, из-за которого ось заведена (#2187): стражей 2264, помечено 220,
     НЕ помечено 2044 — то есть непомеченных в девять раз больше помеченных.

ОСЬ 3 СУДИТ ПОРОЖДЁННЫЕ КОЛЛЕКЦИИ, а не исходники: стражи в дереве двух родов —
общие (`gen.py`) и рукописные, вписанные прямо в кейс. Проверка по исходникам
видела бы только первый род, а третий производитель нашёлся ровно во втором.

СТРАЖ ОБЪЯВЛЯЕТ СЕБЯ САМ. Ось отбирает утверждения по фразе `harness config:` в
ИМЕНИ — и это не догадка по слову: имя производит тот же блок, что и само
утверждение, поэтому «это настройка харнесса» здесь сказано его собственным
автором (тот же довод, которым держится сама метка). Стражи ДРУГОГО рода —
предмет шага, не созданный предыдущим шагом, — этой фразы не несут и метки нести
НЕ ДОЛЖНЫ: их отсутствующий предмет есть находка, и увести её в третью категорию
значило бы завести маску.

САМ ЭТОТ ГЕЙТ ЛИТЕРАЛА НЕ СОДЕРЖИТ — он читает его у того же производителя.
Иначе гейт единственности сам стал бы вторым местом об одном предмете, а его
собственное объяснение — находкой (проверка по подстроке краснеет на прозе о
том, что она проверяет).

ПЕРЕПИСЬ печатает объём осмотренного: «ноль находок» обязано быть отличимо от
«ноль прочитанного».

Самопроверка способности упасть — `precondition_mark_injection_test.py` (инъекция по
каждой оси с законным близнецом).

КТО ЭТУ ПРОБУ ИСПОЛНЯЕТ: `.github/scripts/run-python-probes.py`. Состав он
собирает ОБХОДОМ дерева по образцу `services/*/tests/newman/scripts/*_test.py` и
НИ ОДИН файл проб по имени не называет — поэтому отдельного шага в конвейере файл
не требует, а искать вызывающего предикатом `git grep <имя файла>` бесполезно:
вызова по имени нет ни у кого. Код возврата при этом доезжает до вердикта шага.
Проводку держит `tools/pythonprobes`.
"""

import json
import pathlib
import re
import sys

NEWMAN = pathlib.Path(__file__).resolve().parents[1]

# Присвоение константы — то, что ПРОИЗВОДИТ метку. Упоминание имени константы в
# прозе производителем не является, поэтому образец требует присвоения строки.
RE_PRODUCER = re.compile(r'^PRECONDITION_MARK\s*=\s*(["\'])(?P<mark>.+?)\1\s*$', re.M)


def read_mark(gen_path):
    """Метка и число её производителей — из ЕДИНСТВЕННОГО источника."""
    text = gen_path.read_text(encoding="utf-8")
    hits = RE_PRODUCER.findall(text)
    marks = [m for _, m in hits]
    return marks

# Страж настройки харнесса объявляет себя ФРАЗОЙ в имени утверждения — той же,
# которую пишет его производитель. Комментарий за объявление не считается:
# проверка по сырому тексту краснела бы на прозе, объясняющей эту же защиту.
GUARD_DECL = "harness config:"

# Потолок ПЕЧАТИ находок. Число находок не усекается никогда.
LIST_CAP = 10
RE_PM_TEST = re.compile(r"pm\.test\s*\(")


def audit_guards(collections_dir, mark):
    """Стражи настройки харнесса в порождённых коллекциях и их пометка.

    Возвращает список `(коллекция, шаг, помечен_ли)` и число помеченных.
    Отсутствие каталога коллекций находкой НЕ является — беспредметность
    объявляет вызывающий (`main`), иначе «не сгенерировано» стало бы
    неотличимо от «сгенерировано неверно».
    """
    guards, marked = [], 0
    if not collections_dir.is_dir():
        return guards, marked
    for path in sorted(collections_dir.glob("*.json")):
        try:
            doc = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue

        def walk(node, trail):
            nonlocal marked
            if isinstance(node, list):
                for child in node:
                    walk(child, trail)
                return
            if not isinstance(node, dict):
                return
            name = node.get("name") or trail
            for ev in node.get("event", []) or []:
                src = ev.get("script", {}).get("exec", []) or []
                if isinstance(src, str):
                    src = [src]
                for line in src:
                    if line.lstrip().startswith("//"):
                        continue
                    if not RE_PM_TEST.search(line) or GUARD_DECL not in line:
                        continue
                    hit = mark in line
                    guards.append((path.name, name, hit))
                    if hit:
                        marked += 1
            walk(node.get("item", []), name)

        walk(doc.get("item", []), path.stem)
    return guards, marked



def audit(newman_root):
    findings, census = [], {}
    gen = newman_root / "scripts" / "gen.py"
    gate = newman_root / "scripts" / "assert-suites-green.sh"
    cases_dir = newman_root / "cases"

    if not gen.is_file():
        return {}, ["производителя метки нет вовсе (scripts/gen.py) — вердикт беспредметен"]

    marks = read_mark(gen)
    census["производителей метки в gen.py"] = len(marks)
    if len(marks) != 1:
        findings.append(
            f"производителей метки {len(marks)}, а должен быть ровно один: "
            f"второе объявление разойдётся с первым молча")
        if not marks:
            return census, findings
    mark = marks[0]

    # 1. Ставит ли метку кто-то ещё. Судятся ФАЙЛЫ КЕЙСОВ: там она означала бы
    #    ручное выведение своего падения из находок.
    seen = 0
    for path in sorted(cases_dir.glob("*.py")) if cases_dir.is_dir() else []:
        seen += 1
        if mark in path.read_text(encoding="utf-8"):
            findings.append(
                f"{path.name} ставит метку третьего исхода сам: падение кейса ушло бы "
                f"из находок без чьего-либо решения — то самое вычитание, которое "
                f"снято из вердикта целиком")
    census["файлов кейсов осмотрено"] = seen

    # 3. Ставит ли метку ПРОИЗВОДИТЕЛЬ ФОРМЫ — по порождённым коллекциям.
    guards, marked = audit_guards(newman_root / "collections", mark)
    census["стражей harness config"] = len(guards)
    census["помечено"] = marked
    census["НЕ помечено"] = len(guards) - marked
    for where in guards:
        if where[2]:
            continue
        findings.append(
            f"{where[0]} :: {where[1]} — страж настройки харнесса без метки "
            f"третьего исхода: его отказ приходит вердикту находкой о продукте, "
            f"хотя условие не создал харнесс. Метку ставит производитель формы "
            f"(gen.py), а не файл кейса")

    # 2. Читает ли вердикт метку у производителя, а не выписывает.
    if not gate.is_file():
        findings.append("вердиктного гейта нет (scripts/assert-suites-green.sh) — "
                        "категорию третьего исхода читать нечем")
    else:
        gate_text = gate.read_text(encoding="utf-8")
        census["строк вердиктного гейта"] = gate_text.count("\n") + 1
        if mark in gate_text:
            findings.append(
                "вердиктный гейт выписывает метку своим литералом: два места об одном "
                "предмете разойдутся молча, и помеченное тихо вернётся в находки")
        if "gen.PRECONDITION_MARK" not in gate_text:
            findings.append(
                "вердиктный гейт не берёт метку у производителя (gen.PRECONDITION_MARK): "
                "категория третьего исхода держалась бы совпадением строк")
    return census, findings


def main():
    census, findings = audit(NEWMAN)
    print("перепись: " + " · ".join(f"{k} {v}" for k, v in census.items()))
    if census.get("файлов кейсов осмотрено", 0) == 0:
        print("ОТКАЗ: файлов кейсов не прочитано — вердикт беспредметен", file=sys.stderr)
        return 1
    if findings:
        # Перечень усекается, а ЧИСЛО — нет: находок этого класса бывают тысячи
        # (2044 на дне заведения оси 3), и полный список нечитаем — а нечитаемый
        # перечень перестают читать целиком, вместе с находкой, ради которой он.
        print(f"НАХОДКИ ({len(findings)}):", file=sys.stderr)
        for f in findings[:LIST_CAP]:
            print("  " + f, file=sys.stderr)
        if len(findings) > LIST_CAP:
            print(f"  … и ещё {len(findings) - LIST_CAP} того же вида "
                  f"(перечень усечён; число выше — полное)", file=sys.stderr)
        return 1
    print("ЧИСТО: у метки третьего исхода один производитель, кейсы её не ставят, "
          "вердикт читает её у него")
    return 0


if __name__ == "__main__":
    sys.exit(main())
