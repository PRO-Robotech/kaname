"""Гейт: кейс не ждёт статуса, которого край произвести НЕ МОЖЕТ.

ПРЕДМЕТ. Отображение кода отказа в HTTP-статус делает библиотека, а не наш код:
мультиплексор собран без своего обработчика ошибок. Значит множество
производимых статусов КОНЕЧНО и от сервиса не зависит.

Кейс, ожидающий статуса вне этого множества, не покраснеет НИКОГДА — у его
«Тогда» нет производителя. Это хуже отсутствующего кейса: слот занят, отчёт
зелёный, уверенность есть, проверки нет. Особенно коварна форма `oneOf`,
перечисляющая невозможный статус рядом с возможным: она проходит на возможном, а
невозможный переживает в тексте как объявленное намерение.

ДВА СТАТУСА НАЗВАНЫ ПОИМЁННО, потому что их ждут чаще прочих:

  * 412 — совпадение имён обманчиво: 412 про условные заголовки запроса, а
    «состояние ресурса не позволяет» есть FAILED_PRECONDITION, то есть **400**;
  * 422 — не производится ничем.

ЗДЕСЬ ТРЕТЬИМ СТОЯЛ 405, И ЕГО ОСНОВАНИЕ ИСТЕКЛО. Умолчание маршрутизатора
переводило промах глагола в UNIMPLEMENTED, то есть в 501, и 405 действительно не
производился ничем. Фронт завёл обработчик ошибок МАРШРУТИЗАЦИИ и отвечает на
промах глагола 405 — решением, а не умолчанием (задача #2493): обе внешне
досягаемые поверхности службы дают на него один статус. Значит 405 переехал из
«названных невозможными» в производимое множество, и запись, которой больше нечего
запрещать, снята вместе со своим предметом.

ПРОИЗВОДИТЕЛЕЙ ДВА, И У ВТОРОГО СВОЁ МНОЖЕСТВО. Точка авторизации поверхности
выдачи (`/iam/v1/authorize`, церемония `authorization_code`) — рукописный
обработчик, а не отображение кода отказа: она отвечает перенаправлением `302`,
которого REST-фронт не производит ничем. Поэтому `302` законен ровно в модуле,
чей шаг её адресует (`AUTHORIZE_REDIRECT`, `addresses_authorize`), и остаётся
находкой везде, где её нет.

ГРАНИЦА ГЕЙТА ОБЪЯВЛЕНА, А НЕ УМОЛЧАНА. Обходится каталог кейсов ЭТОГО набора.
Статус, порождённый ОБЩИМ слоем генератора (`tests/newman/kacholib`), сюда не
попадает — и там такой случай есть: помощник «метод не разрешён» перечисляет
полосу с 405, то есть исход, которого край не производит. Предмет чужой (его
зовут кейсы другого набора), и в чужой работе он не чинится; расширить обход на
общий слой значило бы красить свой набор чужим красным. Заведено задачей.

РАСПОЗНАВАТЕЛЬ ЗНАЕТ ТРИ ФОРМЫ, которыми кейс объявляет ожидаемый статус, и это
не полнота ради полноты: форма, ему неизвестная, даёт не красное и не зелёное, а
МОЛЧАНИЕ — всё записанное ею оказывается вне наблюдения. Перепись печатает объём
по каждой форме отдельно, чтобы прибавка распознавателя была отличима от
прибавки в дереве.

КТО ЭТУ ПРОБУ ИСПОЛНЯЕТ: `.github/scripts/run-python-probes.py`. Состав он
собирает ОБХОДОМ дерева по образцу `tests/newman/scripts/*_test.py` (в дереве
платформы к нему добавлен `services/*/tests/newman/scripts/*_test.py`) и
НИ ОДИН файл проб по имени не называет — поэтому отдельного шага в конвейере файл
не требует, а искать вызывающего предикатом `git grep <имя файла>` бесполезно:
вызова по имени нет ни у кого. Код возврата при этом доезжает до вердикта шага.
Проводку держит `.github/scripts/run-python-probes.py`; одноимённый гейт
проводки `PRO-Robotech/kacho:tools/pythonprobes` — координата ДЕРЕВА
ПЛАТФОРМЫ, в этом репозитории его нет.
"""

import ast
import pathlib
import re
import sys

# Множество, которое REST-фронт ДЕЙСТВИТЕЛЬНО производит.
#
# Двенадцать статусов отображения кодов (установлено прогоном
# `runtime.HTTPStatusFromCode` по всем семнадцати кодам) плюс исходы самого
# маршрутизатора: промах пути — 404, промах глагола — 405, а 501 остаётся у
# UNIMPLEMENTED обработчика. 404 и 501 уже входят в двенадцать; 405 — НЕТ, его
# приносит обработчик ошибок маршрутизации фронта, и множество он расширяет.
#
# Множество принадлежит ФРОНТУ СЛУЖБЫ, а не платформенному краю: край своего
# обработчика ошибок маршрутизации не заводит, и промах глагола у него
# по-прежнему 501. Поэтому случай общего слоя генератора, названный в шапке,
# остаётся чужим предметом.
PRODUCIBLE = {200, 400, 401, 403, 404, 405, 409, 429, 499, 500, 501, 503, 504}

# Статусы, которых не бывает, названные поимённо ради текста находки.
NAMED_IMPOSSIBLE = {
    412: "совпадение имён обманчиво: 412 про условные заголовки запроса; "
         "«состояние ресурса не позволяет» есть FAILED_PRECONDITION, то есть 400",
    422: "не производится ни одним кодом отображения и ни одним исходом маршрутизатора",
}

# ИСХОД ТОЧКИ АВТОРИЗАЦИИ — производитель другой, и множество у него своё.
#
# Перенаправление с кодом (RFC 6749 §4.1.2; приёмка LINE-A-1, сценарии 02, 06,
# 29, 30) отвечает РУКОПИСНЫЙ обработчик поверхности выдачи, а не отображение
# кода отказа: REST-фронт 302 не производит ничем, и в множестве выше его нет по
# праву. Поэтому статус законен РОВНО в модуле, чей шаг адресует точку
# авторизации, — модуль без неё, ждущий 302, ждёт исхода без производителя.
#
# Адресация судится КОДОМ модуля: строковой константой пути, разобранной
# деревом, а не подстрокой текста. Путь в комментарии шагом не является, а
# глагол фронта `…/authorize:check` — другой производитель с другим множеством.
AUTHORIZE_PATH = "/iam/v1/authorize"
AUTHORIZE_REDIRECT = {302}


def addresses_authorize(tree) -> bool:
    """Есть ли у модуля шаг, адресующий точку авторизации (с запросом или без)."""
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            v = node.value
            if v == AUTHORIZE_PATH or v.startswith(AUTHORIZE_PATH + "?"):
                return True
    return False


CASES_DIR = pathlib.Path(__file__).resolve().parents[1] / "cases"

# Форма 2: рукописное сравнение кода с одним значением.
RE_LITERAL = re.compile(
    r"pm\.response\.code[^;]{0,160}?(?:to\.eql|to\.equal|===)\s*\(?\s*(\d{3})")
# Форма 3: полоса допустимых кодов.
RE_ONEOF = re.compile(r"pm\.response\.code[^;]{0,200}?to\.be\.oneOf\(\s*\[([\d,\s]+)\]")


def collect(path):
    """Ожидаемые статусы одного модуля кейсов, по формам записи.

    Возвращает пару: статусы по формам и признак «модуль адресует точку
    авторизации» — у неё своё множество (`AUTHORIZE_REDIRECT`).
    """
    text = path.read_text(encoding="utf-8")
    by_form = {"assert_status": [], "литерал": [], "полоса": []}

    # Форма 1 — впрыснутый помощник. Читается РАЗОБРАННЫМ деревом, а не строкой:
    # имя помощника стоит и в объяснениях этого же файла, и предикат по подстроке
    # краснел бы на собственном объяснении проверяемого.
    try:
        tree = ast.parse(text)
    except SyntaxError as exc:  # модуль не разбирается — обход неполон
        raise SystemExit(f"{path.name} не разбирается ({exc}) — вердикт был бы о части")
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        fn = node.func
        if not isinstance(fn, ast.Name) or fn.id != "assert_status":
            continue
        if node.args and isinstance(node.args[0], ast.Constant) and \
                isinstance(node.args[0].value, int):
            by_form["assert_status"].append(node.args[0].value)

    for m in RE_LITERAL.finditer(text):
        by_form["литерал"].append(int(m.group(1)))
    for m in RE_ONEOF.finditer(text):
        for raw in m.group(1).split(","):
            raw = raw.strip()
            if raw:
                by_form["полоса"].append(int(raw))
    return by_form, addresses_authorize(tree)


def audit(cases_dir):
    """Обход набора. Возвращает (перепись, находки)."""
    modules = sorted(p for p in cases_dir.glob("*.py"))
    census = {"модулей": 0, "assert_status": 0, "литерал": 0, "полоса": 0}
    seen = set()
    findings = []
    for path in modules:
        census["модулей"] += 1
        by_form, authorize = collect(path)
        for form, codes in by_form.items():
            census[form] += len(codes)
            for code in codes:
                seen.add(code)
                if code in PRODUCIBLE:
                    continue
                if code in AUTHORIZE_REDIRECT and authorize:
                    continue
                if code in AUTHORIZE_REDIRECT:
                    why = (f"{code} производит только точка авторизации ({AUTHORIZE_PATH}, "
                           f"перенаправление с кодом), а ни один шаг модуля её не адресует")
                else:
                    why = NAMED_IMPOSSIBLE.get(
                        code, "статуса нет ни среди отображаемых кодов, ни среди исходов маршрутизатора")
                findings.append(f"{path.name}: ожидается {code} ({form}) — {why}")
    census["различных статусов"] = len(seen)
    return census, findings


def main():
    if not CASES_DIR.is_dir():
        print(f"ОТКАЗ: каталога кейсов нет ({CASES_DIR}) — вердикт беспредметен", file=sys.stderr)
        return 1
    census, findings = audit(CASES_DIR)
    print("перепись: " + " · ".join(f"{k} {v}" for k, v in census.items()))
    if census["модулей"] == 0:
        print("ОТКАЗ: модулей кейсов прочитано ноль — обход пуст, вердикт беспредметен",
              file=sys.stderr)
        return 1
    total = census["assert_status"] + census["литерал"] + census["полоса"]
    if total == 0:
        print("ОТКАЗ: ожидаемых статусов не найдено ни одного — либо форма записи "
              "сменилась, либо кейсы перестали утверждать статус; в обоих случаях "
              "проверка больше ничего не читает", file=sys.stderr)
        return 1
    if findings:
        print(f"НАХОДКИ ({len(findings)}): кейс ждёт статуса, которого фронт не производит — "
              "такое утверждение не покраснеет никогда:", file=sys.stderr)
        for f in findings:
            print("  " + f, file=sys.stderr)
        return 1
    print(f"ЧИСТО: ожидаемых статусов осмотрено {total}, все принадлежат производимому множеству")
    return 0


if __name__ == "__main__":
    sys.exit(main())
