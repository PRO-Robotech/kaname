# ПРИНЯТА ВЕРСИЯ geo — МЕНЬШИНСТВО СТРОГО ЛУЧШЕ (одна копия против семи).
#
# У шести наборов утверждение о коде ответа шло БЕЗ второго аргумента, то есть
# упавший шаг печатал «expected 403 to equal 200» и не показывал, ЧТО ответил
# сервер. Диагноз тогда ставится по имени шага — ровно то, что нормативные
# правила запрещают (`testing.md` §«Чтение вердикта»: диагноз по ТЕКСТУ отказа).
# Седьмая версия (край) тело показывала, но сырой строкой: многострочный ответ
# ломал одну строку отчёта на десяток. `JSON.stringify` оставляет тело одной
# строкой и экранирует его — поэтому принята она.
def assert_status(code: int) -> List[str]:
    return [
        f"pm.test({js_str(f'status {code}')}, () => pm.expect(pm.response.code, JSON.stringify(pm.response.text())).to.eql({code}));",
    ]

# ПРИНЯТА ВЕРСИЯ geo — МЕНЬШИНСТВО СТРОГО ЛУЧШЕ (одна копия против семи).
#
# У семи наборов стояло `const j = pm.response.json();` — на теле, которое JSON
# не является (страница отказа входного контура, пустой ответ), разбор БРОСАЕТ,
# и шаг падает сообщением разборщика вместо утверждения о коде. Красное при этом
# остаётся красным, но диагноз теряется целиком.
#
# Замаскировать отказ версия geo не может by construction: при неразобранном
# теле `j` пуст, `j.code` — `undefined`, и утверждение о коде не выполняется
# НИКОГДА. То есть меньшинство здесь строго лучше по диагностике и ровно так же
# строго по существу.
def assert_grpc_code(code: int, code_name: str) -> List[str]:
    return [
        f"pm.test({js_str(f'grpc code {code} ({code_name})')}, () => {{",
        "  let j; try { j = pm.response.json(); } catch (e) { j = {}; }",
        f"  pm.expect(j.code, JSON.stringify(j)).to.eql({code});",
        "});",
    ]

