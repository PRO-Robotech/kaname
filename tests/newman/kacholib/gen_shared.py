def assert_refusal_message(template: str, probe: str = "refusal text is the owner's verbatim tone") -> List[str]:
    """Утверждение о ТЕКСТЕ отказа владельца — ЦЕЛИКОМ и с различением регистра.

    ЗАЧЕМ ОТДЕЛЬНЫЙ ПОМОЩНИК. Утверждение вида
    `message.toLowerCase()).to.include('already exists')` проверяет ОБЩУЮ часть
    тона, а не текст владельца: под ним проходит отказ ЛЮБОГО ресурса этого
    сервиса, несущий ту же часть. Тон сообщений — часть контракта
    (`api-conventions.md` §Error-format), и приведение регистра не различает его
    by construction: расхождение по регистру не может покраснеть НИ В ОДНОМ
    прогоне. Замер #1520: таких утверждений в дереве было 20 в 19 шагах, и у
    девяти из них заголовок кейса при этом обещал «verbatim text».

    ЧЕМ ЭТО ЛУЧШЕ РЕГУЛЯРНОГО ВЫРАЖЕНИЯ. Образец с `.*` на месте имени
    утверждает форму, но не имя: отказ о ЧУЖОМ ресурсе с тем же тоном проходит.
    Здесь имя подставляется из окружения, поэтому утверждение — равенство, а
    равенство не оставляет свободных мест. Вдобавок в нём нет знаков выражения,
    и вопрос об их экранировании не возникает вовсе.

    ВХОД — текст владельца дословно, с `{{имя}}` там, где стоит переменная
    окружения набора:

        assert_refusal_message("Network with name net-dup-{{runId}} already exists")

    Помощник сам собирает выражение JavaScript: литеральные куски идут
    сериализатором строки, а `{{имя}}` — чтением окружения. Подстановка `{{…}}`
    В САМИХ СКРИПТАХ НЕ РАБОТАЕТ (newman подставляет переменные в адресе, шапке и
    теле, но не в теле теста), поэтому оставить её здесь значило бы утверждать
    равенство с фигурными скобками — то есть не утверждать ничего.
    """
    parts: List[str] = []
    pos = 0
    for m in _REFUSAL_VAR_RE.finditer(template):
        if m.start() > pos:
            parts.append(js_str(template[pos:m.start()]))
        parts.append(f"pm.environment.get({js_str(m.group(1))})")
        pos = m.end()
    if pos < len(template):
        parts.append(js_str(template[pos:]))
    if not parts:
        raise SystemExit(
            "assert_refusal_message: пустой текст отказа.\n"
            "Это ОТКАЗ, а не пропуск: утверждение о пустом тексте зеленеет на любом ответе."
        )
    return [
        f"pm.test({js_str(probe)}, () => {{",
        "  let j; try { j = pm.response.json(); } catch (e) { j = {}; }",
        f"  pm.expect(j.message, JSON.stringify(j)).to.eql({' + '.join(parts)});",
        "});",
    ]


def assert_refusal_message_contains(template: str,
                                   probe: str = "refusal text carries the owner's verbatim wording") -> List[str]:
    """Утверждение о тексте отказа владельца ЦЕЛИКОМ, но ВХОЖДЕНИЕМ, а не равенством.

    Когда применять — и это НЕ «когда лень выяснить»: сообщение владельца
    доезжает до клиента с ХВОСТОМ, который статически не вычисляется. Два таких
    случая в дереве:

      * накопитель нарушений домена склеивает несколько текстов в одно сообщение
        (`Illegal argument …` у iam), и число слагаемых зависит от входа;
      * текст называет ПЕРЕЧЕНЬ помех (`Network %s is not empty (%s)`), а перечень
        зависит от того, что успело завестись к моменту шага.

    Различие с `assert_refusal_message` — в том, ЧТО доказуемо, а не в строгости
    ради строгости: равенство там, где известен весь текст; вхождение там, где
    известна его часть, но эта часть — ВЕСЬ текст владельца, а не общая часть
    тона. Регистр различается в обоих: приведение регистра не различает тон
    by construction, и расхождение по нему не может покраснеть ни в одном прогоне.

    `{{имя}}` подставляется чтением окружения — как у соседа выше.
    """
    lines = assert_refusal_message(template, probe)
    # Тело одно, различается только само утверждение: собирать вторую копию
    # разбора ответа значило бы завести второе место об одном предмете.
    lines[-2] = lines[-2].replace(".to.eql(", ".to.have.string(", 1)
    return lines


def assert_op_refusal_message(template: str,
                              probe: str = "operation refusal text is the owner's verbatim tone",
                              contains: bool = False) -> List[str]:
    """То же утверждение о тексте владельца, но для КОНВЕРТА ОПЕРАЦИИ.

    ЗАЧЕМ ОТДЕЛЬНЫЙ ВХОД, А НЕ ФЛАГ У СОСЕДА. Синхронный отказ приезжает полем
    `message` верхнего уровня, а отказ асинхронной мутации — вложенным
    `error.message` конверта `Operation` (`api-conventions.md`: мутации
    возвращают `Operation`). Утверждение о `j.message` на конверте операции
    зеленеет на ЛЮБОМ ответе: этого поля там нет, и `undefined` не равен ничему
    ожидаемому... кроме случая, когда ожидаемое тоже пусто. Поэтому доступ к
    полю — часть утверждения, а не его настройка.

    ЧТО ЭТО ЗАМЕНЯЕТ. `assert_op_error(msg_substr=…)` приводит регистр и
    утверждает ВХОЖДЕНИЕ ОБЩЕЙ ЧАСТИ ТОНА («already exists», «cannot be
    deleted»), а такую часть у одного владельца несут несколько разных отказов:
    у iam «cannot be deleted» несут одиннадцать. Утверждение проходит на отказе,
    которого кейс не называл, и подмены одного отказа другим не различает ни при
    каком ответе (#1748, гейт `newmanrefusaltone_test.go`, вид 4). Вдобавок
    `msg_substr` подстановки окружения не несёт, поэтому «текст владельца
    целиком» через него невыразим: имя и идентификатор в тексте живут
    переменными набора.

    ВХОД — текст владельца дословно, с `{{имя}}` на месте переменной окружения:

        assert_op_refusal_message("Account %s contains projects and cannot be "
                                  "deleted" % "{{accountAId}}")

    `contains=True` — когда сообщение доезжает с хвостом, который статически не
    вычисляется (см. `assert_refusal_message_contains`); утверждается всё равно
    ВЕСЬ текст владельца, а не общая часть тона.

    ИМЯ ДОСТУПА `opMsg` — ЧАСТЬ КОНТРАКТА С ГЕЙТАМИ, а не вкус. Гейт
    производителя (`newmanrefusalproducer_test.go`) узнаёт объявленный текст по
    паре «доступ к полю + `JSON.stringify(j)`»; форма доступа, о которой он не
    знает, делает утверждение не находкой и не её отсутствием, а НЕВИДИМЫМ
    (`testing.md` §«Гейт на класс», п. 7). Переименуешь — поправь `rpAssert` тем
    же изменением.
    """
    lines = assert_refusal_message(template, probe)
    # Тело одно: вторая копия разбора ответа была бы вторым местом об одном
    # предмете, и разошлись бы они молча.
    lines.insert(2, "  const opMsg = (j.error && j.error.message) || '';")
    lines[-2] = lines[-2].replace("pm.expect(j.message,", "pm.expect(opMsg,", 1)
    if contains:
        lines[-2] = lines[-2].replace(".to.eql(", ".to.have.string(", 1)
    return lines


