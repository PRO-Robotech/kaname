# расходились они НЕ формой коллекции — она у всех одна, вплоть до порядка
# ключей, — а десятком точечных решений: под каким адресом живёт шаг, какие
# преобразования проходит перечень шагов кейса, что дописывается в пред-скрипт.
# Каждое такое решение названо полем `Emit` и объявляется НАБОРОМ в одном месте,
# вместо того чтобы жить копией тела функции.
#
# ПОЧЕМУ ИМЕННО ТАК, А НЕ «ОДНА ФУНКЦИЯ НА ВСЕХ». Модель кейса (`Case`/`Step`) у
# наборов СВОЯ и остаётся своей: у края шаг несёт трёхзначный выбор слушателя, у
# geo/compute/storage/vpc — двузначный признак, у iam/nlb/registry такого поля
# нет вовсе. Свести это к одному полю значило бы объявить, что решение принято,
# — а его никто не принимал. Общий слой обращается к шагу ПО УТИНОМУ и адрес
# спрашивает у набора.
# ═════════════════════════════════════════════════════════════════════════════

@dataclass
class Emit:
    """Решения набора, от которых зависит форма порождаемой коллекции.

    Поле здесь заводится ТОЛЬКО под расхождение, которое ДЕЙСТВИТЕЛЬНО есть в
    дереве: ручка «на будущее» — то же обещание без держателя, что и мёртвый
    код. Каждое поле ниже названо тем набором, который им пользуется.
    """

    # Вход UUIDv5 для `_postman_id`. Идентификатор ДЕТЕРМИНИРОВАН: случайный
    # делал грязной каждую перегенерацию, и «порождённое совпадает с исходником»
    # нельзя было проверить вовсе, а настоящему расхождению негде было показаться.
    id_slug: str
    # Видимое имя коллекции. У края оно НЕ совпадает со слагом идентификатора
    # (`kacho-gateway` против `kacho-api-gateway`) — расхождение историческое, и
    # сведение его не трогает: смена слага перечеканила бы все идентификаторы.
    display_name: str
    # Пред-скрипт уровня коллекции. Функция, а не список: vpc выбирает его по
    # имени коллекции (часть наборов идёт под администратором по умолчанию).
    pre_global: "Callable[[str], List[str]]"
    # Конвейер шагов кейса — ЗДЕСЬ живёт главное различие наборов, и оно
    # осознанное: какие преобразования применяются и в каком порядке.
    steps_of: "Callable[[object], list]"
    # Пред-скрипт смены предъявителя. Своя у каждого набора: перечень
    # предъявителей — свойство набора, а не формы коллекции.
    auth_pre: "Callable[[Optional[str]], List[str]]"
    # Имя переменной адреса по шагу. Умолчание — единственный публичный адрес.
    host_var: "Callable[[object], str]" = lambda step: "baseUrl"
    # Событие уровня коллекции на исход (iam).
    post_global: "Optional[List[str]]" = None
    # Элементы, идущие ПЕРЕД кейсами (vpc: резолв зон, посев пулов, якорь).
    prefix_items: "Optional[Callable[[str], list]]" = None
    # Дописывается в НАЧАЛО пред-скрипта шага (край: страж переменной адреса,
    # объявленной, но не заданной профилем).
    pre_head: "Optional[Callable[[object, str], List[str]]]" = None
    # Дописывается в КОНЕЦ пред-скрипта шага (iam: страж подстановки — он обязан
    # идти последним, после всех законных производителей адреса, включая сам шаг).
    pre_tail: "tuple" = ()
    # Правка элемента по свойству шага (iam/registry: ослабленная проверка
    # сертификата у шага, который ходит к внешнему предъявителю).
    item_hook: "Optional[Callable[[object, dict], None]]" = None
    # Разбор пути на сегменты. Умолчание общее; край отрезает строку запроса.
    path_segments: "Optional[Callable[[str], List[str]]]" = None


def _default_path_segments(path: str) -> List[str]:
    return [p for p in path.strip("/").split("/") if p]


def step_to_postman(emit: "Emit", step) -> Dict:
    """Один шаг кейса — в элемент коллекции.

    Тело ниже во всех восьми копиях совпадало ДОСЛОВНО, включая порядок ключей;
    расходились только точки, вынесенные в `Emit`.
    """
    var = emit.host_var(step)
    host = "{{" + var + "}}"
    segments = (emit.path_segments or _default_path_segments)(step.path)
    item: Dict = {
        "name": step.name,
        "request": {
            "method": step.method,
            "header": [{"key": "Content-Type", "value": "application/json"}],
            "url": {
                "raw": host + step.path,
                "host": [host],
                "path": segments,
            },
        },
    }
    if emit.item_hook is not None:
        emit.item_hook(step, item)
    if step.body is not None:
        item["request"]["body"] = {
            "mode": "raw",
            "raw": json.dumps(step.body, ensure_ascii=False),
            "options": {"raw": {"language": "json"}},
        }
    pre = list(step.pre_script)
    if emit.pre_head is not None:
        pre = emit.pre_head(step, var) + pre
    if step.auth is not None:
        pre = emit.auth_pre(step.auth) + pre
    pre = pre + list(emit.pre_tail)
    events = []
    if pre:
        events.append({"listen": "prerequest", "script": {"type": "text/javascript", "exec": pre}})
    # Шаг удаления без собственного утверждения получает утверждение по умолчанию
    # (см. `_DELETE_ACCEPTED` выше). Ставится в КОНЕЦ — после обёртки ожидания.
    test_exec = list(step.test_script)
    if step.method == "DELETE" and not _carries_assertion(test_exec):
        test_exec = test_exec + _DELETE_ACCEPTED
    if test_exec:
        events.append({"listen": "test", "script": {"type": "text/javascript", "exec": test_exec}})
    if events:
        item["event"] = events
    return item


def case_to_postman(emit: "Emit", case) -> Dict:
    """Один кейс — в папку коллекции.

    Расхождение всех восьми копий было ровно в ОДНОМ: какие преобразования
    проходит перечень шагов. Оно осознанное (у наборов разные конвейеры) и
    названо полем `steps_of`, а не спрятано в восьми телах.
    """
    tags = [f"class:{c}" for c in case.classes] + [f"priority:{case.priority}"]
    return {
        "name": f"{case.id} — {case.title}",
        "description": " | ".join(tags),
        "item": [step_to_postman(emit, s) for s in emit.steps_of(case)],
    }


def build_collection(emit: "Emit", key: str, cases: list) -> Dict:
    """Перечень кейсов — в коллекцию."""
    events = [
        {"listen": "prerequest", "script": {"type": "text/javascript", "exec": emit.pre_global(key)}},
    ]
    if emit.post_global is not None:
        events.append({"listen": "test", "script": {"type": "text/javascript", "exec": emit.post_global}})
    prefix = emit.prefix_items(key) if emit.prefix_items is not None else []
    return {
        "info": {
            "_postman_id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"{emit.id_slug}/newman/{key}")),
            "name": f"{emit.display_name} / {key}",
            "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
        },
        "event": events,
        "item": prefix + [case_to_postman(emit, c) for c in cases],
        "variable": [],
    }


def load_cases_module(path, injected: Dict, before=None, stem_dashes_to_underscores: bool = True):
    """Загрузить модуль кейсов, впрыснув в его пространство имён помощники набора.

    ПЕРЕЧЕНЬ ВПРЫСКИВАЕМОГО — СЛОВАРЬ, А НЕ СТРОКИ `mod.X = X`. Семь наборов
    выписывали его руками, по строке на имя: перечень из сорока пяти строк,
    который обязан меняться вслед за помощниками и который ни на что не влияет,
    пока имя не понадобилось кейсу. Именно там и накапливался впрыск имён,
    снятых из генератора: строка переживала свой предмет молча.
    """
    if before is not None:
        before()
    stem = path.stem.replace("-", "_") if stem_dashes_to_underscores else path.stem
    spec = importlib.util.spec_from_file_location(stem, path)
    mod = importlib.util.module_from_spec(spec)
    for name, value in injected.items():
        setattr(mod, name, value)
    spec.loader.exec_module(mod)
    return mod


def http_method_not_allowed_block(case_cls, step_cls, prefix: str, base_path: str) -> list:
    """HTTP-глаголы, которых у списочного адреса нет: PUT и DELETE без id.

    ПРИНЯТА ВЕРСИЯ БОЛЬШИНСТВА (две копии против одной) — и она же строго лучше.
    Порождаемые утверждения у обеих ПОБАЙТОВО одни; расходились ЗАГОЛОВКИ, и
    заголовок меньшинства («→ 405 или 404») противоречил собственному
    утверждению шага, принимающему ещё 403 и 501. Заголовок кейса доезжает до
    коллекции именем папки — то есть читатель отчёта видел обещание, которого
    проба не проверяла.

    403 в перечне — не послабление, а задокументированная полоса: край решает
    доступ ДО маршрутизации глагола, поэтому отказ по правам приходит раньше
    отказа по методу (`testing.md` §e2e-инварианты, «authz-first толерантность»).
    Все четыре кода означают «глагол не выполнен», и отрицание сохраняется.
    """
    check = ("pm.test('not allowed (403/404/405/501)', "
             "() => pm.expect(pm.response.code).to.be.oneOf([403, 404, 405, 501]));")
    return [
        case_cls(
            id=f"{prefix}-METHOD-PUT-NOT-ALLOWED",
            title="PUT on List endpoint → 403/404/405/501",
            classes=["VAL", "NEG"], priority="P3",
            steps=[step_cls(name="put-list", method="PUT", path=base_path,
                            body={"projectId": "{{_suiteProjectId}}"},
                            test_script=[check])],
        ),
        case_cls(
            id=f"{prefix}-METHOD-DELETE-LIST",
            title="DELETE on List endpoint (no id) → 403/404/405/501",
            classes=["VAL", "NEG"], priority="P3",
            steps=[step_cls(name="del-list", method="DELETE", path=base_path,
                            test_script=[check])],
        ),
    ]

# Утверждение по умолчанию для шага удаления — ПОБАЙТОВО совпадало во всех
# восьми копиях. Читает его только `step_to_postman`, поэтому константа
# переезжает вместе с ним.
# Утверждение о том, что удаление ПРИНЯТО. Ровно одно и однозначное: `oneOf`
# со взаимоисключающими исходами утверждением не является (testing.md).
_DELETE_ACCEPTED = [
    "// УТВЕРЖДЕНИЕ ПО УМОЛЧАНИЮ для шага удаления: без него шаг зеленел бы и на",
    "// отказе, а следующий опрос уехал бы на opId предыдущей операции.",
    "pm.test('delete accepted: status 200', () => "
    "pm.expect(pm.response.code, pm.response.text()).to.eql(200));",
]


def retry_until_authorized(step, budget: int, interval_ms: int,
                           retry_on=(403, 404), lane_head=False, ledger=None):
    """ОКНО ЗАДАЁТ НАБОР, ТЕЛО — ОБЩЕЕ (#1379).

    Шесть копий этой функции расходились по ТРЁМ осям, и только одна из них была
    расхождением по существу:

      * ВЕЛИЧИНА ОКНА (40×600, 25×500, 15×400, 80×600 мс) — решение набора: путь
        материализации у доменов разный, и подгонять их под одно число значило бы
        решить за них. Поэтому окно здесь — ОБЯЗАТЕЛЬНЫЙ аргумент без умолчания:
        умолчание в общем слое молча стало бы решением за всех;
      * ДВЕ ДОБАВКИ (`lane_head`, `ledger`) — названы полями, а не спрятаны в
        двух копиях тела. `lane_head` РАЗДАН всем наборам с полосой видимости
        (#1477): раздача меняла поведение проб и потому ехала своим вердиктом, а
        не попутным грузом сведения. Число здесь НЕ называется — его измеряет
        гейт `internal/repohygiene` `TestOwnFreshReadWrapPredicateWiredInEvery`
        `NewmanGenerator` третьим утверждением («полоса несёт голову у N») и
        печатает переписью на каждом прогоне. `ledger` остаётся добавкой одного
        набора и кандидатом в общее;
      * ШАПКИ — расходились текстом, и три из шести называли ЧУЖИЕ величины
        («default 15*400ms ≈ 6s» при подписи 40×600). Читатель планировал окно
        вдвое-вчетверо меньше действительного. Поэтому величина здесь НЕ
        называется прозой вовсе: она приходит аргументом и видна на вызове.

    Wrap the FIRST access of the caller's OWN just-created resource in a bounded
    read-your-writes retry over the owner-tuple materialization window.

    opgate (the create confirm-gate) was removed by design-review: Operation.done now
    means the resource is DURABLE, but its owner/creator FGA tuple materializes
    eventually-consistent (at-least-once drainer + reconciler + sync-registrar
    optimisation). Under load the first post-create Get/Update/Delete of the fresh
    resource can briefly return 403 (PERMISSION_DENIED) or 404 at the authz gate
    before the tuple is visible. This is a textbook read-your-writes lag -> the CLIENT
    retries; it is NOT a server barrier.

    Retries the SAME request (setNextRequest -> self) while the response code is in
    `retry_on` (default 403/404), spacing attempts by ~interval_ms (busy-wait -- newman
    fires setNextRequest before any setTimeout). budget*interval_ms bounds the wait
    (default 15*400ms = ~6s) -- fail-closed: on any other code the wrapped step's real
    test_script runs exactly once, and once the budget is spent it ALSO runs on the
    terminal 403/404 (a genuine, non-converging deny still FAILS the real assertions --
    never masked, never infinite).

    Use ONLY on the first access of the caller's OWN fresh resource. Do NOT wrap
    negative / cross-account-deny / absent-id steps (a poll there would mask a real
    deny). The counter/started env-vars are request-name-scoped (step names are
    globally unique after serialization) so the loop never bleeds across cases or
    steps -- same discipline as poll_operation_until_done.

    ГРАНИЦА, КОТОРУЮ ЭТА ОБЁРТКА НЕ ПЕРЕХОДИТ (issue #351). Решение о повторе
    принимается по КОДУ ОТВЕТА шага, поэтому закрыта ровно одна полоса — СИНХРОННЫЙ
    отказ этого запроса (шлюз не разрешил цель проверки прав → 403; чтение скрытого
    ресурса → 404). У АСИНХРОННОЙ мутации отказ ВЛАДЕЛЬЦА чужого ресурса приезжает
    иначе: шаг отвечает `200` и конвертом `Operation`, а отказ лежит терминальной
    ошибкой ВНУТРИ операции и читается уже другим шагом — сюда он не попадает НИКОГДА.
    Обёртка на таком шаге не инертна (полосу шлюза она по-прежнему закрывает), но
    читать её как «окно видимости здесь закрыто» — ошибка: чужой свежий идентификатор
    обязан быть либо ПРОЧИТАН до мутации (`retry_until_authorized(GET <владелец>/<id>)`
    — форма, посаженная PR #350), либо прикрыт повтором по ИСХОДУ операции
    (`poll_operation_until_done(retry_from=…)`). Свойство держит по всему дереву гейт
    `internal/repohygiene/artifactgates`
    `TestAsyncMutationDoesNotCarryAnUnwarmedPeerId`.
    """
    # Полоса, по которой приходит окно видимости, задаётся МЕТОДОМ, а не вкусом
    # автора: у мутации отказ виден как 403, а у ЧТЕНИЯ он спрятан под 404
    # (hide-existence: текст отказа побайтово равен настоящему «не найдено», см.
    # `security.md`). Поэтому рукописное `retry_on=(403,)` на GET — обёртка,
    # которая не может сработать на том коде, который она увидит: форма есть,
    # содержания нет. Такое место в дереве нашлось (vpc1 `get-no-dhcp`: 404 на
    # первом же обращении, ретрай не сработал ни разу, шаг упал). Чинится по
    # построению здесь, а не перечнем в кейсах; 404, названный шагом законным
    # исходом, в retry_on не попадает вовсе — его отсекает вызывающий.
    # Ожидание НИКОГДА не включает код, который шаг сам объявил приемлемым
    # исходом: иначе проба пережидала бы ровно то, ради чего написана, и жгла бы
    # бюджет на успехе. Нормализация здесь, а не у вызывающих: рукописные
    # обёртки этого не делали (5 мест в дереве ждали заявленный ими же 404).
    _acc = _accepted_http_codes("\n".join(step.test_script))
    retry_on = tuple(c for c in retry_on if c not in _acc)
    if step.method == "GET" and 404 not in retry_on and 404 not in _acc:
        retry_on = tuple(retry_on) + (404,)
    # То же и у УДАЛЕНИЯ, и по той же причине — только код приходит не из
    # hide-existence чтения, а из утверждения по умолчанию: шаг удаления без
    # собственного утверждения получит при сериализации `delete accepted: status 200`
    # (_DELETE_ACCEPTED), и 404 для него — падение, а не законное «уже нет».
    # Держим это ЗДЕСЬ, а не у вызывающих: рукописное `retry_on=(403,)` на таком шаге
    # даёт обёртку, которая не ждёт единственный код, на котором шаг упадёт, — форма
    # ожидания есть, содержания нет. 404, названный шагом законным исходом, сюда
    # по-прежнему не попадает: его отсекает `_acc`.
    if (step.method == "DELETE" and not _carries_assertion(list(step.test_script))
            and 404 not in retry_on and 404 not in _acc):
        retry_on = tuple(retry_on) + (404,)
    if not retry_on:
        # Ждать нечего: все коды полосы видимости объявлены исходами. Обёртка
        # выродилась бы в петлю, которая не может сработать, — не ставим её.
        return step
    # ЗДЕСЬ ЖЕ — граница, которую этот отказ ставить обёртку НЕ ловит (issue #351).
    # Условие выше отсекает вырожденный случай «ждать нечего», и это верно только
    # для полосы, ВИДИМОЙ КОДОМ ОТВЕТА. У асинхронной мутации есть вторая полоса —
    # отказ ВЛАДЕЛЬЦА чужого ресурса внутри `Operation`, — и она не видна отсюда ни
    # при каком `retry_on`: обёртка ставится, читается как закрытое окно и им не
    # является. Молча этот случай не проходит: эмитируемый комментарий ниже называет
    # свою полосу вслух, а свойство по дереву держит гейт
    # `internal/repohygiene/artifactgates` TestAsyncMutationDoesNotCarryAnUnwarmedPeerId.
    retry_set = ",".join(str(c) for c in retry_on)
    guard = [
        "// bounded read-your-writes retry over the owner-tuple materialization window",
        "// (opgate removed -> eventual-consistency); retries SELF only on 403/404.",
        "// ПОЛОСА — синхронный отказ ЭТОГО шага. У асинхронной мутации отказ ВЛАДЕЛЬЦА",
        "// приезжает внутри Operation и сюда НЕ попадает: нужен прогрев чтением.",
        # Добавка набора в ГОЛОВУ ожидания: проверка, которая обязана отработать
        # ДО того, как шаг начнёт жечь бюджет. Пусто у тех, кто её не заводил.
        *(_RETRY_LANE_HEAD if lane_head else ()),
        "if (pm.environment.get('_authRetryStarted') !== pm.info.requestName) {",
        "  pm.environment.set('_authRetryCount', '0');",
        "  pm.environment.set('_authRetryStarted', pm.info.requestName);",
        "}",
        "const _arc = parseInt(pm.environment.get('_authRetryCount') || '0', 10);",
        # `_rblank` в условии — не украшение головы: без него шаг СНАЧАЛА называет
        # предмет отказа, а ПОТОМ всё равно уходит в повтор и выжигает бюджет на том
        # же вопросе ни о чём. Голова без этого условия — половина меры.
        f"if ({'!_rblank && ' if lane_head else ''}[{retry_set}].includes(pm.response.code)"
        f" && _arc < {budget}) {{",
        "  pm.environment.set('_authRetryCount', String(_arc + 1));",
        f"  const _ard = Date.now(); while (Date.now() - _ard < {interval_ms}) {{ /* owner-tuple materialization wait */ }}",
        "  pm.execution.setNextRequest(pm.info.requestName);",
        "  return;",
        "}",
        # Добавка набора ПЕРЕД снятием счётчика: разведение «бюджет исчерпан» и
        # «бюджет не понадобился» — без неё оба исхода выглядят одинаково.
        *(ledger(f"[{retry_set}].includes(pm.response.code)", "_arc", budget) if ledger else ()),
        "pm.environment.unset('_authRetryCount');",
        "pm.environment.unset('_authRetryStarted');",
    ]
    _RYA_SEQ[0] += 1
    # Give the wrapped step a globally-unique name so its self-retry
    # setNextRequest(pm.info.requestName) always resolves to ITSELF. Newman resolves a
    # setNextRequest name to the FIRST item with that name in the collection; these
    # suites mostly do NOT prefix step names by case-id, so a wrapped step whose bare
    # name repeats would otherwise jump the retry to an earlier same-named step — the
    # exact hazard poll_operation_until_done avoids via its unique poll-op-<n> name.
    return replace(step, name=f"{step.name}-rya{_RYA_SEQ[0]}",
                   test_script=guard + list(step.test_script))


def retry_until_present(step, id_env_var, budget: int, interval_ms: int, ledger=None):
    """ОКНО ЗАДАЁТ НАБОР, ТЕЛО — ОБЩЕЕ. Зеркало `retry_until_authorized` для
    СПИСОЧНОГО чтения: там ждут код отказа, здесь — появление своей строки в теле
    ответа `200`.

    Три копии этой функции (compute · nlb · vpc) разошлись по ТРЁМ осям, и две из
    трёх были расхождением ПО СУЩЕСТВУ — то есть каждая копия несла починку,
    которой у двух других не было:

      * ЧИСЛО ОЖИДАЕМЫХ ИМЁН. Две копии принимали ОДНО имя переменной и ждали
        появления ОДНОЙ строки; третья принимает список и ждёт появления ВСЕХ.
        Это починка реального дефекта, а не вкус: кейс, утверждающий «все три на
        странице», ждал появления ПЕРВОЙ и падал на второй — она ещё
        материализовалась. Общая форма — список; одно имя остаётся законным
        входом и даёт ТО ЖЕ поведение (`every` над списком из одного).
      * ВЕДОМОСТЬ ИСЧЕРПАНИЯ (`ledger`). Одна копия разводила «бюджет исчерпан» и
        «бюджет не понадобился», две — нет, и у них оба исхода выглядели
        одинаково: никак. Названа полем, как у `retry_until_authorized`, а не
        вшита в тело.
      * ВЕЛИЧИНА ОКНА (50×600 против 25×500) — решение НАБОРА, а не общего слоя
        (#1379): путь материализации у доменов разный. Поэтому окно здесь —
        ОБЯЗАТЕЛЬНЫЙ аргумент без умолчания: умолчание в общем слое молча стало бы
        решением за всех, а шапки трёх копий величину уже называли ПРОЗОЙ и уже
        разошлись с подписью. Здесь величина не называется прозой вовсе — она
        приходит аргументом и видна на вызове.

    Bounded retry a LIST step until the caller's OWN fresh resource id(s) appear in
    the returned array (read-your-writes over the list-authz visibility window;
    opgate removed -> owner-tuple eventual-consistency). The list returns 200 with
    the id ABSENT until the tuple materializes, so retry_until_authorized (403/404)
    does not apply -- we retry while an id is missing. Fail-open after budget: the
    real assertion then runs once and FAILS if still absent (never masked, never
    infinite).

    Use ONLY on a list of the caller's OWN just-created resource. Do NOT wrap
    negative / cross-account-deny / absent-id steps: a poll there would wait out
    exactly the deny the step was written to observe.
    """
    # ПРИНИМАЕТСЯ ИМЯ ЛИБО ПЕРЕЧЕНЬ ИМЁН, И У ПЕРЕЧНЯ ЗДЕСЬ ЕСТЬ ВЫЗЫВАЮЩИЙ.
    #
    # В дереве платформы форма перечня снята — и снята верно ДЛЯ ТОГО дерева:
    # единственный кейс, ждавший появления НЕСКОЛЬКИХ строк, жил в наборе службы
    # доступа, а набор уехал в её репозиторий, то есть СЮДА. Гейт формы мерил круг
    # вызывающих по своему дереву и второго репозитория не видит by construction;
    # вызывающий жив и назван: `cases/iam-access-binding-account-scope.py`.
    #
    # ЦЕНА СНЯТИЯ ИЗМЕРЕНА, А НЕ ПРЕДПОЛОЖЕНА. Без перечня генератор подставляет
    # в скрипт ИМЯ ПЕРЕЧНЯ вместо имён его элементов: `_want` становится
    # `[undefined]`, `_want.every` не сходится НИ ПРИ КАКОМ ответе, ожидание
    # выжигает весь бюджет на каждом прогоне и после fail-open уступает ровно той
    # гонке, ради снятия которой обёртка писалась. Утверждение при этом не
    # теряется — теряется ожидание, и потеря тихая.
    #
    # Вышестоящее дерево само оговаривает условие возврата: перечень возвращается
    # ОДНОЙ строкой и ВМЕСТЕ со своим кейсом. Это она и есть. Тело ниже ждёт
    # появления ВСЕХ названных имён (`_want.every`), а не первого из них.
    want = list(id_env_var) if isinstance(id_env_var, (list, tuple)) else [id_env_var]
    guard = [
        "// bounded read-your-writes retry until own fresh id is present in the list",
        "// (opgate removed -> eventual-consistency); retries SELF while id absent.",
        "if (pm.environment.get('_lstRetryStarted') !== pm.info.requestName) {",
        "  pm.environment.set('_lstRetryCount', '0');",
        "  pm.environment.set('_lstRetryStarted', pm.info.requestName);",
        "}",
        "const _lrc = parseInt(pm.environment.get('_lstRetryCount') || '0', 10);",
        "let _present = false;",
        # УСЛОВИЕ ПОВТОРА ОБЯЗАНО СОВПАДАТЬ С УТВЕРЖДЕНИЕМ, а не быть у́же его:
        # ждём появления ВСЕХ названных имён, а не первого из них.
        "const _want = [" + ", ".join("pm.environment.get(%s)" % js_str(v) for v in want) + "];",
        "try { const _arr = Object.values(pm.response.json()).find(v => Array.isArray(v)) || [];"
        " const _have = _arr.map(x => x.id);"
        " _present = _want.every(w => _have.includes(w)); } catch (e) {}",
        f"if (pm.response.code === 200 && !_present && _lrc < {budget}) {{",
        "  pm.environment.set('_lstRetryCount', String(_lrc + 1));",
        f"  const _lrd = Date.now(); while (Date.now() - _lrd < {interval_ms}) {{ /* list-visibility wait */ }}",
        "  pm.execution.setNextRequest(pm.info.requestName);",
        "  return;",
        "}",
        # Добавка набора ПЕРЕД снятием счётчика — та же дисциплина, что у
        # `retry_until_authorized`: без неё «исчерпан» и «не понадобился» неразличимы.
        *(ledger("pm.response.code === 200 && !_present", "_lrc", budget) if ledger else ()),
        "pm.environment.unset('_lstRetryCount');",
        "pm.environment.unset('_lstRetryStarted');",
    ]
    _RYA_SEQ[0] += 1
    # Уникальное имя — по той же причине, что у `retry_until_authorized`: newman
    # резолвит setNextRequest в ПЕРВЫЙ item с таким именем, и повтор одноимённого
    # шага уехал бы к чужому.
    return replace(step, name=f"{step.name}-lst{_RYA_SEQ[0]}",
                   test_script=guard + list(step.test_script))



# Голова полосы ожидания: отказ ждать по НЕРАЗРЕШЁННОМУ адресу.
#
# ГОЛОВА ПОЛОСЫ ОЖИДАНИЯ: ждать можно ПРАВА, а не появление самого имени.
#
# Её объявляет `lane_head=True` на стороне набора. Когда-то голову нёс ОДИН набор —
# не по решению, а потому что помощник был скопирован до того, как проверку
# написали; раздача остальным шла своим вердиктом (#1477), потому что МЕНЯЕТ
# ПОВЕДЕНИЕ проб: шаг с незахваченной переменной начинает падать сразу и по делу
# вместо того, чтобы падать позже и не по делу. Сколько наборов несут её СЕГОДНЯ —
# здесь не пишется: выписанное число устаревает молча, и оно уже устарело однажды,
# пережив свою раздачу. Величину измеряет и печатает переписью гейт
# `internal/repohygiene` `TestOwnFreshReadWrapPredicateWiredInEveryNewmanGenerator`.
#
# Если адрес шага собран из переменной, которую предыдущий шаг не захватил, в пути
# стоит пустой сегмент либо уцелевшая подстановка — и запрос спрашивает НЕ О
# РЕСУРСЕ. Окно видимости прав такой адрес не наполнит никогда, поэтому повтор
# здесь — ожидание, которое не может сработать. Хуже того, отказ по пустому адресу
# приходит кодом ИЗ полосы ожидания, и шаг выжигает ВЕСЬ бюджет: замер прогона
# 31951162447, часть registry — 1863 запроса из 3903 (48%) ушли по пустому сегменту
# в 23 обёрнутых шагах, около 18 минут стенда на вопросы ни о чём, и ни одно
# утверждение о продукте при этом не проверялось.
#
# ФОРМ НЕРАЗРЕШЁННОГО СЕГМЕНТА ДВЕ, И ВТОРАЯ НАЙДЕНА ОПЫТОМ, А НЕ ЧТЕНИЕМ (#1477).
# Переменная, объявленная и ПУСТАЯ (захват очищает её перед записью), даёт пустой
# сегмент — эту форму голова ловила с самого начала. Переменная, не объявленная
# ВОВСЕ, остаётся подстановкой, и newman отдаёт её сюда ПРОЦЕНТНО-КОДИРОВАННОЙ,
# поэтому предикат по фигурным скобкам не срабатывал на ней НИКОГДА. Прогон на
# подставном сервере (newman 6.2.2): путь пришёл как ["a","%7B%7BmissingVar%7D%7D"].
# Отсюда декодирование перед сверкой — и законный близнец, сегмент с процентами,
# который подстановкой не является, по-прежнему молчит.
#
# ПРОЗА ЖИВЁТ ЗДЕСЬ, А НЕ В ИЗЛУЧАЕМОМ СКРИПТЕ. Голова уезжает в КАЖДЫЙ обёрнутый
# шаг — их в дереве 2894, — и тринадцать строк объяснения на каждый дали бы
# стотысячный прирост коллекций, ничего не сообщив прогону. В скрипт идёт то, что
# читает разбирающий ПАДЕНИЕ; объяснение — тому, кто правит генератор.
_RETRY_LANE_HEAD = (
    "",
    "// Ждать можно ПРАВА на существующее имя, а не появление самого имени: адрес,",
    "// собранный из незахваченной переменной, окно видимости не наполнит никогда.",
    "const _rpath = ((pm.request.url && pm.request.url.path) || []).map(function (s) {",
    "  return String(s && s.value !== undefined ? s.value : s);",
    "});",
    "const _rblank = _rpath.some(function (v) {",
    "  if (v === '') { return true; }",
    "  var _d = v; try { _d = decodeURIComponent(v); } catch (e) { _d = v; }",
    "  return /\\{\\{[^}]*\\}\\}/.test(_d);",
    "});",
    "if (_rblank) {",
    "  pm.environment.unset('_authRetryCount');",
    "  pm.environment.unset('_authRetryStarted');",
    "  pm.test('step addresses a captured variable', function () {",
    "    pm.expect.fail('адрес шага собран из НЕЗАХВАЧЕННОЙ переменной (/' + _rpath.join('/') +",
    "      '): предыдущий шаг не захватил её, повторять нечего');",
    "  });",
    "}",
)

# Счётчик уникальных имён обёрнутых шагов. ПОБАЙТОВО совпадал в шести копиях;
# список, а не число, намеренно — набор сбрасывает его перед каждой коллекцией
# (`_reset_step_name_counters`), и сброс обязан быть виден отсюда.
_RYA_SEQ = [0]



@dataclass
class Run:
    """Решения набора об ОРКЕСТРАЦИИ: что прочитать, что проверить, куда записать.

    Второй дескриптор рядом с `Emit` (#1474). Различие между ними — предмет:
    `Emit` решает ФОРМУ коллекции, `Run` — порядок работ вокруг неё. Одним их не
    делаем: набор, у которого нет своих проверок перед записью, не обязан знать
    про сериализацию шага, и наоборот.

    ПОЛЕ ЗАВОДИТСЯ ТОЛЬКО ПОД РАСХОЖДЕНИЕ, КОТОРОЕ ЕСТЬ В ДЕРЕВЕ. Ручка «на
    будущее» — то же обещание без держателя, что и мёртвый код.
    """

    # Корень набора — от него считается путь в печати исхода.
    root: "Path"
    cases_dir: "Path"
    out_dir: "Path"
    # Каталог скриптов: отсюда берётся отдельная проверка кейсов, если она есть.
    scripts_dir: "Path"
    emit: "Emit"
    # Тип кейса набора. Общий слой его не знает и знать не может: он объявлен в
    # генераторе. Нужен, чтобы отказ на не-`Case` был проверкой, а не догадкой.
    case_cls: type
    # Имена, видимые модулю кейсов. Здесь же набор связывает окно своей полосы
    # видимости (`partial(retry_until_authorized, budget=…, interval_ms=…)`).
    injected: dict
    # Что сделать ПЕРЕД загрузкой каждого модуля кейсов. У семи наборов это сброс
    # счётчиков имён шагов; у края счётчиков нет вовсе.
    before: "Optional[Callable[[], None]]" = None
    # Имя модуля кейсов с дефисом: часть наборов принимает его как есть.
    stem_dashes_to_underscores: bool = True
    # Проверка ОДНОЙ собранной коллекции ДО записи. Возвращает находки; непустой
    # список — отказ, и коллекция на диск не попадает: записать заведомо негодную
    # и выйти отказом хуже, чем не записать (compute — разбор переходов,
    # vpc — исход подзапроса).
    per_collection: "Optional[Callable[[str, dict], List[str]]]" = None
    # Проверка ПОСЛЕ всех коллекций: то, что нельзя решить по одной (iam — фантомы
    # и снятый принципал; vpc — перепись накопленного). Возвращает код возврата.
    after_all: "Optional[Callable[[Path], int]]" = None

    def load(self, path):
        """Загрузить модуль кейсов решениями ЭТОГО набора.

        Отдельная проверка кейсов обязана видеть ровно то, что увидит генерация:
        и впрыскиваемые имена, и сброс счётчиков, и трактовку дефиса в имени
        модуля. Пока она звала загрузчик своими руками, её вызов разошёлся с
        генератором на первой же смене подписи — и проверка перестала исполняться
        ВОВСЕ, отвечая отказом на каждый набор. Здесь разойтись нечему.
        """
        return load_cases_module(path, self.injected, before=self.before,
                                 stem_dashes_to_underscores=self.stem_dashes_to_underscores)

    # ── Форма коллекции решениями ЭТОГО набора ──────────────────────────────
    #
    # Три метода ниже — то же связывание, что `load`, и заведены они по той же
    # причине и той же ценой. Функции хребта принимают дескриптор набора первым
    # параметром; потребитель, зовущий их своими руками, обязан этот дескриптор
    # НАЗВАТЬ — то есть записать решения набора во второй раз. Разошлось это
    # молча: сведение хребта (#1379) дало `case_to_postman`, `step_to_postman` и
    # `build_collection` второй параметр, и двадцать восемь регрессионных проб
    # перестали исполняться ВОВСЕ (#1536) — не упали, а не запустились, что
    # newman и pytest считают в разных каналах.
    #
    # Ручкой «на будущее» это не является: у каждого метода есть вызывающий в
    # дереве сегодня. Держит свойство гейт
    # `TestNewmanConsumersReachTheSpineThroughTheSuiteBinding`.

    def case_item(self, case) -> Dict:
        """Кейс — в папку коллекции решениями набора."""
        return case_to_postman(self.emit, case)

    def step_item(self, step) -> Dict:
        """Шаг — в элемент коллекции решениями набора."""
        return step_to_postman(self.emit, step)

    def collection(self, key: str, cases: list) -> Dict:
        """Перечень кейсов — в коллекцию решениями набора."""
        return build_collection(self.emit, key, cases)

    def case_modules(self) -> list:
        """Модули кейсов набора — тем же отбором, что у генерации."""
        return _case_modules(self)


def _case_modules(run: "Run") -> list:
    """Модули кейсов набора в устойчивом порядке.

    Имя с ведущим подчёркиванием — ПОМОЩНИК, а не набор кейсов. Раньше это знали
    два набора из восьми, у остальных шести таких файлов просто не было, и
    различие выглядело решением, не будучи им: первый же общий помощник в чужом
    наборе был бы загружен как модуль кейсов и дал бы пустой `CASES`, то есть
    коллекцию без единого кейса — молча.
    """
    return sorted(f for f in run.cases_dir.glob("*.py") if not f.name.startswith("_"))


def _scan_suite(run: "Run") -> tuple:
    """Один обход набора ДО записи: чем объявлены кейсы и уникальны ли их имена.

    Возвращает пару перечней находок — «в CASES не-`Case`» и «идентификатор
    повторяется», — и ПОРЯДОК между ними значим. Тип проверяется ПЕРВЫМ, потому
    что перечень идентификаторов у не-`Case` собрать нельзя: обход по нему падает
    разбором чужого объекта и называет СИМПТОМ (`'dict' object has no attribute
    'id'`) вместо предмета. Отказ, посылающий читателя искать не там, стоит
    прогона — и его снимают как непонятный.

    ОБЛАСТЬ ОБОИХ ВОПРОСОВ — ВЕСЬ НАБОР, а не выбранные модули: негодный модуль
    не становится годным оттого, что в этот раз просили соседний.

    ЧЕТЫРЕ НАБОРА ИЗ ВОСЬМИ проверяли дубли ВНУТРИ модуля, четыре — по всему
    набору, и различие никто не принимал: помощник копировался вместе с
    генератором. Внутримодульная проверка не видит совпадения между модулями BY
    CONSTRUCTION, а именно оно и опасно — идентификатор кейса адресует отчёт, и
    два кейса под одним именем сливаются в отчёте в один.
    """
    seen: Dict[str, str] = {}
    bad_types: List[str] = []
    dups: List[str] = []
    for f in _case_modules(run):
        mod = run.load(f)
        cases = getattr(mod, "CASES", [])
        wrong = sorted({type(c).__name__ for c in cases if not isinstance(c, run.case_cls)})
        if wrong:
            bad_types.append(f"  - {f.name}: {wrong}")
            # Идентификаторы этого модуля не собираются: у не-`Case` их может не
            # быть вовсе, и обход упал бы разбором чужого объекта.
            continue
        for c in cases:
            if c.id in seen:
                dups.append(f"  - {c.id!r}: {seen[c.id]} и {f.name}")
            else:
                seen[c.id] = f.name
    return bad_types, dups


def generate(run: "Run", argv: List[str]) -> int:
    """Оркестрация генератора: одна на дерево (#1474).

    Восемь копий решали одно и то же по-разному, и различия НИКТО НЕ ПРИНИМАЛ —
    они накопились копированием соседнего генератора при заведении набора. Три из
    них были не формой, а СОДЕРЖАНИЕМ, и здесь принята строгая сторона:

      * ОБЛАСТЬ ПРОВЕРКИ ДУБЛЕЙ — весь набор (см. `_scan_suite`);
      * НЕ-`Case` В `CASES` — ОТКАЗ. Один набор из восьми на этом пропускал
        МОДУЛЬ ЦЕЛИКОМ и продолжал успехом: коллекция не порождалась, а прогон
        выходил нулём — «не выполнилось», поданное как зелёное (`e2e-flow.md`
        §1). Шесть не проверяли вовсе;
      * ПОМОЩНИК СРЕДИ КЕЙСОВ не грузится как набор кейсов (см. `_case_modules`).

    Отдельная проверка кейсов делегируется, ЕСЛИ она у набора есть, и отказывает
    явно, если её нет: молчаливый успех на `--validate` там, где проверять нечем,
    сообщал бы, что кейсы проверены.
    """
    args = list(argv[1:])
    if "--validate" in args:
        validator = run.scripts_dir / "validate-cases.py"
        if not validator.is_file():
            sys.stderr.write(
                f"gen: --validate запрошен, а проверки кейсов у набора нет ({validator}).\n"
                "Это ОТКАЗ, а не пропуск: выйти успехом значило бы сообщить, что кейсы\n"
                "проверены.\n")
            return 1
        import runpy
        sys.argv = [str(validator)]
        runpy.run_path(str(validator), run_name="__main__")  # он сам зовёт sys.exit
        return 0

    run.out_dir.mkdir(parents=True, exist_ok=True)
    want = set(args)
    found = _case_modules(run)
    if not found:
        sys.stderr.write(f"gen: FAIL — модулей кейсов в {run.cases_dir} нет.\n"
                         "Ноль коллекций — это отказ, а не пустая работа.\n")
        return 1

    bad_types, dups = _scan_suite(run)
    if bad_types:
        sys.stderr.write(
            "gen: FAIL — в CASES лежит не-Case:\n" + "\n".join(bad_types) + "\n"
            "Модуль кейсов, который нельзя сериализовать, НЕ пропускается: пропуск\n"
            "даёт набор без этих кейсов при нулевом коде возврата.\n")
        return 1
    if dups:
        sys.stderr.write("gen: FAIL — идентификатор кейса повторяется в наборе "
                         "(обязан быть уникален):\n" + "\n".join(dups) + "\n")
        return 1

    total = 0
    written = 0
    for f in found:
        res = f.stem
        if want and res not in want:
            continue
        # Тип кейсов и уникальность имён уже решены обходом ВСЕГО набора выше;
        # второй проверки здесь нет намеренно — она была бы недостижимой веткой,
        # то есть документацией контракта, которого код не производит.
        mod = run.load(f)
        cases = getattr(mod, "CASES", [])
        col = build_collection(run.emit, res, cases)
        if run.per_collection is not None:
            findings = run.per_collection(res, col)
            if findings:
                sys.stderr.write(f"[{res}] FAIL — коллекция не записана:\n")
                sys.stderr.write("\n".join(findings) + "\n")
                return 1
        out = run.out_dir / f"{res}.postman_collection.json"
        # Хвостовой перевод строки — у ВСЕХ. Его нёс один набор из восьми, и это
        # было не решением, а недосмотром: файл без него показывается в каждом
        # diff'е строкой «\ No newline at end of file».
        out.write_text(json.dumps(col, indent=2, ensure_ascii=False) + "\n")
        print(f"[{res}] {len(cases)} cases → {out.relative_to(run.root)}")
        total += len(cases)
        written += 1

    # Перепись: «ноль находок» обязано быть отличимо от «ноль прочитанного».
    print(f"[gen] модулей кейсов {len(found)}, коллекций записано {written}, кейсов {total}")
    if written == 0:
        sys.stderr.write("gen: FAIL — не записано ни одной коллекции; отбор не совпал "
                         f"ни с одним модулем ({sorted(want)}).\n")
        return 1
    if run.after_all is not None:
        return run.after_all(run.out_dir)
    return 0


# ─────────────────────────────────────────────────────────────────────────────
# ОЖИДАНИЕ ОПЕРАЦИИ: тело одно на дерево, решения набора — параметрами (#1475)
# ─────────────────────────────────────────────────────────────────────────────
#
# ШЕСТЬ КОПИЙ РАСХОДИЛИСЬ ПО ШЕСТИ ОСЯМ, и по каждой ниже принята сторона.
# Объединять «суммой возможностей» было бы нельзя: одиннадцать параметров, из
# которых набор пользуется двумя-тремя, — это унификация по самой ШИРОКОЙ
# семантике, то есть выдача каждому поведения, которого он не просил. Поэтому
# общим стало то, что у всех ОДНО, а различия названы параметрами с умолчанием,
# сохраняющим прежнее поведение там, где оно было верным.
#
#   1. СТРАЖ ПУСТОГО ИДЕНТИФИКАТОРА — принят. Его несли registry, nlb и vpc;
#      compute и storage не несли, iam нёс в другом месте (см. `pre_extra`).
#      Без него шаг, следующий за синхронно отвергнутой мутацией, уходит на
#      литеральный адрес `/operations/{{opId}}`, получает отказ и повторяет его
#      весь бюджет — то есть выжигает окно на вопрос ни о чём.
#   2. СТРОГИЙ 200 С ТЕЛОМ И РАННИМ ВЫХОДОМ — принят. Его несли registry, nlb и
#      vpc. Без раннего выхода `pm.response.json()` бросает исключение на не-JSON
#      теле отказа, а исключение скрипта НЕ считается упавшим утверждением: оно
#      уходит в четвёртую категорию исхода и не вычитается из вердикта.
#      Диагноз при этом ставится по тексту отказа — тело печатается.
#   3. ВЕЛИЧИНА БЮДЖЕТА — решение набора: у registry путь длиннее прочих.
#      Параметр без умолчания в вызове набора, видимый на связывании.
#   4. ИМЯ ШАГА — уникальное `poll-op-<N>` у пяти наборов; у iam фиксированное,
#      и это РЕШЕНО: его сериализация приписывает имени идентификатор кейса, так
#      что уникальность приходит оттуда. Отсюда `unique_name`.
#   5. ИСХОД ОПЕРАЦИИ (`must_fail`, `capture_id_to`) — общий словарь, а не
#      полоса набора: захват идентификатора ПОСЛЕ доказанного отсутствия ошибки
#      есть норма дерева (`testing.md` §«Fixture-seed обязан проверять op.error»),
#      и держать её у одного набора значило бы оставить фантом остальным.
#   6. ВОЗВРАТ К ПРЕДЫДУЩЕМУ ШАГУ и ПЕРЕЧЕНЬ ФИКСТУР — полоса nlb, и она
#      приходит сюда готовыми строками через `tail`: общий слой не решает, когда
#      набору перезапускать свою мутацию.

# Счётчик уникальных имён шагов опроса. Список, а не число, намеренно: набор
# сбрасывает его перед каждой коллекцией, и сброс обязан быть виден отсюда.
_POLL_SEQ = [0]


def op_poll_step(step_cls, *, auth=None, op_var: str = "opId",
                              budget: int = 30, interval_ms: int = 500,
                              unique_name: bool = True,
                              pre_extra=(), step_extra=None,
                              must_fail: bool = False, must_fail_code: int = 0,
                              must_fail_message: str = "",
                              capture_id_to: str = "", id_expr: str = "",
                              tail=()):
    """Шаг опроса операции до завершения — один на дерево.

    `auth` — АКТОР ОПРОСА, и он обязан совпадать с тем, кто мутацию создал:
    чтение операции owner-scoped по построению, и посторонний получает тот же
    не-раскрывающий 404, что и на несуществующий идентификатор. Шаг, сделанный
    под одной личностью, и опрос под умолчанием коллекции спрашивают об операции
    РАЗНЫХ субъектов, и честный 404 читается как «операция исчезла».

    `capture_id_to` — захват идентификатора созданного ресурса ЗДЕСЬ, а не из
    ответа мутации: `Operation` несёт ПРЕДВАРИТЕЛЬНО ВЫДЕЛЕННЫЙ идентификатор в
    `metadata` ещё до работы воркера, поэтому он есть и у операции, завершившейся
    ОШИБКОЙ. Захват из синхронного ответа — это захват идентификатора ресурса,
    которого может не существовать: дальше кейс правит, читает и убирает ФАНТОМ,
    а край отвечает кодами, ни один из которых не называет настоящую причину.
    Поэтому: опрос до завершения → утверждение об отсутствии ошибки → и только
    тогда запись в переменную; на ошибке переменная СНИМАЕТСЯ.

    `id_expr` без `capture_id_to` отвергается ЯВНО: выражение выбора читается
    только при захвате, и принять его, не прочтя, значило бы пообещать
    вызывающему поведение, которого нет.
    """
    if id_expr and not capture_id_to:
        raise ValueError(
            "id_expr без capture_id_to: выражение выбора id читается ТОЛЬКО при "
            "захвате, поэтому принять его и не прочесть значило бы пообещать "
            "вызывающему поведение, которого нет. Нужен другой опрос — назови "
            "op_var; нужен захват — назови capture_id_to")
    if capture_id_to and must_fail:
        raise ValueError("capture_id_to несовместим с must_fail: у операции, "
                         "предмет которой — отказ, нет созданного ресурса")
    if (must_fail_code or must_fail_message) and not must_fail:
        raise ValueError("must_fail_code/must_fail_message требуют must_fail=True: "
                         "утверждать текст отказа у операции, от которой отказа не "
                         "ждут, значит объявить проверку, которая не исполнится")

    _POLL_SEQ[0] += 1
    name = f"poll-op-{_POLL_SEQ[0]}" if unique_name else "poll-op"

    script = [
        # Опрашивать нечего: предыдущий шаг отвергнут синхронно и операции не
        # создал. Это ЕДИНСТВЕННЫЙ случай, когда шаг не утверждает ничего.
        f"if (!pm.environment.get({js_str(op_var)})) {{",
        "  pm.environment.unset('_pollCount');",
        "  return;",
        "}",
        # ОТКАЗ НА ЧТЕНИИ ОПЕРАЦИИ — КРАСНОЕ. Пока ранний выход стоял ВЫШЕ этой
        # строки, утверждение не могло упасть by construction: до него доходили
        # только те ответы, которые оно и так принимает.
        "pm.test('poll status 200', () => pm.expect(pm.response.code, pm.response.text()).to.eql(200));",
        # Утверждение выше уже сказало «нет»; уходим до того, как json() бросит
        # на не-JSON теле отказа — исключение скрипта скрыло бы ровно то падение,
        # о котором сообщает, и ушло бы в четвёртую категорию исхода.
        "if (pm.response.code !== 200) {",
        "  pm.environment.unset('_pollCount');",
        "  return;",
        "}",
        "const j = pm.response.json();",
        "const pc = parseInt(pm.environment.get('_pollCount') || '0', 10);",
        f"if (!j.done && pc < {budget}) {{",
        "  pm.environment.set('_pollCount', String(pc + 1));",
        # НАСТОЯЩАЯ ПАУЗА МЕЖДУ ПОЛЛАМИ. newman исполняет тест-скрипт синхронно и
        # зовёт setNextRequest ДО любого setTimeout, поэтому занятое ожидание —
        # единственный способ реально разнести опросы. Без него петля на 30
        # итераций покрывает доли секунды, и «поллер сдался» читается как лаг
        # сервиса при здоровом асинхронном хвосте.
        f"  const _pd = Date.now(); while (Date.now() - _pd < {interval_ms}) {{ /* inter-poll delay */ }}",
        "  pm.execution.setNextRequest(pm.info.requestName);",
        "  return;",
        "}",
        "pm.environment.unset('_pollCount');",
    ]
    if not unique_name:
        # Счётчик сбрасывается по имени шага, а имя здесь общее на коллекцию —
        # значит и флаг входа обязан сниматься здесь же.
        script.append("pm.environment.unset('_pollStarted');")
    script += [
        "pm.test('operation done', () => pm.expect(j.done, JSON.stringify(j)).to.eql(true));",
        "if (j.error) pm.environment.set('lastOpError', JSON.stringify(j.error));",
        "else pm.environment.unset('lastOpError');",
        "if (j.response) pm.environment.set('lastOpResponse', JSON.stringify(j.response));",
    ]
    script += list(tail)

    if must_fail:
        script.append(
            "pm.test('operation refused the request (carries an error)', () => "
            "  pm.expect(j.error, JSON.stringify(j)).to.be.an('object'));")
        if must_fail_code:
            script.append(
                f"pm.test({js_str(f'refusal carries gRPC code {must_fail_code}')}, () => "
                f"  pm.expect(j.error && j.error.code, JSON.stringify(j)).to.eql({must_fail_code}));")
        if must_fail_message:
            script.append(
                "pm.test('refusal keeps the contract tone', () => "
                "  pm.expect(j.error && j.error.message, JSON.stringify(j))"
                f"    .to.eql({json.dumps(must_fail_message)}));")
    if capture_id_to:
        expr = id_expr or ("(j.metadata && Object.keys(j.metadata)"
                           ".filter(k => k.endsWith('Id')).map(k => j.metadata[k])[0]) || ''")
        script += [
            "pm.test('operation succeeded (no phantom resource id)', () => "
            "  pm.expect(j.error && JSON.stringify(j.error), 'operation.error')"
            "    .to.eql(undefined));",
            "if (j.error) {",
            f"  pm.environment.unset({js_str(capture_id_to)});",
            "} else {",
            f"  const _cid = ({expr});",
            f"  if (_cid) pm.environment.set({js_str(capture_id_to)}, String(_cid));",
            f"  else pm.environment.unset({js_str(capture_id_to)});",
            "}",
        ]

    kwargs = dict(step_extra or {})
    return step_cls(
        name=name,
        method="GET",
        path="/operations/{{" + op_var + "}}",
        auth=auth or None,
        pre_script=list(pre_extra),
        test_script=script,
        **kwargs,
    )
