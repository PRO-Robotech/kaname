# tests/newman/kacholib/stems.sh — ОТБОР коллекций набора newman, один на дерево.
#
# Рядом с общим слоем генератора (`gen_shared.py`) и по той же причине: что
# именно гонит суита — ОДИН предмет, и мест у него должно быть одно. Пока
# перечень был рукописным массивом у каждого прогонщика, он расходился с деревом
# молча и расходился ровно в одну сторону: новый модуль кейсов появляется,
# коллекция генерируется, а массив о ней не знает.
#
# ФАЙЛ СОДЕРЖИТ ТОЛЬКО ОБЪЯВЛЕНИЯ. Ни одной исполняемой строки на верхнем уровне:
# его берут через `source` из прогонщиков и из гейта дерева, и побочное действие
# при загрузке означало бы, что «спросить перечень» меняет состояние.
#
# ПРАВИЛО ОТБОРА — ТО ЖЕ, ЧТО У ГЕНЕРАТОРА (`gen_shared._case_modules`): имя с
# ведущим подчёркиванием — ПОМОЩНИК, а не набор кейсов. Прежде прогонщики
# пропускали только `__init__`/`__main__`, и различие выглядело решением, не
# будучи им: у vpc/geo/gateway модулей с подчёркиванием нет вовсе, поэтому узкое
# правило нигде не проявлялось. У nlb и registry такой модуль есть — по узкому
# правилу `_helpers` стал бы ОЖИДАЕМОЙ коллекцией, суита доложила бы MISSING и
# покраснела бы по причине, которой нет.
#
# Согласие правила с генератором держится не этим комментарием, а гейтом
# `internal/repohygiene/artifactgates` `TestNewmanSharedStemSelectorMatchesTheGenerator`:
# он ИСПОЛНЯЕТ обе функции ниже на каждом наборе дерева и сверяет ОТВЕТ с
# правилом генератора, а не текст с текстом.

# newman_expected_stems <newman_dir> — коллекции, которые ДОЛЖНЫ существовать:
# по одной на каждый модуль кейсов (`gen.py` эмитит 1:1).
#
# Отсутствие ожидаемой коллекции — не пропуск, а тихая потеря покрытия, поэтому
# прогонщик обязан знать про неё и доложить MISSING.
newman_expected_stems() {
  local dir="${1:?newman_expected_stems: не назван каталог набора}"
  local f stem
  if [[ ! -d "$dir/cases" ]]; then
    echo "newman_expected_stems: нет каталога $dir/cases — отбор беспредметен" >&2
    return 1
  fi
  for f in "$dir"/cases/*.py; do
    [[ -e "$f" ]] || continue
    stem="$(basename "$f" .py)"
    # Правило генератора: ведущее подчёркивание — помощник. Оно ШИРЕ, чем
    # `__init__`/`__main__`, и именно это различие уже стоило бы красного.
    [[ "$stem" == _* ]] && continue
    printf '%s\n' "$stem"
  done
}

# newman_present_stems <newman_dir> — коллекции, ФАКТИЧЕСКИ сгенерированные.
#
# Второй перечень нужен отдельно от первого: коллекция, сгенерированная без
# своего модуля кейсов, — тоже расхождение, и вердикт обязан её накрыть, а не
# пройти мимо.
newman_present_stems() {
  local dir="${1:?newman_present_stems: не назван каталог набора}"
  local f
  if [[ ! -d "$dir/collections" ]]; then
    echo "newman_present_stems: нет каталога $dir/collections — отбор беспредметен" >&2
    return 1
  fi
  for f in "$dir"/collections/*.postman_collection.json; do
    [[ -e "$f" ]] || continue
    basename "$f" .postman_collection.json
  done
}

# newman_all_stems <newman_dir> — объединение обоих перечней в устойчивом
# порядке. Ровно то, что прогонщик обязан ПРОГНАТЬ и накрыть вердиктом: ни одна
# коллекция не пропускается молча, а ожидаемая-но-отсутствующая доезжает до
# таблицы как MISSING.
newman_all_stems() {
  local dir="${1:?newman_all_stems: не назван каталог набора}"
  { newman_expected_stems "$dir"; newman_present_stems "$dir"; } | sort -u
}
