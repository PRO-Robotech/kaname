"""Case-set: встроенный доступ платформы ВИДЕН на поверхности выдач.

ПРЕДМЕТ. Права служебных учёток и публичное чтение глобального справочника были
заведены помимо поверхности выдач — прямыми фактами посева. Администратор,
спрашивающий «кому что выдано», получал ответ, неполный ровно на всё встроенное,
и отличить «ничего не выдано» от «выдано в обход» не мог ничем.

Теперь встроенный доступ — СИСТЕМНЫЕ ВЫДАЧИ, и здесь это проверяется ЧЁРНЫМ
ЯЩИКОМ: через тот же публичный список, которым пользуется администратор.
Внутренние пробы (перепись свежей базы, отзыв через путь записи, вопрос к
вердикту) утверждают о механизме; эта — о том, что механизм ВИДЕН снаружи.

ЧТО УТВЕРЖДАЕТСЯ, И ПОЧЕМУ ИМЕННО ЭТО:

  * системная выдача есть в ответе публичного списка и помечена `system` — иначе
    «видно» осталось бы утверждением о базе, а не о продукте;
  * у неё непусто `grantedRelation` и ПУСТО `roleId` — это вторая форма выдачи;
    ровно одно из двух полей непусто by construction, и ответ обязан это
    показывать, иначе клиент не отличит форму от формы;
  * среди системных есть выдача подстановочному субъекту (`subjectId = "*"`) —
    ею держится публичное чтение справочника, и она единственная, чей субъект
    нельзя назвать поимённо;
  * ЗАКОННЫЙ БЛИЗНЕЦ: в том же ответе есть ОБЫЧНАЯ выдача — с ролью и без
    признака системности. Без него проба зеленела бы и на ответе, где системными
    объявлены все строки подряд.

Test-design: CONF (форма ответа против контракта AccessBinding), ECP (две формы
выдачи как два класса эквивалентности), error-guessing (пустой список читается
как «не выдано» — поэтому непустота утверждается отдельно).

Auth: Bearer {{jwtBootstrap}} — кластерный администратор. Список выдач сужается
пообъектно, и системные выдачи лежат на кластере: субъект, которому их не
выдавали, их и не увидит. Это не послабление пробы, а предмет: «кому что выдано»
спрашивает администратор.
"""

CASES = []


# ---------------------------------------------------------------------------
# IAM-ACB-SYSGRANT-VISIBLE-OK — встроенный доступ виден перечислением выдач.
# ---------------------------------------------------------------------------
CASES.append(Case(
    id="IAM-ACB-SYSGRANT-VISIBLE-OK",
    title="GET /iam/v1/accessBindings as jwtBootstrap → 200; системные выдачи видны, "
          "несут grantedRelation без roleId, среди них есть подстановочный субъект",
    classes=["CONF", "AUTHZ"],
    priority="P0",
    steps=[
        Step(
            name="list-access-bindings-as-cluster-admin",
            method="GET",
            path="/iam/v1/accessBindings?pageSize=1000",
            auth="jwtBootstrap",
            test_script=[
                *assert_status(200),
                "pm.test('ответ несёт непустой массив выдач', () => {",
                "  const j = pm.response.json();",
                "  pm.expect(j.accessBindings, JSON.stringify(j)).to.be.an('array');",
                "  pm.expect(j.accessBindings.length, 'выдач на странице').to.be.greaterThan(0);",
                "});",
                "pm.test('встроенный доступ ВИДЕН: есть системные выдачи', () => {",
                "  const all = pm.response.json().accessBindings || [];",
                "  const sys = all.filter(b => b.system === true);",
                "  pm.expect(sys.length, 'системных выдач в ответе (всего строк ' + all.length + ')')",
                "    .to.be.greaterThan(0);",
                "});",
                "pm.test('у системной выдачи ВТОРАЯ форма: отношение без роли', () => {",
                "  const sys = (pm.response.json().accessBindings || []).filter(b => b.system === true);",
                "  sys.forEach(b => {",
                "    pm.expect(b.grantedRelation, 'grantedRelation у ' + b.id).to.be.a('string').and.not.equal('');",
                "    pm.expect(b.roleId || '', 'roleId у системной выдачи ' + b.id + ' обязан быть пуст')",
                "      .to.equal('');",
                "  });",
                "});",
                "pm.test('публичное чтение справочника: есть выдача подстановочному субъекту', () => {",
                "  const sys = (pm.response.json().accessBindings || []).filter(b => b.system === true);",
                "  const wildcard = sys.filter(b => b.subjectId === '*');",
                "  pm.expect(wildcard.length, 'выдач субъекту «любой аутентифицированный» среди ' + sys.length)",
                "    .to.be.greaterThan(0);",
                "  wildcard.forEach(b => {",
                "    pm.expect(b.subjectType, 'тип подстановочного субъекта').to.equal('user');",
                "  });",
                "});",
                "pm.test('ЗАКОННЫЙ БЛИЗНЕЦ: обычная выдача в том же ответе — с ролью и без признака', () => {",
                "  // Без этого утверждения проба зеленела бы и на ответе, где системными",
                "  // объявлены все строки подряд, — то есть на потере различия, ради",
                "  // которого признак и заведён.",
                "  const all = pm.response.json().accessBindings || [];",
                "  const ordinary = all.filter(b => b.system !== true);",
                "  pm.expect(ordinary.length, 'обычных выдач в ответе').to.be.greaterThan(0);",
                "  ordinary.forEach(b => {",
                "    pm.expect(b.roleId, 'roleId у обычной выдачи ' + b.id).to.be.a('string').and.not.equal('');",
                "    pm.expect(b.grantedRelation || '', 'grantedRelation у обычной выдачи ' + b.id + ' пуст')",
                "      .to.equal('');",
                "  });",
                "});",
            ],
        ),
    ],
))
