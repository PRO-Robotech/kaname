# прощать исход, которого не бывает.
#
# ПОСЛАБЛЕНИЕ НАЗВАНО И ИСТЕКАЕТ. Множество сужается с двух значений до одного
# в тот же заход, которым закрывается #2319; до тех пор набор НЕ утверждает
# сегодняшний `403` правильным — он утверждает лишь то, что отказ принадлежит
# перечню с производителем у каждого значения.
#
