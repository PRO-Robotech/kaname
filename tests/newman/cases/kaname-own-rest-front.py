#
# ПОЧЕМУ МНОЖЕСТВО ВСЁ ЖЕ ДВУЗНАЧНО — ПРИЧИНА УТОЧНЕНА ЗАМЕРОМ (#2319).
#
# Прежде здесь стояло «продукт объявляет одно, а отвечает другое», и это было
# верно, но неточно: причин оказалось ДВЕ, и закрываются они порознь.
#
#   1. В БОЕВОЙ посадке ветвь «назовись» была недостижима by construction:
#      собственный REST-фронт — обычный клиент своего же gRPC-слушателя и
#      дозванивается под КЛИЕНТСКИМ листом службы, поэтому «сертификата нет»
#      ложно на каждом запросе, пришедшем через фронт. ЭТО ПОЧИНЕНО: лист
#      фронта называет хоп, а не вызывающего
#      (services/iam/internal/authzguard/public_caller_policy.go, пробы —
#      own_rest_front_hop_test.go).
#
#   2. ЭТОТ ШАРД поднимает службу в DEV-посадке
#      (deploy/helm/umbrella/values.dev.yaml, `kaname: authMode: dev`), а в dev
#      политика вызывающего вырождается ЦЕЛИКОМ — безымянный проходит её
#      насквозь, и отказ ему выносит дверь, прежним `403`. Поэтому починка п.1
#      сегодняшнего ответа СТЕНДА не меняет, и множество остаётся двузначным.
#
# Сузить его можно не правкой тона, а подъёмом шарда в боевую посадку
# (ban #16: production-mode ВЕЗДЕ). Пока этого нет, «403» здесь — не «правильно»,
# а «так отвечает dev-посадка».
