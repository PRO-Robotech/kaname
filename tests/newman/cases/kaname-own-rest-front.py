# БЕЗЫМЯННЫЙ ВЫЗЫВАЮЩИЙ.
#
# ЗДЕСЬ СТОЯЛО «подсказку аутентификации на этой поверхности производить нечему,
# поэтому утверждать 401 значило бы записать „Тогда“ без производителя» — и это
# УТВЕРЖДЕНИЕ ПЕРЕЖИЛО СВОЙ ПРЕДМЕТ, прожив в наборе ровно десять часов до его
# появления. Производитель есть: `restfront.withAuthenticationChallenge`
