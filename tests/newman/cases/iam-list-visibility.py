"""Case-set iam-list-visibility — страница списка есть страница ВИДИМОГО (задача #645).

ПРЕДМЕТ, И ПОЧЕМУ ЕГО ОБЯЗАН ВИДЕТЬ ЧЁРНЫЙ ЯЩИК. Дефект наблюдали снаружи:
арендатор получал `200` с пустым массивом на списке, тогда как чтение того же
объекта по идентификатору отвечало `200`. Проба, доказывающая фикс, обязана
уметь увидеть его тем же способом, каким его увидели, — отсюда этот набор.
Внутренние пробы (`services/iam/internal/apps/kaname/api/listvisibility`) держат
ПОРЯДОК между страницей и сужением на настоящем Postgres и настоящей модели
прав; здесь проверяется, что этот порядок доезжает до края.

КАК ЗДЕСЬ ВОСПРОИЗВОДИТСЯ ПОРОГ, БЕЗ ЕДИНОГО СОЗДАНИЯ. Порог задачи определён
ОТНОСИТЕЛЬНО `page_size`: «невидимых предшественников больше, чем страница».
Значит его не нужно набивать шестьюдесятью объектами — достаточно попросить
небольшую страницу у вызывающего, перед чьим объектом лежат чужие, созданные
РАНЬШЕ. Такой вызывающий в фикстуре уже есть: `jwtAccountAdminB` владеет
аккаунтом B, который засеивается ПОСЛЕ аккаунта A, а весь аккаунт A ему невидим.
Список запрашивается БЕЗ фильтра по аккаунту — иначе сужение по `accountId`
убрало бы чужие строки из окна ещё в SQL, и порога не осталось бы вовсе.

  * до фикса: окно из `pageSize` СТАРЕЙШИХ строк целиком принадлежит аккаунту A,
    сужение по правам выбрасывает его без остатка → `200 {}`;
  * после фикса: кандидаты отбираются сужёнными, объект аккаунта B в странице.

СИЛА ДИСКРИМИНАТОРА НАЗВАНА ЧЕСТНО. Порог держится, пока население аккаунта A по
этому типу больше `pageSize` (для проектов замерено 55 при странице 50 —
`cases/iam-project.py`, комментарий к IAM-PRJ-LS-CRUD-OK). На свежесозданной базе,
где строк меньше страницы, кейс останется ЗЕЛЁНЫМ и на дефектной сборке — он не
станет ложно падать, он просто перестанет различать. Поэтому он регрессионный
замок, а не доказательство наличия дефекта, и `pageSize` выбран маленьким (25),
чтобы различал как можно дольше.

ОТРИЦАНИЕ — БЕЗ ОБЁРТКИ ПОВТОРА, И ЭТО НЕ ЗАБЫВЧИВОСТЬ. Утверждение «чужого в
моей странице нет» повторять нельзя: повтор на отрицании пережидает ровно то, ради
чего проба написана (`testing.md` §e2e-инварианты). Положительное плечо повтора
тоже не несёт: объекты фикстуры существуют задолго до прогона, окно материализации
прав к ним отношения не имеет — обёртка ставится ТОЛЬКО на первый доступ к своему
СВЕЖЕМУ ресурсу, а свежих здесь нет ни одного.

ПОЧЕМУ ТРИ ПОВЕРХНОСТИ, А НЕ СЕМЬ. Конструкция выше требует у вызывающего
собственного объекта КАЖДОГО типа, созданного позже чужих. Фикстура даёт такой
объект на стороне аккаунта B для трёх типов: проект (`projectB1Id`), аккаунт
(`accountBId`) и пользователь (`userAABId` — его собственная строка, тот самый
ПОЛ поверхности). Для групп, служебных учёток, ролей и привязок доступа
B-стороны в фикстуре нет вовсе, и честный кейс там требует либо создания в
прогоне, либо расширения фикстуры. Это записано задачей, а не подменено слабым
утверждением: набор без предмета зеленеет всегда и занимает место настоящего.

ПОЛ ПОВЕРХНОСТИ ПОЛЬЗОВАТЕЛЕЙ ПРОВЕРЯЕТСЯ ЗДЕСЬ ЖЕ. Собственная строка
вызывающего видна ему без единого кортежа, и она обязана быть УСЛОВИЕМ ОТБОРА
страницы, а не фильтром по уже взятой: строка становится полом, только если она в
страницу попала, а собственная строка может лежать сколь угодно далеко за окном.
Это чёрно-ящичный близнец пробы 645-09 `own_user_row`.

Pre-conditions: `tests/authz-fixtures/setup.sh` (jwtAccountAdminB, accountAId,
accountBId, projectA1Id, projectB1Id, userAAAId, userAABId).
"""

CASES = []

# Страница намеренно МАЛЕНЬКАЯ: она и есть порог. 25 выбрано так, чтобы
# (а) вместить видимое вызывающему по каждому типу с запасом даже после утечек
# прошлых прогонов, и (б) остаться много меньше населения аккаунта A, за счёт
# которого порог и существует.
PAGE = 25

# Каждый набор: (slug, путь без пагинации, поле массива в ответе, свой id,
# чужой id, выражение «строка принадлежит вызывающему»).
_SURFACES = [
    (
        "projects", "/iam/v1/projects", "projects",
        "projectB1Id", "projectA1Id",
        "r.accountId === pm.environment.get('accountBId')",
    ),
    (
        "accounts", "/iam/v1/accounts", "accounts",
        "accountBId", "accountAId",
        "r.id === pm.environment.get('accountBId')",
    ),
    (
        "users", "/iam/v1/users", "users",
        "userAABId", "userAAAId",
        # Ответ пользователя аккаунта БОЛЬШЕ НЕ НАЗЫВАЕТ (kacho#471): у человека
        # их столько, сколько членств, и одного значения, которое можно было бы
        # сравнить, не существует. Признак принадлежности берётся оттуда же,
        # откуда его берёт сам край, — из членств: строка принадлежит
        # вызывающему тогда и только тогда, когда она состоит в его аккаунте, а
        # состав аккаунта отдаёт тот же список, суженный аккаунтом.
        #
        # Это НЕ ослабление: прежний предикат утверждал ровно то же («строка
        # принадлежит аккаунту B»), только читал это из поля, которого больше
        # нет. Состав по-прежнему проверяется целиком, а не по одному
        # названному чужаку — на это есть отдельное утверждение выше.
        "membersOfB.includes(r.id)",
    ),
]

# Поверхности, которым нужен предварительный шаг: он приносит то, чего в ответе
# основного шага больше нет. Ключ — slug.
#
# Шаг ОБЯЗАН быть громким: пустой состав аккаунта сделал бы утверждение состава
# тождественно ложным, а недоступный — тождественно истинным. Оба исхода
# называются здесь же, а не обнаруживаются на разборе чужого прогона.
_PRELUDE = {
    "users": Step(
        name="list-members-of-own-account",
        method="GET",
        path="/iam/v1/users?accountId={{accountBId}}&pageSize=1000",
        auth="jwtAccountAdminB",
        test_script=[
            *assert_status(200),
            "const j = pm.response.json();",
            "const body = JSON.stringify(j);",
            "const rows = j.users || [];",
            "pm.test('[645-users] account membership listing is usable', () => {",
            "  pm.expect(rows, body).to.be.an('array');",
            "  pm.expect(rows.length, 'состав аккаунта пуст: утверждение состава "
            "на следующем шаге стало бы тождественно ложным, а разбор указал бы "
            "на край вместо фикстуры. Ответ: ' + body).to.be.above(0);",
            "});",
            "pm.environment.set('membersOfBIds', rows.map(r => r.id).join(','));",
        ],
    ),
}


for _slug, _path, _field, _own_var, _foreign_var, _belongs in _SURFACES:
    _pre = _PRELUDE.get(_slug)
    CASES.append(Case(
        id=f"IAM-645-LIST-VISIBLE-PAGE-{_slug.upper()}",
        title=(f"{_slug}: own object is on the FIRST small page though older "
               f"invisible rows precede it, and no foreign row comes with it"),
        classes=["AUTHZ", "CRUD", "NEG"],
        priority="P0",
        steps=[
            *([_pre] if _pre else []),
            Step(
                name=f"list-{_slug}-small-page",
                method="GET",
                # БЕЗ фильтра по аккаунту — он убрал бы чужие строки из окна ещё в
                # SQL, и порога не осталось бы (см. доклад файла).
                path=f"{_path}?pageSize={PAGE}",
                auth="jwtAccountAdminB",
                test_script=[
                    "const j = pm.response.json();",
                    "const body = JSON.stringify(j);",
                    f"const rows = j.{_field} || [];",
                    f"const own = pm.environment.get('{_own_var}');",
                    f"const foreign = pm.environment.get('{_foreign_var}');",
                    # Состав аккаунта — из предварительного шага там, где он есть.
                    # Пустой массив у поверхности БЕЗ такого шага безвреден: её
                    # признак принадлежности к нему не обращается.
                    "const membersOfB = (pm.environment.get('membersOfBIds') || '')"
                    ".split(',').filter(Boolean);",
                    # Страж фикстуры: без обоих идентификаторов утверждения ниже
                    # выродились бы в сравнение с undefined и зеленели бы всегда.
                    f"pm.test('[645-{_slug}] fixture supplies both ids', () => {{",
                    "  pm.expect(Boolean(own), 'own id "
                    f"({_own_var}) missing from the environment').to.eql(true);",
                    "  pm.expect(Boolean(foreign), 'foreign id "
                    f"({_foreign_var}) missing from the environment').to.eql(true);",
                    "});",
                    *assert_status(200),
                    f"pm.test('[645-{_slug}] array present', () => "
                    f"pm.expect(rows, body).to.be.an('array'));",
                    # ПОЛОЖИТЕЛЬНОЕ ПЛЕЧО — предмет задачи. Без него отрицание ниже
                    # выполнялось бы пустой страницей, то есть самим дефектом.
                    f"pm.test('[645-{_slug}] own object is on the first small page', () => {{",
                    "  pm.expect(rows.some(r => r.id === own), 'page of ' + rows.length +"
                    f" ' row(s) at pageSize={PAGE} does not contain ' + own +"
                    " ': older rows the caller cannot see occupy the window, so the row"
                    " never reaches the narrowing — that IS the defect of #645. Page: '"
                    " + body).to.eql(true);",
                    "});",
                    # ОТРИЦАНИЕ по конкретному чужому идентификатору. Повтором НЕ
                    # оборачивается никогда.
                    f"pm.test('[645-{_slug}] the named foreign row is absent', () => {{",
                    "  pm.expect(rows.some(r => r.id === foreign), 'foreign row ' + foreign +"
                    " ' leaked into the page: ' + body).to.eql(false);",
                    "});",
                    # ОТРИЦАНИЕ по составу: без него «свой виден» проходило бы и на
                    # сборке, переставшей фильтровать вовсе.
                    f"pm.test('[645-{_slug}] every returned row belongs to the caller', () => {{",
                    f"  const alien = rows.filter(r => !({_belongs}));",
                    "  pm.expect(alien.map(r => r.id), 'rows outside the caller account"
                    " came back on the page: ' + body).to.eql([]);",
                    "});",
                ],
            ),
        ],
    ))
