"""Case-set authz-failclosed — отказ, когда вердикта взять неоткуда.

Своя коллекция, а не кейс внутри authz-deny, потому что ей нужно УСЛОВИЕ,
несовместимое с остальным прогоном: база службы недостижима, а сама служба жива.
Пока кейс жил среди соседей, это условие создать было нечем, и инвариант «нет
вердикта ⇒ отказ, никогда не 200» не проверялся вообще, а выглядело это как
зелёная суита.

ГДЕ ГОНЯЕТСЯ И ЧЕЙ ПРЕДМЕТ (e2e-flow.md §7а; kaname#415). Производитель каждого
утверждения — САМА служба на собственном публичном фронте автономного стенда
(`address_own_front` в конце модуля). Условие создаёт задание `stand` процесса
`.github/workflows/e2e-newman.yml`: ПОСЛЕ всех коллекций собственного фронта шаг
волны предъявляет фронту оба удостоверения, которыми идёт коллекция (контроль: при
живой базе — 200), сворачивает базу стенда (`.github/scripts/stand-own.sh db-fold` —
служба остаётся жить), гоняет эту коллекцию прогонщиком набора и отдаёт вердикт
числами; следующий шаг возвращает базу при любом исходе (`db-unfold`). Не удалось
свернуть базу — шаг называет это «условие не создано», а не красным и не зелёным.

Прежняя редакция гонялась против КРАЯ платформы, сворачивала базу через кластер и
утверждала, КАКАЯ ПОЛОСА КРАЯ ответила (полоса отзыва, полоса ключей). На
автономном стенде края нет вовсе, и предмет переутверждён по фактическому
производителю — службе. Полосы края остались предметом края: их держат пробы его
дерева (PRO-Robotech/kacho:gateway/internal/e2e/revocation_check_e2e_test.go,
PRO-Robotech/kacho:gateway/internal/middleware/auth_keysource_unavailable_test.go).


ЧТО ПРОИЗВОДИТ ОТКАЗ ПОД ЭТИМ УСЛОВИЕМ — ИЗМЕРЕНО, А НЕ ВЫВЕДЕНО
==============================================================

Замер на автономном стенде (2026-10-01): база свёрнута остановкой её контейнера,
служба жива; путь списка проектов, предъявитель машинного посева.

    предъявитель, предъявленный фронту в пределах срока кеша вердикта об отзыве
                                     → 503 {"code":14,"message":"request not performed; try again later","details":[]}
    тот же предъявитель, чужой `kid` → 401 {"code":16,"message":"credential is not accepted","details":[]}
    предъявитель без свежего вердикта об отзыве
                                     → 401 {"code":16,"message":"credential is not accepted","details":[]}

до свёртки — 200 со страницей, 401 на чужом `kid`; после возврата базы — снова
200. Устройство, которое за этим стоит, и почему волна устроена именно так:

  * рубеж предъявителя фронта сначала проверяет подпись по снимку набора ключей и
    спрашивает авторитет отзыва; ПОЛОЖИТЕЛЬНЫЙ вердикт об отзыве («не отозван»)
    фронт помнит срок кеша (у стенда — 30 с,
    `KANAME_AUTHN__PRESENTED_CREDENTIAL__REVOCATION_CACHE_TTL`);
  * не смог спросить авторитет либо реестр ключей — отказ рубежа, НАМЕРЕННО
    неотличимый от негодного удостоверения: 401 тем же текстом
    (`internal/presentedcred/reader.go`, `unavail`). Это свойство держит проба
    уровня кода `internal/presentedcred/reader_test.go`
    (`TestKAN_REV_03_UnavailableAuthorityRefuses`);
  * удостоверение, чей вердикт об отзыве свеж, проходит рубеж, и первый же рубеж
    после него, которому нужна база (положение принципала читается из строк
    людей), отвечает отказом операции — 503 / gRPC 14 фиксированным текстом БЕЗ ЭХА
    ПРИЧИНЫ (`internal/authzguard/address_gate.go`, `TextAddressGateUnavailable`).
    «Не смогли прочесть» не значит «разрешено»;
  * до разбора аргументов запрос не доходит: величина страницы вне диапазона под
    свёрткой даёт тот же 503, а не 400.

Поэтому волна ПРЕДЪЯВЛЯЕТ оба удостоверения фронту прямо перед свёрткой: исход
коллекции не зависит от того, сколько прошло после предыдущих коллекций, — без
этого он был бы функцией расписания (401 после остывания кеша, 503 до него).

Текст отказа утверждается ДОСЛОВНО, и это две вещи сразу: имя производителя (тот
рубеж, которому нужна база) и запрет утечки — сообщение, в которое доехал бы текст
драйвера базы, адрес или код состояния, не совпало бы с фиксированным.


ЧТО КОЛЛЕКЦИЯ УТВЕРЖДАЕТ
========================

Ровно то, что видит арендатор: при недостижимой базе ответ — отказ 503 / gRPC 14,
НИКОГДА не 200 с пустым списком (задача #645), на чтении объекта и на каждом из
семи списков. Утверждение однозначно: `oneOf` не заведён.

ЗАКОННЫЙ БЛИЗНЕЦ ВНУТРИ ВОЛНЫ — кейс `AUTHZ-FAILCLOSED-UNKNOWN-KEY-TWIN`: тот же
путь, тот же предъявитель, отличие в ОДНОМ поле (идентификатор ключа в заголовке),
та же свёрнутая база — и другой исход, 401 от рубежа предъявителя. Без него
«всё отвечает 503» было бы неотличимо от фронта, отвечающего 503 на любой запрос.

ЧЕГО КОЛЛЕКЦИЯ НЕ УТВЕРЖДАЕТ — названо, а не умолчано:

  * что слой прав отказывает при недоступном источнике вердикта, когда ДО него
    запрос доходит. Под этим условием не доходит: рубеж положения стоит раньше и
    спрашивает ту же базу. Механизм держат пробы уровня кода
    (`internal/repo/kaname/pg/pgmaperr_test.go`,
    `TestWrapPgErr_ConnectionRefusals_AreUnavailable` и соседи по файлу);
  * отказ рубежа при недостижимом авторитете отзыва — проба уровня кода выше;
  * полосы края платформы — их предмет у края (ссылки выше).

  ПРЕДИКАТ ВОЗВРАТА: появится условие, при котором база недостижима для слоя прав,
  а рубеж положения отвечает (то есть зависимости РАЗНЫЕ), — утверждение о слое
  прав возвращается сюда своим кейсом.

Техники: классы эквивалентности предъявителя (подлинный · подлинный с чужим ключом),
переход состояния зависимости (база жива → свёрнута → возвращена — последнее держит
шаг возврата), угадывание ошибок (пустая страница вместо отказа, утечка причины в
текст, 400 по разбору аргументов раньше отказа).
"""

