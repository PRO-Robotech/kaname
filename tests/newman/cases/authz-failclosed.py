                "  return CryptoJS.enc.Base64.parse(t).toString(CryptoJS.enc.Utf8);",
                "}",
                "function _b64urlFromText(s) {",
                "  return CryptoJS.enc.Base64.stringify(CryptoJS.enc.Utf8.parse(s))",
