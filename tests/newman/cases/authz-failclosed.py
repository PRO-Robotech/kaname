CASES = []

# Фиксированный текст отказа операции, когда рубеж не смог прочесть свою отметку
# в базе (`internal/authzguard/address_gate.go`, `TextAddressGateUnavailable`).
_STORE_UNREACHABLE_TEXT = "request not performed; try again later"
# Текст рубежа предъявителя на удостоверении, которого фронт не принимает
# (`internal/presentedcred/reader.go`): им служба отвечает и на подделку, и на
# отозванное, и на ключ, которого нет в её наборе.
_CREDENTIAL_REFUSAL_TEXT = "credential is not accepted"


def _refusal_head() -> list:
    """Разбор ответа: тело. Ставится в начало test-скрипта шага."""
    return [
        "let _j; try { _j = pm.response.json(); } catch (_) { _j = {}; }",
        "const _body = pm.response.text();",
    ]


def _unavailable_pair(label: str) -> list:
    """Пара «HTTP-статус + код `google.rpc.Status`».

    Пара, а не один из них: 503 приходит только от UNAVAILABLE, но код несёт
    смысл, а статус — механическое следствие (api-conventions.md).
    """
    return [
        f"pm.test('[FAIL-CLOSED] {label}: 503 Unavailable', () => {{",
        "  pm.expect(pm.response.code, _body).to.eql(503);",
        "});",
        f"pm.test('[FAIL-CLOSED] {label}: grpc code 14 (Unavailable)', () => {{",
        "  pm.expect(_j.code, _body).to.eql(14);",
        "});",
    ]


def _store_unreachable_text(label: str) -> list:
    """Производитель и запрет утечки ОДНИМ утверждением: текст дословно."""
    return [
        f"pm.test('[FAIL-CLOSED] {label}: отказ — фиксированный текст рубежа, которому "
        "нужна база, без эха причины', () => {",
        f"  pm.expect(_j.message, 'текст отказа не тот: либо ответил ДРУГОЙ производитель, "
        "либо в сообщение доехала причина (драйвер базы, адрес, код состояния) — ' + _body)"
        f".to.eql({_STORE_UNREACHABLE_TEXT!r});",
        "});",
    ]


def _never_empty_page(label: str, field: str) -> list:
    """Утверждение о ЗАПРЕЩЁННОМ исходе.

    Не дублирует утверждения об исходе и производителе: те говорят, каким ответ
    обязан быть, это — каким он обязан НЕ быть, и падает с текстом, называющим
    именно ту подмену, ради которой кейс написан.
    """
    return [
        f"pm.test('[FAIL-CLOSED] {label}: never a successful empty page', () => {{",
        "  const _emptyOk = pm.response.code === 200"
        f" && Array.isArray(_j.{field}) && _j.{field}.length === 0;",
        "  pm.expect(_emptyOk, 'answered 200 with an empty array while the store "
        "was unreachable: a tenant cannot tell that from \"nothing has been "
        "granted to you\" — ' + _body).to.eql(false);",
        "});",
    ]


