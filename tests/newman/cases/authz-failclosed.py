"""Case-set authz-failclosed — отказ, когда вердикта о правах взять неоткуда.

Своя коллекция, а не кейс внутри authz-deny, потому что ей нужно УСЛОВИЕ,
несовместимое с остальным прогоном: база источника вердикта, свёрнутая в ноль.
Пока кейс жил среди соседей, это условие создать было нечем, и он держался
исключением в гейте — то есть инвариант «нет вердикта ⇒ отказ, никогда не 200»
не проверялся вообще, а выглядело это как зелёная суита.

Условие создаёт ``scripts/run-failclosed.sh``: ПРОГРЕВАЕТ снимок проверочных
ключей края, сворачивает базу, дожидается, пока решение перестанет отдаваться из
кэша шлюза, гоняет эту коллекцию и поднимает базу обратно. Прогонщик зовёт его
ОТДЕЛЬНОЙ ВОЛНОЙ, после всех остальных — соседям выключенная база сломала бы всё.

Исключения этой коллекции не полагается ни при каком исходе: не удалось создать
условие ⇒ отчёта нет ⇒ гейт докладывает ``authz-failclosed(no-report)`` и
краснеет. «Здесь не запустить» — факт расписания, а не вердикт.

Pre-conditions: `tests/authz-fixtures/setup.sh` (jwtAccountAdminA, accountAId).


ПОЧЕМУ У КАЖДОГО КЕЙСА УТВЕРЖДАЕТСЯ ПРОИЗВОДИТЕЛЬ ОТКАЗА (задача #1198)
=======================================================================

ПРИЗНАК. Семь списочных утверждений объявляли, что отказ производит САМ СЕРВИС, а
проверяли только пару «503 + gRPC 14». Под этим условием такую пару производят
ЧЕТЫРЕ разных места, и по паре они неразличимы:

  * край, полоса проверки подписи — набор проверочных ключей не добыт;
  * край, полоса чтения отзыва — авторитет отзыва не ответил;
  * край, полоса прав — источник вердикта не ответил;
  * СЕРВИС — вердикт не вычислить, потому что база не отвечает.

Совпадение не случайное: недоступность зависимости всюду классифицируется
одинаково и обязана классифицироваться одинаково (#1194). Различать её ИСХОД и её
ПРОИЗВОДИТЕЛЯ — разные задачи, и вторую утверждения не решали.

ПОЧЕМУ КЛАСС ТИХИЙ. Волна, кладущая базу ради проверки отказа сервиса, кладёт
заодно и источник ключей края: наш издатель подписывает своим ключом из ключницы,
а ключница живёт в той же базе. Край держит снимок ключей со сроком (умолчание
процесса — 300 с; действующую величину `scripts/run-failclosed.sh` читает у
РАЗВЁРНУТОГО края, а не предполагает) и обновляет его ЛЕНИВО — значит возраст
снимка на старте волны равномерно размазан по этому сроку, и если он истекает
внутри волны, отвечает край. Прогон при этом
остаётся зелёным: проверка исполняется, отчитывается и утверждает не своё.

РАЗЛИЧИТЕЛЬ — СТРУКТУРНЫЙ, А НЕ ТЕКСТОВЫЙ. Отказ, произведённый СЕРВИСОМ, едет
наружу через мост gRPC↔REST и маршалится публичным маршаллером края, у которого
`EmitUnpopulated=true`; поэтому в теле ВСЕГДА есть ключ `details` (пустым
массивом, если подробностей нет). Отказы самого края пишутся его промежуточными
слоями РУКАМИ, объектом из двух полей, и `details` в них нет НИКОГДА.

Замерено вызовом того же маршаллера, что стоит на боевом пути
(`newPublicJSONPb`, `gateway/internal/restmux/strict_enum.go`):

    public   -> {"code":14,"message":"service unavailable","details":[]}
    internal -> {"code":14,"message":"service unavailable"}

Почему признак взят структурный, а не «текст сообщения сервиса». Текстов у
сервиса под этим условием больше одного (их ставят разные слои), и перечислять их
значило бы завести список, который молча разойдётся с деревом. Ключ `details`
ставит МОСТ, один на все ответы сервиса, — и он не зависит ни от одного из них.

ПРЕДПОСЫЛКА РАЗЛИЧИТЕЛЯ НАЗВАНА И ПРОВЕРЯЕТСЯ ЗДЕСЬ ЖЕ. Он опирается на
`EmitUnpopulated=true` у ПУБЛИЧНОГО маршаллера. Снимут — различитель
перевернётся; но перевернётся он ГРОМКО: полоса сервиса перестанет опознаваться,
и первым же покраснеет положительный контроль ниже, который под тем же условием
обязан доехать до сервиса и получить от него `details`. Тихого зелёного эта
поломка не даёт by construction.

ЧЕГО ЗДЕСЬ НЕТ. Полоса края опознаётся `details`-отсутствием ПЛЮС постоянным
текстом отказа — исключительно чтобы падение НАЗЫВАЛО, какая именно полоса края
ответила. Текст здесь диагностический: вердикт выносит структурный признак.


КАКАЯ ПОЛОСА ОТВЕЧАЕТ ПОД ЭТИМ УСЛОВИЕМ — ИЗМЕРЕНО, А НЕ ВЫВЕДЕНО
=================================================================

Первая редакция различителя ждала `service` от семи списков и `edge:authz` от
чтения одного объекта. Прогон ответил `edge:revocation` на ВСЕ восемь, и это не
дефект продукта, а факт его устройства:

  * авторитет отзыва НАШИХ токенов — тот же iam и та же база, которую эта волна
    и сворачивает: край спрашивает его на внутреннем слушателе iam;
  * полоса отзыва наших токенов fail-closed ПО РЕШЕНИЮ, а не по недосмотру —
    «не дозвонился» не есть «разрешено»; край объявляет это при старте строкой
    `revocation of OUR OWN tokens is read on presentation … unanswered_verdict=refuse`;
  * стоит она на пути АУТЕНТИФИКАЦИИ — то есть перед слоем прав и перед сервисом.

Значит под этим условием запрос не доходит ни до слоя прав, ни до сервиса НИ ПРИ
КАКОМ входе, а `edge:authz` и `service` были ожиданиями, которых не бывает.
Порядок полос не выведен из чтения кода, а виден в том же прогоне: кейс
`AUTHZ-FAILCLOSED-EDGE-KEY-SOURCE-LANE` ЗЕЛЁН, то есть полоса проверочных ключей
отвечает раньше полосы отзыва, а та — раньше прав.

ПОЧЕМУ ПРОГРЕВ ЗДЕСЬ НЕ ПОМОГАЕТ, в отличие от снимка ключей. Ответ авторитета
отзыва край помнит 5 с (`KACHO_INTROSPECTION_CACHE_TTL_SECONDS`, умолчание 5; при
старте край печатает действующую величину полем `cache_ttl_s`). Между последним
ответом авторитета и первым запросом волны прошло 45 с — сворачивание базы 33 с
плюс выжидание кэша решений 12 с. Разрыв больше срока памяти на порядок, и оба
слагаемых нужны самому условию, поэтому укоротить его нечем. Ручку срока не
тронуть по той же причине, что и срок снимка ключей: она читается при СТАРТЕ, а
перекат края обрывает проброс к нему (цена измерена, см. шапку
`scripts/run-failclosed.sh`).

ЧТО ЭТА КОЛЛЕКЦИЯ ПРОВЕРЯЕТ ТЕПЕРЬ. Ровно то, что видит арендатор: при
недостижимом источнике вердикта ответ — отказ 503 / gRPC 14, НИКОГДА не 200 с
пустым списком (задача #645), и произведён он НАЗВАННОЙ полосой. Утверждение
осталось однозначным: `oneOf` не заведён, и ответ другой полосы — например
устаревший снимок ключей, ради которого различитель и вводился, — по-прежнему
роняет кейс.

ЧТО ЭТА КОЛЛЕКЦИЯ БОЛЬШЕ НЕ ПРОВЕРЯЕТ — названо, а не умолчано:

  * что слой прав края отказывает при недоступном источнике вердикта. Свойство
    держит `gateway/internal/middleware/authz_test.go`
    `TestAuthz_GRPC_CheckerError_FailClosed` — с законным близнецом
    `TestAuthz_GRPC_CheckerError_FailOpen` рядом;
  * что САМ СЕРВИС отвечает отказом, а не пустой страницей, когда его базы нет.
    Механизм держит `services/iam/internal/repo/kacho/pg/pgmaperr_test.go`
    (`TestWrapPgErr_ConnectionRefusals_AreUnavailable` и соседи по файлу);
    поверхностной пробы по семи спискам сегодня нет НИ ОДНОЙ.

  ПРЕДИКАТ ВОЗВРАТА обоих: появится условие, при котором вердикт недостижим, а
  авторитет отзыва отвечает (то есть зависимости РАЗНЫЕ), — оба утверждения
  возвращаются сюда вместе со своими полосами. Пока зависимость одна, сквозная
  проба этих двух свойств невозможна by construction, и молчать об этом нельзя:
  утверждение, которого не бывает, — не покрытие, а его видимость.

ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ РАЗЛИЧИТЕЛЯ ЖИВ, И ЕГО ДВА. Внутри коллекции — кейс
`AUTHZ-FAILCLOSED-EDGE-KEY-SOURCE-LANE`: та же поверхность, тот же предъявитель,
тот же исход 503/14 — и ДРУГАЯ ожидаемая полоса. Пока в наборе два разных
ожидания, «различитель залип на одном значении» не проходит. Снаружи —
`scripts/run-failclosed.sh`: ДО сворачивания базы он предъявляет тот самый запрос,
что стоял здесь положительным контролем (величина страницы вне диапазона), и
требует 400 с ключом `details`. Это доказывает на ЭТОМ стенде и ЭТИМ маршаллером,
что ответ сервиса различитель опознаёт как `service`. Не сошлось — волна не
стартует, отчёта нет, гейт называет `authz-failclosed(no-report)`.
"""

CASES = []


# ---------------------------------------------------------------------------
# Общий JS: КТО произвёл отказ.
#
# Функция возвращает ИМЯ ПОЛОСЫ, а не «да/нет»: утверждение сравнивает имя с
# ожидаемым, и падение печатает то, что ответило на самом деле, — иначе разбор
# красного начинался бы с перечня упавших шагов вместо текста отказа
# (`testing.md` §«Диагноз ставится по ТЕКСТУ отказа»).
#
# КОРЗИНЫ «ПРОЧЕЕ» НЕТ. Тело, которое не опознано ни одной полосой, возвращает
# `unrecognised:<текст>` — значение, не равное ни одному ожидаемому, поэтому
# такой ответ РОНЯЕТ утверждение и печатает себя. Не-JSON (страница ошибки
# входного контроллера, обрыв) попадает сюда же.
# ---------------------------------------------------------------------------

_LANE_JS = [
    "function _laneOf(j) {",
    "  // Мост gRPC↔REST маршалит статус публичным маршаллером края",
    "  // (EmitUnpopulated=true) ⇒ ключ `details` есть ВСЕГДА. Отказы самого края",
    "  // пишутся руками объектом из двух полей ⇒ `details` в них нет никогда.",
    "  var bridged = !!j && Object.prototype.hasOwnProperty.call(j, 'details')",
    "    && Array.isArray(j.details);",
    "  if (bridged) { return 'service'; }",
    "  var m = (j && typeof j.message === 'string') ? j.message : '';",
    "  // Ниже — ДИАГНОСТИКА, а не вердикт: вердикт вынесен строкой выше.",
    "  if (m === 'token key source unavailable') { return 'edge:key-source'; }",
    "  if (m === 'revocation check unavailable') { return 'edge:revocation'; }",
    "  if (m === 'authz service unavailable') { return 'edge:authz'; }",
    "  return 'unrecognised:' + JSON.stringify(m);",
    "}",
]

# Что означает каждое имя полосы — для текста падения. Перечень читает ЧЕЛОВЕК,
# разбирающий красное, поэтому он говорит не «ожидали X, получили Y», а чем
# именно это плохо.
_LANE_MEANING = {
    "service": "СЕРВИС (ответ приехал мостом gRPC↔REST)",
    "edge:key-source": "КРАЙ, полоса проверочных ключей (снимок ключей устарел и не обновился)",
    "edge:revocation": "КРАЙ, полоса чтения отзыва",
    "edge:authz": "КРАЙ, полоса прав",
}


def _lane_assert(label: str, expected: str) -> list:
    """Утверждение о ПРОИЗВОДИТЕЛЕ отказа.

    Отдельным `pm.test`, а не довеском к утверждению об исходе: исход и
    производитель — разные факты, и падение обязано называть, какой именно из них
    не сошёлся.
    """
    meaning = _LANE_MEANING[expected]
    return [
        f"pm.test('[FAIL-CLOSED] {label}: отказ произвёл {meaning}', () => {{",
        "  pm.expect(_lane, 'отказ произвёл ' + _lane + ', а кейс утверждает про "
        f"{meaning}: тот же исход (503/14) производят ЧЕТЫРЕ разных места, и по "
        "исходу они неразличимы — ' + _body).to.eql(" + repr(expected) + ");",
        "});",
    ]


def _refusal_head() -> list:
    """Разбор ответа: тело, полоса. Ставится в начало test-скрипта шага."""
    return _LANE_JS + [
        "let _j; try { _j = pm.response.json(); } catch (_) { _j = {}; }",
        "const _body = JSON.stringify(_j);",
        "const _lane = _laneOf(_j);",
    ]


def _unavailable_pair(label: str) -> list:
    """Пара «HTTP-статус + код `google.rpc.Status`».

    Пара, а не один из них: 503 приходит только от UNAVAILABLE, но код несёт
    смысл, а статус — механическое следствие (api-conventions.md, таблица края).
    """
    return [
        f"pm.test('[FAIL-CLOSED] {label}: 503 Unavailable', () => {{",
        "  pm.expect(pm.response.code, _body).to.eql(503);",
        "});",
        f"pm.test('[FAIL-CLOSED] {label}: grpc code 14 (Unavailable)', () => {{",
        "  pm.expect(_j.code, _body).to.eql(14);",
        "});",
    ]


def _never_empty_page(label: str, field: str) -> list:
    """Утверждение о ЗАПРЕЩЁННОМ исходе.

    Не дублирует утверждения об исходе и производителе: те говорят, каким ответ
    обязан быть, это — каким он обязан НЕ быть, и падает с текстом, называющим
    именно ту подмену, ради которой кейс написан.
    """
    return [
        f"pm.test('[FAIL-CLOSED] {label}: never a successful empty page', () => {{",
        "  const _emptyOk = pm.response.code === 200"
        f" && Array.isArray(_j.{field}) && _j.{field}.length === 0;",
        "  pm.expect(_emptyOk, 'answered 200 with an empty array while the verdict "
        "source was unreachable: a tenant cannot tell that from \"nothing has been "
        "granted to you\" — ' + _body).to.eql(false);",
        "});",
    ]


# ---------------------------------------------------------------------------
# AUTHZ-FAILCLOSED-OPENFGA-DOWN
#
# Шлюз развёрнут с `authz.enabled=true, authz.failOpen=false`. Когда вопрос о
# правах не может быть отвечен (источник вердикта недоступен), промежуточный слой
# уходит в ветвь ошибки и при failOpen=false ОБЯЗАН ответить 503 / gRPC 14. Ответ
# 200 здесь означал бы, что отсутствие ответа о правах засчитывается за
# «разрешено», — то есть защита снимается ровно тогда, когда она нужнее всего.
#
# Запрос выбран самый обычный (чтение своего аккаунта): предмет — НЕ конкретный
# метод, а поведение слоя прав; на разрешённом в норме запросе отличие «отказал,
# потому что не смог спросить» от «отказал, потому что не положено» видно чище
# всего — в норме этот же запрос отвечает 200.
#
# ПОЛОСА ЗДЕСЬ — `edge:revocation`, И ЭТО УТВЕРЖДАЕТСЯ. Здесь стоял `edge:authz`
# — ожидание, которого под этим условием не бывает: авторитет отзыва наших
# токенов живёт в ТОЙ ЖЕ базе, что и источник вердикта, его полоса fail-closed по
# решению и стоит на пути аутентификации, то есть ПЕРЕД слоем прав. Разбор,
# числа и предикат возврата прежнего ожидания — в шапке файла, §«Какая полоса
# отвечает под этим условием».
#
# ЧТО УТВЕРЖДЕНИЕ ПРОДОЛЖАЕТ ЛОВИТЬ. Отказ полосы проверочных ключей его НЕ
# подтверждает: та полоса про другую зависимость и наступила бы при исправном
# источнике вердикта — ровно тот молчаливый исход, ради которого различитель
# заведён. Ожидание осталось ОДНИМ значением, `oneOf` не появился.
# ---------------------------------------------------------------------------

CASES.append(Case(
    id="AUTHZ-FAILCLOSED-OPENFGA-DOWN",
    title="gateway returns 503 Unavailable when the authorization store is unreachable (fail-closed)",
    classes=["AUTHZ", "FLOW", "FAIL_CLOSED"],
    priority="P0",
    steps=[
        Step(
            name="any-authz-gated-rpc-during-verdict-source-outage",
            method="GET",
            path="/iam/v1/accounts/{{accountAId}}",
            auth="jwtAccountAdminA",
            test_script=(
                [
                    "// fail-closed: когда источник вердикта недостижим, слой авторизации",
                    "// шлюза уходит в ветвь ошибки и при FailOpen=false отвечает",
                    "// 503 Unavailable / gRPC 14. НИКОГДА 200.",
                    "//",
                    "// Условие создаёт scripts/run-failclosed.sh (своя волна прогона):",
                    "// он прогревает снимок проверочных ключей края, сворачивает базу",
                    "// источника вердикта, ждёт истечения кэша решений шлюза, гоняет эту",
                    "// коллекцию и поднимает базу обратно.",
                ]
                + _refusal_head()
                + _unavailable_pair("authz-gate")
                + _lane_assert("authz-gate", "edge:revocation")
            ),
        ),
    ],
))


# ---------------------------------------------------------------------------
# AUTHZ-FAILCLOSED-LIST-NEVER-EMPTY-200 — ни один список НЕ отвечает пустой
# страницей, когда вердикта о правах взять неоткуда (задача #645), И отказ
# производит НАЗВАННАЯ полоса (задача #1198).
#
# ЗАЧЕМ ОТДЕЛЬНО ОТ СОСЕДА ВЫШЕ. Предмет здесь — СЕМЬ поверхностей разом, а не
# одна: инвариант принадлежит классу (см. «ПОЧЕМУ ВСЕ СЕМЬ» ниже), и точечный
# кейс его не ловит.
#
# ЧЕМ ЭТИ СЕМЬ ОТЛИЧАЮТСЯ ОТ СОСЕДА ПО УСТРОЙСТВУ — и почему это НЕ видно в
# ответе. У `Get` есть запись каталога со scope, поэтому решение о правах
# принимает край. Списочные RPC iam объявлены `scope_filtered` — per-RPC Check
# край по ним НЕ делает (допускает вызов и оставляет сужение владельцу данных),
# то есть на ИСПРАВНОМ стенде отвечает сам сервис.
#
# Под условием ЭТОЙ волны различие не наблюдаемо: обе полосы короткозамыкаются
# раньше — на пути аутентификации, полосой отзыва наших токенов, чей авторитет
# живёт в той же свёрнутой базе. Поэтому здесь и у соседа ожидается ОДНА и та же
# полоса, и это не оплошность, а следствие устройства; разбор и предикат
# возврата — в шапке файла, §«Какая полоса отвечает под этим условием».
# Утверждение «отвечает САМ СЕРВИС» отсюда СНЯТО, а не ослаблено: его условие не
# конструируется, и держат это свойство сегодня другие пробы, названные там же.
#
# (Здесь стояло `<exempt>` — на дереве этих семи записей нет ни одной такой:
# перепись по контрактам семи служб даёт `scope_filtered` 7 из 7. Полосы
# различаются по существу: `<exempt>` допускает вызов внутреннего слушателя
# ВООБЩЕ БЕЗ ПРИНЦИПАЛА, `scope_filtered` идёт ПОСЛЕ его извлечения.)
#
# ЧТО ИМЕННО УТВЕРЖДАЕТСЯ. Пустая страница и отказ — разные ответы, и арендатор
# обязан их различать. `200 {}` на списке означает «тебе ничего не выдано»;
# именно так выглядел бы стенд, на котором вердикта взять неоткуда, — то есть
# сломанное развёртывание было бы неотличимо от корректно запертого. Поэтому
# утверждается ПАРА (HTTP-статус И код `google.rpc.Status`), отдельно — что
# ответ не является успехом с пустым массивом, и отдельно — ЧЬЯ полоса ответила.
#
# ПОЧЕМУ ВСЕ СЕМЬ. Инвариант принадлежит не одной поверхности, а классу: до
# задачи #645 привязки доступа отвечали на непровязанный порт отношений пустой
# страницей, а шесть соседей — отказом. Одна поверхность из семи, ведущая себя
# иначе, и есть та форма дефекта, которую перечень ловит, а точечный кейс нет.
#
# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ ПЕРЕЕХАЛ В ПРОГОНЩИК, И ЭТО НЕ ОСЛАБЛЕНИЕ. Семь
# утверждений ниже — отрицания («ответ обязан быть отказом»), и без контроля они
# зеленели бы на стенде, где до сервиса не доезжает ни один запрос. Контролем был
# первый шаг этого кейса: величина страницы вне допустимого диапазона отвергается
# ПЕРВЫМ СТЕЙТМЕНТОМ обработчика, до единого обращения к базе
# (`shared.ValidateVisiblePagination` в `internal/apps/kacho/api/project/list.go`;
# предел — `MaxListPageSize = 1000`), поэтому ответ 400 / gRPC 3 даёт СЕРВИС.
#
# Под этим условием он неисполним: полоса отзыва наших токенов короткозамыкает
# запрос на пути аутентификации, до сервиса он не доходит НИ ПРИ КАКОМ входе
# (шапка файла, §«Какая полоса отвечает под этим условием»). Шаг, который не
# может сойтись ни при каком входе, — не контроль, а красное без предмета.
#
# Поэтому тот же запрос предъявляет `scripts/run-failclosed.sh` ДО сворачивания
# базы — там он исполним — и требует 400 с ключом `details`. Он доказывает ровно
# то же, что доказывал здесь, и на том же стенде:
#   * запрос ДОЕЗЖАЕТ до сервиса, когда стенд исправен;
#   * ответы сервиса несут `details` — предпосылка различителя выполняется ЗДЕСЬ
#     И СЕЙЧАС, а не по чтению чужого кода;
#   * различитель опознаёт ответ сервиса на исходе, отличном от 503.
# Не сошлось — волна не стартует, отчёта нет, гейт называет
# `authz-failclosed(no-report)`. Спрятать он ничего не может: пропуск контроля
# стоит красного, а не тишины.
#
# ВТОРОЙ КОНТРОЛЬ ОСТАЁТСЯ ВНУТРИ КОЛЛЕКЦИИ — кейс
# `AUTHZ-FAILCLOSED-EDGE-KEY-SOURCE-LANE` ждёт ДРУГУЮ полосу на том же исходе
# 503/14. Пока в наборе два разных ожидания, «различитель залип на одном
# значении» не проходит.
# ---------------------------------------------------------------------------

