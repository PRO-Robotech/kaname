# AUTHZ-FAILCLOSED-EDGE-KEY-SOURCE-LANE — ВТОРАЯ ветка того же условия: край не
# может добыть проверочные ключи и отказывает САМ (задача #1198).
#
# ЗАЧЕМ ОН НУЖЕН. Без него различитель полос был бы утверждением об одной
# стороне: «полоса сервиса опознаётся». Здесь он предъявляется на ответе, который
# по ИСХОДУ неотличим от соседнего кейса (те же 503 / gRPC 14) и обязан быть
# опознан ДРУГОЙ полосой. Два шага одной волны, одна и та же поверхность, один и
# тот же предъявитель — и два разных производителя, каждый назван.
#
# КАК СОЗДАЁТСЯ ПОЛОСА. Предъявляется удостоверение, отличающееся от настоящего
# РОВНО ОДНИМ ПОЛЕМ — идентификатором ключа в заголовке. Край выбирает запись
# издателя по `iss` (он не тронут), не находит такой ключ в снимке и идёт за
# набором ВЫНУЖДЕННО, не спрашивая срок снимка. Источник ключей — ключница в
# свёрнутой базе, поэтому набор не добывается, и край отвечает своей полосой.
#
# ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ «СНИМОК ПРОСТО УСТАРЕЛ», и почему взят этот повод.
# Поводов перезапроса у края два — истёк срок снимка и назван неизвестный ключ, —
# но ветвь добычи набора у них ОДНА, и классификация её отказа одна. Ждать
# истечения срока волна не может: срок 300 с, и это пять минут стенда со
# свёрнутой базой; укоротить срок нельзя тоже — ручка читается при старте, а
# перезапуск края обрывает проброс к нему НАВСЕГДА (цена уже измерена, см. шапку
# `scripts/run-failclosed.sh`). Поэтому берётся повод, который создаётся
# запросом, а не часами: `testing.md` — ждём УСЛОВИЕ, а не время.
#
# ОТЛИЧИЕ ОТ НЕГОДНОГО ТОКЕНА НАЗВАНО. На ИСПРАВНОМ источнике ключей то же самое
# удостоверение даёт 401: набор добыт, ключа в нём нет ⇒ токен негоден. Здесь
# утверждается 503 — то есть «не твоя вина, повтори позже». Ровно эта развилка и
# закрыта задачей #1194; кейс её не пересматривает, а пользуется ею как
# признаком: 401 на этом шаге означал бы, что источник ключей ОТВЕТИЛ, то есть
# условие волны не создано.
#
# ПОЧЕМУ ШАГ ОДИН. Вынужденный перезапрос несёт собственный минимальный интервал:
# второй такой запрос, пришедший сразу следом, набор перезапрашивать не станет и
# получит 401 вместо 503. Шаг здесь ровно один, и он отделён от прогрева всей
# длительностью сворачивания базы и выжидания кэша решений.
# ---------------------------------------------------------------------------

