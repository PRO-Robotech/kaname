"""Case-set basic-access-token — БАЗОВЫЙ ТОКЕН ДОСТУПА (задача #1142).

Приёмка BAT-1, сценарии BAT-1-09 (выдача), BAT-1-26 (предъявление на крае),
BAT-1-42 (отзыв доходит до предъявления), BAT-1-16/17 (срок).

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ — И ЧЕГО НЕ ДОКАЗЫВАЕТ ЛЮБАЯ ПОЛОВИНА
------------------------------------------------------------
Вопрос ставится СКВОЗЬ ОБЕ СТОРОНЫ: выдали → предъявили → прошло → отозвали →
предъявили → отказ. Две пробы по половине («отзыв записался» и «отказ
приходит») не доказывают ничего: каждая сторона исправна, а вместе они про
разный предмет. Контроль, действующий на ВЫДАЧЕ и не действующий на
ПРЕДЪЯВЛЕНИИ, отзывом не является — у долгоживущего секрета цена такого
промаха равна его сроку.

Положительный контроль стоит в ТОМ ЖЕ прогоне и ПЕРЕД отрицанием: без него
«отказ после отзыва» было бы верно и о полосе, которая не работает вовсе.

ФОРМА ОТВЕТА ВЫДАЧИ У ЭТОГО ВИДА
--------------------------------
`secret` непуст; `privateKeyPem` / `publicKeyPem` / `algorithm` пусты ВСЕ.
Утверждается ПАРА — что есть и чего нет: одно «секрет непуст» зеленело бы на
ответе, который вдобавок отдал ключевой материал, то есть на том самом
смешении двух видов, ради разведения которого фаза и заведена.

СРОК ЗАПОЛНЕН ВСЕГДА. «Бессрочно» у этого вида не выражается ни одним входом:
ноль означает «срок не назван» и разрешается умолчанием политики.

КТО ЗДЕСЬ ПРЕДЪЯВИТЕЛЬ — И ПОЧЕМУ НЕ РАСПОРЯДИТЕЛЬ АККАУНТА
------------------------------------------------------------
Выпуск персонального токена гейтится отношением `token_issuer`, и модель
объявляет его вычисляемым от `subject` — то есть держателей ровно двое: сам
человек и надзор облака. Это директива владельца (2026-08-23): пригласивший
вправе выдать и снять права, но не действовать за приглашённого; удостоверение
делает предъявителя САМИМ человеком во всех аккаунтах, где тот состоит.

Первая редакция кейса ходила под `jwtAccountAdminAStepUp` — в боевом посеве это
служебная учётка с ролью распорядителя аккаунта A. Прогон 32768969536 ответил ей
`403 AUTHZ_DENIED` на КАЖДОМ шаге выпуска, и одиннадцать утверждений упали
каскадом от одного отказа. Продукт был прав: соседний кейс того же дерева
(`iam-user.py` :: IAM-USR-TOK-ACTAS-NEG-INVITER) утверждает ровно этот 403 как
ТРЕБУЕМОЕ поведение и зелен в том же прогоне — два места об одном предмете, из
которых верно было второе.

Держателей ровно двое, и второй — НАДЗОР ОБЛАКА. Взят он, а не человек, и это
выбор по МЕСТУ ПРОГОНА, а не по вкусу: предъявитель человека добывается волной
церемонии, а отбор коллекций в неё идёт по перечню переменных, которых машинный
посев не кует (`tests/authz-fixtures/ceremony_credentials.py`). В этом перечне
стоит `jwtHumanCeremony`, но НЕ `jwtHumanCeremonyStepUp`: коллекция, знающая
только поднятого человека, в волну не отбирается — проверено вызовом `scan()`,
и `iam-user.py` уезжает туда по первой переменной, а не по второй. Кейс на
поднятом человеке остался бы в общей волне без предъявителя вовсе.

Поэтому здесь `jwtBootstrap` и `userAAAId` — ровно та пара, которой соседний
кейс (`iam-token-facade-conformance.py` :: issue-user-token) выпускает токен
тому же человеку тем же RPC, зелёная в том же прогоне. Право человека выпускать
СВОЙ токен проверяет IAM-USR-TOK-ACTAS-POS-SELF; предмет ЗДЕСЬ — форма
однострочного секрета и то, что отзыв доходит до предъявления.
"""

