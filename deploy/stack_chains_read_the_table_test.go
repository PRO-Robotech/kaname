// stack_chains_read_the_table_test.go — ГЕЙТ КЛАССА: перечень стендов, по
// которому судят пробы ЭТОГО модуля, читается из единственной таблицы состава
// (`deploy/stacks.txt`), а не выписывается второй копией.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Таблица состава объявляет себя единственным местом, где цепочка `-f` выписана,
// и её единственность держит гейт платформенного модуля
// (`deploy/stack_table_test.go`, TestNoSecondCopyOfAStackChain). Обход того гейта
// — три корня: `deploy`, `gateway`, `.github/workflows`. Каталог `services/` в
// него НЕ ВХОДИТ, поэтому копия, живущая здесь, лежит вне его наблюдения: он не
// краснеет и не зеленеет по ней — он о ней МОЛЧИТ.
//
// Замер, из которого гейт выведен (эпик #2564, полоса профилей своей чеканки).
// Копия `umbrellaChains` в provider_hops_test.go разошлась с таблицей на ТРЁХ
// стендах из шести:
//
//	prorobotech   в копии нет среднего слоя values.dev-prod.yaml. Слой накладки
//	              образов посадку не объявляет и наследует её у слоя под собой,
//	              поэтому без среднего стенд читается как `authMode: dev` — и
//	              перепись контуров поставщика ПРОПУСКАЛА его как dev-класс.
//	              Ровно этот исход шапка таблицы называет прямым текстом.
//	a8f60d        в копии нет ВОВСЕ: стенд не осматривался ни разу.
//	fe3455        в копии три слоя вместо четырёх — нет values.fe3455-ory-posture.yaml,
//	              то есть слоя, объявляющего посадку самого поставщика личности.
//	              Перепись контуров ПОСТАВЩИКА читала его без этого слоя.
//
// Цена измерена вердиктом самой переписи, а не рассуждением: она печатала
// «4 production-class stacks × 3 provider hops = 12 declarations examined» при
// шести объявленных стендах, из которых пять боевого класса. То есть двух
// стендов из пяти она не касалась, а третий читала неполным — и была ЗЕЛЁНОЙ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ГЕЙТ ЗДЕСЬ, А НЕ РАСШИРЕНИЕМ ЧУЖОГО ОБХОДА
//
// Расширить обход платформенного гейта на `services/` — правка ЧУЖОГО гейта, и
// она даёт ложные находки: имена `values.yaml` и `values.prod.yaml` несут ОБА
// чарта, и цепочка собственного чарта службы (`chartChains`) состоит ровно из
// них. Замер: вне обхода 43 совпадения, из них копий УМБРЕЛЛЫ — 7. Гейт, у
// которого 36 находок из 43 ложные, отключат первым.
//
// Здесь предмет уже: не «встречаются ли два имени профиля в одной строке», а
// «СОГЛАСЕН ЛИ перечень стендов этого модуля с таблицей». Он не зависит от имён
// и не путает референты: сравниваются ЦЕПОЧКИ по имени стенда.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЭТОТ ГЕЙТ НЕ УТВЕРЖДАЕТ
//
// Он не судит СОДЕРЖИМОЕ профилей и не знает, что такое чеканка. Его предмет —
// перечень: чей он и сходится ли с источником. Содержимое судят пробы,
// пользующиеся этим перечнем, и они смогут это делать только по полному.
package deploy_test

import (
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

// stacksTableRel — путь таблицы состава от корня внешнего дерева. Каталог
// `services/iam/deploy/` уезжает клиенту отдельным чартом, и там внешнего дерева
// нет: отсутствие таблицы — «условие не создано», а не находка (см. ниже).
const stacksTableRel = "deploy/stacks.txt"

// stackTableLine — та же форма строки, что читает платформенная сторона
// (deploy/stacks.txt, deploy/dbtls_declaration_test.go, tests/helm/stacks.sh).
// Нераспознанная строка — это НЕ «стендов меньше», это «предикат перестал их
// узнавать», и она роняет прогон.
var stackTableLine = regexp.MustCompile(`^([a-z0-9][a-z0-9-]*):(values[^,\s]*(?:,values[^,\s]*)*)$`)

// umbrellaChainsFromTable — цепочки стендов, ПРОЧИТАННЫЕ из таблицы состава.
//
// КОРЕНЬ ВНЕШНЕГО ДЕРЕВА ПРИХОДИТ ПАРАМЕТРОМ, а не вычисляется здесь подъёмом.
// Читатель не вправе решать, где дерево: подъём к САМОМУ ВНЕШНЕМУ маркеру модуля
// выходит за корень своего, и в самостоятельном клоне под чужим деревом он
// указал бы на ЧУЖОЙ файл — вердикт был бы вынесен о нём. Базу назначает
// вызывающий, у которого она уже установлена (`profileSources`), и это же делает
// читателя проверяемым синтетическим корнем без подмены рабочего каталога.
// Свойство держит гейт модуля — internal/domain,
// TestPlatformCoordinatesTouchingTheTreeAreAnchoredInTheModule: он нашёл здесь
// ровно этот дефект, когда база вычислялась подъёмом.
//
// Второй результат — жив ли предмет: в дереве поставляемого чарта таблицы нет,
// и это законно. Вызывающий обязан различать «таблица говорит: стендов ноль»
// (находка) и «таблицы нет вовсе» (условие не создано).
func umbrellaChainsFromTable(t *testing.T, outer string) (map[string][]string, bool) {
	t.Helper()
	path := filepath.Join(outer, stacksTableRel)
	raw, err := os.ReadFile(filepath.Clean(path)) // #nosec G304 -- путь собран из корня собственного дерева
	if err != nil {
		return nil, false
	}
	out := map[string][]string{}
	for _, line := range strings.Split(string(raw), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		m := stackTableLine.FindStringSubmatch(line)
		if m == nil {
			t.Fatalf("строка таблицы состава не разобрана: %q (%s). Это не «стендов меньше», "+
				"а «предикат перестал их узнавать» — молчать здесь значит сузить проверку", line, path)
		}
		out[m[1]] = strings.Split(m[2], ",")
	}
	if len(out) == 0 {
		t.Fatalf("таблица состава %s не назвала ни одного стенда — вердикт беспредметен", path)
	}
	return out, true
}

// judgeChainAgreement — ТЕЛО гейта, вынесенное отдельно, чтобы инъекция звала
// то же, что исполняется на дереве.
//
// Находок три вида, и они РАЗНЫЕ: общий текст скрыл бы, что именно чинить.
func judgeChainAgreement(table, used map[string][]string) []string {
	var findings []string

	names := make([]string, 0, len(table))
	for name := range table {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		want := table[name]
		got, ok := used[name]
		if !ok {
			findings = append(findings, "стенд "+name+" объявлен таблицей состава ("+
				strings.Join(want, " + ")+") и НЕ НАЗВАН перечнем этого модуля: пробы, "+
				"идущие по перечню, не осматривают его вовсе — они о нём молчат, а молчание "+
				"неотличимо от чистоты")
			continue
		}
		if strings.Join(got, ",") != strings.Join(want, ",") {
			findings = append(findings, "стенд "+name+" читается перечнем этого модуля как "+
				strings.Join(got, " + ")+", а таблица состава объявляет "+strings.Join(want, " + ")+
				". Слой, выпавший из копии, посадку не объявляет — стенд наследует её у слоя под "+
				"собой, и пропуск среднего слоя читается пробами как «стенд объявил режим разработки»")
		}
	}

	return findings
}

// TestUmbrellaStackChainsAreReadFromTheTable — перечень стендов, по которому
// судят пробы этого модуля, обязан СОВПАДАТЬ с таблицей состава.
//
// Перечень берётся ЧЕРЕЗ profileSources — то есть через настоящего потребителя,
// а не повторным чтением таблицы. Иначе гейт сравнивал бы таблицу с самой собой
// и оставался бы зелёным при любом перечне, каким бы пробы ни пользовались: он
// обязан краснеть на возвращённом литерале, а не только на разошедшемся файле.
func TestUmbrellaStackChainsAreReadFromTheTable(t *testing.T) {
	table, present := umbrellaChainsFromTable(t, outerRoot(t))
	if !present {
		t.Skipf("таблицы состава %s в этом дереве нет — предмета у гейта нет. "+
			"Это УСЛОВИЕ НЕ СОЗДАНО, а не «дерево чисто»: каталог уезжает клиенту "+
			"отдельным чартом, и внешнего дерева там не бывает", stacksTableRel)
	}

	var used map[string][]string
	for _, src := range profileSources(t) {
		if src.label == "umbrella" {
			used = src.chains
		}
	}
	if used == nil {
		t.Fatalf("таблица состава %s в дереве есть, а источника «umbrella» среди "+
			"объявленных нет: перечень, по которому судят пробы, взять неоткуда, "+
			"и вердикт был бы вынесен неизвестно о чём", stacksTableRel)
	}

	findings := judgeChainAgreement(table, used)
	for _, f := range findings {
		t.Error(f)
	}

	stacksInTable, layersInTable := len(table), 0
	for _, chain := range table {
		layersInTable += len(chain)
	}
	if stacksInTable == 0 || layersInTable == 0 {
		t.Fatalf("обход пуст: стендов %d, слоёв %d — предпосылка исчезла, "+
			"а не дерево стало чистым", stacksInTable, layersInTable)
	}
	t.Logf("осмотрено: стендов в таблице состава — %d, слоёв в них — %d; "+
		"названо перечнем, по которому судят пробы, — %d; расхождений — %d",
		stacksInTable, layersInTable, len(used), len(findings))
}
