// release_namespace_test.go — чарт службы обязан вставать в ТО пространство имён,
// которое выбрал тот, кто ставит.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Служба выносится отдельным продуктом и ставится в ЧУЖОМ облаке. Пространство
// имён там выбирает оператор — ключом `--namespace`, как у любого чарта. Шаблон,
// прописавший имя литералом, этот выбор МОЛЧА ОТМЕНЯЕТ: `helm install
// --namespace <своё>` рендерит объекты в чужое имя, и ключ не даёт ни отказа, ни
// предупреждения.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕМ ЭТО ДОРОЖЕ, ЧЕМ ВЫГЛЯДИТ — два исхода, и оба плохи по-разному
//
//  1. У ОПЕРАТОРА такого пространства имён нет. Установка отказывает на создании
//     объектов, и текст отказа называет имя, которого оператор не писал ни разу,
//     — то есть диагностика уводит от причины.
//  2. У ОПЕРАТОРА такое пространство имён ЕСТЬ и занято чужой работой. Тогда
//     отказа нет вовсе: объекты приезжают в живое чужое пространство имён, и
//     заметить это можно только по последствиям. Наблюдалось на этом дереве —
//     рендер боевого профиля с `--namespace iam-standalone-probe` дал все три
//     объекта в `kacho`, где в тот момент работал соседний стенд.
//
// Второй исход и есть причина, по которой это проба, а не замечание стиля:
// молчаливое попадание не в то пространство имён неотличимо от исправной
// установки до первого столкновения имён.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ИМЕННО УТВЕРЖДАЕТСЯ
//
// Ни один шаблон чарта не называет пространство имён ЛИТЕРАЛОМ. Законны ровно две
// формы, и обе оставляют выбор тому, кто ставит:
//
//   - ключа `namespace:` нет вовсе — объект едет в пространство имён релиза;
//   - `namespace: {{ .Release.Namespace }}` — то же самое, но объявленное явно,
//     поэтому `helm template | kubectl apply` попадает туда же, куда `helm
//     install`.
//
// Проба НЕ требует наличия ключа: чарт, снявший его целиком, тоже верен. Поэтому
// пустой перечень объявлений — не находка, а пустой обход ФАЙЛОВ — находка.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОБЪЯВЛЕНИЕ, А НЕ РЕНДЕР
//
// Та же причина, что у соседних проб этого каталога: рендер требует `helm` на
// машине, и проба, которой нужен инструмент, пропускается ровно там, где она
// нужна. Здесь читается текст шаблона.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ СТРОКИ-КОММЕНТАРИИ ОТБРАСЫВАЮТСЯ
//
// Этот файл и соседние объясняют предмет словами, и слово `namespace:` стоит в
// объяснениях. Проверка по подстроке краснела бы на СОБСТВЕННОМ объяснении и при
// этом молчала бы на снятой защите — тот же класс, что уже разбирался у пробы
// механизма схемы. Судятся только значения ключа вне комментария.
package deploy_test

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

// namespaceKey — объявление пространства имён в шаблоне: ключ `namespace:` с
// непустым значением. Отступ произволен — ключ живёт под `metadata:`.
var namespaceKey = regexp.MustCompile(`^\s*namespace:\s*(\S.*?)\s*$`)

// literalNamespaceFinding — одно попадание: координата и то, что там написано.
type literalNamespaceFinding struct {
	file  string
	line  int
	value string
}

func TestChartTemplatesLeaveTheNamespaceToWhoeverInstalls(t *testing.T) {
	const templatesDir = "templates"

	entries, err := os.ReadDir(templatesDir)
	require.NoError(t, err, "каталог шаблонов чарта не читается: %s", templatesDir)

	var (
		filesRead    int
		linesScanned int
		declarations int
		findings     []literalNamespaceFinding
	)

	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".yaml") {
			continue
		}

		path := filepath.Join(templatesDir, entry.Name())
		raw, readErr := os.ReadFile(path)
		require.NoError(t, readErr, "шаблон не читается: %s", path)

		filesRead++

		for idx, line := range strings.Split(string(raw), "\n") {
			linesScanned++

			// Комментарий целой строкой предметом не является: он объясняет
			// защиту, а не осуществляет её.
			if strings.HasPrefix(strings.TrimSpace(line), "#") {
				continue
			}

			match := namespaceKey.FindStringSubmatch(line)
			if match == nil {
				continue
			}

			declarations++

			// Хвостовой комментарий после значения на предмет не влияет.
			value := match[1]
			if cut := strings.Index(value, "#"); cut >= 0 {
				value = strings.TrimSpace(value[:cut])
			}

			// Величина, вычисляемая шаблоном, оставляет выбор тому, кто ставит.
			if strings.Contains(value, "{{") {
				continue
			}

			findings = append(findings, literalNamespaceFinding{
				file:  path,
				line:  idx + 1,
				value: value,
			})
		}
	}

	t.Logf(
		"перепись: шаблонов прочитано %d · строк осмотрено %d · объявлений пространства имён %d · из них литеральных %d",
		filesRead, linesScanned, declarations, len(findings),
	)

	// Пустой обход — находка, а не идеал: «ноль литералов» обязано быть отличимо
	// от «ноль прочитанного».
	require.NotZero(t, filesRead, "обход пуст: шаблонов чарта не прочитано ни одного — вердикт беспредметен")
	require.NotZero(t, linesScanned, "обход пуст: строк не осмотрено ни одной — вердикт беспредметен")

	for _, finding := range findings {
		t.Errorf(
			"%s:%d — пространство имён названо литералом %q: ключ `--namespace` того, кто ставит, молча отменён. "+
				"Законны две формы: снять ключ вовсе либо написать `namespace: {{ .Release.Namespace }}`",
			finding.file, finding.line, finding.value,
		)
	}
}
