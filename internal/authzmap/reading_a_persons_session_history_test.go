// sessionHistoryRPC — RPC, чей предмет есть ЧТЕНИЕ ИСТОРИИ СЕССИЙ человека.
//
// По FQN, потому что «история сессий» — свойство СМЫСЛА RPC, а не его
// написания. Отношение спрашивается у каталога: литерал имени превратил бы гейт
// в проверку написания и остался бы зелёным, верни кто-то чтение на широкое
// отношение под другим именем.
const sessionHistoryRPC = "kaname.cloud.iam.v1.InternalSessionRevocationsService/ListByUser"

// credentialListRPC — вторая сторона той же личности: перечень удостоверений
// (#1133). Круг держателей у неё и у истории сессий обязан совпадать.
const credentialListRPC = "kaname.cloud.iam.v1.UserTokenService/List"

// sessionTerminatingRPCs — глаголы, ЗАВЕРШАЮЩИЕ сессию. Перечислены, чтобы
// размен, на котором стоит сужение чтения, был утверждением, а не пересказом:
// ни один из них не гейтится отношением на строке личности, поэтому сужение
// чтения не отнимает завершения ни у кого.
var sessionTerminatingRPCs = []string{
	"kaname.cloud.iam.v1.InternalSessionRevocationsService/Revoke",
	"kaname.cloud.iam.v1.InternalIAMService/ForceLogout",
}

// TestReadingAPersonsSessionHistoryHasNoAccountLevelSource — гейт класса.
func TestReadingAPersonsSessionHistoryHasNoAccountLevelSource(t *testing.T) {
	model := canonicalModel(t)
	catalog := catalogByFQN(t)
	require.NotEmpty(t, catalog, "каталог прав разобран в ноль записей — предпосылка гейта сломана")

	// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 3 — сперва, чтобы отрицания ниже не могли зеленеть
	// на сломанном разборе: у ЧТЕНИЯ ЗАПИСИ источники уровня аккаунта обязаны быть.
	readEntry, ok := catalog[recordReadRPC]
	require.Truef(t, ok, "каталог не знает %s — контроль отрицания отсутствует", recordReadRPC)
	readVerdict := inspectCredentialRelation(t, model, readEntry.objectType, readEntry.relation)
	require.ElementsMatchf(t, accountLevelSources(readEntry.relation), readVerdict.AccountLevel,
		"КОНТРОЛЬ: у отношения ЧТЕНИЯ ЗАПИСИ %s.%s обязаны быть ВСЕ источники уровня аккаунта. "+
			"Их отсутствие означает, что разбор модели ничего не нашёл, и тогда отрицания ниже "+
			"вакуумны", readEntry.objectType, readEntry.relation)

	e, ok := catalog[sessionHistoryRPC]
	require.Truef(t, ok, "каталог не знает %s — предмет гейта исчез", sessionHistoryRPC)
	require.Equalf(t, "iam_user", e.objectType,
		"%s гейтится не на объекте личности (%s) — предмет пробы сменился",
		sessionHistoryRPC, e.objectType)

	// Предикат ТОТ ЖЕ, что у #1133, а не копия: копия разошлась бы с оригиналом
	// молча. Имя у него узкое по своему происхождению, и это не натяжка —
	// история отзыва перечисляет `token_jti`, то есть тоже метаданные
	// удостоверений человека.
	v := inspectCredentialRelation(t, model, e.objectType, e.relation)

	// ОТРИЦАНИЕ.
	require.Emptyf(t, v.AccountLevel,
		"%s гейтится отношением %s.%s, у которого есть источники уровня аккаунта: %v.\n"+
			"История сессий — не право на аккаунт, а СВЕДЕНИЯ О ЧЕЛОВЕКЕ: какие его сессии "+
			"сняли, когда и почему.\n"+
			"Личность здесь ГЛОБАЛЬНА (одна строка iam_user на все аккаунты человека, звено "+
			"«личность → аккаунт» вердикт берёт из членства), поэтому право уровня аккаунта "+
			"раскрывает историю целиком — включая аккаунты, к которым его держатель отношения "+
			"не имеет.\n"+
			"Пригласивший вправе выдать и снять права, но не читать сведения о приглашённом.",
		sessionHistoryRPC, e.objectType, e.relation, v.AccountLevel)

	// ОТРИЦАНИЕ 2 — отношение НЕВЫДАВАЕМО.
	require.Falsef(t, v.Grantable,
		"%s гейтится отношением %s.%s, у которого ЕСТЬ прямой список субъектов.\n"+
			"Значит право читать чужую историю сессий можно ВРУЧИТЬ — кортежем, выдачей или "+
			"материализацией, — и тогда разделение прав выше обходится одной записью.\n"+
			"Отношение обязано быть вычисляемым: держателей у него ровно двое, и оба структурны.",
		sessionHistoryRPC, e.objectType, e.relation)

	// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 1 — сам человек.
	require.Truef(t, v.HasSelf,
		"%s гейтится отношением %s.%s, у которого САМ ЧЕЛОВЕК не источник. Тогда запрет выше "+
			"держится не разделением прав, а тем, что отношения не держит никто.\n"+
			"Самочтение в сервисе (`authzguard.IsSelf`) это НЕ закрывает: оно короткозамыкается "+
			"до модели, а запись каталога объявляет полосу для всякого будущего маршрута — на "+
			"нём решает только отношение, и человек остался бы без своей же истории.\n"+
			"Источники плана: %v", sessionHistoryRPC, e.objectType, e.relation, sortedKeys(v.Sources))

	// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 2 — надзор облака.
	require.Truef(t, v.HasCloud,
		"%s гейтится отношением %s.%s, у которого НЕТ надзора облака (%+v). Расследование "+
			"инцидента — единственный довод, у которого на этом предмете ЕСТЬ предмет, и "+
			"сужение обязано оставить его возможным: без него это не сужение, а обрыв.\n"+
			"Источники плана: %v",
		sessionHistoryRPC, e.objectType, e.relation, cloudSource, sortedKeys(v.Sources))

	// РАВЕНСТВО КРУГА, а не вхождение.
	require.ElementsMatchf(t, personalCredentialSources(), keysOf(v.Sources),
		"%s гейтится отношением %s.%s, круг держателей которого НЕ РАВЕН объявленному: "+
			"ожидались сам человек и надзор облака, в плане %v.\n"+
			"Утверждается равенство, а не вхождение: вхождение зеленеет на любом ДОБАВЛЕННОМ "+
			"источнике — то есть на том самом дефекте, который здесь закрывается.",
		sessionHistoryRPC, e.objectType, e.relation, sortedKeys(v.Sources))

	t.Logf("перепись: записей каталога прочитано %d · гейт истории сессий %s.%s "+
		"(источников %d) · контроль чтения записи %s.%s (источников %d, из них уровня "+
		"аккаунта %d)",
		len(catalog), e.objectType, e.relation, len(v.Sources),
		readEntry.objectType, readEntry.relation, len(readVerdict.Sources), len(readVerdict.AccountLevel))
}

// TestTwoSidesOfOneIdentityAgreeOnTheirCircle — история сессий и перечень
// удостоверений раскрываются в ОДИН круг держателей.
//
// Гейт не объявляет круг правильным — он запрещает сторонам РАЗЪЕХАТЬСЯ.
// Утверждается равенство, а не вложение: вложение зеленело бы и на сужении одной
// стороны ниже другой, а это означало бы, что человек видит свои удостоверения и
// не видит своих сессий (или наоборот) — расхождение, которого никто не решал.
func TestTwoSidesOfOneIdentityAgreeOnTheirCircle(t *testing.T) {
	model := canonicalModel(t)
	catalog := catalogByFQN(t)
	require.NotEmpty(t, catalog, "каталог прав разобран в ноль записей — предпосылка гейта сломана")

	sess, ok := catalog[sessionHistoryRPC]
	require.Truef(t, ok, "каталог не знает %s", sessionHistoryRPC)
	tok, ok := catalog[credentialListRPC]
	require.Truef(t, ok, "каталог не знает %s", credentialListRPC)
	require.Equal(t, "iam_user", sess.objectType, "история сессий гейтится не на строке личности")
	require.Equal(t, "iam_user", tok.objectType, "перечень удостоверений гейтится не на строке личности")

	// Отношения РАЗНЫЕ — это и есть предмет сверки. Совпади они, утверждение
	// ниже стало бы тавтологией и перестало бы что-либо стеречь.
	require.NotEqualf(t, sess.relation, tok.relation,
		"история сессий и перечень удостоверений гейтятся ОДНИМ отношением (%s). Тогда "+
			"«стороны согласны» — тавтология: её нельзя нарушить, значит она ничего не "+
			"утверждает. Стороны обязаны быть двумя отношениями с проверяемым равенством "+
			"кругов, иначе имя одного из них лжёт о второй поверхности.", sess.relation)

	// Точка сравнения ОДНА — `identitySideCircles`, и опыт инъекции зовёт ЕЁ ЖЕ.
	// Копия предиката доказывала бы, что работает копия: разойдясь с оригиналом,
	// она разошлась бы молча и именно там, где расхождение не видно.
	sessCircle, tokCircle := identitySideCircles(t, model, sess, tok)

	require.ElementsMatchf(t, keysOf(tokCircle), keysOf(sessCircle),
		"две стороны одной личности раскрываются в РАЗНЫЕ круги держателей.\n"+
			"история сессий (%s.%s): %v\n"+
			"перечень удостоверений (%s.%s): %v\n"+
			"Сессия и удостоверение — соседние стороны одного человека, и разная ширина у них "+
			"была бы решением, которого никто не принимал. Развести их можно — но это решение, "+
			"и принимать его надо здесь, а не побочным эффектом чужой правки.",
		sess.objectType, sess.relation, sortedKeys(sessCircle),
		tok.objectType, tok.relation, sortedKeys(tokCircle))

	t.Logf("стороны личности: история сессий %s.%s и перечень удостоверений %s.%s "+
		"раскрываются в один круг из %d источников: %v",
		sess.objectType, sess.relation, tok.objectType, tok.relation,
		len(sessCircle), sortedKeys(sessCircle))
}

// TestTerminatingASessionIsNotGatedByTheSameRelation — размен назван и измерен.
//
// Сужение ЧТЕНИЯ отняло бы и ЗАВЕРШЕНИЕ, будь они связаны одним отношением.
// Они не связаны: завершающие глаголы освобождены от per-RPC решения края и
// гейтятся полосой ВЫЗЫВАЮЩЕГО МОДУЛЯ (проверенный сертификат плюс
// `system_viewer@cluster` у служебной учётки этого модуля), которая `user_id`
// не читает вовсе. Значит распорядитель аккаунта не терял завершения — он его
// и не имел, а сужение чтения ничего у него не отнимает.
//
// Утверждается, а не пересказывается: появись у завершения отношение на строке
// личности — вывод обязан быть ПЕРЕСМОТРЕН, а не унаследован, и покраснеть это
// должно здесь.
func TestTerminatingASessionIsNotGatedByTheSameRelation(t *testing.T) {
	catalog := catalogByFQN(t)
	require.NotEmpty(t, catalog, "каталог прав разобран в ноль записей — предпосылка гейта сломана")

	sess, ok := catalog[sessionHistoryRPC]
	require.Truef(t, ok, "каталог не знает %s", sessionHistoryRPC)
	require.NotEmptyf(t, sess.relation,
		"КОНТРОЛЬ: у ЧТЕНИЯ истории отношение обязано БЫТЬ — иначе отрицания ниже "+
			"утверждают лишь, что каталог разобран в пустоту")

	checked := 0
	for _, fqn := range sessionTerminatingRPCs {
		e, ok := catalog[fqn]
		require.Truef(t, ok, "каталог не знает %s — перечень завершающих глаголов пережил "+
			"свой предмет", fqn)
		require.Emptyf(t, e.relation,
			"%s гейтится отношением %q на объекте %q. Прежде завершение сессии решалось "+
				"полосой вызывающего МОДУЛЯ и отношения на строке личности не имело, поэтому "+
				"сужение ЧТЕНИЯ истории (#1140) ничего у держателя прав в аккаунте не отнимало.\n"+
				"Предпосылка изменилась: пересмотрите размен, а не эту пробу.", fqn,
			e.relation, e.objectType)
		require.Emptyf(t, e.objectType,
			"%s обзавёлся типом объекта %q при пустом отношении — полоса решения сменилась",
			fqn, e.objectType)
		checked++
	}

	t.Logf("размен: чтение истории гейтится %s.%s · завершающих глаголов сверено %d, "+
		"отношения на строке личности нет ни у одного",
		sess.objectType, sess.relation, checked)
}

// identitySideCircles — круги держателей ОБЕИХ сторон личности, приведённые к
// сравнимому виду. Единственная точка, где они добываются: и гейт выше, и опыт
// инъекции рядом зовут её, а не свою копию.
func identitySideCircles(t *testing.T, model *authzplan.Model, sess, tok catalogGate) (
	sessCircle, tokCircle map[planSource]string,
) {
	t.Helper()
	sessCircle = holderCircle(t, model, sess.objectType, sess.relation)
	tokCircle = holderCircle(t, model, tok.objectType, tok.relation)
	require.NotEmpty(t, sessCircle, "план истории сессий пуст — ни одного источника разрешения")
	require.NotEmpty(t, tokCircle, "план перечня удостоверений пуст — ни одного источника разрешения")
	return sessCircle, tokCircle
}
