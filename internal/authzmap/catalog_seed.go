package authzmap

// catalog_seed.go — ЕДИНСТВЕННЫЙ производитель строк каталога модуля.
//
// # Зачем это существует
//
// Каталог типов заведён строками в `kacho_iam.catalog_module` / `catalog_resource`
// / `catalog_verb` (миграция 20260901113757, задача #1030), а его источником остаются
// литералы этого пакета: `objectTypes` — какие пары грантуемы, `typeVerbRelations`
// — какие глаголы объявлены каждым типом.
//
// Мест, знающих соответствие «литерал → строка», обязано быть ОДНО. Их трое:
// посев миграции, гейт паритета дерева и страж старта. Разойдясь, они дали бы
// худший из исходов — посев, согласный с гейтом, и оба неверные относительно
// того, что судит ключ. Поэтому перечень выводится здесь, а те трое его ЗОВУТ.
//
// # Почему не «сгенерировать SQL и забыть»
//
// Литерал меняется — миграция уже применена и правке не подлежит (запрет #5).
// Значит расхождение неизбежно, и вопрос не «как его не допустить», а «как
// сделать его ВИДИМЫМ». Отсюда две проверки поверх одного перечня: гейт дерева
// сверяет литерал с текстом миграции, страж старта — литерал с живыми строками.

import "sort"

// CatalogSeedRow — одна строка посева каталога ресурсов.
type CatalogSeedRow struct {
	Module   string
	Resource string
	// Dotted — производная форма, та же, какой говорит `role_verb.object_type` и
	// `role_rule_selectors.object_types`. Хранится колонкой под проверкой
	// согласия, а не собирается читателем: словарей имени типа в дереве ровно
	// два, и третьего здесь не заводится.
	Dotted string
}

// CatalogSeedVerb — одна строка посева каталога глаголов.
type CatalogSeedVerb struct {
	Module   string
	Resource string
	// Verb — каноническая форма БЕЗ приставки отношения, та же, какой говорит
	// `role_verb.verb`. Приставку знает компилятор модели.
	Verb string
	// PerObject — строка ПРОИЗВОДИТ пообъектное отношение `v_<verb>` на своём
	// типе. Ложь означает глагол, законный АВТОРСКИ и не дающий кортежа ни на
	// одном объекте: его действие несёт ярус на родителе.
	//
	// Признак заведён задачей #1863, и предмет у него один: словарей ДВА.
	// `typeVerbRelations` отвечает на вопрос «какие отношения объявил тип», а
	// правило роли называет КЛАСС ДЕЙСТВИЯ — и это разные множества. Судить
	// второе первым значило отвергать `create` у всех, кроме реестра.
	PerObject bool
}

// tierOnlyVerbClasses — канонические классы действия, у которых пообъектного
// отношения нет BY CONSTRUCTION, а не по чьему-то решению снять его.
//
// # Почему `create` — и почему он один
//
// Глагольное отношение называет операцию НАД ОБЪЕКТОМ, на который указывает
// кортеж. «Создать» такой операцией не является: в момент решения объекта ещё
// нет, поэтому вопрос всегда задают родителю, и каталог прав это и делает — все
// записи с глаголом `create` гейтятся ярусом записи на родителе либо ярусом
// администратора кластера (замер и решение —
// `services/iam/docs/engineering/architecture/verb-create-withdrawal.md`).
//
// Остальные четыре класса пообъектный референт ИМЕЮТ там, где тип его объявил;
// где не объявил — это осознанное сужение ТИПА, а не структурная невозможность.
// Поэтому набор здесь ровно один, и расширять его «за компанию» нельзя: каждая
// добавленная строка открывает авторскому правилу ярус на родителе, которого
// сегодня ключ не пропускает.
//
// # Исключение у `create` есть, и оно не отменяет правила
//
// `registry.registries` объявляет `v_create` пообъектно, и семантика законная и
// контейнерная: «создать репозиторий в этом пространстве имён» — операция над
// объектом реестра. Производитель ниже это учитывает не перечнем исключений, а
// вопросом к самому типу: строка-ярусная кладётся ТОЛЬКО там, где пообъектной
// нет.
var tierOnlyVerbClasses = []string{"create"}

// TierOnlyVerbClasses — КОПИЯ набора классов, действующих ярусом.
//
// Экспортирована ради гейта предпосылки: перечень, объявленный здесь, обязан
// быть подмножеством закрытого набора классов действия, и проверить это можно
// только назвав его. Второе объявление того же набора разошлось бы с первым
// молча.
func TierOnlyVerbClasses() []string {
	out := make([]string, len(tierOnlyVerbClasses))
	copy(out, tierOnlyVerbClasses)
	return out
}

// CatalogSeedResources — грантуемые пары в порядке точечного ключа.
func CatalogSeedResources() []CatalogSeedRow {
	entries := Catalog()
	out := make([]CatalogSeedRow, 0, len(entries))
	for _, e := range entries {
		out = append(out, CatalogSeedRow{
			Module:   e.Module,
			Resource: e.Resource,
			Dotted:   e.Module + "." + e.Resource,
		})
	}
	return out
}

// CatalogSeedVerbs — пары «(модуль, ресурс) × глагол» в детерминированном
// порядке, ОБЕИХ половин словаря: пообъектной и ярусной.
//
// Тип, у которого набор глаголов не объявлен вовсе, строк не даёт НИ ОДНОЙ —
// ни пообъектных, ни ярусных: у него нет отношения `v_*`, правило на него не
// резолвится ничем, и ярусная строка обещала бы автору выдачу, которой не будет.
//
// Порядок: сначала пообъектные глаголы ресурса (отсортированно), затем ярусные —
// так посев читается как «что тип объявил» плюс «что автор вправе назвать сверх
// этого», а не как один перемешанный список.
func CatalogSeedVerbs() []CatalogSeedVerb {
	out := make([]CatalogSeedVerb, 0, 160)
	for _, r := range CatalogSeedResources() {
		fgaType, ok := ObjectType(r.Module, r.Resource)
		if !ok {
			continue
		}
		verbs := VerbsOfType(fgaType)
		sort.Strings(verbs)
		declared := make(map[string]bool, len(verbs))
		for _, v := range verbs {
			declared[v] = true
			out = append(out, CatalogSeedVerb{
				Module: r.Module, Resource: r.Resource, Verb: v, PerObject: true,
			})
		}
		for _, v := range tierOnlyVerbClasses {
			// Тип, объявивший этот класс ПООБЪЕКТНО, второй строки не получает:
			// у пары (модуль, ресурс, глагол) первичный ключ один, а живость
			// уникальна — вторая строка отвергалась бы схемой.
			if declared[v] {
				continue
			}
			out = append(out, CatalogSeedVerb{Module: r.Module, Resource: r.Resource, Verb: v})
		}
	}
	return out
}
