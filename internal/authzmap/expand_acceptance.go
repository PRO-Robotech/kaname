package authzmap

// expand_acceptance.go — ЕДИНСТВЕННОЕ место, где решается, принимается ли пара
// (тип объекта, отношение) на входе ExpandAccess.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ТРИ `if` В USE-CASE
//
// Приём и компиляция обязаны судить ОДИН набор. Пока приём спрашивал только
// поверхность (`IsExpandableRelation` — объединение наборов ВСЕХ типов), а план
// собирался по набору КОНКРЕТНОГО типа, между ними был зазор, и пара из зазора
// доезжала до формы и возвращалась внутренней ошибкой на корректном запросе
// (#1290). Замер на дереве в день заведения: глагольных типов 27, объединение —
// 7 глаголов, объявленных пар 109, то есть 80 пар приём брал, а компиляция не
// разбирала. По ВСЕЙ поверхности (включая ярусные отношения и членство) зазор
// был шире: 352 пары принималось, 194 компилировалось — 158 из зазора.
//
// Свести решение в одну функцию нужно затем, чтобы перепись спрашивала ТО ЖЕ,
// что RPC. Перепись, переписывающая условие приёма своими словами, — второе
// место об одном предмете, и разойтись с первым она может молча.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ИСХОД НЕ БУЛЕВ
//
// У отказа ТРИ разных основания, и каждое называет СВОЁ поле запроса. Слить их
// в одно «не принимается» значило бы отправить вызывающего править не ту
// координату: у необъявленного типа не объявлено ни одно отношение, а отношение
// вне поверхности негодно при любом типе.

import (
	"fmt"

	"github.com/PRO-Robotech/kaname/internal/authzmodel"
)

// ExpandAcceptance — исход входного контроля пары.
type ExpandAcceptance int

const (
	// ExpandAccepted — тип объявлен, отношение принадлежит поверхности и
	// объявлено ЭТИМ типом: план по паре собирается.
	ExpandAccepted ExpandAcceptance = iota
	// ExpandTypeNotDeclared — такого типа объектов модель не знает вовсе.
	// Виновное поле — тип.
	ExpandTypeNotDeclared
	// ExpandRelationOffSurface — отношение существует, но принадлежит внутренней
	// машинерии модели (переносчики охвата, подтягивающие резолверы,
	// платформенные отношения). Оно негодно при ЛЮБОМ типе, и его отказ старше
	// потипового вопроса — тон этого отказа часть контракта.
	ExpandRelationOffSurface
	// ExpandRelationNotOnType — отношение на поверхности, но ЭТОТ тип его не
	// объявляет. Ровно тот зазор, ради которого функция и заведена.
	ExpandRelationNotOnType
)

func (a ExpandAcceptance) String() string {
	switch a {
	case ExpandAccepted:
		return "принято"
	case ExpandTypeNotDeclared:
		return "тип не объявлен"
	case ExpandRelationOffSurface:
		return "отношение вне поверхности"
	case ExpandRelationNotOnType:
		return "тип не объявляет это отношение"
	default:
		return fmt.Sprintf("ExpandAcceptance(%d)", int(a))
	}
}

// AcceptExpand судит пару (objectType, relation).
//
// Ошибка означает «вшитая модель не разобралась» — это поломка сборки, а не
// негодный ввод, и вызывающий обязан ответить внутренней ошибкой, а не
// INVALID_ARGUMENT: иначе собственная поломка называлась бы виной вызывающего.
//
// Порядок вопросов — от более общей координаты к более частной: тип · поверхность
// · объявление у типа. Он же порядок сообщений, и он же причина, по которой тон
// отказа для машинерии не изменился: отношение вне поверхности отвергается
// раньше, чем задан потиповый вопрос.
func AcceptExpand(objectType, relation string) (ExpandAcceptance, error) {
	plans, err := authzmodel.Shared()
	if err != nil {
		return ExpandAccepted, fmt.Errorf("authzmap: разбор модели прав: %w", err)
	}
	if !plans.DeclaresType(objectType) {
		return ExpandTypeNotDeclared, nil
	}
	if !IsExpandableRelation(relation) {
		return ExpandRelationOffSurface, nil
	}
	if !plans.Declares(objectType, relation) {
		return ExpandRelationNotOnType, nil
	}
	return ExpandAccepted, nil
}
