// TestMain выдаёт пакету ОДИН Postgres на весь тестовый бинарь.
//
// ЗАЧЕМ БАЗА ПАКЕТУ, КОТОРЫЙ РАЗБИРАЕТ ТЕКСТ МОДЕЛИ. Большинство проб здесь
// читают канонический файл модели и утверждают её ФОРМУ — им база не нужна и они
// её не трогают. Но у части утверждений предмет не форма, а ИСХОД: «право
// администратора облака достаёт до листа», «администратор проекта до содержимого
// своего проекта по выводу не достаёт». Исход считает форма вердикта поверх
// собственной базы iam, и спросить его больше негде: внешнего движка отношений в
// дереве нет.
//
// Здесь стоял TestMain, поднимавший этот движок контейнером. Он снят вместе со
// своим предметом; предмет утверждений — нет.
//
// Ничего не запускается: контейнер поднимается на первом обращении, поэтому
// прогон, где каждая такая проба пропущена (`-short`), не платит ничего.
func TestMain(m *testing.M) {
	os.Exit(pgtest.Run(m, pgtest.Config{
		Name:    "iam",
		Migrate: pgtest.Goose(migrations.FS),
	}))
}
