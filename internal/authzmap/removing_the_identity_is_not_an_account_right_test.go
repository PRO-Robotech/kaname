// removing_the_identity_is_not_an_account_right_test.go — гейт на КЛАСС:
// СТЕРЕТЬ СТРОКУ ЛИЧНОСТИ не вправе тот, кто распоряжается аккаунтом.
//
// # Предмет — тот же класс, что #1102, и с более тяжёлым исходом (#1131)
//
// #1102 увёл правку записи и запрет личности с отношений, имеющих источники
// уровня аккаунта: строка `iam_user` — ГЛОБАЛЬНАЯ личность, одна на все аккаунты
// человека (миграции 20260822234500 / 20260823050000), и распоряжаться ею
// аккаунт не вправе.
//
// `Delete` остался на `v_delete`, у которого источников уровня аккаунта ТРИ:
// пообъектная выдача, делегированный администратор аккаунта, владелец аккаунта.
// Удаление той же глобальной строки из аккаунта A стирает человека и в аккаунте
// B — он теряет личность целиком, а не участие в одном тенанте. Это строго
// тяжелее запрета, который #1102 из аккаунта уже вынес: запрет обратим, удаление
// нет.
//
// # Какой из трёх исходов #1131 выбран — и почему
//
// Задача называла три и требовала записать выбор, а не принять его молча:
//
//  1. удаление личности — действие уровня облака, а распорядителю аккаунта
//     служит ИСКЛЮЧЕНИЕ ИЗ АККАУНТА (#1127);
//  2. удаление, разрешённое, пока человек состоит РОВНО В ОДНОМ аккаунте;
//  3. самоудаление остаётся всегда.
//
// Взят ПЕРВЫЙ, вместе с третьим. Второй отвергнут по существу, а не по вкусу:
//
//   - он делает вердикт функцией данных, которых вызывающий не видит. «Сколько
//     у человека членств» — сведения о его участии в ЧУЖИХ аккаунтах; ответ
//     «нельзя, он ещё где-то состоит» сам по себе их раскрывает;
//   - он не выразим в модели: у отношения нет способа спросить мощность
//     множества членств, поэтому решение уехало бы в самодельную проверку
//     сервиса — ровно то, что запрещает `security.md` §«Авторизация живёт в
//     МОДЕЛИ, а не в самодельных проверках»;
//   - и он гонка: между «членство одно» и удалением строки приходит приглашение
//     во второй аккаунт (ban #10, check-then-act). Выразить его атомарно можно
//     было бы только в СУБД, но модель при этом продолжала бы утверждать, что
//     аккаунт удалять вправе, — а это неверно в общем случае;
//   - и он не нужен: потребность аккаунта, ради которой второй исход
//     рассматривался, закрывает исключение из аккаунта (#1127) — оно приходит
//     тем же изменением.
//
// # Что здесь утверждается — и почему через КАТАЛОГ, а не через литерал
//
// Проба не знает наперёд, каким отношением гейтится `Delete`: она СПРАШИВАЕТ его
// у каталога прав (тот генерируется из proto и есть единственный источник
// per-RPC решения края), компилирует отношение из КАНОНИЧЕСКОЙ модели и смотрит
// на источники разрешения. Литерал имени отношения превратил бы гейт в проверку
// написания: он остался бы зелёным, если бы завтра `Delete` вернули на отношение
// с источниками уровня аккаунта под другим именем.
//
// # Круг держателей утверждается РАВЕНСТВОМ, а не вхождением
//
// Вхождение зеленеет на любом ДОБАВЛЕННОМ источнике — то есть на том самом
// дефекте, который здесь закрывается. Круг ровно два: сам человек (самоудаление
// — исход 3, и оно уже сегодня разрешено путём `delete.go`) и надзор облака.
//
// # Обе стороны, потому что односторонняя проба зеленеет на пустом
//
//   - ОТРИЦАНИЕ: источников уровня аккаунта нет ни одного;
//   - ОТРИЦАНИЕ 2: отношение НЕВЫДАВАЕМО — прямого списка субъектов у него нет,
//     иначе запрет обходится одной строкой журнала;
//   - КОНТРОЛЬ 1: сам человек — источник (иначе самоудаление сломано);
//   - КОНТРОЛЬ 2: надзор облака — источник (иначе строку не удалить НИКОМУ, и
//     запрет держался бы не разделением прав, а недостижимостью);
//   - КОНТРОЛЬ 3: у ЧТЕНИЯ записи источники уровня аккаунта ОСТАЛИСЬ — без него
//     «источников нет» неотличимо от «разбор ничего не нашёл».
package authzmap_test

import (
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/PRO-Robotech/kacho-iam/internal/authzplan"
)

// identityRemovalRPC — RPC, чей предмет есть СНЯТИЕ СТРОКИ ЛИЧНОСТИ.
//
// По FQN, потому что «снятие личности» — свойство СМЫСЛА RPC, а не его
// написания. Запись обязана находиться в каталоге, иначе перечень пережил свой
// предмет.
const identityRemovalRPC = "kacho.cloud.iam.v1.UserService/Delete"

// identityRemovalSources — круг держателей, в который отношение снятия обязано
// раскрываться ЦЕЛИКОМ: сам человек и надзор облака.
func identityRemovalSources() []planSource {
	return []planSource{
		{Kind: authzplan.AtomFact, ParentType: "", Relation: "subject"},
		cloudSource,
	}
}

// TestRemovingTheIdentityHasNoAccountLevelSource — гейт класса.
func TestRemovingTheIdentityHasNoAccountLevelSource(t *testing.T) {
	model := canonicalModel(t)
	catalog := catalogByFQN(t)

	require.NotEmpty(t, catalog, "каталог прав разобран в ноль записей — предпосылка гейта сломана")

	// КОНТРОЛЬ 3 — сперва, чтобы отрицание ниже не могло зеленеть на сломанном
	// разборе.
	readEntry, ok := catalog[recordReadRPC]
	require.Truef(t, ok, "каталог не знает %s — контроль отрицания отсутствует", recordReadRPC)
	readVerdict := inspectCredentialRelation(t, model, readEntry.objectType, readEntry.relation)
	require.ElementsMatchf(t, accountLevelSources(readEntry.relation), readVerdict.AccountLevel,
		"КОНТРОЛЬ: у отношения ЧТЕНИЯ ЗАПИСИ %s.%s обязаны быть ВСЕ источники уровня аккаунта. "+
			"Их отсутствие означает, что разбор модели ничего не нашёл, и тогда отрицание ниже "+
			"вакуумно", readEntry.objectType, readEntry.relation)

	e, ok := catalog[identityRemovalRPC]
	require.Truef(t, ok, "каталог не знает %s — перечень «снятие личности» пережил свой предмет",
		identityRemovalRPC)
	require.Equalf(t, "iam_user", e.objectType,
		"%s гейтится не на объекте личности (%s) — предмет пробы сменился",
		identityRemovalRPC, e.objectType)

	v := inspectCredentialRelation(t, model, e.objectType, e.relation)

	// ОТРИЦАНИЕ.
	require.Emptyf(t, v.AccountLevel,
		"%s гейтится отношением %s.%s, у которого есть источники уровня аккаунта: %v.\n"+
			"Строка `iam_user` — ГЛОБАЛЬНАЯ личность: одна на все аккаунты человека. Удаление "+
			"её из аккаунта A стирает человека и в аккаунте B — он теряет личность целиком, "+
			"а не участие в одном тенанте.\n"+
			"Это строго тяжелее запрета, который #1102 из аккаунта уже вынес: запрет обратим, "+
			"удаление нет. Распорядителю аккаунта служит ИСКЛЮЧЕНИЕ ИЗ АККАУНТА "+
			"(`UserService/RemoveFromAccount`, #1127), а не снятие личности.",
		identityRemovalRPC, e.objectType, e.relation, planSourceNames(v.AccountLevel))

	// ОТРИЦАНИЕ 2 — отношение НЕВЫДАВАЕМО.
	require.Falsef(t, v.Grantable,
		"%s гейтится отношением %s.%s, у которого ЕСТЬ прямой список субъектов.\n"+
			"Значит право стереть личность можно ВРУЧИТЬ — кортежем, выдачей или "+
			"материализацией, — и тогда разделение прав выше обходится одной записью.\n"+
			"Отношение обязано быть вычисляемым: держателей у него ровно двое, и оба структурны.",
		identityRemovalRPC, e.objectType, e.relation)

	// КОНТРОЛЬ 1 — сам человек.
	require.Truef(t, v.HasSelf,
		"%s гейтится отношением %s.%s, у которого САМ ЧЕЛОВЕК не источник — самоудаление "+
			"сломано. Оно разрешено всегда и было разрешено до этого сужения "+
			"(`api/user/delete.go`), поэтому его пропажа означала бы, что сужение отняло "+
			"больше, чем собиралось.\nИсточники плана: %v",
		identityRemovalRPC, e.objectType, e.relation, sortedKeys(v.Sources))

	// КОНТРОЛЬ 2 — надзор облака.
	require.Truef(t, v.HasCloud,
		"%s гейтится отношением %s.%s, у которого НЕТ надзора облака (%+v). Тогда чужую строку "+
			"не удалить НИКОМУ, и запрет выше держится не разделением прав, а недостижимостью "+
			"отношения.\nИсточники плана: %v",
		identityRemovalRPC, e.objectType, e.relation, cloudSource, sortedKeys(v.Sources))

	// РАВЕНСТВО КРУГА.
	require.ElementsMatchf(t, identityRemovalSources(), keysOf(v.Sources),
		"%s гейтится отношением %s.%s, круг держателей которого НЕ РАВЕН объявленному: "+
			"ожидались сам человек и надзор облака, в плане %v.\n"+
			"Утверждается равенство, а не вхождение: вхождение зеленеет на любом ДОБАВЛЕННОМ "+
			"источнике — то есть на том самом дефекте, который здесь закрывается.",
		identityRemovalRPC, e.objectType, e.relation, sortedKeys(v.Sources))

	t.Logf("перепись: записей каталога прочитано %d · отношение снятия личности %s.%s "+
		"(источников %d, из них уровня аккаунта %d) · контроль чтения записи %s.%s "+
		"(источников %d, уровня аккаунта %d)",
		len(catalog), e.objectType, e.relation, len(v.Sources), len(v.AccountLevel),
		readEntry.objectType, readEntry.relation, len(readVerdict.Sources), len(readVerdict.AccountLevel))
}
