package authzmap

// empty_type_is_an_unambiguous_miss_test.go — ПУСТОЕ ИМЯ ТИПА ОЗНАЧАЕТ ПРОМАХ
// И НИЧЕГО БОЛЬШЕ (kacho#1980).
//
// # Зачем это утверждение существует
//
// Двузначные читатели закрытой таблицы (`ObjectType`, `FGAObjectType`,
// `DottedType`) отдают пару `(значение, известна ли пара)`. Вызывающий вправе
// взять только первое ТОЛЬКО ПОКА пустое значение не бывает законным: иначе
// «пары нет» и «пара есть, а имя у неё пустое» сливаются в одно, и отличить их
// становится нечем.
//
// Задача #1980 называла это слияние действующим дефектом. Замер показал
// обратное: **значений пусто в таблице ноль**, поэтому слияние НЕ ПРЕДСТАВИМО, а
// пять оставшихся мест дерева, берущих только первое значение, читаются
// потребителями, которые пустоту декодируют СВОЕЙ веткой и дают по ней отдельный
// разбор (`roleexport`: `Produces`, `emptyClassDetail`, `unsuitableDetail` —
// ресурс без пообъектного типа существует, у него право спрашивается на области).
//
// # Почему это ПРОБА, а не строка в комментарии
//
// Свойство держит таблицу, а таблица ПОРОЖДАЕТСЯ манифестами дерева. Первое же
// объявление ресурса с пустым именем типа сделало бы пустоту законным значением
// — и все пять мест стали бы тем самым дефектом, о котором задача и говорит,
// молча и в тот же день. Утверждение обязано падать раньше, чем это случится.

import "testing"

// TestEmptyTypeNameIsNeverALegalValue — сценарий #1980-A.
func TestEmptyTypeNameIsNeverALegalValue(t *testing.T) {
	// Перепись — ДО вердикта: «ноль находок» обязано быть отличимо от «ноль
	// прочитанного», а таблица порождается и может прийти пустой.
	t.Logf("осмотрено: пар в закрытой таблице %d; типов с набором действий %d",
		len(objectTypes), len(typeVerbRelations))
	if len(objectTypes) == 0 || len(typeVerbRelations) == 0 {
		t.Fatalf("таблица пуста (пар %d, типов %d) — вердикт беспредметен: "+
			"утверждение о значениях зеленело бы, не осмотрев ни одного",
			len(objectTypes), len(typeVerbRelations))
	}

	var empty []string
	for key, typ := range objectTypes {
		if typ == "" {
			empty = append(empty, key)
		}
	}
	if len(empty) > 0 {
		t.Errorf("у %d пар имя типа ПУСТО (%v).\n\n"+
			"С этого момента пустое имя — законное значение, и «пары нет» от «пара есть, "+
			"а имя пустое» больше не отличается ничем. Пять мест дерева берут у "+
			"`authzmap.ObjectType` только первое значение — они были верны РОВНО ПОКА "+
			"это утверждение держалось. Либо снимите пустое имя, либо переведите те "+
			"места на чтение второго значения (kacho#1980)", len(empty), empty)
	}
}

// TestMissReturnsTheEmptyName — вторая половина эквивалентности.
//
// Утверждение выше говорит «законного пустого имени нет»; без этого — «промах
// отдаёт пустое имя» — эквивалентность односторонняя, и вызывающий, читающий
// пустоту как промах, опирался бы на половину свойства.
func TestMissReturnsTheEmptyName(t *testing.T) {
	// Пара, которой в закрытой таблице нет by construction: модуль с таким
	// именем не объявлен ни одним манифестом.
	if typ, ok := ObjectType("нет-такого-модуля", "нет-такого-ресурса"); ok || typ != "" {
		t.Errorf("промах отдал (%q, %v), ожидалось (\"\", false): пустота перестала быть "+
			"признаком промаха, и читатель первого значения молча получил бы имя (kacho#1980)",
			typ, ok)
	}
	// Положительный контроль: законная пара обязана отдать НЕПУСТОЕ имя — иначе
	// утверждение выше зеленело бы на реализации, отвечающей пустотой всегда.
	for key, want := range objectTypes {
		module, resource, ok := SplitObjectType(key)
		if !ok {
			t.Fatalf("ключ таблицы %q не разбирается на пару — предпосылка контроля сломана", key)
		}
		got, known := ObjectType(module, resource)
		if !known || got != want || got == "" {
			t.Fatalf("законная пара %q отдала (%q, %v), ожидалось (%q, true)",
				key, got, known, want)
		}
		break
	}
}
