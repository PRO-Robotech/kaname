// governing_the_identity_is_not_an_account_right_test.go — гейт на КЛАСС:
// РАСПОРЯЖАТЬСЯ СТРОКОЙ ЛИЧНОСТИ не вправе тот, кто распоряжается аккаунтом.
//
// # Предмет
//
// Человек в этом дереве — ГЛОБАЛЬНАЯ ЛИЧНОСТЬ: одна строка `iam_user` на все его
// аккаунты (миграции 20260822234500 / 20260823050000, пробы identity_is_global_*).
// Строка больше не есть членство: принадлежность аккаунтам выражают строки
// `memberships`, которых у человека может быть сколько угодно.
//
// Отсюда следствие, которое и закрывает этот гейт: всё, что записано В СТРОКУ,
// действует ВО ВСЕХ аккаунтах человека сразу. Метки строки решают, в какие
// селекторные выдачи он попадает — в любом аккаунте, не только в том, откуда
// метку поставили. Состояние строки решает, войдёт ли он на платформу вообще —
// а не «участвует ли он в этом аккаунте».
//
// Значит распорядитель ОДНОГО аккаунта, получив право на эти действия, получает
// власть за границей своего аккаунта. Директива владельца (2026-08-23) говорит
// прямо: «тот кто пригласил может только удалить/добавить права».
//
// # Что здесь утверждается — и почему через КАТАЛОГ, а не через литерал
//
// Проба не знает наперёд, каким отношением гейтятся эти RPC: она СПРАШИВАЕТ его
// у каталога прав (тот генерируется из proto и является единственным источником
// per-RPC решения края), компилирует отношение из КАНОНИЧЕСКОЙ модели и смотрит
// на источники разрешения. Литерал имени отношения превратил бы гейт в проверку
// написания: он остался бы зелёным, если бы завтра эти RPC вернули на отношение
// с источниками уровня аккаунта под другим именем.
//
// # Обе стороны, потому что односторонняя проба зеленеет на пустом
//
//   - ОТРИЦАНИЕ: у отношения НЕТ источников уровня аккаунта — ни пообъектной
//     выдачи, ни делегированного администратора аккаунта, ни его владельца;
//   - ОТРИЦАНИЕ 2: у отношения НЕТ прямого списка субъектов, то есть его нельзя
//     ВРУЧИТЬ ни кортежем, ни выдачей, ни материализацией. Без этого утверждения
//     запрет выше обходится одной строкой журнала;
//   - ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 1: держатель у отношения ЕСТЬ — администратор
//     облака (`cluster#system_admin`, он же несёт бутстрап-личность). Иначе
//     запрет держался бы не разделением прав, а тем, что отношения не держит
//     никто, и управление личностью было бы сломано незаметно;
//   - ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 2: у ЧТЕНИЯ записи (`UserService/Get`) источники
//     уровня аккаунта обязаны ОСТАТЬСЯ. Читать своих людей — законное дело
//     аккаунта, и без этого контроля «источников нет» неотличимо от «разбор
//     ничего не нашёл».
//
// # Почему администратор облака здесь НАЗВАН, хотя у соседнего гейта не назван
//
// `acting_as_a_person_is_not_editing_his_record_test.go` уровень 1 намеренно не
// называет: у отношения `token_issuer` есть собственный держатель-арендатор (сам
// человек), и надзор облака добавляется плоским коротким замыканием службы
// (`authzguard.SubjectIsClusterAdmin` из `AuthorizeService.verdict`).
//
// Здесь держателя-арендатора НЕТ НИ ОДНОГО — в том и смысл, — а тело отношения
// на языке модели обязано быть непустым. Поэтому источник назван, и назван
// ровно тот, что и в замыкании: `super_admin from account` разворачивается в
// `any_admin from cluster` → `cluster#system_admin`. Совпадение множеств
// проверяется здесь же (контроль 1), а не предполагается: разойдись они —
// покраснеет эта проба, а не чей-то доступ на проде.
package authzmap_test

import (
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/PRO-Robotech/kacho-iam/internal/authzplan"
)

// governingRPCs — публичные RPC, чей предмет есть РАСПОРЯЖЕНИЕ СТРОКОЙ ЛИЧНОСТИ:
// правка самой записи и запрет/снятие запрета личности на платформе.
//
// Перечислены по FQN, потому что «распоряжение строкой» — свойство СМЫСЛА RPC, а
// не его написания. Перечень мал и закрыт; каждая запись обязана находиться в
// каталоге, иначе перечень пережил свой предмет.
var governingRPCs = []string{
	"kacho.cloud.iam.v1.UserService/Update",
	"kacho.cloud.iam.v1.UserService/Block",
	"kacho.cloud.iam.v1.UserService/Unblock",
}

// accountScopedReadRPC — чтение записи. Положительный контроль: именно у него
// источники уровня аккаунта обязаны ОСТАТЬСЯ.
const accountScopedReadRPC = "kacho.cloud.iam.v1.UserService/Get"

// cloudSource — надзор облака (уровни 1-2: администратор облака и бутстрап-личность
// сидят на ОДНОМ отношении, миграция 0058).
var cloudSource = planSource{Kind: authzplan.AtomFact, ParentType: "cluster", Relation: "system_admin"}

// TestGoverningTheIdentityHasNoAccountLevelSource — гейт класса.
func TestGoverningTheIdentityHasNoAccountLevelSource(t *testing.T) {
	model := canonicalModel(t)
	catalog := catalogByFQN(t)

	require.NotEmpty(t, catalog, "каталог прав разобран в ноль записей — предпосылка гейта сломана")

	// Положительный контроль 2 — сперва, чтобы отрицание ниже не могло зеленеть
	// на сломанном разборе.
	readEntry, ok := catalog[accountScopedReadRPC]
	require.Truef(t, ok, "каталог не знает %s — контроль отрицания отсутствует", accountScopedReadRPC)
	readPlan, err := model.Compile(readEntry.objectType, readEntry.relation)
	require.NoErrorf(t, err, "компиляция %s.%s (чтение записи)", readEntry.objectType, readEntry.relation)
	readSources := sourcesOf(t, readPlan)
	for _, want := range accountLevelSources(readEntry.relation) {
		require.Containsf(t, readSources, want,
			"КОНТРОЛЬ: у отношения ЧТЕНИЯ записи %s.%s обязан быть источник уровня аккаунта %+v. "+
				"Его отсутствие означает, что разбор модели ничего не нашёл, и тогда отрицание "+
				"ниже вакуумно", readEntry.objectType, readEntry.relation, want)
	}

	checked := 0
	for _, fqn := range governingRPCs {
		e, ok := catalog[fqn]
		require.Truef(t, ok, "каталог не знает %s — перечень «распоряжения строкой» пережил свой предмет", fqn)
		require.Equalf(t, "iam_user", e.objectType,
			"%s гейтится не на объекте личности (%s) — предмет пробы сменился", fqn, e.objectType)

		plan, err := model.Compile(e.objectType, e.relation)
		require.NoErrorf(t, err, "компиляция %s.%s (%s)", e.objectType, e.relation, fqn)
		require.NotEmptyf(t, plan.Atoms, "план %s.%s пуст — ни одного источника разрешения",
			e.objectType, e.relation)
		got := sourcesOf(t, plan)

		// ОТРИЦАНИЕ.
		for _, banned := range accountLevelSources(e.relation) {
			origin, present := got[banned]
			require.Falsef(t, present,
				"%s гейтится отношением %s.%s, у которого источник уровня аккаунта %+v (%s).\n"+
					"Человек — ГЛОБАЛЬНАЯ личность: одна строка `iam_user` на все его аккаунты. "+
					"Значит записанное в строку действует во ВСЕХ его аккаунтах сразу — метки решают, "+
					"в какие селекторные выдачи он попадает где угодно, а состояние решает, войдёт ли "+
					"он на платформу вообще.\n"+
					"Распорядитель ОДНОГО аккаунта, получив это право, распоряжается за границей "+
					"своего аккаунта. Директива владельца: пригласивший может ТОЛЬКО удалить или "+
					"добавить права — этим он и располагает (выдачи `iam_access_binding` его аккаунта).",
				fqn, e.objectType, e.relation, banned, origin)
		}

		// ОТРИЦАНИЕ 2 — отношение НЕВЫДАВАЕМО.
		ownDirect := planSource{Kind: authzplan.AtomFact, ParentType: "", Relation: e.relation}
		if origin, present := got[ownDirect]; present {
			require.Failf(t, "отношение распоряжения строкой стало выдаваемым",
				"%s гейтится отношением %s.%s, у которого ЕСТЬ прямой список субъектов (%s).\n"+
					"Значит право распоряжаться личностью можно ВРУЧИТЬ — кортежем, выдачей или "+
					"материализацией, — и тогда разделение прав выше обходится одной записью.",
				fqn, e.objectType, e.relation, origin)
		}

		// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 1 — держатель есть.
		require.Containsf(t, got, cloudSource,
			"%s гейтится отношением %s.%s, которого не держит НИКТО: надзора облака "+
				"(%+v) среди источников нет. Тогда запрет выше держится не разделением прав, а "+
				"недостижимостью отношения, и управление личностью сломано незаметно.\nИсточники плана: %v",
			fqn, e.objectType, e.relation, cloudSource, sortedKeys(got))
		checked++
	}

	t.Logf("перепись: записей каталога прочитано %d · RPC «распоряжение строкой» сверено %d · "+
		"контроль чтения записи %s.%s (источников %d)",
		len(catalog), checked, readEntry.objectType, readEntry.relation, len(readSources))
}
