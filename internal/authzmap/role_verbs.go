package authzmap

// role_verbs.go — какие глаголы правило роли даёт на типе. ОДИН предикат на обе
// стороны.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО ЖИВЁТ ЗДЕСЬ, А НЕ В ДОМЕНЕ
//
// Ответ зависит от НАБОРА ГЛАГОЛОВ ТИПА: подстановка `*` разворачивается в него,
// глагол вне набора не даёт отношения, а совместное появление удаления при
// правке проверяется по нему же. Набор объявляет каталог типов, то есть этот
// пакет. Домен его не знает и знать не должен — потому вычисление и переехало
// сюда целиком, а не половиной.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЭТО ЧИНИТ (выведено 2026-08-16, задача #496)
//
// Предикат «что роль разрешает на типе» существовал в ДВУХ местах и отвечал
// по-разному:
//
//   - материализатор кортежей (`access_binding/reconcile`) разворачивал `*` в
//     набор типа и добавлял удаление к правке — то есть давал движку ровно тот
//     набор, которым движок потом отвечает;
//   - проекция `role_verb`, которую читает форма E, считала пары ПО АВТОРСКОМУ
//     написанию: подстановку отбрасывала, удаление не добавляла.
//
// Оба места по отдельности непротиворечивы, поэтому расхождение не видно ни в
// одном обзоре: оно проявляется только вопросом о доступе — движок отвечает
// «да», форма E «нет». Роль-администратор (`verbs: ["*"]`) при этом не давала
// форме E НИ ОДНОГО глагола, а роль-редактор не давала удаления, которое сама же
// материализует.
//
// Теперь предикат один, и обе стороны зовут его. Разойтись им больше нечем.

import "github.com/PRO-Robotech/kaname/internal/domain"

// GrantedVerbs — глаголы, которые правило с авторскими глаголами `authored`
// даёт НА ТИПЕ `fgaType`, в канонической форме и без приставки отношения.
//
// typeVerbs — набор, по которому разворачивается подстановка и отсеивается
// чужой глагол. Он ПАРАМЕТР, а не выводится здесь: у вызывающего бывает причина
// предъявить урезанный набор (отрицательная проба обязана уметь показать тип,
// у которого глагола нет, ДО того как такой тип появится в каталоге).
//
// Тип, у которого набор глаголов не ОБЪЯВЛЕН вовсе, не получает ни одного
// глагола, каким бы ни был `typeVerbs`: отношения `v_*` у него не существует,
// и пара в проекции адресовала бы отношение, которого нет в модели.
func GrantedVerbs(fgaType string, authored, typeVerbs []string) []string {
	return GrantedVerbsWithDeclared(fgaType, len(VerbsOfType(fgaType)) > 0, authored, typeVerbs)
}

// GrantedVerbsWithDeclared — ТОТ ЖЕ предикат, но единственный факт, который он
// берёт у каталога, приходит ПАРАМЕТРОМ: объявляет ли тип набор глаголов вообще.
//
// Разделение заведено задачей #1816. Каталог существует ДВУМЯ выражениями —
// литералом (производная канона `fga_model.fga`) и живыми строками
// `kaname.catalog_*`, — и ответ на «объявлен ли набор» у них расходится ровно
// в один момент: когда строка снята в РАБОТАЮЩЕМ процессе. Вычисление же
// глаголов от источника не зависит вовсе, поэтому оно и осталось ОДНИМ: две
// реализации вопроса «что роль разрешает на типе» по отдельности непротиворечивы
// и расходятся молча — так роль-администратор давала движку весь набор, а
// проекции `role_verb` ни одного глагола (#496).
//
// `declaresVerbs` и `typeVerbs` — РАЗНЫЕ величины, и свести их нельзя: вызывающий
// вправе предъявить набор ЗАПАСНОЙ (якорь без собственного набора разворачивает
// подстановку общим словарём ради вывода яруса), и тогда `typeVerbs` непуст, а
// тип не объявляет ничего.
func GrantedVerbsWithDeclared(fgaType string, declaresVerbs bool, authored, typeVerbs []string) []string {
	if !declaresVerbs {
		return nil
	}
	expanded, _ := domain.ResolveVerbsAndTier(authored, typeVerbs)
	seen := make(map[string]bool, len(expanded)+1)
	out := make([]string, 0, len(expanded)+1)
	hasUpdate := false
	for _, v := range expanded {
		if !domain.IsVerbOfType(v, typeVerbs) {
			continue
		}
		verb := domain.NormalizeVerb(v)
		if verb == "update" {
			hasUpdate = true
		}
		if seen[verb] {
			continue
		}
		seen[verb] = true
		out = append(out, verb)
	}
	// ПРАВКА ВЛЕЧЁТ УДАЛЕНИЕ — НА ЛИСТЕ.
	//
	// В плоской модели с глаголами редактор удаляет то, что редактирует: выдача,
	// несущая правку, обязана нести и удаление, иначе создатель ресурса получает
	// отказ на уборке за СВОИМ ЖЕ объектом (роль-редактор на проекте даёт чтение,
	// перечисление и правку, но не удаление). Закрывается это в единственном месте
	// вычисления набора — без повышения яруса совместимости и без раздачи лишнего
	// удаления всем ролям подряд: удаление получает только тот, кто уже правит.
	//
	// ОБЛАСТИ ИЕРАРХИИ ИСКЛЮЧЕНЫ. Снос аккаунта или проекта — действие владельца
	// или администратора, а не редактора содержимого; выдача уровня правки на
	// области (своей или как содержимого выдачи владельцу аккаунта) удаления самой
	// области получать не должна. Роль, назвавшая удаление явно, его сохраняет —
	// цикл выше уже его добавил.
	//
	// СВЕРКА С НАБОРОМ ТИПА ОБЯЗАТЕЛЬНА И ЗДЕСЬ, не только в цикле: приписанное
	// строкой отношение обошло бы и набор, и таблицу, и тип, у которого удаления не
	// объявлено, получил бы висячее отношение, как только роль назовёт правку.
	if hasUpdate && !IsHierarchyScopeType(fgaType) && domain.IsVerbOfType("delete", typeVerbs) && !seen["delete"] {
		out = append(out, "delete")
	}
	return out
}

// IsHierarchyScopeType — тип-область иерархии (аккаунт, проект).
//
// Вынесен из материализатора и назван здесь, потому что теперь его читают двое:
// удаление, добавляемое к правке, на этих двух типах не добавляется — снос
// области принадлежит владельцу, а не редактору содержимого.
func IsHierarchyScopeType(fgaType string) bool {
	return fgaType == "account" || fgaType == "project"
}

// RoleVerbsFromSelectors — проекция «тип × глагол» из тех же селекторов,
// которыми роль материализуется.
//
// ИСТОЧНИК ОДИН — селекторы: второй (разбор разрешений заново) дал бы два места
// об одном предмете, расходящиеся при первом же изменении формы правила, причём
// молча.
//
// Тип в проекции остаётся ТОЧЕЧНЫМ — тем же, каким он назван в селекторах и
// каким его читает вердикт (`role_verb.object_type`). Набор глаголов при этом
// спрашивается у каталога по имени МОДЕЛИ: два словаря в одном соединении не
// совпадают никогда и молча, поэтому перевод делается здесь, ровно один раз.
//
// Тип, которого каталог не знает, пар не даёт: материализатор на нём тоже не
// эмитит ничего, и выдумать за него набор значило бы дать право, которого движок
// не даёт.
func RoleVerbsFromSelectors(selectors []domain.RuleSelector) []domain.RoleVerb {
	seen := make(map[domain.RoleVerb]bool)
	out := make([]domain.RoleVerb, 0, len(selectors))
	for _, sel := range selectors {
		for _, dotted := range sel.ObjectTypes {
			if dotted == "" {
				continue
			}
			fgaType, ok := FGAObjectType(dotted)
			if !ok {
				continue
			}
			for _, verb := range GrantedVerbs(fgaType, sel.Verbs, VerbsOfType(fgaType)) {
				pair := domain.RoleVerb{ObjectType: dotted, Verb: verb}
				if seen[pair] {
					continue
				}
				seen[pair] = true
				out = append(out, pair)
			}
		}
	}
	return out
}
