// neighbour_account_admin_must_not_reach_the_identity_test.go — полоса RED
// сценария IAM-ID-1-31 (приёмка IAM-ID-1, S3.1, отпечаток
// 46d03ba4b34fdf12db060cef15292fc03f642a93a520e6aea14e3fafaed0723e).
//
// # Сценарий
//
// Человек-личность состоит в ДВУХ аккаунтах — A и B (две строки `memberships`
// на одну строку `iam_user`; конструируемо уже сегодня приглашением известной
// почты во второй аккаунт, §16.2 приёмки). Администратор аккаунта B НЕ должен
// получать доступ к объекту личности (чтение записи и её операций) через своё
// членство в B. Администратор аккаунта A — должен: это его человек.
//
// # Почему сегодня админ B ПОЛУЧАЕТ доступ (предмет защиты отсутствует)
//
// Объектом гейта для `v_get` (`UserService/Get`) и `v_list`
// (`UserService/ListOperations`) стоит ГЛОБАЛЬНАЯ личность `iam_user`. Эти два
// глагола аккаунт-скоупны через `super_admin` = `admin from account`. Предком-
// аккаунтом объекта личности служит звено цепи областей
// `kaname.resource_scope_edge`, берущее предка ИЗ `kaname.memberships`: при N
// членствах у объекта личности N предков-аккаунтов, и `admin from account`
// читает ЛЮБОГО из них. Значит администратор аккаунта B — соседа по членству —
// разворачивается в `super_admin` на общей строке личности и читает её в
// контексте аккаунта A. Это и есть утечка, которую закрывает S3.1.
//
// Остаток S3.1 — ДВЕ вещи (обе отсутствуют на origin/main), и различающий
// сценарий обеих — этот:
//
//	(1) тип `iam_membership` в модели прав (сейчас его нет; 32 типа → станет 33);
//	(2) смена объекта гейта `v_get`/`v_list` с `iam_user` на `iam_membership` —
//	    членство принадлежит РОВНО ОДНОМУ аккаунту, поэтому `admin from account`
//	    на `iam_membership:<человек×A>` резолвится только в администратора A, и
//	    админ B к личности в контексте A уже не дотягивается.
//
// # Что утверждается — и почему через КАТАЛОГ и МОДЕЛЬ, а не через литерал
//
// Проба не выписывает наперёд, каким объектом гейтятся эти RPC: она СПРАШИВАЕТ
// его у каталога прав (единственный источник per-RPC решения края) и компилирует
// отношение из канонической модели. Литерал имени объекта превратил бы гейт в
// проверку написания — он остался бы зелёным, если бы завтра объект сменили под
// другим именем.
//
// # Две стороны, потому что односторонняя проба зеленеет на пустом
//
//   - ОТРИЦАНИЕ (эта проба, RED сегодня): объект гейта для чтения личности обязан
//     быть ОДНО-аккаунтным членством `iam_membership`, а не общей личностью
//     `iam_user`; и тип `iam_membership` обязан существовать в модели, чтобы им
//     вообще можно было гейтить. Пока это `iam_user` при отсутствующем
//     `iam_membership` — админ соседнего аккаунта достаёт до личности.
//   - ПОЛОЖИТЕЛЬНЫЙ БЛИЗНЕЦ (соседняя проба, GREEN сегодня и после фикса): у гейта
//     чтения ЕСТЬ источник уровня аккаунта (`admin from account`) — значит
//     администратор СВОЕГО аккаунта A законно дотягивается до личности. Без этого
//     контроля отрицание было бы вакуумным: «до личности не дотягивается никто»
//     неотличимо от «разбор модели ничего не нашёл».
//
// Предмет пробы — модель прав (глагол × роль × область), не сквозной прогон:
// стенд не нужен. Производитель «Тогда» остатка — приёмка предфазы S3.1;
// реализацию (тип `iam_membership` в обеих байт-идентичных копиях `fga_model.fga`
// + смена объекта гейта) открывает честный красный этой пробы, а не она сама.
package authzmap_test

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/PRO-Robotech/kaname/internal/authzplan"
)

// userReadGateRPCs — публичные RPC чтения объекта личности, чей объект гейта
// остаток S3.1 переносит с `iam_user` на `iam_membership`. Перечислены по FQN,
// потому что «чтение личности» — свойство СМЫСЛА RPC, а не написания. Перечень
// мал и закрыт; каждая запись обязана находиться в каталоге, иначе перечень
// пережил свой предмет.
var userReadGateRPCs = []string{
	"kaname.cloud.iam.v1.UserService/Get",            // v_get  = iam.users.get
	"kaname.cloud.iam.v1.UserService/ListOperations", // v_list = iam.user_operationses.listOperations
}

// membershipObjectType — одно-аккаунтный объект гейта, которым обязано гейтиться
// чтение личности после S3.1.
const membershipObjectType = "iam_membership"

// accountAdminSource — источник уровня аккаунта, которым обладает администратор
// аккаунта: `super_admin` = `admin from account` разворачивается в него. Именно
// он у объекта личности достаёт до администратора ЛЮБОГО из аккаунтов человека.
var accountAdminSource = planSource{Kind: authzplan.AtomFact, ParentType: "account", Relation: "admin"}

// TestUserReadGate_IAMID131_AdminOfNeighbourAccountMustNotReachIdentity —
// ЧЕСТНЫЙ КРАСНЫЙ сценария IAM-ID-1-31.
//
// Красный обязан прийти от предмета защиты, а не от сорванной фикстуры: сперва —
// вся проверка фикстуры (каталог разобран, RPC известны, модель компилируется,
// источник уровня аккаунта на месте), и только ПОТОМ — отрицание.
func TestUserReadGate_IAMID131_AdminOfNeighbourAccountMustNotReachIdentity(t *testing.T) {
	model := canonicalModel(t)
	catalog := catalogByFQN(t)

	// ── фикстура: предпосылки, чтобы красный ниже не был «не выполнилось» ──────
	require.NotEmpty(t, catalog, "каталог прав разобран в ноль записей — предпосылка гейта сломана")

	checked := 0
	for _, fqn := range userReadGateRPCs {
		e, ok := catalog[fqn]
		require.Truef(t, ok, "каталог не знает %s — перечень «чтение личности» пережил свой предмет", fqn)

		plan, err := model.Compile(e.objectType, e.relation)
		require.NoErrorf(t, err, "компиляция %s.%s (%s) — фикстура сломана, это не отрицание",
			e.objectType, e.relation, fqn)
		require.NotEmptyf(t, plan.Atoms, "план %s.%s пуст — ни одного источника разрешения", e.objectType, e.relation)
		got := sourcesOf(t, plan)

		// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: у гейта чтения ЕСТЬ источник уровня аккаунта.
		// Он и делает утечку возможной (админ аккаунта дотягивается до объекта), и
		// он же — легитимный путь администратора СВОЕГО аккаунта. Без него
		// отрицание ниже вакуумно.
		require.Containsf(t, got, accountAdminSource,
			"КОНТРОЛЬ: у гейта чтения %s (%s.%s) нет источника уровня аккаунта %+v — "+
				"тогда вопрос «кто дотягивается» вырожден, и отрицание ниже ничего не значит.\nИсточники: %v",
			fqn, e.objectType, e.relation, accountAdminSource, sortedKeys(got))

		// ── ОТРИЦАНИЕ: предмет защиты обязан существовать ─────────────────────
		//
		// (2) объект гейта — одно-аккаунтное членство, а не общая личность.
		assert.Equalf(t, membershipObjectType, e.objectType,
			"IAM-ID-1-31: АДМИН СОСЕДНЕГО АККАУНТА ПОЛУЧАЕТ ДОСТУП К ЛИЧНОСТИ.\n"+
				"Гейт чтения %s стоит на объекте %q (ГЛОБАЛЬНАЯ личность), а обязан стоять на %q "+
				"(одно-аккаунтное членство).\n"+
				"Механизм утечки: %s.%s аккаунт-скоупен через `admin from account` (источник %+v на месте, "+
				"контроль выше зелёный); предок-аккаунт объекта личности берётся из `kaname.memberships`, "+
				"поэтому при членствах в A и B у объекта ДВА предка, и `admin from account` читает ЛЮБОГО. "+
				"Администратор аккаунта B разворачивается в super_admin на общей строке личности и читает её "+
				"в контексте аккаунта A. Скоупнув гейт на членство `iam_membership:<человек×A>` (ровно один "+
				"предок-аккаунт A), доступ админа B к личности в A исчезает, а доступ админа A остаётся.",
			fqn, e.objectType, membershipObjectType, e.objectType, e.relation, accountAdminSource)

		checked++
	}

	// (1) тип `iam_membership` обязан существовать в модели — иначе им нельзя
	// гейтить. Проверяется ПОСЛЕ пообъектного отрицания, чтобы в красном выводе
	// были ОБА факта остатка S3.1: и «гейт на iam_user», и «типа членства нет».
	assert.NotNilf(t, model.Type(membershipObjectType),
		"IAM-ID-1-31: тип %q в модели прав ОТСУТСТВУЕТ — предмета защиты нет. "+
			"Пока его нет, объектом гейта чтения личности остаётся глобальная `iam_user`, и админ "+
			"соседнего аккаунта дотягивается до личности (остаток S3.1, пункт 1: 32 типа → станет 33).",
		membershipObjectType)

	t.Logf("перепись: записей каталога прочитано %d · RPC чтения личности сверено %d · "+
		"тип %q объявлен моделью: %v",
		len(catalog), checked, membershipObjectType, model.Type(membershipObjectType) != nil)
}

// TestUserReadGate_IAMID131_AdminOfOwnAccountReachesIdentity — ПОЛОЖИТЕЛЬНЫЙ
// БЛИЗНЕЦ сценария IAM-ID-1-31: администратор СВОЕГО аккаунта A законно
// дотягивается до личности в A. Зелён сегодня (гейт `iam_user.v_get`/`v_list`
// несёт `admin from account`) и остаётся зелёным после фикса (гейт
// `iam_membership.v_get`/`v_list` несёт тот же `admin from account`, но уже
// одно-аккаунтный).
//
// Отличается от красной пробы РОВНО ОДНИМ фактом: там — «объект гейта соседа
// НЕ достижим», здесь — «объект гейта СВОЕГО аккаунта достижим». Оба утверждения
// про один и тот же источник `admin from account`; красное меняет объект, зелёное
// оставляет источник.
func TestUserReadGate_IAMID131_AdminOfOwnAccountReachesIdentity(t *testing.T) {
	model := canonicalModel(t)
	catalog := catalogByFQN(t)

	require.NotEmpty(t, catalog, "каталог прав разобран в ноль записей — предпосылка гейта сломана")

	checked := 0
	for _, fqn := range userReadGateRPCs {
		e, ok := catalog[fqn]
		require.Truef(t, ok, "каталог не знает %s — перечень «чтение личности» пережил свой предмет", fqn)

		plan, err := model.Compile(e.objectType, e.relation)
		require.NoErrorf(t, err, "компиляция %s.%s (%s)", e.objectType, e.relation, fqn)
		got := sourcesOf(t, plan)

		require.Containsf(t, got, accountAdminSource,
			"IAM-ID-1-31 близнец: администратор СВОЕГО аккаунта A обязан дотягиваться до личности — "+
				"у гейта чтения %s (%s.%s) должен быть источник уровня аккаунта %+v (`admin from account`). "+
				"Его отсутствие означало бы, что читать своих людей аккаунт больше не вправе.\nИсточники: %v",
			fqn, e.objectType, e.relation, accountAdminSource, sortedKeys(got))
		checked++
	}

	t.Logf("перепись: записей каталога прочитано %d · RPC чтения личности сверено %d · "+
		"источник уровня аккаунта %+v присутствует у каждого", len(catalog), checked, accountAdminSource)
}
