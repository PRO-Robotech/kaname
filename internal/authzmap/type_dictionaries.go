//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗА ДВА СЛОВАРЯ
//
// Один и тот же тип ресурса назван в iam ДВУМЯ разными именами, и оба законны:
//
//	словарь МОДЕЛИ ПРАВ    vpc_network · account · project · cluster
//	словарь КАТАЛОГА       vpc.network · iam.account · iam.project · (нет)
//
// Словарь модели — вокабуляр `fga_model.fga`: им приходит вопрос о доступе, им
// говорит компилятор плана, и ТОЛЬКО он умеет назвать `cluster` — вершину
// иерархии, которой в каталоге ресурсов нет вовсе, потому что кластер не
// ресурс.
//
// Словарь каталога — вокабуляр разрешений (`<модуль>.<ресурс>`): им адресуют
// объекты правила ролей, им же названы типы в проекциях, выведенных из ролей.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЭТИМИ ФУНКЦИЯМИ ДЕРЖИТСЯ
//
// У КАЖДОЙ колонки, несущей имя типа, ровно один словарь, и он объявлен:
//
//	словарь модели    relation_fact.object_type · access_bindings.resource_type ·
//	                  resource_parent_edge.object_type · resource_parent_edge.parent_type
//	словарь каталога  resource_mirror.object_type · role_verb.object_type ·
//	                  role_rule_selectors.object_types
//
// Соединение колонок РАЗНЫХ словарей не совпадает НИКОГДА и молча: исход
// выглядит как «права нет», а не как ошибка. Поэтому перевод делается один раз,
// на границе — там, где значение уезжает в чужой словарь, — и делается ОТСЮДА.
// Второго переходника в дереве не заводится: два места, знающих соответствие,
// разойдутся, и разойдутся тихо.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОБЕ ТОТАЛЬНЫ, А НЕ ОТДАЮТ ok
//
// Пара `(значение, известен ли)` у вызывающего немедленно сворачивается в
// «неизвестный — как есть»: тип вне каталога законен (зеркало держит непрозрачный
// тип чужого сервиса как есть), и превращать его в пустую строку нельзя —
// пустая подстановка совпала бы с пустым значением колонки и превратила бы «типа
// не знаем» в «совпало». Свернуть это здесь значит не дать вызывающему свернуть
// иначе. Кому нужна сама принадлежность каталогу — зовёт `DottedType` /
// `FGAObjectType` и читает `ok`.
//
// ОБЕ ИДЕМПОТЕНТНЫ, и это свойство словарей, а не удача: имя каталога содержит
// точку всегда, имя модели — никогда (в имени типа модель допускает только
// буквы, цифры, `_` и `-`). Пересечения у словарей нет, поэтому повторный
// перевод уже переведённого имени возвращает его же. На этом свойстве стоят
// проверки схемы `*_type NOT LIKE '%.%'` у колонок словаря модели: регрессия
// писателя отвергается строкой, а не перестаёт совпадать молча.
package authzmap

// CatalogTypeName — имя типа в словаре КАТАЛОГА.
//
// Тип вне каталога модели возвращается КАК ЕСТЬ (см. «почему тотальна» выше).
//
// # ЧИТАТЕЛЮ КОЛОНКИ СЛОВАРЯ КАТАЛОГА ЭТОГО НЕ ХВАТАЕТ (kacho#1986)
//
// Зеркальная граница к той, что названа у `ModelTypeName` ниже, и исход у неё
// ТИШЕ. Таблица под этой функцией ПОРОЖДЕНА СБОРКОЙ (`tables_gen.go` из
// манифестов дерева), а функция ТОТАЛЬНА. Значит тип, заведённый применением
// манифеста в РАБОТАЮЩЕМ процессе, она вернёт именем МОДЕЛИ — и это уедет в
// сравнение с колонкой, названной словарём каталога. Ни одна строка не
// совпадёт, отказа не будет: перечисление отдаст пусто, селектор меток объект
// не покроет, а клиент прочтёт это как «прав нет».
//
// Соединяешь колонку словаря каталога — спрашивай имя у ЖИВОЙ СТРОКИ каталога
// (`catalog_resource.dotted` по `object_type`; образец —
// `relverdict/catalogtype.go`, где перевод стоит выражением в самом запросе и
// потому не стоит ни лишнего круга к базе, ни окна между чтениями). Здесь
// остаются вызывающие, которым живая строка недоступна by construction и чей
// вход — только посеянные типы.
func CatalogTypeName(typeName string) string {
	if dotted, known := DottedType(typeName); known {
		return dotted
	}
	return typeName
}

// ModelTypeName — имя типа в словаре МОДЕЛИ ПРАВ.
//
// Тип вне каталога возвращается КАК ЕСТЬ — в том числе `cluster`, которого в
// каталоге нет и быть не должно.
//
// # ПИСАТЕЛЮ КОЛОНКИ СЛОВАРЯ МОДЕЛИ ЭТОГО НЕ ХВАТАЕТ (kacho#1982)
//
// Таблица под этой функцией ПОРОЖДЕНА СБОРКОЙ (`tables_gen.go` из манифестов
// дерева), а функция ТОТАЛЬНА. Значит тип, заведённый применением манифеста в
// РАБОТАЮЩЕМ процессе, она вернёт точечным именем каталога — и это уедет в
// колонку, которая требует имени модели. Наблюдалось у зеркала: вставка ребра
// отвергалась проверкой схемы, то есть регистрация не проходила ВОВСЕ.
//
// Пишешь в колонку словаря модели — спрашивай имя у ЖИВОЙ СТРОКИ каталога
// (`catalog_resource.object_type`; образец — `resource_mirror.modelTypeName`,
// который читает её в той же транзакции). Здесь остаются вызывающие, которым
// живая строка недоступна by construction и чей вход — только посеянные типы.
//
// Свойство, различающее словари, объявлено выше и на нём же стоит сужение у
// писателей: имя каталога содержит точку ВСЕГДА, имя модели — НИКОГДА.
func ModelTypeName(typeName string) string {
	if fga, known := FGAObjectType(typeName); known {
		return fga
	}
	return typeName
}
