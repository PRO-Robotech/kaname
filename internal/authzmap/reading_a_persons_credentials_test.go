// reading_a_persons_credentials_test.go — гейт на КЛАСС: ВИДЕТЬ ПЕРЕЧЕНЬ
// УДОСТОВЕРЕНИЙ ЧЕЛОВЕКА не вправе тот, кто распоряжается его аккаунтом.
//
// # Предмет
//
// Третья сторона одной директивы владельца (2026-08-23): «тот кто пригласил
// может только удалить/добавить права». Две первые уже закрыты соседями —
// ДЕЙСТВОВАТЬ ОТ ИМЕНИ человека (#1086, `acting_as_a_person_*`) и
// РАСПОРЯЖАТЬСЯ ЕГО СТРОКОЙ (#1102, `governing_the_identity_*`). Здесь —
// ЧИТАТЬ СВЕДЕНИЯ О ЕГО ЛИЧНОСТИ (#1133).
//
// Перечень персональных токенов — не право на аккаунт, а сведения о человеке:
// сколько удостоверений у него живо, когда выпущены, когда истекают, чем
// названы. Раскрытие этих сведений — тоже действие за человека, поэтому
// отношение чтения обязано следовать за отношением выпуска, а не за общим
// перечислением личностей.
//
// Личность в этом дереве ГЛОБАЛЬНА: одна строка `iam_user` на все аккаунты
// человека, а принадлежность аккаунтам выражают отдельные строки членства
// (миграции 20260822234500 / 20260823050000). Звено «личность → аккаунт»
// вердикт берёт ИЗ ЧЛЕНСТВА, которых у человека может быть несколько, — значит
// право уровня аккаунта, взятое в ОДНОМ из них, читало бы сведения о человеке
// целиком, включая аккаунты, к которым его держатель отношения не имеет.
//
// # Что здесь утверждается — и почему через КАТАЛОГ, а не через литерал
//
// Проба не знает наперёд, каким отношением гейтится чтение: она СПРАШИВАЕТ его у
// каталога прав (тот порождается из proto и является единственным источником
// per-RPC решения края), компилирует отношение из КАНОНИЧЕСКОЙ модели и смотрит
// на источники разрешения. Литерал имени отношения превратил бы гейт в проверку
// написания: он остался бы зелёным, если бы завтра чтение вернули на широкое
// отношение под другим именем.
//
// # Обе стороны, потому что односторонняя проба зеленеет на пустом
//
//   - ОТРИЦАНИЕ: у отношения чтения НЕТ источников уровня аккаунта — ни
//     пообъектной выдачи, ни делегированного администратора аккаунта, ни его
//     владельца;
//   - ОТРИЦАНИЕ 2: у отношения НЕТ прямого списка субъектов, то есть его нельзя
//     ВРУЧИТЬ ни кортежем, ни выдачей, ни материализацией. Без этого утверждения
//     запрет выше обходится одной строкой журнала;
//   - ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 1: сам человек источник ИМЕЕТ — иначе запрет
//     зеленел бы на отношении, которого не держит никто, и владелец перестал бы
//     видеть свои же удостоверения. Отзыв, недостижимый владельцу, — не отзыв:
//     идентификатор выданного существует ровно один раз, в ответе на выпуск;
//   - ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 2: надзор облака источник ИМЕЕТ — расследование без
//     него невозможно, и его потеря была бы не сужением, а обрывом;
//   - ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 3: у ЧТЕНИЯ ЗАПИСИ (`UserService/Get`) источники
//     уровня аккаунта обязаны ОСТАТЬСЯ. Видеть своих людей — законное дело
//     аккаунта, и без этого контроля «источников нет» неотличимо от «разбор
//     ничего не нашёл».
//
// # Почему надзор облака здесь НАЗВАН, хотя у `token_issuer` не назван
//
// Формы «`subject`» и «`subject or super_admin from account`» дают ОДИН И ТОТ ЖЕ
// круг держателей: плоское короткое замыкание службы
// (`authzguard.SubjectIsClusterAdminPlainE`, зовётся из `AuthorizeService`ПОСЛЕ
// ответа формы) добавляет администратора облака к КАЖДОМУ отношению модели
// безусловно. Выбор между ними — о том, где свойство ЧИТАЕТСЯ, а не о том, кому
// что доступно.
//
// Здесь выбрана названная форма — та же, что у соседей по строке личности
// (`record_writer`, `identity_suspender`, #1102), — потому что предикат снятия
// #1133 требует, чтобы круг держателей был виден КОМПИЛЯТОРУ МОДЕЛИ целиком, в
// одном месте. При форме без имени утверждение «читают ровно двое» пришлось бы
// собирать из двух механизмов, и первый же расход между ними прошёл бы молча.
//
// Расхождение с `token_issuer` названо, а не умолчано: он остаётся формой без
// имени, и это не противоречие, а разная цена читаемости у права, которое НИКОГДА
// не сужалось (выпуск), и у права, которое сужено ЭТИМ изменением (чтение). Что
// надзор облака доходит НА САМОМ ДЕЛЕ, утверждается вердиктом по закоммиченным
// строкам — `services/iam/internal/service/acting_as_a_person_integration_test.go`;
// здесь утверждается только то, что модель его называет.
