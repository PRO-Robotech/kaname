// credentialReadRPCs — публичные RPC, чей предмет есть ЧТЕНИЕ СВЕДЕНИЙ ОБ
// УДОСТОВЕРЕНИЯХ человека.
//
// Перечислены по FQN, потому что «сведения об удостоверениях» — свойство СМЫСЛА
// RPC, а не его написания. Перечень мал и закрыт; каждая запись обязана
// находиться в каталоге, иначе перечень пережил свой предмет.
var credentialReadRPCs = []string{
	"kaname.cloud.iam.v1.UserTokenService/List",
}

// personalCredentialSources — круг держателей, в который отношение чтения
// обязано раскрываться ЦЕЛИКОМ: сам человек и надзор облака. Ровно то, что
// требует предикат снятия #1133, и утверждается оно РАВЕНСТВОМ множеств, а не
// вхождением: вхождение зеленеет на любом добавленном источнике, то есть на том
// самом дефекте, который здесь закрывается.
func personalCredentialSources() []planSource {
	return []planSource{
		{Kind: authzplan.AtomFact, ParentType: "", Relation: "subject"},
		cloudSource,
	}
}

// credentialVerdict — то, что предикат ГОВОРИТ об одном отношении. Отдельным
// типом, потому что ровно этот предикат прогоняется дважды: гейтом ниже — по
// каноническому дереву, и опытом инъекции — по дереву с возвращённым дефектом.
// Копия предиката в опыте доказывала бы, что работает КОПИЯ.
type credentialVerdict struct {
	Sources      map[planSource]string // все источники плана
	AccountLevel []planSource          // найденные источники уровня аккаунта
	Grantable    bool                  // отношение можно ВРУЧИТЬ прямым списком
	HasSelf      bool                  // сам человек — источник
	HasCloud     bool                  // надзор облака — источник
}

// inspectCredentialRelation — единственный предикат этого класса.
func inspectCredentialRelation(t *testing.T, model *authzplan.Model, objectType, relation string) credentialVerdict {
	t.Helper()
	plan, err := model.Compile(objectType, relation)
	require.NoErrorf(t, err, "компиляция %s.%s", objectType, relation)
	require.NotEmptyf(t, plan.Atoms, "план %s.%s пуст — ни одного источника разрешения",
		objectType, relation)
	got := sourcesOf(t, plan)

	v := credentialVerdict{Sources: got}
	for src := range got {
		// Источник уровня аккаунта — ЛЮБАЯ выдача и ЛЮБОЙ факт на аккаунте, а не
		// три поимённо названные пары. Перечень по именам здесь промахнулся бы
		// by construction: пообъектная выдача приезжает атомом, названным ГЛАГОЛОМ
		// того отношения, через которое она выведена (`v_list`), а не именем
		// спрошенного. Признак — вид источника и предок, на котором он лежит.
		if src.Kind == authzplan.AtomBinding || (src.Kind == authzplan.AtomFact && src.ParentType == "account") {
			v.AccountLevel = append(v.AccountLevel, src)
		}
		// Выдаваемость — то же самое плюс прямой список субъектов НА САМОМ
		// объекте, кроме факта личности `subject`: он и есть «я — это я», он
		// пишется заведением человека и вручить его другому нельзя.
		if src.Kind == authzplan.AtomBinding ||
			(src.Kind == authzplan.AtomFact && src.ParentType == "" && src.Relation != "subject") {
			v.Grantable = true
		}
	}
	sort.Slice(v.AccountLevel, func(i, j int) bool {
		if v.AccountLevel[i].ParentType != v.AccountLevel[j].ParentType {
			return v.AccountLevel[i].ParentType < v.AccountLevel[j].ParentType
		}
		return v.AccountLevel[i].Relation < v.AccountLevel[j].Relation
	})
	_, v.HasSelf = got[planSource{Kind: authzplan.AtomFact, ParentType: "", Relation: "subject"}]
	_, v.HasCloud = got[cloudSource]
	return v
}

// TestReadingAPersonsCredentialsHasNoAccountLevelSource — гейт класса.
func TestReadingAPersonsCredentialsHasNoAccountLevelSource(t *testing.T) {
	model := canonicalModel(t)
	catalog := catalogByFQN(t)

	require.NotEmpty(t, catalog, "каталог прав разобран в ноль записей — предпосылка гейта сломана")

	// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 3 — сперва, чтобы отрицание ниже не могло зеленеть
	// на сломанном разборе: у ЧТЕНИЯ ЗАПИСИ источники уровня аккаунта обязаны быть.
	readEntry, ok := catalog[recordReadRPC]
	require.Truef(t, ok, "каталог не знает %s — контроль отрицания отсутствует", recordReadRPC)
	readVerdict := inspectCredentialRelation(t, model, readEntry.objectType, readEntry.relation)
	require.ElementsMatchf(t, accountLevelSources(readEntry.relation), readVerdict.AccountLevel,
		"КОНТРОЛЬ: у отношения ЧТЕНИЯ ЗАПИСИ %s.%s обязаны быть ВСЕ источники уровня аккаунта. "+
			"Их отсутствие означает, что разбор модели ничего не нашёл, и тогда отрицание ниже "+
			"вакуумно", readEntry.objectType, readEntry.relation)

	checked := 0
	for _, fqn := range credentialReadRPCs {
		e, ok := catalog[fqn]
		require.Truef(t, ok, "каталог не знает %s — перечень «чтение сведений об удостоверениях» "+
			"пережил свой предмет", fqn)
		require.Equalf(t, "iam_user", e.objectType,
			"%s гейтится не на объекте личности (%s) — предмет пробы сменился", fqn, e.objectType)

		v := inspectCredentialRelation(t, model, e.objectType, e.relation)

		// ОТРИЦАНИЕ.
		require.Emptyf(t, v.AccountLevel,
			"%s гейтится отношением %s.%s, у которого есть источники уровня аккаунта: %v.\n"+
				"Перечень персональных удостоверений — не право на аккаунт, а СВЕДЕНИЯ О "+
				"ЧЕЛОВЕКЕ: сколько удостоверений живо, когда выпущены, когда истекают.\n"+
				"Личность здесь ГЛОБАЛЬНА (одна строка iam_user на все аккаунты человека, звено "+
				"«личность → аккаунт» вердикт берёт из членства), поэтому право уровня аккаунта "+
				"раскрывает сведения о человеке целиком — включая аккаунты, к которым его "+
				"держатель отношения не имеет.\n"+
				"Отношение чтения обязано следовать за отношением ВЫПУСКА, а не за общим "+
				"перечислением личностей: пригласивший вправе выдать и снять права, но не "+
				"действовать за приглашённого.",
			fqn, e.objectType, e.relation, v.AccountLevel)

		// ОТРИЦАНИЕ 2 — отношение НЕВЫДАВАЕМО.
		//
		// Предмет другой, чем у отрицания выше: там закрыты пути, по которым право
		// ПРИЕЗЖАЕТ держателю выдачи внутри аккаунта, здесь — сама возможность его
		// ВРУЧИТЬ. Прямой список субъектов означает, что отношение можно выдать
		// кортежем, и тогда запрет выше обходится одной строкой журнала: атом
		// собственного прямого списка в перечень банимых не входит by construction.
		require.Falsef(t, v.Grantable,
			"%s гейтится отношением %s.%s, у которого ЕСТЬ прямой список субъектов.\n"+
				"Значит право видеть чужие удостоверения можно ВРУЧИТЬ — кортежем, выдачей "+
				"или материализацией, — и тогда разделение прав выше обходится одной записью.\n"+
				"Отношение обязано быть вычисляемым: держателей у него ровно двое, и оба "+
				"структурны.", fqn, e.objectType, e.relation)

		// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 1 — сам человек.
		require.Truef(t, v.HasSelf,
			"%s гейтится отношением %s.%s, у которого САМ ЧЕЛОВЕК не источник. Тогда запрет выше "+
				"держится не разделением прав, а тем, что отношения не держит никто: владелец "+
				"перестаёт видеть свои же удостоверения, а идентификатор выданного существует "+
				"ровно один раз — в ответе на выпуск. Отзыв, недостижимый владельцу, — не отзыв.\n"+
				"Источники плана: %v", fqn, e.objectType, e.relation, sortedKeys(v.Sources))

		// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 2 — надзор облака.
		require.Truef(t, v.HasCloud,
			"%s гейтится отношением %s.%s, у которого НЕТ надзора облака (%+v). Сужение обязано "+
				"оставить расследование возможным: без него это не сужение, а обрыв.\n"+
				"Источники плана: %v", fqn, e.objectType, e.relation, cloudSource, sortedKeys(v.Sources))

		// РАВЕНСТВО КРУГА, а не вхождение.
		require.ElementsMatchf(t, personalCredentialSources(), keysOf(v.Sources),
			"%s гейтится отношением %s.%s, круг держателей которого НЕ РАВЕН объявленному: "+
				"ожидались сам человек и надзор облака, в плане %v.\n"+
				"Утверждается равенство, а не вхождение: вхождение зеленеет на любом ДОБАВЛЕННОМ "+
				"источнике — то есть на том самом дефекте, который здесь закрывается.",
			fqn, e.objectType, e.relation, sortedKeys(v.Sources))
		checked++
	}

	t.Logf("перепись: записей каталога прочитано %d · RPC «чтение сведений об удостоверениях» "+
		"сверено %d · контроль чтения записи %s.%s (источников %d, из них уровня аккаунта %d)",
		len(catalog), checked, readEntry.objectType, readEntry.relation,
		len(readVerdict.Sources), len(readVerdict.AccountLevel))
}

// keysOf — источники плана без их происхождения, для сравнения множеств.
func keysOf(m map[planSource]string) []planSource {
	out := make([]planSource, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].ParentType != out[j].ParentType {
			return out[i].ParentType < out[j].ParentType
		}
		return out[i].Relation < out[j].Relation
	})
	return out
}

// ── смежный предмет: ключи служебной учётки ──────────────────────────────────
//
// #1133 требует не унаследовать вывод о человеке молча, а СДЕЛАТЬ его для
// машины. Он сделан и записан здесь проверяемым свойством, а не прозой.
//
// ВЫВОД: сужать НЕ НАДО, и основание не во вкусе, а в трёх измеримых отличиях.
//
//  1. У машины НЕТ «самой себя». Отношения `subject` тип `iam_service_account`
//     не объявляет — и объявить не может: строку личности человек занимает сам,
//     а служебная учётка предъявителя своей воли не имеет. Значит сужение до
//     «сам себя плюс облако» оставило бы ключи БЕЗ ТЕНАНТСКОГО ДЕРЖАТЕЛЯ вовсе:
//     не сужение, а обрыв.
//  2. Машина — ресурс АККАУНТА, а не глобальная личность. Её ключ действует там,
//     где действует она, и границы своего аккаунта не покидает; довод «право,
//     взятое внутри одного аккаунта, вышло бы за его границу» здесь не имеет
//     предмета.
//  3. Класса «чтение шире выпуска» здесь НЕТ. Именно он был предметом у человека:
//     выпуск и отзыв держал один источник, чтение — шесть. У машины оба
//     раскрываются в ОДИН И ТОТ ЖЕ круг, и это утверждается ниже равенством
//     множеств. Сужать чтение ниже выпуска значило бы сделать отзыв недостижимым
//     тому, кто вправе выпускать, — ровно то, от чего `token_reader` у человека и
//     существует.
//
// ЧТО ЭТА ПРОБА ДЕРЖИТ ВПЕРЁД. Она не объявляет круг машины правильным — она
// запрещает ему РАЗЪЕХАТЬСЯ. Появится у ключей чтение шире выпуска — покраснеет
// здесь, а не у арендатора.

// saKeyRPCs — RPC ключей служебной учётки: чтение против выпуска и отзыва.
// По FQN, потому что предмет — смысл RPC, а отношения спрашиваются у каталога.
var saKeyRPCs = struct{ read, mutate []string }{
	read:   []string{"kaname.cloud.iam.v1.SAKeyService/List"},
	mutate: []string{"kaname.cloud.iam.v1.SAKeyService/Issue", "kaname.cloud.iam.v1.SAKeyService/Revoke"},
}

// TestServiceAccountKeyReadingIsNotWiderThanIssuing — смежный предмет #1133.
func TestServiceAccountKeyReadingIsNotWiderThanIssuing(t *testing.T) {
	model := canonicalModel(t)
	catalog := catalogByFQN(t)
	require.NotEmpty(t, catalog, "каталог прав разобран в ноль записей — предпосылка гейта сломана")

	// (1) У машины нет «самой себя» — и это ПРИЧИНА, по которой её нельзя сузить
	// той же формой, что человека. Утверждается, а не подразумевается: появись
	// `subject` у машины, вывод выше обязан быть пересмотрен, а не унаследован.
	sa := model.Type("iam_service_account")
	require.NotNil(t, sa, "модель не объявляет `iam_service_account` — предмет пробы исчез")
	require.Nilf(t, sa.Rel("subject"),
		"у `iam_service_account` появилось отношение `subject`. Вывод #1133 «сужать не надо» "+
			"стоял на том, что тенантского держателя-себя у машины НЕТ, и потому сужение до "+
			"«сам себя плюс облако» оставило бы ключи без держателя вовсе. Предпосылка "+
			"изменилась — пересмотрите вывод, а не эту пробу.")

	sourcesFor := func(fqns []string) (map[planSource]string, string) {
		var merged map[planSource]string
		var named string
		for _, fqn := range fqns {
			e, ok := catalog[fqn]
			require.Truef(t, ok, "каталог не знает %s — перечень пережил свой предмет", fqn)
			require.Equalf(t, "iam_service_account", e.objectType,
				"%s гейтится не на объекте машины (%s) — предмет пробы сменился", fqn, e.objectType)
			got := holderCircle(t, model, e.objectType, e.relation)
			if merged == nil {
				merged, named = got, e.objectType+"."+e.relation
				continue
			}
			// Все мутирующие RPC обязаны гейтиться ОДНИМ кругом: разойдись они, и
			// «чтение не шире выпуска» перестало бы быть одним утверждением.
			require.ElementsMatchf(t, keysOf(merged), keysOf(got),
				"%s и %s гейтятся разными кругами держателей — сравнивать чтение стало не с чем",
				named, e.objectType+"."+e.relation)
		}
		return merged, named
	}

	readSources, readName := sourcesFor(saKeyRPCs.read)
	mutateSources, mutateName := sourcesFor(saKeyRPCs.mutate)

	require.NotEmpty(t, readSources, "план чтения ключей пуст — ни одного источника разрешения")
	require.NotEmpty(t, mutateSources, "план выпуска ключей пуст — ни одного источника разрешения")

	// (3) Круги РАВНЫ. Не «чтение ⊆ выпуска»: вложение зеленело бы и на сужении
	// чтения ниже выпуска, а это и есть недостижимый отзыв.
	require.ElementsMatchf(t, keysOf(mutateSources), keysOf(readSources),
		"чтение ключей (%s) и их выпуск с отзывом (%s) раскрываются в РАЗНЫЕ круги держателей.\n"+
			"чтение:  %v\nвыпуск:  %v\n"+
			"Шире у чтения — это класс #1133 («видеть чужие удостоверения проще, чем ими "+
			"распоряжаться»), и его надо закрывать. Шире у выпуска — отзыв стал недостижим "+
			"тому, кто вправе выпускать, а отзыв, недостижимый держателю, — не отзыв.",
		readName, mutateName, sortedKeys(readSources), sortedKeys(mutateSources))

	t.Logf("смежный предмет: `subject` у машины объявлений 0 · чтение %s и выпуск %s "+
		"раскрываются в один круг из %d источников: %v",
		readName, mutateName, len(readSources), sortedKeys(readSources))
}

// ownVerbPlaceholder — имя, под которым сравниваются источники НА САМОМ ОБЪЕКТЕ.
//
// Пообъектная выдача и прямой список субъектов приезжают в план атомом, названным
// ИМЕНЕМ СПРОШЕННОГО ГЛАГОЛА (`v_list` у чтения, `v_update` у выпуска). Сравнивать
// круги держателей по этим именам нельзя: они различаются ВСЕГДА и по построению,
// то есть равенство было бы недостижимо, а проба — вечно красной независимо от
// свойства. Предмет сравнения — ВИД источника и предок, на котором он лежит, а не
// имя глагола, которым его спросили.
const ownVerbPlaceholder = "<сам глагол>"

// normalizeOwnVerb приводит источники на самом объекте к общему имени.
func normalizeOwnVerb(src map[planSource]string, relation string) map[planSource]string {
	out := make(map[planSource]string, len(src))
	for k, origin := range src {
		if k.ParentType == "" && k.Relation == relation {
			k.Relation = ownVerbPlaceholder
		}
		out[k] = origin
	}
	return out
}

// holderCircle — круг держателей отношения, приведённый к сравнимому виду.
// Единственная точка сравнения кругов: копия здесь разошлась бы с опытом инъекции
// молча, и «круги равны» стало бы утверждением о копии.
func holderCircle(t *testing.T, model *authzplan.Model, objectType, relation string) map[planSource]string {
	t.Helper()
	plan, err := model.Compile(objectType, relation)
	require.NoErrorf(t, err, "компиляция %s.%s", objectType, relation)
	require.NotEmptyf(t, plan.Atoms, "план %s.%s пуст — ни одного источника разрешения",
		objectType, relation)
	return normalizeOwnVerb(sourcesOf(t, plan), relation)
}
