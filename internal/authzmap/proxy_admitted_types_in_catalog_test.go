// proxy_admitted_types_in_catalog_test.go — ПРАВИЛО ПРИЁМА И КАТАЛОГ СХОДЯТСЯ.
//
// # ЗАЧЕМ ЭТОТ ГЕЙТ ЗАВЕДЁН
//
// Регистрация ресурса стала спрашивать каталог: тип объекта обязан иметь ЖИВУЮ
// строку `kaname.catalog_resource`, иначе запись отвергается. Сверка живёт в
// базе владельца прав — потребителям она недоступна by construction, — а решение
// «принимать ли кортеж вообще» они читают из общего правила
// `pkg/authz/proxytuple`. Значит у одного предмета появились ДВЕ стороны, и
// разойтись им нельзя.
//
// Расхождение в опасную сторону стоило бы дорого и было бы тихим: правило приёма
// пропускает тип, каталог его не знает — отказ приходит на КАЖДОЙ доставке,
// очередь потребителя считает такой отказ терминальным и травит строку. Это
// ровно тот класс, из-за которого в дереве однажды не доставилась НИ ОДНА строка
// очереди регистраций (`data-integrity.md` §«Межсервисное намерение — контракт
// ПРИНИМАЮЩЕЙ стороны»).
//
// # ЧТО ИМЕННО УТВЕРЖДАЕТСЯ
//
// Не «наш посев совпал с нашим литералом» — это уже держат гейты дрейфа модели.
// Здесь утверждается ПЕРЕСЕЧЕНИЕ двух независимых объявлений: всё, что правило
// приёма пропускает как объект регистрации, каталог обязан знать грантуемым
// типом. Обратная сторона (каталог знает больше, чем правило приёма пропускает)
// законна и не проверяется: у типов iam есть свои писатели помимо прокси.
package authzmap_test

import (
	"sort"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/PRO-Robotech/kacho/pkg/authz/proxytuple"
	"github.com/PRO-Robotech/kaname/internal/authzmap"
)

// TestProxyAdmittedObjectTypesAreInTheCatalog — тип, допущенный правилом приёма,
// обязан резолвиться в точечное имя каталога.
//
// Домен вызывающего выводится из САМОГО типа (часть до первого `_`): именно так
// связывает их правило приёма, и другой формы у этой связи в дереве нет. Помимо
// него спрашивается посадка с НЕИЗВЕСТНЫМ доменом — там связывание по домену
// отключено, и множество допущенного шире, поэтому проверять надо обе.
func TestProxyAdmittedObjectTypesAreInTheCatalog(t *testing.T) {
	model := parseModel(t)

	var admitted, findings []string
	for typ := range model.types {
		for _, caller := range []string{callerDomainOf(typ), ""} {
			// Отношение и субъект берутся из объявленного набора приёма, а не
			// придумываются: гейт спрашивает про ТИП, и всё прочее в тройке обязано
			// быть заведомо законным, иначе отказ пришёл бы от соседней оговорки и
			// «допущенных типов» насчиталось бы меньше, чем есть.
			if err := proxytuple.ValidateTuple(caller, "user:usr1",
				string(proxytuple.RelationOwner), typ+":x"); err != nil {
				continue
			}
			admitted = append(admitted, typ)
			if _, ok := authzmap.DottedType(typ); !ok {
				findings = append(findings, typ)
			}
			break
		}
	}
	sort.Strings(admitted)
	sort.Strings(findings)

	t.Logf("типов в модели: %d; допущено правилом приёма: %d; резолвится каталогом: %d",
		len(model.types), len(admitted), len(admitted)-len(findings))

	// Перепись — отдельное утверждение: без него «ноль находок» было бы
	// неотличимо от «правило приёма перестало пропускать что бы то ни было», и
	// гейт зеленел бы на полностью сломанном правиле.
	require.NotEmpty(t, model.types, "модель разобрана в ноль типов — гейту нечего читать")
	require.NotEmptyf(t, admitted,
		"правило приёма не допустило НИ ОДНОГО типа модели — либо разбор модели разошёлся "+
			"с её синтаксисом, либо правило отвергает всё; «ноль находок» здесь означало бы "+
			"непрочитанное, а не порядок")

	require.Emptyf(t, findings,
		"правило приёма допускает тип, которого каталог ресурсов не знает: %v\n\n"+
			"Регистрация таким типом будет отвергнута принимающей стороной на КАЖДОЙ "+
			"доставке, и очередь потребителя эту строку отравит. Исходов два: завести тип "+
			"грантуемым (authzmap.objectTypes + строка каталога), либо перестать его "+
			"допускать (proxytuple.forbiddenObjectTypes).", findings)
}

// TestPublicReadObjectTypesAreInTheCatalog — вторая, НЕиерархическая полоса
// приёма закрыта тем же утверждением.
//
// Публикация («любой читает этот ресурс») строки зеркала не пишет, поэтому
// оператор каталога её сегодня не касается. Проверяется она здесь именно
// поэтому: закрытый перечень публикуемых типов — второй список об одном
// предмете, и без этой пробы он мог бы уехать от каталога молча, а вместе с ним
// уехала бы и полоса, на которой оператор появится следующим.
func TestPublicReadObjectTypesAreInTheCatalog(t *testing.T) {
	types := proxytuple.PublicReadObjectTypes()
	require.NotEmpty(t, types,
		"перечень публикуемых типов пуст — утверждение ниже стало бы вакуумным")

	var findings []string
	for _, typ := range types {
		if _, ok := authzmap.DottedType(typ); !ok {
			findings = append(findings, typ)
		}
	}
	t.Logf("публикуемых типов: %d; резолвится каталогом: %d", len(types), len(types)-len(findings))
	require.Emptyf(t, findings,
		"тип объявлен публикуемым, но каталог его не знает: %v", findings)
}

// callerDomainOf — короткое имя вызывающего, для которого правило приёма считает
// тип «своим»: часть имени до первого `_`.
//
// У типа без `_` (вершины иерархии и субъектные типы) домена нет — возвращается
// пустая строка, и такой тип проверяется только посадкой с неизвестным доменом.
func callerDomainOf(objectType string) string {
	if i := strings.IndexByte(objectType, '_'); i > 0 {
		return objectType[:i]
	}
	return ""
}
