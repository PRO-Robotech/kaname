package authzmap_test

// catalog_drift_test.go — типы, которые компилятор видит в модели, и типы,
// которые сервис объявляет в своём каталоге, не расходятся.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Два места знают про типы объектов модели прав:
//
//   - каноническая модель (`fga_model.fga`) — то, ЧТО умеет решаться;
//   - каталог `services/iam/internal/authzmap` — то, что сервис умеет НАЗВАТЬ,
//     переводя точечное имя ресурса в тип объекта и обратно.
//
// Разойтись они могут молча и в обе стороны. Тип, появившийся в модели и не
// попавший в каталог, не резолвится краем — вопрос о нём не задаётся вовсе, и
// проверка выглядит пройденной. Тип, оставшийся в каталоге после удаления из
// модели, — обещание полосы, которой нет.
//
// Ни рендер, ни компиляция такого не ловят: каждое место по отдельности
// непротиворечиво.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ГЕЙТ ЖИВЁТ ЗДЕСЬ, А НЕ У КАТАЛОГА
//
// Здесь есть разбор модели. У каталога его нет и не должно быть: он — таблица
// имён, а не читатель DSL. Гейт ставится там, где обе стороны доступны без
// заведения третьей.
//
// Направление сверки ОДНО и названо: каждый тип каталога обязан существовать в
// модели. Обратное направление (тип модели без записи в каталоге) намеренно НЕ
// требуется: модель несёт служебные типы, которые краю не адресуются
// (`cluster`, `iam_fgaproxy` и подобные), и требование «каждый тип модели в
// каталоге» заставило бы вносить их туда ради тишины гейта — то есть заводить
// ложные имена.

import (
	"testing"

	"github.com/PRO-Robotech/kacho-iam/internal/authzmap"
	"github.com/PRO-Robotech/kacho-iam/internal/authzplan"
)

func TestCatalogTypesExistInTheCanonicalModel(t *testing.T) {
	path, dsl, err := authzplan.ResolveCanonicalModel()
	if err != nil {
		t.Fatalf("каноническая модель не найдена (%v) — предпосылка гейта исчезла, "+
			"а не дерево стало чистым", err)
	}
	model, err := authzplan.ParseModel(string(dsl))
	if err != nil {
		t.Fatalf("разбор %s: %v", path, err)
	}

	inModel := map[string]bool{}
	for _, typ := range model.Types {
		inModel[typ.Name] = true
	}

	catalog := authzmap.Catalog()
	var missing []string
	for _, e := range catalog {
		fgaType, ok := authzmap.ObjectType(e.Module, e.Resource)
		if !ok {
			t.Errorf("каталог: %s.%s не переводится в тип объекта собственной же функцией — "+
				"таблица имён противоречит себе", e.Module, e.Resource)
			continue
		}
		if !inModel[fgaType] {
			missing = append(missing, e.Module+"."+e.Resource+" → "+fgaType)
		}
	}

	t.Logf("осмотрено: типов в модели %d, записей каталога %d; типов каталога вне модели %d",
		len(model.Types), len(catalog), len(missing))

	if len(catalog) == 0 || len(model.Types) == 0 {
		t.Fatal("одна из сторон пуста — «расхождений нет» здесь означало бы «сверять было нечего»")
	}

	for _, m := range missing {
		t.Errorf("%s — тип объявлен каталогом, но его НЕТ в канонической модели.\n"+
			"Край переведёт имя ресурса в этот тип и задаст о нём вопрос, на который модель "+
			"ответить не может: полоса объявлена и не гейтит ничего. Либо тип возвращается в "+
			"модель, либо запись уходит из каталога вместе со своим предметом", m)
	}
}
