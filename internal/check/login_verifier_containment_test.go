// loginVerifierSpec — объявление предмета. Живёт ЗДЕСЬ, в файле пробы: литерал
// имени таблицы в ядре гейта сделал бы гейт своей же находкой (см. шапку
// `login_verifier_containment.go`).
//
// Разрешённый файл сегодня ОДИН — адаптер хранилища, а не его пакет: пакет —
// 70 не-тестовых файлов, и разрешение каталогу пропускало вызов выхода в любом.
// Проверяющий пароля (часть П2 фазы Ф2) получит разрешение СВОЕМУ файлу вместе
// со своим кодом и своей причиной — не раньше: раньше оно было бы разрешением
// без предмета, и гейт это объявляет находкой.
//
// Потребители — ровно два оператора базы адаптера: запрос, называющий таблицу,
// и материал уходят в них аргументами. Ключ — как его печатает находка; вызов с
// материалом либо именем таблицы в любой другой функции либо другой вызов той же
// функции — находка, пока не объявлен здесь с причиной.
func loginVerifierSpec() check.LoginVerifierSpec {
	return check.LoginVerifierSpec{
		Accessor:      "Reveal",
		DeclRel:       "internal/domain/login_method.go",
		DeclType:      "LoginVerifier",
		Table:         "user_login_methods",
		TableOwnerRel: "internal/repo/kaname/pg/login_method_repo.go",
		AllowedFiles: map[string]string{
			"internal/repo/kaname/pg/login_method_repo.go": "адаптер хранилища кладёт материал в базу аргументом оператора",
			"internal/passwordverify/verifier.go": "проверяющий пароля сверяет предъявленное с хранимым — " +
				"материал и есть его предмет (часть П2 фазы Ф2). Разрешён ФАЙЛ, а не пакет: разбор, " +
				"сверка с потолком и вычисление стоят в нём целиком, наружу уходят только исход, " +
				"признак формата и числа параметров",
		},
		OpaqueConsumers: map[string]string{
			"LoginMethodRepo.Create → r.pool.QueryRow": "оператор вставки строки способа: материал и запрос с именем таблицы — его аргументы",
			"LoginMethodRepo.Get → r.pool.QueryRow":    "оператор чтения строки способа: запрос с именем таблицы — его аргумент",
			// Замещение материала одним оператором (ID-PW-1 PWV-10, фаза Ф3
			// `kacho#1269`): транзакцию приносит вызывающий — полоса входа и смена
			// пароля кладут материал одним исходом с прочими записями, — поэтому
			// оператор идёт по `tx`, а не по пулу. Материал и запрос с именем
			// таблицы — его аргументы; наружу уходит только число строк.
			"replaceLoginVerifierTx → tx.Exec": "оператор замещения строки способа в транзакции вызывающего: " +
				"материал и запрос с именем таблицы — его аргументы, наружу уходит число затронутых строк",

			// Проверяющий пароля: вызовы, которым материал отдан ПО СУЩЕСТВУ.
			// Объявлен ровно тот, кому гейт видит передачу предмета: объявление
			// без предмета он называет находкой, и правильно — разрешение,
			// которому нечего разрешать, неотличимо от прощённой утечки.
			"inspectAndCompare → strings.HasPrefix": "признак формата читается началом самого значения: " +
				"выбор проверяющего производен от хранимого значения, а не от настройки",
			"compareBcrypt → strconv.ParseUint": "стоимость разбирается из разметки ДО вычисления — " +
				"сверить её с потолком нужно раньше, чем библиотека начнёт считать; наружу уходит число",
			"compareBcrypt → bcrypt.CompareHashAndPassword": "сверка предъявленного пароля с хранимым " +
				"значением — предмет проверяющего; результат библиотеки материала не несёт",
			"compareArgon2id → strings.HasPrefix": "версия разметки читается из самого значения: чужая " +
				"версия значит иную функцию, и вычисляться такое значение не обязано",
			"compareArgon2id → strings.Cut": "разметка PHC делится на параметры, соль и тело. Части " +
				"остаются внутри вызывающей функции и уходят только в вычисление: наружу из файла " +
				"возвращаются исход, признак формата и числа",
		},
	}
}

// TestLoginVerifierStaysInside — гейт: материал способа входа выходит из своего
// типа только в разрешённых местах, и таблицу секрета называет только её
// адаптер.
//
// Что делать, если он сработал, — исходов три, четвёртого нет:
//
//  1. материал нужен этому месту по существу (проверка пароля) → разрешение
//     ФАЙЛУ с причиной, в `loginVerifierSpec`, в том же изменении, что и код;
//  2. нужен не материал, а факт о нём («способ есть», «вид такой-то») → брать
//     факт из строки способа, а не материал;
//  3. вызов попал по инерции → снять.
//
// Приписать место в разрешения без причины — НЕ исход: разрешение без названной
// причины неотличимо от прощённой утечки.
func TestLoginVerifierStaysInside(t *testing.T) {
	t.Parallel()

	wd, err := os.Getwd()
	require.NoErrorf(t, err, "проверка НЕ ИСПОЛНЯЛАСЬ: рабочий каталог не установлен")
	root, err := platformtree.ModuleRootFrom(wd)
	require.NoErrorf(t, err, "проверка НЕ ИСПОЛНЯЛАСЬ: корень модуля не найден")
	tree, err := treecorpus.NewTree(root)
	require.NoErrorf(t, err, "состав дерева не установлен — «ноль находок» здесь означало бы «ноль прочитанного»")
	corpus, err := check.CorpusFrom(tree, check.ProductionGoFile)
	require.NoErrorf(t, err, "проверка НЕ ИСПОЛНЯЛАСЬ: корпус не собран")

	findings, census, err := check.AuditLoginVerifierContainment(corpus, loginVerifierSpec())
	require.NoErrorf(t, err, "проверка НЕ ИСПОЛНЯЛАСЬ")
	t.Logf("%s; находок %d", census, len(findings))

	for _, f := range findings {
		t.Error(f)
	}
}
