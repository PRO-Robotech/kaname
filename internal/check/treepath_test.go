package check_test

// treepath_test.go — ОДНА точка, которой пробы этого пакета называют файлы
// дерева, и одна причина, по которой она здесь появилась.
//
// Пробы пакета адресуются координатами МОНОРЕПО (`services/iam/internal/…`,
// `proto/kaname/…`) и складывали их с «самым внешним go.mod». В монорепо это
// верно. В самостоятельном клоне самый внешний `go.mod` — сам модуль, и та же
// координата указывает в подкаталог, которого нет: 34 пробы этого пакета
// отказывали «нет файла» у всякого, кто склонирует, при том что часть названного
// с модулем ЕДЕТ и лежит уровнем выше по тому же дереву.
//
// Приведение делает platformtree, и оно различает ТРИ исхода, а не два:
// координата дерева платформы · координата внутри модуля · координата того, что
// в поставку не входит. Последнее даёт пропуск с названной предпосылкой —
// «условие не создано», а не находку о продукте.
//
// ПОЧЕМУ ЭТО НЕ МАСКА. Пропуск назначает предпосылка, а не проба, и в монорепо
// ветвь пропуска НЕДОСТИЖИМА: детектор отвечает «платформа есть» для любого
// пути. Держит это гейт пакета platformtree, а не обещание здесь.

import (
	"path"
	"testing"

	"github.com/PRO-Robotech/kaname/internal/testsupport/platformtree"
)

// treePath — файл дерева по координате монорепо, приведённой к посадке.
func treePath(t *testing.T, rel ...string) string {
	t.Helper()
	return platformtree.RequirePath(t, path.Join(rel...))
}

// platformRoot — корень дерева платформы для проб, которым нужно ВСЁ дерево, а
// не файл в нём: обход, ищущий производителя среди СОСЕДНИХ модулей, в клоне
// увидел бы только наш и объявил бы производителя пропавшим. Такая проба в
// клоне не «красная» — у неё не создано условие.
func platformRoot(t *testing.T) string {
	t.Helper()
	return platformtree.Require(t)
}
