// recipe_call_coordinate.go — гейт: КАТАЛОГ, названный строкой ВЫЗОВА в
// комментарии рецепта сборки, существует в этом дереве (задача
// PRO-Robotech/kacho#2613, предикат снятия п. 4).
//
// # Предмет
//
// Комментарий рецепта говорит читателю, ЧЕМ позвать цель: «Вызов: `make -C <кат>
// <цель>`». Строка вызова есть обещание исполнимости ЗДЕСЬ — она не описывает
// историю и не называет чужого держателя, она предписывает команду.
//
// Каталог, которого в дереве нет, делает это обещание неисполнимым, и отказ
// приходит не там, где ошибка: `make -C <нет каталога>` печатает «нет такого
// файла или каталога» и выходит кодом 2, то есть читатель получает отказ ИНСТРУМЕНТА
// вместо отказа цели и идёт разбираться не туда. До задачи #2613 таких строк в
// этом рецепте было ТРИ, и все три называли `services/iam` — каталог монорепо, от
// которого модуль отделён: отслеживаемых путей под `services/` в этом дереве НОЛЬ.
//
// Класс тот же, что у соседей `acceptance_path_coordinate.go` (путь предиката) и
// `acceptance_probe_coordinate.go` (имя пробы): утверждение, пережившее свой
// предмет. Дерево у него другое — не приёмка, а рецепт сборки, — и потому у него
// свой держатель.
//
// # РАЗБОР ПО ПОЗИЦИЯМ АРГУМЕНТОВ, А НЕ ПОИСК ПОДСТРОКИ
//
// Подстрока `services/iam` встречается в этом файле, в прозе рецепта и в
// объяснениях прошлых дефектов — и там она ЗАКОННА: она свидетельствует о том,
// как было. Гейт по подстроке краснел бы на собственном объяснении (ровно тот
// класс, который корпус ловит).
//
// Поэтому каталог опознаётся ПОЗИЦИЕЙ: строка вызова разбирается на поля, и
// каталогом признаётся аргумент ключа `-C` — приклеенный (`-C<кат>`) либо
// следующим полем (`-C <кат>`). Ни одно другое поле каталогом не считается: путь,
// названный прозой, этот гейт не судит вовсе, и это сказано ниже отдельной
// строкой, а не умолчано.
//
// # ГРАНИЦЫ НАЗВАНЫ, А НЕ УМОЛЧАНЫ
//
//   - ПУТЬ, НАЗВАННЫЙ ПРОЗОЙ, не судится. `services/iam/CLA.md` в объясняющем
//     абзаце — координата, а не вызов; её предмет тот же, но её разбор требует
//     отличать координату от формы имени, и это своя работа со своим замером.
//     Число таких строк здесь не печатается: гейт их не ищет, и напечатанный
//     ноль читался бы как «искали и не нашли».
//   - КАТАЛОГ СУДИТСЯ НА СУЩЕСТВОВАНИЕ, а не на исполнимость `make` в нём.
//     Каталог, отслеживаемый деревом, но не несущий своего `Makefile`, здесь не
//     находка: рецепт цитирует такую команду, чтобы объяснить, что она
//     НЕИСПОЛНИМА, и отличить цитату от предписания машинно значило бы судить
//     прозу. Ось соседняя и названа здесь, а не умолчана; предмет её — свой.
//   - ЦЕЛЬ вызова не проверяется. Объявлена ли она рецептом — предмет соседнего
//     гейта провязки (`judge_target_wiring.go`), и второе место об одном
//     предмете разошлось бы с ним молча.
//   - СТРОКА, НАЗВАВШАЯ ЧУЖОЙ РЕПОЗИТОРИЙ, освобождается: её координаты
//     принадлежат чужому дереву, и требовать их отсюда значило бы завести
//     находку на правдивой записи. Освобождение ВИДИМОЕ — перепись печатает его
//     число, иначе оно стало бы слепой зоной ровно того размера, которого никто
//     не видит.
package check

import (
	"fmt"
	"path"
	"regexp"
	"sort"
	"strings"
)

// RecipeCall — строка ВЫЗОВА в комментарии рецепта: та, что предписывает команду.
type RecipeCall struct {
	// Line — номер строки рецепта, чтобы читатель шёл по координате.
	Line int
	// Raw — тело комментария целиком: текст находки называет его дословно.
	Raw string
	// Dir — каталог, названный ключом `-C`. Пусто — вызов каталога не называет.
	Dir string
	// Foreign — строка объявила свои координаты координатами чужого репозитория.
	Foreign bool
}

// RecipeCallCensus — объём осмотренного и находки.
//
// Величины ПО КАЖДОЙ ОСИ отдельно: одно число скрыло бы случай, ради которого
// гейт заведён, — рецепт, в котором строк вызова не нашлось вовсе.
type RecipeCallCensus struct {
	// Lines — строк рецепта прочитано.
	Lines int
	// Comments — из них строк-комментариев.
	Comments int
	// Calls — строк вызова среди них.
	Calls int
	// Dirs — вызовов, назвавших каталог ключом `-C`.
	Dirs int
	// Exempt — из них освобождённых упоминанием чужого репозитория.
	Exempt int
	// Resolved — каталогов, которые в дереве ЕСТЬ.
	Resolved int
	// Findings — находки, каждая с координатой.
	Findings []string
}

// recipeCommentBody — тело строки-комментария рецепта. Группа 1 — текст после `#`.
//
// Комментарий рецепта начинается с `#` в любой позиции строки; ведущие пробелы
// и решётки съедаются, чтобы разбор не зависел от глубины отступа.
var recipeCommentBody = regexp.MustCompile(`^\s*#+\s?(.*)$`)

// recipeBacktickToken — команда в обратных кавычках. Строкой ВЫЗОВА признаётся
// только она: голая проза, начатая латиницей, командой не является, и открытый
// признак записал бы в вызовы половину рецепта.
var recipeBacktickToken = regexp.MustCompile("`([^`]+)`")

// recipeCallVerbs — ЗАКРЫТЫЙ набор глаголов вызова.
//
// Закрыт намеренно: открытый признал бы командой всякий токен в кавычках, а их в
// рецепте десятки — имена целей, ручек и путей.
var recipeCallVerbs = map[string]bool{"make": true, "go": true}

// recipeForeignRepo — упоминание репозитория организации в строке.
var recipeForeignRepo = regexp.MustCompile(`PRO-Robotech/([A-Za-z0-9_.-]+)`)

// recipeLineNamesForeignRepo — строка назвала ЧУЖОЙ репозиторий, то есть
// объявила свои координаты его координатами.
//
// ownHome — дом ЭТОГО дерева в форме `<владелец>/<имя>`; выводится из `go.mod`
// (OwnHomeOfTree), а не выписывается: литерал разошёлся бы с деревом молча.
func recipeLineNamesForeignRepo(body, ownHome string) bool {
	for _, m := range recipeForeignRepo.FindAllString(body, -1) {
		if m != ownHome {
			return true
		}
	}
	return false
}

// RecipeCallsOf — строки вызова в комментариях рецепта.
//
// Возвращает вызовы И объём прочитанного: без второй величины «вызовов ноль»
// было бы неотличимо от «рецепт не прочитан».
func RecipeCallsOf(body, ownHome string) (calls []RecipeCall, lines, comments int) {
	for i, line := range strings.Split(body, "\n") {
		lines++
		m := recipeCommentBody.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		comments++
		text := strings.TrimSpace(m[1])
		if text == "" {
			continue
		}
		foreign := recipeLineNamesForeignRepo(text, ownHome)
		for _, tok := range recipeBacktickToken.FindAllStringSubmatch(text, -1) {
			fields := strings.Fields(tok[1])
			if len(fields) == 0 || !recipeCallVerbs[fields[0]] {
				continue
			}
			calls = append(calls, RecipeCall{
				Line:    i + 1,
				Raw:     text,
				Dir:     recipeChdirArg(fields),
				Foreign: foreign,
			})
		}
	}
	return calls, lines, comments
}

// recipeChdirArg — каталог, названный ключом `-C`, ПО ПОЗИЦИИ аргумента.
//
// Две формы, обе законны у `make` и у `go`: приклеенная (`-C<кат>`) и
// раздельная (`-C <кат>`). Пустая строка означает «вызов каталога не называет» —
// это не находка, а отсутствие предмета.
func recipeChdirArg(fields []string) string {
	for i, f := range fields {
		if rest, ok := strings.CutPrefix(f, "-C"); ok {
			if rest != "" {
				return rest
			}
			if i+1 < len(fields) {
				return fields[i+1]
			}
		}
	}
	return ""
}

// JudgeRecipeCalls — суждение о разобранных вызовах.
//
// Чистая функция от уже прочитанного: её же зовёт инъекция, подавая синтетику.
// Гейт, чью способность падать доказывают правкой живого рецепта, доказательства
// не имеет.
//
// trackedDirs — каталоги, отслеживаемые деревом, выведенные из индекса git.
func JudgeRecipeCalls(calls []RecipeCall, trackedDirs map[string]bool) RecipeCallCensus {
	var c RecipeCallCensus
	c.Calls = len(calls)
	for _, call := range calls {
		if call.Dir == "" {
			continue
		}
		c.Dirs++
		if call.Foreign {
			c.Exempt++
			continue
		}
		if trackedDirs[path.Clean(call.Dir)] {
			c.Resolved++
			continue
		}
		c.Findings = append(c.Findings, fmt.Sprintf(
			"Makefile:%d: строка ВЫЗОВА называет каталог %q, которого в этом дереве НЕТ — "+
				"`make -C` на нём печатает отказ ИНСТРУМЕНТА («нет такого каталога»), а не отказ "+
				"цели, и читатель идёт разбираться не туда. Что делать: назвать каталог, "+
				"который здесь есть, либо — если вызов принадлежит чужому дереву — назвать "+
				"вместе с ним репозиторий, и тогда координата будет его, а не нашей.\n    %s",
			call.Line, call.Dir, call.Raw))
	}
	sort.Strings(c.Findings)
	return c
}

// TrackedDirsOf — каталоги, отслеживаемые деревом, из перечня его путей.
//
// Выводятся из ПУТЕЙ, а не обходом диска: обход прочитал бы игнорируемые
// каталоги (рабочие копии, распаковки, отчёты прогонов), и вердикт стал бы
// свойством рабочего каталога, а не коммита.
func TrackedDirsOf(tracked []string) map[string]bool {
	dirs := make(map[string]bool, len(tracked))
	for _, rel := range tracked {
		for d := path.Dir(rel); d != "." && d != "/" && d != ""; d = path.Dir(d) {
			dirs[d] = true
		}
	}
	return dirs
}
