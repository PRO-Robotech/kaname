// injection_named_exists_test.go — ГЕЙТ КЛАССА: обещание доказательства обязано
// иметь предмет (#2479).
//
// Норма, разбор и перечень законных форм координаты — в шапке
// `injection_named_exists.go`; здесь они не пересказываются, чтобы два места об
// одном предмете не разошлись.
//
// Способность гейта упасть доказана инъекцией —
// injection_named_exists_injection_test.go: тот же вызов на синтетическом дереве,
// где каждый мир отличается от законного близнеца одним фактом.
package check_test

import (
	"os"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kaname/internal/check"
	"github.com/PRO-Robotech/kaname/internal/testsupport/platformtree"
)

func TestEveryNamedInjectionProofExists(t *testing.T) {
	// Обход — по корню МОДУЛЯ службы, а не по корню монорепо. Два довода, и
	// каждый достаточен: в самостоятельном клоне монорепо нет вовсе, а обещания
	// соседних модулей платформы этому модулю не принадлежат — судить их отсюда
	// значило бы краснеть на чужом дереве.
	wd, err := os.Getwd()
	if err != nil {
		t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: рабочий каталог не установлен: %v", err)
	}
	root, err := platformtree.ModuleRootFrom(wd)
	if err != nil {
		t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: корень модуля не найден: %v", err)
	}

	findings, census, err := check.AuditNamedInjections(root)
	if err != nil {
		t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: обход дерева не состоялся: %v", err)
	}

	t.Logf("объём осмотренного: исходников Go разобрано %d · называют доказательство %d файл(ов) · "+
		"упоминаний в комментариях %d · резолвится %d · упоминаний в строковых литералах %d (не судятся)",
		census.GoFiles, census.NamingFiles, census.InComments, census.Resolved, census.InStrings)

	// ПУСТОЙ ОБХОД — находка, а не идеал: «все обещания имеют предмет» верно
	// тривиально, когда обещаний не прочитано ни одного.
	if census.GoFiles == 0 {
		t.Fatal("обход пуст: исходников Go не разобрано ни одного — вердикт беспредметен")
	}
	if census.InComments == 0 {
		t.Fatal("обход пуст: ни одна проба дерева не называет доказательства способности упасть — " +
			"либо распознаватель перестал знать форму координаты, либо доказательств не осталось; " +
			"и то и другое сказано бы этой строкой одинаково, поэтому вердикт беспредметен")
	}

	if len(findings) > 0 {
		var lines []string
		for _, f := range findings {
			lines = append(lines, f.NamedBy+" обещает "+f.Coordinate)
		}
		t.Fatalf("обещаний без предмета %d:\n  • %s\n"+
			"Шапка утверждает, что способность упасть доказана, а доказательства в дереве нет. "+
			"Гейт, потерявший эту способность, на чистом дереве выглядит РОВНО ТАК ЖЕ, как исправный, "+
			"поэтому обещание читается как само доказательство. Либо напишите инъекцию, либо снимите "+
			"обещание вместе с ней", len(findings), strings.Join(lines, "\n  • "))
	}
}
