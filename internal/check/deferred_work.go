// deferred_work.go — СВОЯ часть гейта отложенной работы: корень обхода и виды
// вычитания. Разбор общий и живёт в фундаменте.
//
// # Предмет
//
// Запреты «никакого тех-долга» и «всегда production-grade, НИКОГДА MVP» стоят в
// корпусе правил с самого начала. В ЭТОМ дереве их не держало ничего: держателем
// был гейт монорепо (`PRO-Robotech/kacho:TestNoDeferredWorkInTheTree`), а после
// вынесения службы (`kacho#2597`, `kacho#2598`) он судит ЧУЖОЕ дерево — его
// зелёный о `PRO-Robotech/kaname` не говорит ничего. Четыре приёмки службы
// продолжали называть его своим держателем. Предмет закрыт задачей #40.
//
// # Разбор переехал в фундамент — копии здесь больше нет
//
// Словарь форм, образец, отсев по затравке, граница употребления и упоминания,
// обход и перепись живут в
// [github.com/PRO-Robotech/corelib/treehygiene] и приезжают сюда ПИНОМ версии.
// Здесь они не пересказываются — пересказ и есть то второе место об одном
// предмете, ради снятия которого переезд и сделан.
//
// Цена копии была измерена, а не предположена (#51): разбор отложенной работы
// совпадал с близнецом платформы на 99 строках кода из 186, разбор имён — на 17
// из 34, а словарь форм совпадал по составу ТОЧНО. Совпадение содержимого
// нарушением не смягчалось, а доказывало его: держателя у одинаковости не было
// ни одного, и расхождение наступило бы молча — заведут в одном дереве
// тринадцатую форму, в другом её не будет, и написанное в ней окажется не
// находкой и не чистотой, а НЕВИДИМОСТЬЮ. Ban #20 корпуса правил говорит это
// прямо: файл, чей владелец — другой репозиторий, в этом дереве не лежит; нужен
// предмет — берут пином, не нужен — файла нет.
//
// # Что осталось СВОИМ — и почему именно это
//
// Ровно две вещи, и обе суть утверждения об ЭТОМ дереве, а не об общем разборе:
//
//   - КОРЕНЬ ОБХОДА. Его даёт гейт, и это корень МОДУЛЯ службы: судить дерево
//     платформы отсюда значило бы краснеть на чужом, а в самостоятельном клоне
//     его нет вовсе;
//   - ВИДЫ ВЫЧИТАНИЯ ([treehygiene.DeferralSkip]). Перечень вычитаемого есть
//     утверждение о составе конкретного дерева, и предмет каждого вида измерен
//     ЗДЕСЬ. Готовых видов фундамент не раздаёт намеренно: раздавая их, он
//     утверждал бы о чужом дереве то, чего не измерял, и предикат «вид без
//     предмета» обессмыслился бы.
//
// # Что СНЯТО вместе с переездом — и чем свойство держится теперь
//
// Прежняя редакция несла отдельный вычет имени функции стандартной библиотеки:
// вызова через точку, синтаксически похожего на обращение к читателю кода.
// Ветвь НЕ перенесена, потому что она недостижима — класс границы в самом
// образце фундамента уже отличает вызов через точку от обращения, и инъекция
// фундамента это измерила: с отключённым вычетом вердикт суиты не изменился ни
// на одной пробе.
//
// Свойство при этом не потеряно и держится с ОБЕИХ сторон шва:
// TestDeferralGateStaysSilentOnStdlibContextTODO — здесь, на кроне этого
// дерева; TestDottedCallIsNotADeferral — в фундаменте, на самом образце.
// Ослабят класс границы — покраснеют обе.
package check

import (
	"strings"

	"github.com/PRO-Robotech/corelib/treehygiene"
)

// deferralSkips — три вида, и у КАЖДОГО предмет измерен в ЭТОМ дереве, а не
// унаследован от монорепо: `_test.go` — тестовый корпус службы; `/testdata/` —
// вход проб; `pkg/api/` — сгенерированные стабы своих контрактов (свои с
// `kaname#49`, прежде приезжали модулем платформы).
//
// Вычитается ровно то, что судить нельзя ПО СУЩЕСТВУ, а не то, что неудобно:
// фикстура гейта обязана уметь написать форму дефекта, иначе гейт не проверить
// инъекцией, а маркер в сгенерированном принадлежит генератору.
//
// Вид, которому больше нечего вычитать, — находка, и выносит её гейт этого
// дерева: под именем вида без предмета можно положить что угодно, и счёт не
// сдвинется.
var deferralSkips = []treehygiene.DeferralSkip{
	{
		Name:  "тестовый корпус",
		Why:   "фикстура гейта обязана уметь написать форму дефекта — иначе гейт не проверить инъекцией",
		Match: func(s string) bool { return strings.HasSuffix(s, "_test.go") },
	},
	{
		Name:  "тестовые данные",
		Why:   "вход проб, а не код: маркер там принадлежит сценарию, а не продукту",
		Match: func(s string) bool { return strings.Contains(s, "/testdata/") },
	},
	{
		Name:  "сгенерированное",
		Why:   "маркеры принадлежат генератору стабов, а не автору дерева",
		Match: func(s string) bool { return strings.HasPrefix(s, "pkg/api/") },
	},
}

// DeferralSkips — объявленные виды вычитания; гейт сверяет их предмет.
//
// Отдаётся копия перечня: он есть предмет пробы, и проба не вправе его двигать.
func DeferralSkips() []treehygiene.DeferralSkip {
	out := make([]treehygiene.DeferralSkip, len(deferralSkips))
	copy(out, deferralSkips)
	return out
}

// AuditDeferredWork обходит дерево под root общим разбором фундамента, связав
// его с видами вычитания ЭТОГО дерева.
//
// Связывание живёт здесь, в ОДНОМ месте, и это несущее: инъекция обязана гонять
// ту же функцию, что гейт. Раздай мы виды по вызывающим — каждая проба связывала
// бы их заново, и доказанной оказалась бы не та связка, которая судит дерево.
//
// Возвращает находки и перепись осмотренного: «ноль находок» обязано быть
// отличимо и от «ноль прочитанного», и от «прочитал не там». Вердикт — падать
// ли и с каким текстом — выносит гейт: текст отказа обязан называть исходы,
// принятые в ЭТОМ дереве.
func AuditDeferredWork(root string) (
	findings []treehygiene.DeferralFinding, census treehygiene.DeferralCensus, err error) {
	return treehygiene.AuditDeferredWork(root, deferralSkips)
}
