// retired_verb_census_injection_test.go — перепись снятого глагола умеет упасть
// и смолчать. Каждый мир отличается от законного близнеца одним фактом; входы —
// дословные формы следов, которые снятие оставило бы в дереве.
package check_test

import (
	"strings"
	"testing"

	"github.com/PRO-Robotech/kaname/internal/check"
)

var injVerb = check.RetiredVerb{Name: "UpsertFromIdentity", Control: "LookupSubject", Refs: "инъекция"}

// injControl — живой сосед, чтобы контроль не молчал в мирах о снятом.
const injControl = `"/kaname.cloud.iam.v1.InternalIAMService/LookupSubject": {},`

func TestRetiredVerbCensusRedsOnALeftoverTrace(t *testing.T) {
	t.Parallel()
	cases := map[string]string{
		// запись манифеста — нижний регистр первой буквы, другой префикс
		"manifest.yaml": "      - {name: internalUpsertFromIdentity, class: update, internal: true}\n",
		// политика вызывающих
		"internal/authzguard/caller_policy.go": `	"/kaname.cloud.iam.v1.InternalUserService/UpsertFromIdentity",` + "\n",
		// маршрут REST — другой регистр
		"docs/content/api/user.mdx": "POST /iam/v1/internal/users:upsertFromIdentity\n",
	}
	for path, trace := range cases {
		files := map[string]string{"internal/x.go": injControl, path: trace}
		c := check.JudgeRetiredVerb(files, injVerb)
		if c.Refusal() != "" {
			t.Fatalf("%s: перепись отказала там, где обязана судить: %s", path, c.Refusal())
		}
		if len(c.Findings) != 1 || c.Findings[0] != path {
			t.Errorf("%s: след снятого глагола не назван: %s", path, c)
		}
	}
}

func TestRetiredVerbCensusStaysSilentOnExemptions(t *testing.T) {
	t.Parallel()
	trace := `"/kaname.cloud.iam.v1.InternalUserService/UpsertFromIdentity"`
	cases := map[string]string{
		"pkg/api/kaname/cloud/iam/v1/x.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\n" + trace,
		"proto/declared-breaks.yaml":          "    symbol: InternalUserService.UpsertFromIdentity\n",
		"CHANGELOG.md":                        "- снят `InternalUserService.UpsertFromIdentity`\n",
		"docs/engineering/acceptance/active-identity-has-a-way-in.md": trace,
		"docs/specs/reviews/x/abc.yaml":                               trace,
		"cmd/kaname/internal_user_service_surface_test.go":            trace,
		"internal/check/catalog_copy_parity.go":                       trace,
	}
	for path, content := range cases {
		files := map[string]string{"internal/x.go": injControl, path: content}
		c := check.JudgeRetiredVerb(files, injVerb)
		if c.Refusal() != "" || len(c.Findings) != 0 {
			t.Errorf("%s: исключение не сработало: %s %s", path, c, c.Refusal())
		}
	}
}

// Законный близнец И1: тот же маркер не в начале строки — не порождённый файл.
func TestRetiredVerbCensusGeneratedMarkerIsALineNotASubstring(t *testing.T) {
	t.Parallel()
	files := map[string]string{
		"internal/x.go": injControl,
		"internal/y.go": `const s = "// Code generated by x. DO NOT EDIT."` + "\nUpsertFromIdentity\n",
	}
	c := check.JudgeRetiredVerb(files, injVerb)
	if len(c.Findings) != 1 {
		t.Fatalf("маркер внутри строки снял файл с переписи: %s", c)
	}
}

func TestRetiredVerbCensusRefusesAnEmptyWalkAndASilentControl(t *testing.T) {
	t.Parallel()
	if msg := check.JudgeRetiredVerb(map[string]string{}, injVerb).Refusal(); msg == "" {
		t.Error("пустой обход прошёл как «следов ноль»")
	}
	c := check.JudgeRetiredVerb(map[string]string{"internal/x.go": "package x\n"}, injVerb)
	if msg := c.Refusal(); !strings.Contains(msg, "контроль молчит") {
		t.Errorf("контроль без единого попадания не отказал: %q", msg)
	}
	// Близнец: тот же мир с одним живым именем — перепись судит.
	c = check.JudgeRetiredVerb(map[string]string{"internal/x.go": injControl}, injVerb)
	if c.Refusal() != "" || len(c.Findings) != 0 {
		t.Errorf("законный мир отказал либо назвал находку: %s %s", c, c.Refusal())
	}
}
