// model_canon_check_wiring_test.go — ГЕЙТ КЛАССА: у единственного судьи
// СХОДИМОСТИ БЛОКОВ МОДЕЛИ с манифестами обязан быть вызывающий (задача #17,
// порт семейства `modelcanoncheckwiring`).
//
// # Предмет у этой цели ТОТ ЖЕ, а операнд ДРУГОЙ, и это надо сказать прямо
//
// Цель `model-canon-check` сверяет блоки модели доступов с манифестами
// ОСТАЛЬНЫХ модулей платформы, то есть её второй операнд лежит в чужом дереве.
// В самостоятельном клоне она отдаёт третий исход («условие не создано») и
// помечена `[монорепо]` в перечне целей.
//
// Гейту это НЕ мешает и предмета его не меняет: он судит ПРОВЯЗКУ, а не
// сходимость. Второй операнд нужен ЦЕЛИ, а не ему — ровно так задача #17 и
// разобрала прежнюю посылку «семейство кросс-репозиторное». Провязанный шаг
// обязан читать код возврата четырьмя исходами: тогда отсутствие второго дерева
// даёт видимый пропуск, а не красное и не молчаливый зелёный.
//
// Способность упасть и смолчать доказана общей инъекцией —
// judge_target_wiring_injection_test.go.
package check_test

import "testing"

// ModelCanonCheckTarget — цель, поднимающая единственного судью сходимости.
const ModelCanonCheckTarget = "model-canon-check"

// TestModelCanonCheckTargetHasACaller — имя сохранено дословно с монорепо.
func TestModelCanonCheckTargetHasACaller(t *testing.T) {
	t.Parallel()
	assertJudgeTargetIsWired(t, ModelCanonCheckTarget)
}
