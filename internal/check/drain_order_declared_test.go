// drainCensusFloor — дренируемых очередей, ниже которого обход беспредметен.
//
// Порог стережёт РАЗБОР, а не дерево: обвал переписи означает, что признак
// разъехался с кодом, и молчание гейта стало бы слепотой. Значение — на единицу
// меньше сегодняшнего числа (четыре), чтобы снятие ОДНОЙ очереди решением было
// законным, а обвал распознавания — нет.
const drainCensusFloor = 3

// drainInventory — перепись дерева, собранная ОДИН раз на прогон.
//
// Разбор восьмисот файлов повторяется четырьмя пробами этого семейства, и
// повторять его четырежды незачем: вход у всех один и тот же.
var (
	drainOnce  sync.Once
	drainInv   check.QueueInventory
	drainQueue check.SchemaQueues
	drainErr   error
)

func drainInventory(t *testing.T) (check.QueueInventory, check.SchemaQueues) {
	t.Helper()
	drainOnce.Do(func() {
		wd, err := os.Getwd()
		if err != nil {
			drainErr = err
			return
		}
		root, rerr := platformtree.ModuleRootFrom(wd)
		if rerr != nil {
			drainErr = rerr
			return
		}
		tree := gateTree(t, root)

		migrations, merr := check.MigrationCorpus(tree.tree)
		if merr != nil {
			drainErr = merr
			return
		}
		drainQueue, drainErr = check.QueuesOfSchema(migrations)
		if drainErr != nil {
			return
		}
		corpus, cerr := check.DrainSiteCorpus(tree.tree)
		if cerr != nil {
			drainErr = cerr
			return
		}
		drainInv, drainErr = check.DrainInventoryOf(corpus, drainQueue.Live())
	})
	if drainErr != nil {
		t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: перепись очередей не собрана: %v", drainErr)
	}
	return drainInv, drainQueue
}

// drainCensus — строка переписи, общая всем пробам семейства.
//
// ОБЕ величины формы печатаются РАЗДЕЛЬНО, и это несущее требование задачи:
// одно число «дренируемых N» читается как «все» и скрывает ровно тот случай,
// ради которого гейт заведён, — очередь, объявленную формой, которой
// распознаватель не знает.
func drainCensus(inv check.QueueInventory, schema check.SchemaQueues) string {
	byForm := map[check.DrainForm]int{}
	ordered, commutative := 0, 0
	for _, site := range inv.Drained {
		byForm[site.Form]++
		if site.OrderKey != "" {
			ordered++
			continue
		}
		commutative++
	}
	return "перепись: " + strings.Join([]string{
		"файлов миграций " + strconv.Itoa(schema.FilesRead),
		"объявлений таблиц " + strconv.Itoa(schema.TablesRead),
		"очередей схемы " + strconv.Itoa(len(schema.Live())) +
			" (по имени " + strconv.Itoa(len(schema.ByName)) +
			", по признаку доставки " + strconv.Itoa(len(schema.ByMarker)) + ")",
		"прод-файлов Go " + strconv.Itoa(inv.FilesRead),
		"строковых литералов " + strconv.Itoa(inv.LiteralsRead),
		"мест машинерии очередей " + rolesCensus(inv.Roles),
		"ДРЕНИРУЕМЫХ ОЧЕРЕДЕЙ " + strconv.Itoa(len(inv.Drained)) +
			" — судимых по ПРОВОДКЕ " + strconv.Itoa(byForm[check.DrainFormWiring]) +
			", дренируемых СОБСТВЕННЫМ ОПЕРАТОРОМ " + strconv.Itoa(byForm[check.DrainFormOperator]),
		"из них с ключом порядка " + strconv.Itoa(ordered) + ", без ключа " + strconv.Itoa(commutative),
		"недренируемых очередей схемы " + strconv.Itoa(len(schema.Live())-len(inv.Drained)),
	}, " · ")
}

func rolesCensus(roles map[string]int) string {
	names := make([]string, 0, len(roles))
	for k := range roles {
		names = append(names, k)
	}
	sort.Strings(names)
	parts := make([]string, 0, len(names))
	for _, n := range names {
		parts = append(parts, n+" "+strconv.Itoa(roles[n]))
	}
	return "{" + strings.Join(parts, ", ") + "}"
}

// TestEveryDrainedQueueDeclaresItsOrdering — по КАЖДОЙ дренируемой очереди
// решение о порядке принято: либо задан ключ, либо есть запись о
// коммутативности с обоснованием. Форма объявления дренажа значения не имеет —
// судятся обе одинаково.
//
// Что делать, если гейт сработал, — три исхода, четвёртого нет:
//
//  1. поток несёт две противоположные половины про одну единицу состояния ->
//     задать ключ порядка (САМЫЙ УЗКИЙ, на котором события не коммутируют) и
//     завести под него частичный индекс `(<ключ>, id) WHERE sent_at IS NULL`;
//  2. поток коммутативен -> завести запись в commutativeDrainExempt, назвав ПО
//     СУЩЕСТВУ ПРИМЕНЕНИЯ, почему ни одно событие не отменяет предыдущее;
//  3. неизвестно -> это исход (1): порядок дешевле воскресшего состояния, и его
//     цена — сериализация внутри одного ключа, а не всей очереди.
func TestEveryDrainedQueueDeclaresItsOrdering(t *testing.T) {
	t.Parallel()
	inv, schema := drainInventory(t)
	t.Log(drainCensus(inv, schema))

	// «Ноль находок» обязано быть отличимо от «ноль прочитанного».
	if inv.FilesRead == 0 {
		t.Fatal("обход пуст: прод-файлов Go прочитано ноль — вердикт беспредметен")
	}
	if inv.LiteralsRead == 0 {
		t.Fatal("строковых литералов осмотрено ноль — форма «собственный оператор» не " +
			"могла быть найдена ни при каком дереве, и молчание по ней означает слепоту")
	}
	if len(inv.Drained) < drainCensusFloor {
		t.Fatalf("дренируемых очередей найдено %d при пороге %d — признак разъехался с "+
			"кодом. Ноль находок здесь означает слепоту распознавателя, а не чистое дерево",
			len(inv.Drained), drainCensusFloor)
	}

	// Неизвестный вход — ЯВНЫЙ ОТКАЗ, а не молчание.
	for _, u := range inv.Unclassified {
		t.Errorf("%s — литерал настроек из пространства машинерии очередей, чья роль не "+
			"объявлена. Это НОВАЯ ФОРМА объявления: пропустить её значит вывести её "+
			"очередь из наблюдения молча. Назови роль типа в queueMachineryRoles "+
			"(«дренаж» — двигает строки; «сканер», «возврат», «уборка» — нет).", u)
	}
	for _, a := range inv.Ambiguous {
		t.Errorf("константа %q названа двумя прод-файлами с РАЗНЫМИ значениями, и ею "+
			"названа очередь либо ключ порядка: резолв неоднозначен. Угаданное имя "+
			"означало бы вердикт о чужой очереди — переименуй одну из констант.", a)
	}

	for _, table := range sortedTables(inv.Drained) {
		site := inv.Drained[table]
		if site.OrderKey != "" {
			continue
		}
		why, exempt := commutativeDrainExempt[table]
		if !exempt {
			t.Errorf("очередь %s дренится (форма: %s; %s) БЕЗ ключа порядка и без записи "+
				"о коммутативности.\n\nВыборка без ключа партиции не удерживает порядок: "+
				"строка, отложенная по временной причине, применяется после более свежей "+
				"(общая машинерия сортирует по `attempt_count`), а при нескольких "+
				"исполнителях `FOR UPDATE SKIP LOCKED` отдаёт потомка, пока предшественник "+
				"заперт чужим клеймом. Если поток несёт постановку и снятие одной единицы "+
				"состояния, снятое ВОССТАНОВИТСЯ, и убрать его будет нечем.\n\nЗадай ключ "+
				"порядка + частичный индекс (<ключ>, id) WHERE %s IS NULL, либо заведи "+
				"запись в commutativeDrainExempt с обоснованием ОТ ПРИМЕНЕНИЯ строки.",
				table, site.Form, strings.Join(site.Where, ", "), check.DeliveryMarkerColumn)
			continue
		}
		if strings.TrimSpace(why) == "" {
			t.Errorf("запись о коммутативности %s без обоснования: обязана называть, что "+
				"делает применение строки и почему ни одно событие потока не отменяет "+
				"предыдущее", table)
		}
	}
}

// TestCommutativeDrainExemptionsHaveSubject — запись живёт, пока у неё есть
// предмет: очередь, переставшая дрениться либо получившая ключ порядка,
// унаследует следующую слепую зону.
func TestCommutativeDrainExemptionsHaveSubject(t *testing.T) {
	t.Parallel()
	inv, schema := drainInventory(t)
	t.Log(drainCensus(inv, schema))

	if len(commutativeDrainExempt) == 0 {
		t.Log("роспись освобождений пуста — это ЦЕЛЬ, а не поломка: у каждой " +
			"дренируемой очереди есть ключ порядка")
		return
	}
	for _, table := range sortedKeysOf(commutativeDrainExempt) {
		site, drained := inv.Drained[table]
		if !drained {
			t.Errorf("запись о коммутативности %s больше не имеет предмета: такой "+
				"дренируемой очереди в дереве нет. Удали запись — иначе она достанется "+
				"следующей очереди того же имени вместе со своим молчанием.", table)
			continue
		}
		if site.OrderKey != "" {
			t.Errorf("запись о коммутативности %s больше не имеет предмета: её дренаж "+
				"выбирает по ключу %q (%s), то есть поток объявлен НЕкоммутативным. Два "+
				"места об одном предмете, из которых верно одно. Удали запись.",
				table, site.OrderKey, strings.Join(site.Where, ", "))
		}
	}
}

// TestEveryQueueOfTheSchemaIsAccountedFor — ТРЕТЬЯ ОСЬ: каждая очередь схемы
// учтена.
//
// Без неё перепись отвечает только на вопрос «что я увидел» и молчит о том,
// сколько очередей всего. Ровно это и дало класс, ради которого гейт заведён:
// число «дренируемых 9» читалось как «все», тогда как десятая дренилась формой,
// которой распознаватель не знал.
func TestEveryQueueOfTheSchemaIsAccountedFor(t *testing.T) {
	t.Parallel()
	inv, schema := drainInventory(t)
	t.Log(drainCensus(inv, schema))

	live := schema.Live()
	if len(live) == 0 {
		t.Fatal("очередей схемы найдено ноль — признак разъехался с миграциями, и " +
			"«все учтены» означало бы «учитывать было нечего»")
	}
	// Два признака об одном предмете заведены нарочно: расхождение между ними
	// означает, что один разъехался с деревом, и это обязано быть видно.
	if len(schema.ByMarker) == 0 {
		t.Fatalf("по признаку колонки доставки (%s) не опознано ни одной очереди при %d "+
			"опознанных по имени — признак колонки разъехался со схемой",
			check.DeliveryMarkerColumn, len(schema.ByName))
	}

	for _, table := range live {
		if _, drained := inv.Drained[table]; drained {
			if why, declared := undrainedQueues[table]; declared {
				t.Errorf("очередь %s объявлена недренируемой (%q), а дренаж у неё ЕСТЬ: %s. "+
					"Запись пережила свой предмет — сними её и реши вопрос о порядке "+
					"наравне с остальными.", table, why, strings.Join(inv.Drained[table].Where, ", "))
			}
			continue
		}
		why, declared := undrainedQueues[table]
		if !declared {
			t.Errorf("очередь %s есть в схеме, и ни одна форма объявления дренажа её не "+
				"нашла.\n\nИсходов два: либо её движитель объявлен формой, которой "+
				"распознаватель не знает — и тогда чинить надо РАСПОЗНАВАТЕЛЬ, а не эту "+
				"строку (форма, о которой он не знает, выводит из наблюдения ВСЁ, что ею "+
				"записано); либо движителя нет — и тогда заведи запись в undrainedQueues, "+
				"назвав, чем доставка заменена.", table)
			continue
		}
		if strings.TrimSpace(why) == "" {
			t.Errorf("запись о недренируемости %s без обоснования: обязана называть, чем "+
				"заменена доставка", table)
		}
	}

	for _, table := range sortedKeysOf(undrainedQueues) {
		if !containsString(live, table) {
			t.Errorf("запись о недренируемости %s больше не имеет предмета: такой очереди "+
				"в живой схеме нет. Удали запись вместе с её очередью.", table)
		}
	}
}

// TestExemptDrainSiteNamesTheRosterOfThisTree — обоснование ПУСТОГО ключа
// порядка живёт в ОДНОМ месте, и точка решения на него ССЫЛАЕТСЯ.
//
// # Предмет — и почему это не вкусовщина
//
// Отсутствующий ключ сам по себе не объясняет ничего, поэтому объяснение пишут
// рядом с настройками. Такой комментарий не сверяется ни с чем: он не участвует
// в сборке, не имеет предмета в схеме и не даёт конфликта при слиянии. Пережив
// свой предмет, он остаётся стоять ровно там, где следующий решает, держится ли
// ещё освобождение.
//
// # Почему квалификатор НЕСУЩИЙ
//
// Так и было здесь: две проводки ссылались на роспись `repohygiene.…` — роспись
// ДРУГОГО репозитория, который после выноса службы записей её очередей не несёт
// вовсе (обе истекли там как «предмета нет»). Читатель в точке решения попадал
// туда, где про его очередь не написано ничего, — и видел исправную на вид
// ссылку. Проверка, довольная одним совпадением имени, зеленела бы ровно на
// этом.
func TestExemptDrainSiteNamesTheRosterOfThisTree(t *testing.T) {
	t.Parallel()
	inv, schema := drainInventory(t)
	t.Log(drainCensus(inv, schema))

	// Предпосылка: разбор ВИДИТ комментарии. Без неё гейт молчал бы «чисто» на
	// любом обосновании, включая отсутствующее.
	if inv.CommentsSeen == 0 {
		t.Fatalf("внутри областей объявления дренажа не осмотрено НИ ОДНОГО комментария "+
			"при %d дренируемых очередях — разбор идёт без комментариев, и любое молчание "+
			"этой пробы ничего не доказывает", len(inv.Drained))
	}

	checked := 0
	for _, table := range sortedTables(inv.Drained) {
		site := inv.Drained[table]
		for _, f := range site.ForeignRoster {
			t.Errorf("%s — обоснование очереди %s называет роспись ЧУЖОГО репозитория. "+
				"Записей об очередях этой службы она не несёт: они истекли там вместе со "+
				"своим предметом, когда служба стала отдельным продуктом. Ссылка выглядит "+
				"исполненной и ведёт туда, где про эту очередь не написано ничего. "+
				"Сошлись на %s ЭТОГО дерева.", f, table, check.DrainRosterName)
		}
		if _, exempt := commutativeDrainExempt[table]; !exempt {
			continue // у очереди с ключом обоснование законно локально
		}
		checked++
		if site.RosterNamed {
			continue
		}
		t.Errorf("точка решения очереди %s (%s) не называет %s: очередь освобождена от "+
			"ключа порядка, а в месте, где это видно, не стоит НИЧЕГО — ни поля, ни "+
			"причины его отсутствия. Поставь там комментарий со ссылкой на роспись; само "+
			"обоснование правь в ней, а не здесь — второй его экземпляр разойдётся с "+
			"первым молча.",
			table, strings.Join(site.Where, ", "), check.DrainRosterName)
	}

	t.Logf("освобождённых очередей %d (проверено точек решения %d), комментариев внутри "+
		"областей объявления %d", len(commutativeDrainExempt), checked, inv.CommentsSeen)
}

func sortedTables(m map[string]*check.DrainSite) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func sortedKeysOf(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
