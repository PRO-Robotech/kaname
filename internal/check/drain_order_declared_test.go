//
// # ПРЕДМЕТ И ЦЕНА ЕГО ОТСУТСТВИЯ
//
// Очередь, чей поток несёт две противоположные половины про одну единицу
// состояния, обязана выбираться так, чтобы снятие не применилось раньше
// постановки: иначе снятое ВОССТАНАВЛИВАЕТСЯ, и убрать его больше нечем —
// событий про него в очереди не осталось. Радиус у этого один объект, а сам
// отказ бесшумен: «работает» и «ни один отзыв не доехал» дают одинаковую
// картину.
//
// Исходов законных два — ключ порядка выборки либо запись о коммутативности с
// обоснованием. Незаконен ТРЕТИЙ: решение не принято, а посмотреть, принято ли,
// негде.
//
// # ПОЧЕМУ ГЕЙТ ЗАВОДИТСЯ ЗДЕСЬ, А НЕ БЫЛ ПЕРЕНЕСЁН
//
// Гейт порядка монорепо (`internal/repohygiene`, семейство `outboxorderinggate`)
// судил очереди службы, пока она лежала в дереве платформы. Он строит перепись
// обходом `services/*` СВОЕГО дерева, поэтому после выноса службы отдельным
// продуктом её очереди стали ему невидимы by construction, а обе записи его
// росписи, принадлежавшие службе, ИСТЕКЛИ вместе со своим предметом — то есть
// самоистечение сработало как задумано, и решение о порядке четырёх очередей
// перестало держать что бы то ни было.
//
// Проверка живёт в репозитории своего ПРЕДМЕТА. Предмет здесь.
//
// # ЧТО ГЕЙТ СУДИТ, А ЧТО НЕТ
//
// Судит: принято ли решение, единственный ли у обоснования экземпляр, есть ли у
