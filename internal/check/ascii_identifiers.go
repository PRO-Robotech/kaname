// # Предмет
//
// Ban #17 состоит из двух половин, и в этом дереве держалась ровно одна.
// Объявления конвейера судит `TestDeliveryCarriesItsOwnPipeline`
// (`internal/supplyhygiene`). Идентификаторы Go не судил НИКТО: держателем был
// гейт монорепо (`PRO-Robotech/kacho:TestIdentifiersAreASCII`), а после
// вынесения службы (`kacho#2597`, `kacho#2598`) он судит ЧУЖОЕ дерево — его
// зелёный о `PRO-Robotech/kaname` не говорит ничего. Шесть вхождений в приёмках
// службы продолжали называть его своим держателем. Предмет закрыт задачей #41.
//
// # Разбор переехал в фундамент — копии здесь больше нет
//
// Почему имя обязано быть латинским, чем омоглиф опасен и почему это РАЗБОР, а
// не поиск по образцу, — сказано в
// [github.com/PRO-Robotech/corelib/treehygiene], там же и сам разбор. Здесь это
// не пересказывается: два места об одном предмете расходятся молча, и цена
// копии измерена — разбор имён совпадал с близнецом платформы на 17 строках
// кода из 34 (#51, ban #20).
//
// # Что осталось СВОИМ
//
// Обход и его КОРЕНЬ: фундамент разбирает ОДИН исходник и о деревьях не
// высказывается — судить чужое дерево значило бы краснеть на чужом. Обход по
// корню модуля службы, перепись и порог беспредметности живут у гейта,
// `ascii_identifiers_test.go`.
//
// Своих правил у этого файла нет, и потому он — ШОВ, а не вторая реализация:
// гейт и его инъекция зовут одно имя, и связь с фундаментом объявлена в одном
// месте. Появится у службы своя часть разбора имён — её место здесь, и менять
// придётся один файл, а не три.
package check

import "github.com/PRO-Robotech/corelib/treehygiene"

// NonASCIIIdent — одно нелатинское имя с координатой; тип фундамента, названный
// здесь именем шва.
//
// Псевдоним, а не своя запись: своя дала бы второе объявление об одном предмете,
// а перекладывание полей из чужой записи в свою — место, где поле теряется
// молча.
type NonASCIIIdent = treehygiene.NonASCIIIdent

// ScanNonASCIIIdents разбирает ОДИН исходник и возвращает: сколько имён
// осмотрено и какие из них нелатинские.
//
// Перепись «имён осмотрено N» нужна гейту, чтобы «ноль находок» было отличимо
// от «разбор ничего не увидел»; неразбираемый файл отдаёт признак, а не пустой
// успех, — обе половины держит фундамент, и утверждают их его пробы.
func ScanNonASCIIIdents(name string, src []byte) (seen int, findings []NonASCIIIdent, err error) {
	return treehygiene.ScanNonASCIIIdents(name, src)
}
