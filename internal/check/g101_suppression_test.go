func TestNoG101SuppressionsOutsideGeneratedAPI(t *testing.T) {
	t.Parallel()
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	root, err := platformtree.ModuleRootFrom(wd)
	if err != nil {
		t.Fatal(err)
	}
	files, err := treecorpus.UnderWithSuffix(root, ".go")
	if err != nil {
		t.Fatal(err)
	}
	var census check.G101SuppressionCensus
	for _, abs := range files {
		rel, err := filepath.Rel(root, abs)
		if err != nil {
			t.Fatal(err)
		}
		rel = filepath.ToSlash(rel)
		if strings.HasPrefix(rel, "pkg/api/") {
			continue
		}
		src, err := os.ReadFile(abs) // #nosec G304 -- путь из индекса git своего модуля
		if err != nil {
			t.Fatal(err)
		}
		part, err := check.ScanG101Suppressions(rel, src)
		if err != nil {
			t.Fatal(err)
		}
		census.Add(part)
	}
	t.Logf("перепись: осмотрено %d файлов Go вне pkg/api · %d строк · подавлений G101 %d",
		census.Files, census.Lines, len(census.Sites))
	if err := census.Judge(); err != nil {
		t.Fatal(err)
	}
}

func TestG101SuppressionGateInjectionAndLegalTwin(t *testing.T) {
	t.Parallel()
	marker := "#nosec" + " G101"
	twin := "package sample\nconst exchangePath = \"/iam/v1/token\"\n"
	injected := strings.Replace(twin, "const exchangePath", "// "+marker+" -- адрес маршрута\nconst exchangePath", 1)
	for _, tc := range []struct {
		name string
		src  string
		line string
	}{
		{name: "законный близнец", src: twin},
		{name: "настоящая директива", src: injected, line: "internal/sample.go:2:"},
		{name: "алиас директивы", src: strings.Replace(injected, "// "+marker, "//gosec:disable G101", 1), line: "internal/sample.go:2:"},
		{name: "алиас без номера", src: strings.Replace(injected, "// "+marker, "//gosec:disable", 1), line: "internal/sample.go:2:"},
		{name: "алиас другого правила", src: strings.Replace(injected, "// "+marker, "//gosec:disable G304", 1)},
		{name: "пустой список", src: strings.Replace(injected, marker, "#nosec", 1), line: "internal/sample.go:2:"},
		{name: "все правила", src: strings.Replace(injected, marker, "#nosec block", 1), line: "internal/sample.go:2:"},
		{name: "нераспознанный список тоже подавляет всё", src: strings.Replace(injected, marker, "#nosec G12", 1), line: "internal/sample.go:2:"},
		{name: "вторая директива после обоснования", src: strings.Replace(injected, marker, "#nosec G304 -- пояснение\n// "+marker, 1)},
		{name: "физическая координата", src: "package sample\n//line generated.go:900\n// " + marker + " -- причина\nconst exchangePath = \"/iam/v1/token\"\n", line: "internal/sample.go:3:"},
		{name: "маркер в служебном комментарии", src: "package sample\n//go:generate echo " + marker + "\n// " + marker + " -- причина\nconst exchangePath = \"/iam/v1/token\"\n", line: "internal/sample.go:3:"},
		{name: "сцепленные номера", src: strings.Replace(injected, marker, marker+"G304", 1), line: "internal/sample.go:2:"},
		{name: "номер с буквенным хвостом", src: strings.Replace(injected, marker, marker+"suffix", 1), line: "internal/sample.go:2:"},
		{name: "упоминание в прозе", src: strings.Replace(injected, "// "+marker, "// пояснение "+marker, 1)},
		{name: "первое упоминание в прозе скрывает последующее", src: "package sample\n// пояснение " + marker + "\n// " + marker + " -- причина\nconst exchangePath = \"/iam/v1/token\"\n"},
		{name: "отступ в строке группы", src: "package sample\n// пояснение\n// \t" + marker + " -- причина\nconst exchangePath = \"/iam/v1/token\"\n", line: "internal/sample.go:3:"},
		{name: "список правил", src: strings.Replace(injected, marker, "#nosec G304 G101", 1), line: "internal/sample.go:2:"},
		{name: "блочный комментарий CRLF", src: "package sample\r\n/*\r\n" + marker + " -- причина\r\n*/\r\nconst exchangePath = \"/iam/v1/token\"\r\n", line: "internal/sample.go:3:"},
		{name: "блочный комментарий", src: "package sample\n/* пояснение\n" + marker + "\n*/\nconst exchangePath = \"/iam/v1/token\"\n", line: "internal/sample.go:3:"},
		{name: "продолжение списка", src: strings.Replace(injected, marker, "#nosec\n// G101", 1), line: "internal/sample.go:2:"},
		{name: "порождённый файл вне исключения", src: "// Code generated by sample. DO NOT EDIT.\n" + injected, line: "internal/sample.go:3:"},
		{name: "литерал не директива", src: "package sample\nconst example = \"" + marker + "\"\n"},
		{name: "другое правило", src: strings.Replace(injected, "G101", "G304", 1)},
		{name: "номер упомянут в обосновании", src: strings.Replace(injected, marker, "#nosec G304 -- G101", 1)},
	} {
		t.Run(tc.name, func(t *testing.T) {
			census, err := check.ScanG101Suppressions("internal/sample.go", []byte(tc.src))
			if err != nil {
				t.Fatal(err)
			}
			if census.Files != 1 || census.Lines == 0 {
				t.Fatalf("утрачен объём осмотренного: %+v", census)
			}
			verdict := census.Judge()
			if tc.line == "" {
				if verdict != nil {
					t.Fatal(verdict)
				}
			} else if verdict == nil || !strings.Contains(verdict.Error(), tc.line) || len(census.Sites) != 1 {
				t.Fatalf("инъекция должна дать одну координату %s: %+v, %v", tc.line, census, verdict)
			}
		})
	}
}

func TestG101SuppressionGateRejectsZeroScope(t *testing.T) {
	t.Parallel()
	for _, rel := range []string{"pkg/api/generated.go", "docs/example.txt"} {
		census, err := check.ScanG101Suppressions(rel, []byte("не Go"))
		if err != nil {
			t.Fatal(err)
		}
		if census.Files != 0 || census.Judge() == nil {
			t.Fatalf("исключённый файл не должен зеленить пустой обход: %s: %+v", rel, census)
		}
	}
	if err := (check.G101SuppressionCensus{}).Judge(); err == nil || !strings.Contains(err.Error(), "0 файлов") {
		t.Fatalf("нулевая перепись должна отказать: %v", err)
	}
	if _, err := check.ScanG101Suppressions("internal/broken.go", []byte("не Go")); err == nil {
		t.Fatal("неразобранный исходник нельзя считать осмотренным")
	}
}
