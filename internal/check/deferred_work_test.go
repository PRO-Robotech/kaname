// TestNoDeferredWorkInTheTree — в дереве нет маркеров отложенной работы.
//
// Имя сохранено дословно с монорепо: четыре приёмки службы называют держателем
// ban #11 именно его, и переименование сделало бы эти координаты ложными молча.
//
// Что делать, если гейт сработал, — три исхода, четвёртого нет:
//
//  1. работа нужна → сделать её СЕЙЧАС, в том же изменении. Правила продукта
//     не знают состояния «сделаю в следующем PR»;
//  2. работа не нужна → снять маркер вместе с кодом, который он подпирал;
//  3. работа принадлежит другому предмету и требует решения → завести ПРЕДМЕТ
//     (issue/приёмку) с причиной и предикатом снятия, а в коде не оставлять
//     обещания. Маркер отличается от предмета тем, что за ним никто не отвечает.
//
// Завести запись в перечень прощённых — НЕ исход: перечня нет, и заводить его
// ядро правил запрещает прямо.
func TestNoDeferredWorkInTheTree(t *testing.T) {
	t.Parallel()

	// Обход — по корню МОДУЛЯ службы. В самостоятельном клоне соседей нет
	// вовсе, а дерево платформы этому модулю не принадлежит: судить его отсюда
	// значило бы краснеть на чужом.
	wd, err := os.Getwd()
	if err != nil {
		t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: рабочий каталог не установлен: %v", err)
	}
	root, err := platformtree.ModuleRootFrom(wd)
	if err != nil {
		t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: корень модуля не найден: %v", err)
	}

	findings, census, err := check.AuditDeferredWork(root)
	if err != nil {
		t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: обход дерева не состоялся: %v", err)
	}

	t.Logf("%s; находок %d", census, len(findings))

	if census.Read == 0 {
		t.Fatal("не прочитано ни одного файла — «маркеров нет» здесь означало бы " +
			"«ничего не читал», а не чистое дерево")
	}
	if len(census.Roots) == 0 {
		t.Fatal("верхний уровень индекса пуст — область обхода выведена из ничего, " +
			"и её покрытие ничего не утверждает")
	}
	// Вид вычитания, которому больше нечего вычитать, — находка: под его именем
	// можно положить что угодно, и счёт не сдвинется.
	for _, s := range check.DeferralSkips() {
		if census.Skipped[s.Name] == 0 {
			t.Errorf("вид вычитания %q не вычел НИ ОДНОГО файла — у него больше нет "+
				"предмета (заведён потому, что %s). Снимите вид вместе с предметом: "+
				"оставленный, он остаётся слепой зоной, в которую можно внести "+
				"отсрочку незамеченной", s.Name, s.Why)
		}
	}

	for _, f := range findings {
		t.Errorf("отложенная работа: %s — %q\n"+
			"Правила продукта не знают состояния «сделаю позже» (ban #11, ban #14): "+
			"работа делается сразу в production-форме. Исходы: сделать сейчас / снять "+
			"вместе с кодом / завести ПРЕДМЕТ с причиной и предикатом снятия. Маркер "+
			"отличается от предмета тем, что за ним никто не отвечает — и он переживает "+
			"своё основание", f.Where, f.Line)
	}
}

// TestEveryDeferralFormIsCaughtThroughTheSieve — КАЖДАЯ объявленная форма
// доходит до решения, пройдя СВЯЗКУ ЭТОГО ДЕРЕВА: отсев, образец и виды
// вычитания вместе.
//
// Словарь форм и отсев принадлежат фундаменту, и он же доказывает, что форма
// проходит его собственное сито. Здесь утверждается ДРУГОЕ и о другом предмете:
// что ни один вид вычитания ЭТОГО дерева не ослепляет объявленную форму.
// Фундамент такого сказать не может — видов этого дерева он не знает, а
// заведённый завтра вид, накрывший прод-каталог, снял бы формы с наблюдения
// молча: не находкой и не чистотой, а невидимостью.
//
// Поэтому каждая форма гонится тем же check.AuditDeferredWork, что работает по
// дереву, а не образцом в отрыве от сита и не в отрыве от вычитания.
func TestEveryDeferralFormIsCaughtThroughTheSieve(t *testing.T) {
	t.Parallel()
	forms := treehygiene.DeferralForms()
	if len(forms) == 0 {
		t.Fatal("осмотрено: форм 0 — «все формы ловятся» здесь означало бы «форм нет»")
	}
	for i, f := range forms {
		t.Run(fmt.Sprintf("%02d-%s", i, f.Seed), func(t *testing.T) {
			if !treehygiene.HasDeferralSeed(f.Example) {
				t.Fatalf("затравка %q не встречается в примере %q — отсев отсечёт эту "+
					"форму ДО образца, и она перестанет ловиться, оставаясь на вид "+
					"объявленной", f.Seed, f.Example)
			}
			root := synthDeferralTree(t, map[string]string{
				"internal/thing/thing.go": "package thing\n\n" + f.Example + "\nfunc F() {}\n",
			})
			findings, census, err := check.AuditDeferredWork(root)
			if err != nil {
				t.Fatalf("обход синтетического дерева: %v", err)
			}
			if census.Read == 0 {
				t.Fatal("синтетическое дерево не прочитано")
			}
			if len(findings) != 1 {
				t.Fatalf("форма %q на примере %q не поймана сквозным путём: %+v",
					f.Pattern, f.Example, findings)
			}
		})
	}
	t.Logf("осмотрено: форм %d, затравок %d", len(forms), len(treehygiene.DeferralSeeds()))
}
