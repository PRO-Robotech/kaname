// predecessorRepos — ЕДИНСТВЕННЫЙ держатель факта «у службы есть предшественники».
// Документы приёмки и архитектуры переехали сюда вместе со службой, и замеры в них
// снимались ДО разъезда: их предикаты называют пути `services/iam/**` и гейты
// `internal/repohygiene`, которых в этом дереве не существует.
//
// ПРЕДШЕСТВЕННИКОВ ДВА, А НЕ ОДИН, И ЭТО ЗАМЕР, А НЕ ДОПУЩЕНИЕ. Прежняя редакция
// объявляла один и потому выразить вторую половину корпуса не могла ВООБЩЕ:
// перепись по стволу дала 35 неквалифицированных хешей на строках датировки,
// из них 30 резолвятся в монорепо продукта и 5 — в воркспейсе; в СВОЁМ дереве не
// резолвится ни один. Пять воркспейсных замеров называют свой дом прозой
// («Ревизия измерения (воркспейс)»), то есть автор дом ЗНАЛ, а записать его
// объявленной формой было нечем — гейт принял бы только одно имя.
//
// ПОЧЕМУ ЭТО НЕ ВЕДОМОСТЬ ПРОЩЁННЫХ. Здесь объявлены РЕПОЗИТОРИИ, а не ревизии:
// перечень конечен, не растёт с каждым переехавшим документом и истекает сам —
// перемерят документ на этом дереве, квалификация уйдёт вместе с чужим хешем.
// Ведомость по хешу росла бы вечно и не истекла бы никогда.
var predecessorRepos = map[string]string{
	"PRO-Robotech/kacho": "монорепо продукта: служба жила в нём каталогом " +
		"`services/iam`, и туда же указывают предикаты её замеров",
	"PRO-Robotech/kacho-workspace": "воркспейс: корпус правил, приёмки и записки; " +
		"замеры по текстам правил снимались там",
}

// predecessorNames — имена предшественников в устойчивом порядке, для текста
// находки. Собираются ИЗ объявления выше, а не выписываются вторым местом.
func predecessorNames() string {
	names := make([]string, 0, len(predecessorRepos))
	for name := range predecessorRepos {
		names = append(names, name)
	}
	sort.Strings(names)
	return strings.Join(names, " либо ")
}

// predecessorForms — те же имена, показанные ФОРМОЙ записи. Находка обязана
// говорить не только «куда можно», но и «как пишется»: текст, называющий причину
// и не называющий действия, посылает читателя гадать.
func predecessorForms() string {
	names := make([]string, 0, len(predecessorRepos))
	for name := range predecessorRepos {
		names = append(names, "`"+name+"@<хеш>`")
	}
	sort.Strings(names)
	return strings.Join(names, " либо ")
}

// reDatingMarker — ОБЪЯВЛЕНИЕ замера, а не упоминание слова.
//
// Судится начало строки (допускаются знак цитаты, маркер списка и жирное
// начертание), потому что объявление замера в этом корпусе всегда ОТКРЫВАЕТ
// строку. Знак `>` больше не выводит строку из-под суда: выноска — обычная форма
// этого корпуса, и объявление внутри неё остаётся объявлением.
// ФОРМ ОБЪЯВЛЕНИЯ ТРИ, И ПЕРЕЧЕНЬ НАЗВАН ЧИСЛОМ. Форма, о которой распознаватель
// не знает, даёт не красное и не зелёное, а МОЛЧАНИЕ: всё записанное ею вне
// наблюдения, и слепая зона сама себя расширяет — чем больше документов
// переезжает второй формой, тем шире она становится.
//
// Цена измерена на стволе: первая форма открывает 5 строк, вторая — 39, третья —
// 2. То есть распознаватель, знавший одну форму, видел ОДНУ ВОСЬМУЮ корпуса
// датировок и об остальных семи восьмых молчал.
//
// Перепись печатает величину ПО КАЖДОЙ форме отдельно. Одно суммарное число
// скрывает ровно тот случай, ради которого расширение делается: полоса прежней
// формы не изменилась, а перепись выросла — значит прибавка была слепой зоной,
// а не регрессией дерева.
var datingPhrases = []string{
	"Замер на ревизии",
	"Ревизия измерения",
	"Ревизия замера",
}

const datingLineOpen = `(?m)^[ \t]*(?:>[ \t]*)*(?:[*+\-][ \t]+|\d+\.[ \t]+)?\*{0,2}`

// reDatingLine — СТРОКА, ОТКРЫВАЮЩАЯ объявление. Само объявление собирается
// вместе с продолжением — см. `datingDeclarations`.
// reListItem — новый пункт списка: он закрывает продолжение предыдущего.
var reListItem = regexp.MustCompile(`^[ \t]*(?:[*+\-][ \t]+|\d+\.[ \t]+)`)

var reDatingLine = regexp.MustCompile(
	datingLineOpen + `(?:` + strings.Join(datingPhrases, "|") + `)`)

// datingDeclarations — ОБЪЯВЛЕНИЯ датировки целиком, вместе с продолжением.
//
// ЕДИНИЦА — ОБЪЯВЛЕНИЕ, А НЕ СТРОКА, и это исправление СЛЕПОЙ ЗОНЫ, а не
// придирка. Проза корпуса переносится по ширине, поэтому хеш законно уезжает на
// следующую строку. Прежняя редакция судила ровно одну строку и объявляла такое
// объявление САМОССЫЛКОЙ — то есть находкой там, где ревизия названа и названа
// проверяемо. На стволе таких мест было ЧЕТЫРЕ из сорока шести, и все четыре
// были ложными находками.
//
// Правка НЕ в документах: требовать не переносить строку значило бы подгонять
// документ под инструмент. Правка в единице счёта.
//
// ПРОДОЛЖЕНИЕ КОНЧАЕТСЯ ПУСТОЙ СТРОКОЙ, заголовком, оградой, НОВЫМ объявлением
// либо НОВЫМ ПУНКТОМ СПИСКА. Граница названа явно, а не «сколько-нибудь строк»:
// без пункта списка объявление затягивало соседние пункты целиком и цитировало
// в находке ЧУЖОЙ хеш — измерено на стволе, находка занимала экран и называла
// ревизию, к объявлению не относящуюся. Диагностика здесь часть свойства.
func datingDeclarations(body string) []string {
	lines := strings.Split(body, "\n")
	var out []string
	for i := 0; i < len(lines); i++ {
		if !reDatingLine.MatchString(lines[i]) {
			continue
		}
		decl := []string{lines[i]}
		for j := i + 1; j < len(lines); j++ {
			nxt := strings.TrimSpace(lines[j])
			if nxt == "" || strings.HasPrefix(nxt, "#") ||
				strings.HasPrefix(nxt, "```") || reDatingLine.MatchString(lines[j]) ||
				reListItem.MatchString(lines[j]) {
				break
			}
			decl = append(decl, lines[j])
			i = j
		}
		out = append(out, strings.Join(decl, " "))
	}
	return out
}

// formOf — какой из объявленных форм принадлежит найденная строка. Читается ТА
// ЖЕ строка, что судится, поэтому перепись и суд не могут разойтись.
func formOf(line string) string {
	for _, phrase := range datingPhrases {
		if regexp.MustCompile(datingLineOpen + regexp.QuoteMeta(phrase)).MatchString(line) {
			return phrase
		}
	}
	return "<форма не опознана>"
}

// reQuotedMarker — тот же оборот, взятый в ЯВНЫЕ кавычки-ёлочки: разговор о
// форме, а не объявление. Величина переписи, не находка. Обороты — те же три:
// проза о ЛЮБОЙ из форм остаётся прозой.
var reQuotedMarker = regexp.MustCompile(
	`(?i)«[^»\n]*(?:` + strings.ToLower(strings.Join(datingPhrases, "|")) + `)`)

// reInlineHash — ревизия ЭТОЙ истории: хеш в обратных кавычках.
var reInlineHash = regexp.MustCompile("`([0-9a-f]{7,40})`")

// reForeignHash — ревизия ЧУЖОЙ истории, названная ВМЕСТЕ С НЕЙ:
// `<владелец>/<репозиторий>@<хеш>`.
//
// Образцы непересекающиеся by construction: у квалифицированной формы сразу за
// открывающей кавычкой стоит имя владельца, а не шестнадцатеричный разряд, поэтому
// `reInlineHash` её не видит — и наоборот. Держит это не эта строка, а проба-близнец
// (`...CountsAnInheritedDatingSeparately`), утверждающая `dated == 0` на корпусе, где
// все датировки квалифицированы.
var reForeignHash = regexp.MustCompile(
	"`([A-Za-z0-9][A-Za-z0-9._-]*/[A-Za-z0-9][A-Za-z0-9._-]*)@([0-9a-f]{7,40})`")

// datingCensus — объём осмотренного. Печатается всегда: «ноль находок» обязано
// быть отличимо от «ноль прочитанного».
type datingCensus struct {
	docsRead         int            // файлов документации прочитано
	markers          int            // объявлений замера найдено — всего
	byForm           map[string]int // …и ПО КАЖДОЙ форме отдельно
	dated            int            // из них датированы хешем ЭТОЙ истории
	inherited        int            // датированы ревизией предшественника — квалифицированной цитатой
	undated          int            // из них датированы самоссылкой
	foreign          int            // хеш РЕЗОЛВИТСЯ, но в историю дерева не входит
	absent           int            // хеш не резолвится вовсе, притом что история дерева — наша
	quoted           int            // оборот процитирован прозой — не замер
	ledgerEntries    int            // записей ведомости
	ledgerApplied    int            // записей, которым было что прощать
	ancestryUnjudged int            // «НЕ ВЫПОЛНИЛОСЬ»: вердикт о предке не выносился
}

// ancestryVerdict — исход вопроса «входит ли ревизия в историю дерева».
// Третье состояние обязательно: недоступность истории не есть «да».
type ancestryVerdict int

const (
	ancestryNo       ancestryVerdict = iota // РЕЗОЛВИТСЯ, но не предок — находка
	ancestryYes                             // предок — законно
	ancestryUnjudged                        // не выполнилось: истории нет или она усечена
	ancestryAbsent                          // не резолвится вовсе, а история дерева — наша
)

// auditMeasurementDating — чистое ядро обеих проб: решает по текстам, а не по
// дереву. Ключ ведомости — имя файла, значение — причина с номером задачи.
func auditMeasurementDating(
	docs map[string]string,
	ledger map[string]string,
	ancestry func(hash string) ancestryVerdict,
) ([]string, datingCensus) {
	var findings []string
	c := datingCensus{docsRead: len(docs), ledgerEntries: len(ledger),
		byForm: map[string]int{}}
	// Каждая объявленная форма получает ключ ДО обхода: форма, которой в корпусе
	// нет, обязана печататься нулём, а не исчезать из переписи. Исчезнувшая
	// строка неотличима от строки, которую никто не искал.
	for _, phrase := range datingPhrases {
		c.byForm[phrase] = 0
	}
	forgiven := map[string]bool{}

	names := make([]string, 0, len(docs))
	for name := range docs {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		body := docs[name]
		c.quoted += len(reQuotedMarker.FindAllString(body, -1))

		for _, line := range datingDeclarations(body) {
			c.markers++
			c.byForm[formOf(line)]++

			// Датировкой считается ЛЕВАЯ цитата: объявление датирует то, что стоит
			// сразу за оборотом, а не то, что помянуто дальше по строке.
			bare := reInlineHash.FindStringSubmatchIndex(line)
			qual := reForeignHash.FindStringSubmatchIndex(line)

			switch {
			case qual != nil && (bare == nil || qual[0] < bare[0]):
				repo, hash := line[qual[2]:qual[3]], line[qual[4]:qual[5]]
				if _, declared := predecessorRepos[repo]; !declared {
					findings = append(findings, fmt.Sprintf(
						"НЕОБЪЯВЛЕННАЯ ИСТОРИЯ: %s датирует замер ревизией %s репозитория %s, который "+
							"предшественником этой службы НЕ объявлен — перемерить число негде, а имя "+
							"репозитория само по себе ничего не обещает (%q)",
						name, hash, repo, strings.TrimSpace(line)))
					continue
				}
				// История предшественника здесь не лежит и лечь не может: своё дерево
				// об этой ревизии НЕ спрашивается — спрашивать бессмысленно.
				c.inherited++

			case bare != nil:
				hash := line[bare[2]:bare[3]]
				c.dated++
				switch ancestry(hash) {
				case ancestryNo:
					c.foreign++
					findings = append(findings, fmt.Sprintf(
						"ЧУЖАЯ ЛИНИЯ: %s датирует замер ревизией %s, которая РЕЗОЛВИТСЯ, но в историю этого "+
							"дерева не входит — числа верны для дерева, которого здесь нет (%q)",
						name, hash, strings.TrimSpace(line)))
				case ancestryAbsent:
					c.absent++
					findings = append(findings, fmt.Sprintf(
						"РЕВИЗИИ НЕТ В ЭТОЙ ИСТОРИИ: %s датирует замер ревизией %s, которая в этом дереве "+
							"НЕ РЕЗОЛВИТСЯ ВОВСЕ. Историю службы дерево несёт, значит это описка в хеше либо "+
							"снятая линия. Замер, снятый в истории предшественника, записывается формой "+
							"%s — тогда читателю сказано, ГДЕ число перемерить (%q)",
						name, hash, predecessorForms(), strings.TrimSpace(line)))
				case ancestryUnjudged:
					c.ancestryUnjudged++
				case ancestryYes:
				}

			default:
				c.undated++
				if _, ok := ledger[name]; ok {
					forgiven[name] = true
					continue
				}
				findings = append(findings, fmt.Sprintf(
					"САМОССЫЛКА: %s датирует замер без хеша (%q) — восстановить ревизию можно только "+
						"раскопками по истории, то есть дороже, чем стоит проверка числа",
					name, strings.TrimSpace(line)))
			}
		}
	}

	ledgerNames := make([]string, 0, len(ledger))
	for name := range ledger {
		ledgerNames = append(ledgerNames, name)
	}
	sort.Strings(ledgerNames)
	for _, name := range ledgerNames {
		if forgiven[name] {
			c.ledgerApplied++
			continue
		}
		findings = append(findings, fmt.Sprintf(
			"ВЕДОМОСТИ НЕЧЕГО ПРОЩАТЬ: запись про %s (%s) пережила свой предмет — "+
				"недатированного замера в этом документе больше нет, запись снимается",
			name, ledger[name]))
	}
	return findings, c
}

