// readMarkdownTree читает дерево документации целиком.
//
// Состав берётся ИЗ ИНДЕКСА git (`treecorpus`), а не обходом диска: обход читал
// бы игнорируемое — распаковки, отчёты прогонов, рабочие копии, — и вердикт стал
// бы свойством рабочего каталога, а не коммита. Тот же вызов отказывает на
// кешируемом прогоне: состав дерева берётся подпроцессом, и `go test` о нём не
// знает, поэтому над красным деревом печаталось бы `ok (cached)`.
func readMarkdownTree(t *testing.T, docsDir string) map[string]string {
	t.Helper()
	paths, err := treecorpus.UnderWithSuffix(docsDir, ".md")
	require.NoError(t, err)

	out := map[string]string{}
	for _, path := range paths {
		raw, readErr := os.ReadFile(path) // #nosec G304 -- путь пришёл из индекса git собственного каталога документации
		require.NoError(t, readErr)
		rel, relErr := filepath.Rel(docsDir, path)
		require.NoError(t, relErr)
		out[filepath.ToSlash(rel)] = string(raw)
	}
	return out
}

// gitAncestry — годный предикат: ВХОЖДЕНИЕ В ИСТОРИЮ, а не резолв объекта.
//
// # ПОЧЕМУ УСЕЧЁННАЯ ИСТОРИЯ НЕ ПРОСТО ВЫКЛЮЧАЕТ ПОЛОВИНУ
//
// Неполный клон делает `merge-base` лжецом ТОЛЬКО В ОДНУ СТОРОНУ: ответ «предок»
// он даёт, найдя путь, и путь этот настоящий; ответ «не предок» на усечённой
// истории бывает ложным — путь мог остаться за границей выборки.
//
// Поэтому «не предок» принимается за вердикт лишь тогда, когда он ДОКАЗУЕМ:
// коммит МОЛОЖЕ границы усечения, значит весь путь от него до HEAD целиком
// внутри выбранного куска, и его отсутствие — факт, а не следствие усечения.
// Во всех прочих положениях исход — НЕ ВЫПОЛНИЛОСЬ, и он не вычитается из
// вердикта и не зачитывается в успех.
// historyRoot — корень истории, которую дерево обязано нести, чтобы вердикт об
// ОТСУТСТВУЮЩЕЙ ревизии выносился. Принимается ПАРАМЕТРОМ, а не читается из
// константы: иначе эту ось нельзя подать синтетическому дереву, и она осталась бы
// без доказательства падучести — ровно то состояние, в котором она и была. Держатель
// факта при этом один: `serviceHistoryRoot`, названный в единственной точке вызова.
func gitAncestry(t *testing.T, root, historyRoot, trunkRef string) func(string) ancestryVerdict {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Logf("git недоступен — половина «предок» НЕ ВЫПОЛНЯЛАСЬ")
		return func(string) ancestryVerdict { return ancestryUnjudged }
	}
	// Вызов идёт через общий помощник, а НЕ через exec.Command напрямую:
	// `cmd.Dir` не выбирает репозиторий, когда в окружении есть GIT_DIR —
	// переменная сильнее рабочего каталога, и проба писала бы в чужую копию.
	git := func(args ...string) (string, error) {
		out, err := gitenv.Command(root, args...).Output()
		return strings.TrimSpace(string(out)), err
	}
	shallowOut, err := git("rev-parse", "--is-shallow-repository")
	if err != nil {
		t.Logf("история недоступна — половина «предок» НЕ ВЫПОЛНЯЛАСЬ")
		return func(string) ancestryVerdict { return ancestryUnjudged }
	}
	shallow := shallowOut == "true"

	// boundary — время самой старой доступной точки истории.
	var boundary string
	if shallow {
		roots, rootsErr := git("rev-list", "--max-parents=0", "HEAD")
		if rootsErr != nil || roots == "" {
			t.Logf("граница усечения не определяется — половина «предок» НЕ ВЫПОЛНЯЛАСЬ")
			return func(string) ancestryVerdict { return ancestryUnjudged }
		}
		boundary, _ = git("show", "-s", "--format=%ct", strings.Fields(roots)[0])
		t.Logf("история УСЕЧЕНА: «не предок» принимается только для ревизий моложе границы (%s)", boundary)
	}

	// НЕСЁТ ЛИ ДЕРЕВО ИСТОРИЮ ЭТОЙ СЛУЖБЫ — вопрос задаётся ОДИН раз, ДЕРЕВУ, и от
	// корпуса документов не зависит вовсе.
	//
	// Поставка модуля историю НЕ несёт: `git archive` отдаёт состав коммита, и у
	// арендатора получается свежий репозиторий. В нём не резолвится ни одна ревизия
	// этой истории — не потому, что документы врут, а потому что судить не в чем.
	// Прежняя редакция отвечала на это «не предок», и каждый замер становился
	// находкой у КАЖДОГО, кто склонирует.
	//
	// Прежний сторож спрашивал об этом КОРПУС («знает ли дерево хоть одну названную
	// ревизию») и потому вооружался от того, случилось ли какому-нибудь документу
	// помянуть свой хеш где угодно; см. шапку файла. Здесь спрашивается объявленный
	// корень истории — факт с одним держателем, неизменяемый by construction.
	//
	// Вопрос задаётся ТОЛЬКО на полной истории: на усечённой корень недостижим by
	// construction, и там отсутствие объекта по-прежнему даёт третий исход, а не
	// «истории нет». Так новое различение ничего не отнимает у усечённой посадки.
	// СУДИМАЯ ВЕРШИНА — СТВОЛ, А НЕ `HEAD`, и это несущее различие.
	//
	// Здесь вливают СХЛОПЫВАНИЕМ: коммит ветки предком ствола не становится
	// никогда. Пока вершиной был `HEAD`, гейт отвечал о ДВУХ РАЗНЫХ деревьях —
	// на запросе слияния `HEAD` есть merge-ревизия, и хеш полосы ей предок, а
	// после посадки тот же хеш предком уже не является. Один и тот же документ
	// получал зелёное до вливания и красное после, причём второго вердикта никто
	// не читал: на стволе краснел процесс, чей исход не смотрят.
	//
	// Цена измерена, а не предположена: ствол службы был красен по этой пробе
	// ДВА вливания подряд (`ba43277c`, `c56218b6`), и оба запроса слияния несли
	// зелёный обязательный контекст.
	//
	// Судя по стволу, гейт даёт ОДИН вердикт до и после посадки — то есть говорит
	// о том дереве, в которое работа и едет. Ствол недостижим (клон без ссылки на
	// origin, выгрузка) — вершиной остаётся `HEAD`, и перепись называет это прямо:
	// молчание о подмене вершины было бы тем же классом, что молчание о пропуске.
	trunk := "HEAD"
	if _, e := git("rev-parse", "--verify", trunkRef+"^{commit}"); e == nil {
		trunk = trunkRef
	} else {
		t.Logf("ствол %s в этом дереве не разрешается — вершиной взят HEAD: "+
			"вердикт относится к ветке, а не к стволу, в который она едет", trunkRef)
	}

	carriesOwnHistory := false
	if !shallow {
		if _, e := git("merge-base", "--is-ancestor", historyRoot, trunk); e == nil {
			carriesOwnHistory = true
		} else {
			t.Logf("дерево НЕ несёт объявленную историю (корень %s предком HEAD не является) — "+
				"вердикт об ОТСУТСТВУЮЩЕЙ ревизии НЕ ВЫНОСИТСЯ: поставка модуля историю не несёт",
				historyRoot)
		}
	}

	return func(hash string) ancestryVerdict {
		if _, e := git("cat-file", "-e", hash+"^{commit}"); e != nil {
			if shallow || !carriesOwnHistory {
				// Объекта нет, и сказать почему нечем: на усечённой истории это
				// неотличимо от «не довезли», в поставке — от «истории здесь нет».
				return ancestryUnjudged
			}
			return ancestryAbsent
		}
		if _, e := git("merge-base", "--is-ancestor", hash, trunk); e == nil {
			return ancestryYes
		}
		if !shallow {
			return ancestryNo
		}
		when, e := git("show", "-s", "--format=%ct", hash)
		if e != nil || boundary == "" || len(when) < len(boundary) ||
			(len(when) == len(boundary) && when <= boundary) {
			return ancestryUnjudged
		}
		return ancestryNo
	}
}

// TestMeasurementRevisionsAreDatedByHashAndBelongToThisHistory — несущее утверждение.
func TestMeasurementRevisionsAreDatedByHashAndBelongToThisHistory(t *testing.T) {
	root := monorepoRoot(t)
	docs := readMarkdownTree(t, platformtree.RequirePath(t, iamDocsRelDir))

	require.NotZerof(t, len(docs), "обход документации пуст — вердикт беспредметен (%s)", iamDocsRelDir)

	// Перечень названных ревизий здесь БОЛЬШЕ НЕ СОБИРАЕТСЯ: предпосылкой половины
	// «предок» служит свойство ДЕРЕВА, а не корпуса (см. шапку `gitAncestry`).
	findings, c := auditMeasurementDating(docs, datingLedger(), gitAncestry(t, root, serviceHistoryRoot, serviceTrunkRef))

	forms := make([]string, 0, len(c.byForm))
	for _, phrase := range datingPhrases {
		forms = append(forms, fmt.Sprintf("%s %d", phrase, c.byForm[phrase]))
	}
	if unknown := c.byForm["<форма не опознана>"]; unknown > 0 {
		forms = append(forms, fmt.Sprintf("<форма не опознана> %d", unknown))
	}
	t.Logf("перепись по формам объявления (%d): %s", len(datingPhrases), strings.Join(forms, " · "))

	t.Logf("перепись: документов прочитано %d · объявлений замера %d · датировано хешем %d · "+
		"ревизией предшественника %d · самоссылкой %d · чужой линией %d · отсутствует в истории %d · "+
		"процитировано прозой %d · записей ведомости %d (применено %d) · "+
		"вердикт о предке НЕ ВЫНОСИЛСЯ %d · находок %d",
		c.docsRead, c.markers, c.dated, c.inherited, c.undated, c.foreign, c.absent, c.quoted,
		c.ledgerEntries, c.ledgerApplied, c.ancestryUnjudged, len(findings))

	require.NotZerof(t, c.markers,
		"объявлений замера не найдено ни одного — отрицания гейта стали вакуумными: "+
			"либо корпус сменил форму датировки, либо образец её больше не узнаёт")

	require.Emptyf(t, findings,
		"датировка чисел в документации iam негодна:\n%s", strings.Join(findings, "\n"))
}
