// Число, датированное САМОССЫЛКОЙ, проверить нельзя; ревизия, проверенная
// РЕЗОЛВОМ, проверена негодно. Гейт задачи #1805.
//
// # ДВЕ ПОЛОВИНЫ, И НИ ОДНА НЕ ВЫВОДИТСЯ ИЗ ДРУГОЙ
//
//   - «датировано» — у объявленного замера названа ревизия ХЕШЕМ. Оборот «замер
//     на ревизии записи» ревизии не называет: восстановить её можно только
//     раскопками по истории (`git log -S`), то есть дороже, чем стоит сама
//     проверка;
//   - «датировано ГОДНО» — названный хеш ВХОДИТ В ИСТОРИЮ этого дерева. Предикат
//     «резолвится ли ревизия» на этот вопрос НЕ отвечает: у рабочих копий одного
//     клона общая база объектов, поэтому `git cat-file -t` говорит «да» о
//     коммите ЧУЖОЙ линии. Здесь это не гипотеза: §19 датировали хешем
//     `ee2370e18`, он резолвится и предком этой линии НЕ ЯВЛЯЕТСЯ — сюда его
//     содержимое приехало схлопыванием, под другим хешем.
//
// # ЧТО ГЕЙТ НЕ СУДИТ — НАЗВАНО, ЧТОБЫ ЕГО НЕ ЧИТАЛИ ШИРЕ
//
//   - ИСТИННОСТЬ самих чисел. Перемерить произвольный предикат из прозы машинно
//     нельзя; гейт держит ДАТИРОВКУ — то есть возможность перемерить;
//   - ПРОЗУ О ФОРМЕ. Оборот, взятый в кавычки-ёлочки («замер на ревизии»),
//     замером не является: проверка, краснеющая на собственном объяснении, —
//     ровно тот класс, который здесь и ловится. Такие вхождения считаются
//     отдельной величиной переписи, а не находкой.
//
// # ЧЕМ ПРОЗА ОТЛИЧАЕТСЯ ОТ ОБЪЯВЛЕНИЯ — КАВЫЧКАМИ, А НЕ БЛОКОМ ЦИТАТЫ
//
// Прежняя редакция считала прозой ВСЯКУЮ строку, открытую знаком `>`, и это была
// СЛЕПАЯ ЗОНА, а не решение: выноска (`> [!note]`) — обычная форма этого корпуса,
// и объявление замера внутри неё уходило в счётчик `quoted` вместо суда.
//
// Цена измерена, а не предположена. На ревизии ствола `2171a6690a` прогон печатал
// «объявлений замера 4 · процитировано прозой 3 · находок 2», и среди этих трёх
// «цитат» пряталось НАСТОЯЩЕЕ объявление: приёмка ролей манифеста датировала
// замер ревизией `ebd6122895`, в историю ствола не входящей. То есть находка того
// самого класса, ради которого гейт заведён, была невидима ВНУТРИ него — не
// красное и не зелёное, а отсутствие вопроса. Расширение сместило ровно её:
// объявлений 4 → 5, прозы 3 → 2; полоса прежней формы не изменилась.
//
// Поэтому разделяет теперь ЯВНАЯ ЦИТАТА (ёлочки), а не членство в блоке: строка,
// которая ОТКРЫВАЕТСЯ оборотом, есть объявление, где бы она ни стояла. Способность
// образца видеть новую форму и молчать на её законном близнеце держат три пробы
// рядом (`...IsSilentOnALawfulCalloutDeclaration`, `...RedsOnAForeignRevisionInsideACallout`,
// `...IsSilentOnProseInsideACallout`), а не эта строка.
//
// # ВЕДОМОСТЬ И ЕЁ САМОИСТЕЧЕНИЕ
//
// Два документа приёмки несут недатированный замер и здесь НЕ правятся: на их
// тексте стоит вердикт рецензента, и правка идёт своим заходом (задача названа в
// причине). Ведомость прощает им ТОЛЬКО отсутствие даты и самоистекает: запись,
// которой больше нечего прощать, — находка, а не тишина.
//
// # ПОЛОЖЕНИЙ У ХЕША ЧЕТЫРЕ, А НЕ ДВА, И ОДНО ИЗ НИХ ПРО ДЕРЕВО, А НЕ ПРО ХЕШ
//
// Прежняя редакция знала два — «предок» и «не предок» — и сваливала во второе всё,
// что не резолвится ВОВСЕ, печатая при этом «которая РЕЗОЛВИТСЯ». Читатель, пошедший
// за текстом, сверял предка вместо того, чтобы увидеть ЧУЖОЙ РЕПОЗИТОРИЙ. Диагностика
// здесь часть свойства, а не украшение: находка, называющая ложную причину, посылает
// искать не там, на неё тратят прогон, а потом снимают гейт как непонятный.
//
// После разъезда репозиториев историй ДВЕ — своя и предшественника, — и документ,
// переехавший вместе со службой, законно датирован ревизией, которой в этом дереве
// нет и не будет. Поэтому:
//
//	резолвится и предок           → законно;
//	резолвится и НЕ предок        → находка: чужая ЛИНИЯ той же истории;
//	не резолвится, история НАША   → находка: такой точки в этой истории нет вовсе
//	                                (описка в хеше либо снятая линия);
//	не резолвится, истории НЕТ    → ВЕРДИКТ НЕ ВЫНОСИТСЯ — объявленная граница.
//
// # ЧЕМ ЗАМЕНЁН ПРЕЖНИЙ СТОРОЖ И ПОЧЕМУ ОН БЫЛ НЕГОДЕН
//
// Прежний сторож спрашивал КОРПУС: знает ли дерево хоть одну из названных в документах
// ревизий. Из «знает одну» выводилось «история одна» — вывод, недействительный by
// construction, когда историй две. Наблюдались оба следствия:
//
//   - на стволе службы названо 188 уникальных ревизий, и не резолвится НИ ОДНА, поэтому
//     вердикт не выносился вовсе — пять датировок ревизиями предшественника были
//     невидимы: не красное и не зелёное, а отсутствие вопроса. Предикат числа (единица
//     счёта — УНИКАЛЬНЫЙ хеш в обратных кавычках, вхождений было 603):
//
//	git ls-tree -r origin/main --name-only -- docs | grep '\.md$' |
//	  while read -r f; do git show "origin/main:$f"; done |
//	  grep -oE '`[0-9a-f]{7,40}`' | tr -d '`' | sort -u | wc -l
//   - ветка `issue-2554` помянула в ПРОЗЕ одного документа ревизию этого дерева —
//     единственную резолвящуюся во всём корпусе, — и сторож перевернулся. То есть
//     ВООРУЖЁННОСТЬ гейта зависела от того, случилось ли какому-нибудь документу
//     назвать свой хеш где угодно и в каком угодно смысле.
//
// Теперь вопрос задаётся ДЕРЕВУ и от корпуса не зависит вовсе: несёт ли оно объявленную
// историю этой службы (`serviceHistoryRoot` — предок HEAD). Поставка модуля
// (`git archive` → свежий репозиторий) её не несёт при ЛЮБОМ числе собственных
// коммитов; клон несёт. Ось вооружённости и ось суда совпали.
//
// # ИСТОРИЯ ПРЕДШЕСТВЕННИКА — ОБЪЯВЛЕННЫЙ ФАКТ С ОДНИМ ДЕРЖАТЕЛЕМ
//
// Ведомость прощения ПО ХЕШУ здесь не заводится: она не истекла бы никогда и росла бы
// с каждым переехавшим документом. Вместо неё — требование к самой ЦИТАТЕ: замер,
// снятый в чужой истории, называет её ВМЕСТЕ С РЕВИЗИЕЙ, формой
// `<владелец>/<репозиторий>@<хеш>`. Тогда читателю сказано, ГДЕ число перемерить, то
// есть исполнено ровно то, ради чего гейт существует, — а своё дерево об этой ревизии
// не спрашивается, потому что спрашивать бессмысленно.
//
// Предшественник объявлен ОДИН (`predecessorRepo`): цитата, называющая другой
// репозиторий, — находка. Самоистечение держится тем же: перемерят документ на этом
// дереве — квалификация уйдёт вместе с чужим хешем, и прощать станет нечего.
//
// ЧЕГО ЭТА ПОЛОВИНА НЕ СУДИТ, названо прямо: СУЩЕСТВОВАНИЕ квалифицированной ревизии в
// чужой истории. Проверить его можно только в чужом репозитории, а его присутствие на
// диске — свойство рабочего каталога, не коммита; вердикт, зависящий от раскладки
// диска, запрещён здесь тем же доводом, что и обход диска вместо индекса git.
//
// # СЕГОДНЯ ПОЛОВИНА «ПРЕДОК» НА ДЕРЕВЕ ВАКУУМНА, И ЭТО НАЗВАНО, А НЕ СКРЫТО
//
// Все пять датировок корпуса квалифицированы историей предшественника, поэтому
// перепись печатает `датировано хешем 0`: ни одна строка дерева половину «предок» не
// исполняет. Держит её СЕГОДНЯ только инъекция — `TestGitAncestry_*` на синтетических
// деревьях, — и это законно ровно потому, что инъекция подаёт настоящий git, а не
// подделку. Требования «датировок хешем больше нуля» здесь НЕТ намеренно: оно
// покраснело бы на корпусе, который ничего не нарушает, а состояние и без него видно
// числом. Перемерят любой документ на ЭТОМ дереве — появится простой хеш, и половина
// оживёт сама.

const iamDocsRelDir = "services/iam/docs"

// serviceHistoryRoot — ЕДИНСТВЕННЫЙ держатель факта «дерево несёт историю ЭТОЙ службы».
// Корневой коммит опубликованной истории `PRO-Robotech/kaname`; неизменяем by
// construction — корень не двигается ни одним вливанием, — поэтому устареть не может.
//
// Это свойство ДЕРЕВА, а не хеша: клон его несёт, поставка модуля не несёт.
const serviceHistoryRoot = "1a4dbb2a79c04f762b4f97ca7f7e446a1db3de90"

// predecessorRepo — ЕДИНСТВЕННЫЙ держатель факта «у службы есть предшественник».
// Документы приёмки и архитектуры переехали сюда вместе со службой, и замеры в них
// снимались в монорепо: их предикаты называют пути `services/iam/**` и гейты
// `internal/repohygiene`, которых в этом дереве не существует.
const predecessorRepo = "PRO-Robotech/kacho"

// reDatingMarker — ОБЪЯВЛЕНИЕ замера, а не упоминание слова.
//
// Судится начало строки (допускаются знак цитаты, маркер списка и жирное
// начертание), потому что объявление замера в этом корпусе всегда ОТКРЫВАЕТ
// строку. Знак `>` больше не выводит строку из-под суда: выноска — обычная форма
// этого корпуса, и объявление внутри неё остаётся объявлением.
var reDatingMarker = regexp.MustCompile(`(?m)^[ \t]*(?:>[ \t]*)*(?:[*+\-][ \t]+|\d+\.[ \t]+)?\*{0,2}Замер на ревизии[^\n]*`)

// reQuotedMarker — тот же оборот, взятый в ЯВНЫЕ кавычки-ёлочки: разговор о
// форме, а не объявление. Величина переписи, не находка.
var reQuotedMarker = regexp.MustCompile(`(?mi)«[^»\n]*замер на ревизии`)

// reInlineHash — ревизия ЭТОЙ истории: хеш в обратных кавычках.
var reInlineHash = regexp.MustCompile("`([0-9a-f]{7,40})`")

// reForeignHash — ревизия ЧУЖОЙ истории, названная ВМЕСТЕ С НЕЙ:
// `<владелец>/<репозиторий>@<хеш>`.
//
// Образцы непересекающиеся by construction: у квалифицированной формы сразу за
// открывающей кавычкой стоит имя владельца, а не шестнадцатеричный разряд, поэтому
// `reInlineHash` её не видит — и наоборот. Держит это не эта строка, а проба-близнец
// (`...CountsAnInheritedDatingSeparately`), утверждающая `dated == 0` на корпусе, где
// все датировки квалифицированы.
var reForeignHash = regexp.MustCompile(
	"`([A-Za-z0-9][A-Za-z0-9._-]*/[A-Za-z0-9][A-Za-z0-9._-]*)@([0-9a-f]{7,40})`")

// datingCensus — объём осмотренного. Печатается всегда: «ноль находок» обязано
// быть отличимо от «ноль прочитанного».
type datingCensus struct {
	docsRead         int // файлов документации прочитано
	markers          int // объявлений замера найдено
	dated            int // из них датированы хешем ЭТОЙ истории
	inherited        int // датированы ревизией предшественника — квалифицированной цитатой
	undated          int // из них датированы самоссылкой
	foreign          int // хеш РЕЗОЛВИТСЯ, но в историю дерева не входит
	absent           int // хеш не резолвится вовсе, притом что история дерева — наша
	quoted           int // оборот процитирован прозой — не замер
	ledgerEntries    int // записей ведомости
	ledgerApplied    int // записей, которым было что прощать
	ancestryUnjudged int // «НЕ ВЫПОЛНИЛОСЬ»: вердикт о предке не выносился
}

// ancestryVerdict — исход вопроса «входит ли ревизия в историю дерева».
// Третье состояние обязательно: недоступность истории не есть «да».
type ancestryVerdict int

const (
	ancestryNo       ancestryVerdict = iota // РЕЗОЛВИТСЯ, но не предок — находка
	ancestryYes                             // предок — законно
	ancestryUnjudged                        // не выполнилось: истории нет или она усечена
	ancestryAbsent                          // не резолвится вовсе, а история дерева — наша
)

// auditMeasurementDating — чистое ядро обеих проб: решает по текстам, а не по
// дереву. Ключ ведомости — имя файла, значение — причина с номером задачи.
func auditMeasurementDating(
	docs map[string]string,
	ledger map[string]string,
	ancestry func(hash string) ancestryVerdict,
) ([]string, datingCensus) {
	var findings []string
	c := datingCensus{docsRead: len(docs), ledgerEntries: len(ledger)}
	forgiven := map[string]bool{}

	names := make([]string, 0, len(docs))
	for name := range docs {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		body := docs[name]
		c.quoted += len(reQuotedMarker.FindAllString(body, -1))

		for _, line := range reDatingMarker.FindAllString(body, -1) {
			c.markers++

			// Датировкой считается ЛЕВАЯ цитата: объявление датирует то, что стоит
			// сразу за оборотом, а не то, что помянуто дальше по строке.
			bare := reInlineHash.FindStringSubmatchIndex(line)
			qual := reForeignHash.FindStringSubmatchIndex(line)

			switch {
			case qual != nil && (bare == nil || qual[0] < bare[0]):
				repo, hash := line[qual[2]:qual[3]], line[qual[4]:qual[5]]
				if repo != predecessorRepo {
					findings = append(findings, fmt.Sprintf(
						"НЕОБЪЯВЛЕННАЯ ИСТОРИЯ: %s датирует замер ревизией %s репозитория %s, который "+
							"предшественником этой службы НЕ объявлен — перемерить число негде, а имя "+
							"репозитория само по себе ничего не обещает (%q)",
						name, hash, repo, strings.TrimSpace(line)))
					continue
				}
				// История предшественника здесь не лежит и лечь не может: своё дерево
				// об этой ревизии НЕ спрашивается — спрашивать бессмысленно.
				c.inherited++

			case bare != nil:
				hash := line[bare[2]:bare[3]]
				c.dated++
				switch ancestry(hash) {
				case ancestryNo:
					c.foreign++
					findings = append(findings, fmt.Sprintf(
						"ЧУЖАЯ ЛИНИЯ: %s датирует замер ревизией %s, которая РЕЗОЛВИТСЯ, но в историю этого "+
							"дерева не входит — числа верны для дерева, которого здесь нет (%q)",
						name, hash, strings.TrimSpace(line)))
				case ancestryAbsent:
					c.absent++
					findings = append(findings, fmt.Sprintf(
						"РЕВИЗИИ НЕТ В ЭТОЙ ИСТОРИИ: %s датирует замер ревизией %s, которая в этом дереве "+
							"НЕ РЕЗОЛВИТСЯ ВОВСЕ. Историю службы дерево несёт, значит это описка в хеше либо "+
							"снятая линия. Замер, снятый в истории предшественника, записывается формой "+
							"`%s@<хеш>` — тогда читателю сказано, ГДЕ число перемерить (%q)",
						name, hash, predecessorRepo, strings.TrimSpace(line)))
				case ancestryUnjudged:
					c.ancestryUnjudged++
				case ancestryYes:
				}

			default:
				c.undated++
				if _, ok := ledger[name]; ok {
					forgiven[name] = true
					continue
				}
				findings = append(findings, fmt.Sprintf(
					"САМОССЫЛКА: %s датирует замер без хеша (%q) — восстановить ревизию можно только "+
						"раскопками по истории, то есть дороже, чем стоит проверка числа",
					name, strings.TrimSpace(line)))
			}
		}
	}

	ledgerNames := make([]string, 0, len(ledger))
	for name := range ledger {
		ledgerNames = append(ledgerNames, name)
	}
	sort.Strings(ledgerNames)
	for _, name := range ledgerNames {
		if forgiven[name] {
			c.ledgerApplied++
			continue
		}
		findings = append(findings, fmt.Sprintf(
			"ВЕДОМОСТИ НЕЧЕГО ПРОЩАТЬ: запись про %s (%s) пережила свой предмет — "+
				"недатированного замера в этом документе больше нет, запись снимается",
			name, ledger[name]))
	}
	return findings, c
}

