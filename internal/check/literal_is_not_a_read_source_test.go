// literal_is_not_a_read_source_test.go — гейт ИСТЕЧЕНИЯ ПОСЛАБЛЕНИЯ
// (kacho#1816, приёмка
// `services/iam/docs/engineering/acceptance/catalog-readers-move-to-the-table.md`,
// сценарии IAM-CT-2-08 · -09 · -10 · -11).
//
// # Что здесь послабление
//
// Послаблением является не страж паритета и не сам литерал (§2.1 приёмки прямо
// отвергает их снятие: литерал — производная канона `fga_model.fga`, и без него
// строки каталога остались бы без якоря к канону вовсе). Послабление — РОЛЬ
// ЛИТЕРАЛА КАК ИСТОЧНИКА ЧТЕНИЯ. Она и обязана истечь.
//
// # Популяция ШИРЕ мотива, и это РЕШЕНИЕ, а не недосмотр (задача #1854)
//
// Здесь стояло «на пути запроса», и это было вторым местом об одном предмете:
// мотив запрета говорит о РАБОТАЮЩЕМ процессе (каталожный факт меняется снятием
// строки; читатель на литерале считает снятый тип живым до перезапуска), а
// обход берёт поддерево `services/iam` ЦЕЛИКОМ — включая пакеты, которых в
// работающем процессе нет. Два утверждения, из которых верно одно; следующий
// читатель пошёл бы за шапкой.
//
// Верна ПОПУЛЯЦИЯ, а не шапка, и решают это три вещи:
//
//  1. приёмка §0.3 определяет единицу как «файл ПРОД-КОДА, импортирующий
//     пакет» — по дереву, а не по достижимости из бинаря. Сузить обход значило
//     бы развести гейт с его же приёмкой;
//  2. направление ошибки. Сужение НЕОБРАТИМО и тихо: настоящее нарушение на
//     пути запроса уехало бы в слепую зону молча. Лишняя строгость к сборочному
//     читателю обратима и громка — косвенность видна и снимается;
//  3. довод в пользу сужения ПРОВЕРЕН и не устоял. Задача называла пять
//     недостижимых пакетов и опиралась на то, что `internal/manifest/roleexport`
//     и `internal/modelrender` живут только в сборочных командах. Сегодня оба
//     ДОСТИЖИМЫ из `cmd/kacho-iam` (`moduleroles/rightsexport.go` и `apply.go`
//     → `cmd/kacho-iam/module_roles_apply.go`), то есть сужение, применённое
//     тогда, дало бы слепую зону ВНУТРИ бинаря сегодня — ровно ту
//     необратимость, о которой предупреждал п. 2.
//
// Величины на момент решения (единица — КАТАЛОГ; ориентир, не гейт, и
// перемеряются этими же командами из `services/iam`):
//
//	go list -deps ./cmd/kacho-iam | grep '^github.com/PRO-Robotech/kacho-iam' | sort
//	# → 87 пакетов достижимо из бинаря сервиса
//	grep -rl 'kacho-iam/internal/authzmap"' --include=*.go . | grep -v '_test.go' \
//	  | xargs -n1 dirname | sort -u
//	# → 11 каталогов-импортёров, из них НЕ достижимы бинарём 2:
//	#   internal/repo/kacho/pg/scalegrid · internal/scopesourcecensus
//
// Цена решения названа честно: у этих двух перевод на порт — церемония, новых
// свойств он не даёт. Платится она за то, что граница популяции не зависит от
// того, кто сегодня кого импортирует.
//
// # Почему это гейт дерева, а не проба сервиса
//
// «Ни один прод-файл не спрашивает каталожный факт у литерала» — свойство
// ДЕРЕВА. Проба сервиса о нём не утверждает ничего: внутри работающего процесса
// литерал и живые строки равны по построению (страж старта отказывает в пуске
// при расхождении), поэтому читатель на литерале отвечает ровно то же, что
// читатель на строках, и проба зеленеет при любом их распределении. Различие
// появляется только ПОСЛЕ старта — когда строка снята в работающем процессе, —
// и его утверждает интеграционная проба `-06`/`-07`, а не этот гейт.
//
// # Гейт судит УЗЕЛ РАЗБОРА, а не слово
//
// Имена этих функций встречаются в комментариях — в том числе в комментарии,
// объясняющем сам запрет. Гейт по подстроке краснел бы на собственном
// объяснении; поэтому он разбирает файл и смотрит на выражение выбора
// `<пакет>.<Символ>`, где `<пакет>` — ЛОКАЛЬНОЕ имя импорта `authzmap`
// (псевдоним учитывается), а не строка «authzmap» в тексте.
//
// # Перепись печатается ВСЕГДА
//
// «Ноль находок» обязано быть отличимо от «ноль прочитанного»: обход, не
// прочитавший ни одного импортёра, роняет прогон (`-10`), а число осмотренных
// импортёров и распознанных символов печатается независимо от исхода.

