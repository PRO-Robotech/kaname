// migration_section_split.go — ЯДРО гейта: директива секции мигратора
// объявлена в дереве ОДИН раз, а не выписана заново каждым, кому понадобился
// прямой ход миграции.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ: популяция шире предмета, и расходится она молча
//
// Прямой ход миграции и обратный — РАЗНЫЕ утверждения. Накат обязан быть
// применим к живым строкам; откат восстанавливает снятое, и ни в одном
// развёрнутом дереве его строк нет. Разбор, читающий файл целиком, меряет
// величину, которой не существует.
//
// Разрез поэтому нужен многим, и каждый, кому он понадобился, писал свой.
// Замер на дереве 2026-09-14 дал ОДИННАДЦАТЬ реализаций одного разреза, и они
// давали ПЯТЬ разных ответов на один вопрос — «что делать с файлом без маркера
// прямого хода»: отдать тело целиком ВМЕСТЕ С ОТКАТОМ · отдать пустую строку ·
// отдать всё от начала · отказать · не спрашивать вовсе. Сегодня оба маркера
// стоят у всех семнадцати миграций, поэтому расхождение молчит: премиса
// держится СОВПАДЕНИЕМ, а не устройством. Ровно так же держалась премиса
// гейта пика аккаунтов до `kacho#2363` — до первого оператора вставки в
// откате.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО СУДИТСЯ И ПОЧЕМУ ИМЕННО ЭТО
//
// Находка — СТРОКОВЫЙ ЛИТЕРАЛ с директивой секции в не-тестовом файле Go вне
// файла-владельца разбора. Не «вызов, который режет»: разрез бывает записан
// десятком форм (`Index`, `Cut`, `Split`, срез по двум индексам), и
// распознаватель форм вызова знал бы их не все — то есть молчал бы на
// незнакомой, а молчание от чистоты не отличить. Литерал же в не-тестовом коде
// законного предмета не имеет вовсе: директива объявлена константой, и взять
// её неоткуда, кроме владельца.
//
// ─────────────────────────────────────────────────────────────────────────────
// ГРАНИЦЫ, НАЗВАННЫЕ ВСЛУХ
//
//  1. ФАЙЛЫ ПРОБ НЕ СУДЯТСЯ. Фикстура синтетической миграции обязана нести
//     директиву дословно — это её содержимое, а не копия разбора. Гейт их не
//     читает by construction, и восемь таких копий разреза в пробах дерева
//     остаются его слепой зоной. Названо числом, а не умолчанием.
//  2. СКЛЕЙКА НЕ УЗНАЁТСЯ. Директива, собранная сложением частей, под предикат
//     не подпадает. Форма в дереве не встречалась ни разу; появится — гейт
//     промолчит, и это его граница, а не чистота.
//  3. КОММЕНТАРИЙ — НЕ ЛИТЕРАЛ. Проза о директиве законна и обязана остаться:
//     гейт, краснеющий на собственном объяснении, снимают первым.
//
// Собственного литерала у этого файла нет: он спрашивает написание у владельца
// (`migrations.SectionMarkerStem`). Иначе гейт был бы своей же первой находкой,
// и его пришлось бы прощать — то есть заводить послабление там, где его можно
// не заводить вовсе.
package check

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"strconv"
	"strings"

	"github.com/PRO-Robotech/kaname/internal/migrations"
)

// MigrationSectionOwnerRel — ЕДИНСТВЕННЫЙ файл дерева, которому положено
// выписывать директиву секции: он её и объявляет.
const MigrationSectionOwnerRel = "internal/migrations/sql_text.go"

// MigrationSectionSplitCensus — объём осмотренного.
//
// Две величины на каждой оси, потому что «ноль находок» обязано быть отличимо
// от «ноль прочитанного»: пустой обход и чистое дерево печатают один и тот же
// ноль находок, а означают противоположное.
type MigrationSectionSplitCensus struct {
	FilesRead     int // не-тестовых файлов Go прочитано
	FilesParsed   int // из них разобрано
	Literals      int // строковых литералов с директивой секции встречено
	OwnerLiterals int // из них в файле-владельце разбора
}

// AuditMigrationSectionSplit — находки и перепись по корпусу не-тестовых файлов.
//
// Корпус приходит ПАРАМЕТРОМ: инъекция обязана подать разбору синтетическое
// дерево, а не это.
func AuditMigrationSectionSplit(corpus TreeCorpus) ([]string, MigrationSectionSplitCensus, error) {
	var c MigrationSectionSplitCensus
	var findings []string

	for _, rel := range corpus.Rels() {
		c.FilesRead++
		fset := token.NewFileSet()
		file, err := parser.ParseFile(fset, rel, corpus[rel], parser.ParseComments)
		if err != nil {
			return nil, c, fmt.Errorf("разбор %s: %w — гейт не вправе судить файл, "+
				"которого он не разобрал", rel, err)
		}
		c.FilesParsed++

		ast.Inspect(file, func(n ast.Node) bool {
			lit, ok := n.(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return true
			}
			value, uerr := strconv.Unquote(lit.Value)
			if uerr != nil {
				return true
			}
			if !strings.Contains(value, migrations.SectionMarkerStem) {
				return true
			}
			c.Literals++
			if rel == MigrationSectionOwnerRel {
				c.OwnerLiterals++
				return true
			}
			findings = append(findings, fmt.Sprintf(
				"%s:%d: директива секции мигратора выписана литералом. Разрез прямого и "+
					"обратного хода объявлен ОДИН раз — %s; вторая запись расходится с ним "+
					"молча, потому что на законном входе обе отвечают одинаково. "+
					"Бери `migrations.MigrationUpText` (сырой прямой ход) либо "+
					"`migrations.MigrationUpSection` (он же без комментариев)",
				rel, fset.Position(lit.Pos()).Line, MigrationSectionOwnerRel))
			return true
		})
	}

	switch {
	case c.FilesRead == 0:
		return nil, c, fmt.Errorf("обход пуст: прочитано ноль не-тестовых файлов Go — " +
			"«находок ноль» здесь означало бы «прочитано ноль»")
	case c.OwnerLiterals == 0:
		return nil, c, fmt.Errorf("в %s не встретилось ни одного литерала с директивой "+
			"секции (осмотрено файлов %d, литералов %d) — владелец разбора перестал её "+
			"объявлять либо написание сменилось, и гейт ослеп, не покраснев",
			MigrationSectionOwnerRel, c.FilesRead, c.Literals)
	}
	return findings, c, nil
}
