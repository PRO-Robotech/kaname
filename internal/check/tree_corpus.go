package check

// tree_corpus.go — КОРПУС ОБХОДА как значение, и отказ на пустом обходе как
// ЕДИНСТВЕННЫЙ его держатель (задача PRO-Robotech/kaname#17).
//
// # ПРЕДМЕТ
//
// Гейт, чей обход пуст, молчит — и его молчание неотличимо от «находок нет».
// Требование «ноль находок обязано быть отличимо от ноль прочитанного» здесь
// исполнялось: у каждого гейта стояла безусловная премиса `t.Fatalf`. Но
// доказана она была НИ У ОДНОГО: обход строился в теле пробы от корня своего
// модуля, корень был константой, и подать проверке пустое дерево было нечем.
//
// То есть ветвь отказа существовала, читалась глазами и НИ РАЗУ не исполнялась.
// Это ровно тот класс, который корпус ловит в продукте: форма проверки без
// доказательства, что она способна сработать.
//
// # ПОЧЕМУ ОДИН ДЕРЖАТЕЛЬ, А НЕ ПРЕМИСА В КАЖДОМ ГЕЙТЕ
//
// Премис было по одной на гейт, и каждая — свой текст, своё условие, своя (не)
// доказанность. Пятнадцать копий одного предмета расходятся молча, и разошлись
// бы: половина сравнивала длину карты, половина — поле переписи.
//
// Здесь предмет один: «обход не принёс ничего». Дерево приходит ПАРАМЕТРОМ,
// поэтому инъекция подаёт синтетическое — пустое и непустое, — и отказ
// доказывается исполнением, а не чтением.
//
// # ПОЧЕМУ ДЕРЕВО, А НЕ КОРЕНЬ-СТРОКА
//
// Корень-строка заставила бы читать индекс git отсюда, а синтетический каталог
// репозиторием не является: у него индекса нет вовсе. `treecorpus` различает
// два авторитета ОТДЕЛЬНЫМИ конструкторами (`NewTree` — индекс, `SyntheticTree`
// — обход диска), и выбор делает вызывающий, осознанно. Приняв готовое дерево,
// этот пакет не выбирает за него и не заводит третьего авторитета.

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/PRO-Robotech/corelib/treecorpus"
)

// ErrEmptyTraversal — обход не принёс НИ ОДНОГО файла.
//
// Отдельная ошибка, а не просто текст: вызывающий вправе отличить «прочитано
// ноль» от «читать не удалось», и эти два исхода требуют разных действий —
// первый чинят предметом гейта, второй условиями прогона.
var ErrEmptyTraversal = errors.New("обход пуст: прочитано ноль файлов")

// TreeCorpus — тела отобранных файлов по относительному пути от корня дерева.
type TreeCorpus map[string]string

// Rels — относительные пути корпуса в устойчивом порядке. Детерминизм входа —
// часть контракта проверки: обход, отдающий файлы в разном порядке, даёт
// находки в разном порядке, и два прогона становятся несравнимы.
func (c TreeCorpus) Rels() []string {
	out := make([]string, 0, len(c))
	for rel := range c {
		out = append(out, rel)
	}
	sort.Strings(out)
	return out
}

// CorpusFrom — тела файлов дерева, отобранные предикатом `want`.
//
// Отбор ПАРАМЕТР, а корпус — значение: так гейт перестаёт строить свой обход в
// теле пробы, а инъекция получает возможность подать тот же отбор пустому
// дереву.
//
// ТРИ ИСХОДА, И ТРЕТИЙ НАЗВАН ОТДЕЛЬНОЙ ОШИБКОЙ:
//
//	корпус непуст            — вердикт выносится;
//	файл не прочитан         — отказ с координатой: гейт не вправе судить
//	                           документ, которого он не читал;
//	не отобрано ни одного     — ErrEmptyTraversal, и это НЕ «находок нет».
func CorpusFrom(tree *treecorpus.Tree, want func(rel string) bool) (TreeCorpus, error) {
	if tree == nil {
		return nil, errors.New("дерево не передано: обход не с чего начинать")
	}
	root := tree.Root()
	corpus := TreeCorpus{}
	for _, rel := range tree.SortedFiles() {
		if !want(rel) {
			continue
		}
		// Путь складывается от корня ЭТОГО дерева, а относительный приходит из
		// его же состава: чужого ввода в координате нет.
		body, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel))) // #nosec G304
		if err != nil {
			return nil, fmt.Errorf("чтение %s: %w — гейт не вправе судить файл, "+
				"которого он не прочитал", rel, err)
		}
		corpus[rel] = string(body)
	}
	if len(corpus) == 0 {
		return nil, fmt.Errorf("%w (осмотрено файлов дерева %d, отобрано 0) — «находок "+
			"ноль» здесь означало бы «прочитано ноль», а не «годно»",
			ErrEmptyTraversal, tree.Count())
	}
	return corpus, nil
}

// OutsideTraversal — путь ВНЕ области обхода: система контроля версий, оснастка
// агента, документация, вендоренное и артефакты сборки.
//
// Предикат один на дерево и объявлен здесь: прежде он жил в файле пробы
// соседнего семейства, и всякий следующий обход либо звал чужую пробу, либо
// заводил свою копию перечня. Копии перечня расходятся молча — и расходится та,
// которую не считали.
func OutsideTraversal(rel string) bool {
	for _, seg := range strings.Split(rel, "/") {
		switch seg {
		case ".git", ".claude", "docs", "node_modules", "vendor", "bin":
			return true
		}
	}
	return false
}

// ProductionGoFile — не-тестовый файл Go внутри области обхода.
//
// Отбор, который в этом дереве повторяется чаще прочих. Объявлен один раз по
// той же причине, что и `OutsideTraversal`: три копии «`.go`, не `_test.go`, не
// служебный каталог» разошлись бы на первом же новом исключении.
func ProductionGoFile(rel string) bool {
	return strings.HasSuffix(rel, ".go") &&
		!strings.HasSuffix(rel, "_test.go") &&
		!OutsideTraversal(rel)
}

// MigrationCorpus — файлы миграций из ДЕРЕВА.
//
// Сборщик общий на два семейства (словарь алгоритма и писатель роли модуля):
// обе прежде строили обход сами, и премисы «миграций прочитано ноль» у обеих
// стояли в теле пробы, где подать им пустое дерево было нечем (#17).
func MigrationCorpus(tree *treecorpus.Tree) (TreeCorpus, error) {
	return CorpusFrom(tree, func(rel string) bool {
		return strings.HasPrefix(rel, MigrationsDirRel+"/") && strings.HasSuffix(rel, ".sql")
	})
}
