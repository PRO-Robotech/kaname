// module_identity_seeded_only_by_baseline.go — личность модуля заводит ТОЛЬКО
// применённая базовая миграция (ПР-5 приёмки WIRE-1, задача продукта #2098).
//
// Порт с монорепо (`internal/repohygiene/moduleidentityseededonlybythebaseline_test.go`,
// снят вынесением службы — `kacho#2597`). В монорепо предикат жил ЦЕЛИКОМ
// внутри `_test.go` (пакет-«внешний тест», без отдельного `.go`); здесь он
// вынесен в не-тестовый файл, потому что кроме гейта его читает пересчёт.
//
// # ПРЕДМЕТ (дословно из монорепо)
//
// Личности модулей посеяны БАЗОВОЙ миграцией, то есть приезжают и в установку,
// где платформы нет вовсе. Строка, которую арендатор, развернувший службу
// доступа отдельно, нести не обязан, — это данные окружения, и в миграцию они
// не идут ни при каких условиях (`data-integrity.md` §«Данные СТЕНДА
// заводятся посевом»).
//
// # СОСТОЯНИЕ НА ДЕНЬ ПЕРЕНОСА — ДРУГОЕ, чем в монорепо, и это названо числом
//
// В монорепо (на день заведения гейта) долг был НЕПОДВИЖЕН: применителя у
// раздела `seed` манифеста не было, применённую миграцию не поправить (ban
// #5), а свежая установка без платформы несла пять личностей чужого продукта.
//
// В kaname этот долг ЗАКРЫТ отдельной задачей — #2452
// (`20260909202745_module_identities_leave_the_baseline.sql`, применена ДО
// выноса службы из монорепо, то есть закрытие произошло в исходном дереве, а
// не в этом порту): пять личностей (`kacho-vpc`, `kacho-compute`, `kacho-nlb`,
// `kacho-registry`, `kacho-storage`) СНЯТЫ этой миграцией, а применитель
// заведён (`internal/apps/kaname/moduleseed`), позван из композиционного
// корня. Остаются ДВЕ: `kacho-bootstrap-admin` (личность самой службы, не
// модульная — `IsModule()` false) и `kacho-api-gateway` (модульная, остаток,
// названный вслух в шапке миграции — у края манифеста нет вовсе, применителя
// заводить некому, снимается вместе со своим производителем).
//
// Обе остаются посеянными БАЗОВОЙ миграцией (`0001_initial.sql`, первой в
// порядке применения) — то есть `moduleIdentitiesSeededOutsideTheBaseline`
// сегодня находит ноль нарушений. Это НЕ делает гейт вакуумным: он и дальше
// судит регресс — появление НОВОЙ миграции, сеющей модульную личность НЕ через
// применитель (ровно тот класс, который #2452 только что убрал). Обновлять
// эту прозу нормой `#2098` больше не нужно: предмет её первой половины
// («свежая установка без платформы несёт ноль модульных СА, кроме остатка
// api-gateway») закрывает #2452, а не этот гейт; гейт стережёт РОСТ.
//
// # РОДСТВО, КОТОРОЕ НАДО НАЗВАТЬ — И РАЗЛИЧИЕ (дословно из монорепо)
//
// У ролей модуля такой судья есть отдельным семейством (Г2,
// `migrationnotawriterofmodulerole`, НЕ входит в этот батч) — запрещает
// миграции писать роль модуля, у которого есть манифест, ПОЛНОСТЬЮ (у ролей
// применитель есть). У личностей применитель тоже теперь есть — но не для
// ВСЕХ (api-gateway — остаток), поэтому запрет здесь остаётся УЗКИМ: не
// «личность модуля не сеет никакая миграция», а «личность модуля не сеет
// НИКАКАЯ МИГРАЦИЯ КРОМЕ БАЗОВОЙ» — тот же периметр, что был в монорепо.
//
// # ЧЕГО ГЕЙТ НЕ ЛОВИТ (названо, чтобы на него не сослались шире предмета)
//
// Он про ПОСЕВ, а не про живую базу: строку, заведённую не миграцией, он не
// читает by construction. И он ничего не утверждает о ПОЛНОТЕ посева.
package check

import (
	"fmt"
	"sort"
)

// BaselineMigrationOf — применённая базовая миграция: первая в порядке
// применения. Порядок goose лексикографический, поэтому перечень уже
// отсортирован вызывающим.
func BaselineMigrationOf(ordered []string) string {
	if len(ordered) == 0 {
		return ""
	}
	return ordered[0]
}

// SeedScopeUnfit — ПРЕДМЕТА нет. Отдельной функцией, а не тремя ветвями
// внутри пробы: способность гейта отличить «ноль находок» от «ноль
// прочитанного» проверяется инъекцией, а инъекция не может спросить
// `require`/`t.Fatalf` напрямую.
func SeedScopeUnfit(ordered []string, alive map[string]SeededServiceAccount) string {
	switch {
	case len(ordered) == 0:
		return "миграций не прочитано ни одной — обход пуст, и «ноль находок» здесь " +
			"означало бы «ноль прочитанного»"
	case len(alive) == 0:
		return fmt.Sprintf("в %d миграциях не разобрано ни одной живой служебной учётки: "+
			"либо имя таблицы сменилось, либо форма записи перестала попадать под разбор",
			len(ordered))
	}
	return ""
}

// ModuleIdentitiesSeededOutsideTheBaseline — судья, отделённый от дерева ради
// инъекции. Находка — живая МОДУЛЬНАЯ учётка, чью строку завела не базовая
// миграция.
func ModuleIdentitiesSeededOutsideTheBaseline(alive map[string]SeededServiceAccount, baseline string) []string {
	ids := make([]string, 0, len(alive))
	for id := range alive {
		ids = append(ids, id)
	}
	sort.Strings(ids)

	var out []string
	for _, id := range ids {
		sa := alive[id]
		if !sa.IsModule() || sa.Where == baseline {
			continue
		}
		out = append(out, fmt.Sprintf(
			"%s: миграция заводит личность модуля %q (%s). Личность модуля заводится либо "+
				"применённой базовой миграцией %s (замороженный остаток), либо применителем "+
				"досева манифеста — но не произвольной миграцией. Появление новой миграции, "+
				"сеющей модульную личность мимо применителя, — регресс #2452",
			sa.Where, sa.Name, id, baseline))
	}
	return out
}
