package check

// provider_compensation_retention_premise_test.go — ПРЕДПОСЫЛКА уборки очереди
// компенсаций у внешнего провайдера, а не сама уборка (#2069).
//
// # Что уборка себе позволяет и на каком основании
//
// Общий уборщик очередей платформы щадит ДОСТАВЛЕННУЮ строку, если она защищает
// отравленного предшественника от оживления реконсайлером: оживлённый
// предшественник ушёл бы применяться ПОСЛЕ уже применённого потомка, то есть
// порядок партиции развалился бы. Ради этого ему нужен ключ партиции.
//
// У очереди компенсаций ключ партиции пуст НАМЕРЕННО: её поток коммутативен —
// каждое событие означает «снять у провайдера вот этот объект», и снятия
// независимы. Поэтому её уборщик проще: он снимает доставленную строку по
// возрасту и ничего не щадит.
//
// Это законно ровно пока верна ПРЕДПОСЫЛКА: над этой таблицей нет оживителя
// отравленных строк. «Сегодня оживителя нет» — факт о ДЕРЕВЕ, а не свойство
// замысла, и он вправе перестать быть верным. Предпосылку и стережёт этот гейт.
//
// # Почему гейт, а не абзац
//
// Ровно этого потребовала снятая запись реестра роста таблиц, объявлявшая
// очередь долгом: «послабление обязано нести гейт, который покраснеет, когда
// реконсайлер появится». Абзац на это не годится: он не краснеет.
//
// # Почему судится ТАБЛИЦА, а не служба
//
// Оживитель над очередями iam ЕСТЬ — над очередью писем, у которой свой ключ
// партиции и общий уборщик платформы. К этой очереди он отношения не имеет, и
// его существование её уборку неверной не делает. Гейт, красный на исправном
// дереве, отключают первым, а с ним перестают читать и настоящую находку.

import (
	"path/filepath"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kacho/pkg/treecorpus"
)

// compensationOutboxTable — таблица, чью уборку стережёт предпосылка.
const compensationOutboxTable = "provider_compensation_outbox"

// compensationOutboxTableConst — ВТОРАЯ законная форма, которой ту же таблицу
// называют в коде: имя константы её единственного объявления.
//
// Форма, о которой разбор не знает, даёт не красное и не зелёное, а МОЛЧАНИЕ —
// и записанное в ней осталось бы вне наблюдения. Обе формы утверждаются
// инъекцией порознь.
const compensationOutboxTableConst = "ProviderCompensationTable"

// namesCompensationQueue — узнаёт таблицу в обеих законных формах.
func namesCompensationQueue(table string) bool {
	return strings.Contains(table, compensationOutboxTable) ||
		strings.Contains(table, compensationOutboxTableConst)
}

// TestProviderCompensationRetentionPremiseHolds — ни один оживитель отравленных
// строк не построен НАД ОЧЕРЕДЬЮ КОМПЕНСАЦИЙ, поэтому её уборка вправе снимать
// доставленную строку по возрасту и ничего не щадить.
//
// # Обход берётся у ИНДЕКСА
//
// Гейт судит о СОСТАВЕ дерева; неотслеживаемый файл, попавший в обход, дал бы
// вердикт о том, чего в дереве нет.
func TestProviderCompensationRetentionPremiseHolds(t *testing.T) {
	root := catalogRepoRoot(t)

	files, err := treecorpus.UnderWithSuffix(filepath.Join(root, iamTreeRel), ".go")
	if err != nil {
		t.Fatalf("состав индекса поддерева %s: %v", iamTreeRel, err)
	}

	sites, filesRead, err := redriveSitesOfTree(root, files)
	if err != nil {
		t.Fatalf("%v", err)
	}

	var overThisQueue, overOthers []string
	for _, s := range sites {
		if namesCompensationQueue(s.table) {
			overThisQueue = append(overThisQueue, s.where)
			continue
		}
		overOthers = append(overOthers, s.where+" ("+s.table+")")
	}

	t.Logf("перепись: файлов Go в индексе поддерева %d · прод-файлов прочитано %d · "+
		"мест построения оживителя %d · из них над очередью компенсаций %d · над соседними %d",
		len(files), filesRead, len(sites), len(overThisQueue), len(overOthers))

	// Пустой обход — отказ: гейт, которому нечего было читать, зелен по
	// построению и неотличим от исправного.
	if filesRead == 0 {
		t.Fatalf("обход пуст: в индексе %s ноль прод-файлов Go — вердикт беспредметен", iamTreeRel)
	}
	// Разбор обязан УМЕТЬ узнавать оживителя. Ноль мест построения означал бы,
	// что признак разъехался с кодом, — и молчание гейта означало бы слепоту, а
	// не отсутствие предмета. Законный близнец в дереве есть: оживитель очереди
	// писем.
	if len(sites) == 0 {
		t.Fatal("мест построения оживителя не найдено ни одного — признак разъехался с кодом. " +
			"В дереве службы такой оживитель ЕСТЬ (очередь писем), значит ноль здесь означает слепоту")
	}
	if len(overOthers) == 0 {
		t.Fatal("законный близнец не найден: оживитель над СОСЕДНЕЙ очередью обязан быть виден разбору " +
			"и обязан молчать — без него «над очередью компенсаций ноль» ничего не доказывает")
	}

	if len(overThisQueue) != 0 {
		t.Fatalf(`ПРЕДПОСЫЛКА УБОРКИ ОЧЕРЕДИ КОМПЕНСАЦИЙ БОЛЬШЕ НЕ ВЕРНА.

Над очередью %s построен оживитель отравленных строк: %s

Уборка этой очереди (retention.SubjectProviderCompensationOutbox) снимает
ДОСТАВЛЕННУЮ строку по возрасту и НИЧЕГО не щадит — это было законно ровно пока
оживителя над нею не было. Оживлённая отравленная строка теперь вправе уйти
применяться после уже применённого потомка, чей след уборка сняла: снятие у
провайдера, уже выполненное, было бы повторено поверх заново заведённого
объекта.

Исходов два, и «оставить как есть» среди них нет: либо уборка учится щадить
доставленную строку, защищающую отравленного предшественника (то есть очередь
заводит ключ партиции и переходит на общий уборщик платформы), либо оживитель к
этой очереди не подключается и это записано решением.`,
			compensationOutboxTable, strings.Join(overThisQueue, ", "))
	}
}
