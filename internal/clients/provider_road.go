// provider_road.go — ИСХОД одного обращения по дороге к внешнему поставщику
// личности, разложенный на клетки, которые различают ПРИЧИНУ (kacho#2491, #2492).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ. ДОРОГ ТРИ, СЧЁТ БЫЛ У ОДНОЙ
//
// Профиль объявляет три дороги к поставщику, у каждой свой адрес и свой якорь
// доверия (`KANAME_HYDRA_ADMIN_*`, `KANAME_HYDRA_JWKS_*`, `KANAME_HYDRA_TOKEN_*`).
// Считалась одна — дорога набора ключей, и только она расщепляла два состояния
// оси: «не ответил» (лечится временем) и «по адресу не тот эндпоинт» (временем
// не лечится, чинится оператором).
//
// Цена неразличения названа самим руководством по установке: две самые частые
// ошибки установки — адрес поставщика, не резолвящийся внутри кластера, и
// незаданный корень доверия. Обе дают дежурному ТУ ЖЕ картину, что и лежащий
// поставщик. Для отдельно поставляемой службы это означает, что в три часа ночи
// «сломан продукт» и «оператор не создал условие» на двух дорогах из трёх не
// различимы ничем.
//
// ─────────────────────────────────────────────────────────────────────────────
// ОТДЕЛЬНАЯ КЛЕТКА У «НЕ НАЙДЕНО» — ЭТО ПРИЗНАНИЕ НЕРАЗЛИЧИМОСТИ, А НЕ ОТКАЗ
//
// Один и тот же ответ 404 две поверхности этой службы читали ПРОТИВОПОЛОЖНО:
// зеркало набора ключей — как доказательство «по адресу не тот эндпоинт»
// (громко, своей клеткой), административная дорога — как «уже снято» и успех, на
// котором классификатор очереди компенсаций помечает строку доставленной. При
// неверно настроенном административном адресе снятие «удаётся» на каждой строке,
// и очередь СХОДИТСЯ, НЕ СНЯВ НИЧЕГО.
//
// Обе стороны по отдельности защитимы, и разницу никто не решал. Решение здесь:
//
//	404 на административной дороге ОСТАЁТСЯ успехом вызова — и получает СВОЮ
//	клетку [ProviderRoadOutcomeAbsent], которая честно называется неразличимой.
//
// РАЗМЕН НАЗВАН ЯВНО, потому что второй исход был бы хуже. Признай мы 404
// отказом — строка очереди компенсаций перестала бы помечаться доставленной;
// отказ этого рода повтором не чинится, значит строка дошла бы до порога
// отравления и ЗАКЛИНИЛА свою партицию, а снятое у поставщика осталось бы
// занятым. То есть «строгость» разменяла бы тихую неразличимость на тихую
// остановку очереди.
//
// Что различение даёт взамен: растущий `absent` при НУЛЕВОМ `ok` на той же
// дороге означает адрес, по которому нет ни одного нашего клиента, — то есть
// настройку, а не идемпотентное снятие. Одной величины для этого не хватает:
// вопрос задаётся ПАРОЙ клеток, и обе обязаны существовать.
package clients

// Дороги к внешнему поставщику личности. Набор ЗАКРЫТ и перечислим при сборке.
//
// Дорога НАБОРА КЛЮЧЕЙ здесь намеренно отсутствует: её исходы считает
// собственное семейство зеркала (`kaname_jwks_mirror_outcomes_total`), и вторая
// клетка об одном предмете разошлась бы с первой молча. Перепись «дорог
// объявлено N · дорог со счётом M» сверяет ОБА семейства с профилем.
const (
	// ProviderRoadAdmin — административная дорога: выдача и отзыв ключа
	// служебной учётки, заведение и снятие интерактивного клиента,
	// принудительный выход.
	ProviderRoadAdmin = "admin"
	// ProviderRoadTokenExchange — дорога обмена подписанного утверждения на
	// токен у прежнего издателя (докерная полоса непереведённого контура).
	ProviderRoadTokenExchange = "token_exchange"
)

// ProviderRoads — ЗАКРЫТЫЙ набор дорог, наблюдаемых этим семейством.
var ProviderRoads = []string{ProviderRoadAdmin, ProviderRoadTokenExchange}

// Исходы обращения. Набор ЗАКРЫТ и перечислим при сборке.
const (
	// ProviderRoadOutcomeOK — поставщик ответил по существу.
	//
	// ЗНАМЕНАТЕЛЬ: без него ноль по прочим клеткам отвечает сразу на два
	// вопроса — «отказов не было» и «по этой дороге никто не ходил», — а это
	// противоположные состояния.
	ProviderRoadOutcomeOK = "ok"

	// ProviderRoadOutcomeAbsent — поставщик ответил «не найдено».
	//
	// НЕРАЗЛИЧИМОСТЬ, ПРИЗНАННАЯ ЯВНО: это либо ресурс, которого у поставщика
	// уже нет (идемпотентное снятие — штатный исход), либо адрес, по которому
	// наших ресурсов нет вовсе. Вызов остаётся успешным; различает их ПАРА
	// клеток — растущий `absent` при нулевом `ok` есть настройка.
	ProviderRoadOutcomeAbsent = "absent"

	// ProviderRoadOutcomeRejected — поставщик отверг обращение по существу
	// (негодное удостоверение, конфликт имени). Временем не лечится, но и
	// настройкой дороги не является: чинится тем, кто обращается.
	ProviderRoadOutcomeRejected = "rejected"

	// ProviderRoadOutcomeUnavailable — поставщик не ответил полезно: сеть,
	// срок, отказ его стороны. ЛЕЧИТСЯ ВРЕМЕНЕМ.
	ProviderRoadOutcomeUnavailable = "unavailable"

	// ProviderRoadOutcomeMisconfigured — по адресу НЕ ТОТ эндпоинт.
	//
	// ВРЕМЕНЕМ НЕ ЛЕЧИТСЯ. Доказательством считается ответ, которого исправный
	// эндпоинт поставщика не даёт ни при каком входе: метод не поддержан, ресурс
	// изъят, обработчик не реализован, — а также ответ «успех» с телом, которое
	// не разбирается по контракту этого эндпоинта.
	ProviderRoadOutcomeMisconfigured = "misconfigured"
)

// ProviderRoadOutcomes — ЗАКРЫТЫЙ набор клеток семейства.
var ProviderRoadOutcomes = []string{
	ProviderRoadOutcomeOK,
	ProviderRoadOutcomeAbsent,
	ProviderRoadOutcomeRejected,
	ProviderRoadOutcomeUnavailable,
	ProviderRoadOutcomeMisconfigured,
}

// ProviderRoadObserver — порт счёта исходов дороги.
//
// Порт, а не журнал: вопрос оператора КОЛИЧЕСТВЕННЫЙ («какая доля обращений по
// этой дороге не доходит и почему»), а по строкам журнала это считают глазами,
// уже после того как отказ истолкован.
type ProviderRoadObserver interface {
	ObserveProviderRoad(road, outcome string)
}

// observeProviderRoad — единая точка учёта. nil-наблюдатель законен: счёта нет,
// решения дороги это не меняет.
func observeProviderRoad(obs ProviderRoadObserver, road, outcome string) {
	if obs == nil {
		return
	}
	obs.ObserveProviderRoad(road, outcome)
}

// classifyProviderRoadStatus переводит код ответа поставщика в клетку.
//
// Разбор по СЕМЕЙСТВУ кода, а не по перечню: незнакомый код обязан попасть в
// клетку, а не исчезнуть. Перечень «доказательств настройки» взят тот же, что у
// зеркала набора ключей, — иначе две поверхности одной службы снова читали бы
// один сигнал по-разному.
func classifyProviderRoadStatus(status int) string {
	switch status {
	case 404:
		return ProviderRoadOutcomeAbsent
	case 405, 410, 501:
		// Метод не поддержан · ресурс изъят · обработчик не реализован. Ни один
		// исправный эндпоинт поставщика так не отвечает: это адрес, а не сбой.
		return ProviderRoadOutcomeMisconfigured
	}
	switch {
	case status >= 200 && status < 300:
		return ProviderRoadOutcomeOK
	case status >= 400 && status < 500:
		return ProviderRoadOutcomeRejected
	default:
		return ProviderRoadOutcomeUnavailable
	}
}
