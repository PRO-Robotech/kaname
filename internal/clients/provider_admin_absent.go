// provider_admin_absent.go — АДМИНИСТРАТИВНАЯ ДОРОГА, КОТОРОЙ НЕТ (задача
// kaname#21; преемник kacho#2489, закрытой при живом предмете).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ — АДРЕС, А НЕ ОТВЕТ
//
// На посадке `own` внешнего поставщика личности не существует вообще. До этого
// файла композиционный корень строил дорогу к нему БЕЗУСЛОВНО, и построенной
// она выглядела всегда: резолв адреса пустого не возвращает никогда — при
// незаданной ручке он ВЫВОДИТ адрес из доменного имени. То есть дорога читалась
// как настроенная на стенде, который её не настраивал, и уходила звонить в
// публичный ингресс, неся в заголовке административного предъявителя.
//
// Поэтому предмет здесь — не «клиент отвечает ошибкой», а «клиент НЕ НЕСЁТ
// АДРЕСА». Адрес не резолвится, якорь не читается, транспорт не собирается.
// Отказ — следствие отсутствия дороги, а не её поведение.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ТОТ ЖЕ ТИП, А НЕ ИНТЕРФЕЙС И НЕ ПУСТОЙ УКАЗАТЕЛЬ
//
// Потребителей административной дороги в корне четыре, и один из них принимает
// КОНКРЕТНЫЙ тип. Пустой указатель дал бы им панику на первом же вызове — то
// есть отказ без имени, в чужом месте и позже причины. Интерфейс потребовал бы
// сменить подписи у всех четверых, а требование к этой полосе — минимальность.
//
// Тот же тип с несобранной дорогой держит оба свойства сразу: подписи не
// меняются, а вызов получает ИМЕНОВАННЫЙ отказ, отличимый машинно.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОТКАЗ ОБЯЗАН ОПОЗНАВАТЬСЯ `errors.Is`
//
// «Поставщика на этой посадке нет» и «поставщик не ответил» требуют от
// вызывающего ПРОТИВОПОЛОЖНОГО: первое повтором не лечится никогда, второе
// лечится и обязано повторяться. Отказ, различимый только текстом, заставил бы
// разбирать прозу — и очередь компенсаций повторяла бы вечно то, что не
// исполнится ни при какой попытке (`security-hardening.md` §8: мягкий проход
// обязан отличать настройку от сбоя).
package clients

import (
	"errors"
	"fmt"
)

// ErrNoExternalIdentityProvider — на этой посадке внешнего поставщика личности
// нет вовсе.
//
// ТЕРМИНАЛЬНЫЙ по смыслу: повтор идентичного вызова не пройдёт ни при какой
// попытке, потому что звонить некуда — адреса не существует, а не он временно
// недоступен.
var ErrNoExternalIdentityProvider = errors.New(
	"this posture declares no external identity provider (authn.identity-provider=own): " +
		"the admin road to one is not built, so there is nothing to call — this is terminal, " +
		"not a transient upstream failure, and retrying will never make it succeed")

// NewAbsentProviderAdminClient возвращает административного клиента ПОСАДКИ БЕЗ
// ВНЕШНЕГО ПОСТАВЩИКА: без адреса, без предъявителя и без транспорта.
//
// Ни одно поле не заполняется намеренно: заполненный адрес и есть тот дефект,
// ради которого файл заведён. Признак несобранной дороги — `BaseURL == ""`, и
// он же читается наблюдателем провязки в композиционном корне.
func NewAbsentProviderAdminClient() *HydraAdminClient {
	return &HydraAdminClient{}
}

// roadIsBuilt — собрана ли у этого клиента дорога вообще.
//
// Судит по АДРЕСУ, а не по признаку-флагу: флаг был бы вторым местом об одном
// предмете и разошёлся бы с полями молча. Клиент без адреса звонить не может
// by construction, чем бы его ни собрали.
func (c *HydraAdminClient) roadIsBuilt() bool {
	return c != nil && c.BaseURL != ""
}

// refuseAbsentRoad — единственный производитель отказа «дороги нет».
//
// Один на все методы: три копии одного текста разошлись бы, и разошлась бы та,
// которую правили последней.
func (c *HydraAdminClient) refuseAbsentRoad(op string) error {
	return fmt.Errorf("hydra %s: %w", op, ErrNoExternalIdentityProvider)
}
