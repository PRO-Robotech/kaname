// provider_admin_absent.go — КЛИЕНТ АДМИНИСТРАТИВНОЙ ДОРОГИ БЕЗ АДРЕСА ОТКАЗЫВАЕТ
// ПО ИМЕНИ (задача kaname#21; преемник kacho#2489, закрытой при живом предмете).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ — АДРЕС, А НЕ ОТВЕТ
//
// На посадке `own` внешнего поставщика личности не существует вообще, и дорогу к
// нему композиционный корень НЕ СТРОИТ: развилка посадки (`onProviderAdminRoad`,
// задача kaname#338) отдаёт потребителю ветвь без дороги, и клиента без адреса
// ему не передаёт никто. Прежде такой клиент строился нарочно и уходил
// потребителям значением — развилка его производителя сняла.
//
// Здесь остаётся ЗАПАСНОЙ ОТКАЗ ПО УМОЛЧАНИЮ: клиент, у которого нет адреса,
// звонить не может by construction, чем бы его ни собрали — нулевым значением
// типа или пустым адресом. Каждый метод дороги первым оператором спрашивает
// `roadIsBuilt` и отказывает, не собирая запроса; держит это гейт
// `provider_road_wire_guard`.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОТКАЗ ОБЯЗАН ОПОЗНАВАТЬСЯ `errors.Is`
//
// «Дороги к поставщику нет» и «поставщик не ответил» требуют от вызывающего
// ПРОТИВОПОЛОЖНОГО: первое повтором не лечится никогда, второе лечится и
// обязано повторяться. Отказ, различимый только текстом, заставил бы разбирать
// прозу — и очередь компенсаций повторяла бы вечно то, что не исполнится ни при
// какой попытке (§8: мягкий проход обязан отличать настройку от сбоя).
package clients

import (
	"errors"
	"fmt"
)

// ErrNoExternalIdentityProvider — у клиента нет адреса: административная
// дорога к внешнему поставщику личности не построена.
//
// ТЕРМИНАЛЬНЫЙ по смыслу: повтор идентичного вызова не пройдёт ни при какой
// попытке, потому что звонить некуда — адреса не существует, а не он временно
// недоступен.
var ErrNoExternalIdentityProvider = errors.New(
	"the provider admin client carries no address: the admin road to an external identity " +
		"provider is not built, so there is nothing to call — this is terminal, " +
		"not a transient upstream failure, and retrying will never make it succeed")

// roadIsBuilt — собрана ли у этого клиента дорога вообще.
//
// Судит по АДРЕСУ, а не по признаку-флагу: флаг был бы вторым местом об одном
// предмете и разошёлся бы с полями молча. Клиент без адреса звонить не может
// by construction, чем бы его ни собрали.
func (c *HydraAdminClient) roadIsBuilt() bool {
	return c != nil && c.BaseURL != ""
}

// refuseAbsentRoad — единственный производитель отказа «дороги нет».
//
// Один на все методы: три копии одного текста разошлись бы, и разошлась бы та,
// которую правили последней.
func (c *HydraAdminClient) refuseAbsentRoad(op string) error {
	return fmt.Errorf("provider admin %s: %w", op, ErrNoExternalIdentityProvider)
}
