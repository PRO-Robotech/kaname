// invite_mail_brand_test.go — письмо приглашения не называет чужой продукт.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Тема и тело приглашения — ЕДИНСТВЕННЫЕ два текста службы, которые видит
// арендатор. Оба называли платформу по имени литералом («Приглашение в Kachō»).
//
// Пока служба была частью одной платформы, литерал был верен. Служба вынесена
// отдельным продуктом и ставится в ЧУЖОМ облаке (#2076) — и тогда литерал
// сообщает приглашённому имя продукта, которого тот не покупал и о котором не
// слышал. Это не косметика: письмо приходит человеку, ещё не имеющему доступа,
// и единственное, по чему он решает, настоящее оно или обман, — узнаёт ли он
// отправителя.
//
// Своим именем службы («Kaname») заменять литерал НЕЛЬЗЯ: приглашают работать
// не в службу управления доступом, а в облако, которое её поставило.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ИМЕННО УТВЕРЖДАЕТСЯ
//
//  1. Задано отображаемое имя отправителя — оно и есть имя, которое видит
//     приглашённый: другого источника у письма нет и заводить второй нельзя.
//  2. Имя не задано — письмо НЕ НАЗЫВАЕТ никакого продукта. Отсутствие имени
//     честнее чужого: неверное имя хуже, чем никакого.
//
// Оба случая проверяются вместе: без первого второе зеленело бы на письме, из
// которого вычеркнули всё.

package clients_test

import (
	"strings"
	"testing"

	"github.com/PRO-Robotech/kaname/internal/clients"
)

// brandsThatMustNotBeHardcoded — имена продуктов, которых в письме быть не
// может: платформы, частью которой служба была, и её собственное.
var brandsThatMustNotBeHardcoded = []string{"Kachō", "Kacho", "Kaname", "kaname"}

func TestInviteMailNamesTheSenderNotAHardcodedProduct(t *testing.T) {
	ev := clients.InviteMailEvent{To: "someone@example.test"}

	// (1) Имя отправителя задано — оно и называет приглашающего.
	named := clients.MailRelay{
		From:     "no-reply@operator.test",
		FromName: "Облако Оператора",
		LoginURL: "https://console.operator.test",
	}
	body := string(clients.RenderInviteMail(named, ev))
	if !strings.Contains(body, "Облако Оператора") {
		t.Errorf("письмо не называет отправителя, хотя его имя задано:\n%s", body)
	}
	for _, brand := range brandsThatMustNotBeHardcoded {
		if strings.Contains(body, brand) {
			t.Errorf("письмо называет продукт %q литералом — приглашённый читает имя, "+
				"которого не покупал:\n%s", brand, body)
		}
	}

	// (2) Имя отправителя НЕ задано — письмо не называет никакого продукта.
	anon := clients.MailRelay{From: "no-reply@operator.test"}
	body = string(clients.RenderInviteMail(anon, ev))
	for _, brand := range brandsThatMustNotBeHardcoded {
		if strings.Contains(body, brand) {
			t.Errorf("без имени отправителя письмо всё равно называет продукт %q — "+
				"отсутствие имени честнее чужого:\n%s", brand, body)
		}
	}
	// Положительный контроль второго случая: письмо не выхолощено — призыв на
	// месте. Без него проверка зеленела бы на пустом теле.
	if !strings.Contains(body, "пригласили") {
		t.Errorf("во втором случае из письма исчез призыв — проверка отсутствия "+
			"зеленела бы на пустом теле:\n%s", body)
	}
}
