// Package accesssnapshot снимает множество объектов, доступных субъекту, и
// сравнивает два таких снимка.
//
// Инструмент существует ради одного утверждения перехода IAM-ID-1: права
// переносятся, НЕ РАСШИРЯЯСЬ. Пока оно не закреплено, перенос доказан только
// косвенно.
//
// # Почему страница + пообъектная проверка, а НЕ перечисление разрешённого
//
// Соблазн — спросить у движка прав «перечисли всё, что доступно». Так делать
// нельзя, и причина не в стиле: перечисление разрешённых объектов имеет ЖЁСТКИЙ
// серверный предел, не имеет продолжения, и предел этот ОБЩИЙ НА ТИП, а не
// по-арендаторный (`security.md` §«Фильтрация — страница → проверка страницы»).
// Сравнение двух УСЕЧЁННЫХ множеств сойдётся «элемент в элемент», не доказав
// ничего, — и выглядеть это будет как успех.
//
// Поэтому: страница курсором ИЗ СВОЕЙ БАЗЫ → пообъектная проверка партиями
// ≤100 → следующая страница. Своя база предела не имеет и перечисляет ровно то,
// что в ней лежит.
//
// # Бюджет времени принадлежит ЗАПРОСУ, а не партии
//
// Партии исполняются параллельно под ОДНИМ сроком вызывающего. Последовательные
// партии превращают срок в сумму сроков: на странице контрактного размера
// снимок не укладывался бы в бюджет и давал бы отказ на ПОЛОЖИТЕЛЬНОМ пути.
// Сужать страницу ради бюджета запрещено — размер страницы часть контракта.
//
// # Почему снимок несёт ЧИСЛО ОСМОТРЕННОГО
//
// Пустое множество равно пустому. Снимок, не собравшийся ни по какой причине
// (курсор не отдал строк, движок отказал, грант пуст), сравнивается с таким же
// пустым — и объявляет перенос доказанным. Поэтому снимок несёт `Examined`, а
// `Compare` ОТКАЗЫВАЕТСЯ сравнивать, когда осмотрено ноль: «ноль находок»
// обязано быть отличимо от «ноль прочитанного».
package accesssnapshot

import (
	"context"
	"fmt"
	"sort"
	"sync"

	"golang.org/x/sync/errgroup"
)

// BatchSize — сколько объектов уходит в одну партию проверок.
// Потолок партии — 100 (`security.md` §AuthN/AuthZ).
const BatchSize = 100

// Checker — то, чем задаётся вопрос о доступе. Реализуется продовым клиентом
// движка прав: инструмент обязан спрашивать ТУ ЖЕ сторону, что и продукт,
// иначе он утверждает про свою копию правил.
type Checker interface {
	Check(ctx context.Context, subject, relation, object string) (bool, error)
}

// PageFunc отдаёт следующую страницу идентификаторов объектов ИЗ СВОЕЙ БАЗЫ,
// курсором после afterID. Пустой срез означает «страниц больше нет».
type PageFunc func(ctx context.Context, afterID string, limit int) ([]string, error)

// Snapshot — что субъекту доступно и СКОЛЬКО объектов для этого осмотрено.
type Snapshot struct {
	// Allowed — идентификаторы объектов, на которые движок ответил разрешением.
	Allowed map[string]struct{}
	// Examined — сколько объектов вообще прошло через проверку. Ноль означает,
	// что снимок не собрался, а НЕ что доступа нет.
	Examined int
}

// IDs возвращает разрешённые идентификаторы в устойчивом порядке — сравнивать
// и печатать надо по СОСТАВУ, а не по порядку обхода.
func (s Snapshot) IDs() []string {
	out := make([]string, 0, len(s.Allowed))
	for id := range s.Allowed {
		out = append(out, id)
	}
	sort.Strings(out)
	return out
}

// Take снимает множество доступных субъекту объектов одного типа.
//
// relation — глагол, который спрашивают (например "v_get"); objectType — префикс
// объекта в модели прав (например "project"). Идентификаторы приходят из page.
func Take(
	ctx context.Context, ch Checker, page PageFunc, subject, relation, objectType string,
) (Snapshot, error) {
	snap := Snapshot{Allowed: map[string]struct{}{}}
	var mu sync.Mutex
	after := ""

	for {
		ids, err := page(ctx, after, BatchSize)
		if err != nil {
			return Snapshot{}, fmt.Errorf("страница объектов %s: %w", objectType, err)
		}
		if len(ids) == 0 {
			return snap, nil
		}

		// Партии — параллельно под ОДНИМ сроком вызывающего (см. шапку пакета).
		g, gctx := errgroup.WithContext(ctx)
		for _, id := range ids {
			g.Go(func() error {
				allowed, cerr := ch.Check(gctx, subject, relation, objectType+":"+id)
				if cerr != nil {
					return fmt.Errorf("проверка %s:%s: %w", objectType, id, cerr)
				}
				mu.Lock()
				defer mu.Unlock()
				if allowed {
					snap.Allowed[id] = struct{}{}
				}
				snap.Examined++
				return nil
			})
		}
		if err := g.Wait(); err != nil {
			// Отказ движка — НЕ «доступа нет»: вернуть здесь частичный снимок
			// значило бы объявить потерю прав там, где её никто не наблюдал.
			return Snapshot{}, err
		}
		after = ids[len(ids)-1]
	}
}

// Diff — что потеряно и что приобретено между двумя снимками.
type Diff struct {
	// Lost — было доступно, стало недоступно. Потеря есть дефект переноса.
	Lost []string
	// Gained — не было доступно, стало доступно. Приобретение есть РАСШИРЕНИЕ
	// доступа, и оно опаснее потери: потеря шумит, расширение молчит.
	Gained []string
}

// Empty — множества совпали.
func (d Diff) Empty() bool { return len(d.Lost) == 0 && len(d.Gained) == 0 }

// Compare сверяет два снимка ПО СОСТАВУ и отказывается сравнивать пустоту.
//
// Отказ — не придирка: снимок, не собравшийся ни по какой причине, сравнивается
// с таким же пустым и объявляет перенос доказанным. Это то же «ноль находок
// неотличимо от ноль прочитанного», только про права, — и цена ошибки здесь
// выше, потому что её не видно.
func Compare(before, after Snapshot) (Diff, error) {
	if before.Examined == 0 || after.Examined == 0 {
		return Diff{}, fmt.Errorf(
			"сравнивать нечего: осмотрено объектов до=%d после=%d. Пустой снимок совпадёт "+
				"с любым пустым и объявит перенос доказанным — это не результат, а несобранный замер",
			before.Examined, after.Examined)
	}
	var d Diff
	for id := range before.Allowed {
		if _, ok := after.Allowed[id]; !ok {
			d.Lost = append(d.Lost, id)
		}
	}
	for id := range after.Allowed {
		if _, ok := before.Allowed[id]; !ok {
			d.Gained = append(d.Gained, id)
		}
	}
	sort.Strings(d.Lost)
	sort.Strings(d.Gained)
	return d, nil
}
