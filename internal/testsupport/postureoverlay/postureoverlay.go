// Package postureoverlay — НАКЛАДКИ ОПЕРАТОРА, которыми поставка объявляет
// посадку, у которой своего профиля нет.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ НАКЛАДКА, А НЕ ПРОФИЛЬ
//
// Боевой профиль чарта продукта стоит на `external` решением, и профиля `own`
// в поставке нет: перевод установки на `own` — накладка оператора поверх
// боевого профиля (kacho#2699 п. 3, INSTALL.md §1). Посадка, объявленная так,
// объявлена законно, и гейт покрытия полос обязан её видеть — иначе полоса,
// которую корень поднимает, выглядела бы для него необъявленной (kaname#232).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧИТАТЕЛЕЙ ДВА — ПОЭТОМУ ИСТОЧНИК ОДИН
//
//	рендерная проба чарта (`deploy`, О2) — накладка поверх своего профиля
//	    рендерится и принимается стражем старта;
//	гейт покрытия полос (`cmd/kaname`)  — посадка, объявленная накладкой,
//	    засчитывается объявленной.
//
// Две копии накладки разошлись бы молча: гейт засчитал бы посадку по накладке,
// которую рендер не проверяет, или рендер проверял бы накладку, о которой гейт
// не знает.
//
// Накладка стенда конвейера (`.github/scripts/stand-chart.sh`) сюда не входит:
// она объявляет посадку стенду, а не поставке, и её величины подставляются
// стендом при подъёме.
package postureoverlay

// Overlay — одна накладка оператора.
type Overlay struct {
	name string
	base string
	sets []string
}

// Name — имя накладки в переписи и находках.
func (o Overlay) Name() string { return o.name }

// Base — файл значений чарта продукта, поверх которого ложится накладка, по
// имени в каталоге чарта.
func (o Overlay) Base() string { return o.base }

// Sets — строки накладки в форме `--set` helm: `ключ.значений=величина`.
// Возвращается копия: append в общий срез переписал бы его соседям.
func (o Overlay) Sets() []string { return append([]string(nil), o.sets...) }

// Own — накладка, переводящая боевую цепочку на `own` (INSTALL.md §1):
// посадка, включённый токен-эндпоинт платформы и его четыре величины.
//
// Величины согласованы с заглушками боевого профиля, а не взяты образцами
// таблицы стража: образец перечня адресатов называет адресат докерной полосы
// ДРУГОЙ установки, и страж старта, требующий его внутри перечня, отверг бы
// накладку поверх ЭТОГО профиля.
var Own = Overlay{
	name: "own",
	base: "values.prod.yaml",
	sets: []string{
		"authn.identityProvider=own",
		"authn.clientToken.enabled=true",
		`authn.clientToken.allowedAudiences=registry.example.invalid\,https://access.example.invalid`,
		"authn.clientToken.defaultAudience=https://access.example.invalid",
		"authn.clientToken.tokenTtl=15m",
		"authn.clientToken.bodyCeiling=65536",
	},
}

// All — все накладки поставки.
func All() []Overlay { return []Overlay{Own} }
