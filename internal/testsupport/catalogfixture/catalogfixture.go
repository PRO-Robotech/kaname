// Package catalogfixture — каталожный факт для проб (kacho#1816).
//
// # Зачем отдельный пакет, а не по копии в каждой пробе
//
// Каталожный факт нужен пробам ПЯТИ пакетов сразу, и собирается он всегда
// одинаково — из того же перечня, которым миграция посеяла строки. Копия в
// каждом пакете была бы пятью местами об одном предмете; разойдясь, они дали бы
// пробы, зелёные по разным каталогам.
//
// # Почему фикстура НЕ снисходительнее продукта
//
// Она не выдумывает своего множества: строит `catalog.Facts` из
// `seed.LiteralRows()` — ровно того перечня, который посеян миграцией и с
// которым страж старта сверяет живые строки. То есть проба на этой фикстуре
// видит тот же каталог, что и служба на исправном стенде.
//
// Литерал она при этом НЕ ЧИТАЕТ как каталожный факт: `seed.LiteralRows()`
// зовёт `authzmap.CatalogSeed*` — левую сторону паритета, читать которую есть
// работа посева. Гейт истечения послабления
// (`check.TestIAMCT2_LiteralIsNotAReadSource`) на этом пакете молчит, и молчит
// по существу, а не по исключению.
package catalogfixture

import (
	"github.com/PRO-Robotech/kacho-iam/internal/apps/kacho/seed"
	"github.com/PRO-Robotech/kacho-iam/internal/catalog"
)

// Facts — каталожный факт, равный посеянному миграцией.
//
// Паникует на невозможном: перечень литерала пуст только если сломан сам
// производитель, и тогда любая проба на этой фикстуре утверждала бы о пустом
// каталоге, ничего об этом не сказав.
func Facts() *catalog.Facts {
	f, err := catalog.NewFacts(seed.LiteralRows())
	if err != nil {
		panic("catalogfixture: перечень литерала пуст — сломан производитель посева: " + err.Error())
	}
	return f
}

// Source — источник каталожного факта для провязки use-case'ов и реконсайлера.
func Source() catalog.Source { return catalog.Fixed{F: Facts()} }
