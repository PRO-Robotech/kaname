// Package modulemanifests — манифесты модулей, ДОСТУПНЫЕ ПРОБЕ В ЭТОЙ ПОСАДКЕ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ (#2377)
//
// Сверки «объявлено манифестом ↔ лежит в живой базе» имеют стороны в РАЗНЫХ
// деревьях: манифесты модулей — у платформы (`services/*/manifest.yaml`), база и
// миграции — у службы. Прежде обе стороны брались обходом `<корень>/services`, и
// после разреза этот каталог рядом с модулем не резолвится: сверка становилась
// невыразимой, а расхождение объявления с фактом переставало находиться — ровно
// то, ради чего раздел `roles`/`seed` манифеста и заведён.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗДЕСЬ РЕШЕНО, А ЧТО НЕТ
//
// Решено ОДНО: перечень манифестов есть ФУНКЦИЯ ПОСАДКИ, и он никогда не пуст.
//
// Имя файла манифеста здесь НЕ ПИШЕТСЯ своей рукой: у него один владелец в
// фундаменте и ДВЕ формы — в дереве и в доставке. Объявление, знающее одну,
// обещало бы читателю полноту, которой у него нет. Берётся оно у читателя
// СВОЕЙ службы (`internal/manifest`), а не прямым импортом: направление
// «служба → пакет класса платформы» запрещено целевой раскладкой, и новое такое
// ребро есть находка даже там, где сегодня всё собирается.
//
//	дерево платформы ЕСТЬ  — читаются манифесты ВСЕХ модулей платформы, ровно как
//	                         прежде: числа переписей в монорепо не меняются;
//	дерева платформы НЕТ   — читается манифест САМОГО МОДУЛЯ, входящий в его
//	                         поставку. Сверка сужается, но НЕ ИСЧЕЗАЕТ, и её
//	                         объём объявляется числом.
//
// НЕ решено и решаться здесь не должно: как манифесты СОСЕДЕЙ доезжают до
// самостоятельной службы. Они доезжают ДОСТАВКОЙ в рантайме (именованный
// ConfigMap; у доставки есть производитель, и это предмет платформенного гейта),
// а не деревом сборки. Заводить здесь их копию значило бы завести второе место
// об одном предмете, которое после разреза не сверяется НИЧЕМ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ПРОПУСКА НЕТ
//
// Пропуск здесь означал бы «сторожа больше нет», и молчание было бы неотличимо
// от исправной работы — тот самый тихий класс, ради которого пакет и заведён.
// Поэтому обе посадки дают ОТВЕТ, а перепись печатает, какой именно и сколько
// манифестов прочитано: «ноль находок» обязано быть отличимо от «прочитан один
// из шести».
package modulemanifests

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"

	"github.com/PRO-Robotech/kaname/internal/manifest"
	"github.com/PRO-Robotech/kaname/internal/treeposture"
)

// Posture — посадка, в которой снят перечень.
type Posture string

const (
	// PlatformTree — модуль лежит в дереве платформы: читаются манифесты всех её
	// модулей.
	PlatformTree Posture = "дерево платформы"
	// StandaloneModule — самостоятельный клон: читается манифест самого модуля.
	StandaloneModule Posture = "самостоятельный клон"
)

// Set — перечень манифестов и посадка, в которой он снят.
type Set struct {
	// Posture — какая из двух посадок дала этот перечень.
	Posture Posture
	// Root — корень, от которого координаты ниже отсчитаны.
	Root string
	// Files — координаты манифестов ОТ Root, отсортированные.
	Files []string
}

// Census — строка объёма осмотренного. Печатается ВСЕГДА, а не только при
// находке: без неё «расхождений 0» неотличимо от «прочитано 0».
func (s Set) Census() string {
	return fmt.Sprintf("посадка %s, корень %s, манифестов прочитано %d", s.Posture, s.Root, len(s.Files))
}

// Available — манифесты, доступные в посадке каталога start.
//
// Ошибка означает «проверка НЕ ИСПОЛНЯЛАСЬ»: ни одной из двух посадок назвать не
// удалось либо в названной не нашлось ни одного манифеста. Пустой перечень
// ошибкой НЕ возвращается молча — вызывающий обязан отличать его от согласия.
func Available(start string) (Set, error) {
	root, prefix, err := treeposture.CorpusRoot(start)
	if err != nil {
		return Set{}, fmt.Errorf("посадка не установлена: %w", err)
	}

	if prefix == "" {
		// Самостоятельный клон: модуль и есть корень, его манифест лежит рядом.
		own := manifest.TreeFileName()
		if _, serr := os.Stat(filepath.Join(root, own)); serr != nil {
			return Set{}, fmt.Errorf(
				"самостоятельный клон %s не несёт собственного манифеста (%v): сверять "+
					"объявление с базой нечем, и молчание сверки было бы сказано ни о чём",
				root, serr)
		}
		return Set{Posture: StandaloneModule, Root: root, Files: []string{own}}, nil
	}

	paths, gerr := filepath.Glob(filepath.Join(root, "services", "*", manifest.TreeFileName()))
	if gerr != nil {
		return Set{}, fmt.Errorf("обход манифестов платформы в %s: %w", root, gerr)
	}
	files := make([]string, 0, len(paths))
	for _, p := range paths {
		rel, rerr := filepath.Rel(root, p)
		if rerr != nil {
			return Set{}, fmt.Errorf("координата %s от корня %s: %w", p, root, rerr)
		}
		files = append(files, filepath.ToSlash(rel))
	}
	if len(files) == 0 {
		return Set{}, fmt.Errorf(
			"в дереве платформы %s не найдено ни одного services/*/%s: "+
				"каталог модулей переехал, и сверка стережёт координату, которой нет",
			root, manifest.TreeFileName())
	}
	sort.Strings(files)
	return Set{Posture: PlatformTree, Root: root, Files: files}, nil
}
