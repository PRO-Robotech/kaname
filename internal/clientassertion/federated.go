// federated.go — федеративная полоса приёма: утверждение подписал ВНЕШНИЙ
// издатель, а перечень доверенных издателей ведём мы (задача #1124, RFC 7523
// §2.1 — вид выдачи, не аутентификация клиента).
//
// # Чем эта полоса отличается от полосы аутентификации клиента
//
// Там издатель и субъект обязаны совпадать и оба назвать НАШУ строку, а ключ
// берётся из строки клиента. Здесь издатель — посторонний, субъект — его
// собственный, ключ принадлежит ему, и единственное, что есть у нас, — ЗАПИСЬ
// О ДОВЕРИИ. Промах поэтому даёт не «приняли своё за чужое», а токен платформы
// предъявителю, которого мы не заводили вовсе.
//
// # Три признака, отделяющих утверждение от нашего же токена доступа
//
// На полосе клиента первый признак — объявленный нами тип в заголовке. Здесь
// его нет и быть не может: тип ставит производитель, а производитель тут
// посторонний, и требование типа отвергало бы каждого обычного издателя.
// Признаки, которые остаются и которых достаточно:
//
//  1. **ключ.** Подпись проверяется ключом ИЗДАТЕЛЯ из записи доверия. Наш
//     токен доступа подписан нашим ключом, которого в этой таблице нет;
//  2. **наш идентификатор издателя в этой таблице ЗАПРЕЩЁН** — иначе первый
//     признак снимался бы одной административной записью, и наш собственный
//     токен доступа стал бы приниматься как чужое утверждение;
//  3. **адресат.** Утверждение адресовано нашему издателю; токен доступа
//     адресован ресурсу.
package clientassertion

import (
	"context"
	"time"

	"github.com/golang-jwt/jwt/v5"

	"github.com/PRO-Robotech/kaname/internal/domain"
)

// VerifyFederated проверяет утверждение, подписанное внешним издателем, и
// разрешает его в НАШУ строку через перечень доверенных издателей.
//
// # Порядок — тот же довод, что и на полосе клиента
//
// Дорогое после дешёвого, решения о ключе — после того, как ключ разрешён по
// ЗАПИСИ ДОВЕРИЯ, погашение однократности — последним:
//
//	форма → заголовок (дубли · пометки) → алгоритм словаря → личность →
//	наш издатель запрещён → перечень доверия → срок доверия → алгоритм
//	ЗАПИСИ → подпись → адресат → время → однократность
func (v *Verifier) VerifyFederated(ctx context.Context, raw string) (Result, error) {
	// (1) Форма, дублирующиеся имена членов, пометка «обязателен к пониманию».
	env, res, err := decodeEnvelope(raw)
	if err != nil {
		return res, err
	}

	// (2) Алгоритм заголовка — из закрытого словаря, до разрешения ключа.
	alg, res, err := declaredAlgorithm(env.header)
	if err != nil {
		return res, err
	}

	claims, res, err := decodeClaims(env.payloadBytes)
	if err != nil {
		return res, err
	}

	// (3) Личность. Оба члена обязательны и оба непусты; совпадать они, в
	// отличие от полосы клиента, НЕ обязаны и обычно не совпадают.
	issuer, errIss := stringMember(claims, "iss")
	subject, errSub := stringMember(claims, "sub")
	if errIss != nil || errSub != nil || issuer == "" || subject == "" {
		return refuse(OutcomeIdentityMismatch, "issuer and subject are both required on the federated lane")
	}

	// (4) НАШ идентификатор издателя на этой полосе запрещён БЕЗУСЛОВНО, и
	// проверка стоит ДО обращения к перечню.
	//
	// Без неё признак «это не наш токен доступа» снимался бы одной записью в
	// таблице: занеси кто-нибудь нас самих доверенным издателем с нашим же
	// открытым ключом — и выпущенный нами токен доступа стал бы приниматься
	// как чужое утверждение. Запись такого доверия отвергается и на пути
	// записи; здесь она отвергается ещё раз, потому что путь записи меняется
	// отдельно от этого и мог бы измениться молча.
	if issuer == v.policy.ExpectedAudience {
		return refuse(OutcomeIssuerUntrusted, "our own issuer identifier is never a trusted external issuer")
	}

	// (5) Перечень доверенных издателей — НАША таблица. Пустая означает «не
	// доверяем никому», и это не вырожденный случай, а состояние, ради
	// которого перечень заведён: величина, которая может быть пустой и не
	// проверена на непустоту, означает «принимаем любого».
	trust, client, err := v.issuers.ResolveTrustedIssuer(ctx, issuer, subject)
	switch {
	case domain.IsTrustedIssuerUnknown(err):
		return refuse(OutcomeIssuerUntrusted, "the (issuer, subject) pair is not trusted")
	case err != nil:
		// Недоступность перечня — ОТКАЗ, никогда «пропустить». Мягкий проход
		// означал бы приём утверждения, о доверии к которому мы не установили
		// ничего.
		return refuse(OutcomeRegistryUnavailable, "trusted issuer list is unavailable: %v", err)
	}

	// (6) Срок доверия. Запись без ключевого материала доверия не даёт: она
	// принимала бы всё, что называет её пару.
	if !trust.CanVouch() {
		return refuse(OutcomeIssuerUntrusted, "the trust record carries no key material")
	}
	now := v.policy.Clock().UTC()
	if trust.ExpiresAt != 0 && !now.Before(time.Unix(trust.ExpiresAt, 0).UTC()) {
		// Отдельный исход от «не доверен»: «доверия не было» и «доверие
		// кончилось» суть разные события эксплуатации, и слитые в один счётчик
		// они делают истечение невидимым.
		return refuse(OutcomeTrustExpired, "trust in this (issuer, subject) pair has expired")
	}

	// (7) Алгоритм заголовка обязан равняться зарегистрированному у ЗАПИСИ
	// ДОВЕРИЯ, и сверка стоит ДО проверки подписи. Тот же довод, что на полосе
	// клиента: перечень допустимых алгоритмов строится из нашей записи, а не из
	// заголовка предъявленного, поэтому подмена параметра внутри одного
	// семейства тоже отвергается.
	if alg != trust.Algorithm {
		return refuse(OutcomeAlgorithmMismatch, "declared algorithm is not the one registered for this issuer")
	}

	pub, err := parsePublicKey(trust.PublicKeyPEM)
	if err != nil {
		// Непригодный записанный ключ — НАША неисправность, а не вина
		// предъявителя, но исход для него тот же: принять утверждение, которое
		// нечем проверить, нельзя.
		return refuse(OutcomeIssuerUntrusted, "recorded issuer key material is unusable: %v", err)
	}

	// (8) Подпись — ключом издателя. Собственная проверка утверждений
	// библиотеки отключена намеренно: каждый исход ниже обязан иметь СВОЙ
	// счётчик, а библиотека сводит несколько разных отказов в один.
	if _, perr := jwt.Parse(raw,
		func(*jwt.Token) (any, error) { return pub, nil },
		jwt.WithValidMethods([]string{trust.Algorithm}),
		jwt.WithoutClaimsValidation(),
	); perr != nil {
		return refuse(OutcomeSignatureMismatch, "signature does not verify against the trusted issuer key")
	}

	// (9) Адресат, время, однократность — общий хвост обеих полос. Потолок
	// длительности здесь СВОЙ: внешний издатель выпускает своей нагрузке токен
	// со своим сроком и о потолке полосы клиента не знает.
	//
	// Однократность гасится по НАШЕЙ строке, а не по внешнему субъекту:
	// колонка ключа объявлена как наш идентификатор клиента, и субъекты одного
	// федеративного ключа делят пространство идентификаторов однократности.
	// Цена названа честно — это доверенные одному ключу нагрузки, а не граница
	// между арендаторами; межарендной границей остаётся сама строка.
	return v.admit(ctx, claims, client, v.policy.MaxFederatedLifetime)
}
