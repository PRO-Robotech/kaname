// relationsubjects.go — КАКИЕ ВИДЫ ПОЛУЧАТЕЛЯ принимает объявление отношения.
//
// Задача продукта #1936, приёмка
// `services/iam/docs/engineering/acceptance/module-manifest-relation-grant.md`
// §3.3 и §3.5 (APPROVED круг 1).
//
// # Почему чтение живёт ЗДЕСЬ, а не у вызывающего
//
// Вызывающих у него два — загрузчик манифеста (судит объявленную выдачу) и
// сверка посева (судит живую строку), — и оба спрашивают об одном: что канон
// принимает получателем этого отношения. Копия у каждого разошлась бы молча,
// потому что расходятся такие копии только на невалидном входе.
//
// Дом выбран не по удобству: здесь уже живёт СОСЕДНИЙ вопрос о том же предмете
// — [Plans.Declares] («объявляет ли модель это отношение у этого типа»), и обе
// стороны обязаны судить ОДИН набор. Разведённые по разным пакетам, они дали бы
// зазор между принимаемым и объявленным ровно там, где он не виден.
//
// Прежде чтение жило в пакете сверки посева и было заведено ради ПРОБЫ
// ПРЕДПОСЫЛКИ, которую задача #1936 снимает вместе с её предметом. Оставить его
// там значило бы держать читатель в пакете, у которого предмета не осталось.
//
// # Собственного разбора канона здесь НЕ заводится, и довод уже оплачен
//
// Разбор общий — `services/iam/internal/authzplan`. Свой разбор в этом дереве уже писали: он
// сравнивал запись со СТРОКОЙ `group#member` и потому читал
// `group#member with <условие>` как «членство не принимается», отвечая уверенно
// и неверно. Направление ошибки было худшим из двух — судья оставался зелёным.
//
// # Перевод написаний тоже ОДИН
//
// Манифест пишет вид субъекта `serviceAccount`, канон — `service_account`.
// Перевод делается здесь, у владельца канона; второе написание того же предмета
// разошлось бы с первым молча.
//
// # Ответов ТРИ, а не два
//
// «Такого отношения у типа нет» отличается от «есть, вида не принимает», и оба
// отличаются от «есть, прямых субъектов нет вовсе» (отношение вычисляемое:
// членство может прийти транзитивно, и судить о нём по этой строке нельзя).
// Схлопывание любых двух даёт судью, чей отказ называет НЕВЕРНЫЙ предмет:
// автор чинил бы вид получателя там, где чинить надо выбор отношения.
package authzmodel

import (
	"sort"

	"github.com/PRO-Robotech/kacho-iam/internal/authzplan"
)

// Виды получателя В НАПИСАНИИ МАНИФЕСТА. Перечень закрыт: манифест берёт его у
// контракта `SubjectType`, и третьего написания того же предмета не заводится.
const (
	// KindUser — человек.
	KindUser = "user"
	// KindServiceAccount — служебная запись.
	KindServiceAccount = "serviceAccount"
	// KindGroup — группа; в каноне это членство (`group#member`), а не сам
	// объект группы.
	KindGroup = "group"
)

// canonSubjectType — как вид получателя записан В КАНОНЕ.
//
// Пара «тип субъекта, userset», а не строка: членство группы есть ПАРА
// (`group`, `member`), и судить его написанием значило бы пропустить законную
// форму с условием.
var canonSubjectType = map[string]struct {
	typ     string
	userset string
}{
	KindUser:           {typ: "user"},
	KindServiceAccount: {typ: "service_account"},
	KindGroup:          {typ: "group", userset: "member"},
}

// RelationSubjects — объявление одного отношения у одного типа объекта,
// прочитанное как ответ на вопрос «кого оно принимает получателем».
type RelationSubjects struct {
	// ObjectType и Relation — о чём этот ответ. Оба нужны в текстах отказа:
	// одноимённое отношение соседнего типа судьёй не является, и отказ обязан
	// называть тип, по объявлению которого он вынесен.
	ObjectType string
	Relation   string

	// Direct — были ли у отношения прямые записи субъекта ВООБЩЕ.
	//
	// false означает «отношение вычисляемое», а НЕ «субъектов нет»: разница
	// несущая, см. шапку файла. Вызывающий обязан спросить это ПЕРЕД тем, как
	// толковать пустой [RelationSubjects.Accepts].
	Direct bool

	// Accepts — виды субъекта, принимаемые прямо, В НАПИСАНИИ КАНОНА, без
	// повторов и в устойчивом порядке.
	//
	// Поле существует ради ТЕКСТА отказа: судья показывает автору то, что стоит
	// в каноне. Решения по нему НЕ принимаются — для этого есть
	// [RelationSubjects.AcceptsKind]: сравнение со строкой и было прежней
	// ошибкой.
	Accepts []string

	// direct — разобранные записи прямого userset. Неэкспортировано намеренно:
	// это ИСТИНА объявления, и спрашивать её полагается вопросом, а не разбором
	// строки на стороне вызывающего — иначе второй разбор заведётся снова, уже
	// у потребителя.
	direct []authzplan.DirectSubject
}

// IsDirect — были ли у отношения прямые записи субъекта ВООБЩЕ.
//
// Метод-зеркало поля [RelationSubjects.Direct]. Существует не ради удобства: он
// вместе с [RelationSubjects.AcceptedKinds] и [RelationSubjects.AcceptsKind]
// составляет то, что спрашивает загрузчик манифестов, и позволяет ему задавать
// вопрос ИНТЕРФЕЙСОМ, не импортируя владельца модели (#2002).
//
// Разворот ребра здесь несущий, а не стилистический: загрузчик доставки читался
// бы иначе моделью, которая из его же результата и собирается.
func (s RelationSubjects) IsDirect() bool { return s.Direct }

// AcceptedKinds — виды субъекта, принимаемые прямо, в написании канона.
//
// Метод-зеркало поля [RelationSubjects.Accepts]; предназначено ТЕКСТУ отказа.
// Решения по нему не принимаются — для этого есть [RelationSubjects.AcceptsKind]:
// сравнение со строкой и было прежней ошибкой.
func (s RelationSubjects) AcceptedKinds() []string { return s.Accepts }

// AcceptsKind — принимает ли объявление получателя названного вида.
//
// Вид называется В НАПИСАНИИ МАНИФЕСТА (`serviceAccount`), перевод делается
// здесь. Вид вне закрытого перечня даёт `false`: судить о том, чего манифест
// написать не может, нечем, и «да» здесь было бы вымыслом.
//
// Судится ПАРА (тип субъекта, userset), а не написание записи:
//   - условие (`group#member with mfa_fresh`) сужает, КОГДА членство действует,
//     и не отменяет того, ЧТО это членство, — значит принимает;
//   - подстановка (`group:*`, `user:*`) называет тип субъекта и членством не
//     является, а прямую выдачу поимённому субъекту не разрешает — значит НЕ
//     принимает.
//
// У вычисляемого отношения ответ `false` сам по себе ничего не значит:
// вызывающий обязан сперва спросить [RelationSubjects.Direct].
func (rs RelationSubjects) AcceptsKind(manifestKind string) bool {
	want, known := canonSubjectType[manifestKind]
	if !known {
		return false
	}
	for _, s := range rs.direct {
		if s.Wildcard {
			continue
		}
		if s.Type == want.typ && s.Userset == want.userset {
			return true
		}
	}
	return false
}

// RelationSubjects — объявление отношения `relation` у типа `objectType`.
//
// ok=false означает «канон такого не объявляет»: либо типа нет, либо у типа нет
// такого отношения. Ответ даётся ПО ОБЪЯВЛЕНИЮ СВОЕГО типа — одноимённое
// отношение соседнего типа подменять его не вправе, иначе судья ответил бы про
// чужой предмет.
func (p *Plans) RelationSubjects(objectType, relation string) (RelationSubjects, bool) {
	t := p.model.Type(objectType)
	if t == nil {
		return RelationSubjects{}, false
	}
	rel := t.Rel(relation)
	if rel == nil {
		return RelationSubjects{}, false
	}

	out := RelationSubjects{ObjectType: objectType, Relation: relation}
	seen := map[string]struct{}{}
	// Прямых термов у отношения может быть больше одного (`[a] or admin or [b]`);
	// собираются ВСЕ. Разбор, читающий только первые скобки строки, не увидел бы
	// запись из второго терма — не нарушением, а невидимостью.
	for _, term := range rel.Terms {
		if term.Kind != authzplan.TermDirect {
			continue
		}
		out.Direct = true
		for _, s := range term.Direct {
			out.direct = append(out.direct, s)
			if _, dup := seen[s.String()]; dup {
				continue
			}
			seen[s.String()] = struct{}{}
			out.Accepts = append(out.Accepts, s.String())
		}
	}
	return out, true
}

// RelationNames — имена отношений, объявленных у типа, по возрастанию.
//
// Существует ради ТЕКСТА отказа: автор, назвавший отношение с опечаткой, обязан
// узнать не только что ошибся, но и чем это чинить. Перечень БЕРЁТСЯ У КАНОНА, а
// не выписывается — выписанный разошёлся бы с ним молча.
//
// ok=false — типа канон не объявляет; пустой перечень у объявленного типа
// законен и означает «отношений нет», а не «типа нет».
func (p *Plans) RelationNames(objectType string) ([]string, bool) {
	t := p.model.Type(objectType)
	if t == nil {
		return nil, false
	}
	out := make([]string, 0, len(t.Relations))
	for _, rel := range t.Relations {
		out = append(out, rel.Name)
	}
	sort.Strings(out)
	return out, true
}
