// Package authzmodel — каноническая модель прав, доступная коду iam в рантайме.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ЭТО СУЩЕСТВУЕТ
//
// Реляционная форма вердикта обязана отвечать на ТОТ ЖЕ вопрос, что движок, а
// модель выводит отношения: право читателя следует из права редактора, право
// редактора — из права администратора, право администратора аккаунта
// распространяется вниз. Форма, ищущая имя отношения буквально, ответит «нет»
// держателю права, которое модель ему даёт, — и это не оттенок, а отказ.
//
// Значит выводу нужен разбор модели, а разбору — сама модель, в процессе.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ПРОИЗВОДНАЯ КОПИЯ, А НЕ ЧТЕНИЕ ФАЙЛА В РАНТАЙМЕ
//
// Читать файл на ходу значит завести зависимость от смонтированного пути: её
// надо задать в каждом профиле развёртывания, отказать в старте при её
// отсутствии и не перепутать с адресом соседа. Копия, вшитая в двоичный файл,
// не может разойтись с тем, что собрано, и не требует ни одной ручки.
//
// Цена копии — расхождение с источником, и она уплачена целиком: производная
// порождается целью сборки, а гейт побайтового равенства роняет прогон при
// расхождении (`identity_test.go`).
//
// КОПИЙ ДВЕ: каноническая и эта. Здесь стояло «теперь три — каноническая,
// настройка кластера и эта»; третьей нет. Настройка кластера несла модель,
// пока её применял внешний движок отношений, — движок снят целиком (S6, эпик
// #747), а с ним подчарт и карта, которую тот подчарт монтировал. Их имена
// здесь намеренно НЕ воспроизводятся координатой: мёртвое имя, записанное
// обратными кавычками, читается как живое.
//
// Утверждение пережило свой предмет и обошлось дороже опечатки: читатель,
// ищущий третью копию, ищет то, чего нет, и заводит гейт дрейфа для
// несуществующей производной. То же самое соседний пакет уже говорит прямо
// (`services/iam/internal/authzmap` — шапка гейта дрейфа).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ РАЗБОР ОДИН РАЗ, А НЕ НА ЗАПРОС
//
// Модель неизменна в пределах процесса: она вшита. Разбирать её на каждый вопрос
// значило бы платить разбором ВСЕХ её отношений — а их сотни — за каждое решение
// о доступе. Число здесь намеренно не названо: оно двигается с каждой правкой
// модели, и замороженным оно уже было — стояло «244» при 277 объявлениях в
// дереве, то есть довод опирался на величину, неверную на треть.
// Разбирается один раз, планы считаются по требованию и запоминаются — первый
// вопрос об отношении платит за разбор своего вывода, последующие не платят.
package authzmodel

import (
	_ "embed"
	"errors"
	"fmt"
	"sync"

	"github.com/PRO-Robotech/kacho/internal/authzplan"
)

// DSL — каноническая модель.
//
// Побайтовая копия `proto/kacho/cloud/iam/v1/fga_model.fga`. Порождается
// `make -C deploy fga-model-embed`; правится ТОЛЬКО канонический файл.
//
//go:embed fga_model.fga
var DSL string

// Plans — разобранная модель с запомненными планами вывода.
type Plans struct {
	model *authzplan.Model

	mu sync.RWMutex
	by map[string]authzplan.Plan
}

var (
	// sharedMu держит ОБА признака вместе с самим экземпляром: «установлено» и
	// «прочитано» суть состояния одного предмета, и разведённые по разным
	// замкам они разошлись бы там, где расхождение и опасно, — между проверкой
	// признака и подменой модели.
	sharedMu  sync.Mutex
	shared    *Plans
	sharedErr error
	// installed — модель процесса поставлена явным входом [Install].
	installed bool
	// wasRead — модель уже отдана хотя бы одному читателю. С этого мгновения
	// установка запрещена: она была бы ТИХОЙ ЗАМЕНОЙ, при которой один
	// вызывающий уже принял решение о доступе по одной модели, а следующий
	// примет по другой.
	wasRead bool
)

// ErrModelAlreadyRead — модель процесса уже прочитана, и установка запрещена.
//
// Сигнальная, а не текстовая: вызывающий — композиционный корень — принимает по
// этому различию решение об ОТКАЗЕ В ПУСКЕ, и сравнение по подстроке сломалось
// бы на первой правке формулировки, молча и в сторону продолжения.
var ErrModelAlreadyRead = errors.New(
	"authzmodel: модель процесса уже прочитана — установка после первого чтения есть тихая замена")

// ErrModelAlreadyInstalled — модель процесса уже установлена.
var ErrModelAlreadyInstalled = errors.New(
	"authzmodel: модель процесса уже установлена — второй установки не существует")

// Install ставит НАЗВАННЫЙ текст моделью процесса (#1969, §2 п. 7-8).
//
// # Почему явный вход, а не ленивый поставщик
//
// Ленивый поставщик внутри [Shared] сделал бы момент сборки функцией того, кто
// первым спросил модель, — а спрашивают её пути с РАЗНЫМИ входами: разбор
// доставки читает её лишь на манифестах, объявивших выдачу отношения. Тогда
// стенд поднимался бы на одних манифестах и вставал на других, недетерминированно
// и неотличимо от «условие не создано».
//
// # Почему присваивание [DSL] установкой НЕ является
//
// Оно даёт ровно ту тихую замену, которую запрещает норма: переменная
// экспортирована и изменяема, и подмена ДО первого чтения прошла бы молча. Здесь
// же и установка, и чтение проходят через один замок, поэтому «поздно» —
// наблюдаемое состояние, а не догадка.
func Install(dsl string) error {
	sharedMu.Lock()
	defer sharedMu.Unlock()
	if wasRead {
		return ErrModelAlreadyRead
	}
	if installed {
		return ErrModelAlreadyInstalled
	}
	p, err := New(dsl)
	if err != nil {
		return fmt.Errorf("authzmodel: установка модели процесса: %w", err)
	}
	shared, sharedErr, installed = p, nil, true
	return nil
}

// Shared отдаёт единственный разбор модели ПРОЦЕССА.
//
// Модель процесса — установленная [Install] либо, когда установки не было,
// вшитая. Второго экземпляра не существует: два разбора дали бы форму, где
// входной контроль RPC отвергает корректный запрос, а вердикт его разрешает.
//
// Ошибка разбора возвращается, а не паникует: вызывающий обязан решить, что с
// ней делать. У сборки, где эта ошибка возможна, ровно один разумный исход —
// отказать в старте, — но принимать его за вызывающего значило бы уронить и те
// пути, которым модель не нужна.
func Shared() (*Plans, error) {
	sharedMu.Lock()
	defer sharedMu.Unlock()
	if shared == nil && sharedErr == nil {
		shared, sharedErr = New(DSL)
		if sharedErr != nil {
			sharedErr = fmt.Errorf("authzmodel: разбор вшитой модели: %w", sharedErr)
		}
	}
	// Признак ставится и на ошибке разбора: спросивший модель и получивший отказ
	// всё равно СПРОСИЛ, и последующая установка была бы для него заменой.
	wasRead = true
	return shared, sharedErr
}

// New разбирает НАЗВАННУЮ модель.
//
// Существует потому, что у вопроса «что принимает объявление отношения» есть
// вторая сторона, и живого входа у неё нет: чтобы доказать, что судья отвечает
// «не принимает» там, где не принимает, нужен канон, которого в продукте нет.
// Подать его можно только текстом.
//
// Не «конструктор для проб»: [Shared] выражен через него, поэтому разбор вшитой
// модели и разбор названной — ОДИН код. Заведи их порознь — и доказательство
// поехало бы по одной ветке, а продукт по другой.
//
// Непонятое НЕ пропускается: вход, каноном не являющийся, даёт ошибку, а не
// пустую модель. Пустая модель отвечала бы «такого отношения нет» на всякий
// вопрос — уверенно и о модели, которой не существует.
func New(dsl string) (*Plans, error) {
	m, err := authzplan.ParseModel(dsl)
	if err != nil {
		return nil, fmt.Errorf("authzmodel: разбор модели: %w", err)
	}
	return &Plans{model: m, by: map[string]authzplan.Plan{}}, nil
}

// Plan отдаёт план вывода для отношения типа.
//
// Отсутствие типа или отношения — ОШИБКА, а не пустой план. Пустой план дал бы
// вердикт «нет» на вопрос, которого модель не знает: отказ, объяснимый только
// опечаткой в имени, ищут в правах и не находят.
func (p *Plans) Plan(objectType, relation string) (authzplan.Plan, error) {
	key := objectType + "." + relation

	p.mu.RLock()
	cached, ok := p.by[key]
	p.mu.RUnlock()
	if ok {
		return cached, nil
	}

	plan, err := p.model.Compile(objectType, relation)
	if err != nil {
		return authzplan.Plan{}, fmt.Errorf("authzmodel: %w", err)
	}
	if !plan.Expressible() {
		// Невыразимое называется поимённо. Ответить по неполному плану значило бы
		// дать вердикт, у которого не хватает источников, — и он был бы отказом
		// ровно там, где источник не разобран.
		return authzplan.Plan{}, fmt.Errorf("authzmodel: план %s неполон, не отнесены термы: %v",
			key, plan.Unclassified)
	}

	// `plan.Conditioned` здесь НЕ проверяется, и это решение, а не пропуск (#1979).
	//
	// Отсутствие проверки рядом с проверкой `Unclassified` читается как забытая
	// половина — ею не является. Условие на кортеже до вердикта планом не едет и
	// ехать не должно: оно лежит НА САМОЙ СТРОКЕ факта (`relation_fact`,
	// `condition_name`/`condition_params`) и вычисляется на пути запроса по
	// доводам, приезжающим с вопросом, — свежесть подтверждения личности зависит
	// от «сейчас» и не материализуема ни в какой форме. Строка самоописательна:
	// читателю не нужно знать модель, чтобы соблюсти ограничение. Вывести условие
	// из модели значило бы завести второе место, знающее, при каких условиях
	// действует эта строка, и разойтись с ней в тот момент, когда модель
	// поменяется, а строки останутся.
	//
	// `Conditioned` для потребителя — СПРАВКА: он называет объявления, которые
	// МОГУТ нести условие, и на нём ключуются перечисляющие ответы, у которых
	// доводов запроса нет вовсе.
	//
	// Отвергать план по непустому `Conditioned` было бы НЕ строгостью, а поломкой:
	// в каноне таких пар три (`cluster.console`, `compute_instance.ssh`,
	// `compute_instance.console`), все три — живые отношения, и отказ убил бы их
	// целиком, вместе с их БЕЗУСЛОВНЫМИ источниками (`service_account` у `ssh`,
	// `or admin` у обоих), то есть отобрал бы доступ у тех, чьё право ни от какого
	// условия не зависит.
	//
	// Одно место, где план ДЕЙСТВИТЕЛЬНО потерял бы условие, — прямой список с
	// условием на отношении-ГЛАГОЛЕ: он даёт источник-выдачу, а роль условия нести
	// не может, и право было бы выдано при невыполненном условии. Оно закрыто НЕ
	// здесь и не проверкой `Conditioned`, а САМИМ ПЛАНОМ: такой терм объявляется
	// невыразимым при компиляции, поэтому его ловит проверка `Expressible()`
	// строкой выше — та же, что ловит всякий неразобранный терм.
	//
	// Проверка стоит у порождения атома, а не здесь, потому что различает эти два
	// случая ровно то, КАКОЙ АТОМ порождает терм: привязка условия не несёт, строка
	// факта несёт. У плана несколько потребителей, и решай этот вопрос каждый из
	// них заново — они разошлись бы молча.
	//
	// > [!note] Здесь стояло «этого в модели нет, и держится это гейтом у запроса»
	// > Утверждение было верно для КАНОНА и пережило свой предмет: модель стала
	// > СОБИРАТЬСЯ из доставленных манифестов (#1969), а гейт
	// > `relverdict.TestNoConditionedRelationIsAVerb` читает канон
	// > (`ResolveCanonicalModel`) и доставленного типа не видит by construction.
	// > Имя условия канона доставленному типу доступно — Д4(б) требует ровно его, —
	// > поэтому `[user with mfa_fresh]` на глаголе проходило и разбор, и допуск с
	// > НУЛЁМ находок, а вердикт выдавал право безусловно. Замерено пробой
	// > `TestDeliveredVerbWithConditionIsRefused`, красной до этой правки.
	// > Гейт у запроса не снят: он держит СВОЮ половину — что ветвь выдачи в
	// > verdictSQL вправе объявлять условие пустым, — и остаётся верным про канон.

	p.mu.Lock()
	p.by[key] = plan
	p.mu.Unlock()
	return plan, nil
}

// Declares — объявляет ли модель отношение `relation` у типа `objectType`.
//
// ЭТО ПРЕДПОСЫЛКА КОМПИЛЯЦИИ, СПРОШЕННАЯ ОТДЕЛЬНО. Plan разбирает вывод только
// после того, как убедился в двух вещах: тип объявлен и отношение у него есть.
// Входной контроль RPC обязан судить ТОТ ЖЕ набор — иначе пара из зазора между
// принимаемым и объявленным доезжает до компиляции и возвращает вызывающему
// внутреннюю ошибку на КОРРЕКТНОМ запросе (#1290). «Мы сломались» — неверное
// сообщение: сломались не мы, запрос назвал пару, которой не бывает.
//
// Равенство двух суждений не объявлено, а ДОКАЗАНО по всей модели:
// declares_test.go обходит все типы × все имена отношений и требует
// `Declares(T,R) == (Compile(T,R) без ошибки)` в ОБЕ стороны, печатая объём
// осмотренного.
func (p *Plans) Declares(objectType, relation string) bool {
	t := p.model.Type(objectType)
	return t != nil && t.Rel(relation) != nil
}

// DeclaresType — объявлен ли САМ тип.
//
// Нужен, чтобы отказ называл ВИНОВНОЕ поле: у необъявленного типа не объявлено
// ни одно отношение, поэтому сообщение про отношение увело бы вызывающего
// править не ту координату. Та же предпосылка, на которой компиляция
// останавливается первой (`authzplan.ErrTypeNotDeclared`).
func (p *Plans) DeclaresType(objectType string) bool {
	return p.model.Type(objectType) != nil
}

// Model отдаёт разобранную модель — для гейтов и переписей.
func (p *Plans) Model() *authzplan.Model { return p.model }
