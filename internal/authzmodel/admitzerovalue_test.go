// admitzerovalue_test.go — УМОЛЧАНИЕ отчёта допуска означает самое СТРОГОЕ
// (задача продукта #2000).
//
// # Предмет
//
// [Admit] на входе, который не разобрался, возвращает ошибку и НУЛЕВОЙ
// [AdmissionReport]. У нулевого отчёта `Admitted()` отвечал `true`, а `Census()`
// печатал «находок 0» — то есть отчёт читался как ЧИСТЫЙ. Два состояния были
// инвертированы по безопасности: безобидное («добавлять нечего») отвечало «не
// допущено», опасное («текст не разобрался») — «допущено».
//
// Контракт «вызывающий обязан проверить err раньше Admitted()» ИСПОЛНИМ, но
// естественная форма `rep, err := Admit(x); if !rep.Admitted() { … }` даёт
// fail-open ровно на том входе, ради которого клауза заведена. Величина, которую
// построение подставляет молча, предметом стража быть не может
// (`security.md` §«Пустой список — это „не сужаем"»).
//
// # Почему входов ТРИ, а не два
//
// Без третьего «всегда false» неотличимо от исправленного: проверка, которая
// никого не допускает, зеленела бы на отрицаниях и была бы ровно тем классом,
// который корпус ловит (`testing.md` §«Гейт на класс», п. 2б).

// TestAdmitZeroReportIsNotAdmitted — три входа, три РАЗНЫХ исхода.
func TestAdmitZeroReportIsNotAdmitted(t *testing.T) {
	// ── вход 1: разбор НЕ состоялся ──────────────────────────────────────────
	//
	// `define` вне блока `relations` — разборщик отвергает, [Admit] возвращает
	// ошибку и отчёт. Отчёт обязан отвечать «НЕ допущено».
	unparsable := compose("type acme_widget\n    define v_get: [user, service_account]\n")

	rep, err := Admit(unparsable)
	if err == nil {
		t.Fatalf("предпосылка пробы не создана: ждали отказ разбора, получен отчёт %s", rep.Census())
	}
	if rep.Admitted() {
		t.Fatalf("НЕРАЗБИРАЕМЫЙ вход допущен нулевым отчётом — fail-open; перепись: %s", rep.Census())
	}
	// Перепись обязана НАЗЫВАТЬ предмет: «находок 0» на неразобранном входе
	// читается оператором как «чисто».
	if !strings.Contains(rep.Census(), "суждение не состоялось") {
		t.Fatalf("перепись обязана сказать, что суждения НЕ БЫЛО, иначе «находок 0» "+
			"неотличимо от «прочитано 0»; получено: %s", rep.Census())
	}

	// ── вход 2: законный близнец — судить нечего ─────────────────────────────
	//
	// Голый канон: добавлять нечего. Отвечает «не допущено» по СВОЕЙ причине —
	// третий исход, — и эта причина обязана остаться отличимой от первой.
	bare := mustAdmit(t, DSL)
	if bare.Admitted() {
		t.Fatalf("третий исход НЕ засчитывается в успех; перепись: %s", bare.Census())
	}
	if !bare.NothingToJudge {
		t.Fatalf("голый канон обязан давать третий исход; перепись: %s", bare.Census())
	}
	if strings.Contains(bare.Census(), "суждение не состоялось") {
		t.Fatalf("«судить нечего» и «суждение не состоялось» — РАЗНЫЕ исходы, "+
			"и перепись обязана их различать; получено: %s", bare.Census())
	}

	// ── вход 3: годная композиция ────────────────────────────────────────────
	//
	// Без него «всегда false» неотличимо от починенного.
	good := mustAdmit(t, compose(twin(t)))
	if !good.Admitted() {
		t.Fatalf("годная композиция обязана быть ДОПУЩЕНА, иначе проверка не допускает никого; "+
			"перепись: %s, находки: %v", good.Census(), good.Findings)
	}
}

// TestAdmitZeroValueOfTheTypeIsNotAdmitted — умолчание САМОГО ТИПА, без вызова
// [Admit].
//
// Отдельная проба потому, что предмет другой: выше судится путь ошибки, здесь —
// значение, которое построение подставляет молча. Вызывающий, объявивший
// `var rep AdmissionReport` и не дошедший до вызова (ранний выход, отказ
// соседа), обязан получить СТРОГОЕ умолчание.
func TestAdmitZeroValueOfTheTypeIsNotAdmitted(t *testing.T) {
	var zero AdmissionReport
	if zero.Admitted() {
		t.Fatal("нулевое значение AdmissionReport отвечает «допущено» — " +
			"умолчание типа обязано означать самое СТРОГОЕ, а не самое разрешительное")
	}
}
