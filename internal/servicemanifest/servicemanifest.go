// Package servicemanifest — НОСИТЕЛЬ манифеста самой службы доступа, встроенного в
// образ (приёмка MRW-1, решение Р2; задача kaname#106).
//
// # Зачем манифесту службы нужен свой носитель
//
// Манифесты модулей платформы доезжают до службы ДОСТАВКОЙ: ConfigMap собирает
// обход дерева платформы, а службы там больше нет ни одним файлом, и копия её
// манифеста в чужом репозитории запрещена решением владельца (ban #20). Значит у
// собственного манифеста — того, чей раздел `seed` объявляет группу пишущих
// кортежи и её выдачу, — на пути старта не было ни одного читателя: ни доставки,
// ни встроенности, ни монтирования. Объявление без производителя — класс
// «принято-и-проигнорировано», и закрывается он здесь.
//
// # Почему копия, а не путь в образе и не свой чарт
//
// Директива встраивания привязана к каталогу пакета и родительского каталога не
// принимает (`//go:embed ../../manifest.yaml` → invalid pattern syntax), поэтому
// копия лежит ЗДЕСЬ. Путь в образе завёл бы ручку посадки там, где величина не
// имеет законного разброса, и стража, различающего «не задан» от «не читается».
// Свой чарт, монтирующий манифест в каталог доставки, положил бы его в перечень,
// который читают ПЯТЬ потребителей старта, а решение Р3 требует ровно одного.
//
// # Копий ДВЕ, и равенство держат два артефакта РАЗНОГО рода
//
// Ровно та же цена уже принята у канона модели прав (`internal/authzmodel`):
// цель сборки `make service-manifest-embed` копию ПОРОЖДАЕТ и тут же сверяет
// `cmp`; побайтовое равенство с `manifest.yaml` дерева ДЕРЖИТ проба
// `TestEmbeddedManifestIsByteIdenticalToTheTree`. Цель равенства не держит — она
// его восстанавливает; проба его не восстанавливает — она его судит.
//
// # Почему копия названа НЕ `manifest.yaml`
//
// Оснастка дерева опознаёт манифест модуля по базовому имени файла
// (`manifest.TreeFileName()`), и второй `manifest.yaml` в дереве был бы вторым
// объявлением модуля `iam` — находкой `ErrModuleCollision` by construction.
// Копия поэтому носит имя, которое обход дерева манифестом не считает, а
// содержимым равна ему побайтово: до старта доезжает ровно тот документ, который
// оснастка судила.
//
// # Что этот пакет НЕ делает
//
// Он не судит форму (это `internal/manifest`) и не применяет посев (это
// `internal/apps/kaname/moduleseed`). Он отдаёт документ композиционному корню
// готовым доводом — и никому больше: решение о том, кто из потребителей перечня
// доставки получает манифест службы, записано в Р3 и не здесь.
package servicemanifest

import (
	_ "embed"
	"fmt"

	"github.com/PRO-Robotech/kaname/internal/manifest"
)

// raw — побайтовая копия `manifest.yaml` дерева. Порождается
// `make service-manifest-embed`; правится ТОЛЬКО манифест дерева.
//
//go:embed manifest.embedded.yaml
var raw []byte

// Raw — встроенный документ как есть. Нужен пробе равенства и никому больше:
// потребитель старта берёт разобранный документ через [Load].
func Raw() []byte { return raw }

// Load разбирает встроенный манифест ТЕМ ЖЕ загрузчиком, что читает манифесты
// дерева и доставки, и без оракула модели прав.
//
// Без оракула — решение, а не умолчание (Р3): на пути старта модель ещё
// собирается из доставленного, и спрашивать её здесь значило бы спрашивать у
// ответа. Отношение и вид получателя своего манифеста судит оснастка дерева
// (`make module-manifest-check`, `iamctl validate`), а копия побайтово равна
// тому, что она судила.
func Load(opts ...manifest.LoadOption) (*manifest.Manifest, error) {
	m, err := manifest.Load(raw, opts...)
	if err != nil {
		return nil, fmt.Errorf("встроенный манифест службы: %w", err)
	}
	return m, nil
}
