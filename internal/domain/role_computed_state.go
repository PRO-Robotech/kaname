package domain

// role_computed_state.go — ПРОЕКЦИЯ роли для ответа операции: без вычисленного
// состояния.
//
// # Что обещано арендатору
//
// Нулевые `health` и `lifecycle` означают «ЭТИМ ОТВЕТОМ НЕ ВЫЧИСЛЕНО» и никогда
// «роль здорова» либо «роль объявлена». То же говорят счётчики сегментов, обе
// ведомости и состояния правил. Обещание записано на странице ресурса и в
// комментариях полей выше, и адресовано оно ответам `Create`/`Update`: их
// читает клиент, только что изменивший роль.
//
// # Почему это ПРОЕКЦИЯ, а не запрет вызывать производителя
//
// До заведения этой функции обещание держалось тем, что производителя
// вычисленного состояния никто не звал на пути мутации. Такое свойство
// снимается ОДНОЙ СТРОКОЙ и снимается ТИХО: ни сборка, ни прогон, ни обзор
// изменения не отличат ответ операции с посчитанным состоянием от ответа без
// него — оба валидны по форме.
//
// Обнуление закрывает не один путь к нарушению, а ВСЕ, включая те, которых
// сегодня нет.
//
// # И это НЕ «выбросить полезное»
//
// Состояние роли выводится из проекции прав. На пути мутации она либо ещё не
// изменена, либо уже изменена, но не тем, что вернётся клиенту, — то есть
// посчитанное там состояние относится к ДРУГОМУ снимку. Ответить им значило бы
// назвать состояние, которого у роли не было ни до мутации, ни после.
//
// Заводя ШЕСТОЕ производное поле, снимай его здесь же: держит это проба
// `role_computed_state_test.go`, сверяющая МНОЖЕСТВО полей контракта, которые
// проекция меняет, — не их число.

// WithoutComputedState — копия роли без вычисленного состояния.
//
// Приёмник — ЗНАЧЕНИЕ, и это не стиль: вызывающий переводит роль в ответ
// операции и продолжает пользоваться своей, поэтому проекция обязана быть
// неразрушающей.
//
// TypeVerbs НЕ обнуляется намеренно: у него нулевое значение означает не «не
// вычислено», а ОТКАЗ проекции (см. комментарий поля), и путь мутации его
// заполняет сам — превью глаголов роль несёт и в ответе операции.
func (r Role) WithoutComputedState() Role {
	r.Integrity = RoleIntegrity{}
	r.Lifecycle = RoleLifecycle{}
	r.Withdrawn = nil
	r.PrunedSelectorTypes = nil
	r.RuleStates = nil
	return r
}
