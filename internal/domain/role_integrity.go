import "time"

// role_integrity.go — целость роли: даёт ли она то, что объявляет.
//
// # Откуда берутся ОБЕ величины, и почему не из каталога
//
// Роль ссылается на типы и глаголы каталога платформы, и ссылка теряет референт
// двумя путями: тип объявлен, но модель прав его не знает (форма инцидента
// миграции 513001), либо строка каталога снята применением манифеста.
//
// Величины сравниваются такие:
//
//   - ОБЪЯВЛЕНО — сегменты авторского правила ([RuleRefsOf]). Авторское правило
//     переселение НЕ трогает, поэтому оно уцелевает там, где обе проекции
//     согласованно укорачиваются;
//   - СПРОЕЦИРОВАНО — строки `kacho_iam.role_verb`, единственной таблицы,
//     которую читает цепь вердикта.
//
// Каталог источником состояния быть НЕ МОЖЕТ: в случае 513001 его написание
// законно, а проекция пуста, — и роль, судимая по каталогу, читалась бы
// здоровой. Ведомость сирот только ОБЪЯСНЯЕТ: у роли, пострадавшей по первому
// пути, переселения не было вовсе, и ведомость о ней пуста.
//
// Хранимой колонки у состояния нет намеренно: двенадцать ролей инцидента 513001
// заведены МИГРАЦИЕЙ, и колонку не проставил бы никто — то есть хранимое
// состояние не поймало бы тот самый случай, ради которого заводится.

// RoleHealth — состояние целости роли.
//
// Нулевой вариант несёт ЕДИНСТВЕННЫЙ смысл: «этим ответом не вычислено». Он не
// является ни одним из трёх исходов и [HealthOf] его не возвращает никогда —
// иначе «посчитано, терять нечего» стало бы неотличимо от «не считали».
type RoleHealth uint8

const (
	// RoleHealthUnknown — не вычислено ЭТИМ ответом. НИКОГДА не «здорова».
	RoleHealthUnknown RoleHealth = iota
	// RoleHealthHealthy — каждый адресуемый сегмент имеет строку проекции.
	RoleHealthHealthy
	// RoleHealthDegraded — часть сегментов проекции не даёт, часть даёт.
	RoleHealthDegraded
	// RoleHealthEmpty — сегменты объявлены, проекции нет НИ ОДНОЙ.
	RoleHealthEmpty
)

// RoleIntegrity — состояние целости и пара величин, из которых оно выведено.
//
// Счётчики без состояния были бы двусмысленны: ноль есть И законная величина
// (роль без адресуемых сегментов), И признак «не считали». Разводит их
// [RoleHealth]: у вычисленной целости состояние непустое всегда.
type RoleIntegrity struct {
	Health RoleHealth
	// Declared — сколько адресуемых сегментов объявляют правила роли.
	Declared int
	// Unresolved — сколько из них не дают ни одной строки проекции.
	Unresolved int
}

// HealthOf выводит состояние из пары величин. ЕДИНСТВЕННОЕ место, где решается,
// какое состояние несёт роль.
//
// Роль без адресуемых сегментов (подстановка в модуле и ресурсе — форма `*.*`
// администратора кластера, либо унаследованная роль без правил) читается
// ЗДОРОВОЙ, а не пустой: терять ей нечего, и тревога на ней была бы ложной.
// Прибор, чьи находки ложны, перестают читать — вместе с настоящими находками.
func HealthOf(declared, unresolved int) RoleIntegrity {
	out := RoleIntegrity{Declared: declared, Unresolved: unresolved}
	switch {
	case declared == 0, unresolved == 0:
		out.Health = RoleHealthHealthy
	case unresolved >= declared:
		out.Health = RoleHealthEmpty
	default:
		out.Health = RoleHealthDegraded
	}
	return out
}

// RoleSegment — объявленный сегмент роли в форме, которой спрашивают проекцию.
//
// Точечный тип приходит ОДНИМ выражением ([RoleRuleRef.Dotted]) — тем же, каким
// его строит переселение и каким его хранит каталог. Второе написание разошлось
// бы молча: соединение по разным словарям не совпадает никогда.
type RoleSegment struct {
	RoleID     RoleID
	ObjectType string
	// Verb — пустая строка означает ЯКОРЬ (правило не сузило глаголы): годится
	// любая строка проекции своего типа.
	Verb string
}

// SegmentsOf — объявленные сегменты роли в форме вопроса к проекции.
func SegmentsOf(id RoleID, rules Rules) []RoleSegment {
	refs := RuleRefsOf(rules)
	out := make([]RoleSegment, 0, len(refs))
	for _, ref := range refs {
		out = append(out, RoleSegment{RoleID: id, ObjectType: ref.Dotted(), Verb: ref.Verb})
	}
	return out
}

// WithdrawnGrantSource — из какой проекции правила переселена строка ведомости.
//
// Популяции разделены намеренно: «право отобрано» и «правило перестало
// резолвиться» — разные события для того, кто разбирает последствия, и сложив
// их, мы потеряли бы именно это различие.
type WithdrawnGrantSource uint8

const (
	// WithdrawnGrantSourceUnknown — популяция не прочитана ЭТИМ ответом. Никогда
	// не означает «популяция неизвестна»: ведомость несёт её всегда, закрытым
	// набором на уровне схемы.
	WithdrawnGrantSourceUnknown WithdrawnGrantSource = iota
	// WithdrawnGrantSourceGrant — выдача глагола: право по паре действовало и
	// перестало.
	WithdrawnGrantSourceGrant
	// WithdrawnGrantSourceRuleRef — объявление правила: сегмент перестал
	// резолвиться в каталог.
	WithdrawnGrantSourceRuleRef
)

// WithdrawnGrant — одна проекция правила роли, потерявшая референт при снятии
// строки каталога платформы и ПЕРЕСЕЛЁННАЯ в ведомость, а не отобранная молча.
//
// # Зачем этот тип, когда рядом уже стоят счётчики
//
// [RoleIntegrity] отвечает СКОЛЬКО сегментов перестало проецироваться и не
// отвечает, ЧТО именно и почему. Со стороны арендатора «право отобрали» без
// этого неотличимо от «права не было»: свою роль он не менял, а действовать она
// перестала.
//
// # Он ОБЪЯСНЯЕТ состояние и не определяет его
//
// Целость выводится из того, что читает вердикт, а не из ведомости: у роли,
// пострадавшей вторым путём (тип объявлен, а модель прав его не знает),
// переселения не было ВОВСЕ, и ведомость о ней пуста при нездоровом состоянии.
// Судить целость по ведомости значило бы читать такую роль здоровой — форма
// инцидента 513001.
type WithdrawnGrant struct {
	// ObjectType — точечный тип объекта, чью строку каталога сняли.
	ObjectType string
	// Verb — глагол. ПУСТАЯ строка есть ЯКОРЬ объявления правила, а не «любой
	// глагол»: у объявления, не назвавшего глагол поимённо, его нет.
	Verb string
	// Source — из какой проекции переселена строка.
	Source WithdrawnGrantSource
	// Reason — причина снятия строки каталога, записанная применителем
	// манифеста. Причина ПЛАТФОРМЫ, а не действие арендатора.
	Reason string
	// WithdrawnAt — момент переселения. Время ТРАНЗАКЦИИ применения: у всего,
	// что отобрано одним применением, он совпадает дословно.
	WithdrawnAt time.Time
	// AppliedBy — АВТОР применения, снявшего эту строку (#2005): проверенная
	// личность вызывающего на пути глагола либо названный процессный актор на
	// пути старта. НЕ учётка, под которой исполнялась транзакция.
	//
	// Для разбора «почему у меня отобрали право» это второй по важности вопрос
	// после «почему»: причина называет, ЧТО случилось с платформой, а автор — КТО
	// это сделал.
	//
	// ПУСТАЯ строка означает «строка переселена ДО заведения колонки», а не
	// «автора потеряли»: восстановить его у таких строк не из чего.
	AppliedBy string
	// Cause — ПОЧЕМУ строка переселена (#1913). Различие наблюдаемо, потому что
	// от него зависит поведение: оживление роли снимает строки причины
	// [WithdrawnGrantCauseRoleRetired] и не трогает строк причины
	// [WithdrawnGrantCauseCatalogRetired].
	//
	// Отличается от [WithdrawnGrant.Source] предметом: тот называет, ИЗ КАКОЙ
	// проекции строка переселена, этот — ПОЧЕМУ. Величины независимы: каждая
	// причина встречается у обеих популяций.
	Cause WithdrawnGrantCause
}

// WithdrawnGrantCause — почему проекция переселена в ведомость.
//
// Нулевой вариант означает «этим ответом не вычислено» и НИКОГДА «причина
// неизвестна»: непонятая строка ведомости отвергается разбором, а не выдаётся
// за невычисленную.
type WithdrawnGrantCause uint8

const (
	// WithdrawnGrantCauseUnknown — не вычислено ЭТИМ ответом.
	WithdrawnGrantCauseUnknown WithdrawnGrantCause = iota
	// WithdrawnGrantCauseCatalogRetired — снята строка КАТАЛОГА платформы, на
	// которую ссылалось правило. Роль при этом объявлена и жива.
	WithdrawnGrantCauseCatalogRetired
	// WithdrawnGrantCauseRoleRetired — снята САМА РОЛЬ. Возврат объявления
	// оживляет её и снимает эти строки.
	WithdrawnGrantCauseRoleRetired
)

// SelectorPruneOutcome — что стало со строкой ОТБОРА, из которой вырезан тип.
//
// Величины разделены намеренно: строка, потерявшая последний живой тип, снята
// целиком — правило перестало отбирать вовсе; строка, у которой живой тип
// остался, укорочена — правило сузилось. Для разбирающего последствия это
// события разного рода, и сложив их, мы потеряли бы ровно это различие.
type SelectorPruneOutcome uint8

const (
	// SelectorPruneOutcomeUnknown — исход не прочитан ЭТИМ ответом. Никогда не
	// означает «исход неизвестен»: ведомость несёт его всегда, закрытым набором
	// на уровне схемы (`role_selector_prune_outcome_known`).
	SelectorPruneOutcomeUnknown SelectorPruneOutcome = iota
	// SelectorPruneOutcomeShortened — живой тип у строки остался, она укорочена:
	// правило продолжает отбирать, но уже меньше.
	SelectorPruneOutcomeShortened
	// SelectorPruneOutcomeDropped — живого типа не осталось, строка снята
	// целиком: правило не отбирает ничего.
	SelectorPruneOutcomeDropped
)

// PrunedSelectorType — точечный тип, ВЫРЕЗАННЫЙ применителем каталога из отбора
// правила роли при снятии строки ресурса платформы (#1988).
//
// # Чем это отличается от соседней [WithdrawnGrant], и почему они не сложены
//
// Переселение адресуется парой «тип объекта + глагол» и означает «право по этой
// паре действовало и перестало». Вырезание глагола не имеет ВООБЩЕ: отбор
// правила называет типы, а не пары, — поэтому у него своя ведомость и свой тип
// здесь. Сложить их значило бы дать вырезанному пустой глагол, а пустой глагол
// в соседе есть ЯКОРЬ объявления правила, то есть уже занятое значение.
//
// # Отпечаток правила сюда НЕ ПЕРЕЕЗЖАЕТ
//
// Ведомость ключуется тройкой «роль + отпечаток правила + тип»: отпечаток нужен
// ХРАНЕНИЮ, чтобы два правила, потерявшие один тип, не схлопнулись в одну
// строку. Читающему он не нужен и не отдаётся — это содержательный хеш, которого
// нет ни в одном контракте платформы; выставь мы его, способ хеширования стал бы
// частью контракта, а арендатор своё правило знает содержанием, а не дайджестом.
//
// Следствие названо прямо: строки, различавшиеся ТОЛЬКО отпечатком, для
// читающего есть ОДИН факт и произносятся один раз.
type PrunedSelectorType struct {
	// ObjectType — точечный тип объекта, чью строку каталога сняли.
	ObjectType string
	// Outcome — что стало со строкой отбора, из которой тип вырезан.
	Outcome SelectorPruneOutcome
	// Reason — причина снятия строки каталога, записанная применителем
	// манифеста. Причина ПЛАТФОРМЫ, а не действие арендатора: своё правило он не
	// менял. ПУСТАЯ строка означает «строка каталога причины не несла» (снята
	// ранней миграцией), а не «причину потеряли».
	Reason string
	// PrunedAt — момент вырезания. Время ТРАНЗАКЦИИ применения: у всего, что
	// вырезано одним применением, он совпадает дословно.
	PrunedAt time.Time
	// AppliedBy — АВТОР применения, вырезавшего этот тип (#2005). Та же величина
	// и тот же источник, что у соседа: вопрос «кто снял» у обеих ведомостей
	// общий — арендатор не различает, какой из проекций правила он лишился.
	//
	// ПУСТАЯ строка означает «строка вырезана ДО заведения колонки».
	AppliedBy string
}
