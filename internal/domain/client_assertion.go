// client_assertion.go — доменные понятия аутентификации клиента подписанным
// утверждением (задача #898, приёмка F2).
//
// # Что здесь и чего здесь нет
//
// Здесь — понятия, о которых обязаны договориться ВСЕ слои: чем клиент себя
// называет, из какого реестра он разрешается, и чем отличается повтор от
// первого предъявления. Разбор подписи, чтение базы и форма HTTP-ответа живут
// у своих слоёв: домен о них не знает (чистый Go, только stdlib).
package domain

import (
	"errors"
	"fmt"
	"strings"
)

// ── Однократность ───────────────────────────────────────────────────────────

// ErrAssertionReplayed — утверждение с этим идентификатором однократности уже
// предъявлялось ЭТИМ клиентом.
//
// Отдельный признак, а не общий отказ: наружу все отказы аутентификации
// неразличимы (приёмка F2 §7), но ВНУТРЬ различимость обязана существовать —
// иначе счётчик исхода не с чем связать, и мёртвый контроль становится
// невидимым.
var ErrAssertionReplayed = errors.New("client assertion: single-use identifier already redeemed")

// IsAssertionReplayed отвечает, отвергнуто ли предъявление как ПОВТОР.
//
// Предикат, а не сравнение на месте: вызывающие обёртывают ошибку контекстом, и
// сравнение `err == ErrAssertionReplayed` перестало бы работать на первом же
// обёртывании — молча, потому что «не повтор» и «не смогли распознать»
// выглядят одинаково.
func IsAssertionReplayed(err error) bool { return errors.Is(err, ErrAssertionReplayed) }

// ── Реестр, способный к утверждению ─────────────────────────────────────────

// ErrAssertionClientUnknown — идентификатор не резолвится ни в одну строку
// реестра, СПОСОБНОГО к утверждению.
//
// Один признак на два состояния — «строки нет вовсе» и «строка есть у вида
// клиента, не располагающего ключевым материалом», — и это не упрощение, а
// требование: различимые исходы дали бы предъявителю ОРАКУЛ существования. Он
// сообщал бы, заведён ли такой клиент, а по нему устанавливают и то, каким
// именно видом он заведён.
var ErrAssertionClientUnknown = errors.New("client assertion: client does not resolve in a registry able to assert")

// IsAssertionClientUnknown отвечает, не резолвится ли клиент.
func IsAssertionClientUnknown(err error) bool { return errors.Is(err, ErrAssertionClientUnknown) }

// AssertionClientKind — вид клиента, способного доказать владение ключом.
//
// Словарь ЗАКРЫТ и содержит ровно те виды, у которых в схеме есть ключевой
// материал. Интерактивного клиента здесь нет НАМЕРЕННО: у него нет способа
// доказать владение ключом by construction, поэтому он не резолвится ни во
// что, и отказ наступает на том же шаге, что и для несуществующего клиента
// (приёмка F2 §2.9). Формулировка «нашли строку, ключ пуст» потребовала бы,
// чтобы кто-то поддерживал в третьей таблице инвариант «ключа быть не должно»;
// инвариант, который надо поддерживать, ломается, а выраженный отсутствием
// таблицы на пути — нет.
type AssertionClientKind string

const (
	// AssertionClientUser — клиент, через который выдаётся токен пользователя.
	AssertionClientUser AssertionClientKind = "user"
	// AssertionClientServiceAccount — клиент ключа служебной учётки.
	AssertionClientServiceAccount AssertionClientKind = "service_account"
)

// AssertionClientKinds возвращает закрытый словарь целиком.
func AssertionClientKinds() []AssertionClientKind {
	return []AssertionClientKind{AssertionClientUser, AssertionClientServiceAccount}
}

// AssertionClient — строка реестра, способная предъявить утверждение.
//
// Зеркального значения (идентификатора клиента во внешнем сервере) здесь НЕТ, и
// это не упущение: оно не участвует в разрешении клиента ни как второй ключ
// поиска, ни как запасной (приёмка F2 §2.1). Субъект с двумя именами дал бы две
// записи журнала об одном действии и два ключа однократности на одно
// утверждение — то есть отменил бы однократность, сохранив её форму.
type AssertionClient struct {
	// ID — НАШ идентификатор строки реестра. Им и только им клиент себя
	// называет: он же издатель и субъект утверждения.
	ID string
	// Kind — из какой таблицы реестра строка прочитана.
	Kind AssertionClientKind
	// OwnerID — принципал, от чьего имени клиент получает токен.
	OwnerID string
	// PublicKeyPEM — зарегистрированный открытый ключ.
	PublicKeyPEM string
	// Algorithm — ЗАРЕГИСТРИРОВАННЫЙ алгоритм. Пустое значение — законный вход
	// схемы, и означает оно «ключа нет», а НЕ «любой алгоритм».
	Algorithm string
	// ExpiresAt — момент истечения клиента в Unix-секундах; 0 означает
	// «бессрочно», и это законное состояние схемы (колонка допускает NULL).
	ExpiresAt int64
	// Отзыв ключа НЕ является здесь полем, и это не упущение: колонки отзыва в
	// схеме обеих таблиц НЕТ — отзыв выражен СНЯТИЕМ СТРОКИ. Завести поле
	// значило бы описать состояние, которого схема не допускает, и построить
	// на нём пробу, которую нечем поставить (F1 §14 п. 2). Отозванный клиент
	// не резолвится вовсе, и отказ наступает на том же шаге, что для
	// несуществующего, — то есть требование «отозванный токена не получает»
	// выполняется by construction, а не проверкой поля.
	// OwnerActive — владелец в состоянии ACTIVE. Не-ACTIVE — это ДВА значения
	// словаря (PENDING и BLOCKED), и оба обязаны давать один исход.
	OwnerActive bool
	// DeclaredAudiences — сужение адресатов, ОБЪЯВЛЕННОЕ заказчиком ключа при
	// его выдаче (`IssueSAKeyRequest.audience`, задача #1136).
	//
	// ПУСТОЙ ПЕРЕЧЕНЬ ОЗНАЧАЕТ «СУЖЕНИЯ НЕ ОБЪЯВЛЕНО», А НЕ «ЛЮБОЙ АДРЕСАТ», и
	// это НЕ тот класс, что пустой список доверенных отправителей. Там пустое
	// значение снимало единственный контроль; здесь оно оставляет ВНЕШНЮЮ
	// границу — объявленный посадкой перечень адресатов, который страж старта
	// требует непустым и без которого выдача не строится вовсе. Сужение ключа
	// действует ВНУТРИ этой границы и никогда её не расширяет: адресат, которого
	// посадка не объявила, не выдаётся ни одному ключу, как бы он ни объявился.
	//
	// У клиента пользовательского токена перечня нет BY CONSTRUCTION: адресата
	// его токена проставляет сам сервис из своей настройки, и заказчик не вправе
	// назвать его вовсе (решение Р2, `interactive_client.proto`). Поэтому сужать
	// там нечем, и пустое значение на том пути — не умолчание, а отсутствие
	// предмета.
	DeclaredAudiences []string
}

// CanPresentAssertion отвечает, способна ли строка вообще участвовать в
// аутентификации утверждением.
//
// Пустой зарегистрированный алгоритм и пустой ключ — «ключа нет». Это тот же
// класс, что пустой список доверенных отправителей: значение, которое может
// быть пустым и не проверено на непустоту, означает «не сужаем».
func (c AssertionClient) CanPresentAssertion() bool {
	return strings.TrimSpace(c.Algorithm) != "" && strings.TrimSpace(c.PublicKeyPEM) != ""
}

// ── Идентификатор однократности ─────────────────────────────────────────────

// MaxAssertionIDLength — потолок длины идентификатора однократности.
//
// Значение выбирает ПРЕДЪЯВИТЕЛЬ, поэтому его длина — это его выбор нашего
// расхода. Потолок повторяет ограничение схемы: два места об одном предмете
// разошлись бы молча, поэтому проба сверяет их между собой.
const MaxAssertionIDLength = 256

// ValidateAssertionID проверяет форму идентификатора однократности ДО того, как
// он попадёт в хранилище.
//
// Отказ здесь наступает раньше обращения к базе — иначе потолок держало бы
// ограничение схемы, а вызывающий получал бы отказ хранилища вместо отказа
// формы, и счётчик исхода двигался бы не тот.
func ValidateAssertionID(raw string) error {
	switch {
	case raw == "":
		return fmt.Errorf("client assertion: single-use identifier is required")
	case len(raw) > MaxAssertionIDLength:
		return fmt.Errorf("client assertion: single-use identifier is longer than %d bytes", MaxAssertionIDLength)
	}
	return nil
}
