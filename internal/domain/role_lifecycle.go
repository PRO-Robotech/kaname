package domain

import "time"

// role_lifecycle.go — ЖИЗНЕННОЕ СОСТОЯНИЕ самой роли: объявлена она манифестом
// модуля сегодня либо снята.
//
// Приёмка `services/iam/docs/engineering/acceptance/role-withdrawal-has-a-producer.md`
// §2.6; задача продукта #1913.
//
// # Почему это ОТДЕЛЬНОЕ состояние, а не значение целости
//
// [RoleHealth] отвечает на вопрос «даёт ли роль то, что объявляет», и у него
// есть исход `RoleHealthEmpty` — «сегменты объявлены, проекции нет ни одной».
// Снятая роль даёт ровно его; но ЕГО ЖЕ даёт и совсем другое состояние — роль
// объявлена, а строки каталога под её сегментами сняты.
//
// Различие для арендатора существенно, и следующий шаг у него разный:
//
//	снята      роль не заработает НИКОГДА, пока модуль не объявит её снова
//	объявлена  роль остаётся объявленной, и чинится это на стороне платформы
//
// Сложить два состояния в одно значение — тот же класс, что сложить «не
// вычислено» и «здорова».
//
// # Нулевое значение означает «этим ответом не вычислено»
//
// Ровно как у [RoleHealth] рядом, и по той же причине: ответ операции
// (`Create`/`Update` → `Operation.response`) состояния не несёт, а заполняют его
// ЧТЕНИЯ — `Get` и `List`, одинаково и одним производителем.

// RoleLifecycleState — объявлена роль манифестом либо снята.
//
// Нулевой вариант несёт ЕДИНСТВЕННЫЙ смысл: «этим ответом не вычислено». Он не
// является ни одним из двух исходов, и путь чтения его не возвращает никогда —
// иначе «прочитано, роль объявлена» стало бы неотличимо от «не читали».
type RoleLifecycleState uint8

const (
	// RoleLifecycleUnknown — не вычислено ЭТИМ ответом. НИКОГДА не «объявлена».
	RoleLifecycleUnknown RoleLifecycleState = iota
	// RoleLifecycleDeclared — строка жива: объявление за ней стоит.
	RoleLifecycleDeclared
	// RoleLifecycleWithdrawn — строка помечена снятой: объявления больше нет.
	RoleLifecycleWithdrawn
)

// String — состояние словом. Для журналов и текстов отказа, не для контракта.
func (s RoleLifecycleState) String() string {
	switch s {
	case RoleLifecycleDeclared:
		return "объявлена"
	case RoleLifecycleWithdrawn:
		return "снята"
	default:
		return "не вычислено"
	}
}

// RoleLifecycle — состояние роли и обстоятельства её снятия.
//
// Три сопутствующие величины непусты ТОЛЬКО у снятой роли, и это свойство
// СХЕМЫ, а не кода: `roles_live_matches_retired` делает состояние «снята и
// жива» неконструируемым.
type RoleLifecycle struct {
	State RoleLifecycleState
	// RetiredAt — момент снятия. Нулевое время у объявленной роли.
	RetiredAt time.Time
	// RetiredReason — причина снятия. Без неё «отобрали» неотличимо от
	// «сломалось».
	RetiredReason string
	// RetiredBy — кто снял. Сегодня производитель один — путь старта, и он
	// называет процессного актора; глагол применения придёт с `#1034` и назовёт
	// проверенную личность вызывающего. Пустая строка у снятой роли означает
	// «помечено до заведения колонки», а не «автора потеряли».
	RetiredBy string
}

// Withdrawn — снята ли роль. Отдельный вопрос от `State != Declared`: у
// невычисленного состояния ответ «нет», и он верен — утверждать снятие по
// молчанию нельзя.
func (l RoleLifecycle) Withdrawn() bool { return l.State == RoleLifecycleWithdrawn }

// RoleRetirement — перепись ОДНОГО отзыва роли: что унесено и что помечено.
//
// Числа возвращаются, а не логируются внутри: вызывающий собирает из них
// перепись применения, а «снято» без чисел неотличимо от «прошло мимо».
type RoleRetirement struct {
	// Marked — строка роли помечена снятой. Ложно означает, что оператор пометки
	// не нашёл своей строки: роль уже снята либо владелец не тот.
	Marked bool
	// ResettledVerbs — строк проекции глаголов переселено в ведомость и снято.
	ResettledVerbs int
	// ResettledRuleRefs — строк проекции сегментов переселено и снято.
	ResettledRuleRefs int
	// RemovedSelectors — строк проекции отбора снято. В ведомость они не
	// переселяются: у строки селектора нет пары «тип + глагол», которой
	// адресуются сироты.
	RemovedSelectors int
	// RemovedTargetMembers — строк материализованного состава цели снято.
	RemovedTargetMembers int
}
