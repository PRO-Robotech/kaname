package domain

import (
	"crypto/md5" // #nosec G501 -- деривация детерминированного идентификатора (обязана совпадать с постгресовым md5() применённых миграций), не примитив защиты
	"encoding/hex"
)

// derived_id.go — ЕДИНСТВЕННОЕ объявление деривации детерминированного
// идентификатора (приёмка `roles-come-as-data-not-migrations.md` §3.3).
//
// # Почему это ОДНО объявление на дерево, а не удобная копия рядом
//
// Идентификатор системной роли есть функция её ИМЕНИ: применённые миграции
// адресуют строку выражением `'rol' || substr(md5('<имя>'), 1, 17)`, и на этот
// идентификатор ссылаются выданные права (`access_bindings_role_fk`). Две копии
// формулы разойдутся МОЛЧА — и разойдутся ровно там, где обе отвечают
// «идентификатор вычислен»: полученное значение остаётся синтаксически верным и
// перестаёт находить строку. Наблюдаемо это только по отказу в доступе у
// арендатора, у которого право не отзывали.
//
// До этой правки копий было ДВЕ — `bootstrap_token` и `authzguard`, — и обе
// несли собственное объявление одной и той же формулы. Обе теперь зовут отсюда;
// свойство «объявление одно» держит гейт дерева
// `internal/repohygiene` `TestDeterministicIDDerivationIsDeclaredOnce`, а не эта
// фраза.
//
// # Почему функция, а не ограничение таблицы
//
// `CHECK`, требующий такой формы `id`, отверг бы ПОЛЬЗОВАТЕЛЬСКИЕ роли: они
// адресуются `ids.NewID(PrefixRole)` — крокфордовой базой-32, а не
// шестнадцатеричной. В одной таблице живут две схемы идентичности, и это
// законно: системную роль адресуют по имени из другого кластера,
// пользовательскую — нет.
//
// # Граница нормы названа, иначе норма была бы ложью
//
// Деривации подчиняются не ВСЕ системные роли: у `kacho-system.admin` и
// `kacho-system.viewer` идентификаторы рукописные (`0001_initial.sql`,
// «hand-rolled deterministic ids»), и миграция называет их такими своим
// комментарием. Обе роли — вне набора модулей платформы
// (`authzmap.CatalogSeedModules`), поэтому манифестом невыразимы и применителю
// не достаются.

// derivedIDSuffixLen — длина суффикса, которой адресуют строки применённые
// миграции. Шестнадцать вместо семнадцати дают идентификатор ВЕРНОЙ ФОРМЫ, не
// совпадающий ни с одной существующей строкой, — поэтому величина названа
// здесь, а не вписана в выражение среза.
const derivedIDSuffixLen = 17

// DerivedIDSuffix возвращает первые семнадцать шестнадцатеричных символов
// `md5(seed)` — дословно то же, что постгресовое `substr(md5(seed), 1, 17)`.
//
// Все шестнадцатеричные символы годны как крокфордова база-32
// (`0-9a-f` ⊂ `[0-9a-hjkmnp-tv-z]`), поэтому производные идентификаторы проходят
// ограничения формы `soc_`/`cag_`.
//
// Ничего секретного здесь нет: вход — посевные строки, выход — публичные
// идентификаторы. Дайджест зафиксирован уже применённой миграцией, поэтому иной
// дайджест был бы не «крепче», а просто перестал бы адресовать существующие
// строки.
func DerivedIDSuffix(seed string) string {
	sum := md5.Sum([]byte(seed)) // #nosec G401 -- детерминированный идентификатор (обязан совпадать с постгресовым md5()), не примитив защиты
	return hex.EncodeToString(sum[:])[:derivedIDSuffixLen]
}

// SystemRoleID — идентификатор системной роли по её ИМЕНИ.
//
// Имя роли берётся ДОСЛОВНО: приведение имени к другому написанию перед
// хешированием (змеиное к камельному и обратно) даёт другой идентификатор и
// разрывает выданные права. Имя роли и имя ресурса — разные словари, и
// применитель их не сводит (приёмка §3.7).
func SystemRoleID(name RoleName) RoleID {
	return RoleID(PrefixRole + DerivedIDSuffix(string(name)))
}
