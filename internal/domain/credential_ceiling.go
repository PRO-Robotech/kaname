package domain

// Подчинённые ресурсы и применимость областей величины.
//
// Задача `PRO-Robotech/kacho#1191`, приёмка
// `services/iam/docs/engineering/acceptance/credential-ceiling-per-principal.md`
// (§3.3, §4).

// SubordinateResource — ресурс, адресуемый арендатором и НЕ имеющий своего типа
// модели прав, потому что доступ к нему производен от РОДИТЕЛЯ.
//
// # Зачем понадобился второй источник имён
//
// Вид учёта обязан называть реальные типы модели прав — так гейт каталога и
// устроен, и обоснован он утверждением «модель прав знает КАЖДЫЙ адресуемый
// арендатором тип». На удостоверениях это утверждение ложно: они адресуются
// (`/iam/v1/users/{user_id}/tokens/{token_id}`), имеют свой идентификатор и свои
// глаголы, а типа модели прав у них нет — право на удостоверение вычисляется от
// человека (`token_issuer: subject`), и заводить объект, на который его можно
// было бы ВЫДАТЬ, модель намеренно избегает.
//
// # Почему это расширение, а не ослабление
//
// Множество допустимых имён остаётся закрытым и сверяемым с деревом. Разница с
// первой редакцией — в поле `Tables`: без него запись была бы САМОЗАЯВЛЕНИЕМ.
// У закрытой таблицы типов истинность анкерена гейтом дрейфа против канонической
// модели; здесь анкер — сами таблицы строк и стоящие на них триггеры списания
// (утверждения G5/G6 гейта каталога). Опечатка `iam.credentials` внутреннюю
// согласованность записи проходит и ловится ровно этим анкером.
type SubordinateResource struct {
	// Kind — двухчастный токен, которым подчинённый ресурс называется в видах
	// учёта (`iam.user.credential` → `iam.credential`).
	Kind LimitKind
	// Parents — типы модели прав, от которых производен доступ. Их МОЖЕТ быть
	// несколько: один класс сущности живёт в нескольких таблицах ровно тогда,
	// когда видов родителя несколько.
	Parents []LimitKind
	// Tables — таблицы, чьи строки этот ресурс называет, в форме `схема.имя`.
	// Это АНКЕР записи в дереве, а не справка.
	Tables []string
	// Why — почему своего типа модели прав нет. Запись без причины неотличима
	// от записи без предмета.
	Why string
}

// subordinateResources — ЗАКРЫТЫЙ перечень подчинённых ресурсов.
var subordinateResources = []SubordinateResource{
	{
		Kind:    "iam.credential",
		Parents: []LimitKind{"iam.user", "iam.serviceAccount"},
		Tables: []string{
			"kacho_iam.user_oauth_clients",
			"kacho_iam.service_account_oauth_clients",
		},
		Why: "право на удостоверение вычисляется от принципала (`token_issuer: subject` " +
			"у человека, `v_update` на учётке у машины), поэтому объекта, на который его " +
			"можно было бы выдать, в модели прав нет и заводить его ради имени вида " +
			"значило бы расширить поверхность выдачи ради учёта",
	},
}

// SubordinateResourceOf отдаёт запись подчинённого ресурса по его токену.
func SubordinateResourceOf(k LimitKind) (SubordinateResource, bool) {
	for _, r := range subordinateResources {
		if r.Kind == k {
			return r, true
		}
	}
	return SubordinateResource{}, false
}

// SubordinateResources отдаёт КОПИЮ перечня: перечень — предмет гейта, и
// вызывающий, способный его изменить, сделал бы гейт зависимым от порядка
// вызовов.
func SubordinateResources() []SubordinateResource {
	out := make([]SubordinateResource, len(subordinateResources))
	copy(out, subordinateResources)
	return out
}

// accountScopedKinds — виды, к которым применима область величины `ACCOUNT`.
//
// # Почему это ОБЪЯВЛЕНО, а не выведено
//
// Вывести применимость из вида нельзя, и правило «носитель принадлежит аккаунту
// ⇒ область применима» ложно на первой же записи: человек принадлежит ВСЕМ своим
// аккаунтам сразу. Оставь признак литералом в теле функции списания — и третий
// вид учёта, заведённый позже, молча унаследует ту ветку, в которую попадёт.
// Тот же довод, по которому объявлен носитель.
//
// Согласие этого перечня с телом функции списания держит гейт (G7): множество
// объявленное обязано совпадать с множеством, которое читает область в SQL.
//
// # Почему удостоверения ЧЕЛОВЕКА сюда не входят
//
// Человек состоит во многих аккаунтах, а его удостоверение действует во всех
// сразу. Величина, назначенная администратором одного аккаунта, управляла бы
// числом путей входа, действующих в чужих, — влияние за пределы своих границ.
// У служебной учётки такой неоднозначности нет: она ресурс ровно одного
// аккаунта, и её удостоверения действуют в его границах.
var accountScopedKinds = []LimitKind{
	"iam.serviceAccount.credential",
}

// AccountScopeApplies отвечает, применима ли область аккаунта к виду.
func AccountScopeApplies(k LimitKind) bool {
	for _, c := range accountScopedKinds {
		if c == k {
			return true
		}
	}
	return false
}

// AccountScopedKinds отдаёт КОПИЮ перечня в устойчивом порядке.
func AccountScopedKinds() []LimitKind {
	out := make([]LimitKind, len(accountScopedKinds))
	copy(out, accountScopedKinds)
	return out
}
