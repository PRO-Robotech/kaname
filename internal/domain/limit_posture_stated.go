package domain

import "fmt"

// limit_posture_stated.go — ТРИ ВИДА, ЧЬЮ ВЕЛИЧИНУ ОБЪЯВЛЯЕТ ПОСАДКА, а не
// авторитет величин (приёмка `KAN-QUOTA-1`, `П25`, §2.0/§2.1).
//
// ─────────────────────────────────────────────────────────────────────────────
// ДВЕ РОЛИ ОДНОЙ СЛУЖБЫ, И РАЗЛИЧАЮТСЯ ОНИ ПО ВИДУ, А НЕ ПО ИМЕНИ СЛУЖБЫ
//
// Служба доступа бывает и ВЛАДЕЛЬЦЕМ вида, и ПОТРЕБИТЕЛЕМ чужого. Для видов, чей
// владелец — она сама, величину назначать некому: в самостоятельной установке
// внешнего авторитета нет by construction, и спросить у него нельзя. Такую
// величину объявляет ПОСАДКА, ручкой с отказом старта при незаданном значении.
//
// Для чужих видов роль прежняя: величина приезжает от объявленного внешнего
// авторитета ровно так же, как у остальных пяти потребителей. Одно не заменяет
// другого ни в одну сторону.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТИ ТРИ, А НЕ ДЕВЯТЬ И НЕ НОЛЬ
//
// Разбиение сделано ПРЕДИКАТОМ, а не по имени: действует тот потолок, чей вызов
// списания стоит в применённой миграции. Таких ровно три. Остальные шесть видов
// службы величину принимали и НЕ ПРИМЕНЯЛИ НИ РАЗУ — они сняты вместе с учётом
// (`KAN-Q3-04`), и это закрыло обещание, которого продукт не исполнял.
//
// Снять заодно и эти три было бы РАСШИРЕНИЕМ ПОВЕРХНОСТИ, не названным ни в
// одном артефакте: самостоятельная установка осталась бы без ограничения на
// число аккаунтов и путей входа на одну личность.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЭТО НЕ ЯВЛЯЕТСЯ — АВТОРИТЕТОМ ПОД ДРУГИМ ИМЕНЕМ
//
// У авторитета величин есть контракт, область (`DEFAULT`/`ACCOUNT`/`PROJECT`),
// старшинство между областями и дельта с ревизией. У посадки нет НИ ОДНОГО из
// четырёх: величина одна на вид, объявляется файлом настроек, снаружи не
// назначается и версии не имеет. Различие названо по осям, а не словами.

// postureStatedKinds — виды, чью величину объявляет посадка службы доступа.
//
// Множество ЗАКРЫТО и остаётся подмножеством каталога: эти три вида
// по-прежнему СЧИТАЮТСЯ (списывающий триггер и арендаторское чтение никуда не
// уходят) — меняется только источник величины.
var postureStatedKinds = []LimitKind{
	"iam.account",
	"iam.user.credential",
	"iam.serviceAccount.credential",
}

// PostureStatedKinds — копия закрытого множества, в порядке объявления.
func PostureStatedKinds() []LimitKind {
	out := make([]LimitKind, len(postureStatedKinds))
	copy(out, postureStatedKinds)
	return out
}

// IsPostureStatedKind — величину этого вида объявляет посадка, а не авторитет.
func IsPostureStatedKind(k LimitKind) bool {
	for _, p := range postureStatedKinds {
		if p == k {
			return true
		}
	}
	return false
}

// AuthorityStatedKinds — виды каталога, чью величину назначает ВНЕШНИЙ авторитет.
//
// ВЫВОДИТСЯ из каталога вычетом, а не выписывается вторым списком: выписанный
// разошёлся бы с каталогом молча при первом же новом виде.
func AuthorityStatedKinds() []LimitKind {
	out := make([]LimitKind, 0, len(countableKinds))
	for _, c := range countableKinds {
		if !IsPostureStatedKind(c.Kind) {
			out = append(out, c.Kind)
		}
	}
	return out
}

// refusePostureStatedKind — отказ по ИМЕНИ ВИДА на попытке назначить величину
// снаружи.
//
// Молчаливый приём был бы «принято-и-проигнорировано» в чистом виде: строку
// приняли бы, сохранили и НЕ ПРИМЕНИЛИ — списание читает посадку. Администратор
// увидел бы успех, а арендатор — прежний потолок.
func refusePostureStatedKind(k LimitKind) error {
	return fmt.Errorf(
		"Illegal argument kind: %s is stated by the access service posture, "+
			"not assigned by a limit authority — restart the service with a new "+
			"value instead", k)
}
