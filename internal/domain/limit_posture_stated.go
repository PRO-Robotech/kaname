package domain

// limit_posture_stated.go — ТРИ ВИДА, ЧЬЮ ВЕЛИЧИНУ ОБЪЯВЛЯЕТ ПОСАДКА, а не
// авторитет величин (приёмка `KAN-QUOTA-1`, `П25`, §2.0/§2.1).
//
// ─────────────────────────────────────────────────────────────────────────────
// ДВЕ РОЛИ ОДНОЙ СЛУЖБЫ, И РАЗЛИЧАЮТСЯ ОНИ ПО ВИДУ, А НЕ ПО ИМЕНИ СЛУЖБЫ
//
// Служба доступа бывает и ВЛАДЕЛЬЦЕМ вида, и ПОТРЕБИТЕЛЕМ чужого. Для видов, чей
// владелец — она сама, величину назначать некому: в самостоятельной установке
// внешнего авторитета нет by construction, и спросить у него нельзя. Такую
// величину объявляет ПОСАДКА, ручкой с отказом старта при незаданном значении.
//
// Для чужих видов роль прежняя: величина приезжает от объявленного внешнего
// авторитета ровно так же, как у остальных пяти потребителей. Одно не заменяет
// другого ни в одну сторону.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТИ ТРИ, А НЕ ДЕВЯТЬ И НЕ НОЛЬ
//
// Разбиение сделано ПРЕДИКАТОМ, а не по имени: действует тот потолок, чей вызов
// списания стоит в применённой миграции. Таких ровно три. Остальные шесть видов
// службы величину принимали и НЕ ПРИМЕНЯЛИ НИ РАЗУ — они сняты вместе с учётом
// (`KAN-Q3-04`), и это закрыло обещание, которого продукт не исполнял.
//
// Снять заодно и эти три было бы РАСШИРЕНИЕМ ПОВЕРХНОСТИ, не названным ни в
// одном артефакте: самостоятельная установка осталась бы без ограничения на
// число аккаунтов и путей входа на одну личность.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЭТО НЕ ЯВЛЯЕТСЯ — АВТОРИТЕТОМ ПОД ДРУГИМ ИМЕНЕМ
//
// У авторитета величин есть контракт, область (`DEFAULT`/`ACCOUNT`/`PROJECT`),
// старшинство между областями и дельта с ревизией. У посадки нет НИ ОДНОГО из
// четырёх: величина одна на вид, объявляется файлом настроек, снаружи не
// назначается и версии не имеет. Различие названо по осям, а не словами.

// postureStatedKinds — виды, чью величину объявляет посадка службы доступа.
//
// Множество ЗАКРЫТО. Прежде оно было ПОДМНОЖЕСТВОМ каталога авторитета; каталог
// ушёл вместе с авторитетом стадией S4, и с тех пор это ВЕСЬ перечень видов,
// которые служба считает. Три вида по-прежнему считаются — списывающий триггер и
// арендаторское чтение никуда не уходили, — сменился только источник величины.
var postureStatedKinds = []LimitKind{
	"iam.account",
	"iam.user.credential",
	"iam.serviceAccount.credential",
}

// PostureStatedKinds — копия закрытого множества, в порядке объявления.
func PostureStatedKinds() []LimitKind {
	out := make([]LimitKind, len(postureStatedKinds))
	copy(out, postureStatedKinds)
	return out
}

// IsPostureStatedKind — величину этого вида объявляет посадка, а не авторитет.
func IsPostureStatedKind(k LimitKind) bool {
	for _, p := range postureStatedKinds {
		if p == k {
			return true
		}
	}
	return false
}

// ЗДЕСЬ СТОЯЛ `AuthorityStatedKinds` — виды, чью величину назначал ВНЕШНИЙ
// авторитет. Он выводился вычетом из закрытого каталога, а каталог ушёл вместе с
// авторитетом (`limit.go`, стадия S4). Вычитать больше не из чего и незачем:
// множество видов, чью величину объявляет посадка, и множество видов службы
// теперь СОВПАДАЮТ.
//
// Снято вместе с предметом, а не оставлено возвращать пустой срез: функция,
// отвечающая «таких видов нет» на вопрос, которого никто не задаёт, есть форма
// без содержания.

// ЗДЕСЬ СТОЯЛ `refusePostureStatedKind` — отказ на попытке назначить величину
// этих трёх видов СНАРУЖИ, через авторитет. Снаружи назначать больше нечем:
// глаголов авторитета в контракте службы нет (стадия S4), и вызывающего у
// отказа не осталось ни одного.
//
// Снято вместе с предметом. Отказ без пути, которым к нему приходят, есть
// мёртвая ветвь: она документирует контракт, которого код больше не производит.

// ─────────────────────────────────────────────────────────────────────────────
// НОСИТЕЛЬ ВИДА — ТО, В ЧЁМ ЕГО СЧИТАЮТ, И ПОСЛЕ УХОДА КАТАЛОГА ЕГО ОБЪЯВЛЯЕТ
// ЭТОТ ЖЕ СЛОВАРЬ
//
// Счёт никуда не ушёл: три вида по-прежнему списываются триггером и читаются
// арендатором. Значит и вопрос «в чём считается вид» остался — ушёл только его
// прежний дом, закрытый каталог `countableKinds` (`limit.go`, стадия S4).
//
// ДВУХ МЕСТ ЭТО НЕ ЗАВОДИТ, и проверить это можно счётом: у двух из трёх видов
// носитель ВЫВОДИТСЯ — вложенный вид считается в своём родителе
// (`iam.user.credential` → `iam.user`, метод `ParentKind`). Не выводится ровно
// один: `iam.account` плоский, а считается во внешней к нему ЛИЧНОСТИ. Его и
// объявляет перечень ниже — единственный неизбежный литерал, а не второй список.

// CarrierIdentity — носитель «личность» в том виде, в каком он стоит в схеме.
//
// Значение принадлежит СХЕМЕ (`project_resource_quotas.carrier_type` и предикат
// списывающего триггера), поэтому у адаптера базы свой литерал, а не ссылка
// сюда: адаптер обязан называть то, что лежит в столбце, даже если домен
// однажды назовёт это иначе. Совпадение трёх написаний закреплено пробой
// (`internal/repo/kaname/pg`), а не подразумевается.
const CarrierIdentity = "identity"

// identityCarriedKinds — виды, чей носитель ЛИЧНОСТЬ.
//
// Почему носитель именно личность, а не аккаунт и не проект: аккаунт есть
// корень арендатора, и потолок НАД аккаунтами обязан держать тот, кто существует
// до первого аккаунта и переживает последний. Внутри предмета счёта считать
// нельзя by construction.
//
// Перечень ЗАКРЫТ и обязан оставаться подмножеством видов посадки: величина
// каждого приходит из файла настроек, и вид, попавший сюда мимо посадки, читался
// бы арендатору из источника, которого нет. Свойство держит проба, а не эта
// строка.
var identityCarriedKinds = []LimitKind{
	"iam.account",
}

// IdentityCarriedKinds — копия закрытого перечня, в порядке объявления.
func IdentityCarriedKinds() []LimitKind {
	out := make([]LimitKind, len(identityCarriedKinds))
	copy(out, identityCarriedKinds)
	return out
}

// IsIdentityCarriedKind — вид считается в личности.
func IsIdentityCarriedKind(k LimitKind) bool {
	for _, c := range identityCarriedKinds {
		if c == k {
			return true
		}
	}
	return false
}
