package domain

import "time"

// MembershipID — идентификатор членства, дефис-форма `mbr-<17>`.
//
// Он ВЫЧИСЛЯЕТСЯ из пары «человек × аккаунт» неизменяемой SQL-функцией без
// соли, а не чеканится: писателей строки членства больше одного, и все обязаны
// прийти к ОДНОЙ строке на одну пару. Отсюда два следствия, которые здесь
// названы, потому что они меняют решения читающего кода:
//
//   - идентификатор ПЕРЕИСПОЛЬЗУЕТСЯ. Уникальность пары полная, снятие есть
//     удаление строки, функция неизменяема — значит повторное приглашение того
//     же человека в тот же аккаунт вернёт ТОТ ЖЕ идентификатор. Признак «строка
//     заведена заново» — `CreatedAt`, а не `ID`;
//   - идентификатор ВЫЧИСЛИМ ПОСТОРОННИМ. Зная человека и аккаунт, его получает
//     кто угодно, ни разу не обратившись к платформе. Поэтому одиночное чтение
//     обязано быть суженным по аккаунту в САМОМ ЗАПРОСЕ: без этого адрес чужого
//     членства строится арифметикой, а не перебором.
type MembershipID string

// MembershipState — состояние членства. Значений ровно два, и словарь закреплён
// CHECK'ом на таблице: третьего в колонке не появится.
//
// Согласованность состояния членства со статусом человека конструкцией НЕ
// закреплена — её держат писатели (зеркалящий триггер строки человека и два
// стейтмента репозитория). Читающий код поэтому судит то, что в строке лежит, и
// не выводит одно из другого.
type MembershipState string

const (
	// MembershipStatePending — человек приглашён и ещё не входил.
	//
	// Наблюдаемо АККАУНТ-СКОУПНЫМ чтением и не наблюдаемо своим списком: у
	// приглашённого нет внешнего субъекта, значит нечем аутентифицироваться,
	// значит своего чтения он вызвать не может. Это не расхождение проекций, а
	// арифметика — разные наблюдатели видят разное.
	MembershipStatePending MembershipState = "PENDING"
	// MembershipStateActive — человек состоит в аккаунте.
	MembershipStateActive MembershipState = "ACTIVE"
)

// Membership — принадлежность человека аккаунту как ОТДЕЛЬНАЯ связь.
//
// Ресурс ВЫХОДНОЙ: глаголов создания, правки и снятия у него на читающей
// поверхности нет. Заводит членство приглашение, снимает — исключение из
// аккаунта, и оба принадлежат потоку человека.
type Membership struct {
	ID        MembershipID
	AccountID AccountID
	// AccountName — ЗЕРКАЛО имени аккаунта, источник истины сам аккаунт.
	// Заполняется на чтении соединением в той же БД; пустое значение означает
	// «имя не задано», а НЕ «аккаунта нет».
	AccountName AccountName
	UserID      UserID
	State       MembershipState
	// InvitedBy — кто пригласил. Это и есть след приглашения, ПЕРЕЖИВАЮЩИЙ вход:
	// активация трогает состояние и отметку правки и не трогает это поле.
	// Пусто у членства, заведённого не приглашением.
	InvitedBy UserID
	// CreatedAt — когда членство заведено; для приглашения — когда оно выписано.
	CreatedAt time.Time
	// UpdatedAt — когда состояние менялось в последний раз.
	UpdatedAt time.Time
}
