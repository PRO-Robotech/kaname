// rule_retired_type_names_the_catalog_test.go — отказ на СНЯТОМ типе называет
// точку чтения каталога (kacho#1814, приёмка
// `docs/engineering/acceptance/retired-resource-names-its-successor.md`,
// `IAM-SUC-04`, вторая половина «Тогда»).
//
// # Предмет
//
// Преемника отказ назвать НЕ МОЖЕТ: он приходит из прерванной транзакции, где
// чтения нет by construction, и это решено отдельной приёмкой. Но назвать, ГДЕ
// преемник узнаётся, он обязан — иначе следующий шаг клиента не восстановлен
// ничем: имена ресурсов намеренно не единообразны (`compute.instance`
// единственного числа, `storage.volumes` множественного), поэтому «догадайся»
// исполнимой инструкцией не является.
//
// # Почему это ПАРА полос, а не одна
//
// Полос отказа на несуществующем ресурсе две, и до этой правки они говорили
// РАЗНОЕ: полоса грантуемости адрес каталога называла, полоса снятия — нет.
// Различие никем не решалось — оно побочный эффект того, что гейты писались
// порознь (`architecture.md` §«Параллельные полосы одного механизма обязаны
// сверяться МЕЖДУ СОБОЙ»). Проба сверяет полосы между собой, а не каждую с
// выписанным здесь текстом: выписанный текст был бы вторым местом об одном
// предмете.
package domain

import (
	"strings"
	"testing"
)

// TestRetiredTypeRefusalNamesWhereTheSuccessorIsRead — отказ снятия называет
// точку чтения каталога.
//
// Положительный контроль стоит первым: живой тип обязан пройти. Без него
// «отказ назвал адрес» выполнялось бы и на гейте, отвергающем всё подряд.
func TestRetiredTypeRefusalNamesWhereTheSuccessorIsRead(t *testing.T) {
	if len(retiredDotted) == 0 {
		t.Fatal("словарь снятого пуст — проба не утверждала бы ничего")
	}
	if CatalogEndpoint == "" {
		t.Fatal("адрес каталога пуст — утверждение ниже стало бы тождественно истинным")
	}

	// Положительный контроль: живой тип принят, значит отказы ниже про снятие.
	if err := ruleOnArm(t, liveBothSets, ArmAnchor).Validate(TenantPolicy(), fixtureModules()); err != nil {
		t.Fatalf("живой контроль %q отвергнут: %v — отрицание ниже ничего не доказывает",
			liveBothSets, err)
	}

	named := 0
	for _, dotted := range retiredDotted {
		err := ruleOnArm(t, dotted, ArmAnchor).Validate(TenantPolicy(), fixtureModules())
		if err == nil {
			t.Errorf("правило на снятом %q принято — проба потеряла свой предмет", dotted)
			continue
		}
		msg := err.Error()
		// Тип по-прежнему назван: расширение текста прежнего утверждения не
		// отменяет, и проверяется это здесь же, а не в соседней пробе.
		if !strings.Contains(msg, dotted) {
			t.Errorf("отказ на %q не называет тип: %v", dotted, msg)
		}
		if !strings.Contains(msg, CatalogEndpoint) {
			t.Errorf("отказ на снятом %q не называет, ГДЕ узнать преемника (%s): %v — "+
				"следующий шаг клиента не восстановлен, а имена ресурсов "+
				"намеренно не единообразны, поэтому догадка неверна ровно там, где нужна",
				dotted, CatalogEndpoint, msg)
			continue
		}
		named++
	}
	t.Logf("перепись: снятых типов в словаре %d, отказов, назвавших точку чтения, %d",
		len(retiredDotted), named)
}

// TestCatalogEndpointIsDeclaredOnce — адрес каталога объявлен ОДИН раз на
// дерево.
//
// Вторая копия литерала — два места об одном предмете, и разойдутся они молча:
// обе полосы отказа останутся «правильными» по отдельности, а клиент получит
// два разных адреса на один вопрос. Проба судит ЗНАЧЕНИЕ, а не число вхождений
// в тексте: перепись по подстроке краснела бы на собственном объяснении.
func TestCatalogEndpointIsDeclaredOnce(t *testing.T) {
	// Форма адреса — часть контракта отказа: глагол и путь, а не голый путь.
	// Утверждается СОСТАВ, а не дословный литерал: дословный был бы копией
	// объявления, то есть тем самым вторым местом.
	if !strings.HasPrefix(CatalogEndpoint, "GET ") {
		t.Errorf("адрес каталога %q не называет глагола — клиент не знает, чем читать",
			CatalogEndpoint)
	}
	if !strings.Contains(CatalogEndpoint, "/permissionCatalog") {
		t.Errorf("адрес каталога %q не называет пути витрины разрешений", CatalogEndpoint)
	}
}
