// limit_posture_stated_test.go — СЛОВАРЬ ВИДОВ ПОСЛЕ УХОДА АВТОРИТЕТА: одна
// роль вместо двух, и подмножество носителя внутри неё (приёмка `KAN-QUOTA-1`,
// стадия S4, сценарий `KAN-Q4-14`; задача продукта `PRO-Robotech/kacho#2117`).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗДЕСЬ СТОЯЛО И ПОЧЕМУ ЗАМЕНЕНО, А НЕ ОСЛАБЛЕНО
//
// Файл держал ПЕРЕПИСЬ ПО РОЛИ: разбиение закрытого каталога на две
// непересекающиеся половины — виды, чью величину объявляет посадка, и виды, чью
// величину назначает внешний авторитет. Плюс обе стороны отказа: вид посадки
// авторитетом не принимается, чужой вид принимается.
//
// Стадией S4 авторитет выпилен из службы целиком. У разбиения не осталось второй
// половины, а у отказа — вызывающего: назначить величину снаружи больше нечем.
// Проба, чей предмет снят, НЕ ослабляется и не остаётся «на всякий случай» —
// исходов три, и выбран первый: утверждать НОВОЕ свойство того же предмета.
// Второй — снять вместе с предметом, третий — оставить с записанным предикатом
// истечения; ослабление («уберём это утверждение») исходом не является.
//
// Новое свойство — то, которое пришло на место разбиения: словарь посадки стал
// ЕДИНСТВЕННЫМ перечнем видов, которые служба считает, а носитель внутри него
// разделён на выводимый и объявленный.

import (
	"sort"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kaname/internal/domain"
)

// TestPostureVocabularyIsTheWholeSetOfCountedKinds — словарь посадки есть ВЕСЬ
// перечень видов службы.
//
// Утверждает ТРИ свойства, и каждое своё:
//
//  1. перечень НЕ ПУСТ (иначе всё ниже вакуумно, а потолков в установке нет
//     вовсе — это расширение поверхности, а не чистота);
//  2. вид каждой формы РАЗБИРАЕТСЯ: плоский даёт пустого родителя, вложенный —
//     непустого. Без этого «носитель выводится» было бы обещанием;
//  3. ни один вид не назван ДВАЖДЫ (перечень закрыт, а задвоенный вид дал бы
//     две строки учёта об одном предмете).
func TestPostureVocabularyIsTheWholeSetOfCountedKinds(t *testing.T) {
	t.Parallel()

	kinds := domain.PostureStatedKinds()
	if len(kinds) == 0 {
		t.Fatal("словарь посадки пуст: служба не считает НИ ОДНОГО своего вида, " +
			"то есть самостоятельная установка осталась без ограничения на число " +
			"аккаунтов и путей входа")
	}

	seen := map[domain.LimitKind]bool{}
	var flat, nested []domain.LimitKind
	for _, k := range kinds {
		if seen[k] {
			t.Errorf("вид %s назван словарём дважды: учёт завёл бы две строки об одном предмете", k)
		}
		seen[k] = true

		if !domain.IsPostureStatedKind(k) {
			t.Errorf("вид %s перечислен словарём, но его же предикат членства отвергает: "+
				"два места об одном предмете разошлись", k)
		}

		switch {
		case k.Nested():
			nested = append(nested, k)
			if k.ParentKind() == "" {
				t.Errorf("вложенный вид %s не даёт родителя: его носитель не выводится "+
					"ниоткуда, и списание писало бы строки в пустоту", k)
			}
		default:
			flat = append(flat, k)
			if k.ParentKind() != "" {
				t.Errorf("плоский вид %s даёт родителя %s: разбор имени читает не ту форму",
					k, k.ParentKind())
			}
		}
	}

	// ОБЕ ФОРМЫ ОБЯЗАНЫ БЫТЬ НЕПУСТЫ. Иначе разбор проверен на одной из двух, и
	// вторая половина утверждения не проверена ничем.
	if len(flat) == 0 || len(nested) == 0 {
		t.Fatalf("словарь несёт виды только одной формы (плоских %d, вложенных %d): "+
			"разбор имени проверен наполовину", len(flat), len(nested))
	}

	t.Logf("перепись: видов посадки %d — плоских %d %s, вложенных %d %s",
		len(kinds), len(flat), joined(flat), len(nested), joined(nested))
}

// TestIdentityCarriedKindsAreStatedByThePosture — виды, носимые ЛИЧНОСТЬЮ,
// объявлены посадкой, и это подмножество СОБСТВЕННОЕ.
//
// Свойство несущее, а не формальное: путь чтения квот личности добирает
// недостающее из ПОСАДКИ и другого источника не имеет вовсе. Вид, попавший в
// перечень носителя мимо посадки, читался бы арендатору из источника, которого
// нет, — и узнал бы об этом только тот, кто упёрся бы в отказ.
//
// Отрицание в паре с положительным: перечень носителя непуст И меньше словаря.
// Совпади они — «подмножество» было бы верно тривиально, и проба зеленела бы на
// словаре, где носитель у всех один.
func TestIdentityCarriedKindsAreStatedByThePosture(t *testing.T) {
	t.Parallel()

	carried := domain.IdentityCarriedKinds()
	posture := domain.PostureStatedKinds()

	if len(carried) == 0 {
		t.Fatal("видов, носимых личностью, ноль: потолка над числом аккаунтов не " +
			"существует, и завести их можно сколько угодно")
	}
	if len(carried) >= len(posture) {
		t.Fatalf("перечень носителя (%d) не меньше словаря посадки (%d): подмножество "+
			"вырождено, и утверждение ниже верно тривиально", len(carried), len(posture))
	}

	for _, k := range carried {
		if !domain.IsPostureStatedKind(k) {
			t.Errorf("вид %s носится личностью, но посадкой не объявлен: источника "+
				"величины у него нет ни одного", k)
		}
		if !domain.IsIdentityCarriedKind(k) {
			t.Errorf("вид %s перечислен носителем, но его же предикат членства отвергает", k)
		}
		if k.Nested() {
			t.Errorf("вид %s вложенный: его носитель выводится из имени (%s), и "+
				"объявлять его вторым местом значит заводить расхождение", k, k.ParentKind())
		}
	}

	// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: среди видов посадки есть и НЕ носимые личностью.
	// Без него «все перечисленные — посадочные» зеленело бы на перечне, куда
	// сложили весь словарь целиком.
	var elsewhere []domain.LimitKind
	for _, k := range posture {
		if !domain.IsIdentityCarriedKind(k) {
			elsewhere = append(elsewhere, k)
		}
	}
	if len(elsewhere) == 0 {
		t.Fatal("все виды посадки носятся личностью: различать нечего, и предикат " +
			"носителя ничего не сообщает")
	}

	t.Logf("перепись: видов посадки %d, из них носимых личностью %d %s, прочих %d %s",
		len(posture), len(carried), joined(carried), len(elsewhere), joined(elsewhere))
}

func joined(kinds []domain.LimitKind) string {
	out := make([]string, 0, len(kinds))
	for _, k := range kinds {
		out = append(out, string(k))
	}
	sort.Strings(out)
	return "[" + strings.Join(out, " ") + "]"
}
