// limit_posture_stated_test.go — ПЕРЕПИСЬ ВИДОВ ПО РОЛИ и её обе стороны
// (приёмка `KAN-QUOTA-1`, `П25`, `DoD S3` п. 7; задача продукта #2117).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ПЕРЕПИСЬ ПЕЧАТАЕТ ДВЕ ВЕЛИЧИНЫ И ДВА СПИСКА
//
// Одно число скрывает ровно тот случай, ради которого различение заведено. «Видов
// каталога 27» не говорит, сколько из них служба ВЛАДЕЕТ и сколько ПОТРЕБЛЯЕТ, а
// именно от этого зависит, откуда берётся величина. Поэтому печатаются обе
// половины и обе целиком, а не только их размер: перечень, свернувшийся до
// числа, перестаёт быть проверяемым.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ПРОБА СУДИТ И ЧЕГО НЕ СУДИТ
//
// Она судит РАЗБИЕНИЕ каталога на две непересекающиеся половины и их сумму. Она
// НЕ судит, верны ли сами величины, и не судит, что списание читает посадку, —
// это предмет миграции и интеграционной пробы на живом Postgres.

import (
	"sort"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kaname/internal/domain"
)

// TestKindCensusSplitsByRole — перепись по роли: три величины посадки против
// остальных видов внешнего каталога.
//
// Утверждает ЧЕТЫРЕ свойства разбиения, и каждое своё:
//
//  1. половины НЕ ПЕРЕСЕКАЮТСЯ (иначе у вида два источника величины);
//  2. в сумме дают каталог ЦЕЛИКОМ (иначе вид остался без источника вовсе);
//  3. каждый вид посадки — ЧЛЕН каталога (иначе он не считается и потолок мёртв);
//  4. половина посадки НЕ ПУСТА (иначе всё утверждение вакуумно).
func TestKindCensusSplitsByRole(t *testing.T) {
	own := domain.PostureStatedKinds()
	foreign := domain.AuthorityStatedKinds()
	all := domain.CountableKinds()

	t.Logf("перепись видов по роли:\n"+
		"  каталог целиком:            %d\n"+
		"  владелец — посадка Kaname:  %d  %s\n"+
		"  потребитель — авторитет:    %d  %s",
		len(all), len(own), joined(own), len(foreign), joined(foreign))

	if len(own) == 0 {
		t.Fatal("половина посадки пуста — перепись стала вакуумной: " +
			"утверждение о разбиении выполняется тривиально")
	}

	// 1. Непересечение.
	for _, o := range own {
		for _, f := range foreign {
			if o == f {
				t.Errorf("вид %s стоит в ОБЕИХ половинах: у него два источника "+
					"величины, и который старше — не решал никто", o)
			}
		}
	}

	// 2. Сумма равна каталогу.
	if len(own)+len(foreign) != len(all) {
		t.Errorf("сумма половин %d+%d не равна каталогу %d — значит вид остался "+
			"без источника величины либо посчитан дважды",
			len(own), len(foreign), len(all))
	}

	// 3. Каждый вид посадки — член каталога.
	for _, o := range own {
		if !domain.IsCountableKind(o) {
			t.Errorf("вид %s объявлен видом посадки и НЕ СТОИТ в каталоге: "+
				"его потолок объявлен и не применяется ни разу — тот самый класс, "+
				"который эта стадия закрывает", o)
		}
	}
}

// TestPostureStatedKindsAreRefusedByTheAuthority — обе стороны отказа.
//
// Отрицание («снаружи назначить нельзя») без положительного близнеца («чужой вид
// назначить можно») зеленело бы на валидаторе, отвергающем ВСЁ.
func TestPostureStatedKindsAreRefusedByTheAuthority(t *testing.T) {
	for _, k := range domain.PostureStatedKinds() {
		err := k.Validate()
		if err == nil {
			t.Errorf("вид посадки %s принят авторитетом: величина была бы "+
				"сохранена и не применена ни разу", k)
			continue
		}
		if !strings.Contains(err.Error(), string(k)) {
			t.Errorf("отказ по виду %s не называет вид: %v", k, err)
		}
		if !strings.Contains(err.Error(), "posture") {
			t.Errorf("отказ по виду %s не называет ИСТОЧНИК величины — оператор "+
				"не узнает, где её менять: %v", k, err)
		}
	}

	// ПОЛОЖИТЕЛЬНЫЙ БЛИЗНЕЦ. Чужой вид назначается авторитетом как прежде.
	foreign := domain.AuthorityStatedKinds()
	if len(foreign) == 0 {
		t.Fatal("положительного близнеца нет: чужих видов ноль, значит отрицание " +
			"выше ничего не доказывает")
	}
	for _, k := range foreign {
		if err := k.Validate(); err != nil {
			t.Errorf("чужой вид %s отвергнут — роль потребителя сломана: %v", k, err)
		}
	}
}

func joined(kinds []domain.LimitKind) string {
	out := make([]string, 0, len(kinds))
	for _, k := range kinds {
		out = append(out, string(k))
	}
	sort.Strings(out)
	return "[" + strings.Join(out, " ") + "]"
}
