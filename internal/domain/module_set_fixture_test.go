// module_set_fixture_test.go — набор модулей для проб ВНУТРЕННЕГО пакета.
//
// # Почему фикстура НЕ равна набору платформы, и это решение
//
// Домен закрытого набора больше не объявляет (#1927): он получает его
// параметром. Проба, подающая ровно платформенный набор, зеленела бы и на
// реализации, которая параметр игнорирует и читает встроенный перечень, —
// то есть не отличала бы починку от дефекта, ради снятия которого работа
// делалась.
//
// Поэтому фикстура несёт имя `probe`, которого в каноне платформы нет ни
// одного, и НЕ несёт `geo`, который в каноне тоже отсутствует, но по другой
// причине. Правило, называющее `probe`, принимается ТОЛЬКО если домен читает
// поданный набор.
//
// Второго объявления платформенного набора здесь при этом не заводится: имена
// ниже — фикстура, а не перечень платформы, и точный состав канона пинит
// `authzmap/module_set_drift_test.go`, у которого есть производитель.
func fixtureModules() ModuleSet {
	return ModuleSetOf("iam", "vpc", "compute", "loadbalancer", "registry", "storage", "probe")
}
