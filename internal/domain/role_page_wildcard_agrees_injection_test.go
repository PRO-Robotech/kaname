// role_page_wildcard_agrees_injection_test.go — доказательство, что гейт
// страницы СПОСОБЕН упасть и способен смолчать (задача #2046).
//
// # Главная фикстура — НАСТОЯЩИЙ дефект, а не синтетика
//
// Первый случай ниже — врезка страницы в редакции ДО правки `b47e612c20`,
// перенесённая дословно. Она и была той неправдой, ради которой заведён гейт:
// заявление лежало на глаголах наравне с модулем и ресурсом, а домен глагольную
// подстановку ярусом не ограничивает. Синтетика такого не доказывает: она
// проверяет распознаватель на форме, которую сама же и выбрала.
//
// Историческая редакция называет поля ПРОЗОЙ («глагол-`*`», «модуль/ресурс-`*`»),
// и первая версия распознавателя её не видела вовсе — ни красного, ни зелёного,
// молчание. Признак был расширен по этому наблюдению, а не по замыслу.
//
// # Каждая инъекция меняет РОВНО ОДИН факт против своего близнеца
//
// У находки рядом стоит законный близнец той же формы: полярность против
// полярности, прозаическое имя вплотную к литералу против того же слова вдали
// от него, предложение с маркером против предложения без маркера. Без близнеца
// красное доказывало бы лишь то, что гейт умеет краснеть, — а не то, что он
// краснеет на предмете.
package domain_test

import (
	"strings"
	"testing"
)

// pageFixture — синтетическая страница. Заголовок врезки и пустые строки
// значимы: область подстановки определяется ими.
func pageFixture(body string) string {
	return "## Правила\n\nПреамбула без предмета.\n\n" + body + "\n"
}

// historicalNote — врезка страницы В РЕДАКЦИИ ДО ПРАВКИ, дословно.
const historicalNote = ":::note Wildcard `\"*\"` — только для system-ролей\n" +
	"Literal `\"*\"` в `resources` / `verbs` / `module` допустим лишь в system-ролях. В custom-роли\n" +
	"он вернёт `INVALID_ARGUMENT` (глагол-`*` — «все глаголы типа» — грантабелен, но модуль/ресурс-`*`\n" +
	"system-only).\n:::"

// currentNote — врезка в СЕГОДНЯШНЕЙ редакции, дословно.
const currentNote = ":::note Wildcard `\"*\"` — по полю, а не по роли\n" +
	"Ярусом роли ограничена подстановка в `module` и `resources`: в custom-роли она вернёт\n" +
	"`INVALID_ARGUMENT`, в system-роли законна. Подстановка в `verbs` — **не** ограничена: глагол-`*`\n" +
	"означает «все глаголы типа» и грантабелен в custom-роли тоже; единственное условие — он идёт\n" +
	"единственным элементом (`[\"*\", \"get\"]` → `INVALID_ARGUMENT`).\n:::"

func TestRolePageWildcardGate_Injection(t *testing.T) {
	probes := ruleWildcardProbes()
	fields := ruleContractFields(t)

	cases := []struct {
		name string
		body string
		// wantFinding — подстрока, которую находка обязана нести. Пусто —
		// молчание.
		wantFinding string
		// wantClaims / wantAmbiguous — перепись. Ноль заявлений при ожидаемом
		// молчании означал бы, что гейт молчит от слепоты, а не от согласия.
		wantClaims    int
		wantAmbiguous int
		why           string
	}{
		{
			name:        "НАСТОЯЩИЙ дефект: историческая редакция врезки",
			body:        historicalNote,
			wantFinding: "поле verbs: страница заявляет подстановку ограниченной ярусом",
			wantClaims:  3,
			// Вторая фраза («глагол грантабелен, но модуль/ресурс system-only»)
			// несёт оба маркера и в заявления не идёт — она законна.
			wantAmbiguous: 1,
			why:           "то, ради чего гейт заведён",
		},
		{
			name:       "ЗАКОННЫЙ БЛИЗНЕЦ: сегодняшняя редакция той же врезки",
			body:       currentNote,
			wantClaims: 3,
			why:        "один факт против предыдущего случая — формулировка, а не форма",
		},
		{
			name: "обратная полярность: модуль объявлен НЕ ограниченным",
			body: ":::note Wildcard `\"*\"`\nПодстановка в `module` — не ограничена ярусом роли.\n:::",
			wantFinding: "поле module: страница заявляет подстановку не ограниченной ярусом, " +
				"а домен ограничивает",
			wantClaims: 1,
			why:        "вторая сторона оси: гейт судит расхождение, а не одно его направление",
		},
		{
			name:       "ЗАКОННЫЙ БЛИЗНЕЦ той же полярности: глагол объявлен НЕ ограниченным",
			body:       ":::note Wildcard `\"*\"`\nПодстановка в `verbs` — не ограничена ярусом роли.\n:::",
			wantClaims: 1,
			why:        "та же фраза о поле, чьё поведение ей отвечает, — молчание",
		},
		{
			name: "самопротиворечие через предложения",
			body: ":::note Wildcard `\"*\"`\nПодстановка в `verbs` ограничена ярусом роли. " +
				"Подстановка в `verbs` — не ограничена.\n:::",
			wantFinding: "поле verbs: страница заявляет о нём обе полярности",
			wantClaims:  2,
			why:         "форма наблюдавшегося дефекта: две половины в двух строках",
		},
		{
			name: "ЗАКОННЫЙ БЛИЗНЕЦ: прозаическое имя ВДАЛИ от литерала",
			body: ":::note Wildcard `\"*\"`\nПодстановка `*` ограничена ярусом роли — так же, как " +
				"это устроено у ролей, где глагол выбирается отдельной строкой и никакой " +
				"подстановки в нём нет.\n:::",
			wantClaims: 0,
			why:        "окно привязки несущее: без него слово «глагол» приписало бы заявление verbs",
		},
		{
			name: "ЗАКОННЫЙ БЛИЗНЕЦ: предложение без маркера полярности",
			body: ":::note Wildcard `\"*\"`\nПодстановка в `resourceNames` запрещена: " +
				"`\"*\"` там не принимается ни одной ролью.\n:::",
			wantClaims: 0,
			why:        "«запрет всегда» этой осью не выражается — требовать вердикта значило бы краснеть на верном",
		},
		{
			name: "заявление о поле без производителя поведения",
			body: ":::note Wildcard `\"*\"`\nПодстановка в `matchLabels` ограничена ярусом роли.\n:::",
			// Координата находки — имя КОНТРАКТА (`match_labels`), хотя страница
			// написала верблюжье: вердикт обязан указывать туда, где правят.
			wantFinding: "поле match_labels: страница заявляет о подстановке, а производителя " +
				"поведения у поля нет",
			wantClaims: 1,
			why:        "заявление, которое некому проверить, — тоже находка, а не молчание",
		},
		{
			name:        "область: заголовок врезки несёт литерал, абзац — нет",
			body:        ":::note Wildcard `\"*\"`\nЯрусом роли ограничена подстановка в `verbs`.\n:::",
			wantFinding: "поле verbs: страница заявляет подстановку ограниченной ярусом",
			wantClaims:  1,
			why:         "без области несущее предложение страницы было бы невидимо",
		},
		{
			name:       "ЗАКОННЫЙ БЛИЗНЕЦ: то же предложение ВНЕ области подстановки",
			body:       "Ярусом роли ограничена подстановка в `verbs`.",
			wantClaims: 0,
			why:        "один факт против предыдущего случая — отсутствие литерала в области",
		},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			findings, census, err := auditRolePageWildcardClaims(pageFixture(c.body), probes, fields)
			if err != nil {
				t.Fatalf("разбор не отработал: %v", err)
			}
			t.Logf("перепись: %s", census)

			if census.Claims != c.wantClaims {
				t.Errorf("заявлений распознано %d, хотел %d (%s)", census.Claims, c.wantClaims, c.why)
			}
			if census.Ambiguous != c.wantAmbiguous {
				t.Errorf("предложений с обоими маркерами %d, хотел %d",
					census.Ambiguous, c.wantAmbiguous)
			}

			joined := strings.Join(findings, "\n")
			if c.wantFinding == "" {
				if len(findings) != 0 {
					t.Errorf("гейт краснеет на законном тексте (%s):\n%s", c.why, joined)
				}
				return
			}
			if !strings.Contains(joined, c.wantFinding) {
				t.Errorf("находка не названа (%s).\nхотел подстроку: %q\nполучил:\n%s",
					c.why, c.wantFinding, joined)
			}
		})
	}

	t.Logf("перепись инъекции: случаев %d", len(cases))
}

// TestRolePageWildcardGate_EmptyWalkIsAVerdictlessRun — обход, не нашедший
// области подстановки, вердиктом не является.
//
// Без этого случая гейт над страницей, где врезку сняли, печатал бы «находок 0»
// — то есть «ноль прочитанного», неотличимое от согласия.
func TestRolePageWildcardGate_EmptyWalkIsAVerdictlessRun(t *testing.T) {
	findings, census, err := auditRolePageWildcardClaims(
		pageFixture("Роль несёт правила. Подстановок страница не обсуждает."),
		ruleWildcardProbes(), ruleContractFields(t))
	if err != nil {
		t.Fatalf("разбор не отработал: %v", err)
	}
	if len(findings) != 0 {
		t.Errorf("находки на странице без предмета: %v", findings)
	}
	if census.Scoped != 0 {
		t.Fatalf("абзацев в области подстановки %d, хотел 0 — признак области негоден", census.Scoped)
	}
	t.Logf("перепись: %s — премиса `Scoped == 0` в пробе дерева роняет прогон", census)
}

// TestRolePageWildcardGate_RecognizerKnowsBothWritingsOfAField — распознаватель
// знает ОБА написания имени поля.
//
// Страница арендатора пишет поля в JSON-форме (верблюжьей), контракт — в
// змеиной; гейт судит по координате контракта. Знай он одну форму — половина
// страницы осталась бы вне наблюдения молча.
func TestRolePageWildcardGate_RecognizerKnowsBothWritingsOfAField(t *testing.T) {
	spellings := pageFieldSpellings(ruleContractFields(t))
	for _, w := range []string{"resource_names", "resourceNames", "module", "resources", "verbs"} {
		if got, ok := spellings[w]; !ok {
			t.Errorf("написание %q распознавателю неизвестно — заявление о нём невидимо", w)
		} else if w == "resourceNames" && got != "resource_names" {
			t.Errorf("написание %q приведено к %q, хотел координату контракта", w, got)
		}
	}
	t.Logf("перепись: написаний известно %d на %d полей контракта",
		len(spellings), len(ruleContractFields(t)))
}
