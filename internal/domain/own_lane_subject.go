package domain

// own_lane_subject.go — ИДЕНТИЧНОСТЬ СУБЪЕКТА, ОТЧЕКАНЕННАЯ НАШЕЙ ПОЛОСОЙ
// (приёмка F4d воркспейса, Р10 и F4d-52; производитель — регистрация Ф4,
// задача PRO-Robotech/kacho#1270).
//
// # Почему чеканим мы, а не оставляем пустым
//
// Зеркало человека держит два ограничения разом: у `ACTIVE`/`BLOCKED` внешний
// идентификатор непуст (`users_invite_status_consistency`), а непустое значение
// глобально уникально по всей установке (`users_identity_external_id_uniq`).
// На полосе `own` поставщика нет, значит производителя величины нет ни одного —
// и константа-заполнитель исключена by construction: глобальный ключ допускает
// ровно одну такую строку. Ослабление ограничения отвергнуто (F4d Р10): пустая
// строка получила бы второй смысл «свой», и различить «идентичности нет» и
// «идентичность наша» стало бы нечем.
//
// # Форма — самоописывающаяся
//
//	own:<prefix>-<крокфордово тело>
//
// Голова называет ПОЛОСУ, породившую идентичность: по значению читается
// происхождение без обращения к чужой системе. Хвост — идентификатор общего
// фундамента в дефисном каноне: глобальная уникальность by construction,
// проверки-перед-вставкой нет (ban #10). Двоеточие законно: внешний
// идентификатор никогда не становится строкой субъекта в модели прав — субъект
// там наш `usr-`.
//
// # Почему НЕ детерминированная чеканка от почты
//
// Почта меняется, а идентификатор, назначенный на заведение, обязан пережить
// это неизменным (ban #15). Уникальность человека держит ключ почты; второй
// держатель не нужен.
//
// Голову читает и триггер темпа заведения (`admission_rate_count`; в своде и в Ф4
// — `kacho_admission_rate_count`, переименована миграцией `20260917130000`): по ней
// он узнаёт нашу полосу и берёт носителем ключа то, чем человек представился, —
// адрес (Ф4 Р5). Второе написание головы в схеме сверяет с этой константой
// проба `TestOwnLaneSubjectHeadAgreesWithTheSchema`.

import (
	"strings"

	"github.com/PRO-Robotech/corelib/ids"
)

// OwnLaneSubjectHead — голова идентичности, отчеканенной нашей полосой.
const OwnLaneSubjectHead = "own:"

// ownLaneSubjectPrefix — приставка хвоста в дефисном каноне. Наружу не
// адресуется, поэтому в платформенный каталог приставок не входит.
const ownLaneSubjectPrefix = "sub"

// NewOwnLaneSubject — свежая идентичность субъекта нашей полосы.
func NewOwnLaneSubject() ExternalSubject {
	return ExternalSubject(OwnLaneSubjectHead + ids.NewHyphenID(ownLaneSubjectPrefix))
}

// IsOwnLane — отчеканена ли идентичность нашей полосой (по голове).
func (s ExternalSubject) IsOwnLane() bool {
	return strings.HasPrefix(string(s), OwnLaneSubjectHead)
}
