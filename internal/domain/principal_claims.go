// principal_claims.go — состав утверждений, называющий ПРИНЦИПАЛА, за которого
// говорит выпущенный нами токен.
//
// # Почему имена объявлены, а не выписываются по месту
//
// Читателей у этих имён больше одного: их СТАВИТ чеканка и их ЧИТАЕТ приёмная
// сторона. Пока имена живут литералами по своим пакетам, их различие не
// является ничьей находкой — оно не выражено и потому не может покраснеть.
// Разойтись же им есть чем, и разошлись бы они МОЛЧА: переименование на выпуске
// оставило бы читателя без принципала не отказом, а тишиной — токен проверился
// бы целиком, а за кого он говорит, читатель не узнал бы. Отличить такое
// состояние от «токен выдан системной личности» на стороне читателя нечем.
//
// # Что означает отсутствие каждого
//
// Вид и идентификатор ОБЯЗАТЕЛЬНЫ: «назвать некого» и «назван системный» —
// разные состояния, и смешивать их нельзя, потому что системная личность и есть
// та, которой принадлежат все служебные записи. Отображаемое имя косметическое:
// оно ни на одно решение не влияет и при отсутствии замещается идентификатором.
package domain

const (
	// ClaimPrincipalType — вид принципала: `user` либо `service_account`.
	ClaimPrincipalType = "kaname_principal_type"
	// ClaimPrincipalID — идентификатор принципала.
	ClaimPrincipalID = "kaname_principal_id"
	// ClaimPrincipalDisplay — отображаемое имя принципала. Косметическое.
	ClaimPrincipalDisplay = "kaname_principal_display_name"
)
