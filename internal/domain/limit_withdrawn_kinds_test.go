// Шесть видов, которые НИКОГДА не списывались, каталогом больше не принимаются.
//
// Задача `PRO-Robotech/kacho#2117`, приёмка `KAN-QUOTA-1`, сценарий `KAN-Q3-04`.
//
// # Предмет
//
// У этих шести администратор мог назначить величину, продукт её принимал,
// сохранял и показывал — и НЕ ПРИМЕНЯЛ НИКОГДА: списывающего триггера нет ни у
// одного, списания из прод-кода службы нет тоже. Это класс
// «принято-и-проигнорировано» (`api-conventions.md`): обещанная возможность,
// которой нет. Снятие ЗАКРЫВАЕТ дефект, а не заводит потерю контроля — и в этом
// отличие шести от трёх, которые продолжают действовать.
//
// # Почему проба парная, а не односторонняя
//
// Отрицание «этих видов нет» зеленеет на пустом каталоге и на каталоге, из
// которого вынули всё. Положительный близнец — три ДЕЙСТВУЮЩИХ вида службы,
// каждый со своим списывающим триггером в `0001_initial.sql`, — держит
// утверждение осмысленным: он краснеет, если снятие ушло шире своего предмета.
//
// Разница между группами — ровно один факт, и он назван предикатом приёмки
// (З17/З18): наличие списывающего триггера. Ни имя вида, ни его носитель к
// разбиению отношения не имеют.
func TestSixNeverChargedKindsAreNoLongerCountable(t *testing.T) {
	t.Parallel()

	// Снятые — те, у кого списывающего триггера НЕТ НИ ОДНОГО (З18).
	withdrawn := []domain.LimitKind{
		"iam.project",
		"iam.user",
		"iam.serviceAccount",
		"iam.group",
		"iam.role",
		"iam.accessBinding",
	}

	// Положительный близнец: три вида, чей списывающий триггер стоит в
	// применённой миграции (З17). Они остаются, и проба обязана это утверждать —
	// иначе она зелена на каталоге, из которого вынули и их.
	kept := []domain.LimitKind{
		"iam.account",
		"iam.user.credential",
		"iam.serviceAccount.credential",
	}

	for _, kind := range withdrawn {
		require.Falsef(t, domain.IsCountableKind(kind),
			"вид «%s» никогда не списывался и обязан быть снят с каталога: "+
				"величина на нём принимается, сохраняется и не применяется ни разу", kind)

		err := domain.LimitKind(kind).Validate()
		require.Errorf(t, err,
			"назначение потолка на снятый вид «%s» обязано быть отвергнуто, а не принято молча", kind)
		require.EqualErrorf(t, err,
			"Illegal argument kind: "+string(kind)+" is not a countable resource kind",
			"отказ обязан называть ВИД ПОИМЁННО — тон отказа часть контракта, "+
				"и клиент по нему понимает, что именно отвергнуто")
	}

	for _, kind := range kept {
		require.Truef(t, domain.IsCountableKind(kind),
			"вид «%s» СПИСЫВАЕТСЯ (свой триггер в 0001_initial.sql) и обязан остаться: "+
				"снятие вместе с шестью означало бы расширение поверхности, никем не названное", kind)
		require.NoErrorf(t, domain.LimitKind(kind).Validate(),
			"действующий вид «%s» обязан приниматься", kind)
	}

	t.Logf("перепись: снятых видов %d, оставшихся действующих %d", len(withdrawn), len(kept))
}
