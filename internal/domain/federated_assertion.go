// federated_assertion.go — доменные понятия перечня доверенных издателей
// утверждения (задача #1124).
//
// # Что этот перечень такое и чем он отличается от реестра клиентов
//
// Реестр клиентов отвечает на вопрос «наша ли это строка и её ли ключ». Перечень
// доверенных издателей отвечает на другой: «согласны ли МЫ, что вот этот
// ПОСТОРОННИЙ издатель вправе поручиться вот за этот свой субъект». Ключевой
// материал здесь принадлежит не нам, и решение о доверии — единственное, что у
// нас есть.
//
// Отсюда две вещи, которые верны здесь и неверны у реестра клиентов:
//
//  1. **запись доверия имеет собственный срок.** У клиента срок означает «эта
//     строка больше не выдаёт»; здесь — «мы больше не ручаемся за постороннего».
//     Снятие доверия сроком обязано работать, иначе выданное однажды доверие
//     переживёт то, ради чего выдавалось;
//  2. **пустой перечень означает «не доверяем никому».** Величина, которая
//     может быть пустой и не проверена на непустоту, означает «принимаем
//     любого» — класс, записанный в корпусе про круг законных отправителей. Тут
//     он даёт не «приняли лишний заголовок», а токен платформы предъявителю,
//     которого мы не заводили вовсе.
package domain

import (
	"errors"
	"strings"
)

// ErrTrustedIssuerUnknown — пара (издатель, субъект) не резолвится ни в одну
// запись перечня.
//
// ОДИН признак на все состояния «мы за это не ручаемся»: записи нет вовсе ·
// доверие выдано другому субъекту того же издателя · доверие выдано, но строка,
// которую оно уполномочивало, снята. Различимые исходы дали бы предъявителю
// оракул: по ним устанавливают, заведено ли доверие и кому именно.
var ErrTrustedIssuerUnknown = errors.New(
	"federated assertion: (issuer, subject) does not resolve in the trusted-issuer list")

// IsTrustedIssuerUnknown отвечает, не резолвится ли пара.
//
// Предикат, а не сравнение на месте: вызывающие обёртывают ошибку контекстом, и
// сравнение на равенство перестало бы работать на первом же обёртывании —
// молча, потому что «не доверенный» и «не смогли распознать» выглядят
// одинаково, а второе означало бы недоступность реестра, у которой исход СВОЙ.
func IsTrustedIssuerUnknown(err error) bool { return errors.Is(err, ErrTrustedIssuerUnknown) }

// TrustedIssuer — одна запись НАШЕГО перечня доверенных издателей.
//
// Форма повторяет то, что прежде хранил у себя поставщик: издатель, ТОЧНЫЙ
// субъект, ключевой материал издателя и срок. Повторяет намеренно — перевод
// перечня к нам не должен был заодно менять то, о чём перечень.
type TrustedIssuer struct {
	// ClientID — НАША строка федеративного ключа, которую эта запись
	// уполномочивает. Внешний субъект получает токен от её имени, никогда от
	// своего.
	ClientID string
	// Issuer — идентификатор внешнего издателя, сверяемый с `iss` дословно.
	Issuer string
	// Subject — ТОЧНЫЙ субъект, сверяемый с `sub` дословно.
	//
	// Точный, а не образец: доверие образцу означало бы, что запись покрывает
	// субъектов, которых называющий её не перечислял, — и узнать их состав
	// нельзя ни по записи, ни по журналу.
	Subject string
	// PublicKeyPEM — открытый ключ ИЗДАТЕЛЯ в форме SPKI PEM.
	PublicKeyPEM string
	// Algorithm — зарегистрированный алгоритм издателя. Пустое значение
	// означает «ключа нет», а НЕ «любой алгоритм».
	Algorithm string
	// ExpiresAt — момент истечения ДОВЕРИЯ в Unix-секундах; 0 означает
	// «бессрочно».
	ExpiresAt int64
}

// CanVouch отвечает, способна ли запись вообще служить основанием доверия.
//
// Тот же класс, что `AssertionClient.CanPresentAssertion`: пустой ключ и пустой
// алгоритм — это «ключа нет». Запись без ключа не отвергала бы ничего, а
// принимала бы всё, что называет её пару, — то есть доверие издателю выродилось
// бы в доверие строке таблицы.
func (ti TrustedIssuer) CanVouch() bool {
	return strings.TrimSpace(ti.Algorithm) != "" && strings.TrimSpace(ti.PublicKeyPEM) != ""
}
