package domain

// role_rule_state.go — ПОСТАТЕЙНОЕ состояние правила роли: отозвано отдельно от
// неразрешённого (задача продукта #1962, приёмка
// `services/iam/docs/engineering/acceptance/rule-state-names-withdrawn-apart-from-unresolved.md`).
//
// # Зачем это рядом с уже стоящими счётчиками
//
// [RoleIntegrity] отвечает СКОЛЬКО сегментов роли перестало проецироваться, а
// [WithdrawnGrant] — ЧТО именно и почему. Между ними остаётся вопрос, на который
// не отвечает ни один: КАКОЕ ПРАВИЛО пострадало, и — что важнее — по КАКОЙ ИЗ
// ДВУХ причин.
//
// Причин ровно две, и они дают одинаковую картину счётчиков:
//
//   - объявление СНЯТО платформой — строка каталога ушла, ведомость сирот это
//     записала. Арендатор своё правило не менял, право у него отобрали;
//   - правило НЕ РАЗРЕШИЛОСЬ — оно называет то, чего модель прав не знает, и
//     переселения не было ВОВСЕ (форма инцидента 513001). Ведомость о такой
//     потере молчит by construction.
//
// Без слова эти два состояния неотличимы: у второго `withdrawn_grants` пуст, и
// «право отобрали» читается ровно так же, как «права не было никогда».
//
// # Состояние ВЫВОДИТСЯ, хранимой колонки у него нет
//
// Тем же доводом, что записан в `role_integrity.go`: двенадцать ролей инцидента
// 513001 заведены МИГРАЦИЕЙ, и колонку не проставил бы никто — то есть хранимое
// состояние не поймало бы тот самый случай, ради которого заводится.

// RuleLifecycle — состояние ОДНОГО правила роли.
//
// Нулевой вариант несёт ЕДИНСТВЕННЫЙ смысл: «этим ответом не вычислено».
// [RuleStatesOf] его не возвращает никогда — иначе «посчитано, терять нечего»
// стало бы неотличимо от «не считали».
type RuleLifecycle uint8

const (
	// RuleLifecycleUnknown — не вычислено ЭТИМ ответом. НИКОГДА не «действует».
	RuleLifecycleUnknown RuleLifecycle = iota
	// RuleLifecycleActive — ни один адресуемый сегмент правила не потерян.
	RuleLifecycleActive
	// RuleLifecycleWithdrawn — потерянные сегменты есть, и КАЖДЫЙ объяснён
	// ведомостью переселения: объявление сняла платформа.
	RuleLifecycleWithdrawn
	// RuleLifecycleUnresolved — потерянные сегменты есть, и ХОТЯ БЫ ОДИН не
	// объяснён: правило ссылается на то, чего сейчас нет.
	RuleLifecycleUnresolved
)

// RuleState — состояние одного правила роли и три величины, из которых оно
// выведено.
//
// # Почему слово И счётчики, а не одно из двух
//
// Правило, у которого часть потерь объяснена, а часть нет, читается
// [RuleLifecycleUnresolved] — слово называет состояние, ТРЕБУЮЩЕЕ разбора.
// Схлопыванием это не является ровно потому, что рядом стоят обе величины:
// `Withdrawn` и `Unresolved` видны одновременно, и ни одна не потеряна.
//
// Четвёртое значение («частично отозвано») рассмотрено и отвергнуто: у него нет
// ни своего действия у арендатора, ни своего производителя, при том что
// счётчики уже несут ровно ту же величину.
type RuleState struct {
	// RuleIndex — индекс правила в `Role.Rules`. КЛЮЧ записи: порядок самих
	// записей не значим, сверять надо по нему.
	//
	// Индекс законен как ключ потому, что `roles.rules` — массив JSONB под одним
	// кодеком, и порядок сохраняется by construction: правило читается тем же
	// индексом, каким записано. Действителен он в пределах ОДНОГО ответа:
	// `Update` перестраивает массив, и мутацию индекс не переживает.
	RuleIndex int
	// State — состояние правила. У вычисленного оно непусто ВСЕГДА.
	State RuleLifecycle
	// Segments — сколько АДРЕСУЕМЫХ сегментов объявляет это правило.
	// Ноль законен (подстановка в модуле или ресурсе сегментов не даёт).
	//
	// ЕДИНИЦА ДРУГАЯ, ЧЕМ У [RoleIntegrity.Declared], и потому имя другое:
	// счётчик роли дедуплицирует сегмент по ВСЕЙ роли, здесь — только внутри
	// правила. Равенство сумм поэтому НЕ ГАРАНТИРОВАНО и нарушается ровно
	// тогда, когда один сегмент назван двумя правилами; на прочих ролях суммы
	// совпадают, и это совпадение, а не инвариант.
	Segments int
	// Lost — сколько из объявленных сегментов этого правила не дают ни одной
	// строки проекции, которую читает вердикт.
	//
	// ПРЕДИКАТ ТОТ ЖЕ, что у [RoleIntegrity.Unresolved]: ведомость здесь не
	// спрашивается — её спрашивает [RuleState.Explained] рядом. Различает
	// величины только единица дедупликации.
	Lost int
	// Explained — сколько из потерянных ОБЪЯСНЕНЫ ведомостью переселения.
	// Необъяснённые выводятся вычитанием: третье поле, равное разности двух
	// соседних, разошлось бы с ними при первой же правке.
	Explained int
}

// RuleRefsByRule — объявленные сегменты, разложенные ПО ПРАВИЛАМ.
//
// Длина результата равна длине входа ВСЕГДА: правило без адресуемых сегментов
// даёт пустой срез, а не пропускается. Иначе индекс перестал бы указывать на
// своё правило — то есть ключ [RuleState.RuleIndex] стал бы ложным.
//
// # Чем это отличается от [RuleRefsOf], и различие несущее
//
// [RuleRefsOf] дедуплицирует сегменты ПО ВСЕЙ РОЛИ: два правила, объявившие один
// сегмент, дают одну строку — и это верно для вопроса «сколько адресуемых
// сегментов у роли». Здесь наоборот: дедупликация только ВНУТРИ правила, потому
// что сегмент, потерянный обоими правилами, потерян у ОБОИХ, и схлопнув их, мы
// объявили бы одно из них действующим.
func RuleRefsByRule(rules Rules) [][]RoleRuleRef {
	out := make([][]RoleRuleRef, len(rules))
	for i, r := range rules {
		refs := make([]RoleRuleRef, 0, len(r.Resources))
		if r.Module == wildcard {
			out[i] = refs
			continue
		}
		seen := make(map[RoleRuleRef]bool)
		for _, res := range r.Resources {
			if res == wildcard {
				continue
			}
			for _, ref := range refsOfRule(r, res) {
				if seen[ref] {
					continue
				}
				seen[ref] = true
				refs = append(refs, ref)
			}
		}
		out[i] = refs
	}
	return out
}

// RuleStatesOf — состояние каждого правила роли. ЕДИНСТВЕННОЕ место, где
// решается, какое состояние несёт правило.
//
// Вход:
//
//   - rules — авторские правила роли;
//   - unresolved — сегменты роли, не давшие НИ ОДНОЙ строки проекции, которую
//     читает вердикт. Источник состояния;
//   - withdrawn — ведомость переселения. Только ОБЪЯСНЯЕТ: судить состояние по
//     ней значило бы читать роль, пострадавшую вторым путём, действующей.
//
// Записей в результате ровно `len(rules)`, и `RuleIndex` каждой указывает на
// своё правило.
func RuleStatesOf(rules Rules, unresolved []RoleSegment, withdrawn []WithdrawnGrant) []RuleState {
	if len(rules) == 0 {
		return nil
	}
	lostSet := make(map[RoleRuleRef]bool, len(unresolved))
	for _, s := range unresolved {
		lostSet[refOfSegment(s)] = true
	}
	// Ведомость сверяется ПАРОЙ «тип + глагол», и пустой глагол здесь — ЯКОРЬ,
	// а не «любой глагол»: якорная строка объясняет якорный сегмент и только
	// его. Иначе объяснение одного глагола покрывало бы правило, назвавшее
	// глаголы поимённо.
	explained := make(map[RoleRuleRef]bool, len(withdrawn))
	for _, w := range withdrawn {
		explained[refOfDotted(w.ObjectType, w.Verb)] = true
	}

	byRule := RuleRefsByRule(rules)
	out := make([]RuleState, len(rules))
	for i, refs := range byRule {
		st := RuleState{RuleIndex: i, Segments: len(refs)}
		for _, ref := range refs {
			if !lostSet[ref] {
				continue
			}
			st.Lost++
			if explained[ref] {
				st.Explained++
			}
		}
		switch {
		case st.Lost == 0:
			st.State = RuleLifecycleActive
		case st.Explained == st.Lost:
			st.State = RuleLifecycleWithdrawn
		default:
			st.State = RuleLifecycleUnresolved
		}
		out[i] = st
	}
	return out
}

// refOfSegment — сегмент в форме ссылки правила. Точечное имя разбирается ТЕМ
// ЖЕ разделителем, каким его склеивает [RoleRuleRef.Dotted]; второе написание
// разошлось бы молча.
func refOfSegment(s RoleSegment) RoleRuleRef { return refOfDotted(s.ObjectType, s.Verb) }

// refOfDotted — пара «точечный тип + глагол» в форме ссылки правила.
//
// Разбор идёт по ПЕРВОЙ точке: имя модуля точки не содержит (DB CHECK
// `catalog_module_undotted`), а имя ресурса подчёркивание и дефис допускает.
// Строка без точки даёт ссылку с пустым модулем — она не совпадёт ни с одной
// объявленной, и это верно: такого сегмента правило не объявляло.
func refOfDotted(dotted, verb string) RoleRuleRef {
	for i := 0; i < len(dotted); i++ {
		if dotted[i] == '.' {
			return RoleRuleRef{Module: dotted[:i], Resource: dotted[i+1:], Verb: verb}
		}
	}
	return RoleRuleRef{Resource: dotted, Verb: verb}
}
