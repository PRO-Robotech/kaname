package domain

import "regexp"

// object_type_name.go — ФОРМА имени типа объекта модели прав, объявленная ОДИН
// раз.
//
// # Почему форма стала предметом (задача продукта #2015)
//
// Пока таблица типов была ЗАКРЫТА, форму имени никто не судил и судить было
// незачем: загрузчик манифеста спрашивал ЧЛЕНСТВО, а всякий член таблицы годен
// по форме by construction. Таблица разомкнута — оператор чужого облака
// объявляет свой ресурс доставкой, — и вопрос «годно ли имя» стал первым, на
// который отвечать больше некому.
//
// # Читателей у грамматики ТРИ, и они судят РАЗНОЕ
//
//	`objectType` ресурса манифеста и тип его указателя  (internal/manifest)
//	строка `type <идентификатор>` собранной модели прав (internal/authzmodel, Д7(б))
//	колонка `catalog_resource.object_type`              (CHECK в базе)
//
// Первые два зовут ЭТУ функцию. Третий выражен ограничением базы и потому не
// вправе звать Go вовсе — согласие держит проба, сверяющая текст ограничения с
// [ObjectTypeNameGrammar], а не эта строка.
//
// Вторая копия образца разошлась бы с первой молча — на том имени, о котором
// знает только одна: манифест принял бы тип, который база отвергнет ключом (то
// есть отказ пришёл бы ЧУЖОЙ полосой, фразой Postgres про имя ограничения), либо
// допуск собранной модели отверг бы тип, который манифест уже применил.
//
// # Почему подчёркивание, но не дефис и не точка
//
// Имя типа входит в текст модели прав отдельным идентификатором (`type
// acme_widget`), а грамматика той модели дефиса не принимает. Точка же — РАЗДЕЛИТЕЛЬ
// точечного ключа каталога (`acme.widget`), и имя типа, её содержащее, сделало бы
// разбор ключа неоднозначным.
var objectTypeNameRe = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

// IsWellFormedObjectTypeName — годно ли имя типа объекта по ФОРМЕ, безотносительно
// того, объявлял ли его кто-нибудь.
func IsWellFormedObjectTypeName(objectType string) bool {
	return objectTypeNameRe.MatchString(objectType)
}

// ObjectTypeNameGrammar — образец имени типа СТРОКОЙ, для текстов отказа и для
// сверки с ограничением базы.
//
// Отказ обязан назвать не только негодный токен, но и правило: без правила автор
// манифеста узнаёт, что ошибся, и не узнаёт, чем именно. Величина берётся у того
// же объявления, что судит, — выписанная рядом, она разошлась бы с ним молча.
func ObjectTypeNameGrammar() string { return objectTypeNameRe.String() }
