package domain

// seeded_ids.go — ЗАКРЫТЫЙ перечень идентификаторов, посеянных ПРИМЕНЁННОЙ
// миграцией и не укладывающихся в чеканную форму `<prefix><17>`.
//
// # ПОЧЕМУ ПЕРЕЧЕНЬ, А НЕ ОСЛАБЛЕНИЕ ДЛИНЫ
//
// Ослабить длину значило бы принимать ЛЮБОЙ мусор той же длины у КАЖДОГО
// ресурса. Перечень расширяет приём ровно на те строки, которые продукт посеял
// сам: они неизменяемы by construction (ban #15 — операции смены id не
// существует), их нельзя прислать снаружи (id чеканит сервер, не вызывающий), и
// каждая из них уже лежит в базе.
//
// # ПОЧЕМУ НЕ ПОЧИНИТЬ ПОСЕВ
//
// Применённую миграцию править нельзя (ban #5). Переименование поздней
// миграцией — перенос выдачи с одной роли на другую, то есть тихое расширение
// прав; его отвергает гейт `TestNoMigrationMovesGrantsBetweenRoles`, и замок
// IAM-RM-1-13 обязан пережить изменение. Обойти его каскадом по ключу значило бы
// спрятать перенос от контроля.
//
// # ПОЧЕМУ ЭТО НЕ ПОСЛАБЛЕНИЕ «НА ВСЯКИЙ СЛУЧАЙ»
//
// У перечня есть гейт предмета (`internal/check`,
// `TestSeededIDExceptionsHaveASubject`): каждая запись обязана (а) быть
// НАЙДЕНА посевом миграции и (б) быть ОТВЕРГНУТА чеканной формой. Запись,
// которой больше нечего прощать, — находка, а не тишина.

// seededResourceIDs — литералы, посеянные миграциями. Ключ — сам литерал.
var seededResourceIDs = map[string]struct{}{
	// `kacho-system.viewer`, посев 0001_initial.sql. Длина 21 при чеканных 20.
	SystemViewerRoleID: {},
}

// IsSeededResourceID отвечает, назван ли литерал закрытым перечнем посеянного.
//
// Проверку ПРЕФИКСА он на себя НЕ берёт: её делает вызывающий
// (`shared.ValidateResourceID`), поэтому посеянный id роли не проходит там, где
// ждут аккаунт.
func IsSeededResourceID(id string) bool {
	_, ok := seededResourceIDs[id]
	return ok
}

// SeededResourceIDs возвращает перечень для гейта предмета. Копия — чтобы
// вызывающий не мог расширить приём, правя чужую карту.
func SeededResourceIDs() []string {
	out := make([]string, 0, len(seededResourceIDs))
	for id := range seededResourceIDs {
		out = append(out, id)
	}
	return out
}
