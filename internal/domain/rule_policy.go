package domain

import "fmt"

// RulePolicy — политика послабления подстановки в правилах роли.
//
// # Почему политик ТРИ, а не две (задача продукта #1032)
//
// До неё политика была одна булева — «системный контекст». Признак `is_system`
// вычисляется ровно из непустого кластерного якоря и несёт ДВА смысла сразу:
// «арендатор эту роль не правит» и «этой роли можно подставлять звёздочку».
// Базовая роль модуля обязана быть системной в первом смысле — иначе её правит
// арендатор, — и вместе с ним получала второй: прямой путь к `*.*.*`. В диффе
// это выглядит обычной строкой роли, и ни один обзор её не поймает.
//
// Политики различает ВЛАДЕЛЕЦ, а не ярус:
//
//	арендаторская   якоря кластера нет            module: "*" ✗   ресурс "*" ✗
//	модульная       якорь есть, владелец назван   module: "*" ✗   ресурс "*" ✓ только в своём модуле
//	платформенная   якорь есть, владельца нет     module: "*" ✓   ресурс "*" ✓
//
// Одно правило, а не три исключения: подстановка в роли с владельцем законна
// ровно в пределах её модуля. Отсюда обе строки механически — `module: "*"` не
// находится ни в одном модуле, поэтому отвергается всегда; ресурс `*` находится
// в модуле своего правила, поэтому законен ровно тогда, когда этот модуль и
// есть владелец.
//
// # Глагол `*` не затрагивается — решение, а не пропуск
//
// Он разрешён и в арендаторской роли, безусловно ([validateVerbs]): он не
// сегмент пространства имён, а «все действия названного типа». Сузить его здесь
// значило бы отобрать уже выданное под видом починки.
//
// # Носитель — ЗНАЧЕНИЕ, а не второй булев флаг
//
// Два булевых параметра дают четыре сочетания при трёх законных, и четвёртое
// («не системная, но с владельцем») пришлось бы отвергать четвёртым правилом.
// Политика передаётся одним значением закрытого перечня, выводимым из строки
// функцией ОДНОГО места — [PolicyOfRole]. Второе объявление «системная ли роль
// для целей подстановки» есть находка, и её ловит гейт дерева.
type RulePolicy struct {
	tier  policyTier
	owner string
}

// policyTier — закрытый перечень. Неэкспортирован намеренно: значение
// собирается только [PolicyOfRole], поэтому четвёртого сочетания не бывает by
// construction, а не по договорённости.
type policyTier uint8

const (
	// tierUnset — нулевое значение. Собранная не через [PolicyOfRole] политика
	// отвергается самой строгой ветвью: «не знаю» не есть «можно».
	tierUnset policyTier = iota
	tierTenant
	tierModule
	tierPlatform
)

// PolicyOfRole выводит политику ИЗ СТРОКИ — единственное место в дереве, где
// это делается.
//
// `isSystem` берётся оттуда же, откуда его берёт база: из непустого кластерного
// якоря. `ownerModule` пуст у платформенной роли и непуст у роли, объявленной
// манифестом модуля.
//
// Сочетание «не системная, но с владельцем» законным не является: владельца
// пишет только применитель ролей модуля, а он объявляет роль системной
// безусловно. Такой вход политику получает АРЕНДАТОРСКУЮ — самую строгую:
// послабление выдаётся по доказанному признаку, а не по частично совпавшему.
func PolicyOfRole(isSystem bool, ownerModule string) RulePolicy {
	switch {
	case !isSystem:
		return RulePolicy{tier: tierTenant}
	case ownerModule != "":
		return RulePolicy{tier: tierModule, owner: ownerModule}
	default:
		return RulePolicy{tier: tierPlatform}
	}
}

// TenantPolicy — арендаторская политика в чистом виде.
//
// Нужна вызывающему, у которого строки роли нет вовсе: загрузчик манифеста
// судит правила ДО того, как роль станет строкой, и обязан судить их самой
// строгой политикой. Порядок — часть контракта (сценарий IAM-OM-1-18): отказ
// приходит от загрузчика с координатой строки YAML, а не от применителя, у
// которого координаты нет.
func TenantPolicy() RulePolicy { return RulePolicy{tier: tierTenant} }

// OwnerModule — модуль-владелец роли; пусто у арендаторской и платформенной.
func (p RulePolicy) OwnerModule() string { return p.owner }

// allowsModuleWildcard — подстановка МОДУЛЯ. Законна только у платформенной
// роли: `*` не находится ни в одном модуле, поэтому «в пределах своего модуля»
// для неё невыразимо.
func (p RulePolicy) allowsModuleWildcard() bool { return p.tier == tierPlatform }

// allowsResourceWildcardIn — подстановка РЕСУРСА в правиле, называющем module.
//
// У модульной политики законна ровно в пределах владельца; у платформенной —
// везде; у арендаторской — нигде.
func (p RulePolicy) allowsResourceWildcardIn(module string) bool {
	switch p.tier {
	case tierPlatform:
		return true
	case tierModule:
		return module == p.owner
	default:
		return false
	}
}

// moduleWildcardRefusal — текст отказа подстановки модуля.
//
// У модульной политики он СВОЙ, а не заимствованный у арендаторской. Прежде
// заказывался арендаторский — `wildcard '*' is system-only`, — и он ЛОЖЕН для
// своего предмета: роль модуля системная и есть, поэтому автору манифеста
// сообщалось бы, что подстановка доступна только системным ролям, про роль,
// которая ею является. Отказ обязан восстанавливать следующий шаг: назвать
// предмет отказа, действительное правило и что менять.
func (p RulePolicy) moduleWildcardRefusal() error {
	if p.tier == tierModule {
		return fmt.Errorf("Illegal argument module (wildcard '*' is not available to a role "+
			"owned by module '%s'; name the module this rule grants in)", p.owner)
	}
	return fmt.Errorf("Illegal argument module (wildcard '*' is system-only)")
}

// resourceWildcardRefusal — текст отказа подстановки ресурса.
//
// У модульной политики он называет ОБА значения: без второго автор не знает,
// какое из двух менять — владельца роли или модуль правила.
func (p RulePolicy) resourceWildcardRefusal(field, module string) error {
	if p.tier == tierModule {
		return fmt.Errorf("Illegal argument %s (wildcard '*' is confined to the owning module "+
			"'%s'; this rule names module '%s')", field, p.owner, module)
	}
	return fmt.Errorf("Illegal argument %s (wildcard '*' is system-only)", field)
}
