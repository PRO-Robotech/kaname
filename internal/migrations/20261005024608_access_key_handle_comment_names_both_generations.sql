-- access_key_handle_comment_names_both_generations — описание колонки
-- `kaname.user_access_keys.user_handle` называет ОБА поколения строк, которые
-- в ней лежат (задача PRO-Robotech/kaname#344).
--
-- Санкция: приёмка Ф13 `docs/engineering/acceptance/passwordless-login-with-access-key.md`,
-- редакция 9 (отпечаток 5fe6cca1…8af4, `APPROVED`), решение Р3 и §4.4
-- («четвёртое место — комментарий влитой миграции»); приёмка Ф7
-- `docs/engineering/acceptance/access-keys-are-ours.md` (отпечаток 5ea26ad0…efbe,
-- `APPROVED`), §6 — та же строка с тем же исходом: новая миграция, применённый
-- файл не тронут.
--
-- =============================================================================
-- ЗАЧЕМ ЕЩЁ ОДНА
-- =============================================================================
-- Прежнее описание колонки стояло в применённой миграции
-- `20260917221000_access_keys_are_our_record.sql` и называло значением
-- платформенный id человека. Миграция `20261003212856` заменила его тем же
-- изменением, которым сменилось значение, — и заменила утверждением о ВСЕХ
-- строках («платформенным id человека не является»), верным лишь о новых.
--
-- Р3 кладёт новое значение ТОЛЬКО новым регистрациям: ключ, заведённый раньше,
-- сохраняет то, что тогда легло в его строку, и сверяется со своим —
-- переписать значение, уже лежащее в аутентификаторе, нечем (обратного
-- заполнения нет и быть не может). На посадке, где такие ключи есть, описание
-- отрицало бы значение, лежащее в базе: тот же класс, что и комментарий,
-- который оно заменило, — схема сообщает читателю снятое как действующее,
-- только в обратную сторону.
--
-- Заодно возвращён смысл NULL: колонка его допускает, а замена его опустила.
--
-- Применённые миграции не правятся (ban #5): ни `20260917221000`, ни
-- `20261003212856`. Схема не меняется — только описание.

-- +goose Up

COMMENT ON COLUMN kaname.user_access_keys.user_handle IS
  'Рукоятка user.id, которую церемония регистрации положила в ЭТОТ ключ; с ней сверяется каждое утверждение ключа (полоса входа Ф13). Значение у строки своё навсегда: переписать то, что уже лежит в аутентификаторе, нечем (Ф13 Р3). Ключ, заведённый после миграции 20261003212856, несёт значение из kaname.user_ceremony_handles — 64 случайных байта человека, ни из id, ни из адреса, ни из имени не выводимые. Ключ, заведённый раньше, несёт то, что легло тогда: у ключей Ф7 это платформенный id человека как байты, и сверяется он со своим. NULL — значения строка не несёт; нынешний писатель (приём результата регистрации) кладёт его всегда.';

-- +goose Down

COMMENT ON COLUMN kaname.user_access_keys.user_handle IS
  'Рукоятка user.id, которую церемония регистрации положила в ЭТОТ ключ: значение из kaname.user_ceremony_handles (64 случайных байта на человека). Платформенным id человека НЕ является. С ней сверяется каждое утверждение ключа (полоса входа Ф13).';
