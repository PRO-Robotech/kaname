-- =============================================================================
-- Имя ресурса: одна форма на всё дерево, пустого имени не существует — схема iam.
-- =============================================================================
-- Задача `PRO-Robotech/kacho#1279`; канон заведён `#715`.
--
-- ПОЧЕМУ IAM ПРИХОДИТ ПОСЛЕДНИМ. Когда канон вводили, iam вывели из-под него
-- одним доводом: «имя роли есть идентификатор». Довод верен — `roles/vpc.admin`
-- то, на что ссылаются привязки, — но он про ОДИН тип, а вывели весь сервис.
-- Остальные шесть имён iam (аккаунт, проект, группа, служебная учётка, токен,
-- интерактивный клиент) — косметические метки: адресация идёт по неизменяемому
-- идентификатору (запрет #15). Идентификатор роли под эту миграцию НЕ подпадает
-- и своей формы не меняет.
--
-- ЧТО МЕНЯЕТСЯ В КОНТРАКТЕ. Форма имени сведена к одной — DNS label по RFC 1123,
-- `^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$`. Пустая строка остаётся законным ВХОДОМ
-- создания, но ресурсом с пустым именем не становится: сервис подставляет имя,
-- производное от `id`, до вставки.
--
-- ПОЧЕМУ БАЗУ НАДО ТРОГАТЬ, А НЕ ТОЛЬКО КОД. Прежнее ограничение этой схемы
-- расходится с новой формой В ОБЕ СТОРОНЫ, и обе стороны наблюдаемы:
--
--   * оно УЖЕ канона — требует БУКВУ первым символом (RFC 1123 допускает цифру)
--     и длину от 3 (канон — от 1). Без этой миграции имя `9lives` проходит
--     проверку сервиса и умирает на ограничении таблицы: вызывающий получает
--     внутреннюю ошибку там, где контракт обещал успех;
--   * оно ШИРЕ канона — принимает имя, КОНЧАЮЩЕЕСЯ ДЕФИСОМ (`^[a-z][-a-z0-9]{2,62}$`
--     не требует, чтобы последний символ был буквой или цифрой). Такая строка
--     каноничной не является и, оставшись, ломала бы полный набор утверждений
--     о форме.
--
-- ЧТО ДЕЛАЕТСЯ СО СТАРЫМИ СТРОКАМИ. Строка, чьё имя новой форме не отвечает,
-- получает `name = id`. Правило одно на оба случая — и на пустое имя, и на
-- `legacy-name-`, — потому что `id` глобально уникален by construction: замена
-- не может ни столкнуться с чужим именем, ни зависеть от порядка строк.
-- Изобретать «отрезать хвостовой дефис» здесь нельзя: это было бы ВТОРЫМ
-- производством имени, живущим в SQL и расходящимся с тем, что делает сервис.
--
-- ЗАМЕР ПЕРЕД ПРАВКОЙ. Имён, законных по прежней форме и незаконных по канону,
-- в дереве НЕТ: все посевные имена схемы (`kacho-system`, `kacho-vpc`,
-- `kacho-compute`, `kacho-storage`, `kacho-registry`, `kacho-bootstrap-admin`,
-- `module-quota-readers`, `module-relation-writers`) каноничны как есть, и
-- производимое кодом `personal-cloud-<хвост id>` — тоже. То есть на этом дереве
-- обратное заполнение не меняет ни одной строки; оно стоит здесь ради баз, где
-- арендатор успел завести имя с хвостовым дефисом.
--
-- ЦЕНА НАЗВАНА ЧЕСТНО: выбранное арендатором имя, не отвечающее форме, будет
-- заменено идентификатором. Это допустимо, потому что имя косметическое и
-- изменяемое (запрет #15 — адресация идёт по `id`), а облако не в проде
-- (директива владельца 2026-07-27). Арендатор переименует ресурс одним вызовом.
--
-- ИДЕМПОТЕНТНОСТЬ. Повторный прогон не меняет ничего: после первого прохода
-- строк, не отвечающих форме, не остаётся, а ограничения создаются через
-- DROP IF EXISTS + ADD.
--
-- ПОЧЕМУ ИМЯ ОГРАНИЧЕНИЯ ПРИВОДИТСЯ К `<таблица>_name_check`. Отображение отказа
-- узнаёт полосу формы имени по этой конструкции (`nameform.IsConstraint`), и
-- узнаёт её ТОЧНЫМ сравнением, а не суффиксом: `users_display_name_check` в этой
-- же схеме кончается так же, но сторожит длину другого поля. Интерактивный
-- клиент нёс своё имя ограничения (`interactive_clients_name_form_ck`) — оно
-- переименовывается, иначе отказ формы читался бы как отказ по вводу.

-- +goose Up
-- +goose StatementBegin

SET search_path TO kacho_iam, public;

DO $$
DECLARE
    t   text;
    -- Тенантные таблицы схемы, несущие косметическое имя ресурса.
    --
    -- `roles` здесь НЕТ намеренно: идентификатор роли формой имени не судится
    -- (записанное решение владельца, #715). `clusters` нет по другой причине:
    -- кластер — посевной синглтон, глагола создания у него не существует, и его
    -- единственная строка приходит миграцией. Обе таблицы объявлены носителями
    -- намеренно иной формы в пробе ограничения, и перечень там проверяется в обе
    -- стороны: приди любая из них к канону — запись покраснеет.
    tbl text[] := ARRAY[
        'accounts', 'projects', 'groups', 'service_accounts', 'interactive_clients'
    ];
    -- Единственная форма имени. Держится в одной переменной, чтобы пять
    -- ограничений не могли разойтись между собой внутри одного файла.
    form text := '^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$';
BEGIN
    FOREACH t IN ARRAY tbl LOOP
        -- 1. Имя, не отвечающее форме (включая пустое), заменяется на id.
        --    ДО создания ограничения: иначе оно не построится.
        EXECUTE format(
            'UPDATE kacho_iam.%I SET name = id WHERE name IS NULL OR name !~ %L',
            t, form);

        -- 2. Ограничение формы приводится к канону. Снимаются оба исторических
        --    имени: общее для схемы и своё у интерактивного клиента.
        EXECUTE format('ALTER TABLE kacho_iam.%I DROP CONSTRAINT IF EXISTS %I', t, t || '_name_check');
        EXECUTE format('ALTER TABLE kacho_iam.%I DROP CONSTRAINT IF EXISTS %I', t, t || '_name_form_ck');
        EXECUTE format(
            'ALTER TABLE kacho_iam.%I ADD CONSTRAINT %I CHECK (name ~ %L)',
            t, t || '_name_check', form);
    END LOOP;
END $$;

-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin

-- Откат возвращает ПРЕЖНЮЮ форму ограничений, включая своё имя у интерактивного
-- клиента.
--
-- Он НЕ восстанавливает прежние имена строк: заменённое имя не сохранено нигде,
-- и восстановить его неоткуда. Это свойство отката названо прямо, а не скрыто за
-- «симметричным» текстом: откат вернёт правила, но не данные.
--
-- Отдельно: прежняя форма УЖЕ канона, поэтому строка с каноничным именем, не
-- проходящим по ней (`9lives`, `a`), откат заблокирует. Такая строка заводится
-- только ПОСЛЕ применения этой миграции, и убрать её — работа оператора,
-- решившего откатываться; молча переименовывать чужие ресурсы на пути назад
-- миграция не вправе.

SET search_path TO kacho_iam, public;

DO $$
DECLARE
    t   text;
    tbl text[] := ARRAY[
        'accounts', 'projects', 'groups', 'service_accounts'
    ];
    legacy text := '^[a-z][-a-z0-9]{2,62}$';
BEGIN
    FOREACH t IN ARRAY tbl LOOP
        EXECUTE format('ALTER TABLE kacho_iam.%I DROP CONSTRAINT IF EXISTS %I', t, t || '_name_check');
        EXECUTE format(
            'ALTER TABLE kacho_iam.%I ADD CONSTRAINT %I CHECK (name ~ %L)',
            t, t || '_name_check', legacy);
    END LOOP;
END $$;

ALTER TABLE kacho_iam.interactive_clients
    DROP CONSTRAINT IF EXISTS interactive_clients_name_check;
ALTER TABLE kacho_iam.interactive_clients
    ADD CONSTRAINT interactive_clients_name_form_ck
        CHECK (name ~ '^[a-z][-a-z0-9]{2,62}$');

-- +goose StatementEnd
