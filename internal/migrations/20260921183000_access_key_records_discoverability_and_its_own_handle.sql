-- access_key_records_discoverability_and_its_own_handle — ДВА ФАКТА строки
-- ключа доступа, которые нельзя записать потом (продолжение
-- `20260917221000_access_keys_are_our_record.sql`; применённая миграция не
-- правится — ban #5).
--
-- =============================================================================
-- ПОЧЕМУ «ПОТОМ» ЗДЕСЬ НЕ БЫВАЕТ
-- =============================================================================
-- Обнаружимость сообщается расширением свойств удостоверения (`credProps.rk`)
-- РОВНО ОДИН РАЗ — в церемонии регистрации. Аутентификатор больше никогда
-- этого не скажет, из последующих утверждений признак не выводится: их флаги
-- говорят о присутствии, проверке пользователя и резервном копировании, но не
-- об обнаружимости. Колонка, заведённая позже, у каждого уже заведённого ключа
-- осталась бы пустой НАВСЕГДА.
--
-- Рукоятка (`user.id` церемонии) записывается В АУТЕНТИФИКАТОР и в
-- синхронизируемое хранилище держателя, возвращается в каждом утверждении
-- обнаруживаемого удостоверения и видна в интерфейсе управления удостоверениями
-- операционной системы. Отозвать её нечем — писать туда мы не можем. Пока в ней
-- стоит наш платформенный `id`, развязать учётную запись с ним невозможно:
-- строки снимутся, а рукоятка в чужом хранилище останется называть снятый
-- идентификатор.
--
-- Окно, в котором оба решения ещё принимаются, — до ПЕРВОЙ регистрации на
-- посадке. Перемерено на день миграции: таблицы `kaname.user_access_keys` на
-- живом стенде нет (`20260917221000` не применена, наибольшая применённая —
-- `20260917210000`), ключей ноль. Обратного заполнения поэтому не требуется, и
-- обратного заполнения, которое было бы ЧЕСТНЫМ, для этих двух величин не
-- существует: обнаружимость выдумать нельзя, а рукоятку заведённого ключа
-- сменить нельзя — она уже уехала.
--
-- =============================================================================
-- ОБНАРУЖИМОСТЬ — ТРИ СОСТОЯНИЯ, А НЕ ДВА И НЕ «ПУСТО»
-- =============================================================================
-- `discoverable` — расширение сообщило «обнаруживаемое»;
-- `not-discoverable` — расширение сообщило «НЕ обнаруживаемое»;
-- `not-reported` — расширение не сообщено вовсе.
--
-- Третье — ПЕРВОКЛАССНОЕ состояние, а не отсутствие значения: не все
-- аутентификаторы и не все браузеры расширение возвращают, и отвергать такой
-- результат значило бы отказывать годным ключам за молчание чужой реализации.
-- Поэтому колонка `NOT NULL` со словарём из трёх слов, а не `boolean NULL`:
-- у `NULL` нет способа отличить «не сообщено» от «колонку забыли заполнить».
--
-- Умолчание живёт ровно столько, сколько нужно обратному заполнению, и
-- снимается тем же оператором: вставка, не назвавшая колонку, обязана
-- отказывать, а не молча получать одно из трёх состояний.
--
-- Кто пишет какое состояние СЕГОДНЯ: церемония регистрации — `discoverable`
-- либо `not-reported`; результат, сообщивший «не обнаруживаемое», она отвергает
-- (Ф7-41) и строки не заводит. Значит, `not-discoverable` сегодня не пишет ни
-- одна полоса, и это сказано здесь, а не умолчано.
--
-- Почему состояние всё равно в словаре — и почему это НЕ обещание будущей
-- полосы. Колонка записывает, ЧТО СООБЩИЛО РАСШИРЕНИЕ, а сторон у него ровно
-- три; область значений колонки есть область значений факта, а не область
-- действующей политики одной полосы. Словарь из двух слов означал бы, что
-- колонка не умеет записать собственный предмет, и первое же изменение
-- политики приёма потребовало бы правки схемы — ровно того, чего эта миграция
-- и избегает: величину спрашивают один раз, и переспросить будет не у кого.
-- Что все три состояния доезжают до строки и читаются обратно, держит проба
-- адаптера, а не обещание.
--
-- Словарь закрыт ограничением, и это ограничение — единственное место, где
-- перечень состояний объявлен для базы.
--
-- ЧИТАТЕЛЬ у колонки ЕСТЬ, и он появляется тем же изменением: страж последнего
-- способа входа (Ф7-26) считает способы, ГОДНЫЕ К ПРЕДЪЯВЛЕНИЮ, — то есть
-- строки с `discoverable`, — а не строки вообще. Ключ, обнаружимость которого
-- не подтверждена, способом входа без имени не является by construction: без
-- обнаруживаемого удостоверения полоса входа без имени невозможна.
--
-- =============================================================================
-- РУКОЯТКА — ОТДЕЛЬНОЕ СЛУЧАЙНОЕ ЗНАЧЕНИЕ НА ЧЕЛОВЕКА
-- =============================================================================
-- Норма (§14.6.1) рекомендует ровно это: 64 случайных байта, хранимых у
-- доверяющей стороны и не связанных ни с чем другим. Значение заводится
-- лениво — первой церемонией регистрации человека — и НИКОГДА не меняется:
-- смена рассинхронизировала бы строки ключей с тем, что лежит в
-- аутентификаторах.
--
-- Почему отдельная таблица, а не колонка `users`: рукоятка — величина полосы
-- ключа доступа, а не свойство личности, и её снятие вместе с человеком —
-- ровно то, ради чего она заводится. Каскад по человеку и есть механизм
-- развязки: строки уходят, и рукоятка, оставшаяся в чужом аутентификаторе,
-- больше не называет ничего нашего.
--
-- Почему рукоятка ВСЁ РАВНО хранится и в строке ключа: строка помнит то, что
-- церемония положила в `user.id` ИМЕННО ЭТОГО ключа; у перенесённого ключа она
-- своя, из источника, и ни с одним нашим значением не совпадает. Здешняя
-- таблица — ИСТОЧНИК значения для новых церемоний, а не его единственное место.

-- +goose Up

ALTER TABLE kaname.user_access_keys
    ADD COLUMN discoverability text NOT NULL DEFAULT 'not-reported',
    ADD CONSTRAINT user_access_keys_discoverability_check
        CHECK ((discoverability = ANY (ARRAY['discoverable'::text, 'not-discoverable'::text, 'not-reported'::text])));

-- Умолчание сняло обратное заполнение и уходит вместе с ним: дальше каждая
-- вставка называет состояние сама, иначе отказ.
ALTER TABLE kaname.user_access_keys ALTER COLUMN discoverability DROP DEFAULT;

COMMENT ON COLUMN kaname.user_access_keys.discoverability IS
  'Что расширение свойств удостоверения сообщило В ЦЕРЕМОНИИ РЕГИСТРАЦИИ — единственный момент, когда это известно: discoverable | not-discoverable | not-reported. Третье — первоклассное состояние («чужая реализация промолчала»), а не отсутствие значения. Читатель — страж последнего способа входа (Ф7-26): годным к предъявлению считается только discoverable.';

COMMENT ON COLUMN kaname.user_access_keys.user_handle IS
  'Рукоятка user.id ЭТОГО ключа: у ключей церемонии — значение из kaname.user_ceremony_handles (64 случайных байта на человека), у перенесённых — то, что нёс источник. Платформенным id человека НЕ является и не была бы отзываема, если бы являлась. NULL — источник переноса рукоятки не нёс. Читатель — полоса входа Ф13.';

CREATE TABLE kaname.user_ceremony_handles (
    user_id    text NOT NULL,
    handle     bytea NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT user_ceremony_handles_pkey PRIMARY KEY (user_id),
    CONSTRAINT user_ceremony_handles_user_fk FOREIGN KEY (user_id)
        REFERENCES kaname.users(id) ON DELETE CASCADE,
    CONSTRAINT user_ceremony_handles_handle_key UNIQUE (handle),
    -- Длина — рекомендация нормы §14.6.1, и она же предел колонки рукоятки у
    -- строки ключа: значение, не влезающее туда, до церемонии не дошло бы.
    CONSTRAINT user_ceremony_handles_handle_check CHECK ((octet_length(handle) = 64))
);

COMMENT ON TABLE kaname.user_ceremony_handles IS
  'Рукоятка церемонии человека: 64 случайных байта, заведённые лениво первой регистрацией ключа и неизменные после. Ни с чем не связаны: ни с id, ни с адресом, ни с именем — норма §14.6.1 запрещает выводимость личности из рукоятки, а мы вдобавок получаем развязку, потому что снятие человека уносит строку каскадом.';
COMMENT ON COLUMN kaname.user_ceremony_handles.handle IS
  'Случайное значение; уникально по всей службе (ключ уникальности, а не надежда на разрядность). Наружу не выходит: перечень ключей рукоятку не показывает.';

-- Статистика планировщика по байтовой колонке НЕ собирается — те же доводы,
-- что у соседей: анализ таблицы положил бы выборку значений в `pg_statistic`,
-- и эта копия пережила бы удаление строки, ради которого и заведён каскад.
-- Отбирается рукоятка точным равенством по ключу уникальности.
ALTER TABLE kaname.user_ceremony_handles ALTER COLUMN handle SET STATISTICS 0;

-- +goose Down

-- Откат ОТКАЗЫВАЕТСЯ уничтожать то, что не восстанавливается ниоткуда, — по
-- тем же доводам, что откат `20260917221000`, и теми же двумя величинами:
--
--   * обнаружимость сообщил аутентификатор один раз; снятая колонка означает,
--     что о каждом ключе перестало быть известно, годен ли он к предъявлению,
--     и страж последнего способа входа начинает считать строки;
--   * рукоятка уже лежит в чужих аутентификаторах; снятая таблица означает,
--     что следующая церемония того же человека заведёт ВТОРУЮ рукоятку, и у
--     одного человека окажутся ключи с разными `user.id`.
--
-- Откат безопасен ровно тогда, когда откатывать нечего: ключей ноль и рукояток
-- ноль. Тогда он и проходит.
LOCK TABLE kaname.user_access_keys IN ACCESS EXCLUSIVE MODE;
LOCK TABLE kaname.user_ceremony_handles IN ACCESS EXCLUSIVE MODE;

-- +goose StatementBegin
DO $$
DECLARE
  v_keys    bigint;
  v_handles bigint;
BEGIN
  SELECT count(*) INTO v_keys FROM kaname.user_access_keys;
  SELECT count(*) INTO v_handles FROM kaname.user_ceremony_handles;
  IF v_keys > 0 OR v_handles > 0 THEN
    RAISE EXCEPTION 'refusing to roll back: kaname holds % access key row(s) and % ceremony handle row(s); a rollback would destroy two facts that cannot be recorded again — discoverability is reported once, during registration, and a handle already written into someone''s authenticator cannot be rewritten. WAY OUT: the rollback is safe exactly when both counts are 0; if losing them is the intent, revoke those access keys deliberately first', v_keys, v_handles
      USING ERRCODE = 'restrict_violation';
  END IF;
END;
$$;
-- +goose StatementEnd

DROP TABLE kaname.user_ceremony_handles;

COMMENT ON COLUMN kaname.user_access_keys.user_handle IS
  'Рукоятка user.id церемонии (у ключей Ф7 — платформенный id человека как байты); NULL — источник переноса её не нёс. Читатель — полоса входа Ф13.';

ALTER TABLE kaname.user_access_keys DROP CONSTRAINT user_access_keys_discoverability_check;
ALTER TABLE kaname.user_access_keys DROP COLUMN discoverability;
