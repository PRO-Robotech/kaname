-- `20260927001324_family_revocation_reason_names_the_client_revocation.sql`
-- (kaname#406). Правка применённого файла не доезжает до базы, где он уже
-- применён: мигратор сверяет версию, а не содержимое (ban #5). Слова остаются в
-- тексте применённых миграций как история прежних определений.
--
-- =============================================================================
-- ЗАХВАТ
-- =============================================================================
-- Снятие и постановка ограничения берут на `token_families` исключительный
-- захват до конца наката, и постановка читает таблицу целиком, проверяя
-- лежащие строки. Писатели семейств ждут конца наката; отказавший накат
-- повторяем — частичного состояния у него нет: маркер мигратора, снимающий
-- транзакцию, здесь не ставится, и раздел исполняется одной транзакцией.

-- +goose Up

-- Накат ставит ограничение С ПРОВЕРКОЙ лежащих строк и операторов данных не
-- несёт (Р9). Семейство со словом `logout` или `client-removed` ОТКАЗЫВАЕТ
-- накату кодом 23514 по этому ограничению: версия не сдвигается, строки не
-- трогаются. Выбор держится на двух запретах:
--
--   * снять причину нельзя: причина и отметка отзыва — пара
--     (`token_families_revoked_pair_ck`), отметка и живость — тоже
--     (`token_families_live_pair_ck`); снять причину значит оживить семейство;
--   * переписать в другое слово нельзя: продукт такой строки не писал, её
--     положил оператор мимо продукта, и чужое слово выдумало бы повод,
--     которого журнал не видел.
--
-- В базах продукта таких строк нет по построению; решение о строке, положенной
-- мимо продукта, принимает тот, кто её положил. Держит это проба
-- `TestTokenFamilyMigration_KN_FRV_15_UpRefusesWhileAFamilyCarriesARemovedWord`.
--
-- Ограничение снимается и ставится заново ПОД ТЕМ ЖЕ ИМЕНЕМ: имя — координата,
-- по которой его читают пробы словаря и снимает откат. Порядок значений
-- контрактом не является (Р11).
ALTER TABLE kaname.token_families
    DROP CONSTRAINT token_families_revoked_reason_ck;
ALTER TABLE kaname.token_families
    ADD CONSTRAINT token_families_revoked_reason_ck CHECK (
        ((revoked_reason IS NULL) OR (revoked_reason = ANY (ARRAY[
            'code-replay'::text, 'refresh-replay'::text,
            'session-ended'::text, 'client-revoke'::text]))));

-- +goose Down

-- Откат ставит ровно определение наката #406 — шесть значений — и только
-- расширяет словарь (Р10): любое лежащее значение из четырёх входит в шесть,
-- поэтому проверка лежащих строк отказать не может. Операторов данных нет.
-- Слова `logout` и `client-removed` снова принимаются базой, а домен их не
-- знает — сверка словарей на откаченной базе обязана это назвать. Держит это
-- проба `TestTokenFamilyMigration_KN_FRV_16_DownRestoresTheClientRevokeDefinition`.
ALTER TABLE kaname.token_families
    DROP CONSTRAINT token_families_revoked_reason_ck;
ALTER TABLE kaname.token_families
    ADD CONSTRAINT token_families_revoked_reason_ck CHECK (
        ((revoked_reason IS NULL) OR (revoked_reason = ANY (ARRAY[
            'code-replay'::text, 'refresh-replay'::text, 'logout'::text,
            'session-ended'::text, 'client-removed'::text, 'client-revoke'::text]))));
