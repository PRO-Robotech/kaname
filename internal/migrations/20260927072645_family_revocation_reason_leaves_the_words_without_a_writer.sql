-- Словарь закрыт и перечисляет исчерпывающе. У двух слов писателя не было ни
-- в одной ревизии, и обещанное ими исполняют другие механизмы: выход человека
-- отзывает семейство словом `session-ended`, а факт выхода лежит в записи
-- сессии; снятие клиента уносит семейство каскадом внешнего ключа, и выданное
-- остаётся с пустой живостью. Слова сняты доменом
-- (`domain.FamilyRevocationReasons()`) тем же изменением; совпадение двух
-- словарей держит `TestIntegration_RevocationVocabularyAgreesWithTheDomain`,
-- писателя у каждого слова — гейт
-- `TestFamilyRevocationVocabulary_KN_FRV_17_EveryWordHasAWriter`.
