-- memberships_carry_a_cursor_index_for_their_owner — индекс под курсор СВОЕГО
-- списка членств (приёмка IAM-ID-2, стадия S2; §7 п. 7в; задача kaname#206).
--
-- Санкция: одобренная IAM-ID-2 (воркспейс,
-- `docs/specs/sub-phase-IAM-ID-2-membership-read-acceptance.md`, вердикт
-- круга 7 от 2026-08-27), §7 п. 7в: «S2 — `(user_id, created_at, id)` —
-- курсор своего списка; в S2, не раньше».
--
-- =============================================================================
-- ЧТО ЗАВОДИТСЯ И ПОЧЕМУ ИМЕННО ЭТА ФОРМА
-- =============================================================================
-- Своё чтение (`MembershipService.ListMine`, `GET /iam/v1/me/memberships`)
-- обходит строки ОДНОГО человека курсором `(created_at, id)`: ведущее равенство
-- по `user_id`, за ним ключи курсора подряд и в согласованном направлении —
-- ровно как у соседнего индекса `memberships_account_cursor_idx` для чтения по
-- аккаунту. Довод не производительностный: при сегодняшних объёмах таблица
-- помещается в одну страницу. Довод — объявленная конвенция платформы
-- (kacho#708: у каждого курсорного чтения есть индекс под его порядок) и
-- асимметрия роста: число членств есть число людей, помноженное на число
-- аккаунтов на человека, и весь предмет перехода IAM-ID — снять единицу во
-- втором множителе.
--
-- Голый `(created_at, id)` НЕ заводится: у него нет производителя запроса —
-- плоской коллекции членств контракт не несёт, а оба обхода несут ведущее
-- равенство. Уникальность пары `memberships_user_account_unique (user_id,
-- account_id)` не трогается: она держит инвариант, а не обслуживает запрос, и
-- под курсор с `created_at` не годится.
--
-- =============================================================================
-- ПОЧЕМУ НОВАЯ МИГРАЦИЯ, А НЕ ПРАВКА ПРИМЕНЁННОЙ
-- =============================================================================
-- Мигратор сверяет версию, а не содержимое: правка применённого файла до базы
-- не доезжает (запрет #5).

-- +goose Up
CREATE INDEX memberships_user_cursor_idx
    ON kaname.memberships USING btree (user_id, created_at, id);

-- +goose Down
DROP INDEX IF EXISTS kaname.memberships_user_cursor_idx;
