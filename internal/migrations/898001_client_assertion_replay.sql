-- +goose Up
-- Однократность предъявленного утверждения клиента (задача #898, приёмка F2 §6).
--
-- ПРЕДМЕТ. Утверждение клиента — предъявительский документ: перехвативший его
-- предъявит повторно. Единственное, что отличает первое предъявление от
-- повтора, — запись о погашении, и запись эта обязана быть НЕДЕЛИМОЙ с
-- проверкой. Пара «посмотреть, не предъявлялось ли» и «погасить» под
-- конкуренцией пропускает ОБА одновременных повтора: между чтением и записью
-- есть окно, и оба промахиваются мимо чужой ещё не записанной строки (ban #10).
--
-- ФОРМА. Допуск — ОДИН оператор `INSERT … ON CONFLICT DO NOTHING`, и держит его
-- ПЕРВИЧНЫЙ КЛЮЧ таблицы: именно уникальность ключа делает «проверить и
-- погасить» неделимым. Под конкуренцией строку создаёт ровно одна транзакция,
-- остальные попадают в ветку конфликта и не меняют ничего.
--
-- ПОЧЕМУ КЛЮЧ СОСТАВНОЙ. Идентификатор однократности выбирает ПРЕДЪЯВИТЕЛЬ.
-- Будь ключом он один, клиент, предъявивший некоторое значение, занял бы его у
-- всех остальных клиентов: у соседа, чья библиотека выбрала то же значение,
-- законное ПЕРВОЕ предъявление отвергалось бы как повтор. Отказ в обслуживании
-- соседу получается дешёвым и — что хуже — выглядит корректной работой защиты.
-- Сужать дальше («+ адресат», «+ момент выпуска») нельзя: тогда повтор с
-- изменённым сопутствующим полем становится законным, то есть однократность
-- отменяется, сохранив свою форму.
--
-- ОБЛАСТЬ ГАРАНТИИ — ФЛОТ, а не процесс. Хранилище в памяти пода корректно
-- ровно до второй реплики; со второй оно даёт защиту, которой нет, и при этом
-- выглядит исправным. Поэтому запись лежит там, где её видят все реплики.
--
-- СРОК ЖИЗНИ СТРОКИ равен сроку жизни утверждения — не дольше и не короче.
-- Короче нельзя: снятая раньше строка делает повтор законным. Дольше нельзя:
-- хранилище росло бы без границы, и рост этот выбирает предъявитель. Верхнюю
-- границу задаёт потолок длительности утверждения, объявленный числом в
-- pkg/tokenpolicy: без него утверждение со сроком в годы занимало бы свой ключ
-- на годы, и «ограниченное сроком» хранилище перестало бы быть ограниченным.
-- +goose StatementBegin
CREATE TABLE IF NOT EXISTS kacho_iam.client_assertion_replay (
    -- Наш идентификатор клиента. Зеркальное значение внешнего сервера сюда не
    -- попадает: субъект с двумя именами дал бы ДВА ключа однократности на одно
    -- утверждение, то есть отменил бы её (приёмка F2 §2.1).
    client_id    text        NOT NULL,
    -- Идентификатор однократности, выбранный предъявителем.
    assertion_id text        NOT NULL,
    -- Момент истечения САМОГО утверждения. Он же — срок жизни этой строки.
    expires_at   timestamptz NOT NULL,
    redeemed_at  timestamptz NOT NULL DEFAULT now(),

    -- Инвариант однократности. Составной первичный ключ — не украшение: это
    -- ровно то, что делает допуск атомарным одним оператором.
    CONSTRAINT client_assertion_replay_pkey PRIMARY KEY (client_id, assertion_id),

    CONSTRAINT client_assertion_replay_client_ck
        CHECK (length(client_id) BETWEEN 1 AND 128),

    -- Длина ограничена ДО использования: идентификатор выбирает предъявитель,
    -- и строка неограниченной длины — это его выбор нашего расхода.
    CONSTRAINT client_assertion_replay_assertion_ck
        CHECK (length(assertion_id) BETWEEN 1 AND 256)
);

-- Обход сборщика идёт по сроку годности.
CREATE INDEX IF NOT EXISTS client_assertion_replay_expires_at_idx
    ON kacho_iam.client_assertion_replay (expires_at);

COMMENT ON TABLE kacho_iam.client_assertion_replay IS
    'Погашенные утверждения клиента: пара «клиент + идентификатор однократности». Допуск — один оператор, уникальность держит первичный ключ. Строка живёт до истечения утверждения и убирается сборщиком.';
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
DROP TABLE IF EXISTS kacho_iam.client_assertion_replay;
-- +goose StatementEnd
