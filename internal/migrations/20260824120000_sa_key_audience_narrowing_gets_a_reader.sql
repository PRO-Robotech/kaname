-- 20260824120000_sa_key_audience_narrowing_gets_a_reader — перечень адресатов,
-- объявленный заказчиком ключа, получает МЕСТО ХРАНЕНИЯ и через него читателя
-- на своей полосе выпуска (задача #1136).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ: СУЖЕНИЕ, ПЕРЕСТАВШЕЕ СУЖАТЬ
--
-- Перечень адресатов заказчик называл при выдаче ключа, и он уезжал в
-- регистрацию у прежнего издателя — там же и сужал. После перевода контура на
-- свою чеканку регистрация не заводится вовсе, и перечень перестал иметь
-- читателя: поле принималось, возвращалось в ответе выдачи и не отвергало
-- НИ ОДНОГО входа. Ключ, выданный «для реестра», получал токен любого адресата
-- из общего перечня посадки — в развёрнутых профилях их два, и один из них
-- адресат края.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ КОЛОНКА, А НЕ ВЫВОД ИЗ ЧЕГО-ТО ИМЕЮЩЕГОСЯ
--
-- Выводить сужение не из чего: перечень — свободный выбор заказчика в момент
-- выдачи, он не следует ни из вида ключа, ни из его владельца, ни из посадки.
-- Единственная альтернатива хранению — спросить прежнего издателя, то есть
-- вернуть ровно ту зависимость, ради снятия которой контур и переводили.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ИМЯ КОЛОНКИ НАЗЫВАЕТ, КТО ОБЪЯВИЛ
--
-- Перечней в этом тракте ДВА, и путать их дорого: один объявлен ПОСАДКОЙ
-- (`authn.client-token.allowed-audiences`) и говорит, каким поверхностям
-- платформа вообще чеканит удостоверения; второй объявлен ЗАКАЗЧИКОМ и говорит,
-- для чего заведён этот ключ. Второй действует ВНУТРИ первого и никогда его не
-- расширяет. Имя `declared_audiences` называет автора значения, поэтому читающий
-- колонку не примет её за внешнюю границу.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ПУСТОЙ ПЕРЕЧЕНЬ — ЗАКОННОЕ СОСТОЯНИЕ, А НЕ ДЫРА
--
-- Пусто означает «сужения не объявлено», и внешняя граница при этом остаётся:
-- она непуста по требованию стража старта, без неё выдача не строится вовсе.
-- Это не тот класс, что пустой список доверенных отправителей, — там пустое
-- значение снимало ЕДИНСТВЕННЫЙ контроль.
--
-- Уже существующие строки получают пусто, и это правильно: они выдавались
-- тогда, когда поле не читалось ничем, и объявить задним числом, что они
-- сужены, значило бы лишить их владельцев доступа, которого никто не отзывал.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ФОРМА ЗНАЧЕНИЯ ДЕРЖИТСЯ ОГРАНИЧЕНИЕМ, А НЕ ПРОВЕРКОЙ ПЕРЕД ЗАПИСЬЮ
--
-- Пустая строка среди элементов — адресат, которого нельзя заказать ничем: она
-- не совпала бы ни с одним запросом и молча сузила бы ключ до недостижимого.
-- NULL-элемент даёт то же с другой стороны — сравнение с ним не истинно и не
-- ложно. Обе формы отвергает ограничение таблицы, а не память писателя: писатель
-- сегодня один, а ограничение переживает появление второго.
-- +goose Up

-- Длина элемента повторяет потолок контракта (≤512). Выражена функцией потому,
-- что ограничение таблицы не принимает подзапроса, а поэлементная величина без
-- обхода массива не вычисляется. Функция IMMUTABLE — иначе её нельзя звать из
-- ограничения.
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION kacho_iam.text_array_longest(a text[]) RETURNS integer
    LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
AS $$ SELECT coalesce(max(length(x)), 0) FROM unnest(a) AS x $$;
-- +goose StatementEnd

-- +goose StatementBegin
ALTER TABLE kacho_iam.service_account_oauth_clients
    ADD COLUMN IF NOT EXISTS declared_audiences text[] NOT NULL DEFAULT '{}'::text[];
-- +goose StatementEnd

-- +goose StatementBegin
ALTER TABLE kacho_iam.service_account_oauth_clients
    ADD CONSTRAINT sa_oauth_clients_declared_audiences_wellformed CHECK (
        NOT ('' = ANY (declared_audiences))
        AND array_position(declared_audiences, NULL) IS NULL
        AND kacho_iam.text_array_longest(declared_audiences) <= 512
    );
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
ALTER TABLE kacho_iam.service_account_oauth_clients
    DROP CONSTRAINT IF EXISTS sa_oauth_clients_declared_audiences_wellformed;
-- +goose StatementEnd

-- +goose StatementBegin
ALTER TABLE kacho_iam.service_account_oauth_clients
    DROP COLUMN IF EXISTS declared_audiences;
-- +goose StatementEnd

-- +goose StatementBegin
DROP FUNCTION IF EXISTS kacho_iam.text_array_longest(text[]);
-- +goose StatementEnd
