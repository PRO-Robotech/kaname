-- Группа `module-quota-readers` СНИМАЕТСЯ вместе с членствами (приёмка MRW-1,
-- стадия S2б; задача kaname#106).
--
-- ────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Группу завёл свод `0001_initial.sql` ради права читать пределы своего домена
-- перед списанием. Право отозвано миграцией `20260914091500` (kaname#59), а
-- группа осталась: пустая, ничего не открывающая, и пять манифестов платформы
-- по-прежнему в неё вступали с назначением, которого больше нет. Держателя,
-- который объявил бы её данными, не было и быть не могло: валидатор связности
-- требует, чтобы заведённую манифестом группу он же и одарил, — одарять её
-- нечем. Группа без предмета и без владельца снимается.
--
-- ────────────────────────────────────────────────────────────────────────────
-- ПОРЯДОК СТАДИЙ — ВНЕШНИЙ ПРЕДИКАТ ДОПУСКА, И ОН НАЗВАН
--
-- Сначала вступления уходят из манифестов платформы (S2а, репозиторий
-- `PRO-Robotech/kacho`), потом строки — этой миграцией. Обратный порядок ломает
-- установку: применитель посева, встретив вступление в снятую группу,
-- отказывает («группа system/module-quota-readers не резолвится»), и служба не
-- поднимается. Машинной проверки у этого условия нет — миграция исполняется в
-- init-контейнере и каталога доставки не читает by construction; держится оно
-- порядком работ: S2а влита в ствол платформы и доехала выпуском до установок.
--
-- ────────────────────────────────────────────────────────────────────────────
-- ЧТО СНИМАЕТСЯ, А ЧТО НЕТ — ГРАНИЦА НАЗВАНА
--
-- Снимаются строка группы и её ЧЛЕНСТВА — сколько их записал применитель по
-- вступлениям доставленных манифестов; из свода после `20260909202745` их
-- ноль, и число снятых печатается переписью, а не предполагается равным пяти.
-- Личности-члены НЕ снимаются: они принадлежат доставленным манифестам.
-- Группа `module-relation-writers` НЕ снимается: её объявляет манифест службы.
-- Применённую миграцию `0001` эта не правит (запрет #5).
--
-- Группа, числящаяся субъектом живой выдачи, снимается ОТКАЗОМ, а не молча:
-- триггер `groups_subject_ref_before_delete_trg` отверг бы удаление кодом
-- 23503 именем ограничения, и оператор искал бы предмет в схеме; здесь отказ
-- называет предмет сам — выдачу, которую сперва надо отозвать своим решением.
--
-- ────────────────────────────────────────────────────────────────────────────
-- СЛЕД — ФОРМА ШТАТНЫХ ПРОИЗВОДИТЕЛЕЙ, И НАЗВАНО, ЧТО ИЗ ИХ СО-КОММИТОВ ЗДЕСЬ БЕСПРЕДМЕТНО
--
-- Штатное снятие группы со-коммитит запись аудита `iam.group.deleted` с
-- арендатором (`api/group/delete.go`) — повторяется: ОДНА запись на группу.
-- Штатное снятие члена со-коммитит строку снятия кортежа
-- `group:<группа>#member@<личность>` (`api/group/remove_member.go`) —
-- повторяется: по одной на КАЖДОЕ снятое членство, безусловно, и позже строки
-- записи того же кортежа: прямой факт снимает триггер
-- `relation_fact_follows_journal` на строке снятия, чей `created_at` не раньше
-- `source_version` факта. Дренажа у журнала на этом дереве нет — потребитель
-- журнала один, и это триггер.
--
-- Два других со-коммита беспредметны: событие реконсайла группы — кортежа
-- владельца у группы свода нет, зеркальной строки тоже; событие смены субъекта
-- у члена — гасить нечего, через эту группу член не получает ничего с
-- `20260914091500`. Записи аудита на членство штатное снятие члена не пишет —
-- и миграция не пишет.
--
-- Идентификатор записи аудита ВЫВОДИТСЯ из группы И ВРЕМЕНИ прямого хода:
-- откат возвращает группу, повторный накат снимает её снова, и это ВТОРОЕ
-- состоявшееся снятие — вторая запись, а не молчание об одном из двух.
--
-- ────────────────────────────────────────────────────────────────────────────
-- ТРИ ИСХОДА ПРЯМОГО ХОДА, И ОТСУТСТВИЕ ГРУППЫ — ПЕРЕПИСЬ, А НЕ ОТКАЗ
--
-- «членств N · группа 1» — установка с членствами от применителя;
-- «членств 0 · группа 1» — база миграций без доставки, состояние каждой
-- установки сразу после цепочки и постоянное состояние самостоятельной;
-- «членств 0 · группа 0» — группы нет к моменту прямого хода. Перепись
-- печатается ВСЕГДА: «снимать нечего» и «сняли» снаружи одинаковы.
--
-- ────────────────────────────────────────────────────────────────────────────
-- ЧТО ВОЗВРАЩАЕТ ОТКАТ, И ЧЕГО ОН НЕ ОБЕЩАЕТ
--
-- `Down` возвращает строку группы свода ДОСЛОВНО — тот же идентификатор,
-- аккаунт, назначение и метки: идентификатор стоит в записи аудита прямого
-- хода и в `Down` соседней `20260914091500`, и выданный заново отвязал бы
-- откат от того, что снималось. Членств `Down` не возвращает — ни свода (их
-- сняла `20260909202745`, и её `Down` вернёт свои сам), ни применителя (они
-- принадлежат доставке, и восстановит их следующий старт по вступлениям, если
-- доставка их ещё объявляет). В журнал прав и в аудит `Down` не пишет: кортежей
-- возвращать не с чего, а запись о снятии остаётся свидетельством
-- состоявшегося. Откатная цепочка сходится by construction: `goose` откатывает
-- от старшей версии к младшей, поэтому группа возвращается РАНЬШЕ, чем `Down`
-- соседа попробует вернуть ей выдачу, — а тот на отсутствующей группе выходит
-- молча. Пустой `Down` оставил бы откат соседа без предмета.

-- +goose Up
-- +goose StatementBegin
DO $$
DECLARE
    v_name     CONSTANT text := 'module-quota-readers';
    v_group    text;
    v_account  text;
    v_grants   int;
    v_members  int;
    v_tuples   int;
    v_groups   int;
BEGIN
    -- 0. ЕСТЬ ЛИ ПРЕДМЕТ. Группа адресуется парой (аккаунт, имя): системный
    --    аккаунт один (`accounts_name_unique`), и его имя переведено
    --    миграцией `20260913144108`.
    SELECT g.id, g.account_id INTO v_group, v_account
      FROM kaname.groups g
      JOIN kaname.accounts a ON a.id = g.account_id
     WHERE a.name = 'system' AND g.name = v_name;

    IF v_group IS NULL THEN
        -- Законное состояние: группу сняли до прямого хода. Молчать нельзя —
        -- «снимать нечего» и «сняли» снаружи одинаковы.
        RAISE NOTICE 'перепись снятия %: членств 0 · группа 0 — группы нет, снимать нечего', v_name;
        RETURN;
    END IF;

    -- 1. ГРУППА НЕ ЧИСЛИТСЯ СУБЪЕКТОМ ВЫДАЧИ. Иначе отказ пришёл бы от
    --    триггера ссылки именем ограничения, а не предметом.
    SELECT count(*) INTO v_grants
      FROM kaname.access_bindings
     WHERE subject_type = 'group' AND subject_id = v_group;
    IF v_grants > 0 THEN
        RAISE EXCEPTION 'группа %/% (%) — субъект % активной выдач(и): снятие группы без отзыва '
                        'выдачи было бы отзывом без решения; отзовите выдачу своим решением и повторите',
                        'system', v_name, v_group, v_grants;
    END IF;

    -- 2. СТРОКИ СНЯТИЯ КОРТЕЖЕЙ ЧЛЕНСТВА — на КАЖДОЕ членство, безусловно, до
    --    удаления членств (после него составить строку не из чего). Форма —
    --    штатного снятия члена: субъект `<вид>:<личность>`, объект
    --    `group:<группа>`, отношение `member`. Прямой факт снимет триггер
    --    проекции.
    INSERT INTO kaname.fga_outbox (event_type, payload, created_at)
    SELECT 'fga.tuple.delete',
           jsonb_build_object('user',     gm.member_type || ':' || gm.member_id,
                              'object',   'group:' || gm.group_id,
                              'relation', 'member'),
           now()
      FROM kaname.group_members gm
     WHERE gm.group_id = v_group;
    GET DIAGNOSTICS v_tuples = ROW_COUNT;

    -- 3. СЛЕД — ДО удаления группы, пока строка читается. Тип события и форма
    --    полезной нагрузки — штатного снятия группы; действующее лицо —
    --    платформа, поле пустое, а не подставленная учётка.
    INSERT INTO kaname.audit_outbox (id, event_type, tenant_account_id, event_payload)
    VALUES ('evt_' || substr(md5('quota-readers-group-retired:' || v_group || ':' || now()::text), 1, 24),
            'iam.group.deleted',
            v_account,
            jsonb_build_object(
                'actor',         '',
                'resource_type', 'group',
                'resource_id',   v_group,
                'account_id',    v_account,
                'reason',        'the quota reader right this group was created for is revoked '
                                 || '(kaname#59); no manifest declares the group, so it leaves '
                                 || 'the applied schema (kaname#106, MRW-1 S2b)'));

    -- 4. ЧЛЕНСТВА, затем ГРУППА. Членства ушли бы и каскадом ключа, но их
    --    число печатается переписью, поэтому снимаются явно.
    DELETE FROM kaname.group_members WHERE group_id = v_group;
    GET DIAGNOSTICS v_members = ROW_COUNT;

    DELETE FROM kaname.groups WHERE id = v_group;
    GET DIAGNOSTICS v_groups = ROW_COUNT;

    RAISE NOTICE 'перепись снятия %: членств % · группа % · строк снятия кортежей % · арендатор %',
        v_name, v_members, v_groups, v_tuples, v_account;
END
$$;
-- +goose StatementEnd

