-- human_session_drops_password_change_required — колонка признака «требуется
-- сменить пароль» уходит из записи сессии (задачи PRO-Robotech/kaname#201,
-- решение PRO-Robotech/kacho#2697).
--
-- Санкция: решение оркестратора по kacho#2697 (исход 1 — завершение
-- восстановления остаётся ОДНИМ обращением) и новые редакции приёмок Ф3 (Р8),
-- Ф5 (Р5, Ф5-03/24) и Ф1 (§4.2): сессия восстановления требования не несёт,
-- поле и его читатели снимаются с контракта. Доводы там; здесь — то, что нужно
-- читателю СХЕМЫ.
--
-- =============================================================================
-- ПОЧЕМУ КОЛОНКА СНИМАЕТСЯ, А НЕ ОСТАЁТСЯ «НА ВСЯКИЙ СЛУЧАЙ»
-- =============================================================================
-- Производителя значения `true` у колонки не было ни одного: восстановление
-- задаёт новый пароль тем же обращением, что предъявляет код, и сессия
-- появляется ПОСЛЕ записи пароля — ей уже нечего требовать. Колонка,
-- которую вставка заполняет константой `false`, а чтение отдаёт краю как
-- факт о сессии, есть «принято-и-проигнорировано» на уровне схемы
-- (`api-conventions.md`): читатель на крае писал обработку состояния, которого
-- не бывает. Поле контракта снято с `reserved` номера и имени; колонка снимается
-- этой же полосой, чтобы состав записи и состав контракта не разошлись.
--
-- =============================================================================
-- ПОЧЕМУ НОВАЯ МИГРАЦИЯ, А НЕ ПРАВКА ПРИМЕНЁННОЙ
-- =============================================================================
-- Мигратор сверяет версию, а не содержимое: правка применённого файла
-- (`20260916190000_human_session_is_our_record.sql`) до базы не доезжает.
--
-- =============================================================================
-- ЧТО СО СТРОКАМИ
-- =============================================================================
-- Переноса нет: во всех лежащих строках значение равно умолчанию `false` — иным
-- оно быть не могло, писателя `true` не существовало. Снятие колонки строк не
-- трогает; читатели (`resolveSQL`, вставка) колонку больше не называют.

-- +goose Up

ALTER TABLE kaname.human_sessions DROP COLUMN password_change_required;

-- +goose Down

-- Откат возвращает колонку С ТЕМ ЖЕ умолчанием, что у неё было: `false NOT
-- NULL`. Значение восстанавливается без потери — иного, чем умолчание, в ней не
-- было ни в одной строке (писателя `true` не существовало).
ALTER TABLE kaname.human_sessions ADD COLUMN password_change_required boolean DEFAULT false NOT NULL;
