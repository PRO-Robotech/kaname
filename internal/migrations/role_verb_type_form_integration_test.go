// role_verb_type_form_integration_test.go — комментарий колонки
// `role_verb.object_type` и КЛЮЧ, который её судит, говорят об одной форме
// имени (#1975).
//
// # Предмет
//
// У формы имени в этой колонке ДВА места: комментарий, который читает человек
// (`\d+`), и ключ `role_verb_type_fk`, который решает, примут ли строку. Разойдясь,
// они лгут в самую дорогую сторону: пишущий берёт форму из комментария и получает
// отказ ключа на ровном месте, а причину ищет в переводе имён, которого в этом
// месте нет.
//
// Расхождение уже случалось. Миграция проекции глаголов объявила `--`-строкой,
// что в колонке лежит форма МОДЕЛИ ПРАВ (`vpc_network`) и «не точечное имя
// ресурса»; писатель клал ТОЧЕЧНУЮ. Применённую миграцию не правят (ban #5),
// поэтому комментарий БАЗЫ приведён к истине новой миграцией
// (`0089_role_verb_type_form_comment.sql`), а ключ, заведённый позже, сослался на
// `catalog_resource(dotted, live)` — то есть на точечную форму.
//
// # Почему проба по ЖИВОЙ схеме, а не по тексту миграций
//
// Комментарий и ключ — оба переопределимы поздней миграцией. Текст файла говорит
// о НАМЕРЕНИИ на момент написания; каталог живой базы, накатанной целиком,
// говорит об ИСХОДЕ. Утверждать здесь надо исход: `--`-строка первой миграции
// по-прежнему в дереве и по-прежнему лжёт, но `\d+` её не показывает, и решает
// не она.
package migrations_test

import (
	"database/sql"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

// TestIntegration_RoleVerbTypeFormAgreesWithItsKey — комментарий колонки и
// референт ключа называют ОДНУ форму имени.
//
// Утверждается ПАРА, и обе половины обязательны. Без комментария «ключ ссылается
// на dotted» ничего не говорит человеку, читающему схему; без ключа комментарий
// остаётся обещанием, за которым никто не следит.
func TestIntegration_RoleVerbTypeFormAgreesWithItsKey(t *testing.T) {
	if testing.Short() {
		t.Skip("пропуск интеграционной пробы (нужен Docker)")
	}
	db := freshIamSchema(t)

	// ── половина 1: КЛЮЧ. Он и есть тот, кто решает. ─────────────────────────
	var conname, condef string
	err := db.QueryRow(`
		SELECT conname, pg_get_constraintdef(oid)
		  FROM pg_constraint
		 WHERE conrelid = 'kacho_iam.role_verb'::regclass
		   AND contype = 'f'
		   AND conname = 'role_verb_type_fk'`).Scan(&conname, &condef)
	require.NoError(t, err,
		"ключа role_verb_type_fk нет: без него форму имени в колонке не судит ничто, "+
			"и комментарий ниже становится обещанием без держателя")

	t.Logf("ключ: %s → %s", conname, condef)
	require.Contains(t, condef, "catalog_resource",
		"ключ обязан ссылаться на каталог ресурсов")
	require.Contains(t, condef, "dotted",
		"ключ обязан ссылаться на ТОЧЕЧНУЮ колонку каталога: именно она задаёт форму "+
			"имени, принимаемую в role_verb.object_type")

	// ── половина 2: КОММЕНТАРИЙ, который читает человек. ─────────────────────
	var comment sql.NullString
	err = db.QueryRow(`
		SELECT col_description('kacho_iam.role_verb'::regclass, a.attnum)
		  FROM pg_attribute a
		 WHERE a.attrelid = 'kacho_iam.role_verb'::regclass
		   AND a.attname  = 'object_type'`).Scan(&comment)
	require.NoError(t, err, "колонки object_type нет вовсе")

	// Положительный контроль. Без него всякое отрицание ниже зеленело бы на
	// ПУСТОМ комментарии — то есть ровно в том состоянии, из-за которого предмет
	// и завёлся: `\d+` не показывал бы ничего, а читатель шёл бы к `--`-строке
	// применённой миграции, которая лжёт.
	require.True(t, comment.Valid && strings.TrimSpace(comment.String) != "",
		"комментарий колонки пуст: `\\d+` не скажет читателю ничего, и форму имени он "+
			"возьмёт из `--`-строки применённой миграции, которая называет форму модели прав")

	t.Logf("комментарий: %s", comment.String)

	// Комментарий обязан НАЗЫВАТЬ точечную форму. Судим по названию формы и по
	// её образцу, а не по отсутствию чужого слова: действующий текст объясняет
	// расхождение и потому законно СОДЕРЖИТ написание модели прав внутри
	// собственного отрицания. Проверка «нет подстроки vpc_network» краснела бы
	// на объяснении — том самом, ради которого комментарий и написан.
	lower := strings.ToLower(comment.String)
	require.True(t,
		strings.Contains(lower, "точечн") || strings.Contains(lower, "dotted"),
		"комментарий обязан назвать форму имени ТОЧЕЧНОЙ — той, которую принимает ключ; "+
			"получено: %s", comment.String)
	require.Contains(t, comment.String, ".",
		"комментарий обязан нести образец точечного имени (`vpc.network`): форма, названная "+
			"словом и не показанная, читается по-разному")

	t.Logf("осмотрено: ключей role_verb→catalog_resource 1, комментариев колонки 1; " +
		"форма имени у ключа и у комментария — точечная")
}
