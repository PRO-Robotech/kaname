-- Идентификаторы посева детерминированы и продолжают нумерацию 0094 — иначе
-- повторный прогон на уже посеянной базе был бы неотличим от первого только по
-- содержимому, а не по ключу.
INSERT INTO kacho_iam.limits (id, scope, scope_id, kind, limit_value) VALUES
    -- loadbalancer, вложенный. Проектный потолок слушателей 64, балансировщиков
    -- 16; 16 слушателей на балансировщик допускает четыре полностью занятых
    -- балансировщика в пределах проектного потолка. Вложенный предел СУЖАЕТ
    -- форму потребления, а не отменяет проектный: без него один балансировщик
    -- мог бы забрать все 64 слушателя проекта — ровно та вложенность, про
    -- которую владелец сказал «способно положить инфраструктуру».
    ('lim-00000000000000030', 'DEFAULT', '', 'loadbalancer.networkLoadBalancers.listeners', 16),

    -- registry, вложенный. Проектный потолок репозиториев 256, реестров 8;
    -- 64 репозитория на реестр дают то же соотношение «четыре полных родителя»,
    -- что и у соседа выше. Соотношение выбрано ОДНО на оба домена намеренно:
    -- разные пропорции при одинаковой природе предела читались бы как решение,
    -- за которым что-то стоит, а за ним ничего бы не стояло.
    ('lim-00000000000000031', 'DEFAULT', '', 'registry.registries.repositories',            64)
ON CONFLICT (id) DO NOTHING;

