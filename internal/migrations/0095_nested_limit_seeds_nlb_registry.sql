-- =============================================================================
-- Умолчания для двух вложенных видов, заведённых стадией S4: слушателей в одном
-- балансировщике и репозиториев в одном реестре.
-- =============================================================================
-- Приёмка `docs/specs/sub-phase-quota-v2-materialised-usage-acceptance.md`
-- (APPROVED, раунд 2), DoD S4 п.1 и DoD S1 п.4 (посев покрывает КАЖДЫЙ вид
-- каталога — иначе создание ресурсов этого вида отвергалось бы «потолок не
-- назван», и правило V2-3 из защиты превратилось бы в поломку).
--
-- НОВАЯ МИГРАЦИЯ, А НЕ ПРАВКА 0094. Применённую не правим (ban #5): 0094 уже
-- расширила форму токена до «две ИЛИ три части» и посеяла двадцать видов, и
-- дописать в неё две строки значило бы изменить то, что на живых базах уже
-- исполнено.
--
-- ТОКЕНЫ ВЫПИСАНЫ ИЗ ЗАКРЫТОЙ ТАБЛИЦЫ ГРАНТУЕМЫХ ПАР, А НЕ ПО ПАМЯТИ. У обоих
-- доменов вторая часть токена во МНОЖЕСТВЕННОМ числе, и это факт дерева, а не
-- опечатка: `loadbalancer.listeners`, `registry.repositories`. Написанный по
-- памяти `loadbalancer.networkLoadBalancer.listener` не резолвится ни одной
-- своей частью и отвергается гейтом каталога — что и есть правильное поведение.
-- Предикат сверки:
--   git show HEAD:services/iam/internal/authzmap/fga_types.go \
--     | sed -n '/limitKindObjectTypes = map/,/^}/p'
--
-- ТРЕТИЙ ВЛОЖЕННЫЙ ВИД НЕ ЗАВОДИТСЯ. `loadbalancer.targetGroups.targets` не
-- проходит гейт: `Target` — строка таблицы `kacho_nlb.targets`, но НЕ грантуемый
-- тип (модель объявляет три типа nlb, `nlb_target` среди них нет). Ослабить гейт
-- ради одной удобной пары значило бы открыть его для потолков на предметы,
-- которых модель прав не знает. Риск «слишком много целей в одной группе»
-- остаётся ОТКРЫТЫМ и назван в §6 приёмки вместе с предикатом заведения
-- преемника — а не приравнен к остальным молча.

