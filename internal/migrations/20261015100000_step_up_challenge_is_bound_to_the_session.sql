-- =============================================================================
-- Ключ привязки у трёх видов испытаний разный: у церемоний Ф7 — человек
-- (`access_key_challenges`), у входа ключом (Ф13) — контекст формы
-- (`access_key_login_challenges`), у повышения — ЗАПИСЬ СЕССИИ. Расширение
-- `access_key_challenges` потребовало бы нового назначения и столбца сессии,
-- осмысленного у одного назначения из трёх, второй проверки о двух столбцах и
-- ключа «одно живое» под условием по назначению; раздельность испытаний
-- держалась бы совпадением значения фильтра у каждого читателя. Три ключа —
-- три таблицы: испытание одного вида в чужой церемонии не находится по
-- построению.
--
-- =============================================================================
-- ПРИВЯЗКА — ЗАПИСЬ СЕССИИ, НЕ НОСИТЕЛЬ; ЧЕЛОВЕКА — ЧЕРЕЗ СЕССИЮ
-- =============================================================================
-- Носитель перевыпускается каждым успешным предъявлением: испытание,
-- привязанное к его свёртке, стало бы непредъявимым после соседней ветви.
-- Столбца человека нет — второго источника принадлежности строка не несёт.
-- Снятие записи сессии уборкой снимает её испытания каскадом (один сервис,
-- одна база).
--
-- =============================================================================
-- ОДНО ЖИВОЕ НА СЕССИЮ — ЧАСТИЧНАЯ УНИКАЛЬНОСТЬ; ОДНОКРАТНОСТЬ — ОДИН ОПЕРАТОР
-- =============================================================================
-- Повторная выдача СМЕНЯЕТ прежнее живое испытание сессии: оператор вставки
-- с этим ключом арбитром переписывает строку, а не «снять, затем вставить»
-- (ban #10). Годность и сгорание — одно действие по паре (сессия, испытание).
--
-- =============================================================================
-- ЧАСЫ — ЧАСЫ СЛУЖБЫ; ПРОВЕРКИ «ПРЕДЪЯВЛЕНО НЕ РАНЬШЕ ВЫДАЧИ» НЕТ НАМЕРЕННО
-- =============================================================================
-- Моменты приносит служба параметром, как у испытаний Ф7: срок — величина
-- контракта Ф7, ось времени приёмка строит управляемыми часами. Выдаёт
-- испытание одна реплика, предъявляют другой; проверка порядка двух моментов
-- разных часов отвергала бы верное предъявление на реплике с отстающими
-- часами — поэтому её здесь нет (условие пересверки У1), как нет её и у
-- `access_key_challenges`. Умолчания у моментов нет: забытая величина — отказ
-- записи, а не подстановка.
--
-- =============================================================================
-- РОСТ ОГРАНИЧЕН
-- =============================================================================
-- Живое испытание у сессии одно; погашенные и истёкшие снимает реестр уборки
-- службы порогом в срок испытания: три состояния испытания наружу различимы
-- (не выдавалось · уже предъявлено · истекло), и различимость держит хранение
-- строки.

-- +goose Up

CREATE TABLE kaname.access_key_step_up_challenges (
    challenge   bytea NOT NULL,
    session_id  text NOT NULL,
    issued_at   timestamp with time zone NOT NULL,
    expires_at  timestamp with time zone NOT NULL,
    consumed_at timestamp with time zone,
    CONSTRAINT access_key_step_up_challenges_pkey PRIMARY KEY (challenge),
    CONSTRAINT access_key_step_up_challenges_session_fk
        FOREIGN KEY (session_id) REFERENCES kaname.human_sessions(id) ON DELETE CASCADE,
    CONSTRAINT access_key_step_up_challenges_challenge_check CHECK ((octet_length(challenge) = 32)),
    CONSTRAINT access_key_step_up_challenges_span_check CHECK ((expires_at > issued_at))
);

COMMENT ON TABLE kaname.access_key_step_up_challenges IS
  'Выданные испытания повышения ключом доступа внутри живой сессии: привязаны к записи сессии, однократны (consumed_at), срочны (expires_at — та же величина, что у испытаний церемоний). Моменты ставят часы службы. Одно живое на сессию держит частичный ключ уникальности. Убираются реестром уборки.';
COMMENT ON COLUMN kaname.access_key_step_up_challenges.session_id IS
  'Запись сессии, которой испытание выдано; человек выводится через неё.';

-- Одно ЖИВОЕ испытание на запись сессии: предъявленные строки под ключ не
-- подпадают и сохраняются до уборки.
CREATE UNIQUE INDEX access_key_step_up_challenges_live_session_idx
    ON kaname.access_key_step_up_challenges USING btree (session_id) WHERE (consumed_at IS NULL);

-- Внешний ключ на запись сессии: снятие записи ищет её испытания по столбцу,
-- и без индекса каскад читал бы таблицу целиком.
CREATE INDEX access_key_step_up_challenges_session_idx
    ON kaname.access_key_step_up_challenges USING btree (session_id);

CREATE INDEX access_key_step_up_challenges_expires_idx
    ON kaname.access_key_step_up_challenges USING btree (expires_at);

-- Испытание — одноразовое случайное значение: выборка в статистике
-- планировщика была бы его копией с чужим сроком хранения; отбирается оно
-- точным равенством по первичному ключу.
ALTER TABLE kaname.access_key_step_up_challenges ALTER COLUMN challenge SET STATISTICS 0;

-- +goose Down

-- Откат безопасен: строка испытания не восстанавливает ничьего доступа и
-- ничьим материалом не является — она одноразова. Снятие таблицы означает
-- лишь, что повышение, начатое до отката, придётся начать заново.
DROP TABLE kaname.access_key_step_up_challenges;
