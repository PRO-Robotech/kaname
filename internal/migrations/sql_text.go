// sql_text.go — исполняемая часть миграции: Up-секция без комментариев и без
// содержимого строковых литералов.
//
// Порт с монорепо (`internal/repohygiene/migrationsqltext.go`, снят вынесением
// службы — `kacho#2597`). Поведение переносом не менялось: функции перенесены
// дословно и экспортированы, чтобы их звала внешняя тестовая обёртка
// (`package migrations_test`), а не только пакет-владелец.
//
// ЗДЕСЬ СТОЯЛО «в этом дереве сегодня один владелец — `grant_removal_trace.go`»,
// и предостережение «заводя второй, проверь, не завёл ли кто-то копию». Оба
// пережили свой предмет, и второе не сработало НИ РАЗУ — именно потому, что
// первое лгало: читатель, которому сказали «владелец один», копию не искал.
//
// Перемер 2026-09-14. ЕДИНИЦА СЧЁТА НАЗВАНА, потому что два образца об одном
// предмете дают разные числа: «файл называет имя» считает и прозу, и текст
// находки нового гейта (13), «файл ЗОВЁТ» считает вызовы (11). Ниже — второе.
//
//	git grep -lE '(MigrationUpSection|MigrationUpText)\(' -- '*.go' \
//	  | grep -v internal/migrations/sql_text.go       -> 11 файлов, из них 4 не-тестовых
//	git grep -ln 'strings.Index([a-z]*, *"-\{0,2\} *+goose' -- '*.go'  -> 8, все _test.go
//
// До сведения СВОИХ разрезов в дереве было одиннадцать, и они давали ПЯТЬ
// разных ответов на вопрос «что делать с файлом без маркера прямого хода»:
// отдать тело ЦЕЛИКОМ вместе с откатом · отдать пустую строку · отдать всё от
// начала · отказать · не спрашивать вовсе. Две копии жили в не-тестовом коде
// гейтов и сведены сюда (`kacho#2363`); восемь остались в пробах, где директива
// есть СОДЕРЖИМОЕ фикстуры, и это названная граница, а не чистота.
//
// ДЕРЖИТСЯ ГЕЙТОМ, А НЕ ЭТОЙ ФРАЗОЙ: `internal/check` —
// `TestMigrationSectionSplitIsDeclaredOnce` требует, чтобы директива секции
// была выписана литералом только здесь, печатает объём осмотренного и падает на
// пустом обходе. Предостережение без держателя — то, что здесь уже стояло.
package migrations

import "strings"

// Директивы секции мигратора. ЛИТЕРАЛ ЖИВЁТ ЗДЕСЬ И БОЛЬШЕ НИГДЕ: выписанный
// второй раз, он превращается во второе место об одном предмете — и расходится
// молча, потому что на законном входе обе записи отвечают одинаково.
//
// Стем объявлен отдельно, а маркер отката из него СОБРАН, чтобы у написания
// была одна точка правки: в этом дереве уже встречались три написания одного
// маркера (`-- +goose Down`, `+goose Down` без приставки и пара
// `Up`+`Down` с разрезом между ними), и различались они ровно тем, чего никто
// не решал.
const (
	// SectionMarkerStem — общее начало обеих директив секции.
	SectionMarkerStem = "-- +goose "
	// SectionDownMarker — начало ОБРАТНОГО хода миграции.
	SectionDownMarker = SectionMarkerStem + "Down"
)

// MigrationUpText — ПРЯМОЙ ход миграции сырым текстом, без обработки
// комментариев.
//
// Отделён от [MigrationUpSection] потому, что у разреза и у снятия комментариев
// РАЗНЫЕ вызывающие: часть гейтов дерева снимает комментарии своим разбором и
// нуждается только в разрезе. Пока отдельного входа не было, каждый такой гейт
// заводил СВОЙ разрез — и они разошлись в том, что делать с файлом без маркера
// прямого хода: один отдавал тело целиком ВМЕСТЕ С ОТКАТОМ, другой пустую
// строку, третий отказывал.
//
// Здесь правило одно и оно названо: маркера отката нет — тело прямого хода есть
// весь текст; есть — прямой ход кончается на нём. Маркер ПРЯМОГО хода в разрезе
// не участвует вовсе: всё, что стоит до него, — шапка файла, то есть
// комментарий, и исполняемого в ней нет by construction.
func MigrationUpText(body string) string {
	if i := strings.Index(body, SectionDownMarker); i >= 0 {
		return body[:i]
	}
	return body
}

// MigrationUpSection — исполняемая часть миграции: Up-секция без комментариев.
//
// Порядок двух шагов обязателен и обратим быть не может: маркер отката САМ
// является комментарием, поэтому секция отрезается по СЫРОМУ тексту, и только
// потом забеливаются комментарии. Забелив сперва, разбор потерял бы границу
// секций и прочитал бы откат как часть наката.
func MigrationUpSection(body string) string {
	return SQLBlankComments(MigrationUpText(body))
}

// SQLBlankComments заменяет содержимое SQL-комментариев пробелами, сохраняя
// длину строки и позиции переводов строк.
//
// Приоритет состояний: строка > комментарий > код. Внутри строкового литерала
// `--` комментария не начинает; внутри комментария кавычка строки не открывает.
// Блочные комментарии Postgres ВЛОЖЕННЫЕ — глубина считается, а не ищется
// первый `*/`.
func SQLBlankComments(s string) string {
	out := []byte(s)
	scanSQLComments(s, func(lo, hi int) {
		for i := lo; i < hi && i < len(out); i++ {
			if out[i] != '\n' {
				out[i] = ' '
			}
		}
	})
	return string(out)
}

// SQLBlankStrings заменяет СОДЕРЖИМОЕ строковых литералов пробелами, сохраняя
// длину и позиции переводов строк.
//
// Зачем отдельно от [SQLBlankComments]. Тот забеливает комментарии и при этом
// НАМЕРЕННО пропускает литералы целиком — иначе `--` внутри строки открыл бы
// комментарий. Но литерал не исполняется как SQL: прозаическое сообщение об
// ошибке, содержащее слова конструкции, для инвентаря по образцу неотличимо от
// самой конструкции.
//
// Кавычки-границы ОСТАЮТСЯ на месте: забеливается содержимое, поэтому
// `WHERE x = 'DROP COLUMN'` остаётся синтаксически тем же и по-прежнему не
// склеивает соседние лексемы.
func SQLBlankStrings(s string) string {
	out := []byte(s)
	scanSQLSpans(s, nil, func(lo, hi int) {
		// lo указывает на открывающую кавычку, hi — за закрывающую.
		for i := lo + 1; i < hi-1 && i < len(out); i++ {
			if out[i] != '\n' {
				out[i] = ' '
			}
		}
	})
	return string(out)
}

// scanSQLComments проходит текст один раз и зовёт onComment на каждом
// комментарии. Приоритет состояний: строка > комментарий > код.
func scanSQLComments(s string, onComment func(lo, hi int)) {
	scanSQLSpans(s, onComment, nil)
}

// scanSQLSpans — ЕДИНСТВЕННЫЙ проход по тексту SQL. Зовёт onComment на каждом
// комментарии и onString на каждом строковом литерале; любой из двух может
// быть nil. Приоритет состояний прежний: строка > комментарий > код.
//
// Второй проход здесь не заводится намеренно: два разбора одного текста
// разошлись бы молча — и разошлись бы именно там, где расхождение не видно, на
// законном входе оба отвечают одинаково.
func scanSQLSpans(s string, onComment func(lo, hi int), onString func(lo, hi int)) {
	for i := 0; i < len(s); {
		switch {
		case s[i] == '\'':
			lo := i
			i++
			for i < len(s) {
				if s[i] != '\'' {
					i++
					continue
				}
				if i+1 < len(s) && s[i+1] == '\'' { // '' — экранированная кавычка
					i += 2
					continue
				}
				i++
				break
			}
			if onString != nil {
				onString(lo, i)
			}
		case s[i] == '-' && i+1 < len(s) && s[i+1] == '-':
			j := strings.IndexByte(s[i:], '\n')
			if j < 0 {
				j = len(s)
			} else {
				j += i
			}
			if onComment != nil {
				onComment(i, j)
			}
			i = j
		case s[i] == '/' && i+1 < len(s) && s[i+1] == '*':
			depth, j := 1, i+2
			for j < len(s) && depth > 0 {
				switch {
				case s[j] == '/' && j+1 < len(s) && s[j+1] == '*':
					depth++
					j += 2
				case s[j] == '*' && j+1 < len(s) && s[j+1] == '/':
					depth--
					j += 2
				default:
					j++
				}
			}
			if onComment != nil {
				onComment(i, j)
			}
			i = j
		default:
			i++
		}
	}
}
