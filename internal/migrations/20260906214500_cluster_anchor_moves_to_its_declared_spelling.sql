-- cluster_anchor_moves_to_its_declared_spelling — якорь кластера переезжает на
-- написание, объявленное кодом: `cluster_kacho_root` → `cluster_root`.
--
-- Задача продукта #2113, решение W4 родительской приёмки KAN-WIRE-1 §F5.
-- Довод решения здесь не пересказывается — он в задаче: якорь именует
-- УСТАНОВКУ, а не службу, и у стороннего оператора ею не владеет ни платформа,
-- ни служба, поэтому различитель в имени лжёт в обе стороны.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ МИГРАЦИЯ, А НЕ ДЕЙСТВИЕ ОПЕРАТОРА
--
-- Написание якоря объявлено КОДОМ (`domain.ClusterSingletonID`,
-- `catalogderive.ClusterSingletonID`), и код спрашивает базу этим написанием:
-- `ClusterService.Get`, проверка формы id, каждый кортеж `cluster:<якорь>`.
-- Значит между кодом и базой написание обязано СОВПАДАТЬ, а не сходиться
-- когда-нибудь.
--
-- Базовая миграция сеет якорь ПРЕЖНИМ написанием и править её нельзя (ban #5).
-- Следовательно свежая установка родилась бы с расхождением: код спрашивает
-- `cluster_root`, строка называется `cluster_kacho_root`, кластерного
-- администратора не существует ни для одного запроса. Оставить перевод
-- действием оператора значило бы сделать поломку УМОЛЧАНИЕМ каждой новой
-- установки, а исправность — следствием чужой памяти.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПЕРЕПИСЧИК УЖЕ ЕСТЬ, И ЗДЕСЬ ЕГО ТОЛЬКО ЗОВУТ
--
-- `kaname.rename_cluster_anchor` заведён миграцией
-- 20260906085136_cluster_anchor_gets_a_way_back.sql и объявлен в
-- docs/architecture/cluster-admin-access-recovery.md. Он обходит КАТАЛОГ, а не
-- выписанный перечень таблиц, переносит якорь одной транзакцией по текстовым
-- колонкам, jsonb, умолчаниям столбцов и предикатам ограничений, и частичного
-- состояния не производит by construction.
--
-- Второго переписчика здесь не заводится намеренно: два места об одном предмете
-- разошлись бы молча, и разошлись бы именно на той таблице, о которой никто не
-- подумал.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ТРИ ИСХОДА, И ТРЕТИЙ — ОТКАЗ, А НЕ ТИШИНА
--
-- Написание читается ПО ФАКТУ (`kaname.cluster_anchor()`), а не полагается
-- известным:
--
--   * якорь прежний          → переписывается;
--   * якорь уже объявленный  → делать нечего, миграция проходит молча
--                              (установка, поднятая после перехода);
--   * якорь ТРЕТИЙ           → ОТКАЗ. Молчание здесь означало бы «оставим базу
--                              с написанием, которого код не знает», то есть
--                              ровно ту потерю доступа, ради которой всё это
--                              заведено.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ОБРАТНОГО ШАГА У ЭТОЙ МИГРАЦИИ НЕТ, И ЭТО СКАЗАНО ПРЯМО
--
-- Down переписывает якорь обратно тем же переписчиком — это выразимо и потому
-- объявлено. Но откат ВЕРНЁТ базу к написанию, которого код уже не знает:
-- пользоваться им можно только вместе с откатом кода. Иного смысла у него нет,
-- и притворяться, что есть, — хуже отсутствия.

-- +goose Up
-- +goose StatementBegin
DO $$
DECLARE
    v_declared CONSTANT text := 'cluster_root';
    v_previous CONSTANT text := 'cluster_kacho_root';
    v_now      text;
    v_moved    bigint := 0;
    r          record;
BEGIN
    SELECT kaname.cluster_anchor() INTO v_now;

    IF v_now = v_declared THEN
        RAISE NOTICE 'якорь кластера уже %: переписывать нечего.', v_declared;
        RETURN;
    END IF;

    IF v_now <> v_previous THEN
        RAISE EXCEPTION
            'якорь кластера — %, а переход объявлен с % на %. Написание, которого код не знает, оставлять нельзя: кластерный администратор перестанет существовать для каждого запроса. Разберите расхождение до применения свода.',
            v_now, v_previous, v_declared;
    END IF;

    FOR r IN SELECT * FROM kaname.rename_cluster_anchor(v_previous, v_declared) LOOP
        v_moved := v_moved + 1;
    END LOOP;

    RAISE NOTICE 'якорь кластера переписан % → %; мест затронуто %.',
        v_previous, v_declared, v_moved;

    -- Перепись остатка — ОБЕ величины, иначе «ноль находок» неотличимо от «ноль
    -- прочитанного»: переписчик, разошедшийся со схемой, вернул бы ноль
    -- тронутых мест и ноль остатка одинаково молча.
    FOR r IN SELECT place, kind, hits FROM kaname.cluster_anchor_residue(v_previous) LOOP
        IF r.kind = 'перепись' THEN
            RAISE NOTICE 'осмотрено мест схемы: %.', r.hits;
        ELSE
            RAISE EXCEPTION
                'остаток прежнего написания % в %: переход прошёл наполовину.',
                v_previous, r.place;
        END IF;
    END LOOP;
END $$;
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
DO $$
DECLARE
    v_declared CONSTANT text := 'cluster_root';
    v_previous CONSTANT text := 'cluster_kacho_root';
BEGIN
    IF kaname.cluster_anchor() = v_declared THEN
        PERFORM 1 FROM kaname.rename_cluster_anchor(v_declared, v_previous);
    END IF;
END $$;
-- +goose StatementEnd
