-- Роль `iam.user.edit` выводится из обращения: её единственный глагол снят с типа.
--
-- ПРЕДМЕТ. Роль посеяна 0001, правило переписано 0031 §4.7:
-- `[{"modules":["iam"],"resources":["user"],"verbs":["update"]}]`. Тем же
-- изменением, что и эта миграция (#1128), `v_update` снят с типа `iam_user`:
-- правку содержимого строки личности спрашивает `record_writer`, запрет и его
-- снятие — `identity_suspender` (#1102), и читателя у глагола не осталось ни
-- одного.
--
-- ЧТО РОЛЬ ДАЁТ ПОСЛЕ ЭТОГО — НИЧЕГО, и это следует из кода, а не из осторожности.
-- Набор глаголов правила сверяется с набором ТИПА в одной точке
-- (`authzmap.GrantedVerbs`): глагол вне набора отбрасывается, и вместе с ним
-- отпадает выводимое «правка влечёт удаление» — оно добавляется только тому, кто
-- уже правит. То есть выдача этой роли материализовала бы ноль кортежей.
--
-- ПОЧЕМУ ВЫВОД, А НЕ «ОБРЕТЕНИЕ СМЫСЛА». Смысла, который обещает её имя, у неё
-- быть не может: правку записи личности выражает `record_writer`, а он —
-- ВЫЧИСЛЯЕМОЕ отношение (`super_admin from account`). Вычисляемое отношение
-- нельзя выдать: ни кортежем, ни привязкой, ни материализацией. Роль, которая
-- «даёт только удаление», исходом не является — имя обещало бы не то, что роль
-- делает, и это ровно тот класс, ради которого её и разбирали.
--
-- ЧТО ОСТАЁТСЯ АККАУНТУ. Читать своих людей (`iam.user.view` — у `get`/`list`
-- читатели есть) и распоряжаться их участием: исключение из аккаунта
-- (`UserService.RemoveFromAccount`, гейт `account.member_remover`, #1127).
-- Роль `iam.user.admin` (`verbs: ["*"]`) остаётся: подстановка разворачивается в
-- набор ТИПА, поэтому она продолжает давать всё, что тип объявляет.
--
-- ЧТО ЗДЕСЬ НАМЕРЕННО НЕ ДЕЛАЕТСЯ. Соседняя роль `iam.user.delete` не трогается,
-- хотя её глагол читателя тоже не имеет (#1131). У неё свой предмет, свой разбор
-- и свой вердикт — #1189; закрыть два предмета одной миграцией значило бы сделать
-- вердикт непрослеживаемым.
--
-- НОМЕР МЕНЬШЕ ОДНОГО УЖЕ ЛЕЖАЩЕГО В КАТАЛОГЕ, и это названо, а не умолчано.
-- Метка времени взята с часов заведения (`date -u +%Y%m%d%H%M%S`), как требует
-- соглашение; соседний файл 20260824010000 несёт метку на 37 минут позже.
-- Накат iam собран с приёмом пропущенных (`goose.WithAllowMissing`), поэтому
-- существующая база применит эту миграцию первой из непринятых, а свежая — в
-- числовом порядке. Расхождение схем от разного порядка возможно ТОЛЬКО когда два
-- файла трогают один объект; здесь предметы непересекающиеся — там заменяется
-- триггер зеркала членства, тут удаляются строки одной роли, — поэтому итог обеих
-- последовательностей одинаков.
--
-- ИДЕМПОТЕНТНА. Все стейтменты ключуются на детерминированном идентификаторе
-- роли, поэтому повторный прогон — и повторное применение к уже выведенной базе —
-- не меняют ничего. Аддитивна к истории: ни одна применённая миграция не правится
-- (запрет #5).

-- (1) Селекторы, спроецированные из правил роли. Они каскадируют от roles(id), но
--     удаление названо явно: выведенное состояние не должно зависеть от того, что
--     каскад настроен сегодня именно так.
DELETE FROM kacho_iam.role_rule_selectors
 WHERE role_id = 'rol' || substr(md5('iam.user.edit'), 1, 17);

-- (2) Проекция «роль → тип × глагол», которую читает вердикт. Тоже каскадирует и
--     тоже названа явно, по той же причине.
DELETE FROM kacho_iam.role_verb
 WHERE role_id = 'rol' || substr(md5('iam.user.edit'), 1, 17);

-- (3) Привязки, выдававшие эту роль. `access_bindings_role_fk` — ON DELETE
--     RESTRICT, поэтому они идут ДО роли; субъекты, цели, состав целей, выданные
--     кортежи и условия каскадируют от привязки. Ключ — role_id, а не идентификатор
--     посеянной привязки: привязка, заведённая на эту роль любым другим путём,
--     обязана уйти вместе с ней, иначе шаг (4) упрётся в голый RESTRICT без
--     называемой причины.
DELETE FROM kacho_iam.access_bindings
 WHERE role_id = 'rol' || substr(md5('iam.user.edit'), 1, 17);

-- (4) Сама роль. Область — детерминированный посеянный идентификатор, поэтому
--     аккаунт-областная роль арендатора с тем же именем остаётся своему владельцу.
DELETE FROM kacho_iam.roles
 WHERE id = 'rol' || substr(md5('iam.user.edit'), 1, 17);

