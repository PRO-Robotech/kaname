-- ceremony_handle_is_its_own_random_value — РУКОЯТКА ЦЕРЕМОНИИ человека
-- (`user.id` регистрации ключа доступа) становится отдельным случайным
-- значением, а не платформенным `id` (задача PRO-Robotech/kaname#351).
--
-- Санкция: приёмка `docs/engineering/acceptance/passwordless-login-with-access-key.md`,
-- редакция 9 (отпечаток 5fe6cca1…8af4, запись
-- `docs/specs/reviews/passwordless-login-with-access-key/5fe6cca1aea606f96b2f24174a8f45411291f69250e6fb268b3274fd17a58af4.yaml`,
-- `APPROVED`, событие опубликовано): решение Р3, держатель Ф13-33, §4.4
-- (четвёртое место — комментарий применённой миграции). Доводы там; здесь —
-- то, что нужно читателю СХЕМЫ.
--
-- =============================================================================
-- ЗАЧЕМ
-- =============================================================================
-- Рукоятка записывается В АУТЕНТИФИКАТОР и в синхронизируемое хранилище
-- держателя, возвращается в каждом утверждении обнаруживаемого удостоверения и
-- видна в интерфейсе управления удостоверениями операционной системы. Отозвать
-- её оттуда нечем. Пока в ней стоял платформенный `id`, развязать учётную
-- запись с ним было невозможно: наши строки снимутся, а значение в чужом
-- хранилище останется называть снятое.
--
-- Отсюда своя таблица: 64 случайных байта на человека (верхняя граница нормы
-- WebAuthn для `user.id`), заведённые лениво первой церемонией регистрации и
-- неизменные после — смена рассинхронизировала бы строки ключей с тем, что
-- уже лежит в аутентификаторах. Снятие человека уносит строку КАСКАДОМ: это и
-- есть механизм развязки.
--
-- Почему рукоятка всё равно хранится и в строке ключа (`user_access_keys.user_handle`):
-- сверка утверждения идёт со строкой КЛЮЧА (Ф13-06 «з») — удостоверение
-- сверяется с тем, с чем оно заведено. Здешняя таблица — ИСТОЧНИК значения для
-- церемоний, а не его единственное место.
--
-- Обратного заполнения нет и быть не может: рукоятку уже заведённого ключа
-- сменить нельзя — она уехала. Ключи, заведённые до этой миграции, продолжают
-- сверяться со своим значением в своей строке (Р3, «цена названа»).
--
-- =============================================================================
-- КОММЕНТАРИЙ ПРИМЕНЁННОЙ МИГРАЦИИ
-- =============================================================================
-- `20260917221000_access_keys_are_our_record.sql` называет значением
-- `user_handle` платформенный идентификатор — и в шапке, и в `COMMENT ON COLUMN`.
-- Применённая миграция не правится (ban #5), поэтому комментарий колонки
-- заменяется здесь, тем же изменением, которым меняется значение. Шапка файла
-- остаётся историей того решения.

-- +goose Up

CREATE TABLE kaname.user_ceremony_handles (
    user_id    text NOT NULL,
    handle     bytea NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT user_ceremony_handles_pkey PRIMARY KEY (user_id),
    CONSTRAINT user_ceremony_handles_user_fk FOREIGN KEY (user_id)
        REFERENCES kaname.users(id) ON DELETE CASCADE,
    CONSTRAINT user_ceremony_handles_handle_key UNIQUE (handle),
    -- Ровно верхняя граница нормы: значение во всю ширину не оставляет места,
    -- которое кто-нибудь позже примет за место для осмысленного содержимого.
    -- Предел колонки рукоятки у строки ключа (1…64) его вмещает.
    CONSTRAINT user_ceremony_handles_handle_check CHECK ((octet_length(handle) = 64))
);

COMMENT ON TABLE kaname.user_ceremony_handles IS
  'Рукоятка церемонии человека (user.id регистрации ключа доступа): 64 случайных байта, заведённые первой церемонией и неизменные после. Ни из id, ни из адреса, ни из имени не выводится. Снятие человека уносит строку каскадом — развязка значения, уже лежащего в чужом аутентификаторе, с нашей учётной записью.';
COMMENT ON COLUMN kaname.user_ceremony_handles.handle IS
  'Случайное значение; уникально по всей службе (ключ уникальности, а не надежда на разрядность). Наружу не выходит: перечень ключей рукоятку не показывает.';

COMMENT ON COLUMN kaname.user_access_keys.user_handle IS
  'Рукоятка user.id, которую церемония регистрации положила в ЭТОТ ключ: значение из kaname.user_ceremony_handles (64 случайных байта на человека). Платформенным id человека НЕ является. С ней сверяется каждое утверждение ключа (полоса входа Ф13).';

-- Статистика планировщика по байтовой колонке НЕ собирается — те же доводы,
-- что у соседей: анализ положил бы выборку значений в `pg_statistic`, и эта
-- копия пережила бы удаление строки, ради которого заведён каскад.
ALTER TABLE kaname.user_ceremony_handles ALTER COLUMN handle SET STATISTICS 0;

-- +goose Down

-- Откат ОТКАЗЫВАЕТСЯ уничтожать рукоятки: каждая уже лежит в чужом
-- аутентификаторе, и после снятия таблицы следующая церемония того же человека
-- завела бы ВТОРУЮ — у одного человека оказались бы ключи с разными `user.id`.
-- Откат безопасен ровно тогда, когда рукояток ноль.
LOCK TABLE kaname.user_ceremony_handles IN ACCESS EXCLUSIVE MODE;

-- +goose StatementBegin
DO $$
DECLARE
  v_handles bigint;
BEGIN
  SELECT count(*) INTO v_handles FROM kaname.user_ceremony_handles;
  IF v_handles > 0 THEN
    RAISE EXCEPTION 'refusing to roll back: kaname holds % ceremony handle row(s); each is already written into an authenticator and cannot be rewritten. WAY OUT: the rollback is safe exactly when the count is 0', v_handles
      USING ERRCODE = 'restrict_violation';
  END IF;
END;
$$;
-- +goose StatementEnd

DROP TABLE kaname.user_ceremony_handles;

COMMENT ON COLUMN kaname.user_access_keys.user_handle IS 'Рукоятка user.id церемонии (у ключей Ф7 — платформенный id человека как байты); NULL — источник переноса её не нёс. Читатель — полоса входа Ф13.';
