-- 20260823050000_users_identity_uniqueness_goes_global — ключ идентичности
-- человека перестаёт включать аккаунт.
-- Стадия S4-expand перехода IAM-ID-1, задача kacho#470.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Уникальность строки пользователя объявлена ПАРОЙ:
--
--     users_account_email_unique        UNIQUE (account_id, lower(email))
--     users_account_external_id_unique  UNIQUE (account_id, external_id) WHERE external_id <> ''
--
-- Пока аккаунт входит в ключ, «тот же человек в другом аккаунте» есть ДРУГАЯ
-- строка: другой идентификатор, другой набор прав, и активировать из них можно
-- только одну — вторая остаётся неактивируемой навсегда, а выданное на неё
-- право осиротевшим.
--
-- Здесь вводится ГЛОБАЛЬНЫЙ ключ: одна строка на человека, кем бы его ни
-- пригласили и сколько бы членств у него ни было.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО ЭТА МИГРАЦИЯ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ
--
-- Делает: объявляет два глобальных ключа и отказывается идти, если данные им не
-- удовлетворяют.
--
-- НЕ делает: не снимает ни одного существующего ключа, не трогает колонку
-- `users.account_id` и не меняет ни одного контракта. Это ЭКСПАНД: пер-аккаунтные
-- ключи остаются лежать рядом — они строго слабее глобальных и потому
-- избыточны, но не противоречивы. Снятие колонки и пары ключей — точка
-- невозврата, и она идёт СВОЕЙ миграцией после того, как поле уйдёт с контракта
-- (#471) и у колонки не останется читателей.
--
-- Откат полон by construction: снятие двух индексов, одно действие, данные не
-- тронуты (IAM-ID-1-51 — оба источника живы).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ИМЕНА НОВЫЕ, А НЕ `users_email_uniq` / `users_external_id_uniq`
--
-- Эти два имени носили ПРЕЖНИЕ глобальные ключи, снятые `0011`, и страж
-- `0069_users_identity_uniqueness_guard.sql` перечисляет их как ОТСТАВЛЕННЫЕ.
-- Воскресив имя, мы сделали бы утверждение стража ложным задним числом: он
-- по-прежнему проигрывается на свежей базе и по-прежнему обязан быть прав в
-- момент своего исполнения. Править применённую миграцию нельзя (ban #5), а
-- заводить два места об одном предмете — тем более.
--
-- Имя `users_identity_*` при этом называет НЕ ту же вещь, что снял `0011`:
-- тот ключ запрещал приглашать человека во второй аккаунт (модель этого
-- требовала), этот — запрещает ЗАВОДИТЬ ему вторую строку, потому что второй
-- аккаунт выражается членством, а не строкой. Разные предметы обязаны носить
-- разные имена, иначе следующий читатель решит, что решение отменили.
--
-- Тот же приём и по той же причине применён к ключнице подписных ключей (#897).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ОТКАЗ ПИШЕТСЯ РУКАМИ, ХОТЯ `CREATE UNIQUE INDEX` УПАЛ БЫ И САМ
--
-- Упал бы — сообщением драйвера: «could not create unique index … Key
-- (lower(email))=(…) is duplicated». Оно называет ОДНУ пару и не говорит ни
-- сколько их всего, ни что с этим делать. Оператор, поднимающий стенд, читает
-- этот текст вместо предмета, а число групп — единственная величина, по которой
-- видно, «мы про это не подумали» или «этого не было» (IAM-ID-1-52).
--
-- Отказ здесь — рантайм-диагностика оператору, а не публичный артефакт: он
-- обязан называть предмет прямо (`security.md` §«Три места, которые НЕ
-- подпадают»). Почты он при этом НЕ печатает — это данные арендатора, а для
-- решения довольно чисел.
--
-- Свести дубли умеет `20260822234500_identity_rows_merge_and_rights_travel.sql`;
-- она же называет три формы, которых не сводит, и по каждой отказывает громко.
-- Если эта миграция отказала, значит осталась одна из них — и решение по ней
-- продуктовое, а не миграционное.

-- +goose Up

-- ─────────────────────────────────────────────────────────────────────────────
-- Предусловие. Исполняется, а не декларируется в шапке.
-- +goose StatementBegin
DO $precondition$
DECLARE
    v_email_groups bigint;
    v_email_rows   bigint;
    v_ext_groups   bigint;
    v_ext_rows     bigint;
BEGIN
    SELECT count(*), COALESCE(sum(n), 0) INTO v_email_groups, v_email_rows
      FROM (SELECT count(*) AS n FROM kacho_iam.users
             GROUP BY lower(email) HAVING count(*) > 1) g;

    IF v_email_groups > 0 THEN
        RAISE EXCEPTION
            'глобальный ключ lower(email) объявить нельзя: почт, на которых сошлось больше одной строки, %; строк в них %. '
            'Сведите строки одного человека к одной — это делает миграция 20260822234500_identity_rows_merge_and_rights_travel; '
            'если она уже применена, значит остались группы, которые она сводить отказывается (заблокированная строка, '
            'две ACTIVE-строки на одной почте, выдача-дубль с посторонним субъектом) — решение по ним принимает владелец продукта, '
            'а не миграция. Ни один ключ не изменён, состояние базы то же, что до попытки.',
            v_email_groups, v_email_rows;
    END IF;

    SELECT count(*), COALESCE(sum(n), 0) INTO v_ext_groups, v_ext_rows
      FROM (SELECT count(*) AS n FROM kacho_iam.users
             WHERE external_id <> ''
             GROUP BY external_id HAVING count(*) > 1) g;

    IF v_ext_groups > 0 THEN
        RAISE EXCEPTION
            'глобальный ключ external_id объявить нельзя: внешних субъектов, на которых сошлось больше одной строки, %; строк в них %. '
            'Прежний ключ users_active_external_id_uniq накрывал только ACTIVE, поэтому сойтись могли ACTIVE-строка и BLOCKED-строка '
            'одного человека. Ни один ключ не изменён.',
            v_ext_groups, v_ext_rows;
    END IF;

    RAISE NOTICE 'предусловие глобальных ключей: групп-дублей по почте 0, по внешнему субъекту 0 — ключи объявляются';
END;
$precondition$;
-- +goose StatementEnd

-- ─────────────────────────────────────────────────────────────────────────────
-- Почта — одна строка на человека, независимо от регистра и от аккаунта.
-- Полный, а не частичный: пустой почты не бывает (`users_email_not_blank`),
-- значит предиката, по которому строку следовало бы исключить из ключа, нет.
CREATE UNIQUE INDEX users_identity_email_uniq
    ON kacho_iam.users (lower(email));

-- Внешний субъект — частичный, потому что у приглашённого его нет вовсе
-- (`users_invite_status_consistency` требует пустую строку у PENDING, и пустых
-- бывает много).
--
-- Строго ШИРЕ прежнего `users_active_external_id_uniq` (тот брал только ACTIVE):
-- накрывает ещё и BLOCKED, у которого внешний субъект непуст по тому же CHECK.
-- Прежний остаётся лежать — он избыточен, но не противоречив, и снимается в той
-- же миграции, что снимет пару пер-аккаунтных ключей.
CREATE UNIQUE INDEX users_identity_external_id_uniq
    ON kacho_iam.users (external_id) WHERE external_id <> '';

-- +goose Down

DROP INDEX IF EXISTS kacho_iam.users_identity_external_id_uniq;
DROP INDEX IF EXISTS kacho_iam.users_identity_email_uniq;
