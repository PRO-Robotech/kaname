-- 0086_relation_fact_condition — условие, при котором прямой факт действует.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЗАЧЕМ УСЛОВИЕ ЛЕЖИТ НА СТРОКЕ, А НЕ ВЫВОДИТСЯ ИЗ МОДЕЛИ
--
-- Модель объявляет, что отношение МОЖЕТ нести условие; какое именно условие
-- несёт КОНКРЕТНАЯ запись — свойство записи. Выводить его из модели значило бы
-- завести второе место, знающее, при каких условиях действует эта строка, и
-- разойтись с ней в тот момент, когда модель поменяется, а строки останутся.
-- Строка самоописательна: прочитавший её знает всё, что нужно для вердикта.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ПУСТОЕ ИМЯ, А НЕ NULL
--
-- Отсутствие условия — не отсутствие сведений, а полноценное состояние
-- «действует всегда». NULL заставил бы каждого читателя решать, что означает
-- неизвестность, и первый же читатель, забывший про третье состояние, прочёл бы
-- её как «условие не выполнено» либо как «условие выполнено» — обе ошибки тихие.
-- Пустая строка сравнивается напрямую и не имеет второго прочтения.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО ЛОЖИТСЯ В ПАРАМЕТРЫ
--
-- Условие берёт часть доводов из запроса (свежесть подтверждения личности — это
-- «сейчас», её нельзя хранить), а часть — из самой записи (срок действия, набор
-- допустимых сетей). Вторая часть живёт здесь. Без этой колонки запись была бы
-- НЕПОЛНОЙ КОПИЕЙ кортежа, выглядящей полной, — и целый класс условий молча
-- терял бы свои доводы при переносе.

-- +goose Up

ALTER TABLE kacho_iam.relation_fact
  ADD COLUMN condition_name   text  NOT NULL DEFAULT '',
  ADD COLUMN condition_params jsonb NOT NULL DEFAULT '{}'::jsonb;

-- Параметры — всегда объект. Массив или скаляр здесь означал бы, что читатель
-- обязан разбирать форму, а форма у доводов условия одна: имя → значение.
ALTER TABLE kacho_iam.relation_fact
  ADD CONSTRAINT relation_fact_condition_params_is_object
    CHECK (jsonb_typeof(condition_params) = 'object');

-- Параметры без условия — состояние, у которого нет смысла: их некому читать.
-- Запретить дешевле, чем однажды искать, почему довод не применился.
ALTER TABLE kacho_iam.relation_fact
  ADD CONSTRAINT relation_fact_params_require_condition
    CHECK (condition_name <> '' OR condition_params = '{}'::jsonb);

-- Условное право спрашивают отдельно от безусловного: «какие записи вообще
-- требуют вычисления». Частичный индекс — по тем, что требуют.
CREATE INDEX relation_fact_conditioned
  ON kacho_iam.relation_fact (condition_name)
  WHERE condition_name <> '';

-- +goose Down

DROP INDEX IF EXISTS kacho_iam.relation_fact_conditioned;
ALTER TABLE kacho_iam.relation_fact
  DROP CONSTRAINT IF EXISTS relation_fact_params_require_condition,
  DROP CONSTRAINT IF EXISTS relation_fact_condition_params_is_object,
  DROP COLUMN IF EXISTS condition_params,
  DROP COLUMN IF EXISTS condition_name;
