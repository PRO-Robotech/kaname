-- 20260829124512 — журнал смены субъекта теряет величины предмета: подсказывать
-- ими некому (kacho#1462).
--
-- ───────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Колонки `resource_type`/`resource_id` заполняет КАЖДАЯ мутация выдачи —
-- выдача права и его снятие, — в writer-транзакции, то есть на пути мутации.
-- Читателя у них нет ни одного:
--
--   проекция чтения   `repo/kacho/pg/subject_change_repo.go` выбирает
--                     id, subject_id, op и тип субъекта из payload — и только;
--   контракт          `InternalIAMService.PollSubjectChanges` отдаёт
--                     id, subject_id, op, subject_type — этих величин в нём нет;
--   потребитель       край читает журнал курсором и гасит свой кэш решений;
--                     `pkg/subjectchange.SubjectChange` несёт ID и субъекта.
--
-- Комментарий у объявления называл их «optional scope hint for future
-- per-resource cache invalidation. MVP gateway ignores them» — то есть прямо
-- говорил, что подсказка никому не адресована. Это «принято-и-проигнорировано»
-- на уровне хранения: величина оплачивается сейчас, а обещанного ею механизма
-- не существует.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ СНИМАЮТСЯ, А НЕ ВЫВОДЯТСЯ НАРУЖУ
--
-- Исходов по правилу «принято-и-проигнорировано» три: реализовать · отвергнуть
-- явно · снять с контракта. Реализовать значило бы завести пообъектный сброс
-- кэша решений — это отдельный домен со своей приёмкой, а не поле в чужом
-- сообщении; отвергать явно нечего, потому что вызывающий этих величин не шлёт
-- (их выводит эмиттер из привязки). Остаётся снять, и это умолчание правила.
--
-- Понадобится пообъектный сброс — он придёт своей под-фазой и приведёт СВОЮ
-- величину вместе с читателем, а не за фазу до него.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ЧТО СНИМАЕТСЯ И ЧТО ОСТАЁТСЯ
--
--   снимается  resource_type, resource_id — величины предмета без читателя;
--   снимается  их близнецы в `payload` (перестаёт писать эмиттер, см. коммит);
--   остаётся   id, subject_id, op, event_type, payload, created_at — журнал
--              целиком, его читает край курсором по id.
--
-- Индексов и ограничений на снимаемых колонках нет ни одного (проверено по
-- цепи миграций: единственный индекс журнала — `subject_change_pending_v2_idx`
-- по `created_at`, ограничения 0097 и 754001 судят `payload` и `op`).
-- Триггер журнала `subject_change_outbox_notify` читает только `NEW.id`,
-- поэтому снятие колонок его тела не касается — в отличие от случая
-- 20260823001000, где тело называло снятое поле и отвергало КАЖДУЮ вставку.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ОБРАТИМОСТЬ, НАЗВАННАЯ ЧЕСТНО
--
-- Down возвращает ФОРМУ (две nullable-колонки), но не значения: они не
-- восстановимы, потому что нигде больше не хранились. Это не упущение отката, а
-- свойство снятия величины без читателя — восстанавливать нечего и некому.
-- Строки журнала при этом не трогаются ни в одну сторону.

-- +goose Up

ALTER TABLE kacho_iam.subject_change_outbox DROP COLUMN IF EXISTS resource_type;
ALTER TABLE kacho_iam.subject_change_outbox DROP COLUMN IF EXISTS resource_id;

-- +goose Down

ALTER TABLE kacho_iam.subject_change_outbox ADD COLUMN IF NOT EXISTS resource_type text;
ALTER TABLE kacho_iam.subject_change_outbox ADD COLUMN IF NOT EXISTS resource_id text;
