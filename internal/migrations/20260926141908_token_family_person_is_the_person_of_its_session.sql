-- token_family_person_is_the_person_of_its_session — ЧЕЛОВЕК семейства есть
-- человек ЕГО СЕССИИ, и держит это база (задача PRO-Robotech/kaname#423).
--
-- Санкция: одобренная приёмка LINE-A-1 (воркспейс, ветка 771,
-- `docs/specs/sub-phase-LINE-A-1-own-authorization-endpoint-and-code-acceptance.md`,
-- SHA-256 `b755886fd3a9cbf4070598ad3d921bb92d53d7f4186832a2c34f1d8ca197a7ec`):
-- Р5 «связку назначает ВЫДАЧА», инвариант 1 «церемония аутентифицирует человека
-- через наш вход» — субъект гранта есть человек той сессии, в которой шла
-- церемония, а не значение, названное писателем рядом с ней.
--
-- =============================================================================
-- ЗАЧЕМ
-- =============================================================================
-- Семейство несёт и человека (`user_id`), и сессию (`session_id`), а у сессии
-- свой человек (`human_sessions.user_id`): это ДВА написания одного факта. До
-- этой миграции у семейства стояли два ОДИНОЧНЫХ ключа
-- (`token_families_user_fk`, `token_families_session_fk`), и каждый проверял
-- лишь то, что его значение где-то существует. Строку, в которой сессия одного
-- человека выдаёт права другому, база принимала — от любого писателя, включая
-- ручной SQL и восстановление из дампа; согласие держал только оператор выдачи,
-- и то не сравнением, а тем, что писатель передал правильную пару.
--
-- Нарушить согласие можно ТРЕМЯ путями, и составной ключ закрывает все три:
--
--   - вставка семейства с чужим человеком — проверка ключа, 23503;
--   - смена человека или сессии у семейства — та же проверка на обновлении;
--   - смена человека у сессии, на которую ссылается семейство, — умолчание
--     `NO ACTION` отвергает её, 23503. `ON UPDATE CASCADE` здесь был бы ошибкой
--     того же рода, что описан у ключа контекста кода (миграция
--     `20260920175117`): каскад молча переписал бы человека уже выданного
--     семейства, то есть задним числом передал бы права другому.
--
-- На удалении ключ ведёт себя как прежний ключ сессии — `ON DELETE CASCADE`:
-- семейство уходит вместе со своей сессией.
--
-- =============================================================================
-- ЦЕНА: ПАРА СЕССИИ СТАНОВИТСЯ КЛЮЧОМ
-- =============================================================================
-- Составной ключ ссылается на уникальный набор, поэтому у сессии заводится
-- `human_sessions_id_user_uniq (id, user_id)`. Уникальна пара тривиально —
-- `id` уже первичный ключ; индекс — плата за право на неё сослаться.
--
-- Следствие для замков названо, потому что на них стоит разобранный порядок
-- выдачи: столбец уникального индекса движок считает КЛЮЧЕВЫМ, и обновление,
-- меняющее `user_id`, берёт `FOR UPDATE` вместо `FOR NO KEY UPDATE`. Ни один
-- писатель сессии вне проб `user_id` не меняет (предикат
-- `git grep -nE -A2 'UPDATE +(kaname\.)?human_sessions' -- '*.go' ':!*_test.go'`,
-- каждый `SET` перечисляет свои столбцы), поэтому сила замков у действующих
-- писателей прежняя. Проверка нового ключа на вставке семейства берёт
-- `FOR KEY SHARE` на строке сессии — ту же строку выдача уже держит
-- `FOR SHARE`, нового предмета замка не появляется.
--
-- =============================================================================
-- ОДИНОЧНЫЕ КЛЮЧИ ОСТАЮТСЯ
-- =============================================================================
-- Составной ключ делает `token_families_session_fk` избыточным по смыслу, и
-- всё же оба одиночных ключа остаются:
--
--   - `token_families_user_fk` несёт разобранный порядок замков выдачи против
--     удаления человека: проба `TestOAuthIssuanceOverlappingUserDeletion`
--     читает его триггер по имени;
--   - `token_families_session_fk` назван путём снятия строки в шапке
--     применённой миграции `20260920175117`. Снять ключ, чьё имя — адрес в
--     применённом тексте, — отдельное решение со своей пробой, а не попутная
--     правка.
--
-- Цена избыточности названа: вторая проверка ключа на вставке и второй каскад
-- на удалении сессии, который находит уже пустое множество.
--
-- =============================================================================
-- ЛЕЖАЩИЕ СТРОКИ
-- =============================================================================
-- Строка с несогласной парой — выдача прав чужому человеку, и исправить её
-- нечем: какой из двух людей верен, не говорит ни одна колонка. Поэтому накат
-- такую строку НЕ чинит и НЕ удаляет: ключ отвергает её кодом 23503 с именем
-- ограничения, накат откатывается целиком, и установка остаётся на прежней
-- версии, пока строку не разберёт человек.

-- +goose Up

ALTER TABLE kaname.human_sessions
    ADD CONSTRAINT human_sessions_id_user_uniq UNIQUE (id, user_id);

ALTER TABLE kaname.token_families
    ADD CONSTRAINT token_families_session_user_fk FOREIGN KEY (session_id, user_id)
        REFERENCES kaname.human_sessions(id, user_id) ON DELETE CASCADE;

-- +goose Down

-- Откат снимает ключ, затем набор, на который он ссылался. Данных миграция не
-- писала, и откат их не трогает.
ALTER TABLE kaname.token_families
    DROP CONSTRAINT token_families_session_user_fk;

ALTER TABLE kaname.human_sessions
    DROP CONSTRAINT human_sessions_id_user_uniq;
