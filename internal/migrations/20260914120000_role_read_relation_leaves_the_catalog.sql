-- Действие `get` ресурса `iam.role` УХОДИТ ИЗ КАТАЛОГА вместе с отношением,
-- которого не спрашивал ни один путь запроса (задача продукта kacho#1922,
-- приёмка docs/engineering/acceptance/role-read-relation-retired-not-half-declared.md).
--
-- ────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Тип `iam_role` объявлял отношение `v_get`, и читателя у него не было ни
-- одного: чтение роли поимённо энфорсится ТЕМ ЖЕ предикатом, что страница
-- (`{viewer, v_list}`, internal/authzfilter/visibility.go), обе поверхности
-- зовут один резолвер `resolveVisibleRoleIDs`, и ни одна запись каталога прав
-- края не называет `v_get` на этом типе. Право по такому отношению не открывало
-- ничего — а превью роли его обещало, потому что подстановочное правило
-- `iam.role.admin` (`classes: ["*"]`) разворачивается в набор ТИПА.
--
-- Отношение снято с типа в манифесте и каноне тем же изменением. Здесь
-- снимается ЕГО СЛЕД В КАТАЛОГЕ — строка `kaname.catalog_verb`, посеянная
-- базовой миграцией живой.
--
-- ────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ МИГРАЦИЯ, ЕСЛИ СНЯТИЕ УМЕЕТ ПРИМЕНИТЕЛЬ
--
-- Применитель каталога снимает такую строку на подъёме (`RetireVerb`, план из
-- разности «что в базе» против «что объявлено манифестом»), и на живой базе
-- работу делает он. Предмет ЭТОЙ миграции другой — ПОСЕВ: гейт паритета
-- `TestIAMCT114_CatalogSeedMatchesTheLiteral` читает ТЕКСТ цепочки миграций и
-- требует, чтобы множество живых пообъектных глаголов, которое цепочка
-- оставляет, совпадало с литералом. Базовую миграцию править нельзя (запрет #5),
-- значит согласие достигается ЗДЕСЬ, оператором над её строкой.
--
-- Следствие, которое стоит назвать: свежепромигрированная база перестаёт
-- предлагать снятый глагол С МОМЕНТА МИГРАЦИИ, а не с первого подъёма. Окно,
-- в котором автор правила мог назвать глагол, которого платформа не исполняет,
-- закрывается целиком.
--
-- ────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ПЕРЕСЕЛЕНИЕ СТОИТ ЗДЕСЬ ЖЕ, А НЕ ОСТАВЛЕНО ПРИМЕНИТЕЛЮ
--
-- Ключ `role_rule_ref_verb_fk` ссылается на `(module, resource, verb, live)` и
-- объявлен `DEFERRABLE INITIALLY IMMEDIATE`. Живость входит в ключ С ОБЕИХ
-- СТОРОН, поэтому пометка строки снятой УНИЧТОЖАЕТ референт `('iam','role',
-- 'get', true)`, а не сохраняет его. Снятие и переселение потерявших референт
-- объявлений НЕДЕЛИМЫ by construction: оставь переселение применителю — эта
-- миграция отказала бы на базе арендатора, у которого такое правило есть.
--
-- Переселение повторяет ДОСЛОВНО то, что делает применитель
-- (`resettleRuleRefSQL`, internal/repo/kaname/pg/catalog_consequence_sql.go):
-- объявление арендаторской роли снимается и ТЕМ ЖЕ оператором переезжает в
-- `kaname.role_grant_orphan` — иначе отобранное право неотличимо от никогда не
-- выданного. Отбор сужен до ОДНОЙ пары «ресурс + действие»: у миграции нет
-- входа с массивами, и шире он быть не вправе.
--
-- Системные объявления НЕ переселяются, и это то же решение, что у применителя:
-- манифест, снимающий то, что его же роль называет, противоречит сам себе, и
-- это обязано быть отвергнуто, а не улажено молчаливым отбором права. Поэтому
-- ниже стоит не отбор, а ПРОВЕРКА: системных объявлений этого глагола обязано
-- быть ноль. Замер на посеве — ноль из четырёх строк `role_rule_ref` про
-- `iam/role` (`list`, `update`, NULL, `list`); предикат:
--
--   grep "INSERT INTO kaname.role_rule_ref " internal/migrations/0001_initial.sql \
--     | grep "'iam', 'role', 'get'"
--
-- ────────────────────────────────────────────────────────────────────────────
-- ЧЕГО МИГРАЦИЯ НЕ ТРОГАЕТ
--
-- `kaname.role_verb` — её ключ (`role_verb_type_fk`) ссылается ТОЛЬКО на
-- ресурс, а ресурс `iam.role` остаётся живым: снятие действия этот ключ не
-- задевает, и переселять выдачу на этом входе значило бы отбирать у арендатора
-- право, которого база не отбирает. Пересчёт проекции глаголов роли —
-- предмет досева на подъёме, а не миграции.
--
-- `kaname.role_rule_selectors` — вырезание элементов идёт по ТОЧЕЧНЫМ ТИПАМ
-- снимаемых РЕСУРСОВ; здесь ресурс не снимается, вырезать нечего.
--
-- Ярусная половина словаря (`per_object = false`) — строка `('iam','role',
-- 'create')` живёт своим предметом и снимаемого отношения не производит.

-- +goose Up
-- +goose StatementBegin
DO $$
BEGIN
    IF to_regclass('kaname.catalog_verb') IS NULL THEN
        RAISE EXCEPTION 'kaname.catalog_verb не существует — цепочка миграций применена не с начала';
    END IF;
    IF to_regclass('kaname.role_grant_orphan') IS NULL THEN
        RAISE EXCEPTION 'kaname.role_grant_orphan не существует — переселять снятое было бы некуда';
    END IF;
END
$$;
-- +goose StatementEnd

-- ПРЕДПОСЫЛКА: системное объявление снимаемого глагола — противоречие манифеста
-- самому себе, и оно обязано быть ОТВЕРГНУТО, а не улажено.
-- +goose StatementBegin
DO $$
DECLARE
    system_refs integer;
BEGIN
    SELECT count(*) INTO system_refs
      FROM kaname.role_rule_ref rr
      JOIN kaname.roles r ON r.id = rr.role_id
     WHERE r.is_system
       AND rr.module = 'iam' AND rr.resource = 'role' AND rr.verb = 'get';
    IF system_refs <> 0 THEN
        RAISE EXCEPTION 'системных объявлений iam.role.get — %, ожидалось 0: манифест снимает действие, которое его же роль называет', system_refs;
    END IF;
END
$$;
-- +goose StatementEnd

-- Объявления АРЕНДАТОРСКИХ правил, теряющие референт, снимаются и переселяются
-- ОДНИМ оператором.
-- +goose StatementBegin
WITH dropped AS (
    DELETE FROM kaname.role_rule_ref rr
     WHERE rr.module = 'iam' AND rr.resource = 'role' AND rr.verb = 'get'
       AND EXISTS (SELECT 1 FROM kaname.roles r
                    WHERE r.id = rr.role_id AND r.is_system = false)
    RETURNING rr.role_id, rr.module, rr.resource, rr.verb
)
INSERT INTO kaname.role_grant_orphan (role_id, object_type, verb, source, reason, applied_by)
SELECT d.role_id, d.module || '.' || d.resource, COALESCE(d.verb, ''), 'rule_ref',
       'iam.role.get снят: отношения v_get на типе iam_role не спрашивает ни один путь запроса (kacho#1922)',
       'migration:20260914120000'
  FROM dropped d
ON CONFLICT (role_id, object_type, verb, source, cause) DO NOTHING;
-- +goose StatementEnd

-- Строка каталога ПОМЕЧАЕТСЯ снятой, а не удаляется: снятые строки каталога
-- не удаляются никогда — иначе снятое неотличимо от никогда не объявленного.
UPDATE kaname.catalog_verb
   SET retired_at = now(), live = false,
       retired_reason = 'v_get на iam_role не спрашивает ни один путь запроса; чтение роли энфорсится предикатом страницы (kacho#1922)'
 WHERE module = 'iam' AND resource = 'role' AND verb = 'get' AND live;

-- +goose Down
-- Откат ОЖИВЛЯЕТ строку каталога — ровно ту же, а не вторую: первичный ключ у
-- пары «модуль, ресурс, глагол» один.
--
-- Переселённые объявления арендаторских правил откат НЕ возвращает, и это
-- сказано прямо: их снятие записано в `kaname.role_grant_orphan`, откуда видно,
-- что именно было отобрано и почему. Возврат по этой записи — работа
-- применителя, а не отката схемы; ровно так же ведёт себя снятие, сделанное
-- применителем на подъёме.
UPDATE kaname.catalog_verb
   SET retired_at = NULL, live = true, retired_reason = NULL
 WHERE module = 'iam' AND resource = 'role' AND verb = 'get' AND NOT live;
