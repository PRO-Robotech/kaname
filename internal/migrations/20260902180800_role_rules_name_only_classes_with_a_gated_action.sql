-- +goose StatementBegin

-- Обратного пути нет, и причина названа, а не умолчана.
--
-- Откат вернул бы объявление, которое не даёт НИЧЕГО: отношение `v_get` на типе
-- `iam_role` не спрашивает ни одна запись каталога прав края, поэтому ни один
-- вопрос по нему не задавался за всё время жизни этих правил. Восстанавливать
-- состояние, признанное дефектным, значит объявлять его законным.
--
-- Откату, которому и вправду нужно ЧТЕНИЕ роли по выдаче, нужна не эта строка,
-- а ЧИТАТЕЛЬ отношения — то есть изменение того, что спрашивает полоса чтения
-- роли, со своей приёмкой и своим разбором, а не обращение этой миграции.
SELECT 1;

