-- 20260902180800_role_rules_name_only_classes_with_a_gated_action — правило роли
-- называет только тот класс, у которого есть ДЕЙСТВИЕ с гейтом.
--
-- Задача продукта kacho#1916. Исход миграции утверждает интеграционная проба
-- services/iam/internal/repo/kacho/pg/role_class_has_a_gated_action_integration_test.go.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО НЕВЕРНО СЕГОДНЯ
--
-- Правило роли адресует объект тремя сегментами — модуль, ресурс, класс. Класс
-- что-то ДАЁТ ровно тогда, когда у ресурса есть действие, чей гейт спрашивает
-- пообъектное отношение этого класса на типе ресурса. У ресурса `role` модуля
-- `iam` таким действием не является ни одно:
--
--   RoleService/Get            required_relation пуст (полоса `scope_filtered`)
--   RoleService/List           required_relation пуст (полоса `scope_filtered`)
--   RoleService/Update         v_update @ iam_role
--   RoleService/Delete         v_delete @ iam_role
--   RoleService/ListOperations v_list   @ iam_role
--
-- Чтение роли сужается НА ДАННЫХ — обработчик спрашивает `viewer ∪ v_list` по
-- идентификаторам страницы и по одной читаемой роли, — поэтому `v_get` на
-- `iam_role` не спрашивает НИ ОДНА запись каталога прав края. Замер обеими
-- сторонами: записей каталога со `scope_extractor.object_type = 'iam_role'` —
-- три (`Delete`, `Update`, `ListOperations`), из них с `required_relation =
-- 'v_get'` — НОЛЬ; записей с `required_relation = 'v_get'` во всём каталоге —
-- двадцать семь, и `iam_role` среди их типов нет.
--
-- Две живые роли этот класс называли:
--
--   iam.role.edit  verbs [get list update]
--   iam.role.view  verbs [list get]
--
-- То есть роль ОБЪЯВЛЯЕТ право, которого платформа не исполняет ни при каком
-- входе. Это не расширение доступа — отказ приходит fail-closed, — а обещание,
-- за которым ничего нет: пустое соединение неотличимо от честного «права нет», и
-- обнаруживают такое позже всего, в чужой отладке.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ЭТО НИЧЕГО НЕ ОТНИМАЕТ
--
-- Видимость роли даёт `v_list`, а не `v_get`: обе полосы чтения — и страница
-- (`RoleService/List`), и единичное чтение (`RoleService/Get`) — спрашивают
-- ОДИН вопрос `viewer ∪ v_list`. Он остаётся в обоих правилах. `v_update`
-- остаётся у `iam.role.edit`. Снимается ровно тот класс, по которому не
-- эмитировалось ни одного читаемого кортежа за всё время его жизни: кортеж
-- писался, вопрос по нему не задавался ни разу.
--
-- Довод, которого не даёт формулировка «снять как никогда не действовавшее»: мы
-- не отнимаем. Ни у одной из двух ролей не отпадает ни одна полоса доступа —
-- отпадает второе имя того, чего этим правилом не выдавалось.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ПРЕДИКАТ ЗДЕСЬ — СПИСОК ИЗ ДВУХ, А НЕ КЛАСС; И ЧЕМ КЛАСС ДЕРЖИТСЯ
--
-- Соседняя миграция 20260901231022 снимала глагол ПРЕДИКАТОМ («глагола нет в
-- каталоге»), и это было верно: её различитель — таблица `kacho_iam.catalog_verb`,
-- то есть предмет, лежащий в этой же базе.
--
-- Здесь различитель ЛЕЖИТ ВНЕ БАЗЫ. «Есть ли у действия гейт и какое отношение
-- он спрашивает» знает каталог прав КРАЯ — встроенный
-- gateway/internal/middleware/embed/permission_catalog.json, — и в схеме iam его
-- нет ни одной строкой. Воспроизвести его здесь значило бы завести ВТОРОЙ
-- словарь, который разойдётся с первым молча; ровно этот довод записан в
-- 20260901231022 про список из трёх.
--
-- Поэтому список чинит ЭКЗЕМПЛЯРЫ, а класс держит ГЕЙТ, у которого нужный
-- словарь есть: разбор манифеста (`make -C services/iam module-manifest-check`,
-- стадия «правила ролей») отвергает всякое правило роли, чей класс не покрывает
-- ни одного пригодного действия, и называет роль, ресурс и класс поимённо. Он
-- судит роли, ОБЪЯВЛЕННЫЕ манифестом; тем же изменением, что и эта миграция,
-- манифест iam объявляет все девятнадцать своих ролей, а гейт паритета
-- (`go test ./services/iam/internal/moduleroleparity/`) требует, чтобы живая
-- строка и объявление совпадали. Вместе они закрывают обе стороны: новое
-- правило с пустым классом не пройдёт разбор, новая живая строка без объявления
-- не пройдёт паритет.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧЕГО МИГРАЦИЯ НЕ ТРОГАЕТ, И ЭТО РЕШЕНИЯ, А НЕ ПРОПУСКИ
--
--   * `roles.permissions` — они говорят ДРУГИМ словарём (действия каталога прав,
--     а не пообъектные отношения) и уже сегодня расходятся с правилами:
--     у `iam.role.edit` там `[iam.role.*.update]`, у `iam.role.view` —
--     `[iam.role.*.read, iam.role.*.list, iam.role.*.get]`. Это тот же класс на
--     ВТОРОЙ поверхности, с другим владельцем и другим предикатом; он заведён
--     задачей продукта kacho#1827 и здесь не чинится — смешение сделало бы
--     вердикт непрослеживаемым (тот же довод и та же граница, что у 20260901231022);
--   * `roles.id` / `roles.name` / `roles.description` — выведены из имени и стоят
--     в уже выданных привязках; менять их значило бы завести новые роли и
--     осиротить выдачи;
--   * `kacho_iam.role_rule_selectors` — отпечаток правила считается в Go
--     (`Rule.Fingerprint`), в SQL его не воспроизвести; досев на старте снимает
--     строку со старым отпечатком как отсутствующую в текущем наборе. Писать
--     сюда данные значило бы завести второе место, знающее соответствие;
--   * отношение `v_get` на типе `iam_role` — оно остаётся объявленным моделью, и
--     это ОТДЕЛЬНЫЙ предмет: читателя у него нет ни одного, но снятие отношения
--     меняет каноническую модель, раздел `resources` манифеста и посев
--     `kacho_iam.catalog_verb`. Здесь снимается ОБЕЩАНИЕ роли, а не отношение
--     типа.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ПРОЕКЦИЮ СНИМАЕМ ЯВНО
--
-- `role_rule_ref` — проекция ОБЪЯВЛЕННЫХ сегментов, и её пишет Go
-- (`role_repo.ReplaceRuleRefs`), а системная роль этим путём не проходит
-- никогда: её заводит сырой SQL миграции. Строка, чьего класса правило больше не
-- называет, утверждала бы, что объявление живо, когда его нет, — и была бы
-- референтом ключа, из-за которого сегмент считается объявленным. Снимаем здесь.
--
-- `role_verb` — проекция вердикта, её досевает старт (снимок «снять всё,
-- положить текущее»). На базе, поднятой ТОЛЬКО миграциями, строк этих ролей ноль,
-- поэтому оператор ниже там ничего не удалит — и это не делает его лишним: на
-- базе, где iam уже стартовал, строка `(роль, iam_role, get)` существует, и до
-- следующего старта её читал бы вердикт. Выведенное состояние не должно зависеть
-- от того, когда служба перезапустится.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- МЕТКА ВРЕМЕНИ БОЛЬШЕ СТАРШЕЙ ПРИМЕНЁННОЙ — СВЕРЕНО ЗНАЧЕНИЕМ
--
-- Старшая метка в каталоге на день заведения — 20260902174501; эта — 20260902180800,
-- то есть строго больше. Сверка сделана значением, а не «часы идут вперёд»:
-- метки в этом каталоге ставятся по местным часам, и `date -u` в тот же момент
-- дал бы 20260902150800 — число МЕНЬШЕ старшей применённой, при котором мигратор
-- существующей базы получил бы пропущенную версию.
--
-- ИДЕМПОТЕНТНА. Оператор правил снимает класс, которого после первого прогона уже
-- нет; оба удаления ключуются на том же классе. Повторное применение не меняет
-- ничего. Аддитивна к истории: ни одна применённая миграция не правится (запрет #5).

-- +goose Up
-- +goose StatementBegin

-- (1) Правило. Снимается ИМЕННО класс, а не переписывается правило целиком:
--     литерал был бы вторым местом, объявляющим содержание правила, и молча
--     затёр бы всякое расхождение живой строки с тем, что здесь написано, —
--     то есть спрятал бы ровно то, что сверка манифеста обязана найти.
--     Порядок классов сохраняется (`ORDER BY` по порядковому номеру элемента):
--     `verbs` — упорядоченное поле хранимой формы, и объявление манифеста
--     сверяется с ним побайтово.
UPDATE kacho_iam.roles AS r
   SET rules = sub.rules
  FROM (
    SELECT r2.id AS id,
           jsonb_agg(
             CASE
               WHEN e.rule ->> 'module' = 'iam'
                AND e.rule -> 'resources' @> '["role"]'::jsonb
               THEN jsonb_set(e.rule, '{verbs}',
                      (SELECT coalesce(jsonb_agg(v.val ORDER BY v.ord), '[]'::jsonb)
                         FROM jsonb_array_elements_text(e.rule -> 'verbs')
                              WITH ORDINALITY AS v(val, ord)
                        WHERE v.val <> 'get'))
               ELSE e.rule
             END
             ORDER BY e.ord) AS rules
      FROM kacho_iam.roles AS r2,
           LATERAL jsonb_array_elements(r2.rules) WITH ORDINALITY AS e(rule, ord)
     WHERE r2.id IN ('rol' || substr(md5('iam.role.edit'), 1, 17),
                     'rol' || substr(md5('iam.role.view'), 1, 17))
     GROUP BY r2.id) AS sub
 WHERE r.id = sub.id;

-- (2) Проекция объявленных сегментов: строка снимается вместе со своим предметом.
DELETE FROM kacho_iam.role_rule_ref
 WHERE module = 'iam' AND resource = 'role' AND verb = 'get'
   AND role_id IN ('rol' || substr(md5('iam.role.edit'), 1, 17),
                   'rol' || substr(md5('iam.role.view'), 1, 17));

-- (3) Проекция вердикта: на базе, поднятой только миграциями, строк нет; на
--     стартовавшей — есть, и до следующего досева их читал бы вердикт.
DELETE FROM kacho_iam.role_verb
 WHERE object_type = 'iam_role' AND verb = 'get'
   AND role_id IN ('rol' || substr(md5('iam.role.edit'), 1, 17),
                   'rol' || substr(md5('iam.role.view'), 1, 17));

-- +goose StatementEnd

-- +goose StatementBegin
DO $$
DECLARE
    edit_id    text := 'rol' || substr(md5('iam.role.edit'), 1, 17);
    view_id    text := 'rol' || substr(md5('iam.role.view'), 1, 17);
    edit_verbs jsonb;
    view_verbs jsonb;
    empty_rule text;
    refs_left  bigint;
    refs_total bigint;
BEGIN
    -- ПРЕДПОСЫЛКА. Обе роли обязаны существовать: «класса нет» на отсутствующей
    -- строке получено даром, а не проверено.
    IF NOT EXISTS (SELECT 1 FROM kacho_iam.roles WHERE id = edit_id)
    OR NOT EXISTS (SELECT 1 FROM kacho_iam.roles WHERE id = view_id) THEN
        RAISE EXCEPTION
            'предпосылка нарушена: одной из двух ролей ресурса роли в базе нет (kacho#1916)';
    END IF;

    SELECT rules -> 0 -> 'verbs' INTO edit_verbs FROM kacho_iam.roles WHERE id = edit_id;
    SELECT rules -> 0 -> 'verbs' INTO view_verbs FROM kacho_iam.roles WHERE id = view_id;

    IF edit_verbs <> '["list","update"]'::jsonb THEN
        RAISE EXCEPTION 'iam.role.edit: классы после правки % , ожидались ["list","update"] (kacho#1916)',
            edit_verbs;
    END IF;
    IF view_verbs <> '["list"]'::jsonb THEN
        RAISE EXCEPTION 'iam.role.view: классы после правки % , ожидались ["list"] (kacho#1916)',
            view_verbs;
    END IF;

    -- Правило без единого класса адресует объект и не разрешает на нём ничего —
    -- то есть ровно тот класс, который эта миграция и снимает, только молча.
    SELECT string_agg(r.name, ', ') INTO empty_rule
      FROM kacho_iam.roles r, LATERAL jsonb_array_elements(r.rules) AS e(rule)
     WHERE jsonb_array_length(coalesce(e.rule -> 'verbs', '[]'::jsonb)) = 0;
    IF empty_rule IS NOT NULL THEN
        RAISE EXCEPTION 'после правки правило осталось без единого класса: % (kacho#1916)', empty_rule;
    END IF;

    SELECT count(*) INTO refs_left
      FROM kacho_iam.role_rule_ref
     WHERE module = 'iam' AND resource = 'role' AND verb = 'get';
    IF refs_left <> 0 THEN
        RAISE EXCEPTION
            'проекция объявленных сегментов ещё называет класс get на ресурсе роли: % строк (kacho#1916)',
            refs_left;
    END IF;

    SELECT count(*) INTO refs_total FROM kacho_iam.role_rule_ref;
    RAISE NOTICE 'ролей ресурса роли приведено 2 · строк проекции объявленных сегментов осталось % · из них о ресурсе роли %',
        refs_total,
        (SELECT count(*) FROM kacho_iam.role_rule_ref WHERE module = 'iam' AND resource = 'role');
END;
$$;
-- +goose StatementEnd

