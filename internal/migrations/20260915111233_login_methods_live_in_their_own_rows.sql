-- login_methods_live_in_their_own_rows — СПОСОБ ВХОДА человека и
-- ПОДТВЕРЖДЁННОСТЬ его адреса становятся хранилищем службы (фаза Ф2, часть П1,
-- задача PRO-Robotech/kacho#1268).
--
-- Санкция: одобренная Ф1
-- (`docs/engineering/acceptance/login-session-and-credentials-are-our-contract.md`,
-- ведомость §5, строка Ф2 — «строка удостоверения, строка адреса и её
-- подтверждённость») и одобренная F4d воркспейса (F4d-13…F4d-15: форма строки,
-- уникальность парой «человек, вид», конкуренция; F4d-13 — ЧАСТИЧНО, ниже).
-- Доводы здесь не пересказываются — они там; здесь только то, что нужно
-- читателю СХЕМЫ.
--
-- =============================================================================
-- ПОЧЕМУ НОВАЯ МИГРАЦИЯ, А НЕ ПРАВКА СВОДА
-- =============================================================================
-- Правка применённого файла не доезжает до базы, где он уже применён: мигратор
-- сверяет версию, а не содержимое. Базы, поднятые до этой правки, остались бы
-- без таблицы при коде, который её ждёт.
--
-- =============================================================================
-- СПОСОБ — СТРОКА СВОЕЙ ТАБЛИЦЫ
-- =============================================================================
-- Колонка в зеркале человека сделала бы второй вид способа переносом каждой
-- строки; строка — правкой словаря вида (ограничение ниже), без правки строк.
--
-- Ключ — ПАРА (человек, вид). Первичный ключ и есть та уникальность, которую
-- требует F4d-14: второй способ того же вида отвергает база (23505), а не
-- проверка перед вставкой — под конкуренцией исход не зависит от порядка чтений.
--
-- Человек — `users.id`. Не внешний субъект: у приглашённого он пуст
-- (`users_invite_status_consistency`) и принадлежит поставщику. Не почта: она
-- изменяема. Способ уходит вместе с человеком каскадом — висячей строки с
-- материалом не остаётся.
--
-- Материал НЕПУСТ (23514 на пустой строке): «материала нет» выражается
-- отсутствием строки, а не пустым значением в ней. Формат материала здесь не
-- судится и отдельной колонкой не хранится — он читается из самого значения
-- (часть П2), и второе написание одного факта разошлось бы с первым.
--
-- Индекса по материалу НЕТ намеренно — никакого. Индекс копирует колонку в
-- свои страницы, а уникальный вдобавок делает каждый отказ уникальности каналом
-- выдачи: сервер кладёт значения нарушенного ключа в поле `DETAIL` ошибки и в
-- свой журнал.
--
-- F4d-13 ДЕРЖИТСЯ ЧАСТИЧНО. Сценарий требует от строки «вид способа,
-- проверочный материал, уровень доверия и состояние». Держатся: строка вместо
-- колонки, вид, материал, невыразимость исходного пароля (поля для него нет —
-- 42703) и живой близнец (строка с материалом заводится и читается). Уровень
-- доверия и состояние НЕ заведены — решение, а не пропуск: у обоих нет ни
-- производителя, ни читателя; «уровень как значение хранилища» противоречит
-- Ф1 §0.2, по которому уровень выводится из вида способа; колонка с умолчанием
-- добавляется потом без переноса строк. Носители: уровень доверия —
-- PRO-Robotech/kacho#1280 (Ф11), состояние — PRO-Robotech/kacho#1281 (Ф12).
-- Решение записано: PRO-Robotech/kacho#1268 (комментарий 5680711802).
--
-- МЕХАНИЗМОВ, исполняющихся при записи без ведома писателя, на таблице нет и
-- заводить их нельзя без решения: триггеров, правил перезаписи, политик строк,
-- ограничений сверх объявленных четырёх, доменного типа у колонки. Каждый видит
-- строку либо значение материала и может унести его туда, где у копии свой
-- срок хранения. Держит гейт схемы `internal/repo/kaname/pg`
-- `TestLoginVerifierStaysInsideTheSchema` — он же ищет копии материала во всех
-- отношениях базы и объекты, зависящие от колонки материала.
--
-- Статистика планировщика по колонке материала НЕ собирается (`SET STATISTICS
-- 0`). Анализ таблицы кладёт выборку значений колонки в `pg_statistic`, и эта
-- копия живёт до следующего анализа, переживая удаление строки. Планировщику
-- статистика по материалу не нужна: ни один запрос службы не отбирает по нему.
--
-- =============================================================================
-- ПОДТВЕРЖДЁННОСТЬ ЛЕЖИТ РЯДОМ С АДРЕСОМ И ПРИВЯЗАНА К ЕГО ЗНАЧЕНИЮ
-- =============================================================================
-- Владелец значения адреса уже есть — `users.email`. Отдельная таблица адреса
-- завела бы второе место об одном предмете. Поэтому подтверждённость — одна
-- колонка момента: NULL значит «не подтверждён», пары «признак + время» нет.
--
-- Подтверждённость есть свойство ЗНАЧЕНИЯ, а не человека. Смена почты на чужую,
-- сохранившая отметку, выглядела бы подтверждённой — поэтому снимает её БАЗА,
-- в том же операторе, что меняет адрес, каким бы путём он ни менялся (правка,
-- конфликт вставки, посев). Писателей почты у службы больше одного, и
-- дисциплина каждого разошлась бы.
--
-- Сравнение ПОБАЙТОВОЕ: смена одного регистра тоже снимает отметку — доказано
-- было владение ТЕМ значением. Уникальность адреса судится `lower(email)`; это
-- другой вопрос («чей адрес»), и совпадать с этим («что доказано») он не обязан.
--
-- Отметку нельзя принести вместе с новым адресом одним оператором: новое
-- значение ещё никто не подтверждал. Обратный порядок — подтверждение
-- записывается ПОСЛЕ смены — закрывает сверка значения в операторе записи
-- отметки (адаптер `LoginMethodRepo.MarkEmailVerified`), а не этот триггер.

-- +goose Up

ALTER TABLE kaname.users ADD COLUMN email_verified_at timestamp with time zone;

COMMENT ON COLUMN kaname.users.email_verified_at IS
  'Момент подтверждения ТЕКУЩЕГО значения email. NULL — не подтверждён. Снимается базой при любой смене email (триггер users_email_change_drops_verification).';

-- +goose StatementBegin
CREATE FUNCTION kaname.users_email_change_drops_verification() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  NEW.email_verified_at := NULL;
  RETURN NEW;
END;
$$;
-- +goose StatementEnd

-- Условие на ЗНАЧЕНИЕ, а не на список колонок оператора: `UPDATE OF email`
-- срабатывал бы на переписи тем же значением и молчал бы на смене, внесённой
-- соседним триггером.
--
-- ГРАНИЦА, НАЗВАННАЯ ВСЛУХ. Триггеры одного вида исполняются в порядке имён, и
-- условие WHEN вычисляется над строкой, какой её оставили стоящие ДО нашего.
-- Соседний BEFORE UPDATE-триггер на `users`, чьё имя сортируется ПОСЛЕ нашего и
-- который меняет адрес, сменит его уже после проверки — отметка переживёт
-- смену. Сегодня таких соседей ноль; соседа, заведённого завтра, называет проба
-- `TestIntegration_AddressVerificationTriggerHasNoLaterNeighbour`, и он требует
-- решения: доказать, что адреса он не трогает, либо переименовать наш.
CREATE TRIGGER users_email_change_drops_verification
  BEFORE UPDATE ON kaname.users
  FOR EACH ROW WHEN (OLD.email IS DISTINCT FROM NEW.email)
  EXECUTE FUNCTION kaname.users_email_change_drops_verification();

CREATE TABLE kaname.user_login_methods (
    user_id    text NOT NULL,
    kind       text NOT NULL,
    verifier   text NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT user_login_methods_pkey PRIMARY KEY (user_id, kind),
    CONSTRAINT user_login_methods_user_fk FOREIGN KEY (user_id)
        REFERENCES kaname.users(id) ON DELETE CASCADE,
    -- Словарь видов ЗАКРЫТ и совпадает с `domain.LoginMethodKinds()`.
    CONSTRAINT user_login_methods_kind_check CHECK ((kind = ANY (ARRAY['password'::text]))),
    CONSTRAINT user_login_methods_verifier_check CHECK ((verifier <> ''::text))
);

COMMENT ON TABLE kaname.user_login_methods IS
  'Способ входа человека: строка на пару (человек, вид). verifier — СЕКРЕТ (хеш пароля): копий в других отношениях нет, механизмов, исполняющихся при записи без ведома писателя, на таблице нет, статистика планировщика по нему не собирается.';

ALTER TABLE kaname.user_login_methods ALTER COLUMN verifier SET STATISTICS 0;

-- +goose Down

-- Откат ОТКАЗЫВАЕТСЯ уничтожать то, что не восстанавливается ниоткуда, кроме
-- этих двух мест. Та же мера, что у стража секретов вида SECRET в откате свода.
--
--   - МАТЕРИАЛ способа входа. Перенесённый хеш после снятия прежнего поставщика
--     взять повторно негде: удалённая строка означает, что человек потерял
--     вход, и вернуть его можно только сбросом — тем, от которого Р1 Ф1
--     отказывается как от способа миграции.
--   - ОТМЕТКИ ПОДТВЕРЖДЕНИЯ адреса. После снятия прежнего поставщика
--     доказательство владения адресом лежит только в этой колонке. Её снос
--     возвращает каждого отмеченного к неподтверждённому адресу и закрывает ему
--     действия, которые неподтверждённому закрыты (Ф1-06). Вернуть отметку
--     можно только повторным подтверждением КАЖДЫМ — та же массовая процедура,
--     что и сброс, и тот же отказ от неё. Поэтому отметки стерегутся наравне с
--     материалом: две отметки при нуле способов — тоже отказ.
--
-- ЗАМОК ДО ПОДСЧЁТА. Подсчёт и снос обязаны видеть ОДНО состояние таблиц. Без
-- замка писатель, зафиксировавший строку между подсчётом и сносом, её теряет:
-- под READ COMMITTED подсчёт незафиксированной строки не видит, а снос
-- дожидается её фиксации и уничтожает то, чего подсчёт не видел, — и откат
-- возвращает успех. Это проверка-затем-действие, запрещённая ban #10. Поэтому
-- первый оператор отката запирает обе таблицы: замок ждёт открытых писателей,
-- а подсчёт, идущий после, видит всё, что они зафиксировали. Замок взят до
-- первого запроса транзакции, поэтому и под REPEATABLE READ снимок подсчёта
-- берётся уже после него.
--
-- Режим — ACCESS EXCLUSIVE, тот, которого всё равно требуют снос таблицы,
-- снятие триггера и колонки ниже. SHARE тоже закрыл бы вставку между подсчётом
-- и сносом, но оставил бы повышение замка до ACCESS EXCLUSIVE на месте сноса —
-- окно, в котором второй откат либо читатель, собравшийся писать, взаимно
-- блокируются с этим. Взятый сразу, сильнейший замок повышения не требует.
-- Цена — таблицы недоступны на время подсчёта; снос делает их недоступными в
-- любом случае. Порядок — как у сноса ниже: сперва таблица способов.
--
-- Держит `TestIntegration_LoginMethodRollbackDoesNotRaceItsWriter`: писатель
-- фиксирует, ПОКА откат ждёт его замка, — откат обязан отказать.
LOCK TABLE kaname.user_login_methods, kaname.users IN ACCESS EXCLUSIVE MODE;

-- +goose StatementBegin
DO $$
DECLARE
  v_rows  bigint;
  v_marks bigint;
BEGIN
  SELECT count(*) INTO v_rows FROM kaname.user_login_methods;
  SELECT count(*) INTO v_marks FROM kaname.users WHERE email_verified_at IS NOT NULL;
  -- Всё существенное — в основном сообщении: мигратор доносит до оператора
  -- только его. Оба числа печатаются всегда, включая ноль: отказ, назвавший
  -- одно, не сказал бы, что делать со вторым.
  IF v_rows > 0 OR v_marks > 0 THEN
    RAISE EXCEPTION 'refusing to roll back: kaname.user_login_methods holds % login verifier row(s) and kaname.users.email_verified_at holds % address verification mark(s); a rollback would destroy them irreversibly (a lost verifier is recoverable only by a reset of every holder, a lost mark only by every holder verifying again). WAY OUT: if losing them is the intent, delete those rows and clear those marks deliberately first; the rollback is safe exactly when both counts are 0', v_rows, v_marks
      USING ERRCODE = 'restrict_violation';
  END IF;
END;
$$;
-- +goose StatementEnd

