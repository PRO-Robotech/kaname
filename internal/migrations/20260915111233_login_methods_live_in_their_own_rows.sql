-- login_methods_live_in_their_own_rows — СПОСОБ ВХОДА человека и
-- ПОДТВЕРЖДЁННОСТЬ его адреса становятся хранилищем службы (фаза Ф2, часть П1,
-- задача PRO-Robotech/kacho#1268).
--
-- Санкция: одобренная Ф1
-- (`docs/engineering/acceptance/login-session-and-credentials-are-our-contract.md`,
-- ведомость §5, строка Ф2 — «строка удостоверения, строка адреса и её
-- подтверждённость») и одобренная F4d воркспейса (F4d-13…F4d-15: форма строки,
-- уникальность парой «человек, вид», конкуренция). Доводы здесь не
-- пересказываются — они там; здесь только то, что нужно читателю СХЕМЫ.
--
-- =============================================================================
-- ПОЧЕМУ НОВАЯ МИГРАЦИЯ, А НЕ ПРАВКА СВОДА
-- =============================================================================
-- Правка применённого файла не доезжает до базы, где он уже применён: мигратор
-- сверяет версию, а не содержимое. Базы, поднятые до этой правки, остались бы
-- без таблицы при коде, который её ждёт.
--
-- =============================================================================
-- СПОСОБ — СТРОКА СВОЕЙ ТАБЛИЦЫ
-- =============================================================================
-- Колонка в зеркале человека сделала бы второй вид способа переносом каждой
-- строки; строка — правкой словаря вида (ограничение ниже), без правки строк.
--
-- Ключ — ПАРА (человек, вид). Первичный ключ и есть та уникальность, которую
-- требует F4d-14: второй способ того же вида отвергает база (23505), а не
-- проверка перед вставкой — под конкуренцией исход не зависит от порядка чтений.
--
-- Человек — `users.id`. Не внешний субъект: у приглашённого он пуст
-- (`users_invite_status_consistency`) и принадлежит поставщику. Не почта: она
-- изменяема. Способ уходит вместе с человеком каскадом — висячей строки с
-- материалом не остаётся.
--
-- Материал НЕПУСТ (23514 на пустой строке): «материала нет» выражается
-- отсутствием строки, а не пустым значением в ней. Формат материала здесь не
-- судится и отдельной колонкой не хранится — он читается из самого значения
-- (часть П2), и второе написание одного факта разошлось бы с первым.
--
-- Уникального индекса по материалу НЕТ намеренно. Сервер кладёт значения
-- нарушенного ключа в поле `DETAIL` ошибки и в свой журнал; ключ по материалу
-- делал бы каждый отказ уникальности каналом его выдачи.
--
-- Уровень доверия и состояние способа НЕ заведены — решение, а не пропуск:
-- уровень есть функция вида (правило «вид → уровень» — фаза Ф11, Ф1 §0.2 его не
-- санкционирует), состояние сегодня одно и выражается существованием строки.
--
-- ТРИГГЕРОВ на таблице нет и заводить их нельзя без решения: триггер видит
-- строку ЦЕЛИКОМ и исполняется без ведома писателя. Держит гейт схемы
-- `internal/repo/kaname/pg` `TestLoginVerifierStaysInsideTheSchema`.
--
-- =============================================================================
-- ПОДТВЕРЖДЁННОСТЬ ЛЕЖИТ РЯДОМ С АДРЕСОМ И ПРИВЯЗАНА К ЕГО ЗНАЧЕНИЮ
-- =============================================================================
-- Владелец значения адреса уже есть — `users.email`. Отдельная таблица адреса
-- завела бы второе место об одном предмете. Поэтому подтверждённость — одна
-- колонка момента: NULL значит «не подтверждён», пары «признак + время» нет.
--
-- Подтверждённость есть свойство ЗНАЧЕНИЯ, а не человека. Смена почты на чужую,
-- сохранившая отметку, выглядела бы подтверждённой — поэтому снимает её БАЗА,
-- в том же операторе, что меняет адрес, каким бы путём он ни менялся (правка,
-- конфликт вставки, посев). Писателей почты у службы больше одного, и
-- дисциплина каждого разошлась бы.
--
-- Сравнение ПОБАЙТОВОЕ: смена одного регистра тоже снимает отметку — доказано
-- было владение ТЕМ значением. Уникальность адреса судится `lower(email)`; это
-- другой вопрос («чей адрес»), и совпадать с этим («что доказано») он не обязан.
--
-- Отметку нельзя принести вместе с новым адресом одним оператором: новое
-- значение ещё никто не подтверждал. Обратный порядок — подтверждение
-- записывается ПОСЛЕ смены — закрывает сверка значения в операторе записи
-- отметки (адаптер `LoginMethodRepo.MarkEmailVerified`), а не этот триггер.

-- +goose Up

ALTER TABLE kaname.users ADD COLUMN email_verified_at timestamp with time zone;

COMMENT ON COLUMN kaname.users.email_verified_at IS
  'Момент подтверждения ТЕКУЩЕГО значения email. NULL — не подтверждён. Снимается базой при любой смене email (триггер users_email_change_drops_verification).';

-- +goose StatementBegin
CREATE FUNCTION kaname.users_email_change_drops_verification() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  NEW.email_verified_at := NULL;
  RETURN NEW;
END;
$$;
-- +goose StatementEnd

-- Условие на ЗНАЧЕНИЕ, а не на список колонок оператора: `UPDATE OF email`
-- срабатывал бы на переписи тем же значением и молчал бы на смене, внесённой
-- соседним триггером.
CREATE TRIGGER users_email_change_drops_verification
  BEFORE UPDATE ON kaname.users
  FOR EACH ROW WHEN (OLD.email IS DISTINCT FROM NEW.email)
  EXECUTE FUNCTION kaname.users_email_change_drops_verification();

CREATE TABLE kaname.user_login_methods (
    user_id    text NOT NULL,
    kind       text NOT NULL,
    verifier   text NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT user_login_methods_pkey PRIMARY KEY (user_id, kind),
    CONSTRAINT user_login_methods_user_fk FOREIGN KEY (user_id)
        REFERENCES kaname.users(id) ON DELETE CASCADE,
    -- Словарь видов ЗАКРЫТ и совпадает с `domain.LoginMethodKinds()`.
    CONSTRAINT user_login_methods_kind_check CHECK ((kind = ANY (ARRAY['password'::text]))),
    CONSTRAINT user_login_methods_verifier_check CHECK ((verifier <> ''::text))
);

COMMENT ON TABLE kaname.user_login_methods IS
  'Способ входа человека: строка на пару (человек, вид). verifier — СЕКРЕТ (хеш пароля): не копируется ни в какую другую таблицу, триггеров на таблице нет.';

-- +goose Down

-- Откат ОТКАЗЫВАЕТСЯ уничтожать материал. Перенесённый хеш после снятия
-- прежнего поставщика взять повторно негде: удалённая строка означает, что
-- человек потерял вход, и вернуть его можно только сбросом — тем, от которого
-- Р1 Ф1 отказывается как от способа миграции. Та же мера, что у стража секретов
-- вида SECRET в откате свода.
-- +goose StatementBegin
DO $$
DECLARE
  v_rows bigint;
BEGIN
  SELECT count(*) INTO v_rows FROM kaname.user_login_methods;
  IF v_rows > 0 THEN
    RAISE EXCEPTION 'refusing to roll back: kaname.user_login_methods holds % login verifier row(s); a rollback would destroy them irreversibly', v_rows
      USING ERRCODE = 'restrict_violation';
  END IF;
END;
$$;
-- +goose StatementEnd

DROP TABLE kaname.user_login_methods;
DROP TRIGGER users_email_change_drops_verification ON kaname.users;
DROP FUNCTION kaname.users_email_change_drops_verification();
ALTER TABLE kaname.users DROP COLUMN email_verified_at;
