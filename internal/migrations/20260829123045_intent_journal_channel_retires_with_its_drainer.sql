-- дренажом: будить им некого (kacho#1436).
--
-- ───────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Триггер `fga_outbox_notify_trigger` шлёт `pg_notify('kacho_iam_fga_outbox',
-- NEW.id)` на КАЖДУЮ вставку в `kacho_iam.fga_outbox`, а вставка идёт на пути
-- мутации: каждая выдача и каждое снятие права. Слушателей — ноль.
--
-- Уведомление такого рода существует ради ОДНОГО: разбудить дренаж очереди,
-- чтобы он не ждал следующего тика опроса. Дренаж, применявший строки этого
-- журнала к внешнему движку отношений, снят ВМЕСТЕ С САМИМ ДВИЖКОМ (стадия S6
-- эпика #747), и это сказано в составе сервиса прямо: «ДРЕНАЖА ЖУРНАЛА
-- НАМЕРЕНИЙ ЗДЕСЬ НЕТ — снят вместе с адресатом».
--
-- ───────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ СНИМАЕТСЯ, А НЕ ЖДЁТ БУДУЩЕГО СЛУШАТЕЛЯ
--
-- Единственный читатель журнала сегодня — триггер свёртки
-- `relation_fact_follows_journal` (миграция 0098): он складывает из строки
-- прямой факт, из которого форма собирает вердикт о доступе. Свёртка
-- СИНХРОННА — `AFTER INSERT FOR EACH ROW`, в той же транзакции, — то есть к
-- моменту, когда уведомление могло бы кого-то разбудить, работа уже сделана.
-- Будить нечего не «пока», а by construction: пробуждение ускоряет то, чего не
-- происходит.
--
-- Держать канал «под будущий дренаж» — ровно тот класс, ради закрытия которого
-- заведены #755, #795 и #1398: механизм объявлен, производителя эффекта у него
-- нет. Появится внешний адресат намерений — он придёт своей под-фазой и своей
-- приёмкой и приведёт своё пробуждение ВМЕСТЕ с дренажом, который оно будит.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ЧТО НЕ СНИМАЕТСЯ И ПОЧЕМУ ЭТО НАДО СКАЗАТЬ ВСЛУХ
--
--   остаётся   таблица `kacho_iam.fga_outbox` целиком, со всеми строками и
--              всеми писателями;
--   остаётся   триггер свёртки `relation_fact_follows_journal` и его функция.
--
-- Снять журнал вместе с уведомлением значило бы обесточить источник
-- собственного вердикта — и обесточить МОЛЧА: таблица осталась бы на месте,
-- запросы продолжили бы исполняться, а ответы поехали бы в сторону отказа.
-- Регрессия на это утверждает не только отсутствие канала, но и целость
-- журнала и свёртки:
-- services/iam/internal/migrations/notify_channel_intent_journal_integration_test.go
--
-- ───────────────────────────────────────────────────────────────────────────
-- ПОРЯДОК И ОБРАТИМОСТЬ
--
-- Снимается только ОБЪЯВЛЕНИЕ (триггер и его функция). Данных у канала нет:
-- уведомление не хранится, обратного заполнения не требуется, строки таблицы не
-- трогаются — поэтому Down восстанавливает ровно снятое, включая уровень
-- срабатывания (FOR EACH ROW) и RETURN NEW.
--
-- Порядок срабатывания триггеров таблицы правкой не затрагивается: оставшийся
-- `relation_fact_follows_journal` — единственный AFTER INSERT, и снятие соседа
-- порядок одного не меняет.

-- +goose Up

DROP TRIGGER IF EXISTS fga_outbox_notify_trigger ON kacho_iam.fga_outbox;
DROP FUNCTION IF EXISTS kacho_iam.fga_outbox_notify();

-- +goose Down

-- +goose StatementBegin
CREATE FUNCTION kacho_iam.fga_outbox_notify() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    PERFORM pg_notify('kacho_iam_fga_outbox', NEW.id::text);
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER fga_outbox_notify_trigger
    AFTER INSERT ON kacho_iam.fga_outbox
    FOR EACH ROW EXECUTE FUNCTION kacho_iam.fga_outbox_notify();
