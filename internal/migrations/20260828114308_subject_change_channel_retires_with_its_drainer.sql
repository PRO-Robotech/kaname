-- subject_change_channel_retires_with_its_drainer — канал уведомления снимается
-- вместе со своим триггером, потому что слушателя у него больше нет и построить
-- его нельзя.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Триггер `subject_change_outbox_notify_trigger` на `kacho_iam.subject_change_outbox`
-- шлёт `pg_notify('kacho_iam_subject_outbox_added', NEW.id::text)` на каждую вставку.
-- Производитель работает. Слушателей — НОЛЬ.
--
-- Перепись, по которой это установлено, судит УЗЕЛ-ЛИТЕРАЛ, а не подстроку, и
-- различие здесь несущее: текстовый поиск имени канала по не-тестовым файлам Go даёт
-- ноль, а у соседнего канала — два, и оба вхождения соседа суть КОММЕНТАРИИ. То есть
-- предикат по тексту на этом же вопросе уже ошибается, только в другую сторону.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ДВУХ ПРЕЖНИХ СНЯТИЙ — основание СВОЁ
--
-- У `session_revoked` (755001) слушателя не было НИКОГДА: его замышляли на крае, а
-- край слушать не может by construction. У `audit_event` (795001) не было дренажа,
-- который канал будил бы.
--
-- Здесь слушатель БЫЛ и снят РЕШЕНИЕМ. Им был дренаж `subject_change_outbox`,
-- дозванивавшийся до края и гасивший его кэш решений. Ребро снято целиком (задача
-- #1024): оно шло из листа обратно к потребителю, а адрес края был у владельца прав
-- ОБЯЗАТЕЛЬНОЙ ручкой, из-за чего iam не поднимался там, где края нет вовсе.
-- Направление развёрнуто: соединение открывает потребитель.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ СНИМАЕТСЯ, А НЕ ДОСТРАИВАЕТСЯ
--
-- Слушателем мог бы стать либо потребитель, либо кто-то внутри владельца прав.
-- Ни того, ни другого нет и быть не может:
--
--   * ПОТРЕБИТЕЛЬ (край) слушать не может by construction — драйвера Postgres у него
--     нет, а прямое чтение базы iam это ban #8 (database-per-service). Ровно этот
--     довод записан в 755001, и с тех пор он только окреп.
--
--   * ВНУТРИ ВЛАДЕЛЬЦА будить нечего. Уведомление такого рода существует ради одного:
--     разбудить дренаж очереди, чтобы он не ждал следующего тика опроса. Дренаж снят,
--     а журнал остался и переменил природу: из очереди с доставкой он стал ЖУРНАЛОМ С
--     КУРСОРОМ, который потребитель читает сам (`InternalIAMService.PollSubjectChanges`,
--     выборка по `id > $1`). У чтения курсором пробуждения не бывает: читатель — чужой
--     процесс в чужой сети, и разбудить его можно только ответом на его же вызов.
--
-- Третий исход — «оставить и объявить» — рассмотрен и отвергнут: он законен, только
-- когда назван БУДУЩИЙ потребитель и предикат его появления. Здесь потребитель уже
-- назван, он существует, и он читает курсором. Держать рядом уведомление «под него»
-- значило бы держать обещание, за которое никто не отвечает.
--
-- Отдельно, чтобы это не пришлось выводить заново: общий сервер потока изменений
-- (`pkg/subscription`) слушателем этого канала стать не может тоже. Он живёт у
-- ВЛАДЕЛЬЦА своей схемы и слушает СВОЙ журнал; у потребителя чужой базы нет ровно по
-- тому же ban #8. Отзыв прав доходит до открытого потока перепросом
-- (`pkg/subjectchange`), а не уведомлением.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- УТВЕРЖДЕНИЕ 755001 О СЛУШАТЕЛЕ — ИСТОРИЧЕСКИ ВЕРНОЕ, И СНИМАЕТСЯ ЗДЕСЬ
--
-- Миграция `755001_session_revoked_channel_retires_with_its_listener.sql` обосновывает
-- своё снятие ссылкой на этот канал и говорит о нём: «у которого слушатель есть». В день
-- своей записи это было ВЕРНО — дренаж существовал и был провязан. Сегодня ложно.
--
-- Править её нельзя (запрет #5: применённую миграцию не редактируют), да и не нужно:
-- она свидетельство о состоянии на свою дату, а не действующее утверждение. Поэтому
-- утверждение снимается ЗДЕСЬ, и здесь же названо, чем оно было: доводом, верным на
-- 755001 и пережившим свой предмет ровно на одну задачу (#1024).
--
-- Читателю 755001 это видно не будет — он читает применённый файл и не знает о новом.
-- Поэтому вторая половина снятия лежит не в SQL, а в документах, которые ЧИТАЮТ:
-- реестр отступлений iam и страница реляционного вердикта правятся тем же изменением.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО НЕ СНИМАЕТСЯ И ПОЧЕМУ
--
-- Таблица `kacho_iam.subject_change_outbox` остаётся ЦЕЛИКОМ, со всеми строками и
-- всеми писателями: она и есть то, что читает потребитель. Снимается ровно объявление
-- уведомления. Строки не трогаются, обратного заполнения не требуется, поэтому в
-- ведомости дропов (`dropguard.json`) этой миграции нет и быть не должно: та ведомость
-- судит `DROP TABLE` и число уничтоженных строк, а здесь уничтоженных строк НОЛЬ —
-- измеренный, а не объявленный: миграция не содержит ни одного `DROP TABLE`.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОРЯДОК
--
-- Снимается только ОБЪЯВЛЕНИЕ (триггер и его функция). Данных у канала нет:
-- уведомление не хранится, поэтому обратимость тривиальна, и Down восстанавливает
-- ровно снятое — включая уровень срабатывания (FOR EACH ROW) и `RETURN NEW`.
--
-- Регрессия: services/iam/internal/migrations/notify_channel_has_a_listener_integration_test.go
-- — `TestIntegration_SubjectChangeChannelHasNoProducerLeft` утверждает по ЖИВОЙ схеме,
-- что производителя больше нет, а журнал цел; `TestIntegration_EveryProducedNotifyChannelIsNamedByAConsumer`
-- спрашивает ОБЕ стороны разом — схему о производителе и дерево о потребителе, — и
-- потому ловит класс, а не этот экземпляр.

-- +goose Up

DROP TRIGGER IF EXISTS subject_change_outbox_notify_trigger ON kacho_iam.subject_change_outbox;
DROP FUNCTION IF EXISTS kacho_iam.subject_change_outbox_notify();

-- +goose Down

-- +goose StatementBegin
CREATE FUNCTION kacho_iam.subject_change_outbox_notify() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    PERFORM pg_notify('kacho_iam_subject_outbox_added', NEW.id::text);
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER subject_change_outbox_notify_trigger
    AFTER INSERT ON kacho_iam.subject_change_outbox
    FOR EACH ROW EXECUTE FUNCTION kacho_iam.subject_change_outbox_notify();
