-- +goose Up
-- Таблица версии модели, ЗАГРУЖЕННОЙ во внешний движок прав, снимается: движка
-- больше нет, а загружать модель некуда.
--
-- Задача `PRO-Robotech/kacho#1717`.
--
-- ЧТО СНИМАЕТСЯ. `kacho_iam.fga_model_version` заведена базовой схемой (0001):
-- суррогатный ключ `id` с последовательностью, идентификатор модели у движка
-- (`authorization_model_id`), отпечаток текста модели (`dsl_sha256`), отметка
-- применения и кем применено. Вместе с таблицей уходят три объекта, ей
-- принадлежащих: последовательность `fga_model_version_id_seq` (объявлена
-- `OWNED BY` колонкой и потому снимается вместе с ней), первичный ключ
-- `fga_model_version_pkey` и уникальный ключ по идентификатору модели
-- `fga_model_version_authorization_model_id_key`. Четыре объекта схемы, одно
-- утверждение.
--
-- ЧТО ЭТО НЕ ЗНАЧИТ — сказано первым, потому что имя таблицы читается как
-- версионирование модели прав, и следующий читатель обязан не вывести обратного.
-- Язык, которым модель отношений записана, движок ПЕРЕЖИЛ: его разбирает теперь
-- сама служба, и текст модели остаётся источником истины формы. Снимается не
-- версионирование модели, а отметка о ЗАГРУЗКЕ её в чужое хранилище — величина,
-- у которой нет ни производителя, ни потребителя с тех пор, как хранилище ушло.
--
-- ЧЕМ ЭТА ТАБЛИЦА ОПАСНЕЕ ОБЫКНОВЕННОЙ МЁРТВОЙ. Мёртвая таблица не обещает
-- ничего; эта несёт полную форму журнала выкаток модели — идентификатор версии,
-- отпечаток текста, время и автора применения. Читатель схемы заключает из неё,
-- что смена модели прав где-то фиксируется, и дальше у него два пути, и оба
-- неверны: искать писателя, которого нет, либо завести второго — то есть завести
-- второе место об одном предмете, которое разойдётся с первым молча.
--
-- ЧТО ТЕРЯЕТСЯ. Ничего, что создал бы вызывающий: поверхности для записи строк в
-- эту таблицу не существовало ни на одном слушателе iam — строку писал внешний
-- шаг загрузки модели в движок, снятый вместе с ним. На свежей базе строк ноль
-- by construction: ни одна миграция цепочки в неё не вставляет, и это ПРОВЕРЯЕТСЯ
-- записью в `dropguard.json`, а не принимается на слово. На долгоживущем стенде,
-- поднятом до отставки движка, строки истории загрузок могли остаться; они
-- уничтожаются, и это намеренно — история загрузок в несуществующее хранилище не
-- отвечает ни на один вопрос, который сегодня можно задать.
DROP TABLE IF EXISTS kacho_iam.fga_model_version;

-- +goose Down
-- Возврат в форму базовой схемы (0001) дословно: таблица, последовательность,
-- умолчание колонки и оба ключа. Строк не восстанавливается — их писал шаг,
-- которого больше нет.
--
-- Откат возвращает и приглашение: следующий, читающий схему после него, снова
-- увидит у iam журнал выкаток модели. Решение о том, что загружать модель некуда,
-- от этого не меняется — оно записано здесь и в задаче, а не в наличии или
-- отсутствии таблицы.
CREATE TABLE kacho_iam.fga_model_version (
    id bigint NOT NULL,
    authorization_model_id text NOT NULL,
    dsl_sha256 text NOT NULL,
    applied_at timestamp with time zone DEFAULT now() NOT NULL,
    applied_by text DEFAULT 'bootstrap-job'::text NOT NULL
);

CREATE SEQUENCE kacho_iam.fga_model_version_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

ALTER SEQUENCE kacho_iam.fga_model_version_id_seq OWNED BY kacho_iam.fga_model_version.id;

ALTER TABLE ONLY kacho_iam.fga_model_version ALTER COLUMN id SET DEFAULT nextval('kacho_iam.fga_model_version_id_seq'::regclass);

ALTER TABLE ONLY kacho_iam.fga_model_version
    ADD CONSTRAINT fga_model_version_authorization_model_id_key UNIQUE (authorization_model_id);

ALTER TABLE ONLY kacho_iam.fga_model_version
    ADD CONSTRAINT fga_model_version_pkey PRIMARY KEY (id);
