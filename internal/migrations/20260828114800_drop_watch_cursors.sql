-- +goose Up
-- Ведомость позиций потока ПО ДОМЕНАМ снимается: читателя у неё нет, а форма её
-- приглашает отменить решение о том, где живёт позиция потока, — и не у одного
-- сервиса, а у платформы.
--
-- Задача `PRO-Robotech/kacho#1148`; тот же класс закрыт для compute задачей
-- `PRO-Robotech/kacho#1046`, и разбор оттуда здесь не повторяется — повторяется
-- только то, что относится к iam.
--
-- ЧТО СНИМАЕТСЯ. `kacho_iam.watch_cursors` заведена базовой схемой (0001):
-- первичный ключ `service`, рядом `last_event_id` и `updated_at`, плюс
-- `watch_cursors_service_ck`, перечисляющий три домена поимённо. Прод-читателя у
-- неё нет ни одного: перепись велась по колонкам, а не по имени таблицы, и
-- `last_event_id` встречается в дереве ровно один раз — в объявлении этой самой
-- таблицы. За всю жизнь таблицы в неё не писал никто.
--
-- ЧЕМ ЭТА ТАБЛИЦА ОПАСНЕЕ СВОИХ СЁСТЕР В vpc И nlb. Там ключ — подписчик, и
-- приглашение читается как «храни позицию на сервере этого сервиса». Здесь ключ —
-- СЕРВИС, а ограничение называет домены списком. Это выглядит не забытой
-- таблицей, а ЦЕНТРАЛЬНОЙ ведомостью позиций: iam якобы ведёт, докуда дочитал
-- каждый домен. Подобрав такую форму, следующий автор отменит решение сразу для
-- всей платформы и заодно заведёт ребро от листа обратно к доменам, которого
-- топология не допускает.
--
-- И ведомость эта не расширялась НИ РАЗУ, что видно из неё самой: ограничение
-- называет три домена (`vpc`, `compute`, `loadbalancer`), тогда как сервисов в
-- дереве семь, — `storage`, `registry`, `geo` и сам `iam` в перечень не попали
-- никогда, и ни одна из 143 миграций, предшествовавших этой, его не трогала
-- (единственные вхождения `watch_cursors_service_ck` — создание в 0001 и
-- восстановление в Down этого файла). Перечень отстал от платформы, и
-- отставание никем не замечено, потому что читать его некому.
--
-- ЧТО ЗДЕСЬ НЕ УЛИКА — сказано отдельно, чтобы следующий читатель не вывел её
-- заново, как вывел автор этой миграции и был опровергнут на приёмке. Имя
-- `loadbalancer` рядом с каталогом `services/nlb` выглядит устаревшим, но
-- устаревшим НЕ является: так называется домен платформы — proto-пакет
-- `kacho.cloud.loadbalancer.v1`, бинарь `kacho-loadbalancer`, 115 файлов в
-- индексе. По этой оси ограничение с платформой СОГЛАСОВАНО; отставание
-- доказывает только неполнота перечня, а не написание имени.
--
-- ПОЧЕМУ ЭТО НЕ ПРОСТО МЁРТВЫЙ КОД. Позиция подписки принадлежит КЛИЕНТУ: он
-- присылает курсор, сервер состояния не держит. Отсюда следует свойство, ради
-- которого решение и принято, — поток переживает переподключение К ДРУГОЙ
-- РЕПЛИКЕ, потому что новой реплике нечего про подписчика помнить. Общий сервер
-- потока это уже исполняет: операторов записи в нём ноль. Цена отмены выше цены
-- мёртвого кода: мёртвый код подбирают и выбрасывают, а отменённое решение
-- обнаруживается прогоном, на котором поток не пережил переподключения.
--
-- ПОЧЕМУ СНЯТИЕ, А НЕ КОММЕНТАРИЙ В СХЕМЕ. Комментарий переживает своё основание
-- и читается как описание действительности; снятая таблица не переживает ничего.
-- Приглашения не остаётся, когда не остаётся приглашающего.
--
-- ЧТО ТЕРЯЕТСЯ. Ничего, что создал бы вызывающий: строк в таблице нет и не было,
-- поверхности для их создания не существовало ни на одном слушателе. Ноль строк
-- здесь не предполагается, а ПРОВЕРЯЕТСЯ: запись в `dropguard.json` объявляет
-- ожидание, и гейт снятий пересчитывает его на пустой базе, проигрывая цепочку до
-- версии перед этой.
DROP TABLE IF EXISTS kacho_iam.watch_cursors;

-- +goose Down
-- Возврат в форму базовой схемы (0001), чтобы откат приходил в то состояние, из
-- которого Up вышел, — вместе с ограничением и его отставшим перечнем доменов.
-- Строк не восстанавливается, потому что их не было.
--
-- Откат возвращает и приглашение: следующий, читающий схему после него, снова
-- увидит центральную ведомость позиций по доменам. Решение о том, что позиция
-- принадлежит клиенту, от этого не меняется — оно записано здесь и в приёмке
-- фазы, а не в наличии или отсутствии таблицы.
CREATE TABLE kacho_iam.watch_cursors (
    service       text NOT NULL,
    last_event_id text NOT NULL DEFAULT ''::text,
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT watch_cursors_service_ck CHECK ((service = ANY (ARRAY['vpc'::text, 'compute'::text, 'loadbalancer'::text])))
);

ALTER TABLE ONLY kacho_iam.watch_cursors
    ADD CONSTRAINT watch_cursors_pkey PRIMARY KEY (service);
