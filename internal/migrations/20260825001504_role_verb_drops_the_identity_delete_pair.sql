-- Проекция «роль → тип × глагол» перестаёт нести пару, которой нет в модели.
--
-- ПРЕДМЕТ (#1189). Тем же изменением, что и эта миграция, с типа `iam_user` снят
-- глагол `v_delete`: снятие строки личности спрашивает `identity_remover` (#1131),
-- правку записи — `record_writer`, запрет и его снятие — `identity_suspender`
-- (#1102), и читателя у глагола не осталось ни одного. Пока он был объявлен,
-- подстановка `*` в правиле роли разворачивалась в него, и выдача материализовала
-- пару `(iam.user, delete)` в `kacho_iam.role_verb` — проекции, которую читает
-- вердикт. Замер на свежепосеянной базе: таких ролей ЧЕТЫРЕ — `admin`, `owner`,
-- `kacho-system.admin`, `iam.user.admin`.
--
-- КОМУ ОНА АДРЕСОВАНА — названо прямо, а не подразумевается. На СВЕЖЕЙ базе она
-- удаляет НОЛЬ строк by construction: `role_verb` не заполняет ни одна миграция
-- дерева (предикат: `grep -l 'INSERT INTO kacho_iam.role_verb' …/migrations/*.sql`
-- → пусто), её пишет сервис. Адресат — СУЩЕСТВУЮЩИЙ стенд, где строки уже лежат.
--
-- И ТАМ ЕЁ ПРЕДМЕТ — НЕ СИСТЕМНЫЕ РОЛИ. Их проекция самолечащая: `SyncAllSystem-
-- RoleSelectors` пересчитывает её на КАЖДОМ старте iam, а старт неизбежен —
-- модель вшита в двоичный файл, поэтому её правка означает перекатку службы.
-- Остаются роли, заведённые арендатором: сегмент глагола в `Role.Create` словарём
-- не закрыт, значит роль с `delete` на `iam.user` создавалась успешно, а
-- пересчитать её проекцию некому — она обновляется только правкой самой роли.
--
-- ПОЧЕМУ ЭТО ВООБЩЕ НАДО, ЕСЛИ СТРОКА ИНЕРТНА. Прочитать её нельзя: вердикт
-- компилирует пару (тип, отношение) по вшитой модели, и `iam_user.v_delete` теперь
-- не компилируется — ответ будет ошибкой, а не ложным «да». То есть удаление
-- закрывает не дыру, а РАСХОЖДЕНИЕ: проекция утверждала бы право, которого модель
-- не знает, и это расхождение пережило бы всех, кто помнит, откуда оно взялось.
--
-- ИДЕМПОТЕНТНА и аддитивна к истории: ключуется на паре, повторный прогон не
-- меняет ничего, ни одна применённая миграция не правится (запрет #5).

-- +goose Up
-- +goose StatementBegin

DELETE FROM kacho_iam.role_verb
 WHERE object_type = 'iam.user'
   AND verb = 'delete';

-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin

-- Обратного пути нет. Вернуть строки значило бы вернуть пары, адресующие
-- отношение, которого нет в модели: вердикт на них отвечает ошибкой компиляции, а
-- не решением. Откату, которому действительно нужно пообъектное удаление личности,
-- нужна не строка проекции, а ИСТОЧНИК ПРАВА — то есть изменение канонической
-- модели со своим разбором и своей приёмкой.

SELECT 1;

-- +goose StatementEnd
