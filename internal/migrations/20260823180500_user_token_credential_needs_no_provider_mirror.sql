-- 20260823180500_user_token_credential_needs_no_provider_mirror — удостоверение
-- персонального токена перестаёт требовать зеркала у поставщика
-- (задача #1121, подфаза Ф4б-3 эпика #896).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Колонка зеркала хранит идентификатор клиента у ВНЕШНЕГО поставщика. Нужна она
-- ровно для одного — обмена утверждения У НЕГО. Наш издатель разрешает клиента
-- по идентификатору СВОЕЙ строки (`AssertionClientRepo`: разрешение идёт по
-- `c.id`, зеркальная колонка на этом пути не участвует ни как второй ключ
-- поиска, ни как запасной). Выдача перестала заводить клиента у поставщика,
-- значит у новой строки зеркала НЕТ — и хранилище обязано это выражать.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ОТСУТСТВИЕ ЗНАЧЕНИЯ, А НЕ ПУСТАЯ СТРОКА И НЕ НАШ ЖЕ ИДЕНТИФИКАТОР
--
-- Три довода, каждый самостоятельно достаточный.
--
-- 1. ПУСТАЯ СТРОКА НЕ ПРОХОДИТ ВТОРОЙ РАЗ. Зеркало несёт уникальный индекс, и
--    пустая строка — обычное значение: первая выдача прошла бы, вторая упёрлась
--    бы в 23505. То есть у пользователя был бы ровно один персональный токен, а
--    их по построению много (N:1, `UNIQUE(user_id)` здесь намеренно нет).
--    Отсутствие значения индекс различает: значений `NULL` в уникальном индексе
--    может быть сколько угодно.
--
-- 2. НАШ ЖЕ ИДЕНТИФИКАТОР В ЭТОЙ КОЛОНКЕ — УТВЕРЖДЕНИЕ, КОТОРОГО МЫ НЕ ДЕЛАЛИ.
--    Колонка означает «клиент с таким именем зарегистрирован у поставщика».
--    Записать туда имя своей строки значит заявить регистрацию, которой нет, и
--    сделать обратный поиск по зеркалу разрешающим строки, у которых зеркала
--    быть не может.
--
-- 3. ОКНО ДВУХ ИЗДАТЕЛЕЙ ОБЯЗАНО БЫТЬ ВИДНО В ДАННЫХ. Строки, заведённые ДО
--    перевода, своё зеркало сохраняют — их регистрация у поставщика существует и
--    отчеканенные ею токены живут до своего истечения. Пока «есть зеркало» и
--    «нет зеркала» различимы, остаток окна СЧИТАЕТСЯ:
--
--        SELECT count(*) FROM kacho_iam.user_oauth_clients
--         WHERE hydra_client_id IS NOT NULL;
--
--    Заполни колонку чем угодно — и этот предикат перестанет отвечать на свой
--    вопрос, а снятие поставщика (подфазы #1123/#1125) лишится величины, по
--    которой его назначают.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ОБЛАСТЬ: ТОЛЬКО ПОЛЬЗОВАТЕЛЬСКИЕ ТОКЕНЫ
--
-- Таблица ключей служебной учётки здесь НЕ трогается: её контур переводится
-- своей подфазой (#1120), у него другой владелец предмета, другой отзыв и
-- другой сквозной набор. Одна миграция на оба дала бы послабление там, где
-- писатель ещё пишет зеркало, — то есть сняла бы ограничение раньше, чем
-- исчезнет его предмет.
--
-- Уникальный индекс и внешние ключи остаются как есть: послабляется РОВНО
-- обязательность значения и форма непустого. Непустое зеркало по-прежнему
-- обязано быть годным идентификатором (1..128, `[A-Za-z0-9._:-]`) — иначе
-- послабление накрыло бы и мусор в строках прежнего выпуска.

-- +goose Up

ALTER TABLE kacho_iam.user_oauth_clients
    ALTER COLUMN hydra_client_id DROP NOT NULL;

ALTER TABLE kacho_iam.user_oauth_clients
    DROP CONSTRAINT IF EXISTS user_oauth_clients_hydra_client_id_check,
    ADD CONSTRAINT user_oauth_clients_hydra_client_id_check
        CHECK (hydra_client_id IS NULL
               OR ((length(hydra_client_id) >= 1)
                   AND (length(hydra_client_id) <= 128)
                   AND (hydra_client_id ~ '^[A-Za-z0-9._:-]+$'::text)));

COMMENT ON COLUMN kacho_iam.user_oauth_clients.hydra_client_id IS
    'Идентификатор клиента у внешнего поставщика. NULL — регистрации у него нет (выдача её больше не заводит); непустое значение принадлежит строке прежнего выпуска и держит окно двух издателей.';

-- +goose Down

-- Откат восстанавливает обязательность. Строки без зеркала он не переживёт — и
-- это верно: вернуть ограничение при живых строках, ему не удовлетворяющих,
-- нельзя ни при какой формулировке, а придумывать им значение значило бы
-- заявить регистрацию, которой нет.

ALTER TABLE kacho_iam.user_oauth_clients
    DROP CONSTRAINT IF EXISTS user_oauth_clients_hydra_client_id_check,
    ADD CONSTRAINT user_oauth_clients_hydra_client_id_check
        CHECK (((length(hydra_client_id) >= 1)
                AND (length(hydra_client_id) <= 128)
                AND (hydra_client_id ~ '^[A-Za-z0-9._:-]+$'::text)));

ALTER TABLE kacho_iam.user_oauth_clients
    ALTER COLUMN hydra_client_id SET NOT NULL;
