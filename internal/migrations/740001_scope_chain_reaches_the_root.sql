-- 740001_scope_chain_reaches_the_root — цепь областей доходит до корня, потому
-- что верхние её звенья ВЫВОДЯТСЯ ИЗ СХЕМЫ, а не присылаются владельцем ресурса.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Рёбра цепи появлялись единственным путём — регистрацией ресурса у владельца
-- прав, — и зовут её пять сервисов-соседей только для СВОИХ ресурсов. Объектов
-- типа project и account не регистрирует никто, включая сам iam, поэтому обход
-- вверх доходил до проекта и там останавливался: выдача роли на аккаунт и прямой
-- факт администратора облака на кластере этой формой НЕ НАХОДИЛИСЬ. Верхний ярус
-- `security.md` §«Три уровня супер-доступа», включая аварийный путь, был
-- недостижим, а отказ по нему НЕОТЛИЧИМ от честного.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ВЫВОД, А НЕ ПРОИЗВОДИТЕЛЬ
--
-- Рассматривались три исхода: научить пятерых соседей слать цепь до корня;
-- достроить недостающее на принимающей стороне; вернуть резолв в каждый запрос.
--
-- Первый требует СОГЛАСИЯ пяти независимых кодовых баз о величине, которой ни
-- одна из них не владеет: аккаунт проекта знает iam, а не vpc (комментарий у
-- регистратора vpc так и говорит — «аккаунт на горячем пути не резолвится»).
-- Согласие пяти — ровно та форма, в которой дефект и завёлся: у соседа скопирован
-- вывод, а не проверен факт. Вдобавок присланная цепь — КОПИЯ величины на момент
-- регистрации: переезд проекта в другой аккаунт потребовал бы перерегистрации
-- ВСЕХ его ресурсов, а до неё цепь указывала бы на прежний аккаунт.
--
-- Третий разложил бы одно знание по четырём текстам запросов — четыре места об
-- одном предмете, которые разъедутся молча.
--
-- Второй исход, выбранный здесь, снимает оба возражения РАЗОМ, если достройка —
-- не код, который «не забудет», и не строки, которые кто-то поддерживает, а
-- ВЫВОДИМАЯ СТРУКТУРА: предок проекта И ЕСТЬ `projects.account_id`, предок
-- аккаунта И ЕСТЬ строка синглтона `clusters`. Копии не заводится, обратного
-- заполнения не требуется, устареть нечему: переезд проекта виден следующим же
-- вопросом, снятие проекта убирает звено в тот же момент.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПРЕЦЕДЕНСТВО: ВЛАДЕЛЕЦ СКАЗАЛ — ВЛАДЕЛЕЦ И ПРАВ
--
-- Достройка молчит там, где владелец объекта цепь НАЗВАЛ: `NOT EXISTS` по
-- собственной стороне ребра. Та же дисциплина, что у миграции 0084 («заполнение
-- не вправе затирать точное приблизительным»), и у неё есть второе следствие,
-- ради которого она здесь и стоит: число строк на один объект не растёт. Оно
-- по-прежнему не больше глубины, ограниченной проверкой схемы, — а на этом
-- равенстве держится довод «предел внутри соединения вбок не усекает».
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧЕГО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ
--
-- Не трогает `resource_parent_edge`: таблица остаётся тем, чем была, — цепью в
-- том виде, в каком её прислал владелец. Ни одна её строка не переписывается, ни
-- одна проверка схемы не снимается. Не заводит строк вообще: у представления их
-- нет by construction, поэтому нечего обратно заполнять и нечему разъехаться.

-- +goose Up

CREATE VIEW kacho_iam.resource_scope_edge AS
  -- (1) То, что прислал владелец объекта. Дословно, без отбора: чей ресурс — того
  --     и цепь.
  SELECT e.object_type, e.object_id, e.parent_type, e.parent_id, e.depth
    FROM kacho_iam.resource_parent_edge e
UNION ALL
  -- (2) Предок проекта — его аккаунт. Величина принадлежит iam и лежит в его
  --     собственной строке; здесь она лишь названа в форме ребра.
  SELECT 'project'::text, p.id, 'account'::text, p.account_id, 1
    FROM kacho_iam.projects p
   WHERE p.account_id <> ''
     AND NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'project' AND e.object_id = p.id)
UNION ALL
  -- (3) Предок аккаунта — кластер. Идентификатор берётся ИЗ СТРОКИ синглтона, а
  --     не литералом: литерал был бы вторым местом об одном предмете и разошёлся
  --     бы молча, а отсутствие строки честнее отдать отсутствием звена.
  SELECT 'account'::text, a.id, 'cluster'::text, c.id, 1
    FROM kacho_iam.accounts a
   CROSS JOIN kacho_iam.clusters c
   WHERE NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'account' AND e.object_id = a.id);

COMMENT ON VIEW kacho_iam.resource_scope_edge IS
  'Цепь областей, какой её читает вопрос о доступе: рёбра, присланные владельцами ресурсов (resource_parent_edge), ПЛЮС два звена, выводимых из собственной схемы iam, — project→account (projects.account_id) и account→cluster (синглтон clusters). Выводимые звенья не хранятся: копии нет, обратного заполнения нет, устареть нечему. Владелец, назвавший цепь своего объекта сам, вывод отменяет (NOT EXISTS по object_type/object_id) — точное не затирается приблизительным, и число строк на объект не превышает границы глубины. ПИСАТЬ СЮДА НЕЛЬЗЯ: производители пишут в resource_parent_edge.';

-- Прочтение самой таблицы уточняется здесь же: с этого изменения вопрос о
-- доступе читает не её, а представление выше. Комментарий 732001 говорил «полный
-- путь до корня собирается обходом вверх» — это по-прежнему верно, но искать
-- обход в этой таблице теперь неоткуда, и следующий читатель обязан узнать об
-- этом из базы, а не из файла миграции.
COMMENT ON TABLE kacho_iam.resource_parent_edge IS
  'Цепь предков объекта в том виде, в каком её прислал владелец объекта: строка на предка, глубина — расстояние (1 — непосредственный). ЗАМЫКАНИЕМ НЕ ЯВЛЯЕТСЯ и схемой не требуется: производители шлют короткую цепь (обычно одно звено). СЮДА ПИШУТ, А ЧИТАЮТ ИЗ resource_scope_edge (миграция 740001): вопрос о доступе поднимается по представлению, которое добавляет к этим строкам два звена, выводимых из собственной схемы iam, — project→account и account→cluster. Прежде чем менять обход на одно чтение, докажи полноту замыкания: его не даёт ни эта таблица, ни представление.';

