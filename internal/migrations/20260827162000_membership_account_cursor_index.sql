-- 20260827162000_membership_account_cursor_index — курсорный обход членств
-- аккаунта получает свой порядок из индекса.
--
-- Приёмка: sub-phase-IAM-ID-2-membership-read-acceptance.md, стадия S1
-- (сценарий IAM-ID-2-05 — пагинация; DoD п. 4 — курсор не пропускает и не
-- дублирует строк).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ЭТОТ ИНДЕКС ЗАВОДИТСЯ — ДОВОД НЕ ПРОИЗВОДИТЕЛЬНОСТНЫЙ, И ЭТО ВАЖНО
--
-- При сегодняшних объёмах цена отсутствия равна нулю: таблица помещается в одну
-- страницу, и планировщик возьмёт последовательный обход при любом наборе
-- индексов. Проверка, построенная на плане запроса, здесь НЕ МОЖЕТ УПАСТЬ —
-- ровно это записано в шапке уже существующей пробы дерева.
--
-- Настоящих доводов три, каждый самостоятельно достаточен:
--
--   1. ГЕЙТ ДЕРЕВА покраснеет. `TestEveryCursorPageReadGetsItsOrderFromAnIndex`
--      выводит перечень таблиц из ТЕКСТОВ ЗАПРОСОВ репозиториев и требует
--      индекса под каждую подпись обхода. Чтение членств попадает под него в
--      момент своего появления. То есть индекс — условие зелёного дерева, а не
--      оптимизация.
--   2. ЭТО ОБЪЯВЛЕННАЯ КОНВЕНЦИЯ платформы, а не выбор: единица счёта — пара
--      «таблица × подпись обхода».
--   3. АСИММЕТРИЯ РОСТА. Число членств есть число людей, помноженное на число
--      аккаунтов на человека, и весь предмет перехода отрыва идентичности —
--      снять единицу во втором множителе. Индекс при десятках строк стоит одной
--      страницы записи; после — требует особой формы создания.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОРЯДОК КОЛОНОК: РАВЕНСТВО ВПЕРЕДИ, КЛЮЧИ КУРСОРА ПОДРЯД ЗА НИМ
--
-- Обход выглядит так: `WHERE account_id = $1 [AND (created_at, id) > (…)]
-- ORDER BY created_at, id LIMIT $n`. Аккаунт здесь — РАВЕНСТВО (он обязателен и
-- приходит из пути), поэтому он ведущий; за ним идут ключи курсора ПОДРЯД, в
-- том же порядке и в согласованном направлении (обе колонки ASC, как и обход).
--
-- Смешанное направление (`created_at DESC, id`) выглядело бы сделанной работой и
-- не отдавало бы порядок ни прямым чтением, ни обратным. Здесь его нет.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ НЕ ГОЛЫЙ `(created_at, id)`
--
-- У него не было бы производителя запроса: плоской коллекции членств контракт не
-- несёт — оба объявленных обхода несут ОБЯЗАТЕЛЬНОЕ ведущее равенство (аккаунт
-- в S1, человек в S2). Индекс без запроса — мёртвый вес на каждой вставке.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ НЕ `CONCURRENTLY`
--
-- `CREATE INDEX CONCURRENTLY` не исполняется внутри транзакции, а мигратор
-- накатывает шаг транзакцией. Отказ от транзакции покупается ценой: оборванный
-- параллельный накат оставляет ИНВАЛИДНЫЙ индекс, который надо снимать руками, —
-- и покупать её сегодня не за что: таблица мала, блокировка записи на время
-- построения измеряется миллисекундами. Предикат пересмотра назван честно: когда
-- число строк перестанет помещаться в такое окно, форму создания придётся менять
-- отдельной миграцией, и это будет решение с замером, а не догадка.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО СНИМАЕТСЯ И ПОЧЕМУ
--
-- `memberships_account_idx (account_id)` становится СТРОГИМ ПРЕФИКСОМ нового:
-- всякий запрос, который он обслуживал («кто состоит в этом аккаунте»),
-- обслуживается новым не хуже — btree читает ведущую колонку составного индекса
-- ровно так же. Держать оба значит платить за вторую запись при каждой вставке
-- и удалении, ничего не получая взамен.
--
-- ЧТО НЕ ТРОГАЕТСЯ: `memberships_user_account_unique (user_id, account_id)`. Он
-- держит ИНВАРИАНТ — «человек состоит в аккаунте не более одного раза», — а не
-- обслуживает запрос, и его порядок колонок выбран под инвариант, а не под
-- обход. Снять его ради экономии значило бы разменять целостность на запись.
--
-- Обратный шаг ВОССТАНАВЛИВАЕТ снятый индекс: откат обязан возвращать то
-- состояние, из которого накат вышел, а не приблизительное.

-- +goose Up

CREATE INDEX memberships_account_cursor_idx
    ON kacho_iam.memberships (account_id, created_at, id);

DROP INDEX IF EXISTS kacho_iam.memberships_account_idx;

-- +goose Down

CREATE INDEX memberships_account_idx ON kacho_iam.memberships (account_id);

DROP INDEX IF EXISTS kacho_iam.memberships_account_cursor_idx;
