-- 0085_role_verb_projection — какие глаголы на каких типах даёт роль.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЗАЧЕМ ТАБЛИЦА, ЕСЛИ РАЗРЕШЕНИЯ УЖЕ ЛЕЖАТ В roles.permissions
--
-- Лежат — но массивом строк-разрешений (`"vpc.networks.create"`), а форма E
-- спрашивает пару «тип объекта × глагол». Перевод одного в другое — это КОД:
-- разбор точечного имени, поиск типа в закрытом каталоге, приведение глагола к
-- канонической форме. В SQL этого не выразить, не переписав каталог типов в
-- запрос — то есть не заведя второе место, знающее соответствие.
--
-- Поэтому проекция МАТЕРИАЛИЗУЕТСЯ: её считает iam, когда роль меняется, и
-- кладёт сюда. Читатель — запрос вердикта, который присоединяет её к выдаче.
--
-- ЭТО НЕ ТО ЖЕ, ЧТО role_rule_selectors. Та таблица — сторона МЕТОК: какие типы
-- и какие метки адресует правило роли. Эта — сторона ГЛАГОЛОВ: что правило
-- позволяет делать. Две стороны одного правила, и путать их дорого: первую
-- спрашивают «подходит ли объект», вторую — «разрешено ли действие».
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ГЛАГОЛ ХРАНИТСЯ УЖЕ ПРИВЕДЁННЫМ
--
-- Приведение (регистр, пробелы) — свойство ПРОИЗВОДИТЕЛЯ имени, и делать его
-- на пути запроса значило бы повторять на каждом вопросе работу, результат
-- которой не меняется. Хуже: два места, приводящих имя, разъедутся молча —
-- запрос перестанет находить строки, которые в таблице есть.

-- +goose Up

CREATE TABLE kacho_iam.role_verb (
  role_id     text NOT NULL
    REFERENCES kacho_iam.roles (id) ON DELETE CASCADE,
  -- object_type — тип объекта модели прав (`vpc_network`), не точечное имя
  -- ресурса: запрос вердикта спрашивает именно им, и перевод обязан произойти
  -- ОДИН раз, при записи.
  object_type text NOT NULL,
  -- verb — глагол в канонической форме, БЕЗ приставки отношения: приставку
  -- знает компилятор модели, и дублировать её здесь значило бы завести второе
  -- место, где она может смениться.
  verb        text NOT NULL,

  CONSTRAINT role_verb_pkey PRIMARY KEY (role_id, object_type, verb),
  CONSTRAINT role_verb_type_nonempty CHECK (object_type <> ''),
  CONSTRAINT role_verb_verb_nonempty CHECK (verb <> ''),
  -- Приведённость — свойство хранимого, а не надежда на писателя: строка,
  -- отличающаяся от своей канонической формы, не будет найдена запросом, и
  -- отличить это от «права нет» станет нечем.
  CONSTRAINT role_verb_verb_canonical CHECK (verb = lower(btrim(verb)))
);

-- Обратный вопрос: «какие роли дают этот глагол на этом типе». Им отвечает
-- перечисление субъектов, имеющих право на объекте.
CREATE INDEX role_verb_by_type_verb
  ON kacho_iam.role_verb (object_type, verb);

-- +goose Down

DROP TABLE IF EXISTS kacho_iam.role_verb;
