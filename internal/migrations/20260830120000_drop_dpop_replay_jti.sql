-- +goose Up
-- Ведомость однократности предъявления доказательства снимается у iam: писателя и
-- читателя у неё нет, а форма её приглашает завести второе хранилище того же
-- механизма — в другой схеме, у другого сервиса и по другим часам.
--
-- Задача `PRO-Robotech/kacho#1362`.
--
-- ЧТО СНИМАЕТСЯ. `kacho_iam.dpop_replay_jti` заведена базовой схемой (0001):
-- первичный ключ `jti`, рядом `seen_at`, `htm`, `htu`, `jkt`, индекс по `seen_at`
-- и четыре ограничения длины. Прод-писателей и прод-читателей у неё ноль —
-- перепись велась по имени таблицы в не-тестовом дереве Go и в SQL, и
-- единственные вхождения за пределами объявления в 0001 суть запись реестра
-- роста и одна интеграционная проба, снимаемая вместе с предметом. Ни одна
-- миграция цепочки в неё не вставляла: посева нет, поэтому и ожидание ноль строк
-- не предполагается, а ПРОВЕРЯЕТСЯ записью в `dropguard.json` — гейт снятий
-- проигрывает цепочку до версии перед этой и пересчитывает.
--
-- ЧЕГО ЭТО СНЯТИЕ НЕ ОЗНАЧАЕТ — сказано первым, потому что имя таблицы читается
-- как защита от повтора, и следующий читатель обязан не вывести обратного.
-- Защита от повторного предъявления доказательства ЖИВА и снятием не затронута:
-- она живёт на крае, в `kacho_gateway.dpop_replay`, заведённой собственной
-- миграцией края `20260822140000`, с допуском одним оператором вставки, уборкой
-- по сроку и общим для читателя и уборщика предикатом. Здесь снимается не
-- механизм, а таблица, которая его хранилищем не была НИКОГДА.
--
-- ЧЕМ ЭТА ТАБЛИЦА ОПАСНЕЕ ОБЫКНОВЕННОЙ МЁРТВОЙ. Мёртвая таблица не обещает
-- ничего; эта несёт полную форму ведомости повторов — опознаватель
-- доказательства, отметку предъявления, глагол, адрес и отпечаток ключа, — то
-- есть ровно те поля, которыми доказательство и описывается. Читатель схемы iam
-- заключает из неё, что однократность держит iam, и дальше у него два пути, и
-- оба неверны: счесть хранилище края дублирующим и снять его либо завести второго
-- писателя сюда. Второе хуже: один механизм в двух схемах двух служб решается
-- двумя разными часами и двумя разными сроками, а однократность есть свойство
-- ОДНОГО решения — разъехавшись, два хранилища допустят предъявление, которое
-- каждое из них по отдельности отвергло бы.
--
-- ПОЧЕМУ СНЯТИЕ, А НЕ КОММЕНТАРИЙ В СХЕМЕ. Комментарий переживает своё основание
-- и читается как описание действительности; снятая таблица не переживает ничего.
-- Приглашения не остаётся, когда не остаётся приглашающего.
--
-- ЧТО ТЕРЯЕТСЯ. Ничего, что создал бы вызывающий: поверхности для записи строк в
-- эту таблицу не существовало ни на одном слушателе iam.
DROP TABLE IF EXISTS kacho_iam.dpop_replay_jti;

-- +goose Down
-- Возврат в форму базовой схемы (0001), чтобы откат приходил в то состояние, из
-- которого Up вышел, — дословно, вместе с первичным ключом, индексом по отметке
-- предъявления и всеми четырьмя ограничениями длины. Строк не восстанавливается,
-- потому что их не было.
--
-- Откат возвращает и приглашение: следующий, читающий схему после него, снова
-- увидит у iam ведомость повторов. Решение о том, что однократность держит край,
-- от этого не меняется — оно записано здесь и в задаче, а не в наличии или
-- отсутствии таблицы.
CREATE TABLE kacho_iam.dpop_replay_jti (
    jti text NOT NULL,
    seen_at timestamp with time zone DEFAULT now() NOT NULL,
    htm text DEFAULT ''::text NOT NULL,
    htu text DEFAULT ''::text NOT NULL,
    jkt text DEFAULT ''::text NOT NULL,
    CONSTRAINT dpop_replay_jti_htm_check CHECK ((length(htm) <= 16)),
    CONSTRAINT dpop_replay_jti_htu_check CHECK ((length(htu) <= 2048)),
    CONSTRAINT dpop_replay_jti_jkt_check CHECK ((length(jkt) <= 128)),
    CONSTRAINT dpop_replay_jti_jti_check CHECK (((length(jti) >= 1) AND (length(jti) <= 128)))
);

ALTER TABLE ONLY kacho_iam.dpop_replay_jti
    ADD CONSTRAINT dpop_replay_jti_pkey PRIMARY KEY (jti);

CREATE INDEX dpop_replay_jti_seen_at_idx ON kacho_iam.dpop_replay_jti USING btree (seen_at);
