-- Строка приглашения несёт СВОЙ срок (приёмка ID-MAIL-1, §10 п. 22, MAIL-23).
--
-- ────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Однократность, отзыв и выкуп у приглашения уже есть; СРОКА нет ни у чего.
-- Приглашение, не выкупленное никогда, остаётся выкупаемым навсегда: строка
-- PENDING ждёт первого входа по совпадению адреса, и ждёт она без предела.
-- Человек, которого пригласили и передумали приглашать, вступает в аккаунт
-- через год — потому что ему пришло письмо, и оно не перестало действовать.
--
-- ────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ КОЛОНКА, А НЕ ВЫЧИСЛЕНИЕ ОТ ВРЕМЕНИ ЗАВЕДЕНИЯ
--
-- Величина срока есть ручка посадки, и менять её вправе оператор. Вычисляй
-- служба срок на лету от `created_at`, правка ручки молча сдвинула бы срок у
-- строк, ВЫДАННЫХ под прежней величиной: человеку сказали «неделя», а у него
-- оказались сутки. Срок — свойство выданного приглашения, он записывается в
-- момент выдачи и больше не двигается ничем.
--
-- ────────────────────────────────────────────────────────────────────────────
-- NULL ЗНАЧИТ «СРОК НЕ НАЗНАЧЕН», И ЭТО ЗАКОННОЕ СОСТОЯНИЕ
--
-- Колонка объявлена без умолчания и без NOT NULL: величина, которую построение
-- подставляет молча, предметом стража быть не может. Строка без срока
-- активируется по-прежнему — иначе эта миграция обесценила бы каждое
-- приглашение, выданное раньше её, и сделала бы это молча.
--
-- СТРОКИ, ЖДУЩИЕ ВЫКУПА, СРОК ПОЛУЧАЮТ — и вот почему не наоборот. Оставить их
-- без срока значило бы оставить ровно тот класс, ради которого миграция
-- написана: бессрочно выкупаемое приглашение. Величина взята из УМОЛЧАНИЯ
-- ручки `invite.ttl` (семь суток) — ровно того, под которым служба поднимется
-- сразу после этой миграции; посадка, объявившая иную величину, применит её к
-- приглашениям, выданным ПОСЛЕ, и переписывать ими уже выданное нельзя.
-- Отсчёт — от времени ЗАВЕДЕНИЯ строки, а не от «сейчас»: иначе приглашение,
-- пролежавшее год, получило бы неделю свежести за факт применения миграции.
--
-- ────────────────────────────────────────────────────────────────────────────
-- ЧЕГО ЗДЕСЬ НЕТ
--
-- Индекса по сроку нет намеренно: читателя, выбирающего строки ПО сроку, в
-- дереве не заводится — срок читает CAS активации, уже нашедший строку по
-- первичному ключу. Индекс без читателя стоит записи и не экономит ничего.
-- Заведётся выметатель просроченных — индекс придёт вместе с ним.

-- +goose Up
ALTER TABLE kaname.users
    ADD COLUMN IF NOT EXISTS invite_expires_at timestamp with time zone;

COMMENT ON COLUMN kaname.users.invite_expires_at IS
    'Срок строки приглашения: после него активация отвергается (ID-MAIL-1, MAIL-23). NULL — срок не назначен: так выглядят строки, заведённые до появления колонки.';

UPDATE kaname.users
   SET invite_expires_at = created_at + interval '7 days'
 WHERE invite_status = 'PENDING'
   AND invite_expires_at IS NULL;

-- +goose Down
-- Откат снимает КОЛОНКУ целиком, а не обнуляет её: величина, записанная на
-- строке, есть единственный след срока, и оставлять её при снятом читателе
-- значило бы держать данные, которых никто не судит.
ALTER TABLE kaname.users
    DROP COLUMN IF EXISTS invite_expires_at;
