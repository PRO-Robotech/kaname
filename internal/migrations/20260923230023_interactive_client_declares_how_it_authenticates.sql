-- interactive_client_declares_how_it_authenticates — СПОСОБ аутентификации
-- интерактивного клиента на токен-эндпоинте выражается схемой (задача
-- PRO-Robotech/kaname#317; санкция — одобренная приёмка LINE-A-1, решение Р3,
-- сценарий LINE-A-1-12).
--
-- =============================================================================
-- ЧТО ИЗМЕРЕНО
-- =============================================================================
-- `git grep -n token_endpoint_auth_method -- 'internal/migrations/*.sql'` на
-- ревизии 860078a96 называет ОДНУ строку — объявление колонки
-- `text DEFAULT ''::text NOT NULL` в `0001_initial.sql`. Ни одно ограничение её
-- не сужало. Колонка проверочного значения секрета уже стоит
-- (`20260920175118_interactive_client_carries_its_secret_verifier.sql`), но со
-- способом она не связана. Схема поэтому принимала и клиента без объявленного
-- способа, и публичного клиента с материалом секрета, и способ, которого не
-- знает ни один читатель. Пустое значение при этом читается по-разному: для
-- регистрации клиентов по RFC 7591 опущенный способ означает
-- `client_secret_basic`, а для этой службы — «способ не объявлен». Одно
-- написание с двумя смыслами — не значение, и в словаре его нет.
--
-- =============================================================================
-- ЧТО ЗАВЕДЕНО, ПО ОДНОМУ ФАКТУ НА ОГРАНИЧЕНИЕ
-- =============================================================================
-- 1. `interactive_clients_auth_method_ck` — СПОСОБ ОБЪЯВЛЕН, И СЛОВАРЬ ЗАКРЫТ.
--    Принимается ровно то, что строка выражает целиком: `none` (публичный
--    клиент, владение доказывает PKCE), `client_secret_basic` и
--    `client_secret_post` (секрет; его проверочное значение —
--    `secret_verifier`). Пустой строки в словаре нет, и умолчание колонки
--    снято: вставка, не назвавшая способ, отвергается, а не получает значение,
--    которого никто не объявлял. Подписанного утверждения ключом
--    (`private_key_jwt`) в словаре НЕТ, и это решение: колонки ключа у строки
--    нет, а способ без места для своего материала невыразим. Способ входит в
--    словарь только вместе с колонкой своего материала.
--
--    Способ объявлен БЕЗУСЛОВНО, а не «у клиента с видами выдачи». Условие по
--    видам держалось бы только на том, что клиент без видов на выдачу кода не
--    выходит, — а выдача кода строку клиента берёт, не судя его видов, и
--    внешний ключ кода на клиента их тоже не судит. Исключение открыло бы код
--    клиенту, о котором неизвестно, чем он аутентифицируется.
--
-- 2. `interactive_clients_secret_verifier_method_ck` — МАТЕРИАЛ СЕКРЕТА лежит
--    только у клиента, чей способ секрет предъявляет. Признак публичности
--    поэтому ОДИН — способ `none`, — а не пустота колонки материала: публичный
--    клиент с материалом невыразим, и два источника признака разойтись не
--    могут. Описание колонки материала переписано тем же доводом: прежнее
--    называло её пустоту публичностью и было бы вторым источником признака.
--
-- =============================================================================
-- ЧТО НЕ ВЫРАЖЕНО, И ПОЧЕМУ
-- =============================================================================
-- Обратная связка «способ секретом ⟹ материал лежит в этой строке» НЕ
-- заведена, и это решение. Строка не несёт признака того, где лежит материал
-- клиента: в реестре службы либо у внешнего поставщика, зеркалом которого
-- строка тогда является. Ограничение, требующее материал в строке, сделало бы
-- конфиденциального клиента внешнего поставщика невыразимым. Пустая колонка
-- материала поэтому означает ровно «в этой строке материала нет».
--
-- =============================================================================
-- ЛЕЖАЩИЕ СТРОКИ
-- =============================================================================
-- Обратного заполнения нет. Способ строки кладёт её единственный писатель
-- (`InteractiveClientRepo.Insert`) из ответа производителя, называя колонку
-- явно, и оба производителя объявляют `none`: адаптер внешнего поставщика —
-- запросом `none` и эхом ответа с первой своей ревизии
-- (`internal/clients/hydra_interactive_clients.go`), собственный — константой
-- (`internal/repo/kaname/pg/own_interactive_client_provider.go`). Материала
-- секрета не кладёт ни один прод-писатель. Строка, нарушающая ограничение,
-- делает накат ОТКАЗОМ, и это намеренно: верный способ для неё неизвестен, а
-- выдуманный объявил бы удостоверение, которого клиент не объявлял.

-- +goose Up

-- +goose StatementBegin
ALTER TABLE kaname.interactive_clients
    ALTER COLUMN token_endpoint_auth_method DROP DEFAULT,
    ADD CONSTRAINT interactive_clients_auth_method_ck CHECK (
        (token_endpoint_auth_method = ANY (ARRAY['none'::text,
                                                 'client_secret_basic'::text, 'client_secret_post'::text]))),
    ADD CONSTRAINT interactive_clients_secret_verifier_method_ck CHECK (
        ((secret_verifier = ''::text)
         OR (token_endpoint_auth_method = ANY (ARRAY['client_secret_basic'::text, 'client_secret_post'::text]))));
-- +goose StatementEnd

COMMENT ON COLUMN kaname.interactive_clients.token_endpoint_auth_method IS
  'Способ аутентификации клиента на токен-эндпоинте, объявлен у КАЖДОГО клиента: none (публичный, владение доказывает PKCE) | client_secret_basic | client_secret_post (секрет, проверочное значение в secret_verifier). Умолчания нет: способ кладёт производитель клиента. Признак публичности — none, а не пустота secret_verifier. Держат interactive_clients_auth_method_ck и interactive_clients_secret_verifier_method_ck.';

COMMENT ON COLUMN kaname.interactive_clients.secret_verifier IS
  'Проверочное значение секрета клиента: argon2id разметкой PHC, тот же алгоритм и те же параметры, что у паролей (internal/domain/password_hash_format.go, пол m=65536,t=3,p=4; производитель passwordverify.Hasher). Секрет в открытом виде не хранится. Лежит только у клиента со способом секретом (client_secret_basic | client_secret_post; держит interactive_clients_secret_verifier_method_ck). Пустая строка — в ЭТОЙ строке материала нет; о публичности клиента она не говорит: признак публичности — token_endpoint_auth_method = none.';

-- +goose Down

-- Откат снимает два ограничения и возвращает то, что стояло до предмета:
-- умолчание колонки способа, отсутствие её описания и прежнее описание колонки
-- материала — дословно то, что объявила её миграция. Данных он не трогает:
-- ограничения ничего не записывали, они только отвергали.
ALTER TABLE kaname.interactive_clients
    DROP CONSTRAINT interactive_clients_secret_verifier_method_ck,
    DROP CONSTRAINT interactive_clients_auth_method_ck,
    ALTER COLUMN token_endpoint_auth_method SET DEFAULT ''::text;

COMMENT ON COLUMN kaname.interactive_clients.token_endpoint_auth_method IS NULL;

COMMENT ON COLUMN kaname.interactive_clients.secret_verifier IS
  'Проверочное значение секрета клиента: argon2id разметкой PHC, тот же алгоритм и те же параметры, что у паролей (internal/domain/password_hash_format.go, пол m=65536,t=3,p=4; производитель passwordverify.Hasher). Секрет в открытом виде не хранится. Пустая строка — секрета НЕТ (публичный клиент).';
