-- access_token_belongs_to_its_family — ВЫПУСК ТОКЕНА ДОСТУПА собственной
-- церемонии становится записью службы: идентификатор выпуска → семейство
-- (задача PRO-Robotech/kaname#319).
--
-- Санкция: одобренная приёмка LINE-A-1 редакции 3 (воркспейс, ветка 771,
-- `docs/specs/sub-phase-LINE-A-1-own-authorization-endpoint-and-code-acceptance.md`,
-- SHA-256 `b755886fd3a9cbf4070598ad3d921bb92d53d7f4186832a2c34f1d8ca197a7ec`;
-- сценарии 01, 21, 28, инвариант 7) и решение К10, вариант А
-- (https://github.com/PRO-Robotech/kaname/issues/358#issuecomment-5784900896).
--
-- =============================================================================
-- ЗАЧЕМ
-- =============================================================================
-- Токен доступа сверяют по подписи, без хранилища: поверхность, принимающая
-- его, строки гранта не читает. Поэтому отзыв семейства, записанный только на
-- строке семейства, до предъявления не доезжает — токен отозванного семейства
-- проходил бы везде до своего срока. Поверхности спрашивают о токене по его
-- идентификатору (`jti`); эта таблица отвечает, какому семейству выпуск
-- принадлежит, а живость семейства она несёт сама.
--
-- =============================================================================
-- ПОЧЕМУ ЖИВОСТЬ — КОЛОНКА ВНЕШНЕГО КЛЮЧА, А НЕ СОЕДИНЕНИЕ
-- =============================================================================
-- Приём тот же, что у кода и обновляющего токена
-- (`20260920175117_authorization_code_is_our_record.sql`): ключ
-- `(family_id, family_live)` ссылается на `token_families (id, live)` с
-- `ON UPDATE CASCADE`. Отзыв семейства — обновление КЛЮЧА, и движок сам
-- разводит его с заведением выпуска: успел отзыв — заведение получает 23503;
-- успело заведение — каскад проставляет записи отозванность. «Живой выпуск
-- отозванного семейства» непредставим ни при каком чередовании.
--
-- `family_live` писатель НЕ пишет: при заведении берётся умолчание `true`, и
-- ключ сверяет его с живым семейством — выпуск в неизвестное и в отозванное
-- семейство отвергает база, а не проверка перед вставкой (ban #10).
--
-- =============================================================================
-- ПОЧЕМУ СНЯТИЕ СЕМЕЙСТВА НЕ УНОСИТ ЗАПИСЬ ВЫПУСКА
-- =============================================================================
-- Семейство удаляется каскадом снятия клиента, человека и уборкой сессии.
-- Каскад удаления сюда дал бы «записи нет», а «записи нет» у выпуска означает
-- «семейству не принадлежит» — то есть снятие семейства превращалось бы в
-- ДОПУСК его токенов до их срока. Запрет удаления (`RESTRICT`) держал бы снятие
-- клиента и человека. Поэтому действие на удаление — `SET NULL (family_live)`:
-- запись остаётся, помнит `family_id`, а пустая живость означает «семейства
-- больше нет». Проверка ключа у такой строки не исполняется (MATCH SIMPLE), и
-- это верно: сверять не с чем.
--
-- Отсюда ЕДИНСТВЕННОЕ правило чтения: выпуск отозван, когда живость НЕ ИСТИННА
-- — ложна (отозвано) либо пуста (снято). Оператор чтения один, в слое доступа
-- (`familyRevokedOfIssuanceSQL`); держит это гейт
-- `internal/check` `TestFamilyVerdictHasOneReaderAndEverySurfaceAsksTheRule`.
--
-- Писатель, положивший пустую либо ложную живость в обход умолчания, получит
-- ОТОЗВАННЫЙ выпуск — ошибка такого рода закрывается отказом, а не допуском.
--
-- =============================================================================
-- СРОК СТРОКИ
-- =============================================================================
-- Строку снимает уборка (`retention`, предмет `access_tokens`), когда токен
-- уже не принимает ни одна поверхность: срок вышел раньше, чем
-- `now() − (ClockSkew + RemovalSlack)`. Индекс по сроку — для неё.

-- +goose Up

CREATE TABLE kaname.access_tokens (
    jti         text NOT NULL,
    family_id   text NOT NULL,
    family_live boolean DEFAULT true,
    issued_at   timestamp with time zone NOT NULL,
    expires_at  timestamp with time zone NOT NULL,
    CONSTRAINT access_tokens_pkey PRIMARY KEY (jti),
    -- Форма идентификатора — та, что чеканит подписант (`ids.NewID("tok")`).
    CONSTRAINT access_tokens_jti_form_ck CHECK ((jti ~ '^tok[0-9a-hjkmnp-tv-z]{17}$'::text)),
    CONSTRAINT access_tokens_family_form_ck CHECK ((family_id ~ '^tfm-[0-9a-hjkmnp-tv-z]{17}$'::text)),
    CONSTRAINT access_tokens_expiry_after_issue_ck CHECK ((expires_at > issued_at)),
    CONSTRAINT access_tokens_family_fk FOREIGN KEY (family_id, family_live)
        REFERENCES kaname.token_families(id, live)
        ON UPDATE CASCADE
        ON DELETE SET NULL (family_live)
);

COMMENT ON TABLE kaname.access_tokens IS
  'Выпуск токена доступа собственной церемонии (kaname#319): идентификатор выпуска → семейство. Живость семейства снесена сюда ключом: отзыв доезжает каскадом, снятие семейства оставляет запись с пустой живостью. Выпуск отозван, когда family_live НЕ ИСТИННА.';
COMMENT ON COLUMN kaname.access_tokens.family_live IS
  'Живость семейства: true — живо, false — отозвано (каскад ключа), NULL — семейство снято (ON DELETE SET NULL). Писателем не выставляется: при заведении берётся умолчание, и ключ сверяет его с живым семейством.';
COMMENT ON COLUMN kaname.access_tokens.family_id IS
  'Семейство, в котором токен выпущен. Остаётся и после снятия семейства: запись помнит, чьим выпуском была.';

CREATE INDEX access_tokens_family_idx ON kaname.access_tokens USING btree (family_id, family_live);
CREATE INDEX access_tokens_expires_at_idx ON kaname.access_tokens USING btree (expires_at);

