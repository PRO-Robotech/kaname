-- family_revocation_reason_names_the_client_revocation — ОТЗЫВ КЛИЕНТОМ
-- получает своё слово в словаре причин отзыва семейства: `client-revoke`
-- (задача PRO-Robotech/kaname#406).
--
-- Санкция: одобренная приёмка
-- `docs/engineering/acceptance/client-revocation-has-its-own-family-revocation-reason.md`,
-- редакция 2, SHA-256
-- `08fadfac47b846979da104f14f9597a31d4df70f77bcd9e14bb150395eab432e`
-- (событие одобрения
-- https://github.com/PRO-Robotech/kaname/issues/406#issuecomment-5846063540;
-- сценарии KN-FRV-07…10, решения Р4, Р5, Р6). Доводы там; здесь — то, что
-- нужно читателю СХЕМЫ.
--
-- =============================================================================
-- ЗАЧЕМ
-- =============================================================================
-- Отзыв клиентом (RFC 7009) фундамент называет порту причиной
-- `client-revoke`, и адаптер порта сопрягает её со словом службы ПО ЗНАЧЕНИЮ.
-- Слова не было ни в домене, ни здесь, поэтому отзыв клиентом отказывал
-- операцией и семейства не трогал. Слово объявлено доменом
-- (`domain.FamilyRevocationReasons()`) тем же изменением; совпадение двух
-- словарей в обе стороны держит проба живой схемы
-- `TestIntegration_RevocationVocabularyAgreesWithTheDomain`.
--
-- =============================================================================
-- ПОЧЕМУ НОВАЯ МИГРАЦИЯ, А НЕ ПРАВКА ПРИМЕНЁННОЙ
-- =============================================================================
-- Действующее определение ограничения поставил накат
-- `20260923225650_consent_leaves_the_schema.sql` (kaname#404). Правка
-- применённого файла не доезжает до базы, где он уже применён: мигратор
-- сверяет версию, а не содержимое (ban #5). Перечень нового определения —
-- пять значений наката #404 и `client-revoke`: снятое #404
-- `consent-withdrawn` не возвращается (Р6).
--
-- =============================================================================
-- ЗАХВАТ
-- =============================================================================
-- Снятие и постановка ограничения берут на `token_families` исключительный
-- захват до конца наката, и постановка читает таблицу целиком, проверяя
-- лежащие строки. Писатели семейств ждут конца наката; отказавший накат
-- повторяем — частичного состояния у него нет.

-- +goose Up

-- Накат только РАСШИРЯЕТ словарь: операторов данных в нём нет, и каждая
-- лежащая строка удовлетворяет обоим определениям (Р5). Ограничение
-- снимается и ставится заново ПОД ТЕМ ЖЕ ИМЕНЕМ: имя — координата, по которой
-- его читают пробы словаря и снимает откат.
ALTER TABLE kaname.token_families
    DROP CONSTRAINT token_families_revoked_reason_ck;
ALTER TABLE kaname.token_families
    ADD CONSTRAINT token_families_revoked_reason_ck CHECK (
        ((revoked_reason IS NULL) OR (revoked_reason = ANY (ARRAY[
            'code-replay'::text, 'refresh-replay'::text, 'logout'::text,
            'session-ended'::text, 'client-removed'::text, 'client-revoke'::text]))));

-- +goose Down

-- Откат восстанавливает ровно определение наката #404 — пять значений без
-- `client-revoke` — и ставит его С ПРОВЕРКОЙ лежащих строк (Р4).
--
-- Что со строками, отозванными клиентом. Семейство со словом `client-revoke`
-- ОТКАЗЫВАЕТ откату кодом 23514 по этому ограничению. Откат исполняется одной
-- транзакцией: версия не сдвигается, строки не трогаются, семейство остаётся
-- отозванным. Выбор держится на двух запретах:
--
--   * снять причину нельзя: причина и отметка отзыва — пара
--     (`token_families_revoked_pair_ck`), отметка и живость — тоже
--     (`token_families_live_pair_ck`); снять причину значит оживить семейство,
--     и выданные по нему токены снова принимались бы при предъявлении;
--   * переписать в другое слово нельзя: журнал семейства записал бы чужое
--     событие, а слова «как было до изменения» для этого акта нет — до
--     изменения он не записывался вовсе, он отказывал.
--
-- Выполнимым откат становится, когда таких семейств не остаётся. Уходят они
-- вместе со своей сессией, человеком или клиентом — семейство держат внешние
-- ключи с каскадом на удалении (`token_families_client_fk`,
-- `token_families_user_fk`, `token_families_session_fk`), — и уборка снимает
-- записи сессий по сроку. Держит это проба
-- `TestTokenFamilyMigration_KN_FRV_10_DownRefusesWhileAFamilyCarriesTheWord`.
ALTER TABLE kaname.token_families
    DROP CONSTRAINT token_families_revoked_reason_ck;
ALTER TABLE kaname.token_families
    ADD CONSTRAINT token_families_revoked_reason_ck CHECK (
        ((revoked_reason IS NULL) OR (revoked_reason = ANY (ARRAY[
            'code-replay'::text, 'refresh-replay'::text, 'logout'::text,
            'session-ended'::text, 'client-removed'::text]))));
