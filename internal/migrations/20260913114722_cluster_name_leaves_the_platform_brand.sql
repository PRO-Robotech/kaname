-- cluster_name_leaves_the_platform_brand — ИМЯ корневого кластера перестаёт
-- называть платформу: `kacho-root` → `root`.
--
-- Задача продукта #2554, класс A APPROVED-приёмки
-- `docs/engineering/acceptance/seed-identity-names-its-own-service.md`
-- (§2.1 класс A, §2.3 написание, §8 шаг 1). Довод написания здесь не
-- пересказывается — он в §2.3: имя называет УСТАНОВКУ, а не продукт, и у
-- стороннего оператора ею не владеет ни платформа, ни служба.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ МИГРАЦИЯ, А НЕ ДЕЙСТВИЕ ОПЕРАТОРА
--
-- Имя сеет свод (`0001_initial.sql:3425`), и править его нельзя (ban #5).
-- Оставить перевод оператору значило бы сделать чужое имя УМОЛЧАНИЕМ каждой
-- новой установки: арендатор, поставивший службу одну, получал бы объект с
-- именем продукта, которого он не ставил, а исправность зависела бы от того,
-- вспомнил ли кто-то выполнить ручной шаг.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧЕГО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ — НАЗВАНО, ЧТОБЫ НЕ ИСКАЛИ
--
--   * ЯКОРЬ не трогает. Идентификатор `cluster_root` переехал раньше и своей
--     задачей (#2113, `20260906214500_…`). Здесь предмет — ИМЯ, косметический
--     ярлык, которого ban #15 не связывает ничем; идентификатор обязан остаться
--     прежним до символа, и это снято опытом
--     (`TestClusterName_AnchorDoesNotMoveWithTheName`), а не объявлено;
--   * ОПИСАНИЕ строки не трогает. `'Root cluster for Kachō control plane'` —
--     тоже остаток бренда, но остаток ЗНАЧЕНИЯ, а не имени: приёмка выносит его
--     пунктом П6 (§0.5, §7) вместе с почтой и отображаемым именем якорного
--     пользователя, чтобы одна строка не правилась дважды разными предметами.
--     Здесь он назван, а не забыт;
--   * ОКНА не требует. Читателей имени в прод-коде ноль (§2.1 класс A), поэтому
--     переводить нечего, кроме самой строки.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ТРИ ИСХОДА, И ТРЕТИЙ — ОТКАЗ, А НЕ ТИШИНА
--
-- Написание читается ПО ФАКТУ, а не полагается известным:
--
--   * имя прежнее             → переписывается;
--   * имя уже объявленное     → делать нечего, миграция проходит молча
--                               (установка, поднятая после перехода);
--   * имя ТРЕТЬЕ              → ОТКАЗ. Оператор мог переименовать кластер сам —
--                               это его право, имя косметично, — и затереть
--                               чужой выбор молча значило бы отобрать у него
--                               ровно ту свободу, ради которой имя и мутабельно.

-- +goose Up
-- +goose StatementBegin
DO $$
DECLARE
    v_declared CONSTANT text := 'root';
    v_previous CONSTANT text := 'kacho-root';
    v_now      text;
    v_rows     bigint;
BEGIN
    SELECT count(*) INTO v_rows FROM kaname.clusters;
    IF v_rows <> 1 THEN
        RAISE EXCEPTION
            'строк кластера %, а он singleton: переводить имя не у чего, и молчаливый проход выдал бы это за сделанную работу.',
            v_rows;
    END IF;

    SELECT name INTO v_now FROM kaname.clusters;

    IF v_now = v_declared THEN
        RAISE NOTICE 'имя кластера уже %: переписывать нечего.', v_declared;
        RETURN;
    END IF;

    IF v_now <> v_previous THEN
        RAISE EXCEPTION
            'имя кластера — %, а переход объявлен с % на %. Имя мутабельно, и оператор вправе был выбрать своё: затирать его молча нельзя. Разберите расхождение до применения свода.',
            v_now, v_previous, v_declared;
    END IF;

    UPDATE kaname.clusters SET name = v_declared WHERE name = v_previous;
    GET DIAGNOSTICS v_rows = ROW_COUNT;

    IF v_rows <> 1 THEN
        RAISE EXCEPTION
            'перевод имени затронул строк %, ожидалась одна: состояние кластера не то, о котором миграция говорит.',
            v_rows;
    END IF;

    RAISE NOTICE 'имя кластера переписано % → %.', v_previous, v_declared;
END $$;
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
DO $$
DECLARE
    v_declared CONSTANT text := 'root';
    v_previous CONSTANT text := 'kacho-root';
BEGIN
    -- Обратный ход возвращает ИМЕННО то, что завёл прямой, и только если оно на
    -- месте: база, где оператор выбрал третье написание, обратным ходом не
    -- трогается — иначе откат отобрал бы его выбор так же молча, как затирание.
    UPDATE kaname.clusters SET name = v_previous WHERE name = v_declared;
END $$;
-- +goose StatementEnd
