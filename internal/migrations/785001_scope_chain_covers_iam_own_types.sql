CREATE OR REPLACE VIEW kacho_iam.resource_scope_edge AS
  SELECT e.object_type, e.object_id, e.parent_type, e.parent_id, e.depth
    FROM kacho_iam.resource_parent_edge e
UNION ALL
  SELECT 'project'::text,
         f.object_id,
         split_part(f.subject, ':', 1),
         substr(f.subject, position(':' in f.subject) + 1),
         1
    FROM kacho_iam.relation_fact f
   WHERE f.object_type = 'project'
     AND f.relation = split_part(f.subject, ':', 1)
     AND position('#' in f.subject) = 0
     AND NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'project' AND e.object_id = f.object_id)
UNION ALL
  SELECT 'account'::text, a.id, 'cluster'::text, c.id, 1
    FROM kacho_iam.accounts a
   CROSS JOIN kacho_iam.clusters c
   WHERE NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'account' AND e.object_id = a.id);

COMMENT ON VIEW kacho_iam.resource_scope_edge IS
  'Цепь областей, какой её читает вопрос о доступе: рёбра, присланные владельцами ресурсов (resource_parent_edge), ПЛЮС два достроенных звена. Предок ПРОЕКТА берётся из проекции журнала (relation_fact, отношение называет тип субъекта) — оттуда же, откуда его берёт движок отношений: указатель со-коммитится созданием проекта, account_id неизменяем, миграции проекты не сеют, поэтому журнал полон по построению, а таблица projects наблюдаемо нет (#781/#782). Предок АККАУНТА берётся из схемы (accounts × clusters): аккаунты сеются миграциями 0009/0044/0057 без указателя в журнале, поэтому полна по построению здесь схема. Правило одно: источник, полный по построению для ЭТОГО звена. Владелец, назвавший цепь своего объекта сам, вывод отменяет (NOT EXISTS) — ветви взаимоисключающи, двух мест об одном предмете нет. ПИСАТЬ СЮДА НЕЛЬЗЯ: производители пишут в resource_parent_edge и в журнал.';
