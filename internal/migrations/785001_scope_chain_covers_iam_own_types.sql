-- 785001_scope_chain_covers_iam_own_types — цепь областей достраивает звено
-- ПЯТИ СОБСТВЕННЫМ ТИПАМ iam: пользователю, группе, служебной учётке, роли и
-- привязке. Источник у всех пяти — СХЕМА, колонка собственной строки объекта.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- 740001 достроила два звена (проект → аккаунт, аккаунт → кластер), 781001
-- перевела первое из них на проекцию журнала. Пяти собственным типам iam цепь
-- не достраивала НИЧЕГО, а производители рёбер их не регистрируют: регистрацию
-- ресурса у владельца прав зовут пять сервисов-соседей и только для СВОИХ
-- объектов, а iam своих не регистрирует вовсе.
--
-- Следствие: множество областей такого объекта состояло из него самого, и
-- выдача, сделанная НА АККАУНТ ИЛИ НА ПРОЕКТ, до него не доходила — тогда как
-- действующий решатель её разрешает. Отказ при этом НЕОТЛИЧИМ ОТ ЧЕСТНОГО.
--
-- Измерено на стенде 2026-08-20 (перепись iam-scope-source-census.sh): строк,
-- чьего предка называет источник и не видит цепь, — 640: привязок 432,
-- пользователей 183, служебных учёток 21, ролей 3, групп 1. После достройки —
-- НОЛЬ по всем пяти, в обе стороны.
--
-- ЭТО РАСШИРЕНИЕ ОХВАТА, И НАЗВАТЬ ЕГО НАДО ПРЯМО. В отличие от 781001, где
-- форма и движок читали одну и ту же проекцию и ни одного нового доступа не
-- появлялось, здесь цепь начинает выводить звено из источника, которого не
-- читала вовсе. Наблюдаемо это ШИРЕ, чем было: администратор аккаунта получает
-- управление содержимым своего аккаунта, администратор облака — аварийный путь
-- к нему через кластер, владелец аккаунта — чтение и удаление своей привязки.
-- Прочтение «просто починка» неверно и прячет изменение поверхности доступа за
-- словом.
--
-- ЧЕГО НЕ ПОЯВЛЯЕТСЯ. Ни один субъект не получает доступа к объекту, ВНУТРЬ
-- которого он не имеет выдачи. Звено — указатель ВВЕРХ, от объекта к его
-- области; оно не создаёт выдач, не меняет ролей и не расширяет набор глаголов.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ СХЕМА, А НЕ ЖУРНАЛ — ИЗМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО
--
-- Правило то же, что ввела 781001: звено берётся из источника, полного
-- ПО ПОСТРОЕНИЮ для ЭТОГО звена, и источник называется вслух. У проекта таким
-- источником оказался журнал, у аккаунта — схема. У всех пяти типов — схема, и
-- довода два:
--
--   1. СТРОКИ ЭТИХ ТИПОВ СЕЮТ МИГРАЦИИ. Девять файлов, от 0001 до 0093, заводят
--      группу читателей пределов, служебные учётки модулей вместе с их
--      пользователями, ролями и привязками, системные роли и привязку
--      администратора кластера.
--      Предикат: for t in groups users service_accounts roles access_bindings; do
--        grep -l "INSERT INTO kacho_iam.$t" services/iam/internal/migrations/*.sql; done | sort -u
--
--   2. УКАЗАТЕЛЬ НА ПРЕДКА ДЛЯ ЭТИХ ТИПОВ НЕ КЛАДЁТ В ЖУРНАЛ НИ ОДНА МИГРАЦИЯ
--      ДЕРЕВА — и это сильнее, чем «ни одна из девяти сеющих». Журнальные
--      строки, которые пишут миграции, — это выдачи и членства (fga_writer,
--      system_viewer, system_admin, member, quota_reader). Имена пяти типов
--      встречаются в миграциях пять раз, и все пять — в СЛОВАРЕ ТИПОВ миграции
--      0091, то есть в переводе имён, а не в кортеже.
--      Предикат: git grep -oh "'iam_[a-z_]*" -- 'services/iam/internal/migrations/*.sql' | sort | uniq -c
--
-- То есть в точности случай АККАУНТА, из-за которого 781001 оставила ветвь (3)
-- на схеме, только в большем масштабе: там один засеянный объект, здесь — все
-- объекты, заведённые девятью миграциями.
--
-- ПОЛНОТА ПО ПОСТРОЕНИЮ — не «в таблице сейчас все строки», а СТРОКА И ЕСТЬ
-- ОБЪЕКТ: идентификатор объекта `iam_group:<id>` — первичный ключ строки
-- kacho_iam.groups, и появиться в обход строки объект не может ни через API, ни
-- через миграцию, ни через посев. Указатель лежит колонкой ТОЙ ЖЕ строки и
-- неизменяем после создания (карта неизменяемых полей: «accountId is immutable
-- after <R>.Create»), поэтому копии не заводится и расходиться нечему. У
-- журнала свойство обратное и принципиальное: он ДОПИСЫВАЕМЫЙ, и будь указатель
-- изменяем, журнал накопил бы оба значения и дал объекту двух предков.
--
-- СЛЕДСТВИЕ, КОТОРОЕ НАДО НАЗВАТЬ ОТДЕЛЬНО: объект, названный журналом и не
-- имеющий строки, звена НЕ ПОЛУЧАЕТ — и это верный ответ, а не пропуск. Строки
-- у него нет, значит объекта не существует. На стенде таких 14 454 у группы и
-- 198 у проекта; предмет чужой (#782, объекты, живущие в графе прав и
-- отсутствующие в собственной таблице), и перепись печатает его ОТДЕЛЬНОЙ
-- категорией с атрибуцией, а не растворяет ни в находках, ни в тишине.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ТУ ЖЕ КОЛОНКУ УЖЕ ЧИТАЮТ ДВА МЕСТА ДЕРЕВА — И ЭТО СИЛЬНЕЙШИЙ ДОВОД
--
--   * реконсайлер выдач (reconcile_adapter.go, iamDirectScanSpecs) — при
--     МАТЕРИАЛИЗАЦИИ выдачи, чтобы правило, выданное на область, накрыло
--     объекты внутри неё;
--   * запасной структурный путь запроса (structural_facts_repo.go +
--     domain/structural_tuple.go) — на ПУТИ РЕШЕНИЯ, контекстными кортежами,
--     чтобы каскад супер-доступа резолвился из закоммиченного состояния.
--
-- То есть источник, из которого цепь берёт звено, — тот самый, из которого его
-- УЖЕ берёт действующий решатель. Это не новая величина и не новое утверждение
-- о мире.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЭТАЛОН РАЗНЕСЁН ПОСВОЙСТВЕННО: CONTAINMENT'ОВ В ДЕРЕВЕ ТРИ, И ОНИ РАСХОДЯТСЯ
--
-- Прежде чем звать что-либо эталоном, надо посчитать эталоны. Их три:
-- материализация (iamDirectScanSpecs), запасной структурный путь
-- (StructuralParent / AccountScopedStructuralFact) и сама модель прав. Попарно
-- они НЕ совпадают, и расходятся в двух местах — поэтому эталон здесь
-- называется по каждому свойству отдельно, а не одним источником на всё:
--
--   таблица и колонка-указатель   → материализация: по этой колонке выдача на
--                                   область фактически накрывает объект;
--   закрытый набор областей       → isBindableScope (domain/structural_tuple.go):
--   у привязки                      тот же набор, которым пользуется эмиттер;
--   наличие звена у КЛАСТЕРНОЙ    → запасной структурный путь: у материализации
--   привязки                        предка нет (оба её выражения дают пусто, её
--                                   собственный комментарий это оговаривает), у
--                                   запасного пути есть, и модель на его
--                                   стороне — у типа привязки объявлены все три
--                                   области и трёхстороннее правило
--                                   super_admin from project or admin from
--                                   account or any_admin from cluster.
--
-- ГЕЙТ, СВЕРЯЮЩИЙ ЦЕПЬ С ОДНИМ ЭТАЛОНОМ ДОСЛОВНО, КРАСЕН НА ВЕРНОЙ РЕАЛИЗАЦИИ
-- минимум по двум типам из семи, и второй исход хуже первого: читатель «приведёт
-- стороны в согласие» и тронет материализацию, то есть поведение авторизации.
-- Разнесение держит гейт pg/scopeedgesource_gate_test.go (Г2), который печатает
-- число сверенных типов И число законных различий, которые он пропустил.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- РОЛЬ С ОБЛАСТЬЮ «ПРОЕКТ»: ЗВЕНО ПРОИЗВОДИТСЯ, ПРОБЕЛ МОДЕЛИ НАЗВАН
--
-- Схема допускает три взаимоисключающих якоря роли — ограничение
-- roles_definition_tier_xor: CHECK (num_nonnulls(cluster_id, account_id,
-- project_id) = 1). Материализация проектную роль достаёт (проектный столбец
-- COALESCE(o.project_id,''), аккаунтный добирается соединением с проектами).
-- Запасной путь не даёт НИЧЕГО: он читает roles.account_id, а у проектной роли
-- она NULL, и проекция при пустом аккаунте намеренно возвращает пусто. Модель
-- молчит: у типа iam_role объявлено единственное отношение-указатель, account.
--
-- Цепь производит ПРОЕКТНОЕ звено — потому что без него цепь проектной роли
-- пуста ЦЕЛИКОМ (взять хотя бы аккаунт невозможно: его нет по ограничению), то
-- есть отказ от звена был бы не осторожностью, а гарантированным отказом по
-- всем выдачам для целого класса объектов, которые решатель материализует.
-- К аккаунту такая роль поднимается ОБХОДОМ, через звено проекта, — величина та
-- же, что у материализации, путь другой.
--
-- ЦЕНА НАЗВАНА ЗАРАНЕЕ: по проектным ролям форма E будет отвечать «да» раньше,
-- чем модельный каскад (материализация догоняет; каскад не догонит никогда,
-- потому что арма «от проекта» в модели нет). При теневой сверке это даёт
-- классифицируемое расхождение в направлении «форма разрешает», и прибор обязан
-- считать его ОТДЕЛЬНЫМ ЗНАМЕНАТЕЛЕМ — растворённое в общей доле, оно либо
-- объявит достройку неудачной, либо научит игнорировать долю. Пробел модели
-- вынесен отдельным предметом и здесь НЕ чинится: гейт «у типа есть
-- отношение-указатель под каждое звено цепи» покраснел бы на этом решении, то
-- есть сторожил бы намерение против принятого.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПРИВЯЗКА: ТРИ ОБЛАСТНЫХ ЗНАЧЕНИЯ, И ЗВЕНО НЕ ЗАВИСИТ ОТ СТАТУСА
--
-- Область привязки — СВОБОДНЫЙ ТОКЕН по схеме: access_bindings_resource_ck
-- допускает любой ^[a-z][a-z0-9_]*$ либо '*'. Взять его в цепь без отбора
-- значило бы произвести звено на объект, отношения к которому у типа в модели
-- нет, и заодно соединить две колонки РАЗНЫХ СЛОВАРЕЙ имени типа — а такое
-- соединение не совпадает никогда и молча (класс, ради которого заведены
-- миграция 0091 и гейт TestEveryTypeColumnIsReadInItsOwnDictionary). Три
-- областных значения выбраны ещё и тем, что пишутся ОДИНАКОВО в обоих словарях,
-- поэтому вопроса о переводе на них не возникает вовсе.
--
-- Звено НЕ фильтруется по статусу, и это уже записанное решение: отозванная
-- привязка сохраняет строку и остаётся записью, которую администратор её
-- аккаунта обязан уметь прочитать и удалить; фильтр по статусу отнял бы это
-- ровно тогда, когда очередь отстала. Вернуть выдачу такое звено не может — у
-- получателя были кортежи на объекте ОБЛАСТИ, а это указатель НА ПРИВЯЗКУ.
-- Закреплено пробой cascade_queue_independence_integration_test.go::
-- TestRevokedBindingStaysManageableAndGrantsNothing.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ОБЪЕКТ БЕЗ ПРЕДКА — ЗАКОННЫЙ ИСХОД, А НЕ ПОТЕРЯ
--
-- Ветви ниже отбирают по НЕПУСТОТЕ источника, и объекты, у которых источник
-- предка не даёт, звена не получают ЗАКОННО:
--   * системная роль (cluster_id, оба остальных якоря пусты) — и это ПРАВИЛЬНО:
--     проекция запасного пути прямо говорит, что строка без владеющего аккаунта
--     «must not become reachable from any account's administrator». На стенде
--     таких 50 из 53 ролей;
--   * привязка, чья область вне трёх (ресурсная, '*');
--   * пользователь, группа или служебная учётка с пустым account_id.
-- Перепись, посчитавшая их потерями, произвела бы ЛОЖНЫЕ НАХОДКИ и показала бы
-- предмет хуже, чем он есть. Различает их ПРЕДИКАТ ПО ИСТОЧНИКУ, а не перечень
-- идентификаторов и не имя типа целиком: списком нельзя — системные роли
-- заводятся миграциями и будут заводиться дальше; именем типа нельзя — у
-- iam_role есть и аккаунтные роли, у которых предок обязан быть.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧИСЛО ЗВЕНЬЕВ НА ОБЪЕКТ: ЗАПАС ЕСТЬ, И ОН ПРОВЕРЯЕТСЯ
--
-- Довод 740001 («строк на объект не больше глубин, ключ resource_parent_edge
-- уникален по глубине») ОТМЕНЁН миграцией 781001 для журнальной ветви и здесь
-- НЕ ВОСКРЕШАЕТСЯ. Действующий довод — числом: указателей у объекта столько,
-- сколько у его типа РАЗНЫХ отношений-указателей. Каждая ветвь ниже даёт объекту
-- РОВНО ОДНО звено: у роли ветви (5a) и (5b) взаимоисключающи ограничением
-- схемы, у привязки строка несёт ровно одну пару «тип, идентификатор».
-- Замер на стенде после достройки: максимум 2 (проект: аккаунт и кластер) при
-- MaxAncestorDepth = 4; у 15 583 объектов из 15 819 звено ровно одно. Запас
-- двукратный, но он не самоочевиден и потому ПРОВЕРЯЕТСЯ переписью
-- iam-scope-source-census.sh, которая печатает максимум звеньев на объект и
-- отказывает, если он достиг предела обхода: объект, у которого звеньев столько
-- же, сколько предел, усекается МОЛЧА — цепь не доходит до корня, а отказ
-- неотличим от честного.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ВЛАДЕЛЕЦ, НАЗВАВШИЙ ЦЕПЬ СВОЕГО ОБЪЕКТА САМ, ВЫВОД ОТМЕНЯЕТ
--
-- NOT EXISTS по собственной стороне ребра сохранён ДОСЛОВНО из 740001/781001 в
-- каждой новой ветви: точное не затирается приблизительным. Сегодня правило
-- вырожденно (рёбер собственных типов iam в resource_parent_edge — 0, потому что
-- iam своих объектов не регистрирует), но оно остаётся действующим и
-- объявленным.

-- +goose Up

CREATE OR REPLACE VIEW kacho_iam.resource_scope_edge AS
  -- (1) То, что прислал владелец объекта. Дословно, без отбора: чей ресурс — того
  --     и цепь. Не изменилось.
  SELECT e.object_type, e.object_id, e.parent_type, e.parent_id, e.depth
    FROM kacho_iam.resource_parent_edge e
UNION ALL
  -- (2) Предок ПРОЕКТА — из ПРОЕКЦИИ ЖУРНАЛА (781001). Не изменилось.
  SELECT 'project'::text,
         f.object_id,
         split_part(f.subject, ':', 1),
         substr(f.subject, position(':' in f.subject) + 1),
         1
    FROM kacho_iam.relation_fact f
   WHERE f.object_type = 'project'
     AND f.relation = split_part(f.subject, ':', 1)
     AND position('#' in f.subject) = 0
     AND NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'project' AND e.object_id = f.object_id)
UNION ALL
  -- (3) Предок АККАУНТА — кластер, из схемы (740001). Не изменилось.
  SELECT 'account'::text, a.id, 'cluster'::text, c.id, 1
    FROM kacho_iam.accounts a
   CROSS JOIN kacho_iam.clusters c
   WHERE NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'account' AND e.object_id = a.id)
UNION ALL
  -- (4a) ПОЛЬЗОВАТЕЛЬ → аккаунт. Источник — kacho_iam.users.account_id, та же
  --      колонка, что читают iamDirectScanSpecs["iam.user"].parentAccountExpr и
  --      accountScopedTables["iam_user"].
  SELECT 'iam_user'::text, o.id, 'account'::text, o.account_id, 1
    FROM kacho_iam.users o
   WHERE COALESCE(o.account_id, '') <> ''
     AND NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'iam_user' AND e.object_id = o.id)
UNION ALL
  -- (4b) ГРУППА → аккаунт. Источник — kacho_iam.groups.account_id.
  SELECT 'iam_group'::text, o.id, 'account'::text, o.account_id, 1
    FROM kacho_iam.groups o
   WHERE COALESCE(o.account_id, '') <> ''
     AND NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'iam_group' AND e.object_id = o.id)
UNION ALL
  -- (4c) СЛУЖЕБНАЯ УЧЁТКА → аккаунт. Источник —
  --      kacho_iam.service_accounts.account_id. Проектной колонки у неё нет
  --      вовсе — она снята вместе с полем контракта, писателя у неё не было.
  SELECT 'iam_service_account'::text, o.id, 'account'::text, o.account_id, 1
    FROM kacho_iam.service_accounts o
   WHERE COALESCE(o.account_id, '') <> ''
     AND NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'iam_service_account' AND e.object_id = o.id)
UNION ALL
  -- (5a) РОЛЬ АККАУНТА → аккаунт. Источник — kacho_iam.roles.account_id.
  SELECT 'iam_role'::text, o.id, 'account'::text, o.account_id, 1
    FROM kacho_iam.roles o
   WHERE COALESCE(o.account_id, '') <> ''
     AND NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'iam_role' AND e.object_id = o.id)
UNION ALL
  -- (5b) РОЛЬ ПРОЕКТА → проект. Источник — kacho_iam.roles.project_id.
  --      Взаимоисключающа с (5a) ограничением roles_definition_tier_xor, а к
  --      аккаунту такая роль поднимается ОБХОДОМ, через звено (2). Системная
  --      роль (cluster_id) не попадает ни в одну ветвь — законно.
  SELECT 'iam_role'::text, o.id, 'project'::text, o.project_id, 1
    FROM kacho_iam.roles o
   WHERE COALESCE(o.project_id, '') <> ''
     AND NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'iam_role' AND e.object_id = o.id)
UNION ALL
  -- (6) ПРИВЯЗКА → её область. Источник — пара колонок
  --     kacho_iam.access_bindings.resource_type/resource_id, и ТОЛЬКО для трёх
  --     областных значений закрытого набора isBindableScope. lower() — тот же
  --     нормализатор, что у эмиттера (strings.ToLower в StructuralParent).
  --     Статус не читается намеренно.
  SELECT 'iam_access_binding'::text, o.id, lower(o.resource_type), o.resource_id, 1
    FROM kacho_iam.access_bindings o
   WHERE lower(o.resource_type) IN ('project', 'account', 'cluster')
     AND COALESCE(o.resource_id, '') <> ''
     AND NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'iam_access_binding' AND e.object_id = o.id);

COMMENT ON VIEW kacho_iam.resource_scope_edge IS
  'Цепь областей, какой её читает вопрос о доступе: рёбра, присланные владельцами ресурсов (resource_parent_edge), ПЛЮС достроенные звенья. Предок ПРОЕКТА берётся из проекции журнала (relation_fact, отношение называет тип субъекта) — оттуда же, откуда его берёт движок отношений (#781). Предок АККАУНТА — из схемы (accounts × clusters): аккаунты сеются миграциями без указателя в журнале (#740). Предок ПЯТИ СОБСТВЕННЫХ ТИПОВ iam — из СХЕМЫ, колонкой собственной строки (#785): users/groups/service_accounts/roles.account_id, roles.project_id для проектной роли (взаимоисключающе по roles_definition_tier_xor), access_bindings.resource_type/resource_id для трёх областных значений закрытого набора isBindableScope. Правило одно: источник, полный ПО ПОСТРОЕНИЮ для ЭТОГО звена. У пяти типов полна схема — строка И ЕСТЬ объект, указатель лежит её колонкой и неизменяем, а журнал наблюдаемо неполон: девять миграций сеют эти строки и ни одна не пишет указатель. Владелец, назвавший цепь своего объекта сам, вывод отменяет (NOT EXISTS) — ветви взаимоисключающи, двух мест об одном предмете нет. Каждая ветвь даёт объекту РОВНО ОДНО звено; максимум по дереву 2 при пределе обхода 4, и это проверяется переписью, а не выводится. ПИСАТЬ СЮДА НЕЛЬЗЯ: производители пишут в resource_parent_edge и в журнал.';


