-- 20260823001000 — ключ упорядочивания журнала снимается вместе со своим
-- писателем: триггер называл поле, которого у строки больше нет (kacho#1033).
--
-- ───────────────────────────────────────────────────────────────────────────
-- ПРИЗНАК
--
-- Всякая вставка в `kacho_iam.fga_outbox` отвергается базой:
--
--     ERROR: record "new" has no field "tuple_key" (SQLSTATE 42703)
--
-- Отказ приходит ИЗ ТЕЛА ТРИГГЕРА, а не из оператора вставки, поэтому в его
-- тексте не видно ни таблицы, ни виновника: `42703` в plpgsql означает ровно
-- одно — тело обращается к полю записи, которого у записи нет.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ: ФОРМА СТРОКИ И ТЕЛО ТРИГГЕРА РАЗОШЛИСЬ
--
-- Колонку `tuple_key` завела миграция 0067 как КЛЮЧ УПОРЯДОЧИВАНИЯ: дренаж
-- клеймил строку только тогда, когда в её партиции не осталось недоставленного
-- предшественника. Ключ материализовал триггер `fga_outbox_tuple_key_trigger`
-- (`BEFORE INSERT FOR EACH ROW`), а его наличие держало ограничение
-- `fga_outbox_tuple_key_present_check` — вместе это ОДИН механизм из трёх
-- частей, и части друг без друга не работают:
--
--   писатель      триггер, заполняющий NEW.tuple_key (0067, тело переписано 0099)
--   сторож        CHECK (tuple_key IS NOT NULL) NOT VALID — строка без ключа
--                 молча выпала бы из упорядочивания (NULL = NULL не истинно)
--   читатель      клейм дренажа — СНЯТ вместе с внешним движком прав
--
-- Читателя не стало 2026-08-21 (`a4b6cfba9`, стадия S6 эпика #747): дренаж и
-- его подстраховка удалены из состава сервиса. Журнал остался и остаётся не
-- «на всякий случай» — прямой факт, из которого собирается вердикт о доступе,
-- складывает из его строк триггер `relation_fact_follows_journal` (0098/0100).
-- Читает он `payload`, `event_type`, `created_at` и `id`; `tuple_key` не читает.
--
-- Колонку сняла миграция 20260822160000 (kacho#917) — правильно: величину, у
-- которой нет читателя, оплачивала каждая мутация выдачи. Но писатель и сторож
-- остались, и `DROP COLUMN` их не уносит **by construction**: тело plpgsql
-- разбирается при ИСПОЛНЕНИИ, поэтому база не знает, что триггер называет
-- снятое поле, и молчит до первой вставки.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ЦЕНА, ИЗМЕРЕННАЯ, А НЕ ПРЕДПОЛОЖЕННАЯ
--
-- Отказ накрывает НЕ ПРОБЫ, а путь мутации: `fga_outbox.EmitWriteTx` и
-- `EmitDeleteTx` вставляют ровно те же колонки (`event_type`, `payload`,
-- `created_at`), что и упавшая проба, — то есть отвергнута оказывается КАЖДАЯ
-- выдача и КАЖДЫЙ отзыв доступа, включая собственную регистрацию владельца.
-- Пять красных проб переписи были не предметом, а единственным местом, где это
-- стало видно.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ЧТО СНИМАЕТСЯ ЗДЕСЬ И ЧТО НЕ СНИМАЕТСЯ
--
--   снимается   триггер `fga_outbox_tuple_key_trigger` и его функция
--               `kacho_iam.fga_outbox_tuple_key()` — писатель ключа
--   снимается   ограничение `fga_outbox_tuple_key_present_check` — сторож
--               наличия ключа; без писателя он отвергал бы КАЖДУЮ вставку уже
--               по своей букве, то есть снятие писателя без сторожа заменило бы
--               один отказ другим
--   НЕ снимается  колонка `tuple_key` и частичные индексы по ней — это предмет
--               миграции 20260822160000 (kacho#917), и он там закрыт. Два
--               места об одном предмете разошлись бы на первой же правке;
--               оператор `DROP COLUMN IF EXISTS` здесь выглядел бы страховкой,
--               а был бы вторым автором того же решения.
--
-- Порядок с #917 значения не имеет: обе миграции идемпотентны и ни одна не
-- зависит от того, применена ли вторая. На дереве, где #917 ещё не применена,
-- эта миграция оставляет колонку без писателя — величину, которую никто не
-- заполняет и никто не читает; её снимет #917 своим номером.

-- +goose Up

-- Сторож снимается ПЕРВЫМ. Обратный порядок оставил бы окно, в котором писателя
-- уже нет, а сторож ещё требует ключ, — вставка отвергалась бы по нарушению
-- ограничения. Окно внутри одной транзакции миграции наружу не видно, но
-- порядок называется явно, чтобы следующая правка его не переставила.
ALTER TABLE kacho_iam.fga_outbox
    DROP CONSTRAINT IF EXISTS fga_outbox_tuple_key_present_check;

DROP TRIGGER IF EXISTS fga_outbox_tuple_key_trigger ON kacho_iam.fga_outbox;
DROP FUNCTION IF EXISTS kacho_iam.fga_outbox_tuple_key();

-- +goose Down

-- Возврат восстанавливает механизм ЦЕЛИКОМ и только там, где у него есть
-- предмет: без колонки `tuple_key` восстановленный триггер отверг бы каждую
-- вставку — то есть безусловный возврат воспроизвёл бы ровно тот дефект,
-- который эта миграция закрывает. Поэтому он спрашивает про колонку и, не найдя
-- её, говорит об этом вслух, а не молчит.

-- +goose StatementBegin
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = 'kacho_iam'
           AND table_name   = 'fga_outbox'
           AND column_name  = 'tuple_key'
    ) THEN
        RAISE NOTICE 'kacho_iam.fga_outbox.tuple_key отсутствует (снята миграцией 20260822160000): восстанавливать писателя ключа не над чем, возврат — пустой';
        RETURN;
    END IF;

    CREATE OR REPLACE FUNCTION kacho_iam.fga_outbox_tuple_key() RETURNS trigger
        LANGUAGE plpgsql AS $fn$
        BEGIN
            NEW.tuple_key := (NEW.payload->>'user') || ' ' || (NEW.payload->>'object');
            RETURN NEW;
        END;
        $fn$;

    DROP TRIGGER IF EXISTS fga_outbox_tuple_key_trigger ON kacho_iam.fga_outbox;
    CREATE TRIGGER fga_outbox_tuple_key_trigger
        BEFORE INSERT ON kacho_iam.fga_outbox
        FOR EACH ROW EXECUTE FUNCTION kacho_iam.fga_outbox_tuple_key();

    UPDATE kacho_iam.fga_outbox
       SET tuple_key = (payload->>'user') || ' ' || (payload->>'object')
     WHERE tuple_key IS NULL;

    ALTER TABLE kacho_iam.fga_outbox
        ADD CONSTRAINT fga_outbox_tuple_key_present_check
        CHECK (tuple_key IS NOT NULL) NOT VALID;
END
$$;
-- +goose StatementEnd
