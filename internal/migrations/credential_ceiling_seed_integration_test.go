// credential_ceiling_seed_integration_test.go — СТРОКА УЧЁТА потолка заводится
// вместе с носителем и начинается с НУЛЯ (задача #1191, приёмка §7.4).
//
// # Что здесь держится
//
// Учёт потолка ведут два механизма, и оба обязаны считать ОДНО: строка учёта
// заводится триггером жизненного цикла носителя, а списание правит её на каждой
// выдаче. Проба ниже утверждает начало отсчёта — у принципала БЕЗ удостоверений
// потребление ровно ноль. Другую сторону той же пары утверждает
// `TestCredRcl29_TheRevisedCeilingIsTheOneThatChargingUses`: после одиннадцати
// выдач потребление одиннадцать. Порознь каждая половина зеленела бы на учёте,
// который ставит что попало: первая — на учёте, всегда пишущем ноль; вторая —
// на учёте, считающем от произвольного начала.
//
// # Здесь стояла проба ЗАТРАВКИ (CRED-CAP-35) — предмета у неё нет
//
// Она доводила цепочку до состояния ПЕРЕД потолком, сеяла удостоверения и
// требовала, чтобы миграция потолка завела строку учёта с ФАКТИЧЕСКИМ их числом,
// а не с нулём. Миграций сервиса теперь одна — свод, — и версии, на которой
// можно остановиться «перед потолком», не существует: величины потолка лежат в
// своде с самого начала, поэтому её собственная проверка предпосылки
// («величина потолка уже посеяна») срабатывала первой же строкой.
//
// Проба снята вместе со своим предметом, а не ослаблена: обратное заполнение
// уже лежавших строк — свойство разового перехода, а не схемы. Сценарий приёмки
// CRED-CAP-35 остался без держателя, и это назван в отчёте линии остаток: он был
// НЕСУЩИМ (приёмка называет его единственным путём работы, трогающим живое
// дерево), поэтому вместе с ним без держателя остались и утверждения, которые он
// нёс один, — «существующие сверх предела не удаляются» на живом переходе.

package migrations_test

import (
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/PRO-Robotech/kacho/pkg/pgtest"
)

// CRED-CAP-35 (то, что от него осталось наблюдаемым) — принципал БЕЗ
// удостоверений получает строку учёта, и она начинается с НУЛЯ.
//
// Утверждается ПАРА, а не одно число: строка учёта обязана СУЩЕСТВОВАТЬ (иначе
// списание не с чего вести и предел не наступит никогда) и обязана нести ноль.
// Второй половиной пары служит `TestCredRcl29_TheRevisedCeilingIsTheOneThatChargingUses`
// — там у принципала одиннадцать выдач и потребление одиннадцать. Без неё «ноль»
// зеленел бы на учёте, всегда пишущем ноль.
func TestCredentialCeilingSeed_APrincipalWithoutCredentialsStartsAtZero(t *testing.T) {
	if testing.Short() {
		t.Skip("integration: нужен Postgres в контейнере")
	}
	db := upAllIAMMigrations(t, pgtest.NewEmptyDB(t))
	defer db.Close()

	seedCredentialOwners(t, db)

	// Перепись: строки учёта у обоих видов носителя обязаны быть заведены
	// жизненным циклом носителя. Ноль строк означал бы, что предел не наступит
	// никогда, — и утверждение о величине ниже зеленело бы, не прочитав ничего.
	var rows int
	require.NoError(t, db.QueryRow(`
		SELECT count(*) FROM kaname.project_resource_quotas
		 WHERE kind IN ('iam.user.credential', 'iam.serviceAccount.credential')`).Scan(&rows))
	require.Positive(t, rows,
		"строк учёта у видов удостоверения не заведено ни одной: списанию не с чего "+
			"вести счёт, и предел не наступит никогда")
	t.Logf("осмотрено: строк учёта по видам удостоверения %d", rows)

	var used int64
	require.NoError(t, db.QueryRow(`
		SELECT used FROM kaname.project_resource_quotas
		 WHERE carrier_type = 'iam.user' AND carrier_id = 'usr00000000000000bat'
		   AND kind = 'iam.user.credential'`).Scan(&used))
	require.EqualValues(t, 0, used,
		"у принципала без удостоверений потребление не ноль: учёт считает не то, что считает списание")

	require.NoError(t, db.QueryRow(`
		SELECT used FROM kaname.project_resource_quotas
		 WHERE carrier_type = 'iam.serviceAccount' AND carrier_id = 'sva00000000000000bat'
		   AND kind = 'iam.serviceAccount.credential'`).Scan(&used))
	require.EqualValues(t, 0, used, "то же у служебной учётки")
}
