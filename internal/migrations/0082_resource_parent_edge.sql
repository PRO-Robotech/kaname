-- 0082_resource_parent_edge — цепь родительства объекта произвольной формы.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЗАЧЕМ ОТДЕЛЬНАЯ ТАБЛИЦА, ЕСЛИ У ЗЕРКАЛА УЖЕ ДВА ПРЕДКА
--
-- `resource_mirror` несёт ровно `parent_project_id` и `parent_account_id` — двух
-- предков и ровно этих. Модель прав требует цепи ПРОИЗВОЛЬНОЙ формы:
-- репозиторий → реестр → проект → аккаунт → кластер, глубина четыре. Объект,
-- чей ближайший предок не проект и не аккаунт, в двух колонках не выражается
-- вовсе.
--
-- Это не «на будущее»: сегодня такой объект регистрируется БЕЗ предка, а объект
-- без предка молча выпадает из области выдачи и из каскада — вопрос о нём
-- задаётся, ответ «нет», и это неотличимо от честного отказа.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ РЕБРО, А НЕ МАССИВ В СТРОКЕ ЗЕРКАЛА
--
-- По цепи ходят ВВЕРХ (предки объекта) и ВНИЗ (что лежит под областью). Второе —
-- рекурсивный обход, и он выражается соединением по ребру, а массив пришлось бы
-- разворачивать на каждом шаге. Плюс ребро — единица, которую можно
-- проиндексировать в обе стороны.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ
--
-- Ни одно решение о доступе её не читает — это expand-шаг: пишем, не читаем.
-- Обратное заполнение существующих строк идёт ОТДЕЛЬНОЙ миграцией, когда
-- поставщики начнут слать цепь: заполнять сейчас нечем, а миграция, делающая
-- вид, что заполнила, хуже отсутствующей.

-- +goose Up

CREATE TABLE kacho_iam.resource_parent_edge (
  -- Объект и его НЕПОСРЕДСТВЕННЫЙ предок — обе стороны в форме зеркала
  -- (`object_type` + `object_id`), а не строкой `"type:id"`: строку пришлось бы
  -- разбирать на каждом соединении, и разбор стал бы вторым местом, знающим
  -- форму имени.
  object_type       text    NOT NULL,
  object_id         text    NOT NULL,
  parent_type       text    NOT NULL,
  parent_id         text    NOT NULL,

  -- Расстояние до предка: 1 — непосредственный. Хранится, потому что порядок
  -- цепи — часть факта: «проект над репозиторием» и «аккаунт над репозиторием»
  -- различаются именно им, а вывести его из набора рёбер можно только обходом.
  depth             int     NOT NULL,

  -- Версия состояния у владельца — тот же смысл, что у зеркала: применяем ребро,
  -- только если оно строго новее хранимого. Без этого переупорядоченная доставка
  -- двух регистраций одного объекта затирала бы свежую цепь устаревшей.
  source_version    timestamptz NOT NULL DEFAULT '-infinity',
  updated_at        timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT resource_parent_edge_pkey PRIMARY KEY (object_type, object_id, depth),

  CONSTRAINT resource_parent_edge_object_type_nonempty CHECK (object_type <> ''),
  CONSTRAINT resource_parent_edge_object_id_nonempty   CHECK (object_id   <> ''),
  CONSTRAINT resource_parent_edge_parent_type_nonempty CHECK (parent_type <> ''),
  CONSTRAINT resource_parent_edge_parent_id_nonempty   CHECK (parent_id   <> ''),

  -- Глубина ограничена КОНСТАНТОЙ, а не «пока не кончится»: цепь без предела
  -- превращает обход вверх в неограниченную работу на пути запроса, а цикл в
  -- данных — в вечный запрос. Предел совпадает с тем, что объявляет компилятор
  -- модели (`authzplan.MaxPointerDepth`); расхождение этих двух величин ловит
  -- проба рядом с ним.
  CONSTRAINT resource_parent_edge_depth_bounded CHECK (depth BETWEEN 1 AND 4),

  -- Объект не может быть предком самому себе НИ НА КАКОЙ глубине: это цикл, и
  -- обход вверх на нём не завершится.
  CONSTRAINT resource_parent_edge_no_self CHECK (
    NOT (object_type = parent_type AND object_id = parent_id)
  )
);

-- Обход ВНИЗ: «что лежит под этой областью». Второе направление — то, ради
-- которого ребро и заведено отдельной строкой.
CREATE INDEX resource_parent_edge_by_parent
  ON kacho_iam.resource_parent_edge (parent_type, parent_id);

-- +goose Down

DROP TABLE IF EXISTS kacho_iam.resource_parent_edge;
