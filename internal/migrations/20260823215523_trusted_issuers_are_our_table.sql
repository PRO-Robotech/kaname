-- +goose Up
-- Перечень доверенных издателей утверждения — НАША таблица (задача #1124).
--
-- ПРЕДМЕТ. Решение о том, вправе ли посторонний издатель поручиться за свой
-- субъект, принимал внешний поставщик: запись жила у него, ключ издателя — тоже,
-- и наша проверка утверждения о ней не знала вовсе. Пока перечень чужой,
-- федеративный ключ не может быть решён нами целиком, а административная дорога
-- к поставщику остаётся нужной.
--
-- ЧТО ХРАНИТСЯ. Ровно то, что хранил грант у поставщика: издатель, ТОЧНЫЙ
-- субъект, открытый ключ издателя, его алгоритм и срок доверия. Форма повторена
-- намеренно — перевод перечня к нам не должен был заодно менять то, о чём
-- перечень.
--
-- ПОЧЕМУ КЛЮЧ, А НЕ АДРЕС НАБОРА КЛЮЧЕЙ. Таблицу читает проверка утверждения на
-- пути запроса. Адрес означал бы обращение к постороннему хосту, выбранному
-- арендатором, из процесса, принимающего решение о доступе. Ключ, названный при
-- выдаче, решения о доступе никуда не выносит.
-- +goose StatementBegin
CREATE TABLE IF NOT EXISTS kacho_iam.federated_trusted_issuers (
    -- Издатель, сверяемый с `iss` предъявленного утверждения ДОСЛОВНО.
    issuer text NOT NULL,
    -- ТОЧНЫЙ субъект, сверяемый с `sub` дословно. Не образец: запись,
    -- покрывающая субъектов образцом, называет тех, кого выдававший не
    -- перечислял, и установить их состав нельзя ни по записи, ни по журналу.
    subject text NOT NULL,
    -- Наша строка федеративного ключа, которую эта запись уполномочивает.
    -- Внешний субъект получает токен от её имени, никогда от своего.
    sa_oauth_client_id text NOT NULL,
    -- Открытый ключ ИЗДАТЕЛЯ (SPKI PEM) и его алгоритм.
    public_key_pem text NOT NULL,
    key_algorithm text NOT NULL,
    -- Срок ДОВЕРИЯ. NULL означает «бессрочно» и является законным состоянием:
    -- ключ, выданный без срока, не вправе получить доверие со сроком, взятым
    -- из ниоткуда.
    expires_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),

    -- ПАРА (издатель, субъект) ГЛОБАЛЬНО УНИКАЛЬНА, и это несущий инвариант, а
    -- не удобство поиска.
    --
    -- Без него две наши строки могли бы поручиться за один и тот же внешний
    -- субъект, и разрешение пары стало бы недетерминированным: тот же
    -- предъявитель получал бы токен то одной служебной учётной записи, то
    -- другой. Инвариант держит ПЕРВИЧНЫЙ КЛЮЧ, а не проверка перед вставкой:
    -- «посмотреть, занято ли, и вставить» под конкуренцией пропускает обе
    -- вставки (ban #10).
    CONSTRAINT federated_trusted_issuers_pkey PRIMARY KEY (issuer, subject),

    CONSTRAINT federated_trusted_issuers_client_fk
        FOREIGN KEY (sa_oauth_client_id)
        REFERENCES kacho_iam.service_account_oauth_clients (id) ON DELETE CASCADE,

    -- Отзыв ключа снимает доверие ВМЕСТЕ с ним — тем же каскадом одной базы, а
    -- не отдельным действием, которое можно забыть. Доверие, пережившее строку,
    -- ради которой выдавалось, продолжало бы называть постороннего доверенным
    -- при отсутствии того, кем он представлялся.

    -- Ключевой материал непуст, и алгоритм — из ЗАКРЫТОГО словаря.
    --
    -- Пустой ключ означал бы «доверяем этой паре без проверки подписи», то есть
    -- ровно тот класс, ради которого перечень и заводится: величина, которая
    -- может быть пустой и не проверена на непустоту, означает «принимаем
    -- любого».
    CONSTRAINT federated_trusted_issuers_key_not_blank
        CHECK (btrim(public_key_pem) <> '' AND length(public_key_pem) <= 8192),
    CONSTRAINT federated_trusted_issuers_alg_ck
        CHECK (key_algorithm IN ('ES256', 'RS256', 'EdDSA')),
    CONSTRAINT federated_trusted_issuers_issuer_ck
        CHECK (btrim(issuer) <> '' AND length(issuer) <= 512),
    CONSTRAINT federated_trusted_issuers_subject_ck
        CHECK (btrim(subject) <> '' AND length(subject) <= 512),
    -- Срок доверия, если назван, лежит в будущем относительно момента записи.
    CONSTRAINT federated_trusted_issuers_expires_future_ck
        CHECK (expires_at IS NULL OR expires_at > created_at)
);
-- +goose StatementEnd

-- Разрешение идёт по паре, то есть первичным ключом. Отдельный индекс нужен
-- ДРУГОМУ читателю — снятию доверия вместе со строкой ключа и перечислению
-- выданного по ней.
-- +goose StatementBegin
CREATE INDEX IF NOT EXISTS federated_trusted_issuers_by_client_idx
    ON kacho_iam.federated_trusted_issuers (sa_oauth_client_id);
-- +goose StatementEnd

-- +goose StatementBegin
COMMENT ON TABLE kacho_iam.federated_trusted_issuers IS
  'Перечень доверенных издателей утверждения (#1124). Читается проверкой утверждения на пути запроса (internal/clientassertion, федеративная полоса) — до этой задачи перечень вёл внешний поставщик, и решение о доверии принимал он. Пара (issuer, subject) глобально уникальна: иначе разрешение стало бы недетерминированным. Пустая таблица означает «не доверяем никому» и является законным состоянием.';
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
DROP TABLE IF EXISTS kacho_iam.federated_trusted_issuers;
-- +goose StatementEnd
