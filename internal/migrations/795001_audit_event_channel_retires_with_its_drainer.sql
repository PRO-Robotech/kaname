-- 795001_audit_event_channel_retires_with_its_drainer — уведомление снимается
-- вместе с триггером, потому что будить им некого и в этой фазе будет некого.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Триггер на kacho_iam.audit_outbox шлёт pg_notify('audit_event', '') на каждую
-- вставку. Слушателей — НОЛЬ, и ноль их с первого дня схемы. Перепись по всему
-- дереву (не только по .go) даёт ДВА файла со строкой audit_event: сама
-- миграция-производитель и файл пробы, чьё имя лишь совпадает по звучанию
-- (он про идентификатор события, а не про канал). Контроль предиката: канал со
-- слушателем находится в шести файлах.
--
-- Уведомление к тому же уходит с ПУСТОЙ нагрузкой, то есть даже появившийся
-- слушатель узнал бы только «что-то случилось» и мог бы лишь перечитать всё.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ СНИМАЕТСЯ, А НЕ ДОСТРАИВАЕТСЯ
--
-- Уведомление такого рода существует ради ОДНОГО: разбудить дренаж очереди,
-- чтобы он не ждал следующего тика опроса. Дренажа у этой очереди нет, и
-- построить его сегодня нельзя — приёмника аудита в продукте не существует ни
-- одного. Значит канал не «недоделан», у него нет предмета: он ускоряет то,
-- чего не происходит.
--
-- Держать его «под будущий дренаж» — ровно тот класс, ради закрытия которого
-- заведены #755 и #795: механизм есть, потребителя нет. Будущий приёмник придёт
-- своей под-фазой и своей приёмкой и приведёт своё пробуждение — вместе с
-- дренажом, который оно будит, а не за три фазы до него.
--
-- Что при этом НЕ снимается и почему: таблица audit_outbox остаётся целиком, со
-- всеми строками и всеми писателями. Её снятие — решение уровня требований к
-- журналу аудита control-plane, а не уборка кода; оно записано отдельно, вместе
-- с предикатом пересмотра:
-- services/iam/docs/engineering/architecture/audit-outbox-has-no-receiver.md
--
-- Наблюдаемость очереди этой миграцией не затрагивается и от канала не зависела
-- никогда: состояние снимает периодический сканер таблицы
-- (runAuditOutboxMetrics), а он опрашивает, а не слушает.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОРЯДОК
--
-- Снимается только ОБЪЯВЛЕНИЕ (триггер и его функция). Данных у канала нет:
-- уведомление не хранится, обратного заполнения не требуется, строки таблицы не
-- трогаются — обратимость поэтому тривиальна, и Down восстанавливает ровно
-- снятое, включая уровень срабатывания (FOR EACH STATEMENT) и RETURN NULL.
--
-- Регрессия: services/iam/internal/migrations/notify_channel_has_a_listener_integration_test.go
-- — утверждает по ЖИВОЙ схеме после проигрывания, что производителя больше нет,
-- и парно, что канал очереди со слушателем производителя сохранил.

-- +goose Up

DROP TRIGGER IF EXISTS audit_outbox_notify_trg ON kacho_iam.audit_outbox;
DROP FUNCTION IF EXISTS kacho_iam.audit_outbox_notify();

-- +goose Down

-- +goose StatementBegin
CREATE FUNCTION kacho_iam.audit_outbox_notify() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    PERFORM pg_notify('audit_event', '');
    RETURN NULL;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER audit_outbox_notify_trg
    AFTER INSERT ON kacho_iam.audit_outbox
    FOR EACH STATEMENT EXECUTE FUNCTION kacho_iam.audit_outbox_notify();
