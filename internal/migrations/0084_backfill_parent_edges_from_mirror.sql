-- 0084_backfill_parent_edges_from_mirror — рёбра для объектов, зарегистрированных
-- ДО появления цепи.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЗАЧЕМ ОТДЕЛЬНАЯ МИГРАЦИЯ, А НЕ ПРАВКА 0082
--
-- 0082 применена. Править применённую миграцию запрещено (ban #5): у того, кто
-- её уже накатил, изменение не исполнится, и две базы разойдутся, оставаясь обе
-- «на последней версии».
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО ЗАПОЛНЯЕТСЯ И ЧЕГО ХВАТИТ
--
-- Цепь приходит от владельцев ресурсов, и приходит она только на НОВЫХ
-- регистрациях. Объекты, зарегистрированные раньше, остались бы без рёбер —
-- а объект без предка молча выпадает из области выдачи и из каскада.
--
-- Заполняется тем, что iam УЖЕ знает о себе: двумя колонками зеркала. Это не
-- полная цепь произвольной формы — промежуточных звеньев (реестр над
-- репозиторием) в зеркале нет и взяться им неоткуда, — но это ровно та цепь,
-- которая действовала до сих пор. То есть заполнение восстанавливает
-- СЕГОДНЯШНЮЮ картину, а не выдумывает вчерашнюю.
--
-- ЧЕСТНО НАЗВАННАЯ ГРАНИЦА: у объекта с более глубокой иерархией промежуточное
-- звено появится при первой же перерегистрации владельцем (он теперь шлёт
-- цепь), а до неё объект останется с той цепью, с которой жил всегда. Это не
-- ухудшение и не улучшение — это то же самое, и притворяться, что миграция
-- восстановила больше, было бы ложью о её силе.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ БЕЗ ПЕРЕЗАПИСИ СУЩЕСТВУЮЩИХ
--
-- `ON CONFLICT DO NOTHING`: если ребро уже пришло от владельца, оно ТОЧНЕЕ
-- выведенного из двух колонок — владелец знает свою иерархию, зеркало знает
-- только её проекцию на проект и аккаунт. Заполнение не вправе затирать точное
-- приблизительным.

-- +goose Up

-- Ближайший предок: проект, если зеркало его знает.
INSERT INTO kacho_iam.resource_parent_edge
  (object_type, object_id, parent_type, parent_id, depth, source_version, updated_at)
SELECT m.object_type, m.object_id, 'project', m.parent_project_id, 1, m.source_version, now()
  FROM kacho_iam.resource_mirror m
 WHERE m.parent_project_id <> ''
ON CONFLICT (object_type, object_id, depth) DO NOTHING;

-- Следующий предок: аккаунт. Глубина 2, когда проект известен, и 1, когда нет:
-- цепь обязана быть НЕПРЕРЫВНОЙ, иначе обход вверх остановится на дыре и
-- объявит объект не принадлежащим аккаунту.
INSERT INTO kacho_iam.resource_parent_edge
  (object_type, object_id, parent_type, parent_id, depth, source_version, updated_at)
SELECT m.object_type, m.object_id, 'account', m.parent_account_id,
       CASE WHEN m.parent_project_id <> '' THEN 2 ELSE 1 END,
       m.source_version, now()
  FROM kacho_iam.resource_mirror m
 WHERE m.parent_account_id <> ''
ON CONFLICT (object_type, object_id, depth) DO NOTHING;

-- +goose Down

-- Снимаются ТОЛЬКО выведенные рёбра — те, чей предок проект или аккаунт. Ребро,
-- пришедшее от владельца на промежуточное звено, этой миграцией не заводилось и
-- ею не снимается: откат обязан возвращать состояние, а не обеднять его.
DELETE FROM kacho_iam.resource_parent_edge
 WHERE parent_type IN ('project', 'account');
