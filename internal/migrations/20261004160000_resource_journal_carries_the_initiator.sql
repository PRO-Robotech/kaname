-- resource_journal_carries_the_initiator — строка ресурсного журнала службы
-- доступа несёт ИНИЦИАТОРА изменения (задача PRO-Robotech/kaname#484, полоса
-- X4J; сценарий NTF3-63).
--
-- Санкция: приёмка `docs/specs/sub-phase-NTF-3-kacho-modules-notifications-acceptance.md`
-- репозитория PRO-Robotech/kacho-workspace, Р2 и NTF3-62/NTF3-63, одобрена на
-- отпечатке `ac1f9fc91e4b13e248b9a9bc3a9d31a3c015021714a3461ecc02dbf651ca4ac1`;
-- замысел `docs/changes/issue-2918/design.md`, З2 и З4. Доводы там; здесь —
-- то, что нужно читателю СХЕМЫ.
--
-- =============================================================================
-- ОТКУДА ЗНАЧЕНИЕ
-- =============================================================================
-- Единственный производитель значения — УМОЛЧАНИЕ колонки из настройки
-- транзакции `kacho_journal.initiator`, которую первым оператором выставляет
-- помощник `journaltx.Begin` (локально к транзакции). Оператор вставки в
-- журнал — функции `resource_journal_emit*` — колонку не называет. Настройки
-- нет либо она пуста — `NULLIF` даёт NULL, и `NOT NULL` отвергает строку
-- `23502` с именем колонки; а вместе со строкой журнала — и изменение ресурса,
-- чей триггер её писал: записи без инициатора не бывает ни в журнале, ни в
-- ресурсе.
--
-- =============================================================================
-- ФОРМА
-- =============================================================================
-- Та, что строит `auth.InitiatorOf` corelib, и только она:
--   * `user:` + id семейства пользователя (`usr`), слитной либо дефисной формы,
--     тело — 17 знаков алфавита Крокфорда;
--   * `service_account:` + id семейства сервисного аккаунта (`sva`), те же формы;
--   * `system:` + DNS-метка (RFC 1123, 1..63) — личность компонента
--     `auth.SystemPrincipalFor(<служба>, <роль>)`.
-- Пустая строка, `user:system.…`, id чужого семейства — отказ `23514`.
-- Согласие выражения с `auth.InitiatorOf` держит проба
-- `resource_journal_initiator_form_agrees_with_corelib_integration_test.go`.
--
-- =============================================================================
-- ВРЕМЯ
-- =============================================================================
-- Новой колонки времени нет: `created_at TIMESTAMPTZ NOT NULL DEFAULT now()` —
-- время транзакции изменения; событие несёт его усечённым до секунды.
--
-- =============================================================================
-- СТРОКИ, ЗАПИСАННЫЕ ДО ЭТОЙ МИГРАЦИИ
-- =============================================================================
-- Умолчание вычисляется и для каждой уже лежащей строки. На свежей базе их
-- пишет САМА цепь миграций: снятия и правки посевных строк поздними миграциями
-- (на ревизии этой миграции — три строки: `iam_access_binding DELETED`,
-- `iam_group DELETED`, `iam_user UPDATED`). Их инициатор — компонент, который
-- цепь исполняет, и потому первым оператором выставляется настройка
-- `system:kaname-migrator` локально к транзакции миграции (goose исполняет
-- файл одной транзакцией): прежние строки получают инициатора из того же
-- умолчания, что и будущие, и колонку ни один оператор не называет.
--
-- Стенд с журналом, в который писали люди, этой миграцией приписал бы их
-- изменения компоненту. Такого стенда не бывает: прода нет, стенды поднимаются
-- заново (Д12 приёмки).
--
-- Поздняя миграция, пишущая журналируемую таблицу, выставляет ту же настройку
-- сама: без неё строка журнала, а с ней и миграция, отвергается `23502`.

-- +goose Up

SELECT set_config('kacho_journal.initiator', 'system:kaname-migrator', true);

ALTER TABLE kaname.resource_journal
  ADD COLUMN initiator text NOT NULL
    DEFAULT NULLIF(current_setting('kacho_journal.initiator', true), '')
    CONSTRAINT resource_journal_initiator_form CHECK (initiator ~ (
      '^(user:usr-?[0-9a-hjkmnp-tv-z]{17}'
      || '|service_account:sva-?[0-9a-hjkmnp-tv-z]{17}'
      || '|system:[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?)$'));

-- +goose Down

ALTER TABLE kaname.resource_journal DROP COLUMN initiator;
