-- 20260902174500_selector_types_name_a_live_resource — ТРЕТЬЯ поверхность
-- проекции правила получает референт: каждый элемент
-- `role_rule_selectors.object_types` обязан называть ЖИВУЮ строку каталога.
--
-- Приёмка: services/iam/docs/engineering/acceptance/roles-pointing-at-moved-resources.md
-- (APPROVED круга 2). Сценарии IAM-RM-1-08, -09, -10, -16. Задача продукта #1825.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО НЕВЕРНО СЕГОДНЯ
--
-- Правило роли проецируется в ТРИ места, и референт есть у двух: у `role_rule_ref`
-- (ключ `role_rule_ref_res_fk`) и у `role_verb` (ключ `role_verb_type_fk`). У
-- третьего — массива точечных типов в одной строке селекторов — ключа нет и быть
-- не может: внешний ключ на ЭЛЕМЕНТ массива в Postgres невыразим.
--
-- Расхождение это не гипотетическое, а действующее, и у него РАЗНЫЕ ИСТОЧНИКИ.
-- Проекцию глаголов пересчитывает досев ИЗ КАТАЛОЖНОГО ФАКТА — снятый тип до
-- ключа не доезжает. Селекторы пересчитывает досев ИЗ ОБЪЯВЛЕНИЯ, а точечный тип
-- собирается склейкой `модуль || '.' || ресурс` без сверки с чем бы то ни было.
-- Значит селектор, называющий мёртвый тип, записывается МОЛЧА, а реконсайлер
-- получает работу по типу, объектов которого не существует. Ровно поэтому
-- миграции `0074` пришлось вычищать селекторы двумя отдельными шагами вручную:
-- снять строку, называвшую только снятые типы, и вырезать снятые элементы из
-- подстановочных строк. Ручная вычистка закрывает экземпляр; референт закрывает
-- класс.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ТРИГГЕР, А НЕ ПРОВЕРКА В КОДЕ
--
-- Software check-then-act запрещён (запрет #10): между «спросить каталог» и
-- «вставить строку» существует окно, и под конкуренцией снятие ресурса и запись
-- селектора разойдутся. Ключ на элемент массива невыразим. Остаётся триггер — тем
-- же приёмом и по тому же доводу, каким заведён триггер назначаемости роли.
--
-- Писателей у таблицы ДВА — путь пользовательской роли (`ReplaceRuleSelectors`) и
-- досев системных селекторов, — и это ровно та раскладка, из-за которой инвариант,
-- поставленный на одном писателе, не держится: второй его не исполняет и об этом
-- не знает.
--
-- Форма — `BEFORE INSERT OR UPDATE`, без сужения `OF object_types`: оба писателя
-- пишут через `ON CONFLICT … DO UPDATE`, и сужение пропустило бы обновление,
-- которое массив меняет через `EXCLUDED`.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ОТКАЗ НАЗЫВАЕТ ЭЛЕМЕНТ, А НЕ СТРОКУ
--
-- Подстановочные строки собирает досев, и автор правила ни одного их элемента сам
-- не выбирал. Отказ «в массиве что-то не то» посылает его перечитывать массив,
-- которого он не писал; отказ, называющий ЭЛЕМЕНТ, называет предмет.
--
-- Проверяется КАЖДЫЙ элемент, а не первый: массив, чей первый тип жив, а второй
-- снят, — самая частая форма после ручной вычистки, и разбор, останавливающийся
-- на первом, пропустил бы её целиком.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- FAIL-CLOSED ВЫБРАН, А НЕ СЛУЧИЛСЯ
--
-- Триггер делает наблюдаемым то, что сегодня тихо: пока литерал типов и каталог
-- сходятся, он молчит; разойдись они — досев на старте получит отказ, и служба не
-- поднимется. Альтернатива — пропускать элемент, которого нет в каталоге, — есть
-- ровно тот дефект, который эта миграция закрывает: селектор адресовал бы объекты
-- типа, которого платформа не обслуживает, а вердикт по такой выдаче отказывал бы
-- молча. Тихая полуработа не стоит ничего.
--
-- Цена названа и ограничена: отказ приходит НА СТАРТЕ, не на пути запроса
-- арендатора, и его текст называет элемент и роль. Условие наступления — рассинхрон
-- литерала типов и каталога, то есть состояние, которое закрывает задача #1816.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ДАННЫХ МИГРАЦИЯ НЕ ТРОГАЕТ
--
-- Ни одной строки `roles`, `access_bindings`, `role_rule_selectors` она не пишет:
-- триггер судит ВХОД, а уже лежащие строки не перечитывает. Обратный путь поэтому
-- полный — `DROP TRIGGER` в откатной половине ничего не восстанавливает и ничего
-- не теряет. Что уже лежащие строки не проверены — сказано вслух, а не умолчано:
-- их живость утверждает обход по объявлению
-- (`role_declaration_referent_integration_test.go`), у которого единица счёта своя.

-- +goose Up

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION kacho_iam.role_rule_selector_types_live() RETURNS trigger
    LANGUAGE plpgsql
AS $$
DECLARE
    object_type text;
BEGIN
    FOREACH object_type IN ARRAY NEW.object_types LOOP
        IF NOT EXISTS (
            SELECT 1 FROM kacho_iam.catalog_resource cr
             WHERE cr.dotted = object_type AND cr.live
        ) THEN
            RAISE EXCEPTION
                'object_types: % is not a live platform resource (role %)',
                object_type, NEW.role_id
                USING ERRCODE = '23514',
                      CONSTRAINT = 'role_rule_selectors_types_live';
        END IF;
    END LOOP;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

COMMENT ON FUNCTION kacho_iam.role_rule_selector_types_live() IS
  'Референт ТРЕТЬЕЙ поверхности проекции правила: каждый элемент role_rule_selectors.object_types обязан называть живую строку kacho_iam.catalog_resource. Внешний ключ на элемент массива невыразим, проверка в коде запрещена (ban #10) — поэтому триггер. Проверяется КАЖДЫЙ элемент; отказ 23514 называет элемент и роль.';

CREATE TRIGGER role_rule_selectors_types_live
    BEFORE INSERT OR UPDATE ON kacho_iam.role_rule_selectors
    FOR EACH ROW EXECUTE FUNCTION kacho_iam.role_rule_selector_types_live();

-- +goose Down

-- Откат полный: триггер СУДИТ вход и состояния не меняет, поэтому снятие ничего
-- не восстанавливает и ничего не теряет. Порядок обязателен — функция снимается
-- ПОСЛЕ триггера, который её зовёт.
DROP TRIGGER IF EXISTS role_rule_selectors_types_live ON kacho_iam.role_rule_selectors;
DROP FUNCTION IF EXISTS kacho_iam.role_rule_selector_types_live();
