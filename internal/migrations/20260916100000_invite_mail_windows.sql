-- Окно частоты писем приглашения НА АДРЕС (приёмка ID-MAIL-1, Р14/Р22,
-- MAIL-25, MAIL-42; задача продукта #1775).
--
-- ────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Письмо приглашения отправляют ДВА наших глагола — приглашение и повторная
-- отправка, — и обладатель права приглашать не должен получать из продукта
-- средство рассылки: писем одному адресу за окно уходит не больше объявленного
-- (§4.6 приёмки). Ограничение действует ВСЕГДА — профиль вправе изменить
-- величину, но не снять её (решение владельца Р14).
--
-- ────────────────────────────────────────────────────────────────────────────
-- ФОРМА ВЗЯТА У ОКНА ПРИЁМА ЛИЧНОСТИ, А НЕ ИЗОБРЕТЕНА
--
-- `kaname.identity_admission_windows` (триггер темпа приёма личности) уже держит
-- темп тем же приёмом: одна строка на носителя, фиксированное окно, и переход
-- в следующее окно вместе со списанием считаются ОДНИМ оператором
-- `INSERT … ON CONFLICT DO UPDATE … WHERE <= max`. Ветвь правки берёт
-- блокировку строки, поэтому второй писатель ждёт коммита первого и видит его
-- результат: гонку разрешает база, а не порядок вызовов (запрет #10). Здесь
-- та же форма; величины окна приходят от вызывающего, потому что авторитет у
-- них — настройка службы (`invite.mail-rate-limit`), а не таблица.
--
-- ────────────────────────────────────────────────────────────────────────────
-- КЛЮЧ — НОРМАЛИЗОВАННЫЙ АДРЕС
--
-- Адрес хранится в нижнем регистре и без краевых пробелов, и это держит
-- ограничение CHECK, а не дисциплина писателя: `A@X` и `a@x` — один адресат,
-- иначе регистр буквы обходил бы ограничение.
--
-- ────────────────────────────────────────────────────────────────────────────
-- ЧЕГО ЗДЕСЬ НЕТ
--
-- Выметателя старых окон нет намеренно: строка на адрес одна, перезаписывается
-- на месте и растёт только с числом РАЗНЫХ адресатов, которым продукт писал.
-- Появится потребность — выметатель придёт со своим читателем и индексом.

-- +goose Up
CREATE TABLE IF NOT EXISTS kaname.invite_mail_windows (
    recipient          text        NOT NULL PRIMARY KEY,
    window_started_at  timestamp with time zone NOT NULL,
    sent               integer     NOT NULL,
    updated_at         timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT invite_mail_windows_recipient_normalized_ck
        CHECK (recipient = lower(btrim(recipient)) AND length(recipient) > 0),
    CONSTRAINT invite_mail_windows_sent_positive_ck
        CHECK (sent >= 1)
);

COMMENT ON TABLE kaname.invite_mail_windows IS
    'Окно частоты писем приглашения на адрес (ID-MAIL-1, MAIL-25): одна строка на нормализованный адрес; списание и переход окна — одним оператором с блокировкой строки.';

-- +goose Down
DROP TABLE IF EXISTS kaname.invite_mail_windows;
