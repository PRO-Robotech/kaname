-- =============================================================================
-- Снятие вида `vpc.subnet.networkInterface`: потолок без предмета.
-- =============================================================================
-- Задача `PRO-Robotech/kacho#353`.
--
-- ЧТО БЫЛО НЕВЕРНО. Вид объявлен в каталоге и посеян величиной 64 — то есть
-- администратор облака видит его через `InternalLimitService`, вправе изменить и
-- получает успешный ответ. Списания у него нет и не планируется: решение по паре
-- «подсеть → сетевой интерфейс», записанное в самой задаче, — НЕ ограничивать.
--
-- ПОЧЕМУ НЕ ОГРАНИЧИВАТЬ. Число интерфейсов в подсети ограничено её адресным
-- пространством, и отказ по исчерпанию уже реализован (`RESOURCE_EXHAUSTED`).
-- Второй предел поверх конечного ресурса не защищает ничего: он способен только
-- отказать раньше, чем кончатся адреса, — то есть отнять у арендатора часть уже
-- оплаченного им пространства.
--
-- ПОЧЕМУ ЭТО НЕ «ПУСТЬ ЛЕЖИТ ДО ЛУЧШИХ ВРЕМЁН». Величина, которую задают и
-- которая ничего не делает, — это обещание, за которое никто не отвечает
-- (`api-conventions.md` §«Принято-и-проигнорировано»). Хуже того, здесь она
-- обещает ограничение, которого продукт сознательно НЕ ХОЧЕТ: следующий читатель
-- увидит вид, решит, что предел действует, и построит на этом свои выводы о
-- ёмкости подсети.
--
-- Исходов у такого вида ровно два — реализовать списание либо снять с контракта.
-- Решение по паре уже принято, поэтому исход второй.
--
-- ЧТО ЭТО НЕ ЗАТРАГИВАЕТ. Плоский вид `vpc.networkInterface` (сколько
-- интерфейсов у ПРОЕКТА) остаётся и продолжает списываться: снимается ровно ось
-- «в одной подсети», а не учёт интерфейсов вообще.

-- +goose Up
-- +goose StatementBegin
SET search_path TO kacho_iam, public;

-- Строка снимается целиком, а не помечается отозванной. Отозванная осталась бы
-- читаемой дельтой и продолжала бы описывать вид, которого в каталоге больше
-- нет, — то есть меняла бы одну неправду на другую, потише.
DELETE FROM kacho_iam.limits WHERE kind = 'vpc.subnet.networkInterface';
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
SET search_path TO kacho_iam, public;

-- Возврат ДОСЛОВНЫЙ, включая идентификатор посева: откат, вернувший строку под
-- другим ключом, оставил бы повторный прогон посева неотличимым от первого.
INSERT INTO kacho_iam.limits (id, scope, scope_id, kind, limit_value) VALUES
    ('lim-00000000000000013', 'DEFAULT', '', 'vpc.subnet.networkInterface', 64)
ON CONFLICT (id) DO NOTHING;
-- +goose StatementEnd
