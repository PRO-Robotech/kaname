-- role_composition_reaches_the_journal — событие «состав роли изменился без
-- записи её строки» для журнала подписки (задача #76).
--
-- APPROVED-приёмка
-- `docs/engineering/acceptance/catalog-consequence-reaches-role-readers.md`
-- (§2.4, §2.7, §3.1). Доводы здесь не пересказываются — они там; здесь только
-- то, что нужно читателю СХЕМЫ.
--
-- =============================================================================
-- КТО ЗОВЁТ
-- =============================================================================
-- Путь последствий каталога: он отбирает у арендаторских ролей объявления
-- правил, выдачи глаголов и элементы отбора, строки роли не трогая, — и ВСЯКАЯ
-- миграция новее этой, пишущая подтаблицы роли. Последнее держит гейт
-- `internal/check` (TestRoleSubtableGate_EveryMigrationWritingRoleSubtablesEmitsTheEvent);
-- нижняя граница его популяции — версия ЭТОГО файла, выведенная обходом.
--
-- Подтаблицы роли триггеров события НЕ получают (решение #73): холостой подъём
-- переписывает их целиком и давал бы шторм событий, в которых ничего не
-- произошло. Поэтому событие явное, а не триггерное.
--
-- =============================================================================
-- ПОЧЕМУ ПАМЯТЬ О ПОВТОРЕ — НАСТРОЙКА УРОВНЯ ТРАНЗАКЦИИ
-- =============================================================================
-- Вызывающих два рода, и каждый вправе позвать функцию больше одного раза в
-- одной транзакции; событие обязано лечь ОДНО на роль и транзакцию. Память о
-- том, каким ролям оно уже дано, хранится `set_config(…, true)`: значение живёт
-- до конца ТЕКУЩЕЙ транзакции и откатывается вместе с точкой сохранения, как и
-- строка журнала, которую оно помнит. Настройка уровня сессии либо временная
-- таблица, переживающая коммит, здесь запрещены: соединения пула
-- переиспользуются, и следующая транзакция, задевшая ту же роль, осталась бы без
-- события молча.
--
-- =============================================================================
-- ЧЕГО ФУНКЦИЯ НЕ ДЕЛАЕТ — НАМЕРЕННО
-- =============================================================================
--  1. Не берёт замок строки роли. Чтение роли без блокировки: замок вернул бы
--     со стороны эмиссии взаимную блокировку с правкой правил той же роли.
--  2. Не исполняется с правами владельца. Права вызывающего, все ссылки с явной
--     схемой — как у соседей журнала: иначе право на вызов, которое по
--     умолчанию есть у всех ролей базы, стало бы правом подделывать строки
--     журнала.
--  3. Не несёт состава. Нагрузка — только идентификатор, оболочку собирают
--     функции журнала по заново прочитанной строке роли: событие неотличимо по
--     форме от правки строки роли и доходит до тех же подписчиков.
--  4. Роли, чьей строки уже нет, события не даёт: её снятие эмитит свой триггер.

-- +goose Up

-- +goose StatementBegin
CREATE FUNCTION kaname.resource_journal_emit_role_composition(p_role_ids text[])
  RETURNS integer LANGUAGE plpgsql VOLATILE AS $$
DECLARE
  v_seen jsonb := COALESCE(
    NULLIF(current_setting('kaname.role_composition_emitted', true), ''), '[]')::jsonb;
  v_id   text;
  v_row  jsonb;
  v_n    integer := 0;
BEGIN
  FOR v_id IN
    SELECT DISTINCT u FROM unnest(COALESCE(p_role_ids, ARRAY[]::text[])) AS u
     WHERE COALESCE(u, '') <> ''
     ORDER BY u
  LOOP
    IF v_seen ? v_id THEN
      CONTINUE;
    END IF;

    SELECT to_jsonb(r) INTO v_row FROM kaname.roles r WHERE r.id = v_id;
    IF v_row IS NULL THEN
      CONTINUE;
    END IF;

    INSERT INTO kaname.resource_journal
      (resource_kind, resource_id, project_id, scope, event_type, payload)
    VALUES (
      'iam_role',
      v_id,
      kaname.resource_journal_project('iam_role', v_row),
      kaname.resource_journal_scope('iam_role', v_row),
      'UPDATED',
      jsonb_build_object('id', v_id));

    v_seen := v_seen || to_jsonb(v_id);
    v_n := v_n + 1;
  END LOOP;

  PERFORM set_config('kaname.role_composition_emitted', v_seen::text, true);
  RETURN v_n;
END;
$$;
-- +goose StatementEnd

-- +goose Down
--
-- ЧТО ТЕРЯЕТСЯ: путь последствий каталога снова отбирает права без события.
-- Вызывающий в Go после отката схемы получит отказ «функции нет» и откатит
-- применение целиком — молчаливой потери события откат не вводит.

DROP FUNCTION IF EXISTS kaname.resource_journal_emit_role_composition(text[]);
