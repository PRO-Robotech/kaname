-- scope_default_knows_no_retired_tier — умолчание области перестаёт называть
-- ярус, которого нет в словаре.
--
-- Задача продукта #2060.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО НЕВЕРНО СЕГОДНЯ
--
-- Функция `kaname.access_bindings_scope_default()` проставляет `scope`, когда
-- писатель его не назвал, разбирая `resource_type` оператором `CASE`. Среди
-- ветвей стоит `organization` → кластерный ярус. Яруса с таким именем в словаре
-- нет: якорь привязки — три яруса (`cluster` / `account` / `project`), публичный
-- `Create` приводит `scopeType` закрытым переводом из трёх значений, а прочие
-- писатели ставят ярус литералом. Значение `organization` не проставляет ни один
-- путь записи.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ЭТО ВООБЩЕ ЧИНИТСЯ, ЕСЛИ ВЕТВЬ БЕЗВРЕДНА
--
-- Ветвь недостижима и ничего не ломает: функция читает строку и пишет число, не
-- ссылаясь ни на снятый столбец, ни на снятую таблицу. Чинится не риск, а
-- ЧИТАЕМОСТЬ словаря. Перечень ярусов в этом дереве объявлен не одним местом
-- (домен несёт своё перечисление, схема — своё), и лишняя запись в одном из них
-- читается следующим как действующий словарь — ровно там, где точность нужна.
--
-- Ветви `cloud` и `folder` ОСТАЮТСЯ намеренно: их знает домен
-- (`DeriveFromResourceType`), то есть у них есть встречное объявление, и снятие
-- их здесь развело бы два места об одном предмете. Предмет этой миграции —
-- ровно та ветвь, у которой встречного объявления НЕТ.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ФОРМА — НОВАЯ миграция, а не правка применённой
--
-- Применённую миграцию править нельзя, поэтому тело функции заменяется целиком
-- (`CREATE OR REPLACE FUNCTION`). Триггер не пересоздаётся: он ссылается на
-- функцию по имени и подхватывает новое тело сам.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО МЕНЯЕТСЯ НАБЛЮДАЕМО
--
-- Ровно одно: вид `organization`, поданный без явного яруса, получает теперь
-- умолчание (3) вместо кластерного яруса (1). Достижимых входов правка не
-- касается — три живых яруса, неизвестный вид и явно названный ярус ведут себя
-- дословно как прежде. Держит это интеграционная проба
-- `scope_default_retired_tier_arm_integration_test.go`: она берёт ЖИВУЮ функцию
-- из каталога, вешает её на черновую таблицу и утверждает все шесть исходов.

-- +goose Up
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION kaname.access_bindings_scope_default() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF NEW.scope IS NULL THEN
        NEW.scope := CASE NEW.resource_type
            WHEN 'cluster' THEN 1::smallint
            WHEN 'account' THEN 2::smallint
            WHEN 'cloud'   THEN 2::smallint
            WHEN 'project' THEN 3::smallint
            WHEN 'folder'  THEN 3::smallint
            ELSE 3::smallint
        END;
    END IF;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

COMMENT ON FUNCTION kaname.access_bindings_scope_default() IS
    'Умолчание яруса, когда писатель его не назвал. Словарь ветвей держится встречным объявлением домена (DeriveFromResourceType); вида без встречного объявления здесь не бывает. Явно названный ярус не перезаписывается.';

-- +goose Down
-- +goose StatementBegin
-- Откат НЕ воспроизводит снятую ветвь, и это решение, а не упущение.
--
-- Предикат задачи #2060 требует НУЛЯ вхождений имени снятого яруса по всему
-- каталогу миграций, включая эту миграцию, — значит откат, возвращающий его
-- текст, вернул бы вместе с ним и предмет. Наблюдаемого поведения это не
-- касается: на КАЖДОМ достижимом входе прямой и обратный ход дают один и тот же
-- ярус, а расходятся они ровно на том входе, которого не проставляет ни один
-- путь записи.
SELECT 1;
-- +goose StatementEnd
