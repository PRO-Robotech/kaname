-- СЕССИИ получает четвёртое значение, `admin-force-logout` (задача
-- PRO-Robotech/kaname#334).
--
-- Санкция: одобренная приёмка
-- `docs/engineering/acceptance/forced-exit-has-its-own-session-end-reason.md`
-- (редакция 3, SHA-256
-- `ae35d0e1c1968d2e58281ff2ad5904f68b4bab7b08a3d1bcf53f82eeef353e1b`;
-- решения Р1, Р4, Р5; сценарии KN-SER-06…09). Доводы там; здесь — то, что
-- нужно читателю СХЕМЫ.
--
-- =============================================================================
-- ЧТО МЕНЯЕТСЯ
-- =============================================================================
-- Запись сессии называет того, кто её снял: выход самого человека (`logout`),
-- смена пароля (`password-change`), снятие второго фактора
-- (`second-factor-removed`) — и теперь принудительный выход, произведённый
-- распорядителем (`admin-force-logout`). Слово дословно то, которым служба уже
-- пишет умолчание причины отсечки: предмет у обеих записей один (Р1).
--
-- Ограничение снимается и ставится заново ПОД ТЕМ ЖЕ ИМЕНЕМ
-- (`human_sessions_ended_reason_check`): имя — координата, по которой его
-- снимает откат миграции `20260917160000` и читают пробы словаря. Снятие и
-- заведение идут ОДНОЙ транзакцией — маркера `NO TRANSACTION` здесь нет, и
-- мигратор оборачивает накат целиком. Первый оператор берёт таблицу
-- исключительным захватом до конца транзакции, поэтому окна «ограничения нет»
-- не видит ни один писатель.
--
-- =============================================================================
-- ОБРАТНОГО ЗАПОЛНЕНИЯ НЕТ — И ПОЧЕМУ
-- =============================================================================
-- Значение ДОБАВЛЯЕТСЯ, а лежащие строки накат не трогает: операторов данных в
-- нём нет (Р4, KN-SER-08). Переписывать нечего и нечем:
--
-- * на стволе службы (ревизия измерения приёмки `cbbac984`) административный
--   путь в эту колонку не писал вовсе — ни одна строка, записанная стволом, не
--   помечена неверно;
-- * строки, которым путь принудительного выхода до этого изменения записал
--   `logout`, неотличимы от выхода самого человека ПО ПОСТРОЕНИЮ: признака,
--   по которому перевод `logout` → `admin-force-logout` выбрал бы именно их, в
--   строке нет. Перевод по такому признаку переписал бы и настоящие выходы,
--   то есть исказил бы журнал, а не исправил. Верного решения о прошлом для
--   этих строк не существует; уборка снимает их по сроку наравне с прочими
--   снятыми.

-- +goose Up

ALTER TABLE kaname.human_sessions
    DROP CONSTRAINT human_sessions_ended_reason_check;
ALTER TABLE kaname.human_sessions
    ADD CONSTRAINT human_sessions_ended_reason_check
        CHECK (((ended_reason IS NULL) OR (ended_reason = ANY (ARRAY['logout'::text, 'password-change'::text, 'second-factor-removed'::text, 'admin-force-logout'::text]))));

-- +goose Down

-- Откат возвращает словарь из трёх значений и переводит строки, снятые
-- распорядителем, в `logout` (Р5, KN-SER-09). НАПРАВЛЕНИЕ: различение
-- теряется, факт и момент снятия — нет. `ended_at` откат не трогает: сессия
-- снята и остаётся снятой. `logout` — ровно то, что код до этого изменения
-- писал для того же акта, поэтому после отката база и прежний код снова
-- согласны. Отказ от отката был бы хуже: пока лежат снятые распорядителем
-- строки (а лежат они до уборки), откат был бы невыполним.
--
-- ЗАХВАТ ТАБЛИЦЫ — ПЕРВЫМ оператором, до перевода. Без него между переводом и
-- заведением ограничения из трёх помещается писатель, ещё знающий новое слово:
-- его строка с `admin-force-logout` провалила бы заведение ограничения, и откат
-- отказал бы целиком. Под захватом такой писатель ждёт конца отката и затем
-- получает отказ ограничения — громкий, без искажения записи.
--
-- Откат берёт ТОЛЬКО эту таблицу: ни таблицы личностей, ни её строк. Писатели
-- снятия держат порядок «личность → строки сессии»; захват личности здесь
-- создал бы с ними цикл ожидания. Ограничение CHECK и перевод неключевой
-- колонки чужих таблиц не захватывают.
LOCK TABLE kaname.human_sessions IN ACCESS EXCLUSIVE MODE;

UPDATE kaname.human_sessions SET ended_reason = 'logout' WHERE ended_reason = 'admin-force-logout';

ALTER TABLE kaname.human_sessions
    DROP CONSTRAINT human_sessions_ended_reason_check;
ALTER TABLE kaname.human_sessions
    ADD CONSTRAINT human_sessions_ended_reason_check
        CHECK (((ended_reason IS NULL) OR (ended_reason = ANY (ARRAY['logout'::text, 'password-change'::text, 'second-factor-removed'::text]))));
