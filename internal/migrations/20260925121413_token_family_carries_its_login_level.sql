-- token_family_carries_its_login_level — СЕМЕЙСТВО выданного по коду несёт
-- уровень аутентификации, с которым выдан его грант (задача
-- PRO-Robotech/kaname#423).
--
-- Санкция: одобренная приёмка LINE-A-1 (воркспейс, ветка 771,
-- `docs/specs/sub-phase-LINE-A-1-own-authorization-endpoint-and-code-acceptance.md`,
-- SHA-256 `b755886fd3a9cbf4070598ad3d921bb92d53d7f4186832a2c34f1d8ca197a7ec`):
-- Р5 «выданный код связывает (…, момент аутентификации, уровень доверия)»,
-- Р6 «уровень, перенесённый кодом», сценарии 08, 19, инвариант 6.
--
-- =============================================================================
-- ЗАЧЕМ
-- =============================================================================
-- Уровень ГРАНТА — снимок, сделанный на выдаче кода: обмен и каждый оборот
-- токена обновления переносят его без изменения (контракт порта церемонии
-- фундамента, `corelib/oauthceremony.SessionRecord`). До этой миграции в
-- схеме семейства его не было: запись связывала сессию, но не уровень.
--
-- Взять уровень у СЕССИИ при чтении нельзя, и это измерено, а не выбрано:
-- уровень сессии ПОДВИЖЕН — предъявление второго фактора внутри сессии
-- переписывает его (`humanSessionWriter.PresentInSession`,
-- `SET … assurance_level = $3`). Семейство, выданное на уровне «1», после шага
-- вверх в той же сессии выпускало бы токены уровня «2», которого его код не
-- нёс. Момент аутентификации, напротив, НЕПОДВИЖЕН (`authenticated_at` не
-- входит ни в один `SET` писателя сессии) — поэтому его колонки здесь нет:
-- он читается у сессии, и второго места у него не заводится.
--
-- =============================================================================
-- ЛЕЖАЩИЕ СТРОКИ
-- =============================================================================
-- Производственного писателя семейств до этой задачи не было: церемония в
-- композиционном корне не собиралась. Обратное заполнение всё же стоит — от
-- уровня сессии семейства, — чтобы накат не зависел от того, пуста ли таблица
-- на данной установке: у каждой строки сессия есть (`token_families_session_fk`,
-- `NOT NULL`), и её уровень — единственное, что о гранте известно. Уровень
-- берётся ТЕКУЩИЙ, а не снятый на выдаче: снимка до этой колонки не было нигде,
-- и восстановить его нечем.
--
-- Умолчания у колонки НЕТ: семейство без названного уровня заявляло бы уровень,
-- которого вход не сообщал. Словарь — тот же, что у сессии
-- (`human_sessions_assurance_level_check`).

-- +goose Up

ALTER TABLE kaname.token_families ADD COLUMN acr text;

UPDATE kaname.token_families f
   SET acr = s.assurance_level
  FROM kaname.human_sessions s
 WHERE s.id = f.session_id;

-- +goose StatementBegin
ALTER TABLE kaname.token_families
    ALTER COLUMN acr SET NOT NULL,
    ADD CONSTRAINT token_families_acr_ck CHECK ((acr = ANY (ARRAY['1'::text, '2'::text, '3'::text])));
-- +goose StatementEnd

COMMENT ON COLUMN kaname.token_families.acr IS
  'Уровень аутентификации гранта (acr) — СНИМОК на выдаче кода; обмен и оборот его не пересчитывают. У сессии уровень подвижен (шаг вверх), поэтому он не читается у неё. Словарь — тот же, что у human_sessions.assurance_level; держит token_families_acr_ck. Умолчания нет.';

-- +goose Down

-- Откат снимает колонку вместе с её ограничением. Данных вне колонки он не
-- трогает: миграция ничего, кроме неё, не записывала.
ALTER TABLE kaname.token_families
    DROP CONSTRAINT token_families_acr_ck,
    DROP COLUMN acr;
