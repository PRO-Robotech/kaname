-- login_challenge_is_bound_to_the_form_context — ИСПЫТАНИЕ ПОЛОСЫ ВХОДА
-- ключом доступа получает свою таблицу (фаза Ф13, задача
-- PRO-Robotech/kacho#1282; приёмка
-- `docs/engineering/acceptance/passwordless-login-with-access-key.md`, Р2, §9 п. 4).
--
-- =============================================================================
-- ПОЧЕМУ СВОЯ ТАБЛИЦА, А НЕ КОЛОНКА В ИСПЫТАНИЯХ ЦЕРЕМОНИЙ
-- =============================================================================
-- `access_key_challenges` привязывает строку к ЧЕЛОВЕКУ: там вызывающий назван
-- своей сессией, и внешний ключ на `users` держит эту привязку. У полосы входа
-- человека нет вовсе — его обнаруживают по предъявленному удостоверению уже
-- после сверки. Сделать колонку человека необязательной значило бы ослабить
-- инвариант церемоний ради чужого предмета: строка без человека стала бы
-- законной там, где она законной не является.
--
-- Поэтому у входа своя строка со своим ключом привязки — КОНТЕКСТОМ ФОРМЫ
-- (печенье `kaname_form`, `humansession/form_token.go`). Словари двух таблиц не
-- пересекаются by construction: испытание входа в церемонии не находится, а
-- испытание церемонии не находится на входе, — и держит это раздельность
-- таблиц, а не совпадение значений.
--
-- =============================================================================
-- ОДНО ЖИВОЕ НА КОНТЕКСТ — ЧАСТИЧНАЯ УНИКАЛЬНОСТЬ, НЕ ПРОВЕРКА ПЕРЕД ВСТАВКОЙ
-- =============================================================================
-- Повторная выдача ЗАМЕЩАЕТ прежнее живое испытание контекста (Ф13-03). Будь
-- это «посмотреть, есть ли живое, и решить» — два одновременных запроса одного
-- контекста увидели бы одно и то же состояние и завели бы два живых испытания
-- (ban #10). Инвариант держит частичный ключ уникальности по контексту среди
-- НЕПОТРЕБЛЁННЫХ строк: второе живое в контексте невыразимо, а замещение —
-- снятие прежнего и вставка нового одной транзакцией.
--
-- Потреблённые строки под ключ не подпадают и остаются: по ним отказ различает
-- «предъявлено» от «не выдавалось» — различает ВНУТРИ службы, клетками
-- счётчика; наружу обе полосы отвечают одним отказом (Р7).
--
-- =============================================================================
-- ОДНОКРАТНОСТЬ — ОДИН ОПЕРАТОР
-- =============================================================================
-- Годность и сгорание испытания — одно действие, а не два: строка этого
-- контекста, не потреблённая и не истёкшая на `now`, получает отметку тем же
-- оператором, который её и отбирает. Ноль затронутых строк — она уже
-- потреблена, истекла либо её нет; вызывающему различать это незачем.
--
-- =============================================================================
-- РОСТ ОГРАНИЧЕН УБОРКОЙ
-- =============================================================================
-- У строки есть момент, после которого ни один читатель не изменит из-за неё
-- исхода: срок вышел либо она потреблена. Порог и уборщик — реестр уборки
-- службы, тот же, что у испытаний церемоний.

-- +goose Up

CREATE TABLE kaname.access_key_login_challenges (
    challenge    bytea NOT NULL,
    form_context text NOT NULL,
    issued_at    timestamp with time zone DEFAULT now() NOT NULL,
    expires_at   timestamp with time zone NOT NULL,
    consumed_at  timestamp with time zone,
    CONSTRAINT access_key_login_challenges_pkey PRIMARY KEY (challenge),
    CONSTRAINT access_key_login_challenges_challenge_check CHECK ((octet_length(challenge) = 32)),
    CONSTRAINT access_key_login_challenges_form_context_check
        CHECK ((length(form_context) >= 1 AND length(form_context) <= 128)),
    CONSTRAINT access_key_login_challenges_span_check CHECK ((expires_at > issued_at))
);

COMMENT ON TABLE kaname.access_key_login_challenges IS
  'Выданные испытания полосы входа ключом доступа: привязаны к контексту формы (человек на выдаче неизвестен), однократны (consumed_at), срочны (expires_at — та же величина, что у испытаний церемоний). Одно живое на контекст держит частичный ключ уникальности. Убираются реестром уборки после срока хранения отказа.';
COMMENT ON COLUMN kaname.access_key_login_challenges.form_context IS
  'Контекст формы (печенье kaname_form), под которым испытание выдано: ключ привязки вместо человека — его на выдаче назвать нечем.';

-- Одно ЖИВОЕ испытание на контекст (Ф13-03): потреблённые строки под ключ не
-- подпадают и сохраняются до уборки.
CREATE UNIQUE INDEX access_key_login_challenges_live_context_idx
    ON kaname.access_key_login_challenges USING btree (form_context) WHERE (consumed_at IS NULL);

CREATE INDEX access_key_login_challenges_expires_idx
    ON kaname.access_key_login_challenges USING btree (expires_at);

-- Испытание — одноразовое случайное значение: выборка в статистике планировщика
-- была бы его копией с чужим сроком хранения; отбирается оно точным равенством
-- по первичному ключу.
ALTER TABLE kaname.access_key_login_challenges ALTER COLUMN challenge SET STATISTICS 0;

-- +goose Down

-- Откат безопасен: строка испытания не восстанавливает ничьего доступа и
-- ничьим материалом не является — она одноразова и переживает себя на время
-- уборки. Снятие таблицы означает лишь, что предъявление, начатое до отката,
-- придётся начать заново.
DROP TABLE kaname.access_key_login_challenges;
