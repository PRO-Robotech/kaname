-- resource_journal_admits_the_feed_signal — журнал подписки службы доступа
-- принимает строку СИГНАЛА ЛЕНТЫ `notification_feed:kaname`, и только в одной
-- форме (задача PRO-Robotech/kaname#484, полоса G1 NTF-2).
--
-- Санкция: приёмка `docs/specs/sub-phase-NTF-2-identity-provider-mail-removal-acceptance.md`
-- репозитория PRO-Robotech/kacho-workspace, Р1 «kaname — источник ленты
-- `notification_feed:kaname`» (сигнал `notify` — событие вида «нотификация»
-- существующей подписки kaname с объектом `notification_feed:kaname`),
-- отпечаток `ef9c68019a7d58c7bce1ba0bdeb3ba2f56d508d1c53cb5db9b51de98b3bd825f`.
-- Доводы там; здесь — то, что нужно читателю СХЕМЫ.
--
-- =============================================================================
-- ЗАЧЕМ
-- =============================================================================
-- Строку сигнала пишет функция фундамента `corelib/notify/feed.JournalSignal`
-- (через `subscription.Journal.Emit`) в транзакции постановки письма: вид — ключ
-- журнала `feed.JournalKey` = `notification`, идентификатор — имя ленты модуля,
-- род изменения — слово владельца, нагрузка — пустой объект. Словарь видов этого
-- журнала закрыт ограничением `resource_journal_resource_kind_check`
-- (`20260914090000`), и слова `notification` в нём нет: без этой миграции
-- первая же постановка письма при включённом флаге падала бы `23514`.
--
-- =============================================================================
-- ЧТО ЗАВОДИТСЯ
-- =============================================================================
-- 1. Словарь видов принимает ровно одно новое слово `notification`; постороннее
--    по-прежнему отвергается ТЕМ ЖЕ ограничением с ТЕМ ЖЕ именем — по имени
--    отказ узнают пробы и вызывающие.
--
-- 2. `resource_journal_feed_signal_form_check` — строка вида `notification`
--    лежит в ОДНОЙ форме, и форма держится базой, а не писателем:
--
--    * `resource_id = 'kaname'` — лента службы одна, и имя её — литерал
--      `manifest.AccessServiceFeed`, а не `module` манифеста (NTF-2 Р1, NTF-1
--      Р3). Строка с именем чужой ленты в журнале kaname будила бы шлюз
--      забирать ленту, которой у этой службы нет; форма DNS-метки, которую
--      судит фундамент, такую строку пропустила бы;
--    * `project_id = ''` — лента уровня кластера (`ScopeCluster`): якоря у
--      строки нет, и вопрос видимости задаётся объекту `notification_feed`, а не
--      проекту;
--    * `scope = '[]'` — захваченных областей у сигнала нет: предмет уровня
--      кластера ни в какой области не вместим, и пустой набор — его правда, а
--      не умолчание. Набор областей РАСШИРЯЕТ доступ: клиент сужения
--      (`subscriptionjournal.NarrowClient`) признаёт строку снятия видимой, если
--      вызывающему виден ЛЮБОЙ объект набора. Сегодня до сигнала эта ветвь не
--      доходит — снятием он не бывает (ниже), — и пустой набор держит, чтобы
--      непустого, способного открыть событие ленты без `reader` на
--      `notification_feed:kaname`, у строки сигнала не было вовсе;
--    * `event_type = 'UPDATED'` — лента существует, пока существует служба:
--      сигнал говорит «в ленте появилось», а не «лента заведена» или «снята».
--      Снятие у подписчика означает «убери предмет у себя» — на ленте это была
--      бы ложь. Слово то же, что у всех источников ленты платформы
--      (`notifygen`, `signal_change: UPDATED`).
--
--    Ограничение НЕ касается остальных семи видов: их строки пишут триггеры
--    ресурсов, и их форма объявлена миграцией журнала.
--
-- =============================================================================
-- ЧЕГО ЗДЕСЬ НЕТ, И ПОЧЕМУ
-- =============================================================================
-- Флага почты схема не судит. «Флаг выключен — строк ноль» держит писатель
-- (`mail.Enqueuer` не зовёт постановку вовсе, NTF2-52), а настройку
-- транзакции `kacho_feed.enabled` ставит и читает фундамент: второй судья того
-- же предмета в схеме разошёлся бы с первым молча.
--
-- Индекса не заводится: строки сигнала отбирает общий сервер потока по позиции
-- (`sequence_no`), а вопрос по виду и идентификатору обслуживает уже лежащий
-- `resource_journal_kind_id_idx`.
--
-- ПОЧЕМУ СНЯТЬ И ПОСТАВИТЬ, А НЕ ПРАВИТЬ `20260914090000`: применённая миграция
-- не правится (запрет #5). Снятие и постановка идут ОДНИМ оператором в
-- транзакции миграции — окна без словаря нет.

-- +goose Up

ALTER TABLE kaname.resource_journal
  DROP CONSTRAINT resource_journal_resource_kind_check,
  ADD CONSTRAINT resource_journal_resource_kind_check
    CHECK (resource_kind = ANY (ARRAY[
      'account'::text, 'project'::text, 'iam_user'::text, 'iam_group'::text,
      'iam_service_account'::text, 'iam_role'::text, 'iam_access_binding'::text,
      'notification'::text])),
  ADD CONSTRAINT resource_journal_feed_signal_form_check
    CHECK (resource_kind <> 'notification'
           OR (resource_id = 'kaname'
               AND project_id = ''
               AND scope = '[]'::jsonb
               AND event_type = 'UPDATED'));

-- +goose Down
--
-- Обратный шаг СУЖАЕТ словарь. Если в журнале уже лежат строки сигнала,
-- постановка узкого ограничения отказывает `23514` — это честный отказ, а не
-- потеря строк: строки сигнала уходят из журнала уборщиком по возрасту, а не
-- откатом схемы.

ALTER TABLE kaname.resource_journal
  DROP CONSTRAINT resource_journal_feed_signal_form_check,
  DROP CONSTRAINT resource_journal_resource_kind_check,
  ADD CONSTRAINT resource_journal_resource_kind_check
    CHECK (resource_kind = ANY (ARRAY[
      'account'::text, 'project'::text, 'iam_user'::text, 'iam_group'::text,
      'iam_service_account'::text, 'iam_role'::text, 'iam_access_binding'::text]));
