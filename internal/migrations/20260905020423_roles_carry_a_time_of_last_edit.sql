-- roles_carry_a_time_of_last_edit — время правки роли получает ПРОИЗВОДИТЕЛЯ.
--
-- Задача продукта #1873.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО НЕВЕРНО СЕГОДНЯ
--
-- Контракт `iam.v1.Role` объявляет `updated_at`, и цепочка обрывается на КАЖДОМ
-- звене сразу: столбца у `kaname.roles` нет, писатель его не присваивает,
-- проекция чтения не выбирает, а перевод в контракт стоит под условием
-- непустоты — то есть не срабатывает НИКОГДА. Арендатор видит поле в контракте
-- и в сгенерированных клиентах и не может получить его ни одним вызовом.
--
-- Это класс «возможность объявлена и неисполнима» (`api-conventions.md`
-- §«Неисполнимая возможность»). У соседнего ресурса того же домена
-- (`memberships`) поле живое, поэтому разнобой между двумя ресурсами одного
-- домена сам по себе есть находка (ban #18).
--
-- Цена уже была уплачена один раз: поле домена плюс комментарий писателя,
-- утверждавший «updated_at is bumped on every applied mutation», породили
-- присваивание `updated_at` в соседнем операторе. Неизвестный столбец там —
-- ошибка разбора ВСЕГО оператора (42703), поэтому писатель системной роли был
-- неисполним при любом входе, включая вставку.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ИСХОД — РЕАЛИЗОВАТЬ, а не снять с контракта
--
-- Умолчание правил корпуса для «принято-и-проигнорировано» — снять с контракта.
-- Здесь выбран первый исход, и выбор продуктовый: поле у соседа по домену
-- ЖИВОЕ, значит снятие сделало бы разнобой постоянным, а не убрало бы его.
-- Снятие вдобавок было бы ломающим изменением у каждого читателя роли ради
-- того, чтобы отнять сведение, которое сосед уже даёт.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ФОРМА — та же, что у соседей схемы
--
-- Столбец не заводится сразу `NOT NULL DEFAULT now()`: тогда КАЖДАЯ уже
-- существующая строка объявила бы себя правленной в момент применения миграции,
-- то есть метка солгала бы обо всех ролях разом. Поэтому три шага: завести
-- пустым · заполнить временем СОЗДАНИЯ (роль, которую никто не правил,
-- «правлена» в момент своего появления) · закрепить NOT NULL и умолчание для
-- новых строк.
--
-- Триггера здесь НЕТ намеренно: в этой схеме метку двигают писатели явным
-- присваиванием (`SET … updated_at = …`), и заводить второй механизм ради
-- одной таблицы значило бы завести два места, которые разойдутся молча.

-- ─────────────────────────────────────────────────────────────────────────────
-- ТОЧКА НЕВОЗВРАТА — объявлена, а не получилась сама
--
-- Третий шаг закрепляет `NOT NULL`, и это делает откат ОБРАЗА через эту версию
-- неисполнимым: секция Down на пути отката поставки не исполняется, схема
-- остаётся новой, а прежний образ вставляет строку роли БЕЗ `updated_at` —
-- значит первая же его запись отвергается ограничением. Умолчание `now()`
-- этого не спасает: писатель прежнего образа перечисляет колонки явно, и
-- умолчание применяется только к неназванным, а не к тем, что названы NULL.
--
-- Названо здесь потому, что иначе следующий, кто будет откатывать поставку,
-- узнает об этом отказом записи в проде, а не строкой в миграции.

-- +goose Up

-- +kacho point-of-no-return: NOT NULL на kaname.roles.updated_at — прежний образ вставляет роль без этой колонки и получает отказ на первой же записи; откат образа через эту версию неисполним

ALTER TABLE kaname.roles
    ADD COLUMN updated_at timestamp with time zone;

UPDATE kaname.roles
   SET updated_at = created_at
 WHERE updated_at IS NULL;

ALTER TABLE kaname.roles
    ALTER COLUMN updated_at SET DEFAULT now();

ALTER TABLE kaname.roles
    ALTER COLUMN updated_at SET NOT NULL;

COMMENT ON COLUMN kaname.roles.updated_at IS
    'Время последней применённой правки строки. У роли, которую никто не правил, равно created_at. Двигают писатели явным присваиванием, триггера нет.';

-- +goose Down

ALTER TABLE kaname.roles
    DROP COLUMN updated_at;
