-- 0094_limit_kind_nested_form_and_seeds.sql — форма вида расширяется до
-- вложенной, и умолчание появляется у КАЖДОГО вида каталога.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Стадия S1 приёмки quota-v2 делает две вещи с этой таблицей, и обе аддитивны.
--
-- 1. ФОРМА ВИДА. `limits_kind_form_ck` из 0092 допускает ровно две части
--    (`domain.resource`). Предел «сколько детей помещается в ОДНОМ родителе»
--    выражается тремя (`vpc.network.subnet` — «сколько подсетей в одной сети»),
--    и без расширения формы он невыразим. Опасность, которую владелец назвал
--    прямо («ресурсы, способные положить инфраструктуру»), живёт именно во
--    вложенности: одна сеть с десятью тысячами подсетей — это другой отказ, чем
--    десять тысяч подсетей, разложенных по проектам.
--
-- 2. ПОСЕВ. Гейт покрытия каталога расширен с одного домена на все шесть, и
--    шестнадцать тенантских видов получили потолок. Правило «не сказано =
--    ОТКАЗ» (V2-3) делает посев умолчания ОБЯЗАТЕЛЬНЫМ: вид каталога без строки
--    области DEFAULT означал бы, что ресурсы этого вида создавать нельзя вовсе.
--    Поэтому число посеянных строк сверяется с числом видов каталога пробой, а
--    не намерением.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ НОВАЯ МИГРАЦИЯ, А НЕ ПРАВКА 0092
--
-- 0092 применена. Применённую миграцию не правят (ban #5): правка меняет то, что
-- на уже поднятых базах исполнено, и расхождение между файлом и базой ничем не
-- видно. Ограничение снимается и ставится заново под тем же именем — так замена
-- атомарна в одной транзакции, и промежуточного состояния «таблица без проверки
-- формы» не существует ни для одного писателя.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ФОРМА, А НЕ ПЕРЕЧЕНЬ ВИДОВ
--
-- Разделение из 0092 сохраняется дословно: здесь проверяется ФОРМА, членство в
-- закрытом каталоге — доменом. Вписать перечень видов сюда значило бы требовать
-- миграцию на каждый новый вид, а применённую править нельзя — то есть перечень
-- в схеме зафиксировал бы каталог навсегда.
--
-- Проверить, что ОБЕ части трёхчастного вида называют реальные типы модели прав,
-- схема не может: закрытая таблица типов живёт в коде и растёт вместе с
-- продуктом. Это проверяет гейт `TestLimitKindsAreKnownObjectTypes`, и он
-- проверяет обе части именно потому, что форма второй части в таблице
-- НЕединообразна — единственное число у vpc/compute/iam, множественное у
-- loadbalancer/storage/registry.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ОТКУДА ВЗЯТЫ ВЕЛИЧИНЫ
--
-- Величины ВЫБРАНЫ, а не измерены: наблюдений потребления у платформы пока нет,
-- и объявлять выбранное измеренным значило бы придавать числу вес, которого у
-- него нет. Они согласованы между собой (вывод по каждой строке — в приёмке
-- предшественника, таблица Р13) и задают стартовую точку. Пересматриваются по
-- наблюдаемости V2-8, а не по ощущению.
--
-- Ноль здесь не используется НИ РАЗУ: нулевое умолчание неотличимо для
-- арендатора от «вид запрещён», а запрет — это отсутствие вида в каталоге.

