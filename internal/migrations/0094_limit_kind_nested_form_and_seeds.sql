-- Форма вида: две ИЛИ три части. Расширение строго аддитивно — всякий вид,
-- проходивший прежнюю проверку, проходит и эту.
--
-- Первая часть (домен) строчная; вторая и третья — camelCase, как в закрытой
-- таблице типов. Четвёртой части нет: `vpc.network.subnet.route` означало бы
-- «маршрутов в подсети в сети», то есть предел на внука, у которого нет своего
-- носителя, — такой вид некому считать.
ALTER TABLE kacho_iam.limits
    DROP CONSTRAINT limits_kind_form_ck;

-- +goose StatementEnd
-- +goose StatementBegin

ALTER TABLE kacho_iam.limits
    ADD CONSTRAINT limits_kind_form_ck
        CHECK (kind ~ '^[a-z][a-z0-9]*\.[a-zA-Z][a-zA-Z0-9]*(\.[a-zA-Z][a-zA-Z0-9]*)?$');

