-- verb_withdrawal_needs_a_liveness_key — УРОВЕНЬ ГЛАГОЛОВ: живость ресурса
-- держит КЛЮЧ, а не рассуждение о потребителях.
--
-- Задачи продукта #1868 (решение) и #1878 (исполнение). Решение записано —
-- services/iam/docs/engineering/architecture/catalog-liveness-key-per-level.md.
-- Приёмка services/iam/docs/engineering/acceptance/module-withdrawal-is-described.md
-- (APPROVED круга 2): §2.2 называет этот уровень прямо, §9.2 заказывает выбор на
-- каждом уровне. Близнец сценария IAM-MW-1-08 стоит уровнем ниже — в
-- services/iam/internal/repo/kacho/pg/verb_liveness_key_integration_test.go.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО НЕВЕРНО СЕГОДНЯ
--
-- Каталог трёхуровневый: модули → ресурсы → глаголы. Живость родителя на первом
-- переходе держит ключ `catalog_resource_module_live_fk` (20260902065414), на
-- втором — НИЧТО: `catalog_verb_resource_fk` идёт на ПЕРВИЧНЫЙ ключ ресурса,
-- то есть на строку независимо от её живости. Значит состояние «ресурс снят, а
-- его глаголы живы» ПРЕДСТАВИМО.
--
-- Недостижимым его делает не схема, а РАССУЖДЕНИЕ: правило роли отвергается
-- ключом РЕСУРСА (`role_rule_ref_res_fk` ссылается на
-- `catalog_resource (module, resource, live)`), поэтому до строки глагола дело
-- не доходит. Рассуждение верно — и верно ровно пока верен его перечень
-- потребителей. Перечень меняется, и меняется молча: это ban #10 буквально —
-- инвариант внутри одной базы выражается конструкцией базы, а не тем, кто её
-- сегодня читает.
--
-- Различие уровней при этом было не решено, а СОВПАЛО: два уровня из трёх
-- держали живость ключом, третий — комментарием, и следующий, кто заведёт
-- четвёртый уровень, не нашёл бы места, где сказано, какой выбор верен.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО ЭТА МИГРАЦИЯ ДЕЛАЕТ
--
-- Даёт `catalog_verb` вторую ссылку — на «этот ресурс И он жив». Референт у неё
-- уже был и не использовался ни одним ключом:
-- `catalog_resource_live_uk UNIQUE (module, resource, live)` (20260901113757).
--
-- Порядок держится в ОБЕ стороны, и обе половины проверены прогоном:
--
--   вниз   снять ресурс, пока жив хоть один его глагол   → 23503
--   вниз   снять ресурс, все глаголы которого сняты      → проходит
--   вверх  оживить глагол при снятом ресурсе             → 23503
--   вверх  оживить ресурс, затем его глаголы             → проходит
--
-- Половина «вниз, проходит» — не украшение: без неё отрицание не отличает «ключ
-- держит порядок» от «ресурс снять нельзя НИКОГДА», и ровно этим исходом
-- зеленела бы форма с константной колонкой `true` (разбор — уровнем выше).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ КОЛОНКА ОБРАЩАЕТСЯ В NULL, А НЕ ОБЪЯВЛЕНА КОНСТАНТОЙ `true`
--
-- Довод тот же, что уровнем выше, и он здесь НЕ пересказывается целиком:
-- строки каталога не удаляются, они снимаются, поэтому константная `true`
-- держала бы ссылку на `(module, resource, true)` вечно, и снять ресурс стало бы
-- нельзя НИКОГДА. Генерируемая в `NULL` составляющая плюс умолчание
-- `MATCH SIMPLE` даёт нужное by construction: у снятой строки составляющая
-- пуста, ключ с пустой составляющей считается выполненным, и снятая строка
-- ресурс не удерживает.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧАСТИЧНОЕ СОВПАДЕНИЕ: `MATCH SIMPLE` ПРОПУСКАЕТ ПРОВЕРКУ ЦЕЛИКОМ — И ПОТОМУ
-- ПРЕЖНИЙ КЛЮЧ НЕ СНИМАЕТСЯ
--
-- Это надо сказать вслух, иначе следующий читатель снимет `catalog_verb_
-- resource_fk` как «дубль нового ключа». `MATCH SIMPLE` не проверяет ЧАСТЬ
-- ключа — он не проверяет ключ ВООБЩЕ, как только пуста хоть одна составляющая.
-- Значит у СНЯТОЙ строки глагола новый ключ не утверждает ничего, в том числе
-- и того, что названный ею ресурс вообще существует.
--
-- Существование держит ПРЕЖНИЙ ключ `catalog_verb_resource_fk (module,
-- resource)`: обе его составляющие объявлены `NOT NULL`, поэтому пустой он не
-- бывает никогда. Два ключа отвечают за РАЗНОЕ — существование и живость, — и
-- снятие любого из них открывает свою дыру. Проба утверждает оба ответа
-- ПОИМЁННО (`catalog_verb_resource_fk` на призрака, `catalog_verb_resource_
-- live_fk` на живость), иначе «строка отвергнута» неотличимо от «отвергнута тем
-- ключом, о котором мы думали».
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЦЕНА ФОРМЫ — НАЗВАНА, А НЕ УМОЛЧАНА
--
-- `ADD COLUMN … GENERATED ALWAYS AS … STORED` ПЕРЕПИСЫВАЕТ таблицу и берёт на
-- неё `ACCESS EXCLUSIVE`; `ADD CONSTRAINT … FOREIGN KEY` вдобавок проверяет
-- КАЖДУЮ существующую строку. На каталоге в сто тридцать пять строк это ничто,
-- и потому здесь допустимо; следующий каталог может быть не таким, и тогда цену
-- придётся считать заново.
--
-- ВЫПОЛНИМОСТЬ ИЗМЕРЕНА, А НЕ ПРЕДПОЛОЖЕНА: живых глаголов под снятым ресурсом
-- НОЛЬ (снятых ресурсов 3 — `compute.disk`, `compute.image`, `compute.snapshot`;
-- строк каталога глаголов 135; пересечение пусто). Замер снят на живой базе
-- пробой `TestVerbsUnderARetiredResourceAreAbsent`, а не чтением посева, и
-- проба остаётся в дереве: она утверждает то же свойство, которое держит ключ,
-- и на дереве, куда такую пару завезли бы посевом, покраснела бы РАНЬШЕ этой
-- миграции.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- СЛЕДСТВИЕ, КОТОРОЕ НАДО НАЗВАТЬ ВСЛУХ
--
-- Снятие ресурса теперь ТРЕБУЕТ предварительного снятия его глаголов. Это не
-- издержка, а предмет: сегодня частичное снятие проходит молча, и никто о нём
-- не узнаёт. Порядок «глаголы → ресурсы» становится тем же, что уже действует
-- для «ресурсы → модули», и административный путь снятия ресурса приведён к
-- нему тем же изменением.
--
-- ЧЕГО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ. Она не трогает набор выданного: ключ судит
-- ПРЕДСТАВИМОСТЬ строки каталога, а не материализацию отношений. И не переводит
-- читателя набора модулей со литерала на строки — это остаток #1816.

-- ─────────────────────────────────────────────────────────────────────────────
-- НОМЕР ВЫВЕДЕН ИЗ КАТАЛОГА, А НЕ ИЗ ЧАСОВ — И ЭТО ОТСТУПЛЕНИЕ, НАЗВАННОЕ ВСЛУХ
--
-- Канон (docs/architecture/migration-version-namespace.md) велит брать номер у
-- часов: `date -u +%Y%m%d%H%M%S`. Здесь он взят на секунду выше старшего
-- номера каталога, и вот почему.
--
-- Часы дали `20260902102932`, а в каталоге уже лежит `20260902174500` —
-- на семь часов ВПЕРЕДИ UTC. Посылка канона («часы идут вперёд, поэтому метка
-- времени больше любого унаследованного номера») на этом каталоге не
-- выполняется, и следование букве дало бы ровно тот отказ, ради устранения
-- которого форма и выбрана: немонотонный номер, который проявляется НЕ здесь,
-- а на выкатке у живой базы — расхождением схем при успешном исходе обеих
-- сторон.
--
-- Цена отступления названа: номер, выведенный из каталога, двум линиям от одной
-- базы даёт ОДИН ответ. Этот риск ловится до слияния — гейтом уникальности
-- номера в каталоге (`TestMigrationVersionsAreUniquePerDirectory`), тем же
-- коротким прогоном, что гоняет хук отправки. Риск немонотонности не ловится
-- ничем: гейт формы (`TestNewMigrationOutranksEveryAppliedOne`) судит ФОРМУ
-- имени, а не порядок между двумя метками времени, и на обоих номерах зелен.

-- +goose Up

-- Перепись ДО — чтобы самопроверка ниже утверждала «эта миграция живости не
-- меняла» ЗАМЕРОМ, а не выписанным числом. Выписанное число устарело бы молча:
-- каталог растёт, и его мощность уже менялась дважды за две задачи.
CREATE TEMP TABLE _catalog_verb_before ON COMMIT DROP AS
SELECT (SELECT count(*) FROM kacho_iam.catalog_module   WHERE live) AS modules,
       (SELECT count(*) FROM kacho_iam.catalog_resource WHERE live) AS resources,
       (SELECT count(*) FROM kacho_iam.catalog_verb     WHERE live) AS verbs;

ALTER TABLE kacho_iam.catalog_verb
  ADD COLUMN resource_live boolean
    GENERATED ALWAYS AS (CASE WHEN live THEN true END) STORED;

COMMENT ON COLUMN kacho_iam.catalog_verb.resource_live IS
  'Составляющая ключа «мой ресурс ЖИВ». У живой строки — true, у снятой — NULL, и NULL здесь означает «эта строка ресурс не удерживает», а не «значение не задано»: ключ с пустой составляющей не проверяется вовсе (MATCH SIMPLE). Константа true сделала бы ресурс неснимаемым — снятые строки каталога не удаляются. СУЩЕСТВОВАНИЕ ресурса эта колонка не утверждает: его держит catalog_verb_resource_fk, и потому тот ключ не снимается.';

ALTER TABLE kacho_iam.catalog_verb
  ADD CONSTRAINT catalog_verb_resource_live_fk
    FOREIGN KEY (module, resource, resource_live)
    REFERENCES kacho_iam.catalog_resource (module, resource, live) MATCH SIMPLE
    ON DELETE NO ACTION ON UPDATE NO ACTION;

-- ── САМОПРОВЕРКА ИСХОДА И ПЕРЕПИСЬ ───────────────────────────────────────────
--
-- Утверждается ровно то, что эта миграция обещает: ОБА ключа на месте (живость —
-- новый, существование — прежний), живость ни одной строки не изменилась, и
-- состояние «ресурс снят при живом глаголе» в каталоге отсутствует. Перепись
-- печатается ВСЕГДА — «ноль расхождений» обязано быть отличимо от «ноль
-- прочитанного».

-- +goose StatementBegin
DO $$
DECLARE
    before_mod   int;
    before_res   int;
    before_verb  int;
    after_mod    int;
    after_res    int;
    after_verb   int;
    live_key     int;
    exists_key   int;
    contradicted int;
BEGIN
    SELECT modules, resources, verbs
      INTO before_mod, before_res, before_verb
      FROM _catalog_verb_before;

    SELECT count(*) INTO live_key
      FROM pg_constraint
     WHERE conname = 'catalog_verb_resource_live_fk'
       AND conrelid = 'kacho_iam.catalog_verb'::regclass;
    IF live_key <> 1 THEN
        RAISE EXCEPTION
            'ключ catalog_verb_resource_live_fk не заведён (найдено %): без него '
            'состояние «ресурс снят, его глаголы живы» остаётся представимым '
            '(kacho#1878)', live_key;
    END IF;

    -- Прежний ключ обязан УЦЕЛЕТЬ, и это не педантизм: у снятой строки новый
    -- ключ вакуумен by construction (MATCH SIMPLE), поэтому существование
    -- ресурса держит только он. Снявший его получит строку глагола, ссылающуюся
    -- в никуда, и ни одна проверка об этом не скажет.
    SELECT count(*) INTO exists_key
      FROM pg_constraint
     WHERE conname = 'catalog_verb_resource_fk'
       AND conrelid = 'kacho_iam.catalog_verb'::regclass;
    IF exists_key <> 1 THEN
        RAISE EXCEPTION
            'ключ существования catalog_verb_resource_fk отсутствует (найдено %): '
            'ключ живости его НЕ заменяет — у снятой строки он не проверяется '
            'вовсе (kacho#1878)', exists_key;
    END IF;

    SELECT count(*) INTO after_mod  FROM kacho_iam.catalog_module   WHERE live;
    SELECT count(*) INTO after_res  FROM kacho_iam.catalog_resource WHERE live;
    SELECT count(*) INTO after_verb FROM kacho_iam.catalog_verb     WHERE live;

    IF (after_mod, after_res, after_verb) IS DISTINCT FROM (before_mod, before_res, before_verb) THEN
        RAISE EXCEPTION
            'миграция изменила живой каталог: было модулей %, ресурсов %, глаголов %; '
            'стало %, %, % — ключ обязан менять ПРЕДСТАВИМОЕ, а не посеянное (kacho#1878)',
            before_mod, before_res, before_verb, after_mod, after_res, after_verb;
    END IF;

    -- Ключ только что провалидировал каждую строку, поэтому противоречие здесь
    -- невозможно. Проверка стоит не ради него, а ради того, чтобы перепись
    -- называла ОБЕ величины: «нарушений 0» при «прочитано 0» неотличимо от
    -- исправной работы.
    SELECT count(*) INTO contradicted
      FROM kacho_iam.catalog_verb cv
      JOIN kacho_iam.catalog_resource cr
        ON cr.module = cv.module AND cr.resource = cv.resource
     WHERE cv.live AND NOT cr.live;
    IF contradicted <> 0 THEN
        RAISE EXCEPTION
            'живых глаголов у снятых ресурсов: % — ключ не удержал порядок (kacho#1878)',
            contradicted;
    END IF;

    RAISE NOTICE
        'ключ живости ресурса: осмотрено живых модулей %, ресурсов %, глаголов %; '
        'живых глаголов у снятых ресурсов %; ключей на месте: живость %, существование %',
        after_mod, after_res, after_verb, contradicted, live_key, exists_key;
END;
$$;
-- +goose StatementEnd

-- +goose Down
--
-- Откат снимает ПОРЯДОК, а не данные: ни одна строка каталога не меняется.
-- После него состояние «ресурс снят, его глаголы живы» снова становится
-- представимым — и это надо знать тому, кто откат применяет. Ключ
-- существования `catalog_verb_resource_fk` откат не трогает: он заведён другой
-- миграцией и отвечает за другое.
ALTER TABLE kacho_iam.catalog_verb
  DROP CONSTRAINT catalog_verb_resource_live_fk;

ALTER TABLE kacho_iam.catalog_verb
  DROP COLUMN resource_live;
