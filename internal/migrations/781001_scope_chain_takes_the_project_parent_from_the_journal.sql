-- 781001_scope_chain_takes_the_project_parent_from_the_journal — предок проекта
-- берётся из ПРОЕКЦИИ ЖУРНАЛА, а не из таблицы состояния.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПРЕДМЕТ
--
-- Миграция 740001 достроила цепь областей двумя звеньями, выводимыми из
-- собственной схемы iam: предок проекта — `projects.account_id`, предок
-- аккаунта — синглтон `clusters`. Довод был верен: величина принадлежит iam,
-- копии не заводится, устареть нечему.
--
-- Неверной оказалась молчаливая посылка «строка `projects` есть у каждого
-- проекта». Замер стенда 2026-08-20: таблица состояния знает 38 проектов,
-- проекция журнала (`relation_fact`, `object_type='project'`) — 236. Указатель
-- на аккаунт есть у ВСЕХ 236; 198 проектов существуют только в журнале, и у них
-- живы дочерние ресурсы сети.
--
-- Следствие наблюдаемо и ТИХО: выдача, сделанная на аккаунт, до объекта под
-- таким проектом не доходит, тогда как движок отношений её разрешает. Теневая
-- сверка формы E с движком расходилась на 61 % сравнений (#775, две подачи:
-- на настоящих выдачах 61.0 %, на перестановках 0.13 % — то есть расходятся
-- НАСТОЯЩИЕ выдачи, а не синтетика фикстуры).
--
-- ПОЧЕМУ ЭТО НЕ РАСШИРЕНИЕ ОХВАТА ПРАВ. Ни одного нового доступа здесь не
-- выдаётся. Движок эти доступы УЖЕ разрешает — форма E отвечала «нет» там, где
-- действующий решатель отвечает «да». Правка убирает расхождение, догоняя
-- решателя; обратное прочтение («форма стала пускать больше») неверно и в
-- сообщении коммита названо прямо.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ПРОЕКТ — ИЗ ЖУРНАЛА, А АККАУНТ — ПО-ПРЕЖНЕМУ ИЗ СХЕМЫ
--
-- Асимметрия не подгонка под сегодняшние числа, а следствие того, КТО у каждого
-- звена производитель. Правило одно: звено берётся из источника, полного
-- ПО ПОСТРОЕНИЮ для этого звена, и источник называется вслух.
--
--   проект → аккаунт. Проект заводится ровно одним путём — `Project.Create`,
--   который СО-КОММИТИТ иерархический кортеж в той же транзакции (проба
--   `project must co-commit project→account hierarchy`), а `account_id`
--   неизменяем после создания («accountId is immutable after Project.Create»).
--   Значит указатель в журнале есть у каждого проекта, заведённого продуктом, и
--   не может устареть. Миграций, сеющих `kacho_iam.projects`, в дереве НОЛЬ
--   (предикат: `grep -rn 'INSERT INTO kacho_iam.projects' services/iam/internal/migrations/*.sql`).
--   Журнал полон по построению; таблица состояния — наблюдаемо нет (#782).
--
--   аккаунт → кластер. Здесь всё наоборот, и это ИЗМЕРЕНО, а не предположено:
--   аккаунты сеются миграциями напрямую — 0009, 0044, 0057, — а производитель
--   указателя живёт в рантайме создания аккаунта. У засеянного `kacho-system`
--   указателя в журнале нет вовсе: журнал 235 против 236 строк `accounts`.
--   Для этого звена полна по построению именно схема — строка `accounts` И ЕСТЬ
--   аккаунт. Перевод его на журнал оборвал бы верхний ярус §«Три уровня
--   супер-доступа» ровно на системном аккаунте, поэтому ветвь (3) НЕ ТРОГАЕТСЯ.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ОДИН ИСТОЧНИК НА ЗВЕНО, И ПРАВИЛО РАЗРЕШЕНИЯ КОНФЛИКТА
--
-- После этой миграции предок проекта выводится РОВНО ИЗ ОДНОГО места. Таблица
-- `projects` цепью больше не читается — двух мест об одном предмете не остаётся,
-- поэтому расходиться нечему.
--
-- Ветвь (1) и ветвь (2) взаимоисключающи по построению: `NOT EXISTS` по
-- собственной стороне ребра сохранён дословно из 740001 — владелец, назвавший
-- цепь своего объекта сам, вывод отменяет. Сегодня это правило вырожденно
-- (рёбер типа `project` в `resource_parent_edge` — 0), но оно остаётся
-- действующим и объявленным: точное не затирается приблизительным.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ДИСКРИМИНАТОР УКАЗАТЕЛЯ — СТРУКТУРНЫЙ, А НЕ СПИСОЧНЫЙ
--
-- В `relation_fact` лежат ВСЕ прямые факты, а не только звенья иерархии:
-- `owner`, `admin`, `system_admin` — с субъектом-человеком или служебной
-- учётной записью. Взять оттуда всё подряд значило бы объявить пользователя
-- предком объекта, то есть раздать доступ по кортежу владения.
--
-- Указатель отличается СТРУКТУРНО: отношение НАЗЫВАЕТ ТИП своего субъекта
-- (`project --account--> account:acc-1`, `project --cluster--> cluster:...`).
-- У не-указателей это не выполняется никогда (`admin` ≠ `user`). Перечня пар
-- здесь нет намеренно: список был бы вторым местом об одном предмете и разошёлся
-- бы с моделью прав молча, при заведении первого же нового звена.
--
-- Субъект-userset (`group:grp-1#member`) объектом не является и предком быть не
-- может — такая строка отсекается: иначе в цепь уехал бы идентификатор с хвостом
-- отношения, который не совпадёт ни с одним объектом и потому потерялся бы тихо.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧИСЛО СТРОК НА ОБЪЕКТ: ПРЕЖНИЙ ДОВОД ЗАМЕНЁН, А НЕ УНАСЛЕДОВАН
--
-- 740001 обосновывала «предел внутри соединения вбок не усекает» тем, что строк
-- на объект не больше глубин (ключ `resource_parent_edge` уникален по глубине).
-- Для журнальной ветви этот довод НЕ ДЕЙСТВУЕТ: у проекта указателей два —
-- аккаунт и кластер, — и оба лежат на глубине 1.
--
-- Новый довод — числом: указателей у объекта столько, сколько у его типа
-- РАЗНЫХ отношений-указателей в модели прав; у проекта их 2, у аккаунта 1
-- (замер стенда: max = 2 при `MaxAncestorDepth` = 4). Запас двукратный, но он не
-- самоочевиден и потому ПРОВЕРЯЕТСЯ: перепись `iam-scope-source-census.sh`
-- печатает максимум указателей на объект и отказывает, если он достиг предела
-- обхода. Без этого рост числа звеньев усекал бы цепь молча.
--
-- Звено `проект → кластер` (236 строк) в цепи НОВОЕ: прежде проект доходил до
-- кластера только через аккаунт. Достижимое множество предков от этого не
-- меняется (кластер и так был предком аккаунта), а верхний ярус становится
-- достижим и тогда, когда указатель на аккаунт почему-либо отсутствует.

-- +goose Up

CREATE OR REPLACE VIEW kacho_iam.resource_scope_edge AS
  -- (1) То, что прислал владелец объекта. Дословно, без отбора: чей ресурс — того
  --     и цепь. Не изменилось.
  SELECT e.object_type, e.object_id, e.parent_type, e.parent_id, e.depth
    FROM kacho_iam.resource_parent_edge e
UNION ALL
  -- (2) Предок проекта — ИЗ ПРОЕКЦИИ ЖУРНАЛА, оттуда же, откуда его берёт движок
  --     отношений. Указатель кладёт создание проекта, со-коммитя кортеж в своей
  --     транзакции; `relation_fact` наполняет триггер на строке журнала
  --     (миграция 0098), поэтому копии не заводится и здесь.
  SELECT 'project'::text,
         f.object_id,
         split_part(f.subject, ':', 1),
         substr(f.subject, position(':' in f.subject) + 1),
         1
    FROM kacho_iam.relation_fact f
   WHERE f.object_type = 'project'
     -- Указатель, а не любой прямой факт: отношение называет тип субъекта.
     AND f.relation = split_part(f.subject, ':', 1)
     -- Userset предком не бывает: у него вместо объекта хвост отношения.
     AND position('#' in f.subject) = 0
     AND NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'project' AND e.object_id = f.object_id)
UNION ALL
  -- (3) Предок аккаунта — кластер. НЕ ИЗМЕНИЛОСЬ, и это решение, а не пропуск:
  --     аккаунты сеются миграциями (0009/0044/0057), указателя в журнале у них
  --     нет, и перевод этой ветви на журнал оборвал бы верхний ярус доступа на
  --     системном аккаунте. Полон по построению здесь именно `accounts`.
  SELECT 'account'::text, a.id, 'cluster'::text, c.id, 1
    FROM kacho_iam.accounts a
   CROSS JOIN kacho_iam.clusters c
   WHERE NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'account' AND e.object_id = a.id);

COMMENT ON VIEW kacho_iam.resource_scope_edge IS
  'Цепь областей, какой её читает вопрос о доступе: рёбра, присланные владельцами ресурсов (resource_parent_edge), ПЛЮС два достроенных звена. Предок ПРОЕКТА берётся из проекции журнала (relation_fact, отношение называет тип субъекта) — оттуда же, откуда его берёт движок отношений: указатель со-коммитится созданием проекта, account_id неизменяем, миграции проекты не сеют, поэтому журнал полон по построению, а таблица projects наблюдаемо нет (#781/#782). Предок АККАУНТА берётся из схемы (accounts × clusters): аккаунты сеются миграциями 0009/0044/0057 без указателя в журнале, поэтому полна по построению здесь схема. Правило одно: источник, полный по построению для ЭТОГО звена. Владелец, назвавший цепь своего объекта сам, вывод отменяет (NOT EXISTS) — ветви взаимоисключающи, двух мест об одном предмете нет. ПИСАТЬ СЮДА НЕЛЬЗЯ: производители пишут в resource_parent_edge и в журнал.';

-- +goose Down

CREATE OR REPLACE VIEW kacho_iam.resource_scope_edge AS
  SELECT e.object_type, e.object_id, e.parent_type, e.parent_id, e.depth
    FROM kacho_iam.resource_parent_edge e
UNION ALL
  SELECT 'project'::text, p.id, 'account'::text, p.account_id, 1
    FROM kacho_iam.projects p
   WHERE p.account_id <> ''
     AND NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'project' AND e.object_id = p.id)
UNION ALL
  SELECT 'account'::text, a.id, 'cluster'::text, c.id, 1
    FROM kacho_iam.accounts a
   CROSS JOIN kacho_iam.clusters c
   WHERE NOT EXISTS (
           SELECT 1 FROM kacho_iam.resource_parent_edge e
            WHERE e.object_type = 'account' AND e.object_id = a.id);

COMMENT ON VIEW kacho_iam.resource_scope_edge IS
  'Цепь областей, какой её читает вопрос о доступе: рёбра, присланные владельцами ресурсов (resource_parent_edge), ПЛЮС два звена, выводимых из собственной схемы iam, — project→account (projects.account_id) и account→cluster (синглтон clusters). Выводимые звенья не хранятся: копии нет, обратного заполнения нет, устареть нечему. Владелец, назвавший цепь своего объекта сам, вывод отменяет (NOT EXISTS по object_type/object_id) — точное не затирается приблизительным, и число строк на объект не превышает границы глубины. ПИСАТЬ СЮДА НЕЛЬЗЯ: производители пишут в resource_parent_edge.';
