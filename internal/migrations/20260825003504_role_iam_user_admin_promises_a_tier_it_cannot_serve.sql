-- Роль `iam.user.admin` выводится из обращения: ярус, который обещает её имя, тип
-- больше не может обслужить.
--
-- ПРЕДМЕТ (#1189). Роль посеяна 0001, правило переписано 0031 §4.7:
-- `[{"modules":["iam"],"resources":["user"],"verbs":["*"]}]`. Подстановка
-- разворачивается в набор ТИПА, а тем же изменением, что и эта миграция, с типа
-- `iam_user` снят последний распоряжающийся глагол — `v_delete` (первым был
-- `v_update`, #1128). Набор типа стал `[get list]`.
--
-- ЧТО ИЗ ЭТОГО СЛЕДУЕТ, И ЭТО СЛЕДУЕТ ИЗ КОДА, А НЕ ИЗ ОСТОРОЖНОСТИ. Ярус выводится
-- из РАЗВЁРНУТЫХ глаголов (`domain.ResolveVerbsAndTier`): удаление даёт
-- администратора, правка — редактора, чтение — наблюдателя. С набором `[get list]`
-- роль материализует ярус НАБЛЮДАТЕЛЯ и пообъектные `v_get`/`v_list` — ровно то же,
-- что даёт соседняя `iam.user.view`. То есть роль стала её дубликатом под именем,
-- которое обещает администрирование.
--
-- ПОЧЕМУ ВЫВОД, А НЕ «ПУСТЬ ОСТАЁТСЯ ЧТЕНИЕМ». Смысла, который обещает её имя, у
-- неё быть НЕ МОЖЕТ: распоряжение строкой личности выражено ВЫЧИСЛЯЕМЫМИ
-- отношениями — `record_writer`, `identity_suspender` (#1102), `identity_remover`
-- (#1131), — а вычисляемое отношение нельзя ни выдать, ни материализовать. Пока
-- роль лежит в каталоге, распорядитель выдаёт её, полагая, что вручил
-- администрирование людей, и узнаёт обратное только по последствиям. Это тот самый
-- класс, ради которого разбирали и `iam.user.edit` (#1128).
--
-- ЧЕМ ЭТО ДЕРЖИТСЯ, А НЕ ОБЕЩАЕТСЯ. Гейт паритета ярусов
-- (`tier_parity_integration_test.go`, свойство 1, обратная сторона) требует: ярус,
-- которому НЕЧЕМ быть, не должен существовать в посеве. Без этой миграции он
-- красный и называет координату дословно.
--
-- ЦЕНА НАЗВАНА. На существующем стенде привязки на эту роль удаляются вместе с ней:
-- держатель теряет ЧТЕНИЕ людей, которое роль фактически давала, и получить его
-- заново обязан через `iam.user.view` — роль с тем же исходом и честным именем.
-- Заменять выдачи автоматически эта миграция НЕ будет: подставить одну роль вместо
-- другой значит принять за распорядителя решение, которого он не принимал.
--
-- ЧТО ОСТАЁТСЯ АККАУНТУ. Читать своих людей (`iam.user.view`) и распоряжаться их
-- УЧАСТИЕМ: исключение из аккаунта (`UserService.RemoveFromAccount`, гейт
-- `account.member_remover`, #1127). Личность человека — глобальная строка, одна на
-- все его аккаунты, и права аккаунта за его границу не выходят.
--
-- ИДЕМПОТЕНТНА. Все стейтменты ключуются на детерминированном идентификаторе роли,
-- поэтому повторный прогон — и повторное применение к уже выведенной базе — не
-- меняют ничего. Аддитивна к истории: ни одна применённая миграция не правится
-- (запрет #5). Порядок с соседним файлом того же изменения безразличен: предметы
-- непересекающиеся — там снимаются пары проекции по глаголу, здесь удаляются строки
-- одной роли (её пары уйдут каскадом в любом порядке).

-- +goose Up
-- +goose StatementBegin

-- (1) Селекторы, спроецированные из правил роли. Они каскадируют от roles(id), но
--     удаление названо явно: выведенное состояние не должно зависеть от того, что
--     каскад настроен сегодня именно так.
DELETE FROM kacho_iam.role_rule_selectors
 WHERE role_id = 'rol' || substr(md5('iam.user.admin'), 1, 17);

-- (2) Проекция «роль → тип × глагол», которую читает вердикт. Тоже каскадирует и
--     тоже названа явно, по той же причине.
DELETE FROM kacho_iam.role_verb
 WHERE role_id = 'rol' || substr(md5('iam.user.admin'), 1, 17);

-- (3) Привязки, выдававшие эту роль. `access_bindings_role_fk` — ON DELETE
--     RESTRICT, поэтому они идут ДО роли; субъекты, цели, состав целей, выданные
--     кортежи и условия каскадируют от привязки. Ключ — role_id, а не идентификатор
--     посеянной привязки: привязка, заведённая на эту роль любым другим путём,
--     обязана уйти вместе с ней, иначе шаг (4) упрётся в голый RESTRICT без
--     называемой причины.
DELETE FROM kacho_iam.access_bindings
 WHERE role_id = 'rol' || substr(md5('iam.user.admin'), 1, 17);

-- (4) Сама роль. Область — детерминированный посеянный идентификатор, поэтому
--     аккаунт-областная роль арендатора с тем же именем остаётся своему владельцу.
DELETE FROM kacho_iam.roles
 WHERE id = 'rol' || substr(md5('iam.user.admin'), 1, 17);

-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin

