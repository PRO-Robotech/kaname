-- ключом доступа получает свою таблицу (Ф13, задача PRO-Robotech/kaname#613).
--
-- Санкция: приёмка `docs/engineering/acceptance/passwordless-login-with-access-key.md`,
-- редакция 9 (отпечаток 5fe6cca1…8af4, запись
-- `docs/specs/reviews/passwordless-login-with-access-key/5fe6cca1aea606f96b2f24174a8f45411291f69250e6fb268b3274fd17a58af4.yaml`,
-- APPROVED): Р2 (испытание без имени, одно на контекст, однократное), §9 п. 4.
--
-- =============================================================================
-- ПОЧЕМУ СВОЯ ТАБЛИЦА, А НЕ КОЛОНКА В ИСПЫТАНИЯХ ЦЕРЕМОНИЙ
-- =============================================================================
-- `access_key_challenges` привязывает строку к ЧЕЛОВЕКУ внешним ключом: там
-- вызывающий назван своей сессией. У полосы входа человека нет — его
-- обнаруживают по предъявленному удостоверению уже после сверки. Сделать
-- колонку человека необязательной значило бы ослабить инвариант церемоний ради
-- чужого предмета. У входа своя строка со своим ключом привязки — КОНТЕКСТОМ
-- ФОРМЫ (печенье `kaname_form`); испытание входа в церемонии не находится и
-- наоборот — держит раздельность таблиц, а не совпадение значений.
--
-- =============================================================================
-- ОДНО ЖИВОЕ НА КОНТЕКСТ — ЧАСТИЧНАЯ УНИКАЛЬНОСТЬ, НЕ ПРОВЕРКА ПЕРЕД ВСТАВКОЙ
-- =============================================================================
-- Повторная выдача ЗАМЕЩАЕТ прежнее живое испытание контекста (Ф13-03). Будь
-- это «посмотреть и решить» — два одновременных запроса одного контекста
-- завели бы два живых испытания (ban #10). Второе живое в контексте невыразимо
-- частичным ключом уникальности по НЕПОТРЕБЛЁННЫМ строкам; замещение — снятие
-- прежнего и вставка нового одной транзакцией.
--
-- =============================================================================
-- ОДНОКРАТНОСТЬ — ОДИН ОПЕРАТОР; ВРЕМЯ — ЧАСЫ БАЗЫ
-- =============================================================================
-- Годность и сгорание — одно действие: строка этого контекста, не потреблённая
-- и не истёкшая, получает отметку тем же оператором, который её отбирает.
-- Моменты выдачи, предела и предъявления ставит база (`now()`): реплик службы
-- больше одной, испытание выдаёт одна, а предъявляют другой, и сравнивать
-- моменты разных часов значило бы делать границу срока расхождением часов.
-- Умолчания у `expires_at` нет: срок — величина контракта (Ф7 §7 инв. 5), её
-- приносит вызывающий, и забытая величина — отказ записи, а не подстановка.
--
-- =============================================================================
-- РОСТ ОГРАНИЧЕН УБОРКОЙ
-- =============================================================================
-- У строки есть момент, после которого ни один читатель не изменит из-за неё
-- исхода: срок вышел либо она потреблена. Порог и уборщик — реестр уборки
-- службы, тот же, что у испытаний церемоний.

-- +goose Up

CREATE TABLE kaname.access_key_login_challenges (
    challenge    bytea NOT NULL,
    form_context text NOT NULL,
    issued_at    timestamp with time zone DEFAULT now() NOT NULL,
    expires_at   timestamp with time zone NOT NULL,
    consumed_at  timestamp with time zone,
    CONSTRAINT access_key_login_challenges_pkey PRIMARY KEY (challenge),
    CONSTRAINT access_key_login_challenges_challenge_check CHECK ((octet_length(challenge) = 32)),
    CONSTRAINT access_key_login_challenges_form_context_check
        CHECK ((length(form_context) >= 1 AND length(form_context) <= 128)),
    CONSTRAINT access_key_login_challenges_span_check CHECK ((expires_at > issued_at)),
    CONSTRAINT access_key_login_challenges_consumed_check
        CHECK ((consumed_at IS NULL OR consumed_at >= issued_at))
);

COMMENT ON TABLE kaname.access_key_login_challenges IS
  'Выданные испытания полосы входа ключом доступа: привязаны к контексту формы (человек на выдаче неизвестен), однократны (consumed_at), срочны (expires_at — та же величина, что у испытаний церемоний). Моменты ставят часы базы. Одно живое на контекст держит частичный ключ уникальности. Убираются реестром уборки.';
COMMENT ON COLUMN kaname.access_key_login_challenges.form_context IS
  'Контекст формы (печенье kaname_form), под которым испытание выдано: ключ привязки вместо человека — его на выдаче назвать нечем.';

-- Одно ЖИВОЕ испытание на контекст (Ф13-03): потреблённые строки под ключ не
-- подпадают и сохраняются до уборки.
CREATE UNIQUE INDEX access_key_login_challenges_live_context_idx
    ON kaname.access_key_login_challenges USING btree (form_context) WHERE (consumed_at IS NULL);

CREATE INDEX access_key_login_challenges_expires_idx
    ON kaname.access_key_login_challenges USING btree (expires_at);

-- Испытание — одноразовое случайное значение: выборка в статистике
-- планировщика была бы его копией с чужим сроком хранения; отбирается оно
-- точным равенством по первичному ключу.
ALTER TABLE kaname.access_key_login_challenges ALTER COLUMN challenge SET STATISTICS 0;

-- +goose Down

-- Откат безопасен: строка испытания не восстанавливает ничьего доступа и
-- ничьим материалом не является — она одноразова. Снятие таблицы означает
-- лишь, что предъявление, начатое до отката, придётся начать заново.
DROP TABLE kaname.access_key_login_challenges;
