-- =============================================================================
-- ПОЧЕМУ СВОЙ СТОЛБЕЦ, А НЕ ПРИНЯТЫЙ ШАГ
-- =============================================================================
-- Принятый шаг кода (`last_accepted_step`) пишет и подтверждение заведения, а
-- момента использования сразу после подтверждения быть не должно (SUA-40). У
-- набора запасных кодов шага нет вовсе. Момент — свой столбец; NULL — «не
-- использовали», и наружу это отсутствие ключа ответа, а не нулевое время.
--
-- =============================================================================
-- КТО ПИШЕТ
-- =============================================================================
-- Только операторы ПРЕДЪЯВЛЕНИЯ: условная запись принятого шага кода и снятие
-- элемента набора — тем же оператором, что их предмет. Замена набора и
-- новое заведение кода момент гасят: новый материал не наследует момента
-- прежнего. Подтверждение заведения его не пишет. Лежащих строк накат не
-- трогает — у них момента нет, и это правда: до этой миграции его никто не
-- записывал.
--
-- =============================================================================
-- ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО
-- =============================================================================
-- Проверки «момент не раньше `created_at`» нет: моменты ставят часы разных
-- реплик службы, и отказ схемы на верном предъявлении был бы хуже отсутствия
-- проверки. Момент пароля невыразим: проверка допускает столбец только у
-- способов второго фактора.

-- +goose Up

ALTER TABLE kaname.user_login_methods ADD COLUMN last_used_at timestamp with time zone;

ALTER TABLE kaname.user_login_methods
    ADD CONSTRAINT user_login_methods_last_used_kind_check
        CHECK ((last_used_at IS NULL OR kind IN ('totp', 'lookup_secret')));

COMMENT ON COLUMN kaname.user_login_methods.last_used_at IS
  'Момент последнего принятого предъявления способа второго фактора: принятый код по времени либо снятый запасной код. NULL — не использовали после заведения либо выпуска набора.';

-- +goose Down

-- Откат снимает столбец без потерь входа: момент — не материал способа, после
-- повторного наката строки читаются «не использовали».
ALTER TABLE kaname.user_login_methods DROP CONSTRAINT user_login_methods_last_used_kind_check;
ALTER TABLE kaname.user_login_methods DROP COLUMN last_used_at;
