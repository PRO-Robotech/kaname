// comparator.go — ЕДИНАЯ ТОЧКА, через которую проходит решение о доступе,
// принятое внутри iam.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ У КАЖДОГО СТРАЖА
//
// Сравнение двух форм жило у края (`service.AuthorizeService`), и это верно для
// вопросов, которые край отвечает. Но решения принимает не только он: собственные
// стражи чтения, область выдачи, потолки кластера и сужение страницы спрашивают
// движок сами. Их набор был перемерен по дереву, а не по диффу: пятнадцать мест
// решали доступ, и сравнение не видело ни одного.
//
// Дописать вызов сравнения в каждое из пятнадцати мест значило бы закрыть находку
// и оставить класс: шестнадцатое место пишется как пятнадцать предыдущих, и ничто
// об этом не скажет. Поэтому сравнение стоит там, где у стража НЕТ ВЫБОРА, —
// в значении, которое композиционный корень ему выдаёт. Другого значения у корня
// для стража нет (см. `own_gates.go`, комментарий у `relationStore`), поэтому
// «спросить, не предъявив сравнению» становится не невыполненным требованием, а
// невыразимым действием.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО НЕ ТОЛЬКО ПРО ИЗМЕРЕНИЕ
//
// Ближайшая фаза переключает источник вердикта ПОТИПОВО, с откатом на тип. Это
// верно ровно до тех пор, пока каждый вопрос проходит через одну точку. Страж
// чтения задаёт вопрос ТИПО-НЕЗАВИСИМО (тип приезжает параметром), поэтому
// потиповое переключение не накрывает его никаким порядком типов: на первом же
// переключённом типе один и тот же вопрос об одном и том же объекте получил бы
// ответ новой формы через край и ответ движка через стража. Два действующих
// источника истины на один вопрос — состояние хуже нынешнего, где источник один.
//
// Значит эта точка нужна дважды: сегодня она СРАВНИВАЕТ, а на переключении будет
// тем единственным местом, где источник вердикта меняется. Оба свойства держатся
// одним фактом — вопрос проходит здесь.

package authzcascade

import "context"

// VerdictComparator — узкий порт теневого сравнения.
//
// Объявлен ЗДЕСЬ, а не импортирован: пакет обязан остаться листом (он не вправе
// зависеть ни от края, ни от источника формы E). Реализуется
// `internal_iam/shadowverdict.Comparator`, провязывается композиционным корнем.
// Набор методов — подмножество того, что край держит под именем
// `service.ShadowComparator`; одно значение удовлетворяет обоим, поэтому счётчики
// у края и у стражей общие, а не две разные меры одного предмета.
type VerdictComparator interface {
	// Ask задаёт форме E вопрос СЕЙЧАС и отдаёт сведение исхода. Сведение
	// обязано быть вызвано на каждом пути — отсюда `defer` на местах вызова.
	//
	// engineAnswered=false означает «движок вердикта не дал»: сравнивать не с
	// чем, и исход идёт в отдельную корзину, а не в согласие.
	Ask(ctx context.Context, subject, objectType, objectID, relation string,
		condCtx map[string]any) func(engineAllowed, engineAnswered bool)
	// Decides — принимает ли решение по этому типу ФОРМА.
	//
	// Рубильник живёт в СРАВНИТЕЛЕ, а не здесь, и это не деталь размещения.
	// Поверхностей решения две — край и эта обёртка, — и край через обёртку не
	// проходит вовсе: композиционный корень выдаёт ему голый транспорт (это
	// записанное решение, а не недосмотр). Общее у двух поверхностей ровно одно
	// значение — сравнитель. Рубильник, положенный в него, оказывается один на
	// обе by construction; рубильник у каждой двери разошёлся бы, и один вопрос
	// об одном объекте получил бы два действующих источника.
	Decides(objectType string) bool
	// Verdict — вердикт ФОРМЫ по переключённому типу.
	//
	// Движок спрашивается РЯДОМ функцией `askEngine` и только сверяется; её
	// исход на ответ вызывающему не влияет никак, включая недоступность движка.
	// «Как спросить движок» знает вызывающий: у края к ответу движка добавляются
	// плоский надзор администратора облака и структурный запасной путь, и
	// сравнивать половину ответа значило бы записывать расхождение между
	// стадиями одного решения, а не между формами.
	//
	// Ошибка означает «ФОРМА НЕ ОТВЕТИЛА» и обязана доехать до вызывающего как
	// недоступность. Ни отказом в доступе, ни ответом движка она не становится:
	// запасной путь на движок вернул бы зависимость от него ровно под той
	// нагрузкой, при которой её отсутствие только что объявили измеренным, — и
	// вернул бы невидимо, потому что ответ вызывающему при этом правильный.
	Verdict(ctx context.Context, subject, objectType, objectID, relation string,
		condCtx map[string]any,
		askEngine func(context.Context) (engineAllowed, engineAnswered bool)) (bool, error)
	// VerdictMany — вердикт ФОРМЫ о СТРАНИЦЕ объектов одного переключённого типа.
	//
	// Отдельный метод, а не цикл по `Verdict`, и это про стоимость, а не про
	// удобство: форма отвечает на прямой вопрос точечно, одной читающей
	// транзакцией, и страница по контракту доходит до тысячи объектов. Цикл дал
	// бы транзакцию на объект — ровно тот класс, который на этом дереве уже
	// ловится замером стоимости страницы. Здесь страница стоит ОДНУ транзакцию,
	// а её объекты видят один снимок базы — что вдобавок вернее: страница,
	// собранная из тысячи снимков, не существовала целиком ни в один момент.
	//
	// Ответ обязан прийти в порядке вызывающего: верный, но переставленный
	// вердикт фильтрует страницу чужим ответом.
	VerdictMany(ctx context.Context, subject, objectType string, objectIDs []string, relation string,
		condCtx map[string]any,
		askEngine func(context.Context) (engineVerdicts []bool, engineAnswered bool)) ([]bool, error)
	// Unaskable отмечает решение, которое форме E задать нельзя. Существует
	// ради знаменателя: пропуск, не попавший в число решений, делает долю
	// сравнённого лучше, ничего не улучшив.
	Unaskable(reason, objectType, relation string)
}

// BatchCompareBudget — сколько объектов страницы сверяется за ОДИН батчевый
// вопрос; остальные объявляются незаданными с причиной и остаются в знаменателе.
//
// Величина выбрана из назначения, а не из вкуса, и это единственное место
// под-фазы, где сверка сознательно неполна — поэтому граница названа здесь, а не
// оставлена в чьей-то памяти.
//
// Форма E отвечает на прямой вопрос ТОЧЕЧНО: одна читающая транзакция на
// (субъект, тип, объект, отношение). Сверять страницу поштучно значило бы
// открыть по транзакции на каждый её объект: страница по контракту доходит до
// 1000, сужение спрашивает по отношению из набора типа, а батчевые запросы идут
// с распараллеливанием — то есть сотни одновременных читающих транзакций на один
// живой запрос. Сравнение, которое дороже самого решения, меняет то, что
// измеряет, и первым же всплеском нагрузки будет снято как «дорогая проверка».
//
// Поэтому здесь бюджет, а не отказ от сверки и не полная сверка. Что от этого
// НЕ страдает: маршрутизация. Каждый объект страницы проходит через эту точку,
// поэтому переключение источника вердикта накроет страницу целиком независимо от
// того, сколько её объектов было сверено.
//
// Предикат снятия — внешний факт, а не чьё-то решение: как только форма E
// научится отвечать на вопрос «какие из ЭТИХ идентификаторов доступны» одним
// запросом, бюджет снимается вместе с этой константой, и сверка страницы
// становится полной. Пока такого вопроса у формы E нет, полная сверка
// недостижима не из-за нежелания, а из-за формы источника.
const BatchCompareBudget = 2

// WithComparator провязывает сравнение. Возвращает тот же клиент, чтобы
// композиционный корень собирал значение одним выражением.
//
// nil — законный вход: модульная сборка без формы E получает дешёвый no-op, а не
// панику. Боевая посадка в этом состоянии находиться не должна, поэтому её
// проверяет отказ в старте (`ownGateWiringComplaint`), а не надежда.
func (c *Client) WithComparator(cmp VerdictComparator) *Client {
	if c == nil {
		return nil
	}
	c.compare = cmp
	return c
}

// ComparatorWired сообщает, дошло ли сравнение до значения, которое держат стражи.
// Читается загрузочной проверкой: провязка в пустоту — та же форма без
// содержания, что и отсутствующая проверка, только выглядит исполненной.
func (c *Client) ComparatorWired() bool {
	return c != nil && c.compare != nil
}

// present предъявляет сравнению ОДИН вопрос и отдаёт сведение исхода.
//
// Вопрос уходит форме E ДО обращения к движку и не зависит ни от одного его
// исхода: короткое замыкание, ответ из памятки, недоступность — сравнение всё
// равно состоялось либо честно попало в «не выполнилось». Сравнение, начатое
// после ответа движка, молчит ровно там, где движок ответил дёшево, то есть на
// самом частом пути, и доля сравнённого становится неизвестной.
func (c *Client) present(
	ctx context.Context, subject, relation, object string, condCtx map[string]any,
) func(engineAllowed, engineAnswered bool) {
	if c == nil || c.compare == nil {
		return func(bool, bool) {}
	}
	ref, ok := parseObjectRef(object)
	if !ok {
		// Вопрос без разобранного объекта форме E не задать. Он всё равно
		// решение — значит идёт в знаменатель, а не выпадает из него.
		c.compare.Unaskable("объект вопроса не разобран", "", relation)
		return func(bool, bool) {}
	}
	if subject == "" {
		c.compare.Unaskable("субъект не назван", ref.Type, relation)
		return func(bool, bool) {}
	}
	return c.compare.Ask(ctx, subject, ref.Type, ref.ID, relation, condCtx)
}

// presentPage предъявляет сравнению решения ОДНОЙ батчевой двери.
//
// Сверяется не более `BatchCompareBudget` объектов; остальные объявляются
// незаданными с причиной. Одно сообщение — не одно решение: страница из N
// объектов несёт N решений, и знаменатель обязан увидеть все N, иначе доля
// сравнённого описывает не тот поток.
//
// Выборка — первые объекты страницы, а не случайные: недетерминированная выборка
// сделала бы саму меру невоспроизводимой между прогонами, а смещение здесь
// названо и известно.
func (c *Client) presentPage(
	ctx context.Context, subject, relation string, objects []string, condCtx map[string]any,
) func(verdicts []bool, engineAnswered bool) {
	if c == nil || c.compare == nil || len(objects) == 0 {
		return func([]bool, bool) {}
	}
	budget := BatchCompareBudget
	if budget > len(objects) {
		budget = len(objects)
	}
	settles := make([]func(bool, bool), 0, budget)
	for i := 0; i < budget; i++ {
		settles = append(settles, c.present(ctx, subject, relation, objects[i], condCtx))
	}
	for _, object := range objects[budget:] {
		objectType := ""
		if ref, ok := parseObjectRef(object); ok {
			objectType = ref.Type
		}
		c.compare.Unaskable("страничная сверка ограничена бюджетом на запрос", objectType, relation)
	}
	return func(verdicts []bool, engineAnswered bool) {
		for i, settle := range settles {
			allowed := false
			// Ответ движка выравнен по объектам вызывающим; короткий ответ уже
			// отвергнут как ошибка выше, но сведение обязано устоять и на нём —
			// иначе проба на рассогласование падала бы паникой вместо вердикта.
			if engineAnswered && i < len(verdicts) {
				allowed = verdicts[i]
			}
			settle(allowed, engineAnswered && i < len(verdicts))
		}
	}
}

// decidesByForm — маршрутизация ОДНОГО вопроса: принимает ли решение форма.
//
// Отвечает «нет» на всё, чего форме не задать: непровязанное сравнение,
// неразобранный объект, не названный субъект. Такой вопрос остаётся решением
// движка и предъявляется сравнению прежним путём — со своей причиной и в
// знаменателе.
func (c *Client) decidesByForm(object string) (objectRef, bool) {
	if c == nil || c.compare == nil {
		return objectRef{}, false
	}
	ref, ok := parseObjectRef(object)
	if !ok {
		return objectRef{}, false
	}
	return ref, c.compare.Decides(ref.Type)
}

// verdictByForm спрашивает форму и отдаёт её вердикт.
//
// askEngine — как спросить движок РЯДОМ. Передаётся вызывающей дверью, потому
// что двери спрашивают его по-разному (с памяткой фактов и без), а сравнивать
// надо тот ответ, который на этой двери и был бы окончательным.
func (c *Client) verdictByForm(
	ctx context.Context, subject string, ref objectRef, relation string,
	condCtx map[string]any, askEngine func(context.Context) (bool, bool),
) (bool, error) {
	return c.compare.Verdict(ctx, subject, ref.Type, ref.ID, relation, condCtx, askEngine)
}
