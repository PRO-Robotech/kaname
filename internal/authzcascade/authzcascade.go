// Package authzcascade — ДВЕРЬ РЕШЕНИЯ о доступе для собственных стражей iam.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗДЕСЬ БЫЛО И ПОЧЕМУ ЭТОГО БОЛЬШЕ НЕТ
//
// Пакет назывался каскадом потому, что каскад супер-доступа приходилось
// ДОСТРАИВАТЬ на пути запроса: внешний движок отношений знал только те кортежи,
// которые до него доехали очередью, поэтому отказ пересдавался ему второй раз —
// с «структурными фактами», прочитанными из закоммиченных строк iam и
// приложенными к вопросу как кортежи, действующие только на этот запрос.
//
// Механизма нет. Решение принимает реляционная форма в собственной базе службы
// (`repo/kacho/pg/relverdict`): она поднимает цепь областей по своим таблицам тем
// же планом модели, из которого прежде компилировался ответ движка. Значит второй
// попытки нет не потому, что от неё отказались, а потому, что первая читает ровно
// те строки, которыми вторая её дополняла.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ОСТАЛОСЬ И ПОЧЕМУ ИМЕННО ЗДЕСЬ
//
//	Client — одно значение, которое композиционный корень выдаёт КАЖДОМУ стражу.
//	         Оно и есть причина, по которой страж не может спросить «мимо»: другого
//	         значения в корне для него нет.
//
//	DerivableTypes — типы, чей структурный предок выводится из строки iam. Перечень
//	         остаётся владельцем вопроса «о каком типе цепь областей обязана
//	         высказаться», и его читает перепись источников звена
//	         (`internal/scopesourcecensus`). Выписанный рядом второй перечень не
//	         сдвинулся бы от нового типа и продолжал бы сторожить прежние.
package authzcascade

import "strings"

// DerivableTypes — типы объектов модели прав, чей структурный предок выводится из
// закоммиченной строки kacho_iam: у такой строки предок лежит КОЛОНКОЙ, поэтому
// чтение однозначно.
//
// Экспортирован ради переписи источников звена цепи областей: она обязана
// высказаться о каждом таком типе, включая тип с нулём объектов, и берёт перечень
// у владельца, а не выписывает свой.
var DerivableTypes = map[string]struct{}{
	"iam_access_binding":  {},
	"account":             {},
	"project":             {},
	"iam_user":            {},
	"iam_group":           {},
	"iam_role":            {},
	"iam_service_account": {},
}

// objectRef — «тип:идентификатор», как объект называют стражи и модель.
type objectRef struct {
	Type string
	ID   string
}

// parseObjectRef разбирает «type:id». Второй результат false означает, что строка
// объектом не является — и это НЕ «доступа нет»: вызывающий обязан отличать
// неразобранный вход от отказа, иначе опечатка в имени объекта читалась бы как
// законный отказ и никогда бы не нашлась.
func parseObjectRef(s string) (objectRef, bool) {
	i := strings.IndexByte(s, ':')
	if i <= 0 || i == len(s)-1 {
		return objectRef{}, false
	}
	return objectRef{Type: s[:i], ID: s[i+1:]}, true
}
