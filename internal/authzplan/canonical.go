package authzplan

// canonical.go — где лежит каноническая модель и как её найти.
//
// Живёт рядом с компилятором, а не у прибора, по одной причине: и продукт, и
// прибор обязаны читать ОДИН файл. Две копии обхода дерева разошлись бы молча —
// например, одна нашла бы модель во вложенном клоне, — и сравнение форм измеряло
// бы разные тексты.
//
// Путь читается только пробами и гейтами (компилятор — чистая функция от текста),
// поэтому обращение к дереву здесь допустимо: в рантайме продукта его никто не
// зовёт.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ КАНОН НЕ ИЩЕТСЯ ПОДЪЁМОМ ВВЕРХ (задача PRO-Robotech/kacho#2159)
//
// Прежде резолв поднимался за файлом ДО КОРНЯ ФАЙЛОВОЙ СИСТЕМЫ. Существенно не
// то, что он мог не найти файл, а то, что он НАХОДИЛ ЧУЖОЙ и не сомневался:
// перепись печаталась по дереву, которое назвал вызывающий, а байты — по файлу,
// который нашёлся, и отличить такой зелёный от настоящего было нечем.
//
// Предмет линии — служба, устанавливаемая в ЧУЖОМ облаке. Значит подъём «до
// корня файловой системы» из модуля есть подъём в дерево оператора.
//
// Измерено одно-фактным опытом, а не предположено: клон модуля, положенный под
// каталог с посторонним каноном, печатал «корень обхода: <клон>» и вместе с ним
// величины, снятые с файла ВНЕ клона. Менялся ровно один факт — содержимое
// постороннего файла, — и вердикт менялся вместе с ним, при неизменном дереве.
//
// ЧТО ВМЕСТО ПОДЪЁМА. Канон лежит по каноническому относительному пути ОТ КОРНЯ
// ДЕРЕВА, поэтому корень достаточно НАЗВАТЬ. Резолв читает ровно
// `<корень>/<относительный путь>` и никуда не поднимается — чужой файл ему
// недоступен BY CONSTRUCTION, а не по запрету, который можно обойти.
//
// ─────────────────────────────────────────────────────────────────────────────
// ДВА ОТКАЗА, А НЕ ОДИН, И ЭТО НЕСУЩЕЕ
//
// «Канона в дереве нет, а ВЫШЕ него он лежит» и «канона нет нигде» — разные
// состояния. Слить их в один текст значило бы вернуть предмет другой стороной:
// оператор, у которого канон лежит над деревом, прочитал бы «его нет» и завёл бы
// второй — вместо того чтобы понять, что прежде читался чужой.
//
// Поэтому подъём здесь ОСТАЛСЯ ровно один и только ДИАГНОСТИЧЕСКИЙ: он
// спрашивает у файловой системы наличие (`Stat`) и НИКОГДА не читает содержимое.
// Его исход не попадает в канон ни при каком входе — он попадает только в текст
// отказа.
//
// ─────────────────────────────────────────────────────────────────────────────
// ФОРМА ВЗЯТА У СОСЕДА, А НЕ ИЗОБРЕТЕНА
//
// Тот же класс закрыт у обёрток гейтов модуля (`services/iam/tools/tree-root.sh`,
// задача #2145): корень не считается арифметикой пути, предпосылка проверяется и
// НАЗЫВАЕТСЯ, а «не знаю» не выдаётся ни за «нет находок», ни за «находка».
// Здесь та же форма; отличается МАРКЕР предпосылки, и отличается он не по вкусу:
// маркер обязан отвечать на вопрос ТОГО ЖЕ читателя. Обёртка судит полосу,
// читающую состав КОММИТА, — её предпосылка про индекс. `ResolveCanonicalModelFrom`
// судит дерево, НАЗВАННОЕ вызывающим (им пользуется инъекция обхода, подавая
// синтетическое дерево во временном каталоге, где индекса нет и быть не должно),
// — его предпосылка про содержимое названного корня. `ResolveCanonicalModel`
// дерева не знает и обязан его НАЙТИ: там вопрос ставится индексу, ровно как у
// обёртки.

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"

	"github.com/PRO-Robotech/kaname/internal/treeroot"
)

// fgaModelRelPath — the canonical authorization model, relative to the tree root.
// The SAME single source of truth every other real-FGA proof in this tree reads
// (services/iam/internal/testsupport/fgatest). Its absence is a hard error: a
// comparison against a model this harness invented would measure nothing about
// the product.
const fgaModelRelPath = "proto/kaname/cloud/iam/v1/fga_model.fga"

// shippedModelRelPath — та же модель ПОБАЙТОВО, лежащая ВНУТРИ модуля.
//
// Это не вторая истина и не запасной путь: файл порождается из канонического
// (`make -C deploy fga-model-embed`), вшивается директивой `go:embed` и есть
// ровно тот текст, по которому служба принимает решения о доступе в рантайме.
// Побайтовое равенство двух копий держит гейт `internal/authzmodel`
// (TestEmbeddedModelIsByteIdenticalToCanonical) — там, где обе копии есть.
//
// ЗАЧЕМ РЕЗОЛВУ ЗНАТЬ О НЁМ. До этой строки 85 проб модели отказывали в
// самостоятельном клоне «канона в дереве нет» — то есть красным у каждого, кто
// склонирует, при том что текст модели у него ЕСТЬ и лежит рядом с кодом,
// который его применяет.
//
// ЗДЕСЬ СТОЯЛО «каталог контрактов в поставку модуля не входит: у арендатора
// дерево — сам модуль, и `proto/` в нём нет BY CONSTRUCTION». Это перестало быть
// правдой 2026-09-13: решением владельца контракты службы уехали в её
// репозиторий (kacho#2616), и `proto/kaname/cloud/iam/v1/fga_model.fga` лежит
// теперь В ЭТОМ дереве. Первая ветвь резолва достижима у каждого, кто склонирует
// модуль, — то есть канон и копия снова два файла ОДНОГО дерева, и их равенство
// проверяемо здесь.
//
// Вторая ветвь при этом НЕ снимается: у неё остаётся свой предмет — поставка, в
// которой каталога контрактов нет (архив без `proto/`, образ, несущий только
// двоичное). Снять её значило бы вернуть красное тем, у кого текст модели есть, а
// каталога контрактов нет.
//
// ПОРЯДОК НЕСУЩИЙ: канонический файл спрашивается ПЕРВЫМ. В монорепо он есть,
// поэтому там резолв не меняется ни на байт — вторая ветвь недостижима, и
// числа переписей остаются прежними. Вторая ветвь наступает ровно тогда, когда
// первой нет, и это состояние — свойство ПОСТАВКИ, а не выбор вызывающего.
const shippedModelRelPath = "internal/authzmodel/fga_model.fga"

// CanonicalModelRelPath — тот же относительный путь для вызывающего, который
// печатает перепись.
//
// Экспортирован ради ОДНОГО читателя — исполнителя сверки: его перепись обязана
// называть не только корень обхода, но и файл, по которому она снята, иначе
// «корень назван» и «канон прочитан оттуда» остаются двумя разными
// утверждениями. Второй копии постоянной это не заводит: возвращается она же.
func CanonicalModelRelPath() string { return fgaModelRelPath }

// ShippedModelRelPath — ВТОРАЯ постоянная координата: копия канона, которую
// модуль везёт с собой.
//
// Экспортируется ради одного вопроса, который без неё не задать: КАКОЙ из двух
// координат прочитан канон. Ответ различает посадки — в дереве платформы
// читается контракт, в самостоятельной поставке модуля его нет вовсе и читается
// копия, — и потому отличает «условие сверки не создано» от находки о продукте
// (kacho#2241). Постоянная возвращается та же; второй копии это не заводит.
func ShippedModelRelPath() string { return shippedModelRelPath }

// ErrCanonAboveTree — канона в названном дереве нет, а ВЫШЕ него он лежит.
// Отдельный признак: он отличает «прежде читалось чужое» от «его нет нигде».
var ErrCanonAboveTree = errors.New("канон лежит выше дерева")

// ErrCanonNotInTree — канона нет ни в дереве, ни выше него.
var ErrCanonNotInTree = errors.New("канона в дереве нет")

// ErrTreeNotResolved — дерево назвать нечем: проверка НЕ ИСПОЛНЯЛАСЬ.
var ErrTreeNotResolved = errors.New("дерево под резолвом не установлено")

// ResolveCanonicalModel — канон ТОГО дерева, в котором идёт прогон.
//
// Дерево не выводится арифметикой пути и не ищется подъёмом за маркером: вопрос
// ставится ИНДЕКСУ (`rev-parse --show-toplevel`), а затем проверяется
// предпосылка — что каталог, из которого спрашивают, этим деревом
// ОТСЛЕЖИВАЕТСЯ. Без второй проверки модуль, распакованный внутрь чужого
// репозитория, получил бы корень ЧУЖОГО дерева и вердикт о нём.
func ResolveCanonicalModel() (path string, dsl []byte, err error) {
	wd, err := os.Getwd()
	if err != nil {
		return "", nil, err
	}
	root, err := treeRootOf(wd)
	if err != nil {
		return "", nil, err
	}
	return ResolveCanonicalModelFrom(root)
}

// ResolveCanonicalModelFrom — канон дерева root.
//
// Параметр — КОРЕНЬ ДЕРЕВА, а не путь канона, и различие несущее (#1089, §2 п. 2):
// подменить канон снимком, лежащим рядом со сверщиком, нечем — предъявить такой
// путь этой подписи невозможно. Указать можно лишь целое дерево, у которого канон
// лежит по каноническому относительному пути; ровно этим и пользуется инъекция,
// подавая своё дерево намеренно.
//
// Читает РОВНО `<root>/<fgaModelRelPath>`. За пределы root не выходит ни при
// каком входе: файл выше дерева попадает только в ТЕКСТ отказа и никогда в
// возвращаемые байты.
func ResolveCanonicalModelFrom(root string) (path string, dsl []byte, err error) {
	cand := filepath.Join(root, fgaModelRelPath)
	st, statErr := os.Stat(cand)
	switch {
	case statErr == nil && st.Mode().IsRegular():
		b, rerr := os.ReadFile(cand) // #nosec G304 -- fixed in-tree path, tool-only
		if rerr != nil {
			return cand, nil, rerr
		}
		return cand, b, nil
	case statErr != nil:
		// Канонического файла в дереве нет. Прежде чем объявлять отказ, тот же
		// вопрос задаётся ВТОРОЙ постоянной координате — копии, которую модуль
		// везёт с собой. Обе координаты ФИКСИРОВАНЫ и вызывающим не выбираются:
		// подменить операнд снимком по-прежнему нечем.
		shipped := filepath.Join(root, shippedModelRelPath)
		if sst, serr := os.Stat(shipped); serr == nil && sst.Mode().IsRegular() {
			b, rerr := os.ReadFile(shipped) // #nosec G304 -- fixed in-tree path, tool-only
			if rerr != nil {
				return shipped, nil, rerr
			}
			return shipped, b, nil
		}
	case statErr == nil:
		return "", nil, fmt.Errorf(
			"%w: %s\n  осмотрено дерево:  %s\n  ожидался признак:  обычный файл %s в составе этого дерева\n"+
				"  найдено вместо него: не файл — читать нечего",
			ErrCanonNotInTree, fgaModelRelPath, root, fgaModelRelPath)
	}

	if above := canonAboveTree(root); above != "" {
		return "", nil, fmt.Errorf(
			"%w — дерево под резолвом не то, о котором он может говорить\n"+
				"  осмотрено дерево:   %s\n"+
				"  ожидался признак:   файл %s в составе этого дерева\n"+
				"  найден ВЫШЕ дерева: %s\n"+
				"  читать найденный нельзя: вердикт был бы вынесен о ЧУЖОМ дереве, а перепись\n"+
				"  напечатана по этому — отличить такой зелёный от настоящего нечем",
			ErrCanonAboveTree, root, fgaModelRelPath, above)
	}

	return "", nil, fmt.Errorf(
		"%w: %s\n  осмотрено дерево: %s\n  ожидался признак: файл %s в составе этого дерева\n"+
			"  за пределы дерева резолв не выходит: прочитанный снаружи файл дал бы вердикт\n"+
			"  о постороннем дереве при переписи, напечатанной по этому",
		ErrCanonNotInTree, fgaModelRelPath, root, fgaModelRelPath)
}

// canonAboveTree — ДИАГНОСТИКА, а не резолв: где лежит канон над деревом root.
//
// Спрашивает только НАЛИЧИЕ (`Stat`) и НИКОГДА не читает содержимое; его исход
// попадает исключительно в текст отказа. Существует он ради одного: «канон лежит
// выше дерева» и «канона нет нигде» обязаны РАЗЛИЧАТЬСЯ, иначе оператор, у
// которого прежде читался чужой файл, прочтёт «его нет» и заведёт второй канон
// вместо того, чтобы понять причину.
//
// Пустая строка означает «выше дерева канона нет» — представима отдельно от
// найденного пути.
func canonAboveTree(root string) string {
	dir := filepath.Dir(root)
	for {
		if st, err := os.Stat(filepath.Join(dir, fgaModelRelPath)); err == nil && st.Mode().IsRegular() {
			return filepath.Join(dir, fgaModelRelPath)
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return ""
		}
		dir = parent
	}
}

// treeRootOf — корень дерева, которому принадлежит start.
//
// Резолв объявлен ОДИН раз и живёт у владельца (`internal/treeroot`): вторая
// копия разошлась бы с первой молча — и разошлась бы ровно на предпосылке
// «дерево ОТСЛЕЖИВАЕТ каталог, из которого спрашивают», без которой модуль,
// распакованный внутрь постороннего репозитория, получает корень того
// репозитория (kacho#2239).
func treeRootOf(start string) (string, error) {
	root, err := treeroot.Of(start)
	if err != nil {
		return "", fmt.Errorf("%w: %w", ErrTreeNotResolved, err)
	}
	return root, nil
}
