// Необъявленный тип обязан быть отличим от прочих отказов компиляции — #880.
//
// ПОЧЕМУ СИГНАЛЬНАЯ ОШИБКА, А НЕ СРАВНЕНИЕ ТЕКСТА. Вызывающий принимает по этому
// различию РЕШЕНИЕ О ДОСТУПЕ: тип, которого в словаре нет вовсе, означает «таких
// объектов не существует» — честный отказ; всё остальное означает «я не смог
// ответить» — ошибку. Сравнение по подстроке сообщения сломалось бы на первой же
// правке формулировки, и сломалось бы молча, в сторону разрешения.
func TestCompile_UndeclaredTypeIsSignalled(t *testing.T) {
	m := parseCanonical(t)

	// (а) необъявленный тип — сигнальная ошибка.
	if _, err := m.Compile("scope_grant", "admin"); !errors.Is(err, ErrTypeNotDeclared) {
		t.Errorf("необъявленный тип: err = %v, ожидалась ErrTypeNotDeclared", err)
	}

	// (б) ЗАКОННЫЙ БЛИЗНЕЦ: объявленный тип с несуществующим отношением — НЕ он.
	// Без этой половины проверка ловила бы любую ошибку компиляции и превращала
	// бы в отказ в том числе настоящую поломку.
	if _, err := m.Compile("account", "no_such_relation"); errors.Is(err, ErrTypeNotDeclared) {
		t.Errorf("объявленный тип с чужим отношением ошибочно помечен как необъявленный: %v", err)
	} else if err == nil {
		t.Errorf("объявленный тип с чужим отношением обязан быть ошибкой")
	}
}
