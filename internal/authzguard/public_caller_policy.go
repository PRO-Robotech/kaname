// Публичные глаголы, которые законно зовёт модуль, не являющийся краем.
// Именованные константы — чтобы таблица ниже читалась как перечень рёбер,
// который она отражает.
const (
	// publicProjectGetMethod — проверка проекта на пути запроса, которую делает
	// каждый потребитель перед созданием ресурса с размещением
	// (services/*/internal/clients/iam*: ProjectServiceClient.Get).
	publicProjectGetMethod = "/kaname.cloud.iam.v1.ProjectService/Get"
	// publicBatchCheckMethod — пообъектный фильтр видимости, который запускает
	// каждый обработчик List в vpc/compute/nlb/storage (internal/authzfilter):
	// он спрашивает, какие идентификаторы ОДНОЙ страницы видит человек. Ребру
	// служба→служба место на внутреннем слушателе, и большинство профилей его
	// туда и ставят, — но хотя бы один профиль посадки направляет его на
	// публичный адрес, поэтому публичный слушатель обязан его пускать, иначе
	// фильтр закрывается отказом и арендаторы теряют выдачу собственного List.
	publicBatchCheckMethod = "/kaname.cloud.iam.v1.AuthorizeService/BatchCheck"
)

// publicAuthorizeCheckMethod — вопрос модели доступа, которым край решает о
// КАЖДОМ запросе арендатора (единственное изъятие второго замка, ниже).
const publicAuthorizeCheckMethod = "/kaname.cloud.iam.v1.AuthorizeService/Check"

// PublicGatewayFloorExemptRPCs — публичные глаголы с полом уровня, на которых
// второй замок службы на ветви края НЕ стоит, с основанием каждого.
//
// # Что держит второй замок
//
// На ветви края служба судит пол уровня из СВОЕГО встроенного каталога у
// КАЖДОГО глагола, чья запись объявляет пол выше «0» (kaname#767), а не у
// выписанного перечня. Перечень расходился бы с каталогом молча: новый глагол с
// полом в него сам не попадает, и его пол держал бы только край — по своей
// копии каталога, которая отстаёт от контракта службы на время между вливанием
// контракта и пересборкой края (так было с тремя глаголами ключа доступа:
// «1» в копии края при «2» в контракте, kaname#747). Выведенное из каталога
// множество закрыто по умолчанию: глагол, получивший пол в контракте, получает
// и второй замок тем же изменением.
//
// # Почему изъятие — перечень с основанием, а не настройка
//
// Изъятие ослабляет замок, и потому живёт в коде под ревью, как таблица
// соседей выше: расширяет его изменение, называющее основание, а не настройка
// посадки. Запись, чьего глагола нет среди публичных с полом, — находка
// (TestKN767_ExemptionExpiresWithItsSubject): изъятие истекает вместе с
// предметом.
func PublicGatewayFloorExemptRPCs() map[string]string {
	return map[string]string{
		// Край задаёт этот вопрос САМ, о каждом запросе арендатора, до
		// пересылки (звено авторизации края, вопрос о субъекте из ТЕЛА
		// запроса). Пол уровня, который при этом судится, — пол глагола
		// арендатора, а не этого вопроса: замок по уровню, переданному
		// метаданными, отказывал бы самому решению о доступе — всякий раз,
		// когда край задаёт вопрос без переданного уровня, и за глаголом
		// арендатора без пола у сессии ниже «1». Пол самого вопроса для
		// арендатора, зовущего его через край, держит край.
		publicAuthorizeCheckMethod: "вопрос модели доступа, которым край решает о каждом запросе; " +
			"судится пол глагола арендатора, а не этого вопроса",
	}
}

// UnnamedCallerMessage — ЕДИНСТВЕННЫЙ текст отказа тому, кто не назвался ничем.
//
// # Почему отдельный текст, а не «permission denied»
//
// Отказ существует затем, чтобы вызывающий построил следующий шаг. «Не пускают»
// предлагает просить прав; «назовись» называет действие, которое вызывающий
// может совершить сам. Для арендатора чужого облака, у которого нашего края нет
// by construction, второе — единственный исполнимый ответ: прав он попросить не
// у кого, а удостоверение выдаём мы.
//
// # Почему это не оракул
//
// Различаются здесь два состояния ЗАПРОСА, а не сервера, и оба известны самому
// вызывающему до ответа: он либо приложил удостоверение, либо нет. Отказ
// ПРЕДЪЯВИВШЕМУ негодное остаётся единственным побайтово равным текстом
// (`presentedcred.RefusalMessage`) — там различимость и правда сообщила бы, какая
// половина предъявленного неверна.
//
// Текст — часть контракта, и он экспортирован затем, чтобы проба утверждала ЕГО,
// а не свою копию.
const UnnamedCallerMessage = "no credential presented; authenticate with authorization: Bearer <token>"

// Короткие имена служб-модулей (как их выводит из учётки
// moduleidentity.Roster.ServiceFromAccount формой имени службы установки),
// встречающиеся в таблице вызываемых соседями.
const (
	svcVPC      = "vpc"
	svcCompute  = "compute"
	svcNLB      = "nlb"
	svcStorage  = "storage"
	svcRegistry = "registry"
)

// PublicPeerCallableRPCs возвращает публичные глаголы, которые вправе звать
// модуль, НЕ являющийся краем, — с точными короткими именами служб, которым
// каждый из них разрешён.
//
// Каждая запись — ЗАПРОС, и это правило, а не совпадение: мутирующий глагол
// здесь дал бы соседней службе возможность менять данные арендатора от имени
// переданного человека — ровно ту дыру, которую эта политика закрывает. Замок
// TestPublicPeerCallableRPCs_CarryNoMutation держит это по самому контракту: в
// Kachō мутация — это ровно глагол, возвращающий Operation, поэтому проверка
// читает контракт, а не привычку именования.
//
// Края здесь намеренно нет — его пускает собственная ветвь, и назвать его ещё и
// здесь значило бы завести второй источник правды, который разъедется.
//
// Членство выведено из рёбер во время работы, а не из поиска по имени:
//   - ProjectService/Get — vpc, compute, nlb, storage и registry держат по
//     ProjectServiceClient, направленному на ПУБЛИЧНЫЙ адрес iam, и зовут Get на
//     пути своего Create (существование проекта и владеющий аккаунт);
//   - AuthorizeService/BatchCheck — фильтр видимости страницы в
//     vpc/compute/nlb/storage (internal/authzfilter — единственный метод
//     AuthorizeService, который зовёт любой из них). Его ребру место на
//     внутреннем слушателе, и большинство профилей его туда ставят, но профиль,
//     направляющий его на публичный адрес, существует, и отказ там закрыл бы
//     фильтр и опустошил собственный List арендатора.
func PublicPeerCallableRPCs() map[string][]string {
	return map[string][]string{
		publicProjectGetMethod: {svcVPC, svcCompute, svcNLB, svcStorage, svcRegistry},
		publicBatchCheckMethod: {svcVPC, svcCompute, svcNLB, svcStorage},
	}
}

// PublicCallerPolicy держит политику вызывающего по глаголам на публичном
// слушателе. Строится через NewPublicCallerPolicy.
type PublicCallerPolicy struct {
	// acrCatalog — FQN → объявленный порог доверия. Читается ТОЛЬКО полосой
	// предъявленного удостоверения: на ней порог не производит никто, и
	// признать вызывающего законным, не спросив каталог, значило бы снять
	// требование, которое каталог продолжает объявлять.
	acrCatalog ACRRequirementLookup
	// prodMode = cfg.AuthN.Mode.IsProduction(). dev (false) — проход
	// (небезопасная совместимость: у стенда newman mTLS нет вовсе, и решать не
	// по чему — проверенного сертификата нет); боевая посадка — отказ по
	// умолчанию.
	prodMode bool
	// peerCallable — полное имя глагола → множество коротких имён служб-модулей
	// (не края), которым его разрешено звать.
	peerCallable map[string]map[string]struct{}
	// gatewayFloorExempt — глаголы с полом, на которых второй замок на ветви
	// края не стоит ([PublicGatewayFloorExemptRPCs]); у прочих он стоит везде,
	// где каталог объявил пол.
	gatewayFloorExempt map[string]struct{}
	// presented — ПОРТ: приложил ли вызывающий удостоверение к этому запросу.
	//
	// Порт, а не прямой вызов читателя, и это НЕ оформление. Носитель
	// происхождения личности объявлен нейтральным намеренно: «его пишет читатель
	// предъявленного, а читает политика вызывающего, и ни один из них не обязан
	// знать про другого» — прямая зависимость связала бы решение о ПРАВЕ ЗВАТЬ с
	// реализацией проверки удостоверения, то есть два предмета, которые меняются
	// порознь. Реализацию подставляет композиционный корень.
	presented CredentialPresence
	// modules — личности модулей установки (kaname#984): модулем на этом
	// слушателе признаётся только объявленная пара. Нулевое значение не
	// признаёт никого.
	modules moduleidentity.Roster
}

// WithModuleRoster подставляет перечень личностей модулей установки. Тот же
// перечень и тот же разбор, что у внутреннего слушателя: признание модуля одно
// на оба слушателя.
func (p *PublicCallerPolicy) WithModuleRoster(r moduleidentity.Roster) *PublicCallerPolicy {
	p.modules = r
	return p
}

// CredentialPresence — приложил ли вызывающий удостоверение к ЭТОМУ запросу.
//
// Предикат отвечает о ЗАПРОСЕ, а не о его годности: «предъявил и не сошлось»
// сюда не доходит — читатель отвергает такое выше по цепочке. Различие нужно
// ровно затем, чтобы не советовать назваться тому, кто уже назвался.
type CredentialPresence func(ctx context.Context) bool

// NewPublicCallerPolicy строит политику. peerCallable — таблица вызывающих
// глагол, не являющихся краем (см. PublicPeerCallableRPCs); prodMode берётся из
// cfg.AuthN.Mode.IsProduction().
//
// presented — реализация порта [CredentialPresence]. Параметр ОБЯЗАТЕЛЕН и
// позиционен: сборка, забывшая его подставить, не соберётся вовсе — тогда как
// умолчание сделало бы её молча отвечающей «назовись» тому, кто назвался.
//
// Модулем политика признаёт только пару перечня личностей (WithModuleRoster):
// нулевой перечень не признаёт никого, и форму имени службы установки перечень
// несёт сам (kaname#308).
func NewPublicCallerPolicy(
	prodMode bool,
	peerCallable map[string][]string,
	acrCatalog ACRRequirementLookup,
	presented CredentialPresence,
) *PublicCallerPolicy {
	m := make(map[string]map[string]struct{}, len(peerCallable))
	for method, svcs := range peerCallable {
		set := make(map[string]struct{}, len(svcs))
		for _, svc := range svcs {
			set[svc] = struct{}{}
		}
		m[method] = set
	}
	exempt := make(map[string]struct{})
	for method := range PublicGatewayFloorExemptRPCs() {
		exempt[method] = struct{}{}
	}
	return &PublicCallerPolicy{
		prodMode: prodMode, peerCallable: m, gatewayFloorExempt: exempt,
		acrCatalog: acrCatalog, presented: presented,
	}
}

// allow возвращает nil тогда и только тогда, когда вызов fullMethod проходит
// политику:
//   - вызывающего назвало удостоверение, которое он ПРЕДЪЯВИЛ и которое мы
//     проверили целиком, → nil (у арендатора чужого облака модульного
//     сертификата нет по построению; почему это не расширение — у самой
//     ветви), — если только каталог не объявил пола уровня, до которого
//     удостоверение не дотягивает: тогда УКАЗАНИЕ ПОВЫСИТЬ УРОВЕНЬ
//     (`Unauthenticated` с [iamerr.TextStepUpRequired], Р11, kaname#511), а не
//     отказ прав.
//   - проверенного модульного сертификата нет: dev → nil (небезопасная
//     совместимость); prod → отказ по умолчанию, и КОД ЗДЕСЬ РАЗНЫЙ.
//     Вызывающий, не назвавшийся ничем —
//     ни сертификатом, ни предъявленным удостоверением, ни переданной
//     личностью, — получает `Unauthenticated` с [UnnamedCallerMessage]:
//     «назовись». Всякий, кто назвался и не подошёл, получает прежний
//     `PermissionDenied`. Разница — про следующий шаг вызывающего, а не про
//     строгость: просить прав некому там, где края нет (kacho#2103).
//   - край (api-gateway) → nil: это парадная дверь, где идёт пообъектный
//     вопрос к модели доступа от имени человека, — если только каталог службы
//     не объявил глаголу пол уровня, до которого переданный уровень не
//     дотягивает: его судит второй замок ([PublicCallerPolicy.gatewayFloor]),
//     кроме глаголов [PublicGatewayFloorExemptRPCs].
//   - другой модуль на глаголе, который называет его в таблице вызываемых
//     соседями, → nil.
//   - любой иной модуль: prod → PermissionDenied; dev → nil.
//
// Отказ НАЗВАВШЕМУСЯ — дословный, не текущий "permission denied", тот же, что у
// внутренней политики: по нему не узнать, какая из ветвей его произвела. Ветвь
// безымянного вызывающего отвечает иначе, и это не послабление — она отличает
// два состояния ЗАПРОСА, известные самому вызывающему до ответа (он либо
// приложил удостоверение, либо нет), а не два состояния сервера.
func (p *PublicCallerPolicy) allow(ctx context.Context, fullMethod string) error {
	// Вызывающий, названный ПРЕДЪЯВЛЕННЫМ им удостоверением, — законный
	// публичный вызывающий (задача продукта kacho#2077).
	//
	// Без этой ветки объём приёмки KAN-AUTHN-1 закрыт наполовину: читатель
	// называет арендатора, а здесь его отвергают за отсутствие МОДУЛЬНОГО
	// сертификата — которого у арендатора чужого облака нет и быть не может, он
	// приходит обычным клиентом. Тогда «вызов доходит до обработчика»
	// недостижимо ни при каком токене, и это ровно тот класс, где два правила об
	// одном запросе делают исполнимый вход несуществующим.
	//
	// Расширением поверхности это не является. Пометку ставит ТОЛЬКО читатель и
	// ТОЛЬКО после того, как проверил предъявленное целиком — подпись
	// собственным реестром, издателя, адресат, тип, срок, момент начала
	// действия и отзыв на пути запроса. До этой ветки доходит запрос, который
	// уже доказал, за кого говорит; всё остальное читатель отверг раньше и
	// побайтово одинаковым отказом.
	//
	// ПРАВО ЗВАТЬ этим не выдаётся: ниже по цепочке стоят отсечка анонима и
	// пообъектный вопрос к модели доступа, и оба задаются о названном субъекте.
	// Здесь решается лишь «этот вызывающий вправе быть на этом слушателе».
	if callerorigin.IsPresentedCredential(ctx) {
		// ...НО только там, где каталог не объявил порога доверия.
		//
		// Порог (`required_acr_min`) на публичном пути производит КРАЙ, и до
		// этого перехода край стоял на пути всякого публичного вызывающего by
		// construction: без модульного сертификата дальше не пускали. Полоса
		// предъявленного проходит МИМО края — значит вместе с краем исчезает и
		// единственный производитель порога, а каталог продолжает его
		// объявлять. Пустить такой вызов значило бы снять требование, которого
		// никто не отменял.
		//
		// Ответ здесь — УКАЗАНИЕ повысить уровень, а не отказ прав (Р11 приёмки
		// уровня уверенности, kaname#511): та же форма, что у края (KA1-15).
		// Прежде здесь стоял отказ «как у соседних ветвей» с доводом «различать —
		// оракул»; для этой полосы довод неверен — удостоверение проверено
		// целиком, и свой уровень держатель читает из него самого, так что
		// указание не сообщает ему ничего, кроме шага. Цена прежнего ответа —
		// повышение, которого клиент не узнавал: он шёл искать выдачи прав.
		//
		// Полоса не теряет ничего, что имела: машинный принципал освобождён
		// общим правилом (у машины нет интерактивной церемонии), а человеку
		// решает тот же порог, что решал бы на крае. Меняется РЕНДЕРИНГ вердикта,
		// а не вердикт.
		required := p.requiredACRMin(fullMethod)
		if required == "" || !p.prodMode {
			return nil
		}
		// Решает ОБЩЕЕ правило платформы, а не эта ветвь: ранжирование уровней и
		// освобождение машинного принципала здесь НЕ ПЕРЕВЫВОДЯТСЯ. Именно такой
		// раскол однажды пропустил машину через парадную дверь и навсегда
		// отверг её за ней.
		//
		// Оба входа приходят из удостоверения, проверенного ЦЕЛИКОМ, — то есть
		// уже отфильтрованы доверием, как того требует правило: подделать
		// «служебная учётка» и купить освобождение нельзя, не подделав подпись.
		acr, _ := callerorigin.AssuranceFrom(ctx)
		principalType := ""
		if pr, named := operations.PrincipalFromContextOK(ctx); named {
			principalType = pr.Type
		}
		if grpcsrv.EvaluateStepUp(grpcsrv.StepUpInput{
			PrincipalType: principalType,
			PresentedACR:  acr,
			RequiredACR:   required,
		}) != grpcsrv.StepUpAllow {
			return &stepUpRequired{challenge: iamerr.StepUpChallenge(
				strconv.Itoa(acrlevel.Rank(required)), strconv.Itoa(acrlevel.Rank(acr)))}
		}
		return nil
	}

	// Признание модуля — объявленная пара перечня (kaname#984), тот же разбор,
	// что у внутреннего слушателя.
	module, ok := p.modules.FromContext(ctx)
	svc := module.Service
	if !ok {
		// Проверенного модульного сертификата нет: dev — проход, prod — отказ
		// по умолчанию.
		if !p.prodMode {
			return nil
		}
		// Вызывающий, не назвавшийся НИЧЕМ, получает «назовись», а не «не
		// пускают» (задача продукта kacho#2103).
		//
		// Условие — конъюнкция ДВУХ «нет»: нет предъявленного удостоверения и
		// нет переданной личности. Предъявивший назвался, и посылать его
		// называться заново значило бы предлагать повторить уже сделанное.
		//
		// # Почему сертификата в конъюнкции БОЛЬШЕ НЕТ (задача продукта kacho#2319)
		//
		// Здесь стояло третье «нет» — «нет проверенного сертификата», — и оно
		// делало ветвь недостижимой на той полосе, ради которой она заведена.
		// Мы дошли сюда по `!ok`, то есть лист НЕ РАЗОБРАЛСЯ В ИМЯ МОДУЛЯ:
		// назвать вызывающего ему нечем в любом случае. Требовать сверх этого,
		// чтобы листа не было ВОВСЕ, значит спрашивать не о том — вопрос ветви
		// «назвался ли вызывающий», а не «была ли на проводе криптография».
		//
		// Цена была измерена, а не предположена. Собственный REST-фронт службы —
		// обычный клиент своего же gRPC-слушателя и дозванивается под КЛИЕНТСКИМ
		// листом службы. Значит на КАЖДОМ запросе, пришедшем через фронт,
		// `verified` истинно, конъюнкция ложна by construction, и арендатор
		// чужого облака, не приложивший удостоверения, получал «тебя знают и не
		// пускают» — при том что его никто не знает. Проба kacho#2103 этого не
		// показывала: она подаёт мир БЕЗ сертификата, а развёрнутая посадка
		// такого мира не производит ни на одном запросе.
		//
		// Лист собственного фронта называет ХОП, а не вызывающего. Лист соседа
		// называет ЕГО — и сосед сюда не доходит: его SAN разбирается в имя
		// модуля, `ok` истинно, и отвечает ему ветвь ниже прежним отказом по
		// правам. Обе стороны утверждаются пробами в own_rest_front_hop_test.go.
		//
		// Предъявленное НЕГОДНОЕ сюда не доходит: читатель отвергает его выше по
		// цепочке единственным побайтово равным отказом. Значит эта ветвь
		// отвечает ровно тому, кто не предъявлял, — и различает она состояния
		// ЗАПРОСА, известные самому вызывающему, а не состояния сервера.
		if !p.presentedCredential(ctx) && !namedPrincipal(ctx) {
			return status.Error(codes.Unauthenticated, UnnamedCallerMessage)
		}
		return status.Error(codes.PermissionDenied, "permission denied")
	}
	if svc == gatewayServiceName {
		return p.gatewayFloor(ctx, fullMethod)
	}
	if _, listed := p.peerCallable[fullMethod][svc]; listed {
		return nil
	}
	// Проверенный модуль, которого этот глагол не называет. dev — проход;
	// prod — отказ по умолчанию: модуль плоскости данных не достаёт до правки
	// ресурсов арендатора, выдачи прав и выпуска удостоверений ни от имени
	// переданного человека, ни от своего.
	if !p.prodMode {
		return nil
	}
	return status.Error(codes.PermissionDenied, "permission denied")
}

// gatewayFloor — ВТОРОЙ ЗАМОК пола уровня на ветви края (kaname#747, Р3;
// у каждого глагола с полом — kaname#767).
//
// Решает ОБЩЕЕ правило платформы (`grpcsrv.EvaluateStepUp`) — то же, что у края
// и у пола внутреннего слушателя; ранжирование и освобождение машинного
// принципала здесь не перевыводятся. Входы — только под доверием: уровень и вид
// принципала засчитываются, лишь когда их передал отправитель из круга
// доверенных (`authn.trusted-forwarder-sans`); иначе уровень пуст и вид пуст —
// отказ, и подделанный «service_account» освобождения не покупает.
//
// Отказ — указание повысить уровень (Р11), та же форма, что у полосы
// предъявленного на этом же слушателе: у одного слушателя один ответ на
// недостаток уровня, какой бы путь ни привёл вызывающего.
//
// dev-посадка — проход, как у прочих ветвей политики: без mTLS ветви края на
// стенде нет вовсе.
func (p *PublicCallerPolicy) gatewayFloor(ctx context.Context, fullMethod string) error {
	if _, exempt := p.gatewayFloorExempt[fullMethod]; exempt || !p.prodMode {
		return nil
	}
	required := p.requiredACRMin(fullMethod)
	if acrlevel.Rank(required) == 0 {
		return nil
	}
	acr, trusted := grpcsrv.TrustedACRFromContext(ctx)
	if !trusted {
		acr = ""
	}
	principalType := ""
	if pr, trustedPrincipal := grpcsrv.TrustedPrincipalFromContext(ctx); trustedPrincipal {
		principalType = pr.Type
	}
	if grpcsrv.EvaluateStepUp(grpcsrv.StepUpInput{
		PrincipalType: principalType,
		PresentedACR:  acr,
		RequiredACR:   required,
	}) == grpcsrv.StepUpAllow {
		return nil
	}
	return &stepUpRequired{challenge: iamerr.StepUpChallenge(
		strconv.Itoa(acrlevel.Rank(required)), strconv.Itoa(acrlevel.Rank(acr)))}
}

// presentedCredential — вердикт порта. Неподставленный порт означает «не знаем»,
// и отвечает он КОНСЕРВАТИВНО: «назовись» не советуется. Ошибиться здесь можно в
// две стороны, и они не равны — сказать назвавшемуся «назовись» значит послать
// его повторять сделанное, а сказать безымянному «не пускают» лишь оставляет
// прежний ответ.
func (p *PublicCallerPolicy) presentedCredential(ctx context.Context) bool {
	if p.presented == nil {
		return true
	}
	return p.presented(ctx)
}

// namedPrincipal — личность вызывающего названа хоть чем-то.
//
// Спрашивается ОБЩИМ предикатом носителя, а не своей проверкой полей: «личности
// нет» и «личность есть и пуста» — разные состояния, и своя копия различала бы
// их иначе, чем платформа.
func namedPrincipal(ctx context.Context) bool {
	p, named := operations.PrincipalFromContextOK(ctx)
	return named && !p.IsAnonymous()
}

// requiredACRMin — объявленный каталогом порог доверия для полного имени метода.
//
// Каталог ключуется полным именем без ведущей косой черты — та же нормализация,
// что у порога внутреннего слушателя; своей копии разбора имени здесь нет.
func (p *PublicCallerPolicy) requiredACRMin(fullMethod string) string {
	if p.acrCatalog == nil {
		// Каталога нет ⇒ порог не объявлен ни у одного метода. Это состояние
		// дев-посадки; в боевой каталог обязателен, и его отсутствие отвергает
		// страж старта, а не эта ветвь.
		return ""
	}
	return p.acrCatalog.RequiredACRMin(strings.TrimPrefix(fullMethod, "/"))
}

// stepUpRequired — вердикт «пол не пройден» на полосе предъявленного,
// отрендеренный указанием (Р11): статус `UNAUTHENTICATED` с текстом, называющим
// шаг, и готовый вызов RFC 9470, который перехватчик кладёт в хвост ответа —
// статус `google.rpc.Status` параметров вызова не несёт, а REST-фронт обязан
// поставить их на провод (Ф11-49).
type stepUpRequired struct{ challenge string }

func (e *stepUpRequired) Error() string { return iamerr.TextStepUpRequired }

// GRPCStatus — код и текст указания; `details` пусты, как у края (KA1-15).
func (e *stepUpRequired) GRPCStatus() *status.Status {
	return status.New(codes.Unauthenticated, iamerr.TextStepUpRequired)
}

// stepUpTrailer — хвост ответа с вызовом указания, если err — указание.
func stepUpTrailer(err error) (metadata.MD, bool) {
	var su *stepUpRequired
	if !errors.As(err, &su) {
		return nil, false
	}
	return metadata.Pairs(iamerr.StepUpChallengeTrailer, su.challenge), true
}

// Unary возвращает унарный перехватчик, держащий политику вызывающего публичного
// слушателя.
//
// Хвост с вызовом ставится ДО возврата отказа. Отказ его установки (контекст
// без потока — так бывает лишь вне настоящего слушателя) вердикта не меняет:
// указание уходит тем же статусом, а REST-фронт без вызова поставит голую
// подсказку — ответ беднее, но не ложен и не шире.
func (p *PublicCallerPolicy) Unary() grpc.UnaryServerInterceptor {
	return func(ctx context.Context, req any, info *grpc.UnaryServerInfo, handler grpc.UnaryHandler) (any, error) {
		// The anonymous exception is unary and request-shaped. It must never
		// open the method-only policy used by streams or other RPCs.
		if info.FullMethod == iamv1.AuthorizeService_Check_FullMethodName {
			check, ok := req.(*iamv1.AuthorizeCheckRequest)
			if ok && IsAnonymousSelfCheck(ctx, check, p.modules) {
				return handler(ctx, req)
			}
		}
		if err := p.allow(ctx, info.FullMethod); err != nil {
			if md, ok := stepUpTrailer(err); ok {
				_ = grpc.SetTrailer(ctx, md) // исход отказа от хвоста не зависит — см. выше
			}
			return nil, err
		}
		return handler(ctx, req)
	}
}

// Stream возвращает потоковый перехватчик, держащий политику вызывающего
// публичного слушателя.
func (p *PublicCallerPolicy) Stream() grpc.StreamServerInterceptor {
	return func(srv any, ss grpc.ServerStream, info *grpc.StreamServerInfo, handler grpc.StreamHandler) error {
		if err := p.allow(ss.Context(), info.FullMethod); err != nil {
			if md, ok := stepUpTrailer(err); ok {
				ss.SetTrailer(md)
			}
			return err
		}
		return handler(srv, ss)
	}
}
