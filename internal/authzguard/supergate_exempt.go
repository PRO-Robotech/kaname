package authzguard

// supergate_exempt.go — типы объектов, на которых надзор администратора облака
// НЕ применяется (решение Р5 приёмки NTF-1, замысел З19).
//
// # Предмет
//
// Надзор администратора облака — второе слагаемое исхода двери: на отказе модели
// (или там, где вопроса к модели нет) он даёт «да» субъекту, держащему
// `system_admin` на синглтоне кластера. На ленте уведомлений это слагаемое
// снято: отправитель пространства и читатель ленты — службы, и только они.
// Человек не отправитель и не читатель; рычаг администратора — `Revoke`/
// `Restore` (право на объекте `cluster`, этим перечнем не затронуто).
//
// # Одно место — и одна функция во всех семи местах
//
// Перечень объявлен здесь и только здесь. Пакет выбран графом импорта:
// `internal/service` (места Д-1…Д-5 переписи §1.11) импортирует `authzguard`
// (места Д-6, Д-7), обратного ребра нет. Каждое место класса «обобщённая дверь»
// зовёт `SuperGateExempt` до вопроса надзора; держит это гейт дерева
// `internal/check/supergateexemptsites_test.go` против ведомости классов, он же
// находит вторую декларацию перечня.
//
// # Тип — тот, который увидит модель
//
// Предикат судит ТИП ОБЪЕКТА, разобранный так же, как его разбирает модель
// (`authzcascade.parseObjectRef`: тип — до ПЕРВОГО двоеточия), а не строку
// ресурса и не префикс. Иначе ресурс с типом `notification_feed:x` прошёл бы
// мимо перечня, а модель всё равно спросила бы об объекте `notification_feed`.

import "strings"

// superGateExemptTypes — закрытый перечень типов объектов модели без надзора.
var superGateExemptTypes = map[string]struct{}{
	"notification_feed":      {},
	"notification_namespace": {},
}

// SuperGateExempt — тип объекта модели objectType из перечня: надзор
// администратора облака на нём не спрашивается, исход — исход модели, а там,
// где вопроса к модели нет, — отказ.
func SuperGateExempt(objectType string) bool {
	_, ok := superGateExemptTypes[objectType]
	return ok
}

// SplitModelObject — тип и идентификатор строки «тип:идентификатор» тем же
// разбором, что у модели: разделитель — ПЕРВОЕ двоеточие. Идентификатор вправе
// нести своё двоеточие (`registry_repository:<reg>/<repo>:<tag>`), тип — нет.
//
// Строка без двоеточия, с пустым типом либо пустым идентификатором объектом не
// является — третий результат false. Модель на такой вход отвечает ошибкой, а не
// вердиктом, поэтому до надзора он не доходит.
func SplitModelObject(object string) (objectType, objectID string, ok bool) {
	i := strings.IndexByte(object, ':')
	if i <= 0 || i == len(object)-1 {
		return "", "", false
	}
	return object[:i], object[i+1:], true
}
