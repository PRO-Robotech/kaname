package authzguard

// own_door_role_anchor.go — канонический якорь роли на СОБСТВЕННОЙ двери iam.
//
// # Предмет
//
// `RoleService/Create` объявляет `scope_extractor{account, account_id}`, и
// комментарий контракта тут же говорит, что этим объявлением предмет НЕ
// исчерпан: извлекатель умеет назвать РОВНО ОДНО поле запроса, поэтому запись
// каталога описывает аккаунтную арму, а остальные две разрешает код — с
// порядком старшинства `definition_tier` (канон) → `account_id` (легаси) →
// `project_id` (легаси).
//
// Арм, стало быть, ТРИ, а аннотация несёт одну. Вторая и третья дают пустой
// объект с тем же исходом, что и первая, и это не догадка: 8 отказов шарда iam,
// приписанных сперва «прочему», оказались одним случаем, чей первый шаг заводит
// роль проекта ЛЕГАСИ-полем `project_id`. Починка, закрывшая только канон, его
// бы не покрыла — поэтому здесь исполняется весь порядок, а не его начало.
//
// Край это и делает (`ResolveDefinitionTierScope`). Дверь — не делала: карта
// выводится из аннотаций, а больше названного поля аннотация не несёт. Тогда
// КАНОНИЧЕСКИЙ запрос — тот, что несёт `definition_tier` и не несёт
// `account_id`, — давал пустой идентификатор объекта, а пустой отвергается
// `FormatObject` ДО вопроса к модели, то есть и до плоского надзора
// администратора облака (он живёт внутри `checkAdapter.Check`). Отказ наступал
// раньше любого решения, и пройти эту полосу нельзя было ничем.
//
// Наблюдалось на голове `d1c7a4a89b`: `POST /iam/v1/roles` → 403 `AUTHZ_DENIED`
// (`action=iam.roles.create`, `scope=account`) при теле с
// `definitionTier{iam.account, …}` и без `accountId`; 133 отказа из 145 в шарде
// iam (30 прямых и 103 каскадом по непойманным идентификаторам).
//
// # Источник истины ОДИН, и он не здесь
//
// Отображение «вид яруса → область» принадлежит домену
// (`domain.CustomDefinitionTierToScope`), и край объявляет себя его зеркалом
// прямым текстом: «Mirrors domain.CustomDefinitionTierToScope; the gateway
// cannot import the iam domain». Дверь живёт В ОДНОМ модуле с доменом, поэтому
// берёт первоисточник, а не заводит третью копию правила: копия разошлась бы с
// обработчиком молча, и разошлась бы именно там, где расхождение невидимо, — на
// ярусе, который обработчик считает своим, а дверь чужим.
//
// # Привязка к FQN — инвариант безопасности, а не оптимизация
//
// Якорь читается ТОЛЬКО у методов закрытого перечня. Без привязки поле с этим
// именем, добавленное в любое другое сообщение, начало бы переопределять
// область проверки, тогда как обработчик действовал бы по своей, — то есть
// вызывающий выбирал бы, про какой объект его спросят. Ровно ту же границу
// проводит край, и по той же причине.
//
// Здесь она строже, чем на крае, by construction: край читает СЫРОЕ тело
// запроса (до того, как декодер отбросит неизвестные ключи), а дверь получает
// уже разобранное типизированное сообщение, поэтому поля, которого в сообщении
// нет, не существует и подставить его нельзя.

import (
	"github.com/PRO-Robotech/kacho/pkg/authz"

	iamv1 "github.com/PRO-Robotech/kacho/pkg/api/kaname/cloud/iam/v1"

	"github.com/PRO-Robotech/kaname/internal/domain"
)

// roleCreateMethod — единственный метод, чью область разрешено брать из
// канонического яруса.
//
// Перечень ЗАКРЫТ и состоит из одной записи: сегодня `definition_tier` несёт
// ровно одно сообщение запроса во всём контракте. Новый метод получает якорь
// добавлением поля в своё сообщение И записи сюда — обоими действиями, а не
// одним, потому что привязка к FQN и есть то, что делает якорь безопасным.
const roleCreateMethod = "/kaname.cloud.iam.v1.RoleService/Create"

// withCanonicalRoleAnchor учит карту двери читать канонический якорь роли,
// оставляя легаси-полосу рабочей.
//
// Обёртка НЕ подменяет извлекатель, а идёт перед ним: якорь не задан либо его
// ярус неразрешим (`iam.cluster`, неизвестное значение) — работает выведенный из
// аннотации, и обработчик отвечает своим `INVALID_ARGUMENT`. То есть починка
// ДОБАВЛЯЕТ арму, а не заменяет одну другой.
//
// Записи нет в карте — обёртка не заводит её сама: карта тотальна над пакетами
// контракта, и метод, которого в ней нет, отвергается как незамапленный. Тихо
// дописав его сюда, мы завели бы дверь методу, которого контракт не объявлял.
func withCanonicalRoleAnchor(m authz.RPCMap) authz.RPCMap {
	entry, mapped := m[roleCreateMethod]
	if !mapped || entry.Extract == nil {
		return m
	}
	derived := entry.Extract
	entry.Extract = func(req any) (objectType, objectID string, err error) {
		if t, id, ok := roleCreateScope(req); ok {
			return t, id, nil
		}
		return derived(req)
	}
	m[roleCreateMethod] = entry
	return m
}

// roleCreateScope — область, объявленная запросом, по порядку старшинства
// контракта: канонический ярус → легаси-аккаунт → легаси-проект.
//
// ok=false, когда не объявлена НИ ОДНА арма: тогда решает выведенный из
// аннотации извлекатель, и его пустой объект отвергается звеном — ровно то
// поведение, которое контракт называет для этого случая («neither anchor set →
// `account:*` → no path, fail-closed»). Четвёртой армы «пусто значит можно»
// здесь нет и не заводится.
func roleCreateScope(req any) (objectType, objectID string, ok bool) {
	create, isCreate := req.(*iamv1.CreateRoleRequest)
	if !isCreate {
		return "", "", false
	}
	// 1. Канон. Старше легаси-полей: контракт объявляет «when definition_tier is
	// set it takes precedence», и порядок здесь несущий — иначе вызывающий
	// выбирал бы область проверки сам, подставив легаси-поле, тогда как
	// обработчик действует по канону.
	if tier := create.GetDefinitionTier(); tier != nil {
		account, project, resolved := domain.CustomDefinitionTierToScope(
			tier.GetTierType(), tier.GetTierId())
		switch {
		case !resolved:
			// Ярус назван и неразрешим (`iam.cluster`, неизвестное значение).
			// Область отсюда не берётся, а форму входа судит обработчик своим
			// `INVALID_ARGUMENT` — дверь его вопроса не подменяет.
		case account != "":
			return "account", account, true
		case project != "":
			return "project", project, true
		}
	}
	// 2-3. Легаси. Ровно те две армы, что контракт называет после канона.
	switch {
	case create.GetAccountId() != "":
		return "account", create.GetAccountId(), true
	case create.GetProjectId() != "":
		return "project", create.GetProjectId(), true
	default:
		return "", "", false
	}
}
