// Package manifestoracle — переходник: модель прав отвечает на вопросы
// загрузчика манифестов (задача продукта #2002).
//
// # Зачем отдельный пакет
//
// Загрузчик манифестов объявляет ПОРТ (`manifest.RelationOracle`) и владельца
// модели не импортирует: иначе разбор доставленного манифеста читал бы модель,
// которая из этих же манифестов и собирается, — взаимный замок, из-за которого
// композиция не вставала ни при каком порядке.
//
// Обратное направление — чтобы владелец модели знал о загрузчике — было
// отвергнуто по существу: модель есть предмет платформы, а загрузчик — один из
// её потребителей; знание потребителя в предмете завело бы ребро, которое
// пришлось бы отзывать при появлении второго потребителя.
//
// Значит переходник живёт ТРЕТЬИМ местом, знающим обе стороны и не знаемым ни
// одной. Он ничего не решает сам: всякий вопрос переадресуется владельцу модели
// без второго разбора записи субъекта. Заведи здесь свою логику — и появился бы
// второй судья вида получателя, расходящийся с первым молча, на той записи, о
// которой не знает (условие, подстановка, членство).
package manifestoracle

import (
	"github.com/PRO-Robotech/kacho/services/iam/internal/authzmodel"
	"github.com/PRO-Robotech/kacho/services/iam/internal/manifest"
)

// fromPlans — разобранная модель в роли оракула загрузчика.
type fromPlans struct{ plans *authzmodel.Plans }

// FromPlans вносит НАЗВАННУЮ разобранную модель как оракула загрузчика.
//
// `nil` даёт `nil`-оракула, а не переходник, оборачивающий пустоту: оракул,
// отвечающий «не объявляет» на всякий вопрос, отверг бы КАЖДУЮ законную выдачу
// отношением и был бы неотличим от строгой модели, которой просто нет.
// Загрузчик, оракула не получивший, о существовании отношения не утверждает
// ничего — это наблюдаемое состояние, а не молчаливое «нет».
func FromPlans(p *authzmodel.Plans) manifest.RelationOracle {
	if p == nil {
		return nil
	}
	return fromPlans{plans: p}
}

// Canon вносит КАНОН ОБРАЗА как оракула загрузчика.
//
// Предназначен ОСНАСТКЕ ДЕРЕВА, у которой вопрос имеет смысл: тип уже в каноне,
// и канон о нём авторитетен. На пути СТАРТА службы канон оракулом быть не
// вправе — там модель ещё собирается из доставленного, и тип нового модуля
// канон не объявляет by construction, поэтому суждение каноном отвергло бы
// законную выдачу.
//
// Канон разбирается ЗДЕСЬ, а не берётся у общего разбора модели процесса:
// оснастка спрашивает про образ, и ответ её не вправе зависеть от того,
// поставил ли кто-то модель процесса раньше. Побочно это и снимает замок:
// вопрос оснастки не отмечает модель процесса прочитанной.
func Canon() (manifest.RelationOracle, error) {
	p, err := authzmodel.New(authzmodel.DSL)
	if err != nil {
		return nil, err
	}
	return FromPlans(p), nil
}

// RelationDeclaration — объявление отношения у типа.
func (o fromPlans) RelationDeclaration(objectType, relation string) (manifest.RelationDeclaration, bool) {
	decl, declared := o.plans.RelationSubjects(objectType, relation)
	if !declared {
		// Явный nil, а НЕ нулевое объявление: интерфейс, несущий нулевое
		// значение, интерфейсом-nil не является, и вызывающий, проверивший его
		// на nil, получил бы «объявление есть» там, где его нет.
		return nil, false
	}
	return decl, true
}

// TypeRelations — имена отношений, объявленных типом; для ТЕКСТА отказа.
//
// Второе значение владельца («тип объявлен») здесь не нужно: у незнакомого типа
// перечень пуст, и текст отказа скажет об этом сам.
func (o fromPlans) TypeRelations(objectType string) []string {
	names, _ := o.plans.RelationNames(objectType)
	return names
}
