// Package tokenrevocation — ПРАВИЛО отзыва наших токенов, объявленное один раз.
//
// # Почему правило вынесено, а не повторено
//
// Отзыв читают ДВЕ поверхности: авторитет отзыва, отвечающий на вопрос соседа, и
// читатель предъявленного на публичном слушателе. Правило у них одно, и оно
// нетривиально: ключей отсечки несколько, отзыв субъекта и клиента действует
// ВПЕРЁД, отзыв семейства — при любой отметке выпуска (FamilyKeyClaim), а токен
// без отметки выпуска не сопоставим ни с какой отсечкой.
//
// Вторая копия разошлась бы молча и разошлась бы там, где расхождение не видно:
// имя, заведённое в составе утверждений и забытое в одной из копий, даёт
// клиента, чей отзыв доезжает до одной поверхности и не доезжает до другой, —
// при том что обе зелены на своих пробах, потому что их фикстуры чеканят состав
// сами.
//
// # Исходов ТРИ, а не два
//
// Отозван · не отозван · СПРОСИТЬ НЕ СМОГЛИ. Третий возвращается ошибкой и
// никогда не сливается со вторым: смешать их значило бы сделать сбой хранилища
// неотличимым от отсутствия отзыва, то есть завести мягкий проход при отказе
// зависимости.
package tokenrevocation

import (
	"context"
	"time"

	"github.com/golang-jwt/jwt/v5"
)

// Reader — хранилище отсечек.
//
// Отвечает «с какого момента токены субъекта недействительны». Отсутствие
// записи — законный ответ «отзыва нет», а НЕ ошибка: пустое обязано означать
// пусто.
type Reader interface {
	RevokedBefore(ctx context.Context, subject string) (time.Time, bool, error)
}

// subjectClaims — утверждения, чьё значение служит ВТОРЫМ ключом отсечки.
//
// Перечень объявлен один раз и закрыт: имя, заведённое в составе утверждений и
// забытое здесь, дало бы клиента, чей отзыв не доезжает до предъявления, — и не
// доезжал бы он МОЛЧА, потому что «работает» и «не отозвано» выглядят одинаково.
//
// Субъекта мало. Отзыв КЛИЕНТА — снятие ключа, которым клиент себя
// аутентифицирует, — обязан снимать и уже выданные ИМ токены; иначе контроль
// действует на выдаче и не действует на предъявлении. Ключи не коллизят by
// construction: идентификаторы платформы глобально уникальны.
var subjectClaims = []string{
	// Клиент пользовательского токена.
	"kaname_user_token_id",
	// Клиент ключа служебной учётки.
	"kaname_sa_key_id",
}

// FamilyKeyClaim — утверждение, несущее ключ СЕМЕЙСТВА: идентификатор гранта
// церемонии, один у всех выпусков одной выдачи (задача PRO-Robotech/kaname#396).
//
// Его кладёт выпуск токена доступа церемонии (`ceremonyport.AccessTokens`), а
// отсечку по нему пишет отзыв семейства (слой доступа, `RevokeFamily` и отзыв
// семейств снятой сессии). Имя объявлено ЗДЕСЬ, у правила, и выпуск берёт его
// отсюда: имя, разошедшееся между выпуском и правилом, дало бы отзыв, который до
// предъявления не доезжает, — и не доезжал бы он молча.
//
// # Ключ семейства действует ПРИ ЛЮБОЙ отметке выпуска
//
// Отсечка субъекта и клиента действует ВПЕРЁД: снимается выданное до неё,
// выданное после снова действительно — иначе отзыв был бы вечной блокировкой
// принципала. У семейства будущего нет: отозванное семейство законного нового
// выпуска не имеет, а выпуск, лёгший ПОЗЖЕ отметки, бывает — опередивший на
// одновременном повторе кода гасит код раньше отзыва и выпускает после него.
// Отсечка по моменту выпуска пропустила бы ровно этот токен, ради снятия
// которого отзыв и исполнялся. Поэтому найденная отсечка по ключу семейства
// отвергает токен, когда бы он ни был выпущен; её момент служит только уборке.
const FamilyKeyClaim = "kaname_token_family_id"

// Keys возвращает ВСЕ ключи отсечки для состава утверждений: субъект, каждое
// имя закрытого перечня и ключ семейства — те, что в составе присутствуют
// непустыми.
func Keys(claims jwt.MapClaims) []string {
	out := forwardKeys(claims)
	if family := familyKey(claims); family != "" {
		out = append(out, family)
	}
	return out
}

// forwardKeys — ключи, чья отсечка действует ВПЕРЁД: субъект и закрытый
// перечень клиентов.
func forwardKeys(claims jwt.MapClaims) []string {
	var out []string
	if sub, _ := claims["sub"].(string); sub != "" {
		out = append(out, sub)
	}
	for _, name := range subjectClaims {
		if v, ok := claims[name].(string); ok && v != "" {
			out = append(out, v)
		}
	}
	return out
}

// familyKey — ключ семейства из состава либо пусто.
func familyKey(claims jwt.MapClaims) string {
	family, _ := claims[FamilyKeyClaim].(string)
	return family
}

// Revoked отвечает, отозван ли токен с этим составом утверждений.
//
// Возвращаемая ошибка — ТРЕТИЙ исход, «спросить не смогли»: вызывающий обязан
// закрыться сам, а не читать её как «не отозван».
//
// Токен БЕЗ отметки выпуска считается отозванным. Он не сопоставим ни с какой
// отсечкой — ни с уже стоящей, ни с будущей, — поэтому принять его значило бы
// завести материал, который отозвать нечем; при сомнении отказ.
func Revoked(ctx context.Context, r Reader, claims jwt.MapClaims) (bool, error) {
	issued, err := claims.GetIssuedAt()
	if err != nil || issued == nil {
		return true, nil
	}
	if len(Keys(claims)) == 0 {
		// Материал, у которого НЕТ НИ ОДНОГО ключа отсечки, отозвать нечем — тем
		// же доводом, что и материал без отметки выпуска. Принять его значило бы
		// завести удостоверение, которое нельзя снять ни сейчас, ни потом.
		//
		// Асимметрия здесь была бы дефектом правила, а не поверхности: одна из
		// двух поверхностей несёт внешнее предусловие на непустой субъект, вторая
		// не несёт, и держалось бы правило свойством ЧУЖОГО пакета.
		return true, nil
	}
	if family := familyKey(claims); family != "" {
		// Ключ семейства — ПЕРВЫМ и без сравнения моментов (см. FamilyKeyClaim).
		_, found, err := r.RevokedBefore(ctx, family)
		if err != nil {
			return false, err
		}
		if found {
			return true, nil
		}
	}
	for _, key := range forwardKeys(claims) {
		cutoff, found, err := r.RevokedBefore(ctx, key)
		if err != nil {
			return false, err
		}
		if !found {
			continue
		}
		// Отзыв действует ВПЕРЁД: выпущенное до момента отсечки
		// недействительно, выпущенное после — действительно. Иначе отзыв
		// означал бы вечную блокировку принципала, а не снятие выданного.
		if issued.Time.Before(cutoff) {
			return true, nil
		}
	}
	return false, nil
}
