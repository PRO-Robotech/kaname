// Package contractnaming — ЕДИНСТВЕННОЕ объявление в модуле службы того, КТО
// владеет пакетом контракта модуля платформы.
//
// # Почему пакет заведён
//
// Форма записи каталога прав — `<владелец>.cloud.<модуль>.v1.<Служба>/<Метод>`.
// До 2026-09 владелец ВЫВОДИЛСЯ приставкой имени платформы и был у всех один:
// `kacho`. Вывод был верен, пока имя платформы было и именем каждой её части.
//
// Служба управления доступом получила собственное имя продукта — Kaname
// (решение владельца, задача #2076), и её контракт переехал в
// `kaname.cloud.iam.v1`. С этого момента владелец пакета контракта и имя
// платформы — РАЗНЫЕ СЛОВАРИ, и приставка их больше не связывает.
//
// # Чем это было опасно (задача #2168)
//
// Правило «владелец = kacho» стояло литералом в разборе записи каталога и в
// отборе полосы, за которую служба отвечает. Распознаватель, ключующийся на
// приставке, чужое имя НЕ ОТВЕРГАЕТ — он его НЕ ВИДИТ: все 116 записей iam
// выпали из привязки, семь ключей закрытой таблицы перестали производиться, а
// полоса пообъектной фильтрации перечислением не находилась вовсе. Проверки
// манифеста при этом выходили кодом 0 — молча.
//
// Поэтому владелец объявлен здесь один раз, а не выведен в каждом месте заново.
//
// # Обе величины держатся ГЕЙТОМ, а не обещанием — но РАЗНЫМИ свидетелями
//
// Запись ведомости (`iam` → `kaname`) сверяется с ДЕСКРИПТОРОМ, который
// генерация произвела из контракта (contractnaming_test.go): ведомость,
// разошедшаяся с контрактом, — находка, а не «настройка». Гейт печатает объём
// осмотренного и падает на пустой ведомости.
//
// `platformOwner` дескриптором подтвердить НЕЛЬЗЯ, и это свойство дерева, а не
// упущение: контрактов платформы в репозитории службы нет ни одного
// (`git grep '^package kacho\.cloud' -- proto` → пусто), а прежний свидетель
// сверял имя с пакетом контракта операции — тот переехал под имя фундамента
// (#98) и был снят собственным предикатом истечения.
//
// Свидетель взят у ПОСТАВЛЯЕМОГО каталога прав (platform_owner_witness_test.go):
// он приезжает ОТ ПЛАТФОРМЫ, несёт полные имена методов каждого её модуля и
// меняется без участия этого пакета — в этом его ценность. Утверждается
// ОТНОШЕНИЕ, а не литерал: владелец каждого названного каталогом модуля
// совпадает с тем, что называет `Owner`, а модуль, владельца которому даёт
// именно `platformOwner`, в каталоге ПРИСУТСТВУЕТ. Без второй половины проверка
// молчала бы на каталоге без платформы, и значение снова осталось бы без
// свидетеля при зелёном прогоне (#128).
//
// # Родство с `internal/productnaming` названо, а не подразумевается
//
// Тот же факт («iam зовётся kaname») объявлен в корневом модуле платформы —
// `internal/productnaming`, откуда берутся имя чарта, имя образа, приставка
// окружения и пространство рядов метрик. Импортировать его отсюда НЕЛЬЗЯ: он
// лежит под `internal/` ЧУЖОГО модуля (`github.com/PRO-Robotech/kacho`), и
// правило Go закрывает такой импорт by construction. Поэтому здесь стои́т
// СВОЁ объявление — но не второе место об одном предмете «на честном слове»:
// его истинность проверяется не сверкой с тем объявлением, а сверкой с внешним
// фактом — контрактом для записи ведомости и поставляемым каталогом прав для
// владельца платформы (см. раздел о свидетелях выше).
package contractnaming

import (
	"sort"
	"strings"
)

// platformOwner — владелец контрактов платформы. Им владеет всякий модуль, у
// которого СВОЕГО имени продукта нет; для него соответствие по-прежнему
// выводится.
//
// Значение решает, под каким именем служба ИЩЕТ каталожную запись каждого
// модуля платформы. Разойдись оно с действительностью — записи не отвергаются,
// а НЕ ВИДЯТСЯ (116 записей выпали молча, #2168), поэтому у него есть свидетель,
// способный упасть: TestPlatformOwnerIsTheOneTheDeliveredCatalogDeclares.
const platformOwner = "kacho"

// contractVersion — сегмент версии в имени пакета контракта модуля.
//
// Он ОДИН на все модули и в форме занимает своё место: запись без него
// (`corelib.operation.OperationService/Get`) ресурсом модуля не является —
// это служба фундамента, и разбор обязан её отличать, а не отбрасывать.
const contractVersion = "v1"

// ownerByModule — модули, чей пакет контракта принадлежит СВОЕМУ владельцу.
//
// Ключ — модуль, каким его называет средний сегмент пакета контракта (он же
// каталог исходников под `services/`), значение — владелец. Ведомость закрыта:
// попадание сюда — решение владельца о названии, а не удобство исполнителя.
var ownerByModule = map[string]string{
	"iam": "kaname",
}

// OwnModule — модуль платформы, чей код лежит в этом репозитории.
//
// Имя МОДУЛЯ переезда не переживало и пережить не может: оно и есть каталог
// исходников под `services/`. Переехал ВЛАДЕЛЕЦ его пакета контракта — за ним
// сюда и ходят. Константа объявлена здесь, а не у каждого читателя, потому что
// читателей у неё три и они в разных пакетах.
const OwnModule = "iam"

// OwnContractPackage — пакет контракта ЭТОЙ службы: `kaname.cloud.iam.v1`.
func OwnContractPackage() string { return ContractPackage(OwnModule) }

// Owner — владелец пакета контракта названного модуля.
func Owner(module string) string {
	if owner, ok := ownerByModule[module]; ok {
		return owner
	}
	return platformOwner
}

// PlatformOwner — владелец контрактов платформы.
func PlatformOwner() string { return platformOwner }

// ContractPackage — имя пакета контракта модуля: `<владелец>.cloud.<модуль>.v1`.
//
// Здесь объявлена ВСЯ форма имени пакета, и второй раз она не объявляется:
// разбор записи каталога спрашивает у этого пакета части, а не собирает форму
// заново (см. Split).
func ContractPackage(module string) string {
	return Owner(module) + ".cloud." + module + "." + contractVersion
}

// Split разбирает имя пакета контракта на владельца и модуль.
//
// Второй возврат — имеет ли имя ФОРМУ пакета контракта модуля. Ложь означает
// «это не пакет модуля» (платформенная служба без сегмента версии, посторонняя
// строка), а не «модуля нет»: существование модуля решает вызывающий.
//
// Владелец здесь НЕ СВЕРЯЕТСЯ с ведомостью намеренно: форма и принадлежность —
// разные вопросы, и слив их в один отдал бы вызывающему одно «нет» на две
// разные находки. Принадлежность спрашивают отдельно — OwnsModule.
func Split(protoPackage string) (owner, module string, ok bool) {
	parts := strings.Split(protoPackage, ".")
	// <владелец> · cloud · <модуль> · v1
	if len(parts) != 4 || parts[1] != "cloud" || parts[3] != contractVersion {
		return "", "", false
	}
	if parts[0] == "" || parts[2] == "" {
		return "", "", false
	}
	return parts[0], parts[2], true
}

// OwnsModule — объявлен ли названный владелец владельцем пакета этого модуля.
//
// Отвечает на вопрос «эта запись наша?» одним сравнением с ведомостью, поэтому
// приставка, которую не объявлял никто, отвергается ТАК ЖЕ, как приставка,
// объявленная за другим модулем: и то и другое — запись, за которую в дереве
// никто не отвечает.
func OwnsModule(owner, module string) bool { return owner == Owner(module) }

// RenamedModules — ведомость для гейта: он обязан убедиться, что каждая её
// запись сходится с дескриптором контракта. Возвращается копия — ведомость
// правится решением, а не вызывающим.
func RenamedModules() map[string]string {
	out := make(map[string]string, len(ownerByModule))
	for k, v := range ownerByModule {
		out[k] = v
	}
	return out
}

// KnownOwners — владельцы, объявленные деревом, в детерминированном порядке.
// Заведено для переписей: перечень, зависящий от обхода карты, читался бы
// по-разному от прогона к прогону.
func KnownOwners() []string {
	seen := map[string]struct{}{platformOwner: {}}
	for _, owner := range ownerByModule {
		seen[owner] = struct{}{}
	}
	out := make([]string, 0, len(seen))
	for owner := range seen {
		out = append(out, owner)
	}
	sort.Strings(out)
	return out
}
