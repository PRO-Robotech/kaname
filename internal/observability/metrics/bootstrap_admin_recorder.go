// BootstrapAdminRecorder — исходы попыток посева доступа кластерного
// администратора, по одной попытке согласователя старта.
//
// # Зачем это существует
//
// Согласователь посева объявлен незавершающим ПО КОНТРАКТУ: он повторяет
// попытку бессрочно, подъём не задерживает и на неисполнимом посеве печатает
// `Debug`. При рабочем уровне `Info` это не печатается вовсе — то есть
// «доступ администратора не выдан НИ РАЗУ за всю жизнь стенда» снаружи
// неотличимо от «выдан на первой же попытке».
//
// Цена неразличимости здесь выше обычной: кластерный администратор — тот
// единственный, кто мог бы починить остальное. Стенд, поднявшийся без него,
// выглядит исправным ровно до первого действия, которое требует его прав.
//
// # Почему ряды заводятся ЗАРАНЕЕ, а не вместе с первым событием
//
// Счётчик, у которого полоса появляется вместе с первым попаданием, на стенде
// без единой выдачи ряда `granted` НЕ ИМЕЕТ. Отсутствующий ряд снаружи
// неотличим от отсутствующего согласователя — то есть от той самой тишины,
// ради снятия которой счётчик заведён. Поэтому все полосы объявленного набора
// инициализируются нулём при регистрации: «ноль выдач» становится
// НАБЛЮДАЕМЫМ фактом, а не отсутствием факта.
//
// # Почему числитель считается вместе со знаменателем
//
// Счётчик одних отказов не отличает «отказов не было» от «попыток не было».
// Полосы пропуска и полоса выдачи растут в одном счётчике, поэтому вопрос
// «работает ли посев вообще» отвечается их суммой, а вопрос «выдан ли доступ»
// — одной полосой.
//
// Набор меток ЗАКРЫТ: `outcome` приходит из констант согласователя
// ([seed.BootstrapOutcomes]), никогда из запроса, поэтому кардинальность не
// растёт ни с трафиком, ни с числом арендаторов.
type BootstrapAdminRecorder struct {
	attempts *prometheus.CounterVec
}

// NewBootstrapAdminRecorder регистрирует коллектор в этом реестре и заводит
// ряд по каждой объявленной полосе. Звать один раз на старте.
func (r *Registry) NewBootstrapAdminRecorder() *BootstrapAdminRecorder {
	rec := &BootstrapAdminRecorder{
		attempts: prometheus.NewCounterVec(prometheus.CounterOpts{
			Name: Namespace + "_bootstrap_admin_attempts_total",
			Help: "Исходы попыток посева доступа кластерного администратора: " +
				"granted — выдача закоммичена; disabled — адрес администратора не задан " +
				"(терминально); not_registered — строки личности ещё нет; not_active — " +
				"строка есть, но аутентифицироваться не может; concurrent_race — выдачу " +
				"закоммитила соседняя реплика; failed — отказ. Ненулевая сумма при нулевом " +
				"granted означает, что посев работает и не сходится: доступа у " +
				"кластерного администратора НЕТ.",
		}, []string{"outcome"}),
	}
	// Ряды заводятся до первого события — см. шапку.
	for _, outcome := range seed.BootstrapOutcomes {
		rec.attempts.WithLabelValues(outcome)
	}
	r.reg.MustRegister(rec.attempts)
	return rec
}

// IncBootstrapAdminAttempt — исход одной попытки посева. Реализует порт
// [seed.BootstrapAttemptObserver].
func (rec *BootstrapAdminRecorder) IncBootstrapAdminAttempt(outcome string) {
	rec.attempts.WithLabelValues(outcome).Inc()
}
