package metrics

import "github.com/prometheus/client_golang/prometheus"

// BuildInfoUnstamped — то, что метка версии сборки говорит, когда сборка её НЕ
// ПРОСТАВИЛА.
//
// Пустая метка на витрине читается как «версии нет», а правдоподобное `dev` — как
// имя ветки; оба неотличимы от «величину не измеряли». Отдельное слово делает это
// состояние наблюдаемым: по нему пишется тревога, и оно не притворяется ответом.
const BuildInfoUnstamped = "unstamped"

// RegisterBuildInfo вешает на витрину постоянный ряд `kaname_build_info` с
// метками версии и ревизии работающего двоичного файла.
//
// # Зачем
//
// Первый вопрос дежурного — «какая версия у меня работает». До этого ряда служба
// не отвечала на него НИ ОДНОЙ величиной, и это смыкается с готовностью: её
// собственная проверка умеет отказать словами «образ не может обслужить эту
// схему», то есть назвать РАСХОЖДЕНИЕ, не дав ни одной из двух сравниваемых
// величин. Служба поставляется отдельно от платформы, где такие вопросы
// закрывает чужой инвентарь, — спросить больше некого.
//
// # Откуда приходят значения
//
// Со ШТАМПА СБОРКИ, а не с ручки профиля: величину, которую объявляет оператор,
// он вправе объявить любой, и тогда ряд отвечает не о том, что исполняется, а о
// том, что о нём написали. Штамп ставится там же, где клеймо образа, из ОДНОГО
// объявления (см. `provenance.mk` и `Dockerfile` службы), поэтому строка на
// витрине и строка на образе совпадают дословно.
//
// # Почему `version` и `revision`, а не `version` и `commit`
//
// Под этими именами величины уже стоят клеймом образа
// (`org.opencontainers.image.version` / `.revision`) и лежат файлом внутри него.
// Совпадение имён несущее: оператор сверяет витрину с образом без пересчёта, а
// расхождение читается как расхождение, а не как два способа назвать одно.
//
// # Почему gauge с постоянной единицей, а не метка на прочих рядах
//
// Метка версии, приклеенная к рабочим рядам, меняет их размерность при каждом
// раскате: суммы и доли по ним рвутся на границе выкатки, а `rate()` считает
// прибавку от нуля. Отдельный ряд с постоянным значением этой цены не несёт и
// склеивается с любым другим по времени.
//
// Звать ОДИН раз на старте, из композиционного корня: повторный вызов уронит
// процесс на повторной регистрации — и это верно, потому что двух разных версий
// у одного двоичного файла не бывает.
func (r *Registry) RegisterBuildInfo(version, revision string) {
	r.reg.MustRegister(newBuildInfoCollector(version, revision))
}

// newBuildInfoCollector собирает ряд, подставляя «не проставлено» вместо пустого.
func newBuildInfoCollector(version, revision string) prometheus.Collector {
	g := prometheus.NewGauge(prometheus.GaugeOpts{
		Name: Namespace + "_build_info",
		Help: "Метаданные сборки работающего двоичного файла (постоянная 1). " +
			"Метки `version` и `revision` дословно совпадают с клеймом образа " +
			"(org.opencontainers.image.version / .revision). Значение " +
			"\"" + BuildInfoUnstamped + "\" означает, что сборка штамп не " +
			"проставила: это НЕ версия, а отсутствие измерения.",
		ConstLabels: prometheus.Labels{
			"version":  orUnstamped(version),
			"revision": orUnstamped(revision),
		},
	})
	g.Set(1)
	return g
}

// orUnstamped — пустое приводится к слову, а не остаётся пустой меткой.
func orUnstamped(v string) string {
	if v == "" {
		return BuildInfoUnstamped
	}
	return v
}
