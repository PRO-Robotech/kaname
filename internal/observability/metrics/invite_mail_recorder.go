package metrics

import (
	"strings"

	"github.com/prometheus/client_golang/prometheus"

	"github.com/PRO-Robotech/kacho/services/iam/internal/clients"
)

// InviteMailOutcomesMetric — семейство исходов НАШЕЙ отправки письма приглашения.
//
// Набор клеток ЗАКРЫТ и приходит из констант применителя
// (`clients.InviteMailOutcomes`), а не из ответа почтового узла: иначе
// кардинальность росла бы с трафиком, а имена клеток задавал бы чужой процесс.
const InviteMailOutcomesMetric = "kacho_iam_invite_mail_outcomes_total"

// InviteMailRecorder — счётчик исходов отправки письма приглашения.
//
// # ПОЧЕМУ СДАННЫЕ СЧИТАЮТСЯ НАРАВНЕ С ОТКАЗАМИ
//
// Форма взята у зеркала набора ключей вместе с её обоснованием (приёмка
// ID-MAIL-1, Р25). Пока наружу выходят одни отказы, ноль в них отвечает сразу на
// два вопроса — «отказов не было» и «сюда никто не приходил», — а различие между
// ними и есть различие между работающим отправителем и мёртвым. Реальный
// прецедент проекта: очередь регистраций, у которой за всю жизнь не доехало ни
// одной строки, и это было ненаблюдаемо, потому что синхронный путь работал.
//
// # ПОЧЕМУ НАСТРОЙКА — СВОЯ КЛЕТКА, А НЕ ВИД ОТКАЗА
//
// Недоступность узла проходит со временем; ответ не по протоколу почты по
// объявленному адресу не проходит никогда. Смешать их в одном ряду значит
// спрятать настройку под сбой и сделать постоянную неверную настройку штатным
// режимом (`security.md` §Hardening п. 8).
//
// # ГРАНИЦА УТВЕРЖДЕНИЯ НАЗВАНА ЗДЕСЬ, А НЕ ВЫВЕДЕНА ЧИТАТЕЛЕМ
//
// Счётчик считает НАШИ отправки — письма приглашения. О письмах подтверждения
// адреса и восстановления доступа он не утверждает НИЧЕГО: их отправляет чужой
// процесс, чьи величины из нашего дерева не измеримы вовсе. Счётчик, названный
// «письма продукта» и считающий одну полосу, — то же «принято-и-проигнорировано»,
// только заведённое собственными руками: читатель получил бы величину, которая
// говорит меньше, чем её имя. Поэтому имя семейства называет ПРИГЛАШЕНИЕ.
//
// # ЧТО ЗНАЧИТ «СДАНО»
//
// Сдано РЕТРАНСЛЯТОРУ, а не получено адресатом. Дальше ретранслятора наш вердикт
// не идёт, и продукт нигде не утверждает доставку (Р15). Читать эту клетку как
// «доставлено» — ошибка, которую этот текст и закрывает.
//
// # ВТОРАЯ ОБЯЗАТЕЛЬНАЯ ВЕЛИЧИНА ЖИВЁТ НЕ ЗДЕСЬ
//
// «Висит ли ЭТА строка дольше N» отвечает возраст головы очереди из
// OutboxRecorder (`outbox_oldest_pending_age_seconds{table}`), который ведёт
// периодический скан очереди. Обе величины нужны, ни одна не заменяет другую:
// расхождение исходов говорит «доезжает ли вообще», возраст — «застряла ли
// конкретная».
type InviteMailRecorder struct {
	outcomes *prometheus.CounterVec
}

// NewInviteMailRecorder регистрирует счётчик в этом реестре.
//
// Все клетки закрытого набора инициализируются нулём СРАЗУ: ряд, которого нет
// вовсе, отвечает на «провязан ли механизм», и без предварительной инициализации
// «отказов не было» неотличимо от «отказ ни разу не классифицировали».
func (r *Registry) NewInviteMailRecorder() *InviteMailRecorder {
	rec := &InviteMailRecorder{
		outcomes: prometheus.NewCounterVec(prometheus.CounterOpts{
			Name: InviteMailOutcomesMetric,
			Help: "Исходы отправки письма ПРИГЛАШЕНИЯ нашим отправителем, по клетке закрытого " +
				"набора (" + strings.Join(clients.InviteMailOutcomes, "|") + "). Сданные считаются " +
				"наравне с отказами, поэтому «отказов не было» отличимо от «сюда никто не " +
				"приходил»; настройка стоит своей клеткой, потому что, в отличие от " +
				"недоступности, временем она не лечится. Клетка «sent» означает СДАНО ретранслятору, " +
				"НЕ получено адресатом. О письмах подтверждения адреса и восстановления доступа " +
				"этот счётчик не утверждает ничего: их отправляет процесс поставщика.",
		}, []string{"outcome"}),
	}
	for _, outcome := range clients.InviteMailOutcomes {
		rec.outcomes.WithLabelValues(outcome)
	}
	r.reg.MustRegister(rec.outcomes)
	return rec
}

// IncInviteMailOutcome — исход одной попытки отправки. Реализует
// clients.InviteMailObserver.
func (rec *InviteMailRecorder) IncInviteMailOutcome(outcome string) {
	rec.outcomes.WithLabelValues(outcome).Inc()
}

// InviteMailRecorder возвращает ЕДИНСТВЕННЫЙ экземпляр счётчика этого реестра,
// создавая его при первом обращении.
//
// Единственность нужна по той же причине, что и у соседа: два независимых вызова
// конструктора уронили бы старт на повторной регистрации — и уронили бы именно
// тогда, когда механизм наконец провязали целиком.
func (r *Registry) InviteMailRecorder() *InviteMailRecorder {
	r.inviteMailOnce.Do(func() { r.inviteMail = r.NewInviteMailRecorder() })
	return r.inviteMail
}
