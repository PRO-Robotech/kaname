// namespace_single_source_test.go — имя серии собирается ИЗ КОНСТАНТЫ
// пространства имён, а не выписывается литералом.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Константа `Namespace` заведена ровно ради этого и говорит о себе прямо: «имя
// серии — контракт с панелями и правилами тревог, и собранное в двух местах оно
// разъедется на первом переименовании». Читал её при этом ОДИН вызов из
// тридцати трёх — остальные тридцать два имени стояли литералами, повторяющими
// её значение.
//
// То есть единственный источник был ОБЪЯВЛЕН и не ИСПОЛНЯЛСЯ: правка константы
// двигала одну серию из тридцати трёх, а остальные оставались на прежнем
// префиксе. Ни компилятор, ни прогон об этом не сказали бы ничего — расхождение
// видно только на панели, которой в этом дереве нет вовсе.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ИМЕННО УТВЕРЖДАЕТСЯ
//
// Ни одно поле `Name:` в объявлениях этого пакета не является голым строковым
// литералом. Законная форма — выражение, начинающееся с `Namespace`.
//
// Судится РАЗОБРАННОЕ дерево, а не текст: имя серии встречается в этом пакете и
// в прозе (шапки объясняют, что именно считает счётчик), и предикат по подстроке
// краснел бы на собственном объяснении проверяемого.
//
// Пустой обход — находка: пакет без объявлений означает, что проверка стережёт
// координату, которой больше нет.

package metrics

import (
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestEverySeriesNameIsBuiltFromTheNamespaceConstant(t *testing.T) {
	entries, err := os.ReadDir(".")
	if err != nil {
		t.Fatalf("каталог пакета не читается (%v) — предпосылка проверки исчезла", err)
	}

	fset := token.NewFileSet()
	files, fields, literals := 0, 0, 0
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, perr := parser.ParseFile(fset, filepath.Join(".", name), nil, 0)
		if perr != nil {
			t.Fatalf("%s не разбирается (%v) — обход неполон, вердикт был бы о части", name, perr)
		}
		files++
		ast.Inspect(f, func(n ast.Node) bool {
			kv, ok := n.(*ast.KeyValueExpr)
			if !ok {
				return true
			}
			key, ok := kv.Key.(*ast.Ident)
			if !ok || key.Name != "Name" {
				return true
			}
			fields++
			lit, ok := kv.Value.(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return true // выражение — законная форма, её содержимое судить нечем
			}
			literals++
			t.Errorf("%s:%d — имя серии выписано литералом %s. Единственный источник "+
				"префикса объявлен рядом (`Namespace`) и обязан ЧИТАТЬСЯ: литерал "+
				"повторяет его значение, поэтому правка константы такую серию не "+
				"двигает, а расхождение видно только на панели",
				name, fset.Position(lit.Pos()).Line, lit.Value)
			return true
		})
	}

	t.Logf("осмотрено: файлов пакета %d, полей `Name:` %d, из них выписаны литералом %d",
		files, fields, literals)

	if files == 0 {
		t.Fatal("файлов пакета прочитано ноль — обход пуст, вердикт беспредметен")
	}
	if fields == 0 {
		t.Fatal("полей `Name:` не найдено ни одного — либо форма объявления сменилась, " +
			"либо серий не осталось; в обоих случаях проверка больше ничего не читает")
	}
}
