// provider_hop.go — выбор полосы обмена для контура выдачи докер-токена и
// отставленная дорога к прежнему издателю (задача #1119, Ф4б эпика #896).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Контур выдачи докер-токена переводится на СВОЮ чеканку подключением
// подписанта (`BuildConfig.Signer`). Обе точки входа контура — выдача по
// предъявленным учётным данным и анонимное чтение — при подключённом подписанте
// возвращаются ДО обращения к обменнику: утверждение для прежнего издателя не
// строится, обмен не производится, адрес его токен-эндпоинта не читается ни
// одним путём.
//
// Сборка при этом строила клиента к прежнему издателю БЕЗУСЛОВНО и отказывала в
// старте на негодном якоре — то есть требовала пригодной дороги к тому, с кем на
// этой посадке не разговаривают.
//
// ПОЧЕМУ ЭТО ХУЖЕ ЛИШНЕГО КОДА. Требование без предмета неотличимо от
// действующего. Оператор, читающий отказ, идёт чинить адрес и якорь, по которым
// процесс не пойдёт ни разу; а посадка, у которой прежнего издателя нет вовсе,
// не поднимается по причине, к её работе отношения не имеющей.
//
// ─────────────────────────────────────────────────────────────────────────────
// ГРАНИЦА НАЗВАНА: ТРЕБОВАНИЕ СНИМАЕТСЯ ТОЛЬКО У ПЕРЕВЕДЁННОГО КОНТУРА
//
// Пока подписант не подключён, прежний издатель — ЕДИНСТВЕННЫЙ производитель
// токена на этом контуре, и пригодность дороги к нему обязана проверяться при
// старте ровно как прежде: якорь, который нельзя прочитать, — отказ, а не тихий
// откат к системным корням. Снять требование со всех значило бы обменять видимый
// отказ в старте на непроверенную дорогу, о которой никто не узнает.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЗДЕСЬ НЕТ: СНЯТИЯ САМОЙ ПОЛОСЫ ОБМЕНА
//
// Ветка обмена в use-case остаётся: у неё есть предмет — посадка без своей
// чеканки. Снимается она вместе с последним профилем, который её объявляет, и
// это отдельная работа со своим предикатом.
package registrytokenwire

import (
	"context"
	"fmt"

	registrytokenuc "github.com/PRO-Robotech/kaname/internal/apps/kaname/api/registry_token"
	"github.com/PRO-Robotech/kaname/internal/clients"
)

// retiredProviderExchange — обменник на месте снятой дороги к прежнему издателю.
//
// ПОЧЕМУ НЕ ПУСТОТА. Ненаполненный порт дал бы панику в той единственной точке,
// где он мог бы быть достигнут, — то есть обменял бы читаемый отказ на падение
// процесса. Тип остаётся полным, а достижение его — отказом.
//
// ПОЧЕМУ ОТКАЗ ИМЕННО НЕДОСТУПНОСТЬЮ ИЗДАТЕЛЯ. Достижимость этой ветки была бы
// дефектом НАШЕЙ провязки. Отказ «негодные учётные данные» отправил бы
// предъявителя чинить то, что у него исправно, и увёл бы разбор в его сторону;
// недоступность издателя не обвиняет никого и оставляет повтор осмысленным.
type retiredProviderExchange struct{}

var _ registrytokenuc.TokenExchanger = retiredProviderExchange{}

// Exchange отказывает, называя состояние контура.
func (retiredProviderExchange) Exchange(_ context.Context, _ registrytokenuc.ExchangeInput) (registrytokenuc.ExchangeOutput, error) {
	return registrytokenuc.ExchangeOutput{}, fmt.Errorf(
		"%w: контур переведён на свою чеканку — обмен утверждения у прежнего издателя "+
			"на нём не производится, и дорога к нему не собиралась",
		registrytokenuc.ErrIssuerUnavailable)
}

// providerExchangeFor выбирает полосу обмена по тому, переведён ли контур.
//
// Отдельная функция, а не ветка внутри сборки: выбор полосы — это утверждение о
// том, ЧТО процессу нужно при старте, и его надо уметь спросить, не собирая
// контур целиком.
func providerExchangeFor(cfg BuildConfig) (registrytokenuc.TokenExchanger, error) {
	if cfg.Signer != nil {
		// Переведён: дорога к прежнему издателю не строится, поэтому её адрес и
		// якорь не читаются и негодность любого из них ничего не значит.
		return retiredProviderExchange{}, nil
	}
	// Не переведён: дорога к прежнему издателю несёт подписанное утверждение
	// туда и выпущенный токен обратно. Когда профиль пинит якорь, этот якорь —
	// единственное доверие хопа; непригодный якорь здесь ОШИБКА, а не тихий
	// откат к системным корням, и вызывающий отказывается стартовать на ней.
	tokenClient, err := clients.NewHydraTokenClientWithCA(cfg.HydraTokenURL, cfg.HydraTokenCAFile)
	if err != nil {
		return nil, err
	}
	return NewHydraExchange(tokenClient), nil
}
