// Package authzmapgen — ПРОИЗВОДИТЕЛЬ двух таблиц типов пакета `authzmap` из
// манифестов модулей (задача #1092).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ: СВЕРКУ ЗАМЕНЯЕТ ВЫВОД
//
// Перечень «набор глагольных отношений каждого типа» жил в Go рукописным
// литералом, а манифест модуля объявлен источником истины о том, что у платформы
// существует. Два места об одном предмете обязаны совпадать — и совпадение
// стерёг гейт.
//
// Гейт равенства и вывод решают одну задачу с разной ценой ошибки: гейт ловит
// расхождение ПОСЛЕ того, как оно внесено, и требует править Go при объявлении
// действия; вывод делает расхождение невыразимым by construction. «Объявить
// действие» перестаёт быть правкой Go.
//
// ─────────────────────────────────────────────────────────────────────────────
// КРУГ «ПРОИЗВОДИТЕЛЬ СПРАШИВАЕТ У СВОЕГО ПРОДУКТА» — РАЗОРВАН (задача #1930)
//
// Здесь стояло: вторую таблицу каталога — `objectTypes` — вывести НЕЛЬЗЯ,
// потому что загрузчик проверяет `objectType` каждой записи на членство в ней
// же, и новый тип не проходит ни одной из двух дверей. Это было верно ровно до
// смены РЕФЕРЕНТА, и абзац оставлен разбором, а не удалён: следующий, кто
// упрётся в тот же круг, обязан найти здесь способ, а не запрет.
//
// Что теперь верно: `Collect` зовёт `manifest.CheckTreeForGeneration`, и в этом
// проходе загрузчик существование типа НЕ СУДИТ — судит его канон, сверку с
// которым в обе стороны ведёт `modelrender.Sweep` («манифест порождает тип,
// которого в каноне НЕТ» и обратное). Форму — «тип назван дословно» — загрузчик
// судит по-прежнему и при любом референте.
//
// Полоса ПОТРЕБЛЕНИЯ не тронута: чтение доставленных манифестов на старте
// службы идёт умолчанием, то есть таблицей, и там она законный судья — к тому
// моменту она уже произведена и вкомпилирована. Почему это ОДИН предикат с
// двумя законными референтами, а не два места об одном предмете —
// `manifest.TypeReferent`.
//
// ─────────────────────────────────────────────────────────────────────────────
// ГРАНИЦА, КОТОРУЮ НАДО ЗНАТЬ: ПРОИЗВОДИТЕЛЬ ЗАВИСИТ ОТ СВОЕГО ПРОДУКТА
//
// Загрузчик манифеста импортирует `authzmap` — тот самый пакет, в который
// пишется продукт. Значит перегенерация возможна только из СОБИРАЮЩЕГОСЯ
// состояния: удали продукт — и производитель перестанет собираться вместе с ним.
// Штатный случай (манифест изменился, продукт устарел) от этого не страдает:
// устаревший продукт компилируется. Смена референта эту границу НЕ снимает: она
// про импорт пакета, а не про содержимое таблицы, — и это надо сказать прямо,
// иначе разбор выше прочтётся шире сделанного.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ГЕНЕРАТОР ЖИВЁТ ЗДЕСЬ, А НЕ В `tools/`
//
// Форму манифеста судит ОДИН исполнитель — загрузчик
// `services/iam/internal/manifest`, — и он закрыт правилом видимости Go для
// пакетов вне `services/iam/`. Генератор в `tools/` пришлось бы снабдить ВТОРЫМ
// разбором той же формы, и разошлись бы они молча: генератор перестал бы видеть
// ключ, который загрузчик принимает, а таблица тихо потеряла бы тип. Тот же
// довод уже записан у гейта манифестов в `internal/repohygiene`, где отступление
// названо вместе с причиной — она свойство языка, а не выбор.
//
// Здесь свойство языка работает В НАШУ ПОЛЬЗУ: генератор внутри `services/iam/`
// зовёт настоящий загрузчик, и второго объявления формы не заводится.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ГЕЙТ ДРЕЙФА С МОДЕЛЬЮ ОСТАЁТСЯ
//
// Он сверяет таблицы с КАНОНИЧЕСКОЙ МОДЕЛЬЮ, а не с манифестом, и предмет у него
// другой: манифест и канон — два рендера одного замысла, и их согласие есть
// утверждение, которое кто-то обязан проверять. Снять его вместе с заведением
// вывода значило бы оставить дерево без обоих.
package authzmapgen

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/PRO-Robotech/kacho-iam/internal/manifest"
)

// GeneratedRelPath — координата порождённого файла от корня репозитория.
//
// Объявлена ЗДЕСЬ и один раз: её знают команда записи и гейт свежести, и второе
// объявление развело бы их молча — гейт сверял бы файл, которого никто не пишет.
const GeneratedRelPath = "services/iam/internal/authzmap/tables_gen.go"

// TypeEntry — одна строка обеих таблиц сразу.
//
// Строка одна, потому что и точечное имя, и набор отношений объявляет ОДНА
// запись манифеста: разведя их по двум структурам, генератор завёл бы два
// обхода одного предмета.
type TypeEntry struct {
	// Dotted — имя в словаре КАТАЛОГА: `<модуль>.<ресурс>`.
	Dotted string
	// ObjectType — имя в словаре МОДЕЛИ ПРАВ.
	ObjectType string
	// VerbRelations — набор `v_*`, объявленный этим типом, отсортированно.
	//
	// Пусто означает «тип не глагольный»: строки в `typeVerbRelations` он не
	// даёт вовсе. Различать это от «набор пуст» обязан читатель — потому и
	// отдаётся nil, а не пустой срез.
	VerbRelations []string
}

// Census — ОБЪЁМ осмотренного. Печатается вызывающим всегда: «ноль расхождений»
// обязано быть отличимо от «ноль прочитанного».
type Census struct {
	ManifestsRead int
	PathsSeen     int
	Modules       int
	Resources     int
	VerbBearing   int
	VerbRelations int
	// InternalExcluded — действий ВНУТРЕННЕЙ плоскости, не вошедших в набор.
	//
	// В `StableSummary` (а значит и в порождённый файл) НЕ входит намеренно:
	// туда идут только величины, из которых собран сам файл, а исключённое в
	// него по построению не попало. Здесь же число несущее — без него
	// «отношений действия 109» неотличимо от «внутренних действий нет вовсе»,
	// и снятая ветвь исключения выглядела бы как исправная работа.
	InternalExcluded int
}

// Summary — перепись одной строкой, ВКЛЮЧАЯ объём обхода.
//
// Печатается командой и гейтом: там объём обхода и есть то, что отличает «ноль
// находок» от «ноль прочитанного».
func (c Census) Summary() string {
	return fmt.Sprintf("манифестов прочитано %d (осмотрено путей %d), модулей %d, "+
		"ресурсов %d, из них глагольных %d, отношений действия %d, "+
		"исключено действий внутренней плоскости %d",
		c.ManifestsRead, c.PathsSeen, c.Modules, c.Resources, c.VerbBearing,
		c.VerbRelations, c.InternalExcluded)
}

// StableSummary — перепись для ПОРОЖДЁННОГО ФАЙЛА: только величины, зависящие от
// манифестов.
//
// Объём обхода сюда НЕ входит намеренно. Он считает файлы всего дерева, то есть
// меняется от всякой правки где угодно, — и файл, несущий его, расходился бы со
// своим производителем на изменении, которое к таблицам отношения не имеет.
// Гейт свежести краснел бы, а находка называла бы не предмет: прокси-предикат,
// ломающийся раньше того, что он стережёт.
func (c Census) StableSummary() string {
	return fmt.Sprintf("манифестов %d, модулей %d, ресурсов %d, из них глагольных %d, "+
		"отношений действия %d",
		c.ManifestsRead, c.Modules, c.Resources, c.VerbBearing, c.VerbRelations)
}

// Tables — то, что генератор вывел из дерева.
type Tables struct {
	Entries []TypeEntry
	Census  Census
}

// Collect читает манифесты ДЕРЕВА тем же обходом и тем же загрузчиком, каким их
// читает проверка дерева, и выводит обе таблицы.
//
// Находка обхода — ОТКАЗ, а не пропуск записи: таблица, собранная из части
// манифестов, выглядит целой и молча теряет тип, а потерянный тип не резолвится
// краем — вопрос о нём не задаётся вовсе, и проверка выглядит пройденной.
//
// Беспредметный обход — тоже отказ: «манифестов ноль» неотличимо от «манифесты
// прочитаны и в них ничего нет», а порождённая из пустоты таблица снесла бы
// каталог целиком.
func Collect(root string) (Tables, error) {
	return collectReport(root, manifest.CheckTreeForGeneration(root))
}

// collectReport — СУЖДЕНИЕ о прочитанном обходом: общее у полосы дерева
// репозитория и полосы синтетического дерева.
//
// Различается у полос ровно ИСТОЧНИК ПЕРЕЧНЯ, и выбирает его вызывающий выше —
// по имени, а не догадкой внутри. Второй разбор отчёта, написанный рядом,
// разошёлся бы с первым молча.
func collectReport(root string, report manifest.CheckReport) (Tables, error) {
	if len(report.Findings) != 0 {
		return Tables{}, fmt.Errorf(
			"обход манифестов дерева %s дал находки (%s):\n\t%s\n"+
				"таблица из части манифестов выглядит целой и молча теряет тип",
			root, report.Summary(), strings.Join(report.Findings, "\n\t"))
	}
	if report.ManifestsRead == 0 {
		return Tables{}, fmt.Errorf(
			"обход дерева %s не дал НИ ОДНОГО манифеста (осмотрено путей %d) — "+
				"порождать таблицу типов не из чего; это отказ чтения, а не платформа "+
				"без модулей", root, report.PathsSeen)
	}

	census := Census{ManifestsRead: report.ManifestsRead, PathsSeen: report.PathsSeen}
	byDotted := map[string]TypeEntry{}
	modules := map[string]bool{}
	for _, m := range report.Manifests {
		modules[m.Module] = true
		for i := range m.Resources {
			r := m.Resources[i]
			dotted := m.Module + "." + r.Name
			if prev, seen := byDotted[dotted]; seen {
				return Tables{}, fmt.Errorf(
					"точечное имя %s объявлено дважды (типы %s и %s) — таблица имён "+
						"противоречила бы себе, и какой из двух типов победит, решал бы "+
						"порядок обхода", dotted, prev.ObjectType, r.ObjectType)
			}
			rels, skipped := verbRelationsOf(r)
			census.InternalExcluded += skipped
			byDotted[dotted] = TypeEntry{
				Dotted:        dotted,
				ObjectType:    r.ObjectType,
				VerbRelations: rels,
			}
			census.Resources++
		}
	}
	census.Modules = len(modules)

	dotted := make([]string, 0, len(byDotted))
	for k := range byDotted {
		dotted = append(dotted, k)
	}
	sort.Strings(dotted)

	byType := map[string]string{}
	out := Tables{Entries: make([]TypeEntry, 0, len(dotted))}
	for _, k := range dotted {
		e := byDotted[k]
		if prev, seen := byType[e.ObjectType]; seen {
			return Tables{}, fmt.Errorf(
				"тип объекта %s объявлен двумя ресурсами (%s и %s) — набор отношений "+
					"второго перетёр бы набор первого молча", e.ObjectType, prev, e.Dotted)
		}
		byType[e.ObjectType] = e.Dotted
		if len(e.VerbRelations) != 0 {
			census.VerbBearing++
			census.VerbRelations += len(e.VerbRelations)
		}
		out.Entries = append(out.Entries, e)
	}
	out.Census = census
	return out, nil
}

// verbRelationsOf — набор `v_*` ресурса, отсортированный.
//
// Имя отношения собирает ТО ЖЕ объявление, которым его собирает загрузчик
// (`manifest.VerbRelationName`): имя, написанное здесь иначе, адресовало бы
// отношение, по которому никто не постучится.
//
// Класс, а не имя действия: короткая форма записи восстанавливает класс из
// имени, длинная называет его явно — и разница между `addTargets` и
// `v_addtargets` живёт ровно в одном месте, у загрузчика.
func verbRelationsOf(r manifest.Resource) (rels []string, internalExcluded int) {
	if len(r.Verbs) == 0 {
		return nil, 0
	}
	seen := map[string]bool{}
	out := make([]string, 0, len(r.Verbs))
	for _, v := range r.Verbs {
		// Действие, не порождающее отношения, в набор типа НЕ ВХОДИТ, и правило
		// объявлено один раз (manifest.VerbProducesRelation).
		//
		// ЗДЕСЬ ЦЕНА ОШИБКИ ВЫШЕ, ЧЕМ КАЖЕТСЯ, ПОТОМУ ЧТО КЛЮЧ — КЛАСС. Набор
		// собирается по `v.Class`, а не по имени, поэтому внутреннее действие
		// втащило бы в набор класс, которого у ТЕНАНТСКИХ действий ресурса нет
		// вовсе. Замер на дереве: без этой ветви `vpc_address` и `storage_image`
		// получали `v_create`, а `iam_user` — `v_update`, при том что модель ни
		// одного из трёх не объявляет (рендер внутренние действия пропускает).
		// Тип утверждал бы, что несёт отношение, которого в модели нет, и
		// правило роли на этот класс резолвилось бы в никуда — выдача, которая
		// создаётся, перечисляется и не гейтит ничего.
		if !manifest.VerbProducesRelation(v) {
			internalExcluded++
			continue
		}
		rel := manifest.VerbRelationName(v.Class)
		if seen[rel] {
			continue
		}
		seen[rel] = true
		out = append(out, rel)
	}
	sort.Strings(out)
	return out, internalExcluded
}

// CheckFresh — ОДИН предикат свежести на обоих вызывающих: гейт дерева и
// доказательство его способности упасть.
//
// Второй экземпляр сравнения (одно в теле пробы дерева, другое в инъекции)
// разошёлся бы с первым молча — и доказательство говорило бы о коде, которого
// гейт не исполняет.
//
// Отдаёт перепись ВСЕГДА, включая исход отказа: без неё «файл отстал» не
// отличается от «манифестов не нашлось», а чинятся эти два состояния по-разному.
func CheckFresh(root string) (Census, error) {
	tables, err := Collect(root)
	if err != nil {
		return tables.Census, err
	}
	return compareRendered(root, tables)
}

// compareRendered — сверка ПОРОЖДЁННОГО файла с тем, что даёт производитель:
// общее у обеих полос, потому что предмет сверки от источника перечня не
// зависит.
func compareRendered(root string, tables Tables) (Census, error) {
	want, err := Render(tables)
	if err != nil {
		return tables.Census, err
	}
	path := filepath.Join(root, GeneratedRelPath)
	got, err := os.ReadFile(path) // #nosec G304 -- корень даёт вызывающий, хвост — константа пакета.
	if err != nil {
		return tables.Census, fmt.Errorf(
			"порождённый файл %s не читается (%w) — таблицы типов брать неоткуда",
			GeneratedRelPath, err)
	}
	if !bytes.Equal(got, want) {
		return tables.Census, fmt.Errorf(
			"%s отстал от производителя: файл писал не он (в дереве байт %d, порождается %d). "+
				"Перегенерируйте: go generate ./services/iam/internal/authzmap/... — "+
				"правка руками бессмысленна, внесённое вернётся первой же перегенерацией",
			GeneratedRelPath, len(got), len(want))
	}
	return tables.Census, nil
}
