package restfront

import "net"

// DialTarget переводит адрес ПРИВЯЗКИ слушателя в адрес, по которому до него
// дозваниваются из этого же процесса.
//
// # Почему это не одно и то же
//
// «0.0.0.0» и «[::]» — не адреса машины, а указание «принимать на всех
// интерфейсах». Как цель соединения они неопределённы: часть систем резолвит их
// в петлю молча, часть отказывает, и поведение фронта зависело бы от того, где
// он поднят. Пустой хост (форма «:9090») неопределён ровно так же.
//
// Перевод сделан ЯВНО, потому что цена неявного здесь не отказ, а расхождение
// стендов: на одном фронт работает, на другом — нет, и причина не видна ни в
// одном файле.
//
// Порт сохраняется как есть: фронт идёт к СВОЕМУ слушателю, и другого порта у
// него быть не может.
func DialTarget(listenAddr string) string {
	if listenAddr == "" {
		return ""
	}
	host, port, err := net.SplitHostPort(listenAddr)
	if err != nil {
		// Адрес не разбирается на хост и порт — отдаём как есть: выдумывать
		// здесь значило бы чинить профиль догадкой, а отказ соединения назовёт
		// адрес прямо.
		return listenAddr
	}
	switch host {
	case "", "0.0.0.0", "::":
		return net.JoinHostPort("127.0.0.1", port)
	default:
		return listenAddr
	}
}
