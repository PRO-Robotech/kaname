package restfront

import (
	"context"
	"net"
	"net/http"
	"net/netip"

	"github.com/grpc-ecosystem/grpc-gateway/v2/runtime"
	"google.golang.org/grpc/metadata"
)

// clientaddr.go — адрес клиента публичного фронта, донесённый до собственного
// слушателя (kaname#991).
//
// # Зачем
//
// Фронт — КЛИЕНТ собственного gRPC-слушателя: для слушателя все запросы,
// пришедшие по HTTP, приходят с одного пира — самого фронта. Ограничитель
// допуска слушателя ключует анонимный вызов адресом вызывающего, и без этой
// записи все анонимные клиенты фронта делили бы ОДНО ведро: поток одного
// расходовал бы предел всех.
//
// # Почему отдельный ключ метаданных, а не `x-forwarded-for` библиотеки
//
// Библиотека тоже пишет адрес — хвостом списка, приклеенным к ПРИСЛАННОМУ
// клиентом заголовку. Читать его значит разбирать чужой формат и доверять
// месту в строке, которую наполовину пишет вызывающий. Свой ключ пишет только
// фронт: сопоставитель заголовков не пропускает внутрь НИ ОДНОГО заголовка
// запроса (mux.go), поэтому подставить это значение через HTTP нечем.
//
// # Кто ему верит
//
// Только слушатель, и только когда пир — собственный фронт, узнанный по
// проверенному листу (ownfronthop.go в композиционном корне). Тот же ключ от
// любого другого пира не читается: его может прислать кто угодно.

// MetadataClientAddr — ключ метаданных, которым публичный фронт сообщает
// собственному слушателю адрес своего клиента (без порта).
const MetadataClientAddr = "x-kaname-front-client-addr"

// newPublicMux — мультиплексор публичного фронта: общий конструктор плюс
// запись адреса клиента. Внутреннему фронту запись не нужна — его слушатель
// ключуется листом модуля, а не адресом.
func newPublicMux() *runtime.ServeMux {
	return newMux(runtime.WithMetadata(clientAddrMetadata))
}

// clientAddrMetadata — адрес соединения HTTP-запроса без порта, ровно одним
// значением.
//
// Берётся адрес СОЕДИНЕНИЯ, а не заголовок пересылки: клиент пишет заголовки
// сам. Адрес за балансировщиком сюда приходит тем же полем — его подставляет
// слушатель, принявший заголовок объявленного балансировщика (kaname#989).
//
// Негодный адрес соединения не записывается: тогда слушатель отнесёт вызов к
// ключу самого фронта, а не к ключу, выбранному содержимым строки.
func clientAddrMetadata(_ context.Context, r *http.Request) metadata.MD {
	host, _, err := net.SplitHostPort(r.RemoteAddr)
	if err != nil {
		host = r.RemoteAddr
	}
	addr, err := netip.ParseAddr(host)
	if err != nil || addr.Zone() != "" {
		return nil
	}
	return metadata.Pairs(MetadataClientAddr, addr.Unmap().String())
}
