// doorpackages_test.go — перечень пакетов, по которому гейт фронта выбирает
// маршруты контракта, обязан совпадать с картой ДВЕРИ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО ПРОВЕРКА, А НЕ ОБЩИЙ ИСТОЧНИК
//
// Гейт фронта судит маршруты НЕЗАВИСИМО от того, что о них думает дверь, — в
// этом его ценность: общий источник сделал бы согласие тавтологией, и две
// стороны перестали бы быть двумя. Поэтому перечень остаётся своим, а совпадение
// становится ОТДЕЛЬНЫМ утверждением.
//
// Шапка перечня объявляла это совпадение «предметом отдельной проверки ниже».
// Проверки не было, и перечни разошлись молча: дверь сняла пакет общей формы
// ответа учёта (у него не осталось ни одного RPC), а гейт продолжал выбирать по
// нему маршруты — то есть судил поверхность, которой дверь не обслуживает.

package restfront

import (
	"sort"
	"testing"

	"github.com/PRO-Robotech/kaname/internal/authzguard"
)

// TestFrontPackageListMatchesTheDoorMap — совпадение в ОБЕ стороны.
//
// Пакет двери без записи здесь оставил бы его маршруты вне обхода — «объявлено
// ноль» прочиталось бы как «поднято всё». Запись здесь без пакета двери судила
// бы поверхность, которой дверь не обслуживает.
func TestFrontPackageListMatchesTheDoorMap(t *testing.T) {
	door := append([]string(nil), authzguard.OwnDoorProtoPackages()...)
	sort.Strings(door)
	if len(door) == 0 {
		t.Fatalf("карта двери не объявила ни одного пакета — сверять нечего")
	}

	front := make([]string, 0, len(ownDoorProtoPackages))
	for p, on := range ownDoorProtoPackages {
		if on {
			front = append(front, p)
		}
	}
	sort.Strings(front)

	t.Logf("перепись: пакетов карты двери %d · пакетов перечня фронта %d", len(door), len(front))

	if len(front) == 0 {
		t.Fatalf("перечень фронта пуст: обход маршрутов был бы пуст, и «расхождений ноль» " +
			"означало бы «прочитано ноль»")
	}
	if len(front) != len(door) {
		t.Fatalf("перечни разошлись: дверь держит %v, фронт выбирает по %v", door, front)
	}
	for i := range door {
		if front[i] != door[i] {
			t.Fatalf("перечни разошлись: дверь держит %v, фронт выбирает по %v", door, front)
		}
	}
}
