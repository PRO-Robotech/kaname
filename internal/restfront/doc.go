// Package restfront — собственный REST-фронт службы: два мультиплексора на двух
// слушателях, публичный и внутренний.
//
// # Предмет
//
// Пока служба стоит за краем платформы, её HTTP-поверхность принадлежит краю:
// маршруты объявлены аннотациями контракта, а поднимает их чужое дерево.
// Вынесенная отдельным продуктом, служба края не имеет BY CONSTRUCTION — и её
// REST обязан существовать сам.
//
// # Почему фронтов ДВА, а не один с разбором пути
//
// Раздельность есть свойство СОКЕТА, а не содержимого запроса. Один слушатель,
// решающий «этот путь внутренний, а этот нет», делает принадлежность маршрута
// фронту решением, принимаемым на каждом запросе. Требование «внутреннее не
// публикуется наружу» проверяемо ровно тогда, когда «не опубликован» значит
// «недосягаем»: это доказуемо снаружи одним обращением, а не чтением условия.
//
// # Почему регистрация ТОЛЬКО через собственный адрес
//
// Все звенья, решающие о вызывающем и о доступе к объекту, — перехватчики
// СЛУШАТЕЛЯ. Внутрипроцессная форма регистрации зовёт реализацию напрямую,
// поэтому запрос, пришедший по HTTP, обслуживался бы иначе, чем тот же запрос
// по gRPC: два пути к одному обработчику с разными решениями по дороге. REST и
// gRPC обязаны отвечать ОДНИМ звеном на один вопрос, а единственный способ это
// обеспечить — общий слушатель.
//
// # Почему свой обработчик ошибок здесь НЕ заводится
//
// Отображение кода отказа в HTTP-статус делает библиотека. Пока мультиплексор
// собран без своего обработчика, множество производимых статусов конечно и
// совпадает у обеих HTTP-поверхностей платформы, и вызывающему не приходится
// знать, через какую он пришёл. Заведи фронт свой обработчик — таблица статусов
// в приёмке перестанет описывать поведение и обязана переехать за ним тем же
// изменением.
