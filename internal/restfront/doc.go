// Package restfront — собственный REST-фронт службы: два мультиплексора на двух
// слушателях, публичный и внутренний.
//
// # Предмет
//
// Пока служба стоит за краем платформы, её HTTP-поверхность принадлежит краю:
// маршруты объявлены аннотациями контракта, а поднимает их чужое дерево.
// Вынесенная отдельным продуктом, служба края не имеет BY CONSTRUCTION — и её
// REST обязан существовать сам.
//
// # Почему фронтов ДВА, а не один с разбором пути
//
// Раздельность есть свойство СОКЕТА, а не содержимого запроса. Один слушатель,
// решающий «этот путь внутренний, а этот нет», делает принадлежность маршрута
// фронту решением, принимаемым на каждом запросе. Требование «внутреннее не
// публикуется наружу» проверяемо ровно тогда, когда «не опубликован» значит
// «недосягаем»: это доказуемо снаружи одним обращением, а не чтением условия.
//
// # Почему регистрация ТОЛЬКО через собственный адрес
//
// Все звенья, решающие о вызывающем и о доступе к объекту, — перехватчики
// СЛУШАТЕЛЯ. Внутрипроцессная форма регистрации зовёт реализацию напрямую,
// поэтому запрос, пришедший по HTTP, обслуживался бы иначе, чем тот же запрос
// по gRPC: два пути к одному обработчику с разными решениями по дороге. REST и
// gRPC обязаны отвечать ОДНИМ звеном на один вопрос, а единственный способ это
// обеспечить — общий слушатель.
//
// # Обработчик ошибок вызова: один свой ответ, остальное — умолчание
//
// Отображение кода отказа в HTTP-статус делает библиотека, и множество
// производимых статусов задаёт она: вызывающему не приходится знать, через
// какую поверхность он пришёл. Свой обработчик ошибок вызова у фронта есть
// (stepup.go), но рендерит он ОДИН ответ — указание повысить уровень (решение
// Р11 приёмки уровня уверенности, kaname#511): `401`, тело края побайтово и
// вызов RFC 9470 с параметрами уровня, приехавшими хвостом ответа слушателя.
// Код указания — `UNAUTHENTICATED`, то есть `401` и у умолчания: таблица
// статусов приёмки не меняется ни одной строкой. Всё прочее уходит умолчанию
// дословно.
//
// Прежняя редакция этого абзаца обосновывала отсутствие обработчика тем, что
// множество статусов «совпадает у обеих HTTP-поверхностей платформы». Для
// отдельно поставленной службы это оказалось НЕВЕРНО, и неверно наблюдаемо:
// на промах глагола фронт отвечал 501, а эндпоинт выдачи токена — 405
// (задача #2493).
//
// # Форма отказа на неверный ГЛАГОЛ — одна на обе HTTP-поверхности службы
//
// Фронт и полоса входа отвечают на «путь есть, метод не тот» одной формой
// (задача #261, решение R36 п. 3): `405`,
// `{"code":12,"message":"method not allowed","details":[]}` и заголовок `Allow`
// с методами, которые путь обслуживает. Это решение продукта, а не умолчание:
// библиотека переводит промах глагола в `Unimplemented`, то есть в 501, и «не
// реализовано» уводит клиента с дороги — он идёт заводить задачу вместо того,
// чтобы сменить глагол (задача #2493). Сведение живёт в обработчике ошибок
// МАРШРУТИЗАЦИИ (mux.go), который судит промах глагола и отображения кодов
// отказа не трогает.
//
// Перечень `Allow` не выписан: его отвечает маршрутизатор фронта на вопрос о
// каждом методе HTTP, и обработчики при этом не исполняются (mux.go,
// allowedMethods). Код `12` — тот, что производит маршрутизатор, и тот же
// отдаёт полоса входа, поэтому клиент, ключующийся на `code`, читает один
// класс отказа одинаково по любому адресу службы.
