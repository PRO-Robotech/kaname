// Package treeposture отвечает на ОДИН вопрос: где корень дерева, которое судят
// пробы и приборы этого модуля, — и приводит к нему координату, записанную от
// корня платформы.
//
// ЗДЕСЬ НЕТ `testing` — И ЭТО НЕСУЩЕЕ. Тот же вопрос задаёт не только проба:
// приборы модуля (отпечаток сетки замера, писатель отчётов) читают свои каталоги
// по координатам и в чужой посадке ошибаются ровно так же. Пакет с `testing` в
// импорте прод-код звать не вправе — он утащил бы испытательную оснастку в
// поставляемый двоичный. Поэтому чистая часть живёт здесь, а исход для пробы
// (`Require*`) — в обёртке `internal/testsupport/platformtree`.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОСАДКА ОДНА — И ЭТО ИСПРАВЛЕНИЕ, А НЕ УПРОЩЕНИЕ
//
// Пакет писался под ДВЕ посадки: модуль внутри дерева платформы
// (`<корень>/services/iam`) и модуль самостоятельным клоном. Признаком первой
// служил каталог модулей платформы рядом с нашим, а пробе, спросившей это
// дерево, полагался третий исход — пропуск с названной предпосылкой.
//
// **Первой посадки не существует ни в одном дереве.** После выноса службы
// отдельным репозиторием каталога `services/iam` нет ни у платформы, ни здесь:
//
//	git -C <kacho> ls-tree -r origin/main --name-only | grep -c '^services/iam/'   # → 0
//
// Значит «дерева платформы рядом нет» перестало быть свойством КЛОНА и стало
// свойством ВСЕГО, а пропуск — безусловным. Замер на стволе `83ddd08a`
// (`go test -short -v ./...`, строки пропуска по этой предпосылке): **58**
// строк · **53** верхнеуровневые пробы · 2 подпробы · 1 строка без `SKIP`
// рядом. Единица счёта названа, потому что их три и они дают разные числа.
// Среди пропущенных — гейт безопасности «у каждого публичного RPC есть
// пообъектный вопрос». Молчание такой пробы неотличимо от исправной работы — и
// за это время два перечня каталогов успели разойтись с картой двери, чего не
// увидел никто.
//
// Отсюда устройство: корень суждения — корень МОДУЛЯ, и он устанавливается в
// любом прогоне. Ветви «платформы рядом нет» больше не существует; её снятие
// держит КОМПИЛЯТОР (символа нет), а не обещание.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАПИСЕЙ КООРДИНАТЫ ДВЕ, И РАСПОЗНАВАТЕЛЬ ЗНАЕТ ОБЕ
//
// Пробы называют свои файлы двумя законными записями, и обе распространены:
//
//	services/iam/internal/migrations — ИСТОРИЧЕСКАЯ, от корня монорепо. Живёт в
//	                                  347 файлах дерева; приставка снимается;
//	proto/kaname/cloud/iam/v1        — от корня ЭТОГО дерева. Контракт уезжает
//	                                  вместе с модулем, и координата верна как есть.
//
// Прежний резолв знал только первую: всё, записанное второй, он отвергал как
// «часть дерева платформы, у арендатора отсутствующую by construction». Посылка
// была ложной — каталог контрактов лежит в этом же репозитории, — и именно она
// пропускала гейт публичных RPC.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧУЖОЕ ДЕРЕВО — НАХОДКА, А НЕ ПРОПУСК
//
// Осталась одна законная причина отказать: координата называет то, чего в этом
// репозитории нет и не будет — маршрутизатор платформы, манифест соседнего
// модуля, зонтичный чарт стенда. Это `ErrForeignTree`, и он ГРОМКИЙ: предмета у
// такой пробы здесь нет вовсе, и тихо соглашаться с ней нельзя — именно так
// пропуск и переживает свою предпосылку.
//
// Признак выводится, а не выписывается: первый сегмент координаты обязан быть
// записью ЭТОГО дерева. Выписанный перечень «чужих» каталогов разошёлся бы с
// деревом на первом же новом и разошёлся бы молча.
//
// ─────────────────────────────────────────────────────────────────────────────
// ДЕРЕВО ПЛАТФОРМЫ, НАЗВАННОЕ СНАРУЖИ, ОСТАЁТСЯ
//
// Сверка канона модели с манифестами модулей платформы жива и держится заданием
// конвейера: оно выбирает `services/*/manifest.yaml` из репозитория платформы и
// передаёт корень явно (`make model-canon-check PLATFORM_TREE=…`). Такой корень
// НАЗВАН вызывающим, а не найден подъёмом, — и `PathUnder`/`PrefixUnder` его
// по-прежнему узнают по каталогу модулей.
package treeposture

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// ErrModuleRootUnknown — корень модуля не установлен: судить не о чем.
var ErrModuleRootUnknown = errors.New("корень модуля не установлен")

// ErrForeignTree — координата называет дерево, которого в этом репозитории нет.
//
// Отдельный признак, а не общий отказ: «названного здесь не бывает» и «файла нет»
// — разные вещи, и первая означает, что у пробы нет предмета, а не что предмет
// сломан.
var ErrForeignTree = errors.New("координата называет дерево, которого в этом репозитории нет")

// siblingsDir — каталог, в котором лежат модули платформы.
//
// Признак дерева платформы, НАЗВАННОГО снаружи: подъёмом от модуля оно не
// ищется — модуль в нём не лежит ни в одном дереве.
const siblingsDir = "services"

// SiblingsDir — тот же признак для вызывающего, который спрашивает его о ДРУГОМ
// дереве (обход сверки канона модели судит корень, названный параметром).
const SiblingsDir = siblingsDir

// ModuleRootFrom поднимается от start до БЛИЖАЙШЕГО каталога с `go.mod`.
//
// Маркер — `go.mod`, а не число уровней и не имя каталога: имя у арендатора
// выбирает тот, кто клонировал, а число уровней верно ровно для одной посадки.
func ModuleRootFrom(start string) (string, error) {
	dir := start
	for {
		if st, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil && st.Mode().IsRegular() {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("%w: маркер go.mod не найден подъёмом от %s", ErrModuleRootUnknown, start)
		}
		dir = parent
	}
}

// RootFrom — корень ДЕРЕВА, которое судят пробы и приборы модуля.
//
// Это корень самого модуля: другого дерева у него нет ни в одной посадке.
// Ошибка одна и означает «проверка НЕ ИСПОЛНЯЛАСЬ»: корня модуля нет, то есть
// пробе нечего назвать деревом, о котором она говорит.
func RootFrom(start string) (string, error) { return ModuleRootFrom(start) }

// ModuleDirIn — каталог модуля В НАЗВАННОМ дереве.
//
// Существует ради вызывающих, которые прежде складывали этот путь литералом
// `services/iam`: литерал верен ровно для одной посадки, а в другой указывает в
// несуществующий подкаталог клона. Здесь он ВЫВОДИТСЯ.
//
// Для корня, совпадающего с модулем, возвращает ПУСТУЮ строку, а не «.»:
// приставка «.» склеивается в `./x` и не совпадает ни с одной записью состава —
// МОЛЧА.
func ModuleDirIn(root, moduleRoot string) (string, error) {
	rel, err := filepath.Rel(root, moduleRoot)
	if err != nil {
		return "", fmt.Errorf("%w: модуль %s не сводится под корень %s", ErrModuleRootUnknown, moduleRoot, root)
	}
	if rel == "." {
		return "", nil
	}
	return rel, nil
}

// moduleDirInPlatform — ИСТОРИЧЕСКАЯ запись координаты этого модуля.
//
// Приставка, с которой пробы называют свои файлы со времён монорепо. Каталога с
// таким именем сегодня нет ни в одном дереве, но записей с ним в корпусе сотни,
// и распознаватель обязан их знать: иначе всё, записанное этой формой,
// оказывается вне наблюдения.
const moduleDirInPlatform = "services/iam"

// ModuleDirInPlatform — та же запись для вызывающего, который её сверяет.
func ModuleDirInPlatform() string { return moduleDirInPlatform }

// PathOf — путь, приведённый к дереву, в котором идёт прогон.
//
// Исходов ДВА, и третьего нет:
//
//	координата ЭТОГО дерева (в любой из двух записей) → абсолютный путь;
//	координата ЧУЖОГО дерева                         → ErrForeignTree, находка.
func PathOf(start, rel string) (string, error) {
	moduleRoot, err := ModuleRootFrom(start)
	if err != nil {
		return "", err
	}
	return PathUnder(moduleRoot, rel)
}

// PathUnder — координата, приведённая к НАЗВАННОМУ корню.
//
// Отличается от PathOf тем, что корень УЖЕ ДАН: его спросили у git
// (`rev-parse --show-toplevel`), получили аргументом либо ручкой задания
// (`PLATFORM_TREE`). Поэтому посадка опознаётся по САМОМУ корню, а не по
// рабочему каталогу: два разных ответа об одном дереве разошлись бы молча.
func PathUnder(root, rel string) (string, error) {
	rel = filepath.ToSlash(filepath.Clean(rel))
	if rel == "." || rel == "/" || strings.HasPrefix(rel, "../") {
		return "", fmt.Errorf("%w: путь %q не является координатой от корня дерева", ErrModuleRootUnknown, rel)
	}
	if root == "" {
		return "", fmt.Errorf("%w: корень не назван", ErrModuleRootUnknown)
	}

	// Дерево платформы, названное снаружи: наш модуль лежит в его `services/`.
	// Тогда координата берётся как записана.
	if isPlatformRoot(root) {
		return filepath.Join(root, filepath.FromSlash(rel)), nil
	}

	// Историческая запись: приставка модуля снимается.
	if rel == moduleDirInPlatform {
		return root, nil
	}
	if inside, ok := strings.CutPrefix(rel, moduleDirInPlatform+"/"); ok {
		return filepath.Join(root, filepath.FromSlash(inside)), nil
	}

	// Запись от корня ЭТОГО дерева. Годность решает первый сегмент: он обязан
	// быть записью дерева. Признак выводится обходом, а не выписан перечнем.
	head, _, _ := strings.Cut(rel, "/")
	if _, err := os.Stat(filepath.Join(root, head)); err == nil {
		return filepath.Join(root, filepath.FromSlash(rel)), nil
	}

	return "", fmt.Errorf(
		"%w\n  спрошена координата: %s\n  осмотрен корень:     %s\n"+
			"  ожидался признак: первый сегмент %q есть запись этого дерева\n"+
			"  его нет — значит названное принадлежит дереву платформы (маршрутизатор,\n"+
			"  манифест соседнего модуля, зонтичный чарт стенда) и в этот репозиторий\n"+
			"  не входит. Предмета у такой проверки здесь НЕТ — её снимают вместе с\n"+
			"  предметом либо переносят туда, где предмет живёт",
		ErrForeignTree, rel, root, head)
}

// isPlatformRoot — несёт ли НАЗВАННЫЙ корень наш модуль в каталоге модулей.
func isPlatformRoot(root string) bool {
	st, err := os.Stat(filepath.Join(root, filepath.FromSlash(moduleDirInPlatform)))
	return err == nil && st.IsDir()
}

// CorpusRoot — КОРЕНЬ ДЕРЕВА, которое проба обходит, и ПРИСТАВКА, под которой в
// нём лежат файлы этого модуля.
//
// Есть род проб, которые не читают названный файл, а ОБХОДЯТ состав дерева и
// судят его целиком. Такой пробе нужны две величины сразу: от какого корня брать
// состав и с какой приставки начинаются её собственные файлы.
//
// Модуль сам себе дерево, поэтому приставка ПУСТА. Ошибка означает, что корня
// модуля нет вовсе, — то есть проба не может назвать дерево, о котором говорит.
func CorpusRoot(start string) (root, prefix string, err error) {
	moduleRoot, err := ModuleRootFrom(start)
	if err != nil {
		return "", "", err
	}
	return moduleRoot, "", nil
}

// Under — координата файла модуля в составе, приведённая к приставке.
//
//	Under("services/iam", "internal/x") -> `services/iam/internal/x`;
//	Under("",             "internal/x") -> `internal/x`.
//
// Существует ради вызывающих, которые иначе склеили бы приставку конкатенацией и
// получили ведущий слеш — путь, который не совпадёт ни с одной записью состава,
// причём МОЛЧА.
func Under(prefix, rel string) string {
	rel = strings.TrimPrefix(filepath.ToSlash(rel), "./")
	if prefix == "" || prefix == "." {
		return rel
	}
	if rel == "" {
		return prefix
	}
	return prefix + "/" + rel
}

// PrefixUnder — приставка модуля в составе, отсчитываемом от НАЗВАННОГО корня.
//
// Пуста для дерева модуля и равна исторической записи для дерева платформы,
// названного снаружи (`PLATFORM_TREE`). Нужна обходчикам состава: они сравнивают
// записи с координатами, и склеенная не с той приставкой не совпадёт ни с одной —
// молча.
func PrefixUnder(root string) string {
	if isPlatformRoot(root) {
		return moduleDirInPlatform
	}
	return ""
}

// ─────────────────────────────────────────────────────────────────────────────
// ДЕРЕВО ПЛАТФОРМЫ, НАЗВАННОЕ СНАРУЖИ

// PlatformTreeEnv — ручка, которой вызывающий НАЗЫВАЕТ дерево платформы.
//
// Имя то же, что у переменной рецепта (`make model-canon-check PLATFORM_TREE=…`),
// и это не совпадение: два имени об одном предмете разошлись бы молча, а задание
// конвейера, выкладывающее манифесты соседних модулей, передаёт именно её.
const PlatformTreeEnv = "PLATFORM_TREE"

// NamedPlatformRoot — корень дерева платформы, НАЗВАННЫЙ снаружи, и причина
// отказа словами.
//
// Подъёмом такое дерево не ищется и искаться не может: модуль в нём не лежит ни
// в одной посадке — его туда выкладывает задание. Поэтому источник ровно один —
// ручка, и её отсутствие есть «условие не создано» с НАЗВАННЫМ производителем
// (задание конвейера), а не свойство продукта.
//
// Признак годности — каталог модулей внутри названного корня. Ручка, указавшая
// в дерево без него, отвергается словами: непроверенный корень дал бы пустой
// обход, а «манифестов ноль» прочиталось бы как «расхождений ноль».
func NamedPlatformRoot() (string, string) {
	raw := strings.TrimSpace(os.Getenv(PlatformTreeEnv))
	if raw == "" {
		return "", fmt.Sprintf(
			"дерево платформы не названо: ручка %s пуста. Манифесты соседних модулей в этот "+
				"репозиторий не входят by construction — их выкладывает задание конвейера "+
				"(`authzartifacts`, выборка services/*/manifest.yaml) и передаёт корень этой ручкой",
			PlatformTreeEnv)
	}
	root := filepath.Clean(raw)
	// Корень называет задание конвейера либо оператор, а не ввод арендатора; хвост
	// — константа. Обход дерева по названному корню и есть предмет этой функции.
	st, err := os.Stat(filepath.Join(root, siblingsDir)) // #nosec G703 -- корень назван оператором ручкой, хвост константен
	if err != nil || !st.IsDir() {
		return "", fmt.Sprintf(
			"ручка %s называет %s, а каталога модулей %s/ в нём нет: обход был бы пуст, и "+
				"«манифестов ноль» прочиталось бы как «расхождений ноль»",
			PlatformTreeEnv, root, siblingsDir)
	}
	return root, ""
}
