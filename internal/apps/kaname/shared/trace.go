package shared

import "log/slog"

// MaxTraceIDLen — предел длины корреляционного идентификатора В ЛОГЕ.
//
// Длина приходит от вызывающего КАКАЯ УГОДНО: механизма, ограничивающего её на
// пути запроса, в этом дереве нет — ни интерсептора, ни проверки контракта.
// Прежде предел объявляло расширение контракта, но исполнителя у него не было ни
// одного, и семейство снято целиком (kacho#1255). Писать значение в лог как есть
// значит отдать вызывающему право на объём наших логов.
const MaxTraceIDLen = 64

// TraceAttr — корреляционный идентификатор вызывающего как атрибут записи лога.
//
// # Почему предел и обрезка живут ЗДЕСЬ, а не у каждой полосы
//
// Полос проверки доступа две — публичная (`AuthorizeService.Check`/`BatchCheck`)
// и внутренняя (`InternalIAMService.Check`), — и обе пишут один и тот же
// идентификатор в свои записи. Пока обрезка стояла у одной, второе место об
// одном предмете либо отсутствовало (внутренняя полоса не читала поле ВОВСЕ,
// kacho#1351), либо разошлось бы молча: две копии предела расходятся на первой
// же правке, и увидеть это можно лишь сравнив записи двух полос.
//
// # Что этот атрибут утверждает, а что НЕТ
//
// Он утверждает, что присланный идентификатор доедет до тех записей, которые
// глагол вообще делает, — то есть до отказов. На успешном пути записи нет и не
// будет: authz-Check стоит на КАЖДОМ RPC платформы, и запись на каждый успешный
// Check утопила бы ту самую корреляцию, ради которой поле существует.
//
// Пустой идентификатор даёт пустой атрибут (slog печатает его пустой строкой) —
// это дешевле ветвления на каждом вызове и записи не искажает.
func TraceAttr(traceID string) slog.Attr {
	if len(traceID) > MaxTraceIDLen {
		traceID = traceID[:MaxTraceIDLen]
	}
	return slog.String("trace_id", traceID)
}
