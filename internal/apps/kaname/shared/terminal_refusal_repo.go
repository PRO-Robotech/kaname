package shared

// terminal_refusal_repo.go — надстройка над `operations.Repo`: текст отказа
// выбирается ПО НОСИТЕЛЮ, на котором он поедет к вызывающему.
//
// Приёмка: `docs/engineering/acceptance/refusal-text-names-the-lane-that-can-retry.md`
// (задача `PRO-Robotech/kacho#2439`).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Отказ класса «сериализационный конфликт» переводится в `ABORTED` с текстом
// «повтори запрос». На СИНХРОННОЙ полосе совет верен: вызывающий держит
// соединение, отказ не терминален, повтор того же запроса проходит. На
// ТЕРМИНАЛЬНОМ исходе операции повторять некому — исполнитель повторяет с
// отступом только терминальную ЗАПИСЬ, тело мутации исполняется ОДИН раз, и его
// отказ становится исходом. Вызывающий получает `done:true` и указание
// повторить при том, что внутри платформы повтора не происходит.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ НАДСТРОЙКА НАД РЕПОЗИТОРИЕМ, А НЕ ОБЁРТКА ВОКРУГ ДИСПЕТЧЕРИЗАЦИИ
//
// Полоса не совпадает с местом в коде. Терминальный исход пишут ТРИ разных
// вызывающих: исполнитель операции, его синхронный вариант и use-case, зовущий
// запись напрямую (последний кладёт один и тот же отказ в ОБА носителя разом —
// вызывающему ответом и в строку операции). Общего у всех трёх ровно одно: они
// зовут запись на ПЕРЕДАННОМ ИНТЕРФЕЙСЕ репозитория. Обёртка вокруг
// диспетчеризации накрыла бы только первого, а у третьего оборачивать нечего —
// тела как отдельной функции там нет.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕТВЁРТЫЙ ПИСАТЕЛЬ СУЩЕСТВУЕТ, И ОН ВЫНЕСЕН ИСКЛЮЧЕНИЕМ, А НЕ ЗАБЫТ
//
// Реконсайлер осиротевших операций (`corelib/operations/reconciler.go`) пишет
// терминальную ошибку внутри собственной транзакции, держа пул, и интерфейса
// репозитория не касается вовсе — надстройка его не перехватывает
// СТРУКТУРНО. В предмет он не входит по трём проверенным фактам: код у него
// прибит к `Internal`, текст — замороженная константа, а решение резолвера
// несёт только исход и ответ, полей статуса у него нет, поэтому подставить
// `ABORTED` туда нельзя ни сегодня, ни случайно.
//
// ПРЕДИКАТ ИСТЕЧЕНИЯ исключения ВНЕШНИЙ: появится у решения резолвера поле
// статуса либо перестанет код быть прибитым — исключение теряет основание.
// Наступление видно в чужом дереве, и читает эту строку тот, кто бампит пин.
//
// ─────────────────────────────────────────────────────────────────────────────
// НАДСТРОЙКА ОБЯЗАНА СОХРАНИТЬ ВСЕ АПГРЕЙДЫ РЕПОЗИТОРИЯ — ПЕРЕЧЕНЬ ИЗМЕРЕН
//
// Репозиторий операций несёт больше, чем узкий контракт `Repo`, и часть
// дополнительного берётся ТИПОВЫМ УТВЕРЖДЕНИЕМ, то есть молча пропадает у
// всякого, кто обернул значение и не подумал об этом. Перечень снят обходом
// чужого дерева, а не выведен:
//
//	FullRepo              `Repo` + владение + финализатор метаданных + уборщик
//	                      терминальных строк. Берётся НА КОМПИЛЯЦИИ, поэтому
//	                      потеря была бы отказом сборки, а не тишиной;
//	executionClaimer      `ClaimForExecution` — ВНЕ `FullRepo`, берётся типовым
//	                      утверждением в исполнителе. Потеря тихая, и цена её
//	                      названа самим исполнителем: без подтверждения живости
//	                      он исполняет тело уже терминальной операции и создаёт
//	                      ФАНТОМНЫЙ РЕСУРС.
//
// Второй поэтому пробрасывается ЯВНО, и пробрасывается УСЛОВНО: надстройка
// объявляет метод только когда его несёт обёрнутый. Объявить безусловно значило
// бы сказать исполнителю «claimer есть» поверх репозитория, у которого его нет,
// — и получить отказ исполнения там, где раньше работа шла.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО НАДСТРОЙКА НЕ ДЕЛАЕТ
//
// Не повторяет тело, не меняет кода отказа и не трогает ни одного исхода, кроме
// `ABORTED` с объявленным синхронным текстом. Судится ПАРА: `ABORTED` с чужим
// текстом и чужой код с этим текстом проходят дословно. Одной половины было бы
// мало — у надстройки две возможности промахнуться, и каждая закрыта своим
// отрицательным сценарием.

import (
	"context"

	rpcstatus "google.golang.org/genproto/googleapis/rpc/status"
	"google.golang.org/grpc/codes"
	grpcstatus "google.golang.org/grpc/status"

	"github.com/PRO-Robotech/corelib/operations"

	iamerr "github.com/PRO-Robotech/kaname/internal/errors"
)

// TerminalRefusalRepo — репозиторий операций, выбирающий текст отказа по
// носителю. Всё, кроме записи терминального исхода, делегируется как есть.
type TerminalRefusalRepo struct {
	// FullRepo встроен целиком, а не узкий `Repo`: владение, финализатор
	// метаданных и уборщик терминальных строк нужны use-case'ам службы, и
	// корелиб отдаёт их НА КОМПИЛЯЦИИ намеренно — чтобы провязка не выпала
	// молча. Встроив узкий контракт, надстройка сломала бы сборку у тех
	// use-case'ов, а встроив его и починив сборку утверждением — вернула бы
	// ровно ту тишину, от которой корелиб уходил.
	operations.FullRepo
}

// terminalRefusalClaimingRepo — та же надстройка ПЛЮС проброс подтверждения
// живости. Отдельный тип, потому что объявить метод условно нельзя: тип либо
// несёт его всегда, либо не несёт никогда.
type terminalRefusalClaimingRepo struct {
	TerminalRefusalRepo
	claimer executionClaimer
}

// executionClaimer — форма опционального апгрейда, который исполнитель операций
// берёт типовым утверждением. Объявлен здесь ПОВТОРНО потому, что в корелибе он
// неэкспортируемый: назвать его чужим именем нельзя, а сопоставление интерфейсов
// в языке структурное — совпадения формы метода достаточно.
//
// Расхождение с оригиналом было бы тихим: надстройка перестала бы удовлетворять
// утверждению исполнителя, и подтверждение живости пропало бы без единого
// отказа. Держит согласие проба `TestTerminalRefusalRepoKeepsTheExecutionClaim`.
type executionClaimer interface {
	ClaimForExecution(ctx context.Context, id string) (live bool, err error)
}

// NewTerminalRefusalRepo оборачивает репозиторий операций, сохраняя все его
// апгрейды: подтверждение живости пробрасывается, когда обёрнутый его несёт.
func NewTerminalRefusalRepo(inner operations.FullRepo) operations.FullRepo {
	base := TerminalRefusalRepo{FullRepo: inner}
	if claimer, ok := inner.(executionClaimer); ok {
		return &terminalRefusalClaimingRepo{TerminalRefusalRepo: base, claimer: claimer}
	}
	return &base
}

var (
	_ operations.FullRepo = (*TerminalRefusalRepo)(nil)
	_ operations.FullRepo = (*terminalRefusalClaimingRepo)(nil)
	_ executionClaimer    = (*terminalRefusalClaimingRepo)(nil)
)

// MarkError записывает терминальный отказ, подменив текст СИНХРОННОЙ полосы
// текстом терминальной.
//
// Сверка по ПАРЕ (код и текст дословно), а не по одному признаку: сентинела на
// этом уровне уже нет — он потерян при переводе в статус, — поэтому различать
// приходится тем, что доехало. Пара делает подмену узкой: чужой `ABORTED` и
// чужой код с этим текстом проходят нетронутыми.
func (r *TerminalRefusalRepo) MarkError(ctx context.Context, id string, st *rpcstatus.Status) error {
	return r.FullRepo.MarkError(ctx, id, terminalRefusalStatus(st))
}

// ClaimForExecution пробрасывает подтверждение живости обёрнутому.
func (r *terminalRefusalClaimingRepo) ClaimForExecution(ctx context.Context, id string) (bool, error) {
	return r.claimer.ClaimForExecution(ctx, id)
}

// terminalRefusalStatus — сама подмена, вынесенная отдельно, чтобы её можно было
// предъявить входу без репозитория.
//
// Статус приходит ПРОТО-сообщением, а не оболочкой grpc: контракт репозитория
// объявлен на `google.rpc.Status`, и код в нём — число, а не типизированная
// константа. Приведение делается здесь, у единственного читателя.
//
// Пустой статус проходит нетронутым: он не тот вход, который надстройка судит, и
// падать на нём значило бы завести отказ там, где его не было.
func terminalRefusalStatus(st *rpcstatus.Status) *rpcstatus.Status {
	if st == nil {
		return nil
	}
	// Сравнение идёт в ЧИСЛАХ контракта, а не приведением кода сообщения к типу
	// оболочки: `GetCode()` отдаёт int32 из чужого сообщения, и приведение его к
	// беззнаковому — преобразование с переполнением на неподконтрольном значении.
	// Обратное направление сворачивается компилятором: `codes.Aborted` — константа.
	if st.GetCode() != int32(codes.Aborted) ||
		st.GetMessage() != iamerr.SerializationConflictSyncText {
		return st
	}
	return grpcstatus.New(codes.Aborted, iamerr.SerializationConflictTerminalText).Proto()
}
