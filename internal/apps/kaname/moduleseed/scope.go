package moduleseed

import "github.com/PRO-Robotech/kaname/internal/domain"

// scope.go — перевод якоря области из проволочной формы манифеста в вид
// объекта хранилища.
//
// # Почему перевод БЕРЁТСЯ, а не пишется здесь
//
// Отношение «проволочная форма ↔ голый вид» объявлено в домене ОДИН раз
// (`domain.ScopeTypeFromDotted`, словарь `scopeVocabulary`), и второе его
// перечисление разошлось бы с первым молча: ни компилятор, ни обзор диффа
// второго перечня не видят. Тот же довод записан у самого словаря — он уже
// сводил три места об этом предмете в одно.

// scopeKindOf — голый вид объекта по проволочной форме якоря.
//
// Второй результат — «форма не является якорем», а не «неизвестна»: якорем
// бывают ровно три яруса иерархии, и вид вне их — отказ применителя, потому что
// строка выдачи не на якоре не совпала бы ни с одним вопросом о доступе.
func scopeKindOf(dotted string) (string, bool) {
	return domain.ScopeTypeFromDotted(dotted)
}
