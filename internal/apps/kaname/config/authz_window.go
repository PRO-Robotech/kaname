package config

import "fmt"

// authz_window.go — страж окна отзыва СОБСТВЕННОЙ ДВЕРИ (задача продукта #2307).
//
// # Почему у этой величины нет умолчания
//
// Кешируется только ПОЛОЖИТЕЛЬНЫЙ вердикт, поэтому срок жизни записи и ЕСТЬ
// окно отзыва: столько субъект, у которого право уже отобрали, продолжает
// проходить. Это параметр безопасности, а не производительности, и выбирать его
// за оператора служба не вправе.
//
// Соседи по платформе это состояние отвергают стартом: дескриптор носителя
// (`pkg/servicecontract`) объявляет ровно тот же довод у своей оси окна и
// отказывает в пуске при неположительной величине. Собственная дверь службы
// строит кеш сама, минуя дескриптор, — значит и страж ей нужен свой.
//
// # Что здесь НЕ оспаривается
//
// Умолчание ПРОЦЕССА (`defaults.go`, `authz.cache-ttl`) закрывает незаданную
// ручку и остаётся. Оспаривается ЗАДАННЫЙ ноль: он объявлялся законным — «беру
// умолчание политики» — и уводил величину туда, где оператор её не выбирает.
//
// Для ВЫНЕСЕННОГО МОДУЛЯ это не стилистика. Служба резолвит фундамент пином
// (`services/iam/go.mod`, `replace` — ноль), поэтому величина, которую взял бы
// конструктор кеша при неположительной ручке, живёт в ЧУЖОЙ ревизии и меняется
// не правкой политики, а бампом пина. Совпадение сегодняшних значений (5s у
// пина и у дерева) этим никем не удерживается. Параметр безопасности, который
// нельзя изменить там, где он объявлен, — ничей.

// Validate отвергает неположительное окно отзыва собственной двери.
//
// Действует в ЛЮБОМ режиме, а не только в производственном: окно отзыва
// действует на всяком поднятом стенде, и «зелёный dev» маскирует именно это —
// величину, которую никто не выбирал.
//
// Сообщение называет НАСТРОЙКУ и ПРАВИЛО и не называет значения: текст отказа
// читает оператор посадки.
func (c AuthZConfig) Validate() error {
	if c.CacheTTL > 0 {
		return nil
	}
	return fmt.Errorf(
		"authz.cache-ttl не задано положительным — это ОКНО ОТЗЫВА собственной двери: " +
			"столько субъект, у которого право уже отобрали, продолжает проходить. " +
			"Умолчания у такой величины быть не может, и служба отказывается стартовать, " +
			"а не выбирает окно отзыва за оператора (для вынесенного модуля величина, " +
			"взятая молча, пришла бы вообще из чужой ревизии — фундамент резолвится пином)")
}
