// parsePortValue — голый номер порта либо отказ, называющий РУЧКУ и ПОЛУЧЕННОЕ
// значение.
//
// Отказ называет и то, и другое намеренно. Отказ, приходивший прежде, приходил
// от библиотеки на ОТКРЫТИИ слушателя — последним шагом старта, после того как
// процесс отчитался обо всей посадке, — и не говорил ни имени ручки, ни того,
// откуда взялось значение. Оператор видел адрес, которого не задавал, и
// следующего шага у него не было.
func parsePortValue(env, raw string) (string, error) {
	v := strings.TrimSpace(raw)
	n, err := strconv.Atoi(v)
	if err != nil || n < 1 || n > 65535 {
		hint := ""
		if form, collides := ClusterServiceLinkForm(env); collides {
			hint = fmt.Sprintf(" Имя %s совпадает с формой %s, которой Kubernetes сам "+
				"объявляет поду адреса служб своего пространства имён, — значение вида "+
				"`tcp://<адрес>:<порт>` приходит ОТ КЛАСТЕРА, а не от вас, и перебивает "+
				"заданное. Снять подстановку: `enableServiceLinks: false` в spec пода "+
				"(поставляемый чарт объявляет это сам).", env, form)
		}
		return "", fmt.Errorf("%s: получено %q — ожидается голый номер порта 1..65535, "+
			"например \"9091\".%s", env, raw, hint)
	}
	return strconv.Itoa(n), nil
}

// refuseCollidingFlatEnv проверяет ФОРМУ значения каждой плоской ручки, у
// которой она объявлена, и отвергает старт до любой сборки значений.
//
// Отказ стоит здесь, а не в посадочном страже, намеренно: величину читает
// ЛЮБОЙ двоичный файл службы, а не только тот, кто поднимает слушатель. В
// наблюдавшемся отказе накатчик миграций прошёл все миграции, процесс отчитался
// о посадке — и лишь затем упал на открытии слушателя. Отказ на разборе
// настроек называет предмет первому же, кто стартует.
func refuseCollidingFlatEnv(lookup func(string) (string, bool)) error {
	for _, k := range flatEnvKnobs {
		if k.Shape != shapePort {
			continue
		}
		raw, ok := lookup(k.Env)
		if !ok || strings.TrimSpace(raw) == "" {
			continue
		}
		if _, err := parsePortValue(k.Env, raw); err != nil {
			return err
		}
	}
	return nil
}
