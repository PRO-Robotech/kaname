// service_link_collision.go — ИМЯ РУЧКИ СЛУЖБЫ ПРОТИВ ИМЕНИ, КОТОРОЕ
// ПОДСТАВЛЯЕТ КЛАСТЕР.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Kubernetes объявляет каждому поду адреса всех служб своего пространства имён
// переменными окружения, и имя переменной он ВЫВОДИТ из имени службы: верхний
// регистр, дефис → подчёркивание. Служба `kaname-internal` даёт
// `KANAME_INTERNAL_PORT`, и значение у неё не порт, а `tcp://<адрес>:<порт>`.
//
// Корневой сегмент ВСЕХ переменных этой службы — `KANAME` (см. EnvPrefix), то
// есть тот же, что имя её собственной службы в кластере. Следствие: подстановка
// кластера попадает в СВОЁ ЖЕ пространство имён настроек и перебивает не
// умолчание, а то, что задал оператор.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО НЕ ЗАКРЫВАЕТСЯ ПРИСТАВКОЙ У ВСЕХ РУЧЕК
//
// Вложенные ключи защищены УЖЕ И BY CONSTRUCTION: viper выводит их имена с
// разделителем `__` (см. Load, SetEnvKeyReplacer), а кластер двойного
// подчёркивания не производит. Уязвимы ровно ПЛОСКИЕ имена — легаси-псевдонимы,
// у которых пути ключа нет и вывести имя не из чего.
//
// Смена корневого сегмента сняла бы столкновение и у тех 118 имён, которым он
// не нужен, ценой переименования КАЖДОЙ переменной службы: имя переменной,
// которое читает установка, есть внешне-адресуемая координата, и её смена
// ломает всякую уже настроенную установку. Плата несоразмерна предмету.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗДЕСЬ ОБЪЯВЛЕНО
//
//	ClusterServiceLinkForm — ГРАММАТИКА имён, которые подставляет кластер;
//	flatEnvKnobs           — ВСЕ плоские имена, которые читает загрузка, и
//	                         ФОРМА значения каждого;
//	parsePortValue         — положительная спецификация ручки порта.
//
// Объявление ОДНО: его читают и сборка значений (applyLegacyEnv), и текст
// отказа, и перепись гейта. Второй список разошёлся бы с первым молча.
package config

import (
	"fmt"
	"reflect"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// ─────────────────────────────────────────────────────────────────────────────
// ГРАММАТИКА ПОДСТАВЛЯЕМЫХ ИМЁН
//
// Формы взяты у самого кластера (kubelet, envvars.FromServices +
// makeLinkVariables). Перечень ПОЛНЫЙ намеренно: распознаватель, знающий не все
// законные формы записи предмета, не даёт ни красного, ни зелёного — он молчит,
// и всё записанное в незнакомой ему форме оказывается вне наблюдения.
//
// `<СЛУЖБА>` ниже — имя службы в верхнем регистре с дефисами, заменёнными на
// подчёркивания; `<ПОРТ>` — имя порта тем же преобразованием; `<N>` — номер
// порта; `<ПРОТО>` — TCP | UDP | SCTP.
var clusterServiceLinkForms = []struct {
	form string
	re   *regexp.Regexp
}{
	// Самые узкие формы стоят первыми: имя, подходящее под несколько, обязано
	// назваться той, которая его объясняет точнее.
	{"<СЛУЖБА>_PORT_<N>_<ПРОТО>_PROTO", regexp.MustCompile(`_PORT_[0-9]+_(TCP|UDP|SCTP)_PROTO$`)},
	{"<СЛУЖБА>_PORT_<N>_<ПРОТО>_PORT", regexp.MustCompile(`_PORT_[0-9]+_(TCP|UDP|SCTP)_PORT$`)},
	{"<СЛУЖБА>_PORT_<N>_<ПРОТО>_ADDR", regexp.MustCompile(`_PORT_[0-9]+_(TCP|UDP|SCTP)_ADDR$`)},
	{"<СЛУЖБА>_PORT_<N>_<ПРОТО>", regexp.MustCompile(`_PORT_[0-9]+_(TCP|UDP|SCTP)$`)},
	{"<СЛУЖБА>_SERVICE_PORT_<ПОРТ>", regexp.MustCompile(`_SERVICE_PORT_[A-Z0-9_]+$`)},
	{"<СЛУЖБА>_SERVICE_PORT", regexp.MustCompile(`_SERVICE_PORT$`)},
	{"<СЛУЖБА>_SERVICE_HOST", regexp.MustCompile(`_SERVICE_HOST$`)},
	{"<СЛУЖБА>_PORT", regexp.MustCompile(`_PORT$`)},
}

// ClusterServiceLinkForm — подставляет ли кластер переменную с таким именем.
//
// Отвечает ИМЕНЕМ ФОРМЫ и признаком совпадения. Судится только имя внутри
// корневого сегмента службы: столкновение возможно лишь там, где обе стороны
// адресуют одно пространство.
//
// Экспортируется затем, чтобы гейт класса, проба посадки и обход дерева
// спрашивали ОДИН распознаватель: второй разошёлся бы с первым молча — на
// верном входе оба отвечают одинаково.
func ClusterServiceLinkForm(name string) (string, bool) {
	if !strings.HasPrefix(name, EnvPrefix+"_") {
		return "", false
	}
	for _, f := range clusterServiceLinkForms {
		loc := f.re.FindStringIndex(name)
		if loc == nil {
			continue
		}
		// Слева от хвоста остаётся имя службы. Оно обязано начинаться корневым
		// сегментом — иначе подстановка попала бы в чужое пространство имён и
		// нашей ручки не касалась. Граница `>=` включает службу, названную РОВНО
		// корневым сегментом: `kaname` → `KANAME_PORT`.
		if loc[0] >= len(EnvPrefix) && strings.HasPrefix(name[:loc[0]], EnvPrefix) {
			return f.form, true
		}
	}
	return "", false
}

// ─────────────────────────────────────────────────────────────────────────────
// ФОРМА ЗНАЧЕНИЯ ПЛОСКОЙ РУЧКИ

// envValueShape — форма значения плоской ручки.
type envValueShape uint8

const (
	// shapeOpaque — произвольная строка: режим, длительность, имя, пароль.
	// Своей формы у величины нет, и проверять нечего.
	shapeOpaque envValueShape = iota
	// shapePort — ГОЛЫЙ номер порта, 1..65535. Спецификация положительная, а не
	// список запрещённого: «не схема://…» оставляла бы годными и `abc`, и
	// пустую строку, и `0`, — то есть отвергала бы известное и пропускала
	// остальное.
	shapePort
)

// flatEnvKnob — одна плоская (без `__`) переменная, которую читает загрузка.
type flatEnvKnob struct {
	// Env — имя переменной, как его задаёт оператор.
	Env string
	// Key — путь ключа настроек, который переменная перебивает. Пусто у тех,
	// чьё значение собирается вручную (поля адреса базы).
	Key string
	// Shape — форма значения.
	Shape envValueShape
}

// flatEnvKnobs — ВСЕ плоские имена переменных, которые читает загрузка
// настроек, в одном объявлении.
//
// Объявление одно намеренно: его читают сборка значений, текст отказа и
// перепись гейта. Плоские имена — легаси-псевдонимы: пути ключа у них нет,
// поэтому имя не выводится и обязано быть выписано; вложенные ключи здесь НЕ
// перечисляются — их имена viper выводит сам, и `__` в них делает столкновение
// с кластером невыразимым.
var flatEnvKnobs = []flatEnvKnob{
	{Env: "KANAME_DB_SSLMODE", Key: "repository.postgres.ssl-mode"},
	{Env: "KANAME_DB_MAX_CONNS", Key: "repository.postgres.max-conns"},
	{Env: "KANAME_GRPC_PORT", Key: "_legacy.grpc-port", Shape: shapePort},
	{Env: "KANAME_INTERNAL_PORT", Key: "_legacy.internal-port", Shape: shapePort},
	{Env: "KANAME_AUTH_MODE", Key: "authn.mode"},
	// Окно затирания ключа служебной учётки: чарт задаёт короткое плоское имя,
	// а не namespaced. Величина — длительность Go ("120s").
	{Env: "KANAME_SAKEY_REDACT_GRACE", Key: "authn.sakey-redact-grace"},
	// Окно затирания пользовательского токена — зеркало предыдущей.
	{Env: "KANAME_USERTOKEN_REDACT_GRACE", Key: "authn.usertoken-redact-grace"},
	// Дисциплина срока ключа служебной учётки. Длительности Go.
	{Env: "KANAME_SAKEY_DEFAULT_TTL", Key: "authn.sakey-default-ttl"},
	{Env: "KANAME_SAKEY_MAX_TTL", Key: "authn.sakey-max-ttl"},
	{Env: "KANAME_SAKEY_ACCESS_TOKEN_TTL", Key: "authn.sakey-access-token-ttl"},
	{Env: "KANAME_SAKEY_BIND_DPOP", Key: "authn.sakey-bind-dpop"},
	// Окно отзыва собственной двери. Длительность Go ("5s").
	{Env: "KANAME_AUTHZ_CACHE_TTL", Key: "authz.cache-ttl"},
	// Поля адреса базы: значение собирается вручную (см. applyLegacyEnv),
	// поэтому ключа у них нет. Имена берутся из общего объявления ниже.
	{Env: envDBHost},
	{Env: envDBPort, Shape: shapePort},
	{Env: envDBUser},
	{Env: envDBName},
}

// MTLSEnvNames — имена переменных, которые загрузка посадки транспорта выводит
// из полей своей структуры (`corecfg.LoadPrefixed`, теги `envconfig`).
//
// Выводятся здесь ПОВТОРНО, и это названо честно: правило вывода принадлежит
// общему фундаменту, а не этой службе, поэтому расхождение возможно. Оно
// закреплено с одного конца — перепись гейта класса требует, чтобы хотя бы одно
// выведенное здесь имя ДОЕЗЖАЛО до своего поля через `LoadMTLS`. Без этого якоря
// перепись считала бы имена, которых процесс не читает, и «ноль совпадений»
// означало бы «считал не то».
//
// Имена нужны переписи затем, что они ПЛОСКИЕ: у полей посадки транспорта нет
// пути ключа настроек, поэтому `__` их не защищает, и грамматика кластера
// обязана быть спрошена и у них.
func MTLSEnvNames() []string {
	var out []string
	walkEnvconfigNames(reflect.TypeOf(MTLSConfig{}), EnvPrefix, &out)
	sort.Strings(out)
	return out
}

func walkEnvconfigNames(tp reflect.Type, prefix string, out *[]string) {
	if tp.Kind() != reflect.Struct {
		return
	}
	for i := 0; i < tp.NumField(); i++ {
		f := tp.Field(i)
		seg := f.Tag.Get("envconfig")
		if seg == "" {
			seg = strings.ToUpper(f.Name)
		}
		name := prefix + "_" + seg
		if f.Type.Kind() == reflect.Struct {
			walkEnvconfigNames(f.Type, name, out)
			continue
		}
		*out = append(*out, name)
	}
}

// EnvNameOfKey — имя переменной окружения, которое viper ВЫВОДИТ из пути ключа
// настроек.
//
// Экспортируется затем, чтобы перепись гейта выводила имена ТЕМ ЖЕ правилом,
// каким их выводит процесс (см. envNameOf и SetEnvKeyReplacer в Load): второй
// вывод разошёлся бы с первым молча — на верном входе оба отвечают одинаково.
func EnvNameOfKey(key string) string { return envNameOf(key) }

// flatKnobCollisionFindings — СУЖДЕНИЕ по перечню плоских ручек, отделённое от
// объявления службы.
//
// Отделено намеренно: мера, чью способность падать нельзя предъявить иначе как
// поломкой настоящего объявления, доказательства не имеет. Инъекция зовёт то же
// суждение на своём перечне, меняя против законного близнеца РОВНО ОДИН факт.
//
// Находка — ручка, чьё имя кластер производит, а формы значения у неё не
// объявлено: подстановка кластера перебьёт величину оператора молча.
func flatKnobCollisionFindings(knobs []flatEnvKnob) []string {
	var findings []string
	for _, k := range knobs {
		form, collides := ClusterServiceLinkForm(k.Env)
		if !collides || k.Shape != shapeOpaque {
			continue
		}
		findings = append(findings, fmt.Sprintf("%s: имя совпадает с формой %s, которой "+
			"кластер сам объявляет поду адреса служб своего пространства имён, а форма "+
			"значения у ручки НЕ ОБЪЯВЛЕНА — подстановка кластера перебьёт величину "+
			"оператора молча. Исходы: объявить форму значения либо перевести ручку на путь "+
			"ключа настроек (его имя viper выводит с `__`, а кластер двойного подчёркивания "+
			"не производит)", k.Env, form))
	}
	return findings
}

// FlatEnvKnobNames — плоские имена, которые читает загрузка, выведенные из
// объявления выше.
//
// Экспортируется для обхода дерева: он спрашивает, нет ли в исходниках плоского
// имени, подставляемого кластером, о котором загрузка не объявила ФОРМУ
// значения. Второй список там разошёлся бы с этим молча.
func FlatEnvKnobNames() []string {
	out := make([]string, 0, len(flatEnvKnobs))
	for _, k := range flatEnvKnobs {
		out = append(out, k.Env)
	}
	return out
}

// FlatEnvKnobGuardsItsValue — объявлена ли у плоской ручки форма значения, то
// есть отвергает ли загрузка подстановку кластера вместо величины оператора.
func FlatEnvKnobGuardsItsValue(name string) (declared, guarded bool) {
	for _, k := range flatEnvKnobs {
		if k.Env == name {
			return true, k.Shape != shapeOpaque
		}
	}
	return false, false
}

