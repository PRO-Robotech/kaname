// invite.go — величины ПРИГЛАШЕНИЯ как нашей сущности (приёмка ID-MAIL-1,
// §10 пп. 10 и 22).
//
// # СРОК ЕСТЬ ВСЕГДА, И ЗНАЧЕНИЯ «БЕЗ СРОКА» В СЛОВАРЕ РУЧКИ НЕТ
//
// Умолчание непустое и положительное — по той же причине, по какой непустым
// объявлено ограничение частоты (Р14): незаданная величина означала бы «не
// ограничиваем», то есть приглашение, выкупаемое навсегда. Молчащий профиль
// ограничение НЕ снимает.
//
// Непозитивная величина — ОТКАЗ СТАРТА, а не подстановка умолчания. Различие
// несущее: молчание профиля есть согласие с умолчанием, а объявленный ноль есть
// попытка снять ограничение — и она обязана быть отвергнута там, где её видно,
// а не обращена в разумное значение молча.
//
// # ОТЛИЧИЕ ОТ ВЕЛИЧИН ОТПРАВИТЕЛЯ (invite_mail.go)
//
// Там — узел, отправитель и удостоверение: у них умолчаний НЕТ, потому что
// пустой адрес даёт наблюдаемый отказ. Здесь наоборот: незаданный срок тишины
// не даёт — он даёт бессрочно выкупаемое приглашение, и заметить это нельзя
// ничем. Поэтому умолчание есть, и оно консервативно.
package config

import (
	"fmt"
	"time"
)

// defaultInviteTTL — срок строки приглашения.
//
// ВЕЛИЧИНА НАЗВАНА РЕШЕНИЕМ, А НЕ ВЫБРАНА НАУГАД. Приглашение выкупается
// первым входом человека, а первый вход требует, чтобы человек прочёл письмо,
// завёл вход и подтвердил адрес. Неделя переживает отпуск выходного дня и
// рабочую неделю целиком, но не переживает смену состава команды — то есть
// закрывает ровно тот случай, ради которого срок и заведён: приглашение,
// о котором забыли обе стороны.
//
// ПРЕДИКАТ ПЕРЕСМОТРА — доля клетки `expired` счётчика активаций. Систематически
// истекающие приглашения при живой доставке означают, что окно мало; ноль
// истёкших за квартал — что велико и класс оно не закрывает.
const defaultInviteTTL = 7 * 24 * time.Hour

// InviteConfig — секция `invite`.
//
//	TTL — срок строки приглашения: после него активация отвергается.
type InviteConfig struct {
	TTL time.Duration `mapstructure:"ttl"`
}

// TTLOrDefault — срок, под которым выдаётся приглашение.
//
// Незаданная величина (нулевая) читается как «профиль о сроке не высказался» и
// заменяется умолчанием. ОТРИЦАТЕЛЬНУЮ и явно нулевую отвергает Validate: сюда
// они не доезжают, а если доедут мимо рендера — старт не состоится.
func (c InviteConfig) TTLOrDefault() time.Duration {
	if c.TTL <= 0 {
		return defaultInviteTTL
	}
	return c.TTL
}

// Validate — страж величин приглашения.
//
// Отрицательная величина отвергается; НУЛЕВАЯ читается как «не объявлено» и
// проходит — её заменяет умолчание. Различить «профиль промолчал» и «профиль
// написал ноль» разбор настроек не умеет: обе формы дают нулевое значение поля,
// и требовать отказа на первой значило бы требовать отказа при молчании
// профиля, то есть сделать ручку обязательной у каждой посадки. Снять
// ограничение профиль при этом не может ничем: значения, означающего «без
// срока», в словаре ручки не существует вовсе.
func (c InviteConfig) Validate() error {
	if c.TTL < 0 {
		return fmt.Errorf(
			"invite.ttl must not be negative (got %s) — it is the deadline of an invite row, "+
				"and there is no value meaning «no deadline»: an invite redeemable forever is "+
				"the very defect this knob removes", c.TTL)
	}
	return nil
}
