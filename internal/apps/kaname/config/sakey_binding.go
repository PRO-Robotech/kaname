// sakey_binding.go — предикат «контур выдачи ключей переведён» и страж старта
// над требованием связанного с отправителем токена (задача #1137).
package config

import "fmt"

// SAKeyIssuanceIsOurs — переведён ли контур выдачи ключей служебных учёток на
// свою чеканку.
//
// Тот же предикат решает выдачу ключевой пары ЧЕЛОВЕКА (задача kaname#547):
// её обменивает тот же эндпоинт, и сборка токенов человека спрашивает его же
// через ту же точку корня (`saKeyIssuanceIsOurs`), а не второе чтение ручки.
//
// ПРЕДИКАТ ЖИВЁТ ЗДЕСЬ, А НЕ В СБОРКЕ, потому что читателей у него ТРИ и они в
// разных пакетах: композиционный корень выбирает по нему полосу выдачи, страж
// старта — ниже — по нему же решает, есть ли у соседней ручки читатель, а
// строка таблицы требований полос не пускает посадку `own` с непереведённым
// контуром (задача #337, lane_requirements.go). Копии одного условия разошлись
// бы молча, и разошлись бы именно там, где расхождение не видно: все отвечают
// одинаково на всяком входе, кроме изменившегося.
//
// Само условие — ЭНДПОИНТ ОБМЕНА, а не подписант. Ключ предъявляет подписанное
// утверждение внешний вызывающий, и обменивает он его на нашем токен-эндпоинте;
// подписант без эндпоинта дал бы ключ, которому некуда пойти. Настройка при этом
// требует включённой чеканки от включённого эндпоинта
// (`ClientTokenConfig.Validate`), поэтому «эндпоинт включён» влечёт «подписант
// есть», а не наоборот.
func (c Config) SAKeyIssuanceIsOurs() bool { return c.AuthN.ClientToken.Enabled }

// validateMachineTokenBinding — требование связанного с отправителем токена и
// переведённый контур выдачи несовместимы, и это говорится на старте.
//
// # Что здесь измеряется
//
// У `authn.sakey-bind-dpop` был ровно один читатель: регистрация клиента у
// прежнего издателя (`dpop_bound_access_tokens`, RFC 9449 §5.2). Регистрации
// выдача больше не заводит ни на одной посадке (kaname#362) — значит величина
// не читается ничем, и включивший её оператор на переведённом контуре получил
// бы стенд, где машинные токены НЕ связаны, при полной уверенности в обратном.
// На непереведённом контуре ключевая пара и федеративный ключ не выдаются
// вовсе (выдача отказывает с именем `authn.client-token.enabled`), и ключа,
// связанного лишь по убеждению оператора, там не возникает.
//
// # Почему это отказ, а не тихое умолчание
//
// Тихо проигнорировать половину контроля безопасности — ровно тот класс, что
// «принято-и-проигнорировано»: возможность объявлена, задокументирована, покрыта
// настройкой и не работает ни при каком входе. Отказ в старте виден сразу и
// называет обе настройки; неисполненный контроль не виден никогда.
//
// # Почему не снята ручка целиком
//
// Её эмитирует чарт платформы (kacho:
// deploy/helm/umbrella/charts/kaname/templates/deployment.yaml,
// KANAME_SAKEY_BIND_DPOP): снятая здесь раньше, чем там, ручка перестала бы
// читаться молча — вместо отказа старта оператор получил бы тишину. Снимается
// тем изменением, которым её перестанет эмитировать чарт.
//
// # Границы: что этот страж НЕ утверждает
//
// Он не говорит, что связанные токены на своей полосе невозможны. Он говорит,
// что СЕГОДНЯ их нечем потребовать: выпуск связывает токен по фактически
// предъявленному доказательству владения, а требования на ключе не несёт.
// Появится приём доказательства на токен-эндпоинте — появится и требование, и
// тогда этот страж заменяется на его проверку, а не снимается.
func (c Config) validateMachineTokenBinding() error {
	if !c.AuthN.SAKeyBindDPoP || !c.SAKeyIssuanceIsOurs() {
		return nil
	}
	return fmt.Errorf(
		"authn.sakey-bind-dpop is set while authn.client-token.enabled is set — " +
			"the sender-constrained requirement is registered on the provider's mirror of the key, " +
			"and a translated contour registers no mirror, so the knob has no reader at all: " +
			"the control would be declared and enforced by nothing")
}
