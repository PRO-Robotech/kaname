package modulecatalog

// prune.go — РЕШЕНИЕ по третьей проекции правила (задача продукта #1942).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО БЫЛО НЕВЕРНО
//
// Правило роли проецируется в ТРИ места. У двух референт держится КЛЮЧОМ
// (`role_rule_ref_res_fk`, `role_verb_type_fk`), поэтому снятие строки каталога
// их роняет — и применитель переселяет их тем же оператором. У третьей — массива
// точечных типов в строке `role_rule_selectors` — ключа нет и быть не может:
// внешний ключ на ЭЛЕМЕНТ массива в Postgres невыразим. Её референт держит
// триггер НА ВХОДЕ; снятие строки каталога он не судит.
//
// Пока строки каталога снимала только применённая миграция, остаток закрывал
// человек. С применителем снятие стало ГЛАГОЛОМ, у которого автора-человека рядом
// нет, и остаток стал дефектом: селектор продолжает называть снятый тип, а узнают
// об этом при СЛЕДУЮЩЕЙ записи селектора — отказом, к правившему отношения не
// имеющим.
//
// ─────────────────────────────────────────────────────────────────────────────
// РЕШЕНИЕ: ТРЕТЬЯ ПРОЕКЦИЯ ПРИВОДИТСЯ К КАТАЛОЖНОМУ ФАКТУ
//
// Применитель, снявший строку ресурса, тем же оператором вырезает её из
// `object_types` селекторов АРЕНДАТОРСКИХ ролей.
//
// Соблазн назвать это «молчаливым сужением права» велик, и три прежде
// рассмотренных исхода на нём и споткнулись. Он неверен, и неверен ПО-РАЗНОМУ у
// двух видов правила — поэтому оба названы порознь:
//
//	точечное правило   — арендатор назвал тип сам. Факт отбора УЖЕ ЗАПИСАН:
//	                     вторая проекция того же правила переселена в
//	                     `role_grant_orphan` (источник `rule_ref`) в ЭТОЙ ЖЕ
//	                     транзакции. Третья приводится к записанному, а не
//	                     отбирает что-то сверх — и третьей популяции закрытому
//	                     набору не требуется.
//
//	подстановочное     — массив собран ДОСЕВОМ как рендер платформенного набора
//	                     типов (`AllMaterializableTypes`), а не выбором
//	                     арендатора. Набор платформы сузился сам; вырезание
//	                     возвращает массив к тому, что дал бы свежий досев.
//	                     Отбирать нечего by construction.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ НЕ ОСТАЛЬНЫЕ ТРИ ИСХОДА
//
//  1. **переселить строку целиком в сироты** — у строки селектора нет пары
//     «тип + глагол», которой сироты адресуются; переселять нечем;
//  2. **отвергнуть применение при живой ссылке** — «спросить, затем снять» есть
//     software check-then-act (запрет #10), и под конкуренцией он не держится;
//  3. **оставить как есть** — исходом не является (запрет #11): состояние
//     наблюдается отказом, к правившему отношения не имеющим.
//
// Отдельно: сам выбор «вырезать элементы, а строку без единого живого типа
// снять» здесь не изобретён — его ВЫПОЛНИЛ ЧЕЛОВЕК двумя отдельными шагами
// миграции `0074`, ровно по этому признаку и с этим же доводом (снести строку
// целиком там, где живые типы остались, значило бы унести их материализацию).
// Применитель делает то же самое глаголом, потому что автора-человека рядом с
// глаголом нет.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОРЯДОК — ПОСЛЕ СНЯТИЯ, И ЭТО НЕСУЩЕЕ
//
// Вырезание оставляет в массиве только элементы, называющие ЖИВУЮ строку
// каталога. Отсюда два следствия, и оба нужны:
//
//   - поставь его ПЕРЕД снятием — снимаемая строка ещё жива, и уцелеет ровно тот
//     элемент, ради которого вырезание и делается;
//   - фильтр «оставить живое» делает операцию безопасной ДЛЯ ТРИГГЕРА by
//     construction: строка после правки состоит только из живых типов, поэтому
//     `role_rule_selectors_types_live` её принимает. Вырезай мы лишь «снятое
//     этим применением», строка с ранее повисшим элементом была бы отвергнута
//     триггером — и применитель отказал бы по причине, которой в манифесте нет и
//     которую оператору нечем починить.
//
// ТРОГАЮТСЯ при этом только строки, ПЕРЕСЕКАЮЩИЕСЯ со снятыми ресурсами: предмет
// вырезания есть снятие, а не таблица целиком. Иначе всякий подъём службы правил
// бы селекторы всех арендаторов.
//
// СИСТЕМНЫЕ РОЛИ не трогаются — по тому же доводу, что и у переселения: роль
// системного яруса объявлена манифестом, и если манифест снимает ресурс, который
// его же роль называет, то манифест противоречит сам себе; это обязано быть
// отвергнуто ключом, а не улажено молчаливой правкой роли, которую применитель не
// объявлял.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО РЕШЕНИЕ НЕ ЗАКРЫВАЕТ — НАЗВАНО, А НЕ УМОЛЧАНО
//
// Остаётся окно ОДНОВРЕМЕННОСТИ: транзакция, пишущая селектор ровно в тот момент,
// когда другая снимает строку каталога. Её триггер читает каталог по своему
// снимку и видит строку живой; вырезание чужой незакоммиченной строки не видит.
// Обе коммитятся — селектор остаётся называть снятый тип.
//
// Это ПЕРЕКОС ЗАПИСИ (write skew), и закрывается он только общим замком: строчной
// блокировкой на стороне триггера либо сериализуемым уровнем. Первое — правка
// применённой миграции, то есть НОВАЯ миграция и отдельный предмет; второе меняет
// уровень изоляции всей записи. Ни того, ни другого это изменение не делает и
// делать не вправе.
//
// Окно ОГРАНИЧЕНО и СХОДИТСЯ: вырезание идёт на КАЖДОМ применении, а применение
// идёт на каждом подъёме, поэтому строка, проскочившая окно, приводится следующим
// применением. Предмет и предикат — задача продукта #1985.
//
// Отдельно: строки, повисшие ДО заведения применителя, приводятся тем же
// оператором — но только те, что пересекаются со снятым сейчас. Сплошного
// приведения таблицы это изменение не делает: у него другой предмет и другая
// цена.
