package modulecatalog

// confirm.go — ПОДТВЕРЖДЕНИЕ применения и ПОТОЛКИ последствий: вход, который
// глагол требует, а путь старта не имеет (задача продукта #1034, приёмка §2.5 и
// §2.6).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОДТВЕРЖДЕНИЕ — ОТПЕЧАТОК СОСТОЯНИЯ МОДУЛЯ, А НЕ СЧЁТЧИК РЕВИЗИИ
//
// Счётчик ревизии в этом дереве отвергнут решением с предикатом переоткрытия
// («требование догнать каталог дельтой от потребителя ВНЕ iam»); потребитель
// подтверждения — `Plan` той же службы того же сервиса, значит отвержение в
// силе. Вместо счётчика — непрозрачная строка, производная от строк каталога
// ЭТОГО модуля. Контракт для вызывающего — ТОЛЬКО РАВЕНСТВО: строка не
// разбирается, её алгоритм есть деталь реализации и живёт у писателя.
//
// # Чему подтверждение чувствительно и чему слепо — ВЫВЕДЕНО, а не выбрано
//
//	входит      строки `catalog_module` / `catalog_resource` / `catalog_verb`
//	            этого модуля ровно теми колонками, которые читает `WHERE`
//	            писателя, плюс ключи снятия
//	НЕ входит   `retired_reason` / `retired_at` / `superseded_by` — исхода
//	            применения не меняют, ни один `WHERE` их не читает
//	НЕ входит   ТРИ проекции правила роли (`role_rule_ref`, `role_verb`,
//	            `role_rule_selectors`) — их двигает ЛЮБОЙ арендатор циклом
//	            создания и удаления роли, и подтверждение протухало бы от
//	            действия, к каталогу отношения не имеющего. Отдельно и решающе:
//	            арендаторский писатель этих таблиц замка каталога НЕ БЕРЁТ
//	            вовсе, поэтому «CAS» по ним был бы формой без содержания
//
// Отпечаток подтверждения и шеститабличный отпечаток пробы атомарности — РАЗНЫЕ
// предикаты: у пробы предмет «изменилось ли хоть что-нибудь», у подтверждения —
// «сделает ли применение что-то иное, чем показал план». Сведя их в один
// помощник, мы внесли бы рефакторингом ровно тот случай, который запрещён.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОТОЛКОВ ДВА, ПО ЧИСЛУ ПОПУЛЯЦИЙ ПЕРЕСЕЛЕНИЯ — И ТРЕТЬЯ ИХ НЕ ПОЛУЧАЕТ
//
// Отпечаток стережёт СОСТОЯНИЕ каталога и не стережёт ЧИСЛО переселяемых
// проекций: строки каталога обратимы (следующее применение их оживит), права
// арендатора — нет. Поэтому у необратимого своя пара чисел.
//
// Пара, а не сумма: «право отобрано» (`role_verb`) и «правило перестало
// резолвиться» (`role_rule_ref`) — разные события для того, кто разбирает
// последствия, и один потолок на сумму позволил бы обменять одно на другое
// молча.
//
// ТРЕТЬЯ популяция (вырезание типов из селекторов) потолка НЕ получает, и это
// решение с доводом, а не упущение: её число не принадлежит решению оператора
// (в счёт входят последствия ЧУЖИХ прежних снятий), упереться в потолок можно
// не изменив ничего, а отказ по такому потолку СОХРАНЯЕТ поломку — висячий
// элемент делает строку неприемлемой для триггера живости, то есть арендатор не
// может её править, пока висяк не вырезан. Потолок, отвергнув применение,
// оставил бы и висяк, и запрет правки: запретил бы ПОЧИНКУ, ничего не защитив.
// Вместо потолка у третьей популяции — ВИДИМОСТЬ: три величины в переписи и в
// следе аудита (`audit.go`).

import (
	"errors"
	"fmt"

	"github.com/PRO-Robotech/kaname/internal/manifest"

	"github.com/PRO-Robotech/kaname/internal/apps/kaname/seed"
)

var (
	// ErrExpectedStateRequired — глагол позван без подтверждения.
	//
	// Отказ, а не «применить как есть»: подтверждение и есть то, чем `Plan`
	// связан с `Apply`, и применение без него означает «сделай что-нибудь», а
	// не «сделай то, что я видел».
	ErrExpectedStateRequired = errors.New("modulecatalog: expected_state: required")
	// ErrLimitRequired — потолок последствий не назван.
	//
	// ОТСУТСТВИЕ отличимо от НУЛЯ намеренно: ноль — законное и самое частое
	// значение подтверждения («это применение не отберёт ни одной проекции»).
	// Не будь присутствия отдельным от значения, ноль означал бы «не задано», а
	// «не задано» означает «не сужаем».
	ErrLimitRequired = errors.New("modulecatalog: resettle ceiling: required")
	// ErrStateMoved — каталог модуля сдвинулся с момента плана.
	//
	// Приходит ВНУТРИ транзакции, сразу после замка, и роняет её до коммита.
	ErrStateMoved = errors.New("modulecatalog: the module catalog moved since the plan was produced")
	// ErrResettleCeilingExceeded — превышен потолок популяции переселения.
	ErrResettleCeilingExceeded = errors.New("modulecatalog: resettle ceiling exceeded")
)

// Request — вход применения ГЛАГОЛОМ.
//
// Тип, а не три аргумента: подтверждение и оба потолка суть ОДИН вход, и
// вызывающий, назвавший два из трёх, обязан получить отказ по имени поля, а не
// собрать вызов, который компилируется и означает не то.
//
// Пути СТАРТА этого типа не полагается вовсе: подтверждения там нет by
// construction (доставка применяется целиком, плана не было), а потолок
// последствий на старте означал бы отказ ПУСКА за долг, которого оператор не
// делал.
type Request struct {
	// Manifest — доставленный манифест модуля.
	Manifest *manifest.Manifest
	// ExpectedState — отпечаток состояния модуля, который показал `Plan`.
	// Пустая строка — не «любое состояние», а отсутствие подтверждения, и она
	// отвергается.
	ExpectedState string
	// MaxResettledRuleRefs — потолок ПЕРВОЙ популяции переселения: сколько
	// объявлений правила роли применение вправе переселить в сироты.
	// `nil` ⇒ отказ (см. ErrLimitRequired).
	MaxResettledRuleRefs *int
	// MaxResettledRoleVerbs — потолок ВТОРОЙ популяции: сколько выдач глаголов
	// применение вправе переселить. `nil` ⇒ отказ.
	MaxResettledRoleVerbs *int
	// Anchor — ОПОРА паритета, против которой сверяется произведённое состояние
	// (задача #1861).
	//
	// Едет ЗАПРОСОМ, а не полем применителя: применитель один на процесс, а
	// запросов у него много одновременно, и опора, положенная в него, менялась
	// бы под соседним вызовом. Нулевое значение = опора одного образа, то есть
	// САМАЯ УЗКАЯ: забытая опора сужает допуск до сегодняшнего, а не открывает
	// его.
	Anchor seed.Anchor
}

// confirmation — проверенный вход глагола.
//
// Отдельный неэкспортируемый тип, а не `Request` напрямую: `Request` — то, что
// прислал вызывающий, `confirmation` — то, что прошло проверку. Полоса старта
// получает `nil`, и это выразимо только здесь.
type confirmation struct {
	expectedState         string
	maxResettledRuleRefs  *int
	maxResettledRoleVerbs *int
	anchor                seed.Anchor
}

// validate приводит вход глагола к проверенному виду.
//
// Отказ называет ПОЛЕ, а не «неверный запрос»: вызывающий чинит вход, а не
// гадает, какого из трёх не хватает.
func (r Request) validate() (*confirmation, error) {
	if r.Manifest == nil {
		return nil, fmt.Errorf("%w: manifest: required", ErrDerive)
	}
	if r.ExpectedState == "" {
		return nil, fmt.Errorf("%w: подтверждение обязательно — повторите `Plan` и "+
			"пришлите показанное им состояние", ErrExpectedStateRequired)
	}
	if r.MaxResettledRuleRefs == nil {
		return nil, fmt.Errorf("%w: max_resettled_rule_refs: required — ноль есть законное "+
			"значение («ни одного объявления правила не переселять») и потому не может "+
			"означать «не задано»", ErrLimitRequired)
	}
	if r.MaxResettledRoleVerbs == nil {
		return nil, fmt.Errorf("%w: max_resettled_role_verbs: required — ноль есть законное "+
			"значение («ни одной выдачи не переселять») и потому не может означать "+
			"«не задано»", ErrLimitRequired)
	}
	if *r.MaxResettledRuleRefs < 0 || *r.MaxResettledRoleVerbs < 0 {
		return nil, fmt.Errorf("%w: потолок отрицательным не бывает: "+
			"max_resettled_rule_refs=%d max_resettled_role_verbs=%d",
			ErrLimitRequired, *r.MaxResettledRuleRefs, *r.MaxResettledRoleVerbs)
	}
	return &confirmation{
		expectedState:         r.ExpectedState,
		maxResettledRuleRefs:  r.MaxResettledRuleRefs,
		maxResettledRoleVerbs: r.MaxResettledRoleVerbs,
		anchor:                r.Anchor,
	}, nil
}

// checkCeilings сверяет фактическое переселение с названными потолками.
//
// Сверка идёт ВНУТРИ транзакции, до коммита: превышение обязано откатывать
// применение целиком, а не сообщаться после того, как права уже отобраны.
// Отказ называет ПОПУЛЯЦИЮ, её потолок и фактическое число — оператор чинит
// вход, а не гадает, какая из двух.
func (c *confirmation) checkCeilings(rep Report) error {
	if c == nil {
		return nil
	}
	if rep.Resettled.RuleRefs > *c.maxResettledRuleRefs {
		return fmt.Errorf("%w: объявлений правила переселено бы %d при потолке %d "+
			"(max_resettled_rule_refs); применение отвергнуто до коммита",
			ErrResettleCeilingExceeded, rep.Resettled.RuleRefs, *c.maxResettledRuleRefs)
	}
	if rep.Resettled.RoleVerbs > *c.maxResettledRoleVerbs {
		return fmt.Errorf("%w: выдач глаголов переселено бы %d при потолке %d "+
			"(max_resettled_role_verbs); применение отвергнуто до коммита",
			ErrResettleCeilingExceeded, rep.Resettled.RoleVerbs, *c.maxResettledRoleVerbs)
	}
	return nil
}

// Limit — потолок значением, пригодным для `Request`.
//
// Помощник существует затем, чтобы вызывающему не приходилось заводить
// переменную ради адреса: `&0` в Go невыразимо, а `Limit(0)` читается как
// «ноль назван», что и есть предмет присутствия, отличимого от нуля.
func Limit(n int) *int { return &n }
