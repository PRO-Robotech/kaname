package membership

// create.go — MembershipService.Create: порт создания членства и его вход.
//
// # Где живёт сам поток и почему не здесь
//
// Создание членства — это ПЕРЕЕЗД глагола приглашения на ресурс членства
// (IAM-ID-1 §4, S3.2): контракт меняется, поток — нет. Транзакция приглашения
// (строка человека под глобальным ключом почты, членство в названном аккаунте,
// необязательная выдача на проект, со-коммит указателей журнала и письма) живёт
// в `user.InviteUserUseCase` и до стадии S4 обслуживает ОБА глагола. Второй
// экземпляр того же потока здесь был бы вторым местом об одном предмете, и
// разошлись бы они молча — на первом же изменении семантики приглашения.
//
// Поэтому этот пакет объявляет ПОРТ и ВХОД, а реализует их поток приглашения;
// композиционный корень провязывает одно с другим. Направление зависимости —
// «поставщик реализует порт потребителя»: `user` импортирует этот пакет, не
// наоборот. После S4, когда `UserService.Invite` будет снят, поток переезжает
// сюда целиком, и порт остаётся тем же.
//
// # Что решает транспорт — ничего
//
// Отказы формы (пустой или негодный аккаунт, негодная почта, пара проект/роль
// наполовину), проверка права приглашать и чеканка операции — предмет потока,
// и все они СИНХРОННЫ, до операции. Обработчик разбирает запрос, зовёт порт и
// переводит ответ; кодов он не переводит и не глотает.

import (
	"context"

	"github.com/PRO-Robotech/corelib/operations"

	"github.com/PRO-Robotech/kaname/internal/domain"
)

// CreateInput — вход создания членства, разобранный из `CreateMembershipRequest`.
type CreateInput struct {
	// AccountID — аккаунт, в который приглашают. ОБЯЗАТЕЛЕН: это объект, про
	// который спрашивают модель прав, и половина пары, из которой выводится
	// идентификатор членства.
	AccountID domain.AccountID
	// Email — почта приглашаемого. ОБЯЗАТЕЛЬНА; арбитр — глобальный ключ почты:
	// известному человеку строка не заводится, добавляется членство.
	Email domain.Email
	// DisplayName — имя для СВЕЖЕЙ строки; пусто — локальная часть почты.
	// Известному человеку имя этим полем не переписывается.
	DisplayName domain.DisplayName
	// ProjectID / RoleID — необязательная пара выдачи на проект аккаунта,
	// атомарной с членством. Либо оба, либо ни одного.
	ProjectID domain.ProjectID
	RoleID    domain.RoleID
}

// Creator — порт создания членства.
//
// Отвечает операцией: metadata — `CreateMembershipMetadata`, response —
// `Membership`. Отказы формы и прав — синхронные, до чеканки операции.
type Creator interface {
	CreateMembership(ctx context.Context, in CreateInput) (*operations.Operation, error)
}
