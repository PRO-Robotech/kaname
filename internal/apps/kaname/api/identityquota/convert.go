package identityquota

import (
	iamv1 "github.com/PRO-Robotech/kacho/pkg/api/kaname/cloud/iam/v1"

	"github.com/PRO-Robotech/kacho/pkg/quota/quotaread"
)

// Перевод строк учёта в СВОЙ контракт службы доступа.
//
// # Почему свой, а не общий `pkg/quota/quotapb`
//
// Общий перевод существует ради того, чтобы владельцы ресурсов не разошлись в
// диалекты одних и тех же трёх чисел, и это верно для них. Служба доступа таким
// владельцем быть перестаёт: её потолок — самозащита, объявленная посадкой, а не
// величина, назначенная авторитетом. Заимствуя общий перевод, публичный контракт
// самостоятельного продукта не собирался бы без пакета учёта платформы — и пакет
// нельзя было бы снять, пока этот импорт жив (решение `Д9`, `kacho#2362`).
//
// Это ЗЕРКАЛО довода, которым платформа уже воспользовалась в этом самом месте:
// общая форма перестала брать арму области из контракта службы доступа именно
// затем, чтобы её собственная сборка не зависела от контракта, который предстоит
// снять.
//
// # Что от этого НЕ меняется, и это проверяется, а не обещается
//
// Имена и номера полей, имена и номера арм — прежние дословно, поэтому ни провод,
// ни JSON не изменились ни на байт. Держит это не аккуратность, а согласие двух
// объявлений, проверяемое разбором дескрипторов: `TestIdentityQuotaShapeMatchesThePlatformShapeVerbatim`.
//
// # Решение, а не механика — и оно то же самое
//
// Неопознанная область отображается в `SCOPE_UNSPECIFIED`, а НЕ в `DEFAULT`:
// умолчание есть утверждение «величина платформенная», и делать его на строке,
// которую не удалось прочитать, значит выдавать незнание за факт.

// quotas переводит строки учёта в сообщения контракта, сохраняя порядок.
//
// Возвращается НЕ nil на пустом входе: разница видна на проводе (`[]` против
// отсутствия поля), а обещание контракта про пустой массив сделано в самом
// контракте — нарушать его переводом было бы нечестно вдвойне.
func quotas(states []quotaread.State) []*iamv1.Quota {
	out := make([]*iamv1.Quota, 0, len(states))
	for _, st := range states {
		out = append(out, &iamv1.Quota{
			Kind:          st.Kind,
			Limit:         st.Limit,
			Used:          st.Used,
			SourceScope:   scope(st.SourceScope),
			SourceScopeId: st.SourceScopeID,
			CarrierType:   st.CarrierType,
			CarrierId:     st.CarrierID,
		})
	}
	return out
}

// scope переводит область из строки хранения в перечисление контракта.
//
// Перевод ТОТАЛЕН ПО ТИПУ: арма, которой этот словарь не знает, не может быть
// переведена молча — она попадает в `SCOPE_UNSPECIFIED` здесь, в одной функции.
func scope(s string) iamv1.Quota_Scope {
	switch s {
	case "DEFAULT":
		return iamv1.Quota_DEFAULT
	case "ACCOUNT":
		return iamv1.Quota_ACCOUNT
	case "PROJECT":
		return iamv1.Quota_PROJECT
	default:
		return iamv1.Quota_SCOPE_UNSPECIFIED
	}
}
