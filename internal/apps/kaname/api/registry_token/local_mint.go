package registry_token

import "context"

// MintInput — запрос на выпуск токена НАШИМ подписантом.
//
// Ни одного поля, которое выбирал бы предъявитель: субъект резолвится
// проверенной учётной записью, адресат — настройкой контура, объём —
// политикой потока. Вход, который позволял бы вызывающему назвать себя, был бы
// не выдачей, а олицетворением.
type MintInput struct {
	// Subject — принципал, за которого говорит токен: идентификатор, который
	// резолвит приёмная сторона.
	Subject string
	// Audience — адресат: контур, которому токен предъявляется. Незаданный
	// адресат означал бы «любой».
	Audience string
	// Scope — объём. Для анонимного потока — только чтение.
	Scope string

	// ConfirmationX5TS256 — отпечаток ПРОВЕРЕННОГО клиентского сертификата,
	// предъявленного на хопе выдачи (RFC 8705).
	// ConfirmationJKT — отпечаток ключа доказательства владения (RFC 9449).
	//
	// Оба — МАТЕРИАЛ, ПРЕДЪЯВЛЕННЫЙ ПРИ ВЫДАЧЕ, и оба необязательны. Привязка
	// не выдумывается ни контуром, ни подписантом: пусто означает «материал не
	// предъявляли», и токен остаётся законным предъявительским — сужение здесь
	// было бы новым отказом тенанту, которого фаза не вводила.
	//
	// Поля два, а не одно, потому что формы две и они не взаимозаменяемы: одна
	// говорит «держатель этого сертификата», другая — «держатель этого ключа».
	// Свести их в одну строку значило бы потерять, что именно доказано.
	ConfirmationX5TS256 string
	ConfirmationJKT     string
}

// HasConfirmation отвечает, был ли при выдаче предъявлен материал привязки.
//
// Предикат, а не сравнение у каждого вызывающего: два сравнения одного
// предмета разошлись бы молча, и разошлись бы на вырожденном значении.
func (in MintInput) HasConfirmation() bool {
	return in.ConfirmationX5TS256 != "" || in.ConfirmationJKT != ""
}

// MintOutput — выпущенный токен.
type MintOutput struct {
	AccessToken string
	ExpiresIn   int
}

// LocalMinter — НАШ подписант с точки зрения контура выдачи.
//
// Порт объявлен здесь, у вызывающего: контур не знает ни про ключницу, ни про
// обёртку приватной половины, ни про то, каким алгоритмом подписано.
//
// Он — ЕДИНСТВЕННЫЙ издатель контура и обязательный вход его построителя
// (NewIssueRegistryTokenUseCase). Отказ подписанта контур не обходит ничем:
// запасного издателя нет, и отказ уходит вызывающему недоступностью издателя.
type LocalMinter interface {
	MintToken(ctx context.Context, in MintInput) (MintOutput, error)
}
