package module

// authz.go — гейт права `InternalModuleService`.
//
// # Почему он ЕДИНСТВЕННАЯ авторизация этой поверхности
//
// Внутренний слушатель iam своего рубежа авторизации сверх транспортного не
// несёт, а объявленная ступень подтверждения личности к этим четырём методам
// сегодня не применяется — это записанное решение, а не умолчание: страж ступени
// читает рукописный перечень методов, фронтящихся краем, и та же запись
// объявляет, что звонить методу вправе ТОЛЬКО край. Маршрута у края к ним нет и
// в этой под-фазе не будет, поэтому внесение дало бы поверхность, недостижимую
// ни для кого.
//
// Следствие, ради которого этот файл существует: гейт в хендлере — то
// единственное, что стоит между вызывающим и применением, отбирающим права
// арендатора. Регистрация службы без него не должна существовать НИ В ОДНОМ
// коммите.
//
// # Вопрос задаёт ОБЩИЙ производитель, а не своя копия
//
// Отношение и синглтон названы в дереве однажды (`authzguard.IsClusterAdminE` →
// `SubjectIsClusterAdminPlainE` → `ClusterObject()`). Спросив здесь своей
// строкой, мы завели бы второе место об одном предмете — и разошлось бы оно в
// день, когда синглтон переименуют.

import (
	"context"

	"github.com/PRO-Robotech/kaname/internal/authzguard"
)

// requireClusterSystemAdmin — гейт: вызывающий обязан держать `system_admin` на
// синглтоне `cluster`.
//
// Fail-closed на каждом вырожденном входе: анонимный вызывающий, неназываемая
// личность, НЕПРОВЯЗАННЫЙ проверяющий — отказ. Непровязанный гейт, пропускающий
// вызов, есть худший из возможных исходов: сборка, забывшая его подключить,
// поднимает службу, отдающую применение каталога кому угодно, и заметить это
// нечем.
//
// Ответ РАЗЛИЧАЕТ два состояния, и это не педантизм: модель ответила «нет» —
// `PermissionDenied`, модель не ответила вовсе — `Unavailable`. Второе означает
// «тот же вопрос минутой позже получит ответ»; выдав на него отказ в правах, мы
// показали бы администратору отзыв права там, где была двухсекундная неполадка.
func requireClusterSystemAdmin(ctx context.Context, checker adminChecker) error {
	allowed, err := authzguard.IsClusterAdminE(ctx, checker)
	if err != nil {
		return authzguard.AuthzBackendUnavailable()
	}
	if !allowed {
		return authzguard.PermissionDenied()
	}
	return nil
}
