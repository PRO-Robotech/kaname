package module

// ports.go — узкие порты use-case'ов `InternalModuleService`.
//
// Чистая архитектура: use-case объявляет ПОТРЕБНОСТЬ, адаптеры её исполняют и
// приезжают из композиционного корня (`cmd/kaname/wiring.go`). Ни pgx, ни
// grpc-стабов здесь нет и быть не может.
//
// # Дом этого пакета выбран замером, а не по вкусу
//
// `api/<resource>/` — дом ГЛАГОЛА, и там лежат все внутренние службы-образцы
// (`cluster`, `limit`, `internal_iam`, `internal_operations`);
// `apps/kaname/<предмет>/` — дом МЕХАНИЗМА, который глагол зовёт, и применитель
// каталога среди них. Глагол и механизм — разные предметы, поэтому и живут они
// врозь.

import (
	"context"

	"github.com/PRO-Robotech/kacho/pkg/operations"

	"github.com/PRO-Robotech/kaname/internal/apps/kaname/modulecatalog"
	"github.com/PRO-Robotech/kaname/internal/authzguard"
	"github.com/PRO-Robotech/kaname/internal/catalog"
	"github.com/PRO-Robotech/kaname/internal/manifest"
)

// adminChecker — узкий порт ReBAC (`Check(subject, relation, object)`).
//
// Псевдоним пакетного `authzguard.RelationChecker`, а не своё объявление: тот же
// поддельный проверяющий обязан годиться всем гейтам сервиса, иначе у каждого
// заводится своя подделка и они расходятся молча.
type adminChecker = authzguard.RelationChecker

// Delivery — состояние каталога доставки на момент запроса.
//
// Три состояния доставки различимы ЗДЕСЬ, а не в тексте отказа: они чинятся в
// трёх разных местах — посадкой, источником манифестов и самим манифестом, — и
// слив их в один отказ, мы отправили бы оператора чинить не то.
type Delivery struct {
	// Declared — посадка объявила каталог доставки. Ложь означает «доставки нет
	// вовсе», а не «доставка пуста».
	Declared bool
	// ManifestsRead — манифестов прочитано (в том числе негодных: они прочитаны,
	// и именно поэтому о них есть что сказать).
	ManifestsRead int
	// Findings — находок обхода. Ненулевое означает «объявлена и сорвана».
	Findings int
	// Manifests — РАЗОБРАННЫЕ годные манифесты.
	Manifests []*manifest.Manifest
}

// DeliverySource — порт доставки манифестов, ПЕРЕЧИТЫВАЕМОЙ на пути запроса.
//
// Перечитывается, а не берётся снимком старта: снимок разошёлся бы с тем, что
// применит следующий пуск, и разошёлся бы молча. Манифест телом запроса не
// приходит вовсе — второй путь доставки, расходящийся с первым, превращает
// применение в кирпич (страж паритета откажет следующему пуску).
type DeliverySource interface {
	// Read перечитывает каталог доставки. Перепись возвращается ВСЕГДА,
	// независимо от исхода: без неё «прочитано ноль» неотличимо от «находок
	// ноль».
	Read(ctx context.Context) (Delivery, error)
}

// CatalogStateSource — обе половины каталога ПЛАТФОРМЫ: живая и снятая.
//
// Обе, а не одна, и не один модуль: опора стража паритета есть литерал платформы
// целиком, а страж принимает снятую строку СВОЕЙ корзиной. Подавший ему одно
// живое множество получит законное снятие в недостающих — то есть план объявит
// отказ там, где применение пройдёт.
type CatalogStateSource interface {
	ReadLiveCatalog(ctx context.Context) (catalog.Rows, error)
	ReadRetiredCatalog(ctx context.Context) (catalog.Rows, error)
}

// PlanState — плановая сторона состояния каталога модуля, снятая ОДНИМ чтением.
//
// Одним, а не тремя: отпечаток и оценки последствий обязаны описывать ОДНО
// состояние. Собранные из трёх моментов, они описывали бы состояние, которого не
// было ни в один из них.
type PlanState struct {
	// ExpectedState — отпечаток состояния каталога модуля, непрозрачный для
	// вызывающего и возвращаемый им дословно в `Apply`. Контракт — РАВЕНСТВО и
	// ничего кроме; способ вычисления есть деталь реализации адаптера.
	ExpectedState string
	// Resettled — ОЦЕНКА переселения по популяциям на момент плана.
	Resettled modulecatalog.Resettled
	// Pruned — ОЦЕНКА вырезания третьей проекции, тремя величинами.
	Pruned modulecatalog.Pruned
}

// PlanStateSource — производитель плановой стороны.
//
// # Почему это порт, а не вычисление здесь
//
// Отпечаток производится ТЕМ ЖЕ выражением, которым его сверяет применитель
// (`ConfirmModuleState`), а оценки последствий — тем же отбором, каким переселяет
// применитель. Посчитав их здесь, на языке Go, мы завели бы вторую копию обоих
// предикатов, и разошлись бы они молча — то есть ровно там, где расхождение не
// видно: план обещал бы одно, применение делало другое, и оба были бы «правы».
//
// # Непровязанный порт — ОТКАЗ, а не разрешение
//
// `nil` означает, что производителя плановой стороны в этой сборке нет. Тогда
// `Plan` отказывает, называя причину. Вернуть вместо этого нули значило бы
// солгать о последствиях: ноль в `resettled…AtPlanTime` есть УТВЕРЖДЕНИЕ «ни
// одного права не отберут», а не «мы не считали».
type PlanStateSource interface {
	// PlanState читает отпечаток состояния модуля и оценивает последствия снятия
	// названных строк.
	PlanState(ctx context.Context, module string,
		staleResources []catalog.ResourceRow, staleVerbs []catalog.VerbRow) (PlanState, error)
}

// CatalogApplier — применитель ГЛАГОЛА: сверяет опору всегда и требует
// подтверждения с потолками.
//
// Тип назван потребностью, а не реализацией: путь старта пользуется ДРУГИМ
// применителем (`modulecatalog.Applier`), у которого подтверждения нет by
// construction, и подать его сюда невозможно — их различает ТИП, а не флаг.
type CatalogApplier interface {
	Apply(ctx context.Context, req modulecatalog.Request) (modulecatalog.Report, error)
}

// operationRepo — LRO-порт. Терминальный конверт требует ОБОИХ интерфейсов:
// строка создаётся `done=false` до мутации (чтобы её id был запрашиваем всегда),
// а завершается `MarkDoneWithMetadata` — `MarkDone` третьим параметром берёт
// ОТВЕТ и метаданные не трогает.
type operationRepo interface {
	operations.Repo
	operations.MetadataFinalizer
}
