package humansession

// completed_login.go — ЕДИНСТВЕННЫЙ писатель обнуления счёта неверных
// предъявлений по адресу (Ф12 Р7 редакция 11, сценарий Ф12-46; Ф3 Р10
// редакция 11; задача PRO-Robotech/kaname#287).
//
// # Что решает это место
//
// Счёт по адресу обнуляет вход, ЗАВЕРШЁННЫЙ до уровня всех заведённых у
// личности факторов:
//
//	личность без второго фактора — завершённый вход есть успех пароля
//	                               («1» — и есть уровень всех её факторов);
//	личность с фактором          — «2», достигаемое успехом КОДА: вход с полем
//	                               `secondFactor` либо церемония, доводящая до «2».
//
// Успех одного первого фактора счёт НЕ обнуляет: он успех, но не завершённый
// вход. Инкремент при этом остаётся ОБЩИМ с паролем и оси по фактору не несёт —
// раздельный по фактору счётчик на инкременте отличал бы совпавший пароль по
// темпу окна. Два разных вопроса: считает — общий счёт, обнуляет — уровень.
//
// # Почему один писатель, а не проверка в каждой полосе
//
// Условие — свойство того, какие СТРОКИ СПОСОБОВ ВХОДА заведены у личности, и
// того, что предъявлено в сессии; свойством полосы оно не является. Полоса,
// решающая его своей копией, расходится с соседней молча: обе компилируются,
// обе типизированы, разницу видно только счётчиком. Поэтому полосы зовут это
// место, а порт напрямую не зовут, и держит это гейт дерева `internal/check`
// (`failure_reset_sole_writer_test.go`).
//
// # Ось «заведено» читается ДО транзакции и приходит сюда ДАННЫМИ
//
// Оба адаптера — записи сессии и способов входа — получают ОДИН пул соединений
// (`cmd/kaname/loginlane.go`). Открытая транзакция записи держит соединение, а
// чтение способов берёт второе; чтение ИЗНУТРИ транзакции даёт вложенный захват
// и при исчерпании пула — взаимную блокировку до истечения срока запроса.
// Поэтому заведённое читается `enrollmentBeforeWrite` ДО `Store.Writer`, и сюда
// приходит значением. Остальной пакет держит ту же дисциплину: церемония читает
// способы до открытия транзакции, подтверждение заведения — только после явного
// отката, вход — только после фиксации.
//
// Следствие, названное прямо: снимок «заведено» взят ДО записи этой же
// транзакции, поэтому подтверждение заведения видит строку ещё `pending`, а
// снятие — ещё `active`. Решение от этого не меняется ни в одну сторону: обе
// пары закреплены таблицей (`completed_login_test.go`).
//
// # Ключи доступа в ось «заведено» НЕ ВХОДЯТ — и это названо, а не подразумевается
//
// «Заведено» выводится из строк способов входа, а строки вида `webauthn` в
// способах входа НЕТ by construction: ключ — ресурс своей таблицы
// (`internal/domain/access_key.go`). Значит у личности, чей второй фактор —
// ключ доступа, требуемый уровень считается как «1», и вход одним паролём счёт
// обнулит. Сегодня это недостижимо: предъявление ключа производится
// (`access_keys.FinishAssertion`), но потребителя, поднимающего им уровень
// сессии, в прод-коде нет — ни одна полоса не строит сессию из утверждения
// ключа. Появится такой потребитель (Ф13,
// `docs/engineering/acceptance/passwordless-login-with-access-key.md`) — ось
// обязана учесть ключи ТЕМ ЖЕ изменением, иначе окно подбора вернётся молча.
//
// Предикат снятия: в прод-коде появился потребитель, строящий уровень сессии из
// утверждения ключа. До тех пор посылку исключения стережёт проба предпосылки
// `TestEnrolledAxisReadsExactlyTheLoginMethodKinds` — она падает, как только
// среди видов способов входа заводится ключ.
//
// # Ранжирование — чужое
//
// Сравнение уровней берётся у единой функции ранжирования платформы
// (`grpcsrv.ACRRank`): второй таблицы ранжирования в дереве не заводится
// (`internal/assurance` §«ЧЕГО ПАКЕТ НЕ ДЕЛАЕТ»).

import (
	"context"
	"fmt"
	"log/slog"

	"github.com/PRO-Robotech/corelib/grpcsrv"

	"github.com/PRO-Robotech/kaname/internal/apps/kaname/api/loginmethod"
	"github.com/PRO-Robotech/kaname/internal/assurance"
	"github.com/PRO-Robotech/kaname/internal/domain"
)

// completedLogin — вход, чей исход решает судьбу счёта по адресу.
//
// Хранилищ и журнала здесь НЕТ намеренно: всё, что требует чтения, прочитано
// вызывающим до открытия транзакции. Нулевого указателя, на котором можно
// упасть, у этой структуры нет by construction.
type completedLogin struct {
	// Enrolled — заведённые способы входа, прочитанные ДО транзакции записи.
	Enrolled []assurance.Method
	// EnrolledKnown — заведённое прочитано. false означает «неизвестно», а не
	// «ничего не заведено»: на неизвестном счёт не обнуляется.
	EnrolledKnown bool
	// AddressKey — нормализованный ключ почты: ось, которую обнуляют.
	AddressKey string
	// Presented — слова предъявленного в этой сессии ПОСЛЕ текущего успеха.
	Presented []string
}

// enrollmentBeforeWrite — заведённые способы входа, прочитанные ДО открытия
// транзакции записи (см. шапку: вложенный захват соединения).
//
// Второе значение — «прочитано», а не «непусто». Отказ чтения возвращает
// false, и полоса продолжается: счёт ОСТАЁТСЯ. Несброшенный счёт истекает своим
// окном сам, а сброшенный по незнанию открыл бы окно подбора, которого решение
// не разрешало; ронять из-за этого сам вход — цена, которой решение не
// требовало.
//
// Хранилище способов и журнал здесь всегда есть: каждая полоса, которая сюда
// ходит, без хранилища не собирается, а журнал ей подставляет конструктор
// (`TestEveryEnrollmentReaderRefusesToBuildWithoutTheMethodStore`).
func enrollmentBeforeWrite(
	ctx context.Context, methods loginmethod.Store, logger *slog.Logger, userID domain.UserID,
) ([]assurance.Method, bool) {
	enrolled, err := enrolledMethods(ctx, methods, userID)
	if err != nil {
		logger.ErrorContext(ctx, "failure reset: enrolled login methods unreadable — the address counter is left standing",
			"user_id", string(userID), "err", err.Error())
		return nil, false
	}
	return enrolled, true
}

// resetFailuresOnCompletedLogin — обнулить счёт по адресу, если вход завершён
// до уровня всех заведённых у личности факторов; иначе не трогать.
func resetFailuresOnCompletedLogin(ctx context.Context, w Writer, in completedLogin) error {
	if in.AddressKey == "" || !in.EnrolledKnown {
		return nil
	}
	if !loginCompletedToEnrolledLevel(in.Presented, in.Enrolled) {
		return nil
	}
	if err := w.ResetFailures(ctx, FailureByAddress, in.AddressKey); err != nil {
		return fmt.Errorf("failure reset: address counter not reset: %w", err)
	}
	return nil
}

// loginCompletedToEnrolledLevel — доводит ли предъявленное в сессии вход до
// уровня ВСЕХ заведённых у личности способов входа.
//
// Уровень заведённого считается тем же правилом, что уровень сессии
// (`assurance.PresentableLevels`), а не своей таблицей «способ → уровень»:
// заведённый код по времени и заведённый запасной код дают одно и то же «2»,
// и достаточно ЛЮБОГО из них — поэтому вопрос ставится об уровне, а не о
// покрытии множества заведённых способов.
//
// Пустое множество заведённого и множество предъявленного без уровня — «не
// завершён» (fail-closed): у живой сессии ни того, ни другого не бывает, а
// молчаливое «да» здесь открывало бы окно подбора.
func loginCompletedToEnrolledLevel(presented []string, enrolled []assurance.Method) bool {
	required := 0
	for _, l := range assurance.PresentableLevels(enrolled) {
		if r := grpcsrv.ACRRank(l.String()); r > required {
			required = r
		}
	}
	if required == 0 {
		return false
	}
	reached, ok := assurance.LevelOf(presentationsOf(presented))
	if !ok {
		return false
	}
	return grpcsrv.ACRRank(reached.String()) >= required
}
