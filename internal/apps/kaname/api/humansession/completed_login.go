package humansession

// completed_login.go — ЕДИНСТВЕННЫЙ писатель обнуления счёта неверных
// предъявлений по адресу (Ф12 Р7 редакция 11, сценарий Ф12-46; Ф3 Р10
// редакция 11; задача PRO-Robotech/kaname#287). Завершение восстановления
// решает счёт здесь же (Ф3 Р10 редакция 13, Ф5 Р5 редакция 4, сценарий Ф5-25;
// задача PRO-Robotech/kaname#305).
//
// # Что решает это место
//
// Счёт по адресу обнуляет вход, ЗАВЕРШЁННЫЙ до уровня всех заведённых у
// личности факторов:
//
//	личность без второго фактора — завершённый вход есть успех пароля
//	                               («1» — и есть уровень всех её факторов);
//	личность с фактором          — «2», достигаемое успехом КОДА: вход с полем
//	                               `secondFactor` либо церемония, доводящая до «2».
//
// Успех одного первого фактора счёт НЕ обнуляет: он успех, но не завершённый
// вход. Инкремент при этом остаётся ОБЩИМ с паролем и оси по фактору не несёт —
// раздельный по фактору счётчик на инкременте отличал бы совпавший пароль по
// темпу окна. Два разных вопроса: считает — общий счёт, обнуляет — уровень.
//
// # Почему один писатель, а не проверка в каждой полосе
//
// Условие — свойство того, какие СТРОКИ СПОСОБОВ ВХОДА заведены у личности, и
// того, что предъявлено в сессии; свойством полосы оно не является. Полоса,
// решающая его своей копией, расходится с соседней молча: обе компилируются,
// обе типизированы, разницу видно только счётчиком. Поэтому полосы зовут это
// место, а порт напрямую не зовут, и держит это гейт дерева `internal/check`
// (`failure_reset_sole_writer_test.go`).
//
// # Ось «заведено» читается ВНЕ этого места и приходит сюда ДАННЫМИ
//
// Оба адаптера — записи сессии и способов входа — получают ОДИН пул соединений
// (`cmd/kaname/loginlane.go`). Открытая транзакция записи держит соединение, а
// чтение способов хранилищем способов берёт второе; такое чтение ИЗНУТРИ
// транзакции даёт вложенный захват и при исчерпании пула — взаимную блокировку
// до истечения срока запроса. Поэтому заведённое читается либо
// `enrollmentBeforeWrite` ДО `Store.Writer`, либо соединением самой транзакции
// (`Writer.LoginMethod`, второго соединения не берёт), и сюда приходит
// значением. Остальной пакет держит ту же дисциплину: вход и церемония читают
// способы до открытия транзакции, подтверждение заведения — только после явного
// отката, вход после выдачи — только после фиксации. Завершение восстановления
// читает транзакцией записи и только ПОСЛЕ применения кода: до точки решения
// чтение сделало бы полосы отказа «адрес есть» и «адреса нет» неравными по
// работе, а значит по времени (Ф5 Р7, §8 инв. 4; шапка `recovery_complete.go`).
//
// Следствие, названное прямо: у полос, читающих до транзакции, снимок
// «заведено» взят ДО записи этой же транзакции, поэтому подтверждение заведения
// видит строку ещё `pending`, а снятие — ещё `active`. Решение от этого не
// меняется ни в одну сторону: обе пары закреплены таблицей
// (`completed_login_test.go`). У завершения восстановления снимок взят внутри
// транзакции после замещения материала пароля: строка `password` на месте,
// строк второго фактора транзакция не трогает — решение то же, что до записи.
//
// # Ключи доступа в ось «заведено» ВХОДЯТ — своим чтением и своим худшим исходом
//
// «Заведено» выводится из строк способов входа, а строки вида `webauthn` в
// способах входа НЕТ by construction: ключ — ресурс своей таблицы
// (`internal/domain/access_key.go`). С полосой входа ключом (Ф13,
// `docs/engineering/acceptance/passwordless-login-with-access-key.md`) ключ
// стал производителем уровня сессии, и ось читает его отдельно: есть у личности
// хоть одна строка ключа — в оси стоит `webauthn` (`AccessKeyEnrolled` у обоих
// носителей чтения). Без этого у личности с паролем и ключом требуемый уровень
// считался бы «1», и вход одним паролём счёт обнулял бы — окно подбора,
// которое ось и закрывает.
//
// Требуемый уровень считается ХУДШИМ исходом флагов ключа
// (`assurance.GuaranteedLevels`), а не лучшим: ключ производит «2» всегда, «3» —
// лишь утверждением с проверкой пользователя. Лучший исход требовал бы «3» у
// каждого заведённого ключа, и вход ключом без проверки пользователя перестал
// бы обнулять счёт — против Ф13 Р9 («успешный вход ключом обнуляет счёт по
// адресу — как всякий успешный вход»).
//
// Уровень, ДОСТИГНУТЫЙ входом, приходит сюда записанным (`completedLogin.Level`),
// а не пересчитывается от имён способов: имена не несут флагов утверждения
// ключа (`session_level.go`).
//
// # Ранжирование — чужое
//
// Сравнение уровней берётся у единой функции ранжирования платформы
// (`acrlevel.Rank`): второй таблицы ранжирования в дереве не заводится
// (`internal/assurance` §«ЧЕГО ПАКЕТ НЕ ДЕЛАЕТ»).

import (
	"context"
	"fmt"
	"log/slog"

	"github.com/PRO-Robotech/corelib/acrlevel"

	"github.com/PRO-Robotech/kaname/internal/apps/kaname/api/loginmethod"
	"github.com/PRO-Robotech/kaname/internal/assurance"
	"github.com/PRO-Robotech/kaname/internal/domain"
)

// completedLogin — вход, чей исход решает судьбу счёта по адресу.
//
// Хранилищ и журнала здесь НЕТ намеренно: всё, что требует чтения, прочитано
// вызывающим до открытия транзакции. Нулевого указателя, на котором можно
// упасть, у этой структуры нет by construction.
type completedLogin struct {
	// Enrolled — заведённые способы входа, прочитанные ДО транзакции записи.
	Enrolled []assurance.Method
	// EnrolledKnown — заведённое прочитано. false означает «неизвестно», а не
	// «ничего не заведено»: на неизвестном счёт не обнуляется.
	EnrolledKnown bool
	// AddressKey — нормализованный ключ почты: ось, которую обнуляют.
	AddressKey string
	// Level — уровень записи сессии ПОСЛЕ текущего успеха: выданный операцией
	// выдачи либо легший предъявлением внутри сессии.
	Level string
}

// enrollmentBeforeWrite — заведённые способы входа, прочитанные ДО открытия
// транзакции записи (см. шапку: вложенный захват соединения).
//
// Второе значение — «прочитано», а не «непусто». Отказ чтения возвращает
// false, и полоса продолжается: счёт ОСТАЁТСЯ. Несброшенный счёт истекает своим
// окном сам, а сброшенный по незнанию открыл бы окно подбора, которого решение
// не разрешало; ронять из-за этого сам вход — цена, которой решение не
// требовало.
//
// Хранилище способов и журнал здесь всегда есть. Хранилище держит проба
// `TestEveryEnrollmentReaderRefusesToBuildWithoutTheMethodStore`: полоса, которая
// сюда ходит, без него не собирается. Журнал проба НЕ держит: пустой `Logger`
// заменяет `slog.Default()` конструктор полосы — `NewLoginUseCase` и
// `SecondFactorDeps.validate`. Завершение восстановления сюда не ходит: оно
// читает заведённое транзакцией записи, и хранилища способов у него нет.
func enrollmentBeforeWrite(
	ctx context.Context, methods loginmethod.Store, logger *slog.Logger, userID domain.UserID,
) ([]assurance.Method, bool) {
	enrolled, err := enrolledForCompletion(ctx, methods.Get, methods.AccessKeyEnrolled, userID)
	if err != nil {
		logger.ErrorContext(ctx, "failure reset: enrolled login methods unreadable — the address counter is left standing",
			"user_id", string(userID), "err", err.Error())
		return nil, false
	}
	return enrolled, true
}

// resetFailuresOnCompletedLogin — обнулить счёт по адресу, если вход завершён
// до уровня всех заведённых у личности факторов; иначе не трогать.
func resetFailuresOnCompletedLogin(ctx context.Context, w Writer, in completedLogin) error {
	if in.AddressKey == "" || !in.EnrolledKnown {
		return nil
	}
	if !loginCompletedToEnrolledLevel(in.Level, in.Enrolled) {
		return nil
	}
	if err := w.ResetFailures(ctx, FailureByAddress, in.AddressKey); err != nil {
		return fmt.Errorf("failure reset: address counter not reset: %w", err)
	}
	return nil
}

// loginCompletedToEnrolledLevel — доводит ли достигнутый уровень вход до
// уровня ВСЕХ заведённых у личности способов входа.
//
// Уровень заведённого считается тем же правилом, что уровень сессии
// (`assurance.GuaranteedLevels` — ключ в худшем исходе флагов, шапка), а не
// своей таблицей «способ → уровень»: заведённый код по времени и заведённый
// запасной код дают одно и то же «2», и достаточно ЛЮБОГО из них — поэтому
// вопрос ставится об уровне, а не о покрытии множества заведённых способов.
//
// Пустое множество заведённого и уровень вне оси — «не завершён»
// (fail-closed): у живой сессии ни того, ни другого не бывает, а молчаливое
// «да» здесь открывало бы окно подбора.
func loginCompletedToEnrolledLevel(reached string, enrolled []assurance.Method) bool {
	required := 0
	for _, l := range assurance.GuaranteedLevels(enrolled) {
		if r := acrlevel.Rank(l.String()); r > required {
			required = r
		}
	}
	if required == 0 {
		return false
	}
	return acrlevel.Rank(reached) >= required
}

// accessKeyRead — есть ли у личности строка ключа доступа; носителей два, как
// у loginMethodRead: пул (`loginmethod.Store`) и транзакция (`Writer`).
type accessKeyRead func(ctx context.Context, userID domain.UserID) (bool, error)

// enrolledForCompletion — ось «заведено» единственного писателя обнуления:
// строки способов входа плюс ключ доступа (шапка). Ответ церемонии второго
// фактора ключа не читает: в церемонии ключ не предъявляется (Ф12 Р4), и
// «2 достижимо ключом» назвало бы недостающим то, что этой церемонией не
// предъявить.
func enrolledForCompletion(ctx context.Context, read loginMethodRead, keys accessKeyRead, userID domain.UserID) ([]assurance.Method, error) {
	out, err := enrolledMethods(ctx, read, userID)
	if err != nil {
		return nil, err
	}
	has, err := keys(ctx, userID)
	if err != nil {
		return nil, err
	}
	if has {
		out = append(out, assurance.MethodWebAuthn)
	}
	return out, nil
}
