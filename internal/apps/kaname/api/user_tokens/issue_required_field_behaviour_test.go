// issue_required_field_behaviour_test.go — ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ к правилу об
// ответственном: поле, которое край ДЕЙСТВИТЕЛЬНО требует, отвергается при
// отсутствии (задача #1255, приёмка PROTO-1, сценарий Д-03).
//
// # ЧТО ЗДЕСЬ ЗАМЕНЕНО И ПОЧЕМУ ЗАМЕНЕНО, А НЕ СНЯТО
//
// Прежде обязательность утверждалась ОПИСАТЕЛЕМ: проба читала расширение
// `(required)` семейства `kacho.cloud.validation` и требовала, чтобы у
// `created_by_user_id` его не было, а у `user_id` — было. Семейство снято с
// контрактов целиком: исполнителя на пути запроса у него не было ни одного,
// объявление ничего не ограничивало и при этом выглядело гарантией.
//
// Отрицательная половина прежней пробы («поле, которое край подставляет сам, не
// объявляется обязательным») уже выражена ПОВЕДЕНИЕМ и лежит рядом —
// `handler_sa_lane_no_silent_drop_test.go`: опущенный ответственный принимается
// и подставляется, несовпавший отвергается синхронно с именем поля.
//
// Не хватало ВТОРОЙ половины — того самого положительного контроля, ради
// которого прежняя проба читала опцию у `user_id`. Без него отрицание вакуумно:
// оно зеленело бы на крае, который не требует ВООБЩЕ НИЧЕГО. Здесь контроль
// выражен тем же способом, что и всё остальное в этом файле, — исходом вызова.
//
// # ИСТОЧНИК ОБЯЗАТЕЛЬНОСТИ — ОТКАЗ, А НЕ ОБЪЯВЛЕНИЕ
//
// Поле обязательно ровно тогда, когда запрос без него отвергается. Это
// проверяемо, не расходится с поведением by construction и не зависит от того,
// кто и как прочтёт объявление.
//
// # ЗАВИСИМОСТИ НЕ НУЖНЫ, И ЭТО ЧАСТЬ УТВЕРЖДЕНИЯ
//
// Проверка обязательности стоит ПЕРВЫМ стейтментом use-case — до репозитория,
// до транзакции, до журнала операций. Поэтому use-case строится с пустыми
// зависимостями: дойди исполнение до любой из них, проба упала бы паникой, и
// это отличило бы «отвергнуто рано» от «отвергнуто когда-нибудь».
package user_tokens

import (
	"context"
	"testing"

	"github.com/stretchr/testify/require"
	"google.golang.org/grpc/codes"
	grpcstatus "google.golang.org/grpc/status"
)

// TestIssueUserToken_UserIDIsRequiredByBehaviour — Д-03 на полосе персонального
// токена.
func TestIssueUserToken_UserIDIsRequiredByBehaviour(t *testing.T) {
	// Пустые зависимости намеренно: отказ обязан наступить до первой из них.
	uc := NewIssueUserTokenUseCase(nil, nil, nil)

	_, err := uc.Execute(context.Background(), IssueInput{
		// user_id не назван — это и есть предмет.
		CreatedByUserID: "usr00000000000000007",
	})

	require.Error(t, err,
		"user_id обязателен: без отказа положительный контроль вакуумен, и "+
			"отрицание про created_by зеленело бы на крае, не требующем ничего")
	require.Equal(t, codes.InvalidArgument, grpcstatus.Code(err),
		"отсутствие обязательного поля — INVALID_ARGUMENT")
	// Сверка ДОСЛОВНАЯ, а не по вхождению подстроки: "user_id required" целиком
	// лежит внутри "created_by_user_id required", и проверка на вхождение зеленела
	// бы на отказе про СОСЕДНЕЕ поле. Тон отказа — часть контракта
	// (api-conventions.md §Error-format), поэтому закрепляется дословно.
	require.Equal(t, "user_id required", grpcstatus.Convert(err).Message(),
		"отказ обязан назвать ИМЕННО это поле, иначе вызывающему нечего править")
}

// TestIssueUserToken_CreatedByOmitted_IsNotRefusedForBeingAbsent — вторая
// сторона той же пары: поле, которое край подставляет сам, отсутствием запроса
// не рушит. Отказ, если он придёт, обязан быть НЕ про пустой `created_by_user_id`.
//
// Без этой стороны первая проба зеленела бы на крае, отвергающем всякий запрос
// целиком: «отказ есть» и «отказ про названное поле» — разные утверждения.
func TestIssueUserToken_CreatedByOmitted_IsNotRefusedForBeingAbsent(t *testing.T) {
	uc := NewIssueUserTokenUseCase(nil, nil, nil)

	_, err := uc.Execute(context.Background(), IssueInput{
		UserID: "usr00000000000000001",
		// created_by_user_id не назван; на этой полосе его подставляет обработчик
		// (см. handler.go), поэтому use-case вправе требовать уже подставленное.
	})

	// Здесь важен не факт отказа, а его ПРЕДМЕТ: use-case стоит ниже подстановки,
	// поэтому пустое значение до него не доходит в живом тракте.
	require.Error(t, err, "use-case зовётся после подстановки — пустое значение сюда не приходит")
	require.Equal(t, codes.InvalidArgument, grpcstatus.Code(err))
	require.Equal(t, "created_by_user_id required", grpcstatus.Convert(err).Message(),
		"отказ обязан быть про created_by, а не про user_id: иначе первая проба "+
			"этого файла зеленела бы на любом отказе. Сверка дословная — по вхождению "+
			"подстроки эти два отказа неразличимы")
}
