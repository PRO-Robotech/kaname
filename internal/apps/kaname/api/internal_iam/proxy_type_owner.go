package internal_iam

// proxy_type_owner.go — словарь владения типом объекта для правила проксируемой
// записи (задача продукта #1885).
//
// # Зачем адаптер здесь, а не таблица в правиле
//
// Правило живёт в общем фундаменте (`pkg/authz/proxytuple`) и импортируется всеми
// семью службами; полный перечень типов живёт в закрытой таблице iam
// (`internal/authzmap`), за границей видимости фундамента. Вторая копия перечня
// разошлась бы с первой МОЛЧА — ровно тот класс, ради которого правило и вынесено
// в один экземпляр. Поэтому правило объявляет ПОРТ, а словарь подаёт вызывающий:
// в прод-коде он ровно один, и он здесь.
//
// # Почему модуль КАТАЛОГА, а не короткое имя службы
//
// У балансировщика написания различны: служба `nlb`, модуль каталога
// `loadbalancer`, тип модели `nlb_listener`. Сравнение по имени службы не совпало
// бы для него НИКОГДА и отняло бы три живых типа; наблюдаемо это было бы как
// «ресурс создан, доступа нет». Соответствие «служба ↔ модуль каталога»
// объявлено единожды в `pkg/platformmodules` и читается правилом оттуда.
//
// # Таблица ПОРОЖДАЕТСЯ, и это условие применимости
//
// До задачи #1092 таблица типов была рукописной, и сделать её авторитетом пути
// запроса значило бы требовать правки Go в iam прежде, чем модуль сможет
// зарегистрировать свой новый ресурс. Теперь её порождает манифест того же
// модуля, поэтому объявление ресурса и его право на регистрацию приезжают одним
// изменением. Порядок был назван заранее (`policy.go`, «почему порт всё равно не
// заводится сегодня») и соблюдён.

import (
	"github.com/PRO-Robotech/kaname/internal/authzmap"
)

// catalogTypeOwner — реализация порта `proxytuple.TypeOwner` над ПОРОЖДЁННОЙ
// таблицей типов.
//
// Состояния не держит: таблица — константа сборки, и держатель ей не нужен.
type catalogTypeOwner struct{}

// CatalogModuleOfObjectType — модуль каталога, объявивший этот тип модели прав.
//
// ok=false означает «закрытая таблица типа не знает». Это НЕ отказ: правило
// возвращается к приставке, потому что отвергнуть здесь значило бы ответить
// ОПАКОВЫМ отказом на вход, у которого вызывающему нечего чинить.
func (catalogTypeOwner) CatalogModuleOfObjectType(objType string) (string, bool) {
	dotted, ok := authzmap.DottedType(objType)
	if !ok {
		return "", false
	}
	module, _, ok := authzmap.SplitObjectType(dotted)
	if !ok {
		return "", false
	}
	return module, true
}
