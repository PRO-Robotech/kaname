package internal_iam

// catalog_type.go — ИМЯ ТИПА КАТАЛОГА СПРАШИВАЕТСЯ У ЖИВОЙ СТРОКИ, а не у
// словаря, порождённого сборкой (kacho#1990).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗДЕСЬ СТОЯЛО И ПОЧЕМУ ЭТОГО МАЛО
//
// Перевод брался у `authzmap.DottedType` — оболочки над таблицей
// `authzmap/tables_gen.go`, ПОРОЖДЁННОЙ СБОРКОЙ из манифестов дерева. На промахе
// имя оставалось КАК ЕСТЬ, то есть именем словаря МОДЕЛИ (`billing_invoice`), и
// уезжало в колонку `resource_mirror.object_type`, названную словарём КАТАЛОГА.
//
// Зеркало принимает строку только при ЖИВОЙ строке каталога с таким `dotted`, а
// имя без точки живой строкой быть не может (`catalog_resource_dotted_form`
// CHECK). Следствие: объект типа, заведённого применением манифеста в РАБОТАЮЩЕМ
// процессе, в зеркало не попадал ВОВСЕ — регистрация отвергалась. Ниже по цепи
// чинить было нечего: строки нет.
//
// Это ОБРАТНОЕ направление того же перехода, что закрыт у зеркала
// (`repo/kaname/pg/resource_mirror/model_dictionary.go`, kacho#1982): там имя
// модели по строке каталога, здесь — имя каталога по строке каталога.
//
// ─────────────────────────────────────────────────────────────────────────────
// СУЖЕНИЕ ИДЁТ ПО СВОЙСТВУ, А НЕ ПО ИМЕНИ
//
// Запретить сборочный переходник ПО ИМЕНИ нельзя: он тотален, поэтому любая его
// замена — те же две строки у следующего писателя, и запрет обходится молча.
// Различает словари СВОЙСТВО, и оно объявлено самими словарями
// (`authzmap/type_dictionaries.go`): имя каталога содержит точку ВСЕГДА, имя
// модели — НИКОГДА.
//
//	точка ЕСТЬ → это уже имя каталога → тождество, обращения к базе нет.
//	точки НЕТ  → это имя модели → спрашивается у строки каталога.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРОМАХ ОСТАВЛЯЕТ ИМЯ КАК ЕСТЬ, И ЭТО РЕШЕНИЕ, А НЕ НЕДОСМОТР
//
// Тип, которого у платформы нет ни живым, ни снятым, проходит дальше неизменным
// — ровно туда, где вердикт о нём уже выносится и выносится ПРАВИЛЬНО:
//
//	регистрация  зеркало отвергает строку, называя тип и правило
//	             (`ErrUnknownResourceType` → `INVALID_ARGUMENT` на поле `object`);
//	снятие       удалять нечего, и это успех по контракту прокси
//	             («unregister of an absent tuple → OK»).
//
// Отказать здесь значило бы завести ВТОРОЕ место, выносящее тот же вердикт, и
// сломать второй контракт заодно: снятие несуществующего перестало бы быть
// успехом.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЖИВАЯ СТРОКА ПРЕДПОЧИТАЕТСЯ СНЯТОЙ, И СНЯТАЯ ТОЖЕ ЧИТАЕТСЯ
//
// Обратное направление перехода определено НА ЖИВЫХ строках — это записано
// ключом `catalog_resource_object_type_live_uk UNIQUE (object_type, live)` и
// объяснено его миграцией: два ресурса, отображённые в один тип модели, сделали
// бы перевод неоднозначным.
//
// Но живых строк у имени типа бывает НОЛЬ, а снятая при этом остаётся: снятие
// типа с платформы мягкое (`live = false`, строка на месте). Читай только живые
// — и объект, зарегистрированный до снятия типа, стал бы НЕудаляемым: снятие не
// назвало бы его строку, а зеркало продолжало бы отдавать его правилу. Отказ на
// снятии дороже отказа на приёме: невыполнимое снятие означает право, которое не
// отзывается.
//
// Поэтому читаются обе, живая первой. Строк по имени типа не более двух —
// названный выше ключ допускает по одной на каждое значение `live`, — поэтому
// порядок определяет исход однозначно, а не разрешает спор порядком чтения.

import (
	"context"
	"strings"

	"github.com/PRO-Robotech/kaname/internal/service"
)

// catalogTypeReader — узкий порт чтения: точечное имя КАТАЛОГА по имени типа
// МОДЕЛИ, из строк каталога.
//
// Читается в ТОЙ ЖЕ транзакции, что пишет зеркало: перевод и запись оказываются
// в одном снимке, и окна между «спросил» и «вставил» нет by construction.
//
// `ok=false` означает «строки нет вовсе» — ни живой, ни снятой. Пара
// `(значение, известен ли)` не сворачивается здесь в «как есть»: что означает
// промах, решает вызывающий, и у регистрации со снятием ответы разные.
type catalogTypeReader interface {
	DottedTypeTx(ctx context.Context, tx service.Tx, modelType string) (dotted string, ok bool, err error)
}

// catalogObjectType переводит имя типа, приехавшее в кортеже, в имя словаря
// КАТАЛОГА — то, каким названа колонка `resource_mirror.object_type`.
//
// Сужение — по свойству словарей (см. шапку файла): имя с точкой уже каталожное
// и базе не предъявляется вовсе.
func (uc *RegisterResourceUseCase) catalogObjectType(
	ctx context.Context, tx service.Tx, typeName string,
) (string, error) {
	if strings.Contains(typeName, ".") {
		// Уже словарь каталога. Тождество — не запасной путь: пересечения у
		// словарей нет by construction, поэтому другого прочтения у имени с
		// точкой не существует.
		return typeName, nil
	}
	dotted, ok, err := uc.catalogTypes.DottedTypeTx(ctx, tx, typeName)
	if err != nil {
		return "", err
	}
	if !ok {
		// Типа у платформы нет ни живым, ни снятым. Вердикт выносит тот, кто уже
		// его выносит (см. шапку): здесь имя проходит неизменным.
		return typeName, nil
	}
	return dotted, nil
}
