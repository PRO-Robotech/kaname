// NewRegisterResourceUseCase — конструктор. `mirror` записывает
// строку resource_mirror в той же транзакции записи, что и кортеж владельца.
//
// `catalogTypes` — ПАРАМЕТР, А НЕ ОПЦИЯ, и различие несущее. Необъявленный
// читатель означал бы запасной путь «переводим словарём сборки», то есть ровно
// тот дефект, ради снятия которого он заведён (kacho#1990): запасной путь
// молчалив — он даёт верный ответ на посеянных типах и неверный на заведённых
// применением, и отличить одно от другого по исходу нельзя. Обязательность
// проверяет КОМПИЛЯТОР: каждое место сборки use-case названо им поимённо, и
// забыть провязку нельзя.
//
// `publications` — ТОЖЕ ПАРАМЕТР, и по той же причине. Без него у публикации нет
// порядка: запасным путём здесь был бы голый кортеж в журнал, то есть ровно то
// состояние, в котором запоздавшая доставка открытия после закрытия возвращала бы
// анонимное чтение (kaname#107). Опция с «нет — значит голый кортеж» делала бы
// этот дефект молчаливым умолчанием.
//
// `withdrawal` — ТОЖЕ ПАРАМЕТР (kaname#963). Без него снятие регистрации
// оставляло бы выдачи и названия правил на освободившийся ключ, и повторная
// регистрация того же ключа другим владельцем наследовала бы их: опция с «нет —
// значит не отзываем» и была тем дефектом.
//
// `audit` — ТОЖЕ ПАРАМЕТР (kaname#1005). Регистрация и снятие объекта модулем
// меняют модель прав; опция с «нет — значит не пишем» оставила бы эти изменения
// вне журнала аудита молча, и кто завёл или снял объект, восстановить было бы
// нельзя.
//
// `scopes` — ТОЖЕ ПАРАМЕТР (kaname#982). Регистрация выводит родителя объекта из
// данных kaname и сверяет с ним сведения модуля; опция с «нет — значит верим
// модулю» и была признаком задачи.
func NewRegisterResourceUseCase(
	emitter relationOutboxEmitter,
	mirror resourceMirrorEmitter,
	txb service.TxBeginner,
	catalogTypes catalogTypeReader,
	publications publicReadPublisher,
	withdrawal keyWithdrawal,
	audit registrationAudit,
	scopes registrationScopeReader,
) *RegisterResourceUseCase {
	return &RegisterResourceUseCase{emitter: emitter, mirror: mirror, txb: txb, catalogTypes: catalogTypes,
		publications: publications, withdrawal: withdrawal, audit: audit, scopes: scopes}
}

