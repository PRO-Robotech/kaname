// ids_pinned_test.go — класс C приёмки
// `docs/engineering/acceptance/seed-identity-names-its-own-service.md`
// (§2.2, §4.4, §8 шаг 3, сценарии KAN-SEED-1-14 и -15): идентификаторы посевной
// идентичности ПИННУТЫ литералом, а не выводятся из имени.
//
// # ПОЧЕМУ ПИН, А НЕ ФОРМУЛА
//
// Имя мутабельно и переводится (§2.3); идентификатор неизменяем на всю жизнь
// ресурса (ban #15), а применённую миграцию править нельзя (ban #5). Пока
// идентификатор ВЫВОДИЛСЯ из имени, эти два требования были несовместимы:
// перевод имени сдвинул бы каждый выведенный идентификатор, и полученное
// значение осталось бы СИНТАКСИЧЕСКИ ВЕРНЫМ, перестав адресовать существующую
// строку. Наблюдаемо это только отказом чеканки у оператора, который ничего не
// менял.
//
// # ИСТОЧНИК ОЖИДАЕМОГО — ПРИМЕНЁННЫЙ СВОД, А НЕ ВТОРОЙ РАСЧЁТ
//
// Проба НЕ пересчитывает `md5`: пересчёт был бы вторым объявлением той же
// формулы и сошёлся бы с первым при ЛЮБОМ имени — то есть остался бы зелёным
// ровно в том случае, ради которого написан. Ожидаемое читается из текста
// применённой миграции: там идентификатор посеян литералом и больше не двинется.
package bootstrap_token

import (
	"strings"
	"testing"

	"github.com/PRO-Robotech/kaname/internal/domain"
	"github.com/PRO-Robotech/kaname/internal/migrations"
)

// baselineFile — свод, посеявший строки. Правке не подлежит (ban #5), поэтому
// служит источником ожидаемого.
const baselineFile = "0001_initial.sql"

// TestDeriveIdentity_IDsArePinnedToTheAppliedBaseline — KAN-SEED-1-14/-15:
// каждый идентификатор, который отдаёт `DeriveIdentity`, ЕСТЬ в тексте свода.
//
// Перепись печатается всегда: «ноль расхождений» обязано быть отличимо от «ноль
// прочитанного», а прочитать свод здесь можно ровно один раз и целиком.
func TestDeriveIdentity_IDsArePinnedToTheAppliedBaseline(t *testing.T) {
	body, err := migrations.FS.ReadFile(baselineFile)
	if err != nil {
		t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: свод %s не прочитан: %v — сверять пин не с чем",
			baselineFile, err)
	}
	text := string(body)
	if len(text) == 0 {
		t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: свод %s пуст", baselineFile)
	}

	id := DeriveIdentity()
	pinned := map[string]string{
		"SvaID":           id.SvaID,
		"CreatedByUserID": id.CreatedByUserID,
	}

	t.Logf("перепись: свода прочитано %d байт · пиннутых идентификаторов сверено %d",
		len(text), len(pinned))

	for field, value := range pinned {
		if value == "" {
			t.Errorf("%s пуст — пин снят, и «адресует существующую строку» проверить нечем", field)
			continue
		}
		if !strings.Contains(text, "'"+value+"'") {
			t.Errorf("%s = %q не встречается литералом в %s: идентификатор не адресует ни одной "+
				"посеянной строки. Это и есть цена деривации из имени — значение остаётся "+
				"синтаксически верным и перестаёт находить строку",
				field, value, baselineFile)
		}
	}

	// Идентификатор отображения на клиента провайдера свод НЕ сеет: строку заводит
	// путь запроса (§5 сценарий -15). Поэтому он сверяется не со сводом, а с тем,
	// что он пиннут — то есть не пересчитывается из имени.
	if id.SocID == "" || !strings.HasPrefix(id.SocID, "soc_") {
		t.Errorf("SocID = %q не имеет объявленной формы", id.SocID)
	}
}

// TestDeriveIdentity_FormulaStaysWhereNameAndIDMoveTogether — ЗАКОННЫЙ БЛИЗНЕЦ
// к пину: деривация из имени не снята, она перестала быть хозяином ЗДЕСЬ.
//
// Без этой пробы «пин» неотличим от «формулу вырезали вообще»: служебные учётки
// модулей выводят идентификатор из имени законно — там имя и идентификатор
// двигаются вместе, — и снятие формулы сломало бы их молча.
func TestDeriveIdentity_FormulaStaysWhereNameAndIDMoveTogether(t *testing.T) {
	got := domain.DerivedIDSuffix("kacho-vpc")
	if len(got) != 17 {
		t.Fatalf("деривация из имени отдала суффикс длины %d вместо 17 — формула снята "+
			"вместе с пином, а служебные учётки модулей ею адресуются", len(got))
	}
	// Пин и формула — РАЗНЫЕ ответы на разные вопросы: совпади они, проба выше
	// доказывала бы лишь то, что обе стороны вычисляют одно.
	if domain.PrefixServiceAccount+got == DeriveIdentity().SvaID {
		t.Fatalf("формула на чужом имени дала пиннутый идентификатор — совпадение, " +
			"которое делает обе пробы вакуумными")
	}
}
