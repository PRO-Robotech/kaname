// local_mint.go — НАША чеканка бутстрап-удостоверения (задача #1119, Ф4б эпика
// #896).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО НЕ «ЕЩЁ ОДИН ПОРТ», А СМЫСЛ ВСЕЙ ФАЗЫ
//
// Бутстрап — ЕДИНСТВЕННОЕ удостоверение, которым кластер поднимают с нуля.
// Пока его выдавал внешний поставщик, свежий клон не поднимался в боевой
// посадке, пока тот не поднят и не знает нашего ключа: самодостаточность
// упиралась в чужую сторону ровно в той точке, где своей ещё нет ничего.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ПРИЕХАЛО ВМЕСТЕ С ПЕРЕВОДОМ — И ЭТО НЕ ПОБОЧНЫЙ ЭФФЕКТ
//
// Удостоверение стало НАШИМ токеном по всем осям, включая отзыв: наш авторитет
// отзыва читает его на предъявлении (`tokenintrospecthttp`), потому что издатель
// у него теперь наш. Пока подписывал поставщик, отозвать выданное можно было
// только у него — то есть у стороны, недоступность которой и есть тот случай,
// ради которого бутстрап существует.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО
//
// Ни одного поля, которое выбирал бы вызывающий. Принципал выведен
// детерминированно (`DeriveIdentity`), адресат — настройкой контура, срок —
// политикой. Вход, позволяющий назвать субъекта, был бы не бутстрапом, а
// универсальным ключом.
package bootstrap_token

import (
	"context"
	"errors"
	"time"
)

// MintInput — запрос на выпуск бутстрап-удостоверения НАШИМ подписантом.
type MintInput struct {
	// SAKeyID — НАШ идентификатор строки реестра бутстрап-клиента (`soc_…`).
	// Им резолвится состав утверждений — тем же объявлением, каким он
	// собирается на всех прочих полосах выдачи, чтобы токен, выданный этим
	// путём, не отличался от прежнего у ПРИНЦИПАЛА.
	SAKeyID string
	// PrincipalID — принципал, за которого говорит токен (`sva…`). Резолвится
	// строкой реестра, а не запросом.
	PrincipalID string
	// Audience — адресат: край, которому удостоверение предъявляют.
	// Незаданный адресат означал бы «любой».
	Audience string
	// TTL — срок выпускаемого удостоверения. Решение НАШЕ, потому что подпись
	// наша: величина объявлена контуром, а не выведена из чужого ответа.
	TTL time.Duration
}

// MintOutput — выпущенное удостоверение.
//
// Моменты выпуска и истечения приходят ИЗ ПОДПИСАННОГО токена, а не считаются
// заново вызывающим. Второй расчёт того же предмета разошёлся бы с первым молча
// — и разошёлся бы в ту сторону, где предъявитель считает cluster-admin
// удостоверение умершим, пока край его ещё принимает.
type MintOutput struct {
	AccessToken string
	IssuedAt    time.Time
	ExpiresAt   time.Time
}

// ErrMintingUnavailable — выпустить сейчас нечем: подписывающего ключа нет либо
// ключница недоступна.
//
// ЗАМЕНА, А НЕ ПЕРЕИМЕНОВАНИЕ прежнего `ErrIssuerUnavailable`. Прежний признак
// назывался недоступностью ИЗДАТЕЛЯ, и на пути, где издателя нет, он послал бы
// оператора чинить сторону, до которой процесс не достаёт ни разу. Предмет у
// признака теперь свой: наша ключница.
var ErrMintingUnavailable = errors.New("bootstrap token: minting is unavailable")

// LocalMinter — НАШ подписант с точки зрения контура бутстрапа.
//
// Порт объявлен здесь, у вызывающего: контур не знает ни про ключницу, ни про
// обёртку приватной половины, ни про то, каким алгоритмом подписано и какой
// состав утверждений кладётся в токен.
type LocalMinter interface {
	MintToken(ctx context.Context, in MintInput) (MintOutput, error)
}
