package modulecatalog

// observe.go — применение каталога СДВИГАЕТ СЧЁТЧИК, а не только строку журнала
// (задача продукта #1963).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ЭТО, ЕСЛИ ПЕРЕПИСЬ УЖЕ ПЕЧАТАЕТСЯ
//
// Перепись печатается журналом на старте, и число оператору ДОСТАЁТСЯ — если он
// этот журнал читает. В три часа ночи вопрос стоит иначе, чем при разборе:
// «каталог отстал» или «продукт сломан». Журнал отвечает на него после того, как
// найден нужный под, нужный старт и нужная строка; счётчик отвечает сразу.
//
// ─────────────────────────────────────────────────────────────────────────────
// ВЕЛИЧИН ТРИ, И ОДНОЙ НЕ ХВАТАЕТ НИ НА ОДИН ИЗ ТРЁХ ВОПРОСОВ
//
//	применений ноль    → применитель не ходил вовсе (знаменатель)
//	снятий ноль        → каталог не менялся
//	переселений ноль   → снятие БЫЛО, но ни одной роли не задело
//
// Оставь одни переселения — и ноль будет означать сразу три разных состояния, из
// которых одно (мёртвый применитель) выглядело бы здоровее всех. Сложи снятия с
// переселениями — и потеряешь ровно то различие, ради которого перепись
// применителя и держит две популяции порознь: «право отобрано» и «правило
// перестало резолвиться» — разные события для того, кто разбирает последствия.
//
// ─────────────────────────────────────────────────────────────────────────────
// ГРАНИЦА НАЗВАНА: ОТКАЗ НА ПУТИ СТАРТА МЕТРИКОЙ НЕ НАБЛЮДАЕМ
//
// Исход `failed` производителя имеет — его эмитит всякий отказ `Apply`, — но на
// пути СТАРТА он неснимаем by construction: отказ применения есть отказ пуска
// (`module-catalog-applier-runs-at-boot.md`), а слушатель метрик поднимается
// позже применителя, и процесс до него не доживает. Наблюдаем такой отказ по
// отсутствию процесса и по журналу.
//
// Исход объявлен всё равно, и это не задел «на будущее»: `Apply` — глагол, а не
// шаг старта, и второй его вызывающий (`ModuleService.Apply`, заказан #1034)
// отказ переживает. Счётчик, объявленный только для удавшегося, пришлось бы
// заводить заново вместе с ним — и до тех пор «отказов ноль» означало бы
// «отказов не бывает».
//
// ─────────────────────────────────────────────────────────────────────────────
// НАБЛЮДАТЕЛЬ НЕОБЯЗАТЕЛЕН — И ЭТО РЕШЕНИЕ
//
// Применитель без наблюдателя работает ровно так же: метрика есть наблюдение за
// глаголом, а не условие его исполнения. Сделав её обязательной, мы уронили бы
// всякого вызывающего, метрик не завёдшего, — на пути СТАРТА, то есть в самом
// дорогом месте.

// Исходы применения. Набор ЗАКРЫТ и приходит отсюда, никогда из запроса, поэтому
// кардинальность метрики не растёт с трафиком.
const (
	// ApplyOutcomeApplied — транзакция модуля закоммичена.
	ApplyOutcomeApplied = "applied"
	// ApplyOutcomeFailed — применение отвергнуто; каталог остался прежним.
	ApplyOutcomeFailed = "failed"
)

// Виды снятой строки каталога. Набор ЗАКРЫТ.
const (
	// RetiredKindResource — помечена снятой строка ресурса.
	RetiredKindResource = "resource"
	// RetiredKindVerb — помечена снятой строка действия.
	RetiredKindVerb = "verb"
)

// Популяции переселённых проекций арендаторских ролей. Набор ЗАКРЫТ и повторяет
// популяции `Resettled`: «право отобрано» и «правило перестало резолвиться» —
// разные события, и сложив их, мы потеряли бы именно это различие.
const (
	// ResettledPopulationRuleRef — правило перестало резолвиться.
	ResettledPopulationRuleRef = "rule_ref"
	// ResettledPopulationRoleVerb — право отобрано.
	ResettledPopulationRoleVerb = "role_verb"
)

// Observer — ПОРТ наблюдения за применением. Объявлен ЗДЕСЬ, в use-case: он
// описывает потребность, а не реестр коллекторов.
//
// Величины приходят ПРИМИТИВАМИ, а не переписью: реализация живёт в пакете
// метрик, и знать ей о `Report` незачем — иначе наблюдение стало бы вторым
// читателем формы, который разойдётся с первым при первой же её правке.
type Observer interface {
	// IncCatalogApply — исход применения ОДНОГО манифеста.
	IncCatalogApply(outcome string)
	// AddCatalogRetiredRows — сколько строк каталога помечено снятыми, по виду.
	AddCatalogRetiredRows(kind string, n int)
	// AddCatalogResettledProjections — сколько проекций переселено, по популяции.
	AddCatalogResettledProjections(population string, n int)
}

// WithObserver возвращает применитель, докладывающий наблюдателю. Нулевой
// наблюдатель законен и означает «не наблюдаем».
func (a *Applier) WithObserver(obs Observer) *Applier {
	a.obs = obs
	return a
}

// observe докладывает исход применения ОДНОГО манифеста.
//
// Зовётся ПОСЛЕ того, как транзакция закрыта, и никогда изнутри: строки,
// сосчитанные откаченной транзакцией, в базе не появились, а счётчик, назвавший
// их, лгал бы ровно в том состоянии, ради разбора которого его и читают.
//
// Ноль не докладывается: `Add(0)` заводит серию, которой нечего сказать, а
// отсутствие серии у пары «модуль × вид» и есть ответ «ни разу не было».
func (a *Applier) observe(rep Report, err error) {
	if a.obs == nil {
		return
	}
	if err != nil {
		a.obs.IncCatalogApply(ApplyOutcomeFailed)
		return
	}
	a.obs.IncCatalogApply(ApplyOutcomeApplied)
	if rep.RetiredResources > 0 {
		a.obs.AddCatalogRetiredRows(RetiredKindResource, rep.RetiredResources)
	}
	if rep.RetiredVerbs > 0 {
		a.obs.AddCatalogRetiredRows(RetiredKindVerb, rep.RetiredVerbs)
	}
	if rep.Resettled.RuleRefs > 0 {
		a.obs.AddCatalogResettledProjections(ResettledPopulationRuleRef, rep.Resettled.RuleRefs)
	}
	if rep.Resettled.RoleVerbs > 0 {
		a.obs.AddCatalogResettledProjections(ResettledPopulationRoleVerb, rep.Resettled.RoleVerbs)
	}
}
