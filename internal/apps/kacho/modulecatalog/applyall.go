package modulecatalog

// applyall.go — применение ВСЕЙ доставки как одного действия (задача #1034).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ГЛАГОЛ ЗДЕСЬ, А НЕ ЦИКЛОМ В КОМПОЗИЦИОННОМ КОРНЕ
//
// Корень провязывает, а не решает. Что доставка применяется МОДУЛЬ ЗА МОДУЛЕМ;
// что порядок детерминирован и равен порядку подачи; что первый отказ
// ОСТАНАВЛИВАЕТ применение и называет модуль; что перепись складывается по всем
// модулям — это решения о поведении глагола, и жить им рядом с глаголом.
// Написанные циклом в `serve.go`, они переписывались бы заново всяким, кто
// заведёт второго вызывающего (`ModuleService.Apply` — заказан там же, #1034), и
// разошлись бы с этим молча.
//
// ─────────────────────────────────────────────────────────────────────────────
// ТРАНЗАКЦИЯ — ПО МОДУЛЮ, И ЭТО РЕШЕНИЕ, А НЕ УДОБСТВО
//
// Каждый манифест ложится СВОЕЙ транзакцией. Общая транзакция на всю доставку
// выглядит строже и ею не является: инварианта, охватывающего два модуля, у
// каталога НЕТ by construction — строки адресуются парой «модуль.ресурс», а
// проекция правила, теряющая референт вместе со снимаемой строкой, переселяется
// в той же транзакции, что и снятие, которое её осиротило (см. `apply.go`, шаг 4).
//
// Чем платим, названо числом, а не умолчанием: отказ на k-м манифесте оставляет
// применёнными k−1 предыдущих. Это состояние ОГРАНИЧЕНО и СХОДИТСЯ САМО, потому
// что вызывающий на пути старта отвечает на отказ ОТКАЗОМ ПУСКА (см.
// `services/iam/docs/engineering/architecture/module-catalog-applier-runs-at-boot.md`),
// а применение идемпотентно: следующий подъём повторяет обход с первого модуля и
// либо доходит до конца, либо отказывает на том же месте с тем же текстом.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПЕРВЫЙ ОТКАЗ ОСТАНАВЛИВАЕТ, А НЕ ПРОПУСКАЕТСЯ
//
// Соблазн «применить остальные и вернуть перечень отказов» отвергнут: применитель
// есть ПРОИЗВОДИТЕЛЬ каталога, и «часть модулей применилась, часть нет» — это
// состояние, которое оператору нечем разобрать, если продолжать после первого
// отказа. Остановка делает состояние функцией ОДНОГО названного модуля: всё до
// него применено, он и всё после — нет.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПУСТАЯ ДОСТАВКА — НЕ ОТКАЗ ЭТОГО ГЛАГОЛА
//
// «Доставка объявлена и сорвана» отвергает ЧИТАТЕЛЬ доставки
// (`manifest.LoadDelivered`), и до применителя такое состояние не доходит вовсе.
// Сюда пустой перечень приходит ровно из одного законного состояния — доставка
// посадкой не объявлена, — и применять тогда нечего. Отвергнув его здесь, мы
// уронили бы всякую посадку, доставку не заведшую, то есть завели бы отказ,
// предмет которого уже закрыт соседом.

import (
	"context"
	"fmt"

	"github.com/PRO-Robotech/kacho-iam/internal/manifest"
)

// Census — перепись применения ВСЕЙ доставки.
//
// Складывается по модулям, но `Applied` и `ChangedModules` держатся отдельно от
// сумм строк намеренно: «применено шесть манифестов, изменений ноль» и «применён
// один манифест, изменений ноль» — разные утверждения о состоянии платформы, а
// сумма строк у них одна и та же.
type Census struct {
	// Applied — манифестов применено ПОЛНОСТЬЮ (транзакция закоммичена).
	Applied int
	// ChangedModules — из них тех, чьё применение сдвинуло хоть одну строку.
	ChangedModules int
	// Modules — имена применённых модулей, в порядке применения. Перепись, а не
	// поиск: «применено шесть» не отличается от «применено шесть копий одного»,
	// пока имена не названы.
	Modules []string
	// Строки, сложенные по всем модулям.
	WrittenResources int
	WrittenVerbs     int
	RetiredResources int
	RetiredVerbs     int
	// Resettled — переселённые проекции арендаторских ролей, по популяциям.
	Resettled Resettled
	// PrunedSelectorRows / PrunedSelectorTypes — приведение третьей проекции
	// правила к каталожному факту (`prune.go`).
	PrunedSelectorRows        int
	PrunedSelectorRowsDropped int
	PrunedSelectorTypes       int
}

// Changed — применение доставки сдвинуло каталог хоть в одном модуле.
//
// Это и есть ответ на «идемпотентно ли применение доставки целиком»: второй
// подряд подъём обязан вернуть ложь. Не «прошло без ошибки» — прошло бы и
// притворство.
func (c Census) Changed() bool { return c.ChangedModules > 0 }

// String — перепись одной строкой.
func (c Census) String() string {
	return fmt.Sprintf(
		"применено манифестов %d (%v) · изменивших каталог %d · записано ресурсов %d "+
			"глаголов %d · снято ресурсов %d глаголов %d · переселено правил %d выдач %d · "+
			"селекторов укорочено %d снято %d элементов вырезано %d · изменения %t",
		c.Applied, c.Modules, c.ChangedModules,
		c.WrittenResources, c.WrittenVerbs,
		c.RetiredResources, c.RetiredVerbs,
		c.Resettled.RuleRefs, c.Resettled.RoleVerbs,
		c.PrunedSelectorRows, c.PrunedSelectorRowsDropped, c.PrunedSelectorTypes,
		c.Changed())
}

// add складывает перепись одного модуля в общую.
func (c *Census) add(rep Report) {
	c.Applied++
	c.Modules = append(c.Modules, rep.Module)
	if rep.Changed() {
		c.ChangedModules++
	}
	c.WrittenResources += rep.WrittenResources
	c.WrittenVerbs += rep.WrittenVerbs
	c.RetiredResources += rep.RetiredResources
	c.RetiredVerbs += rep.RetiredVerbs
	c.Resettled.RuleRefs += rep.Resettled.RuleRefs
	c.Resettled.RoleVerbs += rep.Resettled.RoleVerbs
	c.PrunedSelectorRows += rep.PrunedSelectorRows
	c.PrunedSelectorRowsDropped += rep.PrunedSelectorRowsDropped
	c.PrunedSelectorTypes += rep.PrunedSelectorTypes
}

// ApplyAll применяет доставленные манифесты ПО ОДНОМУ, в порядке подачи, и
// возвращает перепись вместе с исходом.
//
// Перепись возвращается ВСЕГДА, включая отказ: без неё «отказ на первом
// манифесте» не отличается от «отказ на последнем», а чинятся эти два состояния
// по-разному.
func (a *Applier) ApplyAll(ctx context.Context, manifests []*manifest.Manifest) (Census, error) {
	var census Census
	for _, m := range manifests {
		rep, err := a.Apply(ctx, m)
		if err != nil {
			// Имя модуля берётся у РАЗОБРАННОГО манифеста, а не у пути файла:
			// путь доставки есть ключ ConfigMap и с именем модуля не совпадает
			// by construction (`manifest/delivery.go`, «почему имя судится иначе»).
			return census, fmt.Errorf(
				"применение манифеста модуля %q (по счёту %d, применено до него %d): %w",
				m.Module, census.Applied+1, census.Applied, err)
		}
		census.add(rep)
	}
	return census, nil
}
