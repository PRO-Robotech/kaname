package moduleroles

// retire.go — ТРИГГЕР ОТЗЫВА: роль, чьё объявление убрано из манифеста,
// помечается снятой.
//
// Приёмка `services/iam/docs/engineering/acceptance/role-withdrawal-has-a-producer.md`
// (APPROVED круга 4), §2.2, §2.5; сценарии IAM-RW-1-05 … -09, -24. Задача
// продукта #1913.
//
// # Состояний раздела `roles:` ТРИ, а не два
//
//	не объявлен          «сверять не с чем»            снятий НЕТ ни одного
//	объявлен и пуст      «ролей у модуля нет»          снимаются ВСЕ его роли
//	объявлен с перечнем  обычный случай                снимаются те, кого в нём нет
//
// Первое и второе дают одинаковый `len(Manifest.Roles) == 0`, поэтому различить
// их ПО СРЕЗУ нельзя: дискриминатор приезжает значением (`Manifest.RolesDeclared`).
// Цена схлопывания названа прямо: манифест, потерявший ключ `roles:` при правке
// соседнего раздела либо при обрезанной доставке, под схлопнутым прочтением снял
// бы ВСЕ роли модуля.
//
// # Снятием НЕ является — три случая, и каждый назван
//
//  1. манифест модуля НЕ ДОСТАВЛЕН вовсе. Причина отсутствия системе неизвестна
//     — удаление, конфликт слияния, неполный ConfigMap и откат выглядят
//     одинаково. Это решение принято `#1034` и здесь не пересматривается;
//     исполняется оно ВЫШЕ: применитель зовётся по доставленным манифестам, и
//     недоставленный сюда не доходит by construction;
//  2. роль принадлежит ДРУГОМУ модулю — её объявление принадлежит его манифесту.
//     Сверка относит такую строку в класс `OtherModule` и не отдаёт её сюда;
//  3. у роли НЕТ модуля-владельца (`admin`, `edit`, `view`, `owner`,
//     `kacho-system.*`) — манифестом они невыразимы by construction. Сверка
//     относит их в класс `WithoutOwner`, а оператор пометки СВЕРХ ТОГО сужен
//     `owner_module = $модуль`: сужения по `is_system` одного было бы мало, оно
//     истинно у всех платформенных ролей сразу.
//
// # Отказ отзыва — ОТКАЗ ПРИМЕНЕНИЯ, а не пропуск
//
// Мягкий проход дал бы производителя, не произведшего ни разу и не сказавшего об
// этом. Предмет здесь — ПРАВО: роль, чьи проекции сняты наполовину, даёт меньше
// объявленного, и отличить это от работающей можно только вызовом.

import (
	"context"
	"fmt"

	"google.golang.org/grpc/codes"

	"github.com/PRO-Robotech/kacho/services/iam/internal/domain"
	"github.com/PRO-Robotech/kacho/services/iam/internal/manifest"
)

// BootActorID — НАЗВАННЫЙ процессный актор пути старта.
//
// Имя своё, а не общее с каталогом: два предмета, два автора, и слитое имя
// сделало бы невозможным вопрос «кто именно снял эту роль» ровно тогда, когда
// его задают. Подставленного `system` здесь не бывает — `Apply` отвергает пустого
// автора до открытия транзакции.
const BootActorID = "iam-module-roles-boot"

// retirementReason — причина, которую читает арендатор у отобранного права.
//
// Текст ОДИН на все снятия этой полосы и называет ПРЕДМЕТ, а не механизм:
// «манифест перестал объявлять» отвечает на вопрос арендатора, тогда как
// «LiveNotDeclared» отвечает на вопрос разработчика.
func retirementReason(module string) string {
	return fmt.Sprintf("манифест модуля %s перестал объявлять эту роль", module)
}

// retire снимает роли модуля, которых больше нет в его объявленном разделе.
//
// Исполняется в ТОЙ ЖЕ транзакции, что запись объявленных: применение, часть
// которого записалась, а часть сняла, обязано откатываться целиком — иначе между
// двумя половинами помещается чужое чтение вердикта.
// Отобранного среза объявленных ролей здесь НЕТ намеренно, и это не упущение:
// снятие судит «объявлена ли роль ВООБЩЕ», а запись — «объявлена ли она
// кластерного яруса». Подай сюда отобранный срез — и роль иного яруса, которую
// применитель законно пропускает, стала бы для сверки НЕобъявленной, то есть
// снималась бы. Сверка получает перечень КАК ЕГО НАПИСАЛИ (`m.Roles`).
func (a *Applier) retire(
	ctx context.Context,
	w RoleWriter,
	m *manifest.Manifest,
	actor string,
	rep *Report,
	failed *domain.RoleName,
) error {
	// Раздел не объявлен — «сверять не с чем». Проверка стоит ЗДЕСЬ ЖЕ, а не
	// только у вызывающего: у транзакции может появиться второй вызывающий, и
	// решение о снятии обязано принимать одно место.
	if !m.RolesDeclared() {
		return nil
	}

	live, lerr := w.LiveSystemRoles(ctx)
	if lerr != nil {
		return fmt.Errorf("%w: живые системные роли: %w", ErrWriteFailed, lerr)
	}

	// Сверка получает ПОЛНУЮ популяцию живых системных ролей и объявленный
	// перечень КАК ЕГО НАПИСАЛИ. Классификацию по владельцу делает она: второй
	// классификатор рядом разошёлся бы с первым молча — на обычном манифесте оба
	// отвечают одинаково.
	found, census := Reconcile(m.Module, m.Roles, live)
	reason := retirementReason(m.Module)

	for _, d := range found {
		if d.Kind != LiveNotDeclared {
			// `DeclaredNotLive` — след того, что писатель до строки не дошёл. Он
			// не снятие и исхода здесь не имеет: снимать нечего.
			continue
		}
		id := domain.SystemRoleID(d.Name)
		out, rerr := w.RetireRole(ctx, id, m.Module, reason, actor)
		if rerr != nil {
			*failed = d.Name
			return fmt.Errorf("%w: %s: %w", ErrWriteFailed, d.Name, rerr)
		}
		rep.Resettled += out.ResettledVerbs + out.ResettledRuleRefs
		// Снятые проекции считаются ОТДЕЛЬНО от переселённых, потому что это
		// разные утверждения о платформе: переселённое ушло в ведомость и
		// объяснено арендатору, снятое — нет (у строки отбора нет пары «тип +
		// глагол», которой адресуются сироты, а состав цели материализует чужую
		// выдачу). Слить их в одно число значило бы объявить объяснённым то,
		// чего никто не объяснял.
		rep.Removed += out.RemovedSelectors + out.RemovedTargetMembers
		if !out.Marked {
			// Недостижимо: писатель отвергает расхождение владения ОТКАЗОМ, а не
			// пустым исходом (`RetireRole`). Ветвь оставлена сторожем: молчаливое
			// «снимать нечего» здесь означало бы роль без прав и с виду исправную,
			// и увидеть это было бы нечем.
			*failed = d.Name
			return fmt.Errorf("%w: %s: писатель не пометил строку и не отказал",
				ErrWriteFailed, d.Name)
		}
		rep.Retired++
		rep.RetiredNames = append(rep.RetiredNames, string(d.Name))
	}

	// Перепись сверки печатается вызывающим вместе с переписью применения: числа
	// «живых осмотрено» и «без модуля-владельца» отвечают на вопрос, который
	// счётчик снятых не закрывает, — сверяли ли вообще что-нибудь.
	rep.Census = census
	return nil
}

// retirementRefusal — отказ полосы неназванного автора.
//
// Отдельная полоса, а не «отказ записи»: чинится он ПРОВЯЗКОЙ вызывающего, а не
// состоянием базы и не входом манифеста, и следующий шаг у них разный.
func retirementRefusal(module string, werr error) error {
	return refuse(codes.FailedPrecondition, werr.Error(),
		LaneRetirementActorUnnamed, module, "", werr)
}
