package seed

// role_rule_ref_reseed.go — досев проекции ОБЪЯВЛЕННЫХ СЕГМЕНТОВ правила
// (`kacho_iam.role_rule_ref`) для системных ролей (kacho#1821).
//
// # Зачем эта полоса
//
// Правило роли читают с ТРЁХ сторон: селекторы отвечают «подходит ли объект»,
// проекция глаголов — «разрешено ли действие», проекция объявленных сегментов
// держит РЕФЕРЕНТ: ключи `role_rule_ref_res_fk` (в живую строку каталога
// ресурсов) и `role_rule_ref_verb_fk` (в каталог глаголов). Первые две
// пересчитывает старт; третью до этой полосы писал только путь ПОЛЬЗОВАТЕЛЬСКОЙ
// роли (`Role.Create`/`Role.Update`) и однократное обратное заполнение миграции.
//
// Системная роль заводится сырым SQL миграции и путём пользовательской роли не
// проходит НИКОГДА. Значит у роли, заведённой БУДУЩЕЙ миграцией, строк проекции
// сегментов не появлялось бы вовсе: ключи оказывались бы ни при чём, а
// молчаливый пропуск — правило, называющее ресурс, которого нет, — вернулся бы
// для системной половины. Ровно тот класс, что уже закрывался для селекторов
// (`SyncAllSystemRoleSelectors`) и для проекции глаголов
// (`ReseedSystemRoleVerbs`): тихий близнец переживает громкого.
//
// # Почему СВОЯ полоса, а не строка в пересчёте глаголов
//
// У полос разные предметы и разные полосы отказа. Проекция глаголов — то, из
// чего цепь вердикта собирает ответ «разрешено ли действие»: её отсутствие есть
// МОЛЧАЛИВЫЙ отказ в доступе. Проекция сегментов — референт, то есть страж
// целостности: её отсутствие не отнимает доступа, оно снимает проверку. Сведи их
// в одну транзакцию — и отказ стража откатывал бы проекцию вердикта, то есть
// отнимал бы доступ по причине, к доступу отношения не имеющей.
//
// Зернистость та же и по той же причине: ОДНА ТРАНЗАКЦИЯ НА РОЛЬ. Инвариант,
// который обязан удержаться, — внутри роли («снять всё, положить текущее»);
// между ролями атомарности нет и не требуется, потому что строки одной роли
// вердикта по другой не читают.
//
// # Каталожный факт здесь НЕ спрашивается — и это не упущение
//
// Пересчёт глаголов берёт пары у снимка каталога: он материализует то, что
// модель знает. Сегменты производятся из АВТОРСКОГО правила
// (`domain.RuleRefsOf`), потому что предмет ключа — ровно те сегменты, которые
// словарь модели потерял бы. Спроси мы каталог, страж перестал бы стеречь: он
// принимал бы на вход уже отфильтрованное и не мог бы отвергнуть ничего.
// Живость же строки каталога судит БАЗА — тем самым ключом, ради которого
// проекция и заведена.
//
// # Своего SQL ЗАПИСИ здесь НЕТ — писателя зовут ЧЕРЕЗ ПОРТ
//
// Писатель проекции в дереве один — `RolesW().ReplaceRuleRefs` порта записи.
// Досев решает лишь КОГДА и ДЛЯ КАКИХ ролей пересчитывать; форма строки,
// отображение отказов и транзакционность ему не принадлежат. Перечень ролей
// читается тем же запросом, что у пересчёта глаголов
// (`listMaterializingSystemRoles`), и по той же причине идёт мимо реплики: на
// старте её отставание наиболее вероятно, а пустой перечень дал бы «осмотрено 0,
// пересеяно 0» — старт прошёл бы, проекция не пересеялась бы, и сказать об этом
// было бы некому.

import (
	"context"
	"errors"
	"fmt"

	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/PRO-Robotech/kacho-iam/internal/apps/kacho/shared"
	"github.com/PRO-Robotech/kacho-iam/internal/domain"
	kachorepo "github.com/PRO-Robotech/kacho-iam/internal/repo/kacho"
)

// Исходы пересчёта одной роли — закрытый набор, приходит из констант этого
// пакета и никогда из запроса, поэтому кардинальность метки не растёт с
// трафиком.
const (
	// RuleRefReseedOutcomeReseeded — транзакция роли закоммичена.
	RuleRefReseedOutcomeReseeded = "reseeded"
	// RuleRefReseedOutcomeFailed — транзакция роли откачена.
	RuleRefReseedOutcomeFailed = "failed"
)

// RuleRefReseedObserver — куда досев сообщает исход по каждой роли.
//
// Успехи считаются наравне с отказами: счётчик одних отказов не отличает
// «отказов не было» от «пересчёта не было вовсе», и путь, умерший целиком,
// выглядел бы здоровее всех.
type RuleRefReseedObserver interface {
	IncRuleRefReseed(outcome string)
}

// RuleRefReseedCensus — перепись одного прогона досева.
//
// «Пересеяно» считает ЗАКОММИЧЕННЫЕ роли, а не начатые: при зернистости по роли
// транзакция роли либо закоммичена, либо нет, и называть надо первое.
type RuleRefReseedCensus struct {
	// Examined — системных ролей с непустыми правилами прочитано.
	Examined int
	// Reseeded — ролей, чья транзакция закоммичена.
	Reseeded int
	// Refs — сегментов, объявленных правилами закоммиченных ролей.
	Refs int
	// Failed — ролей, чья транзакция откачена.
	Failed int
}

// Structural — полоса, на которой повтор даст то же самое: роли есть, пересеяна
// ни одна. Пустое множество ролей структурной полосой НЕ является — это свежая
// база, и роняя на ней старт, проверка краснела бы на достижении цели.
func (c RuleRefReseedCensus) Structural() bool {
	return c.Examined > 0 && c.Reseeded == 0
}

// ReseedSystemRoleRuleRefs пересчитывает проекцию объявленных сегментов КАЖДОЙ
// системной роли, каждую роль — в собственной транзакции.
//
// Отказ на одной роли не прерывает обход: остальные обязаны быть пересеяны, и
// именно это отличает «база моргнула на одной строке» от «механизм не работает».
// Возвращается перепись (всегда, в том числе при отказе) и объединённая ошибка,
// чей текст несёт ОБЕ величины переписи: без них «пересеяно ноль» неотличимо от
// «пересеяно не всё».
//
// Наблюдатель необязателен: `nil` означает «исходы никуда не считать» — так его
// зовут операционные точки входа, у которых реестра метрик нет.
func ReseedSystemRoleRuleRefs(
	ctx context.Context,
	repo kachorepo.Repository,
	pool *pgxpool.Pool,
	obs RuleRefReseedObserver,
) (RuleRefReseedCensus, error) {
	var census RuleRefReseedCensus

	roles, err := listMaterializingSystemRoles(ctx, pool)
	if err != nil {
		return census, err
	}
	census.Examined = len(roles)

	var failures []error
	for _, rr := range roles {
		refs := domain.RuleRefsOf(rr.rules)
		if rerr := replaceRuleRefsInOwnTx(ctx, repo, rr.id, refs); rerr != nil {
			census.Failed++
			failures = append(failures, rerr)
			if obs != nil {
				obs.IncRuleRefReseed(RuleRefReseedOutcomeFailed)
			}
			continue
		}
		census.Reseeded++
		census.Refs += len(refs)
		if obs != nil {
			obs.IncRuleRefReseed(RuleRefReseedOutcomeReseeded)
		}
	}
	if len(failures) == 0 {
		return census, nil
	}
	return census, fmt.Errorf(
		"пересчёт проекции сегментов правила: осмотрено %d, пересеяно %d, отказало %d: %w",
		census.Examined, census.Reseeded, census.Failed, errors.Join(failures...))
}

// replaceRuleRefsInOwnTx — одна роль, одна транзакция порта записи.
//
// Замена «снять всё, положить текущее» обязана быть атомарной по той же причине,
// что у соседней полосы: читатель не вправе увидеть пустой промежуток, в котором
// правило выглядит не объявляющим ничего.
//
// Пустой набор сегментов — законный вход, а не пропуск: правило из одних
// подстановок (`*.*`) конкретных сегментов не даёт, и его прежние строки обязаны
// быть СНЯТЫ. Пропусти мы такую роль — проекция пережила бы своё правило.
func replaceRuleRefsInOwnTx(
	ctx context.Context,
	repo kachorepo.Repository,
	roleID string,
	refs []domain.RoleRuleRef,
) error {
	if err := shared.DoWithWriteTxVoid(ctx, repo,
		func(ctx context.Context, w kachorepo.Writer) error {
			return w.RolesW().ReplaceRuleRefs(ctx, domain.RoleID(roleID), refs)
		}); err != nil {
		return fmt.Errorf("пересчёт проекции сегментов роли %s: %w", roleID, err)
	}
	return nil
}
