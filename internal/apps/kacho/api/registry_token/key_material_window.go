// key_material_window.go — ОКНО ПЕРЕХОДА ЛОМАЮЩЕГО ИЗМЕНЕНИЯ #1143 и счётчик
// полос предъявленного удостоверения.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ОКНО ВООБЩЕ
//
// Введение базового токена (#1142) и снятие приёма ключевого материала (#1143)
// уезжают ОДНИМ образом. Для арендатора между «до» и «после» нет состояния, в
// котором работает хоть что-то: выпустить удостоверение нового вида до
// обновления нельзя — глагол выдачи ещё прежний; войти прежним после — тоже,
// приём снят. Окно — то состояние, в котором работают ОБА, пока оператор
// переводит клиентов.
//
// Отдельно: выдача ключа служебной учётки ПО-ПРЕЖНЕМУ отдаёт KEYPAIR, когда вид
// не назван (`domain.ResolveIssuedKind`, сохранённое дословно прежнее
// поведение). То есть без окна ломается не только уже настроенный клиент, но и
// умолчание глагола выдачи этого же выпуска.
//
// ─────────────────────────────────────────────────────────────────────────────
// ОКНО — МГНОВЕНИЕ, А НЕ ФЛАЖОК, И ЭТО ЕГО САМОИСТЕЧЕНИЕ
//
// Ручка задаётся МОМЕНТОМ ВРЕМЕНИ, до которого окно открыто. Бессрочное окно ею
// НЕВЫРАЗИМО by construction — и это и есть предикат снятия, вписанный в саму
// ручку, а не обещанный рядом с ней.
//
// Флажок «принимать оба» был бы послаблением без предиката снятия: он
// закрывается тогда, когда кто-то вспомнит, то есть никогда. Ломающее изменение
// в этом случае не наступает вовсе, а его предмет — приватная половина пары,
// идущая по сети и оседающая в конфигурации клиента, — остаётся навсегда и
// молча. Ровно класс «контроль открыт навсегда и молча».
//
// ─────────────────────────────────────────────────────────────────────────────
// УМОЛЧАНИЕ — ОКНО ЗАКРЫТО. ЦЕНА ОБОИХ ВАРИАНТОВ НАЗВАНА
//
// Закрыто по умолчанию (выбрано):
//
//	цена — контур, обновившийся без правки настройки, ломает `docker login`
//	всем арендаторам в момент раската. Отказ — 401, неотличимый от «неверный
//	секрет», поэтому арендатор читает его как поломку своего удостоверения.
//	Восстановление: объявить окно и перекатить — минуты работы оператора.
//	ПЛАТА ОГРАНИЧЕНА И НАБЛЮДАЕМА: счётчик ниже показывает отказы прежнему виду
//	с первой же минуты после раската, то есть оператор узнаёт о поломке из
//	наблюдения, а не из жалобы.
//
// Открыто по умолчанию (отвергнуто):
//
//	цена — контур, обновившийся и не закрывший окно, принимает приватный ключ в
//	поле пароля БЕССРОЧНО И МОЛЧА. Ломающее изменение не наступает, его предмет
//	остаётся, и ничто об этом не сообщает: у послабления, включённого по
//	умолчанию, нет предмета, который мог бы истечь. ПЛАТА НЕОГРАНИЧЕНА И
//	НЕНАБЛЮДАЕМА.
//
// Решает асимметрия ОБРАТИМОСТИ: ошибку первого варианта оператор исправляет
// правкой настройки за минуты; ошибку второго он не замечает годами.
//
// ─────────────────────────────────────────────────────────────────────────────
// СЧЁТЧИК СЧИТАЕТ ТРИ ИСХОДА, А НЕ ОДИН
//
// Счётчик одних отказов не отличает «отказов не было» от «входов не было
// вовсе»: и там и там ноль, и полоса, умершая целиком, выглядела бы здоровее
// всех. Поэтому знаменатель считается наравне с числителем, а принятое ОКНОМ —
// отдельно от принятого штатно: именно оно и есть предикат закрытия окна.
package registry_token

import "time"

// Исходы полосы предъявленного удостоверения. Набор ЗАКРЫТ и приходит из этих
// констант, никогда из запроса, — кардинальность не растёт с трафиком.
const (
	// OutcomeBasicAccepted — вход принят штатным видом (базовый токен доступа).
	// ЗНАМЕНАТЕЛЬ: без него ноль отказов неотличим от мёртвой полосы.
	OutcomeBasicAccepted = "basic_accepted"

	// OutcomeKeyMaterialAcceptedInWindow — вход принят ПРЕЖНИМ видом через
	// открытое окно перехода. ПРЕДИКАТ ЗАКРЫТИЯ ОКНА: пока он не ноль, клиенты
	// переведены не все, и закрывать окно рано.
	OutcomeKeyMaterialAcceptedInWindow = "key_material_accepted_in_window"

	// OutcomeKeyMaterialRefused — предъявлен прежний вид, а окна нет либо оно
	// истекло. ПРЕДИКАТ НЕОБХОДИМОСТИ ОКНА: не ноль означает, что клиенты,
	// настроенные по-старому, ещё есть, и обновление их уже ломает.
	OutcomeKeyMaterialRefused = "key_material_refused"
)

// CredentialKindObserver — порт счётчика исходов. Реализуется адаптером метрик
// в композиционном корне; use-case о prometheus не знает (clean-arch).
//
// Порт, а не журнал, потому что вопрос оператора количественный: «скольких я
// ещё не перевёл» и «можно ли закрывать окно». Строка журнала на него не
// отвечает — по ней это считают глазами, уже после того как отказ истолкован.
type CredentialKindObserver interface {
	ObserveCredentialKind(outcome string)
}

// WithCredentialKindObserver провязывает счётчик исходов. nil → счёта нет;
// решения полосы это не меняет.
func (u *IssueRegistryTokenUseCase) WithCredentialKindObserver(o CredentialKindObserver) *IssueRegistryTokenUseCase {
	u.kindObserver = o
	return u
}

// WithKeyMaterialWindow объявляет окно перехода.
//
// Мгновение и проверяющий передаются ОДНИМ вызовом намеренно: порознь они дают
// два неисправных состояния, и оба выглядят настроенными. Окно без
// проверяющего — объявленная и неисполнимая ручка (оператор считает, что
// принимает оба вида, а полоса отвергает прежний). Проверяющий без окна —
// ничем не ограниченный приём снятого вида, то есть отменённое ломающее
// изменение. Связав их, мы делаем оба состояния невыразимыми.
//
// Нулевое мгновение либо nil-проверяющий — окна нет; это УМОЛЧАНИЕ.
func (u *IssueRegistryTokenUseCase) WithKeyMaterialWindow(until time.Time, v CredentialValidator) *IssueRegistryTokenUseCase {
	if until.IsZero() || v == nil {
		u.kmWindowUntil = time.Time{}
		u.kmValidator = nil
		return u
	}
	u.kmWindowUntil = until
	u.kmValidator = v
	return u
}

// keyMaterialWindowOpen — открыто ли окно ПРЯМО СЕЙЧАС.
//
// Спрашивается на КАЖДОМ запросе, а не запоминается при сборке: окно закрывает
// время, и посадка, поднятая до объявленного мгновения, обязана закрыть его
// сама, без перезапуска и без чьего-либо решения.
func (u *IssueRegistryTokenUseCase) keyMaterialWindowOpen() bool {
	if u.kmValidator == nil || u.kmWindowUntil.IsZero() {
		return false
	}
	return u.now().Before(u.kmWindowUntil)
}

// observeKind — счёт одного исхода. Отсутствие счётчика не меняет решения.
func (u *IssueRegistryTokenUseCase) observeKind(outcome string) {
	if u.kindObserver != nil {
		u.kindObserver.ObserveCredentialKind(outcome)
	}
}
