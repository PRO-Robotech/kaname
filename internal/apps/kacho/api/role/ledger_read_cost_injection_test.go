// ledger_read_cost_injection_test.go — доказательство, что пробы соседа
// СПОСОБНЫ упасть (#2001).
//
// # Зачем отдельный файл, а не «и так видно»
//
// Продукт оба свойства уже несёт, поэтому `ledger_read_cost_test.go` зелен с
// первого прогона. Зелёная проба, которая никогда не краснела, неотличима от
// пробы, которая краснеть не умеет, — а именно такой и была прежняя редакция:
// ручки существовали, счётчик рос, утверждений не было ни одного. Заменить одну
// невидимую пустоту другой было бы починкой формы, а не предмета.
//
// # ЧТО ИМЕННО ЗДЕСЬ ДОКАЗЫВАЕТСЯ — и чего доказать нельзя
//
// Доказывается, что утверждения соседа РАЗЛИЧАЮТ дефектное поведение читателя от
// исправного: на дефекте они краснеют, на законном близнеце молчат. Это и есть
// вопрос «не вакуумно ли утверждение».
//
// НЕ доказывается, что дефект внесён в прод-код: подменить прод-читателя проба
// не вправе (ban #13 — проба не трогает прод), поэтому дефект вносится в
// ДУБЛЁРА, а сверяется НАБЛЮДАЕМОЕ — то самое, которое читает утверждение.
// Наблюдаемое совпадает с настоящим дефектом дословно: поролевой читатель даёт
// счётчик, равный числу ролей страницы; помощник, логирующий отказ вместо
// возврата, даёт успешное чтение при недоступной ведомости. Граница названа
// прямо, чтобы её не приняли за большее.
//
// # Инъекция меняет РОВНО ОДИН факт против положительного близнеца
//
// Каждая проба ниже отличается от своего близнеца одной ручкой дублёра, и
// близнец стоит в том же прогоне. Двухфактная инъекция не сказала бы, какая из
// двух правок дала красное.
package role

import (
	stderrors "errors"
	"testing"

	"github.com/stretchr/testify/require"
)

// TestInjection_PerRoleReaderRedensTheCostProbe — инъекция ПЕРВОГО свойства.
//
// Утверждение соседа — `wdCalls == 1` и `psCalls == 1`. Здесь тот же вход подан
// поролевому читателю, и утверждается, что счётчик стал ДРУГИМ: значит проба
// стоимости на этом дефекте краснеет, а не проходит.
func TestInjection_PerRoleReaderRedensTheCostProbe(t *testing.T) {
	// ── дефект ──
	h := pageOfFourRoles(t)
	h.repo.ledgerPerRole = true
	h.wdCalls, h.psCalls = 0, 0

	rows, _, err := h.list()
	require.NoError(t, err, "инъекция обязана менять СТОИМОСТЬ, а не ронять чтение: "+
		"упади оно здесь — красное пришло бы от соседа, и о предмете пробы это не сказало бы ничего")
	require.Len(t, rows, 4)

	require.Equal(t, 4, h.wdCalls,
		"поролевой читатель обязан дать вопрос НА РОЛЬ: четыре роли — четыре вопроса")
	require.Equal(t, 4, h.psCalls, "то же у ведомости вырезания")
	require.NotEqual(t, 1, h.wdCalls,
		"НЕСУЩЕЕ: утверждение соседа `wdCalls == 1` на этом входе обязано ПОКРАСНЕТЬ. "+
			"Совпади оно здесь — проба не различала бы «вопрос один» и «вопрос на роль», "+
			"то есть не измеряла бы ничего")
	require.NotEqual(t, 1, h.psCalls, "то же у ведомости вырезания")

	// ── законный близнец: та же страница БЕЗ инъекции ──
	tw := pageOfFourRoles(t)
	tw.wdCalls, tw.psCalls = 0, 0
	_, _, terr := tw.list()
	require.NoError(t, terr)
	require.Equal(t, 1, tw.wdCalls,
		"законный близнец обязан МОЛЧАТЬ: иначе проба ловила бы форму вызова, а не свойство")
	require.Equal(t, 1, tw.psCalls, "то же у ведомости вырезания")

	t.Logf("осмотрено: страница из 4 ролей; поролевой читатель — переселение %d, вырезание %d; "+
		"законный близнец — %d и %d", h.wdCalls, h.psCalls, tw.wdCalls, tw.psCalls)
}

// TestInjection_SwallowedFailureRedensTheFailClosedProbe — инъекция ВТОРОГО
// свойства.
//
// Утверждение соседа — `require.Error` у обоих чтений при отказавшей ведомости.
// Здесь отказ проглатывается, и утверждается, что чтение стало УСПЕШНЫМ: значит
// проба fail-closed на этом дефекте краснеет.
func TestInjection_SwallowedFailureRedensTheFailClosedProbe(t *testing.T) {
	boom := stderrors.New("ведомость недоступна")

	// ── дефект: отказ проглочен ──
	h := newIntegrityHarness(t)
	r := h.addCustomRole("rol00000000000000i01", ruleOn("vpc", "network", "get"))
	h.project(r, "vpc.network", "get")
	h.repo.ledgerSwallow = true
	h.wdFail, h.psFail = boom, boom

	got, gerr := h.get(r)
	require.NoError(t, gerr,
		"НЕСУЩЕЕ: с проглоченным отказом чтение проходит — значит утверждение соседа "+
			"`require.Error` здесь ПОКРАСНЕЕТ. Не пройди оно — проба не отличала бы "+
			"fail-closed от fail-open")
	require.Empty(t, got.Withdrawn,
		"и роль приезжает БЕЗ записей: со стороны арендатора это неотличимо от роли, "+
			"у которой ничего не отбирали, — ровно то состояние, ради различения которого "+
			"ведомость заведена")
	require.Empty(t, got.PrunedSelectorTypes, "то же у ведомости вырезания")

	// ── законный близнец: тот же отказ БЕЗ проглатывания ──
	tw := newIntegrityHarness(t)
	r2 := tw.addCustomRole("rol00000000000000i02", ruleOn("vpc", "network", "get"))
	tw.project(r2, "vpc.network", "get")
	tw.wdFail = boom

	_, terr := tw.get(r2)
	require.Error(t, terr,
		"законный близнец обязан отказывать: без него утверждение выше зеленело бы "+
			"и у читателя, который не отказывает НИКОГДА")

	// ── второй законный близнец: отказа нет вовсе ──
	ok := newIntegrityHarness(t)
	r3 := ok.addCustomRole("rol00000000000000i03", ruleOn("vpc", "network", "get"))
	ok.project(r3, "vpc.network", "get")
	_, oerr := ok.get(r3)
	require.NoError(t, oerr,
		"без отказа чтение обязано проходить: иначе «отказал» было бы свойством помощника, "+
			"а не ведомости")

	t.Log("осмотрено: проглоченный отказ даёт успешное чтение и пустые ведомости; " +
		"непроглоченный — отказ; отсутствие отказа — успех")
}
