// Package membership — MembershipService: чтение принадлежности человека
// аккаунту на аккаунт-скоупных путях.
//
// # ЕДИНСТВЕННЫЙ ГЕЙТ ЭТИХ ЧТЕНИЙ — ПООБЪЕКТНАЯ ПРОВЕРКА КРАЯ
//
// Второго замка внутри сервиса здесь НЕТ, и это решение, а не пропуск. У запроса
// есть один объект, про который можно задать один вопрос, — аккаунт из пути, — и
// край спрашивает про него модель прав (`viewer` @ `account`) ДО того, как
// вызов дойдёт сюда. Строки при этом и так отбираются по аккаунту из пути
// (условие отбора, а не сужение по правам), поэтому проверка в use-case была бы
// вторым замком к уже закрытой двери — и заодно кодом, который можно забыть в
// следующей ветке.
//
// Прямое следствие, названное вслух: служба НЕ регистрируется на внутреннем
// слушателе. Регистрация неделима по методам — общий слой переписывает ВСЕ
// методы дескриптора, — а на внутреннем слушателе края нет; значит у этих чтений
// там не осталось бы никакой проверки прав вовсе.
package membership

import (
	"context"

	repomembership "github.com/PRO-Robotech/kacho-iam/internal/repo/kacho/membership"
)

// Repo / Session — порты, объявленные ЗДЕСЬ, в use-case, и узкие намеренно:
// довод и его цена записаны у самого порта (`repo/kacho/membership`).
type (
	Repo    = repomembership.Repo
	Session = repomembership.Session
)

// readerOf открывает чтение и возвращает его вместе с закрывающей функцией.
//
// Отдельный помощник, потому что обоим use-case'ам нужен ОДИН порядок:
// открыть — отложить закрытие — читать. Повторённый в двух местах, он рано или
// поздно разойдётся, и разойдётся молча.
func readerOf(ctx context.Context, repo Repo) (repomembership.ReaderIface, func(), error) {
	s, err := repo.MembershipReader(ctx)
	if err != nil {
		return nil, nil, err
	}
	return s.Memberships(), func() { s.Close(ctx) }, nil
}
