// verdict_source.go — секция `authz`: КТО ПРИНИМАЕТ РЕШЕНИЕ О ДОСТУПЕ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ЭТО РУЧКА, А НЕ КОНСТАНТА
//
// Пока источник вердикта выбирается кодом, смена источника — выкатка образа, а
// откат в аварии — ещё одна. Счёт в аварии идёт на минуты, и очередь сборки в
// этот счёт не помещается. Поэтому источник приезжает настройкой и выбирается
// ПО ТИПУ ОБЪЕКТА: радиус ошибки равен одному типу, а не всей платформе.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ДВЕ РУЧКИ, А НЕ ОДНА
//
// «Кто решает» и «сверяем ли вообще» — разные предметы. Слить их значило бы
// сделать выключение сверки невыразимым, пока не переключён хотя бы один тип, —
// а сверка это ФАЗА, и платить за неё на каждом решении вечно никто не
// собирался.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕМ ДЕРЖИТСЯ ДОСТАВКА
//
// Обе ручки едут конфигурационной картой службы, и это безопасно ровно потому,
// что шаблон пода несёт ОТПЕЧАТОК этой карты (`kacho.cloud/config-checksum`):
// правка карты меняет шаблон, под перекатывается, процесс поднимается с новой
// позицией.
//
// Без отпечатка тракт был бы опасен, и опасен тихо: карта читается ОДИН РАЗ при
// старте, её правка шаблон пода не меняет, под не перекатывается — и рубильник
// оказывается «переключён» и не переключён одновременно, причём боевой страж не
// срабатывает, потому что СТАРТА НЕ БЫЛО. Класс наблюдался на этом же стенде,
// поэтому наличие отпечатка проверяется пробой объявления
// (`deploy/verdict_source_declaration_test.go`), а не тем, что кто-то помнит.

package config

import (
	"github.com/PRO-Robotech/kacho/services/iam/internal/verdictsource"
)

// AuthZConfig — секция `authz`.
type AuthZConfig struct {
	// VerdictFormTypes — типы объектов (в словаре МОДЕЛИ прав), решение по
	// которым принимает РЕЛЯЦИОННАЯ ФОРМА, а не внешний движок отношений.
	//
	// Словарь назван, потому что их два, и соединение разных словарей не
	// совпадает никогда и молча: перечень, написанный в словаре каталога
	// (`vpc.network` вместо `vpc_network`), не переключил бы ни одного вопроса и
	// выглядел бы исполненным. Неизвестное имя типа — отказ в старте, а не
	// тихий пропуск.
	//
	// Формат: перечень через запятую в переменной окружения
	// KACHO_IAM_AUTHZ__VERDICT_FORM_TYPES; список YAML под `authz.verdict-form-types`.
	//
	// Пусто (умолчание) — не переключено ничего, решение остаётся за движком.
	// Умолчание названо ЯВНО: источник вердикта о доступе не вправе зависеть от
	// того, чего оператор не написал.
	VerdictFormTypes []string `mapstructure:"verdict-form-types"`

	// ShadowCompare — идёт ли теневая сверка двух форм.
	//
	// Умолчание — ВКЛЮЧЕНО. Выключение это осознанное действие оператора: пока
	// сверка идёт, «расхождений ноль» отличимо от «сравнений ноль», и только на
	// этом различии можно принимать решение о переключении типа.
	//
	// Выключенная сверка НЕ переключает источник и не разрешает переключение:
	// рубильник, названный при выключенной сверке, роняет старт — иначе тип
	// выглядел бы переключённым, а решения продолжали бы идти движком.
	ShadowCompare bool `mapstructure:"shadow-compare"`
}

// VerdictSwitchboard — рубильник, который РЕАЛЬНО доезжает до пути решения.
//
// Единственный источник этого значения на процесс: путь решения, страж старта и
// самоотчёт читают ЭТОТ объект и его ОДИН предикат. Тогда «страж прошёл» ⟺
// «источник действительно переключён» по построению, а не потому, что три
// отдельно написанных тела совпали.
//
// Нормализация перечня (пустые записи, пробелы, повторы) живёт в конструкторе
// типа и здесь не повторяется: два места об одном предмете расходятся молча.
func (a AuthZConfig) VerdictSwitchboard() verdictsource.Switchboard {
	return verdictsource.New(a.VerdictFormTypes...)
}
