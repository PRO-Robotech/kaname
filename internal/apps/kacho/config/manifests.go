// manifests.go — доставка манифестов модулей работающей службе (задача #1875) и
// СБОРКА модели прав установки из доставленного вместе с её допуском (#1971).
//
// Предметов в секции два, и они разные: доставка отвечает «откуда читать»,
// сборка — «участвует ли прочитанное в модели прав и чем эта модель судится».
// Пара доставки объявляется целиком либо не объявляется вовсе; сборка требует
// объявленного допуска И объявленной доставки. Оба стража — ОТКАЗ В ПУСКЕ.
//
// # Предмет
//
// Манифест модуля объявлен источником истины о том, что у платформы существует.
// В дереве он есть — по одному на модуль закрытого набора, — а способа доставить
// его работающей службе не было ни одного: ручки каталога у конфигурации нет,
// монтирования у чарта нет, загрузчик на пути старта никем не зовётся. Пока
// доставки нет, всякая сверка живых строк каталога с ОБЪЯВЛЕННЫМ состоянием
// невыразима: второго операнда у неё не существует (#1861).
//
// # Почему ручка, а не путь константой
//
// Каталог доставки — свойство ПОСАДКИ, а не бинаря: где посадка смонтирует
// манифесты, знает только она. Константа была бы решением, принятым за оператора
// и ему не предъявленным, а сменить его он мог бы только релизом образа — то
// есть ровно тем, от чего доставка и уводит.
//
// # Почему выключатель ЯВНЫЙ, а не «пустой каталог значит выключено»
//
// Пустая строка двусмысленна: «доставка не заведена» и «доставка заведена, а
// каталог забыли назвать» выглядят одинаково, и второе — это «не сужаем» в
// чистом виде (`security.md` §«Пустой список — это „не сужаем"»). Поэтому
// намерение объявляется отдельно, а незаданный при объявленном намерении каталог
// ОТКАЗЫВАЕТ В ПУСКЕ, а не подставляет умолчание.
package config

import (
	"fmt"
	"slices"
	"strings"
)

// ManifestsConfig — секция `manifests` конфигурации службы.
type ManifestsConfig struct {
	// Dir — каталог, в который посадка монтирует манифесты модулей.
	//
	// Пустой означает «доставка не объявлена», и это законное состояние ровно
	// до тех пор, пока не объявлено Required: доставка вводится вперёд своих
	// потребителей, и стенд, её не объявивший, поднимается как прежде.
	Dir string `mapstructure:"dir"`

	// Required — объявляет ли посадка доставленные манифесты ОБЯЗАТЕЛЬНЫМИ.
	//
	// Не «включить чтение»: чтение включает сам Dir. Здесь объявляется, что
	// посадка на манифесты ОПИРАЕТСЯ, — и тогда её молчание о каталоге есть
	// расхождение, а не умолчание.
	//
	// ЗНАЧЕНИЕ `false` ПРИ НАЗВАННОМ КАТАЛОГЕ НЕ СУЩЕСТВУЕТ (#1924). Оно
	// объявлялось и не исполнялось ничем: чтение включает Dir, а сорванную
	// доставку `manifest.LoadDelivered` отвергает НЕЗАВИСИМО от этого поля —
	// решение записано у него же («почему отказ, а не мягкий проход»). То есть
	// исполнимых состояний было два, а объявленных три, и вызывающий — здесь
	// оператор посадки — получал успех рендера, уверенный, что его величина
	// применена. Теперь неполная пара отвергается в ОБЕ стороны.
	Required bool `mapstructure:"required"`

	// ComposeModel — собирается ли модель прав установки ИЗ доставленных
	// манифестов (задача #1971).
	//
	// Не «читать манифесты»: чтение включает сам Dir. Здесь объявляется, что
	// доставленное УЧАСТВУЕТ в модели прав установки, — а значит правка карты
	// настроек кластера начинает эту модель определять. Поэтому объявление
	// сборки обязывает назвать допуск (Admission): производителем доверия к
	// собранной модели служит он, а страж ниже — то, что делает его
	// НЕОБХОДИМЫМ, а не факультативным.
	//
	// ЧИТАТЕЛЯ СБОРКИ В ДЕРЕВЕ СЕГОДНЯ НЕТ — он приезжает полосой #1969, и это
	// сказано здесь, чтобы не выдавать намерение за факт: до её посадки
	// `compose-model: true` проходит стража и не собирает ничего. Величина при
	// этом не мертва — она меняет исход СТАРТА (ban #16: «поле есть» не значит
	// ничего, значит «значение меняет исход старта»), и её живой вызывающий
	// назван у validateComposition ниже.
	ComposeModel bool `mapstructure:"compose-model"`

	// Admission — КАКИМ ДОПУСКОМ судится собранная модель.
	//
	// Значение — одно из закрытого набора `admissionValues`; сегодня в нём одно
	// значение, и это НЕ повод подразумевать его молчанием: набор объявлен,
	// потому что перечень, который нельзя предъявить оператору, перечнем не
	// является — отказ обязан его напечатать (`ADM-B-02`).
	//
	// Пустое при объявленной сборке — ОТКАЗ В ПУСКЕ, а не умолчание. Довод тот
	// же, что у Dir выше: подставленный допуск был бы непуст ВСЕГДА, поэтому
	// собранная модель выглядела бы суждённой на всякой посадке — включая ту,
	// которая допуска не объявляла. Состояния «сборка без допуска» не
	// существует.
	Admission string `mapstructure:"admission"`
}

// AdmissionByContent — допуск по СОДЕРЖАНИЮ: собранная модель судится тем, что
// она добавляет, а не тем, откуда приехала.
//
// ЭКСПОРТИРОВАН НАМЕРЕННО. Значение сравнивает не только страж старта: его
// читает и тот, кто выбирает судью на пути сборки. Второй литерал `"content"` в
// другом файле разошёлся бы с этим молча — ни сборка, ни пробы такого
// расхождения не замечают, а наблюдаемо оно стало бы отказом старта на верной
// посадке. Поэтому написание живёт в ОДНОМ месте, и читатели ссылаются на него,
// а не переписывают.
//
// Решение, которое этим значением называется, — не здесь: оно принято, доказано
// и живёт в `services/iam/docs/engineering/architecture/composed-model-is-admitted-by-content.md`.
const AdmissionByContent = "content"

// admissionValues — ЗАКРЫТЫЙ набор значений `manifests.admission`, объявленный
// одним местом на весь пакет.
//
// Выводится из констант выше, а не выписывается второй раз: перечень и
// сравнение — два места об одном предмете, и разошлись бы они там, где
// расхождение не видно, — на добавлении второго допуска.
var admissionValues = []string{AdmissionByContent}

// Validate — страж старта секции. Две половины, и порядок между ними значим:
// сперва ПАРА ДОСТАВКИ (объявляется целиком либо не объявляется вовсе), затем
// СБОРКА (validateComposition ниже). Порядок объяснён у второй половины: он
// оставляет виновную ручку одной.
//
// Отказ в пуске, а не подстановка умолчания: подставленный каталог был бы
// непустым всегда, поэтому доставка выглядела бы объявленной на всякой посадке —
// включая ту, что не монтирует ничего. Контроль, который не отказывает ни при
// каком входе, контролем не является.
//
// # Почему отвергаются ОБЕ неполные половины, а не одна
//
// Секция есть пара «намерение + координата», и половина пары ХУЖЕ отсутствия
// обеих, потому что выглядит настроенной (`security.md` §«Контроль, у которого
// нет МЕХАНИЗМА исполниться»). Прежде отвергалась одна половина из двух, и
// вторая — «каталог назван, опоры нет» — принималась, означая не то, что
// говорит: чтение включает Dir, а сорванную доставку читатель отвергает при
// любом Required. Величина, принимающая значение, которое ничего не меняет, есть
// «принято-и-проигнорировано» (`api-conventions.md`) этажом ниже поля запроса —
// следующий, кто её поставит, получит не объявленное поведение (#1924).
//
// # Почему не «сделать `false` мягким проходом» и не «снять величину»
//
// Мягкий проход отвергнут не здесь, а у самого читателя, и записан у него же:
// он дал бы контроль, не отказавший ни разу за свою жизнь, а сорванная доставка
// выглядела бы снаружи как «прав не выдали». Снятие величины вернуло бы «молчание
// о координате» в умолчание — тот самый класс «пусто значит не сужаем», против
// которого поле и заводилось, — и замены ему в дереве нет: проверка объявлений
// профилей стенд, доставку не объявивший, законным СЧИТАЕТ.
func (c ManifestsConfig) Validate() error {
	if c.Required && c.Dir == "" {
		return fmt.Errorf(
			"manifests.required объявлен, а manifests.dir пуст — посадка опирается на " +
				"манифесты модулей и не сказала, откуда их читать; умолчания здесь нет " +
				"намеренно: подставленный каталог был бы непуст всегда, и доставка " +
				"выглядела бы объявленной на посадке, которая не монтирует ничего (kacho#1875)")
	}
	if !c.Required && c.Dir != "" {
		return fmt.Errorf(
			"manifests.dir назван (%s), а manifests.required не объявлен — посадка сказала, "+
				"откуда читать манифесты модулей, и объявила, что на них не опирается; "+
				"такого состояния нет: чтение включает сам каталог, и сорванную доставку "+
				"процесс отвергает независимо от manifests.required, поэтому объявленное "+
				"«не опираемся» не исполняется ничем. Либо manifests.required: true "+
				"(опора объявлена честно), либо manifests.dir пуст — на посадке умбреллы "+
				"каталог берётся из manifests.configMapName, и снимается доставка "+
				"опустошением ИМЕНИ, а не отзывом опоры (kacho#1924)", c.Dir)
	}
	return c.validateComposition()
}

// validateComposition — вторая половина стража: СБОРКА модели прав из
// доставленного объявляется вместе со своим ДОПУСКОМ и вместе с доставкой,
// либо не объявляется вовсе (задача #1971, приёмка `ADM-B-01`…`ADM-B-06`).
//
// # Почему отказ в пуске, а не предупреждение
//
// Мягкий проход дал бы контроль, не отказавший ни разу за свою жизнь
// (`security.md` §Hardening, п. 8): собранная и не суждённая модель прав
// поднялась бы молча, а снаружи расхождение выглядело бы как «прав не выдали».
// Отказ виден оператору сразу и называет ручку.
//
// # Порядок проверок — и почему допуск спрашивается РАНЬШЕ доставки
//
// `ADM-B-01` требует, чтобы отказ на «сборка включена, допуск не объявлен»
// называл ОБЕ ручки сборки, — а при не объявленной доставке верны сразу два
// упрёка. Виновная ручка называется одна, поэтому спрашивается сначала допуск.
//
// # Почему НЕПОЛНАЯ ПОЛОВИНА пары доставки сюда не доходит
//
// Обе половины отвергнуты выше собственным текстом (#1924), и второй отказ их
// НЕ ПОДМЕНЯЕТ. Здесь остаётся ровно один случай, на котором страж пары молчит
// намеренно, — пара не объявлена ВОВСЕ: доставка вводилась вперёд своих
// потребителей, и это молчание было верным ровно до тех пор, пока не объявлена
// сборка. Собирать модель из не объявленного каталога не из чего.
//
// # Живой вызывающий — назван, потому что объявленный и никем не позванный
// страж мёртв ровно так же, как ненаписанный
//
// ManifestsConfig.Validate ← Config.Validate (`validate.go`, слагаемое multierr)
// ← main (`cmd/kacho-iam`, `cfg.Validate()` → `os.Exit(1)`). То есть отказ здесь
// есть отказ В ПУСКЕ, а не предупреждение. Координаты названы ИМЕНАМИ, а не
// номерами строк: номер устаревает молча, имя — нет.
//
// Половина, наблюдаемая ЭТИМ пакетом, — что накопитель Config.Validate отказ не
// проглотил (проба `TestConfigValidateCarriesTheCompositionRefusal`). Половина
// «отказ доезжает до остановки процесса непогашенным» пакетом НЕ производится:
// её производитель — гейт по дереву (`З-04` приёмки), и он живёт вне пакета.
func (c ManifestsConfig) validateComposition() error {
	if !c.ComposeModel {
		// Сборка не объявлена — величины допуска не спрашиваются. Посадка
		// честно говорит «собирать нечего»; режима «только для стенда» здесь
		// не заводится, потому что заводить нечего: путь один.
		return nil
	}

	if c.Admission == "" {
		return fmt.Errorf(
			"manifests.compose-model объявлен, а manifests.admission пуст — посадка "+
				"собирает модель прав установки из доставленных манифестов и не сказала, "+
				"чем эта модель судится; состояния «сборка без допуска» не существует, и "+
				"умолчания здесь нет намеренно: подставленный допуск был бы непуст всегда, "+
				"и собранная модель выглядела бы суждённой на посадке, которая допуска не "+
				"объявляла. Допустимые значения manifests.admission: %s (kacho#1971)",
			strings.Join(admissionValues, ", "))
	}

	if !slices.Contains(admissionValues, c.Admission) {
		return fmt.Errorf(
			"manifests.admission=%q — значения нет в закрытом наборе; посадка назвала судью, "+
				"которого в этой сборке не существует, и сборка поднялась бы несуждённой. "+
				"Допустимые значения: %s (kacho#1971)",
			c.Admission, strings.Join(admissionValues, ", "))
	}

	// Пара доставки: сюда доходит только «не объявлена вовсе» — обе неполные
	// половины отвергнуты выше. Значит пустой Dir здесь означает и незаявленную
	// опору тоже, и второго условия у проверки нет: ветвь без входа не
	// заводится.
	if c.Dir == "" {
		return fmt.Errorf(
			"manifests.compose-model объявлен, а доставка манифестов не объявлена вовсе " +
				"(manifests.dir пуст, manifests.required не объявлен) — собирать модель прав " +
				"не из чего: процесс поднялся бы, читая пустой каталог, и это неотличимо от " +
				"«модулей нет». Либо объявите пару доставки целиком, либо снимите " +
				"manifests.compose-model (kacho#1971)")
	}

	return nil
}
