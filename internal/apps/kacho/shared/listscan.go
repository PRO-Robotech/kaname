package shared

import "context"

// listscan.go — наблюдаемость СТОИМОСТИ страницы списка.
//
// # Предмет: величина посчитана и невидима
//
// Приёмка требует, чтобы число рассмотренных строк и обращений к модели прав
// НЕ росло с числом объектов в облаке. Посчитать это можно внутри цикла
// догрузки, но снять было негде: слой видимости — лист, реестр метрик приватен,
// набор меток закрыт. Величина, которую нельзя снять, — это свойство, которое
// нечем наблюдать: тот же класс, что «ноль доставленных строк за всю жизнь
// очереди».
//
// # Почему порт УЗКИЙ и почему замер снимается НА ВЫХОДЕ
//
// Порт принимает только числа и имя вида — слой видимости остаётся листом и не
// начинает знать про метрики. Замер снимается на выходе из цикла догрузки, а не
// внутри: снятый внутри, он померил бы ПОСЛЕДНЮЮ догрузку и остался бы
// постоянным при любом их числе — то есть был бы слеп ровно к тому, что мерит.
//
// Реализация живёт в слое наблюдаемости; здесь — только форма обращения.

// ListScanRecorder принимает стоимость одной отданной страницы.
//
// resource — вид ресурса («account», «project», …), чтобы дорогая поверхность
// была отличима от дешёвой; rows — сколько строк рассмотрено всеми догрузками
// вместе; checks — сколько раз спрошена модель прав.
type ListScanRecorder interface {
	ObserveListScan(ctx context.Context, resource string, rows, checks int)
}

// NoopListScanRecorder — умолчание для мест, где наблюдение не провязано
// (пробы, инструменты). Именованный тип, а не nil-проверка у каждого
// вызывающего: «не провязано» обязано быть решением, а не забытой ветвью.
type NoopListScanRecorder struct{}

// ObserveListScan ничего не делает.
func (NoopListScanRecorder) ObserveListScan(context.Context, string, int, int) {}

// ListScan — накопитель стоимости одной страницы. Считает по мере догрузок и
// отдаётся регистратору один раз, на выходе.
type ListScan struct {
	Rows   int
	Checks int
}

// AddBatch учитывает одну догрузку: её строки и одно обращение к модели.
func (s *ListScan) AddBatch(rows int) {
	s.Rows += rows
	s.Checks++
}

// Report отдаёт накопленное регистратору. Безопасен на нулевом регистраторе:
// вызывающему не нужно знать, провязано ли наблюдение.
func (s *ListScan) Report(ctx context.Context, rec ListScanRecorder, resource string) {
	if rec == nil {
		return
	}
	rec.ObserveListScan(ctx, resource, s.Rows, s.Checks)
}
