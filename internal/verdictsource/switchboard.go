// Package verdictsource — РУБИЛЬНИК ИСТОЧНИКА ВЕРДИКТА о доступе, потиповой.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЭТО РЕШАЕТ
//
// Решение о доступе принимают две формы: внешний движок отношений и
// реляционное вычисление в собственной базе. Пока источник один на всю службу,
// смена источника — это выкатка образа, а откат в аварии — ещё одна. Поэтому
// источник выбирается ПО ТИПУ ОБЪЕКТА и приезжает настройкой: радиус ошибки
// равен одному типу, а не всей платформе, и возврат не ждёт очереди сборки.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ПАКЕТ, А НЕ ПОЛЕ В КОНФИГУРАЦИИ
//
// Значение читают ТРОЕ: путь решения, отказ в старте и самоотчёт процесса.
// Читай они сырое поле — каждый нормализовал бы его сам, и «страж прошёл»
// перестало бы означать «источник действительно переключён»: перечень из одних
// пустых записей непуст по длине и пуст по существу. Ровно этот класс уже
// наблюдался на круге доверенных отправителей, где пустой круг означает «не
// сужаем», а не «запрещаем».
//
// Поэтому нормализация живёт в конструкторе, предикат ровно один (`Decides`), и
// пакет остаётся ЛИСТОМ: он не знает ни о движке, ни о форме, ни о модели прав.
// Отвечает ли форма на вопрос об этом типе — вопрос ДРУГОЙ, и его задаёт страж
// старта, которому модель доступна (см. cmd/kacho-iam).
package verdictsource

import (
	"sort"
	"strings"
)

// Switchboard — по каким типам объектов вердикт принимает ФОРМА.
//
// Нулевое значение законно и означает «не переключено ничего»: решение остаётся
// за движком по каждому типу. Это умолчание названо явно, а не оставлено «как
// получится», — источник вердикта не вправе зависеть от того, чего оператор не
// написал.
type Switchboard struct {
	// byType — множество имён типов в словаре МОДЕЛИ прав (`vpc_network`,
	// `project`, `cluster`), а не в словаре каталога (`vpc.network`).
	//
	// Словарь назван, потому что их два и соединение разных словарей не
	// совпадает никогда и молча: рубильник, названный в словаре каталога, не
	// переключил бы НИ ОДНОГО вопроса и выглядел бы исполненным.
	byType map[string]struct{}
	// declared — устойчивый порядок для самоотчёта и метрики. Перечень едет в
	// журнал старта, а журнал сравнивают между перезапусками.
	declared []string
}

// New собирает рубильник из имён типов, нормализуя их ЗДЕСЬ.
//
// Пустые записи и обрамляющие пробелы отбрасываются, повторы схлопываются. Так
// перечень из одних пустых записей вырождается в пустой рубильник ДЛЯ ВСЕХ
// читателей сразу, а не только для того, кто вспомнил про нормализацию.
func New(objectTypes ...string) Switchboard {
	sb := Switchboard{}
	for _, t := range objectTypes {
		name := strings.TrimSpace(t)
		if name == "" {
			continue
		}
		if sb.byType == nil {
			sb.byType = make(map[string]struct{}, len(objectTypes))
		}
		if _, seen := sb.byType[name]; seen {
			continue
		}
		sb.byType[name] = struct{}{}
		sb.declared = append(sb.declared, name)
	}
	sort.Strings(sb.declared)
	return sb
}

// Parse разбирает плоское значение переменной окружения («a, b,,c»).
//
// Разбор стоит ЗДЕСЬ, рядом с нормализацией: два места, знающие разделитель,
// разошлись бы на первом же значении с пробелом.
func Parse(flat string) Switchboard {
	return New(strings.Split(flat, ",")...)
}

// Decides — принимает ли решение по этому типу ФОРМА.
//
// Единственный предикат пакета. Пустое имя типа не совпадает никогда, даже с
// пустой записью: вопрос, тип которого не разобран, переключать нельзя — его
// некому задать форме.
func (s Switchboard) Decides(objectType string) bool {
	if objectType == "" || s.byType == nil {
		return false
	}
	_, ok := s.byType[objectType]
	return ok
}

// Declared — типы, по которым решает форма, в устойчивом порядке.
//
// Возвращает КОПИЮ: перечень уезжает в самоотчёт и в метрику, и читатель,
// получивший внутренний срез, мог бы его переупорядочить.
func (s Switchboard) Declared() []string {
	if len(s.declared) == 0 {
		return nil
	}
	out := make([]string, len(s.declared))
	copy(out, s.declared)
	return out
}

// IsEmpty — не переключено ничего.
//
// Считает ПРИГОДНЫЕ записи, а не длину сырой строки: страж, самоотчёт и путь
// решения обязаны отвечать на этот вопрос одинаково.
func (s Switchboard) IsEmpty() bool { return len(s.declared) == 0 }
