package catalog

import (
	"context"
	"log/slog"
	"sync/atomic"
	"time"
)

// Исходы обновления снимка. Набор ЗАКРЫТ и приходит отсюда, никогда из запроса,
// поэтому кардинальность метрики не растёт с трафиком.
const (
	// RefreshOutcomeRefreshed — новое множество прочитано и подменило прежнее.
	RefreshOutcomeRefreshed = "refreshed"
	// RefreshOutcomeFailed — обновление не удалось; снимок остался прежним.
	RefreshOutcomeFailed = "failed"
)

// RefreshObserver — порт наблюдения за обновлением снимка.
//
// Счётчика ДВА, и одного не хватает ни на один из двух вопросов. Ноль отказов
// даёт и исправный процесс, и процесс, ни разу не пошедший обновляться, — то
// есть путь, умерший целиком, выглядел бы здоровее всех. Растущий ноль удавшихся
// при этом не говорит, отказывало ли обновление или его не запускали. Знаменатель
// считается наравне с числителем.
type RefreshObserver interface {
	IncCatalogSnapshotRefresh(outcome string)
}

// Snapshot — держатель каталожного факта в процессе.
//
// # Почему СНИМОК, а не запрос на пути запроса
//
// Каталог спрашивают на горячих путях — создание и правка роли, пересчёт
// проекции, сборка кортежей, — а сам он мал (десятки ресурсов, сотня глаголов) и
// меняется реже всего в схеме. Запрос к базе на каждом обращении оплачивался бы
// запросом арендатора; снимок платит один раз за период.
//
// # Отставание ОГРАНИЧЕНО и НАЗВАНО
//
// Величина отставания — период обновления, и он задаётся профилем развёртывания,
// а не вшит: вшитая величина есть решение, принятое за оператора и не
// предъявленное ему.
//
// # Отказ обновления НЕ фатален и НЕ тих
//
// Ронять службу из-за отставшего снимка значило бы менять ограниченное
// отставание на полный отказ. Но и молчать нельзя: контроль, о чьих отказах
// никто не узнаёт, неотличим от отсутствующего. Отсюда пара — запись журнала
// уровня `Error` и счётчик.
type Snapshot struct {
	src   RowSource
	log   *slog.Logger
	obs   RefreshObserver
	facts atomic.Pointer[Facts]
}

// NewSnapshot заполняет снимок УЖЕ ПРОЧИТАННЫМИ строками.
//
// Строки приходят параметром, а не читаются здесь, и это несущее решение, а не
// удобство: на старте их уже прочитал страж паритета, и второе чтение об одном
// предмете дало бы два места, которые разойдутся молча. Проба `IAM-CT-2-01`
// утверждает это РАВЕНСТВОМ: операторов к таблицам каталога за время старта
// ровно столько, сколько шлёт сам страж.
//
// Заполнение НЕ считается обновлением: зачти его — и «ноль обновлений за жизнь
// процесса» станет неотличимо от одного, то есть счётчик перестанет отвечать на
// вопрос, ради которого заведён.
func NewSnapshot(initial Rows, src RowSource, log *slog.Logger, obs RefreshObserver) (*Snapshot, error) {
	facts, err := NewFacts(initial)
	if err != nil {
		return nil, err
	}
	if log == nil {
		log = slog.Default()
	}
	s := &Snapshot{src: src, log: log, obs: obs}
	s.facts.Store(facts)
	return s, nil
}

// Facts — каталожный факт на момент вызова. Реализует Source.
func (s *Snapshot) Facts() *Facts { return s.facts.Load() }

// Refresh перечитывает живое множество и подменяет факт целиком.
//
// Подмена атомарна: вызывающий, взявший факт до неё, доработает на прежнем
// согласованном множестве, а не увидит половину обновления.
//
// Отказ ОСТАВЛЯЕТ ПРЕЖНИЙ снимок — включая случай пустого ответа без ошибки:
// пустой снимок отверг бы все правила арендатора разом, и это читалось бы как
// «продукт сломан», а не как «условие не создано».
func (s *Snapshot) Refresh(ctx context.Context) error {
	rows, err := s.src.ReadLiveCatalog(ctx)
	if err == nil {
		var facts *Facts
		if facts, err = NewFacts(rows); err == nil {
			s.facts.Store(facts)
			s.observe(RefreshOutcomeRefreshed)
			return nil
		}
	}
	s.log.Error("снимок каталога не обновлён", slog.Any("err", err))
	s.observe(RefreshOutcomeFailed)
	return err
}

// РЕПЛИКИ: на-реплику — петля обслуживает снимок СВОЕГО процесса: каталожный
// факт живёт в памяти реплики, и обновить его за соседа нельзя by construction.
// Общего состояния она не трогает, в базу только ЧИТАЕТ, поэтому N реплик дают N
// одинаковых чтений закрытого каталога — цена, ограниченная числом реплик и
// периодом, а не нагрузкой арендатора.
//
// Run обновляет снимок с назначенным периодом и завершается по отмене
// контекста.
//
// Отказ отдельного круга цикл НЕ прерывает: он уже сообщён журналом и счётчиком,
// а прекращение обновлений превратило бы ограниченное отставание в бессрочное.
func (s *Snapshot) Run(ctx context.Context, period time.Duration) {
	if period <= 0 {
		s.log.Error("период обновления снимка каталога не назначен — обновлений не будет",
			slog.Duration("period", period))
		return
	}
	t := time.NewTicker(period)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
			_ = s.Refresh(ctx)
		}
	}
}

func (s *Snapshot) observe(outcome string) {
	if s.obs != nil {
		s.obs.IncCatalogSnapshotRefresh(outcome)
	}
}
