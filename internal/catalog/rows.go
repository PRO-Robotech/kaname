// Package catalog — КАТАЛОЖНЫЙ ФАКТ, прочитанный из СТРОК: какие пары
// «модуль.ресурс» грантуемы и какие глаголы объявлены каждой.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕМ ЭТОТ ПАКЕТ ОТЛИЧАЕТСЯ ОТ ЛИТЕРАЛА `authzmap`
//
// Литерал `authzmap.objectTypes` / `typeVerbRelations` остаётся и снятию не
// подлежит: он производная канона `fga_model.fga`, проверяемая гейтом дрейфа, и
// без него строки каталога остались бы без якоря к канону вовсе. Литерал
// отвечает на вопрос «что объявлено КАНОНОМ»; этот пакет — на вопрос «что живо
// В БАЗЕ ПРЯМО СЕЙЧАС».
//
// Пока строки пишет только миграция, ответы совпадают, и совпадают не случайно:
// страж старта (`seed.AssertCatalogParity`) сверяет литерал с живыми строками на
// КАЖДОМ старте и при расхождении отказывает в пуске. Различие появляется в
// один момент — когда строка снята в РАБОТАЮЩЕМ процессе: страж своё уже
// отработал, а читатель на литерале продолжит считать снятый тип живым до
// следующего перезапуска. Наблюдаемо это не поломкой, а «прав не выдали» либо,
// что хуже, выдачей по типу, который платформа сняла.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: ПЕРЕХОДНИКА ИМЕНИ ТИПА
//
// Имя типа МОДЕЛИ (`vpc_network`, `cluster`) строки каталога не несут — такой
// колонки в `catalog_resource` нет, а `cluster` не имеет строки вовсе, потому
// что вершина иерархии ресурсом не является. Перевод между словарями делает
// `authzmap` (`type_dictionaries.go`), и второго переходника в дереве не
// заводится: два места, знающих соответствие, разойдутся, и разойдутся тихо.
// Поэтому этот пакет ЗОВЁТ переходник, а не повторяет его.
package catalog

import "context"

// ResourceRow — одна ЖИВАЯ строка `kacho_iam.catalog_resource`.
//
// Точечная форма (`dotted`) в структуре не хранится: она производна от пары и
// собирается там, где нужна. Хранить её третьим полем значило бы завести место,
// где она может разойтись с парой, — а согласие этих двух в базе держит
// проверка колонки, а не читатель.
type ResourceRow struct {
	Module   string
	Resource string
}

// VerbRow — одна ЖИВАЯ строка `kacho_iam.catalog_verb`.
type VerbRow struct {
	Module   string
	Resource string
	// Verb — каноническая форма БЕЗ приставки отношения, та же, какой говорит
	// `role_verb.verb`.
	Verb string
	// PerObject — строка производит пообъектное отношение `v_<verb>`. Ложь
	// означает глагол, законный АВТОРСКИ и не дающий кортежа ни на одном
	// объекте: его действие несёт ярус на родителе (задача #1863).
	//
	// Читателю этот признак НЕ безразличен, и в этом весь его смысл: набор
	// глаголов типа обязан оставаться пообъектным, потому что по нему
	// материализуются кортежи. Пропустить сюда ярусную строку значило бы вернуть
	// снятое отношение целиком.
	PerObject bool
}

// Rows — ЖИВОЕ множество каталога, прочитанное одним обращением.
//
// Все три перечня приходят ВМЕСТЕ и от одного чтения. Разнести их по трём
// вызовам значило бы допустить снимок, собранный из разных моментов времени:
// ресурс уже снят, а его глаголы ещё живы — состояние, которого в базе не
// бывает ни при каком порядке применения.
type Rows struct {
	Modules   []string
	Resources []ResourceRow
	Verbs     []VerbRow
}

// RowSource — ПОРТ чтения живого каталога. Объявлен здесь, у потребителя;
// реализация — `repo/kacho/pg/catalog_repo.go`.
type RowSource interface {
	ReadLiveCatalog(ctx context.Context) (Rows, error)
}

// Source — читатель каталожного ФАКТА, каким его видит use-case: он знает, что
// факт откуда-то приходит, и не знает откуда.
//
// Возвращается ЗНАЧЕНИЕ на момент вызова, а не держатель: обновление снимка
// подменяет указатель целиком, поэтому вызывающий, взявший факт один раз,
// работает на согласованном множестве до конца своего вычисления и не увидит
// половину обновления.
type Source interface {
	Facts() *Facts
}

// Fixed — источник, отдающий один и тот же факт. Нужен там, где обновления не
// бывает по построению: разовому пересчёту на старте и пробам.
type Fixed struct{ F *Facts }

// Facts реализует Source.
func (f Fixed) Facts() *Facts { return f.F }
