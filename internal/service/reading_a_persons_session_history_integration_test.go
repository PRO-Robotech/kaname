// reading_a_persons_session_history_integration_test.go — «читать ИСТОРИЮ
// СЕССИЙ человека» решается на той двери, куда приходит каждый запрос платформы
// (`AuthorizeService.CheckRelation` — то, что зовёт `InternalIAMService.Check`).
//
// # Чем эта проба отличается от гейта в authzmap
//
// Гейт `authzmap/reading_a_persons_session_history_test.go` читает МОДЕЛЬ: он
// утверждает, что у отношения нет источников уровня аккаунта. Здесь то же
// свойство спрашивается ВЕРДИКТОМ по закоммиченным строкам — то есть
// проверяется не текст модели, а исход. Разъехаться они могут молча: у края
// своя композиция (ответ формы плюс плоский надзор администратора облака), и
// провязана она в композиционном корне, а не в модели.
//
// Именно поэтому НАДЗОР ОБЛАКА утверждается ЗДЕСЬ: короткое замыкание уровня 1
// в модель не входит и входить не должно, а «сужение оставило расследование
// возможным» — половина решения #1140, и проверять её надо там, где она
// действительно происходит.
//
// # Что сеется — ВСЕ ТРИ пути, которыми право доходит до распорядителя аккаунта
//
//	выдача на аккаунт с ролью, дающей правку `iam.user` — ровно то, что
//	  материализует реконсайлер на свежей строке приглашённого;
//	факт `admin @ account:<acc>` — ДЕЛЕГИРОВАННЫЙ распорядитель аккаунта;
//	факт `owner @ account:<acc>` — владелец аккаунта.
//
// # Почему рядом стоит КОНТРОЛЬ ФИКСТУРЫ
//
// Отказ «распорядитель не читает историю» истинен и на пустом посеве, где никто
// не читает ничего. Поэтому у каждого отказа рядом спрашивается право, которое
// решение владельца оставило НЕТРОНУТЫМ: перечисление людей своего аккаунта.
// Оно обязано остаться — иначе проба меряет сломанную фикстуру, а не сужение.
//
// Настоящий Postgres. Пропускается под кратким режимом.

package service_test

import (
	"testing"

	"github.com/stretchr/testify/require"
)

// TestReadingSessionHistoryIsNotReachableFromInsideTheAccount — вердикт по
// закоммиченным строкам.
func TestReadingSessionHistoryIsNotReachableFromInsideTheAccount(t *testing.T) {
	w := newCIWorld(t)

	const (
		acc        = "acc-sesshist1"
		owner      = "usr-sesshown1"
		inviter    = "usr-sesshinv1"
		invitee    = "usr-sesshnew1"
		stranger   = "usr-sesshstr1"
		cloudAdmin = "usr-sesshcld1"
	)
	w.seedAccountWithOwner(t, acc, owner)
	w.seedUser(t, inviter, acc)
	w.seedUser(t, invitee, acc)
	w.seedUser(t, stranger, acc)
	w.seedUser(t, cloudAdmin, acc)

	obj := "iam_user:" + invitee

	// Путь 1 — ВЫДАЧА внутри аккаунта, чья роль даёт правку личности.
	seedRoleGrantingUserRead(t, w, "rol-sessh1", "acb-sessh1", inviter, acc)
	// Путь 2 — делегированный распорядитель аккаунта.
	w.factThroughJournal(t, "user:"+inviter, "admin", "account", acc)
	// Путь 3 — владелец аккаунта.
	w.factThroughJournal(t, "user:"+owner, "owner", "account", acc)
	// Сам человек. Кортеж пишется на заведении пользователя (internal_upsert.go).
	w.factThroughJournal(t, "user:"+invitee, "subject", "iam_user", invitee)
	// Уровень 1.
	w.factThroughJournal(t, "user:"+cloudAdmin, "system_admin", "cluster", "cluster_root")

	// Отношение спрашивается У КАТАЛОГА, а не пишется литералом: каталог
	// порождается из proto и является единственным источником per-RPC решения
	// края. Литерал означал бы, что проба утверждает о СВОЁМ представлении
	// гейта, а не о действующем.
	histRel, histType := actingAsGateFromCatalog(t,
		"kaname.cloud.iam.v1.InternalSessionRevocationsService/ListByUser")
	require.Equalf(t, "iam_user", histType,
		"история сессий гейтится не на объекте личности (%s)", histType)

	// ── КОНТРОЛЬ ФИКСТУРЫ ────────────────────────────────────────────────────
	// Спрашивается ровно то право уровня аккаунта, которое решение владельца
	// оставило НЕТРОНУТЫМ: видеть своих людей. Без него отказы ниже истинны и
	// на пустом посеве — то есть не отличают сужение от фикстуры, ничего не
	// выдавшей.
	require.True(t, w.allowed(t, "user:"+inviter, "v_list", obj),
		"КОНТРОЛЬ: пригласивший обязан перечислять ЛЮДЕЙ своего аккаунта — иначе отказы "+
			"ниже вакуумны и меряют пустой посев, а не сужение чтения истории сессий")
	require.True(t, w.allowed(t, "user:"+owner, "v_list", obj),
		"КОНТРОЛЬ: владелец аккаунта обязан перечислять ЛЮДЕЙ своего аккаунта")
	// Здесь спрашивался `v_delete` НА СТРОКЕ ЛИЧНОСТИ, и комментарий называл его
	// «удалением члена». Это было неверно уже с #1131: снятие строки спрашивает
	// `identity_remover`, у которого источников уровня аккаунта нет ни одного, — то
	// есть контроль утверждал живым отношение, которого не читал никто, и держался
	// он лишь на том, что глагол ещё был объявлен. Глагол снят (#1189), и на его
	// место встало право, которое директива за распорядителем аккаунта
	// ДЕЙСТВИТЕЛЬНО оставляет: исключить человека ИЗ АККАУНТА (#1127). Оно на
	// объекте аккаунта, а не личности, — и в этом весь смысл разделения.
	require.True(t, w.allowed(t, "user:"+inviter, "member_remover", "account:"+acc),
		"КОНТРОЛЬ: пригласивший обязан сохранить ИСКЛЮЧЕНИЕ ЧЕЛОВЕКА ИЗ АККАУНТА — "+
			"«убрать из своего тенанта и распоряжаться правами» и есть то, что директива "+
			"владельца за ним оставляет; строку личности это не трогает")

	// ── ОТРИЦАНИЕ — предмет пробы ────────────────────────────────────────────
	for _, c := range []struct{ who, role string }{
		{inviter, "пригласивший (делегированный распорядитель аккаунта)"},
		{owner, "владелец аккаунта"},
		{stranger, "посторонний член аккаунта"},
	} {
		require.Falsef(t, w.allowed(t, "user:"+c.who, histRel, obj),
			"история сессий человека (%s) досталась держателю права ВНУТРИ аккаунта — %s "+
				"(user:%s). Личность здесь глобальна: одна строка на все аккаунты человека, "+
				"а звено «личность → аккаунт» вердикт берёт из членства. Значит он увидел бы "+
				"и те сессии, которыми человек действовал в аккаунтах, к которым этот "+
				"держатель отношения не имеет. История сессий — сведения о личности, а не "+
				"право на аккаунт.", histRel, c.role, c.who)
	}

	// ── ПОЛОЖИТЕЛЬНЫЕ КОНТРОЛИ ───────────────────────────────────────────────
	// Сам человек. Без этого запрет выше зеленел бы на отношении, которого не
	// держит никто. Самочтение сервис короткозамыкает и до модели
	// (`authzguard.IsSelf`), но у края такого замыкания нет — там решает только
	// отношение, и без него человек остался бы без своей же истории.
	require.True(t, w.allowed(t, "user:"+invitee, histRel, obj),
		"сам человек обязан читать СВОЮ историю сессий: какие его сессии сняли и когда — "+
			"сведения о нём самом")
	// Уровень 1 — плоский надзор администратора облака. ЭТО И ЕСТЬ причина, по
	// которой проба живёт здесь: короткого замыкания в модели нет, и утверждать
	// про него можно только вердиктом.
	require.True(t, w.allowed(t, "user:"+cloudAdmin, histRel, obj),
		"уровень 1 (администратор облака) обязан сохранить чтение истории: расследование "+
			"инцидента — единственный довод, у которого на этом предмете есть предмет, и "+
			"сужение обязано было оставить его возможным. Иначе это не сужение, а обрыв")

	// ── ДВЕ СТОРОНЫ ЛИЧНОСТИ ОТВЕЧАЮТ ОДИНАКОВО ──────────────────────────────
	// Сессия и удостоверение — соседние стороны одного человека. Модель их
	// согласие уже стережёт равенством кругов; здесь то же спрашивается
	// ВЕРДИКТОМ, потому что разъехаться два механизма могут молча.
	tokRel, tokType := actingAsGateFromCatalog(t, "kaname.cloud.iam.v1.UserTokenService/List")
	require.Equalf(t, "iam_user", tokType,
		"перечень удостоверений гейтится не на объекте личности (%s)", tokType)
	for _, who := range []string{inviter, owner, stranger} {
		require.Equalf(t,
			w.allowed(t, "user:"+who, tokRel, obj),
			w.allowed(t, "user:"+who, histRel, obj),
			"две стороны личности ответили РАЗНО про user:%s: перечень удостоверений (%s) и "+
				"история сессий (%s) разошлись. Разная ширина у них была бы решением, "+
				"которого никто не принимал", who, tokRel, histRel)
	}

	subjectsAsked := map[string]bool{
		owner: true, inviter: true, invitee: true, stranger: true, cloudAdmin: true,
	}
	t.Logf("перепись: гейт истории сессий %s.%s · гейт перечня удостоверений %s.%s · "+
		"субъектов спрошено %d · держателей истории ожидается 2 (сам человек и надзор облака)",
		histType, histRel, tokType, tokRel, len(subjectsAsked))
}
