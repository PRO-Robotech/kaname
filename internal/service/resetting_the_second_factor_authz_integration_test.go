// resetting_the_second_factor_authz_integration_test.go — РАЗБОР ДОСТУПА к
// `UserService/ResetSecondFactor` решается ВЕРДИКТОМ по закоммиченным строкам, на
// той двери, куда приходит каждый запрос платформы (`AuthorizeService.CheckRelation`
// — то, что зовёт `InternalIAMService.Check`).
//
// # Предмет — решение владельца 2026-09-18 (kaname#254, приёмка Ф12 ред. 10)
//
// Дословно: «2fa может сбросить или пользователь или администратор облака». Держателей
// сброса ДВА: сам человек — свой фактор, кодом (глагол `remove` под живой сессией,
// Р9; здесь он НЕ предмет), и администратор облака — этим глаголом (Р10, Ф12-30).
// Распорядитель аккаунта — ни владелец, ни делегированный администратор, ни держатель
// пообъектной выдачи — права сброса НЕ имеет, и никакая выдача ему его не даёт.
//
// Отношение это уже выражает: запись каталога гейтит `ResetSecondFactor` отношением
// `identity_suspender` на `iam_user`, а оно выводится `super_admin from account`, то
// есть `any_admin from cluster` → `cluster#system_admin`; источников уровня аккаунта у
// него нет. Здесь то же свойство спрашивается ВЕРДИКТОМ по строкам — не текстом модели,
// а исходом, — потому что у края своя композиция (ответ формы плюс плоский надзор
// администратора облака), провязанная в композиционном корне, а не в модели.
//
// # Почему это ЗЕЛЁНАЯ проба, а не честный красный
//
// Модель уже верна, поведение уже есть: проба ЗАКРЕПЛЯЕТ одобренное решение. Способность
// падать доказана инъекцией (опыт acceptance-reviewer): дать `identity_suspender` источник
// уровня аккаунта (`or admin from account` в `internal/authzmodel/fga_model.fga`) — и
// отрицания на распорядителе (владелец, делегированный администратор) обязаны покраснеть,
// тогда как надзор облака и то, что директива распорядителю ОСТАВЛЯЕТ, остаются зелёными.
//
// # Пара «отрицание + положительное» — обязательна, и вот почему именно эта
//
// Запрет, проверенный в одиночку, зеленеет на сломанном посеве и на сломанном продукте
// одинаково. Рядом стоит ровно то, что директива распорядителю ОСТАВЛЯЕТ (распоряжение
// выдачами своего аккаунта, чтение своих людей) и надзор облака, который отношение
// держит: без первого отрицания зеленели бы на дереве, где у распорядителя отняли всё; без
// второго — на дереве, где отношения не держит НИКТО, то есть на недостижимости, а не на
// разделении прав.
//
// # Несуществующий и кривой `user_id` — «отказ, неотличимый от отсутствия»
//
// Не держателю разбор доступа отвечает ОДИНАКОВО на существующем, на несуществующем
// well-formed и на кривом id: оракула существования у него нет (Ф12-30, Р10). Держатель
// (администратор облака) проходит разбор доступа НА ЛЮБОМ объекте — существование ему
// раскрывает СЛУЖБА вниз по потоку (`NOT_FOUND`/404 `User <id> not found`), а форму —
// край/служба (`INVALID_ARGUMENT`/400); ни то, ни другое разбором доступа не решается, и
// линия держателя на реальной базе закреплена отдельной пробой службы (пакет `user`).
//
// Настоящий Postgres. Пропускается под кратким режимом.

package service_test

import (
	"testing"

	"github.com/stretchr/testify/require"
)

// TestResetSecondFactorAuthzMatrix — матрица `verb×role×scope` для
// `ResetSecondFactor` вердиктом по закоммиченным строкам (kaname#254, Ф12-30, Р10).
func TestResetSecondFactorAuthzMatrix(t *testing.T) {
	w := newCIWorld(t)

	const (
		acc        = "acc-rsf1"
		owner      = "usr-rsfown1"
		inviter    = "usr-rsfinv1"
		invitee    = "usr-rsfnew1"
		stranger   = "usr-rsfstr1"
		cloudAdmin = "usr-rsfcld1"
	)
	w.seedAccountWithOwner(t, acc, owner)
	w.seedUser(t, inviter, acc)
	w.seedUser(t, invitee, acc)
	w.seedUser(t, stranger, acc)
	w.seedUser(t, cloudAdmin, acc)

	person := "iam_user:" + invitee
	// Несуществующий well-formed `user_id` — форма верна, строки нет: у объекта нет
	// НИ ОДНОГО кортежа, и в частности нет ребра `account`, поэтому надзор облака его
	// достаёт (плоский, объект не смотрит), а любой аккаунтный источник — нет.
	absentWellFormed := "iam_user:usr-rsfghost01"
	// Кривой по форме id — на разборе доступа ведёт себя как отсутствующий: кортежей
	// нет. Форму (400) отклоняет край/служба, не разбор доступа.
	malformed := "iam_user:not-a-user-id"

	// Три пути, которыми право доходит до распорядителя, — и все посеяны тем способом,
	// каким их производит продукт.
	//
	// Путь 1 — ПООБЪЕКТНАЯ выдача внутри аккаунта, чья роль даёт чтение записи: ровно
	// то, что реконсайлер материализует на свежей строке приглашённого.
	seedRoleGrantingUserRead(t, w, "rol-rsf1", "acb-rsf1", inviter, acc)
	// Путь 2 — делегированный администратор аккаунта.
	w.factThroughJournal(t, "user:"+inviter, "admin", "account", acc)
	// Путь 3 — владелец аккаунта.
	w.factThroughJournal(t, "user:"+owner, "owner", "account", acc)
	// Сам человек. Кортеж пишется на заведении пользователя (internal_upsert.go).
	w.factThroughJournal(t, "user:"+invitee, "subject", "iam_user", invitee)
	// Уровень 1 — надзор облака.
	w.factThroughJournal(t, "user:"+cloudAdmin, "system_admin", "cluster", "cluster_root")

	// Выдача, живущая В АККАУНТЕ распорядителя, — предмет его законной власти.
	w.seedRole(t, "rol-rsf2", acc)
	w.seedBinding(t, "acb-rsf2", stranger, "rol-rsf2", "account", acc)
	grantInAccount := "iam_access_binding:acb-rsf2"

	// Гейты спрашиваются У КАТАЛОГА, а не пишутся литералом: каталог порождается из
	// proto и есть единственный источник per-RPC решения края.
	resetRel, resetType := actingAsGateFromCatalog(t, "kaname.cloud.iam.v1.UserService/ResetSecondFactor")
	readRel, readType := actingAsGateFromCatalog(t, "kaname.cloud.iam.v1.UserService/Get")
	grantRel, grantType := actingAsGateFromCatalog(t, "kaname.cloud.iam.v1.AccessBindingService/Delete")

	// ── ПРЕДМЕТ ПРОБЫ НАЗВАН КАТАЛОГОМ ──────────────────────────────────────────
	// Если запись каталога `ResetSecondFactor` съедет с `identity_suspender`/`iam_user`
	// на что-то иное, вся матрица ниже утверждала бы о ЧУЖОМ гейте. Предмет сверяется,
	// а не подразумевается.
	require.Equalf(t, "identity_suspender", resetRel,
		"ResetSecondFactor гейтится не отношением надзора над личностью (%s) — предмет пробы сменился", resetRel)
	require.Equalf(t, "iam_user", resetType,
		"ResetSecondFactor гейтится не на объекте личности (%s) — предмет пробы сменился", resetType)
	require.Equalf(t, "iam_access_binding", grantType,
		"снятие выдачи гейтится не на объекте выдачи (%s) — положительный контроль сменил предмет", grantType)
	require.Equalf(t, "iam_user", readType,
		"чтение записи гейтится не на объекте личности (%s) — положительный контроль сменил предмет", readType)

	// ── КОНТРОЛЬ ФИКСТУРЫ ───────────────────────────────────────────────────────
	// Посев ДЕЙСТВИТЕЛЬНО живой: распорядитель держит на этой строке глагол чтения,
	// который материализует пообъектная выдача. Без этого утверждения каждое отрицание
	// ниже было бы истинно и на пустой базе.
	require.True(t, w.allowed(t, "user:"+inviter, "v_get", person),
		"КОНТРОЛЬ: распорядитель обязан держать глагол `v_get` на строке своего члена — "+
			"иначе фикстура ничего не посеяла и все отрицания ниже вакуумны")

	// ── ОТРИЦАНИЕ — решение владельца: распорядителю и постороннему сброс закрыт ──
	for _, c := range []struct{ who, why string }{
		{owner, "владелец аккаунта"},
		{inviter, "делегированный администратор аккаунта И держатель пообъектной выдачи"},
		{stranger, "рядовой арендатор (посторонний)"},
	} {
		require.Falsef(t, w.allowed(t, "user:"+c.who, resetRel, person),
			"сброс второго фактора (%s.%s) достался распорядителю/постороннему — %s (user:%s).\n"+
				"Личность ГЛОБАЛЬНА: одна строка `iam_user` на все аккаунты человека, и сброс гасит "+
				"ВСЕ его сессии — то есть действует во всех его аккаунтах сразу. Распорядитель одного "+
				"аккаунта, получив это право, решал бы за остальные. Директива владельца оставляет ему "+
				"снятие выдач и исключение из аккаунта, а не глагол над глобальной личностью.",
			resetType, resetRel, c.why, c.who)
	}

	// Сам человек своей записи этим глаголом не распоряжается: `identity_suspender` не
	// содержит `subject` (Ф12-45 «б»). Путь человека — самосброс кодом (`remove`, Р9),
	// отдельный глагол, не предмет этой матрицы.
	require.Falsef(t, w.allowed(t, "user:"+invitee, resetRel, person),
		"человек сбросил себе второй фактор глаголом `ResetSecondFactor` (%s.%s) — надзорное отношение "+
			"`subject` намеренно не содержит; свой фактор человек снимает кодом через `remove`", resetType, resetRel)

	// ── НЕСУЩЕСТВУЮЩИЙ И КРИВОЙ id — «отказ, неотличимый от отсутствия» ──────────
	// Не держателю разбор доступа отвечает ТЕМ ЖЕ отказом на несуществующем well-formed
	// и на кривом id, что и на существующем: оракула существования нет.
	for _, c := range []struct{ who, why string }{
		{owner, "распорядитель-владелец"},
		{inviter, "распорядитель-администратор"},
		{stranger, "посторонний"},
	} {
		require.Falsef(t, w.allowed(t, "user:"+c.who, resetRel, absentWellFormed),
			"%s (user:%s) получил иной исход на НЕСУЩЕСТВУЮЩЕМ well-formed id, чем на существующем: "+
				"разбор доступа обязан отвечать одинаково — оракула существования у не держателя нет", c.why, c.who)
		require.Falsef(t, w.allowed(t, "user:"+c.who, resetRel, malformed),
			"%s (user:%s) получил иной исход на КРИВОМ id: тот же отказ, неотличимый от отсутствия — "+
				"форму отклоняет край/служба (400), а не разбор доступа", c.why, c.who)
	}

	// ── ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 1: то, что директива ОСТАВЛЯЕТ распорядителю ───────
	// Без этих утверждений отрицания выше зеленели бы на дереве, где у распорядителя
	// отняли всё, — и проба отчиталась бы победой о поломке.
	require.Truef(t, w.allowed(t, "user:"+inviter, grantRel, grantInAccount),
		"распорядитель обязан снимать выдачи в СВОЁМ аккаунте (%s на %s): это ровно то, что "+
			"директива владельца ему оставляет, и отрицания выше без этого ничего не утверждают",
		grantRel, grantInAccount)
	require.Truef(t, w.allowed(t, "user:"+owner, grantRel, grantInAccount),
		"владелец аккаунта обязан снимать выдачи в своём аккаунте (%s на %s)", grantRel, grantInAccount)
	require.Truef(t, w.allowed(t, "user:"+inviter, readRel, person),
		"распорядитель обязан ЧИТАТЬ запись своего члена (%s): сужение касалось сброса второго "+
			"фактора, а не видимости людей аккаунта", readRel)

	// ── ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ 2: надзор облака держит отношение (уровень 1) ──────
	// Без него отрицания выше держались бы недостижимостью отношения, а не разделением
	// прав, — и управление личностью было бы сломано незаметно.
	require.Truef(t, w.allowed(t, "user:"+cloudAdmin, resetRel, person),
		"администратор облака обязан держать сброс второго фактора (%s.%s) на строке личности: "+
			"иначе отношение не держит НИКТО, и отрицания выше вакуумны", resetType, resetRel)
	// Держатель проходит разбор доступа НА ЛЮБОМ объекте: существование раскрывает
	// СЛУЖБА (404), форму — край/служба (400), а не разбор доступа.
	require.Truef(t, w.allowed(t, "user:"+cloudAdmin, resetRel, absentWellFormed),
		"администратор облака обязан пройти разбор доступа и на НЕСУЩЕСТВУЮЩЕМ well-formed id: "+
			"«нет такого человека» — ответ СЛУЖБЫ (404 `User <id> not found`), не разбора доступа")
	require.Truef(t, w.allowed(t, "user:"+cloudAdmin, resetRel, malformed),
		"администратор облака обязан пройти разбор доступа и на КРИВОМ id: кривизну отклоняет "+
			"форма (400 `invalid user id`), не разбор доступа")

	t.Logf("перепись: гейт сброса %s.%s (acr«2») · чтения %s.%s · выдачи %s.%s · "+
		"ролей спрошено 4 (владелец·делегированный админ+выдача·посторонний·сам человек)+надзор облака · "+
		"некорректных id спрошено 2 (несуществующий well-formed · кривой)",
		resetType, resetRel, readType, readRel, grantType, grantRel)
}
