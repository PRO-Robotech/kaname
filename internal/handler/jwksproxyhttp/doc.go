// Package jwksproxyhttp — cluster-ВНУТРЕННИЙ публикатор набора проверочных
// ключей.
//
// # Запись ОДНА, и она наша
//
// Публикуется ПРОЕКЦИЯ ключницы (keyset.go): только наши ключи, только
// публичный материал, собственного кэша нет by construction. Путь записи
// объявляется настройкой своей чеканки, а не выводится из издателя
// (binding.go).
//
// Прежде рядом стояла вторая запись — зеркало публичного набора прежнего
// издателя. Оно жило до последней фазы отказа от внешнего сервера и ушло
// вместе с ним (kaname#361): без внешнего издателя зеркалить нечего, а запись
// без источника — находка, а не запас. Привязка теперь отвергает вторую запись
// в старте: вернувшись, она снова поставила бы ключ другого издателя рядом с
// нашим на том же слушателе.
//
// # Снятие authN — задокументированное исключение
//
// Маршрут НАБОРА КЛЮЧЕЙ не требует аутентификации осознанно: на проводе —
// ТОЛЬКО ПУБЛИЧНЫЙ МАТЕРИАЛ проверки подписи, в форме стандартного документа,
// на cluster-ВНУТРЕННЕМ слушателе (:9097, никогда внешнем — ban #6), под
// односторонней TLS с сертификатом внутреннего удостоверяющего центра.
//
// Требовать сертификат у ПОТРЕБИТЕЛЯ набора нельзя: он обязан оставаться
// origin-agnostic, и взаимная TLS сломала бы ровно это свойство.
//
// # Но соседняя поверхность того же слушателя обоснованием НЕ пользуется
//
// Авторитет отзыва (internal/handler/tokenintrospecthttp) стоит на этом же
// слушателе и принимает ПРЕДЪЯВЛЕННЫЙ ТОКЕН, а не отдаёт публичный материал.
// Обоснование выше на него не распространяется, поэтому он требует
// проверенного клиентского сертификата САМ, а слушатель переводится в режим
// «сертификат запрашивается и верифицируется, если предъявлен» — набор ключей
// при этом остаётся доступен без сертификата.
//
// Не добавляйте здесь authN-гейт, не пересмотрев это решение (и TLS-клиента
// потребителя набора).
