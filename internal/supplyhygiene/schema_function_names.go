// schema_function_names.go — судья ИМЁН ФУНКЦИЙ СХЕМЫ: ни одна функция,
// живущая в схеме службы после всей цепочки миграций, не носит имени платформы,
// кроме тех, что названы ведомостью решённого остаться — поимённо и с доводом.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ СУДИТСЯ ЖИВАЯ СХЕМА, А НЕ ТЕКСТ МИГРАЦИЙ
//
// Ось «таблицы» переписи осей (`platform_name_axes_test.go`) держалась ТОЧНЫМ
// ЧИСЛОМ вхождений имени платформы в файлах каталога миграций: 88 в 5 файлах.
// Число это к нулю не идёт НИКОГДА, и это свойство, а не недоработка: функции
// заведены применённым сводом, а применённую миграцию не правят (ban #5).
// Переименование делается НОВОЙ миграцией, после которой текст свода остаётся
// прежним, а объект в базе — уже нет. Значит предмет условия — ИМЯ ОБЪЕКТА
// после всей цепочки, и спрашивать о нём надо у базы, а не у файла.
//
// Судья поэтому принимает перечень имён, СНЯТЫЙ с `pg_proc` живой схемы
// (держатель — `internal/migrations`, прогон под контейнером Postgres), а не
// собирает его чтением `.sql`. Чтение по образцу распознало бы `CREATE FUNCTION`,
// но не `ALTER FUNCTION … RENAME TO` — и объявило бы переименованное живым
// именем платформы, то есть замолчало бы ровно на исходе, ради которого ось и
// заведена.
//
// ─────────────────────────────────────────────────────────────────────────────
// ВЕДОМОСТЬ РЕШЁННОГО ОСТАТЬСЯ — САМОИСТЕКАЮЩАЯ
//
// Две функции отказа учёта отрисованы шаблоном ФУНДАМЕНТА (corelib
// `quota/refusal.sql.tmpl`) и служат шести владельцам одним текстом; их имя
// выбирает шаблон, а не служба (kacho#2538 — «остаться»). Запись ведомости
// живёт, пока функция есть в схеме: запись без функции — послабление без
// предмета, и судья называет её находкой, а не пропускает молча. Потолка у
// ведомости нет — каждая запись поимённа и несёт довод.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО СУДЬЯ НЕ СУДИТ
//
//  1. тела функций. Ссылка на прежнее имя ВНУТРИ тела — вызов, который
//     разрешится во время исполнения, — предмет пробы поведения держателя, а не
//     переписи имён;
//  2. объекты, зависящие от функции (триггеры, ограничения CHECK): они
//     ссылаются на функцию по идентификатору и переименование переживают by
//     construction; что они по-прежнему указывают на переименованную — сверяет
//     держатель отдельным утверждением;
//  3. пустой перечень. «Функций прочитано ноль» — отказ, а не чистая схема:
//     схема службы несёт десятки функций, и ноль означает, что спросили не ту
//     базу.
package supplyhygiene

import (
	"fmt"
	"sort"
	"strings"
)

// SchemaFunctionStay — запись ведомости решённого остаться: функция схемы,
// чьё имя несёт имя платформы по решению, а не по недосмотру.
type SchemaFunctionStay struct {
	// Name — имя функции без квалификатора схемы, как в `pg_proc.proname`.
	Name string
	// Why — довод решения: кто выбирает имя и каким решением это принято.
	Why string
}

// SchemaFunctionCensus — объём осмотренного.
type SchemaFunctionCensus struct {
	// Functions — функций схемы прочитано.
	Functions int
	// Branded — из них несущих имя платформы (обе формы).
	Branded int
	// Stayed — из несущих — названных ведомостью решённого остаться.
	Stayed int
}

// JudgeSchemaFunctionNames судит перечень имён функций схемы против ведомости.
//
// names — `proname` каждой функции схемы службы после всей цепочки; stays —
// ведомость решённого остаться. Оба приходят параметрами: инъекция обязана
// подать тот же судья на синтетике, а не его копию.
func JudgeSchemaFunctionNames(names []string, stays []SchemaFunctionStay) (SchemaFunctionCensus, []string) {
	var (
		census   SchemaFunctionCensus
		findings []string
	)
	if len(names) == 0 {
		return census, []string{"функций схемы прочитано ноль: обход пуст, и о схеме не известно ничего"}
	}

	stayByName := map[string]SchemaFunctionStay{}
	for _, s := range stays {
		switch {
		case strings.TrimSpace(s.Name) == "":
			findings = append(findings, "запись ведомости решённого остаться без имени функции")
			continue
		case strings.TrimSpace(s.Why) == "":
			findings = append(findings, fmt.Sprintf("запись ведомости %q без довода: «остаётся» без "+
				"причины есть послабление, за которым никто не отвечает", s.Name))
		}
		if _, dup := stayByName[s.Name]; dup {
			findings = append(findings, fmt.Sprintf("запись ведомости %q названа дважды", s.Name))
			continue
		}
		stayByName[s.Name] = s
	}

	present := map[string]bool{}
	sorted := append([]string(nil), names...)
	sort.Strings(sorted)
	for _, n := range sorted {
		census.Functions++
		present[n] = true
		if len(PlatformNameHits(n)) == 0 {
			continue
		}
		census.Branded++
		if _, ok := stayByName[n]; ok {
			census.Stayed++
			continue
		}
		findings = append(findings, fmt.Sprintf("функция схемы %q носит имя платформы: оператор, "+
			"поставивший службу одну, видит в СВОЕЙ схеме функцию продукта, которого он не ставил; "+
			"переименование — новой миграцией, либо запись в ведомости решённого остаться с доводом", n))
	}

	stayNames := make([]string, 0, len(stayByName))
	for n := range stayByName {
		stayNames = append(stayNames, n)
	}
	sort.Strings(stayNames)
	for _, n := range stayNames {
		switch {
		case !present[n]:
			findings = append(findings, fmt.Sprintf("запись ведомости %q: функции с таким именем в "+
				"схеме нет — послабление без предмета; снимите запись тем же изменением, что сняло "+
				"предмет", n))
		case len(PlatformNameHits(n)) == 0:
			findings = append(findings, fmt.Sprintf("запись ведомости %q: имя не несёт имени "+
				"платформы — прощать нечего, запись истекла", n))
		}
	}
	return census, findings
}
