// doc_only_package_test.go — пакет, состоящий из ОДНОГО описания.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ (#2503)
//
// Два каталога службы содержали единственный файл Go — `doc.go`, — и оба
// описывали то, чего в них нет: первый перечислял восемь файлов поимённо, типы
// строк и методы перевода в домен и обратно; второй — конструктор репозитория,
// помощник ожидания операции и способ порождения моков. Импортёров у обоих было
// ноль, а порт чтения соседнего каталога ОТПРАВЛЯЛ читателя во второй из них.
//
// Такой пакет — не мёртвый код, а ЛОЖНЫЙ АДРЕС. Мёртвый код читатель опознаёт по
// отсутствию вызывающих; описание несуществующего выглядит живым механизмом, и
// следующий идёт по нему за образцом. Для службы, уезжающей отдельным продуктом,
// цена выше: объявленный паритет отсылал к дереву, которого у клонирующего нет.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО УТВЕРЖДАЕТСЯ — и почему признак именно такой
//
// Каталог, чьи файлы Go исчерпываются одним `doc.go`, не содержит НИ ОДНОГО
// объявления. Значит всякое утверждение его шапки о содержимом каталога ложно by
// construction — независимо от того, что в шапке написано. Признак поэтому
// структурный и не читает прозу вовсе: он не спорит с текстом, он отказывает
// месту, где текст не может быть правдой.
//
// Обратное — `doc.go` РЯДОМ с объявлениями — законно и в дереве обычно: девять
// каталогов на момент заведения. Проверка обязана молчать на всех девяти, и это
// её положительный контроль: без него признак «в каталоге есть doc.go» отключил
// бы девять законных мест и был бы снят первым же прогоном.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ НЕ ПРОВЕРКА ПРОЗЫ ПО ПОДСТРОКЕ — ЗАМЕРЕНО
//
// Первым был написан предикат, читавший шапки: «имя файла, названное в
// комментарии, обязано существовать в том же каталоге». На дереве службы он дал
// **173 находки** при 2279 прочитанных файлах Go — и почти все ложные: проза
// законно называет соседа кратким именем (`serve.go`, `wiring.go`, `main.go`),
// имея в виду файл ДРУГОГО каталога. Предикат с такой долей ложного отключают
// первым, и он не был поставлен.
//
// Структурный признак ложных находок не имеет вовсе: он судит СОСТАВ каталога, а
// не то, как о нём написано.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЭТА ПРОВЕРКА НЕ ЗАКРЫВАЕТ — сказано прямо
//
// Она не судит ИСТИННОСТЬ шапки там, где в каталоге есть объявления: шапка рядом
// с кодом может врать, и такие места закрываются проверками по месту (образец —
// `internal/apps/kaname/api/session_revocations/is_revoked_doc_test.go`). Здесь
// закрыт ровно один класс: описание, у которого предмета нет НИ ОДНОГО.
package supplyhygiene

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"github.com/PRO-Robotech/corelib/treecorpus"
	"github.com/stretchr/testify/require"
)

// docOnlyFileName — имя файла, который несёт шапку пакета и ничего больше.
const docOnlyFileName = "doc.go"

// docOnlyCensus — объём осмотренного. Печатается ВСЕГДА, включая зелёный
// прогон: «ноль находок» обязано быть отличимо от «ноль прочитанного» и от
// «законных близнецов не нашлось, поэтому признак не проверялся».
type docOnlyCensus struct {
	goFiles     int // файлов Go в составе дерева
	dirs        int // каталогов, содержащих хотя бы один файл Go
	dirsWithDoc int // каталогов, содержащих doc.go
	dirsDocOnly int // каталогов, где doc.go — единственный файл Go: находки
	dirsDocPlus int // каталогов, где doc.go лежит РЯДОМ с объявлениями
}

// scanDocOnlyPackages разбирает ПРОИЗВОЛЬНЫЙ корень: настоящее дерево службы и
// синтетический корень инъекции проходят одну и ту же функцию, поэтому
// доказанное на втором верно для первого.
//
// Возвращает перепись и отсортированный перечень находок — путей каталогов.
func scanDocOnlyPackages(tree *treecorpus.Tree) (docOnlyCensus, []string, error) {
	var census docOnlyCensus

	byDir := map[string][]string{}
	for _, rel := range tree.SortedFiles() {
		slash := filepath.ToSlash(rel)
		if !strings.HasSuffix(slash, ".go") {
			continue
		}
		census.goFiles++
		dir := filepath.ToSlash(filepath.Dir(slash))
		byDir[dir] = append(byDir[dir], filepath.Base(slash))
	}
	census.dirs = len(byDir)

	var findings []string
	for dir, names := range byDir {
		hasDoc := false
		for _, n := range names {
			if n == docOnlyFileName {
				hasDoc = true
				break
			}
		}
		if !hasDoc {
			continue
		}
		census.dirsWithDoc++
		if len(names) == 1 {
			census.dirsDocOnly++
			findings = append(findings, dir)
			continue
		}
		census.dirsDocPlus++
	}
	sort.Strings(findings)

	if census.goFiles == 0 {
		return census, nil, fmt.Errorf(
			"описание без предмета: файлов Go в обходе ноль — вердикт беспредметен (корень %q)",
			tree.Root())
	}
	return census, findings, nil
}

// TestNoPackageConsistsOnlyOfItsOwnDescription — гейт класса на дереве службы.
func TestNoPackageConsistsOnlyOfItsOwnDescription(t *testing.T) {
	tree, err := treecorpus.NewTree(serviceRoot)
	require.NoError(t, err, "состав дерева службы не собран — вердикт беспредметен")

	census, findings, err := scanDocOnlyPackages(tree)
	require.NoError(t, err)

	t.Logf("перепись: файлов Go %d · каталогов с файлами Go %d · из них несут %s: %d "+
		"(рядом с объявлениями %d · без объявлений %d)",
		census.goFiles, census.dirs, docOnlyFileName,
		census.dirsWithDoc, census.dirsDocPlus, census.dirsDocOnly)

	// ПРЕДПОСЫЛКИ. Обе ловят вырождение признака, а не дефект дерева.
	require.NotZero(t, census.dirs,
		"каталогов с файлами Go не найдено ни одного — обход сломан, и всякое "+
			"утверждение ниже вакуумно")
	require.NotZerof(t, census.dirsDocPlus,
		"в дереве нет НИ ОДНОГО каталога, где %s лежит рядом с объявлениями — "+
			"значит различение «описание рядом с кодом» / «описание вместо кода» "+
			"не проверено ничем, и признак мог бы отключать законные места молча",
		docOnlyFileName)

	require.Emptyf(t, findings,
		"пакет состоит из одного описания — предмета у его шапки нет ни одного:\n  %s\n\n"+
			"Исходов три: описать то, что в каталоге есть · снять каталог вместе с "+
			"описанием · завести объявления, которые шапка называет. Ложный адрес "+
			"выглядит живым механизмом, и следующий идёт по нему за образцом.",
		strings.Join(findings, "\n  "))
}
