// docs_site_address_test.go — сайт документации называет СВОЙ адрес суффиксом
// ЭТОГО продукта, а не платформы.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Поле `url` конфигурации Docusaurus не косметическое: из него строятся
// канонические ссылки страниц, `sitemap.xml` и абсолютные адреса в разметке для
// поисковых систем. Пока там стоял `https://iam.kacho.cloud`, сайт продукта
// Kaname объявлял читателю и роботам, что живёт на домене ЧУЖОГО продукта (#57).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЭТО ВТОРОЕ СРАБАТЫВАНИЕ ОДНОГО КЛАССА, И ПОТОМУ ГЕЙТ, А НЕ ПРАВКА
//
// Первое было в теле отказа: производитель отвечал `iam.kacho.cloud`, тогда как
// прочие полосы службы — `iam.kaname.cloud`. Различие никем не решалось, оно
// приехало вместе с файлом из модуля платформы, где объявление продукта
// недостижимо. Закрыто `kaname#48` тем же ходом, что и здесь: брать у
// ОБЪЯВЛЕНИЯ, а не у литерала.
//
// Класс, сработавший дважды на двух разных поверхностях, правкой не закрывается:
// третья поверхность приедет так же тихо. Признак у него один и тот же —
// координата пережила переезд и продолжает читаться как действующая.
//
// ─────────────────────────────────────────────────────────────────────────────
// ГЕЙТ СВЕРЯЕТСЯ С СУЩЕСТВОМ, А НЕ С ТЕКСТОМ
//
// Ожидаемый суффикс не выписан здесь строкой — он ИМПОРТИРОВАН из
// `internal/refusaldomain`, единственного места, где продукт называет себя
// (решение приёмки WIRE-1, W3). Выписанная копия разошлась бы с объявлением
// молча и ровно тем способом, который этот гейт и стережёт: два места об одном
// предмете, и расходится то, которое не считали.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ИМЕННО СУДИТСЯ — ПОЛЕ, А НЕ ФАЙЛ
//
// Читается значение ОДНОГО поля `url` конфигурации сайта. Имя платформы законно
// живёт в этом дереве десятками вхождений — как имя proto-пакета
// (`kacho.cloud.operation.v1`: конверт операции принадлежит платформе), как
// SPIFFE-имя чужой службы, как разбор в прозе приёмки. Гейт по подстроке краснел
// бы на каждом и был бы снят первым же читателем; предмет здесь — ЧЕМ САЙТ
// НАЗЫВАЕТ СЕБЯ, а не встречается ли где-то имя соседа.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЭТА ПРОВЕРКА НЕ ЗАКРЫВАЕТ — сказано прямо
//
//   - Она не утверждает, что по этому адресу что-то ОТВЕЧАЕТ. Замер на
//     `4c3ad523`: сайт не собирается ни одним заданием конвейера и не
//     публикуется ничем — адреса, «по которому он обслуживается», не существует.
//     Гейт судит, чем продукт называет себя, а не факт развёртывания.
//   - Она не судит ПОЛОСУ (`iam` против `docs`): какую полосу занять сайту —
//     решение развёртывания, в этом дереве не установленное. Потребуй гейт
//     определённой полосы — он выражал бы мнение автора, а не согласие дерева.
package supplyhygiene

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kaname/internal/refusaldomain"
)

// docsSiteConfig — конфигурация сайта документации относительно корня службы.
const docsSiteConfig = "docs/docusaurus.config.ts"

// docsSiteURLField — поле `url` верхнего уровня со значением в кавычках любого
// вида. Якорь `(?m)^\s{0,4}url:` держит поле ВЕРХНЕГО уровня: одноимённые ключи
// встречаются вложенными (ссылки подвала, элементы панели), и без якоря гейт
// судил бы первое попавшееся.
var docsSiteURLField = regexp.MustCompile(`(?m)^\s{0,4}url:\s*['"]([^'"]+)['"]`)

// docsSiteHost — хост из абсолютного адреса.
var docsSiteHost = regexp.MustCompile(`^[a-zA-Z][a-zA-Z0-9+.-]*://([^/?#]+)`)

// docsSiteCensus — объём осмотренного: «ноль находок» обязано быть отличимо от
// «ноль прочитанного».
type docsSiteCensus struct {
	configsRead int
	urlFields   int
}

// scanDocsSiteAddress — разбор над ПРОИЗВОЛЬНЫМ корнем. Вынесено из пробы затем,
// чтобы способность гейта упасть доказывалась подачей входа, а не чтением.
func scanDocsSiteAddress(root string) (docsSiteCensus, []string) {
	var census docsSiteCensus
	var findings []string

	raw, err := os.ReadFile(filepath.Join(root, docsSiteConfig))
	if err != nil {
		return census, append(findings, docsSiteConfig+": не прочитан: "+err.Error()+
			" — о том, чем сайт называет себя, не сказано ничего, и зелёное здесь означало бы «не читали»")
	}
	census.configsRead++

	m := docsSiteURLField.FindStringSubmatch(string(raw))
	if m == nil {
		return census, append(findings, docsSiteConfig+": поля `url` верхнего уровня не найдено — "+
			"Docusaurus требует его для канонических ссылок и `sitemap.xml`, значит либо сборка сайта "+
			"отказывает, либо распознаватель ослеп на форму записи; и то и другое — находка")
	}
	census.urlFields++

	addr := m[1]
	h := docsSiteHost.FindStringSubmatch(addr)
	if h == nil {
		return census, append(findings, docsSiteConfig+": `url` = `"+addr+
			"` — это не абсолютный адрес, а Docusaurus строит из него АБСОЛЮТНЫЕ ссылки")
	}

	host := strings.ToLower(h[1])
	if i := strings.LastIndex(host, ":"); i > 0 && !strings.Contains(host[i:], "]") {
		host = host[:i] // порт частью имени не является
	}

	want := strings.ToLower(refusaldomain.ProductSuffix)
	if host == want || strings.HasSuffix(host, "."+want) {
		return census, findings
	}

	return census, append(findings, docsSiteConfig+": `url` = `"+addr+
		"` — сайт называет себя доменом `"+host+"`, тогда как ЭТОТ продукт объявляет суффикс `"+want+
		"` (`internal/refusaldomain.ProductSuffix`, решение приёмки WIRE-1). Поле не косметическое: "+
		"из него строятся канонические ссылки, `sitemap.xml` и абсолютные адреса для поисковых роботов, "+
		"то есть сайт объявляет им, что живёт на домене чужого продукта. Тот же класс закрыт в теле "+
		"отказа (kaname#48) тем же ходом — берётся у объявления, а не у литерала (#57)")
}

func TestDocsSiteNamesItselfByTheProductSuffix(t *testing.T) {
	t.Parallel()

	census, findings := scanDocsSiteAddress(serviceRoot)

	t.Logf("перепись: конфигураций сайта прочитано %d · полей `url` разобрано %d · "+
		"суффикс продукта по объявлению `%s` · находок %d",
		census.configsRead, census.urlFields, refusaldomain.ProductSuffix, len(findings))

	// Пустой обход — поломка гейта, а не чистота дерева.
	if census.configsRead == 0 && len(findings) == 0 {
		t.Fatal("конфигурация сайта не прочитана и находок нет — вердикт беспредметен")
	}
	if refusaldomain.ProductSuffix == "" {
		t.Fatal("суффикс продукта объявлен пустым — сравнивать не с чем, и всякое значение `url` прошло бы")
	}

	for _, f := range findings {
		t.Error(f)
	}
}
