// package_qualifier_test.go — ВТОРАЯ полоса записи имени: квалификатор пакета.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Каталоги службы переименованы, пакет объявляет себя `kaname`, а шапки функций
// и проза комментариев продолжали писать прежний квалификатор: `kacho.Reader` и
// два его соседа по порту чтения и записи. Читатель идёт за этим именем и не
// находит его; следующий, кто станет чинить код под неверный комментарий,
// заведёт ВТОРУЮ копию имени вместо одной.
//
// Различение то же, что у соседней проверки каталогов: имя, которым продукт себя
// НАЗЫВАЕТ, — своё; код, который он ИСПОЛНЯЕТ, берётся у платформы как есть.
// Квалификатор своего пакета — первое, а не второе.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОТДЕЛЬНАЯ ПРОВЕРКА, А НЕ РАСШИРЕНИЕ СОСЕДНЕЙ
//
// `directory_name_test.go` судит ДВУСОСТАВНУЮ форму сегмента пути — родительский
// каталог плюс отставленный сегмент, — и узкая форма выбрана там ОСОЗНАННО: она
// пропускает и более длинный сегмент, и путь модуля, и пакет контракта, и имя
// схемы, и якорь кластера. Двусоставная форма здесь НЕ воспроизводится дословно
// намеренно: сосед судит её у каждого файла вне своего перечня, и цитата в этой
// шапке была бы для него настоящей находкой — он это и сказал, когда её внесли.
//
// Квалификатор `kacho.Reader` такой формы не имеет и в полосу соседа не попадает
// by construction, поэтому его перепись честно печатает «ссылок 0» — и это верно
// о том, что он читает.
//
// Расширить соседа значило бы разменять его узость, ради которой он и написан.
// Полоса вторая — значит и распознаватель второй, со своим положительным
// контролем и своим доказательством.
//
// ─────────────────────────────────────────────────────────────────────────────
// РАСПОЗНАВАТЕЛЬ: ЗАГЛАВНАЯ СРАЗУ ПОСЛЕ ТОЧКИ — И БОЛЬШЕ НИЧЕГО
//
// Имя платформы перед точкой несут в этом дереве НЕСКОЛЬКО разных словарей, и
// ни один из них квалификатором пакета не является: пакет контракта · имена DNS
// стенда и кластера · отношения модели прав · домены каталога решений · фикстуры
// проб. Числом их полоса названа НЕ здесь, а переписью на каждом прогоне: число
// в прозе владельца не имеет и стареет молча, а перепись перемеряется сама.
// Литералами словари здесь тоже не выписаны — их место заняли бы вхождения имени
// платформы ровно там, где продукт называет себя своим.
//
// Все они продолжаются СТРОЧНОЙ буквой. Квалификатор пакета Go продолжается
// ЗАГЛАВНОЙ — экспортируемое имя иначе выглядеть не может. Поэтому дискриминатор
// один и он структурный: байт СРАЗУ после точки есть заглавная латинская буква.
//
// «Сразу» здесь несущее слово. Проза кончает предложение точкой, и следующее
// начинается с заглавной («…пакет звался так-то. Реализация живёт…»); между
// ними стоит пробел, поэтому под форму она не подпадает. Кириллическая заглавная
// не подпадает тоже: диапазон назван латинским явно.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ИМЕННО УТВЕРЖДАЕТСЯ — три вещи, и все три вместе
//
//  1. канонический квалификатор ПРИСУТСТВУЕТ в дереве службы. Без этого условия
//     отрицание ниже выполнилось бы на дереве, где нет ни одного квалификатора
//     вовсе: отрицание без положительного близнеца есть вакуумное утверждение;
//  2. отставленного квалификатора в дереве службы НЕТ ни разу;
//  3. перепись НАЗЫВАЕТСЯ числами, включая полосу, которую распознаватель
//     ПРОПУСКАЕТ. Строчное продолжение считается ОТДЕЛЬНО — иначе «ноль находок»
//     было бы неотличимо от «строчных словарей не искали вовсе».
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЛОС-ПРОПУСКОВ ЗДЕСЬ ОДНА, И ЭТО ИЗМЕРЕНО, А НЕ ВЫБРАНО
//
// У соседа их четыре: каталог соседней службы, применённая миграция, захваченный
// отчёт, сама проверка. Здесь остаётся ПОСЛЕДНЯЯ, и только она: проверка обязана
// называть отставленную форму, иначе у распознавателя нет входа, а у инъекции
// нет дефекта.
//
// Прочих трёх полос у этой формы НЕТ ПРЕДМЕТА, и это замерено на дереве службы
// при заведении: отставленный квалификатор стоял в семи файлах, из них ни одного
// применённой миграции, ни одного захваченного отчёта, ни одного каталога
// соседней службы. Полоса без предмета — это послабление, которое не истечёт
// никогда; заводить её «на будущее» значило бы отдать под неё первую же
// настоящую находку. Появится такое вхождение — оно станет НАХОДКОЙ и потребует
// решения вслух, а не тихого пропуска.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЭТА ПРОВЕРКА НЕ ЗАКРЫВАЕТ — сказано прямо
//
// Она судит ДЕРЕВО СЛУЖБЫ и молчит обо всём вне его корня. Тот же квалификатор
// в дереве СОСЕДНЕЙ службы (`services/vpc`, `services/nlb`) — живой код, а не
// находка: у соседа своего имени продукта нет, и его пакет законно объявляет
// себя именем платформы. Ссылка на такой чужой пакет из прозы НАШЕГО дерева
// сегодня отсутствует (замерено: ноль), и потому полосы под неё здесь нет.
// Появится — это будет находка, и её придётся решить вслух.
package supplyhygiene

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kacho/pkg/treecorpus"
	"github.com/stretchr/testify/require"
)

// qualifierOwnFiles — файлы, ПРЕДМЕТ которых есть сама эта проверка. Каждый
// обязан называть отставленный квалификатор, чтобы делать свою работу.
//
// Полоса задана ПЕРЕЧНЕМ, а не признаком формы: признак («файл объявляет
// константу», «файл лежит в этом каталоге») освободил бы и соседей, то есть
// ровно тех, кого проверка заводилась ловить.
var qualifierOwnFiles = map[string]bool{
	"internal/supplyhygiene/package_qualifier_test.go":           true,
	"internal/supplyhygiene/package_qualifier_injection_test.go": true,
}

// qualifierCensus — объём осмотренного. Печатается всегда, включая зелёный
// прогон: «ноль находок» обязано быть отличимо и от «ноль прочитанного», и от
// «строчную полосу не читали».
type qualifierCensus struct {
	filesRead        int // файлов дерева прочитано
	filesBinary      int // пропущено как двоичные
	canonicalQuals   int // вхождений `kaname.<Заглавная>`
	retiredQuals     int // вхождений `kacho.<Заглавная>` — находки
	skippedLowercase int // `kacho.<строчная>`: контракт · DNS · отношение · домен
	skippedOwn       int // пропущено: сама проверка и её доказательство
	filesOwn         int // файлов перечня «предмет = эта проверка»
}

// qualifierFinding — одно вхождение отставленного квалификатора.
type qualifierFinding struct {
	file string
	line int
	text string
}

func (f qualifierFinding) String() string {
	return fmt.Sprintf("%s:%d: %s", f.file, f.line, strings.TrimSpace(f.text))
}

// isQualifierIdentByte — байт, который мог бы продолжать идентификатор слева от
// имени пакета. Нужен, чтобы `mykacho.Reader` не засчитывался нашим пакетом.
func isQualifierIdentByte(b byte) bool {
	return b == '_' || (b >= 'a' && b <= 'z') || (b >= 'A' && b <= 'Z') || (b >= '0' && b <= '9')
}

// countQualifiers считает в строке вхождения `<seg>.<Заглавная>` и ОТДЕЛЬНО —
// `<seg>.<строчная>`. Второе число возвращается затем, чтобы пропущенная полоса
// была названа числом, а не умолчанием.
func countQualifiers(line, seg string) (upper, lower int) {
	needle := seg + "."
	for at := 0; ; {
		idx := strings.Index(line[at:], needle)
		if idx < 0 {
			return upper, lower
		}
		abs := at + idx
		end := abs + len(needle)
		at = end
		// Левая граница: продолжение идентификатора означает другое имя.
		if abs > 0 && isQualifierIdentByte(line[abs-1]) {
			continue
		}
		if end >= len(line) {
			continue
		}
		switch c := line[end]; {
		case c >= 'A' && c <= 'Z':
			upper++
		case c >= 'a' && c <= 'z':
			lower++
		}
	}
}

// scanPackageQualifiers разбирает ПРОИЗВОЛЬНЫЙ корень: настоящее дерево службы и
// синтетический корень инъекции проходят одну и ту же функцию, поэтому
// доказанное на втором верно для первого.
func scanPackageQualifiers(tree *treecorpus.Tree) (qualifierCensus, []qualifierFinding, error) {
	var census qualifierCensus
	var findings []qualifierFinding

	root := tree.Root()
	for _, rel := range tree.SortedFiles() {
		slash := filepath.ToSlash(rel)

		raw, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil {
			return census, nil, fmt.Errorf("квалификатор: файл %s не прочитан: %w", rel, err)
		}
		if strings.IndexByte(string(raw), 0) >= 0 {
			census.filesBinary++
			continue
		}
		census.filesRead++

		own := qualifierOwnFiles[slash]

		var fileRetired int
		for i, line := range strings.Split(string(raw), "\n") {
			canon, _ := countQualifiers(line, canonicalSegment)
			census.canonicalQuals += canon

			upper, lower := countQualifiers(line, retiredSegment)
			census.skippedLowercase += lower
			if upper == 0 {
				continue
			}
			fileRetired += upper
			if own {
				census.skippedOwn += upper
				continue
			}
			census.retiredQuals += upper
			findings = append(findings, qualifierFinding{file: slash, line: i + 1, text: line})
		}
		if fileRetired > 0 && own {
			census.filesOwn++
		}
	}

	if census.filesRead == 0 {
		return census, nil, fmt.Errorf("квалификатор: обход пуст — вердикт беспредметен (корень %q)", root)
	}
	return census, findings, nil
}

// TestServicePackagesAreQualifiedByTheirOwnProductName — гейт класса.
func TestServicePackagesAreQualifiedByTheirOwnProductName(t *testing.T) {
	tree, err := treecorpus.NewTree(serviceRoot)
	require.NoError(t, err, "состав дерева службы не собран — вердикт беспредметен")

	census, findings, err := scanPackageQualifiers(tree)
	require.NoError(t, err)

	t.Logf("перепись: файлов прочитано %d · двоичных пропущено %d · "+
		"квалификаторов %q.<Заглавная> %d · %q.<Заглавная> %d · "+
		"пропущено %q.<строчная> %d (контракт · DNS · отношение · домен) · "+
		"файлов самой проверки %d (%d вхождений)",
		census.filesRead, census.filesBinary,
		canonicalSegment, census.canonicalQuals,
		retiredSegment, census.retiredQuals,
		retiredSegment, census.skippedLowercase,
		census.filesOwn, census.skippedOwn)

	require.NotZero(t, census.canonicalQuals,
		"положительный контроль пуст: квалификатора %q.<Заглавная> в дереве нет ни одного — "+
			"значит распознаватель не работает вовсе, и отрицание ниже вакуумно", canonicalSegment)

	if len(findings) > 0 {
		shown := findings
		if len(shown) > 20 {
			shown = shown[:20]
		}
		var b strings.Builder
		for _, f := range shown {
			b.WriteString("\n  " + f.String())
		}
		t.Fatalf("квалификатор пакета зовётся отставленным именем %q в %d местах "+
			"(показаны первые %d):%s\n\nпакет объявляет себя %q — так его и называют "+
			"шапки функций и проза; канон объявлен константой canonicalSegment в "+
			"directory_name_test.go, одной на обе полосы записи",
			retiredSegment, len(findings), len(shown), b.String(), canonicalSegment)
	}
}
