// generator_coordinates_test.go — координаты оснастки порождения РЕЗОЛВЯТСЯ в
// этом дереве.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Порождение таблиц типов вместе со службой не переехало: обе его координаты
// остались монорепными (#61). Довод `-root ../../../..` отсчитывался от
// `services/iam/internal/authzmap` и приводил к корню платформы, а из этого
// дерева те же четыре шага уводят на два уровня ВЫШЕ корня репозитория.
// `GeneratedRelPath` называл `services/iam/internal/authzmap/tables_gen.go`,
// которого здесь нет: прогон отвечал `no such file or directory` с кодом 2.
//
// ПЕРЕМЕР ДАЛ БОЛЬШЕ, ЧЕМ НАЗЫВАЛА ЗАДАЧА. Тех же координат в оснастке
// порождения оказалось ЧЕТЫРЕ, а не две: сверх названных — строка авторства и
// подсказка перегенерации, ОБЕ внутри самого порождённого файла. Они читались
// читателем как действующие и вели в каталог, которого нет; задача их не
// застала, потому что смотрела на команду и на константу, а не на её продукт.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ГЕЙТ, А НЕ ПРАВКА ЧЕТЫРЁХ СТРОК
//
// Класс — «координата пережила своё дерево» — тихий by construction: она не
// собирается, не исполняется и не роняет ничего. Заметить её можно только
// пойдя по ней, а идут по ней редко и в неудачный момент. Четыре срабатывания
// одного класса в одной оснастке — довод завести держателя, а не поправить
// четвёртое.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ИМЕННО СУДИТСЯ — ПУТЬ, А НЕ СЛОВО
//
// Гейт берёт координаты ОТТУДА, ГДЕ ИМИ ПОЛЬЗУЮТСЯ, и проверяет, что каждая
// разрешается в дереве. Он НЕ ищет подстроку `services/` по файлам: имя каталога
// модулей платформы законно стоит в прозе — в разборе истории переезда, в
// описании источника манифестов (`services/*/manifest.yaml` — это дерево
// ПЛАТФОРМЫ, где манифесты и лежат), в объяснении самой этой находки. Гейт по
// подстроке краснел бы на каждом и был бы снят первым же читателем.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЭТА ПРОВЕРКА НЕ ЗАКРЫВАЕТ — сказано прямо
//
//   - Она не утверждает, что перегенерация ВОСПРОИЗВОДИТ файл: это предмет
//     гейта свежести, и ему нужен корень платформы, которого рядом с
//     самостоятельным клоном нет by construction.
//   - Она судит координаты ОСНАСТКИ ПОРОЖДЕНИЯ, а не всего дерева. Перепись
//     2026-09-13 нашла `services/iam` в 38 местах этих каталогов; из них
//     действующими координатами являются четыре, названные ниже, остальные —
//     проза и константы ЧУЖИХ проб (у них свой предмет и своя задача).
package supplyhygiene

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kaname/internal/authzmapgen"
)

// generatorDirectiveFile — файл, несущий директиву порождения.
const generatorDirectiveFile = "internal/authzmap/fga_types.go"

// generatorDirective — сама директива и её доводы.
var generatorDirective = regexp.MustCompile(`(?m)^//go:generate\s+(.+)$`)

// generatorModuleArg — довод, называющий корень МОДУЛЯ.
var generatorModuleArg = regexp.MustCompile(`-module\s+(\S+)`)

// generatedAttribution — строка авторства порождённого файла: `Code generated by <путь>.`
var generatedAttribution = regexp.MustCompile(`//\s*Code generated by\s+([^\s.]+)\.`)

// generatedRegenHint — подсказка перегенерации: `go generate ./<путь>/...`
var generatedRegenHint = regexp.MustCompile(`go generate\s+\./(\S+?)/\.\.\.`)

// generatorCoordinate — одна названная координата и её происхождение.
type generatorCoordinate struct {
	// Where — где она объявлена (читателю идти чинить сюда).
	Where string
	// What — чем она является, словами: находка обязана называть предмет.
	What string
	// Rel — путь от корня модуля.
	Rel string
	// Marker — файл, обязанный лежать ВНУТРИ координаты, либо пусто.
	//
	// СУЩЕСТВОВАНИЯ КАТАЛОГА НЕДОСТАТОЧНО, и это замер, а не осторожность:
	// прежний довод `../../../..` уводил на два уровня выше корня репозитория —
	// то есть в каталог, который СУЩЕСТВУЕТ почти всегда. Проверка на наличие
	// пропустила бы ровно тот дефект, ради которого заведена. Корень модуля
	// опознаётся тем, что делает его корнем модуля, — файлом `go.mod`.
	Marker string
}

// generatorCensus — объём осмотренного.
type generatorCensus struct {
	sourcesRead int
	coordinates int
	resolved    int
}

// scanGeneratorCoordinates — разбор над ПРОИЗВОЛЬНЫМ корнем. Вынесено из пробы
// затем, чтобы способность гейта упасть доказывалась подачей входа, а не чтением.
func scanGeneratorCoordinates(root string) (generatorCensus, []generatorCoordinate, []string) {
	var census generatorCensus
	var coords []generatorCoordinate
	var findings []string

	// ── 1. константа продукта ────────────────────────────────────────────────
	// Берётся ИМПОРТОМ, а не переписыванием строки: копия разошлась бы с
	// объявлением молча — ровно тот класс, который гейт и стережёт.
	coords = append(coords, generatorCoordinate{
		Where: "internal/authzmapgen.GeneratedRelPath",
		What:  "координата порождённого файла",
		Rel:   authzmapgen.GeneratedRelPath,
	})

	// ── 2. довод `-module` директивы порождения ──────────────────────────────
	if raw, err := os.ReadFile(filepath.Join(root, generatorDirectiveFile)); err != nil {
		findings = append(findings, generatorDirectiveFile+": не прочитан: "+err.Error()+
			" — о директиве порождения не сказано ничего")
	} else {
		census.sourcesRead++
		d := generatorDirective.FindStringSubmatch(string(raw))
		if d == nil {
			findings = append(findings, generatorDirectiveFile+
				": директивы `go:generate` не найдено — перегенерация перестала быть объявленной, "+
				"и способ привести файл в соответствие известен только тому, кто его писал")
		} else if m := generatorModuleArg.FindStringSubmatch(d[1]); m == nil {
			findings = append(findings, generatorDirectiveFile+
				": директива не называет `-module` — корень модуля будет взят умолчанием команды, "+
				"и продукт ляжет относительно каталога вызова, а не модуля")
		} else {
			// Довод относителен каталогу директивы — там его читает `go generate`.
			rel := filepath.Join(filepath.Dir(generatorDirectiveFile), m[1])
			coords = append(coords, generatorCoordinate{
				Where:  generatorDirectiveFile + " (`-module " + m[1] + "`)",
				What:   "корень модуля, куда ложится продукт",
				Rel:    filepath.Clean(rel),
				Marker: "go.mod",
			})
		}
	}

	// ── 3-4. координаты, уехавшие в САМ ПРОДУКТ ──────────────────────────────
	genRel := authzmapgen.GeneratedRelPath
	if raw, err := os.ReadFile(filepath.Join(root, genRel)); err != nil {
		findings = append(findings, genRel+": порождённый файл не прочитан: "+err.Error())
	} else {
		census.sourcesRead++
		head := string(raw)
		if m := generatedAttribution.FindStringSubmatch(head); m != nil {
			coords = append(coords, generatorCoordinate{
				Where: genRel + " (строка авторства)",
				What:  "команда, породившая файл",
				Rel:   m[1],
			})
		} else {
			findings = append(findings, genRel+
				": строки авторства `Code generated by …` нет — читатель не узнает, кто пишет файл, "+
				"и поправит его руками")
		}
		if m := generatedRegenHint.FindStringSubmatch(head); m != nil {
			coords = append(coords, generatorCoordinate{
				Where: genRel + " (подсказка перегенерации)",
				What:  "каталог, по которому зовётся перегенерация",
				Rel:   m[1],
			})
		} else {
			findings = append(findings, genRel+
				": подсказки `go generate ./…/...` нет — правка руками остаётся единственным "+
				"известным читателю способом, а она бессмысленна")
		}
	}

	// ── суждение ─────────────────────────────────────────────────────────────
	census.coordinates = len(coords)
	for _, c := range coords {
		// Выход ЗА ПРЕДЕЛЫ дерева судится раньше существования: путь выше корня
		// почти всегда существует, поэтому проверка наличия его пропустит — а
		// это и есть форма прежнего дефекта (`-root ../../../..`).
		if c.Rel == ".." || strings.HasPrefix(c.Rel, ".."+string(filepath.Separator)) {
			findings = append(findings, c.Where+": координата `"+c.Rel+"` ("+c.What+
				") уводит ЗА ПРЕДЕЛЫ дерева. Каталог выше корня существует почти всегда, "+
				"поэтому такая координата выглядит рабочей и молча указывает не туда — "+
				"ровно форма прежнего дефекта `-root ../../../..` (#61)")
			continue
		}
		if _, err := os.Stat(filepath.Join(root, c.Rel)); err != nil {
			findings = append(findings, c.Where+": координата `"+c.Rel+"` ("+c.What+
				") в этом дереве НЕ РЕЗОЛВИТСЯ. Она пережила переезд службы и читается как "+
				"действующая: пошедший по ней получает отказ, а само дерево при этом собирается "+
				"и молчит (#61)")
			continue
		}
		if c.Marker != "" {
			if _, err := os.Stat(filepath.Join(root, c.Rel, c.Marker)); err != nil {
				findings = append(findings, c.Where+": координата `"+c.Rel+"` ("+c.What+
					") резолвится, но признака `"+c.Marker+"` в ней нет — значит указано НЕ ТО "+
					"дерево. Существование каталога свойства не доказывает: путь мимо цели почти "+
					"всегда ведёт в какой-нибудь существующий каталог (#61)")
				continue
			}
		}
		census.resolved++
	}

	return census, coords, findings
}

func TestGeneratorCoordinatesResolveInThisTree(t *testing.T) {
	t.Parallel()

	census, coords, findings := scanGeneratorCoordinates(serviceRoot)

	var named []string
	for _, c := range coords {
		named = append(named, c.Rel)
	}
	t.Logf("перепись: источников координат прочитано %d · координат названо %d · "+
		"из них резолвится %d · находок %d [%s]",
		census.sourcesRead, census.coordinates, census.resolved, len(findings),
		strings.Join(named, " · "))

	// Пустой обход — поломка гейта, а не чистота дерева.
	if census.coordinates == 0 {
		t.Fatal("координат не названо ни одной — обход беспредметен, и зелёное здесь означало бы " +
			"«ноль прочитанного», а не «ноль находок»")
	}

	for _, f := range findings {
		t.Error(f)
	}

	// Отдельно от находок: источников ДВА, и оба обязаны быть прочитаны.
	// Координаты, уехавшие в продукт, задача не застала именно потому, что
	// смотрела на один источник.
	if len(findings) == 0 && census.sourcesRead != 2 {
		t.Fatalf("находок ноль, а источников прочитано %d из 2 — о нечитанном не сказано ничего",
			census.sourcesRead)
	}
}
