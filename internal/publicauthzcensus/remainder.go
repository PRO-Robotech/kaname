package publicauthzcensus

// remainder.go — ведомость публичных RPC, у которых собственной двери ЕЩЁ НЕТ.
//
// # Это остаток работы, а не список прощённых
//
// Каждая запись — открытая дверь в вынесенном iam, а не согласованное
// послабление. Ведомость существует ровно затем, чтобы остаток был назван
// ЧИСЛОМ и чтобы НОВАЯ дыра не завелась молча: гейт требует, чтобы множества
// совпали ТОЧНО, в обе стороны.
//
// # Записана ПО ФАКТУ, а не потолком
//
// Потолок не краснеет никогда и потому не истекает. Запись, которой больше
// нечего прощать, — находка гейта: она означает, что дверь появилась, а
// ведомость об этом не знает, и следующая настоящая дыра уехала бы под неё.
//
// # Снимается записью, а не правкой числа
//
// Закрывая RPC дверью, снимай его строку тем же изменением. Гейт этого не
// напомнит — он покраснеет.

// DeclaredRemainder возвращает публичные RPC, о которых известно, что двери у
// них нет. Ключ — «Служба/Метод», как печатает RPC.String.
func DeclaredRemainder() map[string]bool {
	out := make(map[string]bool, len(declaredRemainder))
	for _, rpc := range declaredRemainder {
		out[rpc] = true
	}
	return out
}

// declaredRemainder — сам перечень.
//
// ПУСТ, и это ЗАМЕР, а не заготовка. Первая редакция гейта завела его пустым
// намеренно — чтобы прогон назвал остаток целиком, а не принял молча, — и
// назвал: 51 публичный RPC из 78 не задавал пообъектного вопроса ВООБЩЕ.
// Остаток закрыт не записями здесь, а собственной дверью iam
// (`authzguard.NewOwnDoor`), после чего перечень стал пустым по факту.
//
// Пустая ведомость — цель, а не поломка: гейт на ней проходит и печатает
// перепись. Появится строка — значит появился публичный RPC, чью дверь никто не
// повесил, и её придётся объяснить.
