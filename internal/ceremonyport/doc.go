// Package ceremonyport — адаптеры службы к портам церемонии OAuth 2.0
// фундамента (`corelib/oauthceremony`), чьи обязанности держит ТОЛЬКО сторона
// службы (задача PRO-Robotech/kaname#396).
//
// Фундамент объявляет порты и не приносит ни одной реализации: подписного
// материала у церемонии нет, хранилища — тоже. Здесь — три адаптера:
//
//   - AccessTokens — порт выпуска и опознания токена доступа
//     (`oauthceremony.AccessTokenIssuer`) над подписантом службы
//     (`tokensigner`) и её публикуемым набором ключей;
//   - Grants — порт отзыва гранта (`oauthceremony.GrantRevoker`) над писателем
//     отзыва семейства слоя доступа;
//   - NewGrantID — крючок чеканки идентификатора гранта
//     (`oauthceremony.Config.NewGrantID`): ключ семейства чеканит служба.
//
// # Пять обязанностей контракта и где каждая держится
//
//   - K1, отзыв семейства действует при ПРЕДЪЯВЛЕНИИ. Выпуск кладёт в токен
//     ключ семейства (`tokenrevocation.FamilyKeyClaim` — идентификатор
//     гранта); отзыв семейства слоем доступа пишет отсечку по этому ключу там,
//     где её читает правило отзыва (`tokenrevocation`), и правило отвергает
//     токен отозванного семейства при любой отметке выпуска. Пробы —
//     `revocation_reaches_presentation_test.go` (сквозь церемонию и место
//     предъявления) и `family_cutoff_integration_test.go` (слой доступа).
//   - K2, утверждения токена — только выданное: субъект сеанса, клиент, ключ
//     семейства, выданные области и получатели. Запрошенное, протокольные поля
//     запроса и утверждения сеанса в токен не идут; момент выпуска — не раньше
//     секунды вызова, срок — не позже границы церемонии.
//   - K3, опознание судит ТОЛЬКО подлинность: подлинный токен этого издателя —
//     его jti, в том числе истёкший; всё прочее — ErrGrantNotFound; сбой
//     опознания — отказ операции, а не «не наш».
//   - K4, предъявленное значение не уходит ни в журнал, ни в текст отказа:
//     адаптер журнала не ведёт вовсе, а его отказы о токене — один опознаватель
//     без подробностей.
//   - K5, где работает подписант. Подписант — ТОТ ЖЕ, что чеканит все токены
//     службы (`tokensigner.Signer` над ключницей), и адаптер принимает его
//     ЗНАЧЕНИЕМ процесса, а не адресом: церемония, собранная на этом адаптере,
//     и подписант исполняются в одном процессе, и часы выпуска — часы
//     церемонии. Отставания часов подписанта, отказывающего обмену, при такой
//     сборке нет по построению. Подписант вне процесса — другое развёртывание:
//     оно заводится вместе со счётчиком отказов по часам подписанта (описание
//     развёртывания, `docs/engineering/components/31-deployment.md`).
//
// # Чего здесь нет
//
// Хранилищ кода, токенов и клиентов (`ClientDirectory`, `*Vault`) здесь нет:
// это адаптеры над записью церемонии слоя доступа, и у них свои предметы.
package ceremonyport
