// Package ceremonyport — адаптеры службы к портам церемонии OAuth 2.0
// фундамента (`corelib/oauthceremony`), чьи обязанности держит ТОЛЬКО сторона
// службы (задачи PRO-Robotech/kaname#396 и #410).
//
// Фундамент объявляет порты и не приносит ни одной реализации: подписного
// материала у церемонии нет, хранилища и проверочного значения секрета —
// тоже. Здесь — четыре адаптера:
//
//   - AccessTokens — порт выпуска и опознания токена доступа
//     (`oauthceremony.AccessTokenIssuer`) над подписантом службы
//     (`tokensigner`) и её публикуемым набором ключей;
//   - Grants — порт отзыва гранта (`oauthceremony.GrantRevoker`) над писателем
//     отзыва семейства слоя доступа;
//   - NewGrantID — крючок чеканки идентификатора гранта
//     (`oauthceremony.Config.NewGrantID`): ключ семейства чеканит служба;
//   - ClientSecrets — порт сверки секрета клиента
//     (`oauthceremony.ClientSecretVerifier`) над справочником проверочных
//     значений (`interactive_clients.secret_verifier`) и проверяющим паролей
//     (`passwordverify`): значение чеканит тот же хешер, что пишет пароли.
//
// # Пять обязанностей контракта и где каждая держится
//
//   - K1, отзыв семейства действует при ПРЕДЪЯВЛЕНИИ. Выпуск кладёт в токен
//     ключ семейства (`tokenrevocation.FamilyKeyClaim` — идентификатор
//     гранта); отзыв семейства слоем доступа пишет отсечку по этому ключу там,
//     где её читает правило отзыва (`tokenrevocation`), и правило отвергает
//     токен отозванного семейства при любой отметке выпуска. Пробы —
//     `revocation_reaches_presentation_test.go` (сквозь церемонию и место
//     предъявления) и `family_cutoff_integration_test.go` (слой доступа).
//     Исполнены отзывы повтором кода и повтором токена обновления; отзыв
//     клиентом (`client-revoke`) ждёт слова в словаре семейств службы
//     (задача PRO-Robotech/kaname#406) и до него отказывает операцией, не
//     тронув семейства.
//   - K2, утверждения токена — только выданное: субъект сеанса, клиент, ключ
//     семейства, выданные области и получатели, а также контекст входа —
//     уровень (`acr`) и момент (`auth_time`) аутентификации из ПОЛЕЙ записи
//     сеанса, а не из её карты утверждений. Запрошенное, протокольные поля
//     запроса, утверждения сеанса и сессия входа в токен не идут; момент
//     выпуска — не раньше секунды вызова, срок — не позже границы церемонии.
//   - K3, опознание судит ТОЛЬКО подлинность: подлинный токен этого издателя —
//     его jti, в том числе истёкший; всё прочее — ErrGrantNotFound; сбой
//     опознания — отказ операции, а не «не наш». Ключ проверки выбирает то же
//     правило набора, что у читателя предъявленного и интроспекции
//     (`publishedkey`).
//   - K4, предъявленное значение не уходит ни в журнал, ни в текст отказа:
//     адаптер журнала не ведёт вовсе, а его отказы о токене — один опознаватель
//     без подробностей.
//   - K5, где работает подписант. Адаптер принимает подписанта ЗНАЧЕНИЕМ
//     процесса, а не адресом. Церемония в композиционном корне ещё не собрана
//     (задача PRO-Robotech/kaname#407); собранная над ТЕМ ЖЕ подписантом, что
//     чеканит все токены службы (`*tokensigner.Signer` над ключницей), она
//     исполняется в одном процессе с ним, и часы выпуска — часы церемонии:
//     отставания часов подписанта, отказывающего обмену, при такой сборке нет
//     по построению. Что сборка передаёт именно подписанта службы, судит проба
//     монтажа той задачи: интерфейс Signer допускает и внепроцессную
//     реализацию. Подписант вне процесса — другое развёртывание: оно заводится
//     вместе со счётчиком отказов по часам подписанта (описание развёртывания,
//     `docs/engineering/components/31-deployment.md`).
//
// # Секрет клиента: три исхода и одна цена
//
// Совпал · не совпал · сверка не состоялась. Клиент, которого нет, клиент без
// секрета и неназванный клиент — «не совпал», и стоит это вычисления против
// выравнивающего значения проверяющего: отказ неизвестному клиенту не дешевле
// отказа неверному секрету, поэтому невыровненный проверяющий отвергается
// сборкой. Отказ справочника и нечитаемое хранимое значение — отказ операции,
// а не вердикт. Пробы — `client_secrets_test.go` и сквозь церемонию
// `revocation_reaches_presentation_test.go`.
//
// # Чего здесь нет
//
// Хранилищ кода, токенов и клиентов (`ClientDirectory`, `*Vault`) здесь нет:
// это адаптеры над записью церемонии слоя доступа, и у них свои предметы.
