// Package ceremonyport — адаптеры службы к портам церемонии OAuth 2.0
// фундамента (`corelib/oauthceremony`), чьи обязанности держит ТОЛЬКО сторона
// службы (задача PRO-Robotech/kaname#396).
//
// Фундамент объявляет порты и не приносит ни одной реализации: подписного
// материала у церемонии нет, хранилища — тоже. Здесь — три адаптера:
//
//   - AccessTokens — порт выпуска и опознания токена доступа
//     (`oauthceremony.AccessTokenIssuer`) над подписантом службы
//     (`tokensigner`) и её публикуемым набором ключей;
//   - Grants — порт отзыва гранта (`oauthceremony.GrantRevoker`) над писателем
//     отзыва семейства слоя доступа;
//   - NewGrantID — крючок чеканки идентификатора гранта
//     (`oauthceremony.Config.NewGrantID`): ключ семейства чеканит служба.
//
// # Пять обязанностей контракта и где каждая держится
//
//   - K1, отзыв семейства действует при ПРЕДЪЯВЛЕНИИ. Выпуск записывает себя
//     в семейство гранта — запись jti → семейство (`IssuanceRecorder`,
//     kaname#319, решение К10 вариант А) — после подписи и до того, как токен
//     уедет, и отказ записи роняет выпуск. Отметка отзыва семейства доезжает
//     до каждой его записи, и по записи о семействе отвечают `IsRevoked`
//     службы отзыва и правило отзыва (`tokenrevocation`) — при любой отметке
//     выпуска; выпуск в уже отозванное семейство не записывается и потому не
//     состоится. Пробы — `revocation_reaches_presentation_test.go` (сквозь
//     церемонию и место предъявления), `issuance_record_test.go` (запись и её
//     отказ) и `family_revocation_through_three_surfaces_integration_test.go`
//     (слой доступа и три поверхности). Исполнены отзывы повтором кода и
//     повтором токена обновления; отзыв клиентом (`client-revoke`) ждёт слова
//     в словаре семейств службы (задача PRO-Robotech/kaname#406) и до него
//     отказывает операцией, не тронув семейства.
//   - K2, утверждения токена — только выданное: субъект сеанса, клиент,
//     выданные области и получатели. Запрошенное, протокольные поля запроса и
//     утверждения сеанса в токен не идут; семейство — тоже: оно в записи
//     выпуска, а не в составе. Момент выпуска — не раньше секунды вызова, срок
//     — не позже границы церемонии.
//   - K3, опознание судит ТОЛЬКО подлинность: подлинный токен этого издателя —
//     его jti, в том числе истёкший; всё прочее — ErrGrantNotFound; сбой
//     опознания — отказ операции, а не «не наш». Ключ проверки выбирает то же
//     правило набора, что у читателя предъявленного и интроспекции
//     (`publishedkey`).
//   - K4, предъявленное значение не уходит ни в журнал, ни в текст отказа:
//     адаптер журнала не ведёт вовсе, а его отказы о токене — один опознаватель
//     без подробностей.
//   - K5, где работает подписант. Адаптер принимает подписанта ЗНАЧЕНИЕМ
//     процесса, а не адресом. Церемония в композиционном корне ещё не собрана
//     (задача PRO-Robotech/kaname#407); собранная над ТЕМ ЖЕ подписантом, что
//     чеканит все токены службы (`*tokensigner.Signer` над ключницей), она
//     исполняется в одном процессе с ним, и часы выпуска — часы церемонии:
//     отставания часов подписанта, отказывающего обмену, при такой сборке нет
//     по построению. Что сборка передаёт именно подписанта службы, судит проба
//     монтажа той задачи: интерфейс Signer допускает и внепроцессную
//     реализацию. Подписант вне процесса — другое развёртывание: оно заводится
//     вместе со счётчиком отказов по часам подписанта (описание развёртывания,
//     `docs/engineering/components/31-deployment.md`).
//
// # Чего здесь нет
//
// Хранилищ кода, токенов и клиентов (`ClientDirectory`, `*Vault`) здесь нет:
// это адаптеры над записью церемонии слоя доступа, и у них свои предметы.
package ceremonyport
