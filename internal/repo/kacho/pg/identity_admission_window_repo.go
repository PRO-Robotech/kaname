// IdentityAdmissionWindowRepo — окна темпа заведения аккаунтов
// (`kacho_iam.identity_admission_windows`, миграция `20260822231600`).
//
// # Предмет: счётчик живёт окно, а строка — вечно
//
// Строка есть пара «носитель, вид» плюс начало ДЕЙСТВУЮЩЕГО окна и число
// принятых в нём заведений. Окно двигается ВНУТРИ строки: переход в следующее
// окно и списание считаются одним оператором. Поэтому строк ровно столько,
// сколько разных внешних личностей побывало на установке за всю её жизнь, — а
// счётчик, ради которого строка заведена, каждое окно начинается заново.
//
// Темп роста задаёт внешний: кто зашёл, тот и завёл строку. Задача #1364.
//
// # Писателя у этой таблицы в коде НЕТ, и это не упущение
//
// Единственный писатель — триггер применённой миграции
// (`kacho_iam.kacho_admission_rate_count`), срабатывающий отложенно на вставке
// аккаунта. Он же единственный читатель. Репозиторий здесь появляется ровно
// ради уборки: класть рядом с ним запись или чтение значило бы завести второе
// место, принимающее решение о темпе, — а решение обязано остаться одним
// оператором в триггере (ban #10).
type IdentityAdmissionWindowRepo struct {
	pool *pgxpool.Pool
}

// NewIdentityAdmissionWindowRepo — построитель.
func NewIdentityAdmissionWindowRepo(pool *pgxpool.Pool) *IdentityAdmissionWindowRepo {
	return &IdentityAdmissionWindowRepo{pool: pool}
}

// SweepElapsedAdmissionWindows снимает строки, чьё окно истекло.
//
// # Порог — предикат ЧИТАТЕЛЯ, и здесь он читается ИЗ АВТОРИТЕТА, а не копией
//
// Читатель один — триггер. Он сравнивает `now()` с `window_started_at +
// window_seconds`, где `window_seconds` берётся из ДЕЙСТВУЮЩЕЙ строки величин
// (`kacho_iam.account_admission_rate_limits`, `withdrawn_at IS NULL`). Уборщик
// берёт её ОТТУДА ЖЕ и тем же оператором: длительность окна — величина, которую
// владелец облака меняет строкой без выката, и копия в Go разошлась бы с ней
// молча.
//
// # Почему снятие истёкшей строки НИЧЕГО не меняет для читателя
//
// Утверждение проверяемо по тексту триггера, а не по впечатлению. У него две
// ветви одного оператора:
//
//   - строки НЕТ — ветвь вставки, безусловная: `admitted = 1`,
//     `window_started_at = now()`;
//   - строка ЕСТЬ и окно истекло — ветвь правки: те же `admitted = 1` и
//     `window_started_at = now()`, но под условием `1 <= max_events`.
//
// Состояние после обеих ветвей совпадает дословно, а исход расходится ровно
// тогда, когда `max_events < 1`. Ноль — величина ЗАКОННАЯ («за окно ни одного,
// кроме первого»), поэтому уборщик снимает строку ТОЛЬКО у вида, чья
// действующая величина допускает хотя бы одно заведение в окне. Без этого
// условия снятие строки дарило бы носителю одно безусловное заведение там, где
// администратор запретил все.
//
// Вид БЕЗ действующей величины строку тоже сохраняет: у такого вида триггер
// отказывает до всякого обращения к таблице, то есть исход от строки не зависит
// вовсе, — но сохранение здесь дешевле и не требует рассуждения о том, что
// случится, когда величину заведут.
//
// # Часы — БАЗЫ у обеих сторон, поэтому слагаемого запаса нет
//
// Читатель судит `now()` базы, уборщик судит `now()` той же базы, длительность
// окна оба берут из одной строки. Разнице источников взяться неоткуда, и запас
// объявлен нулём ЯВНО — реестр `apps/kacho/retention` держит это пробой, чтобы
// «слагаемое забыли» было отличимо от «слагаемого не бывает».
//
// Вход `grace` в сигнатуре остаётся: форма уборщика одна на все предметы
// (`retention.SweepFunc`), и предмет, которому запас не нужен, объявляет ноль, а
// не заводит вторую форму.
//
// # Что меняется в СМЫСЛЕ отсутствия строки — названо, а не спрятано
//
// Затравка миграции ставила строку каждой существующей личности именно затем,
// чтобы «ряда нет» означало «аккаунтов не заводила». После уборки отсутствие
// означает слабее: «в последнем окне не заводила». Ни один сегодняшний читатель
// на этом различии не стоит — оно проверено выше по обеим ветвям оператора, — но
// следующий, кому понадобится «заводила ли когда-нибудь», обязан читать
// `admitted`/`window_started_at`, а не отсутствие строки, либо пересмотреть эту
// уборку.
//
// Возвращает число снятых строк и признак «партия ушла полной»: без второго
// проход не отличает «убрал всё» от «упёрся в партию» и не догоняет внешний темп
// никогда, оставаясь зелёным по всякой проверке «вызвался ли».
func (r *IdentityAdmissionWindowRepo) SweepElapsedAdmissionWindows(ctx context.Context, grace time.Duration, batch int) (int64, bool, error) {
	const q = `
DELETE FROM kacho_iam.identity_admission_windows
 WHERE ctid IN (
     SELECT w.ctid
       FROM kacho_iam.identity_admission_windows w
       JOIN kacho_iam.account_admission_rate_limits l
         ON l.kind = w.kind
        AND l.withdrawn_at IS NULL
      WHERE l.max_events >= 1
        AND w.window_started_at
              < now() - make_interval(secs => l.window_seconds) - make_interval(secs => $1)
      ORDER BY w.window_started_at
      LIMIT $2
      FOR UPDATE OF w SKIP LOCKED
 )`
	tag, err := r.pool.Exec(ctx, q, grace.Seconds(), batch)
	if err != nil {
		return 0, false, wrapPgErr(err, "IdentityAdmissionWindow", "")
	}
	n := tag.RowsAffected()
	return n, n == int64(batch), nil
}

// LenAdmissionWindows — число строк учёта темпа.
//
// Читается пробой уборщика: она утверждает ЧИСЛО СТРОК, а не то, что уборщик
// вызвался. «Вызвался» зелено и на уборщике, не снявшем ничего, и на уборщике,
// опустошившем таблицу целиком, — то есть на реализации, дарящей носителю
// заведение сверх потолка.
func (r *IdentityAdmissionWindowRepo) LenAdmissionWindows(ctx context.Context) (int64, error) {
	const q = `SELECT count(*) FROM kacho_iam.identity_admission_windows`
	var n int64
	if err := r.pool.QueryRow(ctx, q).Scan(&n); err != nil {
		return 0, wrapPgErr(err, "IdentityAdmissionWindow", "")
	}
	return n, nil
}
