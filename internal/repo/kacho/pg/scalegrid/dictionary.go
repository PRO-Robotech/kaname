package scalegrid

import "github.com/PRO-Robotech/kacho-iam/internal/authzmap"

// ЦЕПЬ ПИШЕТСЯ В СЛОВАРЕ МОДЕЛИ — А СТРОКА ЗЕРКАЛА В СЛОВАРЕ КАТАЛОГА
//
// Один и тот же объект назван в двух таблицах ПО-РАЗНОМУ: `resource_mirror`
// говорит словарём каталога ресурсов (`registry.repositories`), а
// `resource_parent_edge` — словарём модели прав (`registry_repository`), потому
// что цепь читается вопросом о доступе, и им же названы три из четырёх колонок,
// с которыми она соединяется. Соединение по разным написаниям не совпадает
// НИКОГДА и молча: исход выглядел бы как «права нет», а не как ошибка.
//
// # ЭТО БЫЛА ПЕРВАЯ РЕДАКЦИЯ ФАЙЛА, И ОНА ВОЗВРАЩАЛА АРГУМЕНТ КАК ЕСТЬ
//
// Записано не для покаяния, а как ДОКАЗАТЕЛЬСТВО, что сверка посевщика с
// производителем способна упасть. Наивная редакция — самая правдоподобная из
// возможных: ничто в форме вызова не напоминает, что словаря два. Прогон на ней
// дал отказ на четвёртом стейтменте первой же пачки — нарушение проверки схемы
// `resource_parent_edge_object_type_model_dictionary` (`0091`), — тогда как путь
// производителя ту же фикстуру посадил без замечаний.
//
// # ЧЕГО ТА ИНЪЕКЦИЯ НЕ ДОКАЗАЛА, И ПОЧЕМУ СВЕРКА ВСЁ РАВНО НУЖНА
//
// Отказ пришёл ОТ СХЕМЫ, а не от сверки: проверка ловит точку в имени, и
// катологическая форма её содержит. Тип, у которого обе формы совпадают
// (`cluster` — его в каталоге нет вовсе), прошёл бы проверку молча. То есть
// схема закрывает подкласс, а не класс; остаток закрывает построчная сверка, и
// её вторая инъекция — подмена ИМЕНИ ПРЕДКА в цепи — падает уже на ней.

// # ПЕРЕВОД ЗДЕСЬ — НЕ ТОТ ЖЕ, ЧТО У ПРОИЗВОДИТЕЛЯ, И ЭТО РЕШЕНИЕ (#1995)
//
// Здесь стояло обратное: «перевод берётся ТОТ ЖЕ, каким его делает производитель
// (`authzmap.ModelTypeName`), а не своей таблицей». Довод был верен, а
// утверждение ПЕРЕЖИЛО СВОЙ ПРЕДМЕТ: производитель (`resource_mirror`) переведён
// на ЖИВЫЕ строки каталога (#1982) и `authzmap.ModelTypeName` не зовёт больше ни
// разу. Предикат — одной строкой, чтобы его можно было повторить, а не поверить
// шестнадцати знакам хэша:
//
//	git grep -n ModelTypeName -- '*/pg/resource_mirror/*'
//
// Он даёт только прошедшее время в разборе и шапку соседней пробы. Второй
// словарь, о котором предупреждал прежний комментарий, — теперь как раз этот.
//
// Прибор ОСТАЁТСЯ на словаре сборки осознанно. Производитель спрашивает имя у
// строки каталога В ТОЙ ЖЕ транзакции, что и пишет; прибор кладёт стейтменты в
// `pgx.Batch` и знать имя обязан ДО отправки пачки, на каждом из миллиона
// объектов. Повторить путь производителя значит либо обращение к базе на объект
// — тогда сетка мерит стоимость чтения каталога, а не путь вердикта, ради
// которого заведена, — либо второй снимок каталога рядом с первым.
//
// # КАКУЮ ПОПУЛЯЦИЮ ЭТО ОГРАНИЧИВАЕТ — ЗАМЕРОМ, А НЕ СЛОВОМ «НЕМНОГО»
//
// Замер на `034faebf4c` (гейт ниже держит его впредь, поэтому число здесь —
// ориентир, а не единственный носитель):
//
//	строк `kacho_iam.catalog_resource`, посеянных миграциями   30
//	из них ЖИВЫХ                                               27
//	живых, на которых сборка и строка каталога СОВПАДАЮТ       27
//	разошедшихся                                                3 — и ВСЕ ТРИ сняты
//
// То есть на популяции, которую прибор ВООБЩЕ способен посеять, расхождения нет
// ни одного: вставка зеркала обусловлена живой строкой каталога (`seed.go`, CTE
// `live_type`), поэтому до снятых типов посевщик не доходит by construction.
//
// # ГРАНИЦА НЕ ОБЪЯВЛЕНА, А ЭНФОРСИТСЯ — ПОЭТОМУ ЧИСЛА НЕ БЫВАЮТ ТИХО НЕВЕРНЫМИ
//
// Тип, заведённый ПРИМЕНЕНИЕМ МАНИФЕСТА в работающем процессе, в таблице сборки
// отсутствует, и `ModelTypeName` возвращает его КАК ЕСТЬ — то есть с точкой
// (`FGAObjectType` не знает имени → `return typeName`). Обе колонки ребра несут
// `CHECK (… !~~ '%.%')` — `resource_parent_edge_object_type_model_dictionary` и
// `…_parent_type_model_dictionary` (`0001_initial.sql`). Значит посев такого типа
// ОТКАЗЫВАЕТ, а не тихо меряет другую популяцию: прибор останавливается с
// ошибкой схемы, называющей ограничение.
//
// Отсюда и форма остатка. Расхождение словарей на ЖИВОЙ строке было бы тихим,
// поэтому его держит гейт против живой базы; расхождение на типе ВРЕМЕНИ
// ВЫПОЛНЕНИЯ тихим быть не может — его держит схема. Обе половины прогоняются
// одной командой, и обе живут в `services/iam/internal/migrations/`:
//
//	go test -C services/iam ./internal/migrations/ \
//	  -run 'BuildTypeDictionaryAgrees|UnknownDottedTypeIsRefused' -count=1 -v

// edgeObjectType — тип объекта в той форме, в какой его пишет в рёбра
// производитель.
//
// Перевод — словарём СБОРКИ (`authzmap.ModelTypeName`), а не живой строкой
// каталога, которой пользуется производитель. Почему так и что этим ограничено —
// врезка выше.
func edgeObjectType(catalogType string) string { return authzmap.ModelTypeName(catalogType) }

// edgeParentType — тип предка в том же словаре.
//
// Перевод идемпотентен: родительская сторона приезжает от владельца ресурса уже
// модельными именами, и второй перевод её не портит — пересечения у словарей
// нет by construction (имя каталога всегда несёт точку, имя модели — никогда).
func edgeParentType(parentType string) string { return authzmap.ModelTypeName(parentType) }
