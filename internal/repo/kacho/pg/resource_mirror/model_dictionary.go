// model_dictionary.go — ИМЯ ТИПА МОДЕЛИ СПРАШИВАЕТСЯ У ЖИВОЙ СТРОКИ КАТАЛОГА,
// а не у словаря, порождённого сборкой (kacho#1982).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗДЕСЬ СТОЯЛО И ПОЧЕМУ ЭТОГО МАЛО
//
// Перевод брался у `authzmap.ModelTypeName` — оболочки над таблицей
// `authzmap/tables_gen.go`, ПОРОЖДЁННОЙ СБОРКОЙ из манифестов дерева. Оболочка
// ТОТАЛЬНА: незнакомое имя она возвращает как есть. Для типа, заведённого
// применением манифеста в РАБОТАЮЩЕМ процессе, «как есть» — точечное имя
// каталога (`billing.invoice`), а колонка требует имени модели.
//
// Тот же класс, что у материализатора (#1967) и проекции (#1816) — «имя типа
// спрашивается у словаря, порождённого сборкой», — но с ДРУГИМ исходом: там
// промах давал тихий ноль, здесь он даёт отказ проверки схемы
// `resource_parent_edge_object_type_model_dictionary`, то есть откат ВСЕЙ
// транзакции регистрации. Громкий отказ лучше тихого промаха и означает ровно то
// же: объекта в зеркале нет, а без строки зеркала правило не отберёт его ни при
// каком материализаторе.
//
// ─────────────────────────────────────────────────────────────────────────────
// СУЖЕНИЕ ИДЁТ ПО СВОЙСТВУ, А НЕ ПО ИМЕНИ
//
// Запретить сборочный переходник ПО ИМЕНИ нельзя: он тотален, поэтому любая его
// замена — те же две строки у следующего писателя, и запрет обходится молча.
// Различает словари СВОЙСТВО, и оно объявлено самими словарями
// (`authzmap/type_dictionaries.go`): имя каталога содержит точку ВСЕГДА, имя
// модели — НИКОГДА.
//
//	точки НЕТ  → это уже имя модели → тождество. Сюда попадают `cluster`,
//	             `project`, `account`, `registry_registry` — родительская сторона
//	             приезжает от владельца ресурса уже модельными именами, и
//	             каталог о `cluster` не знает вовсе: кластер не ресурс.
//	точка ЕСТЬ → это имя каталога → ОБЯЗАНО резолвиться живой строкой каталога.
//	             Не резолвится — ОТКАЗ, называющий тип и правило, а НЕ проход
//	             значения дальше.
//
// Проход дальше и есть снятый дефект: он отдавал точку в колонку словаря модели,
// и вердикт выносила проверка схемы — правильным исходом, но текстом про
// ограничение таблицы, из которого не видно ни типа, ни того, что чинить.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРОВЕРКА СХЕМЫ ОСТАЁТСЯ, И ЭТО НЕ ДУБЛЬ
//
// `*_type NOT LIKE '%.%'` у обеих колонок ребра — по-прежнему то, ЧЕМ инвариант
// держится: писатель здесь один, а колонок, названных словарём модели, четыре, и
// следующий писатель этого файла не читает. Здесь — производство верного
// значения и понятный отказ; там — невозможность записать неверное.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЛИВНОСТЬ ЗДЕСЬ НЕ СПРАШИВАЕТСЯ — И ЭТО РЕШЕНИЕ
//
// Строка ищется по `dotted` БЕЗ отбора `live`. Перевод — не условие приёма:
// условие приёма стоит отдельным оператором в `UpsertTx` и спрашивает именно
// живую строку. Спроси ливность и здесь — ресурс, чей тип сняли с платформы
// после его регистрации, стал бы НЕудаляемым: `DeleteTx` не смог бы назвать его
// цепь, а строка зеркала продолжала бы участвовать в подборе по признакам. Отказ
// на снятии дороже отказа на приёме: невыполнимое снятие означает право, которое
// не отзывается.
//
// Снятие типа с платформы — мягкое (`live = false`, строка остаётся), поэтому
// промах перевода означает тип, которого у платформы не было НИКОГДА.

// modelTypeName — имя типа в словаре МОДЕЛИ ПРАВ по ЖИВЫМ строкам каталога.
//
// Читает в ТОЙ ЖЕ транзакции, что и писатель: перевод и запись оказываются в
// одном снимке, и окна между «спросил» и «вставил» нет by construction.
//
// Недотированное имя запроса не стоит: оно уже названо словарём модели, и
// обращение к базе на каждом предке цепи было бы платой ни за что —
// родительская сторона приезжает модельными именами всегда.
func modelTypeName(ctx context.Context, tx pgx.Tx, name string) (string, error) {
	if !strings.Contains(name, ".") {
		// Уже словарь модели. Тождество — не запасной путь: пересечения у
		// словарей нет by construction, поэтому другого прочтения у имени без
		// точки не существует.
		return name, nil
	}
	var modelType string
	err := tx.QueryRow(ctx,
		`SELECT object_type FROM kacho_iam.catalog_resource WHERE dotted = $1`,
		name).Scan(&modelType)
	switch {
	case errors.Is(err, pgx.ErrNoRows):
		// Отказ НАЗЫВАЕТ тип и правило. Прежде вердикт по этому же входу выносила
		// проверка схемы — верным исходом, но текстом про ограничение таблицы, из
		// которого не видно ни типа, ни того, что чинить.
		return "", iamerr.Wrapf(iamerr.ErrUnknownResourceType,
			"resource type %q has no entry in the platform resource catalog, so its "+
				"rights-model type name cannot be resolved", name)
	case err != nil:
		return "", fmt.Errorf("resource_parent_edge: имя типа модели для %q: %w", name, err)
	}
	return modelType, nil
}
