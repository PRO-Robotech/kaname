// iamdirectcontainment.go — ЧТЕНИЕ containment'а материализации наружу.
//
// # Зачем он вообще выставлен
//
// `iamDirectScanSpecs` — это ответ материализации на вопрос «какая колонка какой
// строки говорит, что объект лежит ВНУТРИ области». По этой колонке выдача,
// сделанная на область, фактически накрывает объект, и потому она же служит
// эталоном для двух посторонних читателей:
//
//   - гейта, сверяющего с ней ветви представления `resource_scope_edge`
//     (#785): цепь и материализация обязаны считать «внутри» одинаково, иначе
//     форма E и реконсайлер разойдутся молча;
//   - переписи источников звена (`deploy/load-tests/iam-scope-source-census.sh`):
//     ей нужен предикат «у этого объекта источник предка законно пуст», а
//     сочинять его второй раз значило бы завести третье место об одном предмете.
//
// Выставлено ЧТЕНИЕ, а не карта: возвращается копия, и записать в план чтения
// снаружи нельзя. Это тот же приём, которым `labelaxis.go` отдаёт свой реестр
// осей — перечень типов, у которых проба обязана быть, не выписывается второй
// раз, а берётся у владельца.
//
// # Чего этот читатель НЕ утверждает
//
// Он НЕ является эталоном на все свойства звена, и это измерено, а не
// предположено. Containment'ов в дереве три — материализация, запасной
// структурный путь (`domain.StructuralParent` / `AccountScopedStructuralFact`) и
// сама модель прав, — и попарно они не совпадают в двух местах:
//
//	привязка с областью «кластер» — здесь предка НЕТ (оба выражения дают пусто,
//	    см. комментарий у `iam.accessBinding`), у запасного пути он ЕСТЬ, и
//	    модель на стороне запасного пути;
//	роль с областью «проект» — здесь предок ЕСТЬ (аккаунт добирается соединением
//	    с проектами), у запасного пути НЕТ ничего, а модель молчит: отношения
//	    `project` у типа `iam_role` не объявлено вовсе.
//
// Читатель, объявивший эту карту эталоном НА ВСЁ, покраснеет на верной
// реализации по двум типам из семи — и худший исход не в красноте, а в том, что
// его будут «приводить в согласие», правя материализацию, то есть поведение
// авторизации.
package pg

import "sort"

// IAMDirectContainment — одна запись плана чтения материализации, отданная
// наружу.
type IAMDirectContainment struct {
	// ObjectType — тип в словаре КАТАЛОГА (`iam.group`), не модели
	// (`iam_group`). Перевод делает `authzmap.ModelTypeName`; двух словарей в
	// одном соединении быть не должно — соединение по разным написаниям не
	// совпадает никогда и молча.
	ObjectType string
	// Table — таблица состояния, несущая строку объекта.
	Table string
	// ParentAccountExpr / ParentProjectExpr — выражения над псевдонимом `o`
	// (и `p`, если задан Join), дающие аккаунт и проект объекта. Пустой набор
	// аккаунтов вместе с пустым проектом означает, что материализация считает
	// объект не лежащим ни в одной области.
	//
	// ParentAccountExpr СКАЛЯРНО и пусто там, где принадлежность аккаунту не
	// является свойством собственной строки объекта: у ЛИЧНОСТИ она выражена
	// связью `kacho_iam.memberships`, и аккаунтов бывает несколько (#1172).
	// Читателю, спрашивающему «в каких аккаунтах объект», нужен
	// ParentAccountsExpr; ParentAccountExpr отвечает на более узкий вопрос —
	// «какая КОЛОНКА собственной строки на это указывает», и его читает гейт
	// согласия источников цепи областей.
	ParentAccountExpr string
	// ParentAccountsExpr — каноническая форма источника аккаунтов: выражение
	// типа text[], непустое ВСЕГДА. Ровно её читают проекция реконсайлера,
	// сужение по области и полоса «якорь» обратного подбора, поэтому читателю
	// снаружи она и отдаётся: второе выражение того же предмета разошлось бы с
	// нею молча — на вырожденном наборе обе формы дают одно и то же.
	ParentAccountsExpr string
	ParentProjectExpr  string
	// Join — необязательное соединение, без которого выражения не вычислить.
	Join string
}

// IAMDirectContainments отдаёт план чтения материализации, отсортированный по
// типу.
//
// Порядок задан намеренно: читатели печатают перепись, а перепись, у которой
// порядок строк меняется от прогона к прогону, нечитаема и её перестают
// сверять.
func IAMDirectContainments() []IAMDirectContainment {
	out := make([]IAMDirectContainment, 0, len(iamDirectScanSpecs))
	for _, spec := range iamDirectScanSpecs {
		out = append(out, IAMDirectContainment{
			ObjectType:         spec.objectType,
			Table:              spec.table,
			ParentAccountExpr:  spec.parentAccountExpr,
			ParentAccountsExpr: spec.accountsExpr(),
			ParentProjectExpr:  spec.parentProjectExpr,
			Join:               spec.join,
		})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ObjectType < out[j].ObjectType })
	return out
}
