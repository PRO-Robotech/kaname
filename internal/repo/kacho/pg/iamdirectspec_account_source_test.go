package pg

// iamdirectspec_account_source_test.go — ИСТОЧНИК АККАУНТОВ ОБЪЯВЛЕН РОВНО ОДИН
// РАЗ на тип, и каноническая форма выражает ИМЕННО его.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ЭТА ПРОБА СУЩЕСТВУЕТ
//
// План чтения несёт ДВЕ формы объявления источника аккаунтов: скалярную колонку
// собственной строки (`parentAccountExpr`) и набор-выражение (`parentAccountsExpr`,
// #1172 — у личности аккаунтов столько, сколько членств). Две формы одного
// предмета расходятся молча: на вырожденном наборе — один аккаунт — они дают
// одно и то же, поэтому расхождение не проявилось бы ни в одной пробе поведения
// до появления второго членства, то есть ровно в том случае, ради которого
// плюральная форма и заводилась.
//
// Проба требует ТРЁХ вещей, и каждая ловит свой способ ошибиться:
//
//	1. непусто РОВНО ОДНО из двух — иначе тип объявил источник дважды (и тогда
//	   каноническая форма молча предпочла бы один, а гейт согласия источников
//	   сверял бы другой) либо не объявил вовсе;
//	2. каноническая форма непуста ВСЕГДА — её подставляют в SQL три читателя, и
//	   пустая строка дала бы синтаксический отказ на пути авторизации;
//	3. каноническая форма СОДЕРЖИТ объявленный источник дословно — иначе она
//	   отвечала бы на вопрос не о том, что тип объявил.
//
// Плюс перепись: печатается, сколько типов осмотрено и сколько из них берут
// аккаунты связью, а не колонкой. «Ноль находок» обязано быть отличимо от «ноль
// прочитанного».

import (
	"strings"
	"testing"
)

func TestIAMDirectSpec_AccountSourceIsDeclaredExactlyOnce(t *testing.T) {
	if len(iamDirectScanSpecs) == 0 {
		t.Fatal("план чтения материализации ПУСТ: проверять нечего, и молчание здесь " +
			"означало бы «ноль прочитанного», а не «источники объявлены верно»")
	}
	scalar, plural := 0, 0
	for ty, spec := range iamDirectScanSpecs {
		hasScalar := spec.parentAccountExpr != ""
		hasPlural := spec.parentAccountsExpr != ""
		switch {
		case hasScalar && hasPlural:
			t.Errorf("тип %q объявляет источник аккаунтов ДВАЖДЫ (колонкой %q и набором %q): "+
				"каноническая форма молча предпочтёт один из них, а гейт согласия источников "+
				"цепи областей сверит другой", ty, spec.parentAccountExpr, spec.parentAccountsExpr)
		case !hasScalar && !hasPlural:
			t.Errorf("тип %q не объявляет источника аккаунтов вовсе: материализация сочтёт "+
				"объект не лежащим ни в одном аккаунте, и выдача на область его НЕ НАКРОЕТ — "+
				"отказ, неотличимый от честного", ty)
		case hasScalar:
			scalar++
		default:
			plural++
		}

		got := spec.accountsExpr()
		if got == "" {
			t.Errorf("тип %q: каноническая форма источника аккаунтов ПУСТА — она "+
				"подставляется в SQL проекции, сужения по области и полосы «якорь», "+
				"и пустая строка даёт отказ разбора на пути авторизации", ty)
			continue
		}
		declared := spec.parentAccountExpr
		if hasPlural {
			declared = spec.parentAccountsExpr
		}
		if !strings.Contains(got, declared) {
			t.Errorf("тип %q: каноническая форма %q не содержит объявленного источника %q — "+
				"значит она отвечает на вопрос не о том, что тип объявил", ty, got, declared)
		}
	}
	t.Logf("осмотрено типов %d: аккаунты колонкой собственной строки — %d, связью — %d",
		len(iamDirectScanSpecs), scalar, plural)
	if plural == 0 {
		t.Error("НИ ОДИН тип не берёт аккаунты связью, а личность обязана (#1172): " +
			"либо плюральная форма снята, либо проба читает не тот план — в обоих " +
			"случаях её молчание не означает, что источник объявлен верно")
	}
}
