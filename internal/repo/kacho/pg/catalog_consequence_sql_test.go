//
// Задача продукта #1034. Пакет здесь внутренний (`pg`, не `pg_test`): предмет
// пробы — неэкспортируемые объявления SQL, и снаружи их не видно.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ПРОБА, ЕСЛИ ПРЕДИКАТ ОБЪЯВЛЕН ОДИН РАЗ
//
// У третьей популяции он и вправду один: `PruneRetiredSelectorTypes` и план
// вставляют `catalogSelectorPruneCTE` ССЫЛКОЙ, и разойтись им нечем.
//
// У первых двух ссылкой не выходит, и причина не в лени. Гейт дерева
// `internal/repohygiene` `TestIAMRV112_RoleVerbProjectionHasASoleWriter` требует,
// чтобы СТРОКОВЫЙ ЛИТЕРАЛ со снятием строки проекции роли содержал и переселение
// снятого в сироты: снятие и переселение неделимы ровно тогда, когда стоят в
// одном операторе. Предикат лежит в тексте МЕЖДУ ними, поэтому вставка ссылкой
// разрезает литерал ровно там, где гейт требует целости. Требования взаимно
// исключают друг друга by construction.
//
// Уступает форма, а не существо: у гейта предмет — необратимо отобранное право
// арендатора, у ссылки — способ записи. Значит вложение дословное, а
// единственность держит ЭТА проба: дрейф перестаёт быть молчаливым, потому что
// перестаёт садиться.
//
// ─────────────────────────────────────────────────────────────────────────────
// ОТРИЦАНИЕ СТОИТ В ПАРЕ С ПОЛОЖИТЕЛЬНЫМ
//
// «Оператор содержит предикат» на пустом предикате выполняется тривиально
// (`strings.Contains(x, "")` истинно всегда), а «операторов осмотрено N» без
// проверки самого N зеленеет на пустом перечне. Поэтому проба утверждает и то,
// и другое, и печатает перепись: «ноль находок» обязано быть отличимо от «ноль
// прочитанного».

import (
	"strings"
	"testing"
)

// TestPlanAndApplyReadOneSelectionPredicate — каждый оператор писателя содержит
// авторитетное объявление своего предиката ПОБАЙТОВО, а план читает то же
// объявление ссылкой.
func TestPlanAndApplyReadOneSelectionPredicate(t *testing.T) {
	type embedding struct {
		// name — оператор писателя, судимый пробой.
		name string
		// stmt — его текст.
		stmt string
		// predicate — авторитетное объявление, которое он обязан содержать.
		predicate string
		// predicateName — имя объявления, чтобы отказ называл, ЧТО править.
		predicateName string
	}

	embeddings := []embedding{
		{
			name:          "resettleRuleRefSQL",
			stmt:          resettleRuleRefSQL,
			predicate:     catalogStaleRuleRefPredicate,
			predicateName: "catalogStaleRuleRefPredicate",
		},
		{
			name:          "resettleRoleVerbSQL",
			stmt:          resettleRoleVerbSQL,
			predicate:     catalogStaleRoleVerbPredicate,
			predicateName: "catalogStaleRoleVerbPredicate",
		},
	}

	// Положительный контроль предпосылки: пустой предикат содержится в чём
	// угодно, поэтому проверка на пустом объявлении не значила бы ничего.
	for _, e := range embeddings {
		if strings.TrimSpace(e.predicate) == "" {
			t.Fatalf("объявление %s пусто — вложение выполнялось бы тривиально, "+
				"и проба утверждала бы о единственности, ничего не проверив", e.predicateName)
		}
		if strings.TrimSpace(e.stmt) == "" {
			t.Fatalf("оператор %s пуст — вкладывать не во что", e.name)
		}
	}
	if len(embeddings) == 0 {
		t.Fatal("осмотрено ноль операторов — проба не читала дерева, и её молчание " +
			"ничего не значит")
	}

	for _, e := range embeddings {
		if !strings.Contains(e.stmt, e.predicate) {
			t.Errorf("оператор %s НЕ содержит объявления %s побайтово.\n"+
				"План считает последствия по %s, применение снимает строки по тексту "+
				"внутри %s. Разойдясь, они разойдутся МОЛЧА: на манифесте, ничего не "+
				"снимающем, обе стороны отвечают «ноль», и заметить это станет нечем до "+
				"боевой базы — план обещает одно, применение делает другое, и оба «правы».\n"+
				"Вложение дословное намеренно (гейт `TestIAMRV112_RoleVerbProjectionHasASoleWriter` "+
				"требует снятия и переселения в ОДНОМ литерале) — правь оператор под "+
				"объявление, а не наоборот.",
				e.name, e.predicateName, e.predicateName, e.name)
		}
	}

	// Третья популяция вставляется ССЫЛКОЙ и потому расхождения не допускает
	// вовсе; утверждается ровно это — что вставка есть, а не что тексты совпали.
	if !strings.Contains(planConsequencesSQL, catalogSelectorPruneCTE) {
		t.Error("оценка плана не вставляет `catalogSelectorPruneCTE`: третья популяция " +
			"считается вторым объявлением")
	}
	if !strings.Contains(planConsequencesSQL, catalogStaleRuleRefPredicate) ||
		!strings.Contains(planConsequencesSQL, catalogStaleRoleVerbPredicate) {
		t.Error("оценка плана не вставляет авторитетных предикатов переселения: " +
			"первые две популяции считаются вторым объявлением")
	}
	if !strings.Contains(planConsequencesSQL, catalogStaleInputCTE) {
		t.Error("оценка плана не вставляет общего входа отбора: нумерация массивов " +
			"перестаёт совпадать с писательской, и предикат читает не те параметры")
	}

	t.Logf("осмотрено операторов писателя: %d; вложений предиката проверено дословно: %d; "+
		"вставок ссылкой в оценке плана проверено: 4",
		len(embeddings), len(embeddings))
}
