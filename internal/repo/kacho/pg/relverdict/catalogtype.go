// catalogtype.go — ИМЯ ТИПА В СЛОВАРЕ КАТАЛОГА БЕРЁТСЯ У ЖИВОЙ СТРОКИ КАТАЛОГА,
// а не у таблицы, ПОРОЖДЁННОЙ СБОРКОЙ (kacho#1986).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗДЕСЬ СТОЯЛО И ПОЧЕМУ ЭТОГО МАЛО
//
// Параметр словаря каталога связывался значением `authzmap.CatalogTypeName` —
// оболочки над `authzmap/tables_gen.go`, порождённой сборкой из манифестов
// ДЕРЕВА. Оболочка ТОТАЛЬНА: незнакомое имя она возвращает как есть, то есть
// именем словаря МОДЕЛИ (`vpc_network`). Колонки, с которыми параметр
// соединяется, названы словарём КАТАЛОГА (`vpc.network`), и соединение разных
// написаний не совпадает НИКОГДА и молча.
//
// Тот же класс, что у зеркала (#1982), материализатора (#1967) и проекции
// (#1816), но исход ТИШЕ всех трёх: у зеркала промах отвергался проверкой схемы
// — громко, — а здесь перечисление просто возвращает пусто, а селектор меток
// объект не покрывает. Клиент видит «прав нет», а не «что-то сломалось», и от
// честного отказа это неотличимо ничем.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОТДЕЛЬНОЕ ОБРАЩЕНИЕ, А НЕ ВЫРАЖЕНИЕ ВНУТРИ САМОГО ЗАПРОСА
//
// Перевод внутри запроса выглядит строго лучше: круг к базе остаётся один,
// снимок тот же, окна между «спросил имя» и «спросил права» нет. Он был написан,
// ИЗМЕРЕН ПРИБОРОМ ОБЪЁМА И ОТВЕРГНУТ — потому что менял не цену, а ПОРЯДОК
// РОСТА.
//
// Механизм: значение, приезжающее параметром, планировщик оценивает по
// статистике колонки; значение, вычисленное подзапросом или разделом запроса,
// для него НЕПРОЗРАЧНО, и оценка избирательности вырождается в умолчание. На
// малых точках сетки это не видно, на большой — меняет план.
//
// Замер (`scalegrid/REPORT-R7-3-matrix-volume.txt`, четыре точки, рост базы в
// 841 раз), полоса ОТКАЗА, несущие строки:
//
//	параметром (база)          28 · 40 · 52 · 64      растёт ЛОГАРИФМИЧЕСКИ (2.29×)
//	выражением в запросе       28 · 40 · 52 · 1080    растёт ЛИНЕЙНО (38.57×)
//
// Три нижние точки совпадают ДОСЛОВНО, и это существенно: разошлась не цена, а
// план на предельной точке. Нелинейность по населению — отказ, а не медленность,
// поэтому форма с выражением снята целиком, а не подкручена.
//
// ЦЕНА ЭТОЙ ФОРМЫ НАЗВАНА ЧИСЛОМ И ОНА ПОСТОЯННА. Круговых обращений к базе на
// один вопрос становится ДВА вместо одного; строки и тронутое у самого вопроса
// остаются БАЙТ-В-БАЙТ прежними на всех четырёх точках сетки, а сверочная
// величина растёт на **30** — столько строк каталога читает это обращение — и
// растёт на все те же 30 при росте базы в 841 раз. От населения арендатора
// каталог не зависит вовсе: он растёт с числом видов ресурсов платформы.
//
// ─────────────────────────────────────────────────────────────────────────────
// ОКНО МЕЖДУ ДВУМЯ ЧТЕНИЯМИ — НАЗВАНО, А НЕ ЗАМОЛЧАНО
//
// Оба чтения идут в ОДНОЙ транзакции вопроса (`pgx.Tx`, только чтение), но на
// уровне изоляции по умолчанию у двух операторов снимки разные. Значит между
// ними помещается применение, переименовавшее ресурс, и ответ будет дан по
// имени, которое было верным мгновение назад.
//
// Это принято осознанно: исход такого совпадения — один вопрос, отвеченный по
// предыдущему состоянию каталога, то есть та же ограниченная задержка
// распространения, какую платформа уже несёт у материализации прав. Закрывать
// его повышением изоляции значило бы платить сериализацией на КАЖДОМ вопросе
// ради окна в микросекунды.
//
// ─────────────────────────────────────────────────────────────────────────────
// СУЖЕНИЕ ИДЁТ ПО СВОЙСТВУ, А НЕ ПО ИМЕНИ
//
// Запретить сборочный переходник ПО ИМЕНИ нельзя: он тотален, поэтому любая его
// замена — те же две строки у следующего читателя, и запрет обходится молча.
// Различает словари СВОЙСТВО, объявленное самими словарями
// (`authzmap/type_dictionaries.go`): имя каталога содержит точку ВСЕГДА, имя
// модели — НИКОГДА. Здесь свойство выражено САМИМ ИСТОЧНИКОМ: имя берётся из
// колонки `dotted`, у которой точка стоит ограничением схемы
// (`catalog_resource_dotted_form`). Проверять её вторично значило бы завести
// второе место об одном предмете.

// catalogTypeName — имя типа в словаре КАТАЛОГА по ЖИВЫМ строкам каталога.
//
// ТОТАЛЬНА, и это не небрежность. Тип вне каталога законен, и таких два вида:
// вершина иерархии `cluster` (кластер не ресурс, строки у него нет и не будет) и
// непрозрачный тип чужого сервиса. Отказ здесь превратил бы вопрос о доступе к
// ним в ошибку, то есть в «сервис недоступен» вместо ответа. Поэтому промах
// отдаёт имя КАК ЕСТЬ — ровно тем поведением, какое было у снятого переходника,
// — и ни одна из трёх колонок на него не совпадёт, что для этих двух видов и
// верно: строк зеркала и проекции у них не бывает.
//
// Писателю колонки словаря МОДЕЛИ такой тотальности не хватило бы (см.
// `resource_mirror/model_dictionary.go`, где промах — отказ), и это не
// противоречие: там значение уезжает В ЗАПИСЬ и остаётся в таблице; здесь оно
// уезжает В СРАВНЕНИЕ и не совпадает ни с чем.
//
// # ПОЧЕМУ ПОРЯДОК, А НЕ ПРОСТО «НАЙТИ СТРОКУ»
//
// Ключ уникальности каталога — `(object_type, live)`, а не `object_type`. Значит
// один тип модели ЗАКОННО описывают ДВЕ строки: снятая и живая, — и это не край,
// а форма переименования ресурса применением (`superseded_by` у снятой). Отсюда
// оба слагаемых, и каждое закрывает свой исход:
//
//	без `LIMIT`      чтение отдаёт две строки, и вызывающему нечем выбрать;
//	без `ORDER BY`   строка выбирается ПРОИЗВОЛЬНО, и с равным правом приезжает
//	                 имя СНЯТОЙ — то есть ровно тот тихий промах, ради которого
//	                 правка и сделана.
//
// Живое имя и есть то, каким названы `role_verb` и селекторы правил: их ключи
// живости другого имени не допускают.
//
// # ПОЧЕМУ КОЛОНКИ НАЗВАНЫ ПСЕВДОНИМОМ, ХОТЯ ТАБЛИЦА ОДНА
//
// Так пишет ВЕСЬ путь вердикта, и на этом стоит гейт ограниченности чтения
// (`internal/repohygiene` `TestVerdictPathReadsNothingUnbounded`): он признаёт
// чтение привязанным, когда равенство с параметром стоит рядом с колонкой,
// названной псевдонимом. Голая колонка привязкой ему не выглядит — и он честно
// назвал это чтение неограниченным, хотя предел у него есть. Форма приведена к
// той, какую гейт читает, а не гейт научен новой: второй формы записи на этом
// пути не заводится.
func catalogTypeName(ctx context.Context, q pgx.Tx, modelType string) (string, error) {
	var dotted string
	err := q.QueryRow(ctx,
		`SELECT r.dotted
		   FROM kacho_iam.catalog_resource r
		  WHERE r.object_type = $1::text
		  ORDER BY r.live DESC, r.dotted
		  LIMIT 1`, modelType).Scan(&dotted)
	switch {
	case errors.Is(err, pgx.ErrNoRows):
		// Типа в каталоге нет — см. «тотальна» выше.
		return modelType, nil
	case err != nil:
		return "", fmt.Errorf("relverdict: имя типа %q в словаре каталога: %w", modelType, err)
	}
	return dotted, nil
}
