// export_test.go — мост для проб пакета, и он намеренно УЗКИЙ.
//
// # Что здесь есть и чего здесь нет
//
// Здесь только ТЕКСТ запроса и ось меток. Списка параметров здесь НЕТ — и это
// решение, а не упущение. Проба, собирающая девять параметров своей рукой, была
// бы вторым местом об одном предмете: разойдясь с `Ask`, она продолжала бы
// печатать план — план ДРУГОГО запроса, — и расхождение осталось бы незамеченным
// ровно там, где замер и делается. Поэтому оператор для плана ЗАХВАТЫВАЕТСЯ
// трассировщиком у настоящего вызова `Ask`, а этот мост нужен лишь затем, чтобы
// доказать: захвачен именно запрос вердикта, а не какой-то другой оператор
// пакета.
//
// # Почему мост, а не экспорт из прод-кода
//
// Файл кончается на `_test.go`, поэтому в сборку продукта не входит и в отпечаток
// предмета замера (он выводится по НЕ-тестовым файлам каталога) не попадает.
// Экспортировать `verdictQuerySQL` из `query.go` значило бы расширить публичную
// поверхность пакета ради пробы — то есть заплатить прод-контрактом за оснастку.

// VerdictQuerySQLForTest — готовый текст запроса вердикта для выбранной оси меток.
func VerdictQuerySQLForTest(labelTable string) string { return verdictQuerySQL(labelTable) }

// LabelAxisForTest — ось меток, выбранная по типу объекта.
func LabelAxisForTest(objectType string) (string, error) { return labelAxisOf(objectType) }

// MaxConditionRowsForTest — предел числа различных условий на вопрос.
//
// Назван затем, чтобы проба могла сказать, ЧТО за девятый параметр она видит,
// а не считать их молча.
const MaxConditionRowsForTest = maxConditionRows

// ListQuerySQLForTest — готовый текст запроса ПЕРЕЧИСЛЕНИЯ для выбранной оси меток.
//
// Нужен ровно затем же, зачем и текст вердикта: доказать, что трассировщик
// захватил ИМЕННО заход перечисления, а не какой-то другой оператор пакета.
// Числом заходов на вызов `List` мерится худший случай страницы (доля доступных
// 0 %), и считать их можно только по захваченным операторам: сам `List` их не
// возвращает, а завести счётчик внутри него значило бы править прод-код ради
// прибора.
func ListQuerySQLForTest(labelTable string) string { return listQuerySQL(labelTable) }

// RollbackForTest — снятие транзакции чтения так, как его делает адаптер.
//
// Мост нужен затем, что предмет пробы — ИМЕННО контекст снятия, а не поведение
// `pgx.Tx.Rollback` вообще: проба обязана звать тот же код, что исполняется на
// пути чтения, иначе она утверждала бы про свою копию.
func RollbackForTest(ctx context.Context, tx pgx.Tx) error { return rollback(ctx, tx) }
