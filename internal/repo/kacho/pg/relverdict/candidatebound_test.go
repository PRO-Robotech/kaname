// candidatebound_test.go — ИСТОЧНИК КАНДИДАТОВ НЕСЁТ СВОЙ ПРЕДЕЛ НА КАЖДОЙ ОСИ.
//
// # Зачем эта проба существует, если предел уже проверен
//
// Плоскость кривой прочитанных строк утверждает поведенческая проба
// (list_page_cost_integration_test.go). Она сеет `vpc_network`, то есть меряет
// ОСЬ ЗЕРКАЛА — одну из восьми. Остальные семь осей (собственные таблицы iam)
// она не трогает, и до появления этого файла предел на них не держало НИЧТО.
//
// Статический гейт дерева
// `internal/repohygiene` TestRecursiveScopeChainCostsTheRequestNotTheSet сюда не
// достаёт, и это не его недосмотр, а его объявленная граница: он судит строковый
// литерал, а источник кандидатов подставляется в него на лету. Перепись гейта это
// показывает прямо — выражение, посеянное набором, он засчитывает, а предела в
// подставленном теле не видит, потому что тела там ещё нет.
//
// Так вышло не из одной ветви, а из ИХ СХОДА: пока источник был выписан в
// литерале, предел видел гейт; пока оси не было, терять было нечего. Сойдясь,
// две верные правки оставили свойство без единой проверки на семи осях из восьми
// — молча. Этот файл закрывает ровно тот зазор.
//
// # Что именно утверждается — и почему это не «форма без содержания»
//
// Предмет проверки — АРТЕФАКТ, который уедет в Postgres, собранный ТОЙ ЖЕ
// production-функцией (`candidateFrom`), а не её копией в тесте. Утверждается
// три вещи, каждая со своим следствием:
//
//   - предел привязан к параметру размера захода: без него цепь областей
//     раскрутится на всём типе, и стоимость страницы станет стоимостью набора;
//   - порядок отбора кандидатов — по тому же ключу, каким страница отдаётся
//     наружу: разойдись они, курсор пропускал бы строки;
//   - метки едут колонкой кандидата: иначе меточная ветвь добирает их вторым,
//     ничем не ограниченным чтением того же места.
//
// Отрицание идёт В ПАРЕ С ПОЛОЖИТЕЛЬНЫМ и с контролем: тот же предикат обязан
// ОТВЕРГНУТЬ фрагмент без предела. Без контроля «все оси прошли» неотличимо от
// предиката, который не умеет находить ничего.

import (
	"strings"
	"testing"
)

// boundedCandidateSource — предикат: фрагмент ограничивает свой выход размером
// захода, упорядочен по ключу отбора и несёт метки.
//
// Отдаёт причину отказа, а не булево: проба, назвавшая «не прошло» без предмета,
// заставляет следующего читателя выяснять его заново.
func boundedCandidateSource(fragment, limitParam string) (why string) {
	switch {
	case !strings.Contains(fragment, "LIMIT "+limitParam):
		return "нет предела по параметру размера захода " + limitParam +
			": цепь областей раскрутится на всём типе, а предел в конце запроса ограничит " +
			"длину ответа, но не работу"
	case !strings.Contains(fragment, "ORDER BY"):
		return "нет порядка отбора: предел без порядка берёт произвольные строки, и курсор " +
			"перестаёт быть обходом без пропусков"
	case strings.Index(fragment, "ORDER BY") > strings.Index(fragment, "LIMIT "+limitParam):
		return "порядок объявлен ПОСЛЕ предела — предел срезал бы набор до упорядочивания"
	case !strings.Contains(fragment, "labels"):
		return "кандидат не несёт колонки меток: меточная ветвь добрала бы их вторым, ничем " +
			"не ограниченным чтением того же места"
	}
	return ""
}

// TestCandidateSourceIsBoundedOnEveryAxis — свойство обеих осей.
func TestCandidateSourceIsBoundedOnEveryAxis(t *testing.T) {
	const limitParam = "$4"

	// Ось зеркала — пустая таблица. Названа явно, а не выведена из отсутствия
	// записи в реестре: у неё тот же предмет и тот же предел.
	axes := []struct{ name, table string }{{name: "зеркало (типы чужих сервисов)", table: ""}}
	for _, a := range IAMDirectLabelAxes() {
		axes = append(axes, struct{ name, table string }{name: a.ObjectType, table: a.Table})
	}

	if len(axes) != 8 {
		t.Fatalf("предпосылка пробы нарушена: осей %d, а не 8 (зеркало + семь собственных "+
			"таблиц iam). Реестр изменился — проба обязана измениться вместе с ним, иначе "+
			"её «все прошли» относится не к тому множеству", len(axes))
	}

	for _, a := range axes {
		t.Run(a.name, func(t *testing.T) {
			fragment := candidateFrom(a.table, "$2", "$3", limitParam)
			if why := boundedCandidateSource(fragment, limitParam); why != "" {
				t.Fatalf("источник кандидатов оси %q не ограничен: %s\nфрагмент:\n%s",
					a.name, why, fragment)
			}
		})
	}
	t.Logf("осмотрено: осей %d (зеркало + собственных таблиц iam %d); "+
		"у каждой предел привязан к %s", len(axes), len(IAMDirectLabelAxes()), limitParam)
}

// TestCandidateBoundPredicateRejectsAnUnboundedSource — КОНТРОЛЬ предиката.
//
// Без него зелёное выше не отличимо от предиката, который согласен со всем.
// Вход — не выдумка: это ровно та форма, какой источник кандидатов был до
// переноса предела, поэтому проба закрепляет починенный дефект, а не абстракцию.
func TestCandidateBoundPredicateRejectsAnUnboundedSource(t *testing.T) {
	unbounded := "SELECT m.object_id, m.labels\n      FROM kacho_iam.resource_mirror m\n" +
		"     WHERE m.object_type = $2::text\n       AND m.object_id > $3::text"
	if why := boundedCandidateSource(unbounded, "$4"); why == "" {
		t.Fatal("предикат принял источник БЕЗ предела — значит он не умеет находить именно " +
			"то, ради чего написан, и зелёное на восьми осях ничего не означает")
	}

	// Второй контроль — порядок без предела и предел без порядка: обе половины
	// требования обязаны быть несущими по отдельности.
	if why := boundedCandidateSource("SELECT o.id AS object_id, o.labels FROM t o LIMIT $4::int", "$4"); why == "" {
		t.Fatal("предикат принял предел БЕЗ порядка отбора — предел без порядка берёт " +
			"произвольные строки, и курсор перестаёт быть обходом без пропусков")
	}
}
