package relverdict

// asker.go — форма E под порт теневого сравнения.
//
// # Почему отдельный тип, а не метод на пуле
//
// Сравнителю нужны ровно те вопросы, которые форма E умеет отвечать, и порт у
// него узкий. Пул умеет много — отдать его целиком значило бы дать сравнению
// доступ к тому, чего его предмет не требует, и следующая правка легко
// превратила бы теневой путь в пишущий.
//
// # Почему адаптер несёт ВСЕ четыре вопроса, а не один
//
// Форма E отвечает четырьмя запросами — прямой вердикт, перечисление объектов,
// перечисление субъектов, разворот оснований, — и все четыре разложены одной и
// той же раскладкой модели. Адаптер, несущий один из них, оставляет остальные
// три без спрашивающего: сама способность ответить остаётся, а сходимость
// меряется по одному вопросу и объявляется свойством формы целиком.
//
// # Почему СВОЯ транзакция только на чтение
//
// Вердикт складывается из нескольких источников, и читать их обязано ОДНО
// состояние базы: без общей транзакции запрос мог бы увидеть выдачу до отзыва и
// цепь после переноса, то есть сравнить движок с состоянием, которого не было
// ни в один момент. Транзакция только читает и всегда откатывается.

import (
	"context"
	"fmt"
	"sync/atomic"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// rollbackGrace — сколько отпущено САМОМУ снятию транзакции.
//
// Снятие — не часть вопроса и его сроком не ограничено: вопрос кончился, а
// связь ещё надо вернуть пригодной. Величина мала намеренно — недоступная база
// не должна задерживать освобождение слота дольше, чем стоил бы новый коннект.
const rollbackGrace = 2 * time.Second

// rollback снимает транзакцию чтения контекстом, который ЖИВ.
//
// # Почему не тем же контекстом, что ограничивал вопрос
//
// Теневой вопрос идёт со своим коротким сроком. На исчерпании этого срока
// контекст уже мёртв — и снятие, которому его отдают, до базы НЕ ДОЕЗЖАЕТ:
// `Rollback` возвращает ошибку контекста, не отправив ничего. Связь уходит в пул
// с незакрытой транзакцией, пул признаёт её непригодной и уничтожает, заводя
// новую. Наблюдаемая цена — одно подключение за каждый сорванный по сроку
// вопрос: под нагрузкой пул не «дорастает до потолка», а непрерывно перебирает
// связи на стороне, которая и так узкая.
//
// Значения контекста сохраняются (они называют вызывающего), снимается только
// отмена; свой короткий срок ставится взамен, чтобы снятие не висело вечно на
// недоступной базе.
func rollback(ctx context.Context, tx pgx.Tx) error {
	rctx, cancel := context.WithTimeout(context.WithoutCancel(ctx), rollbackGrace)
	defer cancel()
	return tx.Rollback(rctx)
}

// Asker — форма E как источник теневого вердикта.
//
// Помимо ответов ведёт ОДНО наблюдение: сколько раз меточная ветвь дала
// основание НА ПРЯМОМ ВЕРДИКТЕ, по каждой оси отдельно.
//
// Здесь стояло, что без него «расхождений с движком нет» не отличается от
// «меточную ветвь ни разу не спросили»: наблюдение заводилось под теневое
// сравнение форм. Сравнения больше нет — оно снято вместе с внешним движком
// прав. Предмет наблюдения при этом не отпал, а СТАЛ ШИРЕ: форма из теневой
// сделалась единственным источником вердикта, поэтому молчащая ось означает
// теперь не расхождение с кем-то, а выдачи по меткам, которые не действуют, —
// и арендатор читает это как «прав не выдали», а не как ошибку.
//
// Разделено по осям потому, что предикат равенства форм у осей РАЗНЫЙ: число,
// названное для одной, доказывает половину и молчит про другую — именно так
// дефект и дожил до находки.
//
// ГРАНИЦА НАЗВАНА ЯВНО: считается прямой вердикт, и только он. Три обратных
// вопроса (перечисление объектов, перечисление субъектов, разбор оснований)
// сюда не считаются, потому что их ответ — множество, и «основание меточной
// ветви» в нём не единица счёта: одно число на четыре разных вопроса читалось бы
// шире, чем измерено. Ось у обратных вопросов та же и держится их пробами; если
// понадобится число и по ним, оно заводится СВОИМ, а не расширением этого молча.
type Asker struct {
	pool *pgxpool.Pool
	// labelMirror / labelIAMDirect — основания меточной ветви по осям.
	labelMirror    atomic.Int64
	labelIAMDirect atomic.Int64
	// earlyStops — вердиктов, ответивших ДО того, как набор источников дочитан.
	//
	// Знаменатель к двум числам выше. Ранний выход прекращает чтение на первом
	// безусловном основании, поэтому ноль оснований меточной ветви означает либо
	// «ветвь молчала», либо «до неё не дочитали», и без этого числа две причины
	// неразличимы. Печатается рядом, а не вместо: скрыть неопределённость было
	// бы хуже, чем назвать её.
	earlyStops atomic.Int64

	// undeclaredType — отказов, данных по основанию «типа нет в словаре модели».
	//
	// Величина мала и обязана такой оставаться: её законный источник — вопрос про
	// СНЯТЫЙ тип, а таких в живой системе единицы. Растущий счётчик означает
	// ровно одно — кто-то спрашивает про тип, которого модель не знает, и
	// получает отказ вместо ошибки. Чаще всего это опечатка в имени типа
	// настоящего ресурса: доступ пропадает, а выглядит как «прав не выдали».
	//
	// Без этого счётчика мера против одной беды (#880) завела бы вторую — тихую.
	undeclaredType atomic.Int64
}

// LabelArmGrounds отдаёт накопленные числа: сколько оснований дала меточная
// ветвь на оси зеркала и на оси собственных таблиц iam.
//
// Читается коллектором наблюдаемости iam, провязанным в композиционном корне
// (services/iam/cmd/kacho-iam), а не пробой: счётчик, у которого читатель только
// в тесте, наблюдаемым не является.
//
// ЗДЕСЬ СТОЯЛО «читается наблюдателем (сравнитель кладёт их в каждую свою
// запись)» — и это было неправдой с того дня, как сравнение сняли: читателя не
// осталось ни одного, ни в пробе, ни вне её. Комментарий пережил свой предмет и
// при этом отговаривал искать провязку — следующий читатель поверил бы ему, а
// не коду (#1224). Что читатель есть, держит обход дерева
// (internal/repohygiene, TestDeclaredAccumulatorsHaveANonTestReader), а не эта
// строка: провязка наблюдаемости всюду nil-безопасна, поэтому её пропажу не
// поймает ни компилятор, ни проба самого накопителя.
func (a *Asker) LabelArmGrounds() (mirror, iamDirect, earlyStops int64) {
	if a == nil {
		return 0, 0, 0
	}
	return a.labelMirror.Load(), a.labelIAMDirect.Load(), a.earlyStops.Load()
}

// UndeclaredTypeDenials — сколько отказов дано по основанию «тип не объявлен
// моделью» (#880). Растущее число — сигнал опечатки в имени типа, а не нормы.
//
// Читается тем же коллектором наблюдаемости, что и числа выше: сигнал, который
// некому прочитать, сигналом не является — его ноль отвечает сразу и «такого не
// случалось», и «этот код не исполнялся».
func (a *Asker) UndeclaredTypeDenials() int64 {
	if a == nil {
		return 0
	}
	return a.undeclaredType.Load()
}

// observe засчитывает основание меточной ветви на ту ось, у которой спрашивали,
// и отдельно — вердикты, ответившие до того, как набор дочитан.
func (a *Asker) observe(g Grounds) {
	if !g.SetExhausted {
		// Ранний выход считается ОТДЕЛЬНО — он знаменатель, без которого «ноль
		// оснований меточной ветви» неотличимо от «до ветви не дочитали».
		//
		// Ветвь выдач в запросе ОДНА (разделять её на две нельзя — цена названа
		// у grantArmPredicate), поэтому признак называет ветвь ТОГО основания,
		// на котором читатель остановился: при двойном покрытии объекта он не
		// воспроизводим, и контракт это прямо говорит (см. Grounds.LabelArm).
		// Считается он всё равно: на объектах одного покрытия — а таковы все,
		// кому меточное правило и адресовано, — число точное.
		a.earlyStops.Add(1)
	}
	if g.TypeNotDeclared {
		a.undeclaredType.Add(1)
	}
	if !g.LabelArm {
		return
	}
	if g.LabelAxisTable == "" {
		a.labelMirror.Add(1)
		return
	}
	a.labelIAMDirect.Add(1)
}

// NewAsker собирает источник. nil-пул — законный вход: сравнение тогда не
// включается вовсе, а не отвечает молча «нет».
func NewAsker(pool *pgxpool.Pool) *Asker {
	if pool == nil {
		return nil
	}
	return &Asker{pool: pool}
}

// Allowed отвечает на прямой вопрос.
//
// Возвращает ОШИБКУ, а не false, когда ответа получить не удалось: сравнитель
// обязан отличить «форма сказала нет» от «форма не ответила», иначе недоступная
// БД читалась бы как поток расхождений либо как согласие — в зависимости от
// вердикта движка, то есть случайно.
func (a *Asker) Allowed(ctx context.Context, subject, objectType, objectID, relation string, condCtx map[string]any) (bool, error) {
	if a == nil || a.pool == nil {
		return false, fmt.Errorf("relverdict: источник не собран")
	}
	tx, err := a.pool.BeginTx(ctx, pgx.TxOptions{AccessMode: pgx.ReadOnly})
	if err != nil {
		return false, fmt.Errorf("relverdict: транзакция чтения: %w", err)
	}
	defer func() { _ = rollback(ctx, tx) }()

	v, grounds, err := Ask(ctx, tx, Query{
		Subject: subject, ObjectType: objectType, ObjectID: objectID, Relation: relation,
		Context: condCtx,
	})
	// Наблюдение засчитывается ДО разбора вердикта: меточное основание было
	// найдено независимо от того, чем кончился вопрос, и считать его только на
	// разрешении значило бы мерить не ветвь, а исход.
	a.observe(grounds)
	if err != nil {
		return false, err
	}
	switch v {
	case Allow:
		return true, nil
	case Deny:
		return false, nil
	default:
		// Unknown — не «нет». Отдаём ошибкой, чтобы сравнение положило исход в
		// свою корзину «не выполнилось», а не в расхождение.
		return false, fmt.Errorf("relverdict: вердикт не определён (%s)", v)
	}
}

// AllowedMany отвечает на прямой вопрос о СТРАНИЦЕ объектов одного типа —
// ОДНИМ запросом в одной читающей транзакции.
//
// # Почему ОДИН запрос, а не цикл по `Allowed`
//
// Стоимость страницы принадлежит ЗАПРОСУ, а не набору, и мерится она ОБРАЩЕНИЯМИ
// К БАЗЕ. Цикл по `Allowed` открывал бы читающую транзакцию на КАЖДЫЙ объект
// одного живого запроса.
//
// Здесь стояло, что одна транзакция этот класс закрывает. Она закрывала его
// наполовину: транзакция была одна, а вопросов внутри неё оставалось столько же,
// сколько объектов, — «партия» существовала по форме и отсутствовала по существу.
// Цена не в средней задержке, а в ЗАПАСЕ ДО ОТКАЗА: бюджет вызывающего
// принадлежит запросу, а не пункту, поэтому деградация базы превращала здоровый
// положительный список в отказ во столько же раз раньше, во сколько партия
// длиннее единицы. Теперь страница отвечается ОДНИМ запросом (`AskMany`), и
// ЧИСЛО ОБРАЩЕНИЙ не растёт с числом идентификаторов — это утверждает проба,
// считающая обращения наблюдателем операторов, а не время.
//
// # «Обращений не растёт» — НЕ «работы не растёт» (важное различие)
//
// Здесь стояло рядом «страница по контракту доходит до тысячи объектов», и вместе
// с предыдущим абзацем это читалось как обещание, которого замер не даёт.
// Серверная работа растёт СУПЕРЛИНЕЙНО по длине партии: набор различимых областей
// собирается один раз на запрос, но просматривается по разу на каждый объект, то
// есть касаний порядка квадрата длины.
//
// Замер (одна посадка, прогрето, лучшее из трёх) — отношение «страница /
// пообъектно»:
//
//	n=50   0.11      n=100  0.17      n=400  0.37      n=1000  0.86
//
// То есть на ФАКТИЧЕСКИХ размерах партии выигрыш девяти- и шестикратный, а к
// тысяче вырождается почти в единицу. Фактических размеров два, и оба заданы
// вызывающими, а не этой функцией: `authzfilter.MaxBatchChecksPerRequest` = 50 и
// предел партии `BatchCheck` = 100.
//
// Практическое следствие, ради которого абзац и написан: **поднимать эти пределы
// без перезамера нельзя.** Партия длиннее тысячи перестаёт быть выигрышем и
// становится проигрышем; ограничение живёт у вызывающих, и там же стоит его
// объяснение.
//
// # Почему это ещё и вернее
//
// Все объекты страницы видят ОДИН снимок базы. Страница, собранная из тысячи
// снимков, не существовала целиком ни в один момент: между первым и последним
// вопросом выдача могла быть отозвана, и ответ описывал бы состояние, которого
// не было.
//
// Ответ — той же длины и в порядке заданных идентификаторов: верный, но
// переставленный вердикт отфильтровал бы страницу чужим ответом. Первая же
// неудача прекращает разбор и возвращается ОШИБКОЙ — частичный ответ означал бы
// вердикт, которого никто не выносил.
func (a *Asker) AllowedMany(
	ctx context.Context, subject, objectType string, objectIDs []string, relation string,
	condCtx map[string]any,
) ([]bool, error) {
	if a == nil || a.pool == nil {
		return nil, fmt.Errorf("relverdict: источник не собран")
	}
	if len(objectIDs) == 0 {
		return nil, nil
	}
	tx, err := a.pool.BeginTx(ctx, pgx.TxOptions{AccessMode: pgx.ReadOnly})
	if err != nil {
		return nil, fmt.Errorf("relverdict: транзакция чтения: %w", err)
	}
	defer func() { _ = rollback(ctx, tx) }()

	verdicts, grounds, aerr := AskMany(ctx, tx, QueryMany{
		Subject: subject, ObjectType: objectType, ObjectIDs: objectIDs, Relation: relation,
		Context: condCtx,
	})
	// Наблюдение засчитывается ДО разбора вердиктов и по КАЖДОЙ разобранной
	// позиции: основание было найдено независимо от того, чем кончился вопрос, и
	// считать его только на разрешении значило бы мерить не ветвь, а исход.
	for i := range grounds {
		a.observe(grounds[i])
	}
	if aerr != nil {
		return nil, aerr
	}
	if len(verdicts) != len(objectIDs) {
		return nil, fmt.Errorf("relverdict: страница из %d объектов отвечена %d вердиктами — "+
			"ответ не позиционен, и вызывающий сверил бы его со своей страницей не по тем местам",
			len(objectIDs), len(verdicts))
	}

	out := make([]bool, len(objectIDs))
	for i, v := range verdicts {
		switch v {
		case Allow:
			out[i] = true
		case Deny:
			out[i] = false
		default:
			// Unknown — не «нет». Ошибка, чтобы исход лёг в свою корзину, а не
			// стал отказом, неотличимым от честного.
			return nil, fmt.Errorf("relverdict: вердикт не определён (%s) на объекте %q",
				v, objectIDs[i])
		}
	}
	return out, nil
}

// Objects — какие объекты этого типа доступны субъекту.
//
// relations — НАБОР: движок отвечает на читающее действие объединением двух
// отношений (`viewer` ∪ `v_list`), и спросить форму об одном из них значило бы
// сравнить два разных вопроса и записать расхождение там, где спрашивали не то же
// самое. Объединение делается здесь, в одной транзакции: два снимка базы дали бы
// множество, которого не было ни в один момент.
//
// complete=false означает «ответ не помещается в limit» — у сравнения на это своя
// корзина, и выдавать усечённый ответ за полный оно не станет.
func (a *Asker) Objects(ctx context.Context, subject, objectType string, relations []string, limit int) ([]string, bool, error) {
	if a == nil || a.pool == nil {
		return nil, false, fmt.Errorf("relverdict: источник не собран")
	}
	if len(relations) == 0 {
		return nil, false, fmt.Errorf("relverdict: перечисление без отношения — пустой ответ "+
			"за него неотличим от честного «ничего не доступно» (субъект %q, тип %q)", subject, objectType)
	}
	tx, err := a.pool.BeginTx(ctx, pgx.TxOptions{AccessMode: pgx.ReadOnly})
	if err != nil {
		return nil, false, fmt.Errorf("relverdict: транзакция чтения: %w", err)
	}
	defer func() { _ = rollback(ctx, tx) }()

	seen := make(map[string]struct{}, limit)
	out := make([]string, 0, limit)
	for _, rel := range relations {
		ids, next, err := List(ctx, tx, ListQuery{
			Subject: subject, ObjectType: objectType, Relation: rel, Limit: limit,
		})
		if err != nil {
			return nil, false, err
		}
		for _, id := range ids {
			if _, ok := seen[id]; ok {
				continue
			}
			seen[id] = struct{}{}
			out = append(out, id)
		}
		// Курсор непуст — страница полна и продолжение есть: ответ не помещается.
		// Проверяется ПО КАЖДОМУ отношению: объединение двух усечённых страниц
		// длиной обмануло бы проверку на слитом множестве.
		if next != "" {
			return out, false, nil
		}
	}
	return out, true, nil
}

// Subjects — кто имеет это отношение на этом объекте.
func (a *Asker) Subjects(ctx context.Context, objectType, objectID, relation string, limit int) ([]string, bool, error) {
	if a == nil || a.pool == nil {
		return nil, false, fmt.Errorf("relverdict: источник не собран")
	}
	tx, err := a.pool.BeginTx(ctx, pgx.TxOptions{AccessMode: pgx.ReadOnly})
	if err != nil {
		return nil, false, fmt.Errorf("relverdict: транзакция чтения: %w", err)
	}
	defer func() { _ = rollback(ctx, tx) }()

	subjects, next, err := Subjects(ctx, tx, SubjectsQuery{
		ObjectType: objectType, ObjectID: objectID, Relation: relation, Limit: limit,
	})
	if err != nil {
		return nil, false, err
	}
	return subjects, next == "", nil
}

// Sources — кого называют основания права на объекте.
//
// Отдаёт СУБЪЕКТОВ, а не сами основания: форма ответа у двух сторон разная — у
// движка дерево наборов, у формы E плоский перечень с носителем и ветвью, — и
// сверять их поэлементно значило бы объявлять расхождением разную форму записи.
// Одинаково обе стороны называют одно: кто в итоге получает право.
func (a *Asker) Sources(ctx context.Context, objectType, objectID, relation string) ([]string, error) {
	if a == nil || a.pool == nil {
		return nil, fmt.Errorf("relverdict: источник не собран")
	}
	tx, err := a.pool.BeginTx(ctx, pgx.TxOptions{AccessMode: pgx.ReadOnly})
	if err != nil {
		return nil, fmt.Errorf("relverdict: транзакция чтения: %w", err)
	}
	defer func() { _ = rollback(ctx, tx) }()

	sources, err := Expand(ctx, tx, objectType, objectID, relation)
	if err != nil {
		return nil, err
	}
	seen := make(map[string]struct{}, len(sources))
	out := make([]string, 0, len(sources))
	for _, s := range sources {
		if _, ok := seen[s.Subject]; ok {
			continue
		}
		seen[s.Subject] = struct{}{}
		out = append(out, s.Subject)
	}
	return out, nil
}
