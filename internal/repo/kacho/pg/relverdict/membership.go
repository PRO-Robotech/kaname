package relverdict

// membership.go — РАЗВОРОТ ЧЛЕНСТВА ДЛЯ ОБРАТНЫХ ВОПРОСОВ, В ОДНОМ ЭКЗЕМПЛЯРЕ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ (#758)
//
// Обратные вопросы — «кто может» (`subjects.go`) и «почему» (`expand.go`) —
// разворачивают найденные основания на членов названных групп. Прежде разворот
// стоял в обоих файлах ОДНОЙ И ТОЙ ЖЕ строкой:
//
//	JOIN kacho_iam.group_members gm
//	  ON <subject> IN ('group:' || gm.group_id, 'group:' || gm.group_id || '#member')
//
// `gm.group_id` — ВЕДУЩАЯ колонка `group_members_pkey (group_id, member_type,
// member_id)`. Склейка выводит её из-под ключа: сравнивать приходится
// вычисленное значение, а вычисленное значение отбирает строки только ПОСЛЕ
// того, как они прочитаны. Следствие измерено пробой
// `reverse_membership_cost_integration_test.go`: вопрос про ОДИН объект читал
// 10 023 строки при десяти тысячах членств в схеме против 23 при одном — то
// есть стоимость вопроса принадлежала чужим арендаторам.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ НЕ «РАЗОБРАТЬ ПАРАМЕТР», КАК НА ГОРЯЧЕМ ПУТИ
//
// Прямые вопросы (`query.go`, `list.go`) разбирают `$1` — готовую строку
// вызывающего — и заходят в членства парой колонок. У обратных вопросов такого
// параметра НЕТ by construction: развернуть надо не вызывающего, а КАЖДОЕ
// найденное основание, и оно приходит текстовой колонкой набора. Поэтому
// разбирается сама колонка, и разбирается ОДИН РАЗ на строку — соединением
// вбок, а не выражением внутри предиката.
//
// ─────────────────────────────────────────────────────────────────────────────
// СЕМАНТИКА СОХРАНЕНА ДОСЛОВНО, И ЭТО ПРОВЕРЯЕМО
//
// Прежняя форма принимала ровно два написания группы-субъекта: `group:<id>` и
// `group:<id>#member`. Разбор даёт то же множество:
//
//	приставка   `<subject> LIKE 'group:%'`     — иначе строка не про группу;
//	тело        `substr(<subject>, 7)`         — всё после `group:`;
//	имя         `split_part(тело, '#', 1)`     — до первого `#`;
//	ХВОСТ       остаток тела после имени ОБЯЗАН быть пустым либо `#member`.
//
// Проверка хвоста — не перестраховка, а то, что делает разбор ТОЧНЫМ. Без неё
// `group:<id>#other` дал бы имя `<id>` и прошёл, тогда как прежняя форма его
// отвергала. Хвост сверяется ЦЕЛИКОМ (а не вторым куском `split_part`), потому
// что второй кусок у `group:<id>#member#x` тоже равен `member`, а прежняя форма
// такую строку отвергала.
//
// Имена групп `#` не содержат (крокфордова база с приставкой), поэтому обе
// проверки на живых данных тождественно истинны. Они стоят ради того, чтобы
// РАВЕНСТВО ДВУХ ФОРМ доказывалось текстом, а не устройством идентификаторов:
// сменится словарь имён — разбор останется верным.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОДИН ЭКЗЕМПЛЯР, А НЕ ДВЕ ОДИНАКОВЫЕ СТРОКИ
//
// До этой правки одинаковый разворот стоял в двух файлах. Именно поэтому долг и
// прожил: починка горячего пути (#359) прошла по `query.go` и `list.go`, а два
// обратных вопроса остались с прежней формой — и никакой прогон об этом не
// сказал. Один экземпляр не может разойтись сам с собой.

import "strings"

// membersJoinMark — место в тексте обратного запроса, куда встаёт разворот.
//
// Маркер, а не сборка на месте вызова: текст запроса объявлен константой (его
// читают гейт словарей и трассировщик пробы), и подстановка делается там же,
// где подставляется ось меток, — одной функцией на запрос.
const membersJoinMark = "{{members_join}}"

// membershipSubjectMark — место, куда подставляется КОЛОНКА-СУБЪЕКТ набора
// прямых оснований (`g.subject` у «почему», `n.subject` у «кто может»).
const membershipSubjectMark = "{{subject}}"

// membersOfNamedGroupsSQL — соединение с членствами, входящее в оба обратных
// запроса.
//
// Первое соединение вбок отбирает строки, которые вообще про группу, и
// отрезает приставку; второе — выделяет имя и сверяет хвост. Оба возвращают
// ноль либо одну строку, поэтому мощность набора оснований не меняется.
//
// Ключевое соединение — `gm.group_id = group_ref.group_id`: ГОЛАЯ колонка против
// вычисленного скаляра, то есть ровно та форма, которую обслуживает ведущая
// колонка первичного ключа.
const membersOfNamedGroupsSQL = `
  CROSS JOIN LATERAL (
         SELECT substr(` + membershipSubjectMark + `, 7) AS body
          WHERE ` + membershipSubjectMark + ` LIKE 'group:%'
       ) group_write
  CROSS JOIN LATERAL (
         SELECT split_part(group_write.body, '#', 1) AS group_id
          WHERE substr(group_write.body,
                       length(split_part(group_write.body, '#', 1)) + 1) IN ('', '#member')
       ) group_ref
  JOIN kacho_iam.group_members gm ON gm.group_id = group_ref.group_id`

// membersOfNamedGroups — готовый фрагмент для конкретной колонки-субъекта.
func membersOfNamedGroups(subjectCol string) string {
	return strings.ReplaceAll(membersOfNamedGroupsSQL, membershipSubjectMark, subjectCol)
}
