package relverdict

// labelaxis.go — ГДЕ ЛЕЖАТ МЕТКИ ОБЪЕКТА, о котором спрашивают.
//
// ─────────────────────────────────────────────────────────────────────────────
// ДВЕ ОСИ, И ВЫБОР МЕЖДУ НИМИ ДЕЛАЕТ ТИП
//
// Меточная ветвь правила спрашивает одно: покрывают ли метки объекта селектор
// роли. Но лежат эти метки в двух РАЗНЫХ местах, и место — свойство типа:
//
//   · тип чужого сервиса (vpc / compute / storage / nlb / registry) — метки
//     приезжают регистрацией и живут в `resource_mirror`;
//   · собственный тип iam (аккаунт, проект, пользователь, служебная учётная
//     запись, группа, роль, выдача) — метки живут в СВОЕЙ таблице, и в зеркало
//     они не попадают НИКОГДА. Это осознанное решение, а не пробел: зеркало
//     собственных объектов означало бы, что iam регистрирует ресурсы сам у себя,
//     то есть ребро графа в себя.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ВЫБОР ПО ТИПУ, А НЕ ПО НАЛИЧИЮ СТРОКИ В ЗЕРКАЛЕ
//
// «Нет строки зеркала ⇒ ветвь не совпала» — это и есть найденный дефект:
// конъюнкт становится ТОЖДЕСТВЕННО ЛОЖНЫМ на целом семействе типов, а ответ
// «нет» неотличим от честного отказа. Отсутствие строки — не отрицательный
// ответ, а признак того, что спрошено не то место. Поэтому ось выбирается ДО
// запроса, по типу, и её отсутствие у типа, который обязан её иметь, — ОШИБКА
// (см. labelAxisOf), а не тихое «нет».
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ РЕЕСТР — ТОЛЬКО ТАБЛИЦА, А КЛАССИФИКАЦИЯ ВЫВЕДЕНА
//
// Классификацию «этот тип совпадает по своей таблице» уже знает домен
// (`domain.FeedSourceForType`), и второй перечень был бы вторым местом об одном
// предмете: разойдясь, он дал бы ровно исходный дефект под другим именем.
// Поэтому здесь выписано ЕДИНСТВЕННОЕ, чего домен не знает и знать не должен, —
// имя таблицы. Всё остальное выводится, а расхождение вывода с реестром
// превращается в отказ на первом же вопросе.

import (
	"fmt"

	"github.com/PRO-Robotech/kacho/services/iam/internal/domain"
)

// iamDirectLabelTable — таблица, несущая метки объекта СОБСТВЕННОГО типа iam.
//
// Ключ — тип в той форме, в какой его называет вопрос о доступе (`account`,
// `project`, `iam_user`, …): именно она приезжает в `Query.ObjectType`.
// Значение — имя таблицы, ФИКСИРОВАННЫЙ литерал; в запрос оно попадает
// подстановкой, поэтому в реестре не может стоять ничего, пришедшего снаружи.
//
// Каждая из семи таблиц несёт колонку `labels` и GIN-индекс по ней
// (миграции 0023 и 0041), поэтому совпадение остаётся `labels @> match_labels`
// на стороне БД — разбор меток в приложении означал бы вычитывание всех строк
// типа ради того, что индекс отвечает сразу.
var iamDirectLabelTable = map[string]string{
	"account":             "kacho_iam.accounts",
	"project":             "kacho_iam.projects",
	"iam_user":            "kacho_iam.users",
	"iam_service_account": "kacho_iam.service_accounts",
	"iam_group":           "kacho_iam.groups",
	"iam_role":            "kacho_iam.roles",
	"iam_access_binding":  "kacho_iam.access_bindings",
}

// LabelAxis — ось, по которой отвечает меточная ветвь для одного типа.
type LabelAxis struct {
	// ObjectType — тип в форме вопроса о доступе.
	ObjectType string
	// Table — собственная таблица iam. Пусто — ось зеркала.
	Table string
}

// IAMDirectLabelAxes отдаёт реестр осей собственных типов iam.
//
// Существует ради проб и сверок: перечень типов, у которых проба обязана быть,
// не выписывается второй раз, а берётся отсюда. Порядок не гарантируется —
// предмет здесь множество, а не последовательность.
func IAMDirectLabelAxes() []LabelAxis {
	out := make([]LabelAxis, 0, len(iamDirectLabelTable))
	for ty, table := range iamDirectLabelTable {
		out = append(out, LabelAxis{ObjectType: ty, Table: table})
	}
	return out
}

// labelAxisOf выбирает ось для типа.
//
// Пустая таблица означает ось ЗЕРКАЛА — и это положительный ответ, а не «не
// нашли»: типы чужих сервисов именно там и лежат, включая тот, чьего имени в
// каталоге нет вовсе (зеркало держит непрозрачный тип как есть).
//
// Отказ здесь ровно один и он несущий: домен относит тип к совпадающим по СВОЕЙ
// таблице, а таблица не назначена. Отдать в этом случае ось зеркала значило бы
// восстановить исходный дефект — вопрос ушёл бы туда, где объекта нет никогда, и
// ответ «нет» стал бы неотличим от отказа по правам. Поэтому это ошибка: у формы
// E ошибка попадает в корзину «не выполнилось», а не в согласие с движком.
// Тип приезжает сюда В ФОРМЕ МОДЕЛИ, и это не допущение: все четыре вопроса
// зовут раскладку модели ПЕРЕД выбором оси, а она отвергает имя, которого в
// модели нет («тип не объявлен»). Точечное написание того же типа поэтому до
// выбора оси не доходит, и второй ключ реестра защищал бы от входа, которого не
// бывает.
//
// ─────────────────────────────────────────────────────────────────────────────
// ТОЧЕЧНОЕ ИМЯ ПРИХОДИТ ПАРАМЕТРОМ И БЕРЁТСЯ У КАТАЛОГА (kacho#2036)
//
// Здесь стоял перевод модель→каталог сборочной таблицей (`authzmap.DottedType`
// над `tables_gen.go`, порождённой из манифестов ДЕРЕВА). Живое точечное имя
// пишет ПРИМЕНЕНИЕ манифеста в `kacho_iam.catalog_resource`, и от сборочного оно
// расходится: применение вправе и переименовать ресурс, и передать его другому
// модулю. Расхождение по границе `iam.` меняет ОСЬ — то есть место, у которого
// спрашивают метки, — и делает это МОЛЧА: объект, зарегистрированный писателем
// зеркала под живым именем каталога (#1982), искался бы в собственной таблице
// iam, где строки нет и не будет, а ответ «нет» неотличим от честного отказа по
// правам. Тот же класс, что у зеркала (#1982) и у имени типа в соединениях
// (#1986); это был последний его читатель на пути вердикта.
//
// ПАРАМЕТРОМ, А НЕ ВТОРЫМ ЧТЕНИЕМ. Живое имя все четыре вопроса УЖЕ читают —
// `catalogTypeName` (catalogtype.go), один раз на вызов, и цена этого чтения там
// названа числом. Прочитать его здесь ещё раз значило бы удвоить именно ту цену,
// которую тот файл измерил и объявил постоянной. Поэтому функция остаётся
// ЧИСТОЙ: каталог читает вызывающий, а сюда приезжает уже прочитанное.
//
// ПОРЯДОК У ВЫЗЫВАЮЩЕГО ОБРАТИЛСЯ: чтение каталога стоит теперь ПЕРЕД выбором
// оси. Оба обращения — чтения без побочных действий, поэтому обмен местами
// ничего не меняет ни в снимке, ни в числе кругов к базе.
//
// ПРОМАХ КАТАЛОГА СОХРАНЯЕТ ПРЕЖНИЙ ИСХОД, и это свойство схемы, а не совпадение:
// `catalogTypeName` тотальна и на промахе отдаёт имя МОДЕЛИ как есть, а имя
// модели точки не содержит НИКОГДА (`catalog_resource_object_type_form CHECK
// (object_type ~ '^[a-z][a-z0-9_]*$')`). Значит `iam.`-префикса у него не бывает,
// классификатор отвечает «зеркало» — ровно тем, чем прежде отвечала ветвь
// «сборке тип неизвестен».
func labelAxisOf(catalogType, objectType string) (table string, err error) {
	if domain.FeedSourceForType(catalogType) != domain.FeedIAMDirect {
		return "", nil
	}
	t, ok := iamDirectLabelTable[objectType]
	if !ok {
		return "", fmt.Errorf("relverdict: тип %q (%s) совпадает по меткам в СВОЕЙ таблице, "+
			"но таблица ему не назначена — ответить по зеркалу значило бы спросить место, "+
			"где объекта этого типа не бывает, и получить «нет» вместо ответа",
			objectType, catalogType)
	}
	return t, nil
}

// Метки-заполнители в шаблонах запросов.
//
// Подставляются ФРАГМЕНТАМИ, собранными здесь из литералов реестра, — снаружи в
// них не попадает ничего, кроме номеров параметров, которые пишем мы сами.
