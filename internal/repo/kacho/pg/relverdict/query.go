// MaxAncestorDepth — предел обхода цепи предков.
//
// Совпадает с ограничением таблицы рёбер и с пределом компилятора модели. Здесь
// он повторён НЕ как вторая истина, а как страховка обхода: рекурсивный запрос
// без предела на данных с циклом не завершается, и полагаться на то, что цикла
// нет, — значит полагаться на ограничение, которое проверяет другая сторона.
const MaxAncestorDepth = 4

// Verdict — исход вопроса. Три состояния, а не два: «не знаю» отличимо от «нет».
type Verdict int

const (
	// Deny — ни один источник не дал права.
	Deny Verdict = iota
	// Allow — хотя бы один дал.
	Allow
	// Unknown — вопрос затрагивает то, чего эта форма не вычисляет (отношение с
	// условием). НЕ «нет»: слить их значило бы объявить отказом то, на что ответа
	// не получено, — то есть отдать вызывающему решение вместо признания, что
	// решения нет.
	Unknown
)

func (v Verdict) String() string {
	switch v {
	case Allow:
		return "allow"
	case Deny:
		return "deny"
	case Unknown:
		return "unknown"
	}
	return "invalid"
}

// Query — вопрос к форме E.
type Query struct {
	// Subject — целиком, в форме `"user:usr-1"`: подстановочный и групповой
	// субъекты на пару не раскладываются.
	Subject string
	// ObjectType/ObjectID — объект парой, как его называет вопрос и как он лежит
	// в зеркале.
	ObjectType string
	ObjectID   string
	// Relation — отношение в том виде, в каком его называет МОДЕЛЬ (`v_get`,
	// `ssh`, `admin`). Не глагол: приставку снимает компилятор плана там, где
	// источником служит роль, а факт хранится под модельным именем.
	Relation string
	// Context — доводы запроса для условий на записях: «сейчас», уровень
	// уверенности подтверждения личности, применённые методы.
	//
	// Собирается ВЫЗЫВАЮЩИМ и обязан быть уже очищен от значений, присланных
	// клиентом: здесь довод принимается как проверенный. Заводить очистку второй
	// раз тут значило бы завести второе место, знающее, чему можно верить, — и
	// разойтись с первым в сторону лишнего доступа.
	Context map[string]any
}

// maxConditionRows — предел числа различных условий, рассматриваемых на один
// вопрос.
//
// Предел есть, потому что число строк ограничивать обязано что-то; но усечение
// НЕ становится отказом. Достигнут предел ⇒ вердикт «не знаю» с названной
// причиной: тихое «нет» на усечении означало бы отказ, объяснимый только объёмом
// данных, и искали бы его в правах.
const maxConditionRows = 256

// verdictSQL — единственный запрос, отвечающий на вопрос.
//
// Читается сверху вниз: сначала цепь областей объекта (сам объект + предки),
// затем субъекты, за которых говорит вызывающий (он сам, его группы,
// подстановка), затем четыре источника права через OR.
//
// Отдаёт НЕ «да/нет», а условия совпавших источников. Разница существенная:
// свернуть совпадение с условием в «да» значило бы выдать право, действующее при
// невыполненном условии, — то есть ровно то, от чего условие и защищает. Порядок
// по имени условия ставит безусловное совпадение (пустое имя) первым, поэтому
// самый частый случай решается первой же строкой.
//
// Место, где берутся МЕТКИ объекта, оставлено заполнителем: оно зависит от типа
// (`labelaxis.go`) и подставляется фрагментом из закрытого реестра. Написать его
// здесь одним соединением значило бы объявить, что метки всех типов лежат в
// одном месте, — а они лежат в двух, и на одном из семейств такое соединение
// тождественно ложно.
//
// $1 subject · $2 object_type в словаре МОДЕЛИ · $3 object_id ·
// $4 типы предков атомов-фактов ·
// $5 отношения атомов-фактов · $6 глаголы атомов-выдачи · $7 max_depth · $8 limit
// $9 object_type в словаре КАТАЛОГА — им названы `resource_mirror.object_type`,
// `role_verb.object_type` и `role_rule_selectors.object_types`, тогда как вопрос
// приходит словарём модели. Перевод делается ОДИН раз, на входе, и читает ЖИВУЮ
// строку каталога (`catalogTypeName`, catalogtype.go): таблица, порождённая
// сборкой, о типе, заведённом применением манифеста в работающем процессе, не
// знает (kacho#1986). Двух словарей в одном соединении быть не должно —
// соединение по разным написаниям не совпадает НИКОГДА и молча.
const verdictSQL = `
WITH RECURSIVE
-- scope — ОБЛАСТИ, на которые может быть сделана действующая выдача: сам объект
-- и вся его цепь предков.
--
-- ОБХОД, А НЕ ОДНО ЧТЕНИЕ, и это не осторожность. Цепь читается представлением
-- resource_scope_edge, и замыканием не является ни одна из его сторон: ключ
-- (объект, глубина) и проверка глубины 1..4 допускают обе формы, а владельцы
-- ресурсов шлют КОРОТКУЮ цепь — vpc, storage и compute одно звено (проект),
-- реестр два (реестр и проект). Одноразовое чтение схлопнуло бы область до
-- «объект плюс его непосредственный предок»; обход оставляет её открытой вверх.
--
-- ВВЕРХ ЕСТЬ КУДА ИДТИ, и почему — надо сказать здесь, а не подразумевать.
-- Рёбра появляются регистрацией ресурса у владельца прав, а зовут её пять
-- сервисов-соседей только для СВОИХ ресурсов: объектов типа project и account не
-- регистрирует никто, а собственных объектов iam не регистрирует и сам iam.
-- Недостающие звенья ДОСТРАИВАЕТ представление, и у каждого СВОЙ источник — тот,
-- что полон ПО ПОСТРОЕНИЮ именно для ЭТОГО звена:
--
--   проект → его аккаунт    — ПРОЕКЦИЯ ЖУРНАЛА relation_fact: указатель
--                             со-коммитится созданием проекта, а миграции
--                             проекты не сеют (781001, kacho#781);
--   аккаунт → кластер       — СХЕМА, accounts × clusters (синглтон): аккаунты
--                             сеются миграциями, указателя в журнале у них нет
--                             (740001, kacho#740);
--   ЛИЧНОСТЬ → аккаунт     — СХЕМА, таблица kacho_iam.memberships (944001,
--                             kacho#944): принадлежность человека аккаунту
--                             перестала быть колонкой его строки и стала
--                             отдельной связью, которых у него может быть
--                             НЕСКОЛЬКО. Полнота по построению та же, что у
--                             колонки: строка И ЕСТЬ связь (первичный ключ плюс
--                             уникальная пара «человек × аккаунт»), обойти её
--                             нельзя ни через API, ни через посев;
--   четыре собственных типа — СХЕМА, колонка собственной строки объекта:
--   iam → аккаунт либо        groups/service_accounts/roles.account_id,
--   проект                    roles.project_id у проектной роли, пара
--                             access_bindings.resource_type/resource_id для трёх
--                             областных значений закрытого набора. Строка И ЕСТЬ
--                             объект, колонка неизменяема; журнал же полон НЕ по
--                             построению — девять миграций сеют эти строки, и ни
--                             одна не пишет указатель (785001, kacho#785).
--
-- Под представлением лежат kacho_iam.resource_parent_edge (присланное) плюс
-- kacho_iam.relation_fact, kacho_iam.accounts, kacho_iam.clusters,
-- kacho_iam.memberships, kacho_iam.groups, kacho_iam.service_accounts,
-- kacho_iam.roles и kacho_iam.access_bindings (выводимое). Таблица личностей из
-- перечня СНЯТА вместе с ветвью, которая её читала: звено личности берёт аккаунт
-- из членства. Её имя здесь намеренно НЕ ВОСПРОИЗВОДИТСЯ даже в разборе этого
-- снятия — перечень сверяется с телом представления, и имя таблицы, которую цепь
-- не читает, было бы находкой, а не пояснением. Имена названы здесь ЯВНО, и не ради
-- полноты рассказа: отпечаток предмета замера выводит читаемые таблицы ИЗ ТЕКСТА
-- вердикта, поэтому представление, названное одним своим именем, увело бы
-- собственные основания из-под прибора — их правку он перестал бы замечать молча.
--
-- Что из этого следует для формы запроса: выведенные звенья идут ПО ОДНОМУ, как
-- и присланные, поэтому цепь по-прежнему собирается обходом. Ровно этим обходом
-- достижимы верхние уровни security.md §«Три уровня супер-доступа» — выдача на
-- аккаунт и прямой факт администратора облака на кластере; отними его, и оба
-- ответят отказом, НЕОТЛИЧИМЫМ от честного.
--
-- ЦЕНА ОБХОДА ЗАПЛАЧЕНА СОЕДИНЕНИЕМ ВБОК, А НЕ ОБЫЧНЫМ. Рекурсивная ветвь с
-- обычным соединением даёт планировщику право прочитать таблицу рёбер ЦЕЛИКОМ на
-- каждом шаге: измерено 2412 строк за один вердикт при трёх рёбрах у объекта.
-- Соединение вбок с пределом заставляет ходить указателем по ключу.
--
-- ПРЕДЕЛ НЕ УСЕКАЕТ — ДОВОД ЧИСЛОМ, А НЕ РАВЕНСТВОМ. Прежний довод («рёбер у
-- объекта не больше глубин, ключ таблицы уникален по глубине») отменён 781001: у
-- проекта указателей ДВА — аккаунт и кластер, — и оба лежат на глубине 1.
-- Действующий довод: звеньев у объекта столько, сколько у его типа РАЗНЫХ
-- отношений-указателей, и каждая достроенная ветвь даёт объекту ровно одно звено
-- (ветви взаимоисключающи: NOT EXISTS отменяет вывод там, где владелец цепь
-- назвал, а две ветви роли разведены ограничением схемы). Максимум по дереву —
-- 2 при пределе 4, и это число ПРОВЕРЯЕТСЯ переписью источников, а не выводится:
-- объект, у которого звеньев столько же, сколько предел, усекался бы МОЛЧА, а
-- отказ по усечённой цепи неотличим от честного.
-- Та же форма и по той же причине стоит на пути перечисления — одна семантика
-- области на обе точки входа.
scope(s_type, s_id, depth) AS (
    SELECT $2::text, $3::text, 0
  UNION
    SELECT e.parent_type, e.parent_id, s.depth + 1
      FROM scope s
      CROSS JOIN LATERAL (
             SELECT pe.parent_type, pe.parent_id
               FROM kacho_iam.resource_scope_edge pe
              WHERE pe.object_type = s.s_type AND pe.object_id = s.s_id
              ORDER BY pe.depth
              LIMIT $7::int
           ) e
     WHERE s.depth < $7::int
),
-- scope_distinct — ОБЛАСТИ БЕЗ ПОВТОРОВ, и это ЕДИНСТВЕННОЕ, что читают армы.
--
-- Обход выше несёт в кортеже ГЛУБИНУ ШАГА, поэтому UNION не схлопывает предка,
-- достигнутого разными путями. Форма цепи, которую пишет производитель для
-- compute и nlb (ownerregister.ParentChain — проект И аккаунт сразу), даёт
-- аккаунт на глубинах 1 и 2, а стоящий над ним кластер — на 2 и 3: шесть строк
-- при четырёх различных областях.
--
-- Каждая лишняя строка УМНОЖАЕТ ОБА АРМА: ветвь выдач соединена с набором
-- CROSS JOIN, ветвь фактов — по паре колонок. Отбор различных над ОТВЕТОМ
-- прячет это в ответе и не трогает СТОИМОСТЬ, а на отказном вопросе короткого
-- замыкания нет, и цена платится целиком. Измерено пробой
-- scopedistinct_integration_test.go: 6 строк при 4 различных областях.
--
-- ОБХОД СОХРАНЯЕТСЯ ЦЕЛИКОМ — снимается только повтор. Это НЕ переход на одно
-- чтение таблицы рёбер: тот переход опровергнут (таблица хранит присланную
-- цепь, а не замыкание), и здесь его нет.
--
-- Наименьшая глубина БЕЗОПАСНА, и это проверяемо: единственное употребление
-- глубины ниже по запросу — дискриминатор якоря sc.depth = 0, а якорь
-- засевается нулём и по построению остаётся минимумом (выведенная строка даёт
-- s.depth + 1 при s.depth не меньше нуля, то есть нуля дать не может).
scope_distinct(s_type, s_id, depth) AS (
    SELECT s_type, s_id, min(depth) FROM scope GROUP BY s_type, s_id
),
speaker_pair(s_type, s_id, via) AS (
    -- СУБЪЕКТ ВЫДАЧИ — ПАРОЙ КОЛОНОК, а не склейкой.
    --
    -- Склейка subject_type || ':' || subject_id выводит колонки из-под любого
    -- индекса: сравнивать приходится вычисленное значение, а вычисленное
    -- значение отбирает строки только ПОСЛЕ того, как они прочитаны. Пара
    -- колонок сужает набор ДО чтения. Паритет, а не новое устройство: соседнее
    -- соединение того же запроса читает членство парой колонок и обслуживается
    -- индексом (member_type, member_id) с самого начала.
    --
    -- Колонка via называет, ОТКУДА взялась пара, и существует ради текстовой
    -- формы ниже: хвост #member раскрывает ЧЛЕНСТВО, и приписать его группе,
    -- которая сама является вызывающим, значило бы расширить ответ на факты,
    -- которых вызывающему не выдавали.
    SELECT split_part($1::text, ':', 1),
           substr($1::text, length(split_part($1::text, ':', 1)) + 2),
           'self'
  UNION ALL
    SELECT 'group', gm.group_id, 'member'
      FROM kacho_iam.group_members gm
     WHERE gm.member_type = split_part($1::text, ':', 1)
       AND gm.member_id   = substr($1::text, length(split_part($1::text, ':', 1)) + 2)
  UNION ALL
    -- Подстановка объявлена НАМЕРЕННО (глобальный справочник читает всякий
    -- аутентифицированный) и потому перечислена явно, а не выведена из формы
    -- имени.
    SELECT 'user', '*', 'wildcard'
),
speaker(subject) AS (
    -- ТЕКСТОВАЯ форма — для прямых фактов: их субъект хранится строкой, и она
    -- не разбирается на пару нигде в дереве. Обе формы имени группы, и это не
    -- перестраховка: канонический производитель кортежей пишет
    -- group:<id>#member (хвост раскрывает членство на стороне модели), а голой
    -- формой group:<id> адресуется сама группа как субъект. Признать одну и
    -- промолчать о другой значит НЕДОотвечать ровно на права, выданные
    -- каноническим путём, — тихо, потому что неполный ответ выглядит как
    -- честное «ничего нет».
    SELECT $1::text
  UNION
    SELECT 'group:' || sp.s_id FROM speaker_pair sp WHERE sp.via = 'member'
  UNION
    SELECT 'group:' || sp.s_id || '#member' FROM speaker_pair sp WHERE sp.via = 'member'
  UNION
    SELECT 'user:*'
),
fact_atom(parent_type, relation) AS (
    -- Источники-факты плана: где искать и что искать. Пустой тип предка означает
    -- «на самом объекте», непустой — «на предке этого типа».
    SELECT * FROM unnest($4::text[], $5::text[])
)
-- РАННИЙ ВЫХОД: ни одного блокирующего узла над союзом.
--
-- Отбор различных, сортировка и оконная функция — все трое БЛОКИРУЮЩИЕ: ни один
-- не отдаёт первой строки, пока не прочитана последняя. Пока стоял хоть один,
-- «строк прочитано» на разрешающем вопросе совпадало с отказным by construction,
-- и короткое замыкание было заявлено, а не наблюдаемо. Измерено: при трёхстах
-- основаниях на области разрешающий вопрос читал 1222 строки против 19 у
-- отказного — то есть был ДОРОЖЕ.
--
-- ПОРЯДОК ВЕТВЕЙ — ЧАСТЬ УСТРОЙСТВА, А НЕ ОФОРМЛЕНИЕ. Ветвь выдач идёт ПЕРВОЙ,
-- потому что каждая её строка безусловна by construction (выдача условия не
-- несёт: роль раздаёт ГЛАГОЛЫ, а условие в модели стоит на отношениях,
-- глаголами не являющихся). Значит первая же её строка отвечает на вопрос, и
-- читатель останавливается на ней. Ветвь фактов идёт второй и несёт СВОЙ отбор
-- различных — внутри себя, где он не мешает первой ветви: узел Append исполняет
-- потомков по очереди, и до второго дело доходит только когда первый пуст.
--
-- Отбор различных над фактами сохранён ДОСЛОВНО, поэтому предел $8 по-прежнему
-- считает РАЗЛИЧНЫЕ условия, а не сырые строки: ПОРОГ усечения не сдвинулся.
--
-- А вот СОСТОЯНИЕ изменилось, и это надо сказать прямо. Прежде проверка
-- усечения стояла ДО поиска безусловного основания: набор из 256+ условий давал
-- отказ, даже если безусловное основание среди них было. Теперь безусловное
-- основание возвращает разрешение из самого цикла чтения, до проверки. Это
-- РАСШИРЕНИЕ: где был отказ, там теперь разрешение. Поведение защитимо —
-- усечение говорит «я не дочитал», а найденное безусловное основание делает
-- недочитанное несущественным, — но выдавать его за «то же состояние» нельзя.
--
-- ПРЕДЕЛ ВЕТВИ ВЫДАЧ — ОДНА СТРОКА, и это не оптимизация, а то самое короткое
-- замыкание. Замыкание обязано случиться НА СЕРВЕРЕ: закрытие курсора раньше
-- времени сберегает разбор у клиента и ничего не сберегает у базы — портал
-- исполняется до конца, потому что предела строк ему не задано. Измерено: с
-- ранним выходом только на стороне клиента разрешающий вопрос читал 1119 строк
-- против 19 у отказного, то есть оставался ДОРОЖЕ.
--
-- Предел ничего не теряет: все строки этой ветви безусловны и на состав ответа
-- влияют одинаково — прежний отбор различных сворачивал их в ОДНУ ровно так же.
-- Разница лишь в том, что отбор различных сначала читал их все.
--
-- Колонка arm отдаётся КАК ЕСТЬ, построчно. Прежде она сворачивалась оконной
-- функцией по всем строкам; свернуть её нечем, пока чтение вправе прекратиться,
-- и накопление по прочитанному было бы ровно тем, от чего эта правка уходит. Что
-- признак теперь означает и чем «не дала основания» отличимо от «до неё не
-- дочитали» — сказано у Grounds.
SELECT src.cond_name, src.cond_params, src.arm FROM (
  (
{{grant_arm}}
    LIMIT 1
  )
  UNION ALL
  (
{{fact_arm}}
  )
) src
LIMIT $8::int`

// Grounds — что участвовало в ответе, помимо самого вердикта.
//
// Существует ради ОДНОГО числа: сколько раз меточная ветвь дала основание. Без
// него «расхождений между формами нет» не отличается от «меточную ветвь ни разу
// не спросили» — а именно вторым состоянием и был дефект, ради которого ось
// выбирается по типу. Число, которое нельзя предъявить, ничего не утверждает.
//
// Поле ровно одно и названо узко: расширять его «на будущее» значило бы обещать
// наблюдаемость, за которую никто не отвечает.
type Grounds struct {
	// LabelArm — основание, НА КОТОРОМ ОСТАНОВИЛСЯ ЧИТАТЕЛЬ, дала меточная ветвь.
	//
	// КОНТРАКТ СУЖЕН ОСОЗНАННО, и вот его граница. Ветвь выдач ограничена одной
	// строкой (это и есть короткое замыкание, см. запрос), поэтому у объекта,
	// покрытого СРАЗУ НЕСКОЛЬКИМИ ветвями правила, признак называет ту, чью
	// строку вернул планировщик, — и при двойном покрытии он не воспроизводим.
	// Прежняя редакция считала признак по ВСЕМ строкам оконной функцией и была
	// воспроизводима; та форма стоила чтения всего набора на каждом вердикте.
	//
	// Отсюда что признак значит и чего не значит:
	//
	//	значит   — «сколько раз меточная ветвь оказалась ТЕМ основанием, по
	//	           которому выдан доступ»; на объектах одного покрытия (а таковы
	//	           все, кому меточное правило и адресовано) это точное число;
	//	не значит — «сколько раз меточная ветвь ВООБЩЕ дала основание»: при
	//	           двойном покрытии она могла дать и не быть выбрана.
	//
	// Ноль при этом по-прежнему отличим от «не спрашивали»: SetExhausted рядом,
	// и наблюдатель считает недочитанные вердикты отдельным числом. Полное
	// число потребовало бы второго арма, а он оплачивается внешним пределом на
	// КАЖДОМ вопросе — измерено выше у grantArmPredicate.
	LabelArm bool
	// SetExhausted — набор источников дочитан до конца.
	//
	// false означает, что чтение прекращено раньше: найдено безусловное
	// основание. Без этого признака ноль оснований меточной ветви читался бы как
	// «ветвь спрашивали и она молчала», тогда как её могли не спросить вовсе.
	SetExhausted bool
	// LabelAxisTable — таблица, у которой спрашивались метки. Пусто — зеркало.
	// Названа, потому что ось выбирается по типу, и «спросили не там» иначе
	// неотличимо от «нечего было находить».
	LabelAxisTable string

	// TypeNotDeclared — отказ дан потому, что ТИПА объекта в словаре модели нет
	// вовсе (#880).
	//
	// Это ФАКТ О МОДЕЛИ, а не незнание формы: объектов такого типа не
	// существует, значит ни у кого нет на них никакого отношения, и отказ —
	// честный ответ, а не догадка. Ровно так отвечал внешний движок, и ровно
	// этого требует проба снятого носителя точечных выдач.
	//
	// ПОЧЕМУ ЭТО ВООБЩЕ ЗАПИСЫВАЕТСЯ. Тихий отказ по неизвестному типу — удобное
	// место, чтобы утонула опечатка в имени типа НАСТОЯЩЕГО ресурса: доступ
	// пропадёт, а выглядеть будет как «прав не выдали». Основание называется,
	// считается и попадает в журнал — иначе мера, введённая против одного
	// класса, завела бы второй.
	TypeNotDeclared bool
}

// Ask задаёт вопрос форме E.
//
// Ошибка запроса — это ОШИБКА, а не отказ: вернуть Deny на сбое означало бы
// сказать «прав нет» там, где ответа не получено. Вызывающий обязан отличать
// одно от другого — со снятием второй формы это разница между «не смог спросить»
// и «доступа нет», и первое не имеет представления на успешном пути.
// По той же причине ошибкой отвечает и НЕНАЗНАЧЕННАЯ ось меток: см. labelAxisOf.
// verdictQuerySQL — ГОТОВЫЙ запрос вердикта для выбранной оси меток (см. довод
// у expandQuerySQL: собранный запрос читает не только продукт, но и гейт
// словарей, и собирать его гейт не вправе).
// grantArmSQL — ТЕЛО ВЕТВИ ВЫДАЧ, единственное в дереве.
//
// Ветвь встаёт в запрос ДВАЖДЫ и различается ровно предикатом правила. Текст при
// этом ОДИН: скопировать его значило бы завести два места, знающие, что такое
// «выдача достаёт до объекта», и разойтись им молча — в сторону лишнего доступа.
const grantArmSQL = `
    -- ЗАХОД — С ПАРЫ «СУБЪЕКТ + ОБЛАСТЬ», и оба предиката сужают набор ДО
    -- чтения строк. Пока субъект жил на дочерней таблице, а область — на
    -- родительской, одного индекса, обслуживающего оба, не существовало by
    -- construction: заход со стороны области читал ВСЕ выдачи области, заход со
    -- стороны субъекта — ВСЕ выдачи субъекта в облаке. Первое ограничено
    -- размером облака, второе не ограничено ничем. Область перенесена на строку
    -- субъекта (миграция 732001), согласованность держит составной внешний ключ
    -- с каскадом правки, а не синхронизация в коде.
    --
    -- Обращений — не больше, чем произведение мощностей speaker_pair и scope,
    -- и каждое возвращает выдачи ровно этого субъекта ровно в этой области.
    SELECT ''::text AS cond_name, '{}'::jsonb AS cond_params, rs.arm AS arm
      FROM speaker_pair sp
      {{scope_join}}
      JOIN kacho_iam.access_binding_subjects bs
        ON bs.subject_type  = sp.s_type AND bs.subject_id  = sp.s_id
       AND bs.resource_type = sc.s_type AND bs.resource_id = sc.s_id
      JOIN kacho_iam.access_bindings b ON b.id = bs.binding_id
      JOIN kacho_iam.role_verb rv
        ON rv.role_id = b.role_id AND rv.object_type = $9::text
       AND rv.verb = ANY ($6::text[])
      JOIN kacho_iam.role_rule_selectors rs
        ON rs.role_id = b.role_id AND $9::text = ANY (rs.object_types)
      -- Метки нужны только ветви меток, и лежат они там, где велит ТИП: у чужого
      -- ресурса — в зеркале, у собственного объекта iam — в его таблице.
      -- Соединение ЛЕВОЕ на обеих осях, чтобы объект без меток не выпадал из
      -- ветвей якоря и имён: иначе отсутствие меток читалось бы как отсутствие
      -- права.
      {{labels_join}}
     WHERE b.status = 'ACTIVE'
       AND (b.expires_at IS NULL OR b.expires_at > now())
       AND b.revoked_at IS NULL
       AND ({{arm_predicate}})
`

// grantArmPredicate — три ветви правила ОДНИМ предикатом.
//
// РАЗДЕЛЯТЬ ИХ НА ДВА ЗАПРОШЕННЫХ АРМА НЕЛЬЗЯ, и это измерено, а не выведено.
// Соблазн понятен: отдельная меточная ветвь сделала бы признак наблюдения
// детерминированным. Но внешний предел вычерпывает КАЖДУЮ ветвь союза до своего
// числа независимо от того, что отдали предыдущие, — значит вторая ветвь
// оплачивается на ВСЯКОМ вопросе. Замер при трёхстах основаниях: 89 строк за
// вердикт становятся 929 при меточной ветви впереди и 10032 по оси B при ней же
// позади. То есть цена наблюдаемости здесь — сама константа, ради которой
// стадия и делается.
//
// ФУНКЦИЯ, А НЕ КОНСТАНТА, и это не оформление. Ветвь имён сравнивает
// идентификатор объекта, а он назван по-разному у двух форм вопроса: у прямого
// — параметром запроса, у страничного — колонкой внешней стороны соединения
// вбок. Написать предикат дважды значило бы завести два места, знающие, что
// такое «выдача достаёт до объекта», и разойтись им молча — в сторону лишнего
// доступа. Текст остаётся ОДИН, различается только подставленное выражение.
func grantArmPredicate(objectIDExpr string) string {
	return `rs.arm = 'anchor'
          OR (rs.arm = 'names'  AND ` + objectIDExpr + ` = ANY (rs.resource_names))
          OR (rs.arm = 'labels' AND m.labels IS NOT NULL
                                AND m.labels @> rs.match_labels)`
}

// factArmSQL — ТЕЛО ВЕТВИ ПРЯМЫХ ФАКТОВ, единственное в дереве.
//
// Стоит в двух запросах — прямом вопросе и страничном — и различается ровно
// соединением с областями: прямой вопрос спрашивает про один объект, страничный
// обязан сузить области ТЕМ объектом, о котором идёт строка. Довод тот же, что у
// ветви выдач: скопировать текст значило бы завести два места об одном предмете.
const factArmSQL = `
    -- (1) прямой факт. Условие берётся С САМОЙ ЗАПИСИ: она самоописательна, и
    -- читателю не нужно знать модель, чтобы соблюсти ограничение.
    --
    -- Отбор различных стоит ВНУТРИ этой ветви, а не над союзом: здесь он
    -- обязателен (один и тот же условный источник приходит по нескольким
    -- говорящим и нескольким областям), а над союзом он блокировал бы и ветвь
    -- выдач, у которой дублирования нет — все её строки безусловны и
    -- неразличимы, поэтому читателю довольно первой.
    SELECT DISTINCT f.condition_name AS cond_name, f.condition_params AS cond_params,
           ''::text AS arm
      FROM kacho_iam.relation_fact f
      JOIN speaker sp ON sp.subject = f.subject
      {{scope_join}}
      JOIN fact_atom fa
        ON fa.relation = f.relation
       AND CASE WHEN fa.parent_type = ''
                THEN sc.depth = 0
                ELSE fa.parent_type = sc.s_type
           END
`

// Соединения ветвей с областями. Четыре текста, по одному на пару
// «ветвь × форма вопроса»: у прямого вопроса область объекта одна на весь
// запрос, у страничного она принадлежит СТРОКЕ и обязана быть сужена по ней —
// иначе выдача, достающая до одного объекта страницы, разрешила бы всю страницу.
const (
	scopeJoinMark = "{{scope_join}}"

	scopeJoinGrantOne  = "CROSS JOIN scope_distinct sc"
	scopeJoinGrantMany = "JOIN scope_distinct sc ON sc.object_id = o.object_id"

	scopeJoinFactOne  = "JOIN scope_distinct sc ON sc.s_type = f.object_type AND sc.s_id = f.object_id"
	scopeJoinFactMany = "JOIN scope_distinct sc ON sc.object_id = o.object_id\n" +
		"       AND sc.s_type = f.object_type AND sc.s_id = f.object_id"
)

// armsFor собирает обе ветви под ОДНУ форму вопроса.
//
// Одна функция на обе формы, потому что перепутать их местами — это не опечатка,
// а расширение доступа: ветвь, соединённая с областями без сужения по строке,
// отвечает «да» о каждом объекте страницы, до которого достаёт выдача на любой
// один из них.
func armsFor(objectIDExpr, scopeJoinGrant, scopeJoinFact string) (grant, fact string) {
	grant = strings.Replace(grantArmSQL, "{{arm_predicate}}", grantArmPredicate(objectIDExpr), 1)
	grant = strings.Replace(grant, scopeJoinMark, scopeJoinGrant, 1)
	fact = strings.Replace(factArmSQL, scopeJoinMark, scopeJoinFact, 1)
	return grant, fact
}

func verdictQuerySQL(labelTable string) string {
	grant, fact := armsFor("$3::text", scopeJoinGrantOne, scopeJoinFactOne)
	sql := strings.Replace(verdictSQL, "{{grant_arm}}", grant, 1)
	sql = strings.Replace(sql, "{{fact_arm}}", fact, 1)
	return strings.ReplaceAll(sql, labelsJoinMark,
		labelsJoinPinned(labelTable, "$9", "$3"))
}

func Ask(ctx context.Context, q pgx.Tx, in Query) (Verdict, Grounds, error) {
	var g Grounds
	if in.Subject == "" || in.ObjectType == "" || in.ObjectID == "" || in.Relation == "" {
		return Unknown, g, fmt.Errorf("relverdict: неполный вопрос %+v — пустая часть делает "+
			"ответ бессмысленным, и отдавать за него Deny значит выдавать незнание за отказ", in)
	}
	factParents, factRelations, bindVerbs, err := sourcesOf(in.ObjectType, in.Relation)
	if err != nil {
		// Тип, не объявленный моделью, — ОТКАЗ, а не ошибка. Разница в том, что
		// именно мы утверждаем: «объектов такого типа не существует» — это ответ
		// на вопрос, а «я не смог построить план» — признание, что ответа нет.
		// Выдавать второе за первое запрещено (см. ветвь Unknown ниже), но и
		// отвечать ошибкой на первое неверно: вызывающий перестаёт отличать «нет
		// прав» от «сломалось», а снятый тип отвечает пятисоткой вместо «нет».
		if errors.Is(err, authzplan.ErrTypeNotDeclared) {
			g.TypeNotDeclared = true
			return Deny, g, nil
		}
		return Unknown, g, err
	}
	// Имя каталога читается ПЕРЕД выбором оси: ось выбирается по нему же
	// (kacho#2036), и второго чтения каталога ради неё не заводится.
	catalogType, err := catalogTypeName(ctx, q, in.ObjectType)
	if err != nil {
		return Unknown, g, err
	}

	labelTable, err := labelAxisOf(catalogType, in.ObjectType)
	if err != nil {
		return Unknown, g, err
	}
	g.LabelAxisTable = labelTable

	rows, err := q.Query(ctx, verdictQuerySQL(labelTable),
		in.Subject, in.ObjectType, in.ObjectID,
		factParents, factRelations, bindVerbs, MaxAncestorDepth, maxConditionRows,
		catalogType,
	)
	if err != nil {
		return Unknown, g, fmt.Errorf("relverdict: запрос: %w", err)
	}
	defer rows.Close()

	type source struct {
		name   string
		params map[string]any
	}
	var (
		sources  []source
		rowsRead int
	)
	// ЧИТАЕМ ДО ПЕРВОГО БЕЗУСЛОВНОГО ОСНОВАНИЯ И ОСТАНАВЛИВАЕМСЯ.
	//
	// Прежде цикл вычитывал курсор ДО КОНЦА и лишь потом искал основание — то
	// есть даже полностью ленивый запрос платил бы за весь набор. Ветвь выдач
	// идёт в запросе первой и вся безусловна, поэтому на самом частом вопросе
	// («право выдано ролью») ответ находится первой же строкой.
	for rows.Next() {
		var (
			s   source
			arm string
		)
		if err := rows.Scan(&s.name, &s.params, &arm); err != nil {
			return Unknown, g, fmt.Errorf("relverdict: разбор источника: %w", err)
		}
		rowsRead++
		if arm == "labels" {
			g.LabelArm = true
		}
		if s.name == "" {
			// Безусловное основание. Набор дочитывать НЕ НУЖНО и не нужно было
			// никогда: остальные источники ответа не меняют.
			rows.Close()
			if err := rows.Err(); err != nil {
				return Unknown, g, fmt.Errorf("relverdict: чтение источников: %w", err)
			}
			return Allow, g, nil
		}
		sources = append(sources, s)
	}
	if err := rows.Err(); err != nil {
		return Unknown, g, fmt.Errorf("relverdict: чтение источников: %w", err)
	}
	g.SetExhausted = true

	// УСЕЧЕНИЕ ОПРЕДЕЛЯЕТСЯ ПРИЧИНОЙ ОСТАНОВКИ, А НЕ ДЛИНОЙ СРЕЗА.
	//
	// Длина среза остановку не различает: перестали читать на пятой строке —
	// срез короткий, и «набор усечён» стало бы неотличимо от «мы перестали
	// читать». Здесь остановка по найденному основанию уже вернула ответ выше,
	// а сюда доходит только исчерпанный курсор; значит достигнутый предел — это
	// и есть усечение, и ничто другое.
	//
	// Считаются ПРОЧИТАННЫЕ строки, и это то же самое, что различные условия:
	// ветвь фактов несёт свой отбор различных, а ветвь выдач до этого места не
	// доходит вовсе — её первая же строка безусловна. Порог не сдвинулся.
	if rowsRead >= maxConditionRows {
		// Усечение — не отказ. См. maxConditionRows.
		return Unknown, g, fmt.Errorf("relverdict: различных условий на вопрос %d и более — "+
			"набор усечён, и вердикт по нему давать нельзя", maxConditionRows)
	}

	// Сюда доходят ТОЛЬКО условные источники: безусловное основание вернуло бы
	// ответ ещё в цикле чтения. Порядок здесь ни на что не влияет — каждый
	// источник спрашивается, пока один из них не разрешит.
	var notUnderstood error
	for _, s := range sources {
		if s.name == "" {
			return Allow, g, nil
		}
		ok, err := evalCondition(s.name, s.params, in.Context)
		if err != nil {
			// Не понято — запоминаем, но продолжаем: другой источник может дать
			// право безусловно, и тогда незнание про этот ничего не меняет.
			notUnderstood = err
			continue
		}
		if ok {
			return Allow, g, nil
		}
	}
	if notUnderstood != nil {
		return Unknown, g, notUnderstood
	}
	return Deny, g, nil
}

