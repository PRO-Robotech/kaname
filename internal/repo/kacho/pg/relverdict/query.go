// Package relverdict — вердикт о доступе запросом к собственному Postgres iam.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЭТО ОТВЕЧАЕТ
//
// Один вопрос: «может ли ЭТОТ субъект сделать ЭТОТ глагол над ЭТИМ объектом».
// Ответ складывается из четырёх источников, и все четыре живут в схеме iam:
//
//  1. ПРЯМОЙ ФАКТ — владение, поставленное при создании, иерархический
//     указатель, подстановочный субъект (`relation_fact`) — на самом объекте
//     ЛИБО на его предке, если так велит модель;
//  2. ВЫДАЧА РОЛИ на область — сама область объекта либо любой его предок
//     (`access_bindings` × `role_verb`, цепь из `resource_parent_edge`);
//  3. ВЫДАЧА ПО МЕТКАМ — то же, плюс совпадение меток объекта с селектором
//     (`access_binding_selector` × `resource_mirror.labels`);
//  4. ЧЛЕНСТВО В ГРУППЕ — субъектом выдачи бывает группа (`group_members`).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЗАПРОС, А НЕ МАТЕРИАЛИЗАЦИЯ
//
// Материализовать — значит хранить произведение «субъекты × объекты». Выдача по
// меткам делает это произведение комбинаторным по числу ключей меток, а СМЕНА
// ОДНОЙ МЕТКИ заставляет пересчитывать доступ для всех субъектов с меточными
// выдачами. Здесь ничего не хранится: предикат проверяется для ТОГО объекта, о
// котором спросили, поэтому смена метки — один UPDATE, а не пересчёт.
//
// ─────────────────────────────────────────────────────────────────────────────
// ВЫВОД ОТНОШЕНИЙ БЕРЁТСЯ ИЗ МОДЕЛИ, А НЕ ИЗ ИМЕНИ
//
// Модель выводит право: право читателя следует из права редактора, право
// редактора — из права администратора, право администратора аккаунта
// распространяется на всё внутри аккаунта. Форма, ищущая имя отношения
// БУКВАЛЬНО, ответила бы «нет» держателю права, которое модель ему даёт, — и это
// не оттенок, а отказ. Поэтому вопрос сначала компилируется в набор источников
// (`authzplan.Plan`), и запрос спрашивает про КАЖДЫЙ из них: где искать факт
// (на объекте или на предке названного типа) и какие глаголы засчитывать у роли.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЭТОТ ЗАПРОС И ЕСТЬ РЕШЕНИЕ
//
// Здесь стояла граница фазы: «отвечает по-прежнему движок, запрос спрашивается
// рядом и только сравнивается, поэтому его ошибка не может дать лишний доступ».
// Фаза кончилась стадией S6 эпика #747 — внешний движок снят, второй формы нет,
// и запасного ответа за этим запросом больше не стоит.
//
// Следствие названо прямо, потому что оно меняет цену ошибки: ошибка ЗДЕСЬ теперь
// и есть ошибка вердикта. Отсюда же строгость соседних правил — неопределённый
// исход отвечает ОШИБКОЙ, а не отказом (`Unknown` ниже, `Ask` в конце файла): при
// сравнении это была разница между расхождением и согласием, теперь это разница
// между «сервис недоступен» и «доступа нет».
//
// # ВЫВОД ПРИМЕНЯЮТ ВСЕ ЧЕТЫРЕ ВОПРОСА, И ОДНОЙ РАСКЛАДКОЙ
//
// `Ask` (можно ли), `List` (что мне доступно), `Subjects` (кто имеет право) и
// `Expand` (из чего оно складывается) раскладываются ОДНОЙ функцией — `sourcesOf`
// ниже, — и потому не могут разойтись в том, что считают источником права.
// Отличается только направление обхода: прямой вопрос идёт от объекта к
// источникам, обратные — от источника к объектам и субъектам.
//
// Здесь стояло обратное: «обратные вопросы вывода не применяют». Это было верно
// в день, когда писалось, и пережило свой предмет — а утверждение, пережившее
// предмет, опаснее отсутствующего: оно читается как действующее ограничение и
// заводит работу, которой не требуется, либо оправдывает ответ, который уже не
// обязан быть неполным. Держит новое утверждение не эта шапка, а
// `derivation_reverse_integration_test.go`:
// `TestList_CloudAdministratorSeesWhatTheModelDerives`,
// `TestSubjects_CloudAdministratorIsAmongTheSubjects`,
// `TestExpand_NamesTheDerivedGroundAndWhereItLies` и сверка трёх форм между собой
// (`TestReverseAndDirectAnswersAgreeOnTheSameState`). Способность этих проб
// упасть проверена инъекцией, а не прочтением: на состоянии «искать имя
// буквально» СЕМЬ проб файла дают 21 упавшее утверждение, тогда как остальные 22
// пробы пакета остаются зелёными — то есть инъекция различает вывод, а не всё
// подряд.
//
// # ЧТО ОБРАТНЫЕ ВОПРОСЫ НЕ ДЕЛАЮТ (граница, названная явно)
//
// Условие на записи они НЕ вычисляют: у них нет доводов запроса — вопрос «кто
// имеет право» задают не от чьего-то имени и не в чью-то сессию. Поэтому право,
// действующее лишь при выполненном условии, они называют, а не скрывают, и
// `Expand` печатает имя условия рядом с отношением. Отсюда следует граница: их
// ответ — СПРАВКА, решение о доступе принимает `Ask`, который условие вычисляет и
// на невычислимом отвечает «не знаю».
//
// Условие на кортеже (свежесть подтверждения личности) вычисляется ЗДЕСЬ, по
// доводам, приезжающим с вопросом: оно зависит от «сейчас» и не материализуемо
// ни в какой форме. Условие лежит на самой записи факта, поэтому запросу не надо
// знать модель, чтобы его соблюсти, — см. `condition.go`. Условие, которого эта
// форма не умеет вычислять, даёт «не знаю», а не «нет»: молчаливое «нет» слилось
// бы с честным отказом.
