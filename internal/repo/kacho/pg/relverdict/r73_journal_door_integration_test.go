package relverdict_test

// r73_journal_door_integration_test.go — гейт Г7 приёмки R7-3 (стадия S6):
// ЖУРНАЛ НАМЕРЕНИЙ И ЕГО ТРИГГЕР ПЕРЕЖИЛИ СНЯТИЕ ДРЕНАЖА.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗАЩИЩАЕТСЯ И ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ ПРОБА
//
// Команда «снять движок вместе с его очередью», выполненная буквально, обесточила
// бы источник собственного вердикта — и обесточила бы ТИХО: таблица осталась бы на
// месте, запросы продолжили бы исполняться, а ответы поехали бы в сторону отказа.
//
// Причина в том, что у таблицы прямых фактов НЕТ НИ ОДНОГО ПИСАТЕЛЯ ИЗ КОДА: её
// наполняет триггер на журнале намерений (`kacho_iam.fga_outbox`, миграция 0098).
// Снят потребитель журнала (дренаж) и адресат (движок) — сам журнал остался, и
// решение Р7 приёмки требует утвердить это ИСХОДОМ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ УТВЕРЖДАЕТСЯ ОТВЕТ, А НЕ НАЛИЧИЕ СТРОКИ
//
// «В таблице есть строка» — свойство схемы; его сохраняет и обесточенный тракт.
// Спрашивается то, ради чего тракт существует: ОТВЕТ НА ВОПРОС О ДОСТУПЕ после
// мутации. Тогда снятие триггера, снятие журнала, поломка проекции и расхождение
// словарей имён краснеют ОДИНАКОВО — на исходе, а не каждое своим признаком,
// который надо было предугадать.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕМ ПИШЕТСЯ НАМЕРЕНИЕ
//
// ПРОДУКТОВЫМ писателем (`pg.NewCreatorTupleWriter` и `pg.NewFGAOutboxEmitter`), а
// не сырым INSERT'ом. Проба, кладущая строку своим SQL, осталась бы зелёной, если
// продуктовый путь эмиссии сломан или снят, — то есть проверяла бы схему, а не
// тракт.
//
// ─────────────────────────────────────────────────────────────────────────────
// ОТРИЦАНИЕ СТОИТ В ПАРЕ С ПОЛОЖИТЕЛЬНЫМ
//
// Сначала утверждается, что до намерения ответ «нет» (иначе «да» после намерения
// не значило бы ничего: он мог быть «да» всегда), потом — что после намерения
// «да», потом — что после снятия снова «нет».

import (
	"context"
	"testing"

	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/PRO-Robotech/kacho-iam/internal/clients"
	kachopg "github.com/PRO-Robotech/kacho-iam/internal/repo/kacho/pg"
	"github.com/PRO-Robotech/kacho-iam/internal/repo/kacho/pg/relverdict"
	"github.com/PRO-Robotech/kacho-iam/internal/service"
	"github.com/PRO-Robotech/kacho/pkg/pgtest"
)

// TestR7_3_27_JournalSurvivesTheDrainRemoval — Г7.
func TestR7_3_27_JournalSurvivesTheDrainRemoval(t *testing.T) {
	ctx := context.Background()
	pool, err := pgxpool.New(ctx, pgtest.NewDB(t))
	if err != nil {
		t.Fatalf("пул: %v", err)
	}
	pgtest.ClosePoolAtEnd(t, pool)

	const (
		subject    = "user:usr_r73journaldoor"
		objectType = "cluster"
		objectID   = "cluster_kacho_root"
		relation   = "system_admin"
	)
	object := objectType + ":" + objectID

	asker := relverdict.NewAsker(pool)
	if asker == nil {
		t.Fatal("форма не собрана — спрашивать нечем")
	}

	ask := func(stage string) bool {
		t.Helper()
		allowed, aerr := asker.Allowed(ctx, subject, objectType, objectID, relation, nil)
		if aerr != nil {
			// Ошибка — НЕ «доступа нет». Слить их значило бы читать недоступность
			// базы как законный отказ, и проба зеленела бы на сломанной форме.
			t.Fatalf("%s: форма не ответила: %v", stage, aerr)
		}
		return allowed
	}

	// ── Положительный контроль: до намерения права нет ────────────────────────
	//
	// Без него «да» на следующем шаге не утверждает ничего: оно могло быть «да»
	// всегда, и тракт журнала не проверялся бы вовсе.
	if ask("до намерения") {
		t.Fatal("форма отвечает «доступ есть» ДО того, как намерение записано — " +
			"положительный контроль провален: дальнейшее «да» ничего не докажет")
	}

	// ── Мутация выдачи: строка намерения продуктовым писателем ────────────────
	writer := kachopg.NewCreatorTupleWriter(pool)
	if writer == nil {
		t.Fatal("продуктовый писатель намерений не собран")
	}
	if werr := writer.RecordTuples(ctx, []clients.RelationTuple{{
		User: subject, Relation: relation, Object: object,
	}}); werr != nil {
		t.Fatalf("запись намерения продуктовым писателем: %v", werr)
	}

	if !ask("после намерения") {
		t.Fatal("НАМЕРЕНИЕ ЗАПИСАНО, А ДОСТУПА НЕТ.\n" +
			"Источник вердикта обесточен: прямой факт складывается из строки журнала " +
			"`kacho_iam.fga_outbox` ТРИГГЕРОМ (миграция 0098), и другого писателя у него " +
			"нет. Снятие журнала либо его триггера вместе с дренажом движка выглядит " +
			"безобидно — таблица на месте, запросы исполняются, — а ответы едут в сторону " +
			"отказа МОЛЧА. Решение Р7 приёмки R7-3: снимается потребитель журнала, а не журнал")
	}

	// ── Отзыв: намерение снятия тем же продуктовым путём ──────────────────────
	tx, err := pool.Begin(ctx)
	if err != nil {
		t.Fatalf("транзакция отзыва: %v", err)
	}
	if eerr := kachopg.NewFGAOutboxEmitter().EmitDeleteTx(ctx, tx, []service.RelationTuple{{
		User: subject, Relation: relation, Object: object,
	}}); eerr != nil {
		_ = tx.Rollback(ctx)
		t.Fatalf("эмиссия намерения снятия: %v", eerr)
	}
	if cerr := tx.Commit(ctx); cerr != nil {
		t.Fatalf("коммит отзыва: %v", cerr)
	}

	if ask("после отзыва") {
		t.Fatal("ОТЗЫВ ЗАПИСАН, А ДОСТУП ОСТАЛСЯ.\n" +
			"Проекция журнала перестала снимать прямой факт — то есть отзыв не действует " +
			"с коммита, а это и есть свойство, ради которого снимался внешний движок")
	}
}
