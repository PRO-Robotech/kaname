// matrixReportAbsPath — абсолютный путь отчёта, разрешённый от КОРНЯ дерева.
//
// Корень спрашивается у git, а не собирается из `..`: рабочая копия может быть
// где угодно, и относительный путь уехал бы мимо дерева молча. Команда идёт
// через `pkg/gitenv` — прямой вызов git унаследовал бы `GIT_DIR` и увёл бы
// вопрос в чужой репозиторий.
func matrixReportAbsPath() (string, error) {
	out, err := gitenv.Command("", "rev-parse", "--show-toplevel").Output()
	if err != nil {
		return "", fmt.Errorf("корень дерева не установлен, писать отчёт некуда: %w", err)
	}
	return strings.TrimSpace(string(out)) + "/" + matrixReportPath, nil
}

// humanBytes — байты в читаемом виде. Само число печатается рядом: округление
// удобно читать, но сверять по нему нельзя.
func humanBytes(b int64) string {
	switch {
	case b >= 1<<30:
		return fmt.Sprintf("%.2f ГиБ", float64(b)/float64(int64(1)<<30))
	case b >= 1<<20:
		return fmt.Sprintf("%.1f МиБ", float64(b)/float64(int64(1)<<20))
	case b >= 1<<10:
		return fmt.Sprintf("%.1f КиБ", float64(b)/float64(int64(1)<<10))
	default:
		return fmt.Sprintf("%d Б", b)
	}
}

// ratioOf — отношение верхней величины к нижней. Ноль в знаменателе даёт ноль:
// «во столько-то раз» от нуля не считается, и печатать там бесконечность
// значило бы выдать отсутствие основания за результат.
func ratioOf(hi, lo int64) float64 {
	if lo == 0 {
		return 0
	}
	return float64(hi) / float64(lo)
}

// growthVerdict — ответ на главный вопрос ОДНОЙ строкой, по несущей величине.
//
// Порог назван ДО прогона и здесь же: до двух — «не растёт» (дребезг плана и
// смена способа доступа дают такой разброс без всякой деградации); до
// логарифма от кратности объёма — «логарифмически»; дальше — «линейно или
// хуже». Порог, подобранный ПОСЛЕ прогона, описывал бы полученное число, а не
// свойство запроса.
func growthVerdict(hi, lo int64, volumeFactor float64) string {
	switch {
	case lo == 0:
		return "не установлено (нижняя точка дала ноль — делить не на что)"
	case ratioOf(hi, lo) <= matrixFlatCeiling:
		return "НЕ РАСТЁТ (плоско)"
	case ratioOf(hi, lo) <= logCeiling(volumeFactor):
		return "растёт ЛОГАРИФМИЧЕСКИ"
	default:
		return "растёт ЛИНЕЙНО или хуже"
	}
}

// matrixFlatCeiling — во сколько раз несущая величина вправе вырасти, чтобы
// это ещё считалось «не растёт».
//
// Два — тот же запас, что у соседних приборов этого дерева. Деградация этого
// класса даёт ПОРЯДКИ, а не проценты, и двойка отделяет её от дребезга с
// огромным запасом.
const matrixFlatCeiling = 2.0

// logCeiling — потолок логарифмического роста при данной кратности объёма.
//
// Кратность объёма между нижней и верхней точкой равна 1000; логарифм по
// основанию 2 от неё ≈ 10. Множитель 1.5 — тот же запас на дребезг.
func logCeiling(volumeFactor float64) float64 {
	if volumeFactor <= 1 {
		return matrixFlatCeiling
	}
	l := 1.0
	for v := volumeFactor; v > 1; v /= 2 {
		l++
	}
	return l * 1.5
}

