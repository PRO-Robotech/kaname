// Package membership — CQRS port-iface для kacho_iam.memberships.
//
// Writer-половины у порта НЕТ, и это решение, а не пропуск: на читающей
// поверхности членства глаголов изменения не существует. Строку заводит
// приглашение, снимает исключение из аккаунта, и оба живут в потоке человека.
package membership

import (
	"context"
	"time"

	"github.com/PRO-Robotech/kacho-iam/internal/domain"
)

// Repo — УЗКИЙ корень чтения членства, и узость эта выбрана замером, а не вкусом.
//
// Соседние ресурсы этого сервиса достаются через ОБЩИЙ корень `kacho.Reader`,
// перечисляющий все ресурсные читатели разом. Добавить туда членство значило бы
// потребовать нового метода от КАЖДОГО, кто этот интерфейс реализует, — а это
// 46 дублёров в 25 файлах проб СОСЕДНИХ ресурсов, к предмету членства отношения
// не имеющих. Замер сделан прогоном: `go vet ./services/iam/...` после такой
// правки печатает ровно эти 46 отказов.
//
// Поэтому здесь объявлен узкий порт: use-case зависит от того, что ему нужно, а
// не от перечня всего сервиса. Цена названа честно и она одна — второе место,
// открывающее чтение (`Repository.MembershipReader` рядом с `Repository.Reader`),
// четыре строки. Обратная сторона выбрана потому, что она дешевле и не заставляет
// править чужие пробы ради своего предмета.
type Repo interface {
	// MembershipReader открывает чтение. Вызывающий обязан позвать Close ровно
	// один раз — соединение возвращается в пул им.
	MembershipReader(ctx context.Context) (Session, error)
}

// Session — открытое чтение членств.
type Session interface {
	Memberships() ReaderIface
	// Close возвращает соединение в пул. Отдельного Commit нет: чтение ничего не
	// меняет, и предлагать вызывающему выбор между двумя завершениями значило бы
	// заводить решение, которого у него нет.
	Close(ctx context.Context)
}

// ReaderIface — оба чтения СУЖЕНЫ ПО АККАУНТУ, и аккаунт приходит ОТДЕЛЬНЫМ
// обязательным параметром, а не полем фильтра.
//
// Так — потому что сужение обязано быть свойством СИГНАТУРЫ, а не дисциплины
// вызывающего: поле фильтра можно не заполнить, обязательный параметр не
// заполнить нельзя. Оба запроса называют аккаунт в УСЛОВИИ ОТБОРА, поэтому
// строк других аккаунтов они не читают вовсе — и различию неоткуда взяться ни
// в теле ответа, ни во времени его получения.
type ReaderIface interface {
	// Get — членство НАЗВАННОГО аккаунта по идентификатору.
	//
	// Аккаунт стоит в WHERE, а не в проверке после чтения. Поэтому well-formed
	// идентификатор членства ЧУЖОГО аккаунта неотличим от несуществующего: обе
	// строки дают `ErrNotFound` — не потому, что вызывающий проверен и отвергнут,
	// а потому, что запрос их не выбирает by construction.
	Get(ctx context.Context, accountID domain.AccountID, id domain.MembershipID) (domain.Membership, error)

	// List — страница членств названного аккаунта плюс токен продолжения.
	//
	// Порядок — курсорный `(created_at, id)`, и он же порядок объявленного
	// индекса. Перечень объявлен НАБОРОМ: вызывающий сверяет состав, а не
	// индексы.
	List(ctx context.Context, f ListFilter) ([]domain.Membership, string, error)
}

// ListFilter — вход списочного чтения.
type ListFilter struct {
	// AccountID — ОБЯЗАТЕЛЕН. Пустое значение запросом не обслуживается: оно
	// означало бы «все аккаунты», то есть ровно тот межаккаунтный перечень,
	// которого на этой поверхности не бывает.
	AccountID domain.AccountID
	// Filter — ровно один терм из белого списка (`userId`), оператор — только
	// равенство. Разбор грамматики знает и подстрочный поиск; здесь он
	// ОТВЕРГАЕТСЯ явно, а не сводится молча к равенству.
	Filter string
	// PageSize — уже проверенный размер страницы; 0 означает умолчание.
	PageSize int32
	// PageToken — непрозрачный курсор.
	PageToken string
	// After — разобранный курсор. Задаётся путём, который токена не передаёт;
	// имеет приоритет над PageToken.
	After *Cursor
}

// Cursor — разобранная граница страницы.
type Cursor struct {
	CreatedAt time.Time
	ID        string
}
