package pg_test

// owner_tier_on_type_test.go — какой ЯРУС выдача с подстановкой `*` материализует
// на объекте данного типа.
//
// # Зачем помощник, а не литерал в каждой пробе
//
// Ярус выводится из РАЗВЁРНУТЫХ глаголов правила: удаление даёт администратора,
// правка — редактора, чтение — наблюдателя. Подстановку разворачивает набор ТИПА,
// поэтому ярус — свойство типа, а не константа платформы.
//
// Пока все глагольные типы объявляли один набор, ярус выдачи `*.*` был `admin`
// у каждого, и пробы писали его ЛИТЕРАЛОМ — верно по совпадению. С типом, у
// которого распоряжающихся глаголов не осталось (`iam_user`: `v_update` снят
// #1128, `v_delete` — #1189), совпадение кончилось: владелец получает там
// `viewer`, и литерал `"admin"` стал утверждать о типе то, чего материализация не
// делает.
//
// Помощник спрашивает ТОТ ЖЕ предикат, что материализация. Второе место, знающее
// соответствие «глаголы → ярус», разошлось бы с первым молча.

import (
	"github.com/PRO-Robotech/kaname/internal/authzmap"
	"github.com/PRO-Robotech/kaname/internal/domain"
)

// ownerTierOn — ярус, который правило с подстановкой `*` (форма роли владельца)
// материализует на объекте типа `fgaType`.
func ownerTierOn(fgaType string) string {
	_, tier := domain.ResolveVerbsAndTier([]string{"*"}, authzmap.VerbsOfType(fgaType))
	return tier
}
