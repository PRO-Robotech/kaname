package pg

import (
	"context"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"
)

// SharedClock — источник моментов, сравниваемых с отсечкой отзыва-всех, ОДИН на
// все реплики службы (задача kaname#589): часы первичной базы.
//
// Почему база, а не часы процесса. Реплик службы больше одной, и у каждой свои
// часы процесса; момент, поставленный одной, сравнивался бы с отсечкой,
// поставленной другой, и граница правила была бы их расхождением. Первичная
// база одна на все реплики. Её же часами (`now()`) отсечку ставят схемные
// писатели — триггеры снятия клиента и деактивации владельца (миграция
// `20261003202945`), — и любой иной общий источник оставил бы их вторым.
//
// Пул — ПИШУЩИЙ: реплика чтения — другой хост с другими часами, и источник снова
// раздвоился бы. Вызов идёт ДО открытия транзакции вызывающего: чтение из пула
// изнутри открытой транзакции брало бы второе соединение на запрос, и под
// исчерпанием пула запросы ждали бы друг друга.
//
// Остаток назван: после смены первичной базы источник — часы новой первичной, и
// расхождение её часов со старой — расхождение синхронизации времени хостов базы,
// одно на все сравнения.
type SharedClock struct {
	pool *pgxpool.Pool
}

// NewSharedClock — построитель. Пул обязан быть пишущим (см. [SharedClock]).
func NewSharedClock(pool *pgxpool.Pool) *SharedClock {
	return &SharedClock{pool: pool}
}

// Now — момент первичной базы. `now()` вне транзакции — момент оператора, тот же
// вид момента, что ставят схемные писатели отсечки внутри своей.
//
// Ошибка возвращается как есть: в текст отказа наружу она не идёт, класс для
// журнала выделяет вызывающий (`revocationpolicy.MomentFailureClass`).
func (c *SharedClock) Now(ctx context.Context) (time.Time, error) {
	var at time.Time
	if err := c.pool.QueryRow(ctx, `SELECT now()`).Scan(&at); err != nil {
		return time.Time{}, err
	}
	return at.UTC(), nil
}
