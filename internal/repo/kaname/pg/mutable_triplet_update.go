// mutable_triplet_update.go — аргументы статического оператора записи ресурса,
// у которого изменяемых полей ровно ТРИ: `name`, `description`, `labels`
// (задача продукта #2065; тот же приём, что #2058 применила к роли и служебной
// учётке).
//
// # Почему оператор статический
//
// Прежде список `SET` собирался из маски форматированием строки: какие колонки
// пишет оператор, решалось во время исполнения и не проверялось ни типами, ни
// компилятором. Значения связывались параметрами и тогда — вопрос НЕ в
// безопасности запроса, а в том, что ошибка набора колонок не видна ни сборке,
// ни обзору диффа, а видна только прогону, дошедшему до этой ветви маски.
// Соседний оператор того же пакета уже был неисполним при ЛЮБОМ входе из-за
// колонки, которой не было в схеме, — и заметили это не типы, а падение.
//
// Применимость поля переехала из ТЕКСТА оператора в его ПАРАМЕТР: каждой
// изменяемой колонке отвечает пара «признак применимости + значение», и колонка,
// которую маска не назвала, переписывается сама в себя. Наблюдаемо это
// тождественно прежнему поведению — писалось ровно то же значение, — а разница в
// том, что перечень колонок теперь один и он в коде.
//
// # Почему помощник ОБЩИЙ на три ресурса, и где проходит его граница
//
// Аккаунт, группа и проект несли три ПОБАЙТОВО одинаковых сборщика: тот же набор
// изменяемых полей, тот же порядок, тот же текст отказа. Три копии одного
// предмета расходятся молча — правка доезжает не всюду, и разницу читают как
// другое место продукта.
//
// Унификация взята по САМОЙ УЗКОЙ семантике и границу объявляет сама: помощник
// знает ровно три поля. Ресурсу, у которого их станет четыре, он не подойдёт — и
// это будет ошибкой СБОРКИ у вызывающего, а не тихим расхождением. Текст
// оператора при этом остаётся у ресурса: таблица, перечень колонок `RETURNING` и
// сторожа `WHERE` — его собственные и общими быть не могут.
package pg

import (
	iamerr "github.com/PRO-Robotech/kaname/internal/errors"
)

// mutableTripletFields — изменяемые поля ресурса этой формы. Перечень объявлен
// ОДИН раз: он же решает, что принимает маска, и он же задаёт порядок
// подстановок в операторе.
var mutableTripletFields = map[string]bool{"name": true, "description": true, "labels": true}

// mutableTripletUpdateArgs — аргументы статического оператора в порядке
// подстановок, начиная с `$1`:
//
//	$1 id · $2/$3 name · $4/$5 description · $6/$7 labels
//
// Нечётные подстановки — ЗНАЧЕНИЕ, чётные (кроме `$1`) — ПРИЗНАК применимости.
// Оператор пишет колонку только там, где признак истинен, а иначе переписывает
// её саму в себя.
//
// changed=false означает «маска не назвала ни одного изменяемого поля»;
// вызывающий решает сам, исполнять ли оператор. Сегодня это состояние
// недостижимо (пустая маска применяет все три поля, непустая обязана назвать
// хотя бы одно известное), но исход у него был и остаётся прежним — вернуть
// текущую строку чтением, не выполняя записи.
//
// Неизвестное поле маски — `INVALID_ARGUMENT` с конвенционным текстом; он часть
// контракта и здесь не меняется.
func mutableTripletUpdateArgs(
	id, name, description string, labelsJSON []byte, mask []string,
) (args []any, changed bool, err error) {
	apply := map[string]bool{}
	if len(mask) == 0 {
		// Полная правка: применяются все изменяемые поля, неизменяемое из тела
		// вызывающий отфильтровал до записи.
		for k := range mutableTripletFields {
			apply[k] = true
		}
	} else {
		for _, f := range mask {
			if !mutableTripletFields[f] {
				return nil, false, iamerr.Wrapf(iamerr.ErrInvalidArg,
					"Illegal argument update_mask field %q", f)
			}
			apply[f] = true
		}
	}

	changed = apply["name"] || apply["description"] || apply["labels"]

	return []any{
		id,
		apply["name"], name,
		apply["description"], description,
		apply["labels"], labelsJSON,
	}, changed, nil
}

// mutableTripletSetSQL — список присваиваний, общий для ресурсов этой формы.
// Оператор целиком собирается у ресурса: имя таблицы, перечень колонок
// `RETURNING` и сторожа `WHERE` принадлежат ему.
//
// Приведения типов (`::boolean`, `::text`, `::jsonb`) обязательны: сервер выводит
// тип подстановки из контекста, а внутри `CASE` контекстом служит вторая ветвь —
// сама колонка. Явное приведение делает вывод независимым от порядка ветвей.
const mutableTripletSetSQL = `
	       name        = CASE WHEN $2::boolean THEN $3::text  ELSE name        END,
	       description = CASE WHEN $4::boolean THEN $5::text  ELSE description END,
	       labels      = CASE WHEN $6::boolean THEN $7::jsonb ELSE labels      END`
