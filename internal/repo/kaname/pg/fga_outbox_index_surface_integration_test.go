package pg_test

// fga_outbox_index_surface_integration_test.go — у журнала намерений нет индекса,
// которого никто не ищет.
//
// # Что здесь было раньше и почему его нет
//
// Файл назывался по двум миграциям (0067/0068) и закреплял ФОРМУ, от которой
// зависел клейм дренажа: колонку ключа упорядочивания `tuple_key`, частичный
// индекс `(tuple_key, id) WHERE sent_at IS NULL` под коррелированный NOT EXISTS
// и запрет на любой ТРЕТИЙ частичный индекс по `sent_at IS NULL` (приманка для
// планировщика под статистикой пустой очереди).
//
// Ни одного из этих предметов в дереве нет:
//
//   - дренаж снят вместе с внешним движком отношений (стадия S6 эпика #747,
//     `a4b6cfba9`) — клейма, чью форму закреплял файл, не существует;
//   - колонки доставки (`sent_at`, `attempt_count`, `last_error`) и ключ
//     `tuple_key` вместе с ЧЕТЫРЬМЯ частичными индексами сняты миграцией
//     20260822160000 (kacho#917);
//   - писатель ключа — триггер `BEFORE INSERT` — снят миграцией 20260823001000
//     (kacho#1033).
//
// Утверждения «колонка существует» и «частичных индексов ровно два» пережили свой
// предмет и стали утверждениями о несуществующем: они не могли стать зелёными ни
// при каком состоянии дерева. Сняты (kacho#1042).
//
// # Что от них ОСТАЛОСЬ живого — и ради чего файл не удалён целиком
//
// Обе снятые пробы несли, помимо формы клейма, одно утверждение ШИРЕ её: у
// журнала не бывает индекса, которого никто не ищет. Оно было выражено дважды и
// каждый раз узко — «нет индекса по `payload->>'object'` (0061 вытеснен 0067)» и
// «нет ТРЕТЬЕГО частичного индекса по `sent_at IS NULL`». Обе формулировки
// умерли вместе с колонкой; само свойство — нет.
//
// Оно и закрепляется здесь, в единственной форме, которая сегодня имеет смысл:
// кроме первичного ключа у таблицы нет ни одного индекса.
//
// # Почему это не уборка, а цена на пути мутации
//
// В журнал пишет КАЖДАЯ выдача и КАЖДЫЙ отзыв доступа, то есть каждая мутация
// прав арендатора. Индекс на такой таблице оплачивается на этом самом пути.
// Ищущих сегодня двое, и ни одному индекс не нужен:
//
//   - триггер свёртки прямого факта (миграция 0098) читает НОВУЮ строку в той же
//     транзакции, что её породила, — ему нечего искать;
//   - де-дуп загрузочного добора (`internal/apps/kaname/seed/migrate_backfill.go`)
//     идёт NOT EXISTS по полезной нагрузке ОДИН раз на старте и на пути запроса
//     не стоит.
//
// Отсюда правило, которое эта проба и держит: индекс на журнале заводится вместе
// с НАЗВАННЫМ читателем, а не «про запас». Появится читатель — проба покраснеет и
// потребует назвать его здесь; это и есть разговор, который иначе не случится.

import (
	"context"
	"testing"

	"github.com/stretchr/testify/require"

	coredb "github.com/PRO-Robotech/kacho/pkg/db"
)

// TestFGAOutbox_CarriesNoIndexWithoutAReader — перепись индексов журнала.
//
// Утверждение двустороннее: первичный ключ обязан быть на месте (иначе «индексов
// нет» было бы неотличимо от «таблицы нет» и от «запрос смотрит не туда»), а
// сверх него — ни одного.
func TestFGAOutbox_CarriesNoIndexWithoutAReader(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping integration test")
	}
	ctx := context.Background()
	dsn := setupTestDB(t)
	pool, err := coredb.NewPool(ctx, dsn)
	require.NoError(t, err)
	defer pool.Close()

	rows, err := pool.Query(ctx,
		`SELECT indexname, indexdef
		   FROM pg_indexes
		  WHERE schemaname = 'kaname' AND tablename = 'fga_outbox'
		  ORDER BY indexname`)
	require.NoError(t, err)
	defer rows.Close()

	names := make([]string, 0, 4)
	defs := make([]string, 0, 4)
	for rows.Next() {
		var name, def string
		require.NoError(t, rows.Scan(&name, &def))
		names = append(names, name)
		defs = append(defs, def)
	}
	require.NoError(t, rows.Err())

	// Объём осмотренного печатается всегда: «ноль лишних индексов» обязано быть
	// отличимо от «ничего не прочитано».
	t.Logf("осмотрено индексов на kaname.fga_outbox: %d — %v", len(defs), defs)

	// Положительный контроль. Без него проба зеленела бы на схеме, где журнала
	// нет вовсе, и на запросе, промахнувшемся мимо схемы или имени таблицы.
	require.Contains(t, names, "fga_outbox_pkey",
		"первичный ключ журнала не найден — значит эта проба смотрит не на ту таблицу, "+
			"и её отрицательная половина ничего не утверждает")

	require.Equalf(t, []string{"fga_outbox_pkey"}, names,
		"у kaname.fga_outbox есть индекс сверх первичного ключа. В журнал пишет каждая "+
			"выдача и каждый отзыв доступа, поэтому индекс здесь оплачивается на пути мутации "+
			"прав арендатора. Ни один сегодняшний читатель журнала его не ищет: триггер свёртки "+
			"прямого факта (0098) читает свою же строку в той же транзакции, де-дуп загрузочного "+
			"добора идёт по полезной нагрузке один раз на старте. Заводя индекс, назови читателя "+
			"здесь и в шапке файла — иначе это write amplification без спрашивающего, ровно то, "+
			"чем были четыре частичных индекса снятого дренажа. Перепись: %v", defs)
}
