package pg

// scope_anchor_tier_test.go — ярус на якоре, у которого СВОЕГО набора глаголов
// нет, не понижается от сужения набора у ЧУЖОГО типа.
//
// # Предмет (найдено при #1189)
//
// Ярус привязки выводится из РАЗВЁРНУТЫХ глаголов правила: `delete` даёт
// администратора, `update` — редактора, чтение — наблюдателя. Подстановку `*`
// разворачивает набор глаголов ЯКОРЯ, а у якоря-кластера собственного набора нет,
// и `scopeTypeVerbs` подставляет запасной.
//
// Запасным стоял ОБЩИЙ словарь — ПЕРЕСЕЧЕНИЕ наборов всех типов. Пересечение
// объявлено СУЖАЮЩИМСЯ по мере того, как наборы типов расходятся (это записано у
// самого поля каталога), поэтому «полным набором» оно не является и им быть не
// может. Пока расхождений не было, три величины совпадали — пересечение, набор
// типа и «все глаголы платформы», — и подмена не наблюдалась.
//
// Наблюдаться она начала при снятии второго глагола с `iam_user`: пересечение
// стало `[get list]`, и роль-суперпользователь (`*.*` на кластере) молча
// понизилась бы с АДМИНИСТРАТОРА до НАБЛЮДАТЕЛЯ. Ничего в дереве об этом бы не
// сказало: обе стороны по отдельности непротиворечивы, а ярус — производная
// величина, которую никто не пинил.
//
// # Что здесь утверждается
//
// Свойство, а не число: якорь без своего набора обязан разворачивать подстановку
// в набор, дающий ярус АДМИНИСТРАТОРА, — независимо от того, сколько типов и
// какие глаголы сняли у себя. Рядом два контроля: пересечение обязано быть УЖЕ
// запасного (иначе утверждение вакуумно — обе величины совпадали бы), и якорь СО
// СВОИМ набором продолжает разворачиваться в него, а не в запасной.

import (
	"testing"

	"github.com/PRO-Robotech/kaname/internal/authzmap"
	"github.com/PRO-Robotech/kaname/internal/domain"
	"github.com/PRO-Robotech/kaname/internal/testsupport/catalogfixture"
)

// TestScopeAnchorWithoutItsOwnVerbSet_StillResolvesToAdminTier — гейт на дереве.
func TestScopeAnchorWithoutItsOwnVerbSet_StillResolvesToAdminTier(t *testing.T) {
	// ПРЕДПОСЫЛКА: у якоря-кластера действительно нет своего набора. Иначе
	// запасной путь не исполняется, и всё утверждение ниже — про мёртвую ветку.
	if own := authzmap.VerbsOfType("cluster"); len(own) > 0 {
		t.Fatalf("у якоря `cluster` появился свой набор %v — запасной путь больше не "+
			"исполняется, и эта проба утверждает о ветке, которой нет", own)
	}

	fallback := scopeTypeVerbs(catalogfixture.Facts(), "cluster")
	if len(fallback) == 0 {
		t.Fatal("запасной набор пуст — подстановка `*` на якоре развернулась бы в ничто, " +
			"и роль-суперпользователь не дала бы даже чтения")
	}

	_, tier := domain.ResolveVerbsAndTier([]string{"*"}, fallback)
	if tier != "admin" {
		t.Errorf("подстановка `*` на якоре без своего набора дала ярус %q (набор %v), а обязана "+
			"дать `admin`: роль-суперпользователь (`*.*` на кластере) иначе молча понижается "+
			"до наблюдателя. Запасной набор обязан означать «все глаголы платформы», а не "+
			"пересечение наборов типов — пересечение СУЖАЕТСЯ, когда какой-нибудь тип снимает "+
			"у себя глагол, и к правам на кластере это отношения не имеет",
			tier, fallback)
	}

	// ── КОНТРОЛЬ 1: пересечение УЖЕ запасного ───────────────────────────────
	// Иначе утверждение выше зеленело бы и на прежней подмене: пока две величины
	// совпадают, отличить их нельзя.
	common := authzmap.CommonVerbVocabulary()
	if len(common) >= len(fallback) {
		t.Fatalf("общий словарь %v не уже запасного %v — наборы типов сошлись обратно, и "+
			"проба перестала отличать одно от другого", common, fallback)
	}

	// ── КОНТРОЛЬ 2: якорь СО СВОИМ набором берёт СВОЙ ───────────────────────
	// Иначе «запасной шире» читалось бы как «запасной берут всегда».
	own := authzmap.VerbsOfType("project")
	if len(own) == 0 {
		t.Fatal("у якоря `project` нет своего набора — контроль, ради которого он выбран, исчез")
	}
	got := scopeTypeVerbs(catalogfixture.Facts(), "project")
	if len(got) != len(own) {
		t.Errorf("якорь `project` развернулся в %v вместо своего набора %v — запасной путь "+
			"подменяет собственный", got, own)
	}

	t.Logf("перепись: свой набор `project`=%v; запасной для якоря без набора=%v; "+
		"общий словарь (пересечение)=%v; ярус подстановки на якоре=%q",
		own, fallback, common, tier)
}
