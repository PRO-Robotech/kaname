// subject_change_retention.go — УБОРКА журнала смены субъекта
// (`kaname.subject_change_outbox`, задача #1758).
//
// # Предмет
//
// Строка журнала пишется в той же транзакции, что снятие привязки и смена
// состава группы; читает её КРАЙ курсором по позиции. Снятия строк не было ни на
// одном пути: рост монотонный и вечный, темп задаёт арендатор.
//
// Уборка была небезопасна by construction, пока читатель не умел обнаружить
// пропуск: снятая строка в окно `id > since AND id <= settled` просто не
// попадает, курсор переезжает через неё, и «строк не было» становится
// неотличимо от «строки убрали» — то есть неприменённый отзыв доступа, молча.
// Предикат обнаружения заведён (#1712): пол берётся ПОСЛЕ страницы, курсор ниже
// пола получает явный отказ с возобновимой позицией. Здесь заводится вторая
// половина — сама уборка.
//
// # Петля, партии и наблюдаемость живут в `pkg/retention`
//
// Здесь — только ПРЕДИКАТ, потому что предикат есть свойство схемы ЭТОЙ таблицы:
// признака доставки у неё нет, читают её курсором по позиции, и порог выводится
// из наибольшего допустимого отставания читателя
// ([subjectchange.JournalRetention]), а не из того, что кем-то применено.
//
// # Почему СВОЙ оператор, а не уборщик журналов подписки
//
// Механизм подписки НЕ ПРИНИМАЕТ этот журнал, и это решение, а не объём работы
// (`pkg/subscription/doc.go`, §«НЕ принимает журнал смены субъекта»): предметы
// разные — тот поток отвечает арендатору «что стало с твоими ресурсами», этот
// отвечает слою авторизации «твои решения устарели», — отсюда противоположная
// модель доступа и отсутствие колонки вида предмета, которой требует объявление
// журнала подписки. Собрать уборщика из чужого объявления значило бы подменить
// предмет ради переиспользования.
//
// Что при этом ПЕРЕИСПОЛЬЗУЕТСЯ, а не переписывается: наблюдатель границы
// устоявшегося ([subscription.Watermark]) — он в дереве один, и второе
// наблюдение того же класса разошлось бы с первым молча.
//
// # Имя таблицы стоит ЛИТЕРАЛОМ намеренно
//
// Уборщик журналов подписки подставляет имя значением, и цена этого названа у
// него же: гейт роста (`internal/repohygiene` TestLiveTablesNameTheirGrowthLimit)
// такой оператор не резолвит и уносит его в свою слепую зону. Здесь владелец
// один, подставлять нечего, и литерал делает уборку ВИДИМОЙ гейту роста — то
// есть запись реестра о неограниченном росте истекает сама.
package pg

import (
	"context"
	"fmt"
	"log/slog"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/PRO-Robotech/kacho/pkg/subscription"
)

// subjectChangeSweepSQL — предикат уборки журнала смены субъекта.
//
// ЧЕТЫРЕ РЕШЕНИЯ, и первое несущее.
//
//  1. СНИМАЕТСЯ ПРЕФИКС, а не «все старые строки». Весь предикат обнаружения
//     пропуска у читателя держится инвариантом «выше пола дыр нет»: пол есть
//     «самая ранняя удержанная минус один», и читатель, чей курсор не ниже пола,
//     получает страницу как ПОЛНУЮ. Уборка «по возрасту» этот инвариант ломает:
//     отметка времени ставится в НАЧАЛЕ транзакции, а номер выдаётся на ВСТАВКЕ,
//     поэтому строка с бо́льшим номером бывает старше строки с меньшим. Оператор
//     снял бы верхнюю, оставив нижнюю, — пол не сдвинулся бы, а над ним появилась
//     бы дыра, и читатель, законно допущенный по полу, потерял бы отзыв МОЛЧА.
//     Поэтому оператор находит ПЕРВУЮ строку, которую снимать ещё нельзя, и
//     снимает всё строго ниже неё.
//
//  2. ОКНО ГОЛОВЫ ограничено партией (`LIMIT $2`). Границу ищем не по всей
//     таблице, а по голове: у журнала голова и есть самое старое, поэтому один
//     проход по первичному ключу длиной в партию отвечает на вопрос целиком. Без
//     окна `min`/`max` по условию возраста дали бы просмотр всех подлежащих
//     снятию строк на КАЖДУЮ партию, то есть квадрат от накопленного.
//
//  3. ВЕРХНЯЯ ГРАНИЦА — УСТОЯВШАЯСЯ ПОЗИЦИЯ (`$3`), а не край таблицы. Номер
//     выдаётся на вставке, видимость наступает на фиксации, и порядок номеров с
//     порядком фиксаций у этого журнала не связан ничем (разбор — шапка
//     `subject_change_repo.go`). Значит строка с меньшим номером вправе появиться
//     ПОЗЖЕ уже снятой соседки — и появиться НИЖЕ снятого участка, оставив дыру
//     над полом. Ограничение устоявшейся границей закрывает это by construction:
//     ниже неё каждый номер либо уже видим, либо не появится никогда.
//
//  4. КЛЕЙМА (`FOR UPDATE SKIP LOCKED`) здесь НЕТ, и это отличие от уборщика
//     таблицы операций намеренное. Пропуск запертой строки ломает решение 1:
//     вторая реплика сняла бы участок ВЫШЕ того, что заперла первая, и откат
//     первой оставил бы дыру. Реплики сериализуются на замках строк обычным
//     порядком; вторая ждёт конца партии первой (один короткий оператор) и
//     находит участок уже снятым — её `DELETE` снимает ноль. Размен назван:
//     «дыры не бывает» дороже, чем «не ждать».
const subjectChangeSweepSQL = `
WITH head AS (
    SELECT id AS pos, created_at AS aged
      FROM kaname.subject_change_outbox
     WHERE id <= $3
     ORDER BY id
     LIMIT $2
), keep AS (
    SELECT min(pos) AS pos
      FROM head
     WHERE aged >= now() - make_interval(secs => $1)
), cut AS (
    SELECT CASE
             WHEN (SELECT pos FROM keep) IS NULL THEN (SELECT max(pos) FROM head)
             ELSE (SELECT max(pos) FROM head WHERE pos < (SELECT pos FROM keep))
           END AS pos
)
DELETE FROM kaname.subject_change_outbox
 WHERE id <= (SELECT pos FROM cut)`

// SubjectChangeJournalSweeper — уборщик журнала смены субъекта.
//
// # Почему отдельный тип, а не метод читателя
//
// Читатель (`SubjectChangeRepo`) объявлен read-only, и это утверждение о нём
// верно: чтение журнала ничего не меняет. Метод, снимающий строки, сделал бы
// заголовок читателя ложью — то есть завёл бы ровно тот класс, который корпус
// ловит в комментариях.
//
// # Наблюдатель СВОЙ, и это безопасно by construction
//
// Наблюдение границы устоявшегося у уборщика своё, а не общее с читателем.
// Направление вреда здесь односторонне: граница монотонна, поэтому величина,
// наблюдённая ДО оператора, к моменту его исполнения остаётся НИЖНЕЙ оценкой —
// снимется не больше, чем позволено, и в худшем случае меньше. Ошибка в эту
// сторону стоит одного лишнего прохода; в обратную — потерянного отзыва.
type SubjectChangeJournalSweeper struct {
	pool *pgxpool.Pool
	// settled — наблюдатель границы устоявшегося. Уборка судит «что уже
	// устоялось» ТЕМ ЖЕ механизмом, которым это судит читатель, а не своей
	// копией правила.
	settled *subscription.Watermark
}

// NewSubjectChangeJournalSweeper собирает уборщика над пулом владельца журнала.
//
// Журнал процесса НАЗЫВАЕТСЯ вызывающим, а не берётся умолчанием: удержание
// границы незавершившимся писателем — единственное состояние, в котором уборка
// молчит при растущей таблице, и без жалобы оно неотличимо от «убирать нечего».
// Ноль резолвится в [slog.Default].
func NewSubjectChangeJournalSweeper(pool *pgxpool.Pool, log *slog.Logger) *SubjectChangeJournalSweeper {
	return &SubjectChangeJournalSweeper{
		pool:    pool,
		settled: subscription.NewWatermark(subjectChangeTable, subjectChangePosition, log),
	}
}

// SweepAgedRows — один проход партии.
//
// Момент времени входом НЕ приходит: часы уборки — базы, те же, которыми
// умолчание колонки ставит `created_at`. Проверяемость от этого не теряется —
// проход зовётся методом (`retention.Sweeper.Pass`), поэтому пробе не приходится
// ни спать, ни подменять часы.
//
// Возвращает число снятых строк и признак «партия ушла полной». Признак — не
// удобство: без него проход не отличает «убрал всё, что было» от «упёрся в
// партию», и уборка со скоростью одна партия за тик не догоняла бы внешний темп
// НИКОГДА, оставаясь зелёной по всякой проверке «вызвался ли».
func (s *SubjectChangeJournalSweeper) SweepAgedRows(
	ctx context.Context, grace time.Duration, batch int,
) (int64, bool, error) {
	if err := s.settled.Advance(ctx, s.pool); err != nil {
		return 0, false, fmt.Errorf("уборка журнала смены субъекта: граница устоявшегося не наблюдена: %w", err)
	}
	// ХОЛОДНЫЙ СТАРТ — не «убирать нечего»: граница ещё не подтверждена, и
	// верхнего предела у оператора нет. Снять что-либо в этом состоянии значило
	// бы снять по номеру, о видимости которого мы не знаем ничего. Fail-closed:
	// удержать лишнее дешевле, чем унести непрочитанный отзыв.
	//
	// Спрашивается ПРИЗНАК, а не ноль границы, — так предписывает godoc
	// [subscription.Watermark.Settled]: ноль означает «позиции ещё нет», а не
	// «журнал пуст», и различать их обязан всякий, кто на границу садится.
	//
	// Инъекция показала, что СЕГОДНЯ верхняя граница эту ветвь маскирует: снятие
	// проверки не роняет ни одной пробы, потому что у неподтверждённого
	// наблюдателя граница равна нулю и оператор снимает ноль строк. Это НЕ повод
	// снять ветвь: маскировка есть свойство внутреннего инварианта чужого типа,
	// которого его контракт не обещает, — а зависеть от необещанного значит
	// завести расхождение, которое проявится молча.
	if !s.settled.Established() {
		return 0, false, nil
	}
	tag, err := s.pool.Exec(ctx, subjectChangeSweepSQL, grace.Seconds(), batch, s.settled.Settled())
	if err != nil {
		return 0, false, fmt.Errorf("уборка журнала смены субъекта: %w", err)
	}
	n := tag.RowsAffected()
	return n, n >= int64(batch), nil
}
