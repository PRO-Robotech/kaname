// Пакет schemasnapshot — ПРИБОР снятия слепка схемы iam, а не проба.
//
// Он существует ради одного вопроса: «какую схему даёт цепочка миграций».
// Ответ нужен, когда цепочку сводят в одну первичную миграцию, — слепок «до»
// и слепок «после» сравниваются побайтово, и их равенство и есть предикат
// сведения. Запускается ЗАПРОСОМ, переменной окружения; без запроса выходит
// пропуском первым же оператором и ничего не строит.
//
// Почему прибор лежит ИМЕННО здесь — в шапке snapshot_test.go: его место
// выбрано пересечением трёх гейтов, а не удобством.
//
// Команда и перечень переменных — в шапке
// services/iam/internal/migrations/0001_initial.sql, рядом со сводом, который
// прибором и получен. Второго места об этом заводить не надо: расходиться
// будет то из двух, которое читают реже.
//
// Файл существует, чтобы у каталога был пакет: прибор целиком лежит в
// snapshot_test.go, а каталог из одних только проб — не пакет.
