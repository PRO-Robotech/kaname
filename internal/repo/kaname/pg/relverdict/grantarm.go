package relverdict

// grantarm.go — ЕДИНСТВЕННЫЙ В ПАКЕТЕ relverdict дом предиката ветви выдач:
// «достаёт ли выдача роли до ЭТОГО объекта». За пределами пакета свой текст
// ветви правила держит материализатор (`reconcile_adapter.go`, цель там
// сужается в Go — `filterMatchedToTarget`); гейт этого файла его не читает.
//
// Предикат стоит во всех запросах пакета, у которых есть ветвь выдач: прямой
// вопрос и вопрос о странице (`verdictSQL`, `verdictManySQL`), перечень
// (`listSQL`), кто имеет право (`subjectsSQL`) и разбор оснований (`expandSQL`).
// Прежде у каждого из трёх последних была своя копия текста, хотя шапка этого
// предиката называла себя единственной, — и копии разошлись ровно так, как
// предупреждала шапка: ни одна из них не читала цель привязки. Теперь текст
// один, различаются только подставленные выражения; второй дом держит гейт
// `TestGrantArmPredicateHasASingleHome`.

import (
	"errors"
	"fmt"
	"strings"
)

// grantArmPredicate — правило роли И цель привязки ОДНИМ предикатом.
//
// # ДВЕ ОСИ, ОБЕ ОБЯЗАТЕЛЬНЫ
//
// Первая ось — ветвь правила роли (`role_rule_selectors.arm`): якорь даёт тип
// целиком, имена — названные идентификаторы, метки — объекты с совпавшими
// метками. Вторая ось — цель самой привязки (`access_bindings.target`): пустая
// цель, пустой перечень и `allInScope` оставляют всю область, а перечень
// `resources` сужает её до названных объектов. Обе оси пересекаются, а не
// складываются: правило роли не расширяет цель, цель не расширяет правило. Это
// то же пересечение, которое делает материализатор (`filterMatchedToTarget`), —
// решение о доступе и материализованное множество обязаны совпадать.
//
// Объект входит в цель по ПАРЕ «тип, идентификатор», и тип сравнивается в
// словаре каталога (`vpc.network`), том же, каким тип записан в цели
// (`domain.ValidTargetType` берёт его из ленты материализации). Совпадение
// одного идентификатора не годится: объект другого типа с тем же id стал бы
// доступен выдачей, которая его не называет.
//
// Сравнение ТОЧНОЕ у правила верхнего уровня: объекты, лежащие под названным
// контейнером, целью такого правила не охватываются (kaname#857).
//
// # ТРЕТЬЯ ОСЬ — ВЛОЖЕННОСТЬ, И ОНА ЖИВЁТ ЗДЕСЬ ЖЕ (kaname#874)
//
// Селектор ВЛОЖЕННОГО правила (`rs.container_type` непуст) охватывает объект
// своего типа, когда среди его предков есть КОНТЕЙНЕР типа владельца, который
// (1) проходит ветвь правила-владельца — якорь, имена либо метки контейнера — и
// (2) входит в цель выдачи: назван парой «тип, id» либо цель — вся область
// (приёмка `nested-rule-reaches-descendants-of-a-named-container.md`, Р3).
// Предки читаются РЁБРАМИ ОБЪЕКТА по ключу (`resource_parent_edge`): владелец
// присылает всю цепь с глубиной, поэтому «контейнер среди предков» — одно
// чтение при любой глубине, а будущий потомок охвачен в момент регистрации.
//
// Ось стоит ВНУТРИ того же предиката, а не отдельной ветвью союза: иначе у
// вложенного правила была бы своя копия оси цели и своя копия запрета для
// класса, и они разошлись бы с этими. Селектор верхнего уровня проходит прежнюю
// ось цели ДОСЛОВНО, а подзапрос рёбер у него не исполняется вовсе —
// исполнитель останавливает «или» на первой истине (`rs.container_type IS NULL`).
//
// К выдаче СИСТЕМНОМУ КЛАССУ вложенное правило НЕ применяется (Р5, ND-10): у
// класса одна дорога к потомкам — `public_reader` объявленного контейнера, и
// снятие объявления обязано снимать чтение. Ветвь выдач, дающая классу потомков
// по вложенному правилу, была бы второй дорогой, переживающей это снятие.
//
// Метки контейнера берутся из зеркала: контейнер — ресурс модуля (ярусы иерархии
// владельцем вложенного правила быть не могут, Р1 п. 2), а метки собственных
// объектов iam ни один владелец не объявляет контейнером.
//
// Принадлежность КОНТЕЙНЕРА области выдачи отдельно не спрашивается, и это
// вывод, а не допущение: область выдачи — ярус (кластер, аккаунт, проект), и
// она уже найдена в цепи ОБЪЕКТА (заход ветви — с пары «субъект + область»);
// контейнер — тоже предок объекта и не ярус, а цепь объекта одна и упорядочена
// от ближнего предка к ярусам. Значит контейнер лежит под областью той же цепью.
// Материализатор ставит ту же стену явно (`IsContainedIn` контейнера) — по
// своей форме данных, где цепи под рукой нет.
//
// # НЕЗНАКОМАЯ ФОРМА ЦЕЛИ — ОТКАЗ, А НЕ ВСЯ ОБЛАСТЬ
//
// Всю область дают ровно три формы: корень — объект без ключа `resources`
// (`{}`, `{"allInScope": true}`) либо `resources` — пустой перечень. Схема
// других форм не запрещает: корень-массив (`[]`), корень-строка, `resources`
// — null, объект или строка. Для них «-> 'resources'» даёт NULL либо не
// перечень, и сравнение не совпадает ни с одним объектом. Проверять ОТСУТСТВИЕ
// ключа через «-> 'resources' IS NULL» нельзя: у корня-не-объекта NULL даёт и
// это выражение, и такая цель читалась бы как вся область.
//
// # РАЗДЕЛЯТЬ ВЕТВИ ПРАВИЛА НА ДВА ЗАПРОШЕННЫХ АРМА НЕЛЬЗЯ, и это измерено
//
// Соблазн понятен: отдельная меточная ветвь сделала бы признак наблюдения
// детерминированным. Но внешний предел вычерпывает КАЖДУЮ ветвь союза до своего
// числа независимо от того, что отдали предыдущие, — значит вторая ветвь
// оплачивается на ВСЯКОМ вопросе. Замер при трёхстах основаниях: 89 строк за
// вердикт становятся 929 при меточной ветви впереди и 10032 по оси B при ней же
// позади. То есть цена наблюдаемости здесь — сама константа, ради которой
// стадия и делается.
//
// # ФУНКЦИЯ, А НЕ КОНСТАНТА
//
// Тип, идентификатор и метки объекта названы по-разному у разных форм вопроса:
// у прямого — параметром запроса, у страничного — колонкой внешней стороны
// соединения вбок, у перечня — колонкой кандидата. Написать предикат на каждую
// форму значило бы завести несколько мест, знающих, что такое «выдача достаёт
// до объекта», и разойтись им молча — в сторону лишнего доступа. Текст остаётся
// ОДИН, различаются только подставленные выражения.
//
// # ОСЬ ЦЕЛИ ЗАПИСАНА ТАК, ЧТОБЫ НЕ МЕНЯТЬ ОЦЕНКУ ПЛАНИРОВЩИКА
//
// Условие цели стоит на одной таблице — привязке, — и планировщик ставит его
// на её просмотр. Статистики у выражения над `target` нет, поэтому каждое
// слагаемое он оценивает умолчанием (доли процента), и прямая запись
// «(… IS NULL) OR (… = '[]') OR (… @> …)» уменьшала оценку выдач в сотню раз.
// Измерено пробой `TestR7_1_13_EarlyExitIsObservable`: с такой оценкой план
// начинал с просмотра привязок и материализовал ВСЕ строки субъектов выдач
// (301 при трёхстах основаниях), и строк за разрешённый вердикт стало 633
// против 26 — короткое замыкание ветви выдач пропало.
//
// Обёртка «NULLIF(условие, false) IS NOT NULL» истинна ровно тогда, когда
// условие истинно: ложь и NULL (у незнакомой формы цели) оба дают отказ. А
// оценивается она как проверка на отсутствие — почти единицей, какое бы условие
// ни стояло внутри. Оценка выдач остаётся прежней, и
// порядок соединений — тем, ради которого ветвь написана (заход с пары
// «субъект + область»). Смысл обёртка не меняет: её держат пробы цели, стоимость —
// проба раннего выхода.
//
// Псевдонимы таблиц у всех потребителей одни: `b` — привязка, `rs` — селектор
// правила роли.
//
// Проверка меток на отсутствие нужна формам, где метки приходят ЛЕВЫМ
// соединением (промах соединения даёт NULL); у перечня кандидат и есть строка
// с метками, колонка объявлена NOT NULL, и проверка там всегда истинна — цена
// единого текста, а не второй смысл.
//
// # ВЛОЖЕННОСТЬ ЗАПИСАНА ТАК, ЧТОБЫ ОСЬ ЦЕЛИ ОСТАЛАСЬ НА ПРИВЯЗКЕ (kaname#874)
//
// Условие цели прежде ссылалось ТОЛЬКО на привязку и константы, и планировщик
// опускал его в просмотр `access_bindings`. Ось вложенности ссылается на
// селектор (`rs`) и субъект (`bs`); вписанная в то же условие, она делала его
// неопускаемым — и порядок соединений менялся: замер `TestR7_1_13` дал 71 строку
// за разрешённый вердикт при трёх основаниях против 26 (при трёхстах — 24 и 24).
//
// Поэтому условие разложено на ТРИ части; точные — первые две:
//
//  1. уровень селектора, ВЛОЖЕННАЯ строка: класс — нет; среди предков объекта
//     есть контейнер типа владельца, он проходит ветвь владельца и цель (вся
//     область либо назван парой «тип, id»). Подзапрос рёбер исполняется только у
//     вложенной строки: «или» останавливается на `rs.container_type IS NULL`;
//  2. уровень селектора, строка ВЕРХНЕГО уровня: цель называет сам объект либо
//     она — вся область (точное сравнение, как после kaname#857);
//  3. уровень ПРИВЯЗКИ — НЕОБХОДИМОЕ условие обеих: цель — вся область, либо
//     называет объект, либо называет контейнер-предка объекта из вложенного
//     селектора роли. Ссылается только на привязку и константы, поэтому
//     опускается в просмотр привязок, как прежде. Достаточным оно не является и
//     быть не обязано: точный суд — части 1 и 2.
//
// Замер на той же сетке после разложения: верхний уровень — 26 и 24 строки,
// как у ствола; вложенное правило — 32 при трёх основаниях и 25 при трёхстах.
//
// `objectModelTypeExpr` — тип объекта в словаре МОДЕЛИ: им названы рёбра цепи
// (`resource_parent_edge.object_type`), тогда как `objectTypeExpr` — словарь
// каталога, которым тип записан в цели. Двух словарей в одном сравнении нет:
// каждое выражение сравнивается со своим.
func grantArmPredicate(objectTypeExpr, objectModelTypeExpr, objectIDExpr, labelsExpr string) string {
	// Ветвь правила роли на самом объекте — у правила любого уровня.
	arm := `(
             rs.arm = 'anchor'
          OR (rs.arm = 'names'  AND ` + objectIDExpr + ` = ANY (rs.resource_names))
          OR (rs.arm = 'labels' AND ` + labelsExpr + ` IS NOT NULL
                                AND ` + labelsExpr + ` @> rs.match_labels)
         )`
	// Часть 1 — вложенная строка (точно).
	nested := `
     AND (rs.container_type IS NULL OR (bs.subject_type <> 'system_class' AND EXISTS (
             SELECT 1
               FROM kaname.resource_parent_edge ce
              WHERE ce.object_type = ` + objectModelTypeExpr + ` AND ce.object_id = ` + objectIDExpr + `
                AND ce.parent_type = rs.container_object_type
                AND (   rs.container_arm = 'anchor'
                     OR (rs.container_arm = 'names' AND ce.parent_id = ANY (rs.container_resource_names))
                     OR (rs.container_arm = 'labels' AND EXISTS (
                            SELECT 1 FROM kaname.resource_mirror cm
                             WHERE cm.object_type = rs.container_type AND cm.object_id = ce.parent_id
                               AND cm.labels @> rs.container_match_labels)))
                AND (` + wholeScopeTarget + `
                     OR ` + namedInTarget("rs.container_type", "ce.parent_id") + `))))`
	// Часть 2 — строка верхнего уровня (точно).
	top := `
     AND (rs.container_type IS NOT NULL OR NULLIF(
             ` + wholeScopeTarget + `
          OR ` + namedInTarget(objectTypeExpr, objectIDExpr) + `,
         false) IS NOT NULL)`
	// Часть 3 — необходимое условие на привязке (опускаемое).
	binding := `
     AND NULLIF(
             ` + wholeScopeTarget + `
          OR ` + namedInTarget(objectTypeExpr, objectIDExpr) + `
          OR EXISTS (
                 SELECT 1
                   FROM kaname.role_rule_selectors ns
                   JOIN kaname.resource_parent_edge ce
                     ON ce.object_type = ` + objectModelTypeExpr + ` AND ce.object_id = ` + objectIDExpr + `
                    AND ce.parent_type = ns.container_object_type
                  WHERE ns.role_id = b.role_id AND ns.container_type IS NOT NULL
                    AND ` + objectTypeExpr + ` = ANY (ns.object_types)
                    AND ` + namedInTarget("ns.container_type", "ce.parent_id") + `),
         false) IS NOT NULL`
	return arm + nested + top + binding
}

// wholeScopeTarget — цель «вся область»: корень-объект без ключа `resources`
// либо пустой перечень (довод о незнакомых формах — в шапке предиката).
const wholeScopeTarget = `(jsonb_typeof(b.target) = 'object' AND NOT (b.target ? 'resources'))
          OR b.target -> 'resources' = '[]'::jsonb`

// namedInTarget — цель называет пару «тип, id» (тип — в словаре каталога).
func namedInTarget(typeExpr, idExpr string) string {
	return `b.target -> 'resources' @> jsonb_build_array(jsonb_build_object(
                 'type', ` + typeExpr + `, 'id', ` + idExpr + `))`
}

// errTemplateMark — метка шаблона запроса стоит в нём не ровно один раз.
var errTemplateMark = errors.New("метка шаблона запроса стоит не ровно один раз")

// replaceOnce подставляет val на место метки, которая стоит в шаблоне РОВНО
// один раз, а иначе возвращает ошибку и запроса не собирает.
//
// Молчаливая подстановка (strings.Replace) на шаблоне без метки собрала бы
// запрос БЕЗ предиката ветви выдач — то есть выдачу без сужения, — и ничем бы
// себя не выдала. Ошибка идёт тем же путём, что ошибка самого запроса: вопрос
// получает «не знаю» с ошибкой, а не отказ и не разрешение. Шаблоны —
// константы пакета, поэтому это ошибка сборки дерева, а не данных: её ловит
// проба TestEveryAssembledQueryCarriesTheGrantPredicateOnce, собирающая каждую
// форму вопроса.
func replaceOnce(tmpl, mark, val string) (string, error) {
	if n := strings.Count(tmpl, mark); n != 1 {
		return "", fmt.Errorf("relverdict: метка %q стоит в шаблоне %d раз, ждали ровно один: %w",
			mark, n, errTemplateMark)
	}
	return strings.Replace(tmpl, mark, val, 1), nil
}
