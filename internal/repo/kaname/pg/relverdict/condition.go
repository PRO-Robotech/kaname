package relverdict

// condition.go — вычисление условия, при котором прямой факт действует.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ВЫЧИСЛЯЕТСЯ ЗДЕСЬ, А НЕ ХРАНИТСЯ
//
// Свежесть подтверждения личности зависит от «сейчас»: она не материализуема ни
// в какой форме — ни в этой, ни в той, что была до неё. Значит выбор был не
// «вычислять или хранить», а «вычислять у себя или за сетевым скачком». Выбрано
// у себя: решение о доступе целиком принимает одно место (`security.md`
// §«Авторизация живёт в МОДЕЛИ»), а не половина здесь и половина у соседа.
//
// ─────────────────────────────────────────────────────────────────────────────
// ТРИ ИСХОДА, А НЕ ДВА
//
// Условие может быть выполнено, не выполнено — и НЕ ПОНЯТО. Третий исход
// отдельный намеренно:
//
//   - не выполнено — довода нет, и это законный отказ;
//   - НЕ ПОНЯТО (имени условия нет в этом наборе) — ответа не получено, и
//     выдавать его за отказ значило бы объявить «прав нет» там, где мы просто не
//     умеем спросить. Такое обязано подниматься до вердикта «не знаю»: иначе
//     новое условие в модели молча сузило бы доступ всем, кто им пользуется, и
//     заметили бы это по чужим отказам, а не по красной пробе.
//
// ОТСУТСТВУЮЩИЙ ДОВОД — это «не выполнено», а не «не понято». Условие мы знаем,
// вычислить умеем, довода нет ⇒ предикат ложен. Так и должно быть: доводы о
// личности приезжают из проверенного источника, и их отсутствие означает, что
// проверенного значения нет, — принимать это за выполнение значило бы делать
// защиту удовлетворимой её же неполнотой.

import (
	"fmt"
	"strings"
	"time"
)

// mfaFreshWindow — окно свежести подтверждения личности.
//
// Величина повторяет каноническую модель (`current_time - mfa_at <
// duration("15m")`). Повторение здесь НЕ вторая истина, а исполнение: модель
// объявляет, этот код исполняет, и расхождение между ними ловит гейт
// `TestConditionRegistryMatchesTheModel`, который читает модель, а не память.
const mfaFreshWindow = 15 * time.Minute

// mfaFreshACR — уровень уверенности, который условие требует.
const mfaFreshACR = "3"

// mfaFreshMethod — метод подтверждения, который условие требует.
const mfaFreshMethod = "webauthn"

// errUnknownCondition — имени условия нет в наборе.
//
// Отдельный тип, а не текст: вызывающий обязан отличить его от «предикат ложен»
// машинно, и сравнение строк для этого не годится.
type errUnknownCondition struct{ name string }

func (e errUnknownCondition) Error() string {
	return fmt.Sprintf("relverdict: условие %q не вычисляется этой формой — вердикт по нему "+
		"неизвестен, и выдавать его за отказ нельзя", e.name)
}

// conditionFunc — предикат условия.
//
// params — доводы, лежащие на самой записи; reqCtx — доводы запроса. Оба на
// вход, потому что условие законно берёт часть отсюда, часть оттуда: срок
// действия лежит на записи, «сейчас» приезжает с вопросом.
type conditionFunc func(params, reqCtx map[string]any) bool

// conditionRegistry — набор вычисляемых условий.
//
// Набор ЗАКРЫТ: имя вне его даёт «не знаю», а не отказ. Пополняется вместе с
// моделью и удерживается гейтом в обе стороны — условие модели без предиката
// роняет прогон, предикат без условия в модели роняет тоже (запись, которой
// больше нечего вычислять, есть находка).
var conditionRegistry = map[string]conditionFunc{
	"mfa_fresh": mfaFresh,
}

// mfaFresh — свежесть подтверждения личности.
//
// Исполняет ровно то, что объявляет модель: уровень уверенности, наличие метода
// среди применённых и окно давности. Каждый довод — из запроса: хранить их
// негде, они описывают «сейчас».
func mfaFresh(_, reqCtx map[string]any) bool {
	if asString(reqCtx["acr_value"]) != mfaFreshACR {
		return false
	}
	if !containsString(reqCtx["amr_claims"], mfaFreshMethod) {
		return false
	}
	now, okNow := asUnix(reqCtx["current_time"])
	at, okAt := asUnix(reqCtx["mfa_at"])
	if !okNow || !okAt {
		// Довода нет ⇒ предикат ложен. См. шапку файла: неполнота не вправе
		// удовлетворять защиту.
		return false
	}
	if at > now {
		// Подтверждение «из будущего» — не свежесть, а рассогласование часов либо
		// подложенное значение. Ни то, ни другое не довод.
		return false
	}
	return time.Duration(now-at)*time.Second < mfaFreshWindow
}

// evalCondition вычисляет одно условие.
//
// Возвращает ошибку ТОЛЬКО когда условие не понято. Ложный предикат — не ошибка:
// это законный ответ «довода нет».
func evalCondition(name string, params, reqCtx map[string]any) (bool, error) {
	fn, ok := conditionRegistry[name]
	if !ok {
		return false, errUnknownCondition{name: name}
	}
	if params == nil {
		params = map[string]any{}
	}
	if reqCtx == nil {
		reqCtx = map[string]any{}
	}
	return fn(params, reqCtx), nil
}

// asString приводит значение к строке, не выдумывая приведения.
//
// Число здесь НЕ приводится к строке намеренно: уровень уверенности приезжает
// как строка («3»), и молчаливое приведение числа 3 сделало бы условие
// выполнимым значением другого типа — то есть удовлетворимым тем, чего
// проверенный источник не присылал.
func asString(v any) string {
	s, _ := v.(string)
	return s
}

// containsString отвечает, есть ли строка в списке.
//
// Список приезжает и как []string, и как []any (после разбора JSON) — обе формы
// законны, и различать их обязан этот разбор, а не вызывающий.
func containsString(v any, want string) bool {
	switch xs := v.(type) {
	case []string:
		for _, x := range xs {
			if x == want {
				return true
			}
		}
	case []any:
		for _, x := range xs {
			if s, ok := x.(string); ok && s == want {
				return true
			}
		}
	case string:
		// Одиночное значение вместо списка — законная форма ровно одного метода.
		return xs == want
	}
	return false
}

// asUnix приводит момент времени к секундам эпохи.
//
// Форм у момента несколько, потому что он приезжает разными путями: из разбора
// JSON — числом с плавающей точкой, из сборки контекста — целым, из чужого
// заголовка — строкой. Принять одну и промолчать на остальных значило бы, что
// условие ложно из-за формы записи, а не из-за существа.
func asUnix(v any) (int64, bool) {
	switch t := v.(type) {
	case int64:
		return t, true
	case int:
		return int64(t), true
	case float64:
		return int64(t), true
	case time.Time:
		return t.Unix(), true
	case string:
		s := strings.TrimSpace(t)
		if s == "" {
			return 0, false
		}
		if ts, err := time.Parse(time.RFC3339, s); err == nil {
			return ts.Unix(), true
		}
		return 0, false
	}
	return 0, false
}
