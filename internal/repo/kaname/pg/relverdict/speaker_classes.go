package relverdict

// speaker_classes.go — системный класс субъекта в форме вердикта (приёмка
// anonymous-and-authenticated-are-subject-classes.md, kaname#829).
//
// Классы говорящего приходят в каждый из трёх запросов (прямой вопрос, вопрос
// о странице, перечень) ПАРАМЕТРАМИ `$10`, `$11` от одного производителя —
// `domain.SpeakerClasses`. Здесь — второе правило класса, которое обязано
// стоять в КАЖДОЙ ветви выдач, а не в одной: выдача классу раздаёт только
// чтение (Р4, SC-23).

import (
	"strings"

	"github.com/PRO-Robotech/kaname/internal/domain"
)

// classVerbFilterSQL — строка выдачи системному классу раздаёт только глаголы
// чтения, какими бы ни были правила её роли сейчас.
//
// Стоит на КАЖДОМ соединении с `role_verb` (вопрос, перечень, развёртка,
// перечень субъектов): правило, поставленное в одну форму, оставило бы
// соседнюю отвечать «пишет» о том же классе. Фильтр — на каждом выпуске
// ответа, а не однажды при выдаче: роль, выданная классу, может получить
// пишущий глагол путём, который правкой роли не является (поставка роли
// модулем, SC-23), и страж правки роли этого пути не видит.
//
// Набор глаголов совпадает с `domain.IsClassReadVerb`; равенство держит
// проба пакета.
const classVerbFilterSQL = `(bs.subject_type <> 'system_class' OR rv.verb = ANY ('{get,list}'::text[]))`

// classSlot — имя i-го класса говорящего (без вида) либо пустая строка.
//
// Слотов ДВА, потому что классов в словаре два: производитель
// (`domain.SpeakerClasses`) не отдаёт больше, и проба пакета это держит.
// Пустой слот не совпадает ни с одной строкой: у субъекта выдачи и у факта
// пустого имени не бывает.
func classSlot(speaker string, i int) string {
	classes := domain.SpeakerClasses(speaker)
	if i >= len(classes) {
		return ""
	}
	return strings.TrimPrefix(classes[i], string(domain.SubjectTypeSystemClass)+":")
}

// speakerExistsSQL — говорящий `$1` называет СУЩЕСТВУЮЩУЮ учётку (kaname#909).
//
// Классы положены говорящему С ЛИЧНОСТЬЮ (приёмка, Р2), а вид записи
// (`domain.SpeakerClasses`) — ещё не личность: личность — строка учётки. Поэтому
// обе строки класса в паре колонок стоят под этим предикатом, а текстовая форма
// берёт классы из пары, а не вторым написанием параметров.
//
// Видов здесь ровно столько, скольким производитель отдаёт классы: человек и
// служебная учётка; паритет держит проба пакета. Предикат — часть ТОГО ЖЕ
// оператора, а не вопрос перед ним: снимок базы у класса и у выдач общий, и
// кругов к базе не прибавляется. Системный класс сам по себе
// (`system_class:anonymous`) классов сверх себя не выводит и предикатом не
// судится.
const speakerExistsSQL = `(
           (split_part($1::text, ':', 1) = 'user'
            AND EXISTS (SELECT 1 FROM kaname.users u
                         WHERE u.id = substr($1::text, length(split_part($1::text, ':', 1)) + 2)))
        OR (split_part($1::text, ':', 1) = 'service_account'
            AND EXISTS (SELECT 1 FROM kaname.service_accounts s
                         WHERE s.id = substr($1::text, length(split_part($1::text, ':', 1)) + 2)))
       )`

// directSpeakerPairsSQL — общие пары говорящего для обычного и внутреннего вопросов.
// Позиции параметров совпадают, включая два класса, отсекаемые во внутренней ветви.
const directSpeakerPairsSQL = `speaker_pair(s_type, s_id, via) AS (
    -- СУБЪЕКТ ВЫДАЧИ — ПАРОЙ КОЛОНОК, а не склейкой.
    --
    -- Склейка subject_type || ':' || subject_id выводит колонки из-под любого
    -- индекса: сравнивать приходится вычисленное значение, а вычисленное
    -- значение отбирает строки только ПОСЛЕ того, как они прочитаны. Пара
    -- колонок сужает набор ДО чтения. Паритет, а не новое устройство: соседнее
    -- соединение того же запроса читает членство парой колонок и обслуживается
    -- индексом (member_type, member_id) с самого начала.
    --
    -- Колонка via называет, ОТКУДА взялась пара, и существует ради текстовой
    -- формы ниже: хвост #member раскрывает ЧЛЕНСТВО, и приписать его группе,
    -- которая сама является вызывающим, значило бы расширить ответ на факты,
    -- которых вызывающему не выдавали.
    SELECT split_part($1::text, ':', 1),
           substr($1::text, length(split_part($1::text, ':', 1)) + 2),
           'self'
  UNION ALL
    SELECT 'group', gm.group_id, 'member'
      FROM kaname.group_members gm
     WHERE gm.member_type = split_part($1::text, ':', 1)
       AND gm.member_id   = substr($1::text, length(split_part($1::text, ':', 1)) + 2)
  UNION ALL
    -- КЛАССЫ ГОВОРЯЩЕГО (Р2) — значением запроса, а не выводом по месту: их
    -- вычисляет ОДИН производитель (domain.SpeakerClasses) для всех трёх форм
    -- вопроса, и разойтись форме перечня с формой вопроса негде. Безусловной
    -- подстановки «любой» здесь больше нет: аноним выданного вошедшим не
    -- получает (SC-10), группа — ничего (SC-11). Классов у говорящего не больше
    -- двух, и они приходят двумя скалярами. Строк здесь от этого становится
    -- больше, и порядок соединения с субъектами выдач держит не оценка числа
    -- строк, а обращение вбок в ветви выдач (довод — там). Пустое имя класса не
    -- совпадает ни с одной строкой: у субъекта выдачи пустого идентификатора нет.
    SELECT 'system_class', $10::text, 'class' WHERE ` + speakerExistsSQL + `
  UNION ALL
    SELECT 'system_class', $11::text, 'class' WHERE ` + speakerExistsSQL + `
),
`
