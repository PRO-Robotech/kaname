// ListQuery — вопрос «какие объекты этого типа доступны субъекту».
type ListQuery struct {
	Subject    string
	ObjectType string
	// Relation — отношение в том виде, в каком его называет МОДЕЛЬ (`v_get`,
	// `ssh`, `admin`), — та же единица, что у прямого вопроса.
	//
	// Не глагол: глаголы, которые обязана давать роль, вычисляет план, и они не
	// равны спрошенному имени всегда (`v_addtargets` выводится от `v_update`).
	// Принимать здесь глагол значило бы (а) объявить, что всякий обратный вопрос
	// про глагол, — модель это опровергает (`ssh`, `console`, `member`
	// глаголами не являются), и (б) держать в одном пакете две единицы одного
	// предмета, различие которых читателю пришлось бы помнить.
	Relation string
	// AfterID — курсор: строго больший идентификатор. Пусто — первая страница.
	AfterID string
	// Limit — размер страницы. Ноль → DefaultPageSize.
	Limit int
}

// DefaultPageSize — размер страницы по умолчанию.
//
// Величина здесь не «сколько влезет», а «сколько отдать за один вопрос»:
// страница обязана быть достаточно мелкой, чтобы её стоимость принадлежала
// запросу, и достаточно крупной, чтобы обход не превращался в тысячу вызовов.
const DefaultPageSize = 500

// listSQL — те же источники, что у вердикта, и та же раскладка по модели, но
// перечислением.
//
// Читается так же: цепь областей КАЖДОГО объекта-кандидата, субъекты, за которых
// говорит вызывающий, затем источники права ПЛАНА. Отличий два, и оба несущие:
// кандидаты берутся из СВОЕЙ базы — из зеркала для типов чужих сервисов и из
// собственной таблицы для типов iam (`labelaxis.go`), а не из ответа чужого
// хранилища с его пределом; а цепь областей строится для каждого кандидата,
// потому что вопрос задан не про один объект.
//
// Кандидатов ровно столько, сколько вмещает заход ($4), и отбираются они
// первичным ключом `(object_type, object_id)` — тем же порядком, каким страница
// отдаётся наружу. Предел стоит ЗДЕСЬ, в источнике кандидатов, а не на последнем
// действии: цепь областей ниже строится по `candidate`, и предел, применённый
// после неё, ограничивал бы только длину ответа, но не работу.
//
// Право отдаётся КОЛОНКОЙ, а не условием отбора: заход обязан назвать своего
// последнего кандидата, иначе курсор нечем продвинуть, когда доступного в заходе
// не нашлось, — и обход встал бы, объявив пустую страницу концом набора при живых
// правах. Внутри колонки — EXISTS, а не соединение: объект, до которого достают
// ДВА основания сразу (своя выдача и администратор облака), обязан занять в
// странице ровно одно место. Соединение отдало бы его дважды — и это не
// косметика: страница отдаётся курсором, повтор съедает место в ней, а повтор на
// границе сдвигает курсор не туда.
//
// $1 subject · $2 object_type в словаре МОДЕЛИ · $3 after_id · $4 размер захода ·
// $5 max_depth ·
// $6 типы предков атомов-фактов · $7 отношения атомов-фактов · $8 глаголы атомов-выдачи
// $9 object_type в словаре КАТАЛОГА — им названы `resource_mirror.object_type`,
// `role_verb.object_type` и `role_rule_selectors.object_types`, тогда как вопрос
// приходит словарём модели. Перевод делается ОДИН раз, на входе, и читает ЖИВУЮ
// строку каталога (`catalogTypeName`, catalogtype.go): таблица, порождённая
// сборкой, о типе, заведённом применением манифеста в работающем процессе, не
// знает (kacho#1986). Двух словарей в одном соединении быть не должно —
// соединение по разным написаниям не совпадает НИКОГДА и молча.
const listSQL = `
WITH RECURSIVE speaker_pair(s_type, s_id, via) AS (
    -- СУБЪЕКТ ВЫДАЧИ — ПАРОЙ КОЛОНОК, а не склейкой.
    --
    -- Склейка subject_type || ':' || subject_id выводит колонки из-под любого
    -- индекса: сравнивать приходится вычисленное значение, а вычисленное
    -- значение отбирает строки только ПОСЛЕ того, как они прочитаны. Пара
    -- колонок сужает набор ДО чтения. Паритет, а не новое устройство: соседнее
    -- соединение того же запроса читает членство парой колонок и обслуживается
    -- индексом (member_type, member_id) с самого начала.
    --
    -- Колонка via называет, ОТКУДА взялась пара, и существует ради текстовой
    -- формы ниже: хвост #member раскрывает ЧЛЕНСТВО, и приписать его группе,
    -- которая сама является вызывающим, значило бы расширить ответ на факты,
    -- которых вызывающему не выдавали.
    SELECT split_part($1::text, ':', 1),
           substr($1::text, length(split_part($1::text, ':', 1)) + 2),
           'self'
  UNION ALL
    SELECT 'group', gm.group_id, 'member'
      FROM kaname.group_members gm
     WHERE gm.member_type = split_part($1::text, ':', 1)
       AND gm.member_id   = substr($1::text, length(split_part($1::text, ':', 1)) + 2)
  UNION ALL
    -- Подстановка объявлена НАМЕРЕННО (глобальный справочник читает всякий
    -- аутентифицированный) и потому перечислена явно, а не выведена из формы
    -- имени.
    SELECT 'user', '*', 'wildcard'
),
speaker(subject) AS (
    -- ТЕКСТОВАЯ форма — для прямых фактов: их субъект хранится строкой, и она
    -- не разбирается на пару нигде в дереве. Обе формы имени группы, и это не
    -- перестраховка: канонический производитель кортежей пишет
    -- group:<id>#member (хвост раскрывает членство на стороне модели), а голой
    -- формой group:<id> адресуется сама группа как субъект. Признать одну и
    -- промолчать о другой значит НЕДОотвечать ровно на права, выданные
    -- каноническим путём, — тихо, потому что неполный ответ выглядит как
    -- честное «ничего нет».
    SELECT $1::text
  UNION
    SELECT 'group:' || sp.s_id FROM speaker_pair sp WHERE sp.via = 'member'
  UNION
    SELECT 'group:' || sp.s_id || '#member' FROM speaker_pair sp WHERE sp.via = 'member'
  UNION
    SELECT 'user:*'
),
candidate(object_id, labels) AS (
    -- ЗДЕСЬ СХОДЯТСЯ ДВА СВОЙСТВА, И НИ ОДНО ИЗ НИХ НЕ ВЫВОДИТСЯ ИЗ ДРУГОГО.
    --
    -- (1) ОСЬ. Откуда берутся кандидаты — свойство ТИПА: у ресурса чужого
    -- сервиса это зеркало, у собственного объекта iam — его таблица. Написать
    -- здесь одно зеркало значило бы перечислять пустоту для семи типов и потом
    -- аккуратно спрашивать у неё метки. Поэтому источник подставляется по типу
    -- (см. labelaxis.go), а не выписан одной строкой.
    --
    -- (2) ПРЕДЕЛ. Кандидатов ровно столько, сколько вмещает заход, и отбираются
    -- они тем же порядком, каким страница отдаётся наружу. Предел стоит В
    -- ИСТОЧНИКЕ, до раскрутки цепи областей ниже: применённый после неё, он
    -- ограничивал бы длину ответа, но не работу.
    --
    -- И метки едут ВМЕСТЕ с кандидатом, а не добираются вторым чтением того же
    -- места ниже. Второе чтение было бы соединением по всему типу, и планировщик
    -- на пустой статистике брал его целиком: измерено — страница из 1000
    -- объектов читала лишние 10 000 строк ровно там. Ограниченный источник
    -- кандидатов уже держит нужную строку; брать её у него — не оптимизация, а
    -- отказ от второго, ничем не ограниченного пути к ней. Обе оси несут
    -- колонку меток, поэтому свойство держится на каждой, а не только на
    -- зеркальной.
    --
    -- Оба свойства обязаны читаться вместе ещё и потому, что подстановка
    -- источника выводит это выражение из-под статического гейта
    -- internal/repohygiene TestRecursiveScopeChainCostsTheRequestNotTheSet: он
    -- судит литерал, а собранный на лету SQL сам объявляет вне своего объёма.
    -- Предел здесь держится ПОВЕДЕНЧЕСКОЙ пробой — той, что утверждает
    -- плоскость кривой прочитанных строк, — и она обязана оставаться зелёной на
    -- обеих осях.
    {{candidate_from}}
),
scope(object_id, s_type, s_id, depth) AS (
    SELECT c.object_id, $2::text, c.object_id, 0 FROM candidate c
  UNION
    -- Цепь берётся ПО ОДНОМУ объекту, соединением вбок, а не общим соединением с
    -- таблицей рёбер. Разница не стилистическая: у вопроса про ОДИН объект
    -- (вердикт, субъекты, разворот) внешняя сторона — одна строка, и
    -- планировщик сам ходит указателем; здесь внешняя сторона — целая страница,
    -- и на ней он выбирает построить хеш по ВСЕЙ таблице рёбер. Тогда стоимость
    -- страницы снова становится стоимостью набора — только уже не через
    -- кандидатов, а через рёбра, и предел на кандидатах этого не ловит.
    -- Измерено: страница из 50 объектов читала все рёбра типа.
    --
    -- Предел внутри — НЕ усечение и не может им стать: у объекта не бывает
    -- больше рёбер, чем глубин, потому что первичный ключ таблицы уникален по
    -- глубине, а сама глубина ограничена проверкой схемы тем же числом
    -- (миграция 0082). Выведенное схемой звено этого равенства не нарушает:
    -- представление выводит предка ТОЛЬКО там, где владелец объекта своей цепи
    -- не назвал (миграция 740001), поэтому строки не складываются. То есть предел
    -- равен собственной границе строки объекта, а порядок по глубине делает
    -- выборку определённой на случай, если границы когда-нибудь разойдутся:
    -- ближние предки останутся, дальние — те, до которых обход всё равно не
    -- доходит.
    SELECT s.object_id, e.parent_type, e.parent_id, s.depth + 1
      FROM scope s
      CROSS JOIN LATERAL (
             SELECT pe.parent_type, pe.parent_id
               FROM kaname.resource_scope_edge pe
              WHERE pe.object_type = s.s_type AND pe.object_id = s.s_id
              ORDER BY pe.depth
              LIMIT $5::int
           ) e
     WHERE s.depth < $5::int
),
-- scope_distinct — ОБЛАСТИ БЕЗ ПОВТОРОВ, и это ЕДИНСТВЕННОЕ, что читают армы.
--
-- Обход выше несёт в кортеже ГЛУБИНУ ШАГА, поэтому UNION не схлопывает предка,
-- достигнутого разными путями. Форма цепи, которую пишет производитель для
-- compute и nlb (ownerregister.ParentChain — проект И аккаунт сразу), даёт
-- аккаунт на глубинах 1 и 2, а стоящий над ним кластер — на 2 и 3: шесть строк
-- при четырёх различных областях.
--
-- Каждая лишняя строка УМНОЖАЕТ ОБА АРМА: ветвь выдач соединена с набором
-- CROSS JOIN, ветвь фактов — по паре колонок. Отбор различных над ОТВЕТОМ
-- прячет это в ответе и не трогает СТОИМОСТЬ, а на отказном вопросе короткого
-- замыкания нет, и цена платится целиком. Измерено пробой
-- scopedistinct_integration_test.go: 6 строк при 4 различных областях.
--
-- ОБХОД СОХРАНЯЕТСЯ ЦЕЛИКОМ — снимается только повтор. Это НЕ переход на одно
-- чтение таблицы рёбер: тот переход опровергнут (таблица хранит присланную
-- цепь, а не замыкание), и здесь его нет.
--
-- Наименьшая глубина БЕЗОПАСНА, и это проверяемо: единственное употребление
-- глубины ниже по запросу — дискриминатор якоря sc.depth = 0, а якорь
-- засевается нулём и по построению остаётся минимумом (выведенная строка даёт
-- s.depth + 1 при s.depth не меньше нуля, то есть нуля дать не может).
scope_distinct(object_id, s_type, s_id, depth) AS (
    SELECT object_id, s_type, s_id, min(depth) FROM scope GROUP BY object_id, s_type, s_id
),
fact_atom(parent_type, relation) AS (
    SELECT * FROM unnest($6::text[], $7::text[])
)
SELECT c.object_id,
       EXISTS (
        -- (1) прямой факт — на самом объекте ЛИБО на предке названного планом
        -- типа. Без второго администратор облака не увидел бы НИ ОДНОГО объекта:
        -- его строка лежит на кластере и под другим именем.
        SELECT 1
          FROM kaname.relation_fact f
          JOIN speaker sp ON sp.subject = f.subject
          JOIN scope_distinct sc
            ON sc.object_id = c.object_id
           AND sc.s_type = f.object_type AND sc.s_id = f.object_id
          JOIN fact_atom fa
            ON fa.relation = f.relation
           AND CASE WHEN fa.parent_type = ''
                    THEN sc.depth = 0
                    ELSE fa.parent_type = sc.s_type
               END
       )
    OR EXISTS (
        -- (2) выдача роли на область объекта или любого его предка. Глаголы —
        -- из плана: спрошенное имя не всегда равно глаголу, который обязана
        -- давать роль.
        SELECT 1
          -- Заход с пары «субъект + область»: оба предиката сужают набор ДО
          -- чтения строк, и оба стоят теперь на ОДНОМ отношении (миграция
          -- 732001). Склейка субъекта выводила колонки из-под индекса.
          FROM speaker_pair sp
          JOIN scope_distinct sc ON sc.object_id = c.object_id
          JOIN kaname.access_binding_subjects bs
            ON bs.subject_type  = sp.s_type AND bs.subject_id  = sp.s_id
           AND bs.resource_type = sc.s_type AND bs.resource_id = sc.s_id
          JOIN kaname.access_bindings b ON b.id = bs.binding_id
          JOIN kaname.role_verb rv
            ON rv.role_id = b.role_id AND rv.object_type = $9::text
           AND rv.verb = ANY ($8::text[])
          JOIN kaname.role_rule_selectors rs
            ON rs.role_id = b.role_id AND $9::text = ANY (rs.object_types)
         WHERE b.status = 'ACTIVE'
           AND (b.expires_at IS NULL OR b.expires_at > now())
           AND b.revoked_at IS NULL
           AND (
                 rs.arm = 'anchor'
              OR (rs.arm = 'names'  AND c.object_id = ANY (rs.resource_names))
              -- Проверки на отсутствие метки здесь больше нет, и это не
              -- послабление: она стерегла ПРОМАХ внешнего соединения, которого
              -- теперь не бывает by construction — кандидат и есть строка
              -- зеркала, а колонка меток объявлена NOT NULL. Оставить её значило
              -- бы держать ветвь, которая не может быть ложной, и следующий
              -- читатель искал бы случай, когда она срабатывает.
              OR (rs.arm = 'labels' AND c.labels @> rs.match_labels)
           )
       ) AS allowed
  FROM candidate c
 ORDER BY c.object_id`

// listQuerySQL — ГОТОВЫЙ запрос перечисления для выбранной оси кандидатов
// (довод — у expandQuerySQL).
func listQuerySQL(labelTable string) string {
	return strings.Replace(listSQL, candidateFromMark,
		candidateFrom(labelTable, "$9", "$3", "$4"), 1)
}

// List отдаёт страницу доступных объектов и курсор следующей.
//
// Курсор пуст, когда КАНДИДАТЫ ТИПА кончились, — это и есть конец обхода.
// Отдельного запроса «есть ли ещё» нет: он стоил бы столько же, сколько сама
// страница, и на последней странице — всегда впустую.
//
// Заходов может быть несколько, и это не то же самое, что «перечисли вселенную».
// Заход стоит ровно страницу и никогда больше; страница набирается повтором
// захода с продвинутым курсором, а не одним запросом на весь тип. Отсюда
// свойство, ради которого форма и переписана: цена ОДНОГО обращения к базе
// принадлежит запросу, а не набору, — а суммарная цена обхода остаётся ценой
// обхода, как у любого курсора.
//
// Заходы одной страницы читают своими снимками — ровно как страницы одного
// обхода читали ими всегда. Гарантия от этого не сузилась и остаётся той же:
// строка, существовавшая ВЕСЬ обход, не пропускается, потому что курсор
// продвигается монотонно и её диапазон будет осмотрен. Держать всю страницу в
// одном снимке значило бы обещать больше, чем обещает курсор между страницами, —
// то есть обещать разное на соседних границах одного и того же обхода.
func List(ctx context.Context, q pgx.Tx, in ListQuery) (ids []string, nextAfterID string, err error) {
	if in.Subject == "" || in.ObjectType == "" || in.Relation == "" {
		return nil, "", fmt.Errorf("relverdict: неполный вопрос перечисления %+v — пустая "+
			"часть делает ответ бессмысленным, а пустой список за него неотличим от "+
			"честного «ничего не доступно»", in)
	}
	limit := in.Limit
	if limit <= 0 {
		limit = DefaultPageSize
	}
	// Отношение, которого модель не знает, — ОШИБКА, а не пустая страница: пустую
	// страницу за опечатку в имени ищут в правах, где строки нет ни у кого.
	factParents, factRelations, bindVerbs, err := sourcesOf(in.ObjectType, in.Relation)
	if err != nil {
		return nil, "", err
	}
	// Имя типа в словаре КАТАЛОГА — у ЖИВОЙ строки каталога (kacho#1986). Читается
	// ОДИН раз на вызов, как и сборка запроса: заходов у обхода несколько, а тип у
	// них один. Стоит ПЕРЕД выбором оси: ось выбирается по этому же имени
	// (kacho#2036), и второго чтения каталога ради неё не заводится.
	catalogType, err := catalogTypeName(ctx, q, in.ObjectType)
	if err != nil {
		return nil, "", err
	}
	// Ось меток — и одновременно источник кандидатов: объект собственного типа iam
	// живёт в своей таблице целиком. Неназначенная ось — ошибка, а не пустая
	// страница (см. labelAxisOf).
	labelTable, err := labelAxisOf(catalogType, in.ObjectType)
	if err != nil {
		return nil, "", err
	}
	// Источник кандидатов собирается ОДИН раз на вызов, а не на каждый заход: ось
	// выбирается типом, а тип за время обхода не меняется. Заходы получают уже
	// собранный запрос — иначе одна и та же подстановка повторялась бы столько
	// раз, сколько заходов, и разойтись между ними ей было бы негде, зато
	// стоила бы она на каждом.
	//
	// Метка `{{labels_join}}` отсюда ушла вместе со своим предметом: метки едут
	// колонкой кандидата, второго чтения того же места больше нет.
	sql := listQuerySQL(labelTable)

	after := in.AfterID
	for {
		allowed, scanned, last, err := listSweep(ctx, q, sql, in, after, limit,
			factParents, factRelations, bindVerbs, catalogType)
		if err != nil {
			return nil, "", err
		}
		for _, id := range allowed {
			ids = append(ids, id)
			if len(ids) == limit {
				// Страница полна. Курсор — последний ОТДАННЫЙ идентификатор:
				// кандидаты за ним заход осмотрел, но вызывающему не показал, и
				// продвинуть курсор дальше значило бы их потерять.
				return ids, id, nil
			}
		}
		if scanned < limit {
			// Заход не заполнился: кандидатов этого типа за курсором больше нет.
			return ids, "", nil
		}
		after = last
	}
}

// listSweep — один заход: не более `size` кандидатов за курсором, каждый со своим
// ответом «доступен».
//
// Отдаёт ТРИ величины, и третья не выводима из первых двух: сколько кандидатов
// осмотрено (заход неполон ⇒ набор кончился) и каким кандидатом заход кончился
// (курсор следующего захода). Вернуть только доступных значило бы на заходе без
// единого доступного не знать, куда двигаться, — и обход объявил бы конец набора
// при живых правах.
//
// Запрос приходит ГОТОВЫМ, а не берётся из шаблона: источник кандидатов зависит
// от типа, и заход, собравший его сам, отвечал бы по оси зеркала на объекты,
// живущие в собственных таблицах iam, — то есть перечислял бы пустоту, называя
// это отказом в правах.
func listSweep(ctx context.Context, q pgx.Tx, sql string, in ListQuery, after string, size int,
	factParents, factRelations, bindVerbs []string, catalogType string,
) (allowed []string, scanned int, last string, err error) {
	rows, err := q.Query(ctx, sql,
		in.Subject, in.ObjectType, after, size, MaxAncestorDepth,
		factParents, factRelations, bindVerbs, catalogType)
	if err != nil {
		return nil, 0, "", fmt.Errorf("relverdict: перечисление: %w", err)
	}
	defer rows.Close()
	for rows.Next() {
		var (
			id string
			ok bool
		)
		if err := rows.Scan(&id, &ok); err != nil {
			return nil, 0, "", fmt.Errorf("relverdict: чтение строки: %w", err)
		}
		scanned++
		last = id
		if ok {
			allowed = append(allowed, id)
		}
	}
	if err := rows.Err(); err != nil {
		return nil, 0, "", fmt.Errorf("relverdict: обход: %w", err)
	}
	return allowed, scanned, last, nil
}
