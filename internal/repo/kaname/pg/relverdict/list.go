package relverdict

// list.go — перечисление объектов, доступных субъекту, СТРАНИЦЕЙ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЭТО ЧИНИТ
//
// У движка перечисление имеет ЖЁСТКИЙ серверный предел и не имеет продолжения:
// запрос вообще не несёт поля страницы, поэтому «лимит» на стороне клиента —
// лишь обрезка уже усечённого ответа. Следствие наблюдалось вживую: ресурсы
// сверх предела становились владельцу НЕВИДИМЫ навсегда при живых правах, а
// предел был общим на тип, а не по-арендаторным — то есть величиной, на которую
// в многоарендной системе закладываться нельзя вовсе.
//
// Здесь предела нет by construction: это наш запрос к нашей таблице, и страница
// делается курсором так же, как везде. Контракт RPC уже несёт
// `next_page_token` — движок его просто не мог заполнить.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ КУРСОР ПО ИДЕНТИФИКАТОРУ, А НЕ СМЕЩЕНИЕ
//
// Смещение теряет строки при вставке между страницами и повторяет при удалении.
// Курсор по возрастающему идентификатору не пропускает ни одной строки, которая
// существовала весь обход, — та же дисциплина, что у списочных RPC продукта.
//
// ─────────────────────────────────────────────────────────────────────────────
// СТОИМОСТЬ СТРАНИЦЫ ПРИНАДЛЕЖИТ ЗАПРОСУ, А НЕ НАБОРУ
//
// Кандидаты ограничиваются страницей и курсором В САМОМ ЗАПРОСЕ — до того, как
// раскрутится цепь областей. Иначе выходит «перечисли вселенную → отфильтруй»:
// цепь предков строится для КАЖДОГО объекта типа, страница режется последним
// действием, и один и тот же ответ дорожает с ростом набора при неизменной
// странице. Измерено: на десяти тысячах объектов та же страница читала на
// порядок больше строк, чем на тысяче, и величина не менялась от размера
// страницы вовсе — верный признак того, что предел применялся ПОСЛЕ работы.
//
// Отсюда две вещи, которые обязаны читаться вместе:
//
//   - запрос отдаёт ЗАХОД по кандидатам (не более страницы), помечая каждого
//     «доступен/нет», а страницу набирает Go, повторяя заход с продвинутым
//     курсором. Число заходов ограничено числом кандидатов, а стоимость одного —
//     размером страницы;
//   - НАРУЖУ курсором уезжает последний ОТДАННЫЙ идентификатор, а не последний
//     осмотренный кандидат. Продвижение по кандидатам живёт внутри вызова и
//     наружу не выходит: иначе кандидаты, осмотренные заходом после того, как
//     страница заполнилась, оказались бы за курсором, которого вызывающий не
//     видел, — то есть были бы пропущены. Побочно это оставляет закрытым и то,
//     что курсорная семантика вообще-то разрешает раскрыть (`security.md`:
//     продолжение вправе кодировать недоступную строку); здесь такой нужды нет.

