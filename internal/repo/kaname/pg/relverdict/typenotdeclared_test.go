package relverdict

import (
	"context"
	"testing"
)

// Вопрос про НЕОБЪЯВЛЕННЫЙ тип объекта — отказ, а не ошибка (#880).
//
// ПОЧЕМУ БЕЗ БАЗЫ. Оба вопроса ниже отклоняются ДО первого обращения к
// хранилищу: план строится раньше запроса. Поэтому транзакция здесь `nil` — и
// это не уловка, а утверждение о порядке: дойди хоть один из них до базы,
// проба упала бы разыменованием, и мы узнали бы, что порядок изменился.
func TestAsk_UndeclaredTypeIsADenial(t *testing.T) {
	ctx := context.Background()

	// (а) снятый тип-носитель точечных выдач: объектов такого типа не
	// существует ⇒ ни у кого нет на них никакого отношения ⇒ ОТКАЗ.
	v, g, err := Ask(ctx, nil, Query{
		Subject: "user:usr-x", ObjectType: "scope_grant",
		ObjectID: "account|acc-1|compute_instance", Relation: "admin",
	})
	if err != nil {
		t.Errorf("необъявленный тип: err = %v, а ожидался чистый отказ — "+
			"иначе «нет прав» неотличимо от «сломалось»", err)
	}
	if v != Deny {
		t.Errorf("необъявленный тип: вердикт = %s, ожидался %s", v, Deny)
	}
	if !g.TypeNotDeclared {
		t.Errorf("отказ по необъявленному типу обязан называть своё основание: " +
			"без него опечатка в имени типа настоящего ресурса утонет в тихом отказе")
	}

	// (б) ЗАКОННЫЙ БЛИЗНЕЦ: объявленный тип с несуществующим отношением —
	// по-прежнему ОШИБКА. Без этой половины проверка ловила бы любой отказ
	// компиляции и превращала бы в «нет» в том числе настоящую поломку.
	if _, _, err := Ask(ctx, nil, Query{
		Subject: "user:usr-x", ObjectType: "account",
		ObjectID: "acc-1", Relation: "no_such_relation",
	}); err == nil {
		t.Errorf("объявленный тип с чужим отношением обязан оставаться ошибкой: " +
			"«Unknown — не нет» продолжает действовать там, где форма правда не смогла ответить")
	}
}
