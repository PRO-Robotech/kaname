// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ СТРОКА В КОМПОЗИЦИОННОМ КОРНЕ
//
// Предмет переписи — ЧТО она называет, и это утверждение проверяется без базы:
// три состояния разности, оба числа рядом и отличие «чисто» от «пусто» суть
// свойства текста. Написанная по месту в корне, она проверялась бы только
// подъёмом стенда — то есть не проверялась бы.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОБА ЧИСЛА, А НЕ ОДНО
//
// «Разности нет» и «зеркало пусто» дают ОДИНАКОВЫЙ ноль находок и разные
// утверждения о стенде. Перепись называет объём осмотренного рядом с числом
// найденного, поэтому ноль находок отличим от нуля прочитанного.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ НЕРАЗРЕШИМОЕ СЧИТАЕТСЯ ОТДЕЛЬНО
//
// Снятое С ПРЕЕМНИКОМ — объявленное свойство дерева, а не дефект: строка
// переживает снятие намеренно, и каталог называет, куда её переселять. Слить
// его с неразрешимым значило бы назвать находкой исправное состояние сразу
// после всякого законного снятия типа.

import (
	"fmt"
	"strings"
)

// DivergenceCensus — перепись разности одной строкой.
//
// Принимает ровно то, что отдаёт [Divergence], и ничего не спрашивает сам:
// вызывающий уже заплатил за запрос, а второй запрос ради отчёта дал бы второе
// измерение того же предмета — они разошлись бы на первой же записи зеркала.
//
// Пустая разность при нуле осмотренных типов — НЕ «чисто»: зеркало пусто, и
// всякое отрицание о нём сказано ни о чём.
func DivergenceCensus(rows []DivergenceRow, scanned int) string {
	if scanned == 0 {
		return "зеркало пусто: различных типов осмотрено 0 — утверждать о разности нечего"
	}

	unresolvable := UnresolvableDivergence(rows)
	head := fmt.Sprintf("различных типов зеркала осмотрено %d · разность %d · неразрешимых %d",
		scanned, len(rows), len(unresolvable))
	if len(rows) == 0 {
		return head
	}

	var unres, succeeded []string
	for _, r := range rows {
		switch r.State {
		case CatalogRetiredSucceeded:
			succeeded = append(succeeded,
				fmt.Sprintf("%s (строк %d) → %s", r.ObjectType, r.Rows, r.SupersededBy))
		default:
			unres = append(unres,
				fmt.Sprintf("%s (строк %d, %s)", r.ObjectType, r.Rows, r.State))
		}
	}

	out := head
	if len(unres) > 0 {
		// Неразрешимое называется ПЕРВЫМ и поимённо: по каждой такой строке
		// решение принимает владелец, и без имени типа ему нечего решать.
		out += "; исхода нет у: " + strings.Join(unres, ", ")
	}
	if len(succeeded) > 0 {
		out += "; переселимо: " + strings.Join(succeeded, ", ")
	}
	return out
}
