package resource_mirror

// parent_edge_test.go — разбор ссылки на предка отвергает непонятое, а не
// пропускает.
//
// # Предмет
//
// Цепь предков приходит списком строк `"<type>:<id>"`. Звено, форму которого не
// удалось понять, обязано быть ОТКАЗОМ: пропущенное звено делает цепь короче
// настоящей, и объект оказывается под тем предком, под которым он не находится.
// Область выдачи тогда «совпадает» с ожиданием ровно потому, что про звено не
// спросили — тот же класс, что молчаливое проглатывание непонятого термина в
// компиляторе модели.
//
// Проба на разборе, а не на записи: запись требует Postgres и живёт в
// интеграционном прогоне, а свойство «непонятое отвергается» — свойство чистой
// функции, и проверять его контейнером значило бы платить минуты за то, что
// решается микросекундами.

import "testing"

func TestSplitObjectRefRefusesWhatItCannotUnderstand(t *testing.T) {
	good := []struct{ in, typ, id string }{
		{"project:prj-abc", "project", "prj-abc"},
		{"registry_registry:reg-1", "registry_registry", "reg-1"},
		// Двоеточие внутри идентификатора — разделитель ПЕРВЫЙ, остаток целиком id.
		{"account:acc:weird", "account", "acc:weird"},
	}
	for _, c := range good {
		typ, id, ok := splitObjectRef(c.in)
		if !ok || typ != c.typ || id != c.id {
			t.Errorf("%q → (%q,%q,%v), ожидалось (%q,%q,true)", c.in, typ, id, ok, c.typ, c.id)
		}
	}

	bad := []string{
		"",         // пусто
		"project",  // нет разделителя
		":prj-abc", // нет типа
		"project:", // нет идентификатора
	}
	for _, in := range bad {
		if _, _, ok := splitObjectRef(in); ok {
			t.Errorf("%q принято за ссылку на предка — непонятая форма обязана быть отказом: "+
				"пропущенное звено делает цепь короче настоящей, и объект оказывается под тем "+
				"предком, под которым он не находится", in)
		}
	}

	t.Logf("осмотрено: законных форм %d, непонятых %d", len(good), len(bad))
}
