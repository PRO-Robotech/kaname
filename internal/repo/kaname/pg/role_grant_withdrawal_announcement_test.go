// role_grant_withdrawal_announcement_test.go — ОБЪЯВЛЕНИЕ ОТЗЫВА ГОВОРИТ СЛОВАМИ
// ЖУРНАЛА, а не своими (задача службы #76).
//
// Пакет внутренний (`pg`): предмет — неэкспортируемый оператор.
//
// # Предмет
//
// Оператор пишет в чужую таблицу — в журнал подписки, — и всякое слово, которым
// он это делает, УЖЕ объявлено: вид предмета объявляет владелец журнала, род
// изменения объявляет контракт подписки, якорь и области считают функции самого
// журнала. Выписанное здесь вторично, любое из них стало бы вторым местом об
// одном предмете. Разошлись бы они МОЛЧА: строка с видом вне словаря не имеет
// типа объекта модели прав, поэтому подписчику не доставляется вовсе, а ключ
// базы на это не жалуется — вид закрыт `CHECK`, и опечатка внутри словаря
// (скажем, чужой, но законный вид) прошла бы и его.
//
// # Чем эта проба ОШИБАЛАСЬ САМА — названо, потому что класс её же и ловит
//
// Первая редакция судила вид словом «встречается в операторе». Инъекция чужого
// вида в колонку `resource_kind` её НЕ покраснила: тем же словом оператор зовёт
// производителей якоря и областей, и вхождение оставалось на месте. То есть
// проверка судила не тем, что продукт К ПРЕДМЕТУ ПРИМЕНЯЕТ, а тем, что где-то
// написано. Теперь вид судится В ПОЗИЦИИ колонки, а чужие виды закрытого словаря
// отвергаются поимённо — и обе половины доказаны инъекцией.
//
// # Чего эта проба НЕ утверждает
//
// Она не судит ПОВЕДЕНИЕ: что событие рождается ровно на отзыве, ровно одно на
// роль и транзакцию и уходит вместе с откатом — свойства прогона, и держит их
// `role_grant_withdrawal_reaches_the_subscriber_integration_test.go`. Здесь
// утверждается только СЛОВАРЬ: что оператор говорит теми же словами, которыми
// говорит журнал.

import (
	"strings"
	"testing"

	subscriptionv1 "github.com/PRO-Robotech/corelib/api/corelib/subscription"

	"github.com/PRO-Robotech/kaname/internal/subscriptionjournal"
)

// TestWithdrawalAnnouncementSpeaksTheJournalsWords — каждое слово оператора
// приходит от своего объявления, а не выписано рядом.
func TestWithdrawalAnnouncementSpeaksTheJournalsWords(t *testing.T) {
	stmt := announceRoleGrantWithdrawalSQL
	if strings.TrimSpace(stmt) == "" {
		t.Fatal("оператор объявления отзыва пуст: всякое вхождение ниже выполнялось бы " +
			"тривиально, и проба утверждала бы о словаре, ничего не проверив")
	}

	bindings := []struct {
		// what — что связывается.
		what string
		// want — вхождение, которого требует объявление-владелец.
		want string
		// why — чем платим, разойдясь.
		why string
	}{
		{
			what: "дом журнала",
			want: "INSERT INTO " + subscriptionjournal.Table,
			why: "оператор пишет не в тот журнал: у службы шесть очередей с окончанием " +
				"`_outbox`, и ни одна лентой изменений не является",
		},
		{
			// Вид судится В ТОЙ ПОЗИЦИИ, где он становится колонкой `resource_kind`,
			// а не «встречается где-нибудь». Разница не стилистическая: тем же
			// словом оператор зовёт производителей якоря и областей, поэтому
			// проверка «вхождение есть» остаётся зелёной, когда в журнал ложится
			// ЧУЖОЙ вид, — измерено инъекцией, см. шапку §«Чем эта проба
			// ошибалась сама».
			what: "вид предмета В ПОЗИЦИИ `resource_kind`",
			want: "SELECT '" + subscriptionjournal.KindRole + "', r.id,",
			why: "строка с чужим видом уезжает подписчику ЧУЖОГО вида: у роли его " +
				"выборка не спросит никогда, а тот, кто спросит, получит " +
				"идентификатор, которого у него нет. Ключ на это не жалуется — вид " +
				"закрыт `CHECK`, и чужой, но законный проходит его",
		},
		{
			what: "род изменения",
			want: "'" + subscriptionv1.SubscriptionEvent_UPDATED.String() + "'",
			why: "отзыв части прав есть ПРАВКА роли, а не её снятие: словом `DELETED` " +
				"подписчик убрал бы у себя живую роль",
		},
		{
			what: "производитель якоря",
			want: "kaname.resource_journal_project(",
			why: "якорь, выведенный здесь вторично, стал бы вторым правилом вывода и " +
				"разошёлся бы с триггером на первом же ярусе объявления роли",
		},
		{
			what: "производитель областей",
			want: "kaname.resource_journal_scope(",
			why: "то же у набора областей: обе величины суть значения одного типа, и " +
				"расхождение не видно ничем",
		},
		{
			what: "отбор по первичному ключу",
			want: "r.id = ANY(",
			why: "на этом стоит «ровно одно событие на роль и транзакцию»: три популяции " +
				"кладут роли встык, и единственность даёт ключ `roles`, а не сведение " +
				"множеств на языке Go",
		},
	}

	if len(bindings) == 0 {
		t.Fatal("связей осмотрено ноль — проба не читала объявлений, и её молчание " +
			"ничего не значит")
	}

	for _, b := range bindings {
		if strings.TrimSpace(b.want) == "" {
			t.Fatalf("объявление %q дало пустое вхождение: `strings.Contains` истинно "+
				"всегда, и связь не проверялась бы вовсе", b.what)
		}
		if !strings.Contains(stmt, b.want) {
			t.Errorf("оператор объявления отзыва не содержит %s (%q).\nЦена расхождения: %s.\n"+
				"Правь оператор под объявление-владельца, а не наоборот.", b.what, b.want, b.why)
		}
	}

	// ЧУЖОГО вида в операторе быть не должно НИ ОДНОГО: словарь журнала закрыт,
	// и всякое второе слово из него означает, что оператор говорит о другом
	// предмете — хотя бы в одной из трёх своих позиций.
	foreign := map[string]string{
		subscriptionjournal.KindAccount:        "account",
		subscriptionjournal.KindProject:        "project",
		subscriptionjournal.KindUser:           "iam_user",
		subscriptionjournal.KindGroup:          "iam_group",
		subscriptionjournal.KindServiceAccount: "iam_service_account",
		subscriptionjournal.KindAccessBinding:  "iam_access_binding",
	}
	if len(foreign) != 6 {
		t.Fatalf("словарь видов журнала — семь, чужих обязано быть шесть, а взято %d: "+
			"перечень разошёлся с владельцем, и отрицание ниже неполно", len(foreign))
	}
	for kind := range foreign {
		if kind == subscriptionjournal.KindRole {
			t.Fatalf("вид роли попал в перечень ЧУЖИХ: отрицание отвергло бы верный оператор")
		}
		if strings.Contains(stmt, "'"+kind+"'") {
			t.Errorf("оператор называет чужой вид %q: он говорит о другом предмете "+
				"хотя бы в одной из трёх своих позиций (колонка вида, аргумент якоря, "+
				"аргумент областей), и разойтись они могут молча", kind)
		}
	}

	// Второго вывода якоря и областей быть не должно: он читал бы поля строки сам.
	// Признак — извлечение поля из json (`->>`); у оператора его нет ни одного,
	// потому что обе величины считают функции журнала, а нагрузка собирается из
	// колонки напрямую.
	if n := strings.Count(stmt, "->>"); n != 0 {
		t.Errorf("оператор извлекает поля строки сам (%d вхождений `->>`): якорь и области "+
			"обязаны приходить от функций журнала, иначе у них заводится второй "+
			"производитель", n)
	}

	t.Logf("связей с объявлениями-владельцами проверено: %d; чужих видов осмотрено: %d; "+
		"найдено чужих: %d; собственных извлечений поля: %d",
		len(bindings), len(foreign), foreignFound(stmt, foreign), strings.Count(stmt, "->>"))
}

// foreignFound — сколько чужих видов оператор называет. Перепись печатает ОБЕ
// величины — осмотренное и найденное, — иначе «ноль находок» неотличимо от
// «ноль прочитанного».
func foreignFound(stmt string, foreign map[string]string) int {
	n := 0
	for kind := range foreign {
		if strings.Contains(stmt, "'"+kind+"'") {
			n++
		}
	}
	return n
}
