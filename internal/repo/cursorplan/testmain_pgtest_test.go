package cursorplan_test

import (
	"os"
	"testing"

	"github.com/PRO-Robotech/kacho/pkg/pgtest"
)

// TestMain выдаёт пакету ОДИН Postgres.
//
// `Migrate` нет намеренно: проба применяет цепочку сама и потому обязана
// начинать с ПУСТОЙ базы — пре-мигрированный шаблон не оставил бы ей того, о чём
// она спрашивает. Контейнер поднимается лениво, поэтому под `-short`, где проба
// пропускается, не поднимается вовсе.
//
// # Почему проба живёт ЗДЕСЬ, а не рядом с миграциями
//
// Отбор интеграционной джобы идёт ПО ПУТИ и сужен до
// `services/<svc>/internal/(repo|clients|reconciler)`. Пакет миграций в него не
// входит: все семь таких пакетов дерева числятся долгом в
// `shortGatedOutsideSelection` — под кратким они пропускаются, а без краткого их
// не гоняет ни одна джоба. Положить доказательство действия туда значило бы
// написать пробу, которая исполнилась один раз на машине автора.
//
// Соседний `services/<svc>/internal/repo` для этого не годится по другой
// причине: у него своя тяжёлая фикстура на каждую пробу, и пакет уже упирался в
// собственный предел времени. Отдельный пакет даёт и отбор джобы, и свой
// контейнер, ни на кого не влияя.
func TestMain(m *testing.M) {
	os.Exit(pgtest.Run(m, pgtest.Config{Name: "iamcursorplan"}))
}
