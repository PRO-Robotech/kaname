package errors_test

// client_refusal_reason_coverage_test.go — РЕШЕНИЕ О ЯЗЫКЕ КЛИЕНТСКИХ ОТКАЗОВ
// и предикат, которым оно исполняется.
//
// ── ЧТО ИЗМЕРЕНО ────────────────────────────────────────────────────────────
//
// Продукт говорит с клиентом по-русски везде, кроме момента отказа: консоль и
// документация русские целиком, а среди текстов, рождающихся для клиента,
// кириллицы НОЛЬ. Предикат обратной стороны показывает, что искать умеет:
// кириллических литералов в дереве службы сотни, и все адресованы оператору.
//
// Несущее утверждение — «арендатор действительно читает английскую строку» —
// проверено там, где оно решается, а не по литералам службы:
//
//   - край сообщение НЕ переписывает: `runtime.NewServeMux` собирается БЕЗ
//     `WithErrorHandler`, поэтому текст службы уходит в тело ответа как есть;
//   - консоль признак отказа со своим словарём НЕ сопоставляет: словарь
//     «признак → русский текст» в её исходниках отсутствует, а показывает она
//     `err.message` — то есть ту же английскую строку — с общим русским
//     запасным вариантом. Это закреплено её собственной пробой, объявляющей
//     сообщение бэкенда контракт-тоном.
//
// Значит посылка задачи ВЕРНА, а исход «перевод живёт на клиентской
// поверхности» сегодня не выполнен: его предусловия не существует.
//
// ── РЕШЕНИЕ ─────────────────────────────────────────────────────────────────
//
// ТЕКСТ НА ПРОВОДЕ ОСТАЁТСЯ АНГЛИЙСКИМ И СТАБИЛЬНЫМ; РУССКИЙ ТЕКСТ ПРОИЗВОДИТ
// КЛИЕНТСКАЯ ПОВЕРХНОСТЬ ИЗ МАШИННОГО ПРИЗНАКА ОТКАЗА.
//
// Почему не перевод текстов на месте — три довода, и каждый самостоятельно
// достаточен:
//
//  1. тексты отказов ЕСТЬ КОНТРАКТ (`api-conventions.md` §Error-format), и
//     читает их не только консоль: провайдер инфраструктуры, сквозные наборы,
//     docker-клиент, скрипты арендатора. Перевод меняет контракт у всех сразу;
//  2. «перевести часть» исходом не является, а перевести всё — значит завести
//     ВЫБОР ЯЗЫКА на проводе. Тогда у одного отказа две редакции, и всякое
//     утверждение о тексте (а ими держится тон) становится условным: проба
//     обязана ещё и зафиксировать язык, иначе она проверяет неизвестно что;
//  3. язык сообщения — забота ПРЕДСТАВЛЕНИЯ. Перенеся её на провод, мы кладём
//     её в контракт навсегда: снять оттуда нельзя, не сломав клиентов.
//
// Что из этого следует как РАБОТА (и почему она не сделана здесь): исход
// исполним ровно настолько, насколько у отказа есть машинный признак полосы.
// Признака нет — консоли не из чего производить русский текст, и она обязана
// показать строку с провода. Поэтому предикат решения — покрытие признаком, и
// он измеряется ниже.
//
// ── ЧТО ЭТА ПРОБА ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ ───────────────────────────────────
//
// Делает: печатает ОБЕ величины (отказов N, несущих признак M) и падает, когда
// покрытие УМЕНЬШАЕТСЯ. Одно число скрыло бы ровно тот случай, ради которого
// перепись заводится.
//
// НЕ делает: не требует стопроцентного покрытия сегодня. Требование, которое
// дерево заведомо не удовлетворяет, обвалило бы прогон и было бы снято первым
// же следующим — то есть держалось бы ноль дней. Довести покрытие до ста
// процентов — отдельная работа с объёмом, названным здесь числом.

import (
	"sort"
	"strings"
	"testing"
)

// reasonedProducers — построения отказа, у которых машинный признак полосы
// (`google.rpc.ErrorInfo.reason`) есть уже сегодня.
var reasonedProducers = map[string]string{
	"ErrQuotaExceeded":       "QUOTA_EXCEEDED",
	"ErrQuotaRateExceeded":   "QUOTA_RATE_EXCEEDED",
	"ErrQuotaNotProvisioned": "QUOTA_NOT_PROVISIONED",
	"ErrReferenceMissing":    "REFERENCE_MISSING",
	"ErrReferenceInUse":      "REFERENCE_IN_USE",
	// Отказ в правах получает признак на транспортном краю службы
	// (`authzguard.DenyDetailUnary`) — по имени метода, единым местом на все
	// сайты сразу, включая те, что добавят позже.
	"codes.PermissionDenied": "AUTHZ_DENIED",
	// Признак ставится по КОДУ отказа, поэтому обе формы построения — прямая и
	// через признак-родитель — попадают под одно и то же перо перехватчика.
	"ErrPermissionDenied": "AUTHZ_DENIED",
}

// reasonCoverageFloor — ИЗМЕРЕННЫЙ пол покрытия (28 из 351 на ревизии этой
// правки; было 26 — две полосы ссылки добавлены здесь же).
//
// Пол, а не цель: он существует затем, чтобы покрытие не УМЕНЬШИЛОСЬ незаметно.
// Поднимать его следует тем же изменением, которое поднимает покрытие, — иначе
// он превратится в число, которое ничего не держит.
//
// Число названо здесь ОРИЕНТИРОМ объёма оставшейся работы, а не нормативом:
// «сто процентов» требует признака у каждого построения из перечня, который
// проба печатает, и это отдельная работа.
const reasonCoverageFloor = 28

func TestClientRefusalReasonCoverageDoesNotRegress(t *testing.T) {
	texts := collectClientTexts(t)
	if len(texts) == 0 {
		t.Fatal("клиентских текстов прочитано 0 — вердикт беспредметен")
	}

	reasoned := 0
	byProducer := map[string]int{}
	for _, ct := range texts {
		byProducer[ct.producer]++
		if _, ok := reasonedProducers[ct.producer]; ok {
			reasoned++
		}
	}

	// Перечень построений печатается целиком: он и есть объём оставшейся
	// работы, и без него «признака нет у стольких-то» — число без предмета.
	var producers []string
	for p := range byProducer {
		if _, ok := reasonedProducers[p]; ok {
			continue
		}
		producers = append(producers, p)
	}
	sort.Strings(producers)

	t.Logf("перепись: клиентских текстов %d · несут машинный признак полосы %d · без признака %d",
		len(texts), reasoned, len(texts)-reasoned)
	t.Logf("построения БЕЗ признака (это и есть объём работы по переводу на клиентской поверхности): %s",
		strings.Join(producers, ", "))

	// Отрицание в паре с положительным: перепись обязана быть непустой в ОБЕ
	// стороны, иначе «покрытие не упало» зеленело бы на пустом обходе.
	if reasoned == 0 {
		t.Fatal("ни один отказ не несёт машинного признака — разбор разошёлся с деревом")
	}
	if len(producers) == 0 {
		t.Fatal("построений без признака 0 — либо работа окончена (тогда поднимите пол " +
			"и снимите этот отказ), либо разбор разошёлся с деревом")
	}

	if reasoned < reasonCoverageFloor {
		t.Fatalf("покрытие машинным признаком УМЕНЬШИЛОСЬ: %d при поле %d.\n"+
			"Русский текст отказа производит консоль ИЗ ПРИЗНАКА; отказ без признака она показать "+
			"по-русски не может и покажет строку с провода.", reasoned, reasonCoverageFloor)
	}
}
