// objecttype.go — таблица ТИПОВ ОБЪЕКТА разомкнута: оператор чужого облака
// объявляет свой РЕСУРС доставкой, а не пересборкой образа.
//
// Задача продукта #2015. Соседние полосы разомкнули то же самое у МОДУЛЕЙ
// (moduleset.go) и перевели опору паритета каталога на «образ ∪ доставка»; эта —
// последний замок: продукт принимал модуль и отвергал то, ради чего модуль
// объявляют.
//
// # Что здесь было и почему снято
//
// `objectType` каждой записи проверялся на ЧЛЕНСТВО в закрытой таблице
// `authzmap`, ПОРОЖДЁННОЙ сборкой из манифестов НАШЕГО дерева. Тип, которого в
// нашем дереве нет, был поэтому невыразим ни при каком входе, и отказ звучал
// «типа "acme_widget" нет в закрытой таблице типов iam» — то есть называл
// перечень, недоступный автору манифеста и не меняемый ничем, кроме релиза.
//
// # Три вопроса об имени типа, и у каждого свой судья
//
//	как называется     ФОРМА — `domain.IsWellFormedObjectTypeName`, грамматика
//	                   объявлена ОДНАЖДЫ и судит оба поля: `objectType` ресурса и
//	                   тип его указателя. Та же грамматика держит колонку
//	                   `catalog_resource.object_type` ограничением базы;
//	чей он              ВЛАДЕНИЕ — тип, который ОБРАЗ уже несёт, вправе объявить
//	                   только ТА ЖЕ строка, что несёт его в образе. Иначе —
//	                   находка, называющая ОБЕ стороны;
//	один ли у него дом  СТОЛКНОВЕНИЕ — тип, объявленный больше чем одной строкой
//	                   (двумя ресурсами документа либо двумя манифестами одного
//	                   обхода), есть находка, называющая ОБА места.
//
// # Существование типа НЕ спрашивается ни у кого — и это не послабление
//
// Ресурс, объявляющий тип, тем самым его и ЗАВОДИТ: строка каталога несёт имя
// типа СВОИМ полем (`catalog.ResourceRow.ObjectType`), а блок модели прав
// порождается рендером из того же объявления. Спрашивать «а существует ли такой
// тип» значило бы спрашивать у собственного ответа — тот же круг, что уже
// разобран у модулей.
//
// Судьёй существования при этом становятся строки каталога плюс объявления
// ЭТОЙ ЖЕ доставки, и второе покрывает первое by construction: каталог доставки
// — ЗАКРЫТЫЙ НАБОР (delivery.go), всё, что модулем является, лежит в нём
// манифестом, и отсутствие манифеста снятием модуля НЕ является (`#1034`).
// Поэтому отдельной ручки «внести живые строки каталога» здесь не заводится:
// она не давала бы ни одного типа сверх объявленных обходом, а ручка без
// читателя есть мёртвый страж.
//
// # Монотонность — ТА ЖЕ, что у допуска собранной модели прав
//
// Устройство взято у близнеца (`composed-model-admits-only-what-it-owns.md`) и
// не изобретается заново: доставка вправе ДОБАВИТЬ тип, которого образ не несёт,
// и НЕ вправе изменить объявление, которое образ уже несёт.
//
// Цена нарушения названа, потому что она не косметическая. Строка каталога несёт
// имя типа модели прав, и отношение `v_<глагол>` адресуется ИМЕННО ИМ. Присвой
// оператор своей строке чужой тип — правило его роли выдало бы пообъектные права
// на объекты, которых его модуль не создавал; манифесты же есть ДАННЫЕ оператора,
// а не релиз. Тот же довод стоит у опоры паритета (`ErrAnchorRedefinesImage`), и
// закрывают они разные половины одного предмета: та — форму строки образа, эта —
// присвоение чужого типа новой строкой.
//
// # Чего эта дверь НЕ открывает
//
// Указатель ресурса резолвится по типам ТОГО ЖЕ документа, а не всего обхода.
// Замер по дереву: указателей на тип (а не на якорь области) — ОДИН на шесть
// манифестов (`registry.repositories` → `registry_registry`), и он внутридокументный;
// междоменного указателя нет ни одного. Открой я обход — заведомо разрешил бы
// иерархию через границу модуля, которой сегодня нет и решения о которой никто не
// принимал.

// imageOwnerOf — точечный ключ, которым ОБРАЗ адресует этот тип, и признак того,
// что образ его вообще несёт.
//
// Обращение к порождённой сборкой таблице осталось РОВНО ОДНО и означает теперь
// другое: не «существует ли тип», а «не занят ли он образом».
func imageOwnerOf(objectType string) (dotted string, shipped bool) {
	return authzmap.DottedType(objectType)
}

// objectTypeFault — суждение о ТИПЕ одного ресурса: форма и владение.
//
// Возвращает `nil`, когда судить не о чем. Отдельная функция, а не ветвь внутри
// разбора указателей: у неё два предиката и два разных отказа, и вызывающему
// (`validateResourceAnchors`) остаётся только назвать координату.
func objectTypeFault(module, resource, objectType string, guardsImage bool) (error, bool) {
	if !domain.IsWellFormedObjectTypeName(objectType) {
		return fmt.Errorf("%w: тип %q не годен по форме; принимается %s — строчная латиница, "+
			"цифры и подчёркивание, первым знаком буква. Той же формой держит имя типа "+
			"колонка каталога (`catalog_resource_object_type_form`) и строка `type` модели "+
			"прав, поэтому имя иной формы отвергла бы база ключом либо допуск модели",
			ErrObjectTypeMalformed, objectType, domain.ObjectTypeNameGrammar()), true
	}
	if !guardsImage {
		return nil, false
	}
	own := module + "." + resource
	if dotted, shipped := imageOwnerOf(objectType); shipped && dotted != own {
		return fmt.Errorf("%w: тип %q образ объявляет строкой [%s], доставка — строкой [%s]. "+
			"Доставка вправе ДОБАВИТЬ тип, которого образ не несёт, и не вправе присвоить своей "+
			"строке тип чужой: отношение `v_<глагол>` адресуется именно именем типа, и права по "+
			"такой строке материализовались бы на объектах, которых этот модуль не создавал",
			ErrObjectTypeRedefinesImage, objectType, dotted, own), true
	}
	return nil, false
}

// declaredTypesOf — типы, объявленные ресурсами ОДНОГО документа, и находки
// столкновения внутри него.
//
// Находка называет ОБА индекса: названный первый заставил бы автора чинить их по
// одному, по прогону на каждый, и не сказал бы, с чем именно столкнулся ресурс, —
// а какой из двух лишний, решает человек, и решать он вправе только увидев оба.
//
// Негодное по форме имя в перечень НЕ ПОПАДАЕТ: его отвергает [objectTypeFault]
// своей причиной, и признать его здесь значило бы дать указателю сослаться на
// тип, которого установка не примет.
func declaredTypesOf(m *Manifest) (map[string]struct{}, []collidingType) {
	set := make(map[string]struct{}, len(m.Resources))
	first := make(map[string]int, len(m.Resources))
	var collisions []collidingType

	for i := range m.Resources {
		typ := m.Resources[i].ObjectType
		if typ == "" || !domain.IsWellFormedObjectTypeName(typ) {
			continue
		}
		if at, seen := first[typ]; seen {
			collisions = append(collisions, collidingType{Type: typ, First: at, Second: i})
			continue
		}
		first[typ] = i
		set[typ] = struct{}{}
	}
	return set, collisions
}

// collidingType — один тип, объявленный двумя ресурсами одного документа.
type collidingType struct {
	Type   string
	First  int
	Second int
}

// declaredObjectTypes — находки столкновения через ОБХОД: один тип, объявленный
// манифестами РАЗНЫХ модулей.
//
// Одного документа для этого вопроса мало by construction, поэтому судит его
// обход (check.go), а не [Load] — ровно как у имени модуля.
//
// Находка называет ОБА пути по тому же доводу, что и внутри документа.
func declaredObjectTypes(paths []string, docs [][]byte) []string {
	where := make(map[string]string, len(docs))
	var findings []string

	for i, data := range docs {
		for _, typ := range peekObjectTypes(data) {
			if !domain.IsWellFormedObjectTypeName(typ) {
				continue
			}
			if firstPath, seen := where[typ]; seen {
				if firstPath == paths[i] {
					// Столкновение внутри одного документа — предмет [Load]:
					// он видит индексы ресурсов, а обход видит только пути, и
					// вторая находка о том же месте была бы вторым отказом об
					// одном предмете.
					continue
				}
				findings = append(findings, fmt.Sprintf(
					"%s: %v: тип %q уже объявлен манифестом %s — у типа объекта один "+
						"владелец; права, выданные на одну строку, материализовались бы на "+
						"объектах другой, а чья строка каталога доедет до применителя, решал "+
						"бы порядок обхода каталога",
					paths[i], ErrObjectTypeCollision, typ, firstPath))
				continue
			}
			where[typ] = paths[i]
		}
	}
	sort.Strings(findings)
	return findings
}

// peekObjectTypes — типы объекта, названные документом, БЕЗ суждения обо всём
// остальном.
//
// Нужно обходу по тому же доводу, что и [PeekModule]: перечень объявленных типов
// обязан быть известен ДО того, как хоть один документ будет судим целиком, —
// иначе вердикт о столкновении стал бы функцией порядка обхода.
//
// # Почему это НЕ второй словарь
//
// Разбор идёт в ТУ ЖЕ структуру [Manifest] и потому читает ТОТ ЖЕ yaml-тег:
// второго объявления имени ключа здесь не заводится, и разойтись ему не с чем.
// Держит это утверждение проба, а не эта фраза (`peekobjecttypes_internal_test.go`).
//
// Отказ разбора ПРОГЛАТЫВАЕТСЯ, и это не мягкий проход: документ, который не
// разобрался, до [Load] всё равно дойдёт и будет назван находкой. Молчаливо
// пропущен ровно его вклад в перечень объявленных, а негодный документ перечня
// и не образует.
func peekObjectTypes(data []byte) []string {
	var m Manifest
	// Исход разбора здесь НЕ читается намеренно: документ, который не
	// разобрался, типов не даст — срез останется пустым, — а находкой его
	// назовёт [Load] на второй ступени обхода.
	_ = yaml.Unmarshal(data, &m)
	out := make([]string, 0, len(m.Resources))
	for i := range m.Resources {
		if t := m.Resources[i].ObjectType; t != "" {
			out = append(out, t)
		}
	}
	return out
}
