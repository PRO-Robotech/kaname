// check.go — проверка ДЕРЕВА: каждый найденный манифест разбирается тем же
// загрузчиком, которым его прочтёт посев (приёмка §5.5, сценарии MOD-MF-17 · 18
// · 19).
//
// Это прод-потребитель загрузчика: без него загрузчик вестигиален
// (`architecture.md` §LEAN), а с ним негодный манифест роняет прогон, а не
// доезжает до посева и не выясняется на стенде.
//
// # Исходов ТРИ, и третий несущий
//
//	0  годно  — манифест найден, прочитан, разобран и связен;
//	1  находка — манифест негоден либо путь не прочитан;
//	2  VOID   — манифеста не найдено НИ ОДНОГО, проверять нечего.
//
// Третий исход не педантизм. Проверка, отдающая ноль на пустом обходе, объявляет
// годным то, чего не читала: «ноль находок» становится неотличимо от «ноль
// прочитанного» (`testing.md` §«Гейт на класс», п. 3). Манифест, положенный мимо
// ожидаемого имени, остался бы невидимым навсегда, схлопни мы этот исход в успех.
//
// ЗДЕСЬ СТОЯЛО «сегодня дерево именно пустое — манифестов в нём ноль», и это
// утверждение ПЕРЕЖИЛО СВОЙ ПРЕДМЕТ: манифесты в дереве появились, и VOID
// перестал быть исходом, который обход отдаёт СЕЙЧАС. Класс назван, а не стёрт,
// потому что узнаётся он одной командой и стоит того, чтобы её знали:
//
//	git ls-files '*/manifest.yaml' | wc -l    # ноль — VOID есть сегодняшний исход
//
// Число здесь намеренно НЕ выписано вторым местом: оно растёт с каждым новым
// модулем и устарело бы так же молча, как устарел прежний ноль.
//
// # Обход не обрывается на первой находке
//
// Оборванный обход сообщает о ПЕРВОМ негодном манифесте и молчит об остальных:
// автор чинил бы их по одному, по прогону на каждый, не зная, сколько их всего.
// Тот же довод, по которому checkStringKeys собирает каждый ключ-нестроку, а
// валидатор связности — каждую находку.
//
// # Что считается манифестом и почему именно это
//
// Файл с базовым именем ровно `manifest.yaml`. Не совпадение слова: и
// `manifest.yaml.bak`, и `app.manifest.yaml` — другие файлы, и принять их
// значило бы судить чужой документ по нашей форме, выдавая находку там, где её
// никто не писал.
//
// # Что именно читается — и почему это не следует из того, что путь дал обход
//
// Обход порождает путь сам, и оттого кажется, будто читать по нему безопасно.
// Обход, однако, порождает путь по тому, что в дереве ЛЕЖИТ, а не по тому, что
// мы задумали, и между чтением записи каталога и открытием пути лежит окно.
// Поэтому читается ровно то, что удовлетворяет трём условиям сразу, и каждое
// держится построением, а не внимательностью вызывающего:
//
//	под корнем      — открытие идёт через os.Root, и уход за корень отвергает
//	                  ядро (CWE-367, CWE-22); ссылка, остающаяся под корнем,
//	                  законна: предмет — граница корня, а не ссылки;
//	обычный файл    — именованный канал с именем манифеста ждёт писателя
//	                  ВЕЧНО, а зависшая проверка хуже упавшей: вердикта нет
//	                  вовсе, и от медленной её не отличить;
//	не больше предела — файл с именем манифеста бывает порождён сборкой или
//	                  слит из журнала; читатель без предела ложится на нём и не
//	                  даёт вердикта НИ ПО ОДНОМУ манифесту дерева.
//
// Нарушение любого из трёх есть НАХОДКА, называющая величину, — не отказ
// проверки и не молчание. Подробности — у ReadUnderRoot.

const (
	// CheckOK — каждый найденный манифест прочитан и годен.
	CheckOK = 0
	// CheckFailed — найдено негодное либо непрочитанное.
	CheckFailed = 1
	// CheckVoid — манифестов не найдено ни одного: проверять нечего.
	//
	// Отдельное значение, а не CheckOK: оболочка читает КОД, и «нечего» не
	// вправе выглядеть успехом.
	CheckVoid = 2
)

// manifestFileName — имя, под которым модуль кладёт свой манифест.
//
// Одно на дерево и здесь же: второе место, называющее это имя, разошлось бы с
// первым молча, и часть манифестов перестала бы находиться, не дав ни одной
// находки.
const manifestFileName = "manifest.yaml"

// manifestSizeLimit — сколько байт манифеста читатель берёт в память.
//
// Столько, а НЕ МЕНЬШЕ: манифест растёт вместе с числом ресурсов и ролей ОДНОГО
// модуля, и предел обязан покрывать рост, который сам по себе был бы работой
// другого размера. Столько, а НЕ БОЛЬШЕ: превышение обязано означать «это не
// манифест», а не «манифест подрос», — файл, на порядок больший самого большого
// настоящего, есть предмет другого рода.
//
// ЗАПАС ВЫВОДИТСЯ ИЗ ДЕРЕВА, А НЕ ВЫПИСАН ЗДЕСЬ. Здесь стояло «самый большой
// настоящий манифест — vpc, 42 626 байт … запас в 24 раза»: число было снято с
// черновика в ДРУГОМ дереве и пережило свой предмет — и самый большой манифест
// оказался другим файлом, и запас другим (задача #1908). Читает это место тот,
// кто решает, двигать предел или чинить документ, поэтому неверным было ровно
// то, ради чего комментарий и написан.
//
// Держатель — `TestManifestSizeLimitOutgrowsTheBiggestManifestOfThisTree`
// (`checklimit_test.go`): он берёт максимум у дерева ПРОД-ОБХОДОМ на каждом
// прогоне, печатает его вместе с кратностью запаса и краснеет ЗАРАНЕЕ — когда
// запас падает ниже объявленного, а не в минуту, когда чтение упрётся в предел.
// Второго места об одном предмете здесь не заводится: число, выписанное рядом с
// константой, устаревает молча, а перепись — нет.
//
// Предел есть ВЕРХНЯЯ ДОПУСТИМАЯ величина, а не первая запрещённая: ровно предел
// читается.
const manifestSizeLimit = 1 << 20

// skippedDirNames — каталоги, в которые обход не заходит.
//
// Каждая запись — СЛЕПАЯ ЗОНА, выданная сознательно, поэтому их четыре, а не
// «на всякий случай побольше»: чужие зависимости (`node_modules`, `vendor`) и
// порождённое сборкой (`dist`, `build`). Манифест модуля там оказаться не может
// — ни то, ни другое не пишет человек, — а найденный там файл судился бы нашей
// формой, будучи чужим.
//
// Служебные каталоги (`.git`, `.claude`, `.cache`) отсекаются отдельно, по
// ведущей точке: перечислять их поимённо значило бы держать перечень, который
// разойдётся с деревом при первом же новом инструменте.
var skippedDirNames = []string{"node_modules", "vendor", "dist", "build"}

// CheckReport — исход обхода вместе с ПЕРЕПИСЬЮ осмотренного.
//
// Перепись печатается ВСЕГДА, а не только при находках: без неё зелёный вердикт
// не отличить от вердикта обхода, не прочитавшего ничего.
type CheckReport struct {
	// ManifestsRead — манифестов прочитано. Считается и негодный: он прочитан,
	// и именно поэтому о нём есть что сказать.
	ManifestsRead int
	// PathsSeen — файлов осмотрено обходом (не каталогов).
	PathsSeen int
	// DirsSkipped — каталогов, в которые обход не заходил (skippedDirNames и
	// служебные): слепая зона названа числом, а не подразумевается.
	DirsSkipped int
	// Paths — пути прочитанных манифестов относительно корня обхода.
	Paths []string
	// Manifests — РАЗОБРАННЫЕ манифесты, в порядке Paths и только годные:
	// негодный до сюда не доходит, о нём говорит Findings.
	//
	// Обход и так их разбирает; прежде результат разбора выбрасывался, и
	// потребителю доставки пришлось бы читать дерево вторым проходом — то есть
	// завести второе место об одном предмете. Читатель у поля один и он в
	// прод-коде: LoadDelivered (delivery.go).
	Manifests []*Manifest
	// Findings — находки: негодный манифест либо непрочитанный путь. Каждая
	// называет место и предмет.
	Findings []string
}

// ExitCode — один из трёх исходов; порядок ветвления есть часть контракта:
// находка перевешивает пустоту, потому что «не прочитали» есть находка, а не
// «нечего проверять».
func (r CheckReport) ExitCode() int {
	switch {
	case len(r.Findings) > 0:
		return CheckFailed
	case r.ManifestsRead == 0:
		return CheckVoid
	default:
		return CheckOK
	}
}

// Summary — перепись одной строкой. При VOID она ГОВОРИТ ЭТО СЛОВАМИ: код
// возврата читает оболочка, а человек читает строку, и она не вправе выглядеть
// успехом.
func (r CheckReport) Summary() string {
	s := fmt.Sprintf("осмотрено файлов %d · каталогов пропущено %d · манифестов прочитано %d · находок %d",
		r.PathsSeen, r.DirsSkipped, r.ManifestsRead, len(r.Findings))
	if r.ManifestsRead == 0 && len(r.Findings) == 0 {
		s += " — проверять нечего: манифеста нет ни одного"
	}
	return s
}

// CheckTree обходит дерево от root, читает каждый манифест модуля и судит его
// тем же Load, которым его прочтёт посев.
//
// Ошибка не возвращается отдельным значением намеренно: у обхода их бывает
// много, и вызывающему нужен не первый отказ, а ПЕРЕЧЕНЬ вместе с переписью.
// Нечитаемый корень при этом остаётся находкой, а не пустым деревом: опечатка в
// пути иначе печатала бы успокоительное «проверять нечего».
func CheckTree(root string) CheckReport {
	return walkManifests(root, isTreeManifestName)
}

// isTreeManifestName — что считается манифестом В ДЕРЕВЕ РАЗРАБОТКИ: базовое имя
// ровно `manifest.yaml`. Рядом лежат чужие документы, и судить их нашей формой
// значило бы выдавать находку там, где её никто не писал.
func isTreeManifestName(name string) bool { return name == manifestFileName }

// isDeliveredManifestName — что считается манифестом В КАТАЛОГЕ ДОСТАВКИ: ВСЁ,
// кроме служебных записей тома. Предикат другой, и это не послабление, а
// следствие того, что каталог доставки — ЗАКРЫТЫЙ НАБОР (см. delivery.go).
//
// Служебные записи тома ConfigMap исключены по ведущему `..` — соглашение самого
// Kubernetes, а не догадка о его внутренностях: `..data` и `..<отметка времени>`
// он кладёт рядом с ключами и ожидает, что потребитель их не читает.
func isDeliveredManifestName(name string) bool { return !strings.HasPrefix(name, "..") }

// walkManifests — общий обход: РАЗЛИЧАЮТСЯ у него только правило «что здесь
// считается манифестом», всё остальное (граница чтения, перепись, три исхода,
// необрываемость) одно на обе полосы.
//
// Второй обход, написанный рядом, разошёлся бы с первым молча — и разошёлся бы
// именно в той половине, которую никто не читает глазами.
func walkManifests(root string, accept func(name string) bool) CheckReport {
	var report CheckReport

	// Корень открывается ОДИН раз и служит ГРАНИЦЕЙ чтения: всё, что читается
	// дальше, разрешается ядром относительно него, а не по имени, собранному
	// обходом. Не открылся — находка того же вида, что и непрочитанный путь:
	// обходить нечего, и делать вид, что обошли, нельзя.
	treeRoot, err := os.OpenRoot(root)
	if err != nil {
		report.Findings = append(report.Findings, fmt.Sprintf(
			"%s: путь не прочитан: %v — непрочитанное есть НАХОДКА, а не «проверять нечего»: "+
				"проверьте существование и права на путь", root, err))
		return report
	}
	defer func() { _ = treeRoot.Close() }()

	//nolint:errcheck // исход обхода уже разложен по находкам отчёта.
	_ = filepath.WalkDir(root, func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			// Место называется ОТ КОРНЯ, а сам корень — как он назван
			// вызывающим: относительный путь корня к себе есть «.», и такая
			// координата не адресует ничего.
			where := displayPath(root, path)
			if path == root {
				where = root
			}
			report.Findings = append(report.Findings, fmt.Sprintf(
				"%s: путь не прочитан: %v — непрочитанное есть НАХОДКА, а не «проверять нечего»: "+
					"проверьте существование и права на путь", where, walkErr))
			if d == nil {
				// Корень не открылся: обходить нечего, и делать вид, что
				// обошли, нельзя.
				return walkErr
			}
			return nil
		}

		if d.IsDir() {
			if path == root {
				return nil
			}
			if isSkippedDir(d.Name()) {
				report.DirsSkipped++
				return fs.SkipDir
			}
			return nil
		}

		report.PathsSeen++
		if !accept(d.Name()) {
			return nil
		}

		rel := displayPath(root, path)
		data, err := ReadUnderRoot(treeRoot, rel)
		if err != nil {
			report.Findings = append(report.Findings, fmt.Sprintf(
				"%s: манифест не прочитан: %v", rel, err))
			return nil
		}
		report.ManifestsRead++
		report.Paths = append(report.Paths, rel)
		m, err := Load(data)
		if err != nil {
			report.Findings = append(report.Findings, rel+": "+err.Error())
			return nil
		}
		report.Manifests = append(report.Manifests, m)
		return nil
	})

	return report
}

// ReadUnderRoot читает манифест ПОД НАЗВАННЫМ КОРНЕМ, ОБЫЧНЫМ ФАЙЛОМ и НЕ БОЛЬШЕ
// предела. Ни одно из трёх не следует из того, что путь породил обход.
//
// # Почему путь, порождённый обходом, нельзя читать ПО ИМЕНИ
//
// Между тем, как обход прочитал запись каталога, и тем, как читатель открыл
// путь, лежит окно. В нём любой сегмент подменяется ссылкой наружу, и чтение по
// имени уходит за корень, не заметив этого (CWE-367 «время проверки против
// времени использования», CWE-22 «выход за каталог»). Открытие через os.Root
// разрешает КАЖДЫЙ сегмент ядром относительно корня и уход за корень отвергает —
// то есть свойство держится построением, а не тем, что вызывающий помнит о нём.
//
// Ссылка, остающаяся ПОД корнем, законна и читается: предмет — граница корня, а
// не ссылки как таковые. Различие названо вслух, потому что запрет ссылок был бы
// другой политикой, и её никто не принимал.
//
// # Почему род файла берётся С ДЕСКРИПТОРА, а не с записи каталога
//
// Именованный канал с именем манифеста кладёт чтение навсегда: открытие ждёт
// писателя, которого никто не пришлёт. Зависшая проверка хуже упавшей — у неё
// нет вердикта вовсе, и отличить её от медленной нечем. O_NONBLOCK снимает
// ожидание на открытии, а род берётся с УЖЕ ОТКРЫТОГО дескриптора: запись
// каталога говорит о том, что лежало там до открытия, и о читаемом СЕЙЧАС не
// утверждает ничего.
//
// # Почему решает объём ПРОЧИТАННОГО, а не заявленный размер
//
// Файл вправе вырасти между fstat и чтением. Решай размер по fstat — усечённое
// содержимое уехало бы в разбор и дало отказ ФОРМЫ вместо отказа РАЗМЕРА, то
// есть находку, посылающую читателя не туда. Поэтому предел держит сам читатель
// (io.LimitReader), а размер из fstat служит только тем, чтобы НАЗВАТЬ величину:
// без неё читателю нечем решить, чинить файл или поднимать предел.
func ReadUnderRoot(root *os.Root, rel string) ([]byte, error) {
	f, err := root.OpenFile(rel, os.O_RDONLY|syscall.O_NONBLOCK, 0)
	if err != nil {
		// Отказ называется вместе с ГРАНИЦЕЙ, в которой он случился: про уход за
		// корень стандартная библиотека говорит своими словами («path escapes
		// from parent»), и без границы читатель не поймёт, о чём они.
		return nil, fmt.Errorf("не открыт под корнем обхода: %w — читается только то, "+
			"что лежит под корнем; ссылка наружу отвергается ядром", err)
	}
	defer f.Close()

	st, err := f.Stat()
	if err != nil {
		return nil, err
	}
	if !st.Mode().IsRegular() {
		return nil, fmt.Errorf("не обычный файл (режим %s) — читается только обычный файл",
			st.Mode().Type())
	}

	data, err := io.ReadAll(io.LimitReader(f, manifestSizeLimit+1))
	if err != nil {
		return nil, err
	}
	if len(data) > manifestSizeLimit {
		return nil, fmt.Errorf("больше предела: %d байт при пределе %d байт — "+
			"читается не больше предела; проверьте, манифест ли это",
			st.Size(), manifestSizeLimit)
	}
	return data, nil
}

// isSkippedDir — заходит ли обход в каталог с таким именем.
func isSkippedDir(name string) bool {
	if strings.HasPrefix(name, ".") {
		return true
	}
	return contains(skippedDirNames, name)
}

// displayPath — путь относительно корня обхода, косой чертой.
//
// Относительный, потому что находку читает человек, а не машина: абсолютный
// путь временного каталога прогона ничего ему не адресует. Если относительный
// не выводится (иной том), называется исходный — назвать место надо в любом
// случае.
func displayPath(root, path string) string {
	rel, err := filepath.Rel(root, path)
	if err != nil {
		return filepath.ToSlash(path)
	}
	return filepath.ToSlash(rel)
}
