package manifest

import (
	"fmt"
	"strings"

	"github.com/PRO-Robotech/corelib/gitenv"
)

// untrackedRootVerdict — общий хвост всех трёх текстов: ПОЧЕМУ пустой перечень
// есть находка, а не VOID.
const untrackedRootVerdict = "непрочитанное есть НАХОДКА, а не «проверять нечего»: " +
	"полоса дерева читает состав КОММИТА, а коммит об этом корне не знает ничего"

// untrackedRootFinding — находка для корня, под которым индекс не знает НИ
// ОДНОГО файла (задача PRO-Robotech/kaname#384).
//
// # Почему это находка, а не VOID
//
// git отвечает на перечисление пустотой в двух мирах, и ни в одном полоса не
// прочитала состава коммита:
//
//   - корень лежит ВНУТРИ постороннего репозитория и им не отслеживается
//     (неотслеживаемый или игнорируемый каталог): git поднимается от корня до
//     ближайшего `.git` и отвечает индексом ТОГО дерева, а тому дереву об этом
//     корне сказать нечего;
//   - корень — сам репозиторий, но в его индекс не заведено ничего.
//
// VOID объявил бы «манифеста нет ни одного» о корне, на диске которого манифест
// лежит, и исход стал бы свойством места, куда положили корень: тот же корень
// без объемлющего репозитория даёт находку отказом `git ls-files`. Исход у всех
// трёх миров один, а текст называет, какой из них случился, — причину, а не
// симптом.
//
// Дерево разработки отслеживает под своим корнем хоть один файл всегда, поэтому
// у законного корня пустой перечень непредставим, и отказ законного не отнимает.
//
// # Третий исход назван, а не слит с первыми двумя
//
// Кто владеет индексом, спрашивается у git (`rev-parse`), и только на этом
// отказе: законному пути лишний процесс не нужен. Не ответил git либо ответил в
// форме, которой разбор не знает, — это отдельный текст с сырым ответом, а не
// догадка о том, какой из двух миров случился.
func untrackedRootFinding(root string) string {
	out, err := gitenv.Command(root, "rev-parse", "--show-toplevel", "--show-prefix").Output()
	return untrackedRootText(root, out, err)
}

// untrackedRootText — разбор ответа `rev-parse` отдельно от вызова: три исхода
// разбора судятся синтетическим вводом, а не тем, что случилось на машине
// прогона.
func untrackedRootText(root string, out []byte, err error) string {
	if err != nil {
		return fmt.Sprintf("%s: индекс не знает под корнем ни одного файла, а чей это "+
			"индекс, git не назвал: %v — %s", root, err, untrackedRootVerdict)
	}
	// Ответ — ровно две строки: корень рабочего дерева и путь корня обхода в нём
	// (у самого корня рабочего дерева — пустая строка).
	lines := strings.Split(string(out), "\n")
	if len(lines) != 3 || lines[0] == "" || lines[2] != "" {
		return fmt.Sprintf("%s: индекс не знает под корнем ни одного файла, а чей это "+
			"индекс, git ответил в непредусмотренной форме: %q — %s", root, out, untrackedRootVerdict)
	}
	top, prefix := lines[0], lines[1]
	if prefix == "" {
		return fmt.Sprintf("%s: корень — сам репозиторий, но в его индексе нет ни одного "+
			"файла — %s", root, untrackedRootVerdict)
	}
	return fmt.Sprintf("%s: корень лежит внутри репозитория %s (путь в нём %s) и им не "+
		"отслеживается — вердикт того дерева к этому корню отношения не имеет; %s",
		root, top, prefix, untrackedRootVerdict)
}
