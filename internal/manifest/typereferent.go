package manifest

// TypeReferent — ЧЕМ судится существование типа объекта, названного манифестом.
//
// Задача продукта #1930.
//
// # Предмет: производитель спрашивал у своего продукта
//
// Загрузчик проверял `objectType` каждой записи на членство в закрытой таблице
// типов `authzmap` — таблице, которую из этих же манифестов и порождают. Круг
// замыкался так, что НОВЫЙ тип не проходил ни одной из двух дверей: загрузчик
// отвергал его, потому что таблица о нём не знает, а таблица не узнавала,
// потому что перегенерация начинается с загрузки.
//
// Замер, на котором препятствие установлено (взят у производителя, здесь не
// перемерялся): ресурс, дописанный в манифест, отвергается загрузчиком «типа
// нет в закрытой таблице типов iam», поэтому `authzmapgen.Collect` отказывает и
// продукт не обновляется вовсе.
//
// # Референтов ДВА, и оба законны — предикат при этом ОДИН
//
// Различает их не вкус, а то, чем таблица является в момент вопроса:
//
//	ReferentShippedTable  ПОТРЕБЛЕНИЕ: таблица уже произведена и вкомпилирована
//	                      в бинарь. Доставленный манифест, назвавший тип вне
//	                      неё, не работает НИКАК — селектор роли адресовал бы
//	                      несуществующий тип и не дал бы ни одного пообъектного
//	                      права, молча. Здесь таблица — законный судья.
//
//	ReferentCanon         ПОРОЖДЕНИЕ: таблица есть ПРОДУКТ этого прохода, и
//	                      судить им вход значит спрашивать у ответа. Существование
//	                      типа объявляет КАНОНИЧЕСКАЯ МОДЕЛЬ, и сверку с ней в
//	                      обе стороны уже ведёт `modelrender.Sweep` («манифест
//	                      порождает тип, которого в каноне НЕТ» и обратное).
//	                      Загрузчик здесь судит ФОРМУ и не судит существование.
//
// Это НЕ два места об одном предмете: предикат один, а референт называет
// ВЫЗЫВАЮЩИЙ — и вызывающих ровно два вида, каждый со своим смыслом вопроса.
// Умолчание — потребление: забытый референт даёт СТРОГИЙ разбор, а не мягкий.
//
// # Чего смена референта НЕ отнимает у старта службы
//
// Ничего. Чтение доставленных манифестов на старте
// (`services/iam/cmd/kacho-iam/module_manifests.go` → [LoadDelivered]) идёт
// умолчанием, то есть по-прежнему судит таблицей. Новой зависимости от файла
// канона в работающем процессе не заводится: канон читает только оснастка
// дерева, у которой он есть.
type TypeReferent uint8

const (
	// ReferentShippedTable — существование типа судит закрытая таблица,
	// вкомпилированная в бинарь. Нулевое значение: забытый референт даёт
	// сегодняшнее, СТРОГОЕ поведение.
	ReferentShippedTable TypeReferent = iota

	// ReferentCanon — существование типа судит канон модели, и судит его НЕ
	// ЗДЕСЬ: загрузчик оставляет вопрос `modelrender.Sweep`, у которого канон
	// есть. Здесь судится только форма.
	ReferentCanon
)

// judgesTypeExistence — спрашивает ли загрузчик о существовании типа сам.
func (r TypeReferent) judgesTypeExistence() bool { return r == ReferentShippedTable }

// String — для текстов переписи. Референт печатается вместе с исходом: «типов
// не проверяли» и «типы проверены и чисты» иначе неразличимы.
func (r TypeReferent) String() string {
	if r == ReferentCanon {
		return "канон (существование судит modelrender.Sweep)"
	}
	return "закрытая таблица типов"
}
