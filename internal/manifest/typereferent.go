package manifest

// TypeReferent — ЧЕМ является порождённая сборкой таблица типов в момент, когда
// загрузчик о ней спрашивает.
//
// Задачи продукта #1930 (заведение) и #2015 (предмет сменился, см. ниже).
//
// # Здесь стояло «ЧЕМ судится СУЩЕСТВОВАНИЕ типа» — этого предмета больше нет
//
// Прежняя редакция объявляла таблицу судьёй существования на полосе потребления:
// доставленный манифест, назвавший тип вне неё, отвергался. Задача #2015 сняла
// этот предикат целиком — и не как послабление, а потому что он делал продукт
// противоречащим себе: соседняя полоса разомкнула набор МОДУЛЕЙ, то есть
// оператор чужого облака объявлял `module: acme` своим манифестом и тут же
// получал отказ на `objectType: acme_widget`. Продукт принимал модуль и отвергал
// то, ради чего модуль объявляют.
//
// Существование типа теперь ничем не спрашивается: ресурс, объявивший тип, тем
// самым его и заводит — строка каталога несёт имя типа своим полем, а блок
// модели прав порождается из того же объявления (objecttype.go).
//
// # Что различает референт ТЕПЕРЬ — ВЛАДЕНИЕ, а не членство
//
//	ReferentShippedTable  ПОТРЕБЛЕНИЕ: таблица уже произведена и вкомпилирована
//	                      в бинарь, то есть она ЕСТЬ ОБРАЗ. Тип, который образ
//	                      несёт, доставка не вправе присвоить другой строке:
//	                      отношение `v_<глагол>` адресуется именем типа, и права
//	                      по такой строке материализовались бы на объектах, которых
//	                      этот модуль не создавал. Монотонность взята у близнеца —
//	                      допуска собранной модели прав.
//
//	ReferentCanon         ПОРОЖДЕНИЕ: таблица есть ПРОДУКТ этого прохода и образом
//	                      ещё не является. Охранять нечего, а спрашивать её значило
//	                      бы спрашивать у собственного ответа: перенос типа с одной
//	                      строки дерева на другую — законная правка, ради которой
//	                      перегенерация и запускается, — отвергался бы своей же
//	                      будущей таблицей.
//
// Это НЕ два места об одном предмете: предикат один, а референт называет
// ВЫЗЫВАЮЩИЙ — и вызывающих ровно два вида, каждый со своим смыслом вопроса.
// Умолчание — потребление: забытый референт даёт СТРОГИЙ разбор, а не мягкий.
//
// # Форма имени судится при ОБОИХ референтах
//
// Смена референта снимает вопрос о владении, а не о форме. Имя негодной формы
// отвергнет колонка каталога ограничением базы, а строку `type` собранной модели
// — её допуск; пропусти его загрузчик — отказ пришёл бы ЧУЖОЙ полосой, фразой
// Postgres про имя ограничения, и автор манифеста искал бы дефект в базе, а не в
// своём файле.
//
// # Чего смена референта НЕ отнимает у старта службы
//
// Ничего. Чтение доставленных манифестов на старте
// (`services/iam/cmd/kaname/module_manifests.go` → [LoadDelivered]) идёт
// умолчанием, то есть по-прежнему охраняет объявления образа.
type TypeReferent uint8

const (
	// ReferentShippedTable — порождённая сборкой таблица есть ОБРАЗ, и её
	// объявления охраняются от присвоения. Нулевое значение: забытый референт
	// даёт сегодняшнее, СТРОГОЕ поведение.
	ReferentShippedTable TypeReferent = iota

	// ReferentCanon — таблица есть продукт ЭТОГО прохода и образом не является:
	// охранять нечего, судится только форма.
	ReferentCanon
)

// guardsImageOwnership — охраняет ли загрузчик объявления образа.
//
// Имя названо ДЕЙСТВИЕМ, а не референтом («это ли закрытая таблица»): предикат
// прочитанный в месте вызова обязан говорить, ЧТО он решает, — иначе следующий
// читатель восстановит по имени снятый предмет (членство) и починит код под него.
func (r TypeReferent) guardsImageOwnership() bool { return r == ReferentShippedTable }

// String — для текстов переписи. Референт печатается вместе с исходом: «владение
// не охраняли» и «владение проверено и чисто» иначе неразличимы.
func (r TypeReferent) String() string {
	if r == ReferentCanon {
		return "порождение (образа ещё нет, владение не охраняется)"
	}
	return "образ (объявления таблицы охраняются от присвоения)"
}
