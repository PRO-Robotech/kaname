package manifest

// relationoracle.go — модель прав ВНОСИТСЯ в загрузчик вызывающим (задача
// продукта #2002; приёмка
// `services/iam/docs/engineering/acceptance/model-composes-at-boot-from-delivered-manifests.md`,
// §2 п. 6, сценарий `IAM-MB-1-17`).
//
// # Предмет: загрузчик доставки добывал модель, из которой сам же собирается
//
// Разбор доставленного манифеста САМ добывал общий разбор модели ПРОЦЕССА у её
// владельца, а эта модель
// собирается ИЗ разобранных манифестов. Порядок был неисполним: §2 п. 6 требует
// ставить композицию ДО разбора доставки безусловно, а §2 п. 7 запрещает
// установку после первого чтения — она была бы тихой заменой. Оба требования
// верны порознь и вместе невыполнимы, пока разбор добывает модель сам.
//
// # Условность — ХУДШИЙ вид этой зависимости, а не смягчение
//
// Модель читалась только на манифестах, объявивших
// `seed.accessBindings[].grantedRelation`, — 2 из 6 в дереве. Значит стенд
// поднимался бы на четырёх манифестах и вставал у того арендатора, чей манифест
// объявил выдачу отношением: снаружи недетерминированно, а по исходу старта
// неотличимо от «условие не создано».
//
// # Почему ПОРТ, а не импорт владельца модели
//
// Порт разворачивает ребро: модель приходит параметром, и загрузчик перестаёт
// знать, кто её держит. Это и делает выразимым порядок «чтение доставки (без
// модели) → композиция → допуск → установка».
//
// Второй ВХОД в загрузчик — «только форма» рядом с полной загрузкой — отвергнут
// приёмкой: второй путь через тот же разбор разошёлся бы с первым молча, на той
// форме, о которой не знает. Поэтому вход остаётся ОДИН, а параметром меняется
// не путь, а то, ЧЕМ судят.
//
// # Чего отсутствие оракула НЕ означает
//
// Оно не означает «пропустить молча». Загрузчик без оракула судит ФОРМУ выдачи
// (обе формы названы — отказ, ни одной — отказ), а существование типа, отношения
// и указателя судится ПОСЛЕ композиции — там, где ответ авторитетен. Объём
// осмотренного печатает перепись связности: «суждено против модели» стоит рядом
// с «выдач отношением прочитано», иначе ноль суждённых читался бы как «сверили
// и не нашли расхождений».

// RelationOracle — ЧЕМ судится связность выдачи ОТНОШЕНИЕМ с моделью прав.
//
// Вносится вызывающим через [WithRelationOracle]. Не внесён — загрузчик о
// модели не спрашивает вовсе (см. шапку файла).
type RelationOracle interface {
	// RelationDeclaration — объявление отношения у типа. Второе значение
	// `false` означает «тип такого отношения не объявляет», а не «объявляет
	// пустым»: различие несущее, и схлопывание его дало бы уверенный вердикт по
	// вопросу, которого модель не знает.
	RelationDeclaration(objectType, relation string) (RelationDeclaration, bool)

	// TypeRelations — имена отношений, объявленных типом. Нужны ТЕКСТУ отказа:
	// автор, назвавший отношение неверно, обязан увидеть перечень объявленных.
	TypeRelations(objectType string) []string
}

// RelationDeclaration — то, что загрузчику нужно знать об объявлении отношения.
//
// Интерфейс, а не структура: решение о виде получателя принимает ВЛАДЕЛЕЦ
// модели своим кодом. Скопируй сюда поля — и заведётся второй разбор записи
// субъекта, который разойдётся с первым молча, на той записи, о которой не
// знает (условие, подстановка, членство).
type RelationDeclaration interface {
	// IsDirect — были ли у отношения прямые записи субъекта ВООБЩЕ.
	//
	// `false` означает «отношение вычисляемое», а НЕ «субъектов нет»: выдать
	// вычисляемое отношение напрямую нечем, и это отдельный отказ.
	IsDirect() bool

	// AcceptsKind — принимает ли объявление получателя названного вида. Вид
	// называется В НАПИСАНИИ МАНИФЕСТА (`serviceAccount`).
	AcceptsKind(kind string) bool

	// AcceptedKinds — виды, принимаемые прямо, в написании канона. Ради ТЕКСТА
	// отказа; решения по ним не принимаются — для этого есть [AcceptsKind].
	AcceptedKinds() []string
}

// LoadOption — то, что вызывающий ВНОСИТ в загрузку.
type LoadOption func(*loadOptions)

// loadOptions — внесённое вызывающим. Нулевое значение — СТРОГОЕ в том смысле,
// в каком строгость здесь определена: ничего не внесено, значит о модели не
// спрашиваем и о существовании отношения не утверждаем НИЧЕГО. Уверенный
// вердикт по недочитанному был бы вымыслом.
type loadOptions struct {
	oracle RelationOracle
}

// WithRelationOracle вносит модель, против которой судится связность выдачи
// ОТНОШЕНИЕМ.
//
// Вносит её ВЫЗЫВАЮЩИЙ, потому что вызывающих два вида с разным смыслом вопроса
// — тот же довод, что у [TypeReferent]:
//
//	доставка на старте   модель ещё СОБИРАЕТСЯ из этих самых манифестов;
//	                     спрашивать её здесь значит спрашивать у ответа.
//	                     Оракул не вносится.
//
//	порождение таблицы   тип НОВЫЙ, и канон образа о нём не знает by
//	                     construction; суждение каноном отвергло бы законную
//	                     выдачу. Оракул не вносится.
//
//	оснастка дерева      канон есть, и он авторитетен: тип уже в нём. Оракул
//	                     вносится, и связность судится полностью.
//
// `nil` вносить бессмысленно и потому отвергается молчанием: [WithRelationOracle]
// с `nil` оставляет загрузку такой же, какой она была бы без опции.
func WithRelationOracle(o RelationOracle) LoadOption {
	return func(opts *loadOptions) {
		if o == nil {
			return
		}
		opts.oracle = o
	}
}

func newLoadOptions(opts []LoadOption) loadOptions {
	var out loadOptions
	for _, apply := range opts {
		if apply == nil {
			continue
		}
		apply(&out)
	}
	return out
}
