// grantanchor.go — ЯКОРЬ выдачи посева: единственное его объявление и
// единственный его судья (задача продукта #1953).
//
// # Что здесь было неверно
//
// Опубликованная схема пинила якорь двумя `const` — `scopeType: iam.cluster` и
// `scopeId: cluster_kacho_root`, — а единственный объявленный судья формы
// (загрузчик, см. шапку пакета) значения не судил: он требовал лишь, чтобы ключ
// был назван непустым. Схема вторым судьёй не является и судьёй не станет — она
// КОНТРАКТ для автора манифеста и его редактора, — поэтому `const` без отказа у
// загрузчика есть обещание, за которое никто не отвечает.
//
// Замер ВЫЗОВОМ на ревизии заведения задачи: загрузчик принимал `iam.project`,
// `iam.account` и выдуманный `iam.galaxy`, а чужой `scopeId` проходил у ОБЕИХ
// форм выдачи — включая ту, которую #1936 только что укрепил. То есть #1936
// запинил у формы отношения ОДИН ключ якоря из двух, и радиус оказался шире
// названного задачей.
//
// # Почему судья ОДИН на обе формы выдачи
//
// Якорь есть свойство ВЫДАЧИ, а не того, чем она наделяет: выдача действует на
// объекте яруса одинаково, роль это или отношение. Ветвь на форму дала бы
// одному полю два режима по соседним ветвям — ровно тот дрейф, из-за которого
// два правила об одном предмете расходятся молча. Прежде проверка яруса жила
// внутри связности формы ОТНОШЕНИЯ (relationgrant.go) и туда попала by
// construction: чтобы спросить канон, надо знать тип объекта. Теперь тип
// объекта производит ЭТОТ судья и отдаёт его дальше — второго резолва в дереве
// нет ни одного.
//
// # Почему якорь именно кластерный singleton
//
// Посев модуля выдаёт только на кластере: выдачи на аккаунт и проект заводит iam
// при создании самих этих объектов, а не установка модуля — арендаторов на
// момент установки не существует. Кластер же singleton, поэтому объект у него
// ровно один, и «другой кластер» есть строка, которой не отвечает ни одна живая.
//
// # Обе величины берутся У ДОМЕНА, а не выписываются
//
// Вторая копия литерала разошлась бы с первой молча — и разошлась бы там, где
// это не видно: обе отвечают «да» на законном входе. Согласие ЭТИХ величин с
// опубликованной схемой держит отдельная проба
// (`TestSchemaAnchorConstAgreesWithTheLoaderConstants`), потому что свести
// схему и загрузчик к одному объявлению нельзя — см. её шапку.
package manifest

import (
	"fmt"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/PRO-Robotech/kacho/services/iam/internal/domain"
)

// seedGrantAnchorScopeType — ярус, на котором объявляется выдача посева.
const seedGrantAnchorScopeType = domain.ScopeTypeClusterDotted

// seedGrantAnchorScopeID — объект этого яруса. Кластер singleton, поэтому
// объект ровно один.
const seedGrantAnchorScopeID = domain.ClusterSingletonID

// validateGrantAnchor — якорь выдачи судится ПО ЗНАЧЕНИЮ, одинаково для обеих
// форм выдачи.
//
// Возвращает тип объекта якоря, разобранный ОДИН раз, признак пригодности и
// перечень отказов. Тип отдаётся наружу намеренно: второй резолв того же
// значения был бы вторым местом об одном предмете.
//
// # Пустой ключ сюда НЕ доходит, и это разделение ответственности
//
// «Ключ не назван» есть предмет проверки ПОЛНОТЫ выдачи, и она уже назвала его
// своим отказом с своим текстом. Судить пустую строку ещё и здесь значило бы
// выдать автору два отказа за одну незаполненную строку и отправить его чинить
// значение там, где не назван ключ.
//
// # Признак пригодности отдельно от отказов
//
// «Отказов нет» и «якорь пригоден» — разные утверждения: у выдачи с неназванным
// ключом отказов здесь нет, а спрашивать канон о ней всё равно не о чем.
func validateGrantAnchor(doc *yaml.Node, i int, b AccessBinding) (objectType string, usable bool, faults []error) {
	scopeType := strings.TrimSpace(b.ScopeType)
	scopeID := strings.TrimSpace(b.ScopeID)
	if scopeType == "" || scopeID == "" {
		return "", false, nil
	}

	// Оба ключа судятся, и оба отказа выдаются разом: автор, ошибшийся в паре,
	// вправе узнать про обе половины за один заход, а не за два.
	for _, need := range []struct{ key, got, want, why string }{
		{
			key: "scopeType", got: scopeType, want: seedGrantAnchorScopeType,
			why: "посев модуля выдаёт только на кластере: выдачи на аккаунт и проект " +
				"заводит iam при создании самих этих объектов, а не установка модуля",
		},
		{
			key: "scopeId", got: scopeID, want: seedGrantAnchorScopeID,
			why: "кластер — singleton, и объект у него ровно один",
		},
	} {
		if need.got == need.want {
			continue
		}
		faults = append(faults, linkFault{
			kind:  ErrBindingAnchor,
			coord: locate(doc, "seed", "accessBindings", i, need.key),
			detail: fmt.Sprintf(
				"seed.accessBindings[%d].%s: выдача посева объявляется только на якоре %q, получено %q; %s",
				i, need.key, need.want, need.got, need.why),
		})
	}
	if len(faults) > 0 {
		return "", false, faults
	}

	objectType, resolved := domain.ScopeTypeFromDotted(scopeType)
	if !resolved {
		// Недостижимо, пока ярус пиннут константой выше. Ветвь оставлена не
		// «на всякий случай»: смена константы на неразрешимое значение иначе
		// превратила бы резолв в молчаливый пропуск, и канон перестал бы
		// спрашиваться вовсе — без единого отказа.
		return "", false, []error{linkFault{
			kind:   ErrBindingAnchor,
			coord:  locate(doc, "seed", "accessBindings", i, "scopeType"),
			detail: fmt.Sprintf("seed.accessBindings[%d].scopeType: якорь %q не резолвится в тип объекта", i, scopeType),
		}}
	}
	return objectType, true, nil
}
