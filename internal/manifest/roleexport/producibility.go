// producibility.go — ЕДИНСТВЕННОЕ объявление предиката «производит ли правило
// роли тот кортеж, который спрашивает гейт действия».
//
// Приёмка §3.6 п. 3 и §3.7. Предикат читает ОБЕ половины записи каталога —
// отношение И объект, — потому что производимость есть свойство ПАРЫ:
//
//	отношение `v_<действие>` на объекте ТИПА РЕСУРСА          → производится
//	ярус, не выше производимого классом, на объекте типа      → производится
//	то же отношение на `project` / `account` / `cluster`      → НЕ производится
//	отношение вне `{v_*} ∪ {ярусы}`                           → НЕ производится
//
// # Ни одно имя отношения здесь не выписано, и это не стиль
//
// Множество производимого ВЫВОДИТСЯ у тех же двух функций, которыми его строит
// эмиттер кортежей: `authzmap.GrantedVerbs` даёт набор глаголов (включая
// разворачивание подстановки `*`, отсев чужого глагола и удаление, которое
// влечёт правка), `domain.ResolveVerbsAndTier` — ярус. Выписанный перечень имён
// разошёлся бы с эмиттером молча: обе стороны отвечают одинаково на входе, где
// они совпадают.
//
// # Ярусный кортеж эмитится БЕЗУСЛОВНО, и это проверено, а не предположено
//
// Правило, чей глагол не принадлежит набору типа (например `create`, у которого
// пообъектного отношения нет вовсе), глагольных кортежей не даёт — и ярусный
// даёт всё равно (`ruleObjectTuplesWithTypeVerbs`, безусловный `add(tier)`).
// Поэтому класс `create` покрывает действие, чей гейт спрашивает `editor` НА
// ОБЪЕКТЕ ТИПА РЕСУРСА, и не покрывает то же `editor` на проекте.
//
// # Набор глаголов типа берётся ТЕМ ЖЕ запасным путём, что у эмиттера
//
// Тип без собственного набора разворачивает подстановку общим словарём ради
// вывода яруса; глагольных отношений он при этом не получает. Второй ответ на
// этот вопрос понизил бы роль-суперпользователя с администратора до
// наблюдателя — молча.

// VerbFacts — ПОРТ каталожного факта: «какие глаголы объявлены» и «что из
// затребованного грантуемо».
//
// Порт, а не вызов литерала напрямую, по решению kacho#1816: каталожный факт
// живёт в строках, и читатель на литерале продолжил бы считать снятый тип живым.
// Здесь предмет тот же, что у остального пакета, — каталог берётся ПОРТОМ, а не
// встраивается: встроенная копия одна, она у посева, и второй её встраиватель
// был бы вторым объявлением одного предмета.
//
// Удовлетворяется `*catalog.Facts`; сборочная команда строит его из того же
// перечня, которым миграция посеяла строки, поэтому вердикт остаётся
// воспроизводимым из дерева и базы не требует.
type VerbFacts interface {
	VerbsOfType(fgaType string) []string
	CommonVerbVocabulary() []string
	GrantedVerbs(fgaType string, authored, typeVerbs []string) []string
}

// roleTierCascade — ярусы правила роли от слабого к сильному.
//
// Порядок объявлен ЗДЕСЬ один раз, а его согласие с моделью прав держит проба
// сноса (`producibility_model_test.go`): модель говорит `viewer: … or editor` и
// `editor: … or admin`, то есть обладатель сильного яруса удовлетворяет гейт,
// спрашивающий слабый. Литерал без сверки с моделью пережил бы её правку.
var roleTierCascade = []string{"viewer", "editor", "admin"}

// tierRank — место яруса в каскаде; ok=false для имени, ярусом не являющегося.
func tierRank(tier string) (int, bool) {
	for i, t := range roleTierCascade {
		if t == tier {
			return i, true
		}
	}
	return 0, false
}

// typeVerbsOf — набор глаголов типа с тем же запасным путём, что у эмиттера
// кортежей: тип без своего набора получает общий словарь РАДИ ЯРУСА, а
// глагольных отношений не получает всё равно.
func typeVerbsOf(facts VerbFacts, fgaType string) []string {
	if set := facts.VerbsOfType(fgaType); len(set) > 0 {
		return set
	}
	return facts.CommonVerbVocabulary()
}

// Produces отвечает, пишет ли правило роли с глаголом `verb` на ресурсе типа
// `fgaType` тот кортеж, который спрашивает гейт: отношение `relation` на объекте
// типа `object`.
//
// `fgaType` пуст (пара «модуль, ресурс» вне закрытой таблицы типов) — правило
// адресовать нечего, и ответ «нет» без исключений: fail-closed.
func Produces(facts VerbFacts, verb, fgaType, relation, object string) bool {
	if fgaType == "" || relation == "" {
		return false
	}
	// Половина первая — ОБЪЕКТ. Правило-содержимое модуля не пишет ни одного
	// кортежа на объекте области, поэтому одноимённое отношение там для него
	// недостижимо. Проверка стои́т ПЕРВОЙ: без неё `viewer` на проекте прошёл бы
	// по имени, и проверка, заведённая против объявленной и неисполнимой
	// возможности, молча пропустила бы её саму.
	if object != fgaType {
		return false
	}
	typeVerbs := typeVerbsOf(facts, fgaType)
	for _, granted := range facts.GrantedVerbs(fgaType, []string{verb}, typeVerbs) {
		if relation == "v_"+granted {
			return true
		}
	}
	// Половина вторая — ЯРУС. Он эмитится безусловно, поэтому класс, не давший
	// ни одного глагольного отношения, всё равно покрывает гейт, спрашивающий
	// ярус не выше производимого.
	asked, ok := tierRank(relation)
	if !ok {
		return false
	}
	_, produced := domain.ResolveVerbsAndTier([]string{verb}, typeVerbs)
	made, ok := tierRank(produced)
	return ok && asked <= made
}

// Covers — действия ресурса, которые правило роли с глаголом `verb`
// ДЕЙСТВИТЕЛЬНО выдаёт.
//
// Освобождённое действие в покрытие не входит: его получает всякий
// аутентифицированный, а не участник роли, — значит правом оно не выдаётся ни
// для полноты перечня, ни для покрытия, ни для отказа.
//
// # Действие ПЛОСКОСТИ ИСПОЛНЕНИЯ не входит тоже (задача продукта #1835)
//
// Черновик манифеста объявляет запрет прямо: действие плоскости исполнения не
// попадает в роль автоматически ни при каком способе перечисления прав. Пока
// формы «выдать по классу» не существовало, запрет был беспредметен; с ключом
// `classes` предмет появился, и без этой ветви покрытие собиралось по ВСЕМ
// действиям ресурса — то есть класс объявлялся пригодным на одном лишь
// основании внутреннего действия, а выдача зачитывала его наравне с обычным
// чтением.
//
// Довод тот же, что у освобождённого, и он не про удобство: внутреннее действие
// арендатору недоступно by construction (ban #6), поэтому «выдать» его ролью
// арендатора нельзя — можно лишь написать кортеж, который спрашивает гейт
// ВНУТРЕННЕГО слушателя. Это расширение поверхности, которого никто не решал.
//
// Признак берётся у записи каталога (приставка `Internal` у имени службы,
// правило чтения объявлено единственным местом — `splitFQN`), а не выписан
// перечнем: заведут внутреннее действие — оно выпадет из покрытия само.
//
// ПОИМЁННОЕ право этой ветвью НЕ затрагивается: назвать действие по имени —
// осознанный акт автора роли, и разбирает его `namedverbs`. Здесь закрыт ровно
// автоматический путь, о котором запрет и говорит.
func Covers(facts VerbFacts, actions []Action, fgaType, verb string) []Action {
	var out []Action
	for _, a := range actions {
		if a.Exempt() || a.Internal {
			continue
		}
		if Produces(facts, verb, fgaType, a.Relation, a.Object) {
			out = append(out, a)
		}
	}
	return out
}

// SkippedByPlane — действия, которые покрытие пропустило ТОЛЬКО из-за плоскости.
//
// Отдельная функция, а не второе условие внутри `Covers`: отказ обязан назвать
// пропущенное поимённо, иначе «класс ничего не покрывает» читается как опечатка
// в манифесте, и автор идёт искать её у себя — при том что действия у ресурса
// есть и они просто не его плоскости.
func SkippedByPlane(facts VerbFacts, actions []Action, fgaType, verb string) []Action {
	var out []Action
	for _, a := range actions {
		if a.Exempt() || !a.Internal {
			continue
		}
		if Produces(facts, verb, fgaType, a.Relation, a.Object) {
			out = append(out, a)
		}
	}
	return out
}
