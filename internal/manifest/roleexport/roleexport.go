// Package roleexport — производимость права роли модуля: какие действия
// каталога прав правило роли ДЕЙСТВИТЕЛЬНО выдаёт, а какие не выдаёт ни при
// каком написании.
//
// Приёмка: services/iam/docs/engineering/acceptance/module-manifest-roles-and-seed-grants.md
// (задача PRO-Robotech/kacho#1090), §3.6 п. 3 · §3.7 · сценарии MOD-RL-05 и его
// парный положительный.
//
// # Предмет пакета — ПАРА «отношение + объект», а не имя отношения
//
// Правило роли модуля материализует кортежи на объекте СВОЕГО типа: глагольные
// `v_<действие>` и ярус пишутся на `<тип ресурса>:<id>`, а на объект области
// (`project:<X>` / `account:<X>` / `cluster:<X>`) правило-содержимое не пишет
// НИЧЕГО. Поэтому «производимо ли отношение, которое спрашивает гейт» есть
// свойство ПАРЫ, и читать надо обе половины записи каталога — `required_relation`
// И `scope_extractor.object_type`.
//
// Цена чтения по одному имени измерена приёмкой и она не теоретическая: `viewer`
// на `project` и `system_viewer` на `cluster` для правила роли одинаково
// непроизводимы, но первое имя «наше», и по имени оно проходило проверку.
// Разница — 19 действий домена vpc из 95.
//
// # Почему пакет-сосед, а не `internal/manifest` и не `internal/domain`
//
// Разбор манифеста — общий предмет эпика; экспорт и целостность ролей — предмет
// одной задачи. Направление импортов задано и однонаправленно: `roleexport`
// зависит от `manifest` и от `authzmap`, а `manifest` от `roleexport` — НИКОГДА,
// иначе разбор потянул бы за собой каталог прав и перестал быть чистым. В
// `domain` этому не место по правилу слоёв: домен не зависит ни от каталога, ни
// от таблицы типов.
//
// # Каталог приходит ПОРТОМ, а не встраивается здесь
//
// Встроенная копия каталога живёт у посева (`internal/apps/kaname/seed/embedded`),
// и второй её встраиватель был бы вторым объявлением одного предмета. Поэтому
// пакет принимает записи каталога параметром, а собирает их композиционный
// корень — команда обхода дерева. Заодно это держит слой: `roleexport` не
// импортирует ни посев, ни адаптеры.
package roleexport

// CatalogEntry — то, что экспортёр берёт у записи каталога прав, и ровно это.
//
// Три поля, а не вся запись: `permission` и `required_acr_min` ни одного
// решения здесь не меняют, а поле, принятое и не прочитанное, — запрещённый
// исход (`api-conventions.md` §«Принято-и-проигнорировано»). Оба читаемых поля
// читаются ОБА: пара — единица этого пакета.
type CatalogEntry struct {
	// FQN — полное имя метода: `<владелец>.cloud.<модуль>.v1.<Служба>/<Метод>`. Из
	// него выводятся модуль, ресурс и действие (attribution.go).
	FQN string
	// RequiredRelation — отношение, которое спрашивает гейт. ПУСТАЯ строка —
	// это не «неизвестно», а «гейта нет вовсе»: действие освобождено, и правом
	// оно не выдаётся никому, потому что доступно всякому аутентифицированному.
	RequiredRelation string
	// ScopeObjectType — тип объекта, НА КОТОРОМ гейт спрашивает отношение.
	// Вторая половина пары; без неё `viewer` на проекте неотличим от `viewer` на
	// объекте ресурса.
	ScopeObjectType string
}
