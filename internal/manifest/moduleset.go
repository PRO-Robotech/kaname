// moduleset.go — набор модулей РАЗОМКНУТ: оператор чужого облака объявляет свой
// модуль доставкой, а не пересборкой образа.
//
// # Предмет: производитель спрашивал у своего продукта — второй такой круг
//
// Имя модуля судилось перечнем `authzmap.CatalogSeedModules()`, ВЫВЕДЕННЫМ из
// таблицы типов, которая ПОРОЖДАЕТСЯ из манифестов нашего дерева и вкомпилирована
// в бинарь. Модуль, которого в нашем дереве нет, был поэтому невыразим ни при
// каком входе — ни файлом, ни глаголом: оболочка отвергалась «модуль вне
// закрытого набора», а правило роли — «unknown module».
//
// Круг в точности тот же, что уже разобран у таблицы типов ([TypeReferent]), и
// разомкнут он тем же способом: загрузчик судит то, что вправе судить сам
// (ФОРМУ), а вопрос существования адресует тому, у кого на него есть ответ.
//
// # Три вопроса об имени модуля, и у каждого свой судья
//
//	как называется        ФОРМА — `domain.IsWellFormedModuleName`, грамматика
//	                      объявлена ОДНАЖДЫ и судит оба поля: оболочку манифеста
//	                      и сегмент `module` правила роли;
//	один ли у него дом    СТОЛКНОВЕНИЕ — имя, объявленное больше чем одним
//	                      манифестом ОДНОГО обхода, есть находка, называющая ОБА
//	                      места. Одного документа для этого вопроса мало by
//	                      construction, поэтому судит его обход (check.go), а не
//	                      [Load];
//	есть ли такой модуль  ЧЛЕНСТВО — собственное объявление документа плюс набор,
//	                      внесённый вызывающим ([WithModuleSet]). Судится у
//	                      сегмента `module` правила роли, где вопрос и возникает.
//
// # Почему членство спрашивается у ОБХОДА, а не у таблицы образа
//
// Доставка есть ЗАКРЫТЫЙ НАБОР (delivery.go): всё, что модулем является, лежит в
// ней манифестом, потому что отсутствие манифеста снятием модуля НЕ является и
// отвергает старт (`#1034`). Значит объявления обхода и есть полный перечень
// модулей установки, а таблица образа знает лишь ту его часть, что приехала из
// нашего дерева.
//
// Набор, внесённый вызывающим, ДОБАВЛЯЕТСЯ к объявлениям, а не замещает их: так
// провязка живых строк каталога (её опора переезжает задачей `#1861`) может
// только расширить признаваемое и не в силах молча сузить его до перечня, от
// которого мы здесь уходим.
//
// # Что набор решает НА САМОМ ДЕЛЕ — и это измерено, а не задумано
//
// Полоса заводилась в расчёте на то, что правило вправе назвать модуль соседа по
// доставке. Это неверно: `validateRuleOwnership` (roles.go) отвергает такое
// правило ВСЕГДА — междоменная роль принадлежит платформе, а не модулю. Значит
// набор решает не «принять или отвергнуть», а КАКОЙ ОТКАЗ получит автор:
//
//	модуля нет в установке   отказ ДОМЕНА «unknown module» — такого модуля нет
//	                         вовсе, чинится сменой имени;
//	модуль в установке есть  отказ ВЛАДЕНИЯ, называющий ОБА значения — модуль
//	                         есть, но он не твой, чинится переносом роли к
//	                         владельцу.
//
// Починки разные, поэтому и отказы разные; порядок проверок (домен, затем
// владение) есть часть этого решения, а не деталь.
//
// # Пустой набор не есть «принимаем любой»
//
// Ни одна ветвь ниже не превращает отсутствие набора в разрешение: не внесён —
// признаётся ровно собственный модуль документа, и правило, назвавшее чужой,
// отвергается с названной причиной. Тот же fail-closed, что у `domain.ModuleSetOf`
// с пустым перечнем.

var (
	// ErrMalformedModule — имя модуля не той формы.
	//
	// Пришло на место снятого `ErrUnknownModule` и отличается от него предметом:
	// тот судил ЧЛЕНСТВО в перечне, недоступном автору манифеста, этот судит
	// ФОРМУ, которую автор читает в тексте отказа и может исправить.
	ErrMalformedModule = errors.New("manifest: module name is malformed")

	// ErrModuleCollision — имя модуля объявлено больше чем одним манифестом
	// одного обхода.
	//
	// У модуля один манифест и один владелец. Прими мы второй — он молча
	// переопределил бы первый, и чей набор ролей доехал бы до применителя,
	// решал бы порядок обхода каталога.
	ErrModuleCollision = errors.New("manifest: module is declared by more than one manifest")
)

// WithModuleSet вносит набор модулей, известный ВЫЗЫВАЮЩЕМУ.
//
// Вносит его вызывающий по тому же доводу, по которому он вносит референт типа и
// оракул отношений: смысл вопроса «есть ли такой модуль» у вызывающих РАЗНЫЙ.
//
//	обход доставки/дерева   перечень объявлен САМИМ обходом; вызывающий вправе
//	                        добавить к нему живые строки каталога;
//	одиночный [Load]        объявлений обхода нет, признаётся собственный модуль
//	                        документа плюс внесённое.
//
// Набор ДОБАВЛЯЕТСЯ к собственному объявлению документа, а не замещает его:
// манифест всегда вправе говорить о себе.
//
// `nil` вносить бессмысленно и потому отвергается молчанием — как и у
// [WithRelationOracle].
func WithModuleSet(set domain.ModuleSet) LoadOption {
	return func(opts *loadOptions) {
		if set == nil {
			return
		}
		opts.modules = set
	}
}

// moduleSetFor — набор, которым судятся модули, названные ПРАВИЛАМИ ролей
// документа: его собственный модуль плюс внесённый вызывающим.
func moduleSetFor(m *Manifest, supplied domain.ModuleSet) domain.ModuleSet {
	return declaredPlusSupplied{own: m.Module, supplied: supplied}
}

// declaredPlusSupplied — объединение «собственный модуль документа» и
// «внесённое вызывающим».
//
// Тип, а не карта, собранная на месте: собранная карта была бы КОПИЕЙ внесённого
// набора и разошлась бы с ним, если внесённый набор живой (снимок каталога
// обновляется по своему периоду). Здесь вопрос переадресуется источнику каждый
// раз.
type declaredPlusSupplied struct {
	own      string
	supplied domain.ModuleSet
}

// IsKnownModule реализует [domain.ModuleSet].
func (s declaredPlusSupplied) IsKnownModule(module string) bool {
	if module != "" && module == s.own {
		return true
	}
	return s.supplied != nil && s.supplied.IsKnownModule(module)
}

// PeekModule — имя модуля, названное документом, БЕЗ суждения обо всём остальном.
//
// Нужно обходу: перечень объявленных модулей обязан быть известен ДО того, как
// хоть один документ будет судим целиком, — иначе правило, называющее модуль
// соседа по доставке, отвергалось бы порядком обхода, а не по существу.
//
// # Почему это НЕ второй словарь
//
// Разбор идёт в ТУ ЖЕ структуру [Manifest] и потому читает ТОТ ЖЕ yaml-тег:
// второго объявления имени ключа здесь не заводится, и разойтись ему не с чем.
// Строгость `KnownFields` намеренно не включается — форму документа судит [Load],
// и второй судья формы дал бы два отказа об одном предмете.
//
// Отказ разбора здесь ПРОГЛАТЫВАЕТСЯ, и это не мягкий проход: документ, который
// не разобрался, до [Load] всё равно дойдёт и будет назван находкой. Молчаливо
// пропущено ровно одно — его вклад в перечень объявленных, а негодный документ
// перечня и не образует.
//
// # Почему ЭКСПОРТИРОВАНА (задача продукта #2045)
//
// Второй вызывающий — обход модели (`modelrender`), которому надо приписать
// НЕГОДНЫЙ документ модулю, который тот объявил: иначе документ, лежащий на
// месте и просто не разобравшийся, объявляется отсутствующим, и читатель идёт
// заводить манифест, который уже написан.
//
// Своя реализация у второго вызывающего была бы ВТОРЫМ СЛОВАРЁМ — тем самым, от
// которого предостерегает абзац выше, — и разошлась бы она молча: обе дают
// «имя прочитано» на честном документе. Расширение поверхности пакета здесь
// дешевле расхождения.
func PeekModule(data []byte) string {
	var m Manifest
	// Исход разбора здесь НЕ читается намеренно: документ, который не
	// разобрался, имени не даст — поле останется пустым, — а находкой его
	// назовёт [Load] на второй ступени обхода.
	_ = yaml.Unmarshal(data, &m)
	return m.Module
}

// declaredModules — перечень модулей, объявленных обходом, и находки
// столкновения.
//
// Находка называет ОБА места: одно место сказало бы автору, какой манифест
// «лишний», не сказав, с чем он столкнулся, — а какой из двух лишний, решает
// человек, и решать он вправе только увидев оба.
//
// Имя негодной формы в перечень НЕ ПОПАДАЕТ: его отвергает [Load] своей
// причиной, и признать его здесь значило бы дать правилу роли сослаться на
// модуль, которого установка не примет.
func declaredModules(paths []string, docs [][]byte) (domain.ModuleSet, []string) {
	names := make([]string, 0, len(docs))
	where := make(map[string]string, len(docs))
	var findings []string

	for i, data := range docs {
		name := PeekModule(data)
		if name == "" || !domain.IsWellFormedModuleName(name) {
			continue
		}
		if first, seen := where[name]; seen {
			findings = append(findings, fmt.Sprintf(
				"%s: %v: модуль %q уже объявлен манифестом %s — у модуля один манифест "+
					"и один владелец; второй молча переопределил бы первый, и чей набор "+
					"ролей доедет до применителя, решал бы порядок обхода каталога",
				paths[i], ErrModuleCollision, name, first))
			continue
		}
		where[name] = paths[i]
		names = append(names, name)
	}
	return domain.ModuleSetOf(names...), findings
}
