// delivery.go — чтение манифестов, ДОСТАВЛЕННЫХ работающей службе (задача #1875).
//
// # Чем это отличается от CheckTree, стоящего рядом
//
// CheckTree судит ДЕРЕВО РАЗРАБОТКИ: его зовёт инструмент, ему нужен перечень
// находок целиком, и три исхода он отдаёт кодом возврата оболочке. Здесь предмет
// другой — КАТАЛОГ ДОСТАВКИ, смонтированный посадкой, — и вызывающий у него
// один: старт службы, которому нужен не перечень, а ответ «пускать ли». Поэтому
// обход переиспользуется целиком, а превращение его исхода в отказ живёт здесь,
// а не расползается по композиционному корню.
//
// # Почему ИМЯ файла здесь судится иначе, чем в дереве (задача #1901)
//
// В дереве манифест опознаётся базовым именем `manifest.yaml`: рядом лежат чужие
// документы, и судить их нашей формой значило бы выдавать находку там, где её
// никто не писал. В каталоге доставки чужих документов НЕТ: всё, что там лежит,
// положила посадка, а имя файла есть КЛЮЧ ConfigMap, а не имя из дерева.
//
// И это не вкус, а единственная исполнимая форма. Замерено kubectl, обе стороны:
//
//	$ kubectl create configmap probe \
//	    --from-file=iam/manifest.yaml=services/iam/manifest.yaml --dry-run=client -o yaml
//	error: "iam/manifest.yaml" is not a valid key name for a ConfigMap: a valid
//	  config key must consist of alphanumeric characters, '-', '_' or '.'
//
//	$ kubectl create configmap probe --from-file=services/iam/manifest.yaml \
//	    --from-file=services/vpc/manifest.yaml --dry-run=client -o yaml
//	error: cannot add key "manifest.yaml", another key by that name already exists
//	  in Data for ConfigMap "probe"
//
// То есть в одном ConfigMap ключа `manifest.yaml` может быть только ОДИН, а
// подкаталога `<модуль>/` не может быть вовсе. Подкаталог через `items[].path`
// тоже не выручает: том кладёт полезную нагрузку в каталог с ведущими точками, а
// на верхнем уровне оставляет СИМВОЛЬНУЮ ССЫЛКУ на первый сегмент пути, — обход
// ссылки не разыменовывает и вглубь не идёт (замер — в deliverymount_test.go).
//
// Требуя имени `manifest.yaml`, доставка требовала входа, которого не бывает: та
// самая «неисполнимая возможность» (`api-conventions.md`), только не в поле
// запроса, а в форме доставки.
//
// Следствие названо прямо: посторонний ключ в каталоге доставки — НАХОДКА, а не
// то, что читатель вправе молча пропустить. Файл, доставленный и невидимый
// читателю, есть ровно тот класс, ради которого доставка заводилась.
//
// # Почему пустой каталог — ОТКАЗ, а не «модулей нет»
//
// Принято `#1034` дословно: отсутствие файла манифеста снятием НЕ является.
// Причина названа в `#1027`: системе неизвестна ПРИЧИНА отсутствия — удаление,
// конфликт слияния, неполный ConfigMap и откат правки выглядят одинаково. Пустой
// каталог, прочитанный как «платформа ничего не объявляет», сделал бы сорванное
// монтирование неотличимым от снятия всех модулей разом — и это состояние
// приезжало бы не отказом, а тишиной.
//
// # Почему отказ, а не мягкий проход
//
// Мягкий проход дал бы контроль, не отказавший ни разу за свою жизнь
// (`security.md` §Hardening, п. 8): сорванная доставка выглядела бы снаружи как
// «прав не выдали». Здесь она выглядит как «служба не поднялась и сказала,
// почему».

// Modules — имена модулей, объявленные ПРОЧИТАННЫМИ манифестами, в порядке
// путей обхода.
//
// Перепись, а не поиск: величина печатается вызывающим рядом с числом
// прочитанного, иначе «доставлено шесть манифестов» не отличается от
// «доставлено шесть копий одного».
func (r CheckReport) Modules() []string {
	out := make([]string, 0, len(r.Manifests))
	for _, m := range r.Manifests {
		out = append(out, m.Module)
	}
	return out
}

// LoadDelivered читает каталог доставки и превращает исход обхода в решение о
// старте: отчёт возвращается ВСЕГДА (перепись печатается и на отказе), ошибка —
// на всяком исходе, кроме годного.
//
// Отчёт отдаётся и при ошибке намеренно: без переписи «доставка сорвана» не
// отличается от «каталог прочитан, и он пуст», а чинятся эти два состояния
// по-разному.
// Набор модулей, известный вызывающему (живые строки каталога), вносится
// опциями и ДОБАВЛЯЕТСЯ к объявлениям самой доставки — moduleset.go.
func LoadDelivered(root string, opts ...LoadOption) (CheckReport, error) {
	report := CheckDelivery(root, opts...)
	switch report.ExitCode() {
	case CheckOK:
		return report, nil
	case CheckVoid:
		return report, fmt.Errorf(
			"каталог доставки %s не дал НИ ОДНОГО манифеста (осмотрено файлов %d) — "+
				"отсутствие манифеста снятием модуля НЕ является: причина отсутствия "+
				"службе неизвестна, и сорванное монтирование выглядит отсюда так же, "+
				"как снятие всех модулей разом; проверьте источник манифестов у посадки",
			root, report.PathsSeen)
	default:
		return report, fmt.Errorf(
			"каталог доставки %s: манифестов прочитано %d, находок %d:\n\t%s",
			root, report.ManifestsRead, len(report.Findings),
			strings.Join(report.Findings, "\n\t"))
	}
}

// CheckDelivery обходит КАТАЛОГ ДОСТАВКИ: читает каждую доставленную запись,
// кроме служебных записей тома, и судит её тем же Load, что и манифест дерева.
//
// Отдельная точка входа, а не флаг у CheckTree: у полос разные вызывающие и
// разные предметы, и вызывающий не должен выбирать поведение булевым аргументом,
// смысл которого читается только по объявлению.
func CheckDelivery(root string, opts ...LoadOption) CheckReport {
	// Референт — ЗАКРЫТАЯ ТАБЛИЦА, и это не умолчание: доставка есть
	// ПОТРЕБЛЕНИЕ. Таблица к этому моменту уже произведена и вкомпилирована в
	// бинарь, поэтому манифест, назвавший тип вне неё, не работает никак —
	// селектор роли адресовал бы несуществующий тип и не дал бы ни одного
	// пообъектного права, молча. Смена референта в порождающем проходе
	// (#1930) старту службы не отнимает НИЧЕГО: он идёт этой полосой.
	return walkManifestsOnDisk(root, isDeliveredManifestName, ReferentShippedTable, opts...)
}
