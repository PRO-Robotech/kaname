// Пакет manifestcheckrun — ЕДИНСТВЕННЫЙ производитель локальной проверки
// манифестов модуля: обход дерева, разбор каждого `manifest.yaml` тем же Load,
// которым его прочтёт посев iam, и производимость права каждой роли.
//
// # Почему пакет, а не тело команды (задача #1036)
//
// Вызывающих у проверки ДВА, и оба обязаны судить одним исполнителем:
// сборочная цель `module-manifest-check` (её зовёт конвейер) и действие
// `iamctl validate` (его зовёт человек и pre-commit). Вторая композиция тех же
// двух стадий разошлась бы с первой МОЛЧА — и разошлась бы именно там, где
// расхождение не видно: обе дают «годно» на честном дереве. Поэтому композиция
// живёт здесь в одном экземпляре, а обе команды — тонкие: разбор аргументов,
// вызов, код возврата.
//
// Прецедент формы — соседняя команда `authzmap-tables`: весь вывод в
// internal-пакете, потому что тот же вывод зовёт гейт свежести.
//
// # Потоки принимаются АРГУМЕНТАМИ, а не берутся у процесса
//
// Перепись идёт в вывод, находки — в поток ошибок, и это часть контракта: у
// обеих целей оболочка конвейера снимает потоки по отдельности. Приняв их
// аргументами, проверку можно позвать из пробы и прочитать оба потока, не
// поднимая процесса.
//
// # Что проверяется и почему исходов ЧЕТЫРЕ
//
// ЧТО проверяется, документировано на пакете
// services/iam/internal/manifest (check.go). Здесь живёт только композиция
// стадий и перевод их исходов в код возврата.
//
// Стадий у проверки ДВЕ, и порядок между ними — не свойство вызывающего.
// Сначала судится КЛАСС каждого действия раздела `resources` (удовлетворяет ли
// он гейт этого действия), и только потом — правила ролей. Пока первая стадия
// красна, вопрос «полон ли перечень» не имеет определённого множества, по
// которому считается. Порядок и замыкание объявлены в `roleexport.Check`; здесь
// они не воспроизводятся.
//
// Манифест читается ВТОРОЙ раз намеренно. Это второе чтение ФАЙЛА, а не второй
// разбор его формы: судит по-прежнему один загрузчик, и расходиться тут нечему.
//
// Пометка — НЕ находка, и печатаются они в разные потоки. Действие, чей гейт
// непроизводим правилом роли ни при каком классе, и действие, которого каталог
// не знает, вердикта не меняют: раздел `resources` порождается из аннотаций, и
// автор манифеста за их состояние не отвечает. Молчать о них нельзя — иначе они
// выходят из-под всех трёх проверок не нарушением, а невидимостью.
//
// Коды возврата:
//
//	0  годно  — каждый найденный манифест прочитан, разобран и связен;
//	1  находка — манифест негоден либо путь не прочитан;
//	2  VOID   — манифестов не найдено ни одного: проверять нечего;
//	3  проверка НЕ ИСПОЛНЯЛАСЬ — вызов разобрать не удалось.
//
// Третий код отделён от нулевого потому, что «ноль находок» обязано быть
// отличимо от «ноль прочитанного»; четвёртый — потому, что «не выполнилось» не
// вычитается из вердикта и не зачитывается в успех (`testing.md` §«Чтение
// вердикта»).
package manifestcheckrun

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"log/slog"
	"os"

	"github.com/PRO-Robotech/kaname/internal/apps/kaname/seed"
	"github.com/PRO-Robotech/kaname/internal/catalog"
	"github.com/PRO-Robotech/kaname/internal/manifest"
	"github.com/PRO-Robotech/kaname/internal/manifest/roleexport"
	"github.com/PRO-Robotech/kaname/internal/manifestoracle"
)

// ExitNotRun — проверка не исполнялась: вызов разобран не был.
//
// Разбор аргументов у flag.ExitOnError выходит кодом 2 — то есть СОВПАЛ БЫ с
// VOID и объявил бы пустым деревом опечатку в вызове; поэтому у ParseRoot свой
// набор флагов с ContinueOnError и свой код.
const ExitNotRun = 3

func Run(root string, stdout, stderr io.Writer) int {
	// Модель прав ВНОСИТСЯ оснасткой (#2002): загрузчик её больше не добывает —
	// иначе разбор доставки на старте читал бы модель, которая из этих же
	// манифестов и собирается. Здесь вопрос осмыслен: дерево разработки судится
	// каноном образа, и тип, о котором спрашивают, уже в нём.
	//
	// Канон не разобрался — это «проверка НЕ ИСПОЛНЯЛАСЬ», а не «находок нет»:
	// молча ослабить обход значило бы напечатать зелёное о непроверенном.
	relationOracle, oraErr := manifestoracle.Canon()
	if oraErr != nil {
		_, _ = fmt.Fprintf(stderr,
			"проверка прав НЕ ИСПОЛНЯЛАСЬ: канон модели прав не разобран: %v\n", oraErr)
		return ExitNotRun
	}
	report := manifest.CheckTree(root, manifest.WithRelationOracle(relationOracle))

	// Перепись печатается ВСЕГДА и первой: без неё зелёный вердикт неотличим от
	// вердикта обхода, не прочитавшего ничего.
	_, _ = fmt.Fprintf(stdout, "корень обхода: %s\n", root)
	_, _ = fmt.Fprintf(stdout, "перепись: %s\n", report.Summary())
	for _, p := range report.Paths {
		_, _ = fmt.Fprintf(stdout, "  прочитан: %s\n", p)
	}
	for _, f := range report.Findings {
		_, _ = fmt.Fprintf(stderr, "НАХОДКА: %s\n", f)
	}

	rightsCode := checkRights(root, report.Paths, relationOracle, stdout, stderr)

	code := report.ExitCode()
	if code == manifest.CheckOK && rightsCode != manifest.CheckOK {
		code = rightsCode
	}
	if code == manifest.CheckVoid {
		// Словами, а не только кодом: код читает оболочка, а строку — человек,
		// и она не вправе выглядеть успехом.
		//
		// ЗДЕСЬ СТОЯЛО «предмет у проверки появится вместе с первым манифестом
		// модуля»: утверждение ПЕРЕЖИЛО СВОЙ ПРЕДМЕТ — манифесты приехали, и
		// пустой обход означает теперь не «первый ещё не приехал», а «до них не
		// дошли». Текст посылал читателя ЖДАТЬ производителя, который уже
		// произвёл, — то есть уводил от единственной действующей причины VOID.
		// Сегодняшнее число сюда не переписано: оно устарело бы так же молча.
		// Спрашивают его у дерева: git ls-files | grep -cE '/manifest\.yaml$'.
		// Класс и перепись всех форм — kacho#1897.
		// Корень называется В САМОМ сообщении, а не только переписью на stdout:
		// оболочка конвейера снимает stderr отдельной строкой, и «смотрите корень
		// обхода» без корня посылает читателя в пустоту. Держит
		// TestManifestVoidMessagesNameTheWalkRootInThemselves.
		_, _ = fmt.Fprintf(stderr,
			"манифестов в дереве нет ни одного — это НЕ успех, а «проверять нечего»: "+
				"манифесты отслеживаются деревом, поэтому пустой обход означает, что "+
				"до них не дошли — смотрите корень обхода (%s), а не форму манифеста\n", root)
	}
	return code
}

// parseArgs — свой набор флагов, чтобы отказ разбора не выходил кодом VOID.
func ParseRoot(prog string, args []string) (string, error) {
	fs := flag.NewFlagSet(prog, flag.ContinueOnError)
	root := fs.String("root", ".", "корень дерева, в котором ищутся манифесты модулей")
	if err := fs.Parse(args); err != nil {
		return "", err
	}
	if rest := fs.Args(); len(rest) > 0 {
		return "", fmt.Errorf("лишние аргументы: %v — корень задаётся флагом -root", rest)
	}
	if *root == "" {
		return "", errors.New("-root пуст: корень обхода не назван")
	}
	return *root, nil
}

// checkRights — производимость прав ролей каждого прочитанного манифеста.
//
// Возвращает КОД, а не ошибку: у проверки те же три исхода, что у обхода, и
// «каталог не прочитан» не вправе выглядеть ни находкой о манифесте, ни успехом.
//
// Обход манифестов НЕ повторяется: пути приходят от единственного обходчика.
// Повторяется только чтение файла — судит его по-прежнему один загрузчик.
func checkRights(root string, paths []string, relationOracle manifest.RelationOracle,
	stdout, stderr io.Writer,
) int {
	if len(paths) == 0 {
		// Манифестов нет — предмета у этой проверки нет тоже, и молчать об этом
		// нельзя: «ноль находок» обязано быть отличимо от «ноль прочитанного».
		_, _ = fmt.Fprintln(stdout, "права ролей: манифестов не прочитано ни одного — проверять нечего")
		return manifest.CheckOK
	}

	reg, err := seed.LoadPermissionRegistry(context.Background(),
		slog.New(slog.NewTextHandler(stderr, &slog.HandlerOptions{Level: slog.LevelWarn})))
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "проверка прав НЕ ИСПОЛНЯЛАСЬ: каталог прав не прочитан: %v\n", err)
		return ExitNotRun
	}
	// Каталожный факт берётся СНИМКОМ, а не у литерала: читатель на литерале
	// продолжил бы считать снятый тип живым (kacho#1816). Снимок собирается из
	// того же перечня, которым миграция посеяла строки, поэтому вердикт
	// команды остаётся воспроизводимым из ДЕРЕВА и базы не требует — иначе
	// сборочная проверка стала бы функцией состояния чужой базы.
	facts, ferr := catalog.NewFacts(seed.LiteralRows())
	if ferr != nil {
		_, _ = fmt.Fprintf(stderr,
			"проверка прав НЕ ИСПОЛНЯЛАСЬ: каталожный факт не собран: %v\n", ferr)
		return ExitNotRun
	}

	rows := reg.All()
	entries := make([]roleexport.CatalogEntry, 0, len(rows))
	for _, r := range rows {
		entries = append(entries, roleexport.CatalogEntry{
			FQN:              r.FQN,
			RequiredRelation: r.RequiredRelation,
			ScopeObjectType:  r.ScopeExtractor.ObjectType,
		})
	}
	actions, outside := roleexport.Attribute(entries)
	// Записи вне формы модуля НАЗЫВАЮТСЯ: платформенные службы ресурсом модуля
	// не являются, и отбросить их молча значило бы сделать перепись неверной.
	_, _ = fmt.Fprintf(stdout, "каталог прав: записей %d · привязано действий %d · вне формы модуля %d\n",
		len(entries), len(actions), len(outside))
	if len(actions) == 0 {
		_, _ = fmt.Fprintln(stderr,
			"проверка прав НЕ ИСПОЛНЯЛАСЬ: привязано ноль действий — судить нечем")
		return ExitNotRun
	}

	// Второе чтение идёт ПОД КОРНЕМ и тем же читателем, что и обход. Путь сюда
	// принёс обход, а между записью каталога и этим открытием лежит окно: в нём
	// любой сегмент подменяется ссылкой наружу, и чтение ПО ИМЕНИ уходит за
	// корень, не заметив этого. Через os.Root каждый сегмент разрешает ядро
	// относительно корня, поэтому свойство держится построением, а не тем, что
	// вызывающий о нём помнит. Читатель один на всех: вторая реализация
	// разошлась бы с первой молча — и разошлась бы именно там, где расхождение
	// не видно, потому что обе дают «прочитано» на честном дереве.
	treeRoot, err := os.OpenRoot(root)
	if err != nil {
		_, _ = fmt.Fprintf(stderr,
			"проверка прав НЕ ИСПОЛНЯЛАСЬ: корень обхода не открыт: %v\n", err)
		return ExitNotRun
	}
	defer func() { _ = treeRoot.Close() }()

	code := manifest.CheckOK
	for _, rel := range paths {
		data, err := manifest.ReadUnderRoot(treeRoot, rel)
		if err != nil {
			_, _ = fmt.Fprintf(stderr, "НАХОДКА: %s: повторное чтение: %v\n", rel, err)
			code = manifest.CheckFailed
			continue
		}
		m, err := manifest.Load(data, manifest.WithRelationOracle(relationOracle))
		if err != nil {
			// Форму уже осудил обход, и его код возврата это учёл; здесь просто
			// нечего судить дальше.
			continue
		}
		// Обе стадии зовутся ОДНОЙ функцией: порядок «класс → правила» и
		// замыкание на красной первой живут в ней, а не здесь. Проверка
		// порядка, написанная в команде, не защищала бы второго вызывающего той
		// же связки.
		rep := roleexport.Check(facts, m, actions)
		_, _ = fmt.Fprintf(stdout, "  права ролей %s: %s\n", rel, rep.Summary())
		// Соединение «действие раздела ↔ запись каталога» судится ЗДЕСЬ, а не
		// только пробой пакета. Пока вызова не было, обещание соседней
		// диагностики («судит несопоставленное действие сверка соединения, и
		// там это ОТКАЗ») было ложным: у `CheckActionLinkage` не было НИ ОДНОГО
		// вызывающего в прод-коде, и направление «каталог → раздел» не
		// исполнялось нигде.
		lfaults, lcensus := roleexport.CheckActionLinkage(m, actions)
		_, _ = fmt.Fprintf(stdout, "  соединение %s: %s\n", rel, lcensus.Summary())
		for _, f := range lfaults {
			_, _ = fmt.Fprintf(stderr, "НАХОДКА: %s: %s\n", rel, f)
			code = manifest.CheckFailed
		}
		// Пометки печатаются в ВЫВОД, а не в поток ошибок, и вердикта не
		// меняют: состояние, за которое автор манифеста не отвечает, обязано
		// быть названо и обязано быть отличимо от находки.
		for _, n := range rep.Notes {
			_, _ = fmt.Fprintf(stdout, "  пометка (%s): %s: %s\n", n.Kind, rel, n.Detail)
		}
		for _, f := range rep.Faults {
			_, _ = fmt.Fprintf(stderr, "НАХОДКА: %s: %s\n", rel, f)
			code = manifest.CheckFailed
		}
	}
	return code
}
