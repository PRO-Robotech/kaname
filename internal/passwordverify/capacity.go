package passwordverify

// capacity.go — ёмкость проверки: сколько проверок идут ОДНОВРЕМЕННО
// (приёмка §5 PWV-15).
//
// # Почему ёмкость вообще есть
//
// Проверка значения объявленного формата занимает столько памяти, сколько
// назначает параметр в самом значении, — на потолке записи это 128 МиБ. Без
// предела всплеск входов кончился бы не отказом «ёмкость исчерпана», а падением
// процесса вместе с проверкой прав всей платформы.
//
// # Почему «спросить» и «занять» — ОДНА операция
//
// Пара «есть ли место» и «занять место» под конкуренцией пропускает больше
// ёмкости, чем объявлено: между вопросом и занятием успевает вклиниться сосед.
// Захват здесь — одна неблокирующая отправка в канал: занято место или нет,
// решает сам оператор, и разнести решение с его следствием нечем by construction.

import "fmt"

// capacityGate — ёмкость как набор мест.
type capacityGate struct {
	slots chan struct{}
}

// newCapacityGate — ёмкость из объявленной величины.
//
// Величина БЕЗ УМОЛЧАНИЯ: незаданная либо не положительная — отказ построения,
// называющий ручку. Ноль означал бы отказ каждой проверки, а не «без предела»,
// и подставить его молча значило бы выбрать за оператора то, чего он не выбирал.
func newCapacityGate(capacity int) (*capacityGate, error) {
	if capacity <= 0 {
		return nil, fmt.Errorf("Illegal argument password_verifier.capacity = %d: required, положительная — "+
			"ноль означал бы отказ каждой проверки, а не «без предела»", capacity)
	}
	return &capacityGate{slots: make(chan struct{}, capacity)}, nil
}

// acquire — занять место, если оно есть. Возвращает освобождающую функцию и то,
// удалось ли: ОДНОЙ операцией, без промежутка между вопросом и занятием.
func (g *capacityGate) acquire() (func(), bool) {
	select {
	case g.slots <- struct{}{}:
		released := false
		return func() {
			if released {
				return
			}
			released = true
			<-g.slots
		}, true
	default:
		return func() {}, false
	}
}
