package passwordverify

// capacity.go — ёмкость проверки: сколько проверок идут ОДНОВРЕМЕННО
// (приёмка §5 PWV-15).
//
// # Почему ёмкость вообще есть
//
// Проверка значения объявленного формата занимает столько памяти, сколько
// назначает параметр в самом значении, — на потолке записи это 128 МиБ. Без
// предела всплеск входов кончился бы не отказом «ёмкость исчерпана», а падением
// процесса вместе с проверкой прав всей платформы.
//
// # Почему «спросить» и «занять» — ОДНА операция
//
// Пара «есть ли место» и «занять место» под конкуренцией пропускает больше
// ёмкости, чем объявлено: между вопросом и занятием успевает вклиниться сосед.
// Захват здесь — одна неблокирующая отправка в канал: занято место или нет,
// решает сам оператор, и разнести решение с его следствием нечем by construction.

import (
	"context"
	"fmt"
	"runtime"
)

// capacityGate — ёмкость как набор мест.
type capacityGate struct {
	slots chan struct{}
}

// newCapacityGate — ёмкость из объявленной величины.
//
// Текст отказа начинается со строчной и называет ручку: контрактный тон
// «Illegal argument …» принадлежит отказам, которые видит арендатор через
// край, а этот читает ОПЕРАТОР в выводе старта — и разбор ошибок дерева
// требует от внутреннего отказа обычной формы.
//
// Величина БЕЗ УМОЛЧАНИЯ: незаданная либо не положительная — отказ построения,
// называющий ручку. Ноль означал бы отказ каждой проверки, а не «без предела»,
// и подставить его молча значило бы выбрать за оператора то, чего он не выбирал.
func newCapacityGate(capacity int) (*capacityGate, error) {
	if capacity <= 0 {
		return nil, fmt.Errorf("password_verifier.capacity = %d: required, положительная — "+
			"ноль означал бы отказ каждой проверки, а не «без предела»", capacity)
	}
	return &capacityGate{slots: make(chan struct{}, capacity)}, nil
}

// acquire — занять место, если оно есть. Возвращает освобождающую функцию и то,
// удалось ли: ОДНОЙ операцией, без промежутка между вопросом и занятием.
func (g *capacityGate) acquire() (func(), bool) {
	select {
	case g.slots <- struct{}{}:
		released := false
		return func() {
			if released {
				return
			}
			released = true
			<-g.slots
		}, true
	default:
		return func() {}, false
	}
}

// acquireWait — занять место, ДОЖДАВШИСЬ его; срок ожидания — контекст
// вызывающего. Нужен калибровке огибающей: она считает ту же функцию, что и
// проверка, и той же памятью, поэтому идёт в бюджете ёмкости, а не мимо него.
// Полоса входа этим путём не ходит: у неё исчерпание — свой исход, а не
// очередь.
func (g *capacityGate) acquireWait(ctx context.Context) (func(), error) {
	select {
	case g.slots <- struct{}{}:
	case <-ctx.Done():
		return nil, ctx.Err()
	}
	released := false
	return func() {
		if released {
			return
		}
		released = true
		<-g.slots
	}, nil
}

// Capacity — объявленная ёмкость: сколько проверок идут одновременно. Её
// читает полоса, делящая проверяющего с полосой входа (сверка секрета клиента
// церемонии), чтобы занимать не больше своей доли.
func (v *Verifier) Capacity() int { return cap(v.capacity.slots) }

// processorGate — места ВЫЧИСЛЕНИЯ: не больше, чем процессоров у процесса, и
// не больше ёмкости (kaname#882).
//
// Ёмкость — предел допуска по памяти. Вычисление упирается в процессор, и
// сверх числа процессоров одновременные вычисления только делят его: все
// кончаются вместе и позже всех, а следующее за проверкой действие (оператор
// базы со своим сроком) начинается у всех разом на занятом процессоре —
// одновременные операции отказывали по сроку разом. Вычисление сверх мест
// ждёт своего в порядке прихода (ожидающие отправители канала будятся по
// очереди; держит `TestProcessorGate_WaitersTakeTheSlotInArrivalOrder`) и
// кончается по одному: пропускная способность та же, задержка каждого — не
// больше.
//
// Срока ожидания у места нет намеренно, как нет отмены у самого вычисления:
// ждущих не больше ёмкости, и ожидание ограничено ёмкостью × стоимость одной
// проверки. Эту величину учитывает срок операции вызывающего (церемония —
// `ceremonyOperationDeadline`). Число процессоров читается при построении
// (`runtime.GOMAXPROCS`): процессоры, отведённые процессу позже, места не
// добавят.
type processorGate struct {
	slots chan struct{}
}

func newProcessorGate(capacity int) *processorGate {
	n := min(runtime.GOMAXPROCS(0), capacity)
	return &processorGate{slots: make(chan struct{}, max(n, 1))}
}

// acquire занимает место процессора, дождавшись его; возвращает освобождение.
func (g *processorGate) acquire() (release func()) {
	g.slots <- struct{}{}
	return func() { <-g.slots }
}

// ProcessorSlots — мест вычисления: меньшее из процессоров процесса и ёмкости.
func (v *Verifier) ProcessorSlots() int { return cap(v.processor.slots) }
