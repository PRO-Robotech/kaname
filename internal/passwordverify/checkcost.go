package passwordverify

// checkcost.go — СТОИМОСТЬ ОДНОЙ ПРОВЕРКИ на этом железе (kaname#882).
//
// # Зачем она вызывающему
//
// Проверка — вычисление, отмены не знающее, и одновременные проверки делят
// процессор: занятые разом все места ёмкости кончаются не раньше, чем
// ёмкость × стоимость одной проверки, измеренной в одиночку на тех же
// процессорах. Полоса, у которой проверка идёт внутри срока операции
// (сверка секрета клиента церемонии), выводит из этой величины срок,
// учитывающий очередь, — иначе одновременные операции отказывали бы по сроку
// все разом.
//
// # Что меряется
//
// Класс ПРИМАНКИ: её пишет хешер объявленного класса — тот же, что чеканит
// секрет клиента и новые пароли. Замер — калибровка огибающей над этим
// классом (`Envelope.calibrate`): самый дорогой из `calibrationSamples`
// прогонов неверного значения против синтетического значения класса, каждый —
// в месте ёмкости (ожидание места — срок вызывающего) и под мерой вызывающего;
// исходы приёмнику проверяющего не уходят. Значение класса дороже
// объявленного (записанное до того, как объявленный класс понизили) стоит
// дольше замера — граница замера названа здесь, а не спрятана в сроке.

import (
	"context"
	"errors"
	"fmt"
	"time"
)

// CheckCost — стоимость одной проверки класса приманки на этом железе.
//
// Без приманки — отказ: класс замера был бы угадан, и срок, выведенный из
// него, говорил бы о чужой цене.
func (v *Verifier) CheckCost(ctx context.Context, meter CostMeter) (time.Duration, error) {
	if v.decoy.IsZero() {
		return 0, errors.New("password_verifier.check_cost: приманки нет — класс замера не назван; " +
			"стоимость меряется по классу, которым пишется значение (SetDecoy)")
	}
	e, err := NewEnvelope(v, NopEnvelopeObserver{}, meter)
	if err != nil {
		return 0, fmt.Errorf("password_verifier.check_cost: %w", err)
	}
	cost, err := e.calibrate(ctx, v.decoyClass())
	if err != nil {
		return 0, fmt.Errorf("password_verifier.check_cost: %w", err)
	}
	return cost, nil
}
