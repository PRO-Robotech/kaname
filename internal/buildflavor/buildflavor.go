// Package buildflavor — ПРИЗНАК ТЕСТОВОЙ СБОРКИ (kaname#985).
//
// # Предмет
//
// Режим разработки ослабляет проверку вызывающих на внутреннем слушателе, в
// том числе опирающуюся на клиентский сертификат. Пока его разрешало значение
// настройки, продовая посадка переходила в него одной строкой — и страж старта
// это принимал. Теперь режим разработки разрешает только признак СБОРКИ, а не
// значение настройки: выпускной бинарь такого режима не исполняет вовсе.
//
// # Что считается тестовой сборкой
//
// Два источника, и оба — свойства сборки, а не входа процесса:
//
//   - метка сборки [Tag] (`go build -tags kaname_testbuild`) — образ стенда
//     разработки и наборов проб;
//   - бинарь проб Go (`testing.Testing()`): его собирает `go test`, и в
//     выпускной поставке он не бывает.
//
// Переменной окружения, ключа настройки или флага командной строки,
// включающих тестовую сборку, нет и быть не должно: они вернули бы ровно тот
// класс, который пакет закрывает.
package buildflavor

import "testing"

// Tag — метка сборки, объявляющая тестовую сборку. Имя — для текстов отказа
// и для тех, кто собирает образ стенда разработки.
const Tag = "kaname_testbuild"

// IsTestBuild — собран ли процесс как тестовый: меткой [Tag] либо как бинарь
// проб Go.
func IsTestBuild() bool { return testBuildTag || testing.Testing() }
