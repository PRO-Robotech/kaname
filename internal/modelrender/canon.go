// Package modelrender — блоки типов модели доступов ПОРОЖДАЮТСЯ из манифеста
// домена, а порождённое сверяется с каноном ПОБАЙТОВО (задача #1089, приёмка
// services/iam/docs/engineering/acceptance/model-generated-from-manifest.md).
//
// # Почему побайтово, а не «по смыслу»
//
// Сверка по смыслу требует разбора обеих сторон и потому измеряет СОГЛАСИЕ ДВУХ
// РАЗБОРЩИКОВ, а не согласие текстов. Разборщик, не знающий формы, на ней молчит,
// и расхождение уезжает в слепую зону. У байтов слепой зоны нет.
//
// Модель есть контракт: лишняя строка в ней — лишнее право, недостающая — отказ
// там, где доступ выдан. Поэтому расхождение НАЗЫВАЕТ СТОРОНУ (§2 п. 3): эти два
// исхода чинятся разными правками и означают разное для арендатора.
//
// # Единица блока — тело, а не тело с баннером следующего домена
//
// Блок — от строки `type X` до ПЕРВОЙ ПУСТОЙ СТРОКИ. Комментарии канона стоят
// МЕЖДУ блоками (баннер домена принадлежит файлу, а не блоку), и единица «от
// `type X` до следующей строки `type`» приписала бы блоку чужой баннер.
//
// Замер, разводящий две единицы на этом дереве (ревизия HEAD линии). ВЕЛИЧИНА
// НАЗЫВАЕТ СВОЮ ЕДИНИЦУ, и обе строки даны в обеих единицах: канон несёт
// кириллическую прозу, поэтому байт и символ здесь расходятся почти на четверть,
// и число без единицы рядом с числом в другой единице выглядит сопоставимым, не
// будучи им.
//
//	единица A — тело блока          32 блока · 90 701 Б · 66 891 симв · 739 внутриблочных комментариев
//	единица B — тело плюс баннер     32 блока · 112 324 Б · 86 302 симв (весь файл)
//
// Последний сдвиг величин — переход написания якоря кластера
// (`cluster_kacho_root` → `cluster_root`, задача #2113): якорь назван в каноне
// ПЯТЬ раз, каждое называние короче на шесть знаков, и из пяти в телах блоков
// стоят ДВА — отсюда убыль в двенадцать байт у единицы A и в тридцать у
// единицы B. Прежний сдвиг был у
// переименования каталогов службы, до него — у имени схемы Postgres. Величины
// пересняты разбором, а не вычтены на бумаге: канон порождается из манифестов,
// и арифметика в уме дала бы совпадение, которое нечем проверить.
//
// # Канон УШЁЛ ВПЕРЁД от ревизии приёмки, и это сказано здесь, а не подразумевается
//
// Прежняя редакция шапки утверждала побайтовое равенство канона ревизии приёмки
// 5dcefe67. Равенства больше НЕТ: #1820 снял на кластере отношение `console` —
// читателя у него не было ни одного, и выдать его было нечем — и внёс на его
// место разбор снятия. Одним этим коммитом сдвинулись все пять величин выше;
// они пересняты разбором, а утверждение о равенстве снято вместе с предметом,
// потому что гейт величин судит ЧИСЛА и на пережившей себя прозе рядом с ними
// молчит by construction.
//
// Единица счёта осталась ТОЙ ЖЕ, что в §0.7 приёмки, — строка-комментарий с
// отступом внутри тела `type`. На ревизии приёмки этот же счёт давал 720, и
// разборщик здесь с разборщиком приёмки тогда СОШЛИСЬ, а не «оба смолчали».
// Сходится ЕДИНИЦА, а не число: число есть свойство ревизии канона, и §0.7
// остаётся верной записью о своей — переписывать её задним числом значило бы
// сделать ложным замер, который был верен.
//
// Величины ВОСПРОИЗВОДЯТСЯ разбором, а не переписываются: гейт
// `TestCanonHeaderNamesItsUnitAndReproducesTheMeasurement` пересчитывает их из
// канона и падает на просроченной либо посчитанной в другой единице. В строке
// единицы A прежде стояло тело блоков В СИМВОЛАХ под обозначением байтов, рядом
// со строкой единицы B, где байты настоящие; из этой таблицы задача #1847 взяла
// своё число и построила на нём посылку (задача #1857).
//
// Ошибочная пара здесь НЕ воспроизводится дословно намеренно: гейт судит всякую
// величину шапки, и цитата неверного числа краснила бы его на собственном
// объяснении.
package modelrender

import (
	"bytes"
	"sort"

	"github.com/PRO-Robotech/kaname/internal/authzmap"
	"github.com/PRO-Robotech/kaname/internal/catalog"
)

// Block — блок типа канона: имя типа и его байты (единица A).
type Block struct {
	// Type — имя типа из строки `type X`.
	Type string
	// Body — байты блока, включая завершающий перевод строки последней строки.
	Body []byte
}

// SplitCanon разбирает канон на блоки в порядке файла.
//
// Порядок — файла, а не имён: канон правят люди, домены в нём сгруппированы, и
// порядок несёт смысл (§4 B-04). Отдать порядок манифесту значило бы сделать
// сверку функцией порядка строк YAML.
func SplitCanon(dsl []byte) []Block {
	var out []Block
	lines := bytes.Split(dsl, []byte("\n"))
	for i := 0; i < len(lines); i++ {
		if !bytes.HasPrefix(lines[i], []byte("type ")) {
			continue
		}
		// Строка `type` БЕЗ имени типом не является, и второе поле у неё
		// отсутствует. Прежняя редакция брала его безусловно и ПАДАЛА (#1969,
		// §0.14): вход достижим через `Render` — `objectType` из одних пробелов
		// проверку на пустоту проходит и даёт первую строку `"type  "`. С
		// заведением композиции этот разбор встаёт на путь СТАРТА процесса, и
		// паника там есть цикл падения пода, вызванный содержимым карты
		// оператора, а не находка.
		//
		// Пропуск, а не блок с пустым именем: типа по такой строке НЕ
		// ОБЪЯВЛЕНО, и блок с именем `""` уехал бы в карты вызывающих как
		// настоящий. Молчаливым пропуск при этом не остаётся — вызывающий
		// сверяет ИСХОД разбора со своим ожиданием («ровно один блок ровно того
		// типа») и отвергает вход, назвав координату.
		fields := bytes.Fields(lines[i])
		if len(fields) < 2 {
			continue
		}
		name := string(fields[1])
		// Блок кончается пустой строкой ЛИБО следующим объявлением типа. Второе
		// условие не украшение: канон разделяет блоки пустой строкой всегда, но
		// правка, потерявшая разделитель, склеила бы два блока в один — и второй
		// перестал бы находиться ПО ИМЕНИ, то есть остался бы непрочитанным при
		// вердикте о первом. Найдено собственной инъекцией перестановки блоков.
		var body []byte
		for j := i; j < len(lines) && len(bytes.TrimSpace(lines[j])) > 0; j++ {
			if j > i && bytes.HasPrefix(lines[j], []byte("type ")) {
				break
			}
			body = append(append(body, lines[j]...), '\n')
		}
		out = append(out, Block{Type: name, Body: body})
	}
	return out
}

// OwnedTypes — типы канона, отнесённые закрытой таблицей authzmap.objectTypes к
// модулю, в порядке имён.
//
// ЗЕРКАЛО TypesOutsideModules: там — канон минус таблица, здесь — канон И
// таблица. Обе стороны выводятся из ОДНОГО обхода, поэтому «принадлежит модулю» и
// «не принадлежит никакому» не могут разойтись: тип, выпавший из одной стороны,
// появляется в другой, а не пропадает.
//
// Пересечение с КАНОНОМ обязательно, а не удобно: запись таблицы, чьего типа в
// каноне нет, есть расхождение таблицы с моделью, и у него свой держатель —
// безусловный гейт дрейфа (services/iam/internal/authzmap). Потребовав здесь
// рендера такого типа, сверка выдала бы находку на предмет соседа и краснела бы
// до его починки, ничего не говоря о манифесте.
//
// Ключ модуля в таблице и имя модуля закрытого набора — ОДИН словарь, и это
// замер, а не допущение: модуль балансировки таблица зовёт `loadbalancer`, как и
// набор, тогда как ТИПЫ его несут префикс `nlb_`. Согласие держит проба
// TestTheClosedTableSpeaksTheModuleVocabulary — без неё модуль, чей ключ разошёлся
// бы с набором, потерял бы все свои типы из ожидаемого МОЛЧА, и сверка перестала
// бы его видеть, оставаясь зелёной.
func OwnedTypes(resources []catalog.ResourceRow, dsl []byte, module string) []string {
	inCanon := make(map[string]struct{})
	for _, b := range SplitCanon(dsl) {
		inCanon[b.Type] = struct{}{}
	}
	var out []string
	for _, e := range resources {
		if e.Module != module {
			continue
		}
		typ, ok := authzmap.ObjectType(e.Module, e.Resource)
		if !ok {
			continue
		}
		if _, present := inCanon[typ]; present {
			out = append(out, typ)
		}
	}
	sort.Strings(out)
	return out
}

// TypesOutsideModules — типы канона, не отнесённые закрытой таблицей
// authzmap.objectTypes НИ К ОДНОМУ модулю, отсортированно.
//
// ВЫВОДИТСЯ вычитанием (канон минус значения таблицы), а не выписывается:
// выписанный перечень устареет молча, и это ровно тот класс, который #1089 ловит.
//
// Такие типы не порождает ни один манифест, и у сверки с ними ровно два негодных
// исхода: объявить расхождением — гейт красен НАВСЕГДА и его снимут; пропустить
// молча — шестой блок, дописанный рукой, не заметит НИКТО, а это дословно признак
// #1089. Годный исход один: перечень объявлен, число печатается переписью,
// ПРИРОСТ — находка (§2 п. 8, §4 B-06).
func TypesOutsideModules(resources []catalog.ResourceRow, dsl []byte) []string {
	owned := make(map[string]struct{})
	for _, e := range resources {
		if typ, ok := authzmap.ObjectType(e.Module, e.Resource); ok {
			owned[typ] = struct{}{}
		}
	}
	var out []string
	for _, b := range SplitCanon(dsl) {
		if _, ok := owned[b.Type]; !ok {
			out = append(out, b.Type)
		}
	}
	sort.Strings(out)
	return out
}
