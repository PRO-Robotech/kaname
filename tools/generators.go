//go:build tools

// Package tools пинит версии плагинов генерации через `go.mod` службы.
//
// # ЗАЧЕМ
//
// Содержимое `pkg/api` определяет ПЛАГИН, а не buf: у двух машин с разными
// версиями плагина одна и та же команда на одном и том же контракте даёт разный
// вывод. Пока плагин назван голым именем (`local: protoc-gen-go`), его выбирает
// PATH, и выбор этот невидим — обе стороны отвечают «сгенерил».
//
// Здесь плагины импортируются обычными зависимостями, поэтому их версии стоят в
// `go.mod`/`go.sum`. Объявление генерации (`proto/buf.gen.yaml`) зовёт каждый
// через `go run <пакет>`, то есть берёт версию из `go.mod` В МОМЕНТ ВЫЗОВА:
// машина и конвейер совпадают ПО ПОСТРОЕНИЮ, а не по договорённости. Копия в
// PATH при этой форме просто не исполняется, поэтому обойти её по
// невнимательности нельзя.
//
// # ПОЧЕМУ ФАЙЛ ЗАВЕДЁН ВМЕСТЕ С КОНТРАКТАМИ, А НЕ РАНЬШЕ
//
// До переезда контрактов (решение владельца 2026-09-13, kacho#2616) генерация в
// этом дереве не исполнялась ни разу: заглушки приезжали зависимостью
// платформы. Пин без предмета был бы объявлением без исполнителя.
//
// # ВЕРСИИ СОВПАДАЮТ С РАНТАЙМОМ
//
// Плагины пинятся к тем же версиям, против которых собирается порождённый код
// (`google.golang.org/protobuf`, `github.com/grpc-ecosystem/grpc-gateway/v2` в
// `go.mod`). Рассинхрон «стабы сгенерены новее рантайма» этим исключён.
//
// Тег сборки `tools` не даёт пакету попасть в обычную сборку.
package tools

import (
	_ "github.com/grpc-ecosystem/grpc-gateway/v2/protoc-gen-grpc-gateway"
	_ "google.golang.org/grpc/cmd/protoc-gen-go-grpc"
	_ "google.golang.org/protobuf/cmd/protoc-gen-go"
)
