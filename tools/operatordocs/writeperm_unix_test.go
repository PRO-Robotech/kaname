//go:build unix

// writeperm_unix_test.go — ПРАВА, с которыми порождённый документ ложится в дерево.
//
// Предмет узкий: `syncFile` создаёт документа, которого в дереве нет, и права
// создания выбирает сам. Значение прав — решение, а не деталь: перепись по обоим
// модулям (`os.WriteFile` в не-тестовом коде) даёт 0o600 у всех прочих, и два
// вызова этого файла были единственными, кто выбивался. Различие никем не
// решалось — оно возникло как побочный эффект.
//
// # Почему umask снимается, а не терпится
//
// `os.WriteFile` просит режим, а файловая система накладывает на него umask,
// который умеет только СНИМАТЬ биты. При umask 077 просьба 0o644 доедет как
// 0o600 — и проба зазеленела бы на непочиненном коде, то есть измерила бы
// ОБСТАНОВКУ, а не код. Снятый на время пробы umask делает просимый режим
// наблюдаемым дословно.
//
// Проба не параллельная намеренно: umask — свойство процесса, и сосед,
// создающий файл в это же окно, получил бы чужой режим.
//
// # Что здесь НЕ утверждается
//
// Второй вызов `os.WriteFile` того же файла (полоса обновления уже лежащего
// документа) отдельной пробы не имеет, и это не пропуск: `os.WriteFile` режим
// СУЩЕСТВУЮЩЕГО файла не меняет, поэтому просимое значение применяется там
// только в окне между чтением и записью — если документ за это время исчез.
// Окно из пробы не воспроизводится; значение у обеих полос одно и то же.
package operatordocs

import (
	"bytes"
	"os"
	"path/filepath"
	"syscall"
	"testing"
)

func TestSyncFile_CreatesTheDocumentNoWiderThan0600(t *testing.T) {
	old := syscall.Umask(0)
	t.Cleanup(func() { syscall.Umask(old) })

	root := t.TempDir()
	const name = "NOTICES-probe.md"
	const body = "порождённое тело\n"

	var out bytes.Buffer
	findings := syncFile(
		Options{Root: root, Write: true, Out: &out},
		name, body,
		func(string) (string, error) { return body, nil },
	)
	if len(findings) != 0 {
		t.Fatalf("запись документа дала находки %v — полоса создания не исполнилась,\n"+
			"и утверждение о правах было бы вакуумным.\nвывод:\n%s", findings, out.String())
	}

	// Положительный контроль: документ ДЕЙСТВИТЕЛЬНО написан и написан тем, что
	// просили. Без него «права не шире 0600» зеленело бы на ненаписанном файле.
	got, err := os.ReadFile(filepath.Join(root, name)) // #nosec G304 -- корень задан t.TempDir(), имя — константа этой пробы.
	if err != nil {
		t.Fatalf("документ не создан: %v", err)
	}
	if string(got) != body {
		t.Fatalf("создан документ с телом %q, просили %q", string(got), body)
	}

	st, err := os.Stat(filepath.Join(root, name))
	if err != nil {
		t.Fatalf("режим документа не прочитан: %v", err)
	}
	if perm := st.Mode().Perm(); perm&^0o600 != 0 {
		t.Fatalf("документ создан правами %04o — шире 0o600 на %04o.\n"+
			"Перепись дерева: прочие `os.WriteFile` не-тестового кода просят 0o600; "+
			"этот выбивается, и различие никем не решалось.", perm, perm&^0o600)
	}
	t.Logf("режим созданного документа %04o при снятом umask", st.Mode().Perm())
}
