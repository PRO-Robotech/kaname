// Доказательство того, что КАНАЛ ДЛИТЕЛЬНОСТЕЙ харнесса доносит разницу.
//
// Требование 7 («прибор обязан быть показан способным дать РАЗНЫЕ числа на
// заведомо разном входе») распадается на два вопроса, и до #713 они были слиты в
// одно утверждение, из-за чего второй проверялся способом, годным только для
// первого:
//
//   - СВОЙСТВО ВХОДА — стала ли работа вдвое больше. Оно счётное и снимается на
//     настоящем стеке: обращения к движку, строки объёма, стейтменты. Это
//     `harness_test.go`;
//   - СВОЙСТВО ПРИБОРА — доносит ли разницу в выборках до напечатанной величины
//     или схлопывает её. Оно НЕ требует ни стека, ни часов, и проверяется здесь —
//     подачей известных выборок прямо в `Cell.Stats`.
//
// Почему второй вопрос вынесен из стека. Прежняя редакция спрашивала его
// сравнением ДВУХ ЗАМЕРОВ («вдвое большая работа обязана быть медленнее») на
// ранере, который проба не занимает одна: тогда вердикт становится свойством
// машины, а читается как свойство дерева. Замер 2026-08-19 на одном и том же
// входе, 30 снятий в трёх условиях (вхолостую · 36 занятых петель на 12 ядрах ·
// четыре параллельных стека): p50 при N=20 гулял 85.1…148.8 мс (×1.75), при N=40 —
// 171.8…387.5 мс (×2.25), при том что счётная величина тех же снятий дала 4 и 8
// ровно тридцать раз из тридцати. Полоса шума НЕПОДВИЖНОГО входа шире, чем
// удвоение, о котором утверждение спрашивало.
//
// Проверки этого файла не поднимают контейнеров и не пропускаются под `-short`:
// доказательство прибора обязано исполняться в каждом прогоне, а не только там,
// где есть docker.
package authzformbench

import (
	"fmt"
	"testing"
	"time"

	"github.com/stretchr/testify/require"
)

// percentiles — то, что канал длительностей отдаёт наружу.
//
// Отдельный тип, а не `Cell`, ровно затем, чтобы предикат ниже можно было подать
// НЕ ТОЛЬКО настоящему вычислителю: без этого «проба способна упасть» осталось бы
// объявлением.
type percentiles struct {
	Repeats            int
	Min, P50, P95, Max float64
}

// statsOf — настоящий вычислитель: тот самый, чьи числа уезжают в отчёт.
func statsOf(ms []float64) percentiles {
	var c Cell
	c.Stats(ms)
	return percentiles{Repeats: c.Repeats, Min: c.Min, P50: c.P50, P95: c.P95, Max: c.Max}
}

// durationChannelPropagates — предикат требования 7 на стороне прибора.
//
// Возвращает ошибку с НАЗВАННЫМ нарушенным свойством, а не булево: проба, которая
// говорит «не сошлось», не даёт починить, а инъекция ниже сверяет ИМЕННО ТО
// свойство, которое ломала.
//
// Четыре свойства, и каждое закрывает свой способ соврать. Порядок проверок —
// часть предиката, а не оформление: предпосылка спрашивается раньше того, что на
// неё опирается, иначе отказ называет не тот пункт (проверено инъекцией — на
// вычислителе с переставленными колонками предикат сперва сообщал про хвост).
//
//  1. ПОРЯДОК И ЧИСЛО — min ≤ p50 ≤ p95 ≤ max, и число выборок отражено.
//     Величина, выпавшая из порядка, означает, что колонки перепутаны местами, и
//     тогда «p95 больше p50» не сообщает ничего;
//  2. СДВИГ ВИДЕН — выборки, каждая больше прежней, обязаны двинуть все четыре
//     величины. Ловит вычислитель-константу и вычислитель, огрубляющий шкалу
//     (различие меньше кванта исчезает);
//  3. ЗАКОННЫЙ БЛИЗНЕЦ — одинаковые выборки обязаны дать одинаковые величины.
//     Без этого пункта предикат означал бы «любые два числа различны» и был бы
//     зелён на вычислителе, выдающем шум: он «различает» всё, включая равное;
//  4. ХВОСТ ОТДЕЛЁН ОТ СЕРЕДИНЫ — разница ТОЛЬКО в хвосте обязана двинуть p95 и
//     максимум и НЕ двинуть p50. Ловит схлопывание, при котором одна величина
//     копируется в другую: на пункте 2 такой вычислитель зелен, потому что при
//     общем сдвиге растут обе.
func durationChannelPropagates(stat func([]float64) percentiles) error {
	base := []float64{10, 20, 30, 40, 50}
	shifted := make([]float64, len(base))
	for i, v := range base {
		shifted[i] = v + 1000
	}
	tail := append([]float64(nil), base...)
	tail[len(tail)-1] = 5000

	// Все четыре снятия делаются ДО проверок и в объявленном порядке: вычислитель,
	// отвечающий не входом, обязан быть пойман пунктом 2, а не тем, что его
	// позвали лишний раз внутри чужой проверки.
	b, s := stat(base), stat(shifted)
	again := stat(append([]float64(nil), base...))
	tl := stat(tail)

	// (1) ПОРЯДОК И ЧИСЛО — предпосылка остальных трёх. Проверяется первой: у
	// вычислителя, у которого максимум меньше минимума, «хвост не двинулся»
	// сообщало бы про хвост, тогда как перепутаны колонки.
	for _, c := range []struct {
		name string
		p    percentiles
		n    int
	}{{"базовая", b, len(base)}, {"сдвинутая", s, len(shifted)}, {"хвостовая", tl, len(tail)}} {
		if c.p.Repeats != c.n {
			return fmt.Errorf("%s выборка: число выборок %d вместо %d — величина снята не с того, "+
				"что подали", c.name, c.p.Repeats, c.n)
		}
		if !(c.p.Min <= c.p.P50 && c.p.P50 <= c.p.P95 && c.p.P95 <= c.p.Max) {
			return fmt.Errorf("%s выборка: порядок нарушен (min %.3f, p50 %.3f, p95 %.3f, max %.3f)",
				c.name, c.p.Min, c.p.P50, c.p.P95, c.p.Max)
		}
	}

	// (2) СДВИГ ВИДЕН
	for _, p := range []struct {
		name   string
		lo, hi float64
	}{
		{"min", b.Min, s.Min}, {"p50", b.P50, s.P50},
		{"p95", b.P95, s.P95}, {"max", b.Max, s.Max},
	} {
		if !(p.hi > p.lo) {
			return fmt.Errorf("сдвиг не виден: %s на выборках, каждая из которых больше, "+
				"дал %.3f против %.3f — канал длительностей схлопывает разницу", p.name, p.hi, p.lo)
		}
	}

	// (3) ЗАКОННЫЙ БЛИЗНЕЦ: равное обязано остаться равным
	if again != b {
		return fmt.Errorf("одинаковые выборки дали разные величины (%+v против %+v) — "+
			"вычислитель отвечает не входом, и его «различение» ничего не значит", again, b)
	}

	// (4) ХВОСТ ОТДЕЛЁН ОТ СЕРЕДИНЫ
	if !(tl.P95 > b.P95) || !(tl.Max > b.Max) {
		return fmt.Errorf("разница ТОЛЬКО в хвосте не двинула хвостовые величины: "+
			"p95 %.3f против %.3f, max %.3f против %.3f", tl.P95, b.P95, tl.Max, b.Max)
	}
	if tl.P50 != b.P50 {
		return fmt.Errorf("разница ТОЛЬКО в хвосте двинула середину: p50 %.3f против %.3f — "+
			"величины считаются не раздельно, и «p95 рядом с p50» не отличает выброс от сдвига",
			tl.P50, b.P50)
	}
	return nil
}

// TestDurationChannelPropagatesADifference — требование 7 на стороне прибора.
//
// Детерминированно: ни часов, ни контейнеров, ни соседей по машине. Одни и те же
// выборки дают один и тот же ответ на любой машине и под любой загрузкой.
func TestDurationChannelPropagatesADifference(t *testing.T) {
	require.NoError(t, durationChannelPropagates(statsOf),
		"канал длительностей харнесса не доносит разницу до напечатанных величин — "+
			"колонка времени в отчёте не годится, чтобы отличить одну форму от другой")
}

// TestDurationChannelStatsKeepsTheThirdOutcomeVisible — пустая выборка обязана
// стать «не выполнилось» с причиной, а не нулями, неотличимыми от быстрого ответа.
func TestDurationChannelStatsKeepsTheThirdOutcomeVisible(t *testing.T) {
	c := Cell{Outcome: Measured}
	c.Stats(nil)
	require.Equal(t, NotRun, c.Outcome,
		"ячейка без единой выборки объявлена измеренной — «не выполнилось» ушло бы в отчёт "+
			"нулём, то есть в пользу формы")
	require.NotEmpty(t, c.Reason, "исход «не выполнилось» обязан нести причину")
	require.Zero(t, c.Repeats)
}

// ── ЯЧЕЙКА: канал длительностей ЖИВ И СНЯТ С ЭТОЙ ОПЕРАЦИИ ───────────────────
//
// Предикат выше судит ВЫЧИСЛИТЕЛЬ (`Cell.Stats`) на поданных выборках. Здесь —
// вторая половина: годна ли САМА ЯЧЕЙКА, пришедшая с настоящего стека. Её зовёт
// `harness_test.go`, и вынесена она сюда затем, чтобы её способность отвергать
// доказывалась без стека и без docker.
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ: требования, чтобы замеры РАЗЛИЧАЛИСЬ (max > min).
//
// Оно стояло в харнессе и роняло исправный стенд (#1516): «2.739 не больше
// 2.739», два подлинных замера, совпавших до последнего разряда. Разряд здесь и
// есть предмет: прибор усекает длительность до целых микросекунд
// (`timedC`: time.Since(t0).Microseconds()/1000), поэтому два независимых замера
// операции в ~2.7 мс совпадают тем чаще, чем быстрее машина. Вердикт становился
// функцией разрешения часов, а читался как утверждение о дереве.
//
// Расширить квант нельзя — это отодвинуло бы порог, а не убрало его: «совпадут
// реже» есть вероятность там, где нужна невозможность. Повторить прогон нельзя
// тем более: повтор прячет ровно ту гонку, ради которой пробу пишут.
//
// А главное — требование было НЕИСПОЛНИМО ПО СУЩЕСТВУ. Оно спрашивало «замер это
// или подставленная константа», а эти два случая ПО ЗНАЧЕНИЯМ неразличимы:
// подлинный замер быстрой операции и подставленная константа дают одну и ту же
// пару чисел. Ни один предикат над выборками их не разделит.
//
// Поэтому вопрос перенесён туда, где ответ есть, и разделён надвое:
//
//	· «прибор не отдаёт константу» — `TestTimerAnswersTheWorkItWasGiven` ниже,
//	  детерминированно и с НАЗВАННЫМИ допусками: разница входов не выпрашивается
//	  у машины, а СОЗДАЁТСЯ ожиданием;
//	· «вычислитель не схлопывает разницу» — `durationChannelPropagates` выше.
//
// Остальные три свойства ячейки счётны или структурны и от часов не зависят.
func cellDurationChannelIsLive(c Cell, wantRepeats int) error {
	// (1) СЧЁТНОЕ: выборка снята с того числа прогонов, каким объявлена. Нулевой
	// повтор — разогрев и в счёт не идёт.
	if c.Repeats != wantRepeats {
		return fmt.Errorf("измеренных повторов %d при заказанных %d — выборка снята не с того "+
			"числа прогонов, каким объявлена", c.Repeats, wantRepeats)
	}
	// (2) ЧАСЫ ВООБЩЕ ПОШЛИ. Это единственная здесь величина, у которой есть
	// сторона часов, и запас назван числом, а не подразумевается: квант прибора —
	// 1 мкс, а измеряемое — круговое обращение к Postgres. Замер на живом стенде
	// 2026-08-30: самый быстрый повтор выдачи — 6.5 мс, то есть 6500 квантов.
	//
	// У снятого требования запас был НУЛЕВОЙ: оно требовало разницы в ОДИН квант
	// между двумя замерами, которые вправе совпасть. На том же стенде при N=40
	// разброс был 0.1 мс — сто квантов, и до отказа ему оставался один шаг.
	if !(c.Min > 0) {
		return fmt.Errorf("самый быстрый повтор занял ровно ноль — часы не пошли, и колонка " +
			"времени в отчёте была бы нулями, неотличимыми от мгновенного ответа")
	}
	// (3) СТРУКТУРНОЕ: порядок процентов между собой. Часов не спрашивает вовсе.
	if !(c.Min <= c.P50 && c.P50 <= c.P95 && c.P95 <= c.Max) {
		return fmt.Errorf("порядок нарушен (min %.3f, p50 %.3f, p95 %.3f, max %.3f) — "+
			"колонки перепутаны местами", c.Min, c.P50, c.P95, c.Max)
	}
	return nil
}

// TestCellLivenessIsNotAFunctionOfTheClock — инъекция предиката ячейки, обе
// стороны по каждой оси.
//
// ЗАКОННЫЙ БЛИЗНЕЦ здесь несёт главный смысл пробы: ячейка, у которой все замеры
// СОВПАЛИ, обязана пройти. Это ровно тот вход, что уронил конвейер (#1516), и он
// законен — быстрая машина вправе дать одинаковые числа.
func TestCellLivenessIsNotAFunctionOfTheClock(t *testing.T) {
	cellOf := func(ms ...float64) Cell {
		var c Cell
		c.Stats(ms)
		return c
	}

	// (а) ЗАКОННЫЙ БЛИЗНЕЦ: вход инцидента #1516 — два подлинных замера, совпавших
	// после усечения до микросекунд. Молчание здесь и есть починка.
	require.NoError(t, cellDurationChannelIsLive(cellOf(2.739, 2.739), 2),
		"ячейка с совпавшими замерами объявлена негодной — вердикт снова стал функцией "+
			"разрешения часов, а не свойством дерева (#1516)")
	// Тот же вход при РАЗЛИЧАЮЩИХСЯ замерах — тоже молчание: предикат не должен
	// требовать ни совпадения, ни различия.
	require.NoError(t, cellDurationChannelIsLive(cellOf(2.739, 3.115), 2))

	// (б) ВЫРОЖДЕННЫЕ ячейки: каждая ломает СВОЁ свойство, и предикат обязан
	// назвать именно его.
	for _, tc := range []struct {
		name string
		cell Cell
		want int
		says string
	}{
		{"выборка снята с другого числа прогонов", cellOf(1.0, 2.0, 3.0), 2, "повторов 3"},
		{"часы не пошли", cellOf(0, 0), 2, "часы не пошли"},
		{"колонки перепутаны", Cell{Repeats: 2, Min: 9, P50: 5, P95: 5, Max: 1}, 2, "порядок нарушен"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			err := cellDurationChannelIsLive(tc.cell, tc.want)
			require.Error(t, err, "вырожденная ячейка прошла предикат — он ловит форму, а не существо")
			require.Containsf(t, err.Error(), tc.says, "назван не тот пункт: %v", err)
		})
	}
}

// TestTimerAnswersTheWorkItWasGiven — ПРИБОР НЕ ОТДАЁТ КОНСТАНТУ.
//
// Это то самое свойство, ради которого в харнессе стояло «max > min», — но
// спрошенное там, где на него есть ответ. Разница входов здесь не выпрашивается у
// машины, а СОЗДАЁТСЯ: `time.Sleep` гарантирует НЕ МЕНЬШЕ заказанного, поэтому
// нижняя граница медленного замера — контракт стандартной библиотеки, а не удача.
//
// ДОПУСК НАЗВАН ЧИСЛОМ, а не подразумевается, и запас против кванта прибора
// (1 мкс) — стотысячекратный:
//
//	ожидание медленного      slowWork  = 200 мс   (гарантированный низ)
//	требуемая разница        minGap    = 100 мс
//
// Направление влияния машины односторонне и потому безопасно: загрузка может
// только УДЛИНИТЬ медленный замер, что утверждению помогает. Уронить пробу могла
// бы лишь машина, на которой пустая функция исполняется дольше 100 мс, — а это
// уже не «быстрая машина», а неработающее окружение.
//
// Проверяются ОБЕ стороны: константа проваливает разницу, а живой прибор — нет.
func TestTimerAnswersTheWorkItWasGiven(t *testing.T) {
	const (
		slowWork = 200 * time.Millisecond
		minGap   = 100.0 // миллисекунды
	)

	quick, _, err := timedC(func() (Counters, error) { return Counters{}, nil })
	require.NoError(t, err)
	slow, _, err := timedC(func() (Counters, error) {
		time.Sleep(slowWork)
		return Counters{}, nil
	})
	require.NoError(t, err)

	require.GreaterOrEqualf(t, slow-quick, minGap,
		"прибор ответил на вдвое-разную работу почти одинаково (%.3fмс против %.3fмс, разница "+
			"%.3fмс при требуемых %.0fмс) — так отвечает не измерение, а подставленная константа",
		slow, quick, slow-quick, minGap)
	require.GreaterOrEqualf(t, slow, float64(slowWork.Milliseconds())-1,
		"замер функции, ожидавшей %v, вышел %.3fмс — прибор мерит не ту работу, которую ему дали",
		slowWork, slow)
	t.Logf("прибор различает поданную работу: пустая %.3fмс, ожидавшая %v — %.3fмс (разница %.3fмс "+
		"при кванте прибора 0.001мс)", quick, slowWork, slow, slow-quick)
}

// ── инъекция: предикат обязан УМЕТЬ ОТВЕРГАТЬ ─────────────────────────────────

// TestDurationChannelProofIsAbleToFail подаёт предикату ВЫРОЖДЕННЫЕ вычислители.
//
// Без этой пробы `TestDurationChannelPropagatesADifference` был бы утверждением о
// себе: зелёное у предиката, который никогда не краснеет, означает ровно ничего.
// Каждый стенд-ин ломает СВОЁ свойство, и проверяется, что предикат называет
// именно его, — иначе четыре пункта свелись бы к одному, а три остальных стали бы
// украшением.
func TestDurationChannelProofIsAbleToFail(t *testing.T) {
	calls := 0
	cases := []struct {
		name string
		// чем именно вырожден
		what string
		stat func([]float64) percentiles
		// подстрока, по которой видно, что назван нужный пункт
		says string
	}{
		{
			name: "константа",
			what: "величины не зависят от входа вовсе",
			stat: func(ms []float64) percentiles {
				return percentiles{Repeats: len(ms), Min: 1, P50: 1, P95: 1, Max: 1}
			},
			says: "сдвиг не виден",
		},
		{
			name: "огрублённая шкала",
			what: "разница меньше кванта исчезает — квант здесь заведомо крупнее подаваемых величин",
			stat: func(ms []float64) percentiles {
				p := statsOf(ms)
				q := func(v float64) float64 { return float64(int(v/1e6)) * 1e6 }
				return percentiles{Repeats: p.Repeats, Min: q(p.Min), P50: q(p.P50), P95: q(p.P95), Max: q(p.Max)}
			},
			says: "сдвиг не виден",
		},
		{
			name: "нестабильный",
			what: "отвечает не входом: тот же вход даёт разные величины",
			stat: func(ms []float64) percentiles {
				calls++
				p := statsOf(ms)
				p.P50 += float64(calls)
				return p
			},
			says: "одинаковые выборки дали разные величины",
		},
		{
			name: "схлопнутый хвост",
			what: "p95 и max копируются из p50 — на общем сдвиге такой вычислитель зелен",
			stat: func(ms []float64) percentiles {
				p := statsOf(ms)
				p.P95, p.Max = p.P50, p.P50
				return p
			},
			says: "не двинула хвостовые величины",
		},
		{
			name: "перепутанный порядок",
			what: "min и max поменяны местами",
			stat: func(ms []float64) percentiles {
				p := statsOf(ms)
				p.Min, p.Max = p.Max, p.Min
				return p
			},
			says: "порядок нарушен",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			err := durationChannelPropagates(tc.stat)
			require.Errorf(t, err, "вырожденный вычислитель (%s) прошёл предикат — "+
				"значит предикат ловит форму, а не существо", tc.what)
			require.Containsf(t, err.Error(), tc.says,
				"предикат отверг вычислитель (%s), но назвал не тот пункт: %v", tc.what, err)
		})
	}
	// Законный близнец той же формы: настоящий вычислитель, поданный тем же
	// предикатом, обязан МОЛЧАТЬ. Без этой строки инъекция доказывала бы только,
	// что предикат умеет краснеть, — в том числе на исправном приборе.
	require.NoError(t, durationChannelPropagates(statsOf),
		"предикат краснеет на настоящем вычислителе — он ловит форму, а не дефект")
	t.Logf("инъекция: вырожденных вычислителей отвергнуто %d, законный близнец пропущен", len(cases))
}
