// Доказательство предпосылки, на которой этот пакет стоит в санкционированных
// поставщиках гейта `TestNoPackageStartsAContainerPerTest`: контейнер поднимается
// ОДИН на процесс, а изоляция между кейсами достигается собственной СХЕМОЙ внутри
// него.
//
// Гейт это допущение НЕ читает из кода — он ключуется на запись в своём списке, а
// запись обязана называть, где лежит доказательство, и требует, чтобы названный
// файл был отслеживаемым. Без этого файла санкция была бы утверждением о
// намерении: следующий контрибьютор, разбив `sync.Once` или начав поднимать базу
// из тела кейса, не уронил бы ничего, а гейт продолжил бы молчать именно потому,
// что пакет объявлен исключением.
//
// Обе половины проверяются ВМЕСТЕ и по отдельности бессмысленны: «сервер один»
// без «области разные» означает, что кейсы видят чужие строки и меряют не то, что
// думают; «области разные» без «сервер один» означает контейнер на кейс, то есть
// ровно то, что гейт и запрещает.
//
// # Что здесь изменилось со снятием движка отношений (S6)
//
// Предмет остался, носитель сменился. Прежде поставщиком был движок, а единицей
// изоляции — его store; проба заводила два store в одном сервере и требовала
// разных идентификаторов. Сегодня контейнер один — Postgres, на котором меряется
// форма E, — а единицей изоляции стала СХЕМА. Утверждается то же самое, и вторая
// половина стала СТРОЖЕ: разные имена схем ничего не доказывали бы сами по себе,
// поэтому проба пишет строку в одну и требует, чтобы вторая её не видела.
package authzformbench

import (
	"context"
	"testing"

	"github.com/stretchr/testify/require"
)

// TestOneStackManyStores — санкция гейта на этот пакет, выраженная исходом.
func TestOneStackManyStores(t *testing.T) {
	if testing.Short() {
		t.Skip("поднимает контейнеры")
	}
	ctx := context.Background()
	stack, _ := bootForTest(ctx, t)

	sc := NewScenario(2, 1, 2, "editor", DefaultVerbs())
	first, err := newRelStore(ctx, stack.DSN, "iso_first", sc)
	require.NoError(t, err)
	defer func() { _ = first.Teardown(ctx) }()
	second, err := newRelStore(ctx, stack.DSN, "iso_second", sc)
	require.NoError(t, err)
	defer func() { _ = second.Teardown(ctx) }()

	// Половина первая — СЕРВЕР ОДИН. Второй запрос стека обязан вернуть тот же
	// адрес: иначе `sync.Once` разорван и каждый кейс платит своим контейнером.
	again, _ := bootForTest(ctx, t)
	require.Same(t, stack, again,
		"второй запрос стека вернул ДРУГОЙ объект — контейнер поднимается не один раз, "+
			"и пакет перестал соответствовать тому, ради чего он внесён в санкционированные")

	// Половина вторая — ОБЛАСТИ РАЗНЫЕ, и это утверждается ИСХОДОМ, а не именем.
	// Выдача пишется в первую схему; вторая обязана её не увидеть. Сравнение имён
	// схем было бы утверждением о строке, которую проба сама и составила.
	_, err = first.Seed(ctx, sc.Structural(), Grant(FormE, sc))
	require.NoError(t, err)
	_, err = second.Seed(ctx, sc.Structural(), nil)
	require.NoError(t, err)

	subj, obj := sc.Subjects[0], sc.Object(0)
	okFirst, _, err := first.Check(ctx, subj, "v_get", obj)
	require.NoError(t, err)
	require.Truef(t, okFirst, "выдача не видна в СВОЕЙ схеме — засев не состоялся, и вторая "+
		"половина ниже зеленела бы на пустоте, а не на изоляции")

	okSecond, _, err := second.Check(ctx, subj, "v_get", obj)
	require.NoError(t, err)
	require.Falsef(t, okSecond, "выдача, записанная в ОДНУ схему, видна из ДРУГОЙ — изоляции "+
		"между кейсами нет, и любое число, снятое этим пакетом, относится к чужим данным "+
		"вперемешку со своими")
}
