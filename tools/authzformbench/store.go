package authzformbench

import (
	"context"

	"fmt"
)

// Counters — обращения, снятые на одной измеряемой операции.
//
// Колонок было ДВЕ, и это было содержательно, пока сравнивались две стороны: у
// движка отношений «обращение» было HTTP-вызовом, за которым стояло неизвестное
// число запросов к его Postgres, у формы E — SQL-стейтмент. Складывать их было
// нельзя ни в одной ячейке.
//
// Второй стороны больше нет (S6), и колонка обращений к движку СНЯТА, а не
// оставлена нулём: величина, у которой не осталось производителя, печатается
// нулём, неотличимым от измеренного, — ровно тот класс, против которого заведён
// `ProducerStatus` ниже. Осталась одна величина, и у неё есть имя.
type Counters struct {
	StmtSQL int // SQL-стейтменты, снятые на Postgres
}

// Volume — ёмкостная сторона ячейки.
//
// Смысл колонок закреплён здесь, потому что у двух из них он неочевиден:
//
//   - GrantRows   — строки ВЫДАЧИ: привязка, её субъекты и её правило-селектор;
//   - GrantBytes  — логические байты ВСЕХ строк хранилища формы, включая
//     структурные. Асимметрия «строки без структурных, байты со структурными»
//     унаследована от снятой базы сравнения и сохранена намеренно: числа
//     сегодняшних прогонов остаются сопоставимыми с уже опубликованными
//     отчётами (REPORT-*), которые считались этим же правилом. Чтобы асимметрия
//     не читалась молча, структурная часть вынесена в соседнюю пару колонок и
//     печатается рядом;
//   - StructuralRows/Bytes — зеркало объектов и цепь предков: то, что у формы
//     есть независимо от того, выдано ли кому-нибудь право;
//   - TableBytes  — весь размер отношений с индексами. Индекс табличный, а не
//     построковый, поэтому на строку он не делится и печатается отдельно.
type Volume struct {
	GrantRows       int64
	GrantBytes      int64
	StructuralRows  int64
	StructuralBytes int64
	TableBytes      int64
}

// ProducerStatus — состояние ПРОИЗВОДИТЕЛЯ величины `StmtSQL` на одном месте
// снятия.
//
// Величина, у входа которой нет производителя, зеленеет молча: она печатается
// нулём, неотличимым от измеренного. Поэтому производитель называется на каждое
// место снятия и считается заведённым только после контроля в обе стороны —
// счётчик не двигается, когда никто не спрашивает, и двигается ровно на один на
// одном заведомом стейтменте.
type ProducerStatus struct {
	Place    string // где снимается
	Producer string // чем снимается
	OK       bool   // прошёл ли контроль в обе стороны
	Note     string // что именно наблюдалось — печатается и при OK, и при провале
}

func (p ProducerStatus) String() string {
	state := "контроль НЕ пройден"
	if p.OK {
		state = "контроль пройден"
	}
	return fmt.Sprintf("%s — %s — %s (%s)", p.Place, p.Producer, state, p.Note)
}

// Tuple — ЕДИНИЦА НАМЕРЕНИЯ: «такой-то субъект связан таким-то отношением с
// таким-то объектом».
//
// Тип переехал сюда из снятого транспорта к движку отношений и потерял вместе с
// ним две вещи: теги JSON (сериализовать его больше некому — на wire он не
// уходит) и поле условия (условие на кортеже — свойство движка, и форма E его не
// выражает: строка не может отвечать по-разному на два одинаковых запроса).
//
// Он остаётся ОБЩИМ СЛОВАРЁМ, а не формой хранения: производители намерения
// (`Grant`, `RelabelOne`, `RevokeSubject`, `InlineIntent`) говорят на нём, а
// хранилище переводит его в свои строки у себя. Словарь пережил свою вторую
// сторону намеренно — числа сегодняшних прогонов остаются сопоставимыми с уже
// опубликованными отчётами, потому что намерение осталось тем же.
type Tuple struct {
	User     string
	Relation string
	Object   string
}

// RightsStore — граница «хранилище прав»: то единственное, о чём знает измеряющий
// код.
//
// Граница заводилась ради того, чтобы форма E вообще подключилась к матрице:
// прежний конструктор требовал модель авторизации для каждой формы, а засев
// возвращал конкретный тип клиента движка. Реализация у неё теперь ОДНА
// (`relStore`), и это не повод её снимать: она перечисляет операции, которые
// прибор измеряет, и держит их подписи в одном месте — измеряющий код о том, чем
// форма отвечает, по-прежнему не знает.
type RightsStore interface {
	// Seed кладёт структурные строки и (когда grant непуст) строки выдачи.
	// Засев не входит ни в одну измеряемую величину.
	Seed(ctx context.Context, structural, grant []Tuple) (Counters, error)

	// Write и Remove — измеряемые мутации: выдача, переразметка, отзыв.
	Write(ctx context.Context, tuples []Tuple) (Counters, error)
	Remove(ctx context.Context, tuples []Tuple) (Counters, error)

	// InlineGrant пишет ПРЕДМЕТ выдачи и саму выдачу в ОДНОЙ транзакции.
	//
	// Операция существует потому, что у формы E она ВЫРАЗИМА: выдача и её предмет
	// лежат в одной базе. Прежде эта ячейка была содержательна своей пустотой у
	// второй стороны — общей транзакции между БД сервиса и чужим движком не
	// бывает; сегодня она измеряется как абсолютная величина, и «шесть
	// стейтментов» — утверждение о форме, а не о разнице с кем-то.
	InlineGrant(ctx context.Context, data, grant []Tuple) (Counters, error)
	// InlineRevoke — то же для отзыва: отзыв, не зависящий от доставки.
	InlineRevoke(ctx context.Context, data, revoke []Tuple) (Counters, error)

	Check(ctx context.Context, subject, verb, object string) (bool, Counters, error)
	BatchCheck(ctx context.Context, subject, verb string, objects []string) ([]bool, Counters, error)
	// CheckPage разрешает целую страницу и возвращает, на сколько частей она была
	// разложена. Число частей ОБЪЯВЛЯЕТСЯ, а не усредняется: у формы E оно равно
	// единице, и единица, полученная замером, отличима от единицы по умолчанию.
	CheckPage(ctx context.Context, subject, verb string, objects []string,
		partition, parallel int) (verdicts []bool, parts int, c Counters, err error)

	Volume(ctx context.Context) (Volume, error)

	// StmtProducer называет, чем и где снимается `StmtSQL` у этого хранилища и
	// прошёл ли производитель контроль в обе стороны.
	StmtProducer() ProducerStatus

	// Place — из какого места снята каждая ячейка этого хранилища. Отчёт,
	// собранный из двух мест без этого признака, выдаёт за один прогон два.
	// Признак пережил вторую сторону: места по-прежнему два — своя посадка
	// прибора и продуктовые таблицы iam (прогон Ф5), — и путать их нельзя.
	Place() string

	Teardown(ctx context.Context) error
}
