# scope-source-census.sh — перепись ИСТОЧНИКОВ звена цепи областей: что о
# предке объекта знает ЦЕПЬ (представление `kaname.resource_scope_edge`)
# против того, что о нём знают ДВА других источника — колонка собственной строки
# объекта и ПРОЕКЦИЯ ЖУРНАЛА (`kaname.relation_fact`), из которой реляционная
# форма собирает безусловное основание вердикта.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ ЭТА ПЕРЕПИСЬ ПЕРЕЖИЛА СНЯТИЕ ДВИЖКА
#
# Рядом стояла проба расхождения: она мерила ИСХОД — долю вопросов, на которых
# форма разошлась с внешним движком. Сравнивать больше не с чем, и проба снята
# вместе со второй формой (стадия S6 эпика #747).
#
# Эта перепись отвечала на ДРУГОЙ вопрос — «где именно рвётся цепь», — и он
# остался: она держит СВОЙСТВО, а не текущие данные, и видно оно ДО подачи.
# Объект, чьего предка называет источник, обязан иметь предка и в цепи; порванное
# звено теперь означает не расхождение двух форм, а молчаливый отказ там, где
# доступ есть.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПЕРЕЧЕНЬ ТИПОВ ВЫВОДИТСЯ, А НЕ ВЫПИСЫВАЕТСЯ (#785)
#
# Прежняя редакция строила перепись полным внешним соединением с группировкой,
# поэтому тип, у которого ноль объектов С ОБЕИХ СТОРОН, в вывод не попадал
# ВОВСЕ: «о нём не сказано» было неотличимо от «у него всё хорошо». Единственный
# цикл при этом шёл по списку послаблений оператора — то есть перечень типов
# задавал тот, кто прощает расхождения.
#
# Теперь перечень и предикаты берутся у ВЛАДЕЛЬЦЕВ через генератор запроса
# (`services/iam/internal/scopesourcecensus`): типы — из
# `authzcascade.DerivableTypes`, предикат «источник предка законно пуст» — из
# плана чтения материализации (`pg.IAMDirectContainments`). Строка печатается по
# КАЖДОМУ типу, включая тип с нулями.
#
# ─────────────────────────────────────────────────────────────────────────────
# КАТЕГОРИЙ ПЯТЬ, И ТРИ ИЗ НИХ — НЕ НАХОДКИ
#
#   в цепи      — у строки есть звено. Норма.
#   без предка  — звена нет И источник предка ЗАКОННО пуст: системная роль (ни
#                 аккаунта, ни проекта — и она НЕ ДОЛЖНА становиться достижимой
#                 ни из одного аккаунта), привязка с областью вне закрытого
#                 набора, учётка с пустым аккаунтом. Посчитать их потерями
#                 значит показать предмет ХУЖЕ, чем он есть, и следующий
#                 читатель начнёт «чинить» законное.
#   потеряно    — звена нет, А ИСТОЧНИК ПРЕДКА НАЗЫВАЕТ. Находка ВСЕГДА и
#                 никогда не прощается: форма отказывает там, где решатель
#                 разрешает, и отказ неотличим от честного.
#   лишних      — звено есть, а предка не называет НИ источник, НИ журнал.
#                 Обратная полярность: форма РАЗРЕШАЕТ там, где решатель
#                 отказывает. Тише первой и потому опаснее.
#   нет строки  — объект назван журналом либо цепью, а СТРОКИ У НЕГО НЕТ. Это
#                 НЕ потеря цепи: идентификатор объекта И ЕСТЬ первичный ключ
#                 строки, значит объекта без строки не существует, и «цепь не
#                 дала ему предка» — верный ответ. Предмет чужой (#782), и он
#                 ПЕЧАТАЕТСЯ С АТРИБУЦИЕЙ, а не растворяется ни в находках, ни
#                 в тишине.
#
# ─────────────────────────────────────────────────────────────────────────────
# ИСХОДОВ ТРИ, И ТРЕТИЙ НЕ ВЫЧИТАЕТСЯ ИЗ ВЕРДИКТА
#
#   0 — перепись сделана, расхождений нет;
#   1 — перепись сделана, РАСХОЖДЕНИЕ НАЙДЕНО (называется по типам и числами);
#   3 — УСЛОВИЕ НЕ СОЗДАНО: базы нет, схемы нет, перечень типов не получен.
#       Это не «зелено» и не «красно» — «ноль находок» обязано быть отличимо от
#       «ноль прочитанного», поэтому объём осмотренного печатается ВСЕГДА.
#
# Использование:
#   ./scope-source-census.sh                       # перепись на стенде
#   ALLOW_TYPES=iam_group:extra ./scope-source-census.sh
#   PSQL_DSN=postgres://... ./scope-source-census.sh   # против любой базы
#
# PSQL_DSN — адрес базы для ПРЯМОГО подключения вместо `kubectl exec` в под
# стенда. Это не лазейка для проб, а переносимость прибора: перепись обязана
# запускаться и там, где стенда нет (разработческая база, база в контейнере), и
# ОБА пути исполняют ОДИН И ТОТ ЖЕ запрос — тот, что печатает генератор.
# Регрессия на перепись пользуется этим путём; будь у неё свой, она проверяла бы
# не тот прибор, который работает на стенде.
#
# ALLOW_TYPES — послабления, ПОЛЯРНЫЕ: `<тип>:extra`. Прощается ТОЛЬКО полярность
# «лишних»; `<тип>:lost` отвергается самим скриптом. Причина в §Р5 приёмки R7-4:
# у типа, чьё звено выведено из СХЕМЫ, отсутствие указателя в журнале
# расхождением не является — а прежнее неполярное послабление прощало вместе с
# ним и настоящую потерю, то есть выводило тип из-под сторожа целиком.
# Послабление несёт предикат снятия на ВНЕШНЕМ факте: запись живёт, пока у неё
# есть предмет, и перепись падает на записи, которой больше нечего прощать.
set -euo pipefail

NS="${NS:-kacho}"
PG_POD="${PG_POD:-kacho-umbrella-pg-iam-0}"
DB="${DB:-kaname}"
DBUSER="${DBUSER:-postgres}"
ALLOW_TYPES="${ALLOW_TYPES:-}"
MODULE_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Прибор лежит В ТОМ ЖЕ модуле, что и генератор (github.com/PRO-Robotech/kaname),
# и адресуется от СВОЕГО каталога, а не от корня дерева платформы (#2378). Прежде
# он жил под `deploy/` платформы, и координата генератора складывалась из корня
# монорепо: после разреза службы такого корня рядом не будет, а исполнителей вне
# службы у прибора ноль — то есть он остался бы у платформы без единого читателя,
# а его проба уехала бы со службой и объявила третий исход.
#
# `go run` берёт пакет у ГЛАВНОГО модуля рабочего каталога, поэтому вызов не из
# корня модуля отвечает «main module does not contain package» ДО любого условия
# внутри — то есть перепись объявляла бы «условие не создано» на исправном дереве.
# Отсюда переход в MODULE_ROOT перед вызовом.
GEN_PKG="./internal/scopesourcecensus/cmd/scope-source-census-sql"
GEN="$GEN_PKG"

die_precond() { echo "УСЛОВИЕ НЕ СОЗДАНО: $*" >&2; exit 3; }

# pad — выравнивание по СИМВОЛАМ, а не по байтам.
#
# `printf %-Ns` считает БАЙТЫ, и кириллическая шапка из одиннадцати символов
# занимает двадцать один байт: колонки разъезжаются, а перепись, которую нельзя
# прочитать глазами, перестают сверять. `${#s}` в UTF-8-локали считает символы,
# поэтому ширина добирается здесь и передаётся вниз уже готовой строкой.
pad() { # pad <строка> <ширина> [left|right]
  local s="$1" w="$2" side="${3:-right}" n
  n=$(( w - ${#s} )); [ "$n" -lt 0 ] && n=0
  if [ "$side" = "left" ]; then printf '%*s%s' "$n" '' "$s"; else printf '%s%*s' "$s" "$n" ''; fi
}

row() { # row <тип> <строк> <в цепи> <без предка> <потеряно> <лишних> <нет строки>
  printf '  %s %s %s %s %s %s %s\n' \
    "$(pad "$1" 22)" "$(pad "$2" 8 left)" "$(pad "$3" 8 left)" "$(pad "$4" 11 left)" \
    "$(pad "$5" 9 left)" "$(pad "$6" 8 left)" "$(pad "$7" 11 left)"
}


PSQL_DSN="${PSQL_DSN:-}"

q() {
  if [ -n "$PSQL_DSN" ]; then
    psql "$PSQL_DSN" -At -F'|' -c "$1" 2>/dev/null || true
  else
    kubectl -n "$NS" exec "$PG_POD" -- psql -U "$DBUSER" -d "$DB" -At -F'|' -c "$1" 2>/dev/null \
      | grep -v '^Defaulted' || true
  fi
}

qf() { # qf <файл-с-запросом>
  if [ -n "$PSQL_DSN" ]; then
    psql "$PSQL_DSN" -At -F'|' -f "$1" 2>/dev/null || true
  else
    kubectl -n "$NS" exec -i "$PG_POD" -- psql -U "$DBUSER" -d "$DB" -At -F'|' -f - < "$1" 2>/dev/null \
      | grep -v '^Defaulted' || true
  fi
}

# ── 0. Предусловия ───────────────────────────────────────────────────────────
if [ -n "$PSQL_DSN" ]; then
  command -v psql >/dev/null 2>&1 || die_precond "нет psql, а PSQL_DSN задан"
  psql "$PSQL_DSN" -At -c 'SELECT 1' >/dev/null 2>&1 \
    || die_precond "база по PSQL_DSN недоступна"
else
  kubectl -n "$NS" get pod "$PG_POD" >/dev/null 2>&1 \
    || die_precond "пода базы $PG_POD в пространстве $NS нет"
fi
have_view=$(q "SELECT count(*) FROM pg_views WHERE schemaname='kaname' AND viewname='resource_scope_edge';")
[ "${have_view:-0}" = "1" ] \
  || die_precond "представления kaname.resource_scope_edge нет — цепь читать нечем"
have_fact=$(q "SELECT count(*) FROM information_schema.tables WHERE table_schema='kaname' AND table_name='relation_fact';")
[ "${have_fact:-0}" = "1" ] \
  || die_precond "таблицы kaname.relation_fact нет — сверять не с чем"

# Перечень типов и запрос — У ВЛАДЕЛЬЦЕВ. Отказ генератора это УСЛОВИЕ НЕ
# СОЗДАНО, а не «типов ноль»: перепись, не получившая перечня, обязана сказать
# «читать нечем», иначе её молчание прочтут как «расхождений нет».
command -v go >/dev/null 2>&1 \
  || die_precond "нет go: перечень типов выводится из дерева генератором $GEN, выписывать его здесь нельзя"
SQL_FILE="$(mktemp)"; TYPES_FILE="$(mktemp)"
trap 'rm -f "$SQL_FILE" "$TYPES_FILE"' EXIT
( cd "$MODULE_ROOT" && go run "$GEN_PKG" sql ) > "$SQL_FILE" \
  || die_precond "генератор запроса переписи ($GEN sql) отказал — перечень типов не получен"
( cd "$MODULE_ROOT" && go run "$GEN_PKG" types ) > "$TYPES_FILE" \
  || die_precond "генератор перечня типов ($GEN types) отказал"
declared=$(grep -c . "$TYPES_FILE" || true)
[ "${declared:-0}" -gt 0 ] \
  || die_precond "перечень выводимых типов ПУСТ — сторожить нечего, и «ноль находок» здесь означало бы «ноль прочитанного»"

echo "── перепись источников звена цепи ────────────────────────────────────────"
echo "  база ${PSQL_DSN:+прямое подключение}${PSQL_DSN:-$PG_POD/$DB}, снято $(date -u '+%Y-%m-%d %H:%M:%SZ')"
echo "  перечень типов выведен из authzcascade.DerivableTypes через $GEN"

# ── 1. Объём осмотренного — ОТДЕЛЬНЫМ утверждением ───────────────────────────
#
# Без него «расхождений 0» неотличимо от «ничего не прочитали»: пустая проекция
# даёт ровно тот же ноль, что и здоровое дерево.
read -r facts pointers edges <<<"$(q "
  SELECT (SELECT count(*) FROM kaname.relation_fact),
         (SELECT count(*) FROM kaname.relation_fact
           WHERE relation = split_part(subject, ':', 1)),
         (SELECT count(*) FROM kaname.resource_scope_edge);" | tr '|' ' ')"
echo "  осмотрено: прямых фактов ${facts:-0}, из них указателей на предка ${pointers:-0}, рёбер цепи ${edges:-0}"

if [ "${facts:-0}" -eq 0 ] || [ "${edges:-0}" -eq 0 ]; then
  die_precond "читать нечего (фактов ${facts:-0}, рёбер ${edges:-0}) — «расхождений нет» здесь означало бы «ничего не прочитано»"
fi
if [ "${pointers:-0}" -eq 0 ]; then
  die_precond "указателей на предка в проекции журнала ноль — дискриминатор «отношение называет тип субъекта» не нашёл НИ ОДНОГО, значит он разошёлся с формой журнала, а не журнал пуст"
fi

# ── 2. Разбор послаблений: ПОЛЯРНОСТЬ ОБЯЗАТЕЛЬНА ────────────────────────────
#
# Неполярная запись прощала обе стороны разом и выводила тип из-под сторожа
# целиком — следующая настоящая потеря по нему была бы невидима.
allow_extra=""
for entry in $(echo "$ALLOW_TYPES" | tr ',' ' '); do
  [ -n "$entry" ] || continue
  etype="${entry%%:*}"; epol="${entry#*:}"
  if [ "$etype" = "$epol" ]; then
    echo "  ОТКАЗ: послабление «$entry» без полярности." >&2
    echo "  Пишите «$etype:extra». Неполярная запись прощает и настоящую потерю," >&2
    echo "  то есть выводит тип из-под сторожа целиком." >&2
    exit 1
  fi
  case "$epol" in
    extra) allow_extra="$allow_extra $etype" ;;
    lost)
      echo "  ОТКАЗ: полярность «потеряно» не прощается НИКОГДА (тип «$etype»)." >&2
      echo "  Потеря означает, что форма отказывает там, где решатель разрешает, и отказ" >&2
      echo "  неотличим от честного. Простить её значит объявить дыру нормой." >&2
      exit 1 ;;
    *)
      echo "  ОТКАЗ: неизвестная полярность «$epol» в послаблении «$entry»; известна одна: extra." >&2
      exit 1 ;;
  esac
done

# ── 3. Перепись по типам ─────────────────────────────────────────────────────
#
# Единица — ОБЪЕКТ, а не строка журнала: у объекта бывает несколько указателей
# (у проекта их два — аккаунт и кластер), и счёт строк завысил бы стороны
# по-разному.
echo "── по типам ──────────────────────────────────────────────────────────────"
row "тип объекта" "строк" "в цепи" "без предка" "потеряно" "лишних" "нет строки"
rows=$(qf "$SQL_FILE")
[ -n "$rows" ] \
  || die_precond "перепись по типам не вернула ни одной строки при непустых входах — читать нечем"

seen=0; lost_total=0; extra_total=0; norow_total=0
lost_types=""; extra_types=""; norow_types=""; forgiven=""
while IFS='|' read -r otype total in_chain no_parent lost extra no_row; do
  [ -n "$otype" ] || continue
  seen=$((seen + 1))
  row "$otype" "$total" "$in_chain" "$no_parent" "$lost" "$extra" "$no_row"
  [ "${lost:-0}" -gt 0 ] && { lost_total=$((lost_total + lost)); lost_types="$lost_types $otype($lost)"; }
  if [ "${extra:-0}" -gt 0 ]; then
    # Сравнение БЕЗ внешнего процесса: `grep -q` выходит до конца входа, писатель
    # слева получает SIGPIPE, и под `pipefail` найденное объявляется ненайденным
    # (#658). Здесь от этого зависел бы вердикт, поэтому труба недопустима.
    if [[ " $allow_extra " == *" $otype "* ]]; then
      forgiven="$forgiven $otype"
    else
      extra_total=$((extra_total + extra)); extra_types="$extra_types $otype($extra)"
    fi
  fi
  [ "${no_row:-0}" -gt 0 ] && { norow_total=$((norow_total + no_row)); norow_types="$norow_types $otype($no_row)"; }
done <<<"$rows"

echo "  осмотрено типов: $seen из $declared объявленных выводимыми"
if [ "$seen" -ne "$declared" ]; then
  echo "  ОТКАЗ: перепись высказалась о $seen типах из $declared." >&2
  echo "  Тип, о котором не сказано, — НАХОДКА, а не пропуск: его молчание неотличимо" >&2
  echo "  от «у него всё хорошо»." >&2
  exit 1
fi

# ── 4. Объекты без строки — ЧУЖОЙ ПРЕДМЕТ, названный, а не спрятанный ────────
if [ "$norow_total" -gt 0 ]; then
  echo "── объекты без строки (предмет #782) ─────────────────────────────────────"
  echo "  объектов, названных журналом либо цепью и НЕ имеющих строки:$norow_types"
  echo "  Это НЕ потеря цепи: идентификатор объекта и есть первичный ключ строки," >&2
  echo "  поэтому объекта без строки не существует, и отсутствие у него предка —" >&2
  echo "  верный ответ. Предмет живёт задачей #782 и здесь только назван." >&2
fi

# ── 5. Послабление, которому нечего прощать, — НАХОДКА ───────────────────────
#
# Иначе запись переживает свой предмет и маскирует следующее расхождение по
# тому же типу. Предикат снятия — ВНЕШНИЙ факт: тип перестал давать «лишних».
if [ -n "$allow_extra" ]; then
  echo "── послабления ───────────────────────────────────────────────────────────"
  for t in $allow_extra; do
    if [[ " $forgiven " == *" $t "* ]]; then
      echo "  $t:extra — прощено (предмет есть: звено выведено из схемы, в журнале его нет)"
    else
      echo "  ОТКАЗ: тип «$t» объявлен в ALLOW_TYPES с полярностью extra, но «лишних» по нему НЕТ." >&2
      echo "  Прощать нечего — запись пережила свой предмет и замаскирует следующее." >&2
      exit 1
    fi
  done
fi

# ── 6. Предел обхода: звеньев на объект меньше глубины ───────────────────────
#
# Цепь читается соединением вбок с `LIMIT MaxAncestorDepth` по КАЖДОМУ объекту.
# Довод 740001 («строк на объект не больше глубин, ключ уникален по глубине»)
# ОТМЕНЁН миграцией 781001 для журнальной ветви: у проекта указателей два, оба на
# глубине 1. Действующий довод — числом, а числа ПРОВЕРЯЮТ. Объект, у которого
# звеньев столько же, сколько предел, усекается МОЛЧА: цепь не доходит до корня,
# и отказ неотличим от честного.
MAX_DEPTH="${MAX_DEPTH:-4}"
read -r max_ptr max_obj <<<"$(q "
  SELECT n, object_type || ':' || object_id
    FROM (SELECT object_type, object_id, count(*) n
            FROM kaname.resource_scope_edge
           GROUP BY 1, 2) s
   ORDER BY n DESC LIMIT 1;" | tr '|' ' ')"
echo "── предел обхода ─────────────────────────────────────────────────────────"
echo "  максимум звеньев на объект: ${max_ptr:-0} (${max_obj:-нет}), предел обхода $MAX_DEPTH"
if [ "${max_ptr:-0}" -ge "$MAX_DEPTH" ]; then
  echo "  ОТКАЗ: у объекта ${max_obj} звеньев ${max_ptr} при пределе обхода $MAX_DEPTH." >&2
  echo "  Соединение вбок усекает цепь МОЛЧА: она не дойдёт до корня, а отказ в доступе" >&2
  echo "  будет неотличим от честного. Поднимать предел вслепую нельзя — сперва понять," >&2
  echo "  откуда у объекта столько звеньев." >&2
  exit 1
fi

