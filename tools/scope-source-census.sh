echo "── вердикт ───────────────────────────────────────────────────────────────"
rc=0
if [ "$lost_total" -gt 0 ]; then
  echo "  ОТКАЗ: объектов, чьего предка называет источник и НЕ видит цепь:$lost_types" >&2
  echo "  По этим объектам форма E отказывает там, где решатель разрешает: тот же" >&2
  echo "  указатель он достаёт запасным структурным путём из той же колонки, а отказ" >&2
  echo "  формы неотличим от честного." >&2
  rc=1
fi
if [ "$extra_total" -gt 0 ]; then
  echo "  ОТКАЗ: объектов, у которых звено есть у цепи и предка не называет ни источник, ни журнал:$extra_types" >&2
  echo "  Это обратная полярность того же инварианта: форма РАЗРЕШАЕТ там, где решатель" >&2
  echo "  отказывает. Тише первой и опаснее — расширение охвата не выглядит поломкой." >&2
  rc=1
fi
[ "$rc" -eq 0 ] && echo "  расхождений нет ни в одну сторону: цепь видит ровно то, что назвали источники"
exit $rc
