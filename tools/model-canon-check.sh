# model-canon-check.sh — блоки модели доступов сверяются с манифестами модулей
# ПОБАЙТОВО: обход закрытого набора порождает блоки типов из манифеста каждого
# модуля и сравнивает их с каноном, прочитанным ИЗ ДЕРЕВА.
#
# Тонкая обёртка. Что сверяется и почему исходов три, документировано на пакете
# services/iam/internal/modelrender; здесь — только вызов.
#
# ПОЧЕМУ НЕ `go run`. Тот же замер, что у соседа module-manifest-check.sh:
# `go run` СХЛОПЫВАЕТ код возврата программы в единицу — программа, вышедшая с
# кодом 2, даёт `exit status 2` на stderr и код 1 у самой команды. Здесь исходов
# ЧЕТЫРЕ, и через `go run` и «проверять нечего», и «проверка не исполнялась»
# стали бы неотличимы от находки. Поэтому сборка и запуск разнесены, а код
# возврата двоичного файла передаётся наружу дословно.
#
# Аргументы пробрасываются как есть:
#   -root=<каталог>   судить другое дерево (этим пользуются пробы самой цели).

set -euo pipefail

# Корень репозитория вычисляется ДО смены каталога и передаётся явно: умолчание
# флага — текущий каталог, и без явного корня цель судила бы тот каталог, из
# которого её позвали, а не дерево.
REPO_ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
cd "$REPO_ROOT"

BUILD_DIR="$(mktemp -d)"
trap 'rm -rf "$BUILD_DIR"' EXIT
# Сборка идёт В МОДУЛЕ СЛУЖБЫ (`-C`): у неё свой `go.mod`, и путь пакета от
# корня монорепо не резолвится. Корень ДЕРЕВА программе по-прежнему передаётся
# ключом ниже — предмет её обхода не изменился.
go build -C "$REPO_ROOT/services/iam" -o "$BUILD_DIR/model-canon-check" ./tools/modelcanoncheck

# Код возврата снимается явно: под `set -e` ненулевой исход оборвал бы скрипт до
# `exit`, а `exec` не дал бы сработать уборке за собой.
rc=0
"$BUILD_DIR/model-canon-check" -root="$REPO_ROOT" "$@" || rc=$?
exit "$rc"
