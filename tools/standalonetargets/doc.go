// Package standalonetargets судит ОДНО свойство рецепта сборки модуля: цель,
// которую он НЕ пометил `[монорепо]`, обязана работать в самостоятельном клоне.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Модуль живёт в двух посадках — внутри монорепо и самостоятельным клоном у
// арендатора, — и `make help` печатает обе, называя посадку словами. Пометка
// `[монорепо]` в перечне целей есть УТВЕРЖДЕНИЕ О ПОВЕДЕНИИ: помеченная цель
// зовёт соседей по дереву и вне монорепо отказывает словами; НЕпомеченная
// работает у арендатора.
//
// Утверждение это до сих пор не держалось ничем. Задача #2144 закрыла шапку
// файла (`include` несуществующего пути делал недоступным весь перечень целей) и
// на том остановилась: её предикат — `make -n help` кодом 0 и ноль подъёмов в
// тексте — необходим, но НЕ достаточен. Перечень стал читаемым; правдивым он не
// стал.
//
// Замер на `origin/release/kaname` (a9d41c7cd6), самостоятельный клон, собранный
// из состава коммита модуля: целей в перечне 22, помечено `[монорепо]` 6, из
// оставшихся 16 отказали ТРИ — `audit-list-filter`, `model-canon-check`,
// `cla-check`. Все три в монорепо зелены, то есть расходится не код, а
// объявление о нём.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО НЕ ЛОВИТСЯ НИЧЕМ СУЩЕСТВУЮЩИМ
//
// Прогон дерева идёт В МОНОРЕПО — там все три зелены by construction. Отличить
// «цель работает везде» от «цель работает там, где её гоняют» можно только
// ПОСТАВИВ ЕЁ В ДРУГУЮ ПОСАДКУ. Поэтому гейт не читает текст рецепта и не судит
// по признакам: он собирает самостоятельный клон из состава коммита и ЗОВЁТ
// каждую необъявленную цель.
//
// ─────────────────────────────────────────────────────────────────────────────
// ИСХОДОВ ТРИ, И ТРЕТИЙ НЕСУЩИЙ
//
//	годно            — каждая судимая цель отработала в клоне;
//	находка          — цель отказала, хотя `[монорепо]` не объявлено: названы
//	                   имя цели, код возврата и хвост её вывода;
//	НЕ ИСПОЛНЯЛАСЬ   — посадку собрать не удалось (нет git, временный каталог
//	                   лежит внутри репозитория, состав коммита пуст).
//
// Третий отделён от первого потому, что «ноль находок» обязано быть отличимо от
// «ноль прочитанного»: гейт, не собравший клон, о целях не утверждает НИЧЕГО и
// не вправе выглядеть успехом.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ВРЕМЕННЫЙ КАТАЛОГ ПРОВЕРЯЕТСЯ, А НЕ ПРЕДПОЛАГАЕТСЯ
//
// Клон обязан быть САМОСТОЯТЕЛЬНЫМ: если `TMPDIR` указывает внутрь репозитория,
// обход вверх находит ЧУЖОЙ индекс, и цели судят чужое дерево — зелёным. Это тот
// же класс, ради которого написаны tree-root.sh (#2145) и резолв канона (#2159),
// и здесь он воспроизводится собственной фикстурой гейта. Поэтому предпосылка
// проверяется и НАЗЫВАЕТСЯ, а не подразумевается.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ГЕЙТ НЕ ДЕЛАЕТ
//
// Он не судит, ВЕРНО ли цель помечена `[монорепо]`: пометка — решение автора, и
// машинного предиката у «нужны ли ей соседи» нет. Он судит ровно обратное —
// что НЕпомеченная цель работает. Пометить можно всё и получить зелёное; тогда
// `make help` перестанет обещать арендатору хоть что-нибудь, и это будет видно
// человеку в переписи, которую гейт печатает всегда.
