# tree-root.sh — ОДИН ответ на вопрос «какое дерево судит гейт службы», общий для
# всех обёрток в tools/. Подключается точкой (`. "$(dirname "$0")/tree-root.sh"`)
# и объявляет две величины: KANAME_MODULE_ROOT и KANAME_TREE_ROOT.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ КОРЕНЬ НЕ СЧИТАЕТСЯ ПУТЁМ ВВЕРХ (задача #2145)
#
# Прежде обе обёртки брали корень как три уровня вверх от себя. Путь верен ровно
# для одной посадки — модуля внутри монорепо. У самостоятельного клона он
# резолвится МОЛЧА в чужой каталог, и дальше возможны два исхода, из которых
# опаснее второй:
#
#   каталога по вычисленному пути НЕТ  → отказ приходит от `go` («chdir … no such
#                                        file or directory»), то есть гейт не
#                                        сказал о себе ничего;
#   каталог по вычисленному пути ЕСТЬ  → гейт выносит ЗЕЛЁНЫЙ вердикт о ЧУЖОМ
#                                        дереве, печатая по нему свою перепись, и
#                                        отличить его от настоящего НЕЧЕМ.
#
# Второе измерено, а не предположено: модуль, поставленный неотслеживаемым
# каталогом внутрь чужого репозитория, давал «манифестов прочитано 6 · находок 0»
# при заведомо БИТОМ собственном манифесте — тот не попадал в обход вовсе.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ЗДЕСЬ ФАКТ, А ЧТО ПРОВЕРЯЕМАЯ ПРЕДПОСЫЛКА
#
# ФАКТ: обёртка лежит в <модуль>/tools/, поэтому каталог модуля — один уровень
# вверх от неё. Это свойство самого файла, и оно одинаково в обеих посадках.
#
# ПРЕДПОСЫЛКА, которую надо ПРОВЕРИТЬ: дерево, о котором гейт будет говорить,
# действительно содержит ЭТОТ модуль как свой отслеживаемый состав. Полоса дерева
# читает состав КОММИТА (git ls-files), поэтому вопрос ставится к индексу, а не к
# диску: модуль, распакованный внутрь чужого репозитория, индексом того дерева не
# отслеживается — и это единственный признак, отличающий «моё дерево» от
# «оказался внутри чужого».
#
# Исходов у предпосылки ДВА, третьего нет: она выполнена — тогда величины
# объявлены; она не выполнена — тогда отказ, НАЗЫВАЮЩИЙ её словами, кодом
# «проверка НЕ ИСПОЛНЯЛАСЬ» (3). Молчаливое вычисление чужого пути исходом не
# является: «не знаю» не выдаётся ни за «нет находок», ни за «находка».

# KANAME_EXIT_NOT_RUN — «проверка НЕ ИСПОЛНЯЛАСЬ». То же число, что у обеих
# программ (manifestcheckrun.ExitNotRun, modelcanoncheck.exitNotRun): отказ
# предпосылки и отказ разбора аргументов — один исход, и вызывающий читает его
# одинаково.
KANAME_EXIT_NOT_RUN=3

# kaname_tree_root_resolve — объявляет KANAME_MODULE_ROOT и KANAME_TREE_ROOT либо
# отказывает, называя предпосылку. Отказывает ВЫХОДОМ, потому что подключается
# точкой: продолжать после неназванной предпосылки было бы ровно тем, против чего
# файл написан.
kaname_tree_root_resolve() {
  local wrapper_dir="$1"

  KANAME_MODULE_ROOT="$(cd "$wrapper_dir/.." && pwd)"

  # Предпосылка первая: каталог над обёрткой — и вправду модуль службы. Оба
  # признака берутся у СОСТАВА модуля, а не у его имени: имя каталога меняет тот,
  # кто клонирует, и судить по нему значило бы судить чужой выбор.
  if [ ! -f "$KANAME_MODULE_ROOT/go.mod" ] || [ ! -f "$KANAME_MODULE_ROOT/manifest.yaml" ]; then
    echo "проверка НЕ ИСПОЛНЯЛАСЬ: каталог над обёрткой не похож на модуль службы" >&2
    echo "  осмотрено: $KANAME_MODULE_ROOT" >&2
    echo "  ожидалось: go.mod и manifest.yaml — обёртка обязана лежать в <модуль>/tools/" >&2
    exit "$KANAME_EXIT_NOT_RUN"
  fi

  # Предпосылка вторая: у модуля есть дерево, читающее состав коммита. Обход
  # полосы дерева берёт перечень у индекса; без индекса называть дерево нечем.
  if ! KANAME_TREE_ROOT="$(git -C "$KANAME_MODULE_ROOT" rev-parse --show-toplevel 2>/dev/null)" \
     || [ -z "$KANAME_TREE_ROOT" ]; then
    echo "проверка НЕ ИСПОЛНЯЛАСЬ: дерево под гейтом не является репозиторием" >&2
    echo "  осмотрено: $KANAME_MODULE_ROOT" >&2
    echo "  ожидался признак: git отвечает на rev-parse --show-toplevel" >&2
    echo "  обход читает состав КОММИТА, а не диска: на распакованном архиве вердикта нет" >&2
    echo "  и быть не может — это «не исполнялась», а не «находок нет»" >&2
    exit "$KANAME_EXIT_NOT_RUN"
  fi

  # Предпосылка третья, несущая: найденное дерево содержит ЭТОТ модуль своим
  # отслеживаемым составом. Без неё гейт, запущенный из модуля, лежащего внутри
  # чужого репозитория, вынес бы вердикт о том репозитории — и вердикт был бы
  # ЗЕЛЁНЫМ, потому что собственные файлы модуля в обход не попали бы вовсе.
  local rel="${KANAME_MODULE_ROOT#"$KANAME_TREE_ROOT"}"
  rel="${rel#/}"
  local manifest_rel="manifest.yaml"
  [ -n "$rel" ] && manifest_rel="$rel/manifest.yaml"
  if ! git -C "$KANAME_TREE_ROOT" ls-files --error-unmatch -- "$manifest_rel" >/dev/null 2>&1; then
    echo "проверка НЕ ИСПОЛНЯЛАСЬ: дерево под гейтом — не то, о котором гейт может говорить" >&2
    echo "  модуль:  $KANAME_MODULE_ROOT" >&2
    echo "  дерево:  $KANAME_TREE_ROOT" >&2
    echo "  ожидался признак: $manifest_rel в составе коммита этого дерева" >&2
    echo "  его там нет — значит модуль лежит внутри ЧУЖОГО репозитория и не" >&2
    echo "  отслеживается им. Вердикт был бы вынесен о чужом дереве, а собственные" >&2
    echo "  файлы модуля в обход не попали бы вовсе; отличить такой зелёный от" >&2
    echo "  настоящего нечем, поэтому его здесь не бывает" >&2
    exit "$KANAME_EXIT_NOT_RUN"
  fi
}
