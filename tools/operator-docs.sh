# operator-docs.sh — порождает либо сверяет документы стороннего оператора:
# перечень третьих сторон и перечень обязательных величин в документе установки.
#
# ИСХОДОВ ЧЕТЫРЕ, и вызывающий обязан читать КОД, а не вид вывода:
#   0  сходится        порождённое равно лежащему в дереве;
#   1  находка         расхождение, неопознанная лицензия, пустая таблица, нет меток;
#   2  без предмета    сверять нечего — НЕ вердикт о дереве;
#   3  не исполнялось  вызов разобрать не удалось.
#
# ПОЧЕМУ СБОРКА, А НЕ `go run`. `go run` НЕ ПРОПУСКАЕТ код возврата программы:
# на любом ненулевом он отдаёт СВОЙ код 1 и печатает `exit status 3` строкой в
# поток ошибок. Четыре объявленных исхода схлопнулись бы в два, и «без предмета»
# стало бы неотличимо от находки — то есть отсутствие предмета читалось бы как
# вердикт о дереве. Измерено, а не предположено: первая редакция этого файла
# звала `go run` и отдавала 1 там, где программа отдала 3.
#
# Вызов: ./tools/operator-docs.sh [--write]
set -euo pipefail

# Каталог дерева iam — родитель каталога этого скрипта. Выводится, а не
# выписывается: вынесенный репозиторий сменит путь, но не эту связь.
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

bin="$(mktemp -d)/operator-docs"
trap 'rm -rf "$(dirname "$bin")"' EXIT

# `-C "$root"` обязателен: без него сборка идёт от текущего каталога вызывающего,
# а вне дерева модуля её контекста нет вовсе. Цель сборки зовёт скрипт из своего
# каталога, но конвейер и человек — из любого.
go build -C "$root" -o "$bin" ./tools/operatordocs/cmd/operator-docs

args=(-root "$root")
if [[ "${1:-}" == "--write" ]]; then
  args+=(-write)
fi

# Код берётся у САМОЙ программы и отдаётся вызывающему как есть. Ни трубы, ни
# `&&`: труба вернула бы код последнего звена, а `set -e` оборвал бы шаг до того,
# как код будет прочитан.
"$bin" "${args[@]}" && rc=0 || rc=$?
exit "$rc"
