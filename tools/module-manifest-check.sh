# module-manifest-check.sh — форму манифеста КАЖДОГО модуля судит один
# исполнитель: обход дерева читает каждый `manifest.yaml` и разбирает его тем
# же загрузчиком, которым его прочтёт посев iam.
#
# Тонкая обёртка. Что проверяется и почему исходов три, документировано на
# пакете services/iam/internal/manifest; здесь — только вызов.
#
# ПОЧЕМУ НЕ `go run`, ХОТЯ СОСЕД РЯДОМ ЕГО ЗОВЁТ. Измерено, а не выбрано:
# `go run` СХЛОПЫВАЕТ код возврата программы в единицу — программа, вышедшая с
# кодом 2, даёт `exit status 2` на stderr и код 1 у самой команды. У соседа
# (audit-list-filter.sh) исходов два, и схлопывание там ничего не портит; здесь
# исходов ТРИ, и через `go run` третий («проверять нечего») стал бы неотличим от
# находки. Поэтому сборка и запуск разнесены, а код возврата двоичного файла
# передаётся наружу дословно.
#
# Аргументы пробрасываются как есть:
#   -root=<каталог>   судить другое дерево (этим пользуются пробы самой цели).

set -euo pipefail

# Корень репозитория вычисляется ДО смены каталога и передаётся явно: умолчание
# флага — текущий каталог, и без явного корня цель судила бы тот каталог, из
# которого её позвали, а не дерево.
REPO_ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
cd "$REPO_ROOT"

BUILD_DIR="$(mktemp -d)"
trap 'rm -rf "$BUILD_DIR"' EXIT
go build -o "$BUILD_DIR/module-manifest-check" ./services/iam/tools/modulemanifestcheck

# Код возврата снимается явно: под `set -e` ненулевой исход оборвал бы скрипт до
# `exit`, а `exec` не дал бы сработать уборке за собой.
rc=0
"$BUILD_DIR/module-manifest-check" -root="$REPO_ROOT" "$@" || rc=$?
exit "$rc"
