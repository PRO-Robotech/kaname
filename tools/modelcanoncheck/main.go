// Команда model-canon-check — исполнитель побайтовой сверки модели доступов с
// манифестами модулей (задача PRO-Robotech/kacho#1089, приёмка
// services/iam/docs/engineering/acceptance/model-generated-from-manifest.md).
//
// Обходит закрытый набор модулей платформы, порождает блоки типов из манифеста
// каждого и сверяет порождённое с каноном `proto/kacho/cloud/iam/v1/fga_model.fga`
// ПОБАЙТОВО. Второй операнд сверки резолвится обходом вверх от корня дерева и
// параметром не является — подменить его снимком нечем (§2 п. 2).
//
// Тонкая обёртка: ЧТО сверяется и почему исходов три, документировано на пакете
// services/iam/internal/modelrender. Здесь живут вызов, ведомость послаблений и
// перевод отчёта в код возврата.
//
// # Зачем исполнитель, когда есть пробы пакета
//
// Пробы пакета судят обход на СИНТЕТИЧЕСКИХ деревьях и о дереве продукта не
// утверждают ничего. Без исполнителя пакет не имеет прод-потребителя
// (`architecture.md` §LEAN), перепись §2 п. 5 не печатается нигде, а «сверка
// побайтовая» остаётся библиотекой, а не гейтом.
//
// # Коды возврата
//
//	0  сверено — каждый блок канона, принадлежащий модулю набора, порождён и равен;
//	1  находка — расхождение блоков, блок без источника в манифесте, модуль без
//	             манифеста и без записи ведомости, негодный документ, запись
//	             ведомости без предмета;
//	2  VOID    — сверять нечего НИ ДЛЯ ОДНОГО модуля;
//	3  проверка НЕ ИСПОЛНЯЛАСЬ — вызов разобрать не удалось.
//
// Третий код отделён от нулевого потому, что «ноль находок» обязано быть отличимо
// от «ноль прочитанного»; четвёртый — потому, что «не выполнилось» не вычитается
// из вердикта и не зачитывается в успех (`testing.md` §«Чтение вердикта»). Разбор
// аргументов у flag.ExitOnError выходит кодом 2 — то есть СОВПАЛ БЫ с VOID и
// объявил бы пустым деревом опечатку в вызове; поэтому здесь свой набор флагов с
// ContinueOnError и свой код. Тот же довод и тот же выбор, что у соседа
// module-manifest-check.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"

	"github.com/PRO-Robotech/kacho/services/iam/internal/apps/kacho/seed"
	"github.com/PRO-Robotech/kacho/services/iam/internal/modelrender"
)

// exitNotRun — проверка не исполнялась: вызов разобран не был.
const exitNotRun = 3

// ledger — ведомость послаблений: модули закрытого набора, чей манифест ещё не
// приехал в дерево.
//
// ЗАПИСИ ПЕРЕЧИСЛЕНЫ ПОИМЁННО, а не выведены из набора, и это несущее. Выведенная
// из набора ведомость прощала бы КАЖДЫЙ модуль, включая тот, что появится завтра,
// — то есть не истекла бы никогда и не заметила бы новичка. Перечисленная истекает
// сама: манифест модуля приезжает — и его запись становится НАХОДКОЙ «прощать
// нечего», которая требует снять запись тем же изменением.
//
// Номер задачи у каждой записи — предикат снятия. Послабление без номера
// отвергается самим обходом: у него нет предмета, за который кто-то отвечает.
//
// Предикат сегодняшнего состояния: `git ls-files | grep -cE '/manifest\.yaml$'` → 6.
//
// # Ведомость ПУСТА, и это её цель, а не её поломка
//
// Все шесть записей сняты задачей #1091 тем же изменением, которым приехали
// манифесты: обход требует, чтобы запись, которой больше нечего прощать, была
// находкой, — и снятая вместе со своим предметом запись есть исполнение этого
// требования, а не обход его. Пустая ведомость означает, что каждый модуль
// закрытого набора обязан нести манифест, и модуль, добавленный в набор завтра,
// покраснеет сразу — прощать его нечем.
var ledger []modelrender.Waiver

func main() {
	root, err := parseArgs(os.Args[0], os.Args[1:])
	if err != nil {
		if !errors.Is(err, flag.ErrHelp) {
			fmt.Fprintf(os.Stderr, "проверка НЕ ИСПОЛНЯЛАСЬ: %v\n", err)
		}
		os.Exit(exitNotRun)
	}

	// Перечень ресурсов берётся СНИМКОМ каталога, а не у литерала (kacho#1816).
	// Собирается он из того же перечня, которым миграция посеяла строки,
	// поэтому сборочная проверка остаётся воспроизводимой из ДЕРЕВА: сделать её
	// функцией состояния чужой базы значило бы получать разный вердикт канона
	// на одном и том же дереве.
	rows := seed.LiteralRows()

	census, findings, code := modelrender.Sweep(rows.Resources, root, ledger)

	// Перепись печатается ВСЕГДА и первой: без неё зелёный вердикт неотличим от
	// вердикта обхода, не прочитавшего ничего.
	fmt.Printf("корень обхода: %s\n", root)
	fmt.Printf("перепись: %s\n", census)
	for _, f := range findings {
		fmt.Fprintf(os.Stderr, "НАХОДКА: %s\n", f)
	}

	if code == modelrender.SweepVoid {
		// Словами, а не только кодом: код читает оболочка, а строку — человек,
		// и она не вправе выглядеть успехом.
		fmt.Fprintln(os.Stderr,
			"сверять нечего ни для одного модуля — это НЕ успех, а «проверять нечего»: "+
				"предмет у сверки появится вместе с первым манифестом модуля (#1091)")
	}
	os.Exit(code)
}

// parseArgs — свой набор флагов, чтобы отказ разбора не выходил кодом VOID.
func parseArgs(prog string, args []string) (string, error) {
	fs := flag.NewFlagSet(prog, flag.ContinueOnError)
	root := fs.String("root", ".", "корень дерева, в котором ищутся манифесты модулей и канон")
	if err := fs.Parse(args); err != nil {
		return "", err
	}
	if rest := fs.Args(); len(rest) > 0 {
		return "", fmt.Errorf("лишние аргументы: %v — корень задаётся флагом -root", rest)
	}
	if *root == "" {
		return "", errors.New("-root пуст: корень обхода не назван")
	}
	return *root, nil
}
